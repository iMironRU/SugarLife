import { describe, it, expect } from 'vitest';
import { имяСправочникаРядом } from './имяПрибора';

describe('имяСправочникаРядом', () => {
  it('разные имена — показываем справочник рядом', () => {
    expect(имяСправочникаРядом('Medtronic 722', 'Paradigm 522/722')).toBe('Paradigm 522/722');
  });

  it('совпали — второго имени нет', () => {
    expect(имяСправочникаРядом('Dexcom G6', 'Dexcom G6')).toBeNull();
  });

  it('совпали с точностью до разделителей и регистра', () => {
    expect(имяСправочникаРядом('paradigm-522-722', 'Paradigm 522/722')).toBeNull();
  });

  it('одно имя входит в другое — это уточнение, а не вторая железка', () => {
    expect(имяСправочникаРядом('MiniMed 780G', 'MiniMed 780G (Guardian 4)')).toBeNull();
  });

  it('имени из эфира нет — показывать нечего, второго ответа не рисуем', () => {
    expect(имяСправочникаРядом(null, 'Paradigm 522/722')).toBeNull();
    expect(имяСправочникаРядом('', 'Paradigm 522/722')).toBeNull();
  });

  it('справочник молчит — тоже нечего', () => {
    expect(имяСправочникаРядом('Medtronic 722', null)).toBeNull();
    expect(имяСправочникаРядом('Medtronic 722', '   ')).toBeNull();
  });

  it('780G и 770G — разные приборы, и второе имя обязано быть видно', () => {
    expect(имяСправочникаРядом('MiniMed 770G', 'MiniMed 780G')).toBe('MiniMed 780G');
  });
});
