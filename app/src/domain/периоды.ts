/* ОДИН НАБОР ПЕРИОДОВ НА ВЕСЬ РАЗБОР ПРОШЛОГО (SugarLife#690).

   Списков было два, в двух файлах, и они разошлись: «Анализ» предлагал 3·7·14·30, «Метрики» —
   3·7·30·90. Кнопка при этом одна и та же (`period-seg`), вкладки соседние. Человек нажимал на
   один орган управления, и тот менял под ним и набор, и подписи — «3 дн.» против «3 дня».

   Расхождение было не решением, а накоплением: ни одного пояснения, почему наборы разные, ни
   один файл не знал о другом. Цена не в неаккуратности:

   · 14 дней — международное окно разбора гликемии, и на нём построен весь отчёт врачу («Сенсор
     за 14 дней», «Типовой день за 14 дней»). В «Метриках» его не было — то есть посмотреть
     метрики за тот период, за который печатается отчёт, было нельзя;
   · 90 дней — горизонт, на котором говорят о среднем сахаре. В «Анализе» его не было.

   Каждый набор отнимал у своей вкладки ровно то окно, которое там нужнее всего.

   30 дней — календарный месяц. Клинически он ни на чём не стоит и был единственным кандидатом на
   выброс; решение владельца — оставить: месяцами человек думает о своей жизни, даже когда
   медицина думает двумя неделями и кварталом.

   ПОДПИСИ ЧИСЛАМИ, слово — в строку над переключателем. Пять кнопок словами на телефон в 380
   точек не помещаются, числами помещаются свободно. Заодно исчезает разнобой «дн.» против «дня»:
   склонять теперь надо в одном месте. */
export const ПЕРИОДЫ_РАЗБОРА = [3, 7, 14, 30, 90];

/* Склонение по настоящему правилу, а не по нашему набору. Набор фиксированный, и хватило бы
   «3 → дня, остальные → дней»; но список переживёт эту функцию, а неверное правило всплывёт
   молча и не там, где его писали. */
export function дней(n: number): string {
  const сотня = Math.abs(n) % 100;
  const единица = сотня % 10;
  if (сотня >= 11 && сотня <= 14) return 'дней';
  if (единица === 1) return 'день';
  if (единица >= 2 && единица <= 4) return 'дня';
  return 'дней';
}
