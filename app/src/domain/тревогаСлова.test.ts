import { describe, it, expect } from 'vitest';
import { заголовокТревоги, текстТревоги } from './тревогаСлова';

describe('слова тревоги', () => {
  it('называет знакомые тревоги по-человечески', () => {
    expect(заголовокТревоги('гипо', 'Разбудить')).toBe('Низкий сахар');
    expect(заголовокТревоги('молчание-во-сне', 'Разбудить')).toBe('Данных нет');
    expect(текстТревоги('гипо', 'Разбудить', 3.64)).toBe('3,6 ммоль');
  });

  it('незнакомую не теряет, а называет скучно', () => {
    expect(заголовокТревоги('что-то-новое', 'Сегодня')).toBe('Тревога');
    expect(текстТревоги('что-то-новое', 'Сегодня', null)).toBe('Приложение сообщает: что-то-новое');
  });

  /* Тревога о самой доставке — не про сахар: показать рядом с ней 10,2 значит дать повод
     закрыть её как пустяк, а разбудить мы по-прежнему не можем. */
  it('у нарушенного обещания текст про доставку, а не про сахар', () => {
    expect(заголовокТревоги('гипо:не-разбудит', 'ОбещаниеНарушено')).toBe('Тревога может не разбудить');
    expect(текстТревоги('гипо:не-разбудит', 'ОбещаниеНарушено', 10.2))
      .toBe('Проверьте «Охрану»: сейчас разбудить не сможем');
  });
});
