import { describe, it, expect } from 'vitest';
import { мешает, спроситьМожно, кудаВНастройки, пустота, ТЕРПЕНИЕ_МС } from './scanReadiness';
import type { UiSnapshot, ScanReadinessView } from '@/sources/bridge';

/* Почему поиск не находит приборов (SugarLife#333).

   Пустой эфир на чистом Android оказался выключенной службой геолокации, а приложение
   молчало — человек искал неисправность в приборе, которого это не касалось. */

/* Образец снимка: нас интересует одно поле, а тип снимка большой. Приведение через
   `unknown` — не небрежность, а прямое утверждение «здесь нарочно неполный снимок»:
   без него компилятор справедливо возражает, что типы не пересекаются. */
const снимок = (г?: Partial<ScanReadinessView>): UiSnapshot =>
  ({ scanReadiness: г ? { canScan: false, ...г } : undefined } as unknown as UiSnapshot);

describe('что мешает', () => {
  it('движок не жалуется — не выдумываем', () => {
    expect(мешает(снимок())).toBe(null);
    expect(мешает({ scanReadiness: { canScan: true, blockers: [] } } as unknown as UiSnapshot)).toBe(null);
    expect(мешает(null)).toBe(null);
  });

  it('жалуется — отдаём как есть, вместе со словами движка', () => {
    const п = мешает(снимок({ blockers: ['locationOff'], reason: 'Выключена геолокация' }));
    expect(п?.reason).toBe('Выключена геолокация');
  });
});

describe('что предлагать', () => {
  /* Диалог даётся один раз. Отказал насовсем — кнопка «Разрешить» открыла бы ничего,
     то есть тупик, из которого человек не выберется и решит, что приложение сломано. */
  it('разрешение можно спросить — предлагаем спросить', () => {
    expect(спроситьМожно(мешает(снимок({ blockers: ['noPermission'], canAskAgain: true })))).toBe(true);
  });

  it('отказал насовсем — не спрашиваем, ведём в настройки', () => {
    const п = мешает(снимок({ blockers: ['noPermission'], canAskAgain: false, settingsTarget: 'appSettings' }));
    expect(спроситьМожно(п)).toBe(false);
    expect(кудаВНастройки(п)).toBe('appSettings');
  });

  /* Геолокация и блютус разрешением приложения не чинятся — только настройками. */
  it('дело не в разрешении — спрашивать нечего', () => {
    expect(спроситьМожно(мешает(снимок({ blockers: ['locationOff'], settingsTarget: 'location' })))).toBe(false);
  });

  it('вести некуда — честно ничего не предлагаем', () => {
    expect(кудаВНастройки(мешает(снимок({ blockers: ['bluetoothOff'] })))).toBe(null);
  });

  /* ПОЛЯ НЕТ — ПРЕДЛАГАЕМ СПРОСИТЬ, И ЭТО ОСОЗНАННЫЙ РИСК (#710).

     `canAskAgain` шлёт оболочка, и старая может не прислать его вовсе. Тогда мы показываем
     «Разрешить»: у человека, который ещё не отказывал, кнопка сработает, а отказавшему она
     откроет пустоту.

     Обратный выбор хуже: «Открыть настройки» тому, кто просто не успел ответить, посылает его
     чинить руками то, что чинится одним нажатием.

     Полтора месяца это была не теория: iOS не слала поле НИКОГДА, и «Разрешить» показывалось
     всем подряд — при том что сам интент на iOS никто не перехватывал. Теперь оболочка шлёт
     третье состояние, и умолчание снова означает только «старая сборка». */
  it('поля нет — спрашиваем, а не ведём в настройки', () => {
    expect(спроситьМожно(мешает(снимок({ blockers: ['noPermission'] })))).toBe(true);
  });
});

describe('состояние пустого эфира', () => {
  const с = (o: Partial<Parameters<typeof пустота>[0]>) =>
    пустота({ эфирЕсть: true, сканирует: true, долгоЖдём: false, ...o });

  /* В браузере блютуса нет как класса, и списывать пустоту на разрешения — враньё: человек
     пойдёт их проверять и ничего не найдёт. Слова у состояний — в `слова/поиск.ts`. */
  it('браузер — это свойство браузера, а не настроек', () => {
    expect(с({ эфирЕсть: false })).toBe('эфира нет');
  });

  it('поиск не идёт — это своё состояние, а не разновидность пустоты', () => {
    expect(с({ сканирует: false })).toBe('поиск не идёт');
  });

  /* Первые секунды пустота — норма: реклама прибора приходит раз в несколько секунд. */
  it('ждём недолго и ждём долго — разные состояния', () => {
    expect(с({ долгоЖдём: false })).toBe('слушаю');
    expect(с({ долгоЖдём: true })).toBe('долго пусто');
  });
});

describe('терпение', () => {
  it('терпение — двенадцать секунд, и оно одно на всё приложение', () => {
    expect(ТЕРПЕНИЕ_МС).toBe(12_000);
  });
});
