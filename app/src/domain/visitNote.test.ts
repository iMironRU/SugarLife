import { describe, it, expect } from 'vitest';
import { полнота, оценка, строкиНМГ, вопросыДляВрача, динамика, сравнимо, чтоСталоЛучше, ЦЕЛИ, МИН_ДНЕЙ, МИН_ДОЛЯ, ШАГ_НМГ_МИН } from './visitNote';
import type { Entry } from '@/sources/nightscout';

/* Записку читает врач, а не мы. Ошибка здесь не роняет приложение — она молча меняет
   смысл документа: «в цели» вместо «мимо» или полный отчёт вместо дырявого. Проверить
   это глазами нельзя, потому что выглядит одинаково убедительно в обоих случаях. */

const ДЕНЬ = 24 * 3_600_000;
const КОНЕЦ = new Date(2026, 7, 13, 12, 0).getTime();

/** Ровный поток показаний каждые 5 минут на заданном числе дней. */
const поток = (дней: number, доля = 1): Entry[] => {
  const шаг = ШАГ_НМГ_МИН * 60_000;
  const начало = КОНЕЦ - дней * ДЕНЬ;
  const всего = Math.round((дней * ДЕНЬ) / шаг);
  const нужно = Math.round(всего * доля);
  return Array.from({ length: нужно }, (_, i) => ({ t: начало + i * шаг, mmol: 6 } as Entry));
};

describe('полнота данных', () => {
  /* Стандарт требует ≥14 дней и ≥70 % активного времени — это не наша придирчивость,
     а часть таблицы 6 рекомендаций. */
  it('две недели без пропусков — данных хватает', () => {
    const п = полнота(поток(14), КОНЕЦ - 14 * ДЕНЬ, КОНЕЦ);
    expect(п.дней).toBeGreaterThanOrEqual(МИН_ДНЕЙ);
    expect(Math.round(п.доля)).toBe(100);
    expect(п.хватает).toBe(true);
  });

  it('дыры больше трети — данных не хватает, даже если дни идут', () => {
    const п = полнота(поток(14, 0.6), КОНЕЦ - 14 * ДЕНЬ, КОНЕЦ);
    expect(Math.round(п.доля)).toBe(60);
    expect(п.хватает).toBe(false);
  });

  it('неделя вместо двух — не хватает дней, хотя пропусков нет', () => {
    const п = полнота(поток(7), КОНЕЦ - 14 * ДЕНЬ, КОНЕЦ);
    expect(п.дней).toBeLessThan(МИН_ДНЕЙ);
    expect(п.хватает).toBe(false);
  });

  it('пусто — ноль, а не деление на ноль', () => {
    const п = полнота([], КОНЕЦ - 14 * ДЕНЬ, КОНЕЦ);
    expect(п).toMatchObject({ дней: 0, доля: 0, хватает: false });
  });

  /* Показания вне окна в счёт не идут: иначе догруженная история за прошлый месяц
     нарисовала бы полноту там, где сенсор молчал. */
  it('чужие показания за окном не учитываем', () => {
    const старые = поток(14).map((e) => ({ ...e, t: e.t - 60 * ДЕНЬ }));
    expect(полнота(старые, КОНЕЦ - 14 * ДЕНЬ, КОНЕЦ).доля).toBe(0);
  });

  it('порог доли — ровно из документа', () => {
    expect(МИН_ДОЛЯ).toBe(70);
    expect(МИН_ДНЕЙ).toBe(14);
  });
});

describe('оценка по целям', () => {
  it('время в диапазоне: больше цели — в цели', () => {
    expect(оценка(72, 70, 'не меньше')).toBe('в цели');
    expect(оценка(68, 70, 'не меньше')).toBe('мимо');
  });

  it('время ниже: меньше цели — в цели', () => {
    expect(оценка(3, 4, 'не больше')).toBe('в цели');
    expect(оценка(5, 4, 'не больше')).toBe('мимо');
  });

  it('ровно на границе считаем достигнутым — иначе цель недостижима', () => {
    expect(оценка(70, 70, 'не меньше')).toBe('в цели');
    expect(оценка(4, 4, 'не больше')).toBe('в цели');
  });
});

describe('два набора целей', () => {
  const s = { target: 62, tbr: 2, tar: 36, cv: 34 };

  /* То самое, ради чего наборы разведены: одно и то же время в диапазоне читается
     по-разному, и без указания набора цифра ничего не значит. */
  it('62 % времени в диапазоне — мимо обычных целей и в цели по мягким', () => {
    expect(строкиНМГ(s, ЦЕЛИ.обычные)[0].итог).toBe('мимо');
    expect(строкиНМГ(s, ЦЕЛИ.мягкие)[0].итог).toBe('в цели');
  });

  /* А это обратная сторона: мягкие цели строже к гипогликемии, и «2 %» ниже
     диапазона — приемлемо по одному набору и мимо по другому. */
  it('2 % времени ниже — в цели по обычным и мимо по мягким', () => {
    expect(строкиНМГ(s, ЦЕЛИ.обычные)[1].итог).toBe('в цели');
    expect(строкиНМГ(s, ЦЕЛИ.мягкие)[1].итог).toBe('мимо');
  });

  it('порядок строк — как в таблице рекомендаций: диапазон, низкое, высокое, CV', () => {
    expect(строкиНМГ(s, ЦЕЛИ.обычные).map((r) => r.что.split(' ')[0]))
      .toEqual(['Время', 'Время', 'Время', 'Вариабельность']);
    expect(строкиНМГ(s, ЦЕЛИ.обычные)[1].что).toContain('ниже');
    expect(строкиНМГ(s, ЦЕЛИ.обычные)[2].что).toContain('выше');
  });
});

describe('черновик вопросов к врачу', () => {
  const н = (id: string, severity: string, title = 'Находка') => ({ id, severity, title });

  it('берём только то, что требует разговора', () => {
    const в = вопросыДляВрача([н('night-hypo', 'warn'), н('rebound', 'info'), н('dawn', 'bad')]);
    expect(в.map((x) => x.id)).toEqual(['night-hypo', 'dawn']);
  });

  /* Замена канюли и разряженный телефон — не тема пятнадцати минут с эндокринологом.
     Мы их видим и показываем в разборе, но в кабинет не тащим. */
  it('железо и пропуски данных в записку не идут', () => {
    expect(вопросыДляВрача([н('site', 'warn'), н('battery', 'bad'), н('phone', 'warn')])).toEqual([]);
  });

  it('одна находка — один вопрос, без повторов', () => {
    expect(вопросыДляВрача([н('dawn', 'warn'), н('dawn', 'bad')])).toHaveLength(1);
  });

  /* Вопрос, а не вывод: в записке не может быть назначения, даже очевидного. */
  it('формулировки остаются вопросами', () => {
    const все = вопросыДляВрача([
      н('night-hypo', 'warn'), н('dawn', 'warn'), н('basal', 'warn'), н('tbr', 'bad'),
    ]);
    expect(все.length).toBeGreaterThan(0);
    for (const в of все) expect(в.текст.endsWith('?')).toBe(true);
  });

  it('повод остаётся рядом — врачу видно, из чего вопрос вырос', () => {
    const [в] = вопросыДляВрача([н('night-hypo', 'warn', 'Ночные снижения: 6 за 14 дней')]);
    expect(в.повод).toBe('Ночные снижения: 6 за 14 дней');
  });
});

describe('динамика: стало лучше или хуже', () => {
  const было = { target: 46, tbr: 1.2, tar: 52, cv: 39, mean: 10.9 };

  /* Направление у каждого показателя своё: у времени в диапазоне лучше — больше, у
     времени ниже — меньше. Перепутать их значит похвалить человека за рост гипо. */
  it('рост времени в диапазоне — улучшение, рост времени ниже — нет', () => {
    const рост = динамика({ ...было, target: 56, tbr: 3.4 }, было);
    expect(рост.find((с) => с.что.includes('в диапазоне'))?.лучше).toBe(true);
    expect(рост.find((с) => с.что.includes('ниже'))?.лучше).toBe(false);
  });

  /* Разница в один процент — это шум одного неудачного обеда. Объявить её улучшением
     значит учить радоваться случайности. */
  it('мелкие сдвиги изменениями не считаем', () => {
    expect(динамика({ ...было, target: 47.5, cv: 40 }, было)).toEqual([]);
  });

  it('снижение средней глюкозы попадает в список как улучшение', () => {
    const с = динамика({ ...было, mean: 9.8 }, было);
    expect(с).toHaveLength(1);
    expect(с[0]).toMatchObject({ что: 'Средняя глюкоза', лучше: true, вид: 'глюкоза' });
  });

  it('нет данных за один из периодов — сравнивать нечего', () => {
    expect(динамика(null, было)).toEqual([]);
    expect(динамика(было, null)).toEqual([]);
  });
});

describe('можно ли сравнивать периоды', () => {
  const п = (доля: number) => ({ дней: 14, доля, хватает: доля >= МИН_ДОЛЯ });

  /* Дырявый прошлый период — главная ловушка блока: «время в диапазоне выросло» может
     значить лишь то, что пропущены были именно плохие часы. */
  it('дырявый период сравнению не подлежит', () => {
    expect(сравнимо(п(95), п(40))).toBe(false);
    expect(сравнимо(п(40), п(95))).toBe(false);
  });

  it('оба периода полные — сравниваем', () => {
    expect(сравнимо(п(95), п(88))).toBe(true);
  });
});

describe('чем похвастаться', () => {
  it('перечисляем то, что стало лучше', () => {
    const с = динамика({ target: 58, tbr: 0.4, tar: 40, cv: 34, mean: 9.9 },
      { target: 46, tbr: 1.2, tar: 52, cv: 39, mean: 10.9 });
    expect(чтоСталоЛучше(с)).toContain('время в диапазоне');
    expect(чтоСталоЛучше(с)).toContain('и ');
  });

  /* Выдуманная похвала обесценивает настоящую: если лучше не стало — молчим. */
  it('хвалить не за что — молчим', () => {
    const с = динамика({ target: 40, tbr: 3, tar: 58, cv: 42, mean: 11.9 },
      { target: 46, tbr: 1.2, tar: 52, cv: 39, mean: 10.9 });
    expect(с.length).toBeGreaterThan(0);
    expect(чтоСталоЛучше(с)).toBe(null);
  });
});

