/* Часы, когда человек мог поесть.

   Подсветка «еды не вносили N часов» считала календарное время — и в восемь утра
   объявляла восемь часов молчания. Но человек спал: восьмичасовой перерыв ночью это
   норма, а не забытая запись. Такое сообщение не просто бесполезно, оно вредно: если
   приложение регулярно говорит очевидную ерунду, его перестают читать вообще, и
   настоящее предупреждение тоже пройдёт мимо.

   Поэтому считаем не «сколько прошло», а «сколько прошло из того времени, когда человек
   бодрствовал». Ночь при этом не выдумываем по данным — берём разумную границу и
   называем её вслух. Учиться настоящему режиму сна по истории можно (ночь видна как
   отсутствие еды и ровный сахар), но это отдельная задача, а до неё честнее иметь
   явную границу, чем скрытую эвристику. */

export const НОЧЬ_С = 23;  // с этого часа не ждём еды
const НОЧЬ_ДО = 8;  // и до этого

const ЧАС = 3600e3;

function ночнойЧас(h: number): boolean {
  return h >= НОЧЬ_С || h < НОЧЬ_ДО;
}

/** Сколько «дневных» часов прошло между двумя моментами. */
export function часыБодрствования(от: number, до: number): number {
  if (!(до > от)) return 0;
  /* Идём по часам, а не считаем формулой: интервал бывает длиннее суток, и формула
     на переходах через полночь ошибается тихо. Шаг в минуту достаточно точен, а
     стоимость — тысячи итераций на неделю, это доли миллисекунды. */
  const шаг = 60e3;
  let бодрых = 0;
  for (let t = от; t < до; t += шаг) {
    if (!ночнойЧас(new Date(t).getHours())) бодрых += шаг;
  }
  return бодрых / ЧАС;
}
