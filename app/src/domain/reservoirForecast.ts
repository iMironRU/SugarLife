import type { BasalSegmentView } from '@/sources/bridge';

/* Хватит ли инсулина до утра (SugarLife#280).

   ОШИБКА НЕСИММЕТРИЧНА, и это главное в расчёте. Ошиблись в большую сторону — человек
   меняет картридж на пару часов раньше и теряет несколько единиц. Ошиблись в меньшую —
   просыпается в четыре утра с пустым резервуаром, а это кетоны. Поэтому считаем НИЖНЮЮ
   ГРАНИЦУ, а не ожидание: каждое слагаемое берётся в худшую сторону.

   И ВОПРОС ДРУГОЙ. Человек не спрашивает «сколько часов осталось» — он спрашивает
   «доживу ли до утра». Часы скачут на каждом болюсе и потому не запоминаются; ответ
   «хватит / не хватит до утра» устойчив и требует одного решения.

   ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Предсказания еды: она непредсказуема, и «средний болюс»
   вернул бы ту самую ошибку, от которой уходим. Статистики расхода по прошлым дням: она
   врёт ровно в день замены набора — самый дорогой день. */

/** Сколько инсулина уходит на заправку нового набора. Пессимистично: бывает и меньше. */
export const ЗАПРАВКА_ЕД = 15;

/** Запас на коррекции при высоком сахаре — за ночь, пессимистично. */
export const КОРРЕКЦИИ_ЕД = 4;

/** Ниже этого остатка тревожим независимо от времени: до утра тут дело не доживёт. */
export const КРИТИЧЕСКИЙ_ЕД = 10;

export type Прогноз = 'хватит' | 'не хватит до утра' | 'кончается сейчас' | 'неизвестно';

/** Сколько часов до ближайшего наступления времени «ЧЧ:ММ». */
export function часовДо(сейчасМс: number, время: string): number | null {
  const m = /^(\d{1,2}):(\d{2})$/.exec(время.trim());
  if (!m) return null;
  const ч = Number(m[1]); const мин = Number(m[2]);
  if (ч > 23 || мин > 59) return null;
  const д = new Date(сейчасМс);
  const цель = new Date(д.getFullYear(), д.getMonth(), д.getDate(), ч, мин, 0, 0);
  if (цель.getTime() <= сейчасМс) цель.setDate(цель.getDate() + 1);
  return (цель.getTime() - сейчасМс) / 3_600_000;
}

/* Сколько базала уйдёт за ближайшие N часов — по профилю, а не по средней.

   По ВЕРХНЕЙ ставке каждого часа: профиль знает, что под утро ставка выше, и размазывать
   это средней значит недосчитать ровно в те часы, когда человек спит. */
export function базалЗа(
  сегменты: BasalSegmentView[], сейчасМс: number, часов: number,
): number | null {
  if (!сегменты.length || часов <= 0) return null;
  const отсортированы = [...сегменты].sort((a, b) => a.startMinutes - b.startMinutes);
  const ставка = (минутаСуток: number): number => {
    let текущая = отсортированы[отсортированы.length - 1].rateUPerHour;
    for (const с of отсортированы) {
      if (с.startMinutes <= минутаСуток) текущая = с.rateUPerHour;
    }
    return текущая;
  };
  const д = new Date(сейчасМс);
  const начало = д.getHours() * 60 + д.getMinutes();
  let итог = 0;
  /* Шагаем получасом: сегменты профиля кратны получасу, и более мелкий шаг ничего не
     уточнит, а более крупный проскочит короткий утренний сегмент целиком. */
  const шагов = Math.ceil(часов * 2);
  for (let i = 0; i < шагов; i++) {
    const минута = (начало + i * 30) % 1440;
    итог += ставка(минута) * 0.5;
  }
  return итог;
}

export interface Вход {
  /** Остаток в единицах — из снимка (reservoirU), не из форматированной плашки. */
  остаток: number | null;
  /** Когда остаток прочитан с прибора. Помпа могла молчать час — тогда его уже меньше. */
  прочитаноМс?: number | null;
  сейчасМс: number;
  сегменты: BasalSegmentView[];
  /** «ЧЧ:ММ» — когда человек встаёт. Нет — до утра считать не от чего. */
  подъём?: string | null;
  /** Сахар высокий или растёт: значит ночью будут коррекции. */
  ждёмКоррекций?: boolean;
  /** Канюле подходит срок: значит будет заправка нового набора. */
  ждёмЗаправку?: boolean;
}

export interface Ответ {
  прогноз: Прогноз;
  /** Сколько нужно до подъёма по пессимистичному счёту; null — считать не от чего. */
  нужно: number | null;
  часовДоПодъёма: number | null;
}

export function хватитЛи(в: Вход): Ответ {
  const пусто: Ответ = { прогноз: 'неизвестно', нужно: null, часовДоПодъёма: null };
  if (в.остаток == null) return пусто;

  /* Остаток стареет: прочитали час назад — за этот час помпа уже подала. Вычитаем
     базал за прошедшее, иначе прогноз считается от несуществующего запаса. */
  const прошло = в.прочитаноМс ? Math.max(0, (в.сейчасМс - в.прочитаноМс) / 3_600_000) : 0;
  const израсходовано = прошло > 0 ? (базалЗа(в.сегменты, в.прочитаноМс!, прошло) ?? 0) : 0;
  const остаток = Math.max(0, в.остаток - израсходовано);

  if (остаток <= КРИТИЧЕСКИЙ_ЕД) {
    return { прогноз: 'кончается сейчас', нужно: null, часовДоПодъёма: null };
  }

  const часов = в.подъём ? часовДо(в.сейчасМс, в.подъём) : null;
  if (часов == null) return { ...пусто, прогноз: 'неизвестно' };

  const базал = базалЗа(в.сегменты, в.сейчасМс, часов);
  if (базал == null) return { ...пусто, прогноз: 'неизвестно', часовДоПодъёма: часов };

  const нужно = базал
    + (в.ждёмКоррекций ? КОРРЕКЦИИ_ЕД : 0)
    + (в.ждёмЗаправку ? ЗАПРАВКА_ЕД : 0);

  return {
    прогноз: остаток >= нужно ? 'хватит' : 'не хватит до утра',
    нужно, часовДоПодъёма: часов,
  };
}
