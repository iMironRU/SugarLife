import { describe, it, expect } from 'vitest';
import { хватитЛи, часовДо, базалЗа, ЗАПРАВКА_ЕД, КОРРЕКЦИИ_ЕД } from './reservoirForecast';

/* Прогноз резервуара (SugarLife#280). Ошибка здесь стоит ночи: человек просыпается в
   четыре утра с пустой помпой. Поэтому проверяем не «точность», а то, что счёт всегда
   уходит в безопасную сторону. */

const час = 3_600_000;
// 22:00 по местному — типичный момент, когда решают, менять ли картридж на ночь
const вечер = new Date(2026, 7, 15, 22, 0, 0).getTime();
const ровно = [{ startMinutes: 0, rateUPerHour: 1 }];

describe('часы до подъёма', () => {
  it('утро следующего дня, а не прошедшее сегодня', () => {
    expect(часовДо(вечер, '07:00')).toBe(9);
  });

  it('время уже наступило сегодня — значит завтра', () => {
    expect(часовДо(new Date(2026, 7, 15, 8, 0, 0).getTime(), '07:00')).toBe(23);
  });

  it('мусор вместо времени — молчим, а не считаем от нуля', () => {
    expect(часовДо(вечер, 'утром')).toBe(null);
    expect(часовДо(вечер, '25:00')).toBe(null);
  });
});

describe('базал по профилю', () => {
  it('ровный профиль: сколько часов — столько единиц', () => {
    expect(базалЗа(ровно, вечер, 9)).toBeCloseTo(9, 1);
  });

  /* Профиль знает, что под утро ставка выше. Средняя размазала бы это по суткам и
     недосчитала ровно в те часы, когда человек спит. */
  it('утренний сегмент считается по своей ставке, а не по средней', () => {
    /* Профиль читается как расписание суток: ставка держится от своего начала до
       начала следующей. Заря — это отдельный кусок 03:00–07:00, и закрыть его надо
       третьим сегментом, иначе повышенная ставка растянется до полуночи. */
    const сЗарёй = [
      { startMinutes: 0, rateUPerHour: 1 },
      { startMinutes: 3 * 60, rateUPerHour: 2 },
      { startMinutes: 7 * 60, rateUPerHour: 1 },
    ];
    // 22:00 → 07:00: пять часов по 1 (22–03) и четыре по 2 (03–07)
    expect(базалЗа(сЗарёй, вечер, 9)).toBeCloseTo(5 + 8, 1);
  });

  it('профиля нет — не выдумываем', () => {
    expect(базалЗа([], вечер, 9)).toBe(null);
  });
});

describe('хватит ли до утра', () => {
  const база = { сейчасМс: вечер, сегменты: ровно, подъём: '07:00' };

  it('запаса с избытком — молчим', () => {
    expect(хватитЛи({ ...база, остаток: 40 }).прогноз).toBe('хватит');
  });

  it('впритык по базалу — уже не хватит', () => {
    // нужно 9 ед за ночь, осталось 12, но критический порог 10 ещё не задет
    expect(хватитЛи({ ...база, остаток: 12 }).прогноз).toBe('хватит');
    expect(хватитЛи({ ...база, остаток: 12, ждёмКоррекций: true }).прогноз).toBe('не хватит до утра');
  });

  /* Высокий сахар с ростом ночью стоит инсулина. Средняя скорость этого не знает — и
     ровно на этом прогноз ошибался в опасную сторону. */
  it('ждём коррекций — закладываем их заранее', () => {
    const без = хватитЛи({ ...база, остаток: 30 }).нужно ?? 0;
    const с = хватитЛи({ ...база, остаток: 30, ждёмКоррекций: true }).нужно ?? 0;
    expect(с - без).toBe(КОРРЕКЦИИ_ЕД);
  });

  it('канюле подходит срок — закладываем заправку', () => {
    const без = хватитЛи({ ...база, остаток: 30 }).нужно ?? 0;
    const с = хватитЛи({ ...база, остаток: 30, ждёмЗаправку: true }).нужно ?? 0;
    expect(с - без).toBe(ЗАПРАВКА_ЕД);
  });

  /* Остаток стареет: помпа могла молчать час, и за этот час она подавала. Считать от
     старого числа — считать от запаса, которого уже нет. */
  it('остаток стареет вместе с молчанием помпы', () => {
    const свежий = хватитЛи({ ...база, остаток: 12, ждёмКоррекций: true, прочитаноМс: вечер });
    const старый = хватитЛи({ ...база, остаток: 12, ждёмКоррекций: true, прочитаноМс: вечер - 3 * час });
    expect(свежий.прогноз).toBe('не хватит до утра');
    /* Те же двенадцать единиц, прочитанные три часа назад, — это уже девять: помпа всё
       это время подавала. И девять — ниже критического порога, то есть вердикт меняется
       не на градус, а на ступень. Ровно ради этого случая контракт и завёл время
       чтения отдельным полем. */
    expect(старый.прогноз).toBe('кончается сейчас');
    expect(хватитЛи({ ...база, остаток: 14, прочитаноМс: вечер }).прогноз).toBe('хватит');
  });

  /* Ниже критического порога время суток роли не играет: до утра тут дело не доживёт,
     и молчать до вечернего окна нельзя. */
  it('совсем мало — тревожим сразу, не дожидаясь ночи', () => {
    expect(хватитЛи({ ...база, остаток: 8 }).прогноз).toBe('кончается сейчас');
  });

  it('не знаем времени подъёма — не выдумываем ответ', () => {
    expect(хватитЛи({ ...база, остаток: 30, подъём: null }).прогноз).toBe('неизвестно');
  });

  it('остатка не знаем вовсе — тоже молчим', () => {
    expect(хватитЛи({ ...база, остаток: null }).прогноз).toBe('неизвестно');
  });
});
