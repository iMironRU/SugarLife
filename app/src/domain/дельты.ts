import type { Entry } from '@/sources/nightscout';

/*
 * ЛЕНТА НМГ: ПЯТИМИНУТКИ И ТРИ ДЕЛЬТЫ (#698).
 *
 * Минутные показания у нас есть — 1416 за сутки, медианный интервал шестьдесят секунд. Читать их
 * подряд бесполезно: минутный шаг даёт шум, а не картину. И читает человек не «сколько сейчас» —
 * это и так стоит в круге, — а «куда идёт и как быстро». Это дельта, а не значение.
 *
 * ТРИ ГОРИЗОНТА ОТВЕЧАЮТ НА ТРИ РАЗНЫХ ВОПРОСА одной строкой:
 *   5 минут  — что происходит прямо сейчас;
 *   15 минут — устойчиво ли это (столько же длится окно, по которому считается стрелка);
 *   45 минут — куда всё идёт на самом деле.
 *
 * ПРАВИЛО ОДНО И ЖИВЁТ ЗДЕСЬ. Дважды уже чинили расползшиеся правила: две таблицы стрелок (#215) и
 * два набора периодов (#690). Дельта в ленте и «разница» на баннере отвечают на один вопрос, и
 * считаются одинаково: концы и молчание, когда конца нет. (Половина на айфоне пока своя —
 * `ЧтениеСнимка.дельта`; это известное задвоение, а не недосмотр.)
 */

/** Шаг ленты: одна строка — одна пятиминутка. Тот же шаг, что у показа ряда на всех поверхностях. */
export const ШАГ_МИН = 5;

/** Горизонты дельт, минуты. Порядок — от «сейчас» к «на самом деле», в нём же и показываем. */
export const ГОРИЗОНТЫ = [5, 15, 45] as const;

/** Сколько ленты показываем по умолчанию: полтора-два часа, дальше — график. */
export const ОКНО_МИН = 120;

/*
 * ДОПУСК К КОНЦУ ДЕЛЬТЫ — ПОЛОВИНА ШАГА.
 *
 * Показание ровно в «сорок пять минут назад» бывает редко: сенсор отдаёт когда отдаёт. Ближайшее в
 * пределах половины шага — это та же пятиминутка, и брать его честно. Дальше — уже другая, и
 * подписать её чужим горизонтом значит соврать в подписи, а не в числе.
 */
const ДОПУСК_МС = (ШАГ_МИН / 2) * 60_000;

/** Одна строка ленты. */
export interface Пятиминутка {
  /** Начало пятиминутки на сетке — по нему строка названа и по нему считаются дельты. */
  метка: number;
  /** Момент последнего показания внутри. */
  t: number;
  /** Значение строки — ПОСЛЕДНЕЕ измеренное внутри пятиминутки, а не среднее по ней.
      Среднее — число, которого никто не мерил; таким человек считает дозу. */
  mmol: number;
  /** Минутные показания внутри, от новых к старым. Ради них строка и раскрывается. */
  точки: Entry[];
  /** Дельты по [ГОРИЗОНТЫ], в ммоль/л. `null` — молчим: конца в данных нет. */
  дельты: Array<number | null>;
}

/**
 * ДЕЛЬТА ЗА ГОРИЗОНТ: РАЗНИЦА МЕЖДУ ДВУМЯ КОНЦАМИ.
 *
 * `null` — нет показания рядом с дальним концом. Это единственная причина молчать, и вот почему:
 * дельта отвечает «на сколько изменилось между двумя моментами», и дыра ПОСЕРЕДИНЕ горизонта
 * этого ответа не портит — она портит рассказ о том, как именно шло, а на него отвечает график.
 * А вот выдуманный дальний конец портит само число.
 *
 * (В задаче предполагалось молчать и при дыре в середине. Разобрав, оставили только концы:
 * молчать там, где мы знаем ответ, — это тоже потеря, а лишнего обещания «как шло» строка не даёт.)
 *
 * `ряд` — по возрастанию времени; ищем ближайшее к моменту `момент − горизонт`.
 */
export function дельта(ряд: Entry[], момент: number, горизонтМин: number, значение: number): number | null {
  const цель = момент - горизонтМин * 60_000;
  const конец = ближайшее(ряд, цель);
  if (конец == null || Math.abs(конец.t - цель) > ДОПУСК_МС) return null;
  return значение - конец.mmol;
}

/** Ближайшее по времени показание. Двоичным поиском: ряд за сутки — это полторы тысячи точек. */
function ближайшее(ряд: Entry[], цель: number): Entry | null {
  if (!ряд.length) return null;
  let лево = 0, право = ряд.length - 1;
  while (лево < право) {
    const середина = (лево + право) >> 1;
    if (ряд[середина].t < цель) лево = середина + 1; else право = середина;
  }
  const справа = ряд[лево];
  const слева = лево > 0 ? ряд[лево - 1] : null;
  if (!слева) return справа;
  return Math.abs(слева.t - цель) <= Math.abs(справа.t - цель) ? слева : справа;
}

/**
 * Лента: пятиминутки от новых к старым.
 *
 * `entries` — весь ряд по возрастанию: дельты у САМОЙ СТАРОЙ строки смотрят на сорок пять минут
 * дальше окна, и обрезать ряд по окну значило бы получить прочерки на ровном месте.
 */
export function пятиминутки(entries: Entry[], сейчас = Date.now(), окноМин = ОКНО_МИН): Пятиминутка[] {
  const ряд = [...entries].sort((a, b) => a.t - b.t);
  const от = сейчас - окноМин * 60_000;
  const шагМс = ШАГ_МИН * 60_000;

  const корзины = new Map<number, Entry[]>();
  for (const e of ряд) {
    if (e.t < от) continue;
    const метка = Math.floor(e.t / шагМс) * шагМс;
    const было = корзины.get(метка);
    if (было) было.push(e); else корзины.set(метка, [e]);
  }

  return [...корзины.entries()]
    .sort((a, b) => b[0] - a[0])
    .map(([метка, точки]) => {
      const последняя = точки[точки.length - 1];
      return {
        метка,
        t: последняя.t,
        mmol: последняя.mmol,
        точки: [...точки].reverse(),
        дельты: ГОРИЗОНТЫ.map((г) => дельта(ряд, последняя.t, г, последняя.mmol)),
      };
    });
}
