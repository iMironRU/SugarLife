import { describe, it, expect } from 'vitest';
import { пятиминутки, дельта, ГОРИЗОНТЫ, ШАГ_МИН } from './дельты';
import type { Entry } from '@/domain/types';

/* Лента НМГ: пятиминутки и три дельты (#698).

   Дельта — то, ради чего экран и переделан: человек читает не «сколько», а «куда и как быстро».
   Поэтому здесь сторожим не форму строки, а число и МОЛЧАНИЕ: подпись «за 45 минут» на числе,
   посчитанном по показанию сорокаминутной давности, — враньё в подписи. */

const МИН = 60_000;
const БАЗА = 1_700_000_000_000 - (1_700_000_000_000 % (5 * МИН)); // ровно на сетке пятиминуток

const точка = (минутНазад: number, mmol: number): Entry => ({
  t: БАЗА - минутНазад * МИН, mgdl: Math.round(mmol * 18.016), mmol, dir: '',
});

/** Ряд по минуте: значение растёт на 0,1 каждую минуту в прошлое → к «сейчас» падает. */
const ровныйРяд = (минут: number, начало = 6.0, шаг = 0.1): Entry[] =>
  Array.from({ length: минут }, (_, i) => точка(минут - 1 - i, начало + (минут - 1 - i) * шаг))
    .sort((a, b) => a.t - b.t);

describe('дельта', () => {
  it('разница между концами, а не наклон', () => {
    const ряд = [точка(45, 5.0), точка(15, 6.0), точка(5, 6.4), точка(0, 6.6)];
    expect(дельта(ряд, БАЗА, 5, 6.6)).toBeCloseTo(0.2, 6);
    expect(дельта(ряд, БАЗА, 15, 6.6)).toBeCloseTo(0.6, 6);
    expect(дельта(ряд, БАЗА, 45, 6.6)).toBeCloseTo(1.6, 6);
  });

  /* Дальний конец есть, но не там: показание за 40 минут не отвечает на вопрос «за 45».
     Полшага допуска — это та же пятиминутка; дальше молчим. */
  it('нет показания у дальнего конца — молчим', () => {
    const ряд = [точка(40, 5.0), точка(0, 6.6)];
    expect(дельта(ряд, БАЗА, 45, 6.6)).toBeNull();
  });

  it('внутри полушага допуска считаем', () => {
    const ряд = [точка(47, 5.0), точка(0, 6.6)];
    expect(дельта(ряд, БАЗА, 45, 6.6)).toBeCloseTo(1.6, 6);
    expect(дельта([точка(48, 5.0), точка(0, 6.6)], БАЗА, 45, 6.6)).toBeNull();
  });

  /* Дыра ПОСЕРЕДИНЕ горизонта числу не мешает: дельта отвечает «на сколько изменилось между двумя
     моментами», а «как именно шло» рассказывает график. */
  it('дыра посередине не мешает — концы на месте', () => {
    const ряд = [точка(45, 5.0), точка(44, 5.0), точка(1, 6.5), точка(0, 6.6)];
    expect(дельта(ряд, БАЗА, 45, 6.6)).toBeCloseTo(1.6, 6);
  });

  it('пустой ряд — молчание, а не ноль', () => {
    expect(дельта([], БАЗА, 5, 6.6)).toBeNull();
  });

  it('падение отдаёт отрицательное число', () => {
    expect(дельта([точка(5, 7.0), точка(0, 6.4)], БАЗА, 5, 6.4)).toBeCloseTo(-0.6, 6);
  });
});

describe('пятиминутки', () => {
  it('строка — одна пятиминутка, новые сверху', () => {
    /* Тридцать минут по минуте задевают семь пятиминуток: показание ровно на границе сетки
       открывает новую. */
    const лента = пятиминутки(ровныйРяд(30), БАЗА + 30_000, 120);
    expect(лента.length).toBe(7);
    expect(лента[0].метка).toBeGreaterThan(лента[1].метка);
    expect(лента[0].метка % (ШАГ_МИН * МИН)).toBe(0);
  });

  /* Значение строки — ПОСЛЕДНЕЕ измеренное внутри, а не среднее: среднее это число, которого
     никто не мерил, а по числу на экране человек считает дозу. */
  it('значение строки — последнее измеренное внутри', () => {
    const ряд = [точка(4, 6.0), точка(3, 6.1), точка(2, 6.9)].sort((a, b) => a.t - b.t);
    const лента = пятиминутки(ряд, БАЗА, 120);
    expect(лента[0].mmol).toBe(6.9);
    expect(лента[0].точки.map((p) => p.mmol)).toEqual([6.9, 6.1, 6.0]);
  });

  it('у каждой строки три дельты в порядке горизонтов', () => {
    const лента = пятиминутки(ровныйРяд(60), БАЗА, 120);
    expect(лента[0].дельты).toHaveLength(ГОРИЗОНТЫ.length);
    /* Ряд падает на 0,1 в минуту к «сейчас»: за 5 минут −0,5, за 15 −1,5, за 45 −4,5. */
    expect(лента[0].дельты[0]).toBeCloseTo(-0.5, 6);
    expect(лента[0].дельты[1]).toBeCloseTo(-1.5, 6);
    expect(лента[0].дельты[2]).toBeCloseTo(-4.5, 6);
  });

  /* Старым строкам дальний конец лежит ЗА окном ленты. Обрезав ряд по окну, мы получили бы
     прочерки на ровном месте — там, где данные есть. */
  it('дельты старых строк смотрят за окно ленты', () => {
    const лента = пятиминутки(ровныйРяд(120), БАЗА, 30);
    const самая = лента[лента.length - 1];
    expect(самая.дельты[2]).not.toBeNull();
  });

  it('нет данных — нет строк', () => {
    expect(пятиминутки([], БАЗА, 120)).toEqual([]);
  });

  /* Час тишины и одно свежее показание: строка есть, дельт нет ни одной. Прочерк здесь — ответ. */
  it('после долгой тишины строка молчит всеми тремя', () => {
    const лента = пятиминутки([точка(90, 5.0), точка(0, 6.6)], БАЗА, 120);
    expect(лента[0].дельты).toEqual([null, null, null]);
  });
});
