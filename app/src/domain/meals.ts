import type { Treatment } from './types';

/* Приём пищи, внесённый в приложении.

   Три решения, которые определяют всю дальнейшую жизнь этой сущности.

   ПЕРВОЕ: храним в граммах, всегда. Х.Е. — это представление, а не единица хранения:
   один и тот же приём должен читаться одинаково у человека, считающего в граммах, и у
   того, кто считает в хлебных единицах, а коэффициент пересчёта у разных школ разный.
   Записав «2 Х.Е.», мы навсегда потеряли бы, сколько это граммов.

   ВТОРОЕ: время ЕДЫ, а не время внесения. Это не педантизм: активные углеводы
   считаются от момента еды, и запись «съел полчаса назад», сохранённая как «сейчас»,
   сдвигает всю кривую на полчаса и вместе с ней — расчёт дозы. Поэтому время
   спрашиваем и по умолчанию не подставляем «сейчас» молча.

   ТРЕТЬЕ: у записи есть состояние доставки. Куда именно уедет приём — в Nightscout
   напрямую, через мост в ядро или никуда, — вопрос открытый, и он НЕ должен влиять на
   ввод. Человек внёс еду, запись легла в свою базу и живёт. Появится адресат — её
   заберёт отправитель, ничего не меняя ни в интерфейсе, ни в хранении. Это обычная
   исходящая очередь, и она же даёт офлайн бесплатно.

   Идентификатор локальный и стабильный: он станет ключом идемпотентности, когда
   доставка появится. Иначе повторная отправка после обрыва задвоит приём — а
   задвоенные углеводы это задвоенная доза. */

export type MealSync = 'local' | 'pending' | 'sent' | 'failed';

export interface Meal {
  id: string;
  /** Когда ЕЛИ (не когда внесли). */
  t: number;
  /** Углеводы в граммах — всегда. */
  carbs: number;
  /** Болюс на этот приём, если вводили. Не считаем сами: доза — решение человека. */
  insulin?: number;
  /** Завтрак/обед/ужин/перекус — свободная метка, для чтения истории. */
  kind?: string;
  note?: string;
  /** Когда запись создана — отдельно от времени еды, для разбора «когда вносят». */
  createdAt: number;
  sync: MealSync;
}

export interface NewMeal {
  t: number;
  carbs: number;
  insulin?: number;
  kind?: string;
  note?: string;
}

/* Идентификатор: время еды + углеводы + случайная соль. Время и углеводы в ключе не
   для красоты — они делают повтор одного и того же приёма распознаваемым, даже если
   запись пришла из другой копии приложения. */
export function makeMeal(m: NewMeal, now = Date.now(), salt = Math.random()): Meal {
  const соль = Math.floor(salt * 1e6).toString(36);
  return {
    id: `m${m.t}-${Math.round(m.carbs)}-${соль}`,
    t: m.t,
    carbs: m.carbs,
    insulin: m.insulin,
    kind: m.kind,
    note: m.note,
    createdAt: now,
    sync: 'local',
  };
}

/* Тот же приём пришёл из облака.

   Когда доставка появится, наши записи вернутся к нам же через Nightscout — и без
   склейки человек увидит каждый приём дважды. Считаем совпадением близкое время и
   те же углеводы: время может разъехаться на секунды из-за округлений на той стороне,
   а вот количество углеводов совпадает точно — его никто по дороге не пересчитывает. */
const ОКНО_СКЛЕЙКИ_МС = 5 * 60e3;

export function sameMeal(m: Meal, t: Treatment): boolean {
  const углеводы = t.carbs ?? 0;
  if (Math.round(углеводы) !== Math.round(m.carbs)) return false;
  return Math.abs(t.t - m.t) <= ОКНО_СКЛЕЙКИ_МС;
}

/** Наши записи, которых ещё нет в облаке. Остальные показываем из облака как обычно. */
export function onlyLocal(meals: Meal[], cloud: Treatment[]): Meal[] {
  const еда = cloud.filter((t) => (t.carbs ?? 0) > 0);
  return meals.filter((m) => !еда.some((t) => sameMeal(m, t)));
}

/* Быстрые смещения времени. «Сейчас» первым, но не единственным: спросить, когда ели,
   дешевле, чем потом объяснять, почему расчёт разошёлся с ощущениями. */
export const СМЕЩЕНИЯ: { label: string; ms: number }[] = [
  { label: 'сейчас', ms: 0 },
  { label: '15 мин', ms: 15 * 60e3 },
  { label: '30 мин', ms: 30 * 60e3 },
  { label: '1 ч', ms: 60 * 60e3 },
  { label: '2 ч', ms: 2 * 60 * 60e3 },
];
