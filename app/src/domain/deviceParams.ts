import type { UiSnapshot, DeviceView } from '@/sources/bridge';
import { устройствоРоли } from './deviceState';

/* Куда писать параметры драйвера — серийник помпы, частоту радио (SugarLife#224).

   Раньше они жили только у нас, в `sl.device.v1`. Причина была честной: нативного моста
   не существовало, а класть серийник некуда. Теперь движок есть, у него для этого
   отдельный интент `setParams`, и хранить их у себя — значит держать второй экземпляр
   того же знания.

   Разница не косметическая: параметры нужны ДРАЙВЕРУ. Серийник, введённый в приложении
   и осевший в localStorage, для чтения помпы по радио бесполезен — драйвер его не
   увидит. Человек при этом уверен, что ввёл: поле заполнено, галочка стоит.

   ЧТО ОСТАЁТСЯ У НАС. Тот же ввод в браузере: там движка нет вовсе, и единственное
   место — localStorage. Поэтому здесь развилка, а не замена; она же — ответ на вопрос
   «куда писать», а сам ввод одинаков.

   ЧЕГО ЗДЕСЬ НЕТ. Секретов. Пароли от чужих облаков в браузер не кладём вовсе, и в
   параметрах драйвера им тоже не место (SugarLifeCore#3): `Param.type: 'Secret'`
   пишется только в движок и обратно не читается. */

/** Кому адресованы параметры этой категории — устройство в снимке или наш конфиг. */
export function устройствоДляПараметров(
  snap: UiSnapshot | null | undefined, cat: string,
): DeviceView | null {
  if (cat !== 'pump' && cat !== 'sensor') return null;
  return устройствоРоли(snap, cat);
}

/* Значения для формы: из снимка, если движок их знает, иначе локальные.

   Приоритет у движка ровно потому же, почему и в остальном: он читает драйвером, а мы
   пишем. Разойтись эти два набора могут (человек ввёл серийник на другом телефоне), и
   тогда правильный ответ — тот, с которым реально работает драйвер. */
export function значенияПараметров(
  устройство: DeviceView | null,
  локальные: Record<string, string>,
): Record<string, string> {
  const изДвижка = устройство?.params;
  if (!изДвижка) return локальные;
  /* Локальные не подмешиваем: полупустая форма честнее, чем поле, заполненное из
     нашего кэша, — иначе человек не отличит «драйвер это знает» от «мы это помним». */
  return изДвижка;
}
