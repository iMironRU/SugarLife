/* ОДИН ПРИБОР, ДВА ИМЕНИ (SugarLife#770, хвост #281).

   На экране одновременно жили «Medtronic 722» и «Paradigm 522/722», и владелец справедливо
   спросил, какая из двух железок его. Имена приходят из разных мест, и оба верны: прибор
   представляется по своему протоколу — коротко и без семейства, а справочник хранит семейство,
   потому что резервуар и спецификации у 522 и 722 общие и разделять их там незачем.

   Формулировка ядра точнее нашей: они ОТВЕЧАЮТ НА РАЗНЫЕ ВОПРОСЫ, НО ВЫГЛЯДЯТ КАК ОДИН ОТВЕТ.

   Поэтому выбирать между ними нельзя — оба нужны. Можно только показать их так, чтобы связь
   читалась: имя из эфира крупно (его человек сверит с надписью на корпусе), имя справочника —
   подписью с ролью, а не вторым заголовком.

   Своей таблицы «как правильно называется» здесь нет и не будет: она разошлась бы со
   справочником в первую же правку — так у нас уже расходились две таблицы стрелок и два набора
   периодов. Тут только сравнение двух готовых строк. */

/** Буквы и цифры, без регистра и разделителей: «Paradigm 522/722» и «paradigm-522-722» — одно. */
const свести = (s: string) => s.toLowerCase().replace(/[^a-zа-яё0-9]+/gi, '');

/**
 * Имя справочника, если его стоит показать рядом с именем из эфира.
 *
 * `null` — показывать нечего: имя одно, или они совпали, или одно целиком входит в другое
 * («MiniMed 780G» и «MiniMed 780G (Guardian 4)»). Второе имя ради полноты — это ровно та
 * вторая железка, из-за которой задача и заведена.
 */
export function имяСправочникаРядом(
  вЭфире: string | null | undefined,
  справочник: string | null | undefined,
): string | null {
  const с = (справочник ?? '').trim();
  const э = (вЭфире ?? '').trim();
  /* Имя одно — связывать не с чем, и подпись только добавила бы шума. */
  if (!с || !э) return null;
  const a = свести(э), b = свести(с);
  if (!a || !b) return null;
  if (a === b || a.includes(b) || b.includes(a)) return null;
  return с;
}
