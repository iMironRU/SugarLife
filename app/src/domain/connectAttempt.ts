/* Попытка связи: что показывать между «нажал» и «ответило» (SugarLife#303).

   Кнопка показывала доставку интента, а не попытку связи. Движок отвечает «принял» за
   миллисекунды, поэтому «Подключаю…» мелькало быстрее глаза, и человек видел ровно то
   же, что при сломанной кнопке: тап — и ничего. Это неотличимо от поломки, которую мы
   чинили в #301, и найдено ровно там же — на телефоне с настоящей помпой за мостом.

   ПРИНЯЛ И ДОЗВОНИЛСЯ — РАЗНЫЕ СОБЫТИЯ. Первое подтверждает движок сразу, второе видно
   только по снимку: связь у прибора меняется, когда она действительно изменилась. Ждём
   поэтому снимок, а не ответ интента.

   ОЖИДАНИЕ ОБЯЗАНО КОНЧАТЬСЯ. «Подключаюсь…» навсегда — то же молчание, только с
   анимацией. Через срок говорим прямо: не ответил. Для помпы за мостом это нормальное
   состояние, а не сбой: она спит между обменами и может быть занята другим телефоном. */

/** Сколько ждать, прежде чем признать, что прибор не ответил.

    Тридцать секунд — не круглое число «на глаз»: обмен через радиомост идёт заметно
    дольше прямого BLE, и ядро закладывает на квитанцию помпы восемь секунд (core#59).
    Меньше — и мы объявим молчанием обычный медленный обмен; больше — и человек успеет
    решить, что приложение зависло. Величину стоит сверить с ядром, когда у них появится
    честное «взял в работу / дозвонился». */
export const СРОК_ОЖИДАНИЯ_МС = 30_000;

export type Цель = 'связь' | 'разрыв';
export type Ход = 'идёт' | 'получилось' | 'не ответил';

export interface Попытка {
  /** Прибор, к которому относится ожидание: карточку могли закрыть и открыть другую. */
  id: string;
  цель: Цель;
  началоМс: number;
}

export function ходПопытки(п: Попытка, живой: boolean, сейчасМс: number): Ход {
  const достигнута = п.цель === 'связь' ? живой : !живой;
  if (достигнута) return 'получилось';
  return сейчасМс - п.началоМс > СРОК_ОЖИДАНИЯ_МС ? 'не ответил' : 'идёт';
}

/** Слово для строки списка: карточку могли закрыть, а ожидание продолжается. */
export function словоОжидания(п: Попытка | null, id: string, живой: boolean, сейчасМс: number): string | null {
  if (!п || п.id !== id) return null;
  const ход = ходПопытки(п, живой, сейчасМс);
  if (ход === 'получилось') return null;
  if (ход === 'не ответил') return п.цель === 'связь' ? 'не ответил' : 'не отпустился';
  return п.цель === 'связь' ? 'подключаюсь…' : 'отпускаю…';
}

/* Почему не ответил — без выдумок о причине.

   Назвать одну причину мы не можем: движок различает «занят другим телефоном» лишь как
   догадку, а «далеко» не знает вовсе. Поэтому перечисляем то, что человек может
   проверить сам, и в порядке вероятности для прибора за мостом. */
export function почемуМолчит(цель: Цель): string {
  return цель === 'связь'
    ? 'Прибор не ответил. Так бывает: он спит между обменами, лежит далеко или занят другим телефоном. Можно попробовать ещё раз.'
    : 'Прибор не отпустился. Попробуйте ещё раз — связь могла быть занята обменом.';
}
