import { describe, it, expect } from 'vitest';
import { тихоСейчас, ТИХО_ВЫКЛ } from './тихиеЧасы';

/* Окно тихих часов почти всегда переходит через полночь — их для того и заводят, чтобы
   захватить ночь. Значит «с 23 до 7» это не край, а обычный случай, и проверять надо
   именно его: наивное сравнение «час между началом и концом» здесь молчит всю ночь и
   звенит весь день. */

describe('тихие часы', () => {
  it('не заданы — тишины нет', () => {
    expect(тихоСейчас(3, ТИХО_ВЫКЛ, ТИХО_ВЫКЛ)).toBe(false);
    expect(тихоСейчас(3, 23, ТИХО_ВЫКЛ)).toBe(false);
  });

  it('окно внутри суток', () => {
    expect(тихоСейчас(14, 13, 16)).toBe(true);
    expect(тихоСейчас(12, 13, 16)).toBe(false);
    expect(тихоСейчас(16, 13, 16)).toBe(false); // конец не включаем
  });

  it('окно через полночь — обычный случай, а не край', () => {
    expect(тихоСейчас(23, 23, 7)).toBe(true);
    expect(тихоСейчас(3, 23, 7)).toBe(true);
    expect(тихоСейчас(6, 23, 7)).toBe(true);
    expect(тихоСейчас(7, 23, 7)).toBe(false);
    expect(тихоСейчас(12, 23, 7)).toBe(false);
  });

  /* Начало равно концу — это не «сутки тишины», а незаполненная настройка. Считать иначе
     значит однажды заглушить тревоги на весь день по опечатке. */
  it('начало равно концу — тишины нет', () => {
    expect(тихоСейчас(5, 8, 8)).toBe(false);
  });
});
