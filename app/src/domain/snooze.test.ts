import { describe, it, expect } from 'vitest';
import { показывать, убратьЛишние, type Отложения } from './snooze';

/* Правило откладывания под тестами целиком: ошибка здесь не видна на экране — она
   выглядит как «подсветка почему-то не пришла». Медицинское предупреждение, которое
   молча не показалось, хуже назойливого. */

const отложено = (эпизод: string, уровень: number): Отложения => ({ battery: { эпизод, уровень } });

describe('показывать ли отложенную подсветку', () => {
  it('ничего не откладывали — показываем', () => {
    expect(показывать({}, 'battery', 'э1', 97, 3)).toBe(true);
  });

  it('отложили и ничего не изменилось — молчим', () => {
    expect(показывать(отложено('э1', 97), 'battery', 'э1', 97, 3)).toBe(false);
  });

  /* Батарейку поменяли и она снова села — это другой случай, а не тот же самый.
     Молчать по прошлому решению значило бы пропустить новую разрядку. */
  it('сменился эпизод — показываем, что бы ни откладывали раньше', () => {
    expect(показывать(отложено('э1', 97), 'battery', 'э2', 50, 3)).toBe(true);
  });

  it('стало хуже на шаг — возвращаемся', () => {
    expect(показывать(отложено('э1', 97), 'battery', 'э1', 100, 3)).toBe(true);
  });

  it('стало хуже, но меньше чем на шаг — ещё молчим', () => {
    expect(показывать(отложено('э1', 97), 'battery', 'э1', 99, 3)).toBe(false);
  });

  /* Уровень может и падать: помпа показала 4% после 3%, оценка часов подросла.
     Это не повод возвращаться — стало лучше, а не хуже. */
  it('стало лучше — молчим', () => {
    expect(показывать(отложено('э1', 97), 'battery', 'э1', 90, 3)).toBe(false);
  });

  it('чужая подсветка своим отложением не затыкается', () => {
    expect(показывать(отложено('э1', 97), 'reservoir', 'э1', 97, 3)).toBe(true);
  });
});

describe('уборка отложений', () => {
  it('эпизод сменился — запись больше ни на что не влияет, выбрасываем', () => {
    const итог = убратьЛишние({ battery: { эпизод: 'старый', уровень: 97 } }, { battery: 'новый' });
    expect(итог).toEqual({});
  });

  it('эпизод тот же — оставляем', () => {
    const было: Отложения = { battery: { эпизод: 'э1', уровень: 97 } };
    expect(убратьЛишние(было, { battery: 'э1' })).toEqual(было);
  });

  /* Про подсветку, которой сейчас нет на экране, мы не знаем, сменился ли её эпизод.
     Выбросить отложение значило бы показать её заново без причины. */
  it('подсветки сейчас нет — запись не трогаем', () => {
    const было: Отложения = { battery: { эпизод: 'э1', уровень: 97 } };
    expect(убратьЛишние(было, {})).toEqual(было);
  });
});
