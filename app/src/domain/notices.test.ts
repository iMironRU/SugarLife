import { describe, it, expect } from 'vitest';
import { поВажности, ВАЖНОСТЬ } from './notices';

/* Порядок обращений решает, что человек увидит первым, а увидит он два-три верхних.
   Ошибка здесь не ломает экран — она просто задвигает вниз то, из-за чего через час
   остановится помпа. */

describe('порядок обращений', () => {
  it('сверху то, из-за чего прервётся подача', () => {
    const п = поВажности([{ id: 'nofood' }, { id: 'update' }, { id: 'battery' }, { id: 'reservoir-night' }]);
    expect(п.map((x) => x.id)).toEqual(['battery', 'reservoir-night', 'nofood', 'update']);
  });

  /* Данные важнее напоминаний: неподтверждённая заправка делает неверным возраст
     расходников, а «давно не ели» — это просто напоминание. */
  it('порча данных выше напоминаний', () => {
    expect(ВАЖНОСТЬ.refill).toBeLessThan(ВАЖНОСТЬ.nofood);
    expect(ВАЖНОСТЬ['reservoir-stuck']).toBeLessThan(ВАЖНОСТЬ.rise);
  });

  it('обновление приложения — ниже всего, оно вообще не про диабет', () => {
    const все = Object.entries(ВАЖНОСТЬ).filter(([k]) => k !== 'update').map(([, v]) => v);
    expect(ВАЖНОСТЬ.update).toBeGreaterThan(Math.max(...все));
  });

  /* Новому обращению могли забыть назначить важность. Показать его последним лучше,
     чем потерять: пропавшее сообщение никто не заметит, а лишнее внизу — заметят. */
  it('незнакомый id уезжает в конец, но не теряется', () => {
    const п = поВажности([{ id: 'что-то-новое' }, { id: 'battery' }]);
    expect(п.map((x) => x.id)).toEqual(['battery', 'что-то-новое']);
  });

  /* НАБЛЮДЕНИЕ ВЛАДЕЛЬЦА (#523): красные уезжали вниз, потому что порядок был одной шкалой.
     Показываем разом три — и предупреждение о том, что ночью нас не услышат, уезжало за предел
     и не показывалось вовсе. */
  it('красное поднимается над спокойным, даже если важность у него ниже', () => {
    const п = поВажности([
      { id: 'suspended', вид: 'сообщение' },
      { id: 'refill', вид: 'предложение' },
      { id: 'audio', вид: 'предупреждение' },
    ]);
    /* refill (порча данных) выше suspended (состояние) — это прежняя постоянная шкала, и она
       внутри спокойных не изменилась. */
    expect(п.map((x) => x.id)).toEqual(['audio', 'refill', 'suspended']);
  });

  it('внутри красного порядок прежний, постоянный', () => {
    const п = поВажности([
      { id: 'reservoir-night', вид: 'предупреждение' },
      { id: 'battery', вид: 'предупреждение' },
    ]);
    expect(п.map((x) => x.id)).toEqual(['battery', 'reservoir-night']);
  });

  /* Порядок спокойных не должен зависеть от того, есть ли рядом красное: человек привыкает,
     где что лежит, и пересобирать эту привычку каждый день — значит отучить читать. */
  it('спокойные между собой стоят как стояли', () => {
    const без = поВажности([{ id: 'nofood', вид: 'сообщение' }, { id: 'suspended', вид: 'сообщение' }]);
    const с = поВажности([
      { id: 'nofood', вид: 'сообщение' },
      { id: 'audio', вид: 'предупреждение' },
      { id: 'suspended', вид: 'сообщение' },
    ]);
    expect(без.map((x) => x.id)).toEqual(['suspended', 'nofood']);
    expect(с.map((x) => x.id)).toEqual(['audio', 'suspended', 'nofood']);
  });

  /* Вида нет вовсе — обращение считается спокойным. Это осознанно: красным человека тревожат,
     и делать это по умолчанию, из-за забытого поля, нельзя. */
  it('без вида — как спокойное', () => {
    const п = поВажности([{ id: 'battery' }, { id: 'audio', вид: 'предупреждение' }]);
    expect(п.map((x) => x.id)).toEqual(['audio', 'battery']);
  });

  it('при равной важности порядок не перетасовывается', () => {
    const п = поВажности([{ id: 'x', n: 1 }, { id: 'y', n: 2 }] as Array<{ id: string; n: number }>);
    expect(п.map((x) => x.n)).toEqual([1, 2]);
  });
});
