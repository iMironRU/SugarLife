import { describe, it, expect } from 'vitest';
import { поВажности, ВАЖНОСТЬ } from './notices';

/* Порядок обращений решает, что человек увидит первым, а увидит он два-три верхних.
   Ошибка здесь не ломает экран — она просто задвигает вниз то, из-за чего через час
   остановится помпа. */

describe('порядок обращений', () => {
  it('сверху то, из-за чего прервётся подача', () => {
    const п = поВажности([{ id: 'nofood' }, { id: 'update' }, { id: 'battery' }, { id: 'reservoir-night' }]);
    expect(п.map((x) => x.id)).toEqual(['battery', 'reservoir-night', 'nofood', 'update']);
  });

  /* Данные важнее напоминаний: неподтверждённая заправка делает неверным возраст
     расходников, а «давно не ели» — это просто напоминание. */
  it('порча данных выше напоминаний', () => {
    expect(ВАЖНОСТЬ.refill).toBeLessThan(ВАЖНОСТЬ.nofood);
    expect(ВАЖНОСТЬ['reservoir-stuck']).toBeLessThan(ВАЖНОСТЬ.rise);
  });

  it('обновление приложения — ниже всего, оно вообще не про диабет', () => {
    const все = Object.entries(ВАЖНОСТЬ).filter(([k]) => k !== 'update').map(([, v]) => v);
    expect(ВАЖНОСТЬ.update).toBeGreaterThan(Math.max(...все));
  });

  /* Новому обращению могли забыть назначить важность. Показать его последним лучше,
     чем потерять: пропавшее сообщение никто не заметит, а лишнее внизу — заметят. */
  it('незнакомый id уезжает в конец, но не теряется', () => {
    const п = поВажности([{ id: 'что-то-новое' }, { id: 'battery' }]);
    expect(п.map((x) => x.id)).toEqual(['battery', 'что-то-новое']);
  });

  it('при равной важности порядок не перетасовывается', () => {
    const п = поВажности([{ id: 'x', n: 1 }, { id: 'y', n: 2 }] as Array<{ id: string; n: number }>);
    expect(п.map((x) => x.n)).toEqual([1, 2]);
  });
});
