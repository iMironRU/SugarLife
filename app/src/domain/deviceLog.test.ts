import { describe, it, expect } from 'vitest';
import {
  важнее, естьИдентификаторы, подробноЕщёМинут, словоПустого, строкаПолей, ОБЫЧНЫЙ_УРОВЕНЬ,
} from './deviceLog';
import type { LogRecord } from '@/sources/bridge';

/* Журнал обмена с прибором (SugarLife#354). Экран заведён не для нас: три поломки за день
   нашлись через `adb logcat` с компьютера, а у человека с телефоном такого канала нет. */

const з = (p: Partial<LogRecord>): LogRecord =>
  ({ atMs: 0, level: 'Info', event: 'событие', ...p } as LogRecord);

describe('что показывать обычно', () => {
  /* Trace и Debug — кадры обмена, сотни записей в минуту. Человеческое в них тонет,
     поэтому обычный показ начинается с Info. */
  it('кадры обмена в обычном показе не участвуют', () => {
    expect(важнее(з({ level: 'Trace' }), ОБЫЧНЫЙ_УРОВЕНЬ)).toBe(false);
    expect(важнее(з({ level: 'Debug' }), ОБЫЧНЫЙ_УРОВЕНЬ)).toBe(false);
    expect(важнее(з({ level: 'Info' }), ОБЫЧНЫЙ_УРОВЕНЬ)).toBe(true);
    expect(важнее(з({ level: 'Error' }), ОБЫЧНЫЙ_УРОВЕНЬ)).toBe(true);
  });
});

describe('подробность гаснет сама', () => {
  /* Движок выключает её через четверть часа. Переключатель без срока соврал бы ровно
     тогда, когда человек про него забудет. */
  it('осталось время — говорим сколько', () => {
    expect(подробноЕщёМинут(1000 + 9 * 60_000, 1000)).toBe(9);
  });

  it('срок вышел или не включалось — молчим', () => {
    expect(подробноЕщёМинут(1000, 2000)).toBe(null);
    expect(подробноЕщёМинут(null, 1000)).toBe(null);
    expect(подробноЕщёМинут(undefined, 1000)).toBe(null);
  });

  /* Меньше минуты — всё равно «1 мин», а не «0»: ноль читается как «уже выключено», и
     человек нажмёт второй раз. */
  it('меньше минуты — округляем вверх, а не в ноль', () => {
    expect(подробноЕщёМинут(1000 + 5_000, 1000)).toBe(1);
  });
});

describe('пустой журнал — три разных случая', () => {
  it('в браузере журнала нет по построению', () => {
    expect(словоПустого({ журналЕсть: false, всегоЗаписей: 0 })).toMatch(/браузер/i);
  });

  /* На телефоне «нет журнала» значит другое: сборка старше метода. Сказать там «откройте
     на телефоне» — отправить человека туда, где он уже стоит. */
  it('на телефоне — это старая сборка, а не «откройте на телефоне»', () => {
    const т = словоПустого({ журналЕсть: false, всегоЗаписей: 0, вПриложении: true });
    expect(т).toMatch(/сборка/i);
    expect(т).not.toMatch(/в браузере/i);
  });

  it('записи есть, но все служебные — вопрос к порогу, а не к прибору', () => {
    expect(словоПустого({ журналЕсть: true, всегоЗаписей: 40 })).toMatch(/подробн/i);
  });

  it('записей нет вовсе — до первого события', () => {
    expect(словоПустого({ журналЕсть: true, всегоЗаписей: 0 })).toMatch(/появятся/i);
  });
});

describe('опознавательные данные', () => {
  /* Помечает движок: блок-лист по именам полей их не ловит — они внутри сырых кадров. */
  it('есть хоть одна помеченная — спрашиваем перед отправкой', () => {
    expect(естьИдентификаторы([з({}), з({ hasIdentifiers: true })])).toBe(true);
    expect(естьИдентификаторы([з({}), з({})])).toBe(false);
  });
});

describe('поля записи', () => {
  it('пустые значения не показываем', () => {
    expect(строкаПолей({ канал: 'FF32', пусто: null, ещё: '' })).toBe('канал: FF32');
  });

  it('полей нет — строки нет, а не пустая строка', () => {
    expect(строкаПолей(null)).toBe(null);
    expect(строкаПолей({})).toBe(null);
  });
});
