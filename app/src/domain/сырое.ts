import type { UiSnapshot } from '@/sources/bridge';

/* Сырое значение сенсора — помечаем, а не выдаём за истину (SugarLifeCore#88).

   С живого прибора: наше число около 15, у Juggluco заметно ниже. Разобрались — сенсор
   Sibionics отдаёт ТОЛЬКО сырьё, калибровка целиком на телефоне (у Juggluco это
   портированный вендорский алгоритм на 23 тысячи строк), а движок клал сырое число в поле
   «калиброванное». То есть мы не просто не калибровали — мы объявляли сырое истиной.

   По этому числу человек считает дозу. Поэтому правило простое и одностороннее: пока не
   сказано, что значение калибровано, мы не имеем права молчать об этом.

   ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: слова «показание неверно». Мы не калибруем и истинного
   значения не знаем — утверждать ошибку так же безосновательно, как утверждать точность.
   Максимум честного: значение сырое, и по нему стоит свериться с глюкометром, если от
   него зависит доза. */

/* ТРИ СОСТОЯНИЯ, А НЕ ДВА (мост 1.45).

   `сырое` временно: алгоритм прибора ещё не прогрет, надо подождать. `сырое навсегда` — у прибора
   своего алгоритма нет вовсе, и ждать нечего. Булево `glucoseCalibrated` эти случаи уравнивало, а
   советы у них противоположные: в первом «подожди», во втором «сверяйся с глюкометром всегда». */
export type Достоверность = 'калибровано' | 'сырое' | 'сырое навсегда' | 'неизвестно';

export function откудаЧисло(snap: UiSnapshot | null | undefined): Достоверность {
  /* Готовность словом важнее булева: она новее и точнее. Булево читаем, только если слова нет, —
     ядро оставило его ради совместимости со старыми сборками. */
  const г = snap?.monitor?.readiness;
  if (г === 'calculated') return 'калибровано';
  if (г === 'raw') return 'сырое';
  if (г === 'rawForever') return 'сырое навсегда';
  const п = snap?.monitor?.glucoseCalibrated;
  if (п === true) return 'калибровано';
  if (п === false) return 'сырое';
  /* Поля нет — источник про это ничего не сказал: облако, глюкометр, старая сборка.
     Это НЕ «сырое»: облачное число обычно как раз калибровано, и пометить его сырым
     значило бы соврать в другую сторону. */
  return 'неизвестно';
}

/** Заведомо сырое — любое из двух. Неизвестность сюда не входит: она не повод пугать. */
const сыроеЛюбое = (д: Достоверность) => д === 'сырое' || д === 'сырое навсегда';

/** Надо ли предупредить. */
export function предупредитьОСыром(snap: UiSnapshot | null | undefined): boolean {
  return сыроеЛюбое(откудаЧисло(snap));
}

/* Ждать ли, что число станет калиброванным. Разводит два совета, которые булево уравнивало:
   «подожди, прибор прогревается» и «у этого прибора алгоритма нет — сверяйся всегда». */
export function сыроеНавсегда(snap: UiSnapshot | null | undefined): boolean {
  return откудаЧисло(snap) === 'сырое навсегда';
}

/* Слова про сырое — в `слова/сырое.ts` (#324). Здесь только состояние: калибровано число или
   нет, и стоит ли ждать, что станет. */

/* Годится ли число для РАСЧЁТОВ, а не для показа. Разница принципиальная: показать сырое
   с оговоркой честно, а посчитать по нему дозу или активные углеводы — нет: там оговорка
   теряется, а число едет дальше как факт. */
export function годитсяДляРасчёта(snap: UiSnapshot | null | undefined): boolean {
  return !сыроеЛюбое(откудаЧисло(snap));
}
