import { describe, it, expect } from 'vitest';
import { картаПрибора } from './картаПрибора';
import type { HardwareView, DeviceView, UiSnapshot } from '@/sources/bridge';

/* Карточка прибора строится по факту, а не по шаблону (SugarLife#378).

   Проверяем не вёрстку, а обещание: ничего не выдумываем и ничего не теряем. Общий
   шаблон на все приборы даёт либо пустые строки («заряд —»), либо потерянные (день
   сеанса, которого у моста нет, а у сенсора он главный). */

const т = new Date(2026, 7, 19, 12, 0, 0).getTime();
const ДЕНЬ = 86400e3;

const ж = (p: Partial<HardwareView>): HardwareView =>
  ({ id: 'h', name: 'Прибор', kind: 'sensor', connection: 'Streaming', status: 'Live', ...p } as HardwareView);
const у = (p: Partial<DeviceView>): DeviceView => ({ id: 'h', kind: 'sensor', ...p } as DeviceView);
const сн = (hardware: HardwareView[], devices: DeviceView[] = []): UiSnapshot =>
  ({ hardware, devices } as unknown as UiSnapshot);

const ключи = (с: { ключ: string }[]) => с.map((x) => x.ключ);

describe('что сейчас', () => {
  it('время последних данных — первым, ради него и открывают', () => {
    const к = картаПрибора(ж({ latestAtMs: т - 120_000 }), сн([]), т);
    expect(ключи(к.сейчас)[0]).toBe('данные');
    expect(к.сейчас[0].значение).toMatch(/2 мин назад/);
  });

  /* «—» вместо времени читается как поломка. Не знаем — молчим. */
  it('времени нет — строки нет', () => {
    expect(ключи(картаПрибора(ж({}), сн([]), т).сейчас)).not.toContain('данные');
  });

  it('сеанс: сколько осталось', () => {
    const к = картаПрибора(ж({}), сн([], [у({ expiresAtMs: т + 11 * ДЕНЬ })]), т);
    expect(к.сейчас.find((x) => x.ключ === 'сеанс')?.значение).toMatch(/ещё 11 дн/);
  });

  /* Дня «N из 14» здесь нет: начала сеанса движок не присылает, а вычитание из
     официального срока — догадка. На «Сегодня» день считается по другому источнику, и
     смешивать их в одной строке значит разойтись на сутки. */
  it('день сеанса не выдумываем', () => {
    const к = картаПрибора(ж({}), сн([], [у({ expiresAtMs: т + 11 * ДЕНЬ })]), т);
    expect(к.сейчас.find((x) => x.ключ === 'сеанс')?.значение).not.toMatch(/день/);
  });

  /* Прогрев — не поломка, и молчание показаний в это время нормально. */
  it('прогрев объясняем, а не показываем как отсутствие данных', () => {
    const к = картаПрибора(ж({}), сн([], [у({ sessionState: 'WarmingUp', warmupEndsAtMs: т + 40 * 60000 })]), т);
    const с = к.сейчас.find((x) => x.ключ === 'сеанс');
    expect(с?.значение).toMatch(/прогрев, ещё 40 мин/);
    expect(с?.подпись).toMatch(/нормально/);
  });

  /* У моста сеанса нет вовсе — пустая строка про него была бы выдумкой. */
  it('сеанса нет — строки нет', () => {
    expect(ключи(картаПрибора(ж({ kind: 'bridge' }), сн([]), т).сейчас)).not.toContain('сеанс');
  });

  it('сеанс кончился — говорим прямо, а не «ещё −2 дн»', () => {
    const к = картаПрибора(ж({}), сн([], [у({ expiresAtMs: т - ДЕНЬ })]), т);
    expect(к.сейчас.find((x) => x.ключ === 'сеанс')?.значение).toMatch(/закончился/);
  });

  /* «Не настроен» и «чем занят» перебивают слова о связи — правило моста 1.22/1.24. */
  it('не настроен — это и есть состояние', () => {
    const к = картаПрибора(ж({ registryState: 'NotConfigured', note: 'Не хватает настроек: Код сенсора' }), сн([]), т);
    expect(к.состояние).toMatch(/Код сенсора/);
  });
});

describe('что за прибор', () => {
  it('показываем только известное', () => {
    const к = картаПрибора(ж({ bleId: 'AA:BB', inSlot: 'cgm', firmware: '2.4', batteryPct: 74 }), сн([]), т);
    expect(ключи(к.оПриборе)).toEqual(['адрес', 'слот', 'прошивка', 'заряд']);
  });

  it('ничего не известно — пустая справка, а не строки с прочерками', () => {
    expect(картаПрибора(ж({}), сн([]), т).оПриборе).toEqual([]);
  });

  /* Голый процент не отвечает, доживёт ли прибор до конца сеанса. Пока прогноза нет,
     хотя бы предупреждаем на низком заряде. */
  it('низкий заряд объясняем словом', () => {
    const к = картаПрибора(ж({ batteryPct: 12 }), сн([]), т);
    expect(к.оПриборе.find((x) => x.ключ === 'заряд')?.подпись).toMatch(/раньше конца сеанса/);
  });

  it('адрес не первый: он нужен раз в жизни — различить два одинаковых прибора', () => {
    const к = картаПрибора(ж({ bleId: 'AA:BB', latestAtMs: т }), сн([]), т);
    expect(ключи(к.сейчас)).toContain('данные');
    expect(ключи(к.оПриборе)).toContain('адрес');
  });
});
