import { describe, it, expect } from 'vitest';
import { откудаЧисло, предупредитьОСыром, годитсяДляРасчёта, сыроеНавсегда } from './сырое';
import type { UiSnapshot } from '@/sources/bridge';

/* Сырое значение сенсора (SugarLifeCore#88). На живом приборе мы показывали около 15,
   Juggluco — заметно ниже: движок клал сырое число в поле «калиброванное». По этому
   числу человек считает дозу. */

const сн = (v: boolean | null | undefined): UiSnapshot =>
  ({ monitor: v === undefined ? {} : { glucoseCalibrated: v } } as UiSnapshot);

describe('откуда число', () => {
  it('калибровано — так и говорим', () => {
    expect(откудаЧисло(сн(true))).toBe('калибровано');
    expect(предупредитьОСыром(сн(true))).toBe(false);
  });

  it('сырое — предупреждаем', () => {
    expect(откудаЧисло(сн(false))).toBe('сырое');
    expect(предупредитьОСыром(сн(false))).toBe(true);
  });

  /* Поля нет — источник промолчал: облако, глюкометр, старая сборка. Это не «сырое»:
     облачное число обычно калибровано, и пометить его сырым — соврать в другую сторону. */
  it('источник промолчал — не выдумываем ни в одну сторону', () => {
    expect(откудаЧисло(сн(undefined))).toBe('неизвестно');
    expect(откудаЧисло(сн(null))).toBe('неизвестно');
    expect(откудаЧисло(null)).toBe('неизвестно');
    expect(предупредитьОСыром(сн(undefined))).toBe(false);
  });
});

describe('показать можно, посчитать нельзя', () => {
  /* Показать сырое с оговоркой честно. Посчитать по нему дозу — нет: в расчёте оговорка
     теряется, а число едет дальше как факт. */
  it('сырое к расчётам не допускаем', () => {
    expect(годитсяДляРасчёта(сн(false))).toBe(false);
  });

  it('калиброванное и неизвестное — допускаем', () => {
    expect(годитсяДляРасчёта(сн(true))).toBe(true);
    expect(годитсяДляРасчёта(сн(undefined))).toBe(true);
  });
});

/* ГОТОВНОСТЬ СЛОВОМ (мост 1.45). Три состояния вместо двух, и третье — не оттенок второго:
   `raw` значит «подожди, прибор прогревается», `rawForever` — «своего алгоритма нет, ждать нечего».
   Совет человеку у них разный, поэтому и различаем. */
const готовность = (r: string | undefined, старое?: boolean): UiSnapshot =>
  ({ monitor: { readiness: r, ...(старое === undefined ? {} : { glucoseCalibrated: старое }) } } as unknown as UiSnapshot);

describe('готовность числа словом', () => {
  it('calculated — калибровано', () => {
    expect(откудаЧисло(готовность('calculated'))).toBe('калибровано');
    expect(предупредитьОСыром(готовность('calculated'))).toBe(false);
    expect(годитсяДляРасчёта(готовность('calculated'))).toBe(true);
  });

  it('raw — сырое, временно', () => {
    expect(откудаЧисло(готовность('raw'))).toBe('сырое');
    expect(сыроеНавсегда(готовность('raw'))).toBe(false);
  });

  /* Главное, ради чего поле и появилось: «навсегда» обязано и предупреждать, и не идти в расчёт.
     Пропусти его — и прибор без своего алгоритма станет считаться калиброванным. */
  it('rawForever — сырое навсегда: предупреждаем и в расчёт не берём', () => {
    expect(откудаЧисло(готовность('rawForever'))).toBe('сырое навсегда');
    expect(сыроеНавсегда(готовность('rawForever'))).toBe(true);
    expect(предупредитьОСыром(готовность('rawForever'))).toBe(true);
    expect(годитсяДляРасчёта(готовность('rawForever'))).toBe(false);
  });

  it('слово важнее булева: старое поле читаем, только когда слова нет', () => {
    expect(откудаЧисло(готовность('raw', true))).toBe('сырое');
    expect(откудаЧисло(готовность(undefined, true))).toBe('калибровано');
  });
});
