import type { UiSnapshot } from '@/sources/bridge';
import type { DeviceConfig } from '@/settings/deviceConfig';
import { UNKNOWN_MODEL } from '@/settings/deviceConfig';
import { pumpById, sensorById } from './catalog';
import { движокЖивой } from './deviceState';
import { модельСлота } from './slotStatus';

/* Кто хозяин записи об устройстве (SugarLife#224, #281).

   Сведения о приборах жили в двух местах сразу: локальный `sl.device.v1` и снимок движка.
   Два источника про одно расходятся всегда — и уже расходились на экране: подпись «по
   радио» из снимка и значение «только через облако» из конфига, одновременно, про одно
   устройство.

   ЧИТАТЬ из снимка мы научились раньше. Осталось перестать ПИСАТЬ рядом: пока обе записи
   пополняются, они разъедутся снова — вопрос дней. Причём разъедутся тихо, потому что
   каждая по отдельности выглядит правдой.

   ПРАВИЛО. Есть живой движок — он и хозяин: мост, серийник, частота уходят интентами и
   локально не дублируются. Движка нет (браузер, старая сборка) — пишем к себе, иначе
   человеку негде хранить выбранное вовсе.

   ЧТО ОСТАЁТСЯ НАШИМ ВСЕГДА, независимо от движка: модель из нашего справочника (у
   движка своя модель драйвера, а нам нужны резервуар и спецификации), быстрый инсулин,
   химия батарейки помпы (движок про неё не знает, а прогноз строится по ней) и модель
   глюкометра. Это не дубли — этого у движка нет и не будет. */

export function движокХозяин(snap: UiSnapshot | null | undefined): boolean {
  return движокЖивой(snap);
}

/** Дублирующие поля локального конфига — те, что переехали в движок. */
export const ПЕРЕЕХАЛО = ['bridgePumpId', 'bridgeSensorId', 'deviceParams'] as const;

/* Писать ли поле локально. Отдельной функцией, а не условием на месте: мест записи
   несколько, и разъехаться они должны один раз в тесте, а не однажды на телефоне. */
export function писатьЛокально(
  поле: (typeof ПЕРЕЕХАЛО)[number], snap: UiSnapshot | null | undefined,
): boolean {
  void поле;
  return !движокХозяин(snap);
}

/* Какая модель выбрана — один ответ на всё приложение (#224, шаг 4).

   Модель спрашивали в шести местах: список устройств, карточка, петля, облако, профиль,
   выбор в шторке. Каждое читало локальный конфиг напрямую — и после переустановки все
   шесть дружно забывали помпу, хотя движок её помнил и продолжал читать. Снаружи это
   выглядит хуже, чем пустота: экран «Петля» пишет «модель не указана», а сахар идёт.

   Правило то же, что и у остальной записи: движок знает — движок и отвечает. Только
   ЗДЕСЬ он не хозяин, а хранитель. Модель наша: резервуар, шаг базала, спецификации,
   `driverKey` — всё это из нашего справочника, движку они безразличны. Он её просто
   держит рядом с прибором и отдаёт обратно.

   Чужую строку не берём. Движок хранит `deviceModel` сырьём и не проверяет — значит
   прийти может что угодно: запись, сделанную другой сборкой, или ключ, которого в нашем
   справочнике уже нет. Такой ответ для нас не «модель», а шум: по нему не найти ни
   резервуара, ни спецификаций. Тогда отвечает локальный выбор. */
export function выбраннаяМодель(
  кто: 'pump' | 'sensor', cfg: DeviceConfig, snap: UiSnapshot | null | undefined,
): string | null {
  const свой = кто === 'pump' ? cfg.pumpId : cfg.sensorId;
  const изДвижка = модельСлота(snap, кто);
  if (изДвижка && (кто === 'pump' ? pumpById(изДвижка) : sensorById(изДвижка))) return изДвижка;
  /* «Модель не указана» — тоже ответ движка, а не пустота: прибор записан, а какой он,
     человек не сказал. Отличать обязательно, иначе после записи без модели экран снова
     показал бы старый локальный выбор. */
  if (изДвижка === UNKNOWN_MODEL) return UNKNOWN_MODEL;
  return свой;
}
