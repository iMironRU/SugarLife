export type Ожидание = 'поднимаем' | 'долго' | 'очень долго';

/* Восемь секунд — не круглое число, а мера терпения. Первый экран собирается за доли
   секунды даже на слабом телефоне; восемь означают «что-то идёт не так», но ещё не
   «сломалось». Тридцать — уже разговор о том, что делать. */
export const ДОЛГО_МС = 8_000;
export const ОЧЕНЬ_ДОЛГО_МС = 30_000;

export function ожидание(прошлоМс: number): Ожидание {
  if (прошлоМс >= ОЧЕНЬ_ДОЛГО_МС) return 'очень долго';
  if (прошлоМс >= ДОЛГО_МС) return 'долго';
  return 'поднимаем';
}
