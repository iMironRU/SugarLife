/** Часть суток. Ночь отделена намеренно: у ночного подъёма причины другие, чем у дневного. */
export type ЧастьСуток = 'ночь' | 'утро' | 'день' | 'вечер';

export const ЧАСТИ: { ключ: ЧастьСуток; имя: string; с: number; до: number }[] = [
  { ключ: 'ночь', имя: 'ночью', с: 0, до: 6 },
  { ключ: 'утро', имя: 'утром', с: 6, до: 12 },
  { ключ: 'день', имя: 'днём', с: 12, до: 18 },
  { ключ: 'вечер', имя: 'вечером', с: 18, до: 24 },
];

export function частьСуток(t: number): ЧастьСуток {
  const ч = new Date(t).getHours();
  return (ЧАСТИ.find((п) => ч >= п.с && ч < п.до) ?? ЧАСТИ[0]).ключ;
}

export interface РазборБезЗаписи {
  всего: number;
  /** Сколько в среднем за сутки — по этому числу сравнивают периоды. */
  вДень: number;
  /** Сколько в каждой части суток. */
  поЧастям: Record<ЧастьСуток, number>;
  /* Часть суток, на которую приходится БОЛЬШЕ ПОЛОВИНЫ. Именно больше половины, а не
     «чаще других»: три ночью и два утром — это не «ночная картина», а разброс, и
     объявлять его закономерностью значило бы придумать её за человека. */
  преобладает: ЧастьСуток | null;
  /** Типичная величина, ммоль. Медиана, а не среднее: один выброс в +9 сдвинул бы среднее. */
  типичныйПодъём: number;
}

export function разборБезЗаписи(моменты: Момент[], дней: number): РазборБезЗаписи {
  const поЧастям: Record<ЧастьСуток, number> = { ночь: 0, утро: 0, день: 0, вечер: 0 };
  for (const м of моменты) поЧастям[частьСуток(м.at)]++;

  const всего = моменты.length;
  const [лидер] = (Object.entries(поЧастям) as [ЧастьСуток, number][])
    .sort((a, b) => b[1] - a[1]);
  const преобладает = всего > 0 && лидер[1] * 2 > всего ? лидер[0] : null;

  const величины = моменты.map((м) => м.rise).sort((a, b) => a - b);
  const середина = величины.length
    ? величины[Math.floor((величины.length - 1) / 2)]
    : 0;

  return {
    всего,
    вДень: дней > 0 ? Math.round((всего / дней) * 10) / 10 : 0,
    поЧастям,
    преобладает,
    типичныйПодъём: Math.round(середина * 10) / 10,
  };
}

/** Имя части суток для строки: «ночью», «утром». */
export const имяЧасти = (ч: ЧастьСуток): string =>
  (ЧАСТИ.find((п) => п.ключ === ч)?.имя ?? '');
