/** Отметка человека: к какому подъёму и что он про него сказал. */
export interface ОтметкаПодъёма { at: number; причина: Причина; когдаМс: number }

/* Отметку ищем по времени с допуском, а не по точному совпадению.

   Время подъёма считается по показаниям, а они приходят и уточняются: добор истории
   может сдвинуть точку начала на минуту-другую, и отметка, привязанная к точной метке,
   потерялась бы — человек увидел бы тот же подъём снова, уже отмеченный. */
export const ДОПУСК_МС = 20 * 60_000;

export function отметкаДля(отметки: ОтметкаПодъёма[], at: number): ОтметкаПодъёма | null {
  let ближайшая: ОтметкаПодъёма | null = null;
  for (const о of отметки) {
    const δ = Math.abs(о.at - at);
    if (δ > ДОПУСК_МС) continue;
    if (!ближайшая || δ < Math.abs(ближайшая.at - at)) ближайшая = о;
  }
  return ближайшая;
}

/** Сколько чего отмечено — для записки врачу. Порядок по убыванию, как читают. */
export function поПричинам(отметки: ОтметкаПодъёма[]): { причина: Причина; сколько: number }[] {
  const счёт = new Map<Причина, number>();
  for (const о of отметки) счёт.set(о.причина, (счёт.get(о.причина) ?? 0) + 1);
  return [...счёт.entries()]
    .map(([причина, сколько]) => ({ причина, сколько }))
    .sort((a, b) => b.сколько - a.сколько);
}
