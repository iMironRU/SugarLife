/* Чем объяснить подъём (#167, продолжение #432).

   Разбор научился показывать подъёмы без записи. Но пока единственное, что человек мог с
   ними сделать, — записать еду. А если это была не еда, отметка не ставилась вовсе, и
   подъём оставался «необъяснённым» навсегда: разбор показывал его снова и снова, записка
   врачу считала его в общем числе, и с каждой неделей их становилось больше.

   Получалось приложение, которое задаёт вопрос и не принимает ответа. Хуже того — из
   всех ответов оно принимало ровно один, и человек, у которого отвалилась канюля, должен
   был либо соврать про еду, либо молчать.

   ПРИЧИНЫ — СПИСОК ВОЗМОЖНОСТЕЙ, А НЕ ОБВИНЕНИЙ. Ни одна формулировка здесь не говорит
   «ты забыл» или «ты не сделал». Человек с хроническим диагнозом и так живёт с чувством
   вины за каждое число; приложение не должно его добавлять.

   «НЕ ЗНАЮ» — ПОЛНОЦЕННЫЙ ОТВЕТ, и он есть в списке намеренно. Без него человек выберет
   любую причину, лишь бы убрать строку с глаз, — и данные станут хуже, чем пустые: не
   «неизвестно», а «неправда». Врач, читающий «канюля ×3», должен видеть настоящие три
   канюли, а не три нажатия ради тишины. */

export type Причина = 'еда' | 'болюс' | 'канюля' | 'рассвет' | 'болезнь' | 'сенсор' | 'неизвестно';

/* Как каждая причина называется человеку и в каком порядке их предлагать — в `слова/подъёмы.ts`
   (#324). Здесь только перечень возможных ответов: полноту словаря сторожит тип `Причина`, а
   порядок показа — решение слоя показа, а не домена. */

/** Отметка человека: к какому подъёму и что он про него сказал. */
export interface ОтметкаПодъёма { at: number; причина: Причина; когдаМс: number }

/* Отметку ищем по времени с допуском, а не по точному совпадению.

   Время подъёма считается по показаниям, а они приходят и уточняются: добор истории
   может сдвинуть точку начала на минуту-другую, и отметка, привязанная к точной метке,
   потерялась бы — человек увидел бы тот же подъём снова, уже отмеченный. */
export const ДОПУСК_МС = 20 * 60_000;

export function отметкаДля(отметки: ОтметкаПодъёма[], at: number): ОтметкаПодъёма | null {
  let ближайшая: ОтметкаПодъёма | null = null;
  for (const о of отметки) {
    const δ = Math.abs(о.at - at);
    if (δ > ДОПУСК_МС) continue;
    if (!ближайшая || δ < Math.abs(ближайшая.at - at)) ближайшая = о;
  }
  return ближайшая;
}

/** Сколько чего отмечено — для записки врачу. Порядок по убыванию, как читают. */
export function поПричинам(отметки: ОтметкаПодъёма[]): { причина: Причина; сколько: number }[] {
  const счёт = new Map<Причина, number>();
  for (const о of отметки) счёт.set(о.причина, (счёт.get(о.причина) ?? 0) + 1);
  return [...счёт.entries()]
    .map(([причина, сколько]) => ({ причина, сколько }))
    .sort((a, b) => b.сколько - a.сколько);
}
