/* Чем объяснить подъём (#167, продолжение #432).

   Разбор научился показывать подъёмы без записи. Но пока единственное, что человек мог с
   ними сделать, — записать еду. А если это была не еда, отметка не ставилась вовсе, и
   подъём оставался «необъяснённым» навсегда: разбор показывал его снова и снова, записка
   врачу считала его в общем числе, и с каждой неделей их становилось больше.

   Получалось приложение, которое задаёт вопрос и не принимает ответа. Хуже того — из
   всех ответов оно принимало ровно один, и человек, у которого отвалилась канюля, должен
   был либо соврать про еду, либо молчать.

   ПРИЧИНЫ — СПИСОК ВОЗМОЖНОСТЕЙ, А НЕ ОБВИНЕНИЙ. Ни одна формулировка здесь не говорит
   «ты забыл» или «ты не сделал». Человек с хроническим диагнозом и так живёт с чувством
   вины за каждое число; приложение не должно его добавлять.

   «НЕ ЗНАЮ» — ПОЛНОЦЕННЫЙ ОТВЕТ, и он есть в списке намеренно. Без него человек выберет
   любую причину, лишь бы убрать строку с глаз, — и данные станут хуже, чем пустые: не
   «неизвестно», а «неправда». Врач, читающий «канюля ×3», должен видеть настоящие три
   канюли, а не три нажатия ради тишины. */

export type Причина = 'еда' | 'болюс' | 'канюля' | 'рассвет' | 'болезнь' | 'сенсор' | 'неизвестно';

export interface ВидПричины {
  ключ: Причина;
  /** Как её называет человек, когда выбирает. */
  выбор: string;
  /** Как она читается в списке и в записке врачу. */
  метка: string;
  /** Короткое пояснение — почему это вообще вариант. */
  подпись?: string;
}

