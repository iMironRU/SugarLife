/* Порядок обращений — по тому, что стоит на кону (SugarLife#225).

   До сих пор порядок задавался местом в коде: какая карточка написана выше, ту человек
   и видит первой. Это не решение, а случайность — при следующей правке экрана порядок
   поменялся бы сам собой, и никто бы не заметил.

   Порядок здесь один и объясним. Сверху то, из-за чего прервётся подача инсулина:
   севшая батарея и кончающийся резервуар — это часы до остановки помпы. Ниже то, что
   портит данные, по которым мы считаем: неподтверждённая заправка и залипший резервуар
   делают неверным возраст расходников. Ещё ниже — состояния и напоминания. В самом
   низу обновление приложения: единственное, что вообще не про диабет.

   ПОЧЕМУ ЧИСЛАМИ, А НЕ ПОРЯДКОМ В СПИСКЕ. Обращения появляются в разных местах экрана
   и в разное время; список пришлось бы держать в одном порядке в трёх файлах. Число
   же читается рядом с обращением и переживает любую перестановку разметки. */

export const ВАЖНОСТЬ: Record<string, number> = {
  // подача вот-вот прервётся
  battery: 10,
  'reservoir-night': 20,
  'reservoir-soon': 25,
  /* Беда прибора: связи нет, прибор не отвечает (#695). Выше «неверных данных» и ниже
     «подача вот-вот прервётся»: без данных мы не считаем НИЧЕГО, но остановка инсулина
     всё равно страшнее. Серьёзность беды выбирает движок — мы лишь решаем, где место. */
  'device-problem': 30,
  // данные, по которым мы считаем, стали неверными
  refill: 40,
  'reservoir-stuck': 45,
  // состояние железа и связи
  suspended: 50,
  /* Звук в машине (ядро #180). Ниже паузы помпы: там подача уже стоит, здесь — только
     может не прозвучать тревога. Но выше приборов и напоминаний: из всей этой полосы
     единственное, что кончается неуслышанной тревогой за рулём. */
  audio: 55,
  devices: 60,
  // напоминания про записи
  rise: 70,
  nofood: 80,
  // не про диабет вовсе
  update: 90,
};

/** Обращение без разметки — только то, что нужно для порядка. */
export interface Позиция { id: string; вид?: string }

/*
 * КРАСНОЕ НАВЕРХ, ОСТАЛЬНОЕ — ПОСТОЯННЫМ ПОРЯДКОМ (SugarLife#523, наблюдение владельца).
 *
 * Одной шкалы важности мало, и вот почему. Она расставляет обращения по тому, что стоит на кону,
 * — но не различает «случится, если не вмешаться» и «просто знай». Из-за этого предупреждение о
 * звуке в машине («ночью может не разбудить») стояло НИЖЕ сообщения «помпа на паузе», а показываем
 * мы разом три: красное уезжало за предел и не показывалось вовсе.
 *
 * Порядок теперь двухступенчатый:
 *
 *   1. сначала всё, что ТРЕБУЕТ ДЕЙСТВИЯ СЕЙЧАС — вид «предупреждение»;
 *   2. внутри каждой ступени — прежняя постоянная важность.
 *
 * ПОЧЕМУ НЕ СОРТИРОВКА ПО СВЕЖЕСТИ. Порядок, меняющийся каждый день, отнимает привычку: человек
 * перестаёт знать, где что лежит, и начинает читать всё подряд — то есть не читать. Поднимается
 * только красное, и только потому, что действие нельзя отложить; всё прочее стоит там же, где
 * вчера.
 *
 * Вид приходит от самого обращения (`ui/Notice.tsx`), а не выводится здесь по списку кодов: свой
 * перечень «важных» разошёлся бы с разметкой в первую же правку — так у нас уже расходились две
 * таблицы стрелок и два набора периодов.
 */
const ТРЕБУЕТ_ДЕЙСТВИЯ = 'предупреждение';

/* Сортировка устойчивая: при равной важности порядок остаётся тем, в каком обращения
   пришли. Незнакомый id уезжает в конец, но не теряется — новое обращение, которому
   забыли назначить важность, лучше показать последним, чем не показать вовсе. */
export function поВажности<T extends Позиция>(список: T[]): T[] {
  const ступень = (x: Позиция) => (x.вид === ТРЕБУЕТ_ДЕЙСТВИЯ ? 0 : 1);
  return [...список].sort((a, b) =>
    ступень(a) - ступень(b) || (ВАЖНОСТЬ[a.id] ?? 999) - (ВАЖНОСТЬ[b.id] ?? 999));
}
