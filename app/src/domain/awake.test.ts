import { describe, it, expect } from 'vitest';
import { часыБодрствования } from './awake';

const ч = (день: number, час: number, мин = 0) => new Date(2026, 7, день, час, мин).getTime();

describe('часы, когда человек мог поесть', () => {
  it('ночь не считается: в восемь утра после полуночного приёма перерыва почти нет', () => {
    // ровно случай со скриншота: поел в 00:10, сейчас 08:10 — календарно 8 часов
    expect(часыБодрствования(ч(12, 0, 10), ч(12, 8, 10))).toBeCloseTo(0.17, 1);
  });

  it('дневной перерыв считается целиком', () => {
    expect(часыБодрствования(ч(12, 9), ч(12, 15))).toBeCloseTo(6, 1);
  });

  it('перерыв через ночь: считаем только вечер и утро', () => {
    // с 20:00 до 10:00 — три часа вечера (20–23) и два утра (8–10)
    expect(часыБодрствования(ч(12, 20), ч(13, 10))).toBeCloseTo(5, 1);
  });

  it('перерыв длиннее суток не ломается на переходах через полночь', () => {
    // двое суток = два дневных окна по 15 часов
    expect(часыБодрствования(ч(11, 8), ч(13, 8))).toBeCloseTo(30, 0);
  });

  it('целиком внутри ночи — ноль', () => {
    expect(часыБодрствования(ч(12, 1), ч(12, 5))).toBe(0);
  });

  it('вырожденные интервалы не считаем', () => {
    expect(часыБодрствования(ч(12, 10), ч(12, 10))).toBe(0);
    expect(часыБодрствования(ч(12, 15), ч(12, 10))).toBe(0);
  });
});
