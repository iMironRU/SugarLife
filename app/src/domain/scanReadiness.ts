import type { ScanReadinessView, UiSnapshot } from '@/sources/bridge';

/* Почему поиск не находит приборов (SugarLife#333).

   Пустой эфир на чистом Android оказался выключенной службой геолокации, а приложение
   об этом молчало — человек искал неисправность в приборе, которого не касалось ничего.

   Диагноз ставит движок: он запускает скан и единственный знает, почему тот не идёт.
   Своя проверка завела бы второе мнение о том же — та развилка, где мы уже ошибались с
   порогами свежести и состоянием слотов. Здесь только правила показа.

   ГЛАВНОЕ ПРАВИЛО, и оно про время. Когда причина ИЗВЕСТНА, говорить надо сразу: молчать
   двенадцать секунд, зная ответ, — это двенадцать секунд, за которые человек успевает
   решить, что сломан прибор. Когда причина неизвестна, а эфир пуст, наоборот: первые
   секунды пустота — норма, реклама сенсора приходит раз в несколько секунд. Вывалить
   сразу список догадок значит объяснять то, чего ещё не случилось, и приучить
   пролистывать объяснения мимо. */

/** Сколько молчим, прежде чем предполагать причины при ИСПРАВНОМ поиске. */
export const ТЕРПЕНИЕ_МС = 12_000;

export type Помеха = ScanReadinessView | null;

/** Что мешает прямо сейчас. null — движок не жалуется (или молчит вовсе). */
export function мешает(snap: UiSnapshot | null | undefined): Помеха {
  const г = snap?.scanReadiness;
  return г && !г.canScan ? г : null;
}

/* Можно ли ещё раз показать системный диалог.

   Диалог даётся один раз: отказал насовсем — кнопка «Разрешить» открыла бы ничего, то
   есть тупик, из которого человек не выберется и решит, что приложение сломано. Тогда
   ведём в настройки. */
export function спроситьМожно(п: Помеха): boolean {
  return !!п?.blockers?.includes('noPermission') && п.canAskAgain !== false;
}

/** Куда вести, если спросить уже нельзя. null — вести некуда, остаётся объяснить словами. */
export function кудаВНастройки(п: Помеха): string | null {
  return п?.settingsTarget ?? null;
}

/* Что сказать, когда поиск ИДЁТ, а в эфире пусто. Три разных состояния, и слова у них
   разные: разница между «жди» и «иди чини» — это разница между спокойствием и суетой. */
export function словоПустоты(
  { эфирЕсть, сканирует, долгоЖдём }: { эфирЕсть: boolean; сканирует: boolean; долгоЖдём: boolean },
): string {
  if (!эфирЕсть) {
    return 'В браузере блютуса нет — это свойство браузера, а не настроек. Приборы видны в приложении на телефоне; данные при этом идут через облако, и всё остальное работает.';
  }
  if (!сканирует) return 'Поиск не идёт. Обычно это значит, что приложению не разрешили блютус.';
  if (!долгоЖдём) {
    return 'Слушаю эфир. Реклама прибора приходит раз в несколько секунд — держите его ближе к телефону.';
  }
  /* Причины по убыванию вероятности, а не по удобству перечисления: первой — та, что
     случается чаще всего и человеком не подозревается вовсе. */
  return 'Пока никого. Чаще всего причина одна: прибор уже занят другим телефоном или родным приложением производителя — у сенсора один хозяин за раз. Вторая по частоте: прибор далеко или спит между обменами. И третья: он не в режиме поиска — новый сенсор надо активировать, помпу разбудить.';
}
