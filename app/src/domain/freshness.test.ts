import { describe, it, expect } from 'vitest';
import { свежесть, молчитЛи, чтоСПрибором } from './freshness';

/* «На связи», а данных нет (SugarLife#305). Проверяем не формат строки, а границу
   между тремя состояниями, которые человек путает: работает / греется / молчит. */

const т = new Date(2026, 7, 16, 19, 0, 0).getTime();
const мин = 60_000;

describe('свежесть: работает / греется / молчит', () => {
  it('живой источник ничего не добавляет — обычная метка сама всё скажет', () => {
    expect(свежесть({ status: 'Live', latestAtMs: т - мин }, т)).toBe(null);
  });

  /* Ровно тот случай, ради которого всё: связь есть, показаний нет, и раньше строка
     говорила «на связи», а человек читал это как «сенсор работает». */
  it('молчит — говорим, сколько именно', () => {
    expect(свежесть({ status: 'Delayed', latestAtMs: т - 7 * мин }, т))
      .toEqual({ вид: 'молчит', мс: 7 * мин });
  });

  /* Прогрев — не поломка: сенсор после установки полчаса не отдаёт значений. Назвать
     это задержкой значит научить человека не читать предупреждения вообще. */
  it('первое показание ещё не приходило — это ожидание, а не молчание', () => {
    expect(свежесть({ status: 'Connecting', latestAtMs: null }, т)).toEqual({ вид: 'прогрев' });
  });

  it('молчит, а времени нет — говорим факт без выдуманного числа', () => {
    expect(свежесть({ status: 'Delayed', latestAtMs: null }, т)).toEqual({ вид: 'молчит', мс: null });
  });

  /* Порог считает ядро — по типу прибора: сенсор шлёт раз в пять минут, помпа за мостом
     отвечает реже. Своего порога здесь нет намеренно, и тест сторожит именно это:
     подпись появляется от статуса, а не от возраста. */
  it('порог не наш: старое время без Delayed — молчим', () => {
    expect(свежесть({ status: 'Live', latestAtMs: т - 60 * мин }, т)).toBe(null);
  });

  it('нет связи — про свежесть говорить нечего, там другая беда', () => {
    expect(свежесть({ status: 'Disconnected', latestAtMs: т - 60 * мин }, т)).toBe(null);
    expect(молчитЛи({ status: 'Disconnected' })).toBe(false);
    expect(молчитЛи({ status: 'Delayed' })).toBe(true);
  });
});

/* «Чем занят» и «чего не хватает» (мост 1.22/1.24, SugarLifeCore#66/#69).

   Проверяем очерёдность, а не текст: она и есть решение. Прибор, который минутами
   подбирает частоту, показывался как «не отвечает» — то есть приложение объявляло
   поломкой нормальную долгую работу, и человек шёл чинить исправное. */
describe('что с прибором', () => {
  it('не настроен — говорим об этом, а не о связи', () => {
    expect(чтоСПрибором({ registryState: 'NotConfigured', note: 'Не хватает настроек: Код сенсора' }))
      .toEqual({ вид: 'неНастроен', заметка: 'Не хватает настроек: Код сенсора' });
  });

  /* Движок такой прибор не поднимает вовсе — значит и молчать о причине нельзя, даже
     когда он поленился прислать перечень. */
  it('не настроен без перечня — всё равно не молчим', () => {
    expect(чтоСПрибором({ registryState: 'NotConfigured' })).toEqual({ вид: 'неНастроен', заметка: null });
  });

  it('занятие важнее связи', () => {
    expect(чтоСПрибором({ registryState: 'Linked', progress: 'Подбираю частоту помпы' }))
      .toEqual({ вид: 'занят', чем: 'Подбираю частоту помпы' });
  });

  /* «Не настроен» перебивает занятие: заниматься нечем, пока не спросили главное. */
  it('не настроен перебивает занятие', () => {
    expect(чтоСПрибором({ registryState: 'NotConfigured', note: 'Нужен код', progress: 'Ищу' }))
      .toEqual({ вид: 'неНастроен', заметка: 'Нужен код' });
  });

  it('занятия нет — молчим и отдаём решение обычным правилам', () => {
    expect(чтоСПрибором({ registryState: 'Linked' })).toBe(null);
    expect(чтоСПрибором({ progress: '   ' })).toBe(null);
    expect(чтоСПрибором(null)).toBe(null);
  });
});
