import { ПРИЁМ_ПОРЫ } from '@/слова/еда';
import { FOODS, type Food, type Personal } from './foods';
import { LOW } from './agp';

/* Что показать первым в момент открытия шторки еды.

   Список из 68 записей одной лентой — это не помощь, а перекладывание работы. Мы знаем
   про этот момент четыре вещи, и они позволяют показать сверху пять плиток вместо
   листания.

   Порядок сигналов — по силе, а не по удобству вычисления:

   1. САХАР. Если он низкий или быстро падает, человек открыл еду не поужинать: он
      купирует гипо. Это самая частая причина внезапного ввода, особенно ночью. Показать
      ему в этот момент ленту, где сок лежит где-то в «Напитках», — издевательство.
   2. ЯВНОЕ НАМЕРЕНИЕ. Он уже нажал «Завтрак» или «Ужин» — сильнее любой догадки.
   3. СВОЯ ИСТОРИЯ В ЭТОТ ЧАС. Не общая частота: завтрак и ужин могут встречаться
      одинаково часто, но в восемь утра нужен только завтрак.
   4. ЧАС СУТОК. Самый слабый сигнал, работает, когда истории ещё нет.

   Два ограничения, которые важнее самих правил.

   Это ПОДЪЁМ НАВЕРХ, а не отсечение. Люди едят кашу вечером и суп на завтрак; спрятать
   от них остальное — значит заставить искать то, что раньше просто лежало.

   И группа обязана быть ПОДПИСАНА: видно, почему именно эти. Молча переставленный
   список — это когда приложение решает за тебя и не объясняет. Мы так не делаем нигде.

   Отдельно: мы упорядочиваем список, а не советуем дозу. «Сахар 3.4, вот быстрые
   углеводы» — помощь. «Съешь 15 граммов» — назначение, и его мы не даём. */

export type Пора = 'утро' | 'день' | 'вечер' | 'ночь';

export function пора(hour: number): Пора {
  if (hour >= 5 && hour < 11) return 'утро';
  if (hour >= 11 && hour < 16) return 'день';
  if (hour >= 16 && hour < 22) return 'вечер';
  return 'ночь';
}

/* Какой приём подставить по умолчанию при открытии шторки. Правило (какая сейчас пора,
   и почему ночь отдельно) живёт здесь, имя — в слое слов. */
export function приёмПоЧасу(hour: number): string { return ПРИЁМ_ПОРЫ[пора(hour)]; }

/* Гипо — не только «уже ниже порога». Падение с 5.2 со скоростью двух стрелок вниз
   закончится гипо через двадцать минут, и человек это знает, поэтому и открыл еду.
   Ловим оба случая: уже низко, либо ещё в норме, но летит вниз.

   Раньше «летит вниз» проверялось по строке направления от источника — набором кодов
   Nightscout вперемешку с символами стрелок. Теперь направление у нас своё и одно
   (domain/trend.ts), поэтому сюда приходит готовый ответ: падает или нет. */
const ЗАПАС_ММОЛЬ = 1.3;

export function гипоСейчас(mmol: number | null, падаетСейчас: boolean): boolean {
  if (mmol == null) return false;
  if (mmol < LOW) return true;
  return mmol < LOW + ЗАПАС_ММОЛЬ && падаетСейчас;
}

export interface Контекст {
  hour: number;
  /** Текущая глюкоза, ммоль/л. */
  mmol: number | null;
  /** Падает ли сахар прямо сейчас — по нашему расчёту (domain/trend.ts). */
  падает?: boolean;
  /** Что человек выбрал в шторке: «Завтрак» и т.п. */
  выбранныйПриём?: string;
  /** Своя история, уже сгруппированная (domain/foods.ts). */
  своё?: Personal[];
  /** Приёмы с временем еды — для разбора по часам. */
  историяЧасов?: { t: number; kind?: string }[];
}

/* ПОЧЕМУ ИМЕННО ЭТИ — состоянием, а не фразой (#324). Слова — в `слова/еда.ts`.

   Четыре повода поднять плитки наверх, и человеку они объясняются по-разному: «сахар 3,4» несёт
   число, «обычно на ужин» — выбранный им приём, «обычно по утрам» — пору. Собрать эту фразу —
   дело слоя слов; решить, какой повод сработал, — дело домена. */
export type Повод =
  | { вид: 'гипо'; mmol: number }        // уже ниже порога — число в фразе
  | { вид: 'падает' }                    // ещё в норме, но летит вниз
  | { вид: 'намерение'; приём: string }  // человек сам нажал «Ужин»
  | { вид: 'пора'; пора: Пора };         // самый слабый сигнал: час суток

export interface Подсказка {
  /** Почему эти. Называет слой слов — здесь только повод. */
  повод: Повод;
  свои: Personal[];
  из_справочника: Food[];
  /** Тревожный повод — красим иначе. */
  гипо: boolean;
}

const ВСЕГО = 5;

export function подсказка(ctx: Контекст): Подсказка | null {
  const п = пора(ctx.hour);

  /* Гипо. Показываем ВСЁ купирование, не подрезая: в этот момент человек не выбирает
     из ассортимента, а хватает то, что есть под рукой. Своё сюда не подмешиваем —
     обычная еда рядом с купированием сбивает с толку. */
  if (гипоСейчас(ctx.mmol, !!ctx.падает)) {
    return {
      повод: ctx.mmol != null && ctx.mmol < LOW
        ? { вид: 'гипо', mmol: ctx.mmol }
        : { вид: 'падает' },
      свои: [],
      из_справочника: FOODS.filter((f) => f.cat === 'hypo'),
      гипо: true,
    };
  }

  const намерение = ctx.выбранныйПриём;
  const приём = намерение || ПРИЁМ_ПОРЫ[п];

  /* Своё в этот час. Окно ±2 часа: человек завтракает не по будильнику, но и не
     в любое время. Считаем по времени ЕДЫ, а не внесения — внести можно и через час. */
  const близкоПоЧасу = new Set(
    (ctx.историяЧасов ?? [])
      .filter((m) => разницаЧасов(new Date(m.t).getHours(), ctx.hour) <= 2)
      .map((m) => m.kind ?? ''),
  );
  const свои = (ctx.своё ?? [])
    .filter((p) => (намерение ? p.kind === намерение : близкоПоЧасу.has(p.kind)))
    .slice(0, 3);

  const из_справочника = FOODS
    .filter((f) => f.cat === 'meal' && f.name.toLowerCase().includes(приём.toLowerCase()))
    .slice(0, ВСЕГО - свои.length);

  if (!свои.length && !из_справочника.length) return null;

  return {
    повод: намерение ? { вид: 'намерение', приём: намерение } : { вид: 'пора', пора: п },
    свои,
    из_справочника,
    гипо: false,
  };
}

/* Расстояние между часами по кругу: 23 и 1 — это два часа, а не двадцать два. */
function разницаЧасов(a: number, b: number): number {
  const d = Math.abs(a - b) % 24;
  return Math.min(d, 24 - d);
}
