import { describe, it, expect } from 'vitest';
import { выбратьПоказание, сказатьОРасхождении, РАСХОЖДЕНИЕ_МС } from './latestGlucose';

/* Показание в круге (SugarLife#326). По этому числу решают, колоть ли, поэтому проверяем
   не «работает», а что оно НЕ МОЖЕТ оказаться старее того, что человек видит списком
   ниже. Ошибка здесь не падает — она показывает два разных числа на одном экране. */

const т = new Date(2026, 7, 17, 0, 21, 0).getTime();
const мин = 60_000;

describe('какое показание в круге', () => {
  it('база новее — берём базу', () => {
    const в = выбратьПоказание({ mmol: 8.6, atMs: т - 10 * мин }, { mmol: 9.1, atMs: т });
    expect(в.показание?.mmol).toBe(9.1);
    expect(в.откуда).toBe('база');
  });

  it('мост новее — берём мост', () => {
    const в = выбратьПоказание({ mmol: 9.1, atMs: т }, { mmol: 8.6, atMs: т - 10 * мин });
    expect(в.показание?.mmol).toBe(9.1);
    expect(в.откуда).toBe('мост');
  });

  /* При равном времени мост вернее: база наполняется из него же, и его значение
     ближе к источнику. Правило нужно, чтобы выбор не зависел от порядка сравнения. */
  it('время равное — мост', () => {
    const в = выбратьПоказание({ mmol: 9.0, atMs: т }, { mmol: 9.1, atMs: т });
    expect(в.откуда).toBe('мост');
  });

  it('второго источника нет — сравнивать не с чем', () => {
    expect(выбратьПоказание({ mmol: 9.1, atMs: т }, null).отставаниеМс).toBe(null);
    expect(выбратьПоказание(null, { mmol: 9.1, atMs: т }).показание?.mmol).toBe(9.1);
    expect(выбратьПоказание(null, null).показание).toBe(null);
  });

  /* Со второго раза с телефона: мост знал ВРЕМЯ последнего показания, но не само число.
     Такой кандидат — не кандидат: по нему нечего показать, и раньше он выигрывал спор,
     после чего круг молчал при непустом списке строкой ниже. */
  it('кандидат без числа не участвует', () => {
    const в = выбратьПоказание(
      { mmol: NaN, atMs: т }, { mmol: 8.1, atMs: т - 5 * мин },
    );
    expect(в.показание?.mmol).toBe(8.1);
  });

  /* Третий источник — стор, из которого построен список «последних измерений». */
  it('берём свежайшее из трёх', () => {
    const в = выбратьПоказание(
      { mmol: 7.0, atMs: т - 20 * мин }, null, { mmol: 8.1, atMs: т },
    );
    expect(в.показание?.mmol).toBe(8.1);
  });
});

describe('когда говорить о расхождении', () => {
  /* Разница в минуту между двумя путями одного источника — обычное дело, и сообщать о
     ней нечего: сенсор пишет раз в минуту-пять. */
  it('минута — молчим', () => {
    const в = выбратьПоказание({ mmol: 9.0, atMs: т - мин }, { mmol: 9.1, atMs: т });
    expect(сказатьОРасхождении(в)).toBe(false);
  });

  /* Десять минут человек видит сам, сравнивая круг со списком. Промолчать — значит
     оставить его думать, что приложение сломано. */
  it('десять минут — говорим', () => {
    const в = выбратьПоказание({ mmol: 8.6, atMs: т - 10 * мин }, { mmol: 9.1, atMs: т });
    expect(сказатьОРасхождении(в)).toBe(true);
  });

  it('на самом пороге ещё молчим', () => {
    const в = выбратьПоказание({ mmol: 9.0, atMs: т - РАСХОЖДЕНИЕ_МС }, { mmol: 9.1, atMs: т });
    expect(сказатьОРасхождении(в)).toBe(false);
  });

  it('сравнивать не с чем — молчим, а не выдумываем', () => {
    expect(сказатьОРасхождении(выбратьПоказание({ mmol: 9.1, atMs: т }, null))).toBe(false);
  });
});
