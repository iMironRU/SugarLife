import type { Entry } from './types';

/* Когда человек ел — предложить моменты, а не арифметику.

   «15 / 30 мин / 1 ч / 2 ч назад» заставляет считать в уме: сейчас 22:33, поел в
   девять — это сколько? Человек либо считает, либо жмёт наугад, и время еды уезжает.
   А от него считаются активные углеводы и вся кривая.

   Но мы знаем больше, чем «сколько минут назад». Если человек вносит еду задним
   числом, у него есть ПОВОД — и повод виден в данных: сахар пошёл вверх, а еды в этот
   момент не внесено. Это и есть тот момент, который он ищет. Показать «в 20:10, когда
   сахар пошёл вверх» дешевле для него, чем любое смещение.

   Подъём ищем по существу, а не по чувствительности: нужен рост, который бывает от еды,
   а не от шума сенсора и не от медленного дрейфа. Отсюда два условия сразу — заметная
   величина за короткое окно. */

const ОКНО_МС = 45 * 60e3;   // за сколько смотрим рост
const РОСТ_ММОЛЬ = 2.2;      // насколько должен вырасти — меньше бывает и без еды
const ГЛУБИНА_МС = 6 * 3600e3; // дальше шести часов вносить задним числом уже незачем
const РЯДОМ_МС = 45 * 60e3;  // еда в этом окне считается объяснением подъёма
const ВЕРШИНА_МС = 2 * 3600e3; // докуда искать вершину подъёма

export interface Момент {
  at: number;
  /** На сколько ммоль поднялся сахар от этого момента. */
  rise: number;
}

/* Подъёмы сахара, не объяснённые углеводами. Свежие первыми.

   `едаВремена` — времена ВСЕХ известных углеводов, а не только своих записей: еда,
   залогированная в AAPS, приходит из Nightscout, и если её не учесть, мы предложим
   внести уже внесённое. Задвоенные углеводы — задвоенная доза. */
export function необъяснённыеПодъёмы(
  entries: Entry[],
  едаВремена: number[],
  now = Date.now(),
): Момент[] {
  const es = entries.filter((e) => e.t >= now - ГЛУБИНА_МС).sort((a, b) => a.t - b.t);
  if (es.length < 3) return [];

  const найдено: Момент[] = [];
  for (let i = 0; i < es.length; i++) {
    const старт = es[i];
    /* Начало подъёма — самая низкая точка перед ростом. Ищем вперёд по окну: если за
       45 минут сахар прибавил заметно, значит рост начался здесь. */
    const конец = es.find((e) => e.t > старт.t && e.t <= старт.t + ОКНО_МС && e.mmol - старт.mmol >= РОСТ_ММОЛЬ);
    if (!конец) continue;

    // еда рядом объясняет подъём — такой момент предлагать незачем
    if (едаВремена.some((t) => Math.abs(t - старт.t) <= РЯДОМ_МС)) { i = пропустить(es, i, конец.t); continue; }
    // и подъёмы вплотную друг к другу — это один подъём, а не три
    if (найдено.some((m) => Math.abs(m.at - старт.t) <= ОКНО_МС)) { i = пропустить(es, i, конец.t); continue; }

    /* Величину берём до ВЕРШИНЫ подъёма, а не до точки, где сработал порог: человеку
       важно, насколько в итоге поднялось. «+2,2» и «+7,4» — это про разный размер
       съеденного, и по ним он свой приём и узнаёт. */
    const хвост = es.filter((e) => e.t > старт.t && e.t <= старт.t + ВЕРШИНА_МС);
    const вершина = хвост.reduce((m, e) => (e.mmol > m.mmol ? e : m), старт);
    найдено.push({ at: старт.t, rise: Math.round((вершина.mmol - старт.mmol) * 10) / 10 });
    /* Перескакиваем до ВЕРШИНЫ, а не до порога. Иначе ступенчатый подъём — а он такой
       и бывает, сахар растёт рывками — распадается на два-три «момента» подряд, и
       человек выбирает из трёх строк про один и тот же приём. */
    i = пропустить(es, i, вершина.t);
  }
  return найдено.reverse().slice(0, 2);
}

function пропустить(es: Entry[], i: number, доВремени: number): number {
  while (i + 1 < es.length && es[i + 1].t <= доВремени) i++;
  return i;
}

/** «21:50» — время момента для подписи. */
export function времяМомента(t: number): string {
  const d = new Date(t);
  return `${d.getHours()}:${String(d.getMinutes()).padStart(2, '0')}`;
}

