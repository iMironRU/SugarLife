import type { Personal } from './foods';

/* Когда предложить назвать приём (SugarLife#122).

   Принцип проекта: лучший ввод данных тот, которого не было. Каталог-сначала переворачивает
   его — чтобы внести еду, заведи блюдо, — и человек перестаёт вносить вовсе, ровно как
   перестаёт логировать замену канюли в AAPS. Поэтому ввод остаётся числом, а имя
   спрашивается позже, необязательно и один раз.

   ТРИ УСЛОВИЯ, и каждое отсекает свой способ надоесть.

   Повтор. Спрашивать про съеденное однажды бессмысленно: это не «блюдо», это случай.
   Имя нужно тому, что человек ест регулярно, — иначе он называет мусор, который потом
   сам же не узнает в списке.

   Свежесть. Группа, в которой не ели два месяца, именем не станет: человек не вспомнит,
   что это было, и назовёт наугад. Молчание тут точнее.

   Один раз. Отказался — больше не спрашиваем никогда. Вопрос, повторяемый до победы, —
   это не предложение, а вымогательство, и отвечают на него лишь бы отстали.

   И СПРАШИВАЕМ ПРО ОДНУ ГРУППУ ЗА РАЗ, самую частую. Список «назовите ваши шесть блюд»
   превращает необязательное в анкету — то самое, от чего мы уходили. */

/** Со скольких повторов группа перестаёт быть случаем и становится привычкой. */
export const ПОВТОРОВ = 3;
/** Насколько давним может быть последний раз, чтобы человек ещё помнил, что это было. */
export const ДАВНОСТЬ_МС = 30 * 86400e3;

export interface Спросить {
  /** Ключ группы — тот же, что у имён (тип приёма + округлённые углеводы). */
  id: string;
  kind: string;
  carbs: number;
  count: number;
}

export function когоНазвать(
  свои: Personal[],
  { имена, отказы }: { имена: Record<string, string>; отказы: string[] },
  сейчас = Date.now(),
): Спросить | null {
  const подходит = свои.filter((p) =>
    p.count >= ПОВТОРОВ
    && !имена[p.id]
    && !отказы.includes(p.id)
    && сейчас - p.lastAt <= ДАВНОСТЬ_МС);
  if (!подходит.length) return null;
  /* Самая частая — она же самая полезная: имя окупится столько раз, сколько человек это
     ест. При равной частоте берём то, что ели недавнее: оно свежее в памяти. */
  const [лучшая] = [...подходит].sort((a, b) => b.count - a.count || b.lastAt - a.lastAt);
  return { id: лучшая.id, kind: лучшая.kind, carbs: лучшая.carbs, count: лучшая.count };
}

