/* «Отложить» для подсветок на «Сегодня» (SugarLife#147).

   Проблема была не в том, что подсветку нельзя убрать, а в том, что с ней нельзя
   ничего сделать, кроме как выполнить. Батарея на 3% висит часами — по нашим же
   данным около восьми, — и всё это время карточка стоит на экране. Постоянная
   карточка перестаёт читаться: человек привыкает пролистывать её глазами, и
   следующая, та самая важная, уедет вместе с ней.

   Скрывать насовсем нельзя: 3% — это не мнение приложения, а состояние железа, и
   кнопка «больше не показывать» означала бы «выключить предупреждение о том, что
   помпа скоро остановится».

   Поэтому откладываем ЭПИЗОД, а не карточку, и возвращаем по ухудшению, а не по
   таймеру. Две величины на подсветку:

   • ЭПИЗОД — какой это случай. Эта разрядка, этот застой резервуара, этот подъём
     сахара. Сменился эпизод (батарейку поменяли и она снова села) — показываем
     заново, что бы человек ни откладывал в прошлый раз.

   • УРОВЕНЬ — насколько всё плохо ВНУТРИ эпизода, число, которое только растёт.
     Батарея 3% → уровень 97, осталось 2 часа инсулина → уровень выше, чем при
     восьми. Отложили на уровне 97 — вернёмся на 100, а не через час.

   Почему не по времени. Таймер возвращает карточку независимо от того, изменилось
   ли что-нибудь: сел на два часа — вернулось; а за эти два часа могло стать хуже, и
   тогда молчать по расписанию тем более неправильно. Возврат по ухудшению отвечает
   ровно на тот вопрос, ради которого подсветка вообще есть.

   Одно правило на все подсветки — намеренно. Восемь кнопок «Потом» с восемью
   способами хранения разъехались бы через месяц; здесь один способ и одно место. */

export interface Отложение {
  /** Какой это случай: сменился — показываем заново. */
  эпизод: string;
  /** На каком уровне отложили. Больше — хуже. */
  уровень: number;
}

export type Отложения = Record<string, Отложение>;

/* Показывать ли подсветку.

   шаг — насколько должно ухудшиться, чтобы вернуться. Он свой у каждой подсветки и
   задаётся в месте вызова: у батареи проценты, у резервуара часы, и «на сколько это
   заметно хуже» знает только тот, кто эту подсветку пишет. */
export function показывать(
  отложения: Отложения, ключ: string, эпизод: string, уровень: number, шаг: number,
): boolean {
  const было = отложения[ключ];
  if (!было) return true;
  if (было.эпизод !== эпизод) return true;
  return уровень >= было.уровень + шаг;
}

/* Отложения, у которых эпизод уже сменился, можно выбрасывать: они больше никогда
   ни на что не повлияют, а место занимают. Вызывается при записи нового отложения —
   отдельной уборки по расписанию не нужно. */
export function убратьЛишние(отложения: Отложения, живые: Record<string, string>): Отложения {
  const итог: Отложения = {};
  for (const [ключ, знач] of Object.entries(отложения)) {
    if (живые[ключ] === undefined || живые[ключ] === знач.эпизод) итог[ключ] = знач;
  }
  return итог;
}
