/* Дневник экрана: что приложение СКАЗАЛО человеку и когда (#396).

   Первая «История» была собрана из журнала движка, и это оказалось не тем. Журнал —
   переписка с прибором: «прибор изучен: характеристики найдены», «показание получено».
   Он про технику и нужен, когда разбирают неисправность; человек же спрашивает другое:
   когда подключился сенсор, когда отвалился, когда был подъём без записи, когда
   приезжало обновление. То есть ровно то, что он ВИДЕЛ на «Сегодня» и что оттуда ушло.

   Отсюда правило: сюда попадает только то, что было показано на экране, и теми же
   словами. Не «событие в системе», а «строка, которую вы видели». Совпадение слов — не
   косметика: человек ищет в истории ту фразу, которую запомнил, и другая формулировка
   заставляет его гадать, то же это событие или другое.

   ХРАНИМ САМИ, потому что хранить больше некому. Лента подключения живёт в памяти шесть
   записей и умирает с перезапуском; обращения гаснут по времени. Раньше я написал, что
   заводить им хранилище ради истории не станем, — и ошибся: без хранилища история
   отвечает не на тот вопрос, который задают.

   ЗАПИСИ НАЧИНАЮТСЯ С МОМЕНТА УСТАНОВКИ этой сборки. Прошлое не восстановить, и делать
   вид, что лента полна, нельзя — экран об этом говорит прямо. */

export type ВидЗаписи = 'прибор' | 'еда' | 'подъём' | 'сборка' | 'тревога';

export interface ЗаписьДневника {
  ключ: string;
  когдаМс: number;
  вид: ВидЗаписи;
  главное: string;
  подпись?: string | null;
}

/* Неделя и четыреста строк. Дневник лежит в localStorage рядом с настройками, и расти
   ему бесконечно нельзя; неделя — тот срок, на который человек ещё помнит вопрос («а
   когда это было, в среду?»), дальше начинается разбор, а он живёт в «Метриках». */
export const ЖИЗНЬ_МС = 7 * 24 * 3600e3;
export const ПРЕДЕЛ = 400;

/* Одинаковую строку подряд не пишем дважды в течение минуты.

   Снимки от движка приходят пачками, и один и тот же переход способен доехать дважды.
   В ленте это выглядит как мигание связи, которого не было, — а по такой строке человек
   делает выводы про прибор. */
export const ОКНО_ПОВТОРА_МС = 60e3;

/** Чистое правило добавления — его и проверяем тестом, без хранилища и часов. */
export function добавить(
  список: ЗаписьДневника[], новая: ЗаписьДневника, сейчас = Date.now(),
  /* «Однажды» — для строк, которые висят на экране днями: обновление ждёт перезапуска
     столько, сколько человек его откладывает, и на каждом запуске приложения писало бы
     в дневник новую строку. В истории это выглядит как десять обновлений вместо одного.
     Такие события отмечаем один раз на всю глубину дневника. */
  однажды = false,
): ЗаписьДневника[] {
  if (однажды && список.some((з) => з.вид === новая.вид && з.главное === новая.главное)) return список;
  const свежая = список[0];
  if (свежая && свежая.вид === новая.вид && свежая.главное === новая.главное
      && новая.когдаМс - свежая.когдаМс < ОКНО_ПОВТОРА_МС) {
    return список;
  }
  return [новая, ...список]
    .filter((з) => сейчас - з.когдаМс <= ЖИЗНЬ_МС)
    .slice(0, ПРЕДЕЛ);
}
