import { describe, it, expect } from 'vitest';
import { когоНазвать, вопрос, ПОВТОРОВ, ДАВНОСТЬ_МС } from './mealNaming';
import type { Personal } from './foods';

/* Когда предложить назвать приём (SugarLife#122).

   Проверяем не текст, а три способа надоесть, каждый из которых отсекается своим
   условием: спросить про случайное, спросить про забытое, спросить второй раз. */

const т = new Date(2026, 7, 19, 12, 0, 0).getTime();
const г = (p: Partial<Personal>): Personal =>
  ({ id: 'Обед|55', kind: 'Обед', carbs: 55, count: 5, lastAt: т - 86400e3, ...p });

const пусто = { имена: {}, отказы: [] };

describe('кого спросить', () => {
  it('повторяется и не названо — спрашиваем', () => {
    expect(когоНазвать([г({})], пусто, т)?.id).toBe('Обед|55');
  });

  /* Съеденное однажды — это случай, а не блюдо. Назвав его, человек засорит список тем,
     чего сам потом не узнает. */
  it('съедено один-два раза — молчим', () => {
    expect(когоНазвать([г({ count: ПОВТОРОВ - 1 })], пусто, т)).toBe(null);
  });

  /* Через два месяца человек не вспомнит, что это было, и назовёт наугад. */
  it('давно не ели — молчим', () => {
    expect(когоНазвать([г({ lastAt: т - ДАВНОСТЬ_МС - 1 })], пусто, т)).toBe(null);
  });

  it('уже названо — не переспрашиваем', () => {
    expect(когоНазвать([г({})], { имена: { 'Обед|55': 'Гречка с курицей' }, отказы: [] }, т)).toBe(null);
  });

  /* Вопрос, повторяемый до победы, — это не предложение, а вымогательство. */
  it('отказались — не спрашиваем больше никогда', () => {
    expect(когоНазвать([г({})], { имена: {}, отказы: ['Обед|55'] }, т)).toBe(null);
  });

  /* Одна за раз, самая частая: список «назовите шесть блюд» превращает необязательное
     в анкету. */
  it('подходящих несколько — берём самую частую', () => {
    const r = когоНазвать([
      г({ id: 'Обед|55', count: 4 }),
      г({ id: 'Завтрак|30', kind: 'Завтрак', carbs: 30, count: 9 }),
    ], пусто, т);
    expect(r?.id).toBe('Завтрак|30');
  });

  it('нечего спрашивать — null, а не пустой объект', () => {
    expect(когоНазвать([], пусто, т)).toBe(null);
  });
});

describe('как спросить', () => {
  it('называем то, что человек делал, без лишних требований', () => {
    const т1 = вопрос({ id: 'Обед|55', kind: 'Обед', carbs: 55, count: 5 });
    expect(т1).toMatch(/обед/);
    expect(т1).toMatch(/55 г/);
    expect(т1).toMatch(/5 раз/);
  });

  it('окончание числительного не режет глаз', () => {
    expect(вопрос({ id: 'a', kind: 'Обед', carbs: 55, count: 3 })).toMatch(/3 раза/);
    expect(вопрос({ id: 'a', kind: 'Обед', carbs: 55, count: 5 })).toMatch(/5 раз /);
    expect(вопрос({ id: 'a', kind: 'Обед', carbs: 55, count: 11 })).toMatch(/11 раз /);
    expect(вопрос({ id: 'a', kind: 'Обед', carbs: 55, count: 21 })).toMatch(/21 раз /);
  });
});
