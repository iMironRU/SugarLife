import type { AccountView, CloudProviderView, SubjectView, UiSnapshot } from '@/sources/bridge';

/* Облачные учётки: что показывать человеку (SugarLifeCore#52, rev ≥ 1.10).

   Правила здесь, а не в разметке, по той же причине, что и у устройств: экран учёток
   будет не один — каталог провайдеров, форма входа, карточка учётки, — и вопрос «что
   сейчас с этой учёткой» на каждом из них должен получать один ответ. */

/** Учётки этого провайдера. */
export function учёткиПровайдера(
  snap: UiSnapshot | null | undefined, providerId: string,
): AccountView[] {
  return (snap?.accounts ?? []).filter((a) => a.providerId === providerId);
}

/* Нужен ли шаг «чьи данные читаем».

   Спрашиваем только при нескольких субъектах. Единственный движок выбирает сам, и
   показать выбор из одного пункта значило бы попросить человека подтвердить то, что
   уже решено, — шаг, который ничего не меняет, но которого он не забудет. */
export function нуженВыборСубъекта(a: AccountView): boolean {
  return (a.subjects?.length ?? 0) > 1;
}

/** Кого читаем сейчас; null — субъект ещё не выбран или их нет вовсе. */
export function активныйСубъект(a: AccountView): SubjectView | null {
  const id = a.activeSubjectId;
  if (!id) return null;
  return (a.subjects ?? []).find((s) => s.id === id) ?? null;
}

/* Как назвать субъекта. Серийник дописываем к имени прибора: под одной учёткой
   Sibionics лежит несколько сенсоров, и «Сенсор» без номера не различает их вовсе. */
export function имяСубъекта(s: SubjectView): string {
  if (s.kind === 'device' && s.serial) return `${s.displayName} · ${s.serial}`;
  return s.displayName;
}

/* Что сказать про состояние учётки.

   ГЛАВНОЕ ПРАВИЛО: при ошибке показываем remediation движка КАК ЕСТЬ и своим текстом не
   подменяем. Причина конкретная. LibreLinkUp живёт в двенадцати регионах, и вход не в
   тот регион возвращает не «неверный пароль», а указание «учётка в регионе EU2».
   Напишем от себя «проверьте пароль» — человек пойдёт менять верный пароль и не войдёт
   никогда, потому что дело не в нём.

   Своими словами говорим только там, где движок молчит: ошибки нет — значит и объяснять
   нечего. */
export type СостояниеУчётки = 'вошли' | 'входим' | 'ошибка' | 'неизвестно';

export function состояниеУчётки(a: AccountView): СостояниеУчётки {
  switch (a.state) {
    case 'Linked': return 'вошли';
    case 'Linking': return 'входим';
    case 'Error': return 'ошибка';
    default: return 'неизвестно';
  }
}

export const СЛОВО_УЧЁТКИ: Record<СостояниеУчётки, string> = {
  вошли: 'подключено',
  входим: 'входим…',
  ошибка: 'не удалось войти',
  неизвестно: 'состояние неизвестно',
};

/* Что человеку делать — берём у движка, если он сказал.

   Отдельной функцией, потому что соблазн «улучшить» текст возникает каждый раз: он
   длинный, он не наш, он не в тон. Разбор реальных облаков показал, что именно в нём и
   лежит единственная полезная информация — код региона, срок пароля, требование зайти
   на сайт вендора. */
export function чтоДелать(a: AccountView): string | null {
  return a.problem?.remediation?.trim() || null;
}

/** Ошибка региона — та, где подмена текста особенно дорога. */
export const КОД_РЕГИОНА = 'cloud.auth.wrong-region';

export function ошибкаРегиона(a: AccountView): boolean {
  return a.problem?.code === КОД_РЕГИОНА;
}

/* Можно ли войти в этого провайдера сейчас.

   `available: false` показываем, но не даём войти: провайдер в каталоге есть, адаптера
   под него ещё нет. Спрятать значило бы соврать про планы, показать без пометки —
   про готовность. */
export function можноВойти(p: CloudProviderView): boolean {
  return p.available !== false;
}
