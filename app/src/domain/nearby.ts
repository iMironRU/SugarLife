import type { Discovered, HardwareView, UiSnapshot } from '@/sources/bridge';
import { связь } from './deviceState';
import { слотПоСнимку } from './slotStatus';

/* Что в эфире наше, а что новое (SugarLifeCore#34).

   Симптом, с которого пришла задача: заведённый OrangeLink торчал в списке «рядом в
   эфире» вместе с кандидатами на добавление — и человек заводил вторую такую же
   запись. Эфир отвечает на вопрос «кто вещает», реестр — на «кто наш», и путать их
   нельзя: у первого действия «добавить», у второго «переподключить».

   Сопоставляет движок: в объявлении приезжает knownDeviceId — тот же самый
   проекционный id, который мы рисуем в карточке и шлём в connect. Своего сопоставления
   мы не держим не из лени: по имени железки повторяются («Dexcom», «MiaoMiao»), и
   перепутать чужой сенсор со своим — худший из возможных исходов. */

/** Насколько свежим считаем «видели в эфире». */
export const РЯДОМ_СВЕЖЕСТЬ = 90_000;

/* Рядом ли железка. Отсутствие отметки — это «не знаем», а не «далеко»: старый мост
   признака не шлёт вовсе, и рисовать по молчанию «нет рядом» значит утверждать то,
   чего нам никто не говорил. Показываем «рядом» только когда движок это сказал. */
export function рядомЛи(nearbyAtMs: number | null | undefined, сейчас: number): boolean {
  if (nearbyAtMs == null) return false;
  return сейчас - nearbyAtMs <= РЯДОМ_СВЕЖЕСТЬ;
}

/* Чья это запись, если она наша.

   Поле knownDeviceId появилось в 1.8; пока его нет, остаётся прежняя догадка по bleId
   внутри идентификатора записи. Догадка слабее ответа движка, поэтому и стоит второй:
   ошибиться в сторону «новое» безопасно (лишний экран подключения), в сторону «наше» —
   нет (подключение не к тому). */
/* Устройства описаны по форме: сопоставление одинаково для записей из devices[] и для
   железа из hardware[] — обеим нужен только id. */
type Запись = { id: string; nearbyAtMs?: number | null };

export function записьВЭфире(d: Discovered, devices: Запись[]): string | null {
  if (d.knownDeviceId !== undefined) return d.knownDeviceId;
  return devices.find((x) => x.id.includes(d.bleId))?.id ?? null;
}

/** Кандидаты на добавление — только те, кого мы ещё не знаем. */
export function новоеВЭфире(discovered: Discovered[], devices: Запись[]): Discovered[] {
  return discovered.filter((d) => записьВЭфире(d, devices) == null);
}

/* Наши железки, замеченные в эфире прямо сейчас. Два источника, потому что они про
   разное: nearbyAtMs — то, что движок помнит о записи, discovered — то, что он слышит
   в эту секунду при открытом скане. Первое работает без скана, второе — до того, как
   движок успел проставить отметку. */
export function наширядом(
  devices: Запись[], discovered: Discovered[], сейчас: number,
): Set<string> {
  const рядом = new Set<string>();
  for (const d of devices) if (рядомЛи(d.nearbyAtMs, сейчас)) рядом.add(d.id);
  for (const d of discovered) {
    const id = записьВЭфире(d, devices);
    if (id) рядом.add(id);
  }
  return рядом;
}

/* Что показывать в диспетчере устройств (SugarLifeCore#42/#44).

   Движок отдаёт готовый список экземпляров железа — hardware[]. Это и есть диспетчер:
   ни фильтровать по виду, ни отличать облако от железки, ни выводить, где мост, больше
   не нужно. Облаков там нет по построению: облако — источник слота, а не железка, у
   него нет ни «рядом», ни «переподключить», ни батареи.

   Запасной путь остаётся ровно для тех, кто hardware[] не отдаёт: старого моста и
   браузерного шима. Там по-прежнему фильтруем devices[] по виду — но это догадка, и
   отличать её от ответа движка важно: догадка не знает, например, что «pump» в списке
   может оказаться облачной записью. */
export function железоДиспетчера(snap: UiSnapshot | null | undefined): HardwareView[] {
  const своё = snap?.hardware;
  if (своё) return своё.map((h) => состояниеИзИсточника(h, snap));
  return (snap?.devices ?? [])
    .filter((d) => d.kind !== 'service')
    .map((d) => ({
      id: d.id, name: d.name, kind: d.kind === 'bridge' ? 'bridge' : d.kind === 'pump' ? 'pump' : 'sensor',
      connection: d.connection, status: d.status, nearbyAtMs: d.nearbyAtMs,
      autoConnect: d.autoConnect, batteryPct: d.batteryPct, rssi: d.rssi, firmware: d.firmware,
      registryState: d.registryState,
    }));
}

/* Состояние железки — от её же проекции в devices[], если она там есть (SugarLife#249).

   Симптом: человек подключает устройство — плитка не меняется; отключает — не меняется;
   подключает снова — лента честно пишет оба события, а плитка стоит как стояла.

   Разница между списками не в свежести, а в назначении. hardware[] отвечает на «что у
   меня есть»: это инвентарь, и заводится он один раз. devices[] отвечает на «что
   происходит»: по нему движок эмитит переходы, на нём же держится лента и весь остальной
   экран. Спрашивать про жизнь инвентарь — всё равно что узнавать погоду по списку окон.

   Поэтому состояние берём у источника с тем же id, а всё остальное — имя, модель, слот,
   батарею, «рядом» — оставляем железу: это его и есть.

   Id не совпал — ничего не меняем. Совпадение id гарантировано контрактом (тот самый id
   уходит в connect), но домысливать сопоставление по имени нельзя: имена в эфире
   повторяются, и связать чужой сенсор со своим хуже, чем не связать вовсе. */
function состояниеИзИсточника(h: HardwareView, snap: UiSnapshot | null | undefined): HardwareView {
  const источник = (snap?.devices ?? []).find((d) => d.id === h.id);
  if (!источник) return h;
  return { ...h, connection: источник.connection, status: источник.status };
}

/** В каком слоте стоит железка — словом для человека. */
export const СЛОТ: Record<'cgm' | 'insulin', string> = {
  cgm: 'сахар', insulin: 'подача инсулина',
};

/* За каким мостом стоит железка. Связь направлена от железки к мосту: мост обслуживает
   несколько устройств, и «мост знает свою помпу» было бы неправдой (то же правило, что
   у мостСлота в slotStatus.ts). */
export function мостЖелезки(
  h: HardwareView, snap: UiSnapshot | null | undefined,
): HardwareView | null {
  /* С ревизии 1.9 ссылка приезжает у самого железа. Проекция источника остаётся
     запасным путём для старых сборок — там поля нет вовсе. */
  const источник = (snap?.devices ?? []).find((d) => d.id === h.id);
  const id = h.behindBridgeId ?? источник?.behindBridgeId;
  if (!id) return null;
  return (snap?.hardware ?? []).find((x) => x.id === id)
    ?? железоДиспетчера(snap).find((x) => x.id === id) ?? null;
}

/* «Рядом» — только у того, кто сам выходит в эфир (SugarLife#251, SugarLifeCore#50).

   На экране стояло: «Medtronic 722 — нет связи · рядом · [Подключить]», а строкой ниже
   «OrangeLink (мост к помпе) — нет связи». Так быть не может физически: помпа Medtronic
   не вещает по блютусу вовсе, её слышно только через мост на 916 МГц. */
export function рядомЖелезо(
  snap: UiSnapshot | null | undefined, сейчас: number,
): Set<string> {
  const железо = железоДиспетчера(snap);
  const сами = наширядом(железо, snap?.discovered ?? [], сейчас);
  const итог = new Set<string>();
  for (const h of железо) {
    /* У железки за мостом «рядом» не существует как понятие: близость — это реклама в
       эфире, а рекламирует себя мост. Сначала мы приравняли её к близости моста, и это
       было лучше прежнего, но всё равно неправдой — ядро поправило нас каноном
       (SugarLifeCore#50). Правильный ответ про такое устройство даёт не «рядом», а
       звенья: отвечает оно или молчит. */
    if (заМостомЛи(h, snap)) continue;
    if (сами.has(h.id)) итог.add(h.id);
  }
  return итог;
}

/** Стоит ли железка за мостом — по ссылке, а не по виду. */
export function заМостомЛи(h: HardwareView, snap: UiSnapshot | null | undefined): boolean {
  if (h.behindBridgeId != null) return true;
  return (snap?.devices ?? []).some((d) => d.id === h.id && d.behindBridgeId != null);
}

/* Три состояния цепочки вместо одного «нет связи» (SugarLifeCore#50, rev ≥ 1.9).

   У устройства за мостом связей две, и до 1.9 они были склеены в одно поле: помпа
   показывала связь с мостом, мост — ответ помпы. Человек видел два «нет связи» и не мог
   понять, с чего начинать, — а начинать надо с моста: помпа за молчащим мостом не
   отзовётся, сколько к ней ни подходи.

   Слова разные не для красоты: за каждым стоит своё действие. «Мост не на связи» — идти
   к мосту, помпу трогать незачем. «Помпа не отвечает» — расстояние, батарея помпы,
   частота. Третье состояние — рабочее, и называть в нём мост стоит: человек должен
   знать, через что идут его данные. */
export type ЗвеноЦепочки = 'мост молчит' | 'устройство молчит' | 'на связи';

export function звеноЦепочки(
  h: HardwareView, snap: UiSnapshot | null | undefined,
): ЗвеноЦепочки | null {
  if (!заМостомЛи(h, snap)) return null;
  const первое = h.bridgeConnection
    ?? (snap?.devices ?? []).find((d) => d.id === h.id)?.bridgeConnection
    /* Поля нет — старая сборка. Тогда о первом звене судим по самому мосту: хуже, чем
       ответ движка, но честнее молчания. */
    ?? мостЖелезки(h, snap)?.connection;
  if (первое == null) return null;
  if (связь({ connection: первое }) !== 'live') return 'мост молчит';
  return связь(h) === 'live' ? 'на связи' : 'устройство молчит';
}

/** Как сказать это человеку. Имя моста подставляет вызывающий — оно есть не всегда. */
export function словоЦепочки(з: ЗвеноЦепочки, мост: string | null): string {
  if (з === 'мост молчит') return мост ? `«${мост}» не на связи` : 'мост не на связи';
  if (з === 'устройство молчит') return 'мост на связи, устройство не отвечает';
  return мост ? `на связи через «${мост}»` : 'на связи через мост';
}

/* Чем различать два одинаковых прибора (SugarLife#251).

   Два OrangeLink в доме — не выдумка на будущее: мост теряется, покупается второй, и
   оба лежат в списке под одним именем. Различает их адрес в эфире.

   Берём его из id записи: движок кладёт туда bleId, и на этом же построено сопоставление
   эфира с реестром (записьВЭфире). Не нашли — не показываем ничего: выдуманный или
   обрезанный «серийник» хуже его отсутствия, потому что по нему начнут различать. */
const АДРЕС = /([0-9A-F]{2}(?::[0-9A-F]{2}){5})/i;

export function адресВЭфире(h: { id: string }): string | null {
  const m = АДРЕС.exec(h.id);
  return m ? m[1].toUpperCase() : null;
}

/* Потеряна ли связь — и с ЧЕМ именно (SugarLife#247).

   Прежнее правило звучало «отвалилась хоть одна железка — тревога», и на экране это
   выглядело так: лента пишет «Medtronic 722 на связи» и «Sibionics GS1 на связи», а
   прямо под ней карточка «Связь с устройством потеряна». Оба утверждения были по-своему
   верны и вместе читались как неисправность приложения.

   Причина в том, что «на связи» — вопрос к двум разным слоям. Железка отвечает про
   радио, слот — про то, наполняется ли он данными. Радио может отвалиться, пока данные
   идут облаком, и наоборот. Тревожить человека надо о последствии, а не о слое: он
   идёт чинить связь тогда, когда данных нет.

   Поэтому железка попадает в тревогу, только если выполнено всё сразу: она отвалилась,
   она стоит в слоте, и слот из-за этого не наполняется. Мост сам по себе тревогой не
   считается — если он был нужен, молчать начнёт и то, что стоит за ним, и назовём мы
   именно его: человеку понятнее «помпа не на связи», чем «отвалился OrangeLink».

   Молчание движка про слоты (старый мост, браузер) возвращает прежнее поведение: там
   проверить нечем, и лучше лишняя тревога, чем пропущенная. */
export function потерянаСвязь(snap: UiSnapshot | null | undefined): HardwareView[] {
  return железоДиспетчера(snap).filter((h) => {
    if (связь(h) !== 'off') return false;
    const роль = рольЖелезки(h);
    if (!роль) return false;
    const слот = слотПоСнимку(snap, роль);
    if (слот == null) return true;
    return слот !== 'на связи';
  });
}

/* Чей слот наполняет железка. Спрашиваем движок (inSlot), а не выводим по виду: одна и
   та же железка может стоять в слоте, а может лежать в ящике заведённой и ненужной.
   Поля нет — падаем на вид, но мост так не разрешить: он обслуживает чужой слот. */
function рольЖелезки(h: HardwareView): 'sensor' | 'pump' | null {
  if (h.inSlot === 'cgm') return 'sensor';
  if (h.inSlot === 'insulin') return 'pump';
  if (h.inSlot === null) return null;
  return h.kind === 'sensor' ? 'sensor' : h.kind === 'pump' ? 'pump' : null;
}

/** Как назвать железку человеку: модель понятнее имени в эфире. */
export const имяЖелезки = (h: HardwareView): string => h.model || h.name;
