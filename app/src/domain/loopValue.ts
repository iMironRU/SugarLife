import type { Device } from './types';

/* «Нет инсулина» и «неизвестно, сколько инсулина» — разные вещи, и на экране они
   обязаны выглядеть по-разному.

   Активный инсулин и активные углеводы не приходят от помпы: их считает цикл. Помпа
   же отчитывается сама по себе — резервуар, батарея, статус, — и делает это чаще.
   Поэтому бывает состояние, в котором про помпу известно всё, а про инсулин на борту
   не известно ничего: цикл на паузе, потерял связь, перезапускается.

   Показать в этот момент пусто — значит сказать «активного инсулина нет». Это
   неправда, и это ровно та неправда, из-за которой человек может уколоть лишнего.
   Поэтому неизвестное показывается прочерком и приглушённым цветом, а рядом, где
   есть место, — почему: «цикл молчит 40 мин».

   Порог — 20 минут: цикл считает каждые пять, четыре пропуска подряд это уже не
   заминка. За такой срок инсулин успевает заметно отработать, и прежнее число
   становится не «слегка устаревшим», а просто неверным. */

export const СВЕЖЕСТЬ_ЦИКЛА_МС = 20 * 60e3;

/* ПОЧЕМУ ЗНАЧЕНИЮ НЕЛЬЗЯ ВЕРИТЬ — кодом, а не фразой (#324). Слова — в `слова/цикл.ts`.

   Три причины различаются не оттенком: «расчёта не было ни разу» и «цикл замолчал сорок минут
   назад» ведут человека в разные места, и одна из них ещё и несёт срок. */
export type ПочемуНеЗнаем = 'нет расчёта' | 'молчит' | 'нет значения';

export interface ЗначениеЦикла {
  /** Значению можно верить как текущему. */
  known: boolean;
  /** Почему нельзя. null, когда всё в порядке. */
  почему: ПочемуНеЗнаем | null;
  /** Сколько молчит; есть только у `молчит` — остальным сроки не нужны. */
  молчитМс?: number;
}

export function loopValue(value: number | null, loopAt: number | null, now = Date.now()): ЗначениеЦикла {
  if (loopAt == null) return { known: false, почему: 'нет расчёта' };
  const возраст = now - loopAt;
  if (возраст > СВЕЖЕСТЬ_ЦИКЛА_МС) return { known: false, почему: 'молчит', молчитМс: возраст };
  if (value == null) return { known: false, почему: 'нет значения' };
  return { known: true, почему: null };
}

/** Активный инсулин из состояния устройства. */
export function activeInsulin(dev: Device | null, now = Date.now()): ЗначениеЦикла {
  return loopValue(dev?.iob ?? null, dev?.loopAt ?? null, now);
}

/** Активные углеводы из состояния устройства. */
export function activeCarbs(dev: Device | null, now = Date.now()): ЗначениеЦикла {
  return loopValue(dev?.cob ?? null, dev?.loopAt ?? null, now);
}
