import { describe, it, expect } from 'vitest';
import { изЖурнала, изПриёмов, лентаИстории, поДням, свернутьПовторы } from './история';
import type { LogRecord } from '@/sources/bridge';
import type { Meal } from './meals';

/* Лента истории (SugarLife#384): что ушло с экрана, но осталось в данных. */

const т = new Date(2026, 7, 19, 14, 0, 0).getTime();
const ДЕНЬ = 86400e3;
const з = (p: Partial<LogRecord>): LogRecord => ({ atMs: т, level: 'Info', event: 'событие', ...p } as LogRecord);
const м = (p: Partial<Meal>): Meal =>
  ({ id: 'm1', t: т, carbs: 45, createdAt: т, sync: 'local', ...p } as Meal);

describe('из журнала движка', () => {
  /* Кадры обмена — сотни записей в минуту, среди которых человеческое тонет. Им место
     в «Что происходит» у прибора, а не в ленте дня. */
  it('кадры обмена в ленту дня не попадают', () => {
    const е = изЖурнала([з({ level: 'Trace' }), з({ level: 'Debug' }), з({ level: 'Info' })]);
    expect(е).toHaveLength(1);
  });

  it('предупреждения и ошибки — это тревоги, остальное — события прибора', () => {
    expect(изЖурнала([з({ level: 'Warn' })])[0].вид).toBe('тревога');
    expect(изЖурнала([з({ level: 'Error' })])[0].вид).toBe('тревога');
    expect(изЖурнала([з({ level: 'Info' })])[0].вид).toBe('прибор');
  });

  /* Слова движка не переводим: он один знает, что означает код BLE-стека. */
  it('текст события берём как есть', () => {
    expect(изЖурнала([з({ event: 'связь потеряна: прибор ушёл из зоны' })])[0].главное)
      .toBe('связь потеряна: прибор ушёл из зоны');
  });
});

describe('из приёмов', () => {
  it('граммы и человеческое название', () => {
    const е = изПриёмов([м({ t: новыйЧас(13), carbs: 60 })]);
    expect(е[0].главное).toBe('60 г · Обед');
  });

  it('имя, данное человеком, главнее нашей догадки', () => {
    const е = изПриёмов([м({ t: новыйЧас(13), carbs: 55, kind: 'Обед' })], { 'Обед|55': 'Гречка с курицей' });
    expect(е[0].главное).toMatch(/Гречка с курицей/);
  });
});

describe('порядок и группировка', () => {
  /* Человек ищет недавнее, а не начало дня. */
  it('свежее сверху', () => {
    const л = лентаИстории([изПриёмов([м({ id: 'a', t: т - 3600e3 }), м({ id: 'b', t: т })])]);
    expect(л[0].когдаМс).toBe(т);
  });

  it('дни не сливаются в одну простыню', () => {
    const л = лентаИстории([изПриёмов([м({ id: 'a', t: т }), м({ id: 'b', t: т - ДЕНЬ })])]);
    const г = поДням(л);
    expect(г).toHaveLength(2);
    expect(г[0].день).toBeGreaterThan(г[1].день);
  });
});

function новыйЧас(h: number): number {
  const д = new Date(т); д.setHours(h, 0, 0, 0); return д.getTime();
}

describe('повторы', () => {
  /* Движок пишет запись на каждое показание — сотни строк за сутки. В ленте дня они
     вытесняют то, ради чего её открыли: когда отвалилась связь, когда ел. */
  it('подряд идущие одинаковые схлопываются в одну строку', () => {
    const е = свернутьПовторы(изЖурнала([
      з({ atMs: т, event: 'показание получено' }),
      з({ atMs: т - 60e3, event: 'показание получено' }),
      з({ atMs: т - 120e3, event: 'показание получено' }),
    ]));
    expect(е).toHaveLength(1);
    expect(е[0].повторов).toBe(3);
  });

  /* Если между повторами был обрыв — он останется виден между группами, а это и есть
     то, что человек ищет. */
  it('событие между повторами разрывает группу', () => {
    const е = свернутьПовторы(изЖурнала([
      з({ atMs: т, event: 'показание получено' }),
      з({ atMs: т - 60e3, event: 'связь потеряна', level: 'Warn' }),
      з({ atMs: т - 120e3, event: 'показание получено' }),
    ]));
    expect(е.map((x) => x.главное)).toEqual(['показание получено', 'связь потеряна', 'показание получено']);
  });

  it('разные события не смешиваем', () => {
    const е = свернутьПовторы(изЖурнала([з({ event: 'а' }), з({ event: 'б' })]));
    expect(е).toHaveLength(2);
  });
});
