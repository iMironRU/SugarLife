import { describe, it, expect } from 'vitest';
import type { Treatment } from '@/domain/types';
import { изЗамен, изЛечения, изДневника, изПодъёмов, изПриёмов, лентаИстории, поДням, свернутьПовторы } from './история';
import type { ЗаписьДневника } from './дневник';
import type { Meal } from './meals';

/* Лента истории (SugarLife#384): что ушло с экрана, но осталось в данных. */

const т = new Date(2026, 7, 19, 14, 0, 0).getTime();
const ДЕНЬ = 86400e3;
const з = (p: Partial<ЗаписьДневника>): ЗаписьДневника =>
  ({ ключ: `к${p.когдаМс ?? т}${p.главное ?? ''}`, когдаМс: т, вид: 'прибор', главное: 'событие', ...p });
const м = (p: Partial<Meal>): Meal =>
  ({ id: 'm1', t: т, carbs: 45, createdAt: т, sync: 'local', ...p } as Meal);

describe('из дневника экрана', () => {
  /* Дневник писался словами экрана — переводить нечего, и в этом весь смысл замены
     журнала движка: человек ищет ту фразу, которую видел (#396). */
  it('текст берём как есть', () => {
    expect(изДневника([з({ вид: 'еда', главное: 'Внесли 45 г' })])[0].главное).toBe('Внесли 45 г');
  });

  it('вид сохраняется — по нему рисуется значок', () => {
    expect(изДневника([з({ вид: 'тревога', главное: 'что-то не так' })])[0].вид).toBe('тревога');
  });

  /* ЖИЗНЬ ЖЕЛЕЗА В ИСТОРИЮ НЕ ИДЁТ (#597).

     Владелец открыл историю и увидел ленту, забитую «на связи» — «отключился», по паре строк в
     минуту. Причина не в важности, а в количестве: связь мигает дважды в минуту, человек ест
     четыре раза в день. Техника вытеснила собой то, ради чего лента заведена. */
  it('события связи в историю не попадают', () => {
    expect(изДневника([з({ вид: 'прибор', главное: '«Sibionics GS1» отключился' })])).toEqual([]);
  });

  it('сообщения о сборках — тоже не жизнь человека', () => {
    expect(изДневника([з({ вид: 'сборка', главное: 'Обновились до сборки abc1234' })])).toEqual([]);
  });

  it('и не выбрасываем лишнего заодно', () => {
    /* Проверка на саму себя: фильтр должен убирать ДВА вида, а не всё подряд. */
    const оставшиеся = изДневника([
      з({ вид: 'прибор', главное: 'отключился' }),
      з({ вид: 'еда', главное: 'Внесли 45 г' }),
      з({ вид: 'подъём', главное: 'Подъём +3,4' }),
      з({ вид: 'тревога', главное: 'Низкий сахар' }),
    ]);
    expect(оставшиеся.map((с) => с.главное)).toEqual(['Внесли 45 г', 'Подъём +3,4', 'Низкий сахар']);
  });
});

describe('из подъёмов без записи', () => {
  /* Ни одного слова о том, что человек что-то скрыл: причин у подъёма больше двух. */
  it('величина подъёма и факт отсутствия записи — без обвинения', () => {
    const е = изПодъёмов([{ at: т, rise: 3.42 }]);
    expect(е[0].главное).toBe('Подъём +3,4 ммоль');
    expect(е[0].подпись).toBe('сахар пошёл вверх · записи нет');
    expect(е[0].главное + ' ' + е[0].подпись).not.toMatch(/не записал|скрыл|забыл/);
  });
});

describe('из приёмов', () => {
  it('граммы и человеческое название', () => {
    const е = изПриёмов([м({ t: новыйЧас(13), carbs: 60 })]);
    expect(е[0].главное).toBe('60 г · Обед');
  });

  it('имя, данное человеком, главнее нашей догадки', () => {
    const е = изПриёмов([м({ t: новыйЧас(13), carbs: 55, kind: 'Обед' })], { 'Обед|55': 'Гречка с курицей' });
    expect(е[0].главное).toMatch(/Гречка с курицей/);
  });
});

describe('порядок и группировка', () => {
  /* Человек ищет недавнее, а не начало дня. */
  it('свежее сверху', () => {
    const л = лентаИстории([изПриёмов([м({ id: 'a', t: т - 3600e3 }), м({ id: 'b', t: т })])]);
    expect(л[0].когдаМс).toBe(т);
  });

  it('дни не сливаются в одну простыню', () => {
    const л = лентаИстории([изПриёмов([м({ id: 'a', t: т }), м({ id: 'b', t: т - ДЕНЬ })])]);
    const г = поДням(л);
    expect(г).toHaveLength(2);
    expect(г[0].день).toBeGreaterThan(г[1].день);
  });
});

function новыйЧас(h: number): number {
  const д = new Date(т); д.setHours(h, 0, 0, 0); return д.getTime();
}

describe('повторы', () => {
  /* Случай остался и после того, как жизнь железа уехала из ленты (#597): движок повторяет
     «молчание» каждые пятнадцать минут, пока причина держится, и ночь такой тревоги — простыня
     одинаковых строк. Образцом здесь теперь тревога, а не связь: связи в ленте больше нет. */
  it('подряд идущие одинаковые схлопываются в одну строку', () => {
    const е = свернутьПовторы(изДневника([
      з({ вид: 'тревога', когдаМс: т, главное: 'Данные не приходили' }),
      з({ вид: 'тревога', когдаМс: т - 60e3, главное: 'Данные не приходили' }),
      з({ вид: 'тревога', когдаМс: т - 120e3, главное: 'Данные не приходили' }),
    ]));
    expect(е).toHaveLength(1);
    expect(е[0].повторов).toBe(3);
  });

  /* Если между повторами было другое событие — оно останется видно между группами, а
     это и есть то, что человек ищет. */
  it('событие между повторами разрывает группу', () => {
    const е = свернутьПовторы(изДневника([
      з({ вид: 'тревога', когдаМс: т, главное: 'Низкий сахар' }),
      з({ вид: 'еда', когдаМс: т - 60e3, главное: 'Внесли 45 г' }),
      з({ вид: 'тревога', когдаМс: т - 120e3, главное: 'Низкий сахар' }),
    ]));
    expect(е.map((x) => x.главное)).toEqual(['Низкий сахар', 'Внесли 45 г', 'Низкий сахар']);
  });

  it('разные события не смешиваем', () => {
    const е = свернутьПовторы(изДневника([
      з({ вид: 'тревога', главное: 'а' }), з({ вид: 'тревога', главное: 'б' })]));
    expect(е).toHaveLength(2);
  });
});

/* ЗАМЕНЫ РАСХОДНИКОВ (#597). «Когда я менял набор и сенсор» — один из четырёх вопросов, с
   которыми в историю вообще приходят. */
describe('из замен расходников', () => {
  const сейчас = т;
  it('замена в окне попадает в ленту человеческими словами', () => {
    const е = изЗамен({ site: сейчас - 3600e3 }, сейчас - 48 * 3600e3);
    expect(е).toHaveLength(1);
    expect(е[0].главное).toBe('Замена: канюля');
  });

  it('замена старше окна не попадает', () => {
    expect(изЗамен({ site: сейчас - 72 * 3600e3 }, сейчас - 48 * 3600e3)).toEqual([]);
  });

  it('незнакомый расходник молча пропускаем, а не показываем ключом', () => {
    /* «Замена: xyz» человеку не говорит ничего и выглядит поломкой. */
    expect(изЗамен({ xyz: сейчас } as Record<string, number>, сейчас - 3600e3)).toEqual([]);
  });

  it('пусто — это пусто, а не строка «замен не было»', () => {
    expect(изЗамен({}, сейчас - 3600e3)).toEqual([]);
  });
});

/* ЛЕЧЕНИЕ В ЛЕНТЕ (#597). «Я колол или нет» — самый частый и самый опасный вопрос, с которым в
   историю приходят, и до сегодня лента на него не отвечала вовсе. */
describe('из лечения', () => {
  const л = (o: Partial<Treatment>): Treatment =>
    ({ t: т, type: 'Bolus', carbs: null, insulin: null, rate: null, duration: null, ...o });

  it('болюс показывается единицами', () => {
    const е = изЛечения([л({ insulin: 4.25 })], т - 3600e3);
    expect(е[0].главное).toBe('4,3 ед');
    expect(е[0].вид).toBe('болюс');
  });

  it('еда с болюсом — одной строкой, а не двумя', () => {
    /* Это один приём: болюс на еду. Две строки читались бы как два события. */
    const е = изЛечения([л({ type: 'Meal Bolus', insulin: 6, carbs: 45 })], т - 3600e3);
    expect(е).toHaveLength(1);
    expect(е[0].главное).toBe('6,0 ед · 45 г');
  });

  it('РАБОТА ПЕТЛИ в ленту не идёт', () => {
    /* Петля правит базал десятки раз за ночь. Лента, куда идут за «во сколько я ел», утонула бы в
       ней ровно так же, как утонула в мигании связи. Ядро сказало прямо: не показывать. */
    expect(изЛечения([
      л({ type: 'TempBasal', rate: 0.8, duration: 30 }),
      л({ type: 'Basal', rate: 1.0 }),
      л({ type: 'Temp Basal', rate: 0.5 }),
    ], т - 3600e3)).toEqual([]);
  });

  it('пустая запись без инсулина и углеводов не показывается', () => {
    /* Отметки вроде «сменил канюлю» приходят лечением без чисел — им место в замене, не здесь. */
    expect(изЛечения([л({ type: 'Site Change' })], т - 3600e3)).toEqual([]);
  });

  it('старее окна не показываем', () => {
    expect(изЛечения([л({ t: т - 72 * 3600e3, insulin: 3 })], т - 48 * 3600e3)).toEqual([]);
  });

  it('видно, что запись пришла из облака, а не внесена человеком', () => {
    /* Доверие к своей записи и к чужой разное: своя точна по времени, чужая — как записала петля. */
    expect(изЛечения([л({ insulin: 2 })], т - 3600e3)[0].подпись).toBe('из облака');
  });
});