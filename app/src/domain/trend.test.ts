import { describe, it, expect } from 'vitest';
import {
  наклон, стрелкаПоНаклону, направлениеПоИстории, направление, изНаправленияNS,
  скоростьЗа15, СТРЕЛКА, ОКНО_МИН, СВЕЖЕСТЬ_МИН,
} from './trend';
import type { Entry } from '@/sources/nightscout';

/* Стрелку в круге видят чаще любой другой цифры, и по ней принимают решения: подождать
   или колоть. Поэтому её правила под тестами целиком — и особенно те, что заставляют
   стрелку молчать. Ошибка «показали ровно, когда не знали» выглядит нормально ровно до
   того момента, когда человек на неё положится. */

const СЕЙЧАС = new Date(2026, 7, 14, 12, 0).getTime();
const МИН = 60_000;

/** Ряд точек через 5 минут: значения идут от последнего к первому. */
const ряд = (значения: number[], доКонцаМин = 0): Entry[] =>
  значения.map((mmol, i) => ({
    t: СЕЙЧАС - доКонцаМин * МИН - (значения.length - 1 - i) * 5 * МИН,
    mgdl: mmol * 18, mmol, dir: '',
  } as Entry));

describe('наклон по точкам', () => {
  it('ровная линия — ноль', () => {
    expect(наклон(ряд([7, 7, 7, 7]))).toBeCloseTo(0, 6);
  });

  it('рост на 1 ммоль за 15 минут — примерно 0,067 в минуту', () => {
    expect(наклон(ряд([6, 6.33, 6.67, 7]))!).toBeCloseTo(1 / 15, 3);
  });

  /* Регрессия, а не «последняя минус первая»: один выброс на краю окна разворачивал бы
     стрелку целиком, а у сенсоров такие выбросы обычны. */
  it('выброс на краю не переворачивает стрелку', () => {
    expect(стрелкаПоНаклону(наклон(ряд([7, 7.1, 7.2, 7.3]))!)).toBe('Stable');
    // одна точка ушла вниз на 0,6 — стрелка не должна стать «падает»
    expect(стрелкаПоНаклону(наклон(ряд([7, 7.1, 7.2, 6.6]))!)).toBe('Stable');
  });

  it('одна точка — считать нечего', () => {
    expect(наклон(ряд([7]))).toBe(null);
  });
});

describe('пороги стрелок', () => {
  /* Пороги общие с сенсорами (консенсус по НМГ): ступень — 1 мг/дл/мин ≈ 0,055 ммоль. */
  it('меньше ступени — «ровно»', () => {
    expect(стрелкаПоНаклону(0.03)).toBe('Stable');
    expect(стрелкаПоНаклону(-0.03)).toBe('Stable');
  });

  it('ступень за ступенью — вверх', () => {
    expect(стрелкаПоНаклону(0.06)).toBe('RisingSlowly');
    expect(стрелкаПоНаклону(0.12)).toBe('Rising');
    expect(стрелкаПоНаклону(0.2)).toBe('RisingRapidly');
  });

  it('и вниз — зеркально', () => {
    expect(стрелкаПоНаклону(-0.06)).toBe('FallingSlowly');
    expect(стрелкаПоНаклону(-0.12)).toBe('Falling');
    expect(стрелкаПоНаклону(-0.2)).toBe('FallingRapidly');
  });
});

describe('направление по нашей истории', () => {
  it('растущий ряд — стрелка вверх, и ступень соответствует скорости', () => {
    // +1,8 ммоль за 15 мин = 0,12 ммоль/мин — это «растёт», но ещё не «стремительно»
    expect(направлениеПоИстории(ряд([6, 6.6, 7.2, 7.8]), СЕЙЧАС)).toBe('Rising');
    // +3 ммоль за те же 15 минут — уже стремительно
    expect(направлениеПоИстории(ряд([6, 7, 8, 9]), СЕЙЧАС)).toBe('RisingRapidly');
  });

  it('ровный ряд — «ровно», и это уже утверждение по данным, а не подстановка', () => {
    expect(направлениеПоИстории(ряд([7, 7.02, 6.98, 7]), СЕЙЧАС)).toBe('Stable');
  });

  /* Три случая молчания. Каждый — ответ «не знаю», и рисовать вместо него прямую
     стрелку значит сказать «держится ровно» от своего имени. */
  it('данных нет — молчим', () => {
    expect(направлениеПоИстории([], СЕЙЧАС)).toBe('Unknown');
  });

  it('последняя точка старая — молчим, а не рассказываем о прошлом', () => {
    expect(направлениеПоИстории(ряд([6, 6.5, 7, 7.5], СВЕЖЕСТЬ_МИН + 3), СЕЙЧАС)).toBe('Unknown');
  });

  it('точек в окне мало — молчим', () => {
    expect(направлениеПоИстории(ряд([7, 7.5]), СЕЙЧАС)).toBe('Unknown');
  });

  /* Старые точки за окном в расчёт не идут: направление — про «сейчас», а не про
     последние два часа. */
  it('считаем только по окну, а не по всей истории', () => {
    const длинный = ряд([3, 4, 5, 6, 7, 7.05, 7.1, 7.05]);
    expect(направлениеПоИстории(длинный, СЕЙЧАС, ОКНО_МИН)).toBe('Stable');
  });
});

describe('считаем только сами', () => {
  /* Решение владельца: слово источника не берём вовсе. Как считает чужой загрузчик —
     неизвестно: у каждого своё окно и сглаживание, часть проставляет 'Flat' по
     умолчанию. Стрелка, собранная из разных правил в зависимости от того, кто сегодня
     отдаёт данные, — это не одна стрелка, а несколько похожих. */
  it('источник говорит «ровно», история говорит «растёт» — показываем рост', () => {
    const сИсточником = ряд([6, 6.6, 7.2, 7.8]).map((e) => ({ ...e, dir: 'Flat' }));
    expect(направление(сИсточником, СЕЙЧАС)).toBe('Rising');
  });

  it('истории нет — стрелки нет, и слово источника этого не меняет', () => {
    expect(направление([], СЕЙЧАС)).toBe('Unknown');
    expect(СТРЕЛКА[направление([], СЕЙЧАС)]).toBe('');
  });

  /* Коды Nightscout всё ещё нужны — но только там, где направление это свойство
     ЗАПИСИ: в ленте показаний у строки двухдневной давности не может быть
     сегодняшнего расчёта. */
  it('в ленте показаний код записи по-прежнему читаем', () => {
    expect(изНаправленияNS('SingleDown')).toBe('Falling');
    expect(изНаправленияNS('NOT COMPUTABLE')).toBe('Unknown');
    expect(изНаправленияNS(undefined)).toBe('Unknown');
  });
});

describe('скорость за четверть часа', () => {
  it('рост на ммоль за 15 минут так и считается', () => {
    expect(скоростьЗа15(ряд([6, 6.33, 6.67, 7]), СЕЙЧАС)!).toBeCloseTo(1, 1);
  });

  it('данных мало или они старые — null, а не ноль', () => {
    expect(скоростьЗа15(ряд([7, 7.1]), СЕЙЧАС)).toBe(null);
    expect(скоростьЗа15(ряд([6, 6.5, 7, 7.5], 30), СЕЙЧАС)).toBe(null);
  });
});
