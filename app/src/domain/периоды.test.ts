import { describe, it, expect } from 'vitest';
import { ПЕРИОДЫ_РАЗБОРА, дней } from './периоды';

describe('периоды разбора', () => {
  it('набор один и включает оба клинических окна', () => {
    /* 14 — окно отчёта врачу, 90 — горизонт среднего сахара. Пропажа любого из них означает,
       что вкладка не умеет показать то, ради чего в неё и заходят. */
    expect(ПЕРИОДЫ_РАЗБОРА).toContain(14);
    expect(ПЕРИОДЫ_РАЗБОРА).toContain(90);
  });

  it('идут по возрастанию и без повторов', () => {
    expect([...ПЕРИОДЫ_РАЗБОРА].sort((а, б) => а - б)).toEqual(ПЕРИОДЫ_РАЗБОРА);
    expect(new Set(ПЕРИОДЫ_РАЗБОРА).size).toBe(ПЕРИОДЫ_РАЗБОРА.length);
  });

  it('склоняет по правилу, а не по нашему набору', () => {
    expect(ПЕРИОДЫ_РАЗБОРА.map((д) => `${д} ${дней(д)}`))
      .toEqual(['3 дня', '7 дней', '14 дней', '30 дней', '90 дней']);
    // Правило проверяем и там, куда список пока не заходит.
    expect([1, 2, 5, 11, 12, 21, 22, 101].map(дней))
      .toEqual(['день', 'дня', 'дней', 'дней', 'дней', 'день', 'дня', 'день']);
  });
});
