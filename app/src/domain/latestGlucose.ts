/* Какое показание показывать в круге (SugarLife#326).

   С телефона: в списке «Последние измерения» 00:21 — 9,1, а в круге 8,6 и «10 минут
   назад». Два числа про одно и то же на одном экране, и по кругу принимают решение о
   коррекции.

   ОТКУДА БЕРЁТСЯ РАЗНИЦА. Круг брал показание у моста (`monitor`), список и график — из
   нашей базы. Оба наполняются из одного Nightscout, но разными путями и с разной
   частотой: стор опрашивается раз в минуту, база синхронизируется своим расписанием.
   Рассинхрон между ними ничем не ограничен, и база может обогнать мост.

   ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ВЗЯТЬ БАЗУ. С нативным ядром источником может быть сенсор
   напрямую, и тогда мост знает то, чего в базе ещё нет. Правильный ответ не «всегда
   один источник», а «свежайший из двух» — и сказать, если второй заметно отстал.

   ПОЧЕМУ МОЛЧАНИЕ ХУЖЕ ОТСТАВАНИЯ. Человек видит два разных числа и не знает, какому
   верить. Отставание объяснимо (сеть, сон телефона, редкая выгрузка), а молчание про
   него выглядит поломкой — и подрывает доверие к обоим числам сразу. */

export interface Показание {
  mmol: number;
  atMs: number;
}

export type Откуда = 'мост' | 'база';

export interface Выбор {
  показание: Показание | null;
  откуда: Откуда | null;
  /* Насколько отстал ПРОИГРАВШИЙ источник. null — второго источника нет вовсе, и
     сравнивать не с чем: это не «всё сошлось», это «сверить нечем». */
  отставаниеМс: number | null;
}

/* Порог, с которого о расхождении стоит говорить.

   Две минуты — не «точность», а осмысленность: сенсор пишет раз в минуту-пять, и
   разница в одну-две минуты между двумя путями одного и того же источника — обычное
   дело, о котором сообщать нечего. А вот пять и десять минут человек уже видит сам,
   сравнивая круг со списком, — и если мы промолчим, он решит, что приложение сломано. */
export const РАСХОЖДЕНИЕ_МС = 2 * 60_000;

/* Источников не два, а сколько есть, и это не обобщение ради обобщения.

   Второй раз с телефона: в списке 08:10 — 8,1, а в круге прочерк и «нет связи · 1 мин».
   Мост знал ВРЕМЯ последнего показания, но не само число, часовое окно базы в этот
   момент оказалось пустым, — и круг промолчал, хотя число было на том же экране, строкой
   ниже. Стор, из которого строится список, в выборе не участвовал вовсе.

   Поэтому кандидаты приходят списком: добавить третий, четвёртый или убрать источник
   можно, не трогая правило. Правило одно — самый свежий из тех, у кого ЕСТЬ ЧИСЛО.
   Кандидат, знающий только время, кандидатом не является: по нему нечего показать. */
export function выбратьПоказание(...кандидаты: (Показание | null | undefined)[]): Выбор {
  const годные = кандидаты.filter((к): к is Показание => !!к && Number.isFinite(к.mmol));
  if (!годные.length) return { показание: null, откуда: null, отставаниеМс: null };

  /* Порядок кандидатов — это старшинство при равном времени: первым идёт тот, кто ближе
     к источнику. Строгое «новее», а не «не старее», как раз и сохраняет это старшинство. */
  let лучший = годные[0];
  for (const к of годные.slice(1)) if (к.atMs > лучший.atMs) лучший = к;

  const самыйСтарый = годные.reduce((a, b) => (a.atMs < b.atMs ? a : b));
  return {
    показание: лучший,
    откуда: лучший === годные[0] ? 'мост' : 'база',
    отставаниеМс: годные.length > 1 ? лучший.atMs - самыйСтарый.atMs : null,
  };
}

/** Стоит ли сказать, что второй источник отстал. */
export function сказатьОРасхождении(в: Выбор): boolean {
  return в.отставаниеМс != null && в.отставаниеМс > РАСХОЖДЕНИЕ_МС;
}

/* С какого возраста ПОКАЗАННОЕ число считается отставшим.

   Пятнадцать минут — тот же порог, что у шима, и он остаётся нашим только там, где
   статуса нет. Важно другое: мерить надо возраст показанного, а не мнение моста о себе.
   Мост может считать себя отставшим, когда в круге уже стоит свежее значение из базы, —
   и приглушать его было бы неправдой в другую сторону. */
export const ОТСТАВАНИЕ_МС = 15 * 60_000;
