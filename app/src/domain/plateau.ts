/* Сжатие ряда измерений до плато.

   Замеры от помпы приходят раз в минуту, и подряд идущие одинаковые значения не несут
   ничего, кроме объёма. Но и оставлять по одной точке на плато нельзя: тогда теряется
   его КОНЕЦ, а именно он и нужен — «сколько помпа продержалась на 1%» это расстояние
   от входа на плато до выхода с него. Первая версия хранила только вход, и все замеры
   получались нулевыми: вход и выход оказывались одной и той же точкой.

   Поэтому от каждого плато оставляем края: первую точку и последнюю. За девяносто
   дней это сотни строк вместо сотен тысяч.

   Ряд здесь любой: заряд батареи, остаток в резервуаре. Правило одно, поэтому и
   функция одна — иначе завелись бы две копии, и починили бы только одну. */
export interface Plateau { t: number; v: number }

export function compressPlateaus(points: Plateau[]): Plateau[] {
  const s = points
    .filter((p) => Number.isFinite(p.t) && Number.isFinite(p.v))
    .sort((a, b) => a.t - b.t);
  const out: Plateau[] = [];
  for (let i = 0; i < s.length; i++) {
    const край = i === 0 || i === s.length - 1
      || s[i].v !== s[i - 1].v
      || s[i].v !== s[i + 1].v;
    if (край && out[out.length - 1]?.t !== s[i].t) out.push(s[i]);
  }
  return out;
}
