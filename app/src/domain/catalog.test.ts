import { describe, it, expect } from 'vitest';
import { PUMPS, pumpById, СЛИТЫЕ, isCurrentPump } from './catalog';

/* Барьер качества справочника помп (SugarLife#223).

   Справочник — данные, а не код, и ломается он не падением, а тихой неправдой: помпа
   девяностых лежит как актуальная, одна и та же модель заведена дважды с разными
   статусами. Видно это становится далеко от справочника — в списке выбора, где человек
   ищет свою помпу и решает, заработает ли она.

   Проверяем то, что проверяется без источника: противоречия ВНУТРИ данных. Правду о
   рынке barrier не знает и знать не может — её проставляет человек. */

describe('справочник помп', () => {
  it('id уникальны', () => {
    const все = PUMPS.map((p) => p.id);
    expect(все.length).toBe(new Set(все).size);
  });

  /* Дубль ловим по модели без марки: «Accu-Chek D-Tron Plus» и «D-Tron / D-Tron Plus»
     были одной помпой в двух записях, и статусы у них разъехались. */
  it('одна модель — одна запись', () => {
    const ключ = (s: string) => s.toLowerCase().replace(/accu-chek|minimed|[\s/()+.-]/g, '');
    const счёт = new Map<string, string[]>();
    for (const p of PUMPS) {
      const к = ключ(p.model);
      счёт.set(к, [...(счёт.get(к) ?? []), p.model]);
    }
    const дубли = [...счёт.values()].filter((v) => v.length > 1);
    expect(дубли, `дубли: ${JSON.stringify(дубли)}`).toEqual([]);
  });

  it('статус только из словаря — по нему считаются группы списка', () => {
    const можно = new Set(['актуальная', 'снята', 'разработка']);
    const чужие = PUMPS.filter((p) => !можно.has(p.statusClass)).map((p) => p.model);
    expect(чужие).toEqual([]);
  });

  /* Текст и класс должны говорить одно. Именно это расхождение и держало Omnipod Eros в
     «актуальных», хотя в его же строке стояли даты прекращения продаж. */
  it('«актуальная» не противоречит собственному тексту статуса', () => {
    const врут = PUMPS
      .filter((p) => isCurrentPump(p) && /снят|прекращ|свёрнут|вытесняется/i.test(p.status ?? ''))
      .map((p) => `${p.model}: ${p.status}`);
    expect(врут).toEqual([]);
  });

  /* Свалка вместо производителя ломает не список, а поиск: человек ищет «Animas» и не
     находит, потому что производитель у записи назван «закрытые компании». */
  it('производитель — это производитель, а не корзина', () => {
    const корзины = PUMPS
      .filter((p) => /закрыт|ушедши|прочие|разное/i.test(p.manufacturer.split(' (')[0]))
      .map((p) => p.manufacturer);
    expect([...new Set(корзины)]).toEqual([]);
  });

  /* Рынок — единственное поле, которое заполняется вручную и потому чаще всего пустое.
     Пусто обязано означать «не выяснено», а не «не продаётся»: пустой массив прочитали
     бы как второе. */
  it('рынок либо назван, либо не выяснен — пустых списков нет', () => {
    const пустые = PUMPS.filter((p) => Array.isArray(p.market) && p.market.length === 0);
    expect(пустые.map((p) => p.model)).toEqual([]);
  });
});

describe('слитые записи', () => {
  it('удалённый id отвечает тем, во что его слили', () => {
    for (const [было, стало] of Object.entries(СЛИТЫЕ)) {
      expect(PUMPS.some((p) => p.id === было)).toBe(false);
      expect(pumpById(было)?.id).toBe(стало);
    }
  });

  it('цель слияния существует — иначе настройка молча превращается в пустоту', () => {
    for (const стало of Object.values(СЛИТЫЕ)) {
      expect(PUMPS.some((p) => p.id === стало)).toBe(true);
    }
  });
});
