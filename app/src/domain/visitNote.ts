import type { Entry } from '@/sources/nightscout';

/* Записка к приёму: цели, полнота данных, оценка «в цели / вне» (SugarLife#156).

   Записка отвечает на вопрос «что показать и о чём спросить через час в кабинете», и
   потому все числа в ней обязаны называться так же, как их называет врач. Цели взяты
   из клинических рекомендаций «Сахарный диабет 1 типа у взрослых» (РАЭ, одобрены
   Минздравом, ID 286, ред. 2025), таблица 6.

   ДВА НАБОРА ЦЕЛЕЙ, А НЕ ОДИН. Это главное, что выяснилось при чтении документа: для
   молодых и среднего возраста без факторов риска и для пожилых или с факторами риска
   цели РАЗНЫЕ. «TIR 62 %» — недобор по первому набору и хороший результат по второму.
   Показать одно число без указания, чьи цели применяются, значит дать врачу повод
   пересчитывать в уме, а человеку — испугаться или успокоиться не по делу.

   Какой набор его — человек знает от врача (документ прямо говорит про ИНДИВИДУАЛЬНЫЕ
   цели). Мы не выбираем за него и не угадываем по возрасту: возраст мы не спрашиваем,
   а факторы риска — тем более не наше дело. */

export type НаборЦелей = 'обычные' | 'мягкие';

export interface Цели {
  подпись: string;
  tir: number;   // не меньше, %
  tbr: number;   // не больше, %
  tar: number;   // не больше, %
  cv: number;    // не больше, %
}

export const ЦЕЛИ: Record<НаборЦелей, Цели> = {
  обычные: {
    подпись: 'молодой и средний возраст, без факторов риска',
    tir: 70, tbr: 4, tar: 25, cv: 36,
  },
  мягкие: {
    подпись: 'пожилой возраст или факторы риска',
    tir: 50, tbr: 1, tar: 50, cv: 36,
  },
};

/* Полнота данных — часть стандарта, а не наша придирчивость: документ требует не
   меньше 14 дней ношения и не меньше 70 % времени с активным устройством.

   Отчёт по двум неделям с 40 % пропусков и отчёт без пропусков — разные документы, и
   врач должен видеть разницу сразу, а не выяснять её вопросами. */
export const МИН_ДНЕЙ = 14;
export const МИН_ДОЛЯ = 70;
/** Шаг сенсора, минут: по нему считается, сколько показаний «должно было быть». */
export const ШАГ_НМГ_МИН = 5;

export interface Полнота {
  дней: number;        // календарных дней, в которых есть хоть одно показание
  доля: number;        // % от ожидаемого числа показаний
  хватает: boolean;    // и дней, и доли — по стандарту
}

export function полнота(entries: Entry[], отМс: number, доМс: number): Полнота {
  const свои = entries.filter((e) => e.t >= отМс && e.t <= доМс);
  const дни = new Set(свои.map((e) => new Date(e.t).toDateString()));
  const ожидалось = Math.max(1, Math.round((доМс - отМс) / (ШАГ_НМГ_МИН * 60_000)));
  const доля = Math.min(100, (свои.length / ожидалось) * 100);
  return {
    дней: дни.size,
    доля,
    хватает: дни.size >= МИН_ДНЕЙ && доля >= МИН_ДОЛЯ,
  };
}

export type Оценка = 'в цели' | 'мимо';

/* Достигнута ли цель. Слово выбрано намеренно нейтральным: «мимо», а не «плохо» и не
   «требует коррекции». Первое — факт про число, второе — оценка человека, третье —
   назначение, которого мы делать не вправе. */
export function оценка(значение: number, цель: number, вид: 'не меньше' | 'не больше'): Оценка {
  return вид === 'не меньше'
    ? (значение >= цель ? 'в цели' : 'мимо')
    : (значение <= цель ? 'в цели' : 'мимо');
}

/* Динамика: стало лучше или хуже, и в чём (SugarLife#156).

   Отдельный блок, потому что отвечает на вопрос, которого нет ни у метрик, ни у
   разбора: «мои усилия что-то изменили?». Это и повод для разговора с врачом, и
   единственная в приложении возможность похвалить человека за две недели работы —
   а работа тут ежедневная и незаметная.

   ТРИ ПРАВИЛА, БЕЗ КОТОРЫХ БЛОК ВРЁТ.

   1. Окна равной длины. Сравнивать две недели с тремя нельзя: в длинном окне больше
      всего, включая плохое, и «улучшение» получилось бы из арифметики, а не из жизни.

   2. Сравнивать можно только полные окна. Если в прошлом периоде сенсор молчал треть
      времени, «время в диапазоне выросло» может значить ровно одно: пропущены были
      именно плохие часы. Неполные данные не сравниваем вовсе и говорим почему.

   3. Мелкие сдвиги — не изменения. Разница в один процент времени в диапазоне — это
      шум одного неудачного обеда, и объявлять её улучшением значит учить человека
      радоваться случайности. Пороги ниже подобраны так, чтобы отмечать то, что человек
      и сам заметил бы по самочувствию. */

export interface Сдвиг {
  что: string;
  стало: number;
  было: number;
  /** Насколько изменилось, в единицах показателя. */
  дельта: number;
  /** Стало ли лучше. Не «больше/меньше»: у времени ниже диапазона лучше — меньше. */
  лучше: boolean;
  /** Как показать число: проценты или ммоль/л. */
  вид: 'процент' | 'глюкоза';
}

/* Пороги значимости. Взяты не с потолка: время в диапазоне принято обсуждать шагами
   по 5 п.п. (это примерно час в сутки), час низкого сахара в неделю — уже разговор,
   а вариабельность гуляет на пару процентов сама по себе. */
const ПОРОГ = { tir: 3, tbr: 0.5, tar: 3, cv: 2, mean: 0.3 };

export function динамика(
  сейчас: { target: number; tbr: number; tar: number; cv: number; mean: number } | null,
  прошлое: { target: number; tbr: number; tar: number; cv: number; mean: number } | null,
): Сдвиг[] {
  if (!сейчас || !прошлое) return [];
  const строки: Array<[string, number, number, number, boolean, Сдвиг['вид']]> = [
    ['Время в диапазоне', сейчас.target, прошлое.target, ПОРОГ.tir, true, 'процент'],
    ['Время ниже 3,9', сейчас.tbr, прошлое.tbr, ПОРОГ.tbr, false, 'процент'],
    ['Время выше 10,0', сейчас.tar, прошлое.tar, ПОРОГ.tar, false, 'процент'],
    ['Вариабельность (CV)', сейчас.cv, прошлое.cv, ПОРОГ.cv, false, 'процент'],
    ['Средняя глюкоза', сейчас.mean, прошлое.mean, ПОРОГ.mean, false, 'глюкоза'],
  ];
  return строки
    .filter(([, стало, было, порог]) => Math.abs(стало - было) >= порог)
    .map(([что, стало, было, , ростЛучше, вид]) => ({
      что, стало, было, дельта: стало - было,
      лучше: ростЛучше ? стало > было : стало < было,
      вид,
    }));
}

/* Можно ли вообще сравнивать. Отдельной функцией, потому что ответ «нет» — это не
   отсутствие блока, а строка с объяснением: человек, увидевший пустоту, решит, что
   ничего не изменилось, а на самом деле мы просто не знаем. */
export function сравнимо(a: Полнота, b: Полнота): boolean {
  return a.доля >= МИН_ДОЛЯ && b.доля >= МИН_ДОЛЯ;
}
