import type { Entry } from '@/sources/nightscout';

/* Записка к приёму: цели, полнота данных, оценка «в цели / вне» (SugarLife#156).

   Записка отвечает на вопрос «что показать и о чём спросить через час в кабинете», и
   потому все числа в ней обязаны называться так же, как их называет врач. Цели взяты
   из клинических рекомендаций «Сахарный диабет 1 типа у взрослых» (РАЭ, одобрены
   Минздравом, ID 286, ред. 2025), таблица 6.

   ДВА НАБОРА ЦЕЛЕЙ, А НЕ ОДИН. Это главное, что выяснилось при чтении документа: для
   молодых и среднего возраста без факторов риска и для пожилых или с факторами риска
   цели РАЗНЫЕ. «TIR 62 %» — недобор по первому набору и хороший результат по второму.
   Показать одно число без указания, чьи цели применяются, значит дать врачу повод
   пересчитывать в уме, а человеку — испугаться или успокоиться не по делу.

   Какой набор его — человек знает от врача (документ прямо говорит про ИНДИВИДУАЛЬНЫЕ
   цели). Мы не выбираем за него и не угадываем по возрасту: возраст мы не спрашиваем,
   а факторы риска — тем более не наше дело. */

export type НаборЦелей = 'обычные' | 'мягкие';

export interface Цели {
  подпись: string;
  tir: number;   // не меньше, %
  tbr: number;   // не больше, %
  tar: number;   // не больше, %
  cv: number;    // не больше, %
}

export const ЦЕЛИ: Record<НаборЦелей, Цели> = {
  обычные: {
    подпись: 'молодой и средний возраст, без факторов риска',
    tir: 70, tbr: 4, tar: 25, cv: 36,
  },
  мягкие: {
    подпись: 'пожилой возраст или факторы риска',
    tir: 50, tbr: 1, tar: 50, cv: 36,
  },
};

/* Полнота данных — часть стандарта, а не наша придирчивость: документ требует не
   меньше 14 дней ношения и не меньше 70 % времени с активным устройством.

   Отчёт по двум неделям с 40 % пропусков и отчёт без пропусков — разные документы, и
   врач должен видеть разницу сразу, а не выяснять её вопросами. */
export const МИН_ДНЕЙ = 14;
export const МИН_ДОЛЯ = 70;
/** Шаг сенсора, минут: по нему считается, сколько показаний «должно было быть». */
export const ШАГ_НМГ_МИН = 5;

export interface Полнота {
  дней: number;        // календарных дней, в которых есть хоть одно показание
  доля: number;        // % от ожидаемого числа показаний
  хватает: boolean;    // и дней, и доли — по стандарту
}

export function полнота(entries: Entry[], отМс: number, доМс: number): Полнота {
  const свои = entries.filter((e) => e.t >= отМс && e.t <= доМс);
  const дни = new Set(свои.map((e) => new Date(e.t).toDateString()));
  const ожидалось = Math.max(1, Math.round((доМс - отМс) / (ШАГ_НМГ_МИН * 60_000)));
  const доля = Math.min(100, (свои.length / ожидалось) * 100);
  return {
    дней: дни.size,
    доля,
    хватает: дни.size >= МИН_ДНЕЙ && доля >= МИН_ДОЛЯ,
  };
}

export type Оценка = 'в цели' | 'мимо';

/* Достигнута ли цель. Слово выбрано намеренно нейтральным: «мимо», а не «плохо» и не
   «требует коррекции». Первое — факт про число, второе — оценка человека, третье —
   назначение, которого мы делать не вправе. */
export function оценка(значение: number, цель: number, вид: 'не меньше' | 'не больше'): Оценка {
  return вид === 'не меньше'
    ? (значение >= цель ? 'в цели' : 'мимо')
    : (значение <= цель ? 'в цели' : 'мимо');
}

/* Строки НМГ в том порядке, в каком их читает врач: сначала время в диапазоне, потом
   низкое (оно опаснее), потом высокое, потом вариабельность. Порядок — из той же
   таблицы 6, и менять его «как красивее» нельзя: врач ищет глазами привычное место. */
export function строкиНМГ(s: { target: number; tbr: number; tar: number; cv: number }, цели: Цели) {
  return [
    { что: 'Время в диапазоне 3,9–10,0', значение: s.target, цель: `> ${цели.tir} %`, итог: оценка(s.target, цели.tir, 'не меньше') },
    { что: 'Время ниже 3,9', значение: s.tbr, цель: `< ${цели.tbr} %`, итог: оценка(s.tbr, цели.tbr, 'не больше') },
    { что: 'Время выше 10,0', значение: s.tar, цель: `< ${цели.tar} %`, итог: оценка(s.tar, цели.tar, 'не больше') },
    { что: 'Вариабельность (CV)', значение: s.cv, цель: `≤ ${цели.cv} %`, итог: оценка(s.cv, цели.cv, 'не больше') },
  ];
}

/* Черновик вопросов к врачу — из находок разбора (SugarLife#156).

   Ценность приёма наполовину в вопросах: между визитами копится «спросить про ночные
   гипо», а у двери вылетает из головы. Поводы мы и так видим — значит можем собрать
   список, который человек не сочиняет заново, а правит.

   ДВЕ ГРАНИЦЫ, И ОБЕ ВАЖНЫ.

   Первая: в записку идёт ВОПРОС, а не вывод. «Ночью бывает низко — что с этим делать?»
   — вопрос пациента; «нужно снизить ночной базал» — назначение, и его в записке быть
   не может, даже если оно кажется очевидным.

   Вторая: своё поле у находки (insight.question) сюда не годится, хотя соблазн есть.
   Те вопросы обращены к самому человеку («Записываешь все приёмы пищи?») — они помогают
   ему разобраться с данными, а в кабинете звучали бы странно. Врачу нужен другой
   вопрос про ту же находку, поэтому здесь отдельная таблица.

   Находки про железо и пропуски данных в записку не идут вовсе: замена канюли и
   разряженный телефон — не тема пятнадцати минут с эндокринологом. */
const ВОПРОС_ВРАЧУ: Record<string, string> = {
  'night-hypo': 'Ночью бывают снижения — что с этим делать?',
  'low-window': 'Низкий сахар повторяется в одно и то же время — с чем это может быть связано?',
  'high-window': 'Сахар держится высоким в одни и те же часы — с чем это может быть связано?',
  'long-high': 'Бывают долгие подъёмы, которые не сбиваются, — как правильно действовать?',
  'dawn': 'Утром сахар растёт до завтрака — нужно ли что-то менять?',
  'rebound': 'После гипогликемии сахар улетает вверх — как правильно её купировать?',
  'volatile': 'Сахар сильно скачет в течение дня — на что смотреть в первую очередь?',
  'tbr': 'Времени ниже целевого диапазона больше, чем в рекомендациях, — что с этим делать?',
  'tir-trend': 'Время в диапазоне изменилось по сравнению с прошлым периодом — стоит ли что-то менять?',
  'gmi': 'Расчётный показатель по сенсору расходится с последним HbA1c — как это понимать?',
  'basal': 'Базальная доза выглядит непривычно — стоит ли её пересматривать?',
  'bolus': 'Соотношение базала и болюсов изменилось — это нормально?',
};

export interface ВопросВрачу { id: string; текст: string; повод: string }

/* Только то, что требует разговора: bad и warn. info и good в кабинете — шум, а
   пятнадцать минут стоят дороже полноты списка. */
export function вопросыДляВрача(
  находки: Array<{ id: string; severity: string; title: string }>,
): ВопросВрачу[] {
  const итог: ВопросВрачу[] = [];
  for (const н of находки) {
    if (н.severity !== 'bad' && н.severity !== 'warn') continue;
    const текст = ВОПРОС_ВРАЧУ[н.id];
    if (!текст) continue;
    if (итог.some((в) => в.id === н.id)) continue;
    итог.push({ id: н.id, текст, повод: н.title });
  }
  return итог;
}
