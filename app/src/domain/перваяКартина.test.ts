import { describe, it, expect } from 'vitest';
import { ожидание, ДОЛГО_МС, ОЧЕНЬ_ДОЛГО_МС } from './перваяКартина';

/* Правило простое, но проверяем его отдельно: вечная крутилка врёт не меньше серого
   экрана — и та, и другая утверждают «всё идёт по плану», когда план сломался. Границы
   здесь и есть решение, когда перестать успокаивать и начать объяснять. */

describe('ожидание первого снимка', () => {
  it('первые секунды — просто поднимаем', () => {
    expect(ожидание(0)).toBe('поднимаем');
    expect(ожидание(ДОЛГО_МС - 1)).toBe('поднимаем');
  });

  it('дольше обычного — говорим словами, а не крутим колесо', () => {
    expect(ожидание(ДОЛГО_МС)).toBe('долго');
    expect(ожидание(ОЧЕНЬ_ДОЛГО_МС - 1)).toBe('долго');
  });

  it('совсем долго — пора предлагать действие', () => {
    expect(ожидание(ОЧЕНЬ_ДОЛГО_МС)).toBe('очень долго');
    expect(ожидание(5 * 60_000)).toBe('очень долго');
  });
});
