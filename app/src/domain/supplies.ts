import type { UiSnapshot } from '@/sources/bridge';
import { устройствоРоли } from './deviceState';

/* Расходка помпы: остаток и заряд — из снимка, а не из Nightscout (SugarLife#183).

   Ядро просило уйти от `devicestatus` ещё в своём первом пункте, и до контракта 1.11 нам
   было нечем: у нас была только форматированная плашка `monitor.reservoir` — одна на
   приложение и в виде строки.

   Разница не в источнике, а в трёх вещах, которых у облачного числа нет.

   ВОЗРАСТ. Помпа могла молчать час, и «37 ед» — это остаток часовой давности. Nightscout
   отдаёт последнюю запись без различения «прочитали только что» и «лежит со вчера», и
   человек видит одно и то же число в обоих случаях.

   ПРИНАДЛЕЖНОСТЬ. Плашка одна на приложение. С двумя помпами (а это не выдумка: запасная
   на время замены) она отвечает про какую-то одну, и про какую — неизвестно.

   ЧИСЛО, А НЕ СТРОКА. По строке нельзя посчитать, хватит ли до утра (#280).

   Nightscout остаётся запасным путём и честно помечается: данные оттуда бывают
   единственными — например, когда помпа читается только через облако. */

export type ОткудаРасходка = 'прибор' | 'облако';

export interface Расходка {
  /** Остаток инсулина, единицы. null — не знаем. */
  остаток: number | null;
  /** Заряд помпы, проценты. Вольты не переводим: шкала у каждой помпы своя. */
  заряд: number | null;
  /** Когда прочитано с прибора; null — источник времени не сообщил. */
  прочитаноМс: number | null;
  откуда: ОткудаРасходка | null;
}

/** Сведения из Nightscout — ровно те, что у нас были до контракта 1.11. */
export interface ИзОблака {
  reservoir?: number | null;
  pumpBattery?: number | null;
  at?: number | null;
}

export function расходка(
  snap: UiSnapshot | null | undefined, облако: ИзОблака | null | undefined,
): Расходка {
  const помпа = устройствоРоли(snap, 'pump');
  /* Из снимка берём, только если там есть ЧИСЛО. Устройство в снимке может быть, а
     расходку драйвер ещё не прочитал — тогда пустое поле означает «не знаю», и молчать
     вместо облачного ответа было бы хуже: у человека есть цифра, просто из другого
     места. */
  if (помпа?.reservoirU != null) {
    return {
      остаток: помпа.reservoirU,
      заряд: помпа.batteryPct ?? облако?.pumpBattery ?? null,
      прочитаноМс: помпа.reservoirAtMs ?? null,
      откуда: 'прибор',
    };
  }
  if (облако?.reservoir != null || облако?.pumpBattery != null) {
    return {
      остаток: облако?.reservoir ?? null,
      заряд: облако?.pumpBattery ?? null,
      прочитаноМс: облако?.at ?? null,
      откуда: 'облако',
    };
  }
  return { остаток: null, заряд: null, прочитаноМс: null, откуда: null };
}

/* Насколько число устарело, чтобы об этом стоило сказать.

   Полчаса выбраны не на глаз: помпа отдаёт состояние при каждом обмене, и при живой
   связи оно свежее нескольких минут. Полчаса молчания — это уже не «чуть отстало», а
   «связь потеряна, а число осталось на экране». Именно так остаток и врёт: не
   неправильным значением, а правильным, но вчерашним. */
export const УСТАРЕЛО_МС = 30 * 60_000;

export function устарелаЛи(р: Расходка, сейчасМс: number): boolean {
  if (р.прочитаноМс == null) return false;
  return сейчасМс - р.прочитаноМс > УСТАРЕЛО_МС;
}

/** Подпись под числом: откуда и насколько давно. Пусто — говорить нечего. */
export function подписьРасходки(
  р: Расходка, сейчасМс: number, возраст: (мс: number) => string,
): string | null {
  if (р.остаток == null && р.заряд == null) return null;
  const части: string[] = [];
  if (р.откуда === 'облако') части.push('через облако');
  if (р.прочитаноМс != null && устарелаЛи(р, сейчасМс)) части.push(возраст(р.прочитаноМс));
  return части.length ? части.join(' · ') : null;
}
