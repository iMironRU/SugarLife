/* СЛОВА ТРЕВОГИ (SugarLife#482).

   У события тревоги в контракте формулировок нет: движок отдаёт `id`, уровень и число, а как это
   назвать человеку — дело оболочки. Пока `words` от движка не приехали, называем сами.

   ТРЕТЬЯ КОПИЯ ЭТИХ ПРАВИЛ. Первые две — в оболочках: `ПравилаПоказа.kt` и `Тревоги.swift`, они
   озаглавливают системные уведомления, когда приложение закрыто. Общего кода у нативных оболочек и
   веба нет, поэтому копии осознанные — но менять их надо разом, все три. Тест ниже сторожит нашу.

   Незнакомый id обязан получить общее слово и всё равно показаться: список тревог у движка открытый,
   и новая тревога — повод назвать её скучно, а не повод потерять. */

/** Заголовок: о чём тревога. */
export function заголовокТревоги(id: string, уровень: string): string {
  const основа = id.split(':')[0] ?? id;
  if (id.includes('не-разбудит') || уровень === 'ОбещаниеНарушено') return 'Тревога может не разбудить';
  if (основа.startsWith('гипо')) return 'Низкий сахар';
  if (основа.startsWith('высок')) return 'Высокий сахар';
  if (основа.startsWith('прогноз') || основа.includes('падени')) return 'Сахар падает';
  if (основа.startsWith('молчание')) return 'Данных нет';
  if (основа.startsWith('залип')) return 'Линия не меняется';
  if (основа.startsWith('подача')) return 'Подача инсулина стоит';
  if (основа.startsWith('резервуар')) return 'Резервуар заканчивается';
  if (основа.startsWith('батаре')) return 'Батарея помпы';
  return 'Тревога';
}

/** Строка под заголовком: число, если тревога про число, иначе — что происходит. */
export function текстТревоги(id: string, уровень: string, mmol: number | null | undefined): string {
  const заголовок = заголовокТревоги(id, уровень);
  /* «Тревога может не разбудить» с сахаром в тексте читается как тревога ПРО САХАР, и человек
     закрывает её, решив, что 10,2 не повод. Беда здесь другая — в самой доставке. */
  if (заголовок === 'Тревога может не разбудить') return 'Проверьте «Охрану»: сейчас разбудить не сможем';
  if (mmol != null) return `${mmol.toFixed(1).replace('.', ',')} ммоль`;
  if (заголовок === 'Тревога') return `Приложение сообщает: ${id}`;
  return 'Приложение сообщает о состоянии';
}
