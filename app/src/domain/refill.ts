import type { Plateau } from './plateau';

/* Заправка картриджа — распознаём, но никогда не отмечаем молча.

   Раньше мы вообще отказались смотреть на скачки остатка: у Medtronic через AAPS
   значение резервуара скачет вверх само по себе. Отказ был правильным, а вывод —
   слишком широким. Разбор тринадцати дней живых данных, девять скачков вверх:

     настоящие заправки:  9 → 303,  3 → 286,  0 → 302
     глюки чтения:       50 → 101, 50 → 75, 75 → 134, 75 → 175, 75 → 169, 56 → 75

   Разделение идеальное и держится на одном признаке: заправка — это переход С ПОЧТИ
   НУЛЯ В ПОЧТИ ПОЛНЫЙ. Ни один глюк близко к полному не подошёл — все кучкуются в
   середине шкалы и стартуют не со дна.

   Ёмкость не зашиваем числом: у 722-й картридж 300 единиц, у 522-й 176. Берём максимум
   из собственной истории — он и есть «полный» для этой помпы.

   Почему всё равно только вопрос, а не отметка. Признак чистый на тринадцати днях, но
   молчаливая отметка по эвристике — это то же самое, что ноль вместо «неизвестно»:
   если она ошибётся, человек не узнает. Вопрос ошибается дёшево, его просто закрывают.

   И отдельно: скачок остатка говорит про КАРТРИДЖ, а не про инфузионный набор. Их
   часто меняют вместе, но набор можно переставить без заправки, а картридж долить без
   смены набора. Признака смены набора в данных нет вовсе (событий Prime/Fill Cannula
   у нас не пишется), поэтому про набор мы только спрашиваем отдельно. */

const ДНО = 0.15;   // «почти пусто» — доля ёмкости
const ПОЛНЫЙ = 0.85; // «почти полный» — доля ёмкости
/* Дальше этого срока спрашивать бессмысленно: за неделю картридж заправляли ещё
   не раз, и ответ «да, заправил» уже ничего не уточнит. Молча тоже не отмечаем —
   просто молчим. */
export const АКТУАЛЬНО_МС = 7 * 86400e3;

export interface Refill {
  at: number;      // когда заметили заправку
  from: number;    // сколько было
  to: number;      // сколько стало
  capacity: number; // ёмкость картриджа по собственной истории
}

/** Последняя заправка в ряду остатка. null — не нашли (и это норма). */
export function detectRefill(points: Plateau[], now = Date.now()): Refill | null {
  const s = points.filter((p) => Number.isFinite(p.v)).sort((a, b) => a.t - b.t);
  if (s.length < 2) return null;

  const capacity = Math.max(...s.map((p) => p.v));
  if (capacity <= 0) return null;

  for (let i = s.length - 1; i > 0; i--) {
    const было = s[i - 1].v, стало = s[i].v;
    if (было <= capacity * ДНО && стало >= capacity * ПОЛНЫЙ) {
      if (now - s[i].t > АКТУАЛЬНО_МС) return null; // нашли, но спрашивать поздно
      return { at: s[i].t, from: было, to: стало, capacity };
    }
  }
  return null;
}
