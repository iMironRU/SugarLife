import { describe, it, expect } from 'vitest';
import { detectRefill, АКТУАЛЬНО_МС } from './refill';

/* Данные ниже — не выдуманные: это девять реальных скачков остатка вверх за тринадцать
   дней из Nightscout пользователя. Три из них заправки, шесть — глюки чтения AAPS.
   Именно на этом наборе правило и проверяется. */

const ЧАС = 3600e3;
const БАЗА = Date.UTC(2026, 7, 1);
const t = (ч: number) => БАЗА + ч * ЧАС;
const СЕЙЧАС = БАЗА + 100 * ЧАС; // все проверки идут «изнутри» актуального окна

describe('распознавание заправки картриджа', () => {
  it('заправка — переход с почти нуля в почти полный', () => {
    const r = detectRefill([{ t: t(0), v: 9 }, { t: t(1), v: 303 }], СЕЙЧАС);
    expect(r).not.toBeNull();
    expect(r!.from).toBe(9);
    expect(r!.to).toBe(303);
    expect(r!.capacity).toBe(303);
  });

  it('шесть настоящих глюков не считаются заправкой', () => {
    const глюки = [[50, 101], [50, 75], [75, 134], [75, 175], [75, 169], [56, 75]];
    for (const [было, стало] of глюки) {
      // ёмкость известна из истории — в ряду есть полный картридж
      const ряд = [{ t: t(0), v: 300 }, { t: t(10), v: было }, { t: t(11), v: стало }];
      expect(detectRefill(ряд, СЕЙЧАС), `${было} → ${стало}`).toBeNull();
    }
  });

  it('три настоящие заправки распознаются все', () => {
    for (const [было, стало] of [[9, 303], [3, 286], [0, 302]]) {
      const ряд = [{ t: t(0), v: было }, { t: t(1), v: стало }];
      expect(detectRefill(ряд, СЕЙЧАС), `${было} → ${стало}`).not.toBeNull();
    }
  });

  it('ёмкость берётся из истории, а не зашита: у 522-й картридж 176', () => {
    const r = detectRefill([{ t: t(0), v: 176 }, { t: t(20), v: 8 }, { t: t(21), v: 170 }], СЕЙЧАС);
    expect(r!.capacity).toBe(176);
    expect(r!.to).toBe(170);
  });

  it('находит ПОСЛЕДНЮЮ заправку, а не первую', () => {
    const r = detectRefill([
      { t: t(0), v: 5 }, { t: t(1), v: 300 },
      { t: t(50), v: 4 }, { t: t(51), v: 295 },
    ], СЕЙЧАС);
    expect(r!.at).toBe(t(51));
  });

  it('плавный расход заправкой не считается', () => {
    const r = detectRefill([{ t: t(0), v: 300 }, { t: t(10), v: 200 }, { t: t(20), v: 100 }, { t: t(30), v: 10 }], СЕЙЧАС);
    expect(r).toBeNull();
  });

  it('про старую заправку не спрашиваем: за неделю заправляли ещё не раз', () => {
    const ряд = [{ t: t(0), v: 5 }, { t: t(1), v: 300 }];
    expect(detectRefill(ряд, t(1) + АКТУАЛЬНО_МС - ЧАС)).not.toBeNull();
    expect(detectRefill(ряд, t(1) + АКТУАЛЬНО_МС + ЧАС)).toBeNull();
  });

  it('пусто и мусор не ломают', () => {
    expect(detectRefill([])).toBeNull();
    expect(detectRefill([{ t: t(0), v: 100 }])).toBeNull();
    expect(detectRefill([{ t: t(0), v: 0 }, { t: t(1), v: 0 }])).toBeNull();
  });
});
