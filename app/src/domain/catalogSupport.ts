import type { DriverDescriptor } from '@/sources/bridge';

/* Что мы умеем с этой моделью (SugarLife#190, канон SugarLifeCore#37).

   Каталог помп — шестьдесят девять позиций, и до сих пор они лежали одним списком, где
   Disetronic из девяностых стоял рядом с Omnipod 5. Главного человек из такого списка
   не узнавал: заработает ли ЭТА помпа с приложением. Он выбирает модель, чтобы понять,
   что ему будет доступно, а список отвечал ему годом выпуска.

   Ответ знает ядро: драйверы его, и список моделей меняется вместе с ними. Поэтому
   поддержка считается по снимку — `availableDrivers[].supports[].key`, — а в справочнике
   у модели лежит только ключ. Своей копии таблицы у нас нет намеренно: она устарела бы
   в первый же релиз движка, причём молча.

   ТРИ ГРУППЫ, А НЕ ДВЕ. «Только через облако» — не отказ: данные придут через
   Nightscout, и для многих это рабочий вариант на годы. А «старое и снятое» отделено от
   него потому, что отвечает на другой вопрос: не «как читать», а «стоит ли вообще
   выбирать эту модель сегодня». */

export type Поддержка = 'напрямую' | 'облако' | 'снято';

export const ПОДДЕРЖКА_ПОДПИСЬ: Record<Поддержка, string> = {
  напрямую: 'Читаем напрямую',
  облако: 'Только через облако',
  снято: 'Старое и снятое',
};

/** Ключи моделей, которые движок читает прямо сейчас. */
export function ключиДрайверов(drivers: DriverDescriptor[] | undefined | null): Set<string> {
  const итог = new Set<string>();
  for (const d of drivers ?? []) for (const m of d.supports ?? []) итог.add(m.key);
  return итог;
}

/* Умеет ли движок читать эту модель напрямую.

   Ключ в справочнике — необходимое, но не достаточное: сборка движка может быть старее
   нашей таблицы. Поэтому спрашиваем снимок. Нет ключа в снимке — честно «через облако»,
   а не «поддерживается»: обещание прямой связи, которой нет, человек проверит покупкой
   моста.

   Снятая с производства модель остаётся снятой, даже если драйвер её читает: это про
   выбор, а не про чтение. Старый Paradigm читается напрямую — и именно поэтому он
   попадает в «читаем напрямую», если человек его уже носит; но в списке «что купить»
   ему не место. Порядок проверки поэтому такой: сначала умеем ли, потом снято ли. */
export function поддержка(
  driverKey: string | null | undefined,
  актуальная: boolean,
  ключи: Set<string>,
): Поддержка {
  if (driverKey && ключи.has(driverKey)) return 'напрямую';
  return актуальная ? 'облако' : 'снято';
}

/* Порядок групп — от того, что даёт больше, к тому, что даёт меньше. Внутри групп
   порядок задаёт вызывающий: у него есть популярность и алфавит. */
export const ПОРЯДОК_ГРУПП: Поддержка[] = ['напрямую', 'облако', 'снято'];

/* Делить ли список вообще. Старая сборка движка не отдаёт supports, и тогда групп нет:
   показать «читаем напрямую» там, где движок этого не подтверждал, хуже, чем не делить
   вовсе (об этом же мы договорились с ядром). */
export function делимЛи(drivers: DriverDescriptor[] | undefined | null): boolean {
  return (drivers ?? []).some((d) => d.supports != null);
}
