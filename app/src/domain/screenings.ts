export type СостояниеПроверки = 'нет данных' | 'в сроке' | 'скоро' | 'просрочено' | 'ещё рано';

/** За сколько до срока говорим «скоро»: чтобы успеть записаться, а не узнать постфактум. */
export const ЗАРАНЕЕ_ДНЕЙ = 30;

const МЕС = 30 * 24 * 3_600_000;

/* Состояние одной проверки.

   «Нет данных» — отдельное состояние, а не «просрочено». Человек, который только начал
   вести записи, не должен получить восемь красных строк за то, что не помнит дату
   прошлогодней ЭКГ: это не его долг, это наша пустая база. Красным пугают тогда, когда
   срок действительно вышел.

   «Ещё рано» — для проверок, которые по документу начинаются через пять лет от дебюта:
   требовать анализ мочи у человека с годом стажа значит спорить с рекомендацией. */
export function состояние(
  последняя: number | null | undefined,
  проверка: Проверка,
  сейчас: number,
  дебютСД?: number | null,
): СостояниеПроверки {
  if (проверка.спустяЛет && дебютСД && сейчас < дебютСД + проверка.спустяЛет * 12 * МЕС && !последняя) {
    return 'ещё рано';
  }
  if (!последняя) return 'нет данных';
  const срок = последняя + проверка.каждыеМес * МЕС;
  if (сейчас > срок) return 'просрочено';
  if (сейчас > срок - ЗАРАНЕЕ_ДНЕЙ * 24 * 3_600_000) return 'скоро';
  return 'в сроке';
}

/** Сколько месяцев прошло — для строки «был 14 месяцев назад». */
export function месяцевНазад(когда: number, сейчас: number): number {
  return Math.max(0, Math.floor((сейчас - когда) / МЕС));
}

/* Что показать в записке к приёму: сначала то, что просрочено, потом «скоро», потом
   неизвестное. «В сроке» в списке первым не нужно — оно не требует действия, и место
   на странице стоит дороже полноты. */
export const ПОРЯДОК: Record<СостояниеПроверки, number> = {
  'просрочено': 0, 'скоро': 1, 'нет данных': 2, 'в сроке': 3, 'ещё рано': 4,
};

export function поВажности(
  записи: Record<string, number | undefined>, сейчас: number, дебютСД?: number | null,
): Array<{ проверка: Проверка; когда: number | null; состояние: СостояниеПроверки }> {
  return ПРОВЕРКИ
    .map((проверка) => {
      const когда = записи[проверка.id] ?? null;
      return { проверка, когда, состояние: состояние(когда, проверка, сейчас, дебютСД) };
    })
    .sort((a, b) => ПОРЯДОК[a.состояние] - ПОРЯДОК[b.состояние]
      || a.проверка.каждыеМес - b.проверка.каждыеМес);
}
