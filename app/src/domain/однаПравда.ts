import type { UiSnapshot, HardwareView, DeviceView } from '@/sources/bridge';
import type { ChannelView } from '@/sources/bridge';
import { связь, каналРоли, устройствоРоли, активныйКанал } from './deviceState';
import { железоДиспетчера, имяЖелезки, заМостомЛи } from './nearby';
import { чтоСПрибором, type Занятие } from './freshness';

/* Одна правда о приборе — на первом экране (SugarLifeCore#39).

   С живого теста на обоих телефонах: на «Сегодня» баннер «Связь с устройством потеряна»,
   а строкой ниже «Sibionics GS1 на связи · 1 мин» и «Medtronic 722 на связи · 1 мин».
   Формально каждая строка права — роль жива через облако, локальное радио нет, — а
   ВМЕСТЕ они нечитаемы.

   Три вопроса, на которые обязана отвечать строка прибора, и ни одного больше:

     1. подключено ли ЭТО устройство — про локальную связь, одним словом;
     2. откуда идут данные — «по радио» / «через мост» / «через Nightscout»;
     3. когда последние — «1 мин назад».

   ГЛАВНОЕ ПРАВИЛО: «на связи» без «через что» не существует. Голое «на связи» и есть
   та половина ответа, из-за которой человек идёт чинить исправное: помпа «на связи»,
   потому что её видно через Nightscout, а мост при этом молчит.

   Мы это правило уже применяли в крыльях главного экрана, но с оговоркой — писали канал,
   только когда путей несколько (иначе казалось шумом). Оговорка не выдержала живого
   теста: человек не знает, сколько у прибора путей, и «на связи» читает как «по радио». */

export interface СтрокаПравды {
  id: string;
  имя: string;
  /* Состояние ЛОКАЛЬНОЙ связи с этим прибором. СОСТОЯНИЕ, а не слово (#324): как это
     назвать человеку — «подключено» или «на связи», — решает слой слов, и менять
     формулировку он должен, не трогая правило. */
  состояние: 'подключено' | 'подключаюсь' | 'нет связи';
  /** Каким путём идут данные. null — данных нет вовсе, и врать про путь нечем. */
  откуда: ChannelView['kind'] | null;
  /** Когда последние данные, в миллисекундах эпохи. null — не приходили. */
  когдаМс: number | null;
  /* Занятие или «не настроен» — перебивают всё: см. domain/freshness. Тоже состояние,
     а не строка (#324): называет его слой слов. */
  вместоСостояния: Занятие;
  /** Мост — дорога, а не источник: данных он не даёт и в тревогу о данных не входит. */
  дорога: boolean;
}

const СЛОВО: Record<string, СтрокаПравды['состояние']> = {
  live: 'подключено', wait: 'подключаюсь', off: 'нет связи', unknown: 'нет связи',
};

export function однаПравда(snap: UiSnapshot | null | undefined, сейчас: number): СтрокаПравды[] {
  void сейчас;
  return железоДиспетчера(snap).map((h) => {
    const свой = (snap?.devices ?? []).find((d) => d.id === h.id) ?? null;
    return {
      id: h.id,
      имя: имяЖелезки(h),
      состояние: СЛОВО[связь(h)] ?? 'нет связи',
      откуда: откудаДанные(h, свой, snap),
      когдаМс: последнееВремя(h, свой ? активныйКанал(свой)?.latestAtMs ?? null : null),
      вместоСостояния: чтоСПрибором(h),
      дорога: h.kind === 'bridge',
    };
  });
}

/* ОТКУДА ИДУТ ЦИФРЫ — вопрос про РОЛЬ, а не про железку.

   Первая попытка отвечала по каналам самой железки, и оба ответа вышли враньём:
   у помпы, которая читается из Nightscout, писали «через мост» — то есть называли путь,
   который как раз не работает; у молчащего моста — «по радио», хотя по нему не идёт
   ничего и идти не может.

   Правильно так: путь есть, только если РОЛЬ этого прибора кем-то обслуживается прямо
   сейчас. Не обслуживается — пути нет, и молчание тут честнее любого слова.

   У моста роли нет вовсе: он не источник данных, он дорога. Поэтому у него «откуда»
   пустое всегда — его собственное состояние уже сказано словом «подключено/нет связи». */
function откудаДанные(
  h: HardwareView, свой: DeviceView | null, snap: UiSnapshot | null | undefined,
): ChannelView['kind'] | null {
  if (h.kind === 'bridge') return null;
  const роль = устройствоРоли(snap, h.kind === 'pump' ? 'pump' : 'sensor');
  /* Роль обслуживает КОНКРЕТНЫЙ источник — он и отвечает на вопрос. Если это сам наш
     прибор, спрашиваем его; если другой (облачная запись той же помпы) — его. */
  const источник = роль ?? свой;
  if (!источник || связь(источник) === 'off') return null;
  return каналРоли(источник) ?? (заМостомЛи(h, snap) ? 'bridged' : null);
}

function последнееВремя(h: HardwareView, изКанала: number | null): number | null {
  return h.latestAtMs ?? изКанала ?? null;
}

/* Тревога называет КАНАЛ, а не факт обрыва — формулировка живёт в слова/приборы.ts
   (#324). Здесь остаётся только разбор: кто молчит и есть ли у него обходной путь. */
export interface Обрыв {
  /** Молчат по радио, но цифры идут другим путём — это состояние, а не тревога. */
  сОбходом: СтрокаПравды[];
  /** Молчат и данных не дают ниоткуда — вот это тревога. */
  совсем: СтрокаПравды[];
}

export function разборОбрыва(строки: СтрокаПравды[]): Обрыв | null {
  /* Мосты в тревогу о ДАННЫХ не входят: мост ничего не отдаёт, он несёт. Оборванный мост
     виден по прибору за ним — тот скажет, что цифры теперь идут облаком или не идут вовсе.
     Отдельная строка «нет данных от моста» добавляла бы к беде вторую, выдуманную. */
  const молчащие = строки.filter((с) => с.состояние === 'нет связи' && !с.дорога);
  if (!молчащие.length) return null;
  return {
    сОбходом: молчащие.filter((с) => с.откуда),
    совсем: молчащие.filter((с) => !с.откуда),
  };
}
