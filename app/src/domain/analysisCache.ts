import { analyze, type Analysis, type AnalyzeCtx } from './analysis';
import type { Entry, Treatment } from './types';

/* Память разбора между открытиями экрана.

   useMemo внутри компонента живёт ровно столько, сколько открыт экран: вышел и
   вернулся — те же сто миллисекунд счёта заново. То же с периодом: переключил
   14 → 30 → 14, и «14» посчитано дважды. На живых данных один проход стоит около
   104 мс — это шесть пропущенных кадров, и человек их чувствует.

   Ключ — не сами данные, а момент последнего измерения, огрублённый до минуты.
   Выводы за две недели от одной свежей точки не меняются, а сравнивать массивы
   на 4000 элементов дороже, чем считать заново.

   Кэш маленький намеренно: держим последние несколько сочетаний (период × минута),
   остальное вытесняем. Разбор — это выводы о человеке, и хранить их дольше нужного
   незачем; в localStorage не кладём вовсе, чтобы завтрашний экран не показал
   позавчерашние выводы как свежие. */

const РАЗМЕР = 6;
const кэш = new Map<string, Analysis>();

export function analyzeCached(
  entries: Entry[],
  events: Treatment[],
  days: number,
  ctx: AnalyzeCtx = {},
): Analysis {
  const минута = Math.floor((entries[entries.length - 1]?.t ?? 0) / 60000);
  const ключ = `${days}|${минута}|${entries.length}|${ctx.uploaderBattery ?? ''}`;

  const готовое = кэш.get(ключ);
  if (готовое) {
    // освежаем позицию: Map хранит порядок вставки, и повторное обращение
    // не должно приближать запись к вытеснению
    кэш.delete(ключ);
    кэш.set(ключ, готовое);
    return готовое;
  }

  const результат = analyze(entries, events, days, ctx);
  кэш.set(ключ, результат);
  if (кэш.size > РАЗМЕР) кэш.delete(кэш.keys().next().value as string);
  return результат;
}

/** Сброс — при смене источника данных: старые выводы к новым данным не относятся. */
export function clearAnalysisCache(): void { кэш.clear(); }
