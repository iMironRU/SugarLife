import { describe, it, expect } from 'vitest';
import { отметкаДля, поПричинам, ДОПУСК_МС, type ОтметкаПодъёма } from './причиныПодъёма';

const о = (at: number, причина: ОтметкаПодъёма['причина']): ОтметкаПодъёма =>
  ({ at, причина, когдаМс: at });

/* Слова причин и правила о них («не знаю» в списке, ни одна формулировка не обвиняет) уехали в
   `слова/подъёмы.test.ts` вместе со словарём (#324). Здесь остался расчёт. */

describe('поиск отметки по времени', () => {
  const т = new Date(2026, 7, 20, 3, 0, 0).getTime();

  /* Время подъёма уточняется добором истории — отметка, привязанная к точной метке,
     потерялась бы, и человек увидел бы уже отмеченный подъём снова. */
  it('находит отметку, сдвинутую на несколько минут', () => {
    expect(отметкаДля([о(т, 'канюля')], т + 5 * 60_000)?.причина).toBe('канюля');
  });

  it('за пределами допуска — это другой подъём', () => {
    expect(отметкаДля([о(т, 'канюля')], т + ДОПУСК_МС + 60_000)).toBe(null);
  });

  it('из двух близких берёт ближайшую', () => {
    const о1 = о(т, 'еда'); const о2 = о(т + 10 * 60_000, 'болезнь');
    expect(отметкаДля([о1, о2], т + 9 * 60_000)?.причина).toBe('болезнь');
  });
});

describe('сводка по причинам', () => {
  it('считает и сортирует по убыванию', () => {
    const с = поПричинам([о(1, 'канюля'), о(2, 'еда'), о(3, 'канюля'), о(4, 'болезнь')]);
    expect(с[0]).toEqual({ причина: 'канюля', сколько: 2 });
    expect(с).toHaveLength(3);
  });
});
