import type { UiSnapshot, HardwareView, Discovered } from '@/sources/bridge';
import { железоДиспетчера, рядомЖелезо } from './nearby';
import { связь } from './deviceState';

/* Одна лента вместо двух списков (SugarLife#337, п. 3).

   «Что у меня есть и работает ли оно» — для человека ОДИН вопрос. У нас на него
   отвечали три места: эфир показывал только незнакомых, «мои устройства» — только
   заведённых, роли — только назначенных. Разделение было не капризом: заведённый
   OrangeLink в списке кандидатов выглядел как предложение завести второй (SugarLifeCore#34).

   Но цена оказалась выше выгоды. ЗАВЕДЁННЫЙ ПРИБОР ПРОПАДАЛ ИЗ ПОИСКА РОВНО ТОГДА,
   КОГДА ЕГО ИСКАЛИ: человек, у которого сенсор отвалился, шёл в поиск — и не находил
   там ни своего сенсора, ни объяснения. Отличить «прибор сломан» от «приложение его
   забыло» было нечем.

   Правило теперь одно: показываем ВСЁ, а вид строки отвечает, что с этим делать.

   ДВА СЛЕДСТВИЯ, которые важнее самой ленты.

   У работающего прибора нет кнопки «Подключить». Она читается как приглашение
   починить — то есть сломать то, что работает. Молчащий, но живой прибор чинят не
   переподключением, а разбором, и ведёт туда карточка.

   Неслышный прибор ОСТАЁТСЯ в списке приглушённым, а не исчезает. Исчезновение — это
   утверждение «его нет», которого мы не делали: он может быть занят другим телефоном,
   лежать в другой комнате или спать между обменами. */

export type ВидСтроки =
  | 'работает'   // на связи, данные идут
  | 'молчит'     // на связи, данных нет дольше нормы
  | 'рядом'      // свой, не подключён, но слышен в эфире
  | 'неслышно'   // свой, не подключён и в эфире не слышен
  | 'новый';     // не заведён, слышен в эфире

export type Действие = 'подключить' | 'добавить' | null;

export interface Строка {
  id: string;
  вид: ВидСтроки;
  действие: Действие;
  /** Заведённый прибор — со всеми полями снимка; для нового их ещё нет. */
  железо: HardwareView | null;
  /** Объявление из эфира: у нового оно единственный источник сведений. */
  вЭфире: Discovered | null;
}

/* Порядок групп и внутри групп.

   Свои выше новых: человек приходит сюда чаще проверять своё, чем заводить чужое. А
   внутри своих первыми те, с кем что-то не так, — иначе, чтобы найти отвалившийся
   сенсор, придётся прокручивать мимо работающих. */
const ВЕС: Record<ВидСтроки, number> = {
  молчит: 0, неслышно: 1, рядом: 2, работает: 3, новый: 4,
};

export function лента(snap: UiSnapshot | null | undefined, сейчасМс: number): Строка[] {
  const железо = железоДиспетчера(snap);
  const рядом = рядомЖелезо(snap, сейчасМс);
  const эфир = snap?.discovered ?? [];

  const свои: Строка[] = железо.map((h) => {
    /* «Молчит» проверяем ПЕРВЫМ и по статусу движка, а не по нашей связи.

       Порог, с которого молчание перестаёт быть нормой, зависит от типа прибора и
       считается у ядра; второе мнение о нём разошлось бы с первым (#305).

       Первым — потому что наша `связь()` относит Delayed к «ждём», а не к «живой»: для
       точки это правильно (зелёный на отставшем читается как «данные идут прямо
       сейчас»), но здесь дало бы «неслышно» у прибора, который на связи. */
    const вид: ВидСтроки = h.status === 'Delayed' ? 'молчит'
      : связь(h) === 'live' ? 'работает'
      : рядом.has(h.id) ? 'рядом'
      : 'неслышно';
    return {
      id: h.id,
      вид,
      /* Кнопка только у того, кого можно подключить прямо сейчас. У живого её нет по
         правилу выше; у неслышного — потому что нажимать бессмысленно, и кнопка,
         которая заведомо ничего не даст, читается как поломка приложения. */
      действие: вид === 'рядом' ? 'подключить' : null,
      железо: h,
      вЭфире: эфир.find((d) => d.knownDeviceId === h.id) ?? null,
    };
  });

  /* Новое — только по-настоящему незнакомое. Сопоставляет движок через knownDeviceId, а
     не мы по имени: имена железок повторяются, и перепутать чужой сенсор со своим —
     худший исход из возможных. */
  const новые: Строка[] = эфир
    .filter((d) => !d.knownDeviceId)
    .map((d) => ({ id: d.bleId, вид: 'новый' as const, действие: 'добавить' as const, железо: null, вЭфире: d }));

  return [...свои, ...новые].sort((a, b) => ВЕС[a.вид] - ВЕС[b.вид]);
}

/** Есть ли в ленте хоть одна своя строка — по этому решается, звать ли группу «Мои». */
export function естьСвои(строки: Строка[]): boolean {
  return строки.some((с) => с.вид !== 'новый');
}
