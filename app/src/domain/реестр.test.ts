import { describe, it, expect } from 'vitest';
import { движокХозяин, писатьЛокально, ПЕРЕЕХАЛО } from './реестр';
import type { UiSnapshot } from '@/sources/bridge';

/* Кто хозяин записи об устройстве (SugarLife#224).

   Два источника про одно расходятся всегда. Читать из снимка мы научились раньше;
   проверяем то, что осталось, — что рядом мы больше не пишем. */

const сЖивым = { availableDrivers: [{ id: 'sibionics', kind: 'sensor' }] } as unknown as UiSnapshot;
const пустой = {} as UiSnapshot;

describe('хозяин записи', () => {
  it('движок живой — хозяин он', () => {
    expect(движокХозяин(сЖивым)).toBe(true);
  });

  /* В браузере движка нет вовсе, и писать к себе — единственный способ вообще что-то
     запомнить. Запрет там означал бы «выбирайте, но мы забудем». */
  it('движка нет — пишем к себе', () => {
    expect(движокХозяин(пустой)).toBe(false);
    expect(движокХозяин(null)).toBe(false);
  });
});

describe('переехавшие поля', () => {
  it('при живом движке локально не пишем ни одно', () => {
    ПЕРЕЕХАЛО.forEach((п) => expect(писатьЛокально(п, сЖивым)).toBe(false));
  });

  it('без движка пишем все', () => {
    ПЕРЕЕХАЛО.forEach((п) => expect(писатьЛокально(п, пустой)).toBe(true));
  });

  /* Список фиксируем: если кто-то добавит в конфиг новое поле, которое движок уже знает,
     тест не поймает — но этот список подскажет, где смотреть. */
  it('список того, что переехало, — ровно три поля', () => {
    expect([...ПЕРЕЕХАЛО]).toEqual(['bridgePumpId', 'bridgeSensorId', 'deviceParams']);
  });
});
