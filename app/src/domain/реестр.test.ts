import { describe, it, expect } from 'vitest';
import { движокХозяин, писатьЛокально, ПЕРЕЕХАЛО, выбраннаяМодель } from './реестр';
import type { UiSnapshot } from '@/sources/bridge';
import type { DeviceConfig } from '@/settings/deviceConfig';

/* Кто хозяин записи об устройстве (SugarLife#224).

   Два источника про одно расходятся всегда. Читать из снимка мы научились раньше;
   проверяем то, что осталось, — что рядом мы больше не пишем. */

const сЖивым = { availableDrivers: [{ id: 'sibionics', kind: 'sensor' }] } as unknown as UiSnapshot;
const пустой = {} as UiSnapshot;

describe('хозяин записи', () => {
  it('движок живой — хозяин он', () => {
    expect(движокХозяин(сЖивым)).toBe(true);
  });

  /* В браузере движка нет вовсе, и писать к себе — единственный способ вообще что-то
     запомнить. Запрет там означал бы «выбирайте, но мы забудем». */
  it('движка нет — пишем к себе', () => {
    expect(движокХозяин(пустой)).toBe(false);
    expect(движокХозяин(null)).toBe(false);
  });
});

describe('переехавшие поля', () => {
  it('при живом движке локально не пишем ни одно', () => {
    ПЕРЕЕХАЛО.forEach((п) => expect(писатьЛокально(п, сЖивым)).toBe(false));
  });

  it('без движка пишем все', () => {
    ПЕРЕЕХАЛО.forEach((п) => expect(писатьЛокально(п, пустой)).toBe(true));
  });

  /* Список фиксируем: если кто-то добавит в конфиг новое поле, которое движок уже знает,
     тест не поймает — но этот список подскажет, где смотреть. */
  it('список того, что переехало, — ровно три поля', () => {
    expect([...ПЕРЕЕХАЛО]).toEqual(['bridgePumpId', 'bridgeSensorId', 'deviceParams']);
  });
});

/* Какая модель выбрана (#224, шаг 4).

   Локальный конфиг живёт в localStorage: перезапуск он переживает, переустановку — нет.
   Движок помнит запись прибора вместе с нашей моделью (`deviceModel`, rev ≥ 1.14) и
   поднимает её из своей базы. Значит спрашивать надо сначала его — иначе после
   переустановки шесть экранов дружно скажут «модель не указана» при работающей помпе. */

const ПОМПА = 'minimed-group-бывшая-medtronic-diabetes-paradigm-522-722';
const СЕНСОР = 'sibionics-gs1';

const конфиг = (p: Partial<DeviceConfig>): DeviceConfig => ({
  pumpId: null, fastInsulinId: null, sensorId: null, meterModel: null,
  bridgeSensorId: null, bridgePumpId: null, deviceParams: {}, pumpBatteryKind: null, ...p,
});

/* Снимок с ролью: движок сам говорит, какой прибор наполняет слот, — и модель берём у
   него, а не у первого прибора подходящего вида. */
const сМоделью = (kind: 'pump' | 'sensor', модель: string | null): UiSnapshot => ({
  bridgeRevision: '1.14',
  devices: [{ id: 'd1', kind, deviceModel: модель } as unknown as UiSnapshot['devices'][number]],
  roles: [{ role: kind === 'pump' ? 'insulin' : 'cgm', activeSourceId: 'd1' }],
} as unknown as UiSnapshot);

describe('какая модель выбрана', () => {
  it('движок помнит модель — отвечает он', () => {
    expect(выбраннаяМодель('pump', конфиг({ pumpId: null }), сМоделью('pump', ПОМПА))).toBe(ПОМПА);
    expect(выбраннаяМодель('sensor', конфиг({}), сМоделью('sensor', СЕНСОР))).toBe(СЕНСОР);
  });

  /* Прибор записан, модель не названа — это ОТВЕТ движка, а не пробел. Подставить сюда
     старый локальный выбор значило бы показать модель, которую человек только что снял. */
  it('записан без модели — так и говорим', () => {
    expect(выбраннаяМодель('pump', конфиг({ pumpId: ПОМПА }), сМоделью('pump', 'unknown')))
      .toBe('unknown');
  });

  /* В браузере движка нет вовсе: без запасного ответа выбирать модель было бы негде. */
  it('движок молчит — отвечает локальный выбор', () => {
    expect(выбраннаяМодель('pump', конфиг({ pumpId: ПОМПА }), null)).toBe(ПОМПА);
    expect(выбраннаяМодель('pump', конфиг({ pumpId: ПОМПА }), сМоделью('pump', null))).toBe(ПОМПА);
  });

  /* Движок хранит строку сырьём и не проверяет. Пришло то, чего в нашем справочнике нет,
     — по такому ответу не найти ни резервуара, ни спецификаций, и это не модель, а шум. */
  it('чужую строку не берём', () => {
    expect(выбраннаяМодель('pump', конфиг({ pumpId: ПОМПА }), сМоделью('pump', 'medtronic'))).toBe(ПОМПА);
  });

  /* Помпа записана, но ни в одном слоте не стоит (данные ещё не пошли). Единственный
     прибор своего вида — значит про него и речь. */
  it('слот пуст, прибор один — берём его модель', () => {
    const snap = {
      bridgeRevision: '1.14',
      devices: [{ id: 'p', kind: 'pump', deviceModel: ПОМПА }],
    } as unknown as UiSnapshot;
    expect(выбраннаяМодель('pump', конфиг({}), snap)).toBe(ПОМПА);
  });
});
