import { describe, it, expect } from 'vitest';
import { ходПопытки, ходДляСтроки, СРОК_ОЖИДАНИЯ_МС, type Попытка } from './connectAttempt';
import { словоОжидания } from '@/слова/попытка';

/* Ожидание связи (SugarLife#303). Проверяем главное: ожидание кончается, а до конца
   человек видит, что идёт работа. И то и другое — про доверие к кнопке. */

const т0 = new Date(2026, 7, 16, 18, 40, 0).getTime();
const связь: Попытка = { id: 'bridge:1', цель: 'связь', началоМс: т0 };
const разрыв: Попытка = { id: 'bridge:1', цель: 'разрыв', началоМс: т0 };

describe('ход попытки', () => {
  it('связь встала — ожидание закончилось', () => {
    expect(ходПопытки(связь, true, т0 + 3000)).toBe('получилось');
  });

  it('пока не встала и срок не вышел — идёт', () => {
    expect(ходПопытки(связь, false, т0 + 3000)).toBe('идёт');
  });

  /* Главное свойство: «Подключаюсь…» навсегда — это то же молчание, только с
     анимацией. Через срок обязано смениться словами. */
  it('срок вышел — не ответил', () => {
    expect(ходПопытки(связь, false, т0 + СРОК_ОЖИДАНИЯ_МС + 1)).toBe('не ответил');
  });

  /* У разрыва цель обратная, и путать их нельзя: «отпускаю…» при живой связи и
     «подключаюсь…» при мёртвой — это два разных ожидания одного и того же вида. */
  it('разрыв смотрит в другую сторону', () => {
    expect(ходПопытки(разрыв, false, т0 + 1000)).toBe('получилось');
    expect(ходПопытки(разрыв, true, т0 + 1000)).toBe('идёт');
  });
});

describe('слово в строке списка', () => {
  it('ожидание видно и при закрытой карточке', () => {
    expect(словоОжидания(ходДляСтроки(связь, 'bridge:1', false, т0 + 1000))).toBe('подключаюсь…');
    expect(словоОжидания(ходДляСтроки(разрыв, 'bridge:1', true, т0 + 1000))).toBe('отпускаю…');
  });

  /* Ожидание относится к ОДНОМУ прибору. Иначе «подключаюсь…» повисло бы у всех строк
     сразу — а это утверждение о том, чего не делали. */
  it('чужую строку не трогает', () => {
    expect(словоОжидания(ходДляСтроки(связь, 'sensor:2', false, т0 + 1000))).toBe(null);
  });

  it('получилось — слова больше нет, состояние скажет сама строка', () => {
    expect(словоОжидания(ходДляСтроки(связь, 'bridge:1', true, т0 + 1000))).toBe(null);
  });

  it('не ответил — так и написано, а не молчание', () => {
    expect(словоОжидания(ходДляСтроки(связь, 'bridge:1', false, т0 + СРОК_ОЖИДАНИЯ_МС + 1))).toBe('не ответил');
  });

  it('ожидания нет вовсе', () => {
    expect(словоОжидания(ходДляСтроки(null, 'bridge:1', false, т0))).toBe(null);
  });
});
