import { describe, it, expect } from 'vitest';
import { необъяснённыеПодъёмы } from './mealMoment';
import type { Entry } from './types';

const МИН = 60e3;
const now = new Date(2026, 7, 11, 22, 30).getTime();
const e = (минНазад: number, mmol: number): Entry =>
  ({ t: now - минНазад * МИН, mmol, mgdl: Math.round(mmol * 18), dir: '' });

/** Ровная линия, на которую накладываем подъёмы. */
const ровно = (откуда: number, докуда: number, mmol: number) => {
  const out: Entry[] = [];
  for (let м = откуда; м >= докуда; м -= 5) out.push(e(м, mmol));
  return out;
};

describe('моменты еды из данных', () => {
  it('находит подъём и называет его временем, а не смещением', () => {
    const es = [...ровно(200, 125, 6), ...ровно(120, 90, 9), ...ровно(85, 0, 9.5)];
    const m = необъяснённыеПодъёмы(es, [], now);
    expect(m).toHaveLength(1);
    expect(m[0].rise).toBeGreaterThanOrEqual(2.2);
    // момент — начало подъёма, а не его вершина
    expect(m[0].at).toBeLessThanOrEqual(now - 120 * МИН);
  });

  it('величина — до вершины подъёма, а не до срабатывания порога', () => {
    // порог сработает на +2.2, но поднялось в итоге на 5
    // и ступенчатый подъём остаётся ОДНИМ моментом, а не тремя строками про один приём
    const es = [...ровно(200, 125, 6), ...ровно(120, 90, 8.3), ...ровно(85, 0, 11)];
    const m = необъяснённыеПодъёмы(es, [], now);
    expect(m).toHaveLength(1);
    expect(m[0].rise).toBeCloseTo(5, 1);
  });

  it('подъём, объяснённый внесённой едой, не предлагаем', () => {
    const es = [...ровно(200, 125, 6), ...ровно(120, 0, 9)];
    const еда = [now - 122 * МИН];
    expect(необъяснённыеПодъёмы(es, еда, now)).toHaveLength(0);
  });

  it('углеводы из облака объясняют подъём так же, как свои записи', () => {
    // человек залогировал еду в AAPS — предлагать внести её второй раз нельзя
    const es = [...ровно(200, 125, 6), ...ровно(120, 0, 9)];
    const изОблака = [now - 130 * МИН];
    expect(необъяснённыеПодъёмы(es, изОблака, now)).toHaveLength(0);
  });

  it('шум и медленный дрейф подъёмом не считаются', () => {
    const шум = [e(60, 6), e(55, 6.4), e(50, 6.1), e(45, 6.6), e(40, 6.2)];
    expect(необъяснённыеПодъёмы(шум, [], now)).toHaveLength(0);
    // +2 ммоль, но за четыре часа — это не еда
    const дрейф = [e(240, 6), e(120, 7), e(10, 8.2)];
    expect(необъяснённыеПодъёмы(дрейф, [], now)).toHaveLength(0);
  });

  it('один подъём не превращается в три', () => {
    const es = [...ровно(200, 125, 5.5), ...ровно(120, 0, 11)];
    expect(необъяснённыеПодъёмы(es, [], now)).toHaveLength(1);
  });

  it('свежие первыми и не больше двух', () => {
    const es = [
      ...ровно(340, 305, 6), ...ровно(300, 245, 9),
      ...ровно(240, 185, 6), ...ровно(180, 125, 9),
      ...ровно(120, 65, 6), ...ровно(60, 0, 9),
    ];
    const m = необъяснённыеПодъёмы(es, [], now);
    expect(m).toHaveLength(2);
    expect(m[0].at).toBeGreaterThan(m[1].at);
  });

  it('глубже шести часов не заглядываем', () => {
    const es = [e(500, 6), e(480, 9), ...ровно(100, 0, 9)];
    expect(необъяснённыеПодъёмы(es, [], now)).toHaveLength(0);
  });

  it('данных мало — ничего не выдумываем', () => {
    expect(необъяснённыеПодъёмы([], [], now)).toEqual([]);
    expect(необъяснённыеПодъёмы([e(10, 6)], [], now)).toEqual([]);
  });
});
