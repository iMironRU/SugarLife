import data from './catalog/foods.json';
import type { Meal } from './meals';

/* Что подставлять вместо пустого поля.

   Пустое поле — худший ввод из возможных: человек стоит перед ним и придумывает число
   по памяти. Мы не можем измерить его тарелку, но можем не заставлять начинать с нуля.

   Отсюда единица справочника — не продукт, а ПРИЁМ: «плотный завтрак», а не «гречка
   отварная 180 г». Список блюд не решает задачу, а перекладывает её — чтобы внести
   обед, пришлось бы собрать его из четырёх строк. Блюда в справочнике тоже есть, но
   вторым слоем, для тех случаев, когда человек ест одно понятное блюдо.

   И главное про природу этих чисел. Это ОЦЕНКИ, и показывать их надо как оценки.
   Точность мы при этом не теряем: альтернатива справочнику — не измерение, а то же
   самое число, набранное по памяти. Пресет лишь избавляет от пустого поля и становится
   опорной точкой, которую человек тут же правит под себя.

   Дальше опорная точка вытесняется собственной историей: то, что человек ест часто,
   поднимается наверх с ЕГО цифрами, а не с нашими. Справочник нужен, пока истории нет. */

export type FoodCat = 'meal' | 'hypo' | 'dish' | 'snack' | 'drink';

export interface Food {
  id: string;
  cat: FoodCat;
  name: string;
  /** Углеводы в граммах на обычную порцию. Оценка. */
  carbs: number;
  portion?: string;
  /* Жирное и белковое поднимает сахар позже и дольше. Это НАБЛЮДЕНИЕ, а не указание,
     что делать с болюсом: назначений мы не даём. */
  slow?: boolean;
}

export const FOODS = (data as { items: Food[] }).items;

export const CAT_LABEL: Record<FoodCat, string> = {
  meal: 'Приёмы',
  hypo: 'Купировать гипо',
  dish: 'Блюда',
  snack: 'Перекусы',
  drink: 'Напитки',
};

/* Порядок групп — по частоте обращения, а не по алфавиту. «Купировать гипо» стоит
   вторым намеренно: в этот момент человеку некогда листать, и вспоминать, сколько
   углеводов в стакане сока, он не должен. */
export const CAT_ORDER: FoodCat[] = ['meal', 'hypo', 'snack', 'dish', 'drink'];

export function searchFoods(q: string, foods: Food[] = FOODS): Food[] {
  const s = q.trim().toLowerCase();
  if (!s) return foods;
  return foods.filter((f) => (f.name + ' ' + (f.portion ?? '')).toLowerCase().includes(s));
}

/* --- Своё, из истории ---

   Люди едят одно и то же. Поэтому самый полезный «справочник» — тот, что человек уже
   написал сам, просто внося еду. Имён у записей пока нет (называть постфактум — отдельная
   задача), но имя и не нужно: «Обед · 55 г · 6 раз» узнаётся с одного взгляда.

   Группируем по типу приёма и округлённым углеводам: 54 и 56 граммов это один и тот же
   обед, а не два разных. Шаг округления крупный намеренно — мелкий раздробил бы историю
   на кучу почти одинаковых строк, и повтор перестал бы быть виден. */
const ШАГ = 5;

/* Ключ группы — одной функцией на всех (SugarLife#381).

   Имя блюда хранится не в записи, а на ГРУППЕ: тип приёма плюс округлённые углеводы. Ключ
   собирался здесь, внутри группировки, и журналу приходилось бы повторять и округление, и
   слово «Приём» для записей без типа. Две копии правила разошлись бы на первой же правке
   шага — и человек увидел бы имя в одном месте и не увидел в другом. */
export function ключГруппы(kind: string | null | undefined, carbs: number): string {
  return `${kind ?? 'Приём'}|${Math.round(carbs / ШАГ) * ШАГ}`;
}

export interface Personal {
  id: string;
  kind: string;
  carbs: number;
  count: number;
  lastAt: number;
  /** Имя, если человек его дал. Необязательное — см. settings/mealNames.ts. */
  name?: string;
}

export function personalFoods(
  meals: Meal[],
  names: Record<string, string> = {},
  now = Date.now(),
): Personal[] {
  const карта = new Map<string, Personal>();
  for (const m of meals) {
    if (m.carbs <= 0) continue;
    const carbs = Math.round(m.carbs / ШАГ) * ШАГ;
    const kind = m.kind ?? 'Приём';
    const id = ключГруппы(m.kind, m.carbs);
    const было = карта.get(id);
    if (было) { было.count++; было.lastAt = Math.max(было.lastAt, m.t); }
    else карта.set(id, { id, kind, carbs, count: 1, lastAt: m.t, name: names[id] });
  }
  /* Сортировка: частое выше редкого, при равной частоте — свежее выше давнего.
     Не «просто последние»: съеденное однажды месяц назад не должно оттеснять то,
     что человек ест каждое утро. */
  const ДЕНЬ = 86400e3;
  return [...карта.values()].sort((a, b) =>
    b.count - a.count || b.lastAt - a.lastAt,
  ).filter((p) => now - p.lastAt < 90 * ДЕНЬ);
}
