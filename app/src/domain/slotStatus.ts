import type { DeviceView, UiSnapshot } from '@/sources/bridge';
import { СЛОВО_ПУТИ } from '@/слова/слоты';
import { связь, рольСнимка, устройствоРоли, активныйКанал, толькоОблако, движокЖивой } from './deviceState';

/* Состояние слота — по снимку движка, а не по локальной записи (SugarLife#224).

   Сведения об устройствах жили в двух местах, и это было видно на экране: строка
   сенсора показывала подпись «по радио» (из снимка) и значение «только через облако»
   (из локального конфига) — одновременно, про одно и то же устройство. Два источника
   про одно расходятся всегда; вопрос только, когда это заметят.

   Правда о работе — у движка: он один знает, встала ли связь, каким каналом идут
   данные и стоит ли за устройством мост. Локальная запись отвечает на другой вопрос —
   что человек ВЫБРАЛ в справочнике, — и остаётся ровно для него.

   ПОЧЕМУ НЕ ВЫБРОСИЛИ ЛОКАЛЬНЫЙ РАСЧЁТ. В браузере движка нет вовсе: Nightscout-шим
   ролей не отдаёт, и без запасного пути раздел устройств стал бы пустым для всех, кто
   смотрит с компьютера. Поэтому здесь развилка, а не замена. */

export type СостояниеСлота =
  | 'нет записи'      // человек ничего не заводил
  | 'без модели'      // запись есть, модель не названа — работает только облако
  | 'нужен мост'      // модель известна, но путь к ней не полон
  | 'настроено'       // путь есть, но связи сейчас нет
  | 'на связи';       // данные идут прямо сейчас

/* Состояние по снимку. null означает «движок молчит» — не «плохо», а «спроси другого»:
   вызывающий тогда берёт локальный ответ. Это разные вещи, и путать их нельзя: пустой
   слот при живом движке — это ответ, а пустой слот при отсутствии движка — незнание. */
export function слотПоСнимку(
  snap: UiSnapshot | null | undefined, роль: 'sensor' | 'pump',
): СостояниеСлота | null {
  const запись = рольСнимка(snap, роль);
  if (!запись) return null;                       // движок ролей не отдаёт
  const источник = устройствоРоли(snap, роль);
  if (!источник) return 'нет записи';

  if (связь(источник) === 'live') return 'на связи';

  /* Модель не названа — путь только облачный, и это не поломка, а законное состояние:
     данные идут, просто напрямую мы железку читать не умеем. */
  if (источник.driverId == null && толькоОблако(источник)) return 'без модели';

  /* Мост нужен, но его нет: у устройства объявлен канал через мост, а самого моста в
     железе нет. Отдельное состояние, потому что действие человека тут своё — купить
     или подключить посредника, а не «настроить». */
  const каналМоста = (источник.channels ?? []).some((c) => c.kind === 'bridged');
  const мостЕсть = (snap?.hardware ?? []).some((h) => h.kind === 'bridge');
  if (каналМоста && !мостЕсть) return 'нужен мост';

  return 'настроено';
}

/** Через что идут данные слота — словом, если движок сказал. */
export function каналСлота(
  snap: UiSnapshot | null | undefined, роль: 'sensor' | 'pump',
): 'direct' | 'bridged' | 'cloud' | null {
  const запись = рольСнимка(snap, роль);
  if (запись?.via) return запись.via;
  return активныйКанал(устройствоРоли(snap, роль))?.kind ?? null;
}

/* Мост ЭТОГО слота, а не первый попавшийся (SugarLife#224, SugarLifeCore#8).

   Раньше карточка помпы показывала телеметрию любого моста, какой нашёлся в снимке:
   заряд, прошивку, сигнал. Пока мост один — разницы нет, и потому ошибка не всплывала.
   С двумя (OrangeLink у помпы и MiaoMiao у сенсора) карточка сенсора показывала бы
   заряд помпиного моста — и человек менял бы батарейку не в том приборе.

   Связь направлена от железки к мосту (behindBridgeId), а не наоборот: мост может
   обслуживать несколько устройств, и «мост знает свою помпу» было бы неправдой.

   Запасной путь — первый мост в снимке — оставлен для старых сборок, где ссылки нет.
   Он честно хуже: это догадка, верная ровно пока мост один.

   Ищем в ОБОИХ списках. Мост — это железка, и в проекции железа он есть всегда; в
   devices[] он бывает не у всякой сборки. Пока смотрели только туда, карточка писала
   «мост не выбран» рядом со списком, где этот самый мост стоит строкой выше, — та же
   болезнь двух мнений об одном приборе, только внутри снимка. */
/* `testable` необязателен намеренно: «проверить связь» умеет запись прибора, а не строка
   в проекции железа. Пришёл мост только из железа — кнопки нет, и это честно. */
export type МостСлота =
  Pick<DeviceView, 'id' | 'name' | 'batteryPct' | 'firmware' | 'rssi'> & { testable?: boolean };

export function мостСлота(
  snap: UiSnapshot | null | undefined, роль: 'sensor' | 'pump',
): МостСлота | null {
  const источник = устройствоРоли(snap, роль);
  const мосты: МостСлота[] = [...(snap?.devices ?? []), ...(snap?.hardware ?? [])]
    .filter((d) => d.kind === 'bridge');
  if (источник?.behindBridgeId) {
    const свой = мосты.find((d) => d.id === источник.behindBridgeId);
    if (свой) return свой;
    /* Ссылка есть, а моста в списке нет — это не повод показать чужой: лучше молчание,
       чем заряд не того прибора. */
    return null;
  }
  return мосты[0] ?? null;
}

/* Откуда СЕЙЧАС идут данные слота — словом для строки списка (SugarLife#224).

   Отличается от «через что» у карточки (domain/deviceState.ts) одним: там слово молчит,
   когда связи нет, потому что «нет связи по радио» звучит как «попробуй другой путь».
   Здесь вопрос другой — не «работает ли», а «откуда цифры». Помпа может быть не на
   связи по радио, а данные всё равно идти из Nightscout, и человеку важно это видеть в
   списке, не открывая карточку.

   В браузере ответ всегда «через облако», и это не заглушка: движка там нет вовсе,
   единственный источник — Nightscout. Признак живого движка — драйверы в снимке; шим
   их не отдаёт (тем же признаком пользуется плитка «устройства рядом»). */
export function путьСлота(
  snap: UiSnapshot | null | undefined, роль: 'sensor' | 'pump',
): string | null {
  const канал = каналСлота(snap, роль);
  if (канал) return СЛОВО_ПУТИ[канал];
  /* Движка нет — значит всё, что мы показываем, пришло облаком. Это утверждение по
     построению, а не догадка. */
  /* Тот же признак, что и у плитки (#256): сервисный драйвер шима не делает движок
     живым, иначе в браузере мы бы молчали про путь вместо честного «через облако». */
  return движокЖивой(snap) ? null : СЛОВО_ПУТИ.cloud;
}

/* Модель по НАШЕМУ справочнику — из снимка (SugarLife#224, шаг 4).

   Движок хранит её сам: `deviceModel` в params (rev ≥ 1.14, SugarLifeCore#55). Это то же
   значение, которое мы туда положили при выборе, — но у движка оно переживает и
   перезапуск, и восстановление из бэкапа, а наш `sl.device.v1` живёт в localStorage и
   исчезает вместе с ним.

   Поэтому спрашиваем сначала здесь. Ответа нет — берём локальный (domain/реестр.ts):
   в браузере движка нет вовсе, и без запасного ответа выбирать модель было бы негде.

   Ищем у прибора СЛОТА, а не по всему списку: приборов одного вида бывает несколько
   (запасная помпа, снятый сенсор), и «первый попавшийся» показал бы модель не той
   железки. Слот пуст — берём единственный записанный прибор этого вида; их несколько —
   молчим, потому что выбрать за человека тут нечем.

   Своим расчётом слота здесь НЕ пользуемся, в отличие от соседей по файлу. Он выбирает
   лучший источник по связи — для вопроса «откуда сейчас идут цифры» это верно, а для
   вопроса «какая это модель» связь не аргумент: по модели считается ёмкость резервуара,
   и назначить её живому прибору вместо записанного значит соврать в расчёте. Роли в
   снимке нет — считаем, что слот не назван, и идём к правилу «единственный прибор». */
export function модельСлота(
  snap: UiSnapshot | null | undefined, роль: 'sensor' | 'pump',
): string | null {
  const запись = рольСнимка(snap, роль);
  const модель = (d: DeviceView | null | undefined) => d?.deviceModel ?? null;
  if (запись) {
    const активный = модель(устройствоРоли(snap, роль));
    if (активный) return активный;
    /* Слот наполняет облако, а модель мы записали железке. Это ОДНО устройство, просто
       достижимое двумя путями, и роль сама перечисляет оба (sourceIds). Не заглянуть
       туда значит потерять модель ровно в том случае, ради которого запись и заводили:
       помпа на теле, связи по радио нет, цифры идут из Nightscout. */
    const свои = (snap?.devices ?? [])
      .filter((d) => (запись.sourceIds ?? []).includes(d.id) && d.deviceModel);
    return свои.length === 1 ? модель(свои[0]) : null;
  }
  const записанные = (snap?.devices ?? []).filter((d) => d.kind === роль && d.deviceModel);
  return записанные.length === 1 ? модель(записанные[0]) : null;
}
