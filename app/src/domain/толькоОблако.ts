import type { UiSnapshot } from '@/sources/bridge';
import { железоДиспетчера, адресВЭфире } from './nearby';

/* ТОЛЬКО ЛИ ОБЛАКО У ЧЕЛОВЕКА — и почему это вопрос не про приборы, а про жизнь приложения.

   На iOS фоновое выполнение нам даёт ровно одно: пробуждение от прибора по эфиру. Есть сенсор или
   мост — система будит нас, когда он что-то прислал, и всё работает само. Нет ни одного — будить
   нечем: приложение приостанавливается при блокировке экрана и не делает НИЧЕГО. Ни баннер обновить,
   ни повторную тревогу посчитать.

   Поймано на живой гипогликемии владельца (#578): сахар шёл 3,8 → 3,1, а карточка на экране
   блокировки двадцать минут показывала число, снятое в момент, когда он последний раз держал телефон
   в руках. Показания в базе при этом лежали поминутно — они приезжают пачкой при следующем
   пробуждении, со своими исходными временами, и в базе выглядят как непрерывный ряд.

   ПРИЗНАК — АДРЕС В ЭФИРЕ, А НЕ ВИД ПРИБОРА. Облачный сенсор в списке значится сенсором и выглядит
   как железка; отличает их то, есть ли к чему подключаться напрямую. `адресВЭфире` отвечает на
   ровно этот вопрос и уже используется списком приборов — второй способ спросить то же самое
   разошёлся бы с первым. */
export function толькоОблако(snap: UiSnapshot | null | undefined): boolean {
  const железо = железоДиспетчера(snap);
  /* Пусто — это «ничего не настроено», а не «только облако». Предупреждать человека, у которого
     источников нет вовсе, про фоновую работу незачем: ему нечего показывать в принципе, и разговор
     у него другой. */
  if (!железо.length) return false;
  return железо.every((h) => адресВЭфире(h) == null);
}
