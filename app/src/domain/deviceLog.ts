import type { LogRecord, LogLevel } from '@/sources/bridge';
import { часыСек } from '@/слова/время';

/* Журнал обмена с прибором — правила показа (SugarLife#354).

   Экран заведён не для нас: три поломки за день нашлись через `adb logcat` с компьютера,
   а у человека с телефоном такого канала нет — он видит «устройство не отвечает» и не
   может сказать больше ни нам, ни себе.

   Отсюда и решения ниже: показываем то, что читается человеком, и молчим о том, что
   читается только нами. */

/** Насколько запись важна — по ней решают и цвет, и что показать в свёрнутом виде. */
const ВЕС_УРОВНЯ: Record<LogLevel, number> = {
  Trace: 0, Debug: 1, Info: 2, Warn: 3, Error: 4,
};

/* Обычный показ — от Info и выше.

   Trace и Debug это кадры обмена: сотни записей в минуту, среди которых человеческое
   тонет. Их включают отдельно и ненадолго, чтобы воспроизвести проблему. */
export const ОБЫЧНЫЙ_УРОВЕНЬ: LogLevel = 'Info';

export function важнее(з: LogRecord, порог: LogLevel): boolean {
  return ВЕС_УРОВНЯ[з.level] >= ВЕС_УРОВНЯ[порог];
}

/** Есть ли в выборке хоть одна запись с идентификаторами прибора. */
export function естьИдентификаторы(записи: LogRecord[]): boolean {
  return записи.some((з) => з.hasIdentifiers);
}

/* Сколько ещё продержится подробный режим.

   Возвращаем минуты, а не «включено/выключено»: движок гасит подробность сам через
   четверть часа, и переключатель без срока соврал бы ровно тогда, когда человек про него
   забудет. null — подробность не включена. */
export function подробноЕщёМинут(доМс: number | null | undefined, сейчас: number): number | null {
  if (!доМс) return null;
  const осталось = доМс - сейчас;
  if (осталось <= 0) return null;
  return Math.max(1, Math.round(осталось / 60_000));
}

/* ПОЧЕМУ СПИСОК ПУСТ — состоянием, а не фразой (#324). Слова — в `слова/журнал.ts`.

   Четыре разных случая, и путать их нельзя: «сборка старше журнала» лечится обновлением
   приложения, «в браузере журнала нет» — переходом на телефон, «всё отфильтровано» — порогом
   подробности, а «записей нет» — просто ожиданием. Сказать человеку с телефоном «откройте на
   телефоне» значит отправить его туда, где он уже стоит. */
export type Пустой = 'сборка старая' | 'в браузере' | 'только служебные' | 'записей нет';

export function пустой(
  { журналЕсть, всегоЗаписей, вПриложении }:
  { журналЕсть: boolean; всегоЗаписей: number; вПриложении?: boolean },
): Пустой {
  if (!журналЕсть) return вПриложении ? 'сборка старая' : 'в браузере';
  if (всегоЗаписей > 0) return 'только служебные';
  return 'записей нет';
}

/** Время записи — часы:минуты:секунды. Секунды здесь не педантизм: события идут пачками. */
export function времяЗаписи(atMs: number): string {
  return часыСек(atMs);
}

/* Поля записи — одной строкой. Показываем как есть: имена придумал тот, кто знает
   протокол, и «перевести» их у нас нет ни права, ни контекста. */
export function строкаПолей(поля: LogRecord['fields']): string | null {
  if (!поля) return null;
  const части = Object.entries(поля)
    .filter(([, v]) => v !== null && v !== '')
    .map(([k, v]) => `${k}: ${v}`);
  return части.length ? части.join(' · ') : null;
}
