import { describe, it, expect } from 'vitest';
import { поддержка, ключиДрайверов, делимЛи } from './catalogSupport';
import type { DriverDescriptor } from '@/sources/bridge';

/* Обещание «читаем напрямую» человек проверяет покупкой моста и вечером за настройкой.
   Ошибка здесь стоит денег и разочарования, а выглядит как обычная строка в списке —
   поэтому граница под тестами целиком. */

const драйвер = (supports?: Array<{ key: string }>): DriverDescriptor => ({
  id: 'medtronic', displayName: 'Medtronic', kind: 'pump', roles: [],
  settings: { parameters: [] }, available: true,
  supports: supports as DriverDescriptor['supports'],
});

const ключи = ключиДрайверов([драйвер([{ key: 'medtronic-522-722' }, { key: 'medtronic-554-754' }])]);

describe('что мы умеем с моделью', () => {
  it('ключ есть и движок его знает — читаем напрямую', () => {
    expect(поддержка('medtronic-522-722', false, ключи)).toBe('напрямую');
  });

  /* Наша таблица может опережать сборку движка: ключ проставлен, а драйвера с ним нет.
     Обещать прямую связь в этом случае нельзя — человек пойдёт покупать мост. */
  it('ключ есть, а движок про него не знает — честно через облако', () => {
    expect(поддержка('medtronic-780g', true, ключи)).toBe('облако');
  });

  it('ключа нет вовсе — актуальная модель работает через облако', () => {
    expect(поддержка(null, true, ключи)).toBe('облако');
    expect(поддержка(undefined, true, ключи)).toBe('облако');
  });

  it('ключа нет и модель снята — «старое и снятое»', () => {
    expect(поддержка(null, false, ключи)).toBe('снято');
  });

  /* Снятый Paradigm читается напрямую — и попадает в «читаем напрямую», потому что
     человек его УЖЕ носит. «Снято» отвечает на другой вопрос: стоит ли выбирать эту
     модель сегодня, а не умеем ли мы её читать. */
  it('снятая с производства, но читаемая — всё равно «напрямую»', () => {
    expect(поддержка('medtronic-554-754', false, ключи)).toBe('напрямую');
  });
});

describe('ключи из снимка', () => {
  it('собираются со всех драйверов', () => {
    const k = ключиДрайверов([драйвер([{ key: 'a' }]), драйвер([{ key: 'b' }, { key: 'c' }])]);
    expect([...k].sort()).toEqual(['a', 'b', 'c']);
  });

  it('драйверов нет — пусто, а не падение', () => {
    expect(ключиДрайверов(undefined).size).toBe(0);
    expect(ключиДрайверов([драйвер()]).size).toBe(0);
  });
});

describe('делить ли список на группы', () => {
  /* Старая сборка движка supports не отдаёт. Показать «читаем напрямую» там, где движок
     этого не подтверждал, хуже, чем не делить вовсе — так и договорились с ядром. */
  it('движок про модели молчит — групп нет', () => {
    expect(делимЛи([драйвер()])).toBe(false);
    expect(делимЛи([])).toBe(false);
    expect(делимЛи(undefined)).toBe(false);
  });

  it('хотя бы один драйвер назвал модели — делим', () => {
    expect(делимЛи([драйвер(), драйвер([{ key: 'a' }])])).toBe(true);
  });

  /* Пустой supports — это ответ «этот драйвер не читает ни одной известной модели», а
     не молчание: делить можно. */
  it('пустой список моделей — тоже ответ', () => {
    expect(делимЛи([драйвер([])])).toBe(true);
  });
});
