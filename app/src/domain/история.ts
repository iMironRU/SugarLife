/* Одна лента того, что уже ушло с экрана (SugarLife#384).

   «Сегодня» живёт настоящим: обращения гаснут, лента подключения исчезает через минуты,
   приём уезжает вверх и пропадает. Это правильно — экран действия не должен превращаться
   в архив. Но потом человек спрашивает: «во сколько я ел?», «когда сенсор отвалился?»,
   «я вообще менял канюлю?» — и ответить нечем, хотя данные есть.

   ЧТО СЮДА ВХОДИТ — то, что человек ВИДЕЛ на «Сегодня», и теми же словами (#396).

   Первая версия собиралась из журнала движка, и это было не то: журнал — переписка с
   прибором («прибор изучен: характеристики найдены», «показание получено»), он про
   технику и нужен, когда разбирают неисправность. Человек же открывает историю с другим
   вопросом: когда подключился сенсор, когда отвалился, когда был подъём без записи. То
   есть спрашивает про строки, которые видел сам. Журнал остался там, где он и полезен, —
   в «Что происходит» у прибора.

   Три источника, и все отвечают на «что было со МНОЙ»: дневник экрана (связь, обновления),
   приёмы из нашей базы и подъёмы без записи, посчитанные по тем же правилам, что в
   «Приёмах». Ничего четвёртого не выдумываем.

   ЧЕГО ЗДЕСЬ НЕТ: оценок. Ни «много углеводов», ни «долго без связи». Лента отвечает на
   «что было», а не «хорошо ли это»; разбор живёт в «Метриках» и там ему место. */

export type ВидСобытия = 'еда' | 'прибор' | 'подъём' | 'сборка' | 'тревога' | 'замена' | 'болюс';

/* СУТЬ СОБЫТИЯ — ЧИСЛАМИ И ПРИЗНАКАМИ, А НЕ ФРАЗОЙ (#324, третий заход).

   Здесь лента собирала текст сама: «Замена: сенсор», «Подъём +2,3 ммоль», «25 г · перекус». Правку
   слова нельзя было сделать, не тронув расчёт, а расчёт нельзя было проверить, не сверяя буквы.

   Теперь домен отвечает СОСТОЯНИЕМ, а называет его `слова/история.ts`. Тот же приём, что во втором
   заходе с `loopValue`: было `reason: «цикл молчит 40 мин»`, стало `почему: «молчит»` плюс срок
   числом.

   ЗАПИСЬ ДНЕВНИКА — ОСОБЫЙ СЛУЧАЙ, и он честный. Её текст пишем не мы: он приходит готовым из
   дневника и здесь только едет мимо. Это данные, а не формулировка ленты. */
export type СутьСобытия =
  /** Запись дневника: текст пришёл готовым, мы его не сочиняли. */
  | { род: 'запись'; главное: string; подпись: string | null }
  /** Замена расходника: `что` — машинный вид (`sensor`, `site`, `reservoir`, `battery`). */
  | { род: 'замена'; что: string }
  /** Ввод: инсулин в единицах или еда в граммах. */
  | { род: 'ввод'; инсулин: boolean; сколько: number; изОблака: true }
  /** Подъём без записи: на сколько ммоль поднялось. */
  | { род: 'подъём'; наСколько: number }
  /** Приём: граммы плюс уже названный вид приёма (имя даёт `имяПриёма`). */
  | { род: 'приём'; граммы: number; имя: string; уточнение: string | null };

export interface Событие {
  ключ: string;
  когдаМс: number;
  вид: ВидСобытия;
  суть: СутьСобытия;
  /** Сколько раз подряд это повторилось. Нет — было один раз. */
  повторов?: number;
  /** Верхняя граница группы повторов: событие шло с `когдаМс` по `доМс`. */
  доМс?: number;
}

/* ЖИЗНЬ ЧЕЛОВЕКА, А НЕ ЖИЗНЬ ЖЕЛЕЗА (#597).

   Владелец открыл историю и увидел ленту, забитую техникой: «на связи» — «отключился», по паре
   строк в минуту, на весь экран. Его слова: «Зачем столько одного и того же в истории. Я то думал
   там будет иное».

   Причина не в важности, а в количестве. Связь мигает дважды в минуту, а человек ест четыре раза в
   день — техника вытеснила собой ровно то, ради чего лента заведена.

   Отдельно: для облачного источника это ещё и неправда. Там Nightscout по HTTP, и «отключился»
   означает в лучшем случае «запрос не прошёл».

   Поэтому в историю идёт только то, о чём человек может вспомнить или спросить: что он ел, что с
   ним было, что его будило. Жизнь железа целиком уезжает в диагностику — там её и ищут, и с другой
   целью: вопрос «почему приложение молчало» задают в другой момент.

   Разделение у нас БЫЛО и не использовалось: у записи дневника есть `вид`, и события связи давно
   помечены как `'прибор'`. Не хватало одной строки — этой. */
const ЖИЗНЬ_ЖЕЛЕЗА: ЗаписьДневника['вид'][] = ['прибор', 'сборка'];

export function изДневника(записи: ЗаписьДневника[]): Событие[] {
  return записи.filter((з) => !ЖИЗНЬ_ЖЕЛЕЗА.includes(з.вид)).map((з) => ({
    ключ: з.ключ,
    когдаМс: з.когдаМс,
    вид: (з.вид === 'тревога' ? 'тревога' : з.вид === 'сборка' ? 'сборка' : 'прибор') as ВидСобытия,
    суть: { род: 'запись', главное: з.главное, подпись: з.подпись ?? null },
  }));
}

/* ЗАМЕНЫ РАСХОДНИКОВ (#597).

   Владелец спросил прямо: «когда я менял набор и сенсор?» — и это один из четырёх вопросов, с
   которыми в историю вообще приходят. Возраст канюли решает, не пора ли менять; возраст сенсора
   объясняет, почему числа поплыли.

   ОГОВОРКА, КОТОРУЮ НАДО ЗНАТЬ: мы храним только ПОСЛЕДНЮЮ замену каждого расходника, не историю.
   Значит в ленте будет одна строка на вид, и только если замена попала в окно. Позавчерашнюю смену
   сенсора при вчерашней канюле человек увидит, а позапрошлую — нет: её у нас нет.

   Заводить историю замен ради ленты не станем: это данные, и решение о них принимается не здесь. */
/* КАКИЕ ЗАМЕНЫ МЫ ВООБЩЕ ЗНАЕМ. Здесь только машинные виды — имена живут в `слова/история.ts`.

   Список нужен как ФИЛЬТР, а не как словарь: незнакомый вид в ленту не пускаем. «Замена: xyz»
   человеку не говорит ничего и выглядит поломкой — а замена, которую он не узнаёт, хуже
   отсутствующей: вопрос «когда я менял канюлю» она не закрывает, но место занимает.

   Два списка вместо одного — цена разделения, и она реальна: они могут разойтись. Поэтому в
   `слова/история.test.ts` стоит проверка, что каждый знакомый вид назван. */
export const ЗНАКОМЫЕ_ЗАМЕНЫ = ['sensor', 'site', 'reservoir', 'battery'] as const;

export function изЗамен(замены: Record<string, number | undefined>, от: number): Событие[] {
  return Object.entries(замены)
    .filter(([вид, когда]) => когда != null && когда >= от
      && (ЗНАКОМЫЕ_ЗАМЕНЫ as readonly string[]).includes(вид))
    .map(([вид, когда]) => ({
      ключ: `замена:${вид}:${когда}`,
      когдаМс: когда as number,
      вид: 'замена' as ВидСобытия,
      суть: { род: 'замена', что: вид },
    }));
}

/* ЛЕЧЕНИЕ: БОЛЮСЫ И ЕДА (#597, ядро #175).

   «Я колол или нет» — самый частый и самый опасный вопрос, с которым в историю приходят. Лента на
   него не отвечала вовсе: болюсы лежат у нас с подключения облака и не показывались.

   ЧТО СЧИТАТЬ ЖИЗНЬЮ ЧЕЛОВЕКА, РЕШАЕМ НЕ МЫ. Вчера здесь стоял список `['TempBasal', 'Basal']` —
   времянка. Ядро дало флаг `humanOnly`, и он лучше списка: имена заводят они, а остановку подачи
   они осознанно отнесли к человеку (по виду записи не отличить «снял помпу в душ» от «петля
   остановила при низком»). Своим списком мы бы её выбросили и не заметили.

   Сюда приходит уже отфильтрованное — см. `показ/лентаЧеловека.ts`. */
/* ИНСУЛИН ЭТО ИЛИ ЕДА — ОДИН ОТВЕТ НА ДВЕ ЛЕНТЫ (SugarLife#697).

   Лента вводов уехала на экран «Инсулин», а еда из облака осталась в «Истории». Источник у них
   общий (`лентаЧеловека`), значит и разделяющее правило должно быть общим: две копии одного
   `test()` разошлись бы на первом же новом виде записи, и запись пропала бы разом отовсюду
   либо задвоилась. */
export const этоИнсулин = (kind: string): boolean => /bolus|инсулин/i.test(kind);

export function изЛечения(точки: { atMs: number; kind: string; amount: number }[]): Событие[] {
  return точки
    .filter((т) => т.amount > 0)
    .map((т) => {
      const инсулин = этоИнсулин(т.kind);
      return {
        ключ: `лечение:${т.atMs}:${т.kind}`,
        когдаМс: т.atMs,
        вид: (инсулин ? 'болюс' : 'еда') as ВидСобытия,
        /* Откуда запись — не украшение: доверие к своей и к чужой разное. Признаком, а не
           фразой: «из облака» напишут слова. */
        суть: { род: 'ввод', инсулин, сколько: т.amount, изОблака: true },
      };
    });
}

/* Подъёмы без записи. Считаются, а не хранятся, — и это единственная часть ленты,
   которая знает про прошлое ДО установки дневника: правило работает по показаниям, а они
   лежат в истории движка.

   Ни одного слова о том, что человек что-то скрыл: причин у подъёма больше двух (#167) —
   недоданный болюс, отвалившаяся канюля, рассветный феномен, болезнь, нагрев сенсора. */
export function изПодъёмов(моменты: Момент[]): Событие[] {
  return моменты.map((м) => ({
    ключ: `rise-${м.at}`,
    когдаМс: м.at,
    вид: 'подъём' as const,
    суть: { род: 'подъём', наСколько: м.rise },
  }));
}

export function изПриёмов(meals: Meal[], имена: Record<string, string> = {}): Событие[] {
  return meals.map((m) => {
    const час = new Date(m.t).getHours();
    const п = подписьПриёма({
      имя: имена[`${m.kind ?? 'Приём'}|${Math.round(m.carbs / 5) * 5}`],
      kind: m.kind, часЕды: час, граммы: m.carbs,
    });
    return {
      ключ: `meal-${m.id}`,
      когдаМс: m.t,
      вид: 'еда' as const,
      суть: { род: 'приём', граммы: m.carbs, имя: п.главное, уточнение: п.уточнение ?? null },
    };
  });
}

/* ПОВТОРЫ СВОРАЧИВАЕМ — теперь не ради журнала, а ради дёргающейся связи.

   Журнала в ленте больше нет, и сотен строк «показание получено» тоже. Но остаётся
   случай, ради которого правило и стоит держать: сенсор на границе радиуса отваливается
   и цепляется обратно раз в минуту, и ночь такой связи превращает ленту в простыню из
   одинаковых строк. «„Sibionics GS1“ отключился · 14 раз» отвечает на вопрос лучше, чем
   четырнадцать отдельных строк, — и, в отличие от них, сразу говорит, что связь рвётся.

   Схлопываем только соседей: если между двумя «показание получено» был обрыв, они
   останутся двумя группами, и обрыв будет виден между ними — а это и есть то, что
   человек ищет. */
export function свернутьПовторы(события: Событие[]): Событие[] {
  const итог: Событие[] = [];
  for (const с of события) {
    const прошлое = итог[итог.length - 1];
    if (прошлое && прошлое.вид === с.вид && ключСути(прошлое.суть) === ключСути(с.суть)) {
      прошлое.повторов = (прошлое.повторов ?? 1) + 1;
      /* Время оставляем САМОЕ РАННЕЕ в группе, а показываем диапазон: «с 23:35» честнее,
         чем время последнего повтора, будто событие случилось только что. */
      прошлое.доМс = прошлое.доМс ?? прошлое.когдаМс;
      прошлое.когдаМс = с.когдаМс;
      continue;
    }
    итог.push({ ...с });
  }
  return итог;
}

/* СРАВНИВАЕМ СУТЬ, А НЕ СОБРАННЫЙ ТЕКСТ (#324).

   Раньше свёртка сличала `главное` — то есть готовую фразу. Это работало, но держалось на
   совпадении: измени формулировку, добавь в неё время или единицу — и одинаковые события
   перестанут схлопываться, а разные, наоборот, могут склеиться. В дневнике это не косметика:
   склеенные записи означают, что человек не увидит одно из двух событий.

   По сути надёжнее и заодно понятнее: видно, ЧТО именно считается одним и тем же. */
function ключСути(с: СутьСобытия): string {
  switch (с.род) {
    /* Текст записи — единственное, что у неё есть; он и различает. */
    case 'запись': return `запись|${с.главное}|${с.подпись ?? ''}`;
    case 'замена': return `замена|${с.что}`;
    case 'ввод': return `ввод|${с.инсулин ? 'и' : 'е'}|${с.сколько}`;
    case 'подъём': return `подъём|${с.наСколько}`;
    case 'приём': return `приём|${с.граммы}|${с.имя}`;
  }
}

/** Свежее сверху: человек ищет недавнее, а не начало дня. */
export function лентаИстории(части: Событие[][]): Событие[] {
  return части.flat().sort((a, b) => b.когдаМс - a.когдаМс);
}

/** По дням, чтобы «вчера» не сливалось с «сегодня» в одну простыню. */
export function поДням(события: Событие[]): { день: number; события: Событие[] }[] {
  const карта = new Map<number, Событие[]>();
  for (const с of события) {
    const д = new Date(с.когдаМс); д.setHours(0, 0, 0, 0);
    const к = д.getTime();
    (карта.get(к) ?? карта.set(к, []).get(к)!).push(с);
  }
  return [...карта.entries()].sort((a, b) => b[0] - a[0]).map(([день, события]) => ({ день, события }));
}
