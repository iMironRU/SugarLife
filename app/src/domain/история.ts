import type { LogRecord } from '@/sources/bridge';
import type { Meal } from './meals';
import { подписьПриёма } from './имяПриёма';

/* Одна лента того, что уже ушло с экрана (SugarLife#384).

   «Сегодня» живёт настоящим: обращения гаснут, лента подключения исчезает через минуты,
   приём уезжает вверх и пропадает. Это правильно — экран действия не должен превращаться
   в архив. Но потом человек спрашивает: «во сколько я ел?», «когда сенсор отвалился?»,
   «я вообще менял канюлю?» — и ответить нечем, хотя данные есть.

   ЧТО СЮДА ВХОДИТ — только то, что где-то ХРАНИТСЯ. Приёмы лежат в нашей базе, события
   приборов — в журнале движка (он их пишет в SQLite и переживает перезапуск). Ощущения
   вроде вибро при подключении живут в памяти и до истории не доживают; выдумывать им
   хранилище ради ленты мы не станем.

   ЧЕГО ЗДЕСЬ НЕТ: оценок. Ни «много углеводов», ни «долго без связи». Лента отвечает на
   «что было», а не «хорошо ли это»; разбор живёт в «Метриках» и там ему место. */

export type ВидСобытия = 'еда' | 'прибор' | 'тревога';

export interface Событие {
  ключ: string;
  когдаМс: number;
  вид: ВидСобытия;
  главное: string;
  подпись?: string | null;
  /** Сколько раз подряд это повторилось. Нет — было один раз. */
  повторов?: number;
  /** Верхняя граница группы повторов: событие шло с `когдаМс` по `доМс`. */
  доМс?: number;
}

/* Из журнала движка берём НЕ ВСЁ. Кадры обмена (Trace/Debug) — это сотни записей в
   минуту, среди которых человеческое тонет; им место в «Что происходит» у прибора, а не
   в общей ленте дня. Здесь — то, что человек назвал бы событием. */
export function изЖурнала(записи: LogRecord[]): Событие[] {
  return записи
    .filter((з) => з.level === 'Info' || з.level === 'Warn' || з.level === 'Error')
    .map((з) => ({
      ключ: `log-${з.atMs}-${з.event}`,
      когдаМс: з.atMs,
      вид: (з.level === 'Warn' || з.level === 'Error' ? 'тревога' : 'прибор') as ВидСобытия,
      главное: з.event,
      подпись: з.deviceId ? null : null,
    }));
}

export function изПриёмов(meals: Meal[], имена: Record<string, string> = {}): Событие[] {
  return meals.map((m) => {
    const час = new Date(m.t).getHours();
    const п = подписьПриёма({
      имя: имена[`${m.kind ?? 'Приём'}|${Math.round(m.carbs / 5) * 5}`],
      kind: m.kind, часЕды: час, граммы: m.carbs,
    });
    return {
      ключ: `meal-${m.id}`,
      когдаМс: m.t,
      вид: 'еда' as const,
      главное: `${Math.round(m.carbs)} г · ${п.главное}`,
      подпись: п.уточнение,
    };
  });
}

/* ПОВТОРЫ СВОРАЧИВАЕМ, и без этого лента бесполезна.

   Движок пишет запись на каждое показание — раз в минуту-пять, то есть сотни строк
   «показание получено» за сутки. В ленте дня они вытесняют то единственное, ради чего
   человек её открыл: когда отвалилась связь, когда он ел, когда менял канюлю.

   Сворачиваем ПО ТЕКСТУ и подряд идущие: «показание получено · 128 раз» отвечает на «шли
   ли данные» лучше, чем сто двадцать восемь одинаковых строк, и не прячет между ними
   обрыв. Правило общее — ничего не знает ни про одну конкретную формулировку движка,
   иначе завтра он поменяет слово и лента снова захлебнётся.

   Схлопываем только соседей: если между двумя «показание получено» был обрыв, они
   останутся двумя группами, и обрыв будет виден между ними — а это и есть то, что
   человек ищет. */
export function свернутьПовторы(события: Событие[]): Событие[] {
  const итог: Событие[] = [];
  for (const с of события) {
    const прошлое = итог[итог.length - 1];
    if (прошлое && прошлое.вид === с.вид && базовыйТекст(прошлое) === с.главное) {
      прошлое.повторов = (прошлое.повторов ?? 1) + 1;
      /* Время оставляем САМОЕ РАННЕЕ в группе, а показываем диапазон: «с 23:35» честнее,
         чем время последнего повтора, будто событие случилось только что. */
      прошлое.доМс = прошлое.доМс ?? прошлое.когдаМс;
      прошлое.когдаМс = с.когдаМс;
      continue;
    }
    итог.push({ ...с });
  }
  return итог;
}

function базовыйТекст(с: Событие): string {
  return с.главное;
}

/** Свежее сверху: человек ищет недавнее, а не начало дня. */
export function лентаИстории(части: Событие[][]): Событие[] {
  return части.flat().sort((a, b) => b.когдаМс - a.когдаМс);
}

/** По дням, чтобы «вчера» не сливалось с «сегодня» в одну простыню. */
export function поДням(события: Событие[]): { день: number; события: Событие[] }[] {
  const карта = new Map<number, Событие[]>();
  for (const с of события) {
    const д = new Date(с.когдаМс); д.setHours(0, 0, 0, 0);
    const к = д.getTime();
    (карта.get(к) ?? карта.set(к, []).get(к)!).push(с);
  }
  return [...карта.entries()].sort((a, b) => b[0] - a[0]).map(([день, события]) => ({ день, события }));
}
