import { describe, it, expect } from 'vitest';
import { подсказка, пора, гипоСейчас, приёмПоЧасу } from './foodNow';
import type { Personal } from './foods';

const своё = (kind: string, carbs: number, count: number): Personal =>
  ({ id: `${kind}|${carbs}`, kind, carbs, count, lastAt: Date.now() });
const ел = (час: number, kind: string) => ({ t: new Date(2026, 7, 11, час, 0).getTime(), kind });

describe('пора суток', () => {
  it('границы там, где люди едят, а не по календарю', () => {
    expect(пора(5)).toBe('утро');
    expect(пора(10)).toBe('утро');
    expect(пора(11)).toBe('день');
    expect(пора(16)).toBe('вечер');
    expect(пора(22)).toBe('ночь');
    expect(пора(3)).toBe('ночь');
  });
});

describe('гипо прямо сейчас', () => {
  it('ниже порога — да, независимо от тренда', () => {
    expect(гипоСейчас(3.4, false)).toBe(true);
  });
  it('ещё в норме, но падает — тоже да: через двадцать минут будет гипо', () => {
    expect(гипоСейчас(4.8, true)).toBe(true);
    expect(гипоСейчас(4.8, false)).toBe(false);
    expect(гипоСейчас(6.5, true)).toBe(false);
  });
  it('без данных не выдумываем', () => {
    expect(гипоСейчас(null, true)).toBe(false);
  });
});

describe('что показать первым', () => {
  it('низкий сахар вытесняет всё: только купирование, целиком', () => {
    const p = подсказка({ hour: 3, mmol: 3.2, падает: false, своё: [своё('Ужин', 50, 20)] })!;
    expect(p.гипо).toBe(true);
    expect(p.свои).toHaveLength(0);
    expect(p.из_справочника.every((f) => f.cat === 'hypo')).toBe(true);
    expect(p.из_справочника.length).toBeGreaterThanOrEqual(4);
    expect(p.повод).toEqual({ вид: 'гипо', mmol: 3.2 });
  });

  it('падение с нормального сахара — тоже купирование', () => {
    expect(подсказка({ hour: 14, mmol: 4.7, падает: true })!.гипо).toBe(true);
  });

  it('явный выбор приёма сильнее часа суток', () => {
    const p = подсказка({ hour: 8, mmol: 7, выбранныйПриём: 'Ужин', своё: [своё('Ужин', 45, 9), своё('Завтрак', 40, 30)] })!;
    expect(p.свои.map((s) => s.kind)).toEqual(['Ужин']);
    expect(p.повод).toEqual({ вид: 'намерение', приём: 'Ужин' });
  });

  it('без явного выбора — своё из этого времени суток, а не самое частое вообще', () => {
    const p = подсказка({
      hour: 8, mmol: 7,
      своё: [своё('Ужин', 50, 40), своё('Завтрак', 40, 5)],
      историяЧасов: [ел(8, 'Завтрак'), ел(20, 'Ужин')],
    })!;
    expect(p.свои.map((s) => s.kind)).toEqual(['Завтрак']);
  });

  it('окно по часу круговое: в полночь час ночи — рядом, а не через сутки', () => {
    const p = подсказка({ hour: 0, mmol: 7, своё: [своё('Перекус', 20, 3)], историяЧасов: [ел(23, 'Перекус')] })!;
    expect(p.свои.map((s) => s.kind)).toEqual(['Перекус']);
  });

  it('истории нет — подставляем пресеты по времени, а не пустоту', () => {
    const p = подсказка({ hour: 8, mmol: 7 })!;
    expect(p.свои).toHaveLength(0);
    expect(p.из_справочника.length).toBeGreaterThan(0);
    expect(p.из_справочника.every((f) => /завтрак/i.test(f.name))).toBe(true);
  });

  /* Группа обязана быть подписана: молча переставленный список — это когда приложение решает за
     тебя и не объясняет. Здесь проверяем, что повод назван всегда; сама фраза — в слова/еда. */
  it('подсказка всегда объясняет себя', () => {
    for (const ctx of [{ hour: 8, mmol: 7 }, { hour: 3, mmol: 3.1 }, { hour: 19, mmol: 8 }]) {
      expect(подсказка(ctx)?.повод.вид).toBeTruthy();
    }
  });

  it('больше пяти плиток не показываем', () => {
    const p = подсказка({
      hour: 13, mmol: 7,
      своё: [своё('Обед', 50, 9), своё('Обед', 60, 8), своё('Обед', 40, 7), своё('Обед', 70, 6)],
      историяЧасов: [ел(13, 'Обед')],
    })!;
    expect(p.свои.length + p.из_справочника.length).toBeLessThanOrEqual(5);
  });
});

describe('приём по умолчанию', () => {
  it('подставляется по часу, а не всегда «Обед»', () => {
    expect(приёмПоЧасу(8)).toBe('Завтрак');
    expect(приёмПоЧасу(13)).toBe('Обед');
    expect(приёмПоЧасу(20)).toBe('Ужин');
    expect(приёмПоЧасу(3)).toBe('Перекус');
  });
});
