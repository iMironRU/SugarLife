import { describe, it, expect } from 'vitest';
import { ждатьНеДольше, пауза } from './ждатьНеДольше';

const скоро = <T>(v: T, мс: number) => new Promise<T>((r) => setTimeout(() => r(v), мс));
/** Обещание, которое не завершится никогда, — то самое, что держало экран. */
const никогда = () => new Promise<never>(() => {});

describe('ждать не дольше срока', () => {
  it('дождались всех — виновных нет', async () => {
    expect(await ждатьНеДольше([
      { имя: 'облако', дело: скоро(1, 5) },
      { имя: 'история', дело: скоро(2, 10) },
    ], 200)).toEqual([]);
  });

  /* Ради этого случая всё и написано: одно из дел не отвечает никогда, а жест обязан вернуться. */
  it('кто не ответил — тот и назван', async () => {
    expect(await ждатьНеДольше([
      { имя: 'облако', дело: скоро(1, 5) },
      { имя: 'движок', дело: никогда() },
    ], 60)).toEqual(['движок']);
  });

  it('не ответил никто — названы все', async () => {
    expect(await ждатьНеДольше([
      { имя: 'облако', дело: никогда() },
      { имя: 'движок', дело: никогда() },
    ], 40)).toEqual(['облако', 'движок']);
  });

  /* Отказ — это ответ. Упавший запрос экран не держит, и виновником молчания не является:
     иначе в журнал попадали бы имена тех, кто честно ответил «не смог». */
  it('отказ считается ответом, а не молчанием', async () => {
    expect(await ждатьНеДольше([
      { имя: 'облако', дело: Promise.reject(new Error('нет сети')) },
    ], 60)).toEqual([]);
  });

  /* МИНИМУМ ПОКАЗА — отдельно от ожидания. Владелец: «мне нужно понимание что не зависли».
     Быстрый ответ не должен превращать спинер во вспышку, а долгий — в неподвижный экран. */
  it('минимум показа держит жест, даже когда ответ уже готов', async () => {
    const начало = Date.now();
    await Promise.all([
      ждатьНеДольше([{ имя: 'облако', дело: Promise.resolve(1) }], 1000),
      пауза(120),
    ]);
    expect(Date.now() - начало).toBeGreaterThanOrEqual(110);
  });

  /* Возврат не должен ждать срока, если все ответили раньше: иначе каждый жест висел бы
     восемь секунд даже при мгновенном ответе. */
  it('возвращается сразу, а не по сроку', async () => {
    const начало = Date.now();
    await ждатьНеДольше([{ имя: 'облако', дело: скоро(1, 5) }], 1000);
    expect(Date.now() - начало).toBeLessThan(500);
  });
});
