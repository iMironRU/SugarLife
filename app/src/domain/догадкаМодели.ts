import type { UiSnapshot } from '@/sources/bridge';
import { PUMPS, SENSORS } from './catalog';
import { устройствоРоли } from './deviceState';

/* ДВИЖОК УЖЕ ПОНЯЛ, ЧТО ЭТО ЗА ЖЕЛЕЗКА (SugarLife#485).

   При подключении он знает `driverId` — чем прибор читается — и `model`: понятное имя от драйвера,
   «Medtronic 722». А наш справочник об этом не спрашивает: человек открывает «Модель» и ищет в списке
   из шестидесяти девяти помп ту, которую приложение уже держит в руках.

   ПРЕДЛОЖИТЬ, А НЕ ВЫБРАТЬ ЗА ЧЕЛОВЕКА. Семейство драйвера — это не модель: у одного `medtronic` в
   справочнике десяток строк с разной ёмкостью резервуара, и разницу знает только человек. Модель у нас
   определяет резервуар и спецификации, поэтому молчаливая запись означала бы враньё в прогнозе «на
   сколько хватит» — и человек об этом не узнал бы.

   ДВЕ ДОГАДКИ, НЕ БОЛЬШЕ. Список подсказок длиннее двух — это уже второй справочник поверх первого;
   тогда честнее открыть настоящий. */

export interface Догадка {
  id: string;
  имя: string;
  /** Имя, которым назвался сам прибор. Показывать обязательно: это и есть основание догадки. */
  какНазвался: string;
  /** Совпало точно, а не «похоже». Такую можно предлагать первой кнопкой. */
  точно: boolean;
}

/* Сравниваем по числам и буквам отдельно.
   «Paradigm 522/722» и «Medtronic 722» совпадают именно числом, а «MiniMed 780G» и «MiniMed 770G» —
   почти всем, кроме числа, и перепутать их нельзя: у них разный резервуар. */
const числа = (s: string) => (s.match(/\d+/g) ?? []).filter((n) => n.length >= 2);
const буквы = (s: string) => s.toLowerCase().replace(/[^a-zа-яё]+/gi, ' ').trim().split(/\s+/).filter(Boolean);

function похожесть(имяДвижка: string, имяСправочника: string): number {
  const чД = числа(имяДвижка), чС = числа(имяСправочника);
  const бД = буквы(имяДвижка), бС = буквы(имяСправочника);
  const общиеЧисла = чД.filter((n) => чС.includes(n)).length;
  const общиеБуквы = бД.filter((w) => бС.includes(w)).length;
  /* Число весит больше слова: у «780G» и «770G» слова одинаковые целиком, и решает только оно.
     Числа при этом сравниваем как есть, без «похожих»: 722 и 723 — разные приборы. */
  return общиеЧисла * 10 + общиеБуквы;
}

/* Как назвался прибор слота и чем он читается. null — спрашивать не о чем.

   ТОЛЬКО СВОЙ ВИД И ТОЛЬКО С ДРАЙВЕРОМ. Слот помпы часто наполняет облако: активный источник роли —
   служба «Nightscout», у неё нет ни драйвера, ни модели. Первая версия брала её как «прибор» и
   предлагала помпу, похожую по буквам на слово Nightscout. Ошибка тихая и обидная: человек тапнул бы
   «это она» и получил чужой резервуар.

   Драйвера нет — догадки нет. Имя без драйвера это не факт, а строка: искать по ней в справочнике из
   шестидесяти девяти помп значит гадать, а гадание тут дороже молчания. */
function приборСлота(snap: UiSnapshot | null | undefined, вид: 'pump' | 'sensor') {
  const изРоли = устройствоРоли(snap, вид);
  const кандидаты = [
    изРоли,
    ...(snap?.devices ?? []),
    ...(snap?.hardware ?? []),
  ].filter((п): п is NonNullable<typeof п> => !!п && п.kind === вид)
    .map((п) => п as { driverId?: string | null; model?: string | null; name?: string | null; deviceModel?: string | null });
  for (const п of кандидаты) {
    if (!п.driverId) continue;
    return { driverId: п.driverId, имя: п.model || п.name || null, ужеЕсть: !!п.deviceModel };
  }
  return null;
}

/**
 * Что предложить вместо списка из 69.
 *
 * Пусто — предлагать нечего, и это законный ответ: движок молчит, драйвер незнаком справочнику или
 * модель уже выбрана. Пустая подсказка лучше выдуманной: неверная модель тише ошибки, но дороже.
 */
export function догадкаМодели(
  вид: 'pump' | 'sensor', snap: UiSnapshot | null | undefined, ужеВыбрано: string | null,
): Догадка[] {
  if (ужеВыбрано) return [];
  const прибор = приборСлота(snap, вид);
  if (!прибор) return [];

  const справочник = вид === 'pump'
    ? PUMPS.map((p) => ({ id: p.id, имя: p.model, ключ: p.driverKey }))
    : SENSORS.map((s) => ({ id: s.id, имя: s.name, ключ: s.driverKey }));

  /* Сужаем по СЕМЕЙСТВУ драйвера, а не по полному ключу.

     У движка `driverId` — семейство («medtronic»), у нас `driverKey` — модельный ключ
     («medtronic-522-722»), потому что резервуар и шаг базала у моделей одного драйвера разные.
     Сравнивать их напрямую значит не найти ничего никогда. */
  const семейство = (ключ: string) => ключ.split('-')[0].toLowerCase();
  const свои = справочник.filter((м) => м.ключ && семейство(м.ключ) === прибор.driverId.toLowerCase());
  if (!свои.length) return [];

  const имяДвижка = прибор.имя ?? '';
  const сОценкой = свои
    .map((м) => ({ ...м, вес: имяДвижка ? похожесть(имяДвижка, м.имя) : 0 }))
    .sort((а, б) => б.вес - а.вес || а.имя.localeCompare(б.имя));

  /* Единственная модель семейства — это уже ответ, а не догадка: гадать не из чего. */
  const единственная = свои.length === 1;
  const лучший = сОценкой[0];
  const второй = сОценкой[1];
  const точно = единственная || (лучший.вес >= 10 && (!второй || второй.вес < лучший.вес));

  const итог = [лучший, ...(второй && второй.вес > 0 && второй.вес === лучший.вес ? [второй] : [])];
  return итог.slice(0, 2).map((м) => ({
    id: м.id,
    имя: м.имя,
    какНазвался: имяДвижка || прибор.driverId,
    точно: точно && итог.length === 1,
  }));
}
