import type { Entry } from '@/sources/nightscout';
import type { Trend } from '@/sources/bridge';

/* Направление сахара: считаем сами, когда источник его не прислал (SugarLife#215).

   Раньше на этом месте стояло `direction || 'Flat'` — то есть при молчании источника мы
   рисовали прямую стрелку. Это утверждение, которого никто не делал: «сахар держится
   ровно» человек читает как разрешение не вмешиваться, а на самом деле мы просто не
   знали. Стрелку в круге видят чаще всех остальных цифр, и врать ей нельзя.

   Считать есть из чего: история глюкозы у нас своя, точки каждые пять минут. Наклон по
   ним — та же величина, которую считает сам сенсор, и пороги для стрелок в индустрии
   общие (консенсус по НМГ): ±1 мг/дл/мин — «ровно», дальше по одной ступени на каждый
   мг/дл/мин. В ммоль/л это ±0,055 на минуту.

   ПОЧЕМУ ТОЛЬКО СВОЙ РАСЧЁТ. Сначала мы брали слово источника, а считали лишь когда он
   молчал. Отказались сознательно: как считает чужой загрузчик — неизвестно. У разных
   сенсоров и релеев окно и сглаживание свои, часть проставляет 'Flat' по умолчанию, а
   часть не проставляет ничего. Стрелка, собранная из разных правил в зависимости от
   того, кто сегодня отдаёт данные, — это не одна стрелка, а несколько похожих.

   Наше правило одно и написано здесь: пятнадцать минут, регрессия, общие пороги. Оно
   может разойтись со стрелкой в родном приложении сенсора — и это честнее, чем
   показывать число, происхождение которого мы объяснить не можем.

   КОГДА МОЛЧИМ. Свежих точек мало или последняя старая — стрелки нет. Пятнадцать минут
   считаются по трём точкам; по одной точке «направление» — это фантазия, а по
   получасовой давности — рассказ о прошлом, выданный за настоящее. */

/** Окно, по которому считается наклон. Стандарт индустрии — четверть часа. */
export const ОКНО_МИН = 15;
/** Старше этого последняя точка — направления не показываем вовсе. */
export const СВЕЖЕСТЬ_МИН = 12;
/** Меньше этого точек в окне — не считаем. */
export const МИНИМУМ_ТОЧЕК = 3;

/* Пороги в ммоль/л за минуту. Переведены из общепринятых мг/дл/мин делением на 18,016 —
   и оставлены числами, а не выражением: так их видно глазами при сверке с документом. */
const СТУПЕНЬ = 0.0555; // 1 мг/дл/мин

/* Наклон по методу наименьших квадратов, ммоль/л за минуту.

   Не «последняя минус первая»: одна выскочившая точка на краю окна разворачивала бы
   стрелку целиком, а у сенсоров такие выбросы обычны. Регрессия по всем точкам окна
   даёт то же, что считает сам сенсор, и не пляшет от единичного шума. */
export function наклон(точки: Array<{ t: number; mmol: number }>): number | null {
  if (точки.length < 2) return null;
  const t0 = точки[0].t;
  const xs = точки.map((p) => (p.t - t0) / 60_000); // минуты
  const ys = точки.map((p) => p.mmol);
  const n = xs.length;
  const сумX = xs.reduce((a, b) => a + b, 0);
  const сумY = ys.reduce((a, b) => a + b, 0);
  const сумXY = xs.reduce((a, x, i) => a + x * ys[i], 0);
  const сумXX = xs.reduce((a, x) => a + x * x, 0);
  const знаменатель = n * сумXX - сумX * сумX;
  if (Math.abs(знаменатель) < 1e-9) return null; // все точки в одно время
  return (n * сумXY - сумX * сумY) / знаменатель;
}

/** Наклон → слово контракта. Пороги те же, что у сенсоров: по ступени на мг/дл/мин. */
export function стрелкаПоНаклону(наклонМмольМин: number): Trend {
  const k = наклонМмольМин;
  if (k >= 3 * СТУПЕНЬ) return 'RisingRapidly';
  if (k >= 2 * СТУПЕНЬ) return 'Rising';
  if (k >= 1 * СТУПЕНЬ) return 'RisingSlowly';
  if (k <= -3 * СТУПЕНЬ) return 'FallingRapidly';
  if (k <= -2 * СТУПЕНЬ) return 'Falling';
  if (k <= -1 * СТУПЕНЬ) return 'FallingSlowly';
  return 'Stable';
}

/* Направление по нашей истории. Возвращает 'Unknown', когда считать не из чего — и это
   ответ, а не отговорка: пустая стрелка честнее прямой. */
export function направлениеПоИстории(
  entries: Entry[], сейчас = Date.now(), окноМин = ОКНО_МИН,
): Trend {
  if (!entries.length) return 'Unknown';
  const последняя = entries[entries.length - 1];
  if (сейчас - последняя.t > СВЕЖЕСТЬ_МИН * 60_000) return 'Unknown';
  const окно = entries.filter((e) => последняя.t - e.t <= окноМин * 60_000);
  if (окно.length < МИНИМУМ_ТОЧЕК) return 'Unknown';
  const k = наклон(окно);
  return k == null ? 'Unknown' : стрелкаПоНаклону(k);
}

/* Стрелки одной таблицей на всё приложение. Их было две — по словам контракта в панели
   и по кодам Nightscout в сторе, — и вели они себя по-разному при неизвестном
   направлении: одна не показывала ничего, вторая рисовала «ровно». */
export const СТРЕЛКА: Record<Trend, string> = {
  RisingRapidly: '⇈', Rising: '↑', RisingSlowly: '↗', Stable: '→',
  FallingSlowly: '↘', Falling: '↓', FallingRapidly: '⇊',
  /* Оба «не знаю» — пустые. В контракте их два: Unknown от драйвера и прочерк от
     старого моста; для человека это одно и то же, и рисовать в этом месте нечего. */
  Unknown: '', '—': '',
};

/** Коды Nightscout → слова контракта. Пусто/неизвестное — честное 'Unknown'. */
export function изНаправленияNS(dir: string | null | undefined): Trend {
  switch (dir) {
    case 'DoubleUp': return 'RisingRapidly';
    case 'SingleUp': return 'Rising';
    case 'FortyFiveUp': return 'RisingSlowly';
    case 'Flat': return 'Stable';
    case 'FortyFiveDown': return 'FallingSlowly';
    case 'SingleDown': return 'Falling';
    case 'DoubleDown': return 'FallingRapidly';
    default: return 'Unknown';
  }
}

/* Направление для показа — всегда наш расчёт по истории.

   Слово источника здесь больше не участвует: см. «почему только свой расчёт» выше.
   Функция оставлена отдельно от направлениеПоИстории, потому что смысл разный: та
   считает по ряду точек, эта отвечает на вопрос «что показать человеку сейчас», и если
   правило когда-нибудь усложнится, менять надо будет её. */
export function направление(entries: Entry[], сейчас = Date.now()): Trend {
  return направлениеПоИстории(entries, сейчас);
}

/* Падает ли сахар прямо сейчас — для решений, а не для показа (domain/foodNow.ts).
   Отдельно от стрелки, потому что вопрос другой: стрелке достаточно «вниз», а решению
   про быстрые углеводы важна и скорость. */
export function падает(entries: Entry[], сейчас = Date.now()): boolean {
  const t = направлениеПоИстории(entries, сейчас);
  return t === 'FallingSlowly' || t === 'Falling' || t === 'FallingRapidly';
}

/* Скорость словами — для тех мест, где важно «насколько быстро», а не только «куда».
   Ноль ступеней от «ровно» отличается: 0,3 ммоль за четверть часа перед сном значит
   совсем не то же, что 1,5. */
export function скоростьЗа15(entries: Entry[], сейчас = Date.now()): number | null {
  if (!entries.length) return null;
  const последняя = entries[entries.length - 1];
  if (сейчас - последняя.t > СВЕЖЕСТЬ_МИН * 60_000) return null;
  const окно = entries.filter((e) => последняя.t - e.t <= ОКНО_МИН * 60_000);
  if (окно.length < МИНИМУМ_ТОЧЕК) return null;
  const k = наклон(окно);
  return k == null ? null : k * ОКНО_МИН;
}
