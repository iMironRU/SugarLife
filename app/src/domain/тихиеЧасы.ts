/* Тихие часы (#418).

   Правило вынесено сюда и проверено тестом, хотя ночью его исполняет натив: правило одно
   на два языка, и разъехаться им нельзя. Здесь — то, по чему экран показывает «сейчас
   тихо»; там — то, по чему решают, звенеть ли. Пусть одинаковое хотя бы будет написано
   одинаково и проверено в одном месте.

   ГЛУШАТ ТОЛЬКО ВЫСОКИЙ. Низкий сахар ночью требует действий сейчас, и заглушённая
   тревога — не тревога. Ради этого исключения тихие часы вообще имеют право
   существовать: без него человек однажды выключил бы тревоги целиком. */
export const ТИХО_ВЫКЛ = -1;

export function тихоСейчас(час: number, с: number, до: number): boolean {
  if (с === ТИХО_ВЫКЛ || до === ТИХО_ВЫКЛ || с === до) return false;
  /* Окно почти всегда переходит через полночь — их для того и заводят. Наивное «час между
     началом и концом» здесь молчало бы всю ночь и звенело весь день. */
  return с < до ? час >= с && час < до : час >= с || час < до;
}
