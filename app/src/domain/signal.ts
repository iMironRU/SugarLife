/* Уровень сигнала — словами.

   Дециблы человеку ничего не говорят. У этой цифры одно практическое применение:
   понять, та ли это железка, которую ты держишь в руке, — и на этот вопрос отвечают
   слова «рядом» и «далеко», а не «−73 дБм».

   Границы взяты по здравому смыслу BLE-адвертайзинга: около −60 это вытянутая рука,
   около −80 — соседняя комната. Точность тут не нужна и вредна: обещать по RSSI
   расстояние нельзя, оно зависит от тела, кармана и стен. */
export function близость(rssi: number | null | undefined): string | undefined {
  if (rssi == null || !Number.isFinite(rssi)) return undefined;
  if (rssi >= -60) return 'рядом';
  if (rssi >= -80) return 'недалеко';
  return 'далеко';
}
