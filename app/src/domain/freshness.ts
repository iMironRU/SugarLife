import type { HardwareView } from '@/sources/bridge';

/* «На связи», а данных нет (SugarLife#305).

   Строка прибора отвечала на вопрос про КАНАЛ, а человек читает её как ответ про
   ПРИБОР. «Sibionics GS1 — на связи», и в ту же минуту сверху «7 мин» с растущим
   возрастом: связь жива, показаний нет. Человек видит «на связи» и идёт снимать и
   переставлять сенсор, потому что искать причину ему негде.

   ПОРОГ НЕ СЧИТАЕМ САМИ. Ядро уже считает его по типу прибора: сенсор шлёт раз в пять
   минут, помпа за мостом отвечает реже, и её молчание нормально. Ответ лежит в
   `status`: Delayed — «связь есть, данных нет дольше нормы». Свой порог здесь означал
   бы второе мнение о том же, а два мнения о молчании прибора разойдутся в первый же
   день (SugarLifeCore, мост 1.18).

   СКОЛЬКО ИМЕННО — из `latestAtMs`, и это отдельное от `nearbyAtMs` поле: реклама в
   эфире не значит, что прибор что-то сказал.

   ПРОГРЕВ — НЕ ЗАДЕРЖКА. Connecting при живой связи значит «сенсор ещё ни разу ничего
   не сказал»: он греется после установки, и это ожидание, а не поломка. Сказать здесь
   «данных нет 7 мин» — назвать нормальную работу неисправностью, а такие сообщения
   быстро перестают читать вместе со всеми остальными. */

export function молчитЛи(h: Pick<HardwareView, 'status'>): boolean {
  return h.status === 'Delayed';
}

/* Длительность, а не момент. «данных нет 7 мин назад» — не по-русски и не про то:
   вопрос не «когда было последнее», а «сколько уже нет». Поэтому своё слово, а не
   agoText, который отвечает на первый вопрос и нужен в других местах. */
export function сколькоНет(мс: number): string {
  const м = Math.max(0, Math.round(мс / 60000));
  if (м < 60) return `${м} мин`;
  const ч = Math.floor(м / 60);
  return `${ч} ч`;
}

/** Подпись про свежесть; null — говорить нечего, состояние скажет обычная метка. */
export function подписьСвежести(
  h: Pick<HardwareView, 'status' | 'latestAtMs'>, сейчасМс: number,
): string | null {
  if (h.status === 'Connecting') return 'ждём первое показание';
  if (h.status !== 'Delayed') return null;
  /* Задержка есть, а времени нет — так бывает у прибора, который не сообщал ничего с
     самого старта. Говорим о факте, не выдумывая числа. */
  if (h.latestAtMs == null) return 'на связи, данных нет';
  return `на связи, данных нет ${сколькоНет(сейчасМс - h.latestAtMs)}`;
}
