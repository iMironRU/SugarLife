import type { HardwareView } from '@/sources/bridge';

/* «На связи», а данных нет (SugarLife#305).

   Строка прибора отвечала на вопрос про КАНАЛ, а человек читает её как ответ про
   ПРИБОР. «Sibionics GS1 — на связи», и в ту же минуту сверху «7 мин» с растущим
   возрастом: связь жива, показаний нет. Человек видит «на связи» и идёт снимать и
   переставлять сенсор, потому что искать причину ему негде.

   ПОРОГ НЕ СЧИТАЕМ САМИ. Ядро уже считает его по типу прибора: сенсор шлёт раз в пять
   минут, помпа за мостом отвечает реже, и её молчание нормально. Ответ лежит в
   `status`: Delayed — «связь есть, данных нет дольше нормы». Свой порог здесь означал
   бы второе мнение о том же, а два мнения о молчании прибора разойдутся в первый же
   день (SugarLifeCore, мост 1.18).

   СКОЛЬКО ИМЕННО — из `latestAtMs`, и это отдельное от `nearbyAtMs` поле: реклама в
   эфире не значит, что прибор что-то сказал.

   ПРОГРЕВ — НЕ ЗАДЕРЖКА. Connecting при живой связи значит «сенсор ещё ни разу ничего
   не сказал»: он греется после установки, и это ожидание, а не поломка. Сказать здесь
   «данных нет 7 мин» — назвать нормальную работу неисправностью, а такие сообщения
   быстро перестают читать вместе со всеми остальными. */

export function молчитЛи(h: Pick<HardwareView, 'status'>): boolean {
  return h.status === 'Delayed';
}

/* ЧТО со свежестью — состояние, а не подпись (#324). Слова живут в слова/приборы.ts.

   `null` — говорить нечего, состояние скажет обычная метка связи.
   `прогрев` — сенсор ещё ни разу ничего не сказал, это ожидание, а не поломка.
   `молчит` — связь есть, данных нет дольше нормы; `мс` пусто, когда прибор не сообщал
   ничего с самого старта: факт есть, числа нет, и выдумывать его нельзя. */
export type Свежесть =
  | { вид: 'прогрев' }
  | { вид: 'молчит'; мс: number | null }
  | null;

export function свежесть(
  h: Pick<HardwareView, 'status' | 'latestAtMs'>, сейчасМс: number,
): Свежесть {
  if (h.status === 'Connecting') return { вид: 'прогрев' };
  if (h.status !== 'Delayed') return null;
  return { вид: 'молчит', мс: h.latestAtMs == null ? null : сейчасМс - h.latestAtMs };
}

/* Чем прибор занят и чего ему не хватает — одной строкой (мост 1.22/1.24).

   Порядок ответов не косметика, а очерёдность вопросов у человека, который смотрит на
   молчащий прибор.

   ПЕРВОЕ — «не настроен». Это не поломка связи, а незаданный вопрос: движок такой прибор
   не поднимает вовсе, и любые слова про связь были бы про то, чего не происходит.

   ВТОРОЕ — «чем занят». Подбор частоты у помпы идёт минутами, и всё это время статус
   говорил «устройство не отвечает». Прибор работал. Долгая работа без признака работы
   неотличима от поломки — и чинят то, что не сломано.

   И только потом — обычные слова о связи. */
export type Занятие =
  /* Заметку и ход работы присылает движок — это его слова, и переводить их нам нечем:
     он один знает, чего именно не хватает и что сейчас делает. Пустая заметка — наш
     случай, и подпись к нему живёт в слое слов. */
  | { вид: 'неНастроен'; заметка: string | null }
  /* `доля` — 0..100, если движок её знает. `null` — не знает, и тогда полосы НЕТ.

     Подбор частоты помпы идёт по списку, где заранее не сказать, на какой попытке отзовётся
     прибор: полоса, ползущая в никуда, врёт хуже, чем честные слова. А вот добор истории
     сенсора длится минуты и долю знает — там она и нужна (ядро #86, доехало в мосте 1.66). */
  | { вид: 'занят'; чем: string; доля: number | null }
  | null;

export function чтоСПрибором(
  d: {
    registryState?: string | null; note?: string | null;
    progress?: string | null; progressPercent?: number | null;
  } | null | undefined,
): Занятие {
  if (!d) return null;
  if (d.registryState === 'NotConfigured') return { вид: 'неНастроен', заметка: d.note?.trim() || null };
  const ход = d.progress?.trim();
  if (!ход) return null;
  /* Границы обрезаем сами: полоса на 103 % или на −1 читается как поломка, а движок числа не
     обещал выверенными — он обещал долю. */
  const п = d.progressPercent;
  const доля = typeof п === 'number' && Number.isFinite(п) ? Math.max(0, Math.min(100, Math.round(п))) : null;
  return { вид: 'занят', чем: ход, доля };
}
