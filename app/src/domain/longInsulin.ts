import type { UiSnapshot } from '@/sources/bridge';

/* Длинный инсулин — ОТДЕЛЬНО от активного (SugarLife#287, контракт 1.15).

   Сложив 24 ед Туджео с 4 ед короткого, мы показали бы 28 «активных». Человек либо
   испугается числа, либо недооценит короткий на его фоне — а по этому числу решают, колоть
   ли ещё. Поэтому длинный никогда не входит в активный и живёт своей строкой, фоном.

   СРОК НЕ ВЫДУМЫВАЕМ. `longActingUntilMs` приходит, только если человек задал длительность
   СВОЕГО инсулина: у Тресибы 42 часа, у Лантуса 24, у Туджео больше суток и зависит от
   дозы. Подставить «типичное» значит сказать за него то, чего он не говорил, — и ошибиться
   ровно в тот момент, когда он проверяет, действует ли ещё вчерашний укол.

   ЗАКОНЧИВШИЙСЯ НЕ ПРЯЧЕМ, но и не выдаём за действующий: «был вчера в 22:10» — это ответ,
   а молчание — нет. Человек на ручках приходит сюда именно с вопросом «я вообще колол?». */

/** Сколько держим на экране укол, о длительности которого нам ничего не сказали. */
export const БЕЗ_СРОКА_МС = 36 * 3600e3;

export interface Фон {
  ед: number;
  когдаМс: number;
  /** Известный срок окончания; null — длительность не задана. */
  доМс: number | null;
  /** Действует ли ещё по известному сроку. null — срока нет, утверждать нечего. */
  действует: boolean | null;
}

export function фонИнсулина(
  snap: UiSnapshot | null | undefined, сейчас: number,
): Фон | null {
  const m = snap?.monitor;
  const ед = m?.longActingUnits;
  const когда = m?.longActingAtMs;
  if (ед == null || !Number.isFinite(ед) || ед <= 0 || когда == null) return null;

  const до = m?.longActingUntilMs ?? null;
  /* Без срока укол не может висеть вечно: сутки с лишним — предел, после которого
     «вчерашний длинный» перестаёт быть ответом на вопрос «что у меня сейчас». */
  if (до == null && сейчас - когда > БЕЗ_СРОКА_МС) return null;
  return { ед, когдаМс: когда, доМс: до, действует: до == null ? null : сейчас < до };
}

