/* Как назвать приём: завтрак, обед, полдник, перекус, поздний ужин (SugarLife#381).

   В журнале стояло «Перекус» у любой записи, потому что тип брался только по часу. А
   человек различает приёмы иначе: сорок граммов в час дня — обед, пятнадцать граммов в
   час дня — перекус между делами. Размер здесь значит не меньше времени.

   ЭТО ДОГАДКА О ЧУЖОЙ ЖИЗНИ, и относиться к ней надо соответственно. У работающего в
   ночь «завтрак» в восемь вечера; у того, кто ест два раза в день, полдника нет вовсе.
   Поэтому подпись правится одним касанием и НИКОГДА не участвует в расчётах: доза
   считается от граммов и времени, а не от того, как мы назвали приём. Иначе получится
   умное приложение, которое спорит с человеком о том, что он ел.

   Пороги — вещь, которую правят по живым данным, поэтому они здесь, под тестами, а не
   в разметке. */

export const ВИДЫ = ['Завтрак', 'Обед', 'Полдник', 'Ужин', 'Поздний ужин', 'Перекус', 'Ночной перекус'] as const;
export type ВидПриёма = (typeof ВИДЫ)[number];

/* Граница между «поел» и «перехватил». Двадцать граммов — примерно бутерброд или банан:
   меньше этого приёмом пищи не называют, сколько бы времени ни было на часах. */
export const ПЕРЕКУС_ДО_Г = 20;

export function имяПриёма(часЕды: number, граммы: number): ВидПриёма {
  const ночь = часЕды >= 23 || часЕды < 5;
  /* Маленькая порция — перекус в любое время. Ночью говорим об этом прямо: ночная еда
     чаще всего купирование гипо, и путать её с ужином не стоит — в разборе это разные
     события. */
  if (граммы > 0 && граммы < ПЕРЕКУС_ДО_Г) return ночь ? 'Ночной перекус' : 'Перекус';
  if (ночь) return 'Поздний ужин';
  if (часЕды < 11) return 'Завтрак';
  if (часЕды < 15) return 'Обед';
  /* Полдник — только для того, что между обедом и ужином и невелико. Полноценная еда в
     четыре часа дня для многих и есть обед, поэтому граница по размеру, а не по часу. */
  if (часЕды < 17) return граммы < 35 ? 'Полдник' : 'Обед';
  if (часЕды < 22) return 'Ужин';
  return 'Поздний ужин';
}

/* Что показать в строке журнала. Имя, данное человеком (#122), главнее нашей догадки:
   он назвал это блюдо сам, и подменять его «обедом» — спорить с ним о его же еде. */
export function подписьПриёма(
  { имя, kind, часЕды, граммы }:
  { имя?: string | null; kind?: string | null; часЕды: number; граммы: number },
): { главное: string; уточнение: string | null } {
  const вид = имяПриёма(часЕды, граммы);
  if (имя?.trim()) return { главное: имя.trim(), уточнение: вид.toLowerCase() };
  /* Тип, выбранный человеком руками, тоже главнее догадки — но только если он не
     совпадает с ней дословно, иначе получим «Обед · обед». */
  if (kind?.trim() && kind.trim() !== вид) return { главное: kind.trim(), уточнение: null };
  return { главное: вид, уточнение: null };
}
