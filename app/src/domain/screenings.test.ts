import { describe, it, expect } from 'vitest';
import { состояние, месяцевНазад, поВажности, ПРОВЕРКИ, ЗАРАНЕЕ_ДНЕЙ } from './screenings';

/* Сроки проверок держим тестами не ради арифметики, а ради границ между состояниями.
   Ошибка здесь выглядит убедительно: строка есть, дата есть, цвет есть — и он врёт.
   Человек либо идёт сдавать анализ, который сдавать не время, либо спокойно живёт с
   просроченным скринингом, потому что приложение сказало «в сроке». */

const МЕС = 30 * 24 * 3_600_000;
const СЕЙЧАС = new Date(2026, 7, 13).getTime();
const назад = (мес: number) => СЕЙЧАС - мес * МЕС;
const глаза = ПРОВЕРКИ.find((p) => p.id === 'eyes')!;   // раз в год, но не раньше 5 лет
const hba1c = ПРОВЕРКИ.find((p) => p.id === 'hba1c')!;  // раз в 3 месяца

describe('состояние плановой проверки', () => {
  it('прошло меньше срока — в сроке', () => {
    expect(состояние(назад(1), hba1c, СЕЙЧАС)).toBe('в сроке');
  });

  it('срок вышел — просрочено', () => {
    expect(состояние(назад(4), hba1c, СЕЙЧАС)).toBe('просрочено');
  });

  /* «Скоро» существует ради записи к врачу: узнать, что срок вышел вчера, поздно —
     талона на сегодня всё равно нет. */
  it('до срока меньше месяца — скоро', () => {
    const почти = СЕЙЧАС - 3 * МЕС + (ЗАРАНЕЕ_ДНЕЙ - 5) * 24 * 3_600_000;
    expect(состояние(почти, hba1c, СЕЙЧАС)).toBe('скоро');
  });

  /* Пустая база — не долг человека. Восемь красных строк за то, что он не помнит дату
     прошлогодней ЭКГ, — это мы пугаем его своей пустотой. */
  it('даты нет — «нет данных», а не «просрочено»', () => {
    expect(состояние(null, hba1c, СЕЙЧАС)).toBe('нет данных');
    expect(состояние(undefined, hba1c, СЕЙЧАС)).toBe('нет данных');
  });

  /* Часть проверок по документу начинается через пять лет от дебюта. Требовать их
     раньше — спорить с рекомендацией, на которую же и ссылаемся. */
  it('первые пять лет от дебюта — «ещё рано» для глаз и почек', () => {
    const дебютГодНазад = СЕЙЧАС - 12 * МЕС;
    expect(состояние(null, глаза, СЕЙЧАС, дебютГодНазад)).toBe('ещё рано');
  });

  it('после пяти лет от дебюта — обычное «нет данных»', () => {
    const дебют6ЛетНазад = СЕЙЧАС - 6 * 12 * МЕС;
    expect(состояние(null, глаза, СЕЙЧАС, дебют6ЛетНазад)).toBe('нет данных');
  });

  /* Если проверку уже делали, срок дебюта больше ничего не решает: раз сдавали —
     значит, время пришло, и дальше считаем от последней даты. */
  it('уже делали — считаем от последней даты, а не от дебюта', () => {
    const дебютГодНазад = СЕЙЧАС - 12 * МЕС;
    expect(состояние(назад(14), глаза, СЕЙЧАС, дебютГодНазад)).toBe('просрочено');
  });
});

describe('сколько прошло', () => {
  it('считаем в месяцах, вниз — «был 14 месяцев назад» точнее «больше года»', () => {
    expect(месяцевНазад(назад(14), СЕЙЧАС)).toBe(14);
    expect(месяцевНазад(СЕЙЧАС, СЕЙЧАС)).toBe(0);
  });
});

describe('порядок в записке', () => {
  /* Порядок — это и есть половина пользы: врач и человек читают сверху, и то, что
     требует действия, обязано стоять первым. */
  it('сначала просроченное, потом «скоро», потом неизвестное', () => {
    const список = поВажности({ hba1c: назад(4), ecg: назад(11.5), feet: назад(1) }, СЕЙЧАС);
    expect(список[0].проверка.id).toBe('hba1c');       // просрочено
    expect(список[1].проверка.id).toBe('ecg');         // скоро: до года осталось полмесяца
    expect(список.at(-1)!.состояние).not.toBe('просрочено');
  });

  it('в списке все проверки из рекомендаций, ни одна не теряется', () => {
    expect(поВажности({}, СЕЙЧАС)).toHaveLength(ПРОВЕРКИ.length);
  });
});
