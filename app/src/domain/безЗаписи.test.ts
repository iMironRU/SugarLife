import { describe, it, expect } from 'vitest';
import { разборБезЗаписи, частьСуток } from './безЗаписи';

const вЧас = (ч: number, rise = 3) => {
  const д = new Date(2026, 7, 20, ч, 0, 0);
  return { at: д.getTime(), rise };
};

describe('часть суток', () => {
  it('ночь отделена от утра — у ночного подъёма причины другие', () => {
    expect(частьСуток(вЧас(3).at)).toBe('ночь');
    expect(частьСуток(вЧас(7).at)).toBe('утро');
    expect(частьСуток(вЧас(14).at)).toBe('день');
    expect(частьСуток(вЧас(21).at)).toBe('вечер');
  });
});

describe('разбор подъёмов без записи', () => {
  it('пусто — ноль, а не выдумки', () => {
    const р = разборБезЗаписи([], 14);
    expect(р.всего).toBe(0);
    expect(р.преобладает).toBe(null);
    expect(р.типичныйПодъём).toBe(0);
  });

  it('считает в день по длине окна, а не по числу дней с событиями', () => {
    expect(разборБезЗаписи([вЧас(3), вЧас(4), вЧас(5), вЧас(6), вЧас(7), вЧас(8), вЧас(9)], 14).вДень).toBe(0.5);
  });

  /* Больше половины, а не «чаще других»: три ночью и два утром — это разброс, а не
     закономерность, и объявлять его закономерностью значит придумать её за человека. */
  it('преобладание — только когда больше половины', () => {
    expect(разборБезЗаписи([вЧас(2), вЧас(3), вЧас(4)], 7).преобладает).toBe('ночь');
    expect(разборБезЗаписи([вЧас(2), вЧас(3), вЧас(8), вЧас(14)], 7).преобладает).toBe(null);
  });

  /* Медиана, а не среднее: один выброс в +9 сдвинул бы среднее и назвал бы типичным
     то, что случилось однажды. */
  it('типичная величина — медиана', () => {
    expect(разборБезЗаписи([вЧас(2, 2.5), вЧас(3, 3.0), вЧас(4, 9.0)], 7).типичныйПодъём).toBe(3);
  });
});
