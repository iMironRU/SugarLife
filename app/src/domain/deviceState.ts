import type { DeviceView, UiSnapshot } from '@/sources/bridge';

/* Состояние связи устройства — одно правило на всё приложение.

   Симптом, с которого началось (SugarLifeCore#19): экран устройств показывает «на
   связи», а «Сегодня» об этом молчит. Причина не в разметке — источников состояния
   было три: Nightscout-стор на главном, снимок движка в карточке устройства и
   реестр моделей в localStorage. Три источника всегда рано или поздно расходятся,
   и человек видит два разных ответа на один вопрос «работает ли сейчас».

   Правда о связи — у движка: он один знает, что происходит с линком и с потоком
   данных. Nightscout-стор остаётся источником ДАННЫХ (история, лечение, резервуар),
   но не источником состояния: он знает только про свой сокет.

   Здесь — перевод снимка в то немногое, что нужно интерфейсу. Своего знания у
   модуля нет: он ничего не додумывает и не хранит, только выбирает поле и
   сокращает словарь движка до четырёх состояний.

   Почему именно четырёх. «Подключаюсь» и «связь есть, показаний ещё нет» для
   человека — одно ожидание, и рисовать их по-разному значит требовать, чтобы он
   знал устройство протокола. А вот «нет данных» и «не знаю, есть ли связь» — разные,
   и слить их нельзя: старый мост состояния не присылает, и молчание надо показывать
   как молчание, а не как обрыв. */

export type Связь = 'live' | 'wait' | 'off' | 'unknown';

/* Приоритет полей: status → live → connection.

   status (SourceStatus) — жизненный цикл получения данных, он и отвечает на вопрос
   «работает ли». connection (Link) — только состояние линка, и он слабее: сенсор
   бывает Connected и при этом Acquiring, то есть связь есть, а показаний нет. Начни
   мы с connection — получили бы зелёную точку у молчащего сенсора, ровно то враньё,
   от которого уходили в круге с активным инсулином. */
export function связь(d: DeviceView | null | undefined): Связь {
  if (!d) return 'unknown';
  switch (d.status) {
    case 'Live': return 'live';
    case 'Acquiring': case 'Connecting': return 'wait';
    /* Delayed — связь есть, но свежего нет. Для точки это ожидание, а не жизнь:
       зелёный на отставшем источнике читается как «данные идут прямо сейчас». */
    case 'Delayed': return 'wait';
    case 'Disconnected': return 'off';
    default: break;
  }
  if (d.live === true) return 'live';
  switch (d.connection) {
    case 'Streaming': case 'Connected': return 'live';
    case 'Connecting': return 'wait';
    case 'Disconnected': case 'Error': return 'off';
    default: return 'unknown';
  }
}

/* Кого считать источником глюкозы. Роль берём из снимка, а не гадаем по виду:
   помпа — тоже kind-устройство, но сахар не отдаёт, а Nightscout отдаёт, будучи
   сервисом.

   Порядок предпочтения: primary → железка → что нашлось. primary впереди всех,
   потому что именно на него смотрит монитор. Без него сенсор идёт вперёд сервиса:
   в списке рядом могут стоять сенсор и облачный поток, и «первый попавшийся» зависел
   бы от порядка устройств в снимке — то есть от того, что нам никто не обещал. */
export function источникГлюкозы(snap: UiSnapshot | null | undefined): DeviceView | null {
  const все = (snap?.devices ?? []).filter(
    (d) => d.kind === 'sensor' || (d.roles ?? []).includes('GlucoseSource'),
  );
  return все.find((d) => d.primary) ?? все.find((d) => d.kind === 'sensor') ?? все[0] ?? null;
}

/* Помпа — только сама помпа, и это сложнее, чем kind === 'pump'.

   Метка отвечает на вопрос «на связи ли помпа». Живой Nightscout отвечает на другой —
   «жив ли облачный сокет»; помпа может молчать час, пока облако бодро отдаёт
   последний известный документ. Смешать эти два ответа значит вернуть ровно то
   враньё, из-за которого задача #19 и появилась.

   Одного kind для различения не хватало: движок метил вид ПО РОЛЯМ, и облачный
   источник состояния помпы приезжал на нативе тоже как kind: 'pump' (предупреждение
   ядра в SugarLifeCore#19). С коммитом 08c8e94 они это изменили — облачные источники
   теперь kind: 'service', и одна проверка вида уже отсекла бы облако.

   Проверку ниже всё равно оставляем, и не из недоверия: устройство бывает
   многоканальным, и «помпа с активным облачным каналом» — это по-прежнему kind
   'pump', про прямую связь с которым мы ничего не знаем. Вид отвечает на вопрос «кто
   это», каналы — на вопрос «как мы об этом узнаём», и второй вопрос никуда не делся.

   Различаем в два шага, от точного к запасному:

   1. Каналы (rev 1.8, #23). Движок прямо говорит, чем достижимо устройство и какой
      канал сейчас активен. Это буквальный ответ, а не признак.
   2. driverId. У облачного источника его нет, у настоящей BLE-помпы — id драйвера.
      Записанная-без-модели помпа тоже придёт без driverId, но она Disconnected и под
      «на связи» не попадёт.

   Обе проверки — на снимке; своего знания о том, какие бывают помпы, здесь нет. */
export function источникПомпы(snap: UiSnapshot | null | undefined): DeviceView | null {
  const помпы = (snap?.devices ?? []).find((d) => d.kind === 'pump' && !толькоОблако(d));
  return помпы ?? null;
}

/* Состояние приезжает только облаком. Отдельной функцией, потому что вопрос ещё
   вернётся: карточке помпы каналы нужно будет показать списком, и «через облако,
   N мин» — такая же честная строка, как «напрямую». */
export function толькоОблако(d: DeviceView): boolean {
  const каналы = d.channels ?? [];
  if (каналы.length) {
    const активный = каналы.find((c) => c.id === d.activeChannel) ?? каналы[0];
    return активный.kind === 'cloud';
  }
  return d.driverId == null;
}

/* Железки этого вида — те, которые действительно наши, без облачных потоков.

   Вынесено из карточки устройства и покрыто тестом не ради красоты. Это список, по
   которому уходит removeDevice, а ядро подтвердило (SugarLifeCore#26), что удаление
   облачного источника не игнорируется: движок снимет его и положит в tombstone —
   приём данных из Nightscout выключится и сам не вернётся даже после перезапуска.

   То есть ошибка в этом фильтре не «покажет лишнее», а тихо выключит человеку
   мониторинг по кнопке «забыть помпу». Такие места держат тестом. */
export function своиЖелезки(
  snap: UiSnapshot | null | undefined, вид: DeviceView['kind'],
): DeviceView[] {
  return (snap?.devices ?? []).filter((d) => d.kind === вид && !толькоОблако(d));
}

/* Состояние источника глюкозы для панели.

   Монитор — это вычисление движка по основному источнику, и пока devices[] и monitor
   считаются порознь (SugarLifeCore#22), поле устройства точнее: оно про конкретную
   железку. Монитор идёт запасным — он есть даже там, где устройство статуса не
   прислало. Оба из одного снимка, стор здесь не участвует ни в каком виде. */
export function связьГлюкозы(snap: UiSnapshot | null | undefined): Связь {
  const d = источникГлюкозы(snap);
  if (d?.status || d?.live != null) return связь(d);
  /* У устройства только линк — тогда монитор точнее: линк отвечает «соединение
     установлено», а вопрос стоит «идут ли данные». Ровно здесь Nightscout-шим и
     подставил бы зелёную точку молчащему источнику: сокет-то жив. */
  const m = snap?.monitor;
  if (m && (m.status || m.live != null)) {
    return связь({ status: m.status, live: m.live, connection: m.link } as DeviceView);
  }
  return связь(d);
}

/* Предложить слить облачный источник помпы с заведённой железкой (SugarLifeCore#23).

   Половину риска снимает сам факт, что предлагать приходится: движок сливает каналы
   САМ, когда Nightscout несёт серийник настроенной помпы. Если облачная помпа всё
   ещё отдельным устройством — значит серийника не было или он не совпал, и мы
   заведомо в неуверенном положении. Значит не гадаем, а показываем человеку строки.

   Отсюда два условия, и оба про честность, а не про удобство.

   ПЕРВОЕ: молчим, пока показать нечего. Без sourceLabel вопрос выродится в «у вас
   две помпы, это одна и та же?» — предложение подтвердить наше предположение, не
   имея ни одного факта. Человек скажет «да» из вежливости к интерфейсу, а сольются
   два разных устройства: общий Nightscout в семье, две помпы в доме — это не
   выдуманный случай.

   ВТОРОЕ: не предлагаем то, что уже слито. Устройство с облачным каналом внутри —
   это результат слияния, ручного или автоматического; спрашивать о нём заново
   значит предлагать переделать сделанное. */
export interface Слияние { облако: DeviceView; железка: DeviceView; серийник: string | null }

export function предложениеСлияния(snap: UiSnapshot | null | undefined): Слияние | null {
  const помпы = (snap?.devices ?? []).filter((d) => d.kind === 'pump');
  const облако = помпы.find((d) => толькоОблако(d) && !(d.channels ?? []).length);
  const железка = помпы.find((d) => !толькоОблако(d));
  if (!облако || !железка) return null;
  if ((железка.channels ?? []).some((c) => c.kind === 'cloud')) return null;
  if (!облако.sourceLabel) return null;
  return { облако, железка, серийник: серийникИз(железка.id) };
}

/* Серийник — суффикс идентификатора после двоеточия («medtronic-722:123456»).
   Разбираем здесь, а не в разметке: строка приходит от движка, и место, где мы
   делаем о ней предположение, должно быть одно и покрыто тестом. */
export function серийникИз(id: string): string | null {
  const i = id.indexOf(':');
  const хвост = i >= 0 ? id.slice(i + 1).trim() : '';
  return хвост || null;
}

/* Подпись для доступности и подсказки. Точка без имени — украшение: читалка экрана
   не видит цвета, а долгое нажатие ничего не объясняет. */
export const меткаСвязи: Record<Связь, string | null> = {
  live: 'на связи, данные идут',
  wait: 'подключается — данных пока нет',
  off: 'нет связи',
  unknown: null,
};
