import type { DeviceView, UiSnapshot } from '@/sources/bridge';

/* Состояние связи устройства — одно правило на всё приложение.

   Симптом, с которого началось (SugarLifeCore#19): экран устройств показывает «на
   связи», а «Сегодня» об этом молчит. Причина не в разметке — источников состояния
   было три: Nightscout-стор на главном, снимок движка в карточке устройства и
   реестр моделей в localStorage. Три источника всегда рано или поздно расходятся,
   и человек видит два разных ответа на один вопрос «работает ли сейчас».

   Правда о связи — у движка: он один знает, что происходит с линком и с потоком
   данных. Nightscout-стор остаётся источником ДАННЫХ (история, лечение, резервуар),
   но не источником состояния: он знает только про свой сокет.

   Здесь — перевод снимка в то немногое, что нужно интерфейсу. Своего знания у
   модуля нет: он ничего не додумывает и не хранит, только выбирает поле и
   сокращает словарь движка до четырёх состояний.

   Почему именно четырёх. «Подключаюсь» и «связь есть, показаний ещё нет» для
   человека — одно ожидание, и рисовать их по-разному значит требовать, чтобы он
   знал устройство протокола. А вот «нет данных» и «не знаю, есть ли связь» — разные,
   и слить их нельзя: старый мост состояния не присылает, и молчание надо показывать
   как молчание, а не как обрыв. */

export type Связь = 'live' | 'wait' | 'off' | 'unknown';

/* Приоритет полей: status → live → connection.

   status (SourceStatus) — жизненный цикл получения данных, он и отвечает на вопрос
   «работает ли». connection (Link) — только состояние линка, и он слабее: сенсор
   бывает Connected и при этом Acquiring, то есть связь есть, а показаний нет. Начни
   мы с connection — получили бы зелёную точку у молчащего сенсора, ровно то враньё,
   от которого уходили в круге с активным инсулином. */
export function связь(d: DeviceView | null | undefined): Связь {
  if (!d) return 'unknown';
  switch (d.status) {
    case 'Live': return 'live';
    case 'Acquiring': case 'Connecting': return 'wait';
    /* Delayed — связь есть, но свежего нет. Для точки это ожидание, а не жизнь:
       зелёный на отставшем источнике читается как «данные идут прямо сейчас». */
    case 'Delayed': return 'wait';
    case 'Disconnected': return 'off';
    default: break;
  }
  if (d.live === true) return 'live';
  switch (d.connection) {
    case 'Streaming': case 'Connected': return 'live';
    case 'Connecting': return 'wait';
    case 'Disconnected': case 'Error': return 'off';
    default: return 'unknown';
  }
}

/* Кого считать источником глюкозы. Роль берём из снимка, а не гадаем по виду:
   помпа — тоже kind-устройство, но сахар не отдаёт, а Nightscout отдаёт, будучи
   сервисом. primary впереди всех: при нескольких сенсорах монитор смотрит именно
   на него, и точка в панели должна говорить про него же. */
export function источникГлюкозы(snap: UiSnapshot | null | undefined): DeviceView | null {
  const все = (snap?.devices ?? []).filter(
    (d) => d.kind === 'sensor' || (d.roles ?? []).includes('GlucoseSource'),
  );
  return все.find((d) => d.primary) ?? все[0] ?? null;
}

/* Помпа — только сама помпа.

   Подставить сюда сервис с ролью PumpStateSource заманчиво: через Nightscout мы про
   помпу что-то знаем, значит вроде бы есть и связь. Но метка отвечает на вопрос «на
   связи ли помпа», а живой Nightscout отвечает на другой — «жив ли облачный сокет».
   Помпа может молчать час, пока облако бодро отдаёт последний известный документ, и
   зелёная точка сказала бы ровно то враньё, из-за которого задача и появилась.

   Заодно это то же правило, по которому карточку рисует DeviceSection (ищет
   kind === 'pump'). Экраны сходятся не потому, что мы их сверили, а потому что
   спрашивают одно и то же. Помпы в снимке нет — метки нет: про её связь мы честно
   ничего не знаем, а строка статуса над панелью и так говорит про облако. */
export function источникПомпы(snap: UiSnapshot | null | undefined): DeviceView | null {
  return (snap?.devices ?? []).find((d) => d.kind === 'pump') ?? null;
}

/* Состояние источника глюкозы для панели.

   Монитор — это вычисление движка по основному источнику, и пока devices[] и monitor
   считаются порознь (SugarLifeCore#22), поле устройства точнее: оно про конкретную
   железку. Монитор идёт запасным — он есть даже там, где устройство статуса не
   прислало. Оба из одного снимка, стор здесь не участвует ни в каком виде. */
export function связьГлюкозы(snap: UiSnapshot | null | undefined): Связь {
  const d = источникГлюкозы(snap);
  if (d?.status || d?.live != null) return связь(d);
  /* У устройства только линк — тогда монитор точнее: линк отвечает «соединение
     установлено», а вопрос стоит «идут ли данные». Ровно здесь Nightscout-шим и
     подставил бы зелёную точку молчащему источнику: сокет-то жив. */
  const m = snap?.monitor;
  if (m && (m.status || m.live != null)) {
    return связь({ status: m.status, live: m.live, connection: m.link } as DeviceView);
  }
  return связь(d);
}

/* Подпись для доступности и подсказки. Точка без имени — украшение: читалка экрана
   не видит цвета, а долгое нажатие ничего не объясняет. */
export const меткаСвязи: Record<Связь, string | null> = {
  live: 'на связи, данные идут',
  wait: 'подключается — данных пока нет',
  off: 'нет связи',
  unknown: null,
};
