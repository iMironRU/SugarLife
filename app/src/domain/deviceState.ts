import type { ChannelView, DeviceView, Link, RoleView, SourceStatus, UiSnapshot } from '@/sources/bridge';

/* Состояние связи устройства — одно правило на всё приложение.

   Симптом, с которого началось (SugarLifeCore#19): экран устройств показывает «на
   связи», а «Сегодня» об этом молчит. Причина не в разметке — источников состояния
   было три: Nightscout-стор на главном, снимок движка в карточке устройства и
   реестр моделей в localStorage. Три источника всегда рано или поздно расходятся,
   и человек видит два разных ответа на один вопрос «работает ли сейчас».

   Правда о связи — у движка: он один знает, что происходит с линком и с потоком
   данных. Nightscout-стор остаётся источником ДАННЫХ (история, лечение, резервуар),
   но не источником состояния: он знает только про свой сокет.

   Здесь — перевод снимка в то немногое, что нужно интерфейсу. Своего знания у
   модуля нет: он ничего не додумывает и не хранит, только выбирает поле и
   сокращает словарь движка до четырёх состояний.

   Почему именно четырёх. «Подключаюсь» и «связь есть, показаний ещё нет» для
   человека — одно ожидание, и рисовать их по-разному значит требовать, чтобы он
   знал устройство протокола. А вот «нет данных» и «не знаю, есть ли связь» — разные,
   и слить их нельзя: старый мост состояния не присылает, и молчание надо показывать
   как молчание, а не как обрыв. */

export type Связь = 'live' | 'wait' | 'off' | 'unknown';

/* Сколько показание считается «текущим» для круга. Тот же порог, что у выбора показания
   (domain/latestGlucose): два разных ответа на «свежее ли оно» были бы ровно тем
   рассинхроном, из которого выросла эта задача. */
export const ОТСТАВАНИЕ_КРУГА_МС = 15 * 60_000;

/* Приоритет полей: status → live → connection.

   status (SourceStatus) — жизненный цикл получения данных, он и отвечает на вопрос
   «работает ли». connection (Link) — только состояние линка, и он слабее: сенсор
   бывает Connected и при этом Acquiring, то есть связь есть, а показаний нет. Начни
   мы с connection — получили бы зелёную точку у молчащего сенсора, ровно то враньё,
   от которого уходили в круге с активным инсулином. */
/* Аргумент описан по форме, а не типом DeviceView: то же состояние приходит теперь и
   у железа из hardware[] (SugarLifeCore#44), и приводить одно к другому приведением
   типа значило бы врать компилятору там, где типы просто разные. */
export type ЧтоСоСвязью = {
  status?: SourceStatus | null;
  live?: boolean;
  connection?: Link | string;
};

export function связь(d: ЧтоСоСвязью | null | undefined): Связь {
  if (!d) return 'unknown';
  switch (d.status) {
    case 'Live': return 'live';
    case 'Acquiring': case 'Connecting': return 'wait';
    /* Delayed — связь есть, но свежего нет. Для точки это ожидание, а не жизнь:
       зелёный на отставшем источнике читается как «данные идут прямо сейчас». */
    case 'Delayed': return 'wait';
    case 'Disconnected': return 'off';
    /* Ручка читается прикосновением (rev ≥ 1.15): это не «нет связи» и не «ждём». Своего
       состояния заводить не стали — для точки и метки это «известно, но не поток»,
       ровно то же, что «unknown» уже и означает: не утверждать про связь ничего. */
    case 'ReadOnTouch': return 'unknown';
    default: break;
  }
  if (d.live === true) return 'live';
  switch (d.connection) {
    case 'Streaming': case 'Connected': return 'live';
    case 'Connecting': return 'wait';
    case 'Disconnected': case 'Error': return 'off';
    default: return 'unknown';
  }
}

/* Кого считать источником глюкозы. Роль берём из снимка, а не гадаем по виду:
   помпа — тоже kind-устройство, но сахар не отдаёт, а Nightscout отдаёт, будучи
   сервисом.

   Порядок предпочтения: primary → железка → что нашлось. primary впереди всех,
   потому что именно на него смотрит монитор. Без него сенсор идёт вперёд сервиса:
   в списке рядом могут стоять сенсор и облачный поток, и «первый попавшийся» зависел
   бы от порядка устройств в снимке — то есть от того, что нам никто не обещал. */
export function источникГлюкозы(snap: UiSnapshot | null | undefined): DeviceView | null {
  const все = (snap?.devices ?? []).filter(
    (d) => d.kind === 'sensor' || (d.roles ?? []).includes('GlucoseSource'),
  );
  /* Явный выбор человека сильнее любого качества: он для того и явный. Дальше —
     общее правило «кто реально даёт данные» (SugarLifeCore#43). */
  return все.find((d) => d.primary) ?? лучшийИсточник(все);
}

/* Помпа — только сама помпа, и это сложнее, чем kind === 'pump'.

   Метка отвечает на вопрос «на связи ли помпа». Живой Nightscout отвечает на другой —
   «жив ли облачный сокет»; помпа может молчать час, пока облако бодро отдаёт
   последний известный документ. Смешать эти два ответа значит вернуть ровно то
   враньё, из-за которого задача #19 и появилась.

   Одного kind для различения не хватало: движок метил вид ПО РОЛЯМ, и облачный
   источник состояния помпы приезжал на нативе тоже как kind: 'pump' (предупреждение
   ядра в SugarLifeCore#19). С коммитом 08c8e94 они это изменили — облачные источники
   теперь kind: 'service', и одна проверка вида уже отсекла бы облако.

   Проверку ниже всё равно оставляем, и не из недоверия: устройство бывает
   многоканальным, и «помпа с активным облачным каналом» — это по-прежнему kind
   'pump', про прямую связь с которым мы ничего не знаем. Вид отвечает на вопрос «кто
   это», каналы — на вопрос «как мы об этом узнаём», и второй вопрос никуда не делся.

   Различаем в два шага, от точного к запасному:

   1. Каналы (rev 1.8, #23). Движок прямо говорит, чем достижимо устройство и какой
      канал сейчас активен. Это буквальный ответ, а не признак.
   2. driverId. У облачного источника его нет, у настоящей BLE-помпы — id драйвера.
      Записанная-без-модели помпа тоже придёт без driverId, но она Disconnected и под
      «на связи» не попадёт.

   Обе проверки — на снимке; своего знания о том, какие бывают помпы, здесь нет. */
export function источникПомпы(snap: UiSnapshot | null | undefined): DeviceView | null {
  const помпы = (snap?.devices ?? []).find((d) => d.kind === 'pump' && !толькоОблако(d));
  return помпы ?? null;
}

/* Состояние приезжает только облаком. Отдельной функцией, потому что вопрос ещё
   вернётся: карточке помпы каналы нужно будет показать списком, и «через облако,
   N мин» — такая же честная строка, как «напрямую». */
export function толькоОблако(d: DeviceView): boolean {
  const каналы = d.channels ?? [];
  if (каналы.length) {
    const активный = каналы.find((c) => c.id === d.activeChannel) ?? каналы[0];
    return активный.kind === 'cloud';
  }
  return d.driverId == null;
}

/* Железки этого вида — те, которые действительно наши, без облачных потоков.

   Вынесено из карточки устройства и покрыто тестом не ради красоты. Это список, по
   которому уходит removeDevice, а ядро подтвердило (SugarLifeCore#26), что удаление
   облачного источника не игнорируется: движок снимет его и положит в tombstone —
   приём данных из Nightscout выключится и сам не вернётся даже после перезапуска.

   То есть ошибка в этом фильтре не «покажет лишнее», а тихо выключит человеку
   мониторинг по кнопке «забыть помпу». Такие места держат тестом. */
export function своиЖелезки(
  snap: UiSnapshot | null | undefined, вид: DeviceView['kind'],
): DeviceView[] {
  return (snap?.devices ?? []).filter((d) => d.kind === вид && !толькоОблако(d));
}

/* Состояние источника глюкозы для панели.

   Здесь была ветка «монитор перебивает устройство, у которого есть только линк». Она
   лечила расхождение: устройство несло сокет, монитор — жизненный цикл, и линк
   выдавал бы молчащий источник за живой.

   Расхождения больше нет по построению. Движок считает статус один раз и кладёт
   результат и в devices[primary], и в monitor (SugarLifeCore#22, залочено их тестом),
   а наш Nightscout-шим с тех же пор строит устройство из того же вычисления, что и
   монитор (sources/bridgeNightscout.ts). Оба конца контракта дают одно и то же.

   Ветку убрали, а не оставили «на всякий случай». Компенсация, которой нечего
   компенсировать, живёт вечно и тихо расходится с реальностью: через полгода никто
   уже не помнит, что она лечила, и боится трогать. Если расхождение вернётся, это
   поломка контракта — её надо чинить там, а не прятать здесь. */
export function связьГлюкозы(snap: UiSnapshot | null | undefined): Связь {
  const d = источникГлюкозы(snap);
  if (d) return связь(d);
  /* Устройств нет вовсе — старый мост, который их не проецирует. Тогда монитор
     единственное, что у нас есть про основной источник. */
  const m = snap?.monitor;
  if (!m) return 'unknown';
  return связь({ status: m.status, live: m.live, connection: m.link } as DeviceView);
}

/* Предложить слить облачный источник помпы с заведённой железкой (SugarLifeCore#23).

   Половину риска снимает сам факт, что предлагать приходится: движок сливает каналы
   САМ, когда Nightscout несёт серийник настроенной помпы. Если облачная помпа всё
   ещё отдельным устройством — значит серийника не было или он не совпал, и мы
   заведомо в неуверенном положении. Значит не гадаем, а показываем человеку строки.

   Отсюда два условия, и оба про честность, а не про удобство.

   ПЕРВОЕ: молчим, пока показать нечего. Без sourceLabel вопрос выродится в «у вас
   две помпы, это одна и та же?» — предложение подтвердить наше предположение, не
   имея ни одного факта. Человек скажет «да» из вежливости к интерфейсу, а сольются
   два разных устройства: общий Nightscout в семье, две помпы в доме — это не
   выдуманный случай.

   ВТОРОЕ: не предлагаем то, что уже слито. Устройство с облачным каналом внутри —
   это результат слияния, ручного или автоматического; спрашивать о нём заново
   значит предлагать переделать сделанное. */
export interface Слияние { облако: DeviceView; железка: DeviceView; серийник: string | null }

export function предложениеСлияния(snap: UiSnapshot | null | undefined): Слияние | null {
  const помпы = (snap?.devices ?? []).filter((d) => d.kind === 'pump');
  const облако = помпы.find((d) => толькоОблако(d) && !(d.channels ?? []).length);
  const железка = помпы.find((d) => !толькоОблако(d));
  if (!облако || !железка) return null;
  if ((железка.channels ?? []).some((c) => c.kind === 'cloud')) return null;
  if (!облако.sourceLabel) return null;
  return { облако, железка, серийник: серийникИз(железка.id) };
}

/* Серийник — суффикс идентификатора после двоеточия («medtronic-722:123456»).
   Разбираем здесь, а не в разметке: строка приходит от движка, и место, где мы
   делаем о ней предположение, должно быть одно и покрыто тестом. */
export function серийникИз(id: string): string | null {
  const i = id.indexOf(':');
  const хвост = i >= 0 ? id.slice(i + 1).trim() : '';
  return хвост || null;
}

/* Что показывать в круге глюкозы (SugarLifeCore#27).

   С железа: при подключении сенсора цифры в круге «бегут». Это догрузка истории, а
   читается как живая глюкоза. Круг — самая доверенная цифра в приложении, по ней
   решают, колоть ли; он не имеет права показывать то, чем нельзя пользоваться.

   Правило: число бывает ТОЛЬКО у подтверждённо свежих данных.

   • «ждём» (Connecting/Acquiring) — числа нет вовсе, часики вместо него. Приглушать
     здесь нечего: свежего показания ещё не было ни одного, а показать историческое —
     это и есть ошибка, из-за которой задача заведена.
   • «отстало» (Delayed) — число было и остаётся, но приглушённым и с возрастом.
     Прятать последнее известное тоже нечестно: человеку важно знать, от чего он ушёл.
     Важно лишь, чтобы оно не выглядело текущим.
   • «нет» — прочерк.

   Отдельной функцией, а не веткой в разметке: это состояния ожидания, которых в
   браузере не бывает, и единственный способ их проверить — тест. */
export type ВидКруга = 'число' | 'ждём' | 'отстало' | 'нет';

/* ЧАСИКИ — ПРО ОТСУТСТВИЕ СВЕЖЕГО ЧИСЛА, А НЕ ПРО СОСТОЯНИЕ ИСТОЧНИКА.

   С телефона: в круге часики и «догоняю…», а строкой ниже список показаний, самому
   свежему из которых минута. Приложение показывает два ответа на один вопрос, и
   доверенное место — круг — оказывается пустым при полных данных.

   Разбор: сюда приходил только `monitor.status`. У внешнего CGM через Nightscout движок
   держит его в 'Acquiring' подолгу — прямого потока у него нет, — и круг всё это время
   считал, что показывать нечего. Хотя показывать было что.

   Довод, по которому статусу верили («у него ещё не было ни одного показания, и возраст
   мерить не у чего»), верен ровно до появления показания с отметкой времени. Появилось —
   возраст измерим, и он отвечает на вопрос точнее любого статуса.

   Защита из SugarLifeCore#27 при этом остаётся целой: при подключении сенсора в круг
   лезла ДОГРУЗКА ИСТОРИИ, а у неё отметки времени старые. Старое показание к числу не
   пропускает тот же возраст — теперь по факту, а не по косвенному признаку.

   `возрастПоказанияМс` — сколько лет тому числу, которое реально будет показано (его
   выбирает domain/latestGlucose из нескольких источников). null — числа нет вовсе. */
export function видКруга(
  snap: UiSnapshot | null | undefined,
  возрастПоказанияМс?: number | null,
): ВидКруга {
  const свежее = возрастПоказанияМс != null && возрастПоказанияМс <= ОТСТАВАНИЕ_КРУГА_МС;
  const st = snap?.monitor?.status;
  switch (st) {
    case 'Acquiring': case 'Connecting': return свежее ? 'число' : 'ждём';
    case 'Delayed': return 'отстало';
    /* «Нет» — тоже про источник, но здесь спорить не с чем: даже когда число есть,
       свежим оно при оборванном источнике не бывает. А если вдруг оказалось — значит
       кто-то другой донёс его до нас минуту назад, и прятать его незачем. */
    case 'Disconnected': return свежее ? 'число' : 'нет';
    case 'Live': return 'число';
    default: break;
  }
  /* Старый мост статуса не присылает. Тогда число показываем как раньше: спрятать
     его на догадке значило бы сломать работающий экран ради состояния, о котором
     нам ничего не сказали. */
  return 'число';
}

/* Подпись для доступности и подсказки. Точка без имени — украшение: читалка экрана
   не видит цвета, а долгое нажатие ничего не объясняет. */
/* Через что пришло состояние — то, чего человеку не хватало больше всего.

   Симптом (SugarLifeCore#34): «Помпа на связи», а мост при этом молчит. Обе строки
   правдивы: помпу видно через Nightscout, потому что её туда пишет другой телефон, а
   наш мост действительно оборван. Голое «на связи» слило два разных факта в один, и
   человек шёл чинить то, что не сломано.

   Слова отвечают на вопрос «откуда я это знаю», а не называют технологию: «по радио»,
   а не BLE. Технология — не его забота, а вот кто именно молчит — его.

   Облако у нас сегодня одно, поэтому названо прямо. Когда каналов станет больше
   (Connector, SugarLifeCore#15), имя должно приехать из канала: «через облако»
   ничего не говорит человеку, у которого их два. */
export const СЛОВО_КАНАЛА: Record<ChannelView['kind'], string> = {
  direct: 'по радио', bridged: 'через мост', cloud: 'через Nightscout',
};

/* Устройство РОЛИ — включая то, до которого мы дотягиваемся только облаком.

   Это не то же самое, что источникПомпы, и разница принципиальная. Там вопрос «на
   связи ли сама помпа», и облачную мы обязаны исключить: зелёная точка на ней —
   враньё. Здесь вопрос другой — «откуда взялись эти цифры», и облачная помпа на него
   отвечает: из Nightscout. Молчание вместо ответа как раз и оставляет человека с
   «Помпа на связи» без объяснения, кто это сказал (SugarLifeCore#34).

   Роль спрашиваем у снимка, а не у вида: сенсор выбирается тем же правилом, что и
   источник глюкозы (primary → сенсор → первый), помпа — первая с ролью подачи. */
/* Кто из кандидатов РЕАЛЬНО даёт данные (SugarLifeCore#43).

   Прежнее правило — «первый с нужным видом» — молча зависело от порядка регистрации.
   У ядра это дало живой баг: облако поднимается раньше BLE, и в слоте подачи навсегда
   оказывалось облако, даже когда железная помпа была на связи. Экран честно повторял
   за ним: «через Nightscout» рядом с работающей помпой.

   Порядок сравнения: сначала качество статуса (кто отдаёт свежее), при равенстве —
   железка перед сервисом, потом своё перед облачным каналом. Это не вкусовщина: у
   железа есть «переподключить» и батарея, а у облачной записи только чужие данные, и
   при прочих равных полезнее та, с которой человек может что-то сделать.

   Смысл правила (а) при этом не изменился: облако — законный активный источник, если
   оно единственное, кто отдаёт свежее. Изменилась устойчивость ответа. */
const КАЧЕСТВО: Record<string, number> = {
  Live: 0, Acquiring: 1, Connecting: 1, Delayed: 2, Disconnected: 4,
};

export function лучшийИсточник(кандидаты: DeviceView[]): DeviceView | null {
  if (!кандидаты.length) return null;
  const вес = (d: DeviceView) => (d.status ? КАЧЕСТВО[d.status] ?? 3 : (связь(d) === 'live' ? 0 : 3));
  const сервис = (d: DeviceView) => Number(d.kind === 'service');
  return [...кандидаты].sort((a, b) =>
    вес(a) - вес(b)
    || сервис(a) - сервис(b)
    || Number(толькоОблако(a)) - Number(толькоОблако(b)))[0] ?? null;
}

export function устройствоРоли(
  snap: UiSnapshot | null | undefined, роль: 'sensor' | 'pump',
): DeviceView | null {
  /* Если движок отдаёт роли — слушаем его, а не считаем заново.

     Правило у нас с ним одно (SugarLifeCore#34 взял нашу формулировку дословно), но
     считать по нему в двух местах всё равно нельзя: расходятся не правила, а их
     реализации, и расхождение будет видно как «экран говорит одно, алгоритм делает
     другое». Свой расчёт остаётся ровно для того случая, когда ролей в снимке нет:
     старый мост, Nightscout-шим в браузере. */
  const изДвижка = рольСнимка(snap, роль);
  if (изДвижка) {
    /* Роль есть, источника нет — это ответ, а не пробел: показывать «взято отсюда»,
       когда движок говорит «неоткуда», значит выдумывать. */
    if (!изДвижка.activeSourceId) return null;
    return (snap?.devices ?? []).find((d) => d.id === изДвижка.activeSourceId) ?? null;
  }
  if (роль === 'sensor') return источникГлюкозы(snap);
  return лучшийИсточник((snap?.devices ?? []).filter((d) => d.kind === 'pump'));
}

/** Роль из снимка движка (rev ≥ 1.8). Пусто — движок ролей ещё не отдаёт. */
export function рольСнимка(
  snap: UiSnapshot | null | undefined, роль: 'sensor' | 'pump',
): RoleView | null {
  const имя = роль === 'sensor' ? 'cgm' : 'insulin';
  return (snap?.roles ?? []).find((r) => r.role === имя) ?? null;
}

/* То же самое одним словом — для панели, где на строку приходится треть экрана.
   Полная фраза там не помещается, а обрезанная хуже короткой. */
export const КОРОТКО_КАНАЛ: Record<ChannelView['kind'], string> = {
  direct: 'радио', bridged: 'мост', cloud: 'облако',
};

/** Активный канал устройства — тот, чьи поля подняты наверх снимком. */
export function активныйКанал(d: DeviceView | null | undefined): ChannelView | null {
  const каналы = d?.channels ?? [];
  if (!каналы.length) return null;
  return каналы.find((c) => c.id === d?.activeChannel) ?? каналы[0];
}

/* Как дописать «через что» к состоянию связи.

   Пусто отдаём в двух случаях, и оба намеренные. Каналов нет вовсе — старый мост,
   и любое слово тут было бы выдумкой. Связи нет — «нет связи по радио» звучит как
   «есть другой путь, попробуйте его», а никакого другого пути нет: движок уже выбрал
   бы лучший канал, если бы тот работал. */
export function черезЧто(d: DeviceView | null | undefined, via?: RoleView['via']): string | null {
  /* via с роли главнее собственного разбора каналов: движок знает про источник больше,
     чем видно в устройстве, — например когда роль обслуживается не тем устройством,
     на которое мы смотрим. Своё вычисление остаётся, пока ролей в снимке нет. */
  const вид = via ?? активныйКанал(d)?.kind ?? null;
  if (!вид) return null;
  return связь(d) === 'off' ? null : СЛОВО_КАНАЛА[вид];
}

/* Короткое «через что» — но только когда путей действительно несколько.

   На панели у крыла есть одна короткая строка, и занимать её словом «радио» там, где
   выбора нет, значит менять полезное на очевидное. А вот когда каналов два, слово
   решает: именно тут живёт «помпа на связи, а мост нет». */
export function черезЧтоСпорное(d: DeviceView | null | undefined): string | null {
  if ((d?.channels?.length ?? 0) < 2) return null;
  const к = активныйКанал(d);
  if (!к || связь(d) === 'off') return null;
  return КОРОТКО_КАНАЛ[к.kind];
}

export const меткаСвязи: Record<Связь, string | null> = {
  live: 'на связи, данные идут',
  wait: 'подключается — данных пока нет',
  off: 'нет связи',
  unknown: null,
};

/* Настоящий движок или браузерный шим (SugarLife#256).

   Признаком живого движка у нас числилось «в снимке есть хоть один драйвер». Он был
   верным ровно до тех пор, пока Nightscout-шим не завёл собственный драйвер — сам
   Nightscout, чтобы через ту же форму вводить адрес и токен. С этого момента признак
   стал утвердительным всегда, и в вебе появилась карточка «Подключить устройство» с
   предложением посмотреть, что рядом в эфире. Эфира в браузере нет как класса, и
   кнопка вела в поиск, который не найдёт ничего и никогда.

   Правильный признак — драйвер ЖЕЛЕЗА, а не сервиса. Облачный источник тоже драйвер, но
   у него нет ни эфира, ни «рядом», ни «подключить»; вопрос «умеем ли мы разговаривать с
   приборами» отвечается только наличием прибора среди драйверов.

   Проверять платформу вместо этого нельзя: браузер может говорить с нативным движком
   через релей, и тогда эфир есть, а Capacitor.isNativePlatform() ложно. */
export function движокЖивой(snap: UiSnapshot | null | undefined): boolean {
  return (snap?.availableDrivers ?? []).some((d) => d.kind !== 'service');
}
