import { describe, it, expect } from 'vitest';
import { имяПриёма, подписьПриёма, ПЕРЕКУС_ДО_Г } from './имяПриёма';

/* Названия приёмов (SugarLife#381). В журнале у всего стоял «Перекус»: тип брался
   только по часу. Человек различает иначе — сорок граммов в час дня это обед, а
   пятнадцать в тот же час перекус между делами. */

describe('размер значит не меньше времени', () => {
  it('маленькая порция — перекус в любое время', () => {
    expect(имяПриёма(8, 10)).toBe('Перекус');
    expect(имяПриёма(13, 15)).toBe('Перекус');
    expect(имяПриёма(19, 12)).toBe('Перекус');
  });

  it('полноценная — по часу', () => {
    expect(имяПриёма(8, 45)).toBe('Завтрак');
    expect(имяПриёма(13, 60)).toBe('Обед');
    expect(имяПриёма(19, 50)).toBe('Ужин');
  });

  /* Полноценная еда в четыре часа дня для многих и есть обед, поэтому полдник —
     только про небольшое. */
  it('между обедом и ужином решает размер', () => {
    expect(имяПриёма(16, 25)).toBe('Полдник');
    expect(имяПриёма(16, 55)).toBe('Обед');
  });

  it('поздно вечером — поздний ужин', () => {
    expect(имяПриёма(23, 40)).toBe('Поздний ужин');
    expect(имяПриёма(2, 40)).toBe('Поздний ужин');
  });

  /* Ночная еда чаще всего купирование гипо, и путать её с ужином не стоит: в разборе
     это разные события. */
  it('ночью маленькое — ночной перекус, а не ужин', () => {
    expect(имяПриёма(3, 12)).toBe('Ночной перекус');
  });

  it('граница перекуса — одна и та же везде', () => {
    expect(имяПриёма(13, ПЕРЕКУС_ДО_Г - 1)).toBe('Перекус');
    expect(имяПриёма(13, ПЕРЕКУС_ДО_Г)).toBe('Обед');
  });
});

describe('чьё слово главнее', () => {
  /* Человек назвал блюдо сам — подменять его «обедом» значит спорить с ним о его еде. */
  it('имя от человека главнее нашей догадки', () => {
    const п = подписьПриёма({ имя: 'Гречка с курицей', часЕды: 13, граммы: 55 });
    expect(п.главное).toBe('Гречка с курицей');
    expect(п.уточнение).toBe('обед');
  });

  it('выбранный руками тип тоже главнее', () => {
    expect(подписьПриёма({ kind: 'Ужин', часЕды: 13, граммы: 55 }).главное).toBe('Ужин');
  });

  /* «Обед · обед» — так выглядит приложение, которое не помнит, что само же и написало. */
  it('совпал с догадкой — не повторяем дважды', () => {
    expect(подписьПриёма({ kind: 'Обед', часЕды: 13, граммы: 55 })).toEqual({ главное: 'Обед', уточнение: null });
  });

  it('ничего не задано — наша догадка', () => {
    expect(подписьПриёма({ часЕды: 8, граммы: 40 }).главное).toBe('Завтрак');
  });
});
