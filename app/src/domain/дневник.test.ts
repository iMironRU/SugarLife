import { describe, it, expect } from 'vitest';
import { добавить, ПРЕДЕЛ, ЖИЗНЬ_МС, type ЗаписьДневника } from './дневник';

const з = (когдаМс: number, главное: string, вид: ЗаписьДневника['вид'] = 'прибор'): ЗаписьДневника =>
  ({ ключ: `${вид}-${когдаМс}`, когдаМс, вид, главное });

/* Часы передаём явно во ВСЕХ проверках. С `Date.now()` по умолчанию тест про порядок
   молча превращался бы в тест про срок хранения: маленькие метки времени старше недели,
   и список выходил пустым — падало не то, что проверяли. */
const СЕЙЧАС = 1_800_000_000_000;

describe('дневник', () => {
  it('свежее сверху', () => {
    const л = добавить(добавить([], з(СЕЙЧАС - 2000, 'а'), СЕЙЧАС), з(СЕЙЧАС - 1000, 'б'), СЕЙЧАС);
    expect(л.map((x) => x.главное)).toEqual(['б', 'а']);
  });

  it('одинаковую строку подряд в течение минуты не дублирует', () => {
    const л = добавить(добавить([], з(СЕЙЧАС - 30_000, '«Sibionics» на связи'), СЕЙЧАС), з(СЕЙЧАС - 20_000, '«Sibionics» на связи'), СЕЙЧАС);
    expect(л).toHaveLength(1);
  });

  it('но через минуту это уже новое событие — связь могла отвалиться и вернуться', () => {
    const л = добавить(добавить([], з(СЕЙЧАС - 120_000, '«Sibionics» на связи'), СЕЙЧАС), з(СЕЙЧАС - 20_000, '«Sibionics» на связи'), СЕЙЧАС);
    expect(л).toHaveLength(2);
  });

  it('разные строки не схлопывает', () => {
    const л = добавить(добавить([], з(СЕЙЧАС - 2000, 'на связи'), СЕЙЧАС), з(СЕЙЧАС - 1000, 'отключился'), СЕЙЧАС);
    expect(л).toHaveLength(2);
  });

  it('старше недели выбрасывает', () => {
    const сейчас = 10 * ЖИЗНЬ_МС;
    const л = добавить([з(сейчас - ЖИЗНЬ_МС - 1, 'древнее')], з(сейчас, 'новое'), сейчас);
    expect(л.map((x) => x.главное)).toEqual(['новое']);
  });

  it('не растёт выше предела', () => {
    let л: ЗаписьДневника[] = [];
    for (let i = 0; i < ПРЕДЕЛ + 50; i++) л = добавить(л, з(1000 + i * 120_000, 'строка ' + i), 1000 + i * 120_000);
    expect(л).toHaveLength(ПРЕДЕЛ);
    expect(л[0].главное).toBe('строка ' + (ПРЕДЕЛ + 49));
  });
});

describe('«однажды» — для строк, которые висят на экране днями', () => {
  const СЕЙЧАС2 = 1_800_000_000_000;
  it('второй раз ту же строку не пишет, даже через сутки', () => {
    const первый = добавить([], з(СЕЙЧАС2 - 86_400_000, 'Обновление ждёт перезапуска', 'сборка'), СЕЙЧАС2, true);
    const второй = добавить(первый, з(СЕЙЧАС2, 'Обновление ждёт перезапуска', 'сборка'), СЕЙЧАС2, true);
    expect(второй).toHaveLength(1);
  });
  it('но другую строку пишет', () => {
    const первый = добавить([], з(СЕЙЧАС2 - 86_400_000, 'Обновление ждёт перезапуска', 'сборка'), СЕЙЧАС2, true);
    const второй = добавить(первый, з(СЕЙЧАС2, 'Обновились до сборки abc1234', 'сборка'), СЕЙЧАС2, true);
    expect(второй).toHaveLength(2);
  });
});
