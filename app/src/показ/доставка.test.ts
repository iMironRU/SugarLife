import { describe, it, expect } from 'vitest';
import { строкиДоставки } from './доставка';
import type { ConnectorView } from '@/sources/bridge';

const к = (p: Partial<ConnectorView>): ConnectorView =>
  ({ id: 'ns', displayName: 'Nightscout', ...p });

const СЕЙЧАС = 1_700_000_000_000;

describe('доезжают ли данные', () => {
  it('свежая отправка — доезжает', () => {
    const [с] = строкиДоставки([к({ lastSentAtMs: СЕЙЧАС - 60_000, uploadEveryMin: 5 })], СЕЙЧАС);
    expect(с.знак).toBe('ок');
    expect(с.под).toContain('доезжает');
  });

  it('очередь при свежей отправке бедой не считается', () => {
    /* Между выгрузками записи копятся всегда: при шаге в пять минут горсть показаний в очереди —
       обычная жизнь, а не поломка. */
    const [с] = строкиДоставки([к({ lastSentAtMs: СЕЙЧАС - 60_000, outboxPending: 4 })], СЕЙЧАС);
    expect(с.знак).toBe('ок');
    expect(с.под).toContain('в очереди 4');
  });

  it('три шага молчания — не доезжает', () => {
    const [с] = строкиДоставки([к({ lastSentAtMs: СЕЙЧАС - 20 * 60_000, uploadEveryMin: 5 })], СЕЙЧАС);
    expect(с.знак).toBe('нет');
    expect(с.под).toContain('последняя запись');
  });

  it('порог считается от шага выгрузки, а не от выдуманного числа', () => {
    /* При часовой выгрузке двадцать минут молчания — норма; при пятиминутной — уже нет. */
    const [часовой] = строкиДоставки([к({ lastSentAtMs: СЕЙЧАС - 20 * 60_000, uploadEveryMin: 60 })], СЕЙЧАС);
    expect(часовой.знак).toBe('ок');
  });

  it('ошибка приёмника показывается как есть', () => {
    const [с] = строкиДоставки([к({ outboxLastError: '401 Unauthorized', lastSentAtMs: СЕЙЧАС })], СЕЙЧАС);
    expect(с.знак).toBe('нет');
    expect(с.под).toBe('401 Unauthorized');
  });

  it('ни разу не отправляли — не поломка, но и не «доезжает»', () => {
    const [с] = строкиДоставки([к({})], СЕЙЧАС);
    expect(с.знак).toBe('ждём');
  });

  it('приёмников нет — раздела нет: пустой блок читается как «ничего не уходит»', () => {
    expect(строкиДоставки(undefined)).toEqual([]);
    expect(строкиДоставки([])).toEqual([]);
  });
});
