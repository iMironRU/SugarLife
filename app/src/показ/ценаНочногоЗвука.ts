import { прочитать, записать } from '@/settings/storage';
import type { Платформа } from '@/показ/охрана';

/* ЦЕНУ НАЗЫВАЕМ ДО ТОГО, КАК ЧЕЛОВЕК ЗАПЛАТИТ (#473, путь первого знакомства).

   На айфоне беззвучный режим пробивает только собственный звук приложения, и чтобы он был наготове
   ночью, приложение держит открытым звуковой поток. У этого есть цена, и она наступает не ночью, а
   в машине: телефон с открытым потоком магнитола считает источником звука и переключается на него.

   Цена написана в подробностях строки «Разбудить звуком». Но человек, который нажимает кнопку
   починки, подробностей не открывает — кнопка и есть способ их не читать. То есть мы поставили
   объяснение ровно туда, куда торопящийся не заглянет.

   Владелец в задаче сказал это прямо: «галочка „надёжные тревоги" без этой строки обманывает».

   СПРАШИВАЕМ ОДИН РАЗ. Узнав про магнитолу однажды, человек это помнит; повторять при каждом
   включении значит превратить объяснение в помеху и научить жать «да» не читая.

   ТОЛЬКО НА АЙФОНЕ. На Android тревога пробивает тихий режим своим каналом, звуковой поток там для
   другого, и цены с магнитолой нет. Спрашивать там значило бы придумать человеку проблему.

   ЧЕГО ЗДЕСЬ НЕТ: выбора «держать всегда или только ночью». Он в задаче назван и он правильный —
   у кого нет машины, тому платить не за что, — но окно сна держит движок, и такой выбор без него
   не сделать. Отдельным разговором. */

const КЛЮЧ = 'sl.ночной-звук.цена-сказана';

export const ЦЕНА_НОЧНОГО_ЗВУКА =
  'Чтобы тревога звучала на беззвучном телефоне, приложение будет держать открытым звуковой поток.\n\n'
  + 'Цена одна и она заметна в машине: телефон с открытым потоком магнитола считает источником '
  + 'звука и переключается на него. Ночью поток держат, днём отпускают.\n\n'
  + 'Включить?';

/** Надо ли объяснить цену перед включением. */
export function ценуСпросить(платформа: Платформа): boolean {
  return платформа === 'ios' && прочитать(КЛЮЧ) !== 'да';
}

/** Человек услышал цену — больше не спрашиваем. Зовётся и при согласии, и при отказе:
 *  отказавшийся тоже её узнал, и повторять ему тем более незачем. */
export function ценуСказали(): void {
  записать(КЛЮЧ, 'да');
}
