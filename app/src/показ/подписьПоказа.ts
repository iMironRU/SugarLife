/* ЧТО СЕЙЧАС ВИДНО, НЕ ОТКРЫВАЯ ПРИЛОЖЕНИЕ — ОДНОЙ СТРОКОЙ (SugarLife#556).

   Вход в раздел называется «Экран блокировки и значок», но название говорит, ЧТО там настраивается,
   а не КАК настроено сейчас. Разница существенная: человек, у которого баннер выключен, приходит с
   вопросом «почему я не вижу сахар на блокировке» — и по названию раздела ответа не получает.

   Поэтому в подписи — состояние, а не перечень возможностей: включённое перечисляем, ничего не
   включено — говорим об этом прямо. «Ничего не показываем» звучит резче, чем хотелось бы, и это
   намеренно: три выключенных переключателя выглядят на экране одинаково скучно, а означают, что
   телефон молчит про сахар вообще.

   Значок называем видом, а не «включён»: у него четыре вида, и «7,9» против «79» — разные ответы на
   вопрос «что я увижу». */

export interface СостояниеПоказа {
  /** Живой баннер включён. null — платформа не умеет (веб, старая iOS). */
  баннер: boolean | null;
  /** Сводка в шторке включена. null — не умеем спросить. */
  сводка: boolean | null;
  /** Вид значка: 'выключен' | 'сахар' | 'десятые' | 'целые' | 'мг'. null — нет значка. */
  значок: string | null;
}

const ВИД_ЗНАЧКА: Record<string, string> = {
  сахар: 'значок 7,9',
  десятые: 'значок 79',
  целые: 'значок 8',
  мг: 'значок 142',
};

export function подписьПоказа(с: СостояниеПоказа): string {
  const части: string[] = [];
  if (с.баннер) части.push('баннер');
  if (с.сводка) части.push('сводка');
  if (с.значок && с.значок !== 'выключен') части.push(ВИД_ЗНАЧКА[с.значок] ?? 'значок');

  if (части.length) return части.join(' · ');

  /* Ничего не умеем спросить — значит и сказать нечего: в браузере этих поверхностей нет вовсе, и
     «ничего не показываем» там прозвучало бы как поломка, а не как состояние. */
  if (с.баннер == null && с.сводка == null && с.значок == null) {
    return 'живой баннер, сводка в шторке, цифры на иконке';
  }
  return 'сейчас ничего не показываем';
}
