import { УСТАРЕЛО_МС } from '@/domain/supplies';

export interface Знание { значение: number; когдаМс: number }

export type ПоказЗаряда =
  | { вид: 'число'; значение: number }
  /** Знали и перестали: место занято, вопрос виден, число не выдумываем. */
  | { вид: 'вопрос'; тревожно: boolean }
  /** Никогда не знали — законная пустота. */
  | null;

export function показЗаряда(
  сейчасЗначение: number | null | undefined,
  знали: Знание | null | undefined,
  сейчасМс: number,
  наИсходе: number,
): ПоказЗаряда {
  if (сейчасЗначение != null && Number.isFinite(сейчасЗначение)) {
    return { вид: 'число', значение: сейчасЗначение };
  }
  if (!знали || !Number.isFinite(знали.значение)) return null;
  const молчит = сейчасМс - знали.когдаМс;
  /* Часы съехали назад — не гадаем, тем же правилом, что в место.ts и в калибраторе. */
  if (молчит < 0 || молчит <= УСТАРЕЛО_МС) return null;
  return { вид: 'вопрос', тревожно: знали.значение <= наИсходе };
}
