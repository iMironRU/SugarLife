/* «У МЕНЯ ЖЕ ЯНДЕКС ОТКРЫВАЕТСЯ» (просьба владельца, 16.09.2026; рядом — ядро #239).

   Владелец сказал прямо: «нужно показывать, что даже если у человека откроется Яндекс, это не
   значит, что мы можем ему показать». В России это не редкость, а обычный день: мобильный
   интернет уходит в белые списки, разрешённые сайты работают, остальное нет.

   ЧЕЛОВЕК ПРОВЕРЯЕТ СВЯЗЬ ТЕМ, ЧТО У НЕГО ПОД РУКОЙ, — открывает мессенджер или поисковик. Тот
   отвечает, и дальше он делает единственный возможный вывод: интернет есть, значит беда в
   приложении. И идёт чинить не то — перезапускать нас, смахивать, переустанавливать. Смахивание
   при этом убивает ровно то, что мы держим живым ради ночи.

   ГОВОРИМ ВЕЗДЕ, ГДЕ ДО СЕРВЕРА НЕ ДОШЛИ, — А НЕ ТОЛЬКО ПРИ «ИНТЕРНЕТ ЕСТЬ» (владелец: «видит
   сеть по-разному»). Сначала здесь стоял один код, `cloud.unreachable.online`. Это неверно:
   мнение о сети у телефона не одно, а два, и они расходятся. Наблюдатель пути может считать,
   что сеть есть, а запрос в ту же секунду падает с `NSURLErrorDomain -1009` — «соединения нет».
   Движок разбирает беду по тексту ошибки, значит в сети с белым списком беда назовётся
   `cloud.offline`, хотя Яндекс у человека открывается прекрасно.

   Поэтому делим не по мнению телефона, а по тому, ДОШЛИ ЛИ МЫ ДО СЕРВЕРА:

     cloud.offline              ← до сервера не дошли: говорим
     cloud.unreachable          ← не дошли: говорим
     cloud.unreachable.online   ← не дошли, и телефон это признаёт: говорим
     cloud.server.error         ← сервер ОТВЕТИЛ: связь исправна, разговор про чужие сайты лишний
     cloud.tls.failed           ← дошли до сервера, не договорились о шифровании — то же самое
     nightscout.auth.failed     ← дошли, сервер нас не пустил

   Фраза начинается с «если» именно поэтому: когда сети правда нет, у человека и Яндекс не
   откроется, и условие честно не сработает у него в голове. Утверждать за него, что чужие сайты
   работают, мы не имеем права — знать этого мы не можем.

   ЧЕГО ЗДЕСЬ НЕТ. Мы не говорим, что действуют белые списки: проверить это нечем, и сверку
   «открыт Яндекс, а остальное нет» делает не оболочка, а движок (ядро #239). Оговорка не
   называет причину, она снимает ложный вывод. */

/** До сервера не дошли — только тогда оговорка верна. */
export const КОДЫ_БЕЗ_ХОДА = new Set([
  'cloud.offline',
  'cloud.unreachable',
  'cloud.unreachable.online',
]);

export function чужиеСайтыНеСчитаются(код: string | null | undefined): boolean {
  return !!код && КОДЫ_БЕЗ_ХОДА.has(код);
}
