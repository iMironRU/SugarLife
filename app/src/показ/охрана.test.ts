import { describe, it, expect } from 'vitest';
import { охрана } from './охрана';
import type { ГотовностьТревог } from '@/platform/тревоги';

const г = (п: Partial<ГотовностьТревог> = {}): ГотовностьТревог => ({
  проблема: false, чегоНет: [], поломки: [], ...п,
});
const фонОк = { ignoring: true, manufacturer: 'x', problem: false, reason: '', whatToDo: '', weCanOpenSettings: false };

describe('охрана отвечает раньше, чем перечисляет', () => {
  it('всё на месте — обещание в силе', () => {
    const о = охрана({ платформа: 'android', тревогиВедутся: true, порогМолчанияМин: 30, готовность: г(), фон: фонОк, сенсорМолчитМин: 2 });
    expect(о.ответ).toBe('разбудим');
  });

  /* Главный случай: пороги настроены, тревога включена — и всё равно не услышим. Ответ
     обязан быть «может не разбудить», а не «разбудим с оговоркой». */
  it('нет доступа к «Не беспокоить» — обещания нет, сколько бы порогов ни стояло', () => {
    const о = охрана({
      платформа: 'android',
      тревогиВедутся: true, порогМолчанияМин: 30,
      готовность: г({ поломки: [{ код: 'dnd-access', текст: 'нет доступа к «Не беспокоить» — ночью тревога будет беззвучной' }] }),
      фон: фонОк, сенсорМолчитМин: 2,
    });
    expect(о.ответ).toBe('может не разбудить');
    expect(о.почему).toContain('Не беспокоить');
  });

  /* Правил нет — считать тревоги некому. Это не выбор человека, а старое ядро, и говорить
     «разбудим» нельзя тем более. */
  it('движок правил не отдаёт — не сторожим, и сказано об этом', () => {
    const о = охрана({ платформа: 'android', тревогиВедутся: false, готовность: г(), фон: фонОк, сенсорМолчитМин: 2 });
    expect(о.ответ).toBe('не сторожим');
  });

  /* Пропажу данных сторожит движок своим правилом. Нет правила — молчание сенсора выглядит ровно
     как хороший сахар, и обещать «разбудим» нельзя. Кнопки при этом не предлагаем: правила у движка,
     и включить их отсюда нечем. */
  it('у движка нет правила про молчание — «может не разбудить», но чинить нечем', () => {
    const о = охрана({ платформа: 'android', тревогиВедутся: true, порогМолчанияМин: null, готовность: г(), фон: фонОк, сенсорМолчитМин: 2 });
    expect(о.ответ).toBe('может не разбудить');
    expect(о.строки.some((с) => с.имя === 'Заметим пропажу данных' && с.знак === 'нет')).toBe(true);
    expect(о.строки.every((с) => с.действие !== undefined ? с.действие !== ('включить сторож' as never) : true)).toBe(true);
  });

  /* «Не знаем» — третий знак, и он не должен превращаться в «сломано»: неизвестное про
     прошивку не повод пугать человека каждый вечер. */
  it('неизвестное не считается поломкой', () => {
    const о = охрана({ платформа: 'android', тревогиВедутся: true, порогМолчанияМин: 30, готовность: г(), фон: null, сенсорМолчитМин: 2 });
    expect(о.ответ).toBe('разбудим');
    expect(о.строки.some((с) => с.знак === 'не знаем')).toBe(true);
  });

  it('сборки старше проверки честно говорят, что не знают', () => {
    const о = охрана({ платформа: 'android', тревогиВедутся: true, порогМолчанияМин: 30, готовность: null, фон: фонОк, сенсорМолчитМин: 2 });
    expect(о.ответ).toBe('не сторожим');
    expect(о.строки[0].знак).toBe('не знаем');
  });

  it('данных давно нет — это часть того же обещания', () => {
    const о = охрана({ платформа: 'android', тревогиВедутся: true, порогМолчанияМин: 30, готовность: г(), фон: фонОк, сенсорМолчитМин: 40 });
    expect(о.ответ).toBe('может не разбудить');
  });
});

/* АЙФОН — отдельная модель обещания (core#115). Ночью его будит не система, а мы сами:
   собственный звук приложения — единственное, что пробивает беззвучный режим. */
describe('айфон обещает ровно то, что может', () => {
  const ios = (п: { звук: boolean; тревоги?: boolean }) => охрана({
    платформа: 'ios', тревогиВедутся: п.тревоги ?? true, готовность: null, фон: null,
    сенсорМолчитМин: 2, ночнойЗвук: п.звук,
  });

  it('звук держим — обещание в силе', () => {
    expect(ios({ звук: true }).ответ).toBe('разбудим');
  });

  /* Главная ошибка, которую этот тест закрывает: раньше здесь стояло «не сторожим»
     всегда, и айфон выглядел безнадёжным, хотя лечится одним переключателем. */
  it('звука нет — «может не разбудить», и предлагается включить, а не смириться', () => {
    const о = ios({ звук: false });
    expect(о.ответ).toBe('может не разбудить');
    expect(о.главное).toBe('включить ночной звук');
  });

  /* Правил нет — на айфоне это тем более «не сторожим»: считать некому, и предлагать включить
     звук бессмысленно, звучать всё равно нечему. */
  it('движок правил не отдаёт — не сторожим, и кнопки не предлагаем', () => {
    const о = ios({ звук: false, тревоги: false });
    expect(о.ответ).toBe('не сторожим');
    expect(о.главное).toBe(undefined);
  });

  /* Про выгрузку приложения говорим всегда и отдельным знаком: это не поломка, которую
     чинят, а предел, о котором человек должен знать до того, как ляжет спать. */
  it('предел назван даже при исправном состоянии', () => {
    expect(ios({ звук: true }).строки.some((с) => с.знак === 'не знаем' && /выгруз/.test(с.имя))).toBe(true);
  });
});

/* Коды вместо разбора фразы (#475). Раньше все поломки разрешений валились в один пункт,
   а кнопку выбирали, ища в тексте подстроку «Не беспокоить» — способ, который ломается от
   правки формулировки. */
describe('поломки раскладываются по пунктам по коду', () => {
  const с = (код: string, текст = 'что-то не так') => охрана({
    платформа: 'android', тревогиВедутся: true, порогМолчанияМин: 30, фон: null, сенсорМолчитМин: 2,
    готовность: { проблема: true, чегоНет: [текст], поломки: [{ код, текст }] },
  });

  it('полный экран — свой пункт и своя кнопка', () => {
    const о = с('fullscreen');
    const строка = о.строки.find((x) => x.знак === 'нет');
    expect(строка?.имя).toBe('Покажем на весь экран');
    expect(строка?.действие).toBe('разрешить полный экран');
  });

  it('«не беспокоить» — про звук', () => {
    expect(с('dnd-access').строки.find((x) => x.знак === 'нет')?.действие).toBe('доступ к «Не беспокоить»');
  });

  /* Понижённый канал чинится только руками в системных настройках, отдельного экрана нет.
     Кнопка, которая никуда не ведёт, хуже её отсутствия. */
  it('понижённый канал показываем, но кнопку не обещаем', () => {
    const строка = с('channel-lowered').строки.find((x) => x.знак === 'нет');
    expect(строка).toBeTruthy();
    expect(строка?.действие).toBeUndefined();
  });

  /* Сборки старше кодов присылают только фразы: показать поломку не в том пункте лучше,
     чем не показать вовсе. */
  it('без кодов поломка всё равно видна', () => {
    const о = охрана({
      платформа: 'android', тревогиВедутся: true, порогМолчанияМин: 30, фон: null, сенсорМолчитМин: 2,
      готовность: { проблема: true, чегоНет: ['старая фраза'], поломки: [{ код: 'dnd-access', текст: 'старая фраза' }] },
    });
    expect(о.ответ).toBe('может не разбудить');
  });
});

/* Старое ядро — отдельный ответ, а не «правил нет» (#482). Своей логики решений у нас не осталось,
   и молчание здесь неотличимо от исправной работы: человек ляжет спать, думая, что защищён. */
describe('ядро старее модели тревог', () => {
  const г2 = (): ГотовностьТревог => ({ проблема: false, чегоНет: [], поломки: [] });
  const фон2 = { ignoring: true, manufacturer: 'x', problem: false, reason: '', whatToDo: '', weCanOpenSettings: false };

  it('говорим про обновление приложения, а не про настройки', () => {
    const о = охрана({
      платформа: 'android', тревогиВедутся: false, ядроСтарое: true,
      готовность: г2(), фон: фон2, сенсорМолчитМин: 2,
    });
    expect(о.ответ).toBe('не сторожим');
    expect(о.почему).toContain('ядро старее');
    expect(о.строки[0].под).toContain('обновите приложение целиком');
    /* Кнопки нет: починить сборку ядра человек не может, а кнопка, которая ничего не умеет,
       хуже честного молчания. */
    expect(о.главное).toBe(undefined);
  });

  it('новое ядро без правил — другая фраза', () => {
    const о = охрана({
      платформа: 'android', тревогиВедутся: false, ядроСтарое: false,
      готовность: г2(), фон: фон2, сенсорМолчитМин: 2,
    });
    expect(о.почему).toContain('не следит ни за чем');
  });
});
