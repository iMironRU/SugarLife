import { describe, it, expect, beforeEach, vi } from 'vitest';
import { строки, type ПунктНатива } from './разрешения';
import type { PermissionView } from '@/sources/bridge';

/* Хранилище подменяем, а не тянем jsdom: модуль читает один ключ, и целая среда браузера ради
   этого — плата не по делу. */
const склад = new Map<string, string>();
vi.stubGlobal('localStorage', {
  getItem: (k: string) => склад.get(k) ?? null,
  setItem: (k: string, v: string) => { склад.set(k, v); },
  removeItem: (k: string) => { склад.delete(k); },
});

const { знакомствоНужно, чтоПоказать, знакомствоЗакрыто, знакомствоБыло, толькоРассказать } =
  await import('./первоеЗнакомство');

const п = (id: string, статус: ПунктНатива['статус'], спросить = false): ПунктНатива =>
  ({ id, статус, спросить });

const из = (o: Partial<PermissionView> & { id: string }): PermissionView => ({
  need: 'Обязательно', purpose: 'Выживание', platforms: ['Android', 'iOS'],
  gives: 'что даёт', withoutIt: 'что останется', price: null, checkable: true, whyYou: null, ...o,
});

describe('первое знакомство', () => {
  beforeEach(() => склад.clear());

  it('зовём, когда обязательного не хватает', () => {
    const с = строки([п('батарея', 'нет')], [из({ id: 'БезЭкономииБатареи' })]);
    expect(знакомствоНужно(true, с)).toBe(true);
  });

  it('молчим, когда всё на месте: стена галочек учит пролистывать', () => {
    const с = строки([п('батарея', 'разрешено')], [из({ id: 'БезЭкономииБатареи' })]);
    expect(чтоПоказать(с)).toHaveLength(0);
    expect(знакомствоНужно(true, с)).toBe(false);
  });

  it('желательное в первую минуту не показываем', () => {
    const с = строки([п('камера', 'нет')], [из({ id: 'Камера', need: 'Желательно' })]);
    expect(чтоПоказать(с)).toHaveLength(0);
    expect(знакомствоНужно(true, с)).toBe(false);
  });

  it('в вебе не зовём: чинить там нечего', () => {
    const с = строки([п('батарея', 'нет')], [из({ id: 'БезЭкономииБатареи' })]);
    expect(знакомствоНужно(false, с)).toBe(false);
  });

  it('второй раз не зовём — дальше этим занят путь вечера', () => {
    const с = строки([п('батарея', 'нет')], [из({ id: 'БезЭкономииБатареи' })]);
    expect(знакомствоБыло()).toBe(false);
    знакомствоЗакрыто();
    expect(знакомствоБыло()).toBe(true);
    expect(знакомствоНужно(true, с)).toBe(false);
  });

  it('«ещё не спрашивали» — тоже повод провести: разрешения ещё нет', () => {
    const с = строки([п('уведомления', 'не спрашивали', true)], [из({ id: 'Уведомления' })]);
    expect(чтоПоказать(с).map((р) => р.id)).toEqual(['уведомления']);
  });

  it('непроверяемое отделяем: у него кнопки нет и быть не может', () => {
    const с = строки(
      [п('батарея', 'нет')],
      [из({ id: 'БезЭкономииБатареи' }), из({ id: 'ВендорскаяЗащита', checkable: false, platforms: ['Android'] })],
      'Android');
    expect(чтоПоказать(с).map((р) => р.id)).toContain('ВендорскаяЗащита');
    expect(толькоРассказать(с).map((р) => р.id)).toEqual(['ВендорскаяЗащита']);
  });

  it('без каталога не зовём: чего именно не хватает, знает движок', () => {
    const с = строки([п('батарея', 'нет')]);
    expect(знакомствоНужно(true, с)).toBe(false);
  });
});
