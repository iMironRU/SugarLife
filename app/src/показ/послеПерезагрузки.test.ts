import { describe, it, expect } from 'vitest';
import { послеПерезагрузки, ПОРОГ_ПО_УМОЛЧАНИЮ_МИН } from './послеПерезагрузки';
import type { GuardGapView } from '@/sources/bridge';

const р = (п: Partial<GuardGapView> = {}): GuardGapView =>
  ({ atMs: 1_000, minutes: 40, why: 'reboot', words: 'Нас не было 40 минут после перезагрузки.', ...п });

describe('послеПерезагрузки', () => {
  it('перезагрузка длиннее порога — говорим словами движка', () => {
    const о = послеПерезагрузки({ история: [р()] });
    expect(о?.текст).toBe('Нас не было 40 минут после перезагрузки.');
    expect(о?.поМс).toBe(1_000);
  });

  it('короче порога — молчим: обещание движка не нарушено', () => {
    expect(послеПерезагрузки({ история: [р({ minutes: ПОРОГ_ПО_УМОЛЧАНИЮ_МИН })] })).toBeNull();
  });

  it('порог берём у движка, а не свой', () => {
    const короткий = [р({ minutes: 25 })];
    expect(послеПерезагрузки({ история: короткий, порогМолчанияМин: 30 })).toBeNull();
    expect(послеПерезагрузки({ история: короткий, порогМолчанияМин: 20 })).not.toBeNull();
  });

  it('смахнули или убили — это другая беда и другой разговор', () => {
    expect(послеПерезагрузки({ история: [р({ why: 'swiped' }), р({ why: 'killed' })] })).toBeNull();
  });

  it('о чём уже говорили — второй раз не говорим', () => {
    expect(послеПерезагрузки({ история: [р({ atMs: 5_000 })], сказаноПо: 5_000 })).toBeNull();
    expect(послеПерезагрузки({ история: [р({ atMs: 6_000 })], сказаноПо: 5_000 })).not.toBeNull();
  });

  it('новостью служит самый долгий, а не сумма: три по двадцать и один час — разные ночи', () => {
    const о = послеПерезагрузки({ история: [
      р({ atMs: 1, minutes: 20, words: 'двадцать' }),
      р({ atMs: 2, minutes: 60, words: 'час' }),
      р({ atMs: 3, minutes: 20, words: 'двадцать' }),
    ] });
    expect(о?.текст).toBe('час И ещё 2 раза за это время.');
    /* Отметка — по самому свежему, иначе о старых расскажем ещё раз. */
    expect(о?.поМс).toBe(3);
  });

  it('склонение считаем, а не подставляем', () => {
    const много = (n: number) => послеПерезагрузки({ история: [
      р({ atMs: 100, minutes: 99, words: 'долго' }),
      ...Array.from({ length: n }, (_, i) => р({ atMs: i + 1, minutes: 30, words: 'к' })),
    ] })?.текст ?? '';
    expect(много(1)).toContain('1 раз ');
    expect(много(2)).toContain('2 раза ');
    expect(много(5)).toContain('5 раз ');
    expect(много(11)).toContain('11 раз ');
    expect(много(22)).toContain('22 раза ');
  });

  it('истории нет — говорить не о чем', () => {
    expect(послеПерезагрузки({ история: null })).toBeNull();
    expect(послеПерезагрузки({})).toBeNull();
  });
});
