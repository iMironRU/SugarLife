import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/* СТОРОЖ ОДНОГО ОТВЕТА (#528, #530).

   Правило «инсулин берём там же, где экран» было записано словами в App.tsx и всё равно нарушено:
   к сегодняшнему дню на один вопрос отвечали три места, и одно из них кормило экран блокировки.
   Владелец увидел три разных числа об одном инсулине на трёх поверхностях.

   Записанное правило ничего не стережёт. Стережёт проверка.

   ЧТО ИМЕННО ЗАПРЕЩЕНО: считать активный инсулин где-либо, кроме показ/сейчас.ts. Не «читать
   снимок» — читать его можно, вопросов к снимку много. Запрещено ВТОРОЙ РАЗ ОТВЕЧАТЬ на вопрос, у
   которого уже есть один ответ.

   Список разрешённых — поимённо, а не по каталогу: каталог растёт сам, и однажды в него попадёт
   файл, которому туда не надо. */

const КОРЕНЬ = join(process.cwd(), 'src');

/** Кто вправе считать активный инсулин. Всё остальное обязано спрашивать. */
const ХОЗЯЕВА = [
  'показ/сейчас.ts',        // единственный ответ для экрана и поверхностей
  'показ/чужаяПетля.ts',    // выбор «свой или чужой» — сама механика выбора
  'domain/loopValue.ts',    // свежесть чужого расчёта
];

/** Признаки собственного расчёта инсулина. */
const ПРИЗНАКИ = [/активныйИнсулин\s*\(/, /activeInsulin\s*\(/];

function файлы(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? файлы(p) : [p];
  });
}

describe('на вопрос об активном инсулине отвечает одно место', () => {
  it('никто, кроме хозяев, его не считает', () => {
    const нарушители: string[] = [];
    for (const f of файлы(КОРЕНЬ)) {
      if (!f.endsWith('.ts') && !f.endsWith('.tsx')) continue;
      if (f.endsWith('.test.ts') || f.endsWith('.test.tsx')) continue;
      const отн = f.slice(КОРЕНЬ.length + 1);
      if (ХОЗЯЕВА.includes(отн)) continue;
      const текст = readFileSync(f, 'utf8');
      if (ПРИЗНАКИ.some((м) => м.test(текст))) нарушители.push(отн);
    }
    expect(нарушители).toEqual([]);
  });
});

import { подписьОстатка } from './сейчас';

/* ПОДПИСЬ ПОД ОСТАТКОМ НА ПЛИТКЕ «ПОМПА».

   Утром здесь было пустое место: свой врущий срок мы убрали, а движок молчал, пока охвата
   истории меньше шести часов. Владелец прочитал пустоту как поломку — и был прав.

   Днём ядро закрыло обе половины: остаток теперь переживает перезапуск (#158), а строку под
   числом присылает готовой — `shortWords`. Своей вёрстки здесь не осталось совсем, и тест
   стережёт именно это: подпись обязана быть ЕГО словами, а не собранными заново нашими. */
describe('подпись под остатком на плитке', () => {
  it('показывает короткую строку движка как есть', () => {
    const п = подписьОстатка({ units: 262, words: 'Осталось 262 ед. Хватит на 2 д 3 ч.', shortWords: '≈ 2 д 3 ч' });
    expect(п.текст).toBe('≈ 2 д 3 ч');
    expect(п.тревожно).toBe(false);
  });

  it('движок ещё считает расход — говорит об этом сам, и мы не молчим', () => {
    const п = подписьОстатка({ units: 262, runsOutAtMs: null, shortWords: 'считаем расход', words: '' });
    expect(п.текст).toBe('считаем расход');
  });

  it('«до утра не хватит» красит подпись, но слов не добавляет', () => {
    /* Ядро в #158 сказало прямо: тревогу в короткую строку оно НЕ кладёт — «важное, сказанное
       там, где на него не смотрят». Вечернее напоминание приходит тревогой, а признак
       `enoughUntilMorning` остаётся нам, чтобы подкрасить.

       Поэтому строка здесь обычная, срочная только по смыслу, — а жёлтой её делаем мы. Своих
       слов не дописываем: их место занято, и занято правильно. */
    const п = подписьОстатка({ units: 12, enoughUntilMorning: false, shortWords: '≈ 4 ч', words: '' });
    expect(п.текст).toBe('≈ 4 ч');
    expect(п.тревожно).toBe(true);
  });

  it('снимка нет вовсе — ничего не выдумываем', () => {
    expect(подписьОстатка(null)).toEqual({ текст: '', тревожно: false });
  });

  it('своей строки не собираем даже когда есть из чего', () => {
    /* Срок и расход на месте, а короткой строки нет: старый мост. Соблазн собрать «≈ 3 д» самим
       ровно здесь и появлялся дважды. Не собираем: это второй ответ на один вопрос. */
    const п = подписьОстатка({ units: 262, runsOutAtMs: 9e12, perHour: 3.3, words: 'что-то', shortWords: '' });
    expect(п.текст).toBe('');
  });
});
