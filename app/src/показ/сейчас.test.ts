import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { подписьОстатка } from '@/показ/сейчас';

/* СТОРОЖ ОДНОГО ОТВЕТА (#528, #530).

   Правило «инсулин берём там же, где экран» было записано словами в App.tsx и всё равно нарушено:
   к сегодняшнему дню на один вопрос отвечали три места, и одно из них кормило экран блокировки.
   Владелец увидел три разных числа об одном инсулине на трёх поверхностях.

   Записанное правило ничего не стережёт. Стережёт проверка.

   ЧТО ИМЕННО ЗАПРЕЩЕНО: считать активный инсулин где-либо, кроме показ/сейчас.ts. Не «читать
   снимок» — читать его можно, вопросов к снимку много. Запрещено ВТОРОЙ РАЗ ОТВЕЧАТЬ на вопрос, у
   которого уже есть один ответ.

   Список разрешённых — поимённо, а не по каталогу: каталог растёт сам, и однажды в него попадёт
   файл, которому туда не надо. */

const КОРЕНЬ = join(process.cwd(), 'src');

/** Кто вправе считать активный инсулин. Всё остальное обязано спрашивать. */
const ХОЗЯЕВА = [
  'показ/сейчас.ts',        // единственный ответ для экрана и поверхностей
  'показ/чужаяПетля.ts',    // выбор «свой или чужой» — сама механика выбора
  'domain/loopValue.ts',    // свежесть чужого расчёта
];

/** Признаки собственного расчёта инсулина. */
const ПРИЗНАКИ = [/активныйИнсулин\s*\(/, /activeInsulin\s*\(/];

function файлы(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? файлы(p) : [p];
  });
}

describe('на вопрос об активном инсулине отвечает одно место', () => {
  it('никто, кроме хозяев, его не считает', () => {
    const нарушители: string[] = [];
    for (const f of файлы(КОРЕНЬ)) {
      if (!f.endsWith('.ts') && !f.endsWith('.tsx')) continue;
      if (f.endsWith('.test.ts') || f.endsWith('.test.tsx')) continue;
      const отн = f.slice(КОРЕНЬ.length + 1);
      if (ХОЗЯЕВА.includes(отн)) continue;
      const текст = readFileSync(f, 'utf8');
      if (ПРИЗНАКИ.some((м) => м.test(текст))) нарушители.push(отн);
    }
    expect(нарушители).toEqual([]);
  });
});

import { наСколькоХватитДней } from './сейчас';

/* На сколько хватит инсулина. Проверяем то, что в компоненте было выражением в одну строку и
   потому ловилось только глазами на телефоне — через несколько недель после появления. */
describe('на сколько хватит инсулина', () => {
  const сейчас = 1_000_000_000_000;

  it('срок от движка — самый прямой ответ', () => {
    const через3дня = сейчас + 3 * 86400e3;
    expect(наСколькоХватитДней({ units: 262, runsOutAtMs: через3дня, words: '' }, 262, сейчас))
      .toBeCloseTo(3, 5);
  });

  /* Ровно случай владельца: 262 ед при 3,3 ед/час — это 3,3 дня, а не 7 д 3 ч. */
  it('нет срока — считаем по измеренному расходу', () => {
    const д = наСколькоХватитДней({ units: 262, perHour: 3.3, words: '' }, 262, сейчас);
    expect(д).not.toBeNull();
    expect(д!).toBeGreaterThan(3.2);
    expect(д!).toBeLessThan(3.4);
  });

  /* Своего запасного расчёта нет: оценка, врущая вдвое в опасную сторону, хуже отсутствующей. */
  it('движок молчит — молчим и мы', () => {
    expect(наСколькоХватитДней(null, 262, сейчас)).toBeNull();
    expect(наСколькоХватитДней({ units: 262, words: '' }, 262, сейчас)).toBeNull();
  });

  /* Ноль в расходе — не «хватит навсегда», а деление на ноль. */
  it('нулевой расход ответом не считаем', () => {
    expect(наСколькоХватитДней({ units: 262, perHour: 0, words: '' }, 262, сейчас)).toBeNull();
  });

  /* Срок уже прошёл — ноль, а не отрицательное число дней. */
  it('срок в прошлом даёт ноль, а не минус', () => {
    expect(наСколькоХватитДней({ units: 5, runsOutAtMs: сейчас - 86400e3, words: '' }, 5, сейчас))
      .toBe(0);
  });
});

describe('подпись под остатком на плитке', () => {
  const дниЧасы = (д: number) => `${Math.floor(д)} д`;
  const срок = (дней: number) => СЕЙЧАС + дней * 86400e3;
  const СЕЙЧАС = 1_700_000_000_000;

  it('есть срок — показываем срок', () => {
    const п = подписьОстатка(
      { units: 262, runsOutAtMs: срок(3), words: '' },
      262,
      СЕЙЧАС,
      дниЧасы,
    );
    expect(п.текст).toBe('≈ 3 д');
    expect(п.тревожно).toBe(false);
  });

  it('срока нет и вердикта нет — говорим, почему пусто, а не молчим', () => {
    /* Ровно случай владельца: движок прислал «Осталось 262 ед. Расход пока не посчитан».
       До этого места на плитке было пустое место, и оно читалось как поломка. */
    const п = подписьОстатка(
      { units: 262, perHour: null, runsOutAtMs: null, enoughUntilMorning: null, words: '' },
      262,
      СЕЙЧАС,
      дниЧасы,
    );
    expect(п.текст).toBe('расход считается');
    expect(п.тревожно).toBe(false);
  });

  it('срока нет, но движок сказал «до утра не хватит» — вердикт не теряем', () => {
    /* Вердикт движок говорит и на коротком окне: заниженный расход означает, что не хватит
       тем более. Это дороже срока, и на плитке он должен быть виден. */
    const п = подписьОстатка(
      { units: 12, runsOutAtMs: null, enoughUntilMorning: false, words: '' },
      12,
      СЕЙЧАС,
      дниЧасы,
    );
    expect(п.текст).toBe('до утра не хватит');
    expect(п.тревожно).toBe(true);
  });

  it('срок есть, но до утра не хватит — показываем срок и всё равно тревожимся', () => {
    const п = подписьОстатка(
      { units: 6, runsOutAtMs: срок(0.2), enoughUntilMorning: false, words: '' },
      6,
      СЕЙЧАС,
      дниЧасы,
    );
    expect(п.текст).toBe('≈ 0 д');
    expect(п.тревожно).toBe(true);
  });

  it('снимка нет вовсе — не выдумываем ни срока, ни тревоги', () => {
    const п = подписьОстатка(null, null, СЕЙЧАС, дниЧасы);
    expect(п.текст).toBe('расход считается');
    expect(п.тревожно).toBe(false);
  });
});
