import { порогМолчанияМин } from './порогМолчания';
import { прочитать, записать } from '@/settings/storage';
import { useSnapshot } from '@/sources/bridge';
import { готовностьТревог, громкостьТревоги, фокусРазрешён, type ГотовностьТревог, type ГромкостьТревоги } from '@/platform/тревоги';
import { фонГотовность, бодрствование, type ФонОтвет } from '@/platform/фон';
