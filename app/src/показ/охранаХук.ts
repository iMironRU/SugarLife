/* Один сбор для двух мест: раздела «Охрана» и строки на «Сегодня» (#473).

   Спрашиваем натив дважды — про тревоги и про фон, — и делать это в двух компонентах
   значило бы два разных ответа на один вопрос в один момент времени.

   ОДНОГО ХУКА ДЛЯ ЭТОГО МАЛО (#500). Строка на «Сегодня» и раздел «Охрана» держат по своей копии
   состояния: человек включал ночной звук в разделе, тот перечитывал натив и говорил «разбудим», а
   строка на «Сегодня» продолжала показывать «может не разбудить», потому что спрашивала при своём
   первом показе и больше не спрашивала. Два ответа на один вопрос в одном приложении — и человек
   справедливо не знает, какому верить.

   Поэтому перечитывают ВСЕ и одновременно: `обновить()` будит каждого потребителя, а не своего
   владельца. По той же причине перечитываем при возвращении в приложение: доступ мог быть выдан в
   системных настройках, куда мы сами же и отправили. */
const слушатели = new Set<() => void>();

/** Перечитать состояние охраны во всех местах, где оно показано. */
function перечитатьОхрану(): void {
  слушатели.forEach((ф) => ф());
}

/* СПИСОК ФОКУСА «НЕ БЕСПОКОИТЬ» — ЕДИНСТВЕННОЕ, ЧТО МЫ СПРАШИВАЕМ У ЧЕЛОВЕКА (#561).

   Состав фокуса система приложению не отдаёт: это приватная настройка. А без него на сборке без
   права на срочные ответ «ночью может не разбудить» становится вечным — погасить его нечем.
   Поэтому спрашиваем один раз и запоминаем; ошибиться человек может, и это его право: свой экран
   настроек он видел, а мы нет. */
const КЛЮЧ_ФОКУСА = 'sl.focus-allowed';

export function подтвердитьФокус(да: boolean): void {
  записать(КЛЮЧ_ФОКУСА, да ? 'да' : 'нет');
  /* И НАТИВУ ТОЖЕ — иначе движок об этом не узнает (#685). Ответ хранился только здесь, а доклад
     о доставке собирает натив: движок продолжал слышать «доступа нет» и просил починить то, что
     человек уже починил. Просьба, которую нельзя погасить, приучает пролистывать предупреждения. */
  void фокусРазрешён(да);
  перечитатьОхрану();
}

export function фокусПодтверждён(): boolean {
  return прочитать(КЛЮЧ_ФОКУСА) === 'да';
}

export function useОхрана(): { охрана: Охрана | null; обновить: () => void; платформа: Платформа } {
  const снимок = useSnapshot();
  const [готовность, setГотовность] = useState<ГотовностьТревог | null>(null);
  const [фон, setФон] = useState<ФонОтвет | null>(null);
  const [звук, setЗвук] = useState(false);
  const [громкость, setГромкость] = useState<ГромкостьТревоги | null>(null);
  const [спросили, setСпросили] = useState(false);
  /* Счётчик перечитываний. Без него экран, на котором человек только что выдал доступ или
     включил тревогу, продолжал бы показывать прежний ответ: состояние живёт в системе, а
     не у нас, и узнать о перемене можно только спросив заново. Молчаливо не изменившийся
     ответ после нажатия читается как «не сработало». */
  const [заход, setЗаход] = useState(0);

  useEffect(() => {
    let жив = true;
    /* Живой баннер отсюда ушёл вместе со своей строкой (#500): он не будит, и спрашивать о нём
       здесь больше нечего. */
    void Promise.all([готовностьТревог(), фонГотовность(), бодрствование(), громкостьТревоги()])
      .then(([г, ф, бд, гр]) => {
        if (!жив) return;
        setГотовность(г); setФон(ф); setГромкость(гр);
        setЗвук(!!бд && бд.режим !== 'выключено');
        setСпросили(true);
      });
    return () => { жив = false; };
  }, [заход]);

  useEffect(() => {
    const ещёРаз = () => setЗаход((з) => з + 1);
    слушатели.add(ещёРаз);
    /* Возврат в приложение — тот самый момент, когда ответ мог измениться без нас: человек ходил
       выдавать доступ в системные настройки. */
    const приВозврате = () => { if (document.visibilityState === 'visible') ещёРаз(); };
    document.addEventListener('visibilitychange', приВозврате);
    return () => { слушатели.delete(ещёРаз); document.removeEventListener('visibilitychange', приВозврате); };
  }, []);

  const обновить = () => перечитатьОхрану();
  /* Платформу считаем ДО раннего выхода: она нужна разделу и тогда, когда ответа про охрану ещё
     нет. Ниже она стояла после `if (!спросили)`, и на первом кадре раздел получал бы пустоту. */
  const платформа: Платформа = !Capacitor.isNativePlatform() ? 'веб'
    : Capacitor.getPlatform() === 'ios' ? 'ios' : 'android';
  if (!спросили) return { охрана: null, обновить, платформа };
  const м = снимок?.monitor;
  /* Кто считает тревоги — видно в снимке: есть правила, значит считает движок (#482). Своей
     настройки «тревоги включены» у нас больше нет, и спрашивать натив об этом нечего. */
  /* Умеет ли ядро тревоги вообще — по ревизии, а не по наличию правил: пустой список бывает и у
     нового ядра, а старое не отдаст их никогда. Причины разные, и ответ человеку тоже разный. */
  const умеет = ядроУмеетТревоги(снимок?.bridgeRevision);
  const правила = снимок?.alarmRules ?? [];
  /* Порог берём по имени ключа, а не по порядку (показ/порогМолчания.ts). Здесь стоял поиск
     «первого ключа со словом silence», то есть дневной или ночной срок — как повезёт с порядком
     полей в снимке. Число на экране в обоих случаях выглядело настоящим. */
  const порогМолчания = порогМолчанияМин(правила, 'день');
  /* Ответ движка главнее нашего расчёта (мост 1.49). Наш остаётся для ядра старше — совсем убрать
     его сейчас значило бы оставить экран пустым на старой сборке. */
  if (снимок?.nightPromise) return { охрана: изОбещания(снимок.nightPromise, платформа), обновить, платформа };
  const итог = охрана({
    /* Ответ человека про список фокуса (#561): проверить его нечем, поэтому просто помним. */
    фокусПодтверждён: прочитать(КЛЮЧ_ФОКУСА) === 'да',
    платформа,
    ночнойЗвук: звук,
    громкость,
    тревогиВедутся: умеет && правила.length > 0,
    ядроСтарое: !умеет,
    порогМолчанияМин: порогМолчания,
    готовность,
    фон,
    сенсорМолчитМин: м?.latestAtMs ? Math.max(0, Math.round((Date.now() - м.latestAtMs) / 60_000)) : null,
  });
  /* Платформа наружу: цену ночного звука спрашиваем только на айфоне, а считать её заново
     в разделе значило бы завести второе мнение о том же. */
  return { охрана: итог, обновить, платформа };
}

/* СКОЛЬКО КРАСНОГО В ОХРАНЕ — ОДНО ЧИСЛО НА ВСЕ МЕСТА (#523).

   «Красное» на экране и «красное» в цифре обязаны быть одним и тем же — иначе повторим историю двух
   светофоров: у каждого своё мнение, и расходятся они молча. Поэтому счётчик считается ЗДЕСЬ, из тех
   же строк, что рисует раздел, а не заново на каждом экране.

   Считаем только то, что человек может починить сейчас: пункты со знаком «нет». «Не знаем» в цифру не
   идёт — иначе бейдж будет висеть всегда (список фокуса нам не спросить никогда), и его перестанут
   замечать ровно к тому дню, когда он что-то значит. */
export function useКрасноеВОхране(): number {
  const { охрана } = useОхрана();
  if (!охрана) return 0;
  return охрана.строки.filter((с) => с.знак === 'нет').length;
}
