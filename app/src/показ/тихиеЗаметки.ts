import type { ActiveAlarmView, UiSnapshot } from '@/sources/bridge';

/* ТИХАЯ ПОЛОСА: ТО, ЧТО ГОВОРЯТ, НО НЕ ТРЕБУЮТ ОТВЕТА (#812, ядро #811).

   `ЖивыеТревоги` отсеивают всё, у чего `needsAck` не стоит, и отсеивают правильно: полоса
   заводилась как место, где на тревогу ОТВЕЧАЮТ, и строка без действия там просто занимает первый
   экран. Но из этого вышло, что `УровеньТревоги.Заметка` не показывается вообще НИГДЕ — движок его
   шлёт, а человек не видит.

   Первым это вскрылось на «полёте вниз» (#811): движок предупреждает за 46 минут вместо девяти у
   сирены, но только если есть куда сказать.

   ПОЧЕМУ ОТДЕЛЬНАЯ ПОЛОСА, А НЕ ЕЩЁ ОДНА СТРОКА У ТРЕВОГ. У них разная цена ошибки. Тревога права
   почти всегда и требует действия; заметка права в одном случае из пяти — это измерено на 598
   сутках — и не требует ничего. Смешать их значит либо приучить отвечать на то, что ответа не
   ждёт, либо обесценить настоящую тревогу соседством. Полоса «полёт вниз» — спидометр: ему и
   положено гореть часто.

   БЕРЁМ ПО УРОВНЮ, А НЕ ПО ИМЕНИ ТРЕВОГИ. `полёт-вниз` сегодня один, но заметки будут и другие, и
   каждую новую пришлось бы вписывать сюда руками — то есть однажды не вписать, и она снова
   пропала бы молча. Уровень и есть общее правило: «сказать, не требуя».

   СЛОВ СВОИХ НЕ ПИШЕМ. `words` собираются заново на каждый снимок, значит числа в них свежие. Про
   падение сахара это к тому же медицинское высказывание, и двух его редакций быть не должно. */

export interface Заметка {
  id: string;
  /** Готовая фраза движка. Пустых сюда не пускаем. */
  текст: string;
  /** Когда началась — для порядка: свежая выше. */
  когда: number;
}

/** Уровень, который говорит и ничего не требует. */
const ТИХИЙ = 'Заметка';

export function тихиеЗаметки(снимок: UiSnapshot | null | undefined): Заметка[] {
  const все: ActiveAlarmView[] = снимок?.alarmsNow ?? [];
  return все
    .filter((т) => т.level === ТИХИЙ)
    /* `needsAck` у заметки не стоит по смыслу. Но если движок однажды пришлёт заметку, ждущую
       ответа, её место на полосе тревог, а не здесь: там есть кнопка. Молча забрать её себе
       значило бы спрятать действие. */
    .filter((т) => !т.needsAck)
    .filter((т) => !!т.words)
    .map((т) => ({ id: т.id, текст: т.words, когда: т.sinceMs ?? 0 }))
    .sort((а, б) => б.когда - а.когда);
}
