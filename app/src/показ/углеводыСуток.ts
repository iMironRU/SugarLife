import { onlyLocal } from '@/domain/meals';
import type { Meal } from '@/domain/meals';
import type { Treatment } from '@/domain/types';

/* «Я ЭТО ЗАПИСАЛ?» — ВОПРОС ПРО СЕБЯ, А НЕ ПРО ИСТОЧНИК ЗАПИСИ (SugarLife#746).

   Владелец: «пишет, что сутки не вносили углеводы, а я вносил». Он вносил — в AAPS, и через
   Nightscout приёмы доехали до движка: три за сутки, 10, 15 и 25 граммов. Экран сказал «За сутки
   не вносили».

   ЧТО БЫЛО НА САМОМ ДЕЛЕ. Строка честно складывала ДВА источника — но одним из них была НАША
   СОБСТВЕННАЯ загрузка Nightscout (`sources/deviceExtras` → `loadEventsRange`), второй загрузчик
   из #528. Она включается только если облако настроено в НАШЕМ приложении; на нативной сборке
   облако держит движок, и наша загрузка молчит. Два источника на бумаге, ноль на телефоне.

   Ошибка тем и коварна, что выглядит как правильный код: строка «из обоих источников» стоит в
   комментарии рядом, и она даже правдива — просто один из двух пуст.

   МЕСТО У ФРАЗЫ ХУДШЕЕ ИЗ ВОЗМОЖНЫХ: прямо под «активные углеводы — цикл не присылал расчёт».
   Две строки подряд читаются как «еды у тебя нет и расчёта нет», то есть как приглашение поесть
   или подколоть. У человека в этот момент 25 граммов семнадцать часов назад и 10 час назад.

   ЗАЧЕМ СВОИ ЗАПИСИ ВООБЩЕ. Внесённое у нас уезжает в облако не мгновенно и возвращается оттуда
   не сразу. Без них человек внёс бы приём и продолжал читать «не вносили» — ту же неправду, но с
   другой стороны. Склейка обязательна: наш же приём вернётся из облака, и без неё он посчитается
   дважды, а задвоенные углеводы — задвоенная доза. */

export interface ПриёмСуток { t: number; carbs: number }

export function углеводыСуток(
  /* Из движка: `лентаЧеловека` уже отфильтрована его флагом `humanOnly` — что считать жизнью
     человека, решают там, где заводят имена записей. */
  изДвижка: { atMs: number; kind: string; amount: number }[] | null,
  /* Наша собственная загрузка облака. На нативной сборке пуста, в браузере — единственная. */
  изОблака: Treatment[],
  свои: Meal[],
  /* Граница слева. Двух вопросов два окна: «когда я ел в последний раз» — сутки назад,
     «сколько я съел сегодня» — с полуночи. Разные окна тут не противоречие, а разные
     вопросы, и оба задаются на одной плитке. */
  отМс: number,
): ПриёмСуток[] {
  const углеводыДвижка = (изДвижка ?? [])
    .filter((т) => /carb|углевод/i.test(т.kind) && т.amount > 0)
    .map((т) => ({ t: т.atMs, carbs: т.amount }));
  const углеводыОблака = изОблака
    .filter((e) => (e.carbs ?? 0) > 0)
    .map((e) => ({ t: e.t, carbs: e.carbs as number }));

  /* Движок и наша загрузка читают ОДНО облако: без склейки один и тот же приём пришёл бы
     дважды. Совпадением считаем минуту и грамм — точнее не бывает, потому что время записи
     у двух путей округляется по-разному. */
  const чужие = [...углеводыДвижка];
  for (const о of углеводыОблака) {
    if (!чужие.some((д) => Math.abs(д.t - о.t) < 60e3 && Math.round(д.carbs) === Math.round(о.carbs))) {
      чужие.push(о);
    }
  }

  /* Свои — только те, что ещё не вернулись из облака. Правило склейки общее (domain/meals.ts),
     и второго здесь заводить нельзя. */
  const облачные: Treatment[] = чужие.map((ч) => ({ t: ч.t, carbs: ч.carbs } as Treatment));
  const мои = onlyLocal(свои, облачные).map((m) => ({ t: m.t, carbs: m.carbs }));

  return [...чужие, ...мои].filter((п) => п.t >= отМс).sort((a, b) => a.t - b.t);
}
