import { describe, it, expect } from 'vitest';
import { часовДоПустого } from './часовДоПустого';

/* Предупреждение «резервуар кончится ночью» не срабатывало на телефоне никогда: часы
   считались из нашей загрузки Nightscout, а она на нативной сборке молчит (SugarLife#748). */
describe('часов до пустого', () => {
  const сейчас = 1_700_000_000_000;

  it('момент от движка сильнее нашей средней', () => {
    /* Даже когда средняя даёт другой ответ: движок знает базал именно этих часов, а мы нет. */
    expect(часовДоПустого(сейчас + 5 * 3600e3, 100, 24, сейчас)).toBeCloseTo(5, 5);
  });

  it('без движка считаем по средней — хуже, но лучше молчания', () => {
    expect(часовДоПустого(null, 10, 20, сейчас)).toBeCloseTo(12, 5);
  });

  /* Прошедший момент — «уже кончился», а не «минус три часа»: отрицательные часы молча
     выпали бы из всех порогов, и обращение снова не появилось бы. */
  it('прошедший момент даёт ноль, а не отрицательное', () => {
    expect(часовДоПустого(сейчас - 3 * 3600e3, 5, 24, сейчас)).toBe(0);
  });

  it('нечего считать — говорим null, а не ноль', () => {
    expect(часовДоПустого(null, null, 24, сейчас)).toBeNull();
    expect(часовДоПустого(null, 10, null, сейчас)).toBeNull();
    expect(часовДоПустого(null, 10, 0, сейчас)).toBeNull();
    expect(часовДоПустого(NaN, 10, null, сейчас)).toBeNull();
  });
});
