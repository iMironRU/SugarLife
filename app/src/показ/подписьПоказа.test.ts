import { describe, it, expect } from 'vitest';
import { подписьПоказа } from './подписьПоказа';

describe('подпись входа «Экран блокировки и значок»', () => {
  it('перечисляет включённое', () => {
    expect(подписьПоказа({ баннер: true, сводка: true, значок: 'сахар' }))
      .toBe('баннер · сводка · значок 7,9');
  });

  it('вид значка виден в подписи: 7,9 и 79 — разные ответы', () => {
    expect(подписьПоказа({ баннер: false, сводка: false, значок: 'десятые' })).toBe('значок 79');
    expect(подписьПоказа({ баннер: false, сводка: false, значок: 'мг' })).toBe('значок 142');
  });

  it('всё выключено — говорим прямо', () => {
    /* Три выключенных переключателя выглядят одинаково скучно, а означают, что телефон молчит про
       сахар вообще. Человек приходит сюда именно с этим вопросом. */
    expect(подписьПоказа({ баннер: false, сводка: false, значок: 'выключен' }))
      .toBe('сейчас ничего не показываем');
  });

  it('в браузере этих поверхностей нет — тогда описываем, а не пугаем', () => {
    expect(подписьПоказа({ баннер: null, сводка: null, значок: null }))
      .toBe('живой баннер, сводка в шторке, цифры на иконке');
  });

  it('незнакомый вид значка не выдумываем', () => {
    expect(подписьПоказа({ баннер: false, сводка: false, значок: 'что-то-новое' })).toBe('значок');
  });
});
