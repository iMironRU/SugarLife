import { describe, it, expect } from 'vitest';
import { вечернийВопрос, НЕ_РАЗБУДИТ } from './вечернийДозор';
import type { NightPromiseView, SleepView } from '@/sources/bridge';

const сон = (п: Partial<SleepView> = {}): SleepView =>
  ({ asleep: false, checkDue: true, minutesToSleep: 30, ...п });
const плохо: NightPromiseView = {
  willWake: false, answer: 'Нет доступа к «Не беспокоить» — тревога прозвучит беззвучно.',
  reasons: [], warnings: [],
};
const хорошо: NightPromiseView = { willWake: true, answer: 'Разбудим.', reasons: [], warnings: [] };
const сейчас = Date.parse('2026-09-02T22:30:00');

describe('вечернийВопрос', () => {
  it('пора и обещание нарушено — спрашиваем словами движка', () => {
    const в = вечернийВопрос({ сон: сон(), обещание: плохо, сейчас });
    expect(в?.заголовок).toBe(НЕ_РАЗБУДИТ);
    expect(в?.текст).toBe(плохо.answer);
  });

  it('всё в силе — молчим: исправное состояние каждый вечер учит смахивать не читая', () => {
    expect(вечернийВопрос({ сон: сон(), обещание: хорошо, сейчас })).toBeNull();
  });

  it('не наш час — молчим', () => {
    expect(вечернийВопрос({ сон: сон({ checkDue: false }), обещание: плохо, сейчас })).toBeNull();
    expect(вечернийВопрос({ сон: null, обещание: плохо, сейчас })).toBeNull();
  });

  it('человек уже уснул — не будим вопросом о готовности', () => {
    expect(вечернийВопрос({ сон: сон({ asleep: true }), обещание: плохо, сейчас })).toBeNull();
  });

  it('обещания от движка нет — на догадке не пугаем', () => {
    expect(вечернийВопрос({ сон: сон(), обещание: null, сейчас })).toBeNull();
  });

  it('за этот вечер уже спрашивали — второй раз молчим', () => {
    const первый = вечернийВопрос({ сон: сон(), обещание: плохо, сейчас });
    expect(первый).not.toBeNull();
    const второй = вечернийВопрос({
      сон: сон(), обещание: плохо, сейчас: сейчас + 5 * 60_000, спрашивалиЗа: первый!.ключ,
    });
    expect(второй).toBeNull();
  });

  it('ключ считается по началу окна, а не по дате: окно после полуночи — один вечер', () => {
    /* 23:50, до сна 30 минут — окно откроется в 00:20 следующего дня. Через десять минут,
       в полночь, календарная дата уже другая, а вечер тот же. */
    const до = вечернийВопрос({
      сон: сон({ minutesToSleep: 30 }), обещание: плохо, сейчас: Date.parse('2026-09-02T23:50:00'),
    });
    const после = вечернийВопрос({
      сон: сон({ minutesToSleep: 20 }), обещание: плохо, сейчас: Date.parse('2026-09-03T00:00:00'),
    });
    expect(до!.ключ).toBe(после!.ключ);
  });

  it('срока до сна движок не назвал — 22:59 и 23:01 остаются одним вечером', () => {
    const без = (t: string) => вечернийВопрос({
      сон: сон({ minutesToSleep: null }), обещание: плохо, сейчас: Date.parse(t),
    })!.ключ;
    expect(без('2026-09-02T22:29:00')).toBe(без('2026-09-02T22:31:00'));
  });

  it('следующий вечер — спрашиваем снова', () => {
    const первый = вечернийВопрос({ сон: сон(), обещание: плохо, сейчас });
    const завтра = вечернийВопрос({
      сон: сон(), обещание: плохо, сейчас: сейчас + 24 * 3600_000, спрашивалиЗа: первый!.ключ,
    });
    expect(завтра).not.toBeNull();
  });
});
