import { describe, it, expect } from 'vitest';
import { правилаНаЭкран, значениеСловом, следующее, ядроУмеетТревоги } from './правилаТревог';
import type { AlarmRuleView } from '@/sources/bridge';

/* Правила приезжают от движка, и главное их свойство — открытость списка: новая тревога должна
   появиться на экране сама. Проверяем именно это, а не красоту подписей. */

const правило = (п: Partial<AlarmRuleView>): AlarmRuleView => ({
  id: 'гипо', level: 'Разбудить', kind: 'low', settings: {}, ...п,
});

describe('правила тревог на экран', () => {
  it('знакомое правило получает имя и человеческий уровень', () => {
    const [п] = правилаНаЭкран([правило({ settings: { 'targets.lowMmol': '3.9' } })]);
    expect(п.имя).toBe('Низкий сахар');
    expect(п.уровень).toBe('разбудит ночью');
    expect(значениеСловом(п.поля[0])).toBe('3,9');
    expect(п.поля[0].единица).toBe('ммоль');
  });

  /* Новая тревога от движка обязана показаться, а не пропасть: имя берём из id (он и так словами),
     единицу и шаг угадываем по окончанию ключа. Догадка безопасна — значение правит человек, а
     проверяет движок. */
  it('незнакомое правило показывается, а не теряется', () => {
    const [п] = правилаНаЭкран([правило({
      id: 'катетер-стар', kind: 'catheterAge', settings: { 'alarms.catheter.hoursMin': '72' },
    })]);
    expect(п.имя).toBe('катетер-стар');
    expect(п.поля[0].единица).toBe('мин');
    expect(значениеСловом(п.поля[0])).toBe('72');
  });

  it('«on/off» — это выключатель, а не число', () => {
    const [п] = правилаНаЭкран([правило({ kind: 'silence', settings: { 'alarms.exactWakeups': 'on' } })]);
    expect(п.поля[0].выключатель).toBe(true);
    expect(п.поля[0].включено).toBe(true);
    expect(значениеСловом(п.поля[0])).toBe('включён');
    expect(следующее(п.поля[0], 1)).toBe(null);
  });

  it('оговорка и ссылка проходят как есть', () => {
    const [п] = правилаНаЭкран([правило({
      effectiveWords: 'порог 15 мин, фактически до 24 — будильник системы неточен',
      helpUrl: 'https://example.org/точность',
    })]);
    expect(п.оговорка).toContain('фактически до 24');
    expect(п.ссылка).toBe('https://example.org/точность');
  });

  /* 0.1 + 0.2 в двоичной дроби даёт 0.30000000000000004, и такое значение уехало бы движку как есть. */
  it('шаг не тащит двоичный хвост', () => {
    const [п] = правилаНаЭкран([правило({ settings: { 'targets.lowMmol': '4.2' } })]);
    expect(следующее(п.поля[0], 1)).toBe('4.3');
    expect(следующее(п.поля[0], -1)).toBe('4.1');
  });

  /* Порога «минус пять минут» не бывает: движок отверг бы его молча, и человек решил бы, что кнопка
     сломана. */
  it('в ноль и ниже не уводим', () => {
    const [п] = правилаНаЭкран([правило({ kind: 'silence', settings: { 'alarms.silence.dayMin': '5' } })]);
    expect(следующее(п.поля[0], -1)).toBe(null);
  });

  it('правил нет вовсе — пусто, а не выдуманный список', () => {
    expect(правилаНаЭкран(undefined)).toEqual([]);
  });
});

/* Выключатель правила (ядро добавило по нашей просьбе, #482). Ключ приходит среди обычных настроек,
   но подпись «enabled» человеку ничего не говорит, а у защиты от гипогликемии выключателя нет вовсе —
   и об этом надо сказать словами, иначе человек пойдёт выключать уведомления целиком. */
describe('выключатель правила', () => {
  it('ключ .enabled становится понятным выключателем и идёт первым', () => {
    const [п] = правилаНаЭкран([правило({
      id: 'прогноз-падения', kind: 'forecast', enabled: true, canDisable: true,
      settings: { 'alarms.forecast.windowMin': '15', 'alarms.прогноз-падения.enabled': 'on' },
    })]);
    expect(п.поля[0].выключатель).toBe(true);
    expect(п.поля[0].имя).toBe('Следить за этим');
    expect(п.включено).toBe(true);
    expect(п.выключаемо).toBe(true);
    expect(п.почемуНельзя).toBe(null);
  });

  it('выключенное правило видно по заголовку', () => {
    const [п] = правилаНаЭкран([правило({ enabled: false, canDisable: true })]);
    expect(п.включено).toBe(false);
  });

  /* Молчание во сне выключать нельзя, и причина неочевидна: без данных гипо-тревога не сработает
     вовсе. Поэтому объяснение у неё своё, а не общее. */
  it('незыблемое правило объясняет себя, а не молчит', () => {
    const [сон] = правилаНаЭкран([правило({ kind: 'silence', canDisable: false })]);
    expect(сон.выключаемо).toBe(false);
    expect(сон.почемуНельзя).toContain('считать нечего');
    const [низкий] = правилаНаЭкран([правило({ kind: 'low', canDisable: false })]);
    expect(низкий.почемуНельзя).toContain('ради которой');
  });

  /* Старое ядро признаков не отдаёт. Считать это «выключено» нельзя: экран показал бы правило
     погашенным, хотя движок его считает. */
  it('нет признаков — правило включено и выключаемо', () => {
    const [п] = правилаНаЭкран([правило({})]);
    expect(п.включено).toBe(true);
    expect(п.выключаемо).toBe(true);
  });
});

/* Старое ядро в этой сборке означает «тревог нет вовсе»: своей логики решений у нас не осталось.
   Отказ тихий — экран выглядит обычным, — поэтому проверяем ревизию прямо. */
describe('хватает ли ядра для тревог', () => {
  it('1.30 и новее — умеет', () => {
    expect(ядроУмеетТревоги('1.30')).toBe(true);
    expect(ядроУмеетТревоги('1.31')).toBe(true);
    expect(ядроУмеетТревоги('2.0')).toBe(true);
  });

  it('старее — не умеет, и молчать об этом нельзя', () => {
    expect(ядроУмеетТревоги('1.29')).toBe(false);
    expect(ядроУмеетТревоги('1.9')).toBe(false);
  });

  /* Ревизии нет вовсе — браузерный шим или сборка, о которой мы ничего не знаем. Считать её
     умеющей значило бы пообещать тревоги там, где их точно нет. */
  it('ревизии нет — считаем, что не умеет', () => {
    expect(ядроУмеетТревоги(undefined)).toBe(false);
    expect(ядроУмеетТревоги('непонятно')).toBe(false);
  });
});
