import type { Находка } from '@/domain/analysis';
import { словаНаходки } from './находки';

/* Черновик вопросов к врачу — из находок разбора (SugarLife#156).

   Ценность приёма наполовину в вопросах: между визитами копится «спросить про ночные
   гипо», а у двери вылетает из головы. Поводы мы и так видим — значит можем собрать
   список, который человек не сочиняет заново, а правит.

   ДВЕ ГРАНИЦЫ, И ОБЕ ВАЖНЫ.

   Первая: в записку идёт ВОПРОС, а не вывод. «Ночью бывает низко — что с этим делать?»
   — вопрос пациента; «нужно снизить ночной базал» — назначение, и его в записке быть
   не может, даже если оно кажется очевидным.

   Вторая: своё поле у находки (insight.question) сюда не годится, хотя соблазн есть.
   Те вопросы обращены к самому человеку («Записываешь все приёмы пищи?») — они помогают
   ему разобраться с данными, а в кабинете звучали бы странно. Врачу нужен другой
   вопрос про ту же находку, поэтому здесь отдельная таблица.

   Находки про железо и пропуски данных в записку не идут вовсе: замена канюли и
   разряженный телефон — не тема пятнадцати минут с эндокринологом. */
const ВОПРОС_ВРАЧУ: Record<string, string> = {
  'night-hypo': 'Ночью бывают снижения — что с этим делать?',
  'low-window': 'Низкий сахар повторяется в одно и то же время — с чем это может быть связано?',
  'high-window': 'Сахар держится высоким в одни и те же часы — с чем это может быть связано?',
  'long-high': 'Бывают долгие подъёмы, которые не сбиваются, — как правильно действовать?',
  'dawn': 'Утром сахар растёт до завтрака — нужно ли что-то менять?',
  'rebound': 'После гипогликемии сахар улетает вверх — как правильно её купировать?',
  'volatile': 'Сахар сильно скачет в течение дня — на что смотреть в первую очередь?',
  'tbr': 'Времени ниже целевого диапазона больше, чем в рекомендациях, — что с этим делать?',
  'tir-trend': 'Время в диапазоне изменилось по сравнению с прошлым периодом — стоит ли что-то менять?',
  'gmi': 'Расчётный показатель по сенсору расходится с последним HbA1c — как это понимать?',
  'basal': 'Базальная доза выглядит непривычно — стоит ли её пересматривать?',
  'bolus': 'Соотношение базала и болюсов изменилось — это нормально?',
  /* Вопрос сформулирован ОТ ФАКТА, а не от вины (#432, #167): «подъёмы, под которыми нет
     записи» — то, что видно в данных. «Я забываю записывать еду» было бы уже ответом, и
     ответом, выбранным за человека из шести возможных. */
  'без-записи': 'Бывают подъёмы, под которыми нет записи о еде, — как понять, от чего они?',
};

export interface ВопросВрачу { id: string; текст: string; повод: string }

/* Только то, что требует разговора: bad и warn. info и good в кабинете — шум, а
   пятнадцать минут стоят дороже полноты списка. */
export function вопросыДляВрача(находки: Находка[]): ВопросВрачу[] {
  const итог: ВопросВрачу[] = [];
  for (const н of находки) {
    if (н.severity !== 'bad' && н.severity !== 'warn') continue;
    const текст = ВОПРОС_ВРАЧУ[н.id];
    if (!текст) continue;
    if (итог.some((в) => в.id === н.id)) continue;
    /* Повод — заголовок находки: врач должен видеть, из чего вопрос вырос. Раньше он
       приезжал сюда готовой строкой из домена; теперь берём его там же, где живут все
       остальные слова находок. */
    итог.push({ id: н.id, текст, повод: словаНаходки(н).title });
  }
  return итог;
}
