import { useSnapshot, type Monitor } from '@/sources/bridge';
import { useStore } from '@/sources/store';
import type { Device } from '@/domain/types';

/* ЧИСЛА ЧУЖОЙ ПЕТЛИ — ИЗ ОДНОГО МЕСТА (SugarLife#528, мост 1.42).

   Активный инсулин и активные углеводы считает не наш движок, а чужая система (AAPS, iAPS) и кладёт
   в `devicestatus` Nightscout. До сих пор их доставал веб-слой собственной загрузкой — это и был
   второй источник, из-за которого экран спорил с тревогой: движок кричал «данных нет», а на
   «Сегодня» стояли свежие числа.

   Теперь их читает движок и отдаёт в снимке. Здесь — единственное место, где решается, откуда взять,
   и правило простое: сказал движок — верим ему; молчит (старая сборка ядра или браузерный шим) —
   берём прежним путём. Двух ответов на один вопрос в коде больше нет.

   ЭТО НЕ НАШИ ЧИСЛА, И ПОДПИСЫВАТЬ ИХ НАДО ЧЕСТНО. Наш `confirmedIOB` строится на свидетельстве —
   мы можем объяснить, откуда он взялся. Чужой расчёт приходит готовым и необъяснимым: на вопрос
   «почему столько» ответа у нас нет. Поэтому рядом с числом идёт имя автора (`by`), а возраст
   расчёта обязателен — часовой давности расчёт не значит ничего (это правило уже живёт в
   `domain/loopValue.ts`). */

export interface ЧужаяПетля {
  /** Активный инсулин по чужому расчёту. */
  iob: number | null;
  /** Активные углеводы по чужому расчёту. */
  cob: number | null;
  /** Когда считали. Без него число нельзя показывать: см. loopValue. */
  loopAt: number | null;
  /** Кто считал — «AndroidAPS», «iAPS». null: неизвестно, тогда и подписи нет. */
  by: string | null;
}

const пусто: ЧужаяПетля = { iob: null, cob: null, loopAt: null, by: null };

/* КТО СЧИТАЛ — ИМЕНЕМ ПРОГРАММЫ, А НЕ СТРОКОЙ ИЗ БАЗЫ.

   В `devicestatus` авторы подписываются по-своему: AAPS кладёт «openaps://Xiaomi 2410FPCC5G» —
   схему и модель телефона, Loop и его потомки «loop://iPhone». Показать это как есть значит
   написать под числом «по расчёту openaps://Xiaomi 2410FPCC5G»: человек видит имя своего телефона
   там, где спрашивал, чей это расчёт.

   Незнакомое имя оставляем как есть, только подрезаем: выдумывать за неизвестную программу нельзя,
   а разорвать строку в подписи можно.

   Модель телефона отбрасываем намеренно. Она отвечает на вопрос «где считали», а спрашивают
   «кто считал» — и на телефоне человека программа всё равно одна. */
export function ктоСчитал(by: string | null | undefined): string | null {
  const с = (by ?? '').trim();
  if (!с) return null;
  const схема = с.split('://')[0].toLowerCase();
  if (схема === 'openaps') return 'AndroidAPS';
  if (схема === 'loop') return 'Loop';
  return с.length > 24 ? с.slice(0, 23) + '…' : с;
}

/* Правило выбора отдельно от хука — его и проверяем тестом.

   Смотрим на `loopAtMs`, а не на сами числа: движок мог прислать расчёт, в котором углеводов нет
   (их не считали), и это не повод возвращаться к старому источнику — иначе получилось бы, что
   инсулин у нас от движка, а углеводы от веб-слоя, и они разъедутся во времени. */
export function выбрать(monitor: Monitor | null | undefined, dev: Device | null): ЧужаяПетля {
  if (monitor?.loopAtMs != null) {
    return {
      iob: monitor.loopIOB ?? null,
      cob: monitor.loopCOB ?? null,
      loopAt: monitor.loopAtMs,
      by: ктоСчитал(monitor.loopBy),
    };
  }
  if (!dev) return пусто;
  return { iob: dev.iob ?? null, cob: dev.cob ?? null, loopAt: dev.loopAt ?? null, by: null };
}

export function useЧужаяПетля(): ЧужаяПетля {
  const снимок = useSnapshot();
  const { data } = useStore();
  return выбрать(снимок?.monitor, data?.device ?? null);
}
