import { describe, it, expect } from 'vitest';
import { собрать, type Подробность } from './живыеТревоги';

const п = (o: Partial<Подробность>): Подробность =>
  ({ level: 'Разбудить', mmol: null, ack: true, at: 1000, ...o });

describe('живые тревоги', () => {
  it('называет тревогу словами и ставит свежую первой', () => {
    const под = new Map([['гипо', п({ mmol: 3.4, at: 2000 })], ['молчание', п({ at: 3000 })]]);
    const r = собрать(['гипо', 'молчание'], под, new Map());
    expect(r.map((т) => т.заголовок)).toEqual(['Данных нет', 'Низкий сахар']);
    expect(r[1].текст).toBe('3,4 ммоль');
  });

  /* Приложение открыли после срабатывания — события мы не застали. Кнопку всё равно показываем:
     лишняя дешевле, чем воющая тревога без ответа. */
  it('без события считает, что ответ нужен', () => {
    expect(собрать(['что-то'], new Map(), new Map())[0].нуженОтвет).toBe(true);
  });

  it('отвеченную не показывает, пока движок держит её активной', () => {
    const под = new Map([['гипо', п({ at: 1000 })]]);
    expect(собрать(['гипо'], под, new Map([['гипо', 1500]]))).toHaveLength(0);
  });

  it('на повтор возвращает: событие свежее ответа', () => {
    const под = new Map([['гипо', п({ at: 2000 })]]);
    const ответы = new Map([['гипо', 1500]]);
    expect(собрать(['гипо'], под, ответы)).toHaveLength(1);
    /* Ответ забыт вместе с показом: иначе следующий повтор снова скрылся бы старым ответом. */
    expect(ответы.has('гипо')).toBe(false);
  });
});
