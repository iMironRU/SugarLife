import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { собрать, type Подробность, изСостояния, понял, забытьОтветы, _прочитатьОтветы } from './живыеТревоги';
import type { ActiveAlarmView } from '@/sources/bridge';

const п = (o: Partial<Подробность>): Подробность =>
  ({ level: 'Разбудить', mmol: null, ack: true, at: 1000, ...o });

describe('живые тревоги', () => {
  it('называет тревогу словами и среди равных ставит свежую первой', () => {
    const под = new Map([['гипо', п({ mmol: 3.4, at: 2000 })], ['молчание', п({ at: 3000 })]]);
    const r = собрать(['гипо', 'молчание'], под, new Map());
    expect(r.map((т) => т.заголовок)).toEqual(['Данных нет', 'Низкий сахар']);
    expect(r[1].текст).toBe('3,4 ммоль');
  });

  /* Свежая заметка не должна отталкивать вниз низкий сахар: наверху то, что важнее, а не то,
     что пришло позже. */
  it('важное выше свежего', () => {
    const под = new Map([
      ['гипо', п({ level: 'Разбудить', mmol: 3.4, at: 1000 })],
      ['резервуар', п({ level: 'Заметка', at: 9000 })],
    ]);
    expect(собрать(['резервуар', 'гипо'], под, new Map()).map((т) => т.id))
      .toEqual(['гипо', 'резервуар']);
  });

  /* Приложение открыли после срабатывания — события мы не застали. Кнопку всё равно показываем:
     лишняя дешевле, чем воющая тревога без ответа. */
  /* Крупным кеглем на полосе идёт число — а у «данных нет» его нет вовсе. Раньше туда попадало
     первое слово пояснения, и на экране стояло огромное «Приложение». */
  it('число отдельно от пояснения: нет числа — нет и крупной строки', () => {
    const под = new Map([['гипо', п({ mmol: 3.4 })], ['молчание', п({ mmol: null })]]);
    const r = собрать(['гипо', 'молчание'], под, new Map());
    expect(r.find((т) => т.id === 'гипо')?.число).toBe('3,4');
    expect(r.find((т) => т.id === 'молчание')?.число).toBeNull();
  });

  it('без события считает, что ответ нужен', () => {
    expect(собрать(['что-то'], new Map(), new Map())[0].нуженОтвет).toBe(true);
  });

  /* Та же граница на запасном пути: без «Понял» — не наша полоса. */
  it('по событиям: тревога без «Понял» на полосу не попадает', () => {
    const под = new Map([['тихая', п({ ack: false })]]);
    expect(собрать(['тихая'], под, new Map())).toHaveLength(0);
  });

  it('отвеченную не показывает, пока движок держит её активной', () => {
    const под = new Map([['гипо', п({ at: 1000 })]]);
    expect(собрать(['гипо'], под, new Map([['гипо', 1500]]))).toHaveLength(0);
  });

  it('на повтор возвращает: событие свежее ответа', () => {
    const под = new Map([['гипо', п({ at: 2000 })]]);
    const ответы = new Map([['гипо', 1500]]);
    expect(собрать(['гипо'], под, ответы)).toHaveLength(1);
    /* Ответ забыт вместе с показом: иначе следующий повтор снова скрылся бы старым ответом. */
    expect(ответы.has('гипо')).toBe(false);
  });
});

describe('слова движка на полосе тревоги', () => {
  const п = (words?: string | null) => new Map([['молчание-днём', {
    level: 'Разбудить', mmol: null, ack: true, at: 1000, words,
  }]]);

  it('говорит словами движка, когда они есть', () => {
    /* «Приложение сообщает о состоянии» — наша заглушка для тревог без числа. Владелец увидел её у
       «Данных нет»: тревога сработала, а сказать ей нечего. У движка слова для этого повода есть. */
    const [т] = собрать(['молчание-днём'], п('Показания перестали приходить. Проверьте связь с сенсором.'), new Map());
    expect(т.текст).toBe('Показания перестали приходить. Проверьте связь с сенсором.');
  });

  it('без слов движка остаётся наш текст, а не пустота', () => {
    const [т] = собрать(['молчание-днём'], п(null), new Map());
    expect(т.текст).toBe('Приложение сообщает о состоянии');
  });

  it('пустые слова движка не считаются словами', () => {
    const [т] = собрать(['молчание-днём'], п('   '), new Map());
    expect(т.текст).toBe('Приложение сообщает о состоянии');
  });
});

/* ПОЛОСА ПО СОСТОЯНИЮ (мост 1.48, ядро #141). События одноразовы — снимок их забирает и очищает, а
   полоса постоянная. Через минуту после срабатывания у нас оставался один идентификатор, и на двух
   самых важных тревогах вылезала заглушка «Приложение сообщает о состоянии». */
describe('полоса по состоянию тревог', () => {
  const т = (p: Partial<ActiveAlarmView>): ActiveAlarmView => ({
    id: 'гипо', level: 'Разбудить', baseLevel: 'Разбудить',
    words: 'Низкий сахар: 3,1. Съешьте быстрые углеводы.', mmol: 3.1,
    sinceMs: 1000, needsAck: true, acked: false, ...p,
  });

  it('слова и число берём у движка как есть — заглушки больше нет', () => {
    const [с] = изСостояния([т({})], new Map());
    expect(с.текст).toBe('Низкий сахар: 3,1. Съешьте быстрые углеводы.');
    expect(с.число).toBe('3,1');
    expect(с.нуженОтвет).toBe(true);
  });

  /* ОТВЕЧЕННАЯ УХОДИТ С ПОЛОСЫ — как и уведомление. Раньше строка оставалась без кнопки: сахар и так
     крупно в кружке над полосой, действия не осталось, убрать нельзя ничем. Мёртвый элемент на первом
     экране. Движку верим больше своей памяти: `отвечено` не переживает перезапуск, `acked` переживает. */
  it('acked — строка уходит вместе с кнопкой', () => {
    expect(изСостояния([т({ acked: true })], new Map())).toHaveLength(0);
  });

  /* Вернуть её должен движок и в свой срок: `repeat` приезжает с новым `sinceMs`. Решать за него,
     когда напомнить, мы не беремся — это его расчёт. */
  it('повтор после ответа возвращает полосу', () => {
    const [с] = изСостояния([т({ acked: false, sinceMs: 5000 })], new Map([['гипо', 2000]]));
    expect(с).toBeTruthy();
    expect(с.нуженОтвет).toBe(true);
  });

  /* ПОЛОСА — МЕСТО, ГДЕ ОТВЕЧАЮТ. Владелец увидел «Высокий сахар, 17 минут назад» без кнопки и без
     способа убрать: заголовок, число, возраст, инсулин — и всё это, кроме заголовка, уже стояло в
     кружке прямо над полосой. Движок такую тревогу доставил уведомлением, где она смахивается. */
  it('тревога без «Понял» на полосу не попадает', () => {
    expect(изСостояния([т({ needsAck: false })], new Map())).toHaveLength(0);
  });

  it('свой ответ прячет тревогу, пока движок про него не знает', () => {
    expect(изСостояния([т({ sinceMs: 1000 })], new Map([['гипо', 2000]]))).toHaveLength(0);
  });

  /* Зазвонила заново — ответ к ней уже не относится. */
  it('срабатывание позже ответа снова показывает полосу', () => {
    expect(изСостояния([т({ sinceMs: 3000 })], new Map([['гипо', 2000]]))).toHaveLength(1);
  });
});

/* ОТВЕТ ПЕРЕЖИВАЕТ ПЕРЕЗАПУСК (замечание владельца: гасил «Данных нет» четыре раза за утро).

   Память жила в модуле и умирала вместе с процессом, а на движок полагаться нельзя: по журналу его
   `acked` сбрасывается при восстановлении. Проверяем не «функция вызвалась», а то, ради чего она
   написана: погасили, перезапустились, строка не вернулась. */
describe('ответ переживает перезапуск', () => {
  /* В тестах localStorage нет, и storage.ts честно глотает отказ. Без подставного хранилища
     проверка прошла бы «зелено», ничего не проверив: ответ никуда не записывался, а тревога и так
     не показывалась бы по другой причине. Подставляем настоящий путь целиком. */
  const хранилище = new Map<string, string>();
  beforeAll(() => {
    (globalThis as { localStorage?: unknown }).localStorage = {
      getItem: (k: string) => хранилище.get(k) ?? null,
      setItem: (k: string, v: string) => { хранилище.set(k, v); },
      removeItem: (k: string) => { хранилище.delete(k); },
    };
  });
  afterAll(() => { delete (globalThis as { localStorage?: unknown }).localStorage; });

  const т = (p: Partial<ActiveAlarmView>): ActiveAlarmView => ({
    id: 'молчание', level: 'Разбудить', baseLevel: 'Разбудить',
    words: 'Показания перестали приходить.', mmol: null,
    sinceMs: 1000, needsAck: true, acked: false, ...p,
  });

  it('погасили — после перезапуска не возвращается', () => {
    забытьОтветы();
    понял('молчание');
    /* «Перезапуск»: читаем память заново, как это делает модуль при загрузке. */
    expect(изСостояния([т({})], _прочитатьОтветы())).toHaveLength(0);
  });

  it('зазвонила заново — возвращается, ответ к ней не относится', () => {
    забытьОтветы();
    понял('молчание');
    expect(изСостояния([т({ sinceMs: Date.now() + 1000 })], _прочитатьОтветы())).toHaveLength(1);
  });

  it('чужой ответ чужую тревогу не гасит', () => {
    забытьОтветы();
    понял('молчание');
    expect(изСостояния([т({ id: 'гипо' })], _прочитатьОтветы())).toHaveLength(1);
  });
});
