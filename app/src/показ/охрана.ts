import type { ГотовностьТревог } from '@/platform/тревоги';
import type { ФонОтвет } from '@/platform/фон';

/* Раздел «Охрана»: ответ на один вопрос — разбудят ли этой ночью (#473, core#115).

   ЗАЧЕМ ОТДЕЛЬНЫЙ СБОРЩИК. Всё, от чего зависит ответ, лежит в разных местах: пороги в
   настройках тревог, сторож молчания там же, доступ к «Не беспокоить» в системе,
   исключение из энергосбережения на экране готовности, приборы — в снимке движка. Человек
   не может сложить это сам, а складывать в разметке значило бы, что правило живёт в
   разметке.

   ГЛАВНОЕ ПРАВИЛО: СНАЧАЛА ОТВЕТ. Не список галочек, из которого человек должен вывести
   вывод, а вывод: «этой ночью разбудим». Список — ниже, для того, кто спросит «из чего это
   следует». Пороги при беззвучной тревоге не значат ничего, поэтому и стоят последними.

   ЧЕГО НЕ ЗНАЕМ — ГОВОРИМ, ЧТО НЕ ЗНАЕМ. Вендорскую защиту прошивки проверить нельзя
   никаким API. Зелёная галочка там была бы враньём, красная — паникой; поэтому третий
   знак, отдельный. */

export type Ответ =
  | 'разбудим'        // обещание в силе
  | 'может не разбудить' // тревоги включены, но что-то мешает их услышать
  | 'не сторожим';    // тревога о низком сахаре выключена — обещания нет вовсе

export type Знак = 'ок' | 'нет' | 'не знаем';

export type Действие = 'доступ к «Не беспокоить»' | 'включить сторож' | 'настройки фона' | 'включить тревогу'
  | 'включить ночной звук';

export interface Строка {
  знак: Знак;
  имя: string;
  под?: string;
  /** Что предложить сделать. Есть только у того, что человек может починить. */
  действие?: Действие;
}

export interface Охрана {
  ответ: Ответ;
  /** Почему так — одной фразой, под ответом. */
  почему: string;
  строки: Строка[];
  /* Что предложить первой кнопкой. Не просто «первое сломанное»: если тревога выключена
     целиком, чинить разрешения бессмысленно — сначала надо, чтобы было чему звучать. */
  главное?: Действие;
}

export type Платформа = 'android' | 'ios' | 'веб';

export function охрана(вход: {
  платформа: Платформа;
  тревогиВключены: boolean;
  готовность: ГотовностьТревог | null;
  фон: ФонОтвет | null;
  сенсорМолчитМин: number | null;
  /** Живой баннер на экране блокировки. */
  баннерВключён?: boolean;
  /* Держим ли на iOS фоновый звуковой поток. Только он пробивает беззвучный режим — и
     только он объясняет, почему магнитола в машине переключается на телефон. */
  ночнойЗвук?: boolean;
}): Охрана {
  const { платформа, тревогиВключены, готовность, фон, сенсорМолчитМин } = вход;
  const строки: Строка[] = [];

  /* АЙФОН МОЖЕТ РАЗБУДИТЬ — НО ТОЛЬКО ПОКА ДЕРЖИТ ЗВУК (core#115).

     Сначала я написал здесь «не можем» и спрятал раздел вовсе. Оба решения были неверны.

     Пробиться сквозь беззвучный режим на iOS можно единственным способом: собственным
     звуком приложения. Critical Alert для этого не нужен — нужен живой фоновый звуковой
     поток, тот самый, что мы уже держим для облачного режима (#388). Пока он есть,
     тревога звучит даже на беззвучном телефоне.

     ЗА ЭТО ПЛАТИТ МАШИНА. Телефон с открытым потоком магнитола считает активным
     источником и переключается на него — радио выключается. Поэтому поток держат ночью,
     когда человек не за рулём, а днём отпускают: днём хватает обычного уведомления.

     У кого машины нет — тому платить не за что, и «держать всегда» остаётся его выбором.
     Решать это за него мы не станем.

     Чего мы не обещаем и на iOS: если система выгрузит приложение целиком, звучать будет
     нечему. Это не «почти работает», это отдельный случай, и он назван. */
  if (платформа === 'ios') {
    const держимЗвук = !!вход.ночнойЗвук;
    const общее: Строка[] = [
      держимЗвук
        ? { знак: 'ок', имя: 'Разбудить звуком', под: 'держим звуковой поток — тревога пробьёт беззвучный режим' }
        : { знак: 'нет', имя: 'Разбудить звуком', под: 'звук не удерживается — на беззвучном телефоне тревога не прозвучит',
            действие: 'включить ночной звук' },
      вход.баннерВключён
        ? { знак: 'ок', имя: 'Сахар на экране блокировки', под: 'живой баннер включён' }
        : { знак: 'не знаем', имя: 'Сахар на экране блокировки', под: 'живой баннер выключен' },
      { знак: 'не знаем', имя: 'Если система выгрузит приложение', под: 'звучать будет нечему — этого мы не переживём' },
    ];
    if (!тревогиВключены) {
      return {
        ответ: 'не сторожим',
        почему: 'Тревога о низком сахаре выключена — ночью мы промолчим, что бы ни случилось.',
        строки: [{ знак: 'нет', имя: 'Тревога о низком сахаре', под: 'выключена', действие: 'включить тревогу' }, ...общее],
        главное: 'включить тревогу',
      };
    }
    return держимЗвук
      ? {
        ответ: 'разбудим',
        почему: 'Звук держим сами — тревога прозвучит даже на беззвучном телефоне. Днём поток стоит того, '
          + 'что магнитола считает телефон источником звука; поэтому его держат ночью.',
        строки: общее,
      }
      : {
        ответ: 'может не разбудить',
        почему: 'На айфоне беззвучный режим пробивает только собственный звук приложения, а он сейчас не удерживается.',
        строки: общее,
        главное: 'включить ночной звук',
      };
  }

  if (платформа === 'веб') {
    return {
      ответ: 'не сторожим',
      почему: 'В браузере тревог нет: страница спит вместе с телефоном. Ночная охрана работает в приложении на Android.',
      строки: [{ знак: 'нет', имя: 'Разбудить ночью', под: 'браузер не будит' }],
    };
  }

  /* Сборка старше проверки или браузер — не знаем ничего. Молчание здесь читалось бы как
     обещание разбудить, поэтому отвечаем прямо. */
  if (!готовность) {
    return {
      ответ: 'не сторожим',
      почему: 'Про эту сборку сказать нечего: узнать, разбудит ли ночью, отсюда нельзя.',
      строки: [{ знак: 'не знаем', имя: 'Готовность тревог', под: 'сборка старше проверки или это браузер' }],
    };
  }

  /* Разрешения. Натив отвечает списком того, чего не хватает, — словами и сразу
     человеческими: ответ обязан быть одинаковым на обеих платформах, и придумывать его
     второй раз здесь мы не станем. Пустой список означает, что все проверки прошли. */
  if (готовность.чегоНет.length === 0) {
    строки.push({ знак: 'ок', имя: 'Услышим тревогу', под: 'звук будильника, поверх «не беспокоить», на весь экран' });
  } else {
    for (const беда of готовность.чегоНет) {
      строки.push({
        знак: 'нет', имя: 'Услышим тревогу', под: беда,
        действие: беда.includes('Не беспокоить') ? 'доступ к «Не беспокоить»' : undefined,
      });
    }
  }

  строки.push(готовность.сторожМолчания
    ? { знак: 'ок', имя: 'Заметим пропажу данных', под: `молчание дольше ${готовность.порогМолчанияМин} мин` }
    : { знак: 'нет', имя: 'Заметим пропажу данных', под: 'сторож молчания выключен', действие: 'включить сторож' });

  /* Приборы — не разрешение, но часть того же обещания: тревога о низком сахаре считается
     от показаний, и если их нет, будить будет нечем независимо от настроек. */
  строки.push(сенсорМолчитМин == null
    ? { знак: 'не знаем', имя: 'Приборы на связи', под: 'показаний ещё не было' }
    : сенсорМолчитМин <= 15
      ? { знак: 'ок', имя: 'Приборы на связи', под: `последнее показание ${сенсорМолчитМин} мин назад` }
      : { знак: 'нет', имя: 'Приборы на связи', под: `данных нет ${сенсорМолчитМин} мин` });

  if (фон?.problem) {
    строки.push({
      знак: 'нет', имя: 'Телефон не усыпит приложение', под: фон.reason,
      действие: фон.weCanOpenSettings ? 'настройки фона' : undefined,
    });
  } else if (фон) {
    строки.push({ знак: 'ок', имя: 'Телефон не усыпит приложение', под: 'исключение из энергосбережения выдано' });
  } else {
    /* Про фон не спросить — вендорская защита прошивки не отвечает ни на какой API. */
    строки.push({ знак: 'не знаем', имя: 'Прошивка не душит фон', под: 'этого мы проверить не можем' });
  }

  if (!тревогиВключены) {
    /* Порядок починки имеет значение: разрешения нужны, чтобы УСЛЫШАТЬ тревогу, но пока
       её нет, слышать нечего. Поэтому первой кнопкой — включить, а разрешения останутся
       в списке и станут главными на следующем заходе. */
    return {
      ответ: 'не сторожим',
      почему: 'Тревога о низком сахаре выключена — ночью мы промолчим, что бы ни случилось.',
      строки: [{ знак: 'нет', имя: 'Тревога о низком сахаре', под: 'выключена', действие: 'включить тревогу' }, ...строки],
      главное: 'включить тревогу',
    };
  }

  const сломано = строки.filter((с) => с.знак === 'нет');
  if (сломано.length) {
    return {
      ответ: 'может не разбудить',
      почему: сломано[0].под ? заглавная(сломано[0].под) + '.' : 'Что-то мешает нас услышать.',
      строки,
      главное: сломано.find((с) => с.действие)?.действие,
    };
  }
  return {
    ответ: 'разбудим',
    почему: 'Низкий сахар и пропажа данных. Звук будильника поверх «не беспокоить», даже если телефон беззвучный.',
    строки,
  };
}

const заглавная = (с: string) => с.charAt(0).toUpperCase() + с.slice(1);
