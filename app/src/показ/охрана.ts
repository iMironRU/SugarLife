import type { ФонОтвет } from '@/platform/фон';
import type { NightPromiseView, NightReasonView } from '@/sources/bridge';

/* Раздел «Охрана»: ответ на один вопрос — разбудят ли этой ночью (#473, core#115).

   ЗАЧЕМ ОТДЕЛЬНЫЙ СБОРЩИК. Всё, от чего зависит ответ, лежит в разных местах: пороги в
   настройках тревог, сторож молчания там же, доступ к «Не беспокоить» в системе,
   исключение из энергосбережения на экране готовности, приборы — в снимке движка. Человек
   не может сложить это сам, а складывать в разметке значило бы, что правило живёт в
   разметке.

   ГЛАВНОЕ ПРАВИЛО: СНАЧАЛА ОТВЕТ. Не список галочек, из которого человек должен вывести
   вывод, а вывод: «этой ночью разбудим». Список — ниже, для того, кто спросит «из чего это
   следует». Пороги при беззвучной тревоге не значат ничего, поэтому и стоят последними.

   ЧЕГО НЕ ЗНАЕМ — ГОВОРИМ, ЧТО НЕ ЗНАЕМ. Вендорскую защиту прошивки проверить нельзя
   никаким API. Зелёная галочка там была бы враньём, красная — паникой; поэтому третий
   знак, отдельный. */

export type Ответ =
  | 'разбудим'        // обещание в силе
  | 'может не разбудить' // тревоги считаются, но что-то мешает их услышать
  | 'не сторожим';    // считать тревоги некому — обещания нет вовсе

export type Знак = 'ок' | 'нет' | 'не знаем';

/* Действий стало меньше, и это не упрощение (#482). «Включить тревогу» и «включить сторож» исчезли
   вместе с нашими порогами: правила считает движок, и включать нам больше нечего. Осталось то, что
   человек и правда может починить руками, — разрешения и фон. */
export type Действие = 'доступ к «Не беспокоить»' | 'настройки фона'
  | 'включить ночной звук' | 'разрешить полный экран' | 'включить уведомления'
  /* Единственное действие, которое чинится целиком внутри приложения: системного экрана для
     громкости нет, и идти человеку никуда не надо. */
  | 'разрешить поднимать громкость'
  /* Айфонное: срочные, сводка по расписанию и экран блокировки правятся в одном месте —
     в настройках уведомлений приложения. */
  | 'настройки уведомлений';

export interface Строка {
  знак: Знак;
  имя: string;
  под?: string;
  /* ПОЛНЫЙ ОТВЕТ — В ШТОРКЕ, А НЕ В ОБРЕЗАННОЙ СТРОКЕ (#529).

     В списке строка одна и короткая, и длинный текст в ней обрывался многоточием: человек видел
     «нет доступа к „Не беспокоить" — ноч…» и не мог ни дочитать, ни понять, что делать. Строка
     отвечает «что», подробность отвечает «почему и как с этим быть» — тот же приём, что у правил
     тревог: список сверху, объяснение по нажатию. */
  подробно?: string;
  /** Что предложить сделать. Есть только у того, что человек может починить. */
  действие?: Действие;
}

/*
 * КРАСНОЕ, КОТОРОЕ ОТСЮДА НЕ ПОЧИНИТЬ, ОСТАЁТСЯ НА ВИДУ — И ГОВОРИТ ОБ ЭТОМ (#523, решение владельца).
 *
 * Вопрос был такой: что делать со строкой, которую человек уже видел и починить сейчас не может —
 * нет доступа к «Не беспокоить», а он в метро. Прятать до вечера или держать.
 *
 * Держим. Спрятанное предупреждение о том, что ночью не разбудят, — это ровно то молчание, из-за
 * которого человек ложится спать, думая, что защищён.
 *
 * Но держать молча тоже нельзя: строка без кнопки читается как недоделка, и человек ищет кнопку,
 * которой нет. Поэтому один раз говорим словами — «отсюда не починить». Это не оправдание, а
 * ответ на вопрос, который он себе задаёт, глядя на красную строку без действия.
 *
 * Признак вычисляется, а не проставляется руками: строка чинится отсюда, если у неё есть действие.
 * Список действий закрытый (см. `Действие`) — значит забыть его обновить нельзя.
 */
export function чинитсяОтсюда(с: Строка): boolean {
  return с.действие != null;
}

/** Красное, у которого действия нет: показываем словами, что кнопки не будет. */
export function отсюдаНеПочинить(с: Строка): boolean {
  return с.знак === 'нет' && !чинитсяОтсюда(с);
}

export interface Охрана {
  ответ: Ответ;
  /** Почему так — одной фразой, под ответом. */
  почему: string;
  строки: Строка[];
  /* Что предложить первой кнопкой. Не просто «первое сломанное»: если тревога выключена
     целиком, чинить разрешения бессмысленно — сначала надо, чтобы было чему звучать. */
  главное?: Действие;
}

export type Платформа = 'android' | 'ios' | 'веб';

/* ОТВЕТ ДВИЖКА ГЛАВНЕЕ НАШЕГО РАСЧЁТА (мост 1.49, ядро #588).

   Всё, что ниже, — 372 строки правил о том, разбудим ли этой ночью. Ядро забрало этот расчёт к себе,
   и довод тот же, который мы весь день ловим в других местах: две реализации одного правила
   расходятся молча, а узнаёт об этом человек ночью.

   Наш расчёт остаётся ЗАПАСНЫМ путём — для ядра старше 1.49, где `nightPromise` не приезжает. Совсем
   выбросить его сейчас значило бы оставить экран пустым на старой сборке; выбросим, когда 1.49
   станет минимальной.

   Раскладку и действия по-прежнему делаем мы (#115: экран и путь — наши). У движка берём ответ,
   причины и слова «что делать»: одна формулировка на обе платформы, и медицинского высказывания мы
   больше не сочиняем. */
/* НОЧНОЕ ОБНОВЛЕНИЕ СИСТЕМЫ — ЕДИНСТВЕННОЕ, ЧТО ВЫКЛЮЧАЕТ НАС ЦЕЛИКОМ (#477).

   Система ставит обновление ночью и перезагружает телефон. Дальше на обеих платформах одно и то
   же: приложение не поднимается само, пока человек не разблокирует телефон или не откроет его
   руками. Он спит. Значит до утра нет ни сбора данных, ни тревог, и узнает он об этом по дырке в
   графике.

   ПОЧЕМУ ЗНАК «НЕ ЗНАЕМ», А НЕ «НЕТ». Назначено ли обновление на эту ночь, приложению узнать
   нечем: публичного способа спросить об этом у системы нет ни у Android, ни у iOS. Красный знак
   означал бы, что мы что-то проверили и нашли поломку, — это была бы паника на пустом месте.
   Зелёного тут тоже быть не может: «всё в порядке ✓» там, где мы не проверяли, — ровно то, чего
   просили не писать.

   ПОЧЕМУ СТРОКА ПОСТОЯННАЯ. Она не сообщает событие, она называет границу нашего обещания. Раздел
   отвечает на вопрос «я защищён этой ночью», и честный ответ включает «кроме случая, когда нас
   выключит сама платформа». Убрать её значит обещать больше, чем мы можем.

   КНОПКИ НЕТ НАМЕРЕННО. Экран автообновлений у каждого производителя свой, а намерение, ведущее
   в никуда, хуже его отсутствия. Говорим словами, где искать. */
export function ночноеОбновление(платформа: Платформа): Строка | null {
  if (платформа === 'веб') return null;
  const общее = 'Приложение не может узнать, назначено ли обновление на эту ночь: такого способа '
    + 'у системы нет. Если ночная защита важнее свежей прошивки — выключите автоматическую '
    + 'установку.';
  return {
    знак: 'не знаем',
    имя: 'Ночное обновление системы',
    под: 'выключит мониторинг до утра — проверить это мы не можем',
    подробно: платформа === 'ios'
      ? 'iPhone ставит обновления ночью, пока телефон на зарядке, и перезагружается. После '
        + 'перезагрузки приложение не запускается само — оно поднимется, только когда вы его '
        + 'откроете. То есть до утра ни данных, ни тревог.\n\n' + общее
        + '\n\n«Настройки» → «Основные» → «Обновление ПО» → «Автообновления».'
      : 'Система ставит обновление ночью и перезагружает телефон. После перезагрузки Android не '
        + 'запускает приложения до первой разблокировки — а вы спите. То есть до утра ни данных, '
        + 'ни тревог, и тревога о низком сахаре сработать не может.\n\n' + общее
        + '\n\nИщите в системных настройках «Обновление системы» — там же расписание установки.',
  };
}

export function изОбещания(о: NightPromiseView, платформа: Платформа): Охрана {
  /* Живучесть первой: без данных и заряда никакие разрешения не помогут. Порядок задаёт ядро полем
     `shelf`, и это его решение, а не наша сортировка по вкусу. */
  const порядок = (п: NightReasonView) => (п.shelf === 'survival' ? 0 : 1);
  const причины = [...о.reasons].sort((а, б) => порядок(а) - порядок(б));
  const обновление = ночноеОбновление(платформа);
  return {
    ответ: о.willWake ? 'разбудим' : 'может не разбудить',
    почему: о.answer,
    строки: [
      /* КНОПКИ ЗДЕСЬ ПОКА НЕТ, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. Движок говорит `canOpen` — «вести есть куда», —
         но не говорит КУДА: наши действия это закрытый список конкретных системных экранов, и
         угадывать его по коду причины значило бы вернуть в наш код зашитое знание о чужих правилах,
         от которого мы весь день уходим. Спрошено у ядра.

         Потерять кнопку неприятно, но `whatToDo` словами движка объясняет, что делать, — а кнопка,
         ведущая не туда, хуже её отсутствия. */
      ...причины.map((п) => ({ знак: 'нет' as Знак, имя: п.words, подробно: п.whatToDo })),
      /* Предупреждения — НЕ про то, услышит ли человек тревогу: «инсулин кончится в четыре утра».
         Разбудим прекрасно, просто будить будет поздно. Мешать их с причинами нельзя — человек
         перестанет различать, что чинить. Поэтому и знак другой. */
      ...о.warnings.map((п) => ({ знак: 'не знаем' as Знак, имя: п.words, подробно: п.whatToDo })),
      /* Наша строка идёт последней и после слов движка: движок про автообновления системы не знает
         и знать не может — это факт платформы, а не медицины. */
      ...(обновление ? [обновление] : []),
    ],
  };
}

export function охрана(вход: {
  платформа: Платформа;
  /* Считает ли кто-то тревоги. Это уже не наша настройка, а факт: движок отдал правила — значит
     считает (SugarLife#482). Своей логики решений у нас не осталось, и «выключенных тревог» тоже:
     либо правила есть, либо тревог нет вовсе, и второе надо сказать прямо. */
  тревогиВедутся: boolean;
  /* Ядро старее модели тревог. Отдельно от «правил нет»: там движок умеет, но ни за чем не следит,
     а здесь считать некому в принципе, и починить это можно только обновлением приложения. */
  ядроСтарое?: boolean;
  /** Через сколько минут молчания движок будит. null — правила про молчание у него нет. */
  порогМолчанияМин?: number | null;
  готовность: ГотовностьТревог | null;
  фон: ФонОтвет | null;
  сенсорМолчитМин: number | null;
  /* Держим ли на iOS фоновый звуковой поток. Только он пробивает беззвучный режим — и
     только он объясняет, почему магнитола в машине переключается на телефон. */
  ночнойЗвук?: boolean;
  /* Громкость на айфоне: поднимаем ли её на время тревоги и какая она сейчас. Свой звук пробивает
     беззвучный режим, но не убавленный уровень — а «звук держим» без этого читается как обещание,
     которого мы не давали. null — вопрос не про эту платформу. */
  громкость?: { поднимаем: boolean; уровень: number } | null;
  /* ЧЕЛОВЕК СКАЗАЛ, ЧТО ДОБАВИЛ НАС В РАЗРЕШЁННЫЕ ФОКУСА (#561).

     Состав «Не беспокоить» — приватная настройка, системе её не отдают. Пока мы этого не знали,
     красная строка «ночью может не разбудить» висела ВСЕГДА и погасить её было нечем: право на
     срочные уведомления личной команде Apple не выдаёт, а список фокуса не проверить.

     Постоянное предупреждение, которое нельзя погасить, — ровно то, за что мы ругаем чужие
     приложения: оно учит не читать предупреждения. Тот же приём, что у ядра с вендорской защитой
     прошивки (BackgroundReadiness): непроверяемое спрашиваем ОДИН раз и запоминаем ответ.

     Ошибиться человек может, и это его право: он видел свой экран настроек, а мы — нет. */
  фокусПодтверждён?: boolean;
}): Охрана {
  const { платформа, тревогиВедутся, готовность, фон, сенсорМолчитМин } = вход;
  const строки: Строка[] = [];

  /* АЙФОН МОЖЕТ РАЗБУДИТЬ — НО ТОЛЬКО ПОКА ДЕРЖИТ ЗВУК (core#115).

     Сначала я написал здесь «не можем» и спрятал раздел вовсе. Оба решения были неверны.

     Пробиться сквозь беззвучный режим на iOS можно единственным способом: собственным
     звуком приложения. Critical Alert для этого не нужен — нужен живой фоновый звуковой
     поток, тот самый, что мы уже держим для облачного режима (#388). Пока он есть,
     тревога звучит даже на беззвучном телефоне.

     ЗА ЭТО ПЛАТИТ МАШИНА. Телефон с открытым потоком магнитола считает активным
     источником и переключается на него — радио выключается. Поэтому поток держат ночью,
     когда человек не за рулём, а днём отпускают: днём хватает обычного уведомления.

     У кого машины нет — тому платить не за что, и «держать всегда» остаётся его выбором.
     Решать это за него мы не станем.

     Чего мы не обещаем и на iOS: если система выгрузит приложение целиком, звучать будет
     нечему. Это не «почти работает», это отдельный случай, и он назван. */
  if (платформа === 'ios') {
    const держимЗвук = !!вход.ночнойЗвук;
    const общее: Строка[] = [
      держимЗвук
        ? { знак: 'ок', имя: 'Разбудить звуком',
          под: 'держим звуковой поток — тревога пробьёт беззвучный режим',
          подробно: 'На айфоне беззвучный режим пробивает только собственный звук приложения. Чтобы он был '
            + 'наготове ночью, приложение держит открытым звуковой поток — тихий, но живой.\n\n'
            + 'За это платит машина: телефон с открытым потоком магнитола считает источником звука и '
            + 'переключается на него. Поэтому поток держат ночью, а днём отпускают.' }
        : { знак: 'нет', имя: 'Разбудить звуком',
          под: 'звук не удерживается — на беззвучном телефоне тревога не прозвучит',
          подробно: 'На айфоне беззвучный режим пробивает только собственный звук приложения, и сейчас он '
            + 'не удерживается: если телефон окажется беззвучным, тревога прозвучит только уведомлением, '
            + 'а его в беззвучном режиме не слышно.\n\n'
            + 'Включите «Держать звук ночью» — приложение будет держать тихий звуковой поток, чтобы '
            + 'ночью было чем прозвучать.',
          действие: 'включить ночной звук' },
      /* ГРОМКОСТЬ — ОТДЕЛЬНОЙ СТРОКОЙ, а не сноской к звуку (#482). Держать поток и звучать на
         четверти громкости — разные вещи, и вторая слышна из-под подушки хуже первой. */
      ...(вход.громкость
        ? [вход.громкость.поднимаем
          ? { знак: 'ок' as const, имя: 'Громкость',
            под: 'на время тревоги поднимем до предела и вернём обратно' }
          : вход.громкость.уровень < 0.35
            ? { знак: 'нет' as const, имя: 'Громкость',
              под: `сейчас ${Math.round(вход.громкость.уровень * 100)} % и поднимать запрещено — можно не услышать`,
              действие: 'разрешить поднимать громкость' as const }
            : { знак: 'не знаем' as const, имя: 'Громкость',
              под: `сейчас ${Math.round(вход.громкость.уровень * 100)} %, поднимать её мы не будем` }]
        : []),
      /* ЖИВОГО БАННЕРА ЗДЕСЬ БОЛЬШЕ НЕТ (#500). Он не будит — он показывает, и зелёная галочка за
         него в списке «разбудим ли ночью» отвечала на другой вопрос. Место баннера — в «Тревогах»,
         рядом с виджетом: там оба отвечают на «что я узнаю, не открывая приложение». */
      /* ПОЛОМКИ РАЗРЕШЕНИЙ — И НА АЙФОНЕ СТРОКАМИ (#500). Владелец прошёл это вживую: сирена
         прозвучала (наш звук — не уведомление), а карточки при «Не беспокоить» не было. Бодрствование
         и громкость уже показаны своими строками выше — их коды пропускаем, чтобы не сказать одно
         дважды разными словами. */
      ...(вход.готовность?.поломки ?? [])
        .filter((п) => п.код !== 'ios-keep-alive' && п.код !== 'ios-volume')
        .map((п): Строка => ({
          /* ПРАВО НЕ ВЫДАНО — НО ЧЕЛОВЕК МОЖЕТ ЭТО ОБОЙТИ, И ТОГДА ЭТО НЕ ПОЛОМКА (#561).

             `time-sensitive-unsupported` означает, что сборка подписана без права на срочные:
             личной команде Apple его не выдаёт, и настройками это не чинится. Но результат —
             «карточку спрячет фокус» — снимается другим путём: добавлением нас в разрешённые
             приложения «Не беспокоить». Проверить список система не даёт, поэтому верим человеку
             на слово, если он сказал, что добавил.

             Без этого красная строка «ночью может не разбудить» висела вечно и погасить её было
             нечем — предупреждение, которое нельзя устранить, учит не читать предупреждения. */
          знак: (п.код === 'time-sensitive-unsupported' && вход.фокусПодтверждён) ? 'ок' : 'нет',
          имя: п.код === 'notifications-off' ? 'Уведомления включены'
            : п.код === 'time-sensitive-off' || п.код === 'time-sensitive-unsupported' ? 'Сквозь «Не беспокоить»'
              : п.код === 'scheduled-summary' ? 'Без задержки сводки'
                : п.код === 'lock-screen-off' ? 'Видно на блокировке'
                  : 'Услышим тревогу',
          под: (п.код === 'time-sensitive-unsupported' && вход.фокусПодтверждён)
            ? 'права на срочные у сборки нет, но вы добавили нас в разрешённые фокуса'
            : п.текст,
          /* «Сборка без права» настройками не чинится — только переустановкой, кнопку не обещаем. */
          действие: п.код === 'time-sensitive-unsupported' ? undefined : 'настройки уведомлений',
        })),
      /* ТИХИЕ ТРЕВОГИ — ОТДЕЛЬНОЙ СТРОКОЙ, ПОТОМУ ЧТО ОНИ НЕ ПРО НОЧЬ (#785).

         Поймано на живом телефоне: в семь утра пришла тревога о резервуаре, движок приказал её
         «прокричать» — и владелец УВИДЕЛ её глазами, а не услышал.

         Причина не поломка. Своим звуком мы играем только «орать»: он единственный слышен на
         беззвучном телефоне, и играть его для «кричать» значило бы будить там, где обещали не
         будить. Всё, что тише, уходит обычным уведомлением — а оно идёт на громкости звонка,
         которую мы ни поднять, ни прочитать не можем: положения переключателя «без звука» iOS
         приложению не показывает.

         Значит человек вправе знать: часть тревог он может не услышать вовсе, и мы не узнаем об
         этом тоже. Знак «не знаем», а не «нет»: это не сломано, это свойство платформы — как
         строка про прошивку ниже.

         Строка НЕ обещает починки и не даёт кнопки. Чинится это не здесь: движку надо сказать, что
         у наших двух каналов разная надёжность, и пусть он решает, поднимать ли уровень (#785). */
      { знак: 'не знаем', имя: 'Тревоги, которые не будят',
        под: 'идут звуком системы — на беззвучном телефоне их можно не услышать',
        подробно: 'Тревоги делятся на те, что будят, и те, что просто сообщают. Будящие приложение '
          + 'играет своим звуком: он слышен, даже когда телефон переведён в беззвучный режим.\n\n'
          + 'Остальные идут обычным уведомлением, а оно звучит на громкости звонка. Поднять её мы '
          + 'не можем, и узнать, включён ли беззвучный режим, — тоже: система этого не сообщает. '
          + 'Поэтому такие тревоги вы, скорее всего, увидите, а не услышите.\n\n'
          + 'Это не поломка и чинится не здесь. Если тревога такого рода важна — её уровень задаётся '
          + 'в правилах, а не в настройках телефона.' },
      /* ЧЕГО ПРОВЕРИТЬ НЕЛЬЗЯ — ГОВОРИМ, А НЕ МОЛЧИМ (#500). Состав фокуса «Не беспокоить» —
         приватная настройка: узнать, в списке ли мы разрешённых, у системы не спросить. Срочные
         уведомления проходят сквозь фокус и без списка, но проверить это можно только руками —
         включив «Не беспокоить» и нажав «Проверить тревогу сейчас». */
      { знак: вход.фокусПодтверждён ? 'ок' : 'не знаем',
        имя: 'Список «Не беспокоить»',
        под: вход.фокусПодтверждён
          ? 'вы подтвердили, что добавили нас в разрешённые'
          : 'в разрешённых ли мы приложениях фокуса — системе не спросить',
        подробно: 'У фокуса «Не беспокоить» есть список приложений, которым разрешено показывать '
          + 'уведомления. Узнать, входим ли мы в него, система приложению не даёт — это приватная '
          + 'настройка, и обещать вам что-либо здесь мы не вправе.\n\n'
          + 'Что сделать: Настройки → Фокусирование → «Не беспокоить» → Приложения → добавить SugarLife. '
          + 'После этого включите фокус и нажмите «Проверить тревогу сейчас»: если карточка появилась — '
          + 'ночью она появится тоже.' },
      { знак: 'не знаем', имя: 'Если система выгрузит приложение',
        под: 'звучать будет нечему — этого мы не переживём',
        подробно: 'Тревогу считает и подаёт само приложение. Если система выгрузит его целиком — '
          + 'из-за нехватки памяти или потому что вы смахнули его из недавних, — считать и звучать '
          + 'станет некому.\n\n'
          + 'Что помогает: не закрывать приложение вручную и держать «Держать звук ночью» включённым — '
          + 'живой звуковой поток заодно не даёт системе усыпить приложение.' },
    ];
    if (!тревогиВедутся) {
      return {
        ответ: 'не сторожим',
        почему: вход.ядроСтарое
          ? 'В этой сборке тревог нет: ядро старее модели тревог, считать их некому.'
          : 'Тревоги считает движок, а он сейчас не следит ни за чем — ночью мы промолчим.',
        строки: [{
          знак: 'нет', имя: 'Правила тревог',
          под: вход.ядроСтарое ? 'ядро старее модели тревог — обновите приложение целиком'
            : 'движок не следит ни за одним поводом',
        }, ...общее],
      };
    }
    /* Сломанное разрешение бьёт ответ даже при живом звуке: звук будит рядом с телефоном, а
       карточку, которой не видно, не прочтёт никто. */
    const поломка = общее.find((с) => с.знак === 'нет');
    if (держимЗвук && поломка) {
      return {
        ответ: 'может не разбудить',
        почему: `Звук держим, но не всё в порядке: ${поломка.под ?? поломка.имя}.`,
        строки: общее,
        главное: поломка.действие,
      };
    }
    return держимЗвук
      ? {
        ответ: 'разбудим',
        почему: 'Звук держим сами — тревога прозвучит даже на беззвучном телефоне. Днём поток стоит того, '
          + 'что магнитола считает телефон источником звука; поэтому его держат ночью.',
        строки: общее,
      }
      : {
        ответ: 'может не разбудить',
        почему: 'На айфоне беззвучный режим пробивает только собственный звук приложения, а он сейчас не удерживается.',
        строки: общее,
        главное: 'включить ночной звук',
      };
  }

  if (платформа === 'веб') {
    return {
      ответ: 'не сторожим',
      почему: 'В браузере тревог нет: страница спит вместе с телефоном. Ночная охрана работает в приложении на Android.',
      строки: [{ знак: 'нет', имя: 'Разбудить ночью', под: 'браузер не будит' }],
    };
  }

  /* Сборка старше проверки или браузер — не знаем ничего. Молчание здесь читалось бы как
     обещание разбудить, поэтому отвечаем прямо. */
  if (!готовность) {
    return {
      ответ: 'не сторожим',
      почему: 'Про эту сборку сказать нечего: узнать, разбудит ли ночью, отсюда нельзя.',
      строки: [{ знак: 'не знаем', имя: 'Готовность тревог', под: 'сборка старше проверки или это браузер' }],
    };
  }

  /* Разрешения. Натив отвечает списком того, чего не хватает, — словами и сразу
     человеческими: ответ обязан быть одинаковым на обеих платформах, и придумывать его
     второй раз здесь мы не станем. Пустой список означает, что все проверки прошли. */
  /* Раскладываем по КОДУ, а не по тексту (#475). Раньше все поломки разрешений валились в
     один пункт «услышим тревогу», а искать в фразе подстроку «Не беспокоить», чтобы
     догадаться, какую кнопку показать, — способ, который ломается от правки формулировки.

     Фразу по-прежнему берём у ядра приложения целиком: она одна на обе платформы, и
     переписывать её здесь значило бы завести второй ответ на тот же вопрос. */
  if (готовность.поломки.length === 0) {
    строки.push({ знак: 'ок', имя: 'Услышим тревогу',
      под: 'звук будильника, поверх «не беспокоить», на весь экран',
      подробно: 'Тревога живёт в отдельном канале уведомлений: громкость будильника, обход тихого '
        + 'режима, полноэкранный показ и вибрация.\n\nВсе три разрешения, от которых это зависит, '
        + 'выданы — значит ночью прозвучит так, как задумано. Проверить, не дожидаясь ночи, можно '
        + 'кнопкой «Проверить тревогу сейчас».' });
  } else {
    for (const п of готовность.поломки) {
      строки.push({
        знак: 'нет',
        имя: п.код === 'fullscreen' ? 'Покажем на весь экран'
          : п.код === 'notifications-off' ? 'Уведомления включены'
            : 'Услышим тревогу',
        под: п.текст,
        действие: п.код === 'dnd-access' ? 'доступ к «Не беспокоить»'
          : п.код === 'fullscreen' ? 'разрешить полный экран'
            : п.код === 'notifications-off' ? 'включить уведомления'
              /* Понижённый канал чинится только руками в системных настройках приложения,
                 и отдельного экрана для этого нет — кнопку не обещаем. */
              : undefined,
      });
    }
  }

  /* Пропажу данных сторожит движок своим правилом (#482). Раньше здесь стоял наш сторож с
     собственным порогом; теперь порог приходит из правил, а если правила про молчание нет — говорим
     это прямо, потому что молчание сенсора выглядит ровно как хороший сахар. */
  строки.push(вход.порогМолчанияМин != null
    ? { знак: 'ок', имя: 'Заметим пропажу данных', под: `молчание дольше ${вход.порогМолчанияМин} мин`,
      подробно: `Если показания перестанут приходить дольше чем на ${вход.порогМолчанияМин} минут, `
        + 'приложение разбудит вас само.\n\nЭто не мелочь: молчание сенсора выглядит на экране ровно '
        + 'как хороший ровный сахар — число просто перестаёт меняться. Без этой тревоги ночь с '
        + 'отвалившимся датчиком не отличить от спокойной.' }
    : { знак: 'нет', имя: 'Заметим пропажу данных', под: 'у движка нет правила про молчание',
      подробно: 'Сейчас никто не следит за тем, что данные перестали приходить. Молчание сенсора '
        + 'выглядит как ровный сахар, и отличить одно от другого ночью нечем.\n\n'
        + 'Правило задаёт движок; если его нет, обновите приложение целиком — не только интерфейс.' });

  /* Приборы — не разрешение, но часть того же обещания: тревога о низком сахаре считается
     от показаний, и если их нет, будить будет нечем независимо от настроек. */
  строки.push(сенсорМолчитМин == null
    ? { знак: 'не знаем', имя: 'Приборы на связи', под: 'показаний ещё не было',
      подробно: 'Показаний пока не приходило вовсе. Тревога о низком сахаре считается от них — пока '
        + 'данных нет, считать не от чего, и разбудить будет нечем независимо от настроек.' }
    : сенсорМолчитМин <= 15
      ? { знак: 'ок', имя: 'Приборы на связи', под: `последнее показание ${сенсорМолчитМин} мин назад`,
        подробно: 'Данные приходят. Это основа всего остального: тревоги считаются от показаний, и '
          + 'пока они идут, охране есть с чем работать.' }
      : { знак: 'нет', имя: 'Приборы на связи', под: `данных нет ${сенсорМолчитМин} мин`,
        подробно: `Последнее показание пришло ${сенсорМолчитМин} минут назад. Тревога о низком сахаре `
          + 'считается от показаний — пока их нет, она молчит не потому, что всё хорошо.\n\n'
          + 'Проверьте сенсор и связь с ним: телефон рядом, передатчик на месте, приложение-источник '
          + 'работает.' });

  if (фон?.problem) {
    строки.push({
      знак: 'нет', имя: 'Телефон не усыпит приложение', под: фон.reason,
      действие: фон.weCanOpenSettings ? 'настройки фона' : undefined,
    });
  } else if (фон) {
    строки.push({ знак: 'ок', имя: 'Телефон не усыпит приложение', под: 'исключение из энергосбережения выдано' });
  } else {
    /* Про фон не спросить — вендорская защита прошивки не отвечает ни на какой API. */
    строки.push({ знак: 'не знаем', имя: 'Прошивка не душит фон', под: 'этого мы проверить не можем' });
  }

  /* Та же строка, что и на пути обещания: граница обещания одна, и зависеть от возраста ядра она
     не должна. */
  const обновление = ночноеОбновление(вход.платформа);
  if (обновление) строки.push(обновление);

  if (!тревогиВедутся) {
    /* Правил нет — считать некому, и чинить разрешения бессмысленно: услышать нечего. Кнопки здесь
       тоже нет, и это честно: починить сборку ядра человек не может, её надо обновить целиком. */
    return {
      ответ: 'не сторожим',
      почему: вход.ядроСтарое
        ? 'В этой сборке тревог нет: ядро старее модели тревог, считать их некому.'
        : 'Тревоги считает движок, а он сейчас не следит ни за чем — ночью мы промолчим.',
      строки: [{
        знак: 'нет', имя: 'Правила тревог',
        под: вход.ядроСтарое ? 'ядро старее модели тревог — обновите приложение целиком'
          : 'движок не следит ни за одним поводом',
      }, ...строки],
    };
  }

  const сломано = строки.filter((с) => с.знак === 'нет');
  if (сломано.length) {
    return {
      ответ: 'может не разбудить',
      почему: сломано[0].под ? заглавная(сломано[0].под) + '.' : 'Что-то мешает нас услышать.',
      строки,
      главное: сломано.find((с) => с.действие)?.действие,
    };
  }
  return {
    ответ: 'разбудим',
    почему: 'Низкий сахар и пропажа данных. Звук будильника поверх «не беспокоить», даже если телефон беззвучный.',
    строки,
  };
}

const заглавная = (с: string) => с.charAt(0).toUpperCase() + с.slice(1);
