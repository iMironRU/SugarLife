/** Незнакомый код не прячем: пусть будет виден как есть — это честнее пустого места. */
function слова(id: string, из?: PermissionView): { имя: string; зачем: string } {
  const наше = СЛОВА[id];
  if (наше) return наше;
  /* Строка пришла из каталога движка: объяснение у него есть, имени нет — имя наше. */
  if (из) return { имя: ИМЯ_КАТАЛОГА[из.id] ?? из.id, зачем: из.gives };
  return { имя: id, зачем: '' };
}

/* КАТАЛОГ ДВИЖКА И ОПРОС СИСТЕМЫ — ЭТО ДВА РАЗНЫХ ЗНАНИЯ (мост ≥ 1.71, ядро #217, наш #813).

   Движок знает, ЧТО просить у этого человека и какими словами: он видит режим работы (свой прибор
   или наблюдение через интернет) и отдаёт уже отфильтрованный список. Система знает, ЧТО НАМ ДАЛИ.
   Ни одно из двух не выводится из другого, поэтому сращиваем, а не выбираем.

   ИМЕНА СРЕДСТВ У ДВИЖКА СВОИ (`ВендорскаяЗащита`), у нашего натива свои (`батарея`). Совпадают не
   все и не обязаны: у движка тринадцать средств, у нас пять на Android и восемь на iOS. Поэтому
   таблица, а не сравнение строк — и обе стороны, не нашедшие пары, остаются на экране: каталожная
   без состояния (мы просто не умеем его узнать), нативная — на наших прежних словах. */
const ПО_КАТАЛОГУ: Record<string, string> = {
  'Уведомления': 'уведомления',
  'ПравоНаСрочные': 'срочные',
  'ЭкранБлокировки': 'экран-блокировки',
  'ПолныйЭкран': 'поверх-экрана',
  'БезЭкономииБатареи': 'батарея',
  'Bluetooth': 'bluetooth',
  'Камера': 'камера',
  'Здоровье': 'здоровье',
};

/* Имена для средств, которых наш натив не опрашивает. Слова объяснений приходят от движка, а имя
   строки — наше: движок его не присылает, а «ВендорскаяЗащита» в списке читать нельзя. Спросил у
   ядра, не отдавать ли имя тоже (#813). */
const ИМЯ_КАТАЛОГА: Record<string, string> = {
  'ДоступКТихому': 'Доступ к «Не беспокоить»',
  'ТочныеБудильники': 'Точные будильники',
  'ВендорскаяЗащита': 'Защита от выгрузки прошивкой',
  'СводкаПоРасписанию': 'Уведомления вне сводки по расписанию',
  'ЗвуковойПоток': 'Свой звуковой поток',
};

/** Вес каталожной строки: сначала обязательное, потом выживание, потом всё прочее. */
function весКаталога(с: Строка): number {
  const обяз = с.нужно === 'Обязательно' ? 0 : с.нужно === 'Желательно' ? 1 : 2;
  const выж = с.зачемЭто === 'Выживание' ? 0 : с.зачемЭто === 'Возможность' ? 1 : 2;
  return обяз * 4 + выж;
}

export function строки(
  список: ПунктНатива[],
  каталог: PermissionView[] = [],
  платформа?: 'Android' | 'iOS',
): Строка[] {
  /* Средства, которых наш натив не опрашивает вовсе. Их состояние узнать нечем — но молчать о них
     нельзя: на Android именно здесь живёт вендорская защита, без которой всё кончается через восемь
     минут, а спросить систему о ней невозможно в принципе. */
  const своиже = new Set(список.map((п) => п.id));
  const лишние: ПунктНатива[] = каталог
    .filter((к) => !ПО_КАТАЛОГУ[к.id] || !своиже.has(ПО_КАТАЛОГУ[к.id]))
    .filter((к) => !платформа || к.platforms.length === 0 || к.platforms.includes(платформа))
    .map((к) => ({ id: к.id, статус: 'неизвестно' as const, спросить: false }));
  return [...список, ...лишние]
    .map((п): Строка => {
      /* Каталог ищем и по нашему коду, и по имени движка: в списке лежат оба вида строк. */
      const из = каталог.find((к) => ПО_КАТАЛОГУ[к.id] === п.id || к.id === п.id);
      const { имя, зачем } = слова(п.id, из);
      /* КРАСНЫЙ — ТОЛЬКО ЗАПРЕТ. «Ещё не спрашивали» запретом не является: у камеры это обычное
         состояние до первого сканирования, и красная точка там пугает без повода — а заодно
         обесценивает красную точку там, где она про настоящий отказ. */
      const порядок = п.статус === 'разрешено' ? 'да'
        : (п.статус === 'нет' || п.статус === 'частично') ? 'нет' : 'вопрос';
      return {
        ...п,
        имя,
        /* ЧЕЙ ТЕКСТ ПОБЕЖДАЕТ. Платформа знает про КОНКРЕТНЫЙ телефон — её слова первые. Дальше
           каталог движка: он написан подробнее нашего и учитывает режим работы. Наши общие слова
           остаются последней опорой, для средств, которых движок не прислал. */
        зачем: п.пояснение || из?.gives || зачем,
        нужно: из?.need as Строка['нужно'],
        зачемЭто: из?.purpose as Строка['зачемЭто'],
        безНего: из?.withoutIt,
        почемуВам: из?.whyYou ?? undefined,
        цена: из?.price ?? undefined,
        проверяемо: из?.checkable,
        знак: порядок,
        /* «Разрешено» — не повод предлагать действие: отнимать у себя разрешение через наш экран
           человек не собирается, а кнопка рядом со словом «разрешено» выглядит как «отозвать». */
        /* У «неизвестно» действия нет вовсе: система не ответила, и настройки этого не исправят —
           на iOS так выглядит сборка, подписанная без права на срочные. Кнопка, которая ничего не
           меняет, хуже её отсутствия: человек нажимает, ничего не происходит, виноватым остаётся
           приложение. Объяснение при этом никуда не девается — оно в шторке. */
        действие: п.статус === 'разрешено' || п.статус === 'неизвестно' ? null
          : (п.спросить ? 'спросить' : 'настройки'),
      };
    })
    .sort((а, б) => {
      /* Сначала то, что не в порядке: список из десяти строк читают до первой проблемы, и если она
         внизу — её не увидят. Внутри каждой половины — по цене отказа. */
      const беда = (с: Строка) => (с.знак === 'да' ? 1 : 0);
      if (беда(а) !== беда(б)) return беда(а) - беда(б);
      /* Каталог знает, что этому человеку обязательно, а что желательно, — это важнее нашего
         прежнего порядка «по цене отказа»: тот писался вслепую, одинаковым для всех. */
      if (весКаталога(а) !== весКаталога(б)) return весКаталога(а) - весКаталога(б);
      const вес = (с: Строка) => {
        const и = ПОРЯДОК.indexOf(с.id);
        return и < 0 ? ПОРЯДОК.length : и;
      };
      return вес(а) - вес(б);
    });
}

/* Цифра на входе в раздел — только про запреты.

   «Не спрашивали» в неё не входит по той же причине, по которой не красится красным: камера до
   первого сканирования не спрошена всегда, и цифра «1» висела бы на разделе вечно. Цифра, которая
   горит постоянно, перестаёт что-либо значить — ровно то, из-за чего в проекте вычищают
   постоянные подсветки. */
export function сколькоНеВПорядке(список: ПунктНатива[]): number {
  return список.filter((п) => п.статус === 'нет' || п.статус === 'частично').length;
}
