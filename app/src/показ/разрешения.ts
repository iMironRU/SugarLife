/** Незнакомый код не прячем: пусть будет виден как есть — это честнее пустого места. */
function слова(id: string): { имя: string; зачем: string } {
  return СЛОВА[id] ?? { имя: id, зачем: '' };
}

export function строки(список: ПунктНатива[]): Строка[] {
  return список
    .map((п): Строка => {
      const { имя, зачем } = слова(п.id);
      /* КРАСНЫЙ — ТОЛЬКО ЗАПРЕТ. «Ещё не спрашивали» запретом не является: у камеры это обычное
         состояние до первого сканирования, и красная точка там пугает без повода — а заодно
         обесценивает красную точку там, где она про настоящий отказ. */
      const порядок = п.статус === 'разрешено' ? 'да'
        : (п.статус === 'нет' || п.статус === 'частично') ? 'нет' : 'вопрос';
      return {
        ...п,
        имя,
        /* Слова платформы важнее наших: они знают про конкретный телефон, а мы писали общее. */
        зачем: п.пояснение || зачем,
        знак: порядок,
        /* «Разрешено» — не повод предлагать действие: отнимать у себя разрешение через наш экран
           человек не собирается, а кнопка рядом со словом «разрешено» выглядит как «отозвать». */
        /* У «неизвестно» действия нет вовсе: система не ответила, и настройки этого не исправят —
           на iOS так выглядит сборка, подписанная без права на срочные. Кнопка, которая ничего не
           меняет, хуже её отсутствия: человек нажимает, ничего не происходит, виноватым остаётся
           приложение. Объяснение при этом никуда не девается — оно в шторке. */
        действие: п.статус === 'разрешено' || п.статус === 'неизвестно' ? null
          : (п.спросить ? 'спросить' : 'настройки'),
      };
    })
    .sort((а, б) => {
      /* Сначала то, что не в порядке: список из десяти строк читают до первой проблемы, и если она
         внизу — её не увидят. Внутри каждой половины — по цене отказа. */
      const беда = (с: Строка) => (с.знак === 'да' ? 1 : 0);
      if (беда(а) !== беда(б)) return беда(а) - беда(б);
      const вес = (с: Строка) => {
        const и = ПОРЯДОК.indexOf(с.id);
        return и < 0 ? ПОРЯДОК.length : и;
      };
      return вес(а) - вес(б);
    });
}

/* Цифра на входе в раздел — только про запреты.

   «Не спрашивали» в неё не входит по той же причине, по которой не красится красным: камера до
   первого сканирования не спрошена всегда, и цифра «1» висела бы на разделе вечно. Цифра, которая
   горит постоянно, перестаёт что-либо значить — ровно то, из-за чего в проекте вычищают
   постоянные подсветки. */
export function сколькоНеВПорядке(список: ПунктНатива[]): number {
  return список.filter((п) => п.статус === 'нет' || п.статус === 'частично').length;
}
