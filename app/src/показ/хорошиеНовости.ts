import type { AlarmEventView } from '@/sources/bridge';

/* ХОРОШУЮ НОВОСТЬ ТОЖЕ НАДО СКАЗАТЬ (SugarLife#482, просьба ядра; вопрос владельца).

   Владелец спросил прямо: «есть „подача остановлена“ — а почему нет уведомления о начале?»

   До сих пор событие отбоя мы просто гасили, и не по недосмотру: в `words` у отбоя лежала фраза
   самой тревоги — «Подача инсулина остановлена». Показывать такое при снятии нельзя, поэтому мы
   молчали. Теперь ядро кладёт туда свою фразу: «Подача возобновлена», «Сахар поднялся: 5,2»,
   «Показания снова идут».

   ПОЧЕМУ МОЛЧАНИЕ — ПЛОХОЙ СПОСОБ СООБЩИТЬ ХОРОШЕЕ. Человек, который встал ночью и пошёл
   возобновлять подачу, без подтверждения пойдёт проверять ещё раз. Исчезновение тревоги
   неотличимо от того, что она не сработала вовсе, — а различить это ему нужно именно ночью.

   ТРИ УСЛОВИЯ ЯДРА, И ВСЕ ТРИ ОСМЫСЛЕННЫЕ:

   · без звука. Хорошая новость, сказанная будильником, — плохая новость;
   · без «Понял». Отвечать не на что, а кнопка требует действия там, где его нет;
   · живёт недолго. Это сообщение, а не состояние, и само уходит.

   `words == null` — говорить нечего, гасим молча, как раньше. Так приходит отбой учебной тревоги и
   вечерней проверки: там снятие не новость.

   СКОЛЬКО ЖИВЁТ. Десять минут — два круга показаний. Если человек за это время не взял телефон в
   руки, новость перестала быть новостью: он уже видит на экране нормальный сахар и идущую подачу.
   А что было ночью, отвечает не эта строка, а «Ночь позади» — там место истории, здесь минуты.

   СОБЫТИЯ ОДНОРАЗОВЫ. Снимок забирает их и очищает, поэтому копилка снаружи: без неё новость жила
   бы ровно до следующего снимка, то есть могла не пережить и одного взгляда на экран. */

export const ЖИЗНЬ_МС = 10 * 60_000;

export interface ХорошаяНовость {
  /** Ключ срабатывания: он же не даёт показать одну новость дважды. */
  id: string;
  слова: string;
  когдаМс: number;
  /* СКОЛЬКО ЕЙ ОСТАЛОСЬ, МИНУТАМИ (просьба владельца).

     «Если само — то нужен таймер или надпись, через сколько уйдёт». Он прав, и довод тот же, что
     у полосы тревоги со строкой «снимется через N мин»: молча исчезнувшее неотличимо от «мне
     показалось», а вопрос человека к экрану звучит как «почему это ещё здесь».

     Минутами, а не секундами: тикающие цифры на хорошей новости превращают её в напоминание.
     Ноль не бывает — при нуле новость уже удалена. */
  уйдётЧерезМин: number;
}

export type Копилка = Map<string, ХорошаяНовость>;

/** Забрать из снимка то, о чём стоит сказать. Копилку меняем на месте: она живёт дольше снимка. */
export function принять(
  копилка: Копилка, события: readonly AlarmEventView[] | null | undefined, сейчас: number,
): void {
  for (const с of события ?? []) {
    if (!с?.id || с.what !== 'cleared') continue;
    const слова = (с.words ?? '').trim();
    /* Слов нет — новости нет. Своей фразы не сочиняем: что именно вернулось в норму, знает движок,
       а «тревога снята» — это про нас, а не про человека. */
    if (!слова) continue;
    /* Уже приняли — время не обновляем: иначе повторный снимок с тем же событием продлевал бы
       жизнь новости бесконечно. */
    if (копилка.has(с.id)) continue;
    копилка.set(с.id, { id: с.id, слова, когдаМс: с.atMs ?? сейчас, уйдётЧерезМин: 0 });
  }
}

/** Что показать прямо сейчас. Просроченное выбрасываем из копилки — она не архив. */
export function свежие(копилка: Копилка, сейчас: number): ХорошаяНовость[] {
  const живые: ХорошаяНовость[] = [];
  for (const н of [...копилка.values()]) {
    const осталось = ЖИЗНЬ_МС - (сейчас - н.когдаМс);
    if (осталось <= 0) { копилка.delete(н.id); continue; }
    живые.push({ ...н, уйдётЧерезМин: Math.max(1, Math.ceil(осталось / 60_000)) });
  }
  /* Свежая новость выше старой: если их две, верхняя — та, что человек ещё не видел. */
  return живые.sort((а, б) => б.когдаМс - а.когдаМс);
}
