/** Ключ настройки движка. Значения — `on` / `off`, как у остальных его переключателей. */
export const КЛЮЧ_ВЫГРУЗКИ = 'nightscout.uploadAll';

/** Цена. Стоит рядом с переключателем всегда, а не прячется в подробностях. */
export const ЦЕНА_ВЫГРУЗКИ_ВСЕХ =
  'Лента в Nightscout одна, и читатели берут из неё самое свежее, не глядя, чей это прибор. '
  + 'Если приборы расходятся, петля будет считать дозу вперемешку по обоим. '
  + 'Нужны оба ряда — заведите второй адрес.';

/** Сколько приборов вообще могут дать сахар. Один — переключать нечего. */
export function приборовСахара(snap: UiSnapshot | null | undefined): number {
  return источникиСлота(snap, 'сахар').filter((и) => и.id !== 'руками').length;
}

/** Есть ли куда выгружать: без приёмника разговор беспредметен. */
function естьПриёмник(snap: UiSnapshot | null | undefined): boolean {
  return (snap?.connectors ?? []).length > 0;
}

/** Показывать ли переключатель. */
export function выгрузкуПоказывать(snap: UiSnapshot | null | undefined): boolean {
  return естьПриёмник(snap) && приборовСахара(snap) > 1;
}

/** Включено ли сейчас. Читаем у приёмника, а не из своей памяти: решает движок. */
export function выгружаемВсех(snap: UiSnapshot | null | undefined): boolean {
  return (snap?.connectors ?? []).some((к) => к.uploadAll === true);
}
