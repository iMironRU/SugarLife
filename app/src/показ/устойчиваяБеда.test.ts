import { describe, it, expect } from 'vitest';
import { ДЕРЖИМ_МС, осталосьМс, удержать } from './устойчиваяБеда';

const беда = (code: string) => ({ code, title: 'т', remediation: 'р' } as never);

describe('беда связи не моргает', () => {
  it('живая беда запоминается вместе со временем', () => {
    const r = удержать({ новая: беда('cloud.offline'), прежнее: { беда: null, виднаВМс: null }, сейчасМс: 1000 });
    expect(r.беда?.code).toBe('cloud.offline');
    expect(r.виднаВМс).toBe(1000);
  });

  /* Движок снимает беду на каждой попытке переподключиться — вот это и есть моргание. */
  it('пропавшую держим, пока не вышел срок', () => {
    const было = { беда: беда('cloud.offline'), виднаВМс: 1000 };
    const r = удержать({ новая: null, прежнее: было, сейчасМс: 1000 + ДЕРЖИМ_МС - 1 });
    expect(r.беда?.code).toBe('cloud.offline');
    /* Время не двигаем: иначе мигание продлевало бы удержание бесконечно. */
    expect(r.виднаВМс).toBe(1000);
  });

  it('по истечении срока верим, что связь вернулась', () => {
    const было = { беда: беда('cloud.offline'), виднаВМс: 1000 };
    expect(удержать({ новая: null, прежнее: было, сейчасМс: 1000 + ДЕРЖИМ_МС }).беда).toBeNull();
  });

  it('новая беда вытесняет удержанную сразу', () => {
    const было = { беда: беда('cloud.offline'), виднаВМс: 1000 };
    const r = удержать({ новая: беда('nightscout.auth.failed'), прежнее: было, сейчасМс: 1500 });
    expect(r.беда?.code).toBe('nightscout.auth.failed');
    expect(r.виднаВМс).toBe(1500);
  });

  it('осталось: сколько ещё держать', () => {
    expect(осталосьМс({ беда: null, виднаВМс: null }, 5)).toBeNull();
    expect(осталосьМс({ беда: беда('cloud.offline'), виднаВМс: 1000 }, 1000 + 20_000))
      .toBe(ДЕРЖИМ_МС - 20_000);
  });
});
