/* Слова находок разбора (SugarLife#324, #407).

   Разбор считает и возвращает ФАКТ: «канюля стоит пять дней», «медиана в этих часах выше
   верхней границы», «подъёмов без записи столько-то». Как это назвать человеку — решается
   здесь, и только здесь.

   Зачем это разделение. Файл разбора — самый плотный по правилам в приложении: пороги,
   окна, эпизоды, медианы. Пока формулировки жили внутри него, любая правка слова означала
   правку в файле, где рядом стоят числа, по которым человек принимает решения об инсулине.
   Обратное тоже верно: правило нельзя было проверить тестом, не сверяя буквы.

   Единицы глюкозы — тоже слова. Ммоль или мг/дл выбирает человек в настройках, и разбору
   до этого дела нет: он оперирует ммоль, а перевод и подпись живут здесь.

   ПОЛНОТА ДЕРЖИТСЯ ТИПОМ. `Record<ВидНаходки, …>` не даст завести правило без слов: новый
   вид не соберётся, пока ему не написана фраза. */

export interface СловаНаходки {
  title: string;
  message: string;
  question?: string;
}

/** Глюкоза в текущих единицах со знаком: «7,8 ммоль/л». */
