/** Разница глюкозы без подписи единиц — для мг/дл множитель другой. */
const gd = (mmol: number) => (unitLabel() === 'ммоль/л' ? mmol.toFixed(1) : Math.round(mmol * 18).toString());
const ч = (n: number) => `${n}:00`;

