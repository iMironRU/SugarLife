import type { UiSnapshot } from '@/sources/bridge';

/* ПРИБОРЫ РАСХОДЯТСЯ (#822, ядро #221, мост 1.73).

   У владельца два сенсора на разных руках расходятся на четыре ммоль. Ни одна программа про это не
   говорит: показывают одно число и молчат о том, что второе другое.

   РЕШЕНИЕ, ГОВОРИТЬ ЛИ, — НЕ НАШЕ, и это главное здесь. Два сенсора расходятся всегда: разное
   кровоснабжение, разный возраст, разный участок. Движок отсеивает всё, что объясняется приборами —
   расхождение должно продержаться четверть часа, числа быть одного сорта и возраста, обоим приборам
   есть двенадцать часов, — и только тогда кладёт поле. Поля нет — молчим, не рассуждая.

   ФРАЗУ ТОЖЕ НЕ ПИШЕМ: «как минимум один ошибается — проверьте глюкометром, какой ближе» это
   медицинское высказывание. Мы сами просили ядро отдавать число и фразу вместе, чтобы не было
   соблазна дописать вторую половину.

   А ВОТ ЧИСЛА ПРИБОРОВ ДОБАВЛЯЕМ, И ЭТО НЕ УКРАШЕНИЕ. Совет «проверьте глюкометром, какой ближе»
   невыполним, если не видно, какой прибор что показывает: человек померит и не будет знать, к чему
   приложить результат. Числа берём у самих приборов (`latestGlucoseMmol`), имена — их же. */

export interface СтрокаРасхождения {
  /** Готовая фраза движка. */
  текст: string;
  /** Кто с кем разошёлся: имя и число. Пусто — приборы не нашлись, тогда только фраза. */
  приборы: { id: string; имя: string; число: string }[];
}

const число = (x: number) => x.toFixed(1).replace('.', ',');

export function расхождение(снимок: UiSnapshot | null | undefined): СтрокаРасхождения | null {
  const р = снимок?.divergence;
  if (!р?.text) return null;

  const все = снимок?.devices ?? [];
  const приборы = (р.deviceIds ?? [])
    .map((id) => все.find((d) => d.id === id))
    /* Прибора нет в списке или числа у него нет — строку про него не выдумываем: «—» рядом с
       именем читается как поломка прибора, хотя это наша неполнота. */
    .filter((d) => d && d.latestGlucoseMmol != null)
    .map((d) => ({
      id: d!.id,
      имя: d!.name ?? d!.id,
      число: число(d!.latestGlucoseMmol as number),
    }));

  return { текст: р.text, приборы };
}

/** Подсветить ли карточку этого прибора: он один из разошедшихся. */
export function приборРазошёлся(снимок: UiSnapshot | null | undefined, id: string): boolean {
  return (снимок?.divergence?.deviceIds ?? []).includes(id);
}
