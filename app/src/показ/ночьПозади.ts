import type { AlarmEpisodeView, SleepView } from '@/sources/bridge';

/* ЧТО БЫЛО НОЧЬЮ (#597, ядро #176).

   Единственная часть суток, о которой у человека НЕТ своих воспоминаний. Он спал. Была ли тревога,
   услышал ли он её, ответил ли — до сегодня это знал только разработчик, читающий журнал.

   СОБИРАЛИ САМИ — ТЕПЕРЬ БЕРЁМ У ЯДРА. Вчера мы сшивали `Началась` с `ack` по идентификатору из
   журнала движка. Это была времянка, и ядро дало то, чего у нас быть не могло:

     · `asleep` — спал ли человек В ТУ МИНУТУ. Они прямо просили не выводить это заново из окна
       сна: окно меняется задним числом, когда часы досчитали, а запись должна остаться как было;
     · `unwoken` — дошло до «Разбудить», спал, не ответил ни разу. Не то же, что «не ответил»:
       днём человек вправе смахнуть и заняться делом;
     · `words` — то, что он увидел ПЕРВЫМ, а не пересчитанное потом.

   Своего второго ответа не заводим: сшивать по времени больше не нужно.

   ГОВОРИМ И О МОЛЧАНИИ. «Ночь прошла спокойно» — это ответ, а пустое место ответом не является:
   человек не отличит «тревог не было» от «мы спали и не знаем». */

export interface НочноеСобытие {
  когдаМс: number;
  что: string;
  /** Через сколько ответил; null — не ответил вовсе. */
  ответЧерезС: number | null;
  /** Дошло до «Разбудить», спал и не ответил. Показываем первым и заметнее прочего. */
  неДобудились: boolean;
}

export interface НочьПозади {
  строки: НочноеСобытие[];
  /** Ни одной тревоги, и мы при этом знали, что происходит. Это ответ, а не пустота. */
  спокойно: boolean;
}

/* ОКНО — ОТ ДВИЖКА. С 1.60 блок `sleep` есть ВСЕГДА, и «своего окна нет» выражается не пустотой, а
   `answerFrom === 'commonWindow'`. Общее окно движок называет словами (23:00–7:00) — берём его
   границы, а не зашиваем свои: два окна разойдутся в первый же день. */
const ОБЩЕЕ = { отЧаса: 23, доЧаса: 7 };

export function границыНочи(сейчасМс: number, окно?: SleepView | null): { от: number; до: number } {
  const доЧаса = часИз(окно?.to) ?? ОБЩЕЕ.доЧаса;
  const отЧаса = часИз(окно?.from) ?? ОБЩЕЕ.отЧаса;
  const д = new Date(сейчасМс);
  const утро = new Date(д.getFullYear(), д.getMonth(), д.getDate(), доЧаса, 0, 0, 0).getTime();
  /* До подъёма «прошедшая ночь» — это ещё текущая: человек проснулся раньше и спрашивает про неё. */
  const до = сейчасМс < утро ? сейчасМс : утро;
  const часов = (24 - отЧаса + доЧаса) % 24 || 8;
  return { от: до - часов * 3600e3, до };
}

/** «23:00» → 23. Ерунду не разбираем: лучше общее окно, чем съехавшее на случайное число. */
function часИз(строка?: string | null): number | null {
  const м = /^(\d{1,2}):\d{2}$/.exec(строка ?? '');
  const ч = м ? Number(м[1]) : NaN;
  return Number.isInteger(ч) && ч >= 0 && ч <= 23 ? ч : null;
}

export function ночьПозади(
  эпизоды: AlarmEpisodeView[] | undefined | null,
  сейчасМс: number,
  окно?: SleepView | null,
): НочьПозади {
  /* Эпизодов нет вовсе — движок их не ведёт (старый мост) или ещё не поднялся. Это не «спокойно»:
     сказать «тревог не было», когда мы не знаем, — дать лечь спать с ложной уверенностью. */
  if (!эпизоды) return { строки: [], спокойно: false };

  const { от, до } = границыНочи(сейчасМс, окно);
  const строки = эпизоды
    .filter((э) => э.startedAtMs >= от && э.startedAtMs <= до)
    .sort((a, b) => a.startedAtMs - b.startedAtMs)
    .map((э) => ({
      когдаМс: э.startedAtMs,
      /* Слова ядра как есть: оно писало их человеку, переводить нечего. */
      что: э.words,
      ответЧерезС: э.ackAfterMs != null ? Math.round(э.ackAfterMs / 1000) : null,
      неДобудились: !!э.unwoken,
    }));

  return { строки, спокойно: строки.length === 0 };
}
