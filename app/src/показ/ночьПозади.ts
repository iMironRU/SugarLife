import type { LogRecord } from '@/sources/bridge';

/* ЧТО БЫЛО НОЧЬЮ (#597).

   Единственная часть суток, о которой у человека НЕТ своих воспоминаний. Он спал. Была ли тревога,
   услышал ли он её, ответил ли — сегодня это знает только разработчик, читающий журнал движка.

   Поэтому ночь стоит в истории первой и отдельно: остальное человек помнит сам и приходит уточнить,
   а здесь ему нечего уточнять — он узнаёт впервые.

   СОБИРАЕМ ИЗ ЖУРНАЛА ДВИЖКА, а не заводим своё хранилище: приказ, слова и исход звука пишет он, и
   заводить рядом вторую запись о том же значило бы получить два ответа на вопрос «прозвучало ли».

   ГОВОРИМ И О МОЛЧАНИИ. «Ночь прошла спокойно» — это ответ, а пустое место ответом не является:
   человек не отличит «тревог не было» от «мы спали и не знаем». */

export interface НочноеСобытие {
  когдаМс: number;
  /** Что случилось, словами движка. */
  что: string;
  /** Через сколько ответил человек; null — не ответил вовсе. */
  ответЧерезС: number | null;
}

export interface НочьПозади {
  событий: number;
  строки: НочноеСобытие[];
  /** Ни одной тревоги — но мы при этом работали. Это ответ, а не пустота. */
  спокойно: boolean;
}

/* ОКНО — ОТ ДВИЖКА, ЕСЛИ ОН ЕГО ЗНАЕТ.

   Владелец спросил: «ночь же задаётся в настройках?». Должна — и в контракте ядра окно есть
   (`sleep.from` / `sleep.to`, `SleepView`). Но записи в него у нас нет ни строчки, экрана тоже, и
   движок поэтому возвращает пустой `SleepView`: без окна и без переключателя ему «говорить не о
   чем».

   То есть модель сна описана с обеих сторон и не работает НИ РАЗУ. Пока это так, окно здесь —
   заглушка 23:00–07:00, и она честно названа заглушкой.

   Как только окно появится — от кнопки «лёг спать» или от настройки, — оно приедет сюда снимком, и
   заглушка перестанет использоваться сама. Своего второго окна мы не заводим. */
const ЗАГЛУШКА = { отЧаса: 23, доЧаса: 7 };

/** Границы прошедшей ночи. `окно` — от движка (`SleepView`), null — берём заглушку. */
export function границыНочи(
  сейчасМс: number, окно?: { from?: string | null; to?: string | null } | null,
): { от: number; до: number } {
  const доЧаса = часИз(окно?.to) ?? ЗАГЛУШКА.доЧаса;
  const отЧаса = часИз(окно?.from) ?? ЗАГЛУШКА.отЧаса;
  const д = new Date(сейчасМс);
  const утро = new Date(д.getFullYear(), д.getMonth(), д.getDate(), доЧаса, 0, 0, 0).getTime();
  /* До подъёма «прошедшая ночь» — это ещё текущая: человек проснулся раньше и спрашивает про неё. */
  const до = сейчасМс < утро ? сейчасМс : утро;
  /* Длина окна через полночь: с 23 до 7 — восемь часов. */
  const часов = (24 - отЧаса + доЧаса) % 24 || 8;
  return { от: до - часов * 3600e3, до };
}

/** «23:00» → 23. Ерунду не разбираем: лучше заглушка, чем окно, съехавшее на случайное число. */
function часИз(строка?: string | null): number | null {
  const м = /^(\d{1,2}):\d{2}$/.exec(строка ?? '');
  const ч = м ? Number(м[1]) : NaN;
  return Number.isInteger(ч) && ч >= 0 && ч <= 23 ? ч : null;
}

/* Тревога и ответ — две разные записи движка, и связывает их только порядок во времени: `Началась`
   с идентификатором, потом `ack` с тем же. Идентификатор берём из полей, а не из текста: текст
   пишет движок для человека и вправе его менять. */
export function ночьПозади(
  записи: LogRecord[], сейчасМс: number,
  окно?: { from?: string | null; to?: string | null } | null,
): НочьПозади {
  const { от, до } = границыНочи(сейчасМс, окно);
  const ночные = записи
    .filter((з) => з.atMs >= от && з.atMs <= до && з.tag === 'alarm')
    .sort((a, b) => a.atMs - b.atMs);

  const строки: НочноеСобытие[] = [];
  const начатые = new Map<string, НочноеСобытие>();

  for (const з of ночные) {
    const id = String(з.fields?.id ?? '');
    if (з.event === 'Началась' && id) {
      const с: НочноеСобытие = { когдаМс: з.atMs, что: словамиПро(id), ответЧерезС: null };
      начатые.set(id, с);
      строки.push(с);
    } else if (з.event === 'ack' && id) {
      const с = начатые.get(id);
      /* Ответ засчитываем только своей тревоге: `ack` без начала — это подтверждение того, что
         началось до ночи, и приписывать его ночной тревоге значило бы соврать в сторону покоя. */
      if (с && с.ответЧерезС === null) с.ответЧерезС = Math.round((з.atMs - с.когдаМс) / 1000);
    }
  }

  /* «Спокойно» имеем право сказать, только если журнал за эту ночь вообще есть: пустой журнал
     означает, что мы не работали, и это противоположный ответ. */
  const былиЖивы = записи.some((з) => з.atMs >= от && з.atMs <= до);
  return { событий: строки.length, строки, спокойно: былиЖивы && строки.length === 0 };
}

/* Имена тревог движка — его же словами, но короче: в ленте нужна строка, а не абзац. Незнакомое
   имя показываем как есть: выдуманное название хуже непонятного. */
function словамиПро(id: string): string {
  switch (id) {
    case 'гипо': return 'Низкий сахар';
    case 'прогноз-падения': return 'Сахар падал';
    case 'гипер': return 'Высокий сахар';
    case 'молчание': return 'Данные не приходили';
    case 'подача-остановлена': return 'Подача была остановлена';
    default: return id;
  }
}
