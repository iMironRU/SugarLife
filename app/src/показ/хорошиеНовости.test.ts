import { describe, it, expect } from 'vitest';
import { принять, свежие, ЖИЗНЬ_МС, type Копилка } from './хорошиеНовости';
import type { AlarmEventView } from '@/sources/bridge';

const с = (o: Partial<AlarmEventView>): AlarmEventView =>
  ({ id: 'подача:1', what: 'cleared', level: 'Разбудить', baseLevel: 'Разбудить', atMs: 1_000, ...o });
const t = 1_000;

describe('хорошие новости', () => {
  it('отбой со словами движка показываем', () => {
    const к: Копилка = new Map();
    принять(к, [с({ words: 'Подача возобновлена.' })], t);
    expect(свежие(к, t).map((н) => н.слова)).toEqual(['Подача возобновлена.']);
  });

  /* Слов нет — новости нет. Своей фразы не сочиняем: «тревога снята» это про нас, а не про
     человека, и такой отбой приходит у учебной тревоги. */
  it('без слов гасим молча, как раньше', () => {
    const к: Копилка = new Map();
    принять(к, [с({ words: null }), с({ id: 'x', words: '   ' })], t);
    expect(свежие(к, t)).toEqual([]);
  });

  it('это не про начало и не про повтор — только про отбой', () => {
    const к: Копилка = new Map();
    принять(к, [
      с({ id: 'a', what: 'started', words: 'Подача инсулина остановлена.' }),
      с({ id: 'b', what: 'repeat', words: 'Подача инсулина остановлена.' }),
      с({ id: 'c', what: 'pauseOver', words: 'Пауза кончилась.' }),
    ], t);
    expect(свежие(к, t)).toEqual([]);
  });

  it('живёт недолго: это сообщение, а не состояние', () => {
    const к: Копилка = new Map();
    принять(к, [с({ words: 'Подача возобновлена.', atMs: t })], t);
    expect(свежие(к, t + ЖИЗНЬ_МС - 1)).toHaveLength(1);
    expect(свежие(к, t + ЖИЗНЬ_МС)).toHaveLength(0);
  });

  /* Просроченное выбрасываем: копилка это окно, а не архив, и расти ей незачем. */
  it('просроченное уходит из копилки, а не копится', () => {
    const к: Копилка = new Map();
    принять(к, [с({ words: 'Подача возобновлена.', atMs: t })], t);
    свежие(к, t + ЖИЗНЬ_МС);
    expect(к.size).toBe(0);
  });

  /* Снимок приходит раз в несколько минут, и одно событие может приехать дважды. Продлевать ему
     жизнь нельзя: так «недолго» превратилось бы в «пока движок не замолчит». */
  it('повторное событие не продлевает жизнь новости', () => {
    const к: Копилка = new Map();
    принять(к, [с({ words: 'Подача возобновлена.', atMs: t })], t);
    принять(к, [с({ words: 'Подача возобновлена.', atMs: t + 5 * 60_000 })], t + 5 * 60_000);
    expect(к.get('подача:1')?.когдаМс).toBe(t);
    expect(свежие(к, t + ЖИЗНЬ_МС)).toHaveLength(0);
  });

  it('свежая новость стоит выше старой', () => {
    const к: Копилка = new Map();
    принять(к, [
      с({ id: 'старая', words: 'Показания снова идут.', atMs: t }),
      с({ id: 'новая', words: 'Сахар поднялся: 5,2.', atMs: t + 60_000 }),
    ], t);
    expect(свежие(к, t + 2 * 60_000).map((н) => н.id)).toEqual(['новая', 'старая']);
  });
});
