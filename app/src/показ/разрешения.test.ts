import { describe, it, expect } from 'vitest';
import { строки, сколькоНеВПорядке, type ПунктНатива } from './разрешения';

const п = (id: string, статус: ПунктНатива['статус'], спросить = false,
           пояснение?: string): ПунктНатива => ({ id, статус, спросить, пояснение });

describe('разрешения', () => {
  it('поднимает наверх то, что не в порядке', () => {
    /* Список читают до первой проблемы. Если запрет внизу — его не увидят, а узнают о нём ночью. */
    const р = строки([п('камера', 'разрешено'), п('уведомления', 'нет'), п('bluetooth', 'разрешено')]);
    expect(р[0].id).toBe('уведомления');
  });

  it('среди бед первым идёт то, что дороже стоит', () => {
    const р = строки([п('камера', 'нет'), п('срочные', 'нет'), п('батарея', 'нет')]);
    expect(р.map((с) => с.id)).toEqual(['срочные', 'батарея', 'камера']);
  });

  it('спрашивать предлагает только там, где вопрос ещё имеет смысл', () => {
    /* Второй диалог система молча проглатывает: кнопка «Разрешить» после отказа не делает ничего,
       и человек решает, что сломано приложение. */
    const р = строки([п('уведомления', 'не спрашивали', true), п('камера', 'нет', false)]);
    expect(р.find((с) => с.id === 'уведомления')?.действие).toBe('спросить');
    expect(р.find((с) => с.id === 'камера')?.действие).toBe('настройки');
  });

  it('у разрешённого действия нет', () => {
    expect(строки([п('камера', 'разрешено')])[0].действие).toBeNull();
  });

  it('незнакомый код показывает как есть, а не прячет', () => {
    const с = строки([п('что-то-новое', 'нет')])[0];
    expect(с.имя).toBe('что-то-новое');
    expect(с.знак).toBe('нет');
  });

  it('«неизвестно» бедой не считает', () => {
    /* Система не ответила — это не запрет. Пугать цифрой на входе в раздел из-за незнания нельзя. */
    expect(сколькоНеВПорядке([п('срочные', 'неизвестно'), п('камера', 'нет')])).toBe(1);
  });

  it('слова платформы важнее наших: она знает про конкретный телефон', () => {
    /* У энергосбережения объяснение приходит от ядра — оно учитывает производителя и то, нужно ли
       исключение вообще. Наше общее «иначе система усыпляет» там было бы грубее и иногда неверно. */
    const с = строки([п('батарея', 'частично', false, 'телефон разрешает работать в фоне')])[0];
    expect(с.зачем).toBe('телефон разрешает работать в фоне');
  });

  it('«ещё не спрашивали» не красит красным и не считается бедой', () => {
    /* У камеры это обычное состояние до первого сканирования: красная точка и вечная цифра «1» на
       разделе научили бы не замечать ни то, ни другое. */
    const с = строки([п('камера', 'не спрашивали', true)])[0];
    expect(с.знак).toBe('вопрос');
    expect(с.действие).toBe('спросить');
    expect(сколькоНеВПорядке([п('камера', 'не спрашивали', true)])).toBe(0);
  });

  it('у «неизвестно» действия нет: настройки этого не чинят', () => {
    /* Так выглядит сборка, подписанная без права на срочные. Кнопка «настройки» тут не меняет
       ничего, и виноватым в этом остаётся приложение. */
    expect(строки([п('срочные', 'неизвестно')])[0].действие).toBeNull();
  });
});
