import type { AlarmRuleView } from '@/sources/bridge';

/* ЧЕРЕЗ СКОЛЬКО МОЛЧАНИЯ ДВИЖОК РАЗБУДИТ — ОДНИМ МЕСТОМ.

   Порогов у правила два и они разные: днём человек заметит пропажу сам, ночью не заметит никак,
   поэтому во сне срок строже. Спрашивающий обязан сказать, про какой из них спрашивает, — иначе
   ответ зависит от того, в каком порядке движок положил ключи в снимок.

   Здесь стояло именно это: `Object.values(settings).find((_, i) => Object.keys(settings)[i]
   .includes('silence'))`. То есть брался первый попавшийся ключ со словом «silence» — днём или во
   сне, как повезёт с порядком. Ошибка тихая: число на экране выглядит настоящим в обоих случаях.

   Ключа нет — отвечаем `null`, а не подставляем соседний. Соседний здесь означает «сказали про
   день, имея в виду ночь», и это ровно тот класс вранья, из-за которого поле и заводилось. */

export type Когда = 'день' | 'сон';

const КЛЮЧ: Record<Когда, string> = {
  день: 'alarms.silence.dayMin',
  сон: 'alarms.silence.sleepMin',
};

export function порогМолчанияМин(
  правила: readonly AlarmRuleView[] | null | undefined,
  когда: Когда,
): number | null {
  const правило = (правила ?? []).find((п) => п.kind === 'silence');
  const строка = правило?.settings?.[КЛЮЧ[когда]];
  if (строка == null) return null;
  const число = Number(строка);
  return Number.isFinite(число) ? число : null;
}
