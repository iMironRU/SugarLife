import type { Problem, UiSnapshot } from '@/sources/bridge';
import { ярлыкБеды } from '@/слова/застой';

/* ПОКАЗЫВАТЬ ЛИ РАССКАЗ ПРО ОБРЫВ СВЯЗИ (SugarLife#805, поймано на живом телефоне).

   Владелец прислал снимок: сверху «Внешний CGM · 1 мин», то есть показание минутной давности, а
   ниже — «Связи нет. Данные пойдут сами, как только сеть вернётся». Утверждение о настоящем,
   которое неверно в ту же секунду, когда его читают.

   Как так вышло. Беда живёт на источнике и снимается, когда ЕГО канал снова ответит. Но числа
   могут пойти другим путём — по радио, из второго облака, — и тогда прошлая беда остаётся висеть
   при живых данных.

   ПРАВИЛО, КОТОРОЕ ИЗ ЭТОГО СЛЕДУЕТ, И ОНО ШИРЕ ОДНОГО ЭКРАНА: два наших высказывания о настоящем
   не имеют права противоречить друг другу. Число на экране свежее — значит связь есть, и рассказ
   про её отсутствие надо гасить, чей бы канал ни жаловался.

   ГАСИМ РОВНО ОДИН КОД, И ЭТО ВАЖНЕЕ, ЧЕМ КАЖЕТСЯ.

   Первая версия правила гасила всё «про сеть», и тест поймал, что я выдумываю коды. Разобрал
   настоящие — и оказалось, что противоречит свежим числам только один:

     cloud.offline              «связи нет»          ← про НАШ телефон, и при живых числах это ложь
     cloud.unreachable          «облако недоступно»  ← про конкретное облако, остаётся правдой
     cloud.unreachable.online   «облако не отвечает» ← то же
     cloud.server.error         «облако с ошибкой»   ← то же
     cloud.tls.failed           «шифрование не встало»
     nightscout.auth.failed     «доступ отклонён»

   Все, кроме первого, говорят про ОДИН канал. Если числа пришли другим путём, канал всё равно
   сломан, и человеку это чинить — гасить такое значило бы прятать настоящую беду.

   А «связи нет» — утверждение про телефон целиком, и рядом со свежим числом оно просто неверно. */
const ПРО_ТЕЛЕФОН = new Set(['cloud.offline']);

export function проСеть(код: string | null | undefined): boolean {
  return !!код && ПРО_ТЕЛЕФОН.has(код);
}

/**
 * Что показать в блоке застоя. `null` — молчим.
 *
 * `свежо` — идут ли показания прямо сейчас. Тот же признак, по которому шапка пишет возраст:
 * второго мнения о свежести мы не заводим (`domain/freshness.ts`).
 */
export function бедаДляПоказа(
  проблема: Problem | null | undefined, свежо: boolean,
): Problem | null {
  if (!проблема || !ярлыкБеды(проблема.code)) return null;
  if (свежо && проСеть(проблема.code)) return null;
  return проблема;
}

/** Идут ли показания прямо сейчас — по статусу монитора, как везде. */
export function показанияСвежие(snap: UiSnapshot | null | undefined): boolean {
  return (snap?.monitor?.status ?? '') === 'Live';
}
