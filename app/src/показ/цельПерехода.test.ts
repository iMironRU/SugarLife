import { describe, it, expect } from 'vitest';
import { слушатьЦель, податьЦель } from './цельПерехода';

/* Проверяем то, ради чего эта прослойка вообще существует: цель приходит раньше, чем появляется
   тот, кто умеет открывать разделы. Холодный старт из уведомления — главный случай (#524): человека
   подняли ночью, он нажал на тревогу, приложение поднимается с нуля. Если цель теряется здесь, она
   теряется ровно тогда, когда была нужна. */
describe('цель перехода', () => {
  it('дожидается подписчика, если пришла до него', () => {
    податьЦель('охрана');
    const было: string[] = [];
    const отписаться = слушатьЦель((ц) => было.push(ц));
    expect(было).toEqual(['охрана']);
    отписаться();
  });

  it('отдаёт накопленную цель один раз, а не каждому следующему', () => {
    податьЦель('сенсор');
    const первый: string[] = [];
    const отписаться1 = слушатьЦель((ц) => первый.push(ц));
    отписаться1();
    const второй: string[] = [];
    const отписаться2 = слушатьЦель((ц) => второй.push(ц));
    expect(первый).toEqual(['сенсор']);
    expect(второй).toEqual([]);
    отписаться2();
  });

  it('ведёт туда, куда нажали последним', () => {
    /* Пока человек шёл до телефона, могло прийти второе уведомление. Очередь переходов провела бы
       его через оба экрана — вести надо туда, куда он нажал. */
    податьЦель('помпа');
    податьЦель('сегодня');
    const было: string[] = [];
    const отписаться = слушатьЦель((ц) => было.push(ц));
    expect(было).toEqual(['сегодня']);
    отписаться();
  });

  it('при живом подписчике отдаёт сразу', () => {
    const было: string[] = [];
    const отписаться = слушатьЦель((ц) => было.push(ц));
    податьЦель('охрана');
    податьЦель('помпа');
    expect(было).toEqual(['охрана', 'помпа']);
    отписаться();
  });

  it('пустую цель не пускает: «никуда» — это не место', () => {
    const было: string[] = [];
    const отписаться = слушатьЦель((ц) => было.push(ц));
    податьЦель('');
    expect(было).toEqual([]);
    отписаться();
  });
});
