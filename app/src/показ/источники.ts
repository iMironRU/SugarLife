import type { DeviceView, UiSnapshot } from '@/sources/bridge';
import { связь, устройствоРоли, толькоОблако, рольСнимка } from '@/domain/deviceState';
import { каналСлота } from '@/domain/slotStatus';
import { СЛОВО_ПУТИ } from '@/слова/слоты';
import { мостЖелезки, имяЖелезки, железоДиспетчера } from '@/domain/nearby';

/* Откуда берутся данные — по слотам, а не по приборам (SugarLife#277).

   Человек приходит сюда не с вопросом «что у меня есть», а с вопросом «почему цифры
   старые». Отвечает на него слот: что нужно (сахар, инсулин, углеводы) → чем приходит
   (напрямую, через мост, облаком) → кто даёт (прибор, облако, руки).

   Глюкометр здесь ИСТОЧНИК САХАРА, а не отдельная строка. У ядра он пока отдельная роль
   (`meter`), и это расхождение записано в #277: измеряет он ту же величину, просто
   дискретно и руками, и человеку он «ещё один способ узнать сахар».

   Углеводы — слот, которого в контракте нет вовсе. Их наполняет человек, и именно
   поэтому слот нужен: без него не видно разницы между «не ел» и «не внёс», а на ней
   стоит половина наших подсказок. */

export type Слот = 'сахар' | 'инсулин' | 'углеводы';

export interface Источник {
  id: string;
  имя: string;
  /** Чем он приходит — словом человеку. */
  подпись: string;
  активен: boolean;
  /** Готов отдавать прямо сейчас: по нему решается, предлагать ли «предпочесть». */
  живой: boolean;
}

const РОЛЬ: Record<'сахар' | 'инсулин', 'sensor' | 'pump'> = {
  сахар: 'sensor', инсулин: 'pump',
};

/* Кандидаты слота: всё, что умеет его наполнять.

   Берём из devices[] — это проекции источников, и именно они отвечают на «кто даёт».
   Железо (hardware[]) отвечает на другой вопрос и сюда не идёт: мост данных не даёт, он
   их переносит, и предлагать выбрать мост источником — сбивать с толку. */
export function источникиСлота(
  snap: UiSnapshot | null | undefined, слот: Слот,
): Источник[] {
  if (слот === 'углеводы') {
    /* Руками — всегда доступный источник, и потому единственный, у которого нет
       состояния. Весы и распознавание еды встанут сюда же, когда появятся. */
    return [{ id: 'руками', имя: 'Ручной ввод', подпись: 'всегда доступен', активен: true, живой: true }];
  }
  const активный = устройствоРоли(snap, РОЛЬ[слот])?.id ?? null;
  const приборы = (snap?.devices ?? [])
    .filter((d) => подходит(d, слот))
    .map((d) => ({
      id: d.id,
      имя: d.name,
      подпись: подписьИсточника(d, snap, слот),
      активен: d.id === активный,
      живой: связь(d) === 'live',
    }));
  if (слот !== 'сахар') return приборы;
  /* Ручной ввод — такой же источник сахара, как прибор: человек померил глюкометром и
     внёс. Стоит последним и никогда не «сейчас»: он не поток, он дополняет. Показываем
     всегда, потому что доступен всегда — это единственный источник, который не может
     отвалиться. */
  return [...приборы, {
    id: 'руками', имя: 'Ручной ввод', подпись: 'значение с глюкометра, внесённое руками',
    активен: false, живой: true,
  }];
}

function подходит(d: DeviceView, слот: Слот): boolean {
  const роли = d.roles ?? [];
  /* Глюкометр — источник САХАРА, а не свой слот (SugarLife#277, SugarLifeCore#55).

     Он измеряет ту же величину, просто дискретно: одно значение вместо потока. У ядра
     роль `meter` осталась — она про драйвер, про то, что прибор такого вида существует;
     слотом она быть перестала, и правильно: человеку «ещё один способ узнать сахар» не
     заводит отдельной строки в вопросе «откуда цифры».

     Отдельного вида устройства под глюкометр в контракте нет: он приезжает обычным
     источником глюкозы (`GlucoseSource`). Поэтому и проверять надо роль, а не вид —
     проверка вида молча пропустила бы его. */
  if (слот === 'сахар') return d.kind === 'sensor' || роли.includes('GlucoseSource');
  return d.kind === 'pump' || роли.includes('PumpStateSource') || роли.includes('DeliveryHistorySource');
}

/* Как описать источник одной строкой: чем приходит и в каком он состоянии.

   Мост называем по имени: «через OrangeLink» человеку полезнее, чем «через мост», —
   когда мостов два, второе не отвечает ни на что. */
/* Что именно приносит облачный источник (замечание с телефона).

   В слоте «инсулин» из одного Nightscout приезжают ДВА источника: «Внешняя помпа» и
   «Лечение». Оба подписаны «облако», у обоих в имени один и тот же адрес, и человек
   читает это как дубль — «почему два одинаковых».

   Дубля нет: это разные потоки одного сервера. Один отдаёт состояние помпы — остаток,
   заряд, базал; другой записи о подачах — болюсы. Половины разные, и слот наполняют
   вместе. Разводит их роль, которую движок и присылает (`addCloudSource.streams`
   заводит их отдельно, а `roles` говорит, кто чем стал). Без этой подписи выбор между
   ними выглядит выбором между одинаковым. */
function чтоПриносит(d: DeviceView): string | null {
  const роли = d.roles ?? [];
  if (роли.includes('PumpStateSource')) return 'остаток, заряд, базал';
  if (роли.includes('DeliveryHistorySource')) return 'записи о болюсах';
  return null;
}

function подписьИсточника(
  d: DeviceView, snap: UiSnapshot | null | undefined, слот?: Слот,
): string {
  if (толькоОблако(d)) {
    /* Только в слоте инсулина: у сахара облачный источник один, и уточнять нечего —
       лишнее слово там читалось бы как намёк на второй, которого нет. */
    const что = слот === 'инсулин' ? чтоПриносит(d) : null;
    return что ? `облако · ${что}` : 'облако';
  }
  const железо = железоДиспетчера(snap).find((h) => h.id === d.id);
  const мост = железо ? мостЖелезки(железо, snap) : null;
  const путь = мост ? `через «${имяЖелезки(мост)}»` : 'напрямую по блютусу';
  const состояние = связь(d) === 'live' ? 'на связи'
    : связь(d) === 'wait' ? 'подключается' : 'нет связи';
  return `${путь} · ${состояние}`;
}

/* Почему слот наполняет именно этот источник — и стоит ли об этом говорить.

   Молчим, когда всё хорошо: объяснение при работающем прямом чтении — шум. Говорим,
   когда данные идут в обход железа, потому что это и есть невидимая половина правды:
   «на связи» у слота при молчащем приборе человек читает как «всё в порядке», а цифры
   при этом могут отставать на часы. */
export function причинаСлота(
  snap: UiSnapshot | null | undefined, слот: Слот,
): string | null {
  if (слот === 'углеводы') return null;
  /* С 1.13 причину говорит движок (fallbackReason): он знает, ЧТО именно молчит, а мы
     бы написали общее место. Берём как есть — то же правило, что с remediation у
     облачных ошибок. Свой расчёт ниже остаётся для сборок постарше. */
  const отДвижка = рольСнимка(snap, РОЛЬ[слот])?.fallbackReason?.trim();
  if (отДвижка) return отДвижка;
  if (каналСлота(snap, РОЛЬ[слот]) !== 'cloud') return null;

  const своё = (snap?.devices ?? []).find((d) => подходит(d, слот) && !толькоОблако(d));
  if (!своё) return null;
  if (связь(своё) === 'live') return null;

  const железо = железоДиспетчера(snap).find((h) => h.id === своё.id);
  const мост = железо ? мостЖелезки(железо, snap) : null;
  if (мост && связь(мост) !== 'live') {
    return `До прибора не дозвониться: «${имяЖелезки(мост)}» не на связи, а «${своё.name}» слышно только через него.`;
  }
  return `Прямое чтение недоступно: «${своё.name}» не на связи. Цифры приходят из облака и могут отставать.`;
}

/* Наполняется ли слот вообще. Зелёная точка при пустом слоте — обещание, которого никто
   не давал: «источник не выбран» это не «всё хорошо». */
export function наполненЛи(snap: UiSnapshot | null | undefined, слот: Слот): boolean {
  if (слот === 'углеводы') return true;
  return устройствоРоли(snap, РОЛЬ[слот]) != null;
}

/* Какую учётку чинить, если слот молчит из-за неё (rev ≥ 1.14).

   Возвращаем id, а не текст: назвать учётку по-человечески может только тот, кто видит
   accounts[], а это дело экрана. Наше дело — сказать, что причина именно там. */
export function учёткаСлота(
  snap: UiSnapshot | null | undefined, слот: Слот,
): string | null {
  if (слот === 'углеводы') return null;
  const кто = устройствоРоли(snap, РОЛЬ[слот]);
  if (!кто?.requiresAccountId) return null;
  /* Живой источник чинить не надо: учётка нужна ему всегда, а говорим мы о ней только
     когда данные не идут. */
  return связь(кто) === 'live' ? null : кто.requiresAccountId;
}

/** Чем слот наполняется сейчас — короткой строкой под именем. */
export function откудаСейчас(
  snap: UiSnapshot | null | undefined, слот: Слот,
): string {
  if (слот === 'углеводы') return 'вношу сам';
  const канал = каналСлота(snap, РОЛЬ[слот]);
  const кто = устройствоРоли(snap, РОЛЬ[слот]);
  if (!кто) return 'источник не выбран';
  return [канал ? СЛОВО_ПУТИ[канал] : null, кто.name].filter(Boolean).join(' · ');
}
