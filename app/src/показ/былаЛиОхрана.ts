import type { GuardGapView } from '@/sources/bridge';

/* БЫЛА ЛИ ОХРАНА, ПОКА Я СПАЛ (мост 1.46, ядро #138).

   Единственный из внутренних журналов, который обязан быть виден человеку: он отвечает на ЕГО
   вопрос, а не на наш. Приложение, поднявшееся после того, как его выгрузили, вело себя как ни в
   чём не бывало — и человек не узнавал, что ночь прошла без наблюдения.

   Мы это поле зеркалили и не показывали нигде. Ядро указало на него прямо, и день, в который оно
   указало, был днём с двадцатью одной выгрузкой: без этой строки «телефон убил приложение» и «всё
   было хорошо» выглядят на экране одинаково.

   ЗАЧЕМ СВОДКА, А НЕ СПИСОК. Двадцать одна строка «нас не было 7 минут» — это не двадцать одна
   новость, а одна: ночь прошла с дырами. Список нужен тому, кто уже спросил «когда именно»; ответ
   нужен всем. Поэтому наверху одна фраза, а подробности ниже и мельче.

   ЧИСЛА НЕ ОКРУГЛЯЕМ В МЕНЬШУЮ СТОРОНУ. «Меньше минуты» пишем как есть: дыра в полминуты между
   двумя показаниями значит меньше, чем дыра в час, и делать вид, что её не было, — то же враньё,
   только маленькое. */

export interface СводкаОхраны {
  /** Одна фраза для человека. Пусто — говорить не о чем, дыр не было. */
  ответ: string | null;
  /** Сколько раз нас не было. */
  сколько: number;
  /** Суммарно минут. */
  всего: number;
  /** Самая длинная дыра, минут. */
  самая: number;
}

/** Почему нас не было — словами. Незнакомую причину не выдумываем. */
export function почему(код: string): string {
  if (код === 'reboot') return 'перезагрузка телефона';
  if (код === 'swiped') return 'приложение смахнули';
  if (код === 'killed') return 'телефон выгрузил приложение';
  return '';
}

/**
 * Сводка по дырам за окно.
 *
 * @param дыры что прислал движок
 * @param сейчас текущее время (передаётся, а не берётся из часов: так функция проверяема)
 * @param часов какое окно считаем — сутки по умолчанию
 */
export function сводка(дыры: GuardGapView[], сейчас: number, часов = 24): СводкаОхраны {
  const порог = сейчас - часов * 3600e3;
  const свежие = дыры.filter((д) => д.atMs > порог);
  if (!свежие.length) return { ответ: null, сколько: 0, всего: 0, самая: 0 };

  const всего = свежие.reduce((с, д) => с + д.minutes, 0);
  const самая = свежие.reduce((м, д) => Math.max(м, д.minutes), 0);
  const раз = свежие.length;

  /* Одна дыра и много дыр — разные новости, и говорить о них надо по-разному. Одна означает
     случай; двадцать одна — что так теперь живём, и это уже про настройки телефона. */
  const ответ = раз === 1
    ? `За сутки приложение выгружали один раз, на ${минуты(самая)}.`
    : `За сутки приложение выгружали ${раз} раз, суммарно на ${минуты(всего)}. `
      + `Самый долгий перерыв — ${минуты(самая)}.`;
  return { ответ, сколько: раз, всего, самая };
}

/** Минуты словами: часы отдельно, потому что «на 145 минут» человек не читает. */
export function минуты(м: number): string {
  if (м < 1) return 'меньше минуты';
  if (м < 60) return `${Math.round(м)} мин`;
  const ч = Math.floor(м / 60);
  const ост = Math.round(м % 60);
  return ост ? `${ч} ч ${ост} мин` : `${ч} ч`;
}
