import type { GuardGapView } from '@/sources/bridge';

/* БЫЛА ЛИ ОХРАНА, ПОКА Я СПАЛ (мост 1.46, ядро #138).

   Единственный из внутренних журналов, который обязан быть виден человеку: он отвечает на ЕГО
   вопрос, а не на наш. Приложение, поднявшееся после того, как его выгрузили, вело себя как ни в
   чём не бывало — и человек не узнавал, что ночь прошла без наблюдения.

   Мы это поле зеркалили и не показывали нигде. Ядро указало на него прямо, и день, в который оно
   указало, был днём с двадцатью одной выгрузкой: без этой строки «телефон убил приложение» и «всё
   было хорошо» выглядят на экране одинаково.

   ЗАЧЕМ СВОДКА, А НЕ СПИСОК. Двадцать одна строка «нас не было 7 минут» — это не двадцать одна
   новость, а одна: ночь прошла с дырами. Список нужен тому, кто уже спросил «когда именно»; ответ
   нужен всем. Поэтому наверху одна фраза, а подробности ниже и мельче.

   ЧИСЛА НЕ ОКРУГЛЯЕМ В МЕНЬШУЮ СТОРОНУ. «Меньше минуты» пишем как есть: дыра в полминуты между
   двумя показаниями значит меньше, чем дыра в час, и делать вид, что её не было, — то же враньё,
   только маленькое. */

export interface СводкаОхраны {
  /** Одна фраза для человека. Пусто — говорить не о чем, дыр не было. */
  ответ: string | null;
  /** Сколько раз нас не было. */
  сколько: number;
  /** Суммарно минут. */
  всего: number;
  /** Самая длинная дыра, минут. */
  самая: number;
  /* Была ли ночь чистой. `null` — окна сна не знаем, и тогда про ночь не говорим вовсе:
     выдумывать её границы значило бы объявлять чистой ночь, которой мы не видели. */
  ночьЧистая?: boolean | null;
}

/* ГРАНИЦЫ ПОСЛЕДНЕЙ НОЧИ (SugarLife#727).

   Окно приходит от движка строками «23:00» / «07:00» (`SleepView.from` / `to`). Оно бывает
   переходящим через полночь — это обычный случай, а не край.

   ЕСЛИ НОЧЬ ЕЩЁ ИДЁТ, СЧИТАЕМ ЕЁ ДО СЕЙЧАС. Человек, проснувшийся в четыре утра и открывший
   экран, спрашивает про эту ночь, а не про прошлую; сказать ему про позавчерашнюю — значит
   ответить не на его вопрос.

   Возвращаем `null`, когда окна нет: своих границ не выдумываем. */
export function границыНочи(
  от: string | null | undefined, до: string | null | undefined, сейчас: number,
): { от: number; до: number } | null {
  const мин = (t: string | null | undefined): number | null => {
    const м = /^(\d{1,2}):(\d{2})$/.exec((t ?? '').trim());
    if (!м) return null;
    const ч = Number(м[1]), м2 = Number(м[2]);
    return ч >= 0 && ч < 24 && м2 >= 0 && м2 < 60 ? ч * 60 + м2 : null;
  };
  const о = мин(от), д = мин(до);
  if (о == null || д == null) return null;

  const н = new Date(сейчас);
  const полночь = new Date(н.getFullYear(), н.getMonth(), н.getDate()).getTime();
  const МИН = 60000, СУТКИ = 1440 * МИН;
  const текущиеМинуты = (сейчас - полночь) / МИН;

  const концаСегодня = полночь + д * МИН;
  /* Кончилась ли ночь сегодня. Если ещё идёт — берём её до СЕЙЧАС: человек, проснувшийся в
     четыре утра, спрашивает про эту ночь, а не про прошлую. */
  const до_ = текущиеМинуты >= д ? концаСегодня : Math.min(сейчас, концаСегодня);

  /* Начало — ближайший час отхода ко сну ПЕРЕД концом, а не «конец минус длительность».
     Разница видна ровно в идущей ночи: в четыре утра длительность увела бы начало на
     восемь часов назад, то есть на восемь вечера, когда человек ещё не ложился. */
  const о_сегодня = полночь + о * МИН;
  const от_ = о > д ? о_сегодня - СУТКИ : о_сегодня;
  /* Ночь ещё не начиналась и не идёт (окно внутри суток, а сейчас раньше него) — прошлая. */
  return от_ <= до_ ? { от: от_, до: до_ } : { от: от_ - СУТКИ, до: до_ - СУТКИ };
}

/** Почему нас не было — словами. Незнакомую причину не выдумываем. */
export function почему(код: string): string {
  if (код === 'reboot') return 'перезагрузка телефона';
  if (код === 'swiped') return 'приложение смахнули';
  if (код === 'killed') return 'телефон выгрузил приложение';
  /* Обрыв связи приезжает сюда же с 1.69: ядро решило не заводить третью поверхность, и довод
     верный — для человека «нас не было» и «связи не было» об одном, сколько он был без присмотра. */
  if (код === 'network') return 'не было связи';
  return '';
}

/**
 * Сводка по дырам за окно.
 *
 * @param дыры что прислал движок
 * @param сейчас текущее время (передаётся, а не берётся из часов: так функция проверяема)
 * @param часов какое окно считаем — сутки по умолчанию
 */
export function сводка(
  дыры: GuardGapView[], сейчас: number, часов = 24,
  ночь?: { от: number; до: number } | null,
): СводкаОхраны {
  const порог = сейчас - часов * 3600e3;
  const свежие = дыры.filter((д) => д.atMs > порог);

  /* НОЧЬ ПЕРВОЙ, И ДАЖЕ ЧИСТАЯ (SugarLife#727).

     Окно было сутками без разбора, и сутки смешивают несравнимое. Днём приложение
     перезапускают постоянно, и почти всегда это мы сами: установка сборки, обновление по
     воздуху, ручное снятие при проверке. Ночью никто ничего не устанавливает — и именно
     ночью человек спит и зависит от тревог.

     Число за сутки, набитое нашей же вознёй, вытесняло то единственное, ради чего строка
     заведена. Хуже: оно её обесценивало — человек привыкал, что там всегда что-то есть.

     ЧИСТУЮ НОЧЬ ГОВОРИМ ВСЛУХ, и это исключение из нашего же правила «когда всё хорошо, не
     пишем ничего». Здесь молчание не читается как «хорошо»: человек открывает этот экран
     ровно затем, чтобы узнать, наблюдали ли за ним, пока он спал. Пустота на этот вопрос
     не отвечает. */
  const ночные = ночь ? свежие.filter((д) => д.atMs >= ночь.от && д.atMs <= ночь.до) : [];
  const дневные = ночь ? свежие.filter((д) => д.atMs < ночь.от || д.atMs > ночь.до) : свежие;

  if (ночь && !ночные.length) {
    /* Дневные не выбрасываем, но и не пугаем ими: они про наладку, а не про жизнь. */
    const хвост = дневные.length ? ` Днём — ${словомПроРазы(дневные)}.` : '';
    return {
      ответ: `Ночь прошла без перерывов.${хвост}`,
      сколько: дневные.length, всего: сумма(дневные), самая: самаяДлинная(дневные),
      ночьЧистая: true,
    };
  }

  if (ночные.length) {
    const хвост = дневные.length ? ` Днём — ${словомПроРазы(дневные)}.` : '';
    return {
      ответ: `Ночью приложение выгружали ${словомПроРазы(ночные)}.${хвост}`,
      сколько: ночные.length, всего: сумма(ночные), самая: самаяДлинная(ночные),
      ночьЧистая: false,
    };
  }

  /* Окна сна не знаем — отвечаем как прежде, сутками, и про ночь не говорим ничего:
     выдумывать её границы значило бы объявлять чистой ночь, которой мы не видели. */
  if (!свежие.length) return { ответ: null, сколько: 0, всего: 0, самая: 0, ночьЧистая: null };
  return {
    ответ: `За сутки приложение выгружали ${словомПроРазы(свежие)}.`,
    сколько: свежие.length, всего: сумма(свежие), самая: самаяДлинная(свежие),
    ночьЧистая: null,
  };
}

const сумма = (д: GuardGapView[]): number => д.reduce((с, x) => с + x.minutes, 0);
const самаяДлинная = (д: GuardGapView[]): number => д.reduce((м, x) => Math.max(м, x.minutes), 0);

/* Одна дыра и много дыр — разные новости, и говорить о них надо по-разному. Одна означает
   случай; двадцать одна — что так теперь живём, и это уже про настройки телефона. */
function словомПроРазы(д: GuardGapView[]): string {
  if (д.length === 1) return `один раз, на ${минуты(самаяДлинная(д))}`;
  return `${д.length} раз, суммарно на ${минуты(сумма(д))}; самый долгий перерыв — ${минуты(самаяДлинная(д))}`;
}

/** Минуты словами: часы отдельно, потому что «на 145 минут» человек не читает. */
export function минуты(м: number): string {
  if (м < 1) return 'меньше минуты';
  if (м < 60) return `${Math.round(м)} мин`;
  const ч = Math.floor(м / 60);
  const ост = Math.round(м % 60);
  return ост ? `${ч} ч ${ост} мин` : `${ч} ч`;
}
