import { describe, it, expect } from 'vitest';
import { чужиеСайтыНеСчитаются } from './чужиеСайты';

describe('оговорка про чужие сайты', () => {
  it('говорим, когда телефон видит сеть, а до облака хода нет', () => {
    expect(чужиеСайтыНеСчитаются('cloud.unreachable.online')).toBe(true);
  });

  /* Айфон отвечает «соединения нет» (-1009) и в сети с белым списком, где Яндекс открывается.
     Мнение телефона о сети не одно, а два, и они расходятся: делим по тому, дошли ли до сервера. */
  it('говорим и при «сети нет»: этот ответ приходит и там, где чужие сайты работают', () => {
    expect(чужиеСайтыНеСчитаются('cloud.offline')).toBe(true);
    expect(чужиеСайтыНеСчитаются('cloud.unreachable')).toBe(true);
  });

  /* Сервер ответил — связь исправна, чинить надо не сеть. */
  it('молчим, когда сервер ответил ошибкой, отказал в доступе или не дал шифрование', () => {
    for (const код of ['cloud.server.error', 'nightscout.auth.failed', 'cloud.tls.failed']) {
      expect(чужиеСайтыНеСчитаются(код), код).toBe(false);
    }
  });

  it('молчим на пустом и незнакомом коде', () => {
    expect(чужиеСайтыНеСчитаются(null)).toBe(false);
    expect(чужиеСайтыНеСчитаются(undefined)).toBe(false);
    expect(чужиеСайтыНеСчитаются('ble.link.lost')).toBe(false);
  });
});
