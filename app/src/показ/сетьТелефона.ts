import { useEffect, useState } from 'react';
import { Capacitor } from '@capacitor/core';
import { естьСеть, слушатьСеть } from '@/platform/сеть';

/* «НЕТ СЕТИ» ОБЯЗАНО ПОЯВЛЯТЬСЯ СРАЗУ (решение владельца, 16.09.2026).

   Владелец включил авиарежим и смотрел на экран: «долго ничего не менялось». Строка состояния
   узнавала о пропаже сети от браузера, а браузер здесь — плохой свидетель.

   ПЕРВЫЙ ЗАХОД БЫЛ НЕВЕРЕН, и это стоит записать. Я решил, что опаздывают только СОБЫТИЯ
   `online`/`offline`, а само свойство `navigator.onLine` обновляется вовремя, и завёл опрос раз в
   полсекунды. В демо это подтвердилось — там я сам подменил свойство. На телефоне опыт провалился:
   в WKWebView `navigator.onLine` в авиарежиме остаётся `true`. Опрос врущего источника врёт ровно
   так же, только чаще. Урок тот же, что с меткой на часах: проверять надо на телефоне, а подмена в
   демо доказывает работу проводки, а не правдивость источника.

   ТЕПЕРЬ СОСТОЯНИЕ ПРИХОДИТ ИЗ НАТИВА (`platform/сеть.ts`): наблюдатель пути знает о пропаже за
   доли секунды. Опрос остался только для браузера, где натива нет, а `navigator.onLine` не врёт.

   ЧЕСТНАЯ ГРАНИЦА. Ответ — «есть ли у телефона ход в сеть», а не «дойдём ли мы до Nightscout». Про
   второе говорит оговорка про чужие сайты (`показ/чужиеСайты.ts`). */

/** Как часто переспрашиваем браузер. Только веб: у натива состояние приходит событием. */
export const ТАКТ_ОПРОСА_МС = 500;

export function useСетьТелефона(): boolean {
  const [онлайн, поставить] = useState<boolean>(естьСеть);

  useEffect(() => {
    const свериться = () => поставить(естьСеть());
    const снять = слушатьСеть((есть) => поставить(есть));
    свериться();
    if (Capacitor.isNativePlatform()) return снять;

    /* Браузер: событий у нас два, и оба ненадёжны — плюс сверка при возвращении на вкладку. */
    window.addEventListener('online', свериться);
    window.addEventListener('offline', свериться);
    document.addEventListener('visibilitychange', свериться);
    const такт = window.setInterval(свериться, ТАКТ_ОПРОСА_МС);
    return () => {
      снять();
      window.removeEventListener('online', свериться);
      window.removeEventListener('offline', свериться);
      document.removeEventListener('visibilitychange', свериться);
      window.clearInterval(такт);
    };
  }, []);

  return онлайн;
}
