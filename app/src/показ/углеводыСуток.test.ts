import { describe, it, expect } from 'vitest';
import { углеводыСуток } from './углеводыСуток';
import type { Meal } from '@/domain/meals';
import type { Treatment } from '@/domain/types';

/* «Я это записал?» — вопрос про себя, а не про источник записи (SugarLife#746, находка ядра).

   Владелец вносил углеводы в AAPS, они доехали до движка через Nightscout — а экран говорил
   «За сутки не вносили». Строка честно складывала два источника, но одним из них была НАША
   загрузка облака, которая на нативной сборке молчит. Два источника на бумаге, ноль на деле. */

const ч = 3600e3;
const сейчас = new Date(2026, 8, 1, 20, 0).getTime();
const еда = (t: number, carbs: number): Meal => ({ id: `m${t}`, t, carbs } as Meal);
const обл = (t: number, carbs: number): Treatment => ({ t, carbs } as Treatment);
const дв = (t: number, amount: number) => ({ atMs: t, kind: 'Carbs', amount });

describe('углеводы за сутки', () => {
  it('видит еду, внесённую в чужой программе и пришедшую через движок', () => {
    const п = углеводыСуток(
      [дв(сейчас - 1.3 * ч, 10), дв(сейчас - 6.6 * ч, 15), дв(сейчас - 17.2 * ч, 25)],
      [], [], сейчас - 24 * ч,
    );
    expect(п).toHaveLength(3);
    expect(п[п.length - 1].carbs).toBe(10);
  });

  /* Без своих записей человек внёс бы приём и продолжал читать «не вносили» — та же неправда,
     но с другой стороны: облако отвечает не мгновенно. */
  it('свои записи видны сразу, до возврата из облака', () => {
    const п = углеводыСуток([], [], [еда(сейчас - 5 * 60e3, 40)], сейчас - 24 * ч);
    expect(п).toHaveLength(1);
    expect(п[0].carbs).toBe(40);
  });

  /* Задвоенные углеводы — задвоенная доза. Правило склейки общее (domain/meals.ts). */
  it('свой приём, вернувшийся из движка, не считается дважды', () => {
    const t = сейчас - 2 * ч;
    const п = углеводыСуток([дв(t, 40)], [], [еда(t + 20e3, 40)], сейчас - 24 * ч);
    expect(п).toHaveLength(1);
  });

  /* Движок и наша загрузка читают ОДНО облако. Время записи у двух путей округляется
     по-разному, поэтому совпадением считаем минуту и грамм. */
  it('один приём из движка и из нашей загрузки — не два', () => {
    const t = сейчас - 3 * ч;
    const п = углеводыСуток([дв(t, 25)], [обл(t + 30e3, 25)], [], сейчас - 24 * ч);
    expect(п).toHaveLength(1);
  });

  it('разные приёмы рядом по времени не склеиваются', () => {
    const t = сейчас - 3 * ч;
    const п = углеводыСуток([дв(t, 25)], [обл(t + 30e3, 12)], [], сейчас - 24 * ч);
    expect(п).toHaveLength(2);
  });

  it('старше суток — не считается', () => {
    expect(углеводыСуток([дв(сейчас - 25 * ч, 30)], [], [], сейчас)).toEqual([]);
  });

  /* Движка нет (браузер) — работаем на своей загрузке, а не падаем. */
  it('null от движка не ломает счёт', () => {
    const п = углеводыСуток(null, [обл(сейчас - ч, 20)], [], сейчас - 24 * ч);
    expect(п).toHaveLength(1);
  });

  it('порядок — по времени, последний в конце', () => {
    const п = углеводыСуток([дв(сейчас - 5 * ч, 15), дв(сейчас - ч, 10)], [], [], сейчас - 24 * ч);
    expect(п.map((x) => x.carbs)).toEqual([15, 10]);
  });
});
