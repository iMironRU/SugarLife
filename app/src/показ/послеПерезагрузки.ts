/** Пока движок не назвал свой порог. Строгая половина его пары (15 во сне, 20 днём). */
export const ПОРОГ_ПО_УМОЛЧАНИЮ_МИН = 15;

export interface ПропущенноеПослеПерезагрузки {
  заголовок: string;
  /** Слова движка про самый долгий разрыв плюс счёт, если их было несколько. */
  текст: string;
  /** Время самого свежего разрыва: кладём в отметку, чтобы не сказать дважды. */
  поМс: number;
}

export function послеПерезагрузки(вход: {
  история?: GuardGapView[] | null;
  /** Время самого свежего разрыва, о котором уже говорили. */
  сказаноПо?: number | null;
  /** Через сколько минут молчания движок обещает будить. */
  порогМолчанияМин?: number | null;
}): ПропущенноеПослеПерезагрузки | null {
  const порог = вход.порогМолчанияМин ?? ПОРОГ_ПО_УМОЛЧАНИЮ_МИН;
  const сказаноПо = вход.сказаноПо ?? 0;
  const свои = (вход.история ?? [])
    .filter((р) => р.why === 'reboot' && р.atMs > сказаноПо && р.minutes > порог)
    .sort((а, б) => а.atMs - б.atMs);
  if (!свои.length) return null;

  /* Самый долгий — он и есть новость. Сумма была бы честнее арифметически и хуже по делу: три
     разрыва по двадцать минут и один на час — это разные ночи, а сумма у них одна. */
  const самый = свои.reduce((а, б) => (б.minutes > а.minutes ? б : а));
  const ещё = свои.length - 1;
  return {
    заголовок: 'Ночью мониторинга не было',
    текст: самый.words + (ещё > 0 ? ` И ещё ${ещё} ${раз(ещё)} за это время.` : ''),
    поМс: свои[свои.length - 1].atMs,
  };
}

function раз(n: number): string {
  const д = n % 10, с = n % 100;
  if (с >= 11 && с <= 14) return 'раз';
  if (д === 1) return 'раз';
  if (д >= 2 && д <= 4) return 'раза';
  return 'раз';
}
