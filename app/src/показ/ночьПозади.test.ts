import { describe, it, expect } from 'vitest';
import { ночьПозади, границыНочи } from './ночьПозади';
import type { LogRecord } from '@/sources/bridge';

const УТРО = new Date('2026-08-29T09:00:00').getTime();
const з = (t: string, event: string, id?: string): LogRecord =>
  ({ atMs: new Date(t).getTime(), level: 'Info', tag: 'alarm', event,
     fields: id ? { id } : null }) as LogRecord;

describe('что было ночью', () => {
  it('тревога и ответ склеиваются по идентификатору', () => {
    const н = ночьПозади([
      з('2026-08-29T02:49:23', 'Началась', 'прогноз-падения'),
      з('2026-08-29T02:50:23', 'ack', 'прогноз-падения'),
    ], УТРО);
    expect(н.строки).toHaveLength(1);
    expect(н.строки[0].что).toBe('Сахар падал');
    expect(н.строки[0].ответЧерезС).toBe(60);
  });

  it('тревога без ответа так и остаётся без ответа', () => {
    /* Самое важное, что может сказать этот экран: вас звали, и вы не ответили. */
    const н = ночьПозади([з('2026-08-29T03:08:00', 'Началась', 'гипо')], УТРО);
    expect(н.строки[0].ответЧерезС).toBeNull();
  });

  it('подтверждение без начала не засчитывается', () => {
    /* `ack` мог прийти от тревоги, начавшейся ДО ночи. Приписать его ночной — соврать в сторону
       покоя, а это ровно та ложь, которой здесь быть нельзя. */
    const н = ночьПозади([з('2026-08-29T02:00:00', 'ack', 'гипо')], УТРО);
    expect(н.строки).toHaveLength(0);
    expect(н.спокойно).toBe(true);
  });

  it('«спокойно» говорим только если журнал за ночь есть', () => {
    /* Пустой журнал означает, что мы НЕ РАБОТАЛИ, — это противоположный ответ, и путать его с
       «тревог не было» нельзя: человек ляжет спать, считая, что его разбудят. */
    expect(ночьПозади([], УТРО).спокойно).toBe(false);
    expect(ночьПозади([з('2026-08-29T03:00:00', 'delivery')], УТРО).спокойно).toBe(true);
  });

  it('дневные тревоги в ночь не попадают', () => {
    const н = ночьПозади([з('2026-08-29T13:00:00', 'Началась', 'гипер')], УТРО);
    expect(н.строки).toHaveLength(0);
  });

  it('до семи утра ночь — это ещё текущая', () => {
    /* Человек проснулся в шесть и спрашивает про ночь, которая ещё идёт. */
    const шесть = new Date('2026-08-29T06:00:00').getTime();
    const { до } = границыНочи(шесть);
    expect(до).toBe(шесть);
  });

  it('незнакомую тревогу показываем как есть, а не выдумываем название', () => {
    const н = ночьПозади([з('2026-08-29T02:00:00', 'Началась', 'новая-тревога')], УТРО);
    expect(н.строки[0].что).toBe('новая-тревога');
  });

  /* ОКНО ОТ ДВИЖКА (#597). Владелец: «ночь же задаётся в настройках?». Должна — и как только окно
     появится, заглушка 23:00–07:00 перестанет использоваться сама. */
  it('окно движка вытесняет заглушку', () => {
    const н = ночьПозади([
      з('2026-08-29T01:30:00', 'Началась', 'гипо'),
    ], new Date('2026-08-29T10:00:00').getTime(), { from: '01:00', to: '06:00' });
    expect(н.строки).toHaveLength(1);
  });

  it('тревога вне окна движка в ночь не попадает', () => {
    const н = ночьПозади([
      з('2026-08-29T00:30:00', 'Началась', 'гипо'),
    ], new Date('2026-08-29T10:00:00').getTime(), { from: '01:00', to: '06:00' });
    expect(н.строки).toHaveLength(0);
  });

  it('кривое окно не ломает ночь — берём заглушку', () => {
    /* Лучше заглушка, чем окно, съехавшее на случайное число: человек не заметит подмены. */
    const { от, до } = границыНочи(УТРО, { from: 'ерунда', to: null });
    expect(до - от).toBe(8 * 3600e3);
  });
});