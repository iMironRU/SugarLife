import { describe, it, expect } from 'vitest';
import { ночьПозади, границыНочи } from './ночьПозади';
import type { AlarmEpisodeView } from '@/sources/bridge';

const УТРО = new Date('2026-08-29T09:00:00').getTime();
const э = (t: string, o: Partial<AlarmEpisodeView> = {}): AlarmEpisodeView => ({
  id: 'гипо', startedAtMs: new Date(t).getTime(), baseLevel: 'Разбудить', peakLevel: 'Разбудить',
  words: 'Низкий сахар', ...o,
});

/* ЧТО БЫЛО НОЧЬЮ (#597, ядро #176).

   Эпизоды теперь берём у ядра — вчерашняя сборка из журнала снята. Проверяем не склейку (её делают
   они), а то, за что отвечаем мы: границы ночи и честность молчания. */
describe('что было ночью', () => {
  it('ночные эпизоды показываются словами ядра', () => {
    const н = ночьПозади([э('2026-08-29T02:49:23', { words: 'Сахар падал', ackAfterMs: 60000 })], УТРО);
    expect(н.строки).toHaveLength(1);
    expect(н.строки[0].что).toBe('Сахар падал');
    expect(н.строки[0].ответЧерезС).toBe(60);
  });

  it('«не добудились» отличается от «не ответил»', () => {
    /* Днём смахнуть — право человека. Ночью «не ответил» означает, что его звали и не дозвались,
       и это единственное, что он узнаёт отсюда впервые. */
    const н = ночьПозади([э('2026-08-29T03:08:00', { unwoken: true })], УТРО);
    expect(н.строки[0].неДобудились).toBe(true);
  });

  it('дневные эпизоды в ночь не попадают', () => {
    expect(ночьПозади([э('2026-08-29T13:00:00')], УТРО).строки).toHaveLength(0);
  });

  it('эпизоды есть, ночных нет — говорим «спокойно»', () => {
    expect(ночьПозади([э('2026-08-29T13:00:00')], УТРО).спокойно).toBe(true);
    expect(ночьПозади([], УТРО).спокойно).toBe(true);
  });

  it('эпизодов нет вовсе — молчим, а не обещаем покой', () => {
    /* Старый мост или движок не поднялся. Сказать «тревог не было», когда мы не знаем, — дать
       человеку лечь спать с ложной уверенностью. */
    expect(ночьПозади(undefined, УТРО).спокойно).toBe(false);
    expect(ночьПозади(null, УТРО).спокойно).toBe(false);
  });

  it('окно движка вытесняет общее', () => {
    const н = ночьПозади([э('2026-08-29T01:30:00')], УТРО, { asleep: false, from: '01:00', to: '06:00' });
    expect(н.строки).toHaveLength(1);
    expect(ночьПозади([э('2026-08-29T00:30:00')], УТРО, { asleep: false, from: '01:00', to: '06:00' }).строки)
      .toHaveLength(0);
  });

  it('кривое окно не ломает ночь — берём общее', () => {
    const { от, до } = границыНочи(УТРО, { asleep: false, from: 'ерунда', to: null });
    expect(до - от).toBe(8 * 3600e3);
  });

  it('до подъёма ночь — это ещё текущая', () => {
    /* Человек проснулся в шесть и спрашивает про ночь, которая ещё идёт. */
    const шесть = new Date('2026-08-29T06:00:00').getTime();
    expect(границыНочи(шесть).до).toBe(шесть);
  });
});
