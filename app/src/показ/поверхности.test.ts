import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/* СТОРОЖ ЧЕТЫРЁХ ПОВЕРХНОСТЕЙ (#655).

   28 августа значок и тихая сводка перестали обновляться. Не потому, что сломались, — потому что
   они жили ВНУТРИ решения о живой карточке, в одной из его веток. Карточку выключили, поставили
   ранний выход, и обе поверхности уехали вместе с ней. Человек увидел это на заблокированном
   телефоне, а мы — только с его слов.

   Правило было записано в коде ещё в августе, но словами и только про виджет: «одна общая ветка
   означала бы, что выключенный баннер молча гасит и виджет». Значок со сводкой его не получили.

   Записанное правило ничего не стережёт. Стережёт проверка.

   Каждая поверхность обновляется СВОЕЙ строкой из обработчика снимка. Ни одна не спрятана внутри
   другой: у них разные бюджеты, разные причины быть выключенными и разная цена молчания. */
const НАТИВ = join(__dirname, '../../ios/App/App');

/* Кто кого обновляет: вызов → файл и функция, которым он разрешён.

   С 28 августа у поверхностей не только своя функция, но и свой ФАЙЛ (#663). Соседство в одном
   файле и было причиной: разделяемому коду негде было жить, кроме общего дома, и поверхность,
   которой он понадобился, переезжала туда же. */
const ПОВЕРХНОСТИ: Array<{ вызов: string; файл: string; хозяин: string }> = [
  { вызов: 'Значок.общий.обновить(', файл: 'ПоверхностьЗначка.swift', хозяин: 'обновить' },
  { вызов: 'Сводка.общая.обновить(', файл: 'ПоверхностьЗначка.swift', хозяин: 'обновить' },
  { вызов: 'ЖивойБаннер.обновить(', файл: 'SugarLifeBridgePlugin.swift', хозяин: 'решитьПоБаннеру' },
];

/** Вызов с началом слова: иначе одно имя ловится внутри другого. */
function границаСлова(вызов: string): RegExp {
  return new RegExp(`(^|[^\\wА-Яа-яёЁ])${вызов.replace(/[.()]/g, '\\$&')}`);
}

/** Имя функции, внутри которой стоит строка: ближайшее объявление выше по файлу. */
function чьяСтрока(строки: string[], номер: number): string {
  for (let i = номер; i >= 0; i--) {
    const m = строки[i].match(/^\s*(?:@\w+[^\n]*\n\s*)?(?:private |public |internal )?func\s+([^(\s]+)/);
    if (m) return m[1];
  }
  return '(вне функции)';
}

describe('поверхности не спрятаны друг в друге', () => {
  /* Ищем по ВСЕМ файлам натива: вызов, уехавший в чужой файл, — это ровно то, что мы ловим. */
  const файлы = readdirSync(НАТИВ).filter((и) => и.endsWith('.swift'));

  for (const { вызов, файл, хозяин } of ПОВЕРХНОСТИ) {
    it(`${вызов} зовут только из ${файл} → ${хозяин}()`, () => {
      const чужие: string[] = [];
      for (const и of файлы) {
        const строки = readFileSync(join(НАТИВ, и), 'utf8').split('\n');
        строки.forEach((s, i) => {
          /* По границе слова, а не подстрокой: `ЗначокИСводка.общая.обновить(` содержит внутри
             себя `Сводка.общая.обновить(`, и сторож поймал сам себя на первом же запуске. */
          if (!границаСлова(вызов).test(s) || s.trimStart().startsWith('//')) return;
          const где = чьяСтрока(строки, i);
          if (и !== файл || где !== хозяин) чужие.push(`${и}:${i + 1} — внутри ${где}()`);
        });
      }
      expect(чужие, `${вызов} обновляет свою поверхность и не должен жить в чужом доме`).toEqual([]);
    });
  }

  it('каждая поверхность вызвана из обработчика снимка своей строкой', () => {
    /* Не «где-то есть вызов», а именно четыре отдельные строки подряд в одном месте: так видно,
       что выключение одной не уносит остальные. */
    const текст = readFileSync(join(НАТИВ, 'SugarLifeBridgePlugin.swift'), 'utf8');
    for (const зов of ['обновитьЖивойБаннер(json)', 'обновитьВиджет(json)', 'ЗначокИСводка.общая.обновить(json', 'Тревоги.общие.приСнимке(json)']) {
      expect(текст, `${зов} должен вызываться из обработчика снимка отдельной строкой`).toContain(зов);
    }
  });
});
