import { describe, it, expect } from 'vitest';
import { analyze } from '@/domain/analysis';
import { словаНаходки } from './находки';
import type { Entry, Treatment } from '@/domain/types';
import type { ВидНаходки } from '@/domain/analysis';
import { ВИДЫ_ДЛЯ_ПРОВЕРКИ } from '@/domain/analysis';

/* Слова находок. Проверяем не буквы, а то, без чего карточка бесполезна: что слова есть
   у КАЖДОЙ находки, которую разбор вообще может выдать, и что числа из правила доехали
   до фразы. Формулировки правятся часто, и тест, повторяющий их дословно, ломался бы на
   каждой правке, не поймав ни одной ошибки. */

const сейчас = Date.now(), ч = 3600e3, д = 24 * ч;
const мк = (n: number, знач: (i: number) => number): Entry[] =>
  Array.from({ length: n }, (_, i) => ({
    t: сейчас - (n - i) * 5 * 60_000, mmol: знач(i),
  })) as Entry[];
const событие = (type: string, назад: number): Treatment =>
  ({ t: сейчас - назад, type } as Treatment);

describe('у каждой находки есть слова', () => {
  it('разбор на живых данных — ни одной карточки без заголовка и текста', () => {
    const a = analyze(мк(288 * 14, (i) => (i % 300 === 0 ? 3 : 12)), [событие('Site Change', 5 * д)], 14);
    expect(a.insights.length).toBeGreaterThan(0);
    for (const н of a.insights) {
      const с = словаНаходки(н);
      expect(с.title.trim().length, н.вид).toBeGreaterThan(0);
      expect(с.message.trim().length, н.вид).toBeGreaterThan(0);
    }
  });

  /* Числа правила обязаны доехать до фразы: заголовок «Канюля стоит дн.» без числа
     выглядит поломкой, а находка при этом сработала верно. */
  it('числа из правила попадают в заголовок', () => {
    const с = словаНаходки({ id: 'site', вид: 'канюля-пора', kind: 'device', severity: 'warn', п: { дней: 7 } });
    expect(с.title).toContain('7');
  });

  it('вопрос человеку остаётся там, где он был', () => {
    expect(словаНаходки({ id: 'carbs', вид: 'еда-не-пишется', kind: 'habit', severity: 'warn' }).question)
      .toBeTruthy();
  });
});

/* ВСЕ ВИДЫ, А НЕ ТОЛЬКО ТЕ, ЧТО УДАЛОСЬ ВЫЗВАТЬ ДАННЫМИ.

   Разбор рождает находки по условиям: чтобы увидеть «GMI выше цели» или «откат в гипер»,
   нужны данные ровно такой формы. Синтетическим рядом их все не вызвать, а значит часть
   формулировок никогда не была показана — и опечатка в них всплыла бы у человека на
   телефоне, а не здесь.

   Поэтому проходим по списку видов и проверяем то, что ломается молча: пустая строка,
   «undefined» вместо числа, «NaN» — всё это выглядит как поломка приложения, хотя правило
   сработало верно. */
describe('слова есть у каждого вида, а не только у сработавших', () => {
  const ВСЕ: Array<[ВидНаходки, Record<string, number | string>]> = [
    ['канюля-пора', { дней: 6 }], ['канюля-скоро', { дней: 3 }],
    ['резервуар-давно', { дней: 7 }],
    ['датчик-перерос', { день: 15 }], ['датчик-скоро', { день: 11 }],
    ['батарея-давно', { дней: 25 }],
    ['ритм-канюли', { дней: 2.7 }], ['ритм-датчика', { дней: 9.4 }],
    ['телефон-разряжен', { процент: 12 }],
    ['ночные-гипо', { сколько: 4, дней: 14, низ: 3.9 }],
    ['гипо-тяжёлая', { доля: 1.7, порог: 3 }], ['гипо-много', { доля: 6.2, порог: 3.9 }],
    ['гипо-в-норме', { доля: 1.1 }],
    ['откат', { сколько: 3, верх: 10 }],
    ['заря', { рост: 2.1, в3: 6.4, в7: 8.5 }],
    ['окно-высоко', { с: 13, до: 18, медиана: 12.7 }],
    ['окно-низко', { с: 2, до: 5, медиана: 3.6 }],
    ['непредсказуемый-час', { час: 19, низ: 4.1, верх: 14.8 }],
    ['тренд-вверх', { сейчас: 68, сдвиг: 5 }], ['тренд-вниз', { сейчас: 51, сдвиг: -6 }],
    ['gmi-выше', { gmi: 7.6, среднее: 9.8 }],
    ['долгая-гипер', { сколько: 2, порог: 13.9 }],
    ['нмг-дыры', { процент: 44 }], ['нмг-пропуски', { процент: 72 }], ['нмг-полные', { процент: 95 }],
    ['базал-неполный', { дней: 4, всего: 14 }],
    ['без-записи', { всего: 12, дней: 14, типичный: 3.2, преобладает: 'ночь' }],
    ['еда-не-пишется', {}], ['еда-мало', { вДень: 1.4 }], ['болюсов-нет', {}],
  ];

  it.each(ВСЕ)('%s — заголовок и текст без дыр', (вид, п) => {
    const с = словаНаходки({ id: 'x', вид, kind: 'glucose', severity: 'info', п });
    for (const строка of [с.title, с.message, с.question ?? 'ok']) {
      expect(строка.trim().length, вид).toBeGreaterThan(0);
      expect(строка, вид).not.toMatch(/undefined|NaN|\[object/);
    }
  });

  /* Список выше обязан покрывать ВСЕ виды: забыть строчку здесь — то же самое, что не
     проверить вид вовсе, только с ложным чувством покрытия. */
  it('в списке перечислены все виды, какие есть', () => {
    const перечислено = new Set(ВСЕ.map(([в]) => в));
    for (const н of ВИДЫ_ДЛЯ_ПРОВЕРКИ) expect(перечислено.has(н), н).toBe(true);
    expect(перечислено.size).toBe(ВИДЫ_ДЛЯ_ПРОВЕРКИ.length);
  });
});
