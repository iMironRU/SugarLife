import { queryHistory, type TreatmentPoint } from '@/sources/bridge';

/* ЛЕНТА ТОЛЬКО ПРО ЧЕЛОВЕКА (#597, ядро #175).

   «Я колол или нет» — самый частый и самый опасный вопрос, с которым в историю приходят.

   ВЧЕРА МЫ ФИЛЬТРОВАЛИ САМИ: держали список `['TempBasal', 'Basal', 'Temp Basal']` и выбрасывали
   их из своей базы. Это была времянка, и ядро дало флаг: `humanOnly` в запросе истории.

   Их флаг лучше нашего списка по двум причинам, и обе не про удобство:

   · СПИСОК ИМЁН РАССОХНЕТСЯ. Появится «SMB» или «Automatic Bolus» — мы узнаем об этом от человека,
     увидевшего ленту, забитую работой петли. Флаг решает у того, кто эти имена и заводит.

   · ОСТАНОВКУ ПОДАЧИ ЯДРО ОТНЕСЛО К ЧЕЛОВЕКУ, и объяснило: по виду записи не решается, снял ли он
     помпу в душ или петля остановила при низком сахаре. Ошибка в эту сторону стоит лишней строки;
     в обратную — пропущенного события, из-за которого человек не поймёт, почему ночью рос сахар.
     Своим списком мы бы её выбросили и не заметили.

   Флагом, а не полем записи — тоже их решение: полю пришлось бы лежать в базе, и «что считать
   жизнью человека» стало бы зависеть от даты внесения. */
export async function лентаЧеловека(отМс: number, доМс: number): Promise<TreatmentPoint[] | null> {
  try {
    const ответ = await queryHistory({ kind: 'Treatments', fromMs: отМс, toMs: доМс, humanOnly: true });
    return ответ.treatments;
  } catch {
    /* Движка нет (браузер) или он не поднялся. Возвращаем null, а не пустой список: «лечения не
       было» и «спросить не у кого» — разные ответы, и второй не должен читаться как первый. */
    return null;
  }
}
