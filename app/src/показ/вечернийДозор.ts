/** Заголовок один и тот же, что и в разделе: два имени одного состояния — это два состояния. */
export const НЕ_РАЗБУДИТ = 'Ночью может не разбудить';

export interface ВечернийВопрос {
  заголовок: string;
  /** Слова движка, без нашего пересказа. */
  текст: string;
  /** Отметка «за этот вечер спросили». Хранится у нас, сравнивается строкой. */
  ключ: string;
}

/**
 * Ключ вечера — по началу окна сна, а не по календарной дате.
 *
 * Окно, начинающееся после полуночи, дало бы два разных дня на один вечер, и человек получил бы
 * второй вопрос через минуту после первого. Начало окна при этом стоит на месте, сколько бы раз мы
 * ни пересчитывали: движок отдаёт `minutesToSleep`, и оно убывает ровно с той же скоростью, с
 * какой растёт «сейчас».
 *
 * СРОКА НЕТ — ОГРУБЛЯЕМ ДО ТРЁХ ЧАСОВ. Тогда начала окна мы не знаем и вынуждены считать от
 * «сейчас», а «сейчас» ползёт: 22:59 и 23:01 дали бы два разных часа и два одинаковых вопроса за
 * один вечер. Трёхчасовая корзина их сводит, и при этом не сводит вечер с дневным сном — а сон
 * днём у нас состояние, а не исключение (#473).
 */
function ключВечера(сейчас: number, доСнаМин: number | null | undefined): string {
  const точно = доСнаМин != null;
  const началоМс = сейчас + (доСнаМин ?? 30) * 60_000;
  const д = new Date(началоМс);
  const час = точно ? д.getHours() : Math.floor(д.getHours() / 3) * 3;
  return `${д.getFullYear()}-${д.getMonth() + 1}-${д.getDate()}-${час}`;
}

export function вечернийВопрос(вход: {
  сон?: SleepView | null;
  обещание?: NightPromiseView | null;
  сейчас: number;
  /** Ключ вечера, за который уже спрашивали. */
  спрашивалиЗа?: string | null;
}): ВечернийВопрос | null {
  const { сон, обещание, сейчас } = вход;
  /* Не наш час — молчим. Спросить раньше значит спросить у человека, который ещё занят делами;
     позже — у спящего. */
  if (сон?.checkDue !== true) return null;
  /* УЖЕ СПИТ — ПОЕЗД УШЁЛ. Между «пора спросить» и «уснул» человек мог лечь; будить его вопросом
     о готовности значит своими руками устроить ровно то, от чего защищаем. */
  if (сон.asleep) return null;
  /* ОТВЕТА НЕТ — ВОПРОСА НЕТ. Движок старее модели ночного обещания: сказать «может не разбудить»
     нам не на чем, а сказать «всё хорошо» нельзя тем более. Раздел в этом случае считает сам и
     показывает запасной ответ тому, кто зашёл; пугать уведомлением на догадке мы не будем. */
  if (!обещание) return null;
  /* Всё в силе — молчим, см. вверху. */
  if (обещание.willWake) return null;

  const ключ = ключВечера(сейчас, сон.minutesToSleep);
  if (вход.спрашивалиЗа === ключ) return null;

  return { заголовок: НЕ_РАЗБУДИТ, текст: обещание.answer, ключ };
}
