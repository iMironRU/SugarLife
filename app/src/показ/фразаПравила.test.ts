import { describe, it, expect } from 'vitest';
import { фразаПравила, числаВнеФразы, type Кусок } from './фразаПравила';
import type { Поле } from './правилаТревог';

/* Правило одной фразой (#590, мост 1.67).

   Сторожим не вёрстку, а честность: во фразе не должно оказаться ни сырого ключа вместо числа, ни
   потерянной настройки. И то и другое молчаливо: экран выглядит целым, а число, по которому будят
   ночью, либо нечитаемо, либо недоступно для правки. */

const поле = (ключ: string, значение = '15'): Поле => ({
  ключ, имя: ключ, значение, число: Number(значение), единица: 'мин', шаг: 1, знаков: 0,
  выключатель: false, включено: false, границы: null,
});

const тексты = (к: Кусок[] | null) => (к ?? []).map((x) => (x.вид === 'текст' ? x.текст : `«${x.поле.ключ}»`)).join('');

describe('фраза правила', () => {
  it('режет шаблон на текст и числа', () => {
    const куски = фразаПравила('Разбудить, если ниже {a} через {b} мин.', [поле('a', '3.9'), поле('b', '20')]);
    expect(куски).toHaveLength(5);
    expect(тексты(куски)).toBe('Разбудить, если ниже «a» через «b» мин.');
  });

  /* Ключ без настройки — это `{alarms.forecast.windowMin}` на экране вместо числа. Так у нас
     однажды показался код `cloud-uploader-down` вместо ярлыка. Лучше прежний список полей. */
  it('незнакомый ключ отменяет фразу целиком', () => {
    expect(фразаПравила('Ниже {a} и выше {нетТакого}.', [поле('a')])).toBeNull();
  });

  it('нет шаблона — нет фразы', () => {
    expect(фразаПравила(null, [поле('a')])).toBeNull();
    expect(фразаПравила('', [поле('a')])).toBeNull();
  });

  /* Фраза без мест под числа прячет числа совсем: тронуть в ней нечего. */
  it('фраза без чисел не считается фразой', () => {
    expect(фразаПравила('Разбудить, когда сахар низкий.', [поле('a')])).toBeNull();
  });

  it('число в начале и в конце не теряет соседний текст', () => {
    expect(тексты(фразаПравила('{a} мин', [поле('a')]))).toBe('«a» мин');
    expect(тексты(фразаПравила('через {a}', [поле('a')]))).toBe('через «a»');
    expect(тексты(фразаПравила('{a}', [поле('a')]))).toBe('«a»');
  });

  it('одно число дважды — оба места живые', () => {
    const куски = фразаПравила('От {a} до {a}.', [поле('a')]);
    expect((куски ?? []).filter((к) => к.вид === 'число')).toHaveLength(2);
  });
});

describe('числа вне фразы', () => {
  const поля = [поле('a'), поле('b'), { ...поле('c'), выключатель: true }];

  /* Настройка, не попавшая во фразу, обязана остаться на экране: спрятав её, мы оставили бы её
     работать, а править стало бы негде. */
  it('то, чего во фразе нет, показываем отдельно', () => {
    const куски = фразаПравила('Ниже {a}.', поля);
    expect(числаВнеФразы(куски, поля).map((ф) => ф.ключ)).toEqual(['b']);
  });

  it('фразы нет — показываем все числа, как раньше', () => {
    expect(числаВнеФразы(null, поля).map((ф) => ф.ключ)).toEqual(['a', 'b']);
  });

  /* Выключатель живёт в шапке правила: в списке чисел он был бы вторым переключателем того же. */
  it('выключатель в числа не попадает', () => {
    expect(числаВнеФразы(фразаПравила('Ниже {a} и {b}.', поля), поля)).toEqual([]);
  });
});
