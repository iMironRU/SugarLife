import { прочитать, записать } from '@/settings/storage';
import type { Строка } from '@/показ/разрешения';

/* ПУТЬ ТРЕТИЙ: ПЕРВОЕ ЗНАКОМСТВО (#473).

   Владелец в задаче: «когда человек включает ночные тревоги впервые — провести по разрешениям
   сразу, а не ждать вечера».

   ПОЧЕМУ НЕ ХВАТАЕТ ВЕЧЕРНЕГО ПУТИ. Он работает и он правильный: за полчаса до сна приходит вопрос
   «разбудят ли этой ночью», и приходит только когда обещание нарушено (#780). Но между установкой
   приложения и первым таким вечером лежит целый день, и всё это время человек уверен, что защита
   есть. Она есть не всегда: мастер первого запуска спрашивает только блютус — то, без чего не
   найти приборы. Про то, без чего не разбудят, он не говорит ни слова.

   ПОЧЕМУ СПИСОК НЕ НАШ. Что именно нужно ЭТОМУ человеку, знает движок: без своих приборов
   обязательна защита от выгрузки прошивкой, со своим сенсором она лишь желательна, а Bluetooth в
   первом случае не нужен вовсе (#813, мост 1.71). Список приходит уже отфильтрованным, и решать за
   него, что показать, мы не будем — иначе через месяц он разойдётся с каталогом молча.

   МОЛЧИМ, ЕСЛИ ВСЁ ХОРОШО. То же правило, что владелец назвал для вечера: исправное состояние
   сообщать незачем. Здесь оно даже важнее — это первая минута знакомства, и стена зелёных галочек
   учит пролистывать ровно тот экран, ради которого всё затевалось.

   ТОЛЬКО ОБЯЗАТЕЛЬНОЕ. Желательное сюда не берём намеренно: в первую минуту у человека нет ни
   опыта, ни повода отличать «без этого не разбудят» от «без этого будет чуть хуже». Смешать их —
   значит потерять доверие к первому. Желательное живёт в разделе разрешений, где его прочтёт тот,
   кто пришёл разбираться. */

const КЛЮЧ = 'sl.знакомство.ночь';

/** Что провести человека по этому уже пробовали. Второй раз не зовём: путь вечера на месте, и
 *  он поймает то, что человек отложил или отозвал потом. */
export function знакомствоБыло(): boolean {
  return прочитать(КЛЮЧ) === 'да';
}

/** Показали — больше не показываем. Зовётся и когда прошли до конца, и когда закрыли на первом
 *  шаге: человек увидел, чего не хватает, и это его право — отложить. */
export function знакомствоЗакрыто(): void {
  записать(КЛЮЧ, 'да');
}

/**
 * По чему проводим. Пусто — проводить не по чему, и экрана быть не должно.
 *
 * Порядок берём как есть: `строки()` уже поставила беду выше порядка, а обязательное выше
 * желательного. Своей сортировки здесь нет намеренно — две сортировки одного списка расходятся.
 */
export function чтоПоказать(строки: Строка[]): Строка[] {
  return строки.filter((с) => с.нужно === 'Обязательно' && с.знак !== 'да');
}

/**
 * Звать ли знакомство вообще.
 *
 * `платформаЕсть` — идёт ли речь о телефоне: в вебе этих разрешений нет физически, и экран,
 * который не может ничего починить, там был бы обманом.
 */
export function знакомствоНужно(платформаЕсть: boolean, строки: Строка[]): boolean {
  if (!платформаЕсть || знакомствоБыло()) return false;
  return чтоПоказать(строки).length > 0;
}

/**
 * Из чего человек не выберется сам.
 *
 * У непроверяемого средства (защита от выгрузки прошивкой) кнопки нет и быть не может: система не
 * даёт ни прочитать состояние, ни открыть свой экран. Знать это надо здесь, а не только в шторке:
 * экран, где половина строк без кнопок, обязан сказать почему, иначе читается как поломка.
 */
export function толькоРассказать(строки: Строка[]): Строка[] {
  return чтоПоказать(строки).filter((с) => с.действие === null);
}
