import { describe, it, expect, beforeEach, vi } from 'vitest';
import { ценуСпросить, ценуСказали, ЦЕНА_НОЧНОГО_ЗВУКА } from './ценаНочногоЗвука';

/* Хранилища в тестовой среде нет — подменяем его, а не среду: правило проверяется на памяти,
   а не на localStorage, и тащить сюда jsdom ради одного флага незачем. */
const память = new Map<string, string>();
vi.stubGlobal('localStorage', {
  getItem: (k: string) => память.get(k) ?? null,
  setItem: (k: string, v: string) => { память.set(k, v); },
  removeItem: (k: string) => { память.delete(k); },
});

beforeEach(() => память.clear());

describe('цена ночного звука', () => {
  /* «Галочка „надёжные тревоги" без этой строки обманывает» — слова владельца в #473. */
  it('на айфоне спрашиваем, пока не сказали', () => {
    expect(ценуСпросить('ios')).toBe(true);
  });

  it('сказали один раз — больше не спрашиваем', () => {
    ценуСказали();
    expect(ценуСпросить('ios')).toBe(false);
  });

  /* На Android тревога пробивает тихий режим своим каналом, и цены с магнитолой нет.
     Спрашивать там значило бы придумать человеку проблему. */
  it('на других платформах не спрашиваем вовсе', () => {
    expect(ценуСпросить('android')).toBe(false);
    expect(ценуСпросить('веб')).toBe(false);
  });

  /* Цена должна быть названа там, где человек её увидит: про машину и про то, что ночью держим,
     а днём отпускаем. Без второго первое звучит приговором. */
  it('в тексте названа машина и сказано, что днём отпускаем', () => {
    expect(ЦЕНА_НОЧНОГО_ЗВУКА).toMatch(/машин/i);
    expect(ЦЕНА_НОЧНОГО_ЗВУКА).toMatch(/днём отпускают/);
  });
});
