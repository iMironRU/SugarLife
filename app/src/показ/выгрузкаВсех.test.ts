import { describe, it, expect } from 'vitest';
import { выгрузкуПоказывать, выгружаемВсех, приборовСахара, ЦЕНА_ВЫГРУЗКИ_ВСЕХ } from './выгрузкаВсех';
import type { UiSnapshot } from '@/sources/bridge';

/* Снимок собираем минимальный: `источникиСлота` для сахара смотрит на приборы. */
const снимок = (приборов: number, приёмников = 1, всех = false): UiSnapshot => ({
  devices: Array.from({ length: приборов }, (_, i) => ({
    id: `d${i}`, name: `Сенсор ${i}`, kind: 'sensor', roles: ['sensor'],
    link: 'Streaming', status: 'Live',
  })),
  connectors: Array.from({ length: приёмников }, (_, i) => ({
    id: `c${i}`, name: 'Nightscout', uploadAll: всех,
  })),
} as unknown as UiSnapshot);

describe('выгружать все приборы или только основной', () => {
  it('с одним прибором не показываем: переключать нечего', () => {
    /* «Все» и «только основной» при одном сенсоре — одно и то же, а предупреждение
       описывало бы опасность, которой не может случиться. */
    expect(выгрузкуПоказывать(снимок(1))).toBe(false);
  });

  it('с двумя показываем: вот тут выбор появляется', () => {
    expect(выгрузкуПоказывать(снимок(2))).toBe(true);
  });

  it('без приёмника не показываем: выгружать некуда', () => {
    expect(выгрузкуПоказывать(снимок(2, 0))).toBe(false);
  });

  it('состояние читаем у приёмника, а не помним сами', () => {
    expect(выгружаемВсех(снимок(2, 1, true))).toBe(true);
    expect(выгружаемВсех(снимок(2, 1, false))).toBe(false);
  });

  it('пустой снимок — молчим, а не гадаем', () => {
    expect(выгрузкуПоказывать(null)).toBe(false);
    expect(выгружаемВсех(null)).toBe(false);
    expect(приборовСахара(null)).toBe(0);
  });

  /* Цена — не украшение: без неё человек включит и через неделю будет искать, почему петля
     считает дозу не по тому прибору. Проверяем, что в ней названы обе стороны: что случится
     и что делать вместо. */
  it('в цене названо и последствие, и правильный способ', () => {
    expect(ЦЕНА_ВЫГРУЗКИ_ВСЕХ).toMatch(/петл/i);
    expect(ЦЕНА_ВЫГРУЗКИ_ВСЕХ).toMatch(/второй адрес/i);
  });
});
