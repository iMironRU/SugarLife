import type { AlarmRuleView , SettingBoundsView } from '@/sources/bridge';
import { имяПравила, полеКлюча, почемуНельзяВыключить, УРОВЕНЬ_СЛОВОМ } from '@/слова/тревоги';

/* Правила тревог — в том виде, в каком их читает человек (SugarLife#482).

   Экран не хранит своей копии правил и не знает заранее, какие они бывают: движок отдаёт список с
   ключами настроек, тем же ключом настройка и правится. Новая тревога появляется на экране сама.

   Здесь только раскладка: что за правило, какие у него поля, как показать значение и что дописать под
   ним. Никаких порогов и условий — они уехали в движок целиком, и держать их тень здесь значило бы
   завести второе мнение о том, когда будить. */

export interface Поле {
  ключ: string;
  имя: string;
  /** Значение как пришло — правим и отдаём обратно строкой, движок разбирает сам. */
  значение: string;
  число: number | null;
  единица: string;
  шаг: number;
  знаков: number;
  /** Выключатель, а не число: значение приходит как «on»/«off». */
  выключатель: boolean;
  включено: boolean;
  /* Границы от движка (мост 1.47). Пусто — предела нет или поле не числовое.

     До них наш единственный ограничитель был «больше нуля»: кнопкой «−0,1» порог гипо доводился до
     0,1 ммоль, и отказ приходил уже ПОСЛЕ нажатия, то есть читался как поломка кнопки. Шаг тоже
     берём отсюда, когда он есть: свой мы выводили из числа знаков — догадкой. */
  границы?: SettingBoundsView | null;
}

export interface ПравилоНаЭкран {
  id: string;
  имя: string;
  /** Следит ли движок за этим сейчас. Выключенное правило он убирает из профиля целиком. */
  включено: boolean;
  /* Можно ли отказаться вовсе. false — выключателя не рисуем, но и не молчим: почему нельзя,
     сказано словами (см. `почемуНельзя`). Молчаливое отсутствие человек читает как недоделку. */
  выключаемо: boolean;
  почемуНельзя: string | null;
  /** Как эта тревога подаёт голос — словом, а не названием уровня движка. */
  уровень: string;
  поля: Поле[];
  /* Правило одной фразой с местами под числа (мост 1.67, #590). Пусто — старое ядро или правило
     без условия; тогда показываем поля списком, как раньше. */
  фраза: string | null;
  /** Честная оговорка от движка: «порог 15 мин, фактически до 24». Пусто — оговаривать нечего. */
  оговорка: string | null;
  ссылка: string | null;
  зеркало: string | null;
}

const ВЫКЛЮЧАТЕЛИ = new Set(['on', 'off', 'true', 'false']);

/** Число из строки движка. Не разобралось — не выдумываем: поле останется без −/+, но значение покажем. */
function число(значение: string): number | null {
  const n = Number(значение.replace(',', '.'));
  return Number.isFinite(n) ? n : null;
}

/* ДВА ПРАВИЛА С ОДНИМ ИМЕНЕМ — ЭТО НЕ ИМЯ (SugarLife#500).

   Движок отдаёт «прибор молчит» дважды: одно правило сторожит днём, другое во сне, и различаются они
   только ключом настройки (`alarms.silence.dayMin` и `…sleepMin`). В развёрнутой простыне разницу было
   видно по подписи поля внутри; в свёрнутом списке два одинаковых «Прибор молчит» подряд читаются как
   ошибка приложения — и человек не знает, какой из них он сейчас выключает.

   Уточняем по суффиксу ключа, а не по виду правила: так это работает для любой будущей пары «днём и
   во сне», которую движок заведёт без нашего участия. */
function когдаСторожит(ключи: string[]): string {
  if (ключи.some((к) => к.endsWith('sleepMin'))) return ' во сне';
  if (ключи.some((к) => к.endsWith('dayMin'))) return ' днём';
  return '';
}

export function правилаНаЭкран(правила: AlarmRuleView[] | undefined): ПравилоНаЭкран[] {
  return (правила ?? []).map((п) => ({
    id: п.id,
    имя: имяПравила(п.kind, п.id) + когдаСторожит(Object.keys(п.settings ?? {})),
    включено: п.enabled !== false,
    выключаемо: п.canDisable !== false,
    почемуНельзя: п.canDisable === false ? почемуНельзяВыключить(п.kind) : null,
    уровень: УРОВЕНЬ_СЛОВОМ[String(п.level)] ?? String(п.level),
    /* Выключатель — первым: сначала «следим ли вообще», потом «при каких числах». Обратный порядок
       заставлял бы читать пороги правила, которое выключено. */
    поля: Object.entries(п.settings ?? {}).sort(([а], [б]) =>
      Number(б.endsWith('.enabled')) - Number(а.endsWith('.enabled'))).map(([ключ, значение]) => {
      const о = полеКлюча(ключ);
      const выключатель = ВЫКЛЮЧАТЕЛИ.has(значение);
      return {
        ключ,
        имя: о.имя,
        значение,
        число: выключатель ? null : число(значение),
        единица: о.единица,
        шаг: п.bounds?.[ключ]?.step ?? о.шаг,
        знаков: о.знаков,
        выключатель,
        включено: значение === 'on' || значение === 'true',
        границы: п.bounds?.[ключ] ?? null,
      };
    }),
    фраза: п.sentence || null,
    оговорка: п.effectiveWords || null,
    ссылка: п.helpUrl || null,
    зеркало: п.helpUrlMirror || null,
  }));
}

/* СВЁРНУТОЕ ПРАВИЛО ОДНОЙ СТРОКОЙ (SugarLife#500).

   Раскрытые целиком, все правила подряд складывались в простыню: у каждого заголовок, выключатель,
   два-три числа с кнопками −/+ и ссылка на статью. Пролистать её глазами нельзя — а вопрос у человека
   обычно один: «за чем он вообще следит и при каких числах».

   Поэтому в свёрнутом виде — голос правила и его числа: «разбудит ночью · 3,9 ммоль · 15 мин».
   Больше двух чисел не берём: третье уже не читается на ходу, а за ним всё равно надо раскрывать.
   У выключенного правила чисел нет вовсе — движок убирает его из профиля, и порог у неработающего
   правила читался бы как обещание. */
export function сводкаПравила(п: ПравилоНаЭкран): string {
  if (!п.включено) return 'выключено';
  /* МЁРТВОЕ ПРАВИЛО ВИДНО СРАЗУ (мост ≥ 1.40, ядро SugarLifeCore#125). Тревоги помпы без помпы
     мертвы: подача, резервуар, батарея молчат не потому, что всё хорошо, а потому что знать нечем.
     Числа рядом с таким правилом читаются как обещание сторожить — а сторожить нечем. Молчание,
     неотличимое от нормы, и есть худший вид отказа. */
  if (п.оговорка?.startsWith('не работает')) return п.оговорка;
  const числа = п.поля
    .filter((поле) => !поле.выключатель)
    .slice(0, 2)
    .map((поле) => значениеСловом(поле) + (поле.единица ? ` ${поле.единица}` : ''));
  return [п.уровень, ...числа].join(' · ');
}

/** Значение числом для показа: запятая вместо точки и столько знаков, сколько у этой величины смысл. */
export function значениеСловом(поле: Поле): string {
  if (поле.выключатель) return поле.включено ? 'включён' : 'выключен';
  if (поле.число == null) return поле.значение;
  return поле.число.toFixed(поле.знаков).replace('.', ',');
}

/**
 * Следующее значение при нажатии −/+.
 *
 * Считаем в целых шагах и округляем к сетке шага: 0.1 + 0.2 в двоичной дроби даёт 0.30000000000000004,
 * и такое значение уехало бы движку как есть. Ноль и отрицательное не пускаем: порога «минус пять минут»
 * не бывает, а движок отверг бы его молча — и человек решил бы, что кнопка сломана.
 */
export function следующее(поле: Поле, куда: 1 | -1): string | null {
  if (поле.выключатель || поле.число == null || поле.шаг <= 0) return null;
  const шагов = Math.round(поле.число / поле.шаг) + куда;
  if (шагов <= 0) return null;
  const новое = шагов * поле.шаг;
  /* ЗА ПРЕДЕЛ ДВИЖКА НЕ ПУСКАЕМ (мост 1.47). Раньше здесь стояло только «больше нуля», и порог гипо
     кнопкой доводился до 0,1 ммоль: движок отказывал, но уже ПОСЛЕ нажатия, а отказ постфактум
     читается как поломка кнопки. Гашение — удобство; последней линией остаётся отказ движка. */
  const г = поле.границы;
  if (г) {
    const eps = поле.шаг / 100;
    if (новое < г.min - eps || новое > г.max + eps) return null;
  }
  return новое.toFixed(поле.знаков);
}

/* НАСКОЛЬКО ЧИСЛО УШЛО В ОПАСНУЮ СТОРОНУ (мост 1.47, ядро #137).

   Та же шкала, что у пределов петли, и намеренно та же: два места, где число решает медицинский
   вопрос, должны выглядеть одинаково. Внутри зелёной зоны — обычный цвет, вышли — жёлтый, прошли
   полпути до жёсткого предела — красный.

   Красим ТОЛЬКО в сторону `worseTowards`. Словами ядра: поднять порог гипо — шум, опустить — беда, и
   красить оба конца одинаково значило бы уравнять одно с другим. */
export type УровеньРискаПоля = 'норма' | 'край' | 'предел';

export function рискПоля(поле: Поле): УровеньРискаПоля {
  const г = поле.границы;
  if (!г || поле.число == null) return 'норма';
  const вниз = г.worseTowards === 'down';
  const внутри = вниз ? поле.число >= г.safeFrom : поле.число <= г.safeTo;
  if (внутри) return 'норма';
  const порог = вниз ? г.safeFrom : г.safeTo;
  const предел = вниз ? г.min : г.max;
  const ход = Math.abs(предел - порог);
  if (ход < 1e-9) return 'предел';
  /* Допуск в сравнении не придирка: 3,9 → 3,6 при пределе 3,3 — ровно половина пути, но в двоичной
     дроби получается 0,49999999999999983, и число у самой границы красилось бы то так, то иначе в
     зависимости от того, какими числами задан предел. Цвет, зависящий от разряда после
     пятнадцатого знака, — худший вид непредсказуемости. */
  return Math.abs(поле.число - порог) / ход >= 0.5 - 1e-9 ? 'предел' : 'край';
}

/* ХВАТАЕТ ЛИ ЯДРА ДЛЯ ТРЕВОГ (SugarLife#482, просьба ядра).

   Своей логики решений у нас больше нет, и старое ядро в этой сборке означает не «тревоги настроены
   иначе», а «тревог нет вовсе». Это худший из отказов — тихий: экран выглядит обычным, человек ложится
   спать, думая, что защищён.

   Поэтому проверяем прямо ревизию моста, а не наличие правил: пустой список правил бывает и у нового
   ядра (например, все выключены), а старое ядро не отдаст их никогда. Две причины — два разных ответа,
   и путать их нельзя. */

export function ядроУмеетТревоги(ревизия: string | null | undefined): boolean {
  const [старшая, младшая] = String(ревизия ?? '').split('.');
  const с = Number(старшая), м = Number(младшая);
  if (!Number.isFinite(с) || !Number.isFinite(м)) return false;
  return с > 1 || (с === 1 && м >= 30);
}
