import { describe, it, expect } from 'vitest';
import { показЗаряда } from './пропажаЗаряда';
import { УСТАРЕЛО_МС } from '@/domain/supplies';

/* Заряд пропал — это не «всё в порядке» (SugarLife#715).

   Владелец: «а куда из статусной строки делся значок зарядки помпы?» Последнее, что он видел,
   было 3 %. «Не знаем» и «в порядке» стали выглядеть одинаково — пустым местом, — а между ними
   разница в часы до остановки подачи. */

const СЕЙЧАС = 1_700_000_000_000;
const НА_ИСХОДЕ = 20;

describe('показ заряда', () => {
  it('число есть — показываем число', () => {
    expect(показЗаряда(64, null, СЕЙЧАС, НА_ИСХОДЕ)).toEqual({ вид: 'число', значение: 64 });
    /* Даже ноль: помпа его показывает редко, но это ЗНАНИЕ, а не пустота. */
    expect(показЗаряда(0, null, СЕЙЧАС, НА_ИСХОДЕ)).toEqual({ вид: 'число', значение: 0 });
  });

  /* Никогда не знали — законная пустота: ни помпы, ни моста может просто не быть. */
  it('никогда не знали — пусто', () => {
    expect(показЗаряда(null, null, СЕЙЧАС, НА_ИСХОДЕ)).toBeNull();
  });

  /* После замены помпы заряд приходит не сразу; мигать вопросом на каждой замене — тоже врать. */
  it('замолчал недавно — молчим и мы', () => {
    const знали = { значение: 3, когдаМс: СЕЙЧАС - УСТАРЕЛО_МС };
    expect(показЗаряда(null, знали, СЕЙЧАС, НА_ИСХОДЕ)).toBeNull();
  });

  it('знали и перестали — показываем вопрос, а не пустоту', () => {
    const знали = { значение: 64, когдаМс: СЕЙЧАС - УСТАРЕЛО_МС - 1000 };
    expect(показЗаряда(null, знали, СЕЙЧАС, НА_ИСХОДЕ)).toEqual({ вид: 'вопрос', тревожно: false });
  });

  /* Тот самый случай владельца: пропало то, что почти кончилось. Это хуже, чем просто
     «не знаем», и выглядеть одинаково они не должны. */
  it('пропало с последнего низкого — вопрос тревожный', () => {
    const знали = { значение: 3, когдаМс: СЕЙЧАС - 2 * УСТАРЕЛО_МС };
    expect(показЗаряда(null, знали, СЕЙЧАС, НА_ИСХОДЕ)).toEqual({ вид: 'вопрос', тревожно: true });
  });

  /* Число не выдумываем: показать последние «3 %» значило бы выдать вчерашнее за сегодняшнее. */
  it('старое число наружу не отдаём', () => {
    const п = показЗаряда(null, { значение: 3, когдаМс: СЕЙЧАС - 5 * УСТАРЕЛО_МС }, СЕЙЧАС, НА_ИСХОДЕ);
    expect(п && 'значение' in п).toBe(false);
  });

  it('часы съехали назад — не гадаем', () => {
    expect(показЗаряда(null, { значение: 3, когдаМс: СЕЙЧАС + 60e3 }, СЕЙЧАС, НА_ИСХОДЕ)).toBeNull();
  });
});
