import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/* СТОРОЖ ИМЁН В СКРИПТАХ (#676).

   bash 3.2 — тот, что стоит в macOS, — НЕ ПОНИМАЕТ не-ASCII имён переменных. Пишешь `имя=значение`,
   и он отвечает «command not found», причём в середине работающего в остальном скрипта.

   За проект я наступил на это СЕМЬ раз. Каждый раз — минута на догадку и правка, каждый раз я
   помнил про это правило ровно до следующего скрипта. Комментарии в коде про bash 3.2 стоят в трёх
   местах и не помогли ни разу: их читает тот, кто уже правит этот файл, а ошибку делает тот, кто
   пишет новый.

   Владелец спросил прямо: «можем сделать так, чтобы не было восьмого раза?». Может только проверка.

   ЧТО ИМЕННО ЗАПРЕЩЕНО: имена переменных и функций. Комментарии, строки и вывод — по-русски, как и
   везде в проекте: они не имена, bash их не разбирает. */
const СКРИПТЫ = join(__dirname, '../../scripts');

/* Присваивание, цикл, объявление функции — три места, где рождается имя. */
const ИМЯ = "[A-Za-z0-9_\\u0080-\\uffff]*[^\\x00-\\x7f][A-Za-z0-9_\\u0080-\\uffff]*";
const ОБРАЗЦЫ: { что: string; как: RegExp }[] = [
  /* Не-ASCII может стоять ГДЕ УГОДНО в имени, а не только первым знаком. Первая версия этой
     проверки обрывала имя на первой же кириллической букве и подсаженное `список=""` пропустила. */
  { что: 'присваивание', как: new RegExp(`^\\s*(?:local\\s+|export\\s+)?(${ИМЯ})\\s*=`) },
  { что: 'цикл for', как: new RegExp(`^\\s*for\\s+(${ИМЯ})\\s+in\\b`) },
  { что: 'обращение $', как: new RegExp(`\\$\\{?(${ИМЯ})`) },
  { что: 'функция', как: new RegExp(`^\\s*(?:function\\s+)?(${ИМЯ})\\s*\\(\\)\\s*\\{`) },
];

/** Строка кода без комментария и без содержимого кавычек: имена живут только в коде. */
function толькоКод(строка: string): string {
  return строка
    .replace(/'[^']*'/g, "''")
    .replace(/"[^"]*"/g, '""')
    .replace(/#.*$/, '');
}

describe('в скриптах нет кириллических имён', () => {
  const файлы = readdirSync(СКРИПТЫ).filter((и) => и.endsWith('.sh'));

  it('скрипты вообще есть — иначе проверка стережёт пустоту', () => {
    expect(файлы.length).toBeGreaterThan(0);
  });

  for (const имя of файлы) {
    it(`${имя}`, () => {
      const строки = readFileSync(join(СКРИПТЫ, имя), 'utf8').split('\n');
      const беды: string[] = [];
      строки.forEach((сырая, i) => {
        const код = толькоКод(сырая);
        for (const { что, как } of ОБРАЗЦЫ) {
          const м = код.match(как);
          if (м) беды.push(`строка ${i + 1}, ${что}: ${м[1]}`);
        }
      });
      expect(
        беды,
        `${имя}: bash 3.2 в macOS не понимает не-ASCII имён — он ответит «command not found». `
        + 'Имена латиницей; комментарии и вывод по-русски можно.',
      ).toEqual([]);
    });
  }
});
