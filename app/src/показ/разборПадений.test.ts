import { describe, it, expect } from 'vitest';
import { падения, сводка, ИМЯ_ПАДЕНИЯ } from './разборПадений';
import type { UiSnapshot } from '@/sources/bridge';

const ЧАС = 3600e3;
const т = new Date(2026, 8, 8, 12, 0, 0).getTime();
const э = (o: Record<string, unknown>) => ({
  id: ИМЯ_ПАДЕНИЯ, startedAtMs: т, baseLevel: 'Заметка', peakLevel: 'Заметка',
  words: 'Сахар идёт вниз', ...o,
});
const снимок = (...alarmEpisodes: unknown[]) => ({ alarmEpisodes } as unknown as UiSnapshot);

describe('разбор падений', () => {
  it('берём только падения — чужие эпизоды не наши', () => {
    const с = снимок(э({}), э({ id: 'гипо', startedAtMs: т - ЧАС }));
    expect(падения(с, т - 10 * ЧАС).map((п) => п.когдаМс)).toEqual([т]);
  });

  it('старее окна не берём', () => {
    const с = снимок(э({ startedAtMs: т - 100 * ЧАС }));
    expect(падения(с, т - 10 * ЧАС)).toEqual([]);
  });

  it('свежее сверху: человек ищет недавнее', () => {
    const с = снимок(э({ startedAtMs: т - 5 * ЧАС }), э({ startedAtMs: т }));
    expect(падения(с, т - 10 * ЧАС).map((п) => п.когдаМс)).toEqual([т, т - 5 * ЧАС]);
  });

  it('длительность считаем по отбою', () => {
    const с = снимок(э({ clearedAtMs: т + 25 * 60e3 }));
    expect(падения(с, т - ЧАС)[0].минут).toBe(25);
  });

  /* Число, растущее на глазах у того, кто читает прошлое, — не факт, а иллюзия движения. */
  it('идущее сейчас длительности не имеет, а не «столько-то до сих пор»', () => {
    expect(падения(снимок(э({})), т - ЧАС)[0].минут).toBeNull();
  });

  it('сахар в начале и сон берём у движка как есть', () => {
    const п = падения(снимок(э({ mmol: 10.6, asleep: true })), т - ЧАС)[0];
    expect(п.сНачала).toBe(10.6);
    expect(п.спал).toBe(true);
  });

  it('пустой снимок — пустая лента, а не поломка', () => {
    expect(падения(null, 0)).toEqual([]);
    expect(падения({} as UiSnapshot, 0)).toEqual([]);
  });

  describe('свод', () => {
    it('считает ночные отдельно: ночь человек восстановить не может', () => {
      const ряд = падения(снимок(
        э({ startedAtMs: т, asleep: true, clearedAtMs: т + 20 * 60e3 }),
        э({ startedAtMs: т - ЧАС, clearedAtMs: т - ЧАС + 40 * 60e3 }),
      ), т - 10 * ЧАС);
      const с = сводка(ряд, 14);
      expect(с.всего).toBe(2);
      expect(с.ночью).toBe(1);
      expect(с.медианаМинут).toBe(30);
    });

    /* «Раз в три дня» из двух эпизодов подряд было бы неправдой в успокаивающую сторону. */
    it('окно берём заданное, а не по крайним эпизодам', () => {
      expect(сводка(падения(снимок(э({})), 0), 90).суток).toBe(90);
    });

    it('незаконченные в медиану не идут', () => {
      const ряд = падения(снимок(э({}), э({ startedAtMs: т - ЧАС, clearedAtMs: т - ЧАС + 10 * 60e3 })), 0);
      expect(сводка(ряд, 14).медианаМинут).toBe(10);
    });

    it('ничего не было — медианы нет, а не ноль', () => {
      expect(сводка([], 14).медианаМинут).toBeNull();
    });
  });
});
