/* СКОЛЬКО ЧАСОВ ДО ПУСТОГО РЕЗЕРВУАРА (SugarLife#748).

   Число кормит два обращения: «кончится ночью» (порог 14 ч) и «кончится сегодня» (6 ч).

   ОТКУДА БРАЛОСЬ РАНЬШЕ И ПОЧЕМУ ЭТО ПЛОХО. Остаток делился на среднюю суточную дозу из
   `extras.tdd` — то есть из НАШЕЙ собственной загрузки Nightscout. На нативной сборке эта
   загрузка молчит: облако держит движок. Значит `tdd` пуст, `hoursLeft` равен null, и
   предупреждение «резервуар кончится ночью, замените заранее» НЕ СРАБАТЫВАЕТ НИКОГДА.

   Тихо: ничего не падает, обращение просто не появляется. А решение это принимают один раз
   и вечером; не сработав, оно не оставляет следа — человек узнаёт утром по прерванной подаче.

   Нашли это из #746, где та же мёртвая загрузка сказала «за сутки не вносили» человеку с
   тремя приёмами.

   ОТКУДА БЕРЁМ ТЕПЕРЬ. У движка есть `insulinLeft.runsOutAtMs` — момент, а не оценка по
   средней: он знает и остаток, и скорость расхода, и базал именно этих часов. Момент лучше
   часов и тем, что не протухает между расчётом и показом.

   Наша средняя остаётся ЗАПАСНЫМ путём — для браузера, где движка нет вовсе. Она хуже, но
   лучше молчания; молчание здесь и было бедой. */

export function часовДоПустого(
  runsOutAtMs: number | null | undefined,
  остаток: number | null,
  суточнаяДоза: number | null,
  сейчас: number,
): number | null {
  if (typeof runsOutAtMs === 'number' && Number.isFinite(runsOutAtMs)) {
    const ч = (runsOutAtMs - сейчас) / 3600e3;
    /* Прошедший момент — не «минус три часа», а «уже кончился». Отрицательные часы дальше
       по коду сравниваются с порогами и молча выпадают из всех условий. */
    return ч > 0 ? ч : 0;
  }
  if (остаток == null || !суточнаяДоза || суточнаяДоза <= 0) return null;
  return остаток / (суточнаяДоза / 24);
}
