import { оценка, type Цели, type Сдвиг } from '@/domain/visitNote';

/* Записка к приёму — то, что видит врач и в каком порядке (SugarLife#407).

   Правила записки остались в домене: цели из клинических рекомендаций, полнота данных,
   пороги значимости, «в цели или мимо». Здесь только раскладка — какие строки, в каком
   порядке и какими словами. Ни одного условия сверх того, что уже решил домен.

   Разделять их стоило именно в записке: числа в ней клинические, и их правка — вопрос к
   документу, а не к экрану. Пока подпись и порог жили в одной функции, любая правка
   формулировки лезла туда же, где стоит «> 70 %». */

/* Строки НМГ в том порядке, в каком их читает врач: сначала время в диапазоне, потом
   низкое (оно опаснее), потом высокое, потом вариабельность. Порядок — из той же
   таблицы 6, и менять его «как красивее» нельзя: врач ищет глазами привычное место. */
export function строкиНМГ(s: { target: number; tbr: number; tar: number; cv: number }, цели: Цели) {
  return [
    { что: 'Время в диапазоне 3,9–10,0', значение: s.target, цель: `> ${цели.tir} %`, итог: оценка(s.target, цели.tir, 'не меньше') },
    { что: 'Время ниже 3,9', значение: s.tbr, цель: `< ${цели.tbr} %`, итог: оценка(s.tbr, цели.tbr, 'не больше') },
    { что: 'Время выше 10,0', значение: s.tar, цель: `< ${цели.tar} %`, итог: оценка(s.tar, цели.tar, 'не больше') },
    { что: 'Вариабельность (CV)', значение: s.cv, цель: `≤ ${цели.cv} %`, итог: оценка(s.cv, цели.cv, 'не больше') },
  ];
}

/* Чем похвастаться. Отдельно от списка сдвигов, потому что человеку нужна одна фраза,
   а не таблица: «стало лучше: время в диапазоне и реже низкий сахар». Если лучше не
   стало — молчим, а не подбадриваем: выдуманная похвала обесценивает настоящую. */
export function чтоСталоЛучше(сдвиги: Сдвиг[]): string | null {
  const лучше = сдвиги.filter((с) => с.лучше);
  if (!лучше.length) return null;
  const имена = лучше.map((с) => с.что.replace(' (CV)', '').toLowerCase());
  return имена.length === 1 ? имена[0] : `${имена.slice(0, -1).join(', ')} и ${имена.at(-1)}`;
}
