import { registerPlugin, Capacitor } from '@capacitor/core';

/* КУДА ВЕСТИ ЧЕЛОВЕКА, ПРИШЕДШЕГО ИЗ УВЕДОМЛЕНИЯ (SugarLife#524).

   Раньше тап по тревоге открывал приложение «где остановились» — на том экране, что был открыт в
   прошлый раз. Уведомление знает, о чём оно, а приложение об этом не узнавало: человек получал
   загадку вместо ответа, причём ночью и спросонья.

   Теперь уведомление несёт цель, а приложение её открывает.

   ЦЕЛЬ ЖДЁТ, ПОКА ЭКРАН БУДЕТ ГОТОВ. Приложение могли выгрузить: уведомление поднимет его с нуля, и
   цель придёт раньше, чем появится тот, кто умеет открывать разделы. Поэтому она копится здесь и
   отдаётся подписчику, когда он появится, — а не теряется по дороге.

   ЦЕЛЬ ОДНА И ПОСЛЕДНЯЯ. Пока человек шёл до телефона, могло прийти ещё одно уведомление; вести
   надо туда, куда он нажал последним, а не устраивать очередь переходов. */

/** Куда идти. Строка от натива: «сегодня», «охрана», «прибор:<id>», «помпа». */
export type Цель = string;

interface Плагин {
  addListener(event: 'цель', cb: (e: { цель: string }) => void): Promise<{ remove: () => void }>;
  /** Цель, пришедшая до подписки: приложение поднимали ради неё, а слушать было ещё некому. */
  ожидающаяЦель(): Promise<{ цель: string }>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

let последняя: Цель | null = null;
const слушатели = new Set<(ц: Цель) => void>();

function принять(ц: Цель): void {
  if (!ц) return;
  if (слушатели.size === 0) { последняя = ц; return; }
  слушатели.forEach((ф) => ф(ц));
}

if (Capacitor.isNativePlatform()) {
  void Native.addListener('цель', (e) => принять(e.цель)).catch(() => {
    /* Сборка старше перехода по цели — тогда уведомления просто открывают приложение, как раньше.
       Это не поломка, о которой надо кричать: хуже прежнего не стало. */
  });
  void Native.ожидающаяЦель().then((r) => принять(r.цель)).catch(() => {});
}

/**
 * Подписаться на цели перехода.
 *
 * Сразу после подписки отдаём ту, что успела прийти до неё: холодный старт из уведомления — это
 * ровно тот случай, ради которого всё делалось.
 */
export function слушатьЦель(ф: (ц: Цель) => void): () => void {
  слушатели.add(ф);
  if (последняя) { const ц = последняя; последняя = null; ф(ц); }
  return () => { слушатели.delete(ф); };
}

/** Только для тестов и демо-моста: подать цель, как будто её прислал натив. */
export function податьЦель(ц: Цель): void { принять(ц); }
