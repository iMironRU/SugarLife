import { useEffect, useRef, useState } from 'react';
import { useSnapshot } from '@/sources/bridge';
import { источникГлюкозы } from '@/domain/deviceState';
import { бедаДляПоказа, показанияСвежие } from '@/показ/застойПоказывать';
import { осталосьМс, удержать, type Удержание } from '@/показ/устойчиваяБеда';

/* ОДИН ОТВЕТ НА ВОПРОС «ЧТО СЕЙЧАС С СВЯЗЬЮ» — на все места, где об этом говорим.

   Мест три: «Сегодня», блок застоя и оговорка про чужие сайты. Считай каждое само — и они
   разойдутся в первую же минуту мигания: одно успеет перерисоваться с бедой, другое без неё.

   Удержание живёт здесь, а не в правиле показа: правило чистое и проверяется тестом, а память о
   времени — дело экрана. */
export function useБедаСвязи() {
  const снимок = useSnapshot();
  const беда = бедаДляПоказа(источникГлюкозы(снимок)?.problem, показанияСвежие(снимок));
  const держим = useRef<Удержание>({ беда: null, виднаВМс: null });
  /* Тик нужен, чтобы перерисоваться, когда удержание кончилось, а нового снимка ещё не было:
     иначе «связи нет» висело бы до следующего снимка — до пяти минут после возвращения связи. */
  const [, тик] = useState(0);

  держим.current = удержать({ новая: беда, прежнее: держим.current, сейчасМс: Date.now() });
  const текущая = держим.current;

  useEffect(() => {
    if (беда) return;
    const осталось = осталосьМс(текущая, Date.now());
    if (осталось == null) return;
    const т = setTimeout(() => тик((n) => n + 1), осталось + 50);
    return () => clearTimeout(т);
  });

  return текущая.беда;
}
