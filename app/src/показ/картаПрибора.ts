import type { HardwareView, UiSnapshot, DeviceView } from '@/sources/bridge';
import { связь, активныйКанал } from '@/domain/deviceState';
import { меткаСвязи, подписьСвежести, подписьЗанятия } from '@/слова/приборы';
import { чтоСПрибором, свежесть } from '@/domain/freshness';
import { sourceStatusLabel } from '@/domain/sourceStatus';
import { заМостомЛи, мостЖелезки, имяЖелезки } from '@/domain/nearby';

/* Что показывать в карточке прибора — по факту, а не по шаблону (SugarLife#378).

   Карточку открывают с ОДНИМ вопросом: почему прибор молчит. А открывалась она строкой
   «Адрес E2:38:B4:63:51:59» — сведением, которое нужно раз в жизни, чтобы различить два
   одинаковых прибора. Ни последнего показания, ни дня сеанса, ни «чем занят» в ней не
   было вовсе: на главном экране про датчик знали больше, чем в его собственной карточке.

   ПРИБОРЫ РАЗНЫЕ, и это главное. У сенсора есть сеанс с концом, у помпы — резервуар и
   батарея, у моста нет ни того ни другого, зато он кого-то обслуживает. Общий шаблон на
   всех даёт либо пустые строки, либо отсутствующие: «заряд —» ничем не лучше молчания,
   а спрятанный день сеанса — прямая потеря.

   Поэтому здесь три вопроса по порядку, и каждый отвечает только тем, что известно:

     1. ЧТО СЕЙЧАС — ради чего открыли: занят, не настроен, на связи ли, когда данные,
        сколько осталось сеанса.
     2. ЧТО ЭТО ЗА ПРИБОР — справка: адрес, слот, прошивка, заряд. Читают редко, поэтому
        ниже и тише.
     3. ЧТО МОЖНО СДЕЛАТЬ — действия, и разрушительное отдельно от обычных. */

export interface Строка {
  ключ: string;
  метка: string;
  значение: string;
  /** Пояснение под строкой — только там, где голое число врёт (заряд, сеанс). */
  подпись?: string;
}

export interface КартаПрибора {
  /** Одна фраза о состоянии — в подзаголовок карточки. */
  состояние: string;
  /* ПОПУТЧИК (мост ≥ 1.40, SugarLife#422). Прибор ведёт другая программа: мы слушаем её сеанс,
     данные приходят обеим, историю не запрашиваем. Слово, а не догадка из связи: «подключено» без
     уточнения человек читает как «мы основные» — и ждёт от нас полной истории, которой не будет. */
  попутчик: boolean;
  сейчас: Строка[];
  оПриборе: Строка[];
  /** Мост, за которым стоит прибор, — если он есть. */
  черезМост: string | null;
}

const ДЕНЬ = 86400e3;

export function картаПрибора(
  h: HardwareView, snap: UiSnapshot | null | undefined, сейчасМс: number,
): КартаПрибора {
  const свой = (snap?.devices ?? []).find((d) => d.id === h.id) ?? null;
  const занят = подписьЗанятия(чтоСПрибором(h));
  const состояние = занят
    ?? подписьСвежести(свежесть(h, сейчасМс))
    ?? sourceStatusLabel(h.status)
    ?? меткаСвязи[связь(h)]
    ?? 'нет связи';

  const попутчик = свой?.companion === true;

  const сейчас: Строка[] = [];

  /* Кому уступаем — сразу под состоянием (мост ≥ 1.36). Молчаливое «не подключено» человек читает
     как поломку и лезет чинить то, что работает как задумано. */
  if (snap?.yieldingTo) {
    сейчас.push({
      ключ: 'уступаем', метка: 'Ждём очереди', значение: snap.yieldingTo,
      подпись: 'Прибор занят другой программой. Подключимся, когда она освободит его.',
    });
  } else if (попутчик) {
    сейчас.push({
      ключ: 'попутчик', метка: 'Кто ведёт прибор', значение: 'другая программа',
      подпись: 'Данные получают обе. Историю мы не запрашиваем — её ведёт основная программа.',
    });
  }

  /* Когда последние данные — первое, что нужно человеку с молчащим прибором. Показываем
     только если время известно: «—» здесь читается как поломка. */
  const когда = h.latestAtMs ?? активныйКанал(свой)?.latestAtMs ?? null;
  if (когда != null) {
    сейчас.push({ ключ: 'данные', метка: 'Последние данные', значение: время(когда, сейчасМс) });
  }

  /* Сеанс — только у того, у кого он есть. У моста и глюкометра сеанса нет вовсе, и
     пустая строка про него была бы выдумкой. */
  const сеанс = сеансСтрока(свой, сейчасМс);
  if (сеанс) сейчас.push(сеанс);

  const оПриборе: Строка[] = [];
  /* Адрес нужен, чтобы различить два одинаковых прибора, — и только для этого. Поэтому
     он не первый, а в справке. */
  const адрес = h.bleId ?? null;
  if (адрес) оПриборе.push({ ключ: 'адрес', метка: 'Адрес в эфире', значение: адрес });
  if (h.inSlot) оПриборе.push({ ключ: 'слот', метка: 'Слот', значение: СЛОТ[h.inSlot] });
  if (h.firmware) оПриборе.push({ ключ: 'прошивка', метка: 'Прошивка', значение: h.firmware });
  if (h.batteryPct != null) {
    оПриборе.push({
      ключ: 'заряд', метка: 'Заряд', значение: `${h.batteryPct}%`,
      /* Голый процент не отвечает ни на один вопрос: доживёт ли до конца сеанса? Пока
         прогноза для сенсора у нас нет, честнее сказать, чего это число не значит. */
      подпись: h.batteryPct <= 20 ? 'мало — прибор может отвалиться раньше конца сеанса' : undefined,
    });
  }

  const мост = мостЖелезки(h, snap);
  return {
    состояние,
    попутчик,
    сейчас,
    оПриборе,
    черезМост: мост ? имяЖелезки(мост) : (заМостомЛи(h, snap) ? 'через мост' : null),
  };
}

/* Сеанс сенсора: сколько осталось и что с ним.

   Дня «N из 14» здесь НЕТ намеренно: начала сеанса движок не присылает, а вычислять его
   вычитанием из официального срока — значит выдать догадку за факт. На «Сегодня» день
   считается по событию замены из Nightscout, и это другой источник; смешивать их в одной
   строке нельзя — разойдутся на сутки и человек не поймёт, какой цифре верить.

   Конец берём `expiresAtMs`, а не официальный: у части сенсоров он дольше, и «сеанс
   закончился» на работающем приборе — худший вид неправды, он заставляет менять
   исправное. */
function сеансСтрока(d: DeviceView | null, сейчас: number): Строка | null {
  if (!d) return null;
  if (d.sessionState === 'WarmingUp') {
    const до = d.warmupEndsAtMs;
    return {
      ключ: 'сеанс', метка: 'Сеанс',
      значение: до != null && до > сейчас ? `прогрев, ещё ${краткоСрок(до - сейчас)}` : 'прогрев',
      подпись: 'пока греется, показаний не будет — это нормально',
    };
  }
  const конец = d.expiresAtMs ?? d.officialEndMs ?? null;
  if (конец == null) return null;
  const осталось = конец - сейчас;
  return {
    ключ: 'сеанс', метка: 'Сеанс',
    значение: осталось > 0 ? `ещё ${краткоСрок(осталось)}` : 'закончился',
    подпись: осталось > 0 && осталось < 2 * ДЕНЬ ? 'скоро менять' : undefined,
  };
}

function краткоСрок(мс: number): string {
  const мин = Math.round(мс / 60000);
  if (мин < 60) return `${мин} мин`;
  const ч = Math.round(мс / 3600e3);
  if (ч < 24) return `${ч} ч`;
  return `${Math.round(ч / 24)} дн`;
}

function время(t: number, сейчас: number): string {
  const мин = Math.round((сейчас - t) / 60000);
  if (мин < 1) return 'только что';
  if (мин < 60) return `${мин} мин назад`;
  const ч = Math.round(мин / 60);
  return ч < 24 ? `${ч} ч назад` : `${Math.round(ч / 24)} дн назад`;
}
