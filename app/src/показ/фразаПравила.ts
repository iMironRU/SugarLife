import type { Поле } from './правилаТревог';

/*
 * ПРАВИЛО ЧИТАЕТСЯ ПРЕДЛОЖЕНИЕМ, А ЧИСЛА СТОЯТ ВНУТРИ НЕГО (#590, мост 1.67).
 *
 * Экран показывал четыре поля с восемью кнопками. Четыре числа — это одно правило, разобранное на
 * запчасти: «смотрим назад 15 мин · считаем вперёд 20 мин · только ниже 5,5 · скорость 0,15»
 * вместе означают одну фразу, и собрать её человек должен был сам, в голове и спросонья. Владелец
 * про такой экран сказал: «с первого да и с третьего взгляда ничего не понятно».
 *
 * ФРАЗУ СОЧИНЯЕМ НЕ МЫ. Она приходит от движка вместе с правилом — местами под числа служат ключи
 * настроек. Собирать медицинское утверждение из чужих параметров мы себе не позволяем, а шаблон по
 * идентификатору правила сломал бы главное свойство экрана: новая тревога появляется на нём сама,
 * без единой правки в интерфейсе.
 *
 * Здесь — только разбор: где текст, где число и какому полю оно принадлежит.
 */

export type Кусок =
  | { вид: 'текст'; текст: string }
  | { вид: 'число'; поле: Поле };

/*
 * НЕ РАЗОБРАЛОСЬ — ФРАЗЫ НЕТ ВОВСЕ, а не фраза с дырой.
 *
 * Если ключ в шаблоне не совпал с ключом настройки, человек увидел бы на экране
 * `{alarms.forecast.windowMin}` вместо числа. Ровно так у нас однажды показался код
 * `cloud-uploader-down` вместо ярлыка, и это выглядит как поломка приложения — а речь о числе, по
 * которому будят ночью.
 *
 * Поэтому здесь всё или ничего: `null` означает «показывай прежним списком полей». Список хуже
 * читается, но он верен.
 */
export function фразаПравила(шаблон: string | null | undefined, поля: Поле[]): Кусок[] | null {
  if (!шаблон) return null;
  const поКлючу = new Map(поля.map((ф) => [ф.ключ, ф]));
  const куски: Кусок[] = [];
  let место = 0;
  const метка = /\{([^{}]+)\}/g;
  let м: RegExpExecArray | null;
  while ((м = метка.exec(шаблон)) != null) {
    const поле = поКлючу.get(м[1]);
    if (!поле) return null;
    if (м.index > место) куски.push({ вид: 'текст', текст: шаблон.slice(место, м.index) });
    куски.push({ вид: 'число', поле });
    место = м.index + м[0].length;
  }
  /* Ни одного места под число — это не фраза правила, а просто текст. Показывать её вместо полей
     значило бы спрятать числа совсем: тронуть в такой фразе нечего. */
  if (!куски.some((к) => к.вид === 'число')) return null;
  if (место < шаблон.length) куски.push({ вид: 'текст', текст: шаблон.slice(место) });
  return куски;
}

/*
 * ЧИСЛА, КОТОРЫХ ВО ФРАЗЕ НЕТ.
 *
 * Фраза покрывает условие правила, но у правила бывают и другие настройки — например «повторять
 * через». Спрятать их, показав только фразу, значило бы потерять настройку молча: она осталась бы
 * работать, а править её стало бы негде.
 *
 * Выключатели сюда не идут: они живут в шапке правила отдельно от чисел.
 */
export function числаВнеФразы(куски: Кусок[] | null, поля: Поле[]): Поле[] {
  const числовые = поля.filter((ф) => !ф.выключатель);
  if (!куски) return числовые;
  const во = new Set(куски.filter((к) => к.вид === 'число').map((к) => (к as { поле: Поле }).поле.ключ));
  return числовые.filter((ф) => !во.has(ф.ключ));
}
