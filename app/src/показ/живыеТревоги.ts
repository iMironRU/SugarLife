import { useEffect, useRef, useState } from 'react';
import { useSnapshot, sendIntent, type ActiveAlarmView } from '@/sources/bridge';
import { заголовокТревоги, текстТревоги, весУровня } from '@/domain/тревогаСлова';

/* ТРЕВОГА, НА КОТОРУЮ НЕЧЕМ ОТВЕТИТЬ (SugarLife#482).

   Кнопка «Понял» жила только в системном уведомлении — а там она спрятана: на айфоне баннер надо
   потянуть вниз, на Android — развернуть. Человек, разбуженный сиреной, открывает приложение и не
   находит ничего: тревога висит, звук идёт, ответить негде. Худший момент для поиска кнопки.

   Здесь она видна сразу. Что висит — знает движок (`activeAlarms`), чем это было — помним мы:
   события приходят по одному разу («что нового», а не журнал), поэтому подробности каждого id
   держим у себя и сверяем со списком живых.

   ЧЕГО ЗДЕСЬ НЕТ: решения о том, когда будить, и своих порогов. Только показать и передать «понял».

   И КОГО ЗДЕСЬ НЕТ: тревог, которые ответа не требуют.

   Владелец увидел на «Сегодня» карточку «Высокий сахар, 17 минут назад» — без кнопки, без способа
   убрать, и спросил, норма ли это. Не норма. На карточке стояли заголовок, число, возраст и
   активный инсулин — а число и инсулин в эту минуту уже видны в кружке прямо над ней. То есть
   полоса повторяла соседа и не давала сделать ничего.

   Полоса заведена под одно (#482): разбуженный сиреной открывает приложение и сразу видит, что
   случилось, и кнопку, которая это выключает. У тревоги без `needsAck` такой кнопки нет и быть не
   может — движок её и не ждёт. Значит и повода занимать первый экран у неё нет: движок уже доставил
   её уведомлением, где она смахивается, а состояние видно на самом экране.

   Не «спрятали неудобное»: уровень и голос по-прежнему решает движок, мы лишь не превращаем
   сообщение в несмахиваемую карточку поверх экрана действия. */

export interface ЖиваяТревога {
  id: string;
  заголовок: string;
  текст: string;
  уровень: string;
  /* ЧИСЛО ОТДЕЛЬНО ОТ ПОЯСНЕНИЯ (макет v2, #500). Полоса показывает число крупным кеглем — но
     только если тревога про число. У «данных нет» и «линия не меняется» числа нет вовсе, и первое
     слово пояснения, поставленное на его место, дало на экране огромное «Приложение». */
  число: string | null;
  /** Требует ответа. false — показываем, но кнопкой не просим: гасить нечего. */
  нуженОтвет: boolean;
  /* ПРИЧИНА УЖЕ УШЛА, ТРЕВОГА ЕЩЁ ДЕРЖИТСЯ (мост 1.54). Слова движка в этой фазе говорят «сахар
     пошёл вверх», и красный цвет рядом с ними противоречит сам себе — человек верит цвету. */
  налучше: boolean;
  /** Через сколько минут снимется, если улучшение удержится. 0 — не считают. */
  снимется: number;
  когда: number;
}

/* ОТВЕЧЕННОЕ — НЕ ЖИВОЕ (SugarLife#482).

   Движок держит тревогу в `activeAlarms`, пока держится причина: «понял» гасит звонок, а не низкий
   сахар. Для полосы это значит, что после ответа она висела бы, пока сахар не вернётся, — с кнопкой,
   на которую уже нажали. Уведомление в этот момент снимается, и полоса обязана вести себя так же.

   Вернётся она сама: движок присылает `repeat`/`escalated` с новым временем, и событие свежее ответа
   снова показывает полосу.

   НАША ПАМЯТЬ — ТОЛЬКО МОСТ ДО ПОДТВЕРЖДЕНИЯ, И ЖИВЁТ ОНА СЕКУНДЫ.

   Час назад я сделал её долгой и сохранил на диск: владелец гасил «Данных нет» и видел её снова,
   и я решил, что виноват перезапуск. Ядро проверило (SugarLifeCore#147) и ответило двумя фактами,
   каждый из которых опровергает правку.

   Первый: `acked` перезапуск ПЕРЕЖИВАЕТ — он лежит в состоянии тревоги и читается обратно. Своей
   памяти для этого не нужно вовсе.

   Второй, и он серьёзнее: у «молчания» уровень «Разбудить» и повтор при игноре каждые 15 минут.
   После снуза движок САМ снимает признак ответа и звонит заново — это настойчивость, а не сбой.
   А `sinceMs` при повторе не меняется: он про начало тревоги. То есть моя долгая память, сравнивая
   ответ со `sinceMs`, глушила бы каждый повтор будящей тревоги — сутки подряд, молча.

   Правильная граница: наш ответ закрывает строку ровно до того мгновения, когда движок скажет своё.
   Дальше правду говорит только `acked`. Если ответ до движка не доехал, строка вернётся через
   несколько секунд — и это верно: значит гасить не получилось, и человек должен это увидеть. */

/* Сколько держим свой ответ, не дождавшись подтверждения. Секунды: столько идёт круг «интент →
   движок → снимок». Дольше — начнём глушить повторы, короче — строка мигнёт под пальцем. */
const ОКНО_ПОДТВЕРЖДЕНИЯ = 20e3;
const отвечено = new Map<string, number>();

export function useЖивыеТревоги(): ЖиваяТревога[] {
  const снимок = useSnapshot();
  /* Подробности живут в ref, а не в состоянии: они меняются только вместе со снимком, и лишняя
     перерисовка на каждое событие тут ничего не добавляет. */
  const подробности = useRef(new Map<string, Подробность>());
  const [, перерисовать] = useState(0);

  const события = снимок?.alarmEvents;
  const активные = снимок?.activeAlarms;

  useEffect(() => {
    if (!события?.length) return;
    for (const с of события) {
      if (!с?.id) continue;
      if (с.what === 'cleared') { подробности.current.delete(с.id); continue; }
      подробности.current.set(с.id, {
        level: String(с.level ?? ''),
        mmol: с.mmol ?? null,
        ack: !!с.needsAck,
        at: с.atMs ?? Date.now(),
        /* Слова движка (мост 1.31). Он знает про повод больше нашего: и что случилось, и что
           делать, и как это звучит за рулём. */
        words: с.words ?? null,
      });
    }
    перерисовать((n) => n + 1);
  }, [события]);

  /* СОСТОЯНИЕ ГЛАВНЕЕ ПРОИСШЕСТВИЯ (мост 1.48, ядро #141).

     `alarmEvents` одноразовы: снимок их забирает и очищает. Полоса же постоянная, и через минуту
     после срабатывания у нас оставался один идентификатор — из него честно не построить ничего.
     Отсюда «Приложение сообщает о состоянии» на гипо и прогнозе падения: у них события подворачивались
     под руку реже прочих, и заглушка вылезала вернее.

     `alarmsNow` — состояние: слова собираются заново на каждый снимок, значит число в них СВЕЖЕЕ, а
     не то, что было в минуту срабатывания. Для низкого сахара это и нужно — человек смотрит на
     полосу, чтобы понять, что происходит сейчас.

     Копилку событий держим запасным путём: ядро старше 1.48 `alarmsNow` не шлёт, и без неё полоса
     исчезла бы совсем. */
  if (снимок?.alarmsNow?.length) return изСостояния(снимок.alarmsNow, отвечено);
  return собрать(активные ?? [], подробности.current, отвечено);
}

/** Полоса по состоянию тревог: всё, что нужно, уже пришло — собирать нечего. */
export function изСостояния(
  сейчас: ActiveAlarmView[],
  ответы: Map<string, number>,
): ЖиваяТревога[] {
  return сейчас.filter((т) => {
    /* Ответа не требует — на полосе ей делать нечего (см. шапку файла). */
    if (!т.needsAck) return false;
    /* ОТВЕЧЕННАЯ ТРЕВОГА УХОДИТ С ПОЛОСЫ — как и уведомление (правило в шапке файла).

       Здесь было `return true`: строку оставляли, кнопку убирали. Владелец посмотрел на это на
       телефоне и спросил, какой в этом смысл, — и смысла не нашлось. Сахар в эту минуту и так стоит
       крупно в кружке над полосой, действия на строке не осталось, убрать её нельзя ничем. Полоса
       заводилась как место, где на тревогу ОТВЕЧАЮТ; без ответа она просто занимает первый экран.

       Причина при этом никуда не делась, и прятать её мы не боимся: движок держит тревогу и пришлёт
       `repeat` с новым `sinceMs`, когда придёт срок напомнить. Возвращать её раньше срока — значит
       решать за движок, когда человеку напомнить, а это его расчёт, не наш.

       Движку верим больше своей памяти: `отвечено` не переживает перезапуск, а `acked` переживает. */
    if (т.acked) return false;
    /* Свой ответ учитываем, только пока движок про него ещё не сказал. Сравнивать со `sinceMs`
       нельзя: при повторе он не меняется, и сравнение похоронило бы настойчивость тревоги. */
    const ответ = ответы.get(т.id);
    if (ответ != null && Date.now() - ответ >= ОКНО_ПОДТВЕРЖДЕНИЯ) ответы.delete(т.id);
    return ответы.get(т.id) == null;
  }).map((т) => ({
    id: т.id,
    заголовок: заголовокТревоги(т.id, т.level),
    /* Слова движка без запасного варианта: в состоянии они есть всегда. Своих поверх не пишем — про
       гипогликемию это медицинское высказывание, и оно не наше. */
    текст: т.words,
    число: т.mmol != null ? т.mmol.toFixed(1).replace('.', ',') : null,
    уровень: т.level,
    /* Отвеченные сюда не доходят — отсеяны выше. */
    нуженОтвет: !!т.needsAck,
    налучше: !!т.improving,
    снимется: т.clearsInMin ?? 0,
    когда: т.sinceMs,
  })).sort((a, b) => весУровня(a.уровень) - весУровня(b.уровень) || b.когда - a.когда);
}

export interface Подробность {
  level: string; mmol: number | null; ack: boolean; at: number;
  /* Готовая фраза от движка. null — старое ядро или повод без слов: тогда говорим своими. */
  words?: string | null;
}

/** Что показать: живое минус отвеченное, с человеческими словами. Чистая — потому и проверяемая. */
export function собрать(
  активные: string[],
  подробности: Map<string, Подробность>,
  ответы: Map<string, number>,
): ЖиваяТревога[] {
  return активные.filter((id) => {
    /* Ответа не требует — не показываем. Событие мы могли не застать (приложение запустили после
       срабатывания): тогда `ack` неизвестен, и ниже он считается нужным — показать лишнюю строку
       дешевле, чем спрятать воющую тревогу без ответа. */
    const п0 = подробности.get(id);
    if (п0 && !п0.ack) return false;
    const ответ = ответы.get(id);
    if (ответ == null) return true;
    /* Событие свежее ответа — тревога зазвонила заново, и ответ к ней уже не относится. */
    const п = подробности.get(id);
    if (п && п.at > ответ) { ответы.delete(id); return true; }
    return false;
  }).map((id) => {
    const п = подробности.get(id);
    const уровень = п?.level ?? '';
    return {
      id,
      заголовок: заголовокТревоги(id, уровень),
      /* СЛОВА ДВИЖКА ГЛАВНЕЕ НАШИХ (#563, то же правило, что в нативных уведомлениях).

         На полосе стояло «Приложение сообщает о состоянии» — заглушка, которую мы пишем, когда у
         тревоги нет числа. Владелец увидел её у «Линии не меняется» и «Данных нет»: тревога
         сработала, а сказать ей нечего.

         У движка для этих поводов слова есть, и уже приезжают в `words` — их читали нативные
         уведомления, а экран нет. Своих формулировок поверх не пишем: на двух платформах они
         разойдутся, а речь о том, что человеку делать прямо сейчас. */
      текст: п?.words?.trim() || текстТревоги(id, уровень, п?.mmol),
      число: п?.mmol != null ? п.mmol.toFixed(1).replace('.', ',') : null,
      уровень,
      /* Событие мы могли не застать — приложение запустили после срабатывания. Тогда считаем, что
         ответ нужен: показать лишнюю кнопку дешевле, чем оставить воющую тревогу без ответа. */
      нуженОтвет: п?.ack ?? true,
      /* Запасной путь по событиям про разворот не знает: признак живёт только в состоянии. Красим
         как обычно — это прежнее поведение, а не решение. */
      налучше: false,
      снимется: 0,
      когда: п?.at ?? 0,
    };
  }).sort((a, b) => весУровня(a.уровень) - весУровня(b.уровень) || b.когда - a.когда);
}

/** Сказать движку «понял». Время — момент нажатия: доехать ответ может позже. */
export function понял(id: string): void {
  отвечено.set(id, Date.now());
  void sendIntent({ type: 'acknowledgeAlarm', alarmId: id, atMs: Date.now() });
}

/** Только для тестов: своя память оболочки между проверками не переносится. */
export function забытьОтветы(): void {
  отвечено.clear();
}

/** Только для тестов: та самая память, которую передают в `изСостояния` внутри хука. */
export const _ответы = отвечено;

