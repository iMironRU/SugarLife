import { describe, it, expect } from 'vitest';
import { сводка, минуты, почему, границыНочи } from './былаЛиОхрана';
import type { GuardGapView } from '@/sources/bridge';

const д = (o: Partial<GuardGapView>): GuardGapView =>
  ({ atMs: 1000, minutes: 7, why: 'killed', words: 'нас выгрузили', ...o });

describe('была ли охрана', () => {
  const сейчас = 100 * 3600e3;

  it('дыр не было — говорить не о чем', () => {
    expect(сводка([], сейчас).ответ).toBeNull();
  });

  /* Одна дыра и много дыр — разные новости. Одна означает случай; двадцать одна — что так теперь
     живём, и это уже про настройки телефона. */
  it('одна дыра названа как случай', () => {
    const с = сводка([д({ atMs: сейчас - 3600e3, minutes: 12 })], сейчас);
    expect(с.сколько).toBe(1);
    expect(с.ответ).toContain('один раз');
  });

  it('много дыр — счёт, сумма и самая длинная', () => {
    const с = сводка([
      д({ atMs: сейчас - 3600e3, minutes: 7 }),
      д({ atMs: сейчас - 7200e3, minutes: 90 }),
      д({ atMs: сейчас - 5400e3, minutes: 12 }),
    ], сейчас);
    expect(с.сколько).toBe(3);
    expect(с.всего).toBe(109);
    expect(с.самая).toBe(90);
    expect(с.ответ).toContain('1 ч 30 мин');
  });

  /* Окно — сутки: вчерашняя ночь отвечает на вопрос про эту ночь только запутыванием. */
  it('старое за окно не берём', () => {
    expect(сводка([д({ atMs: сейчас - 30 * 3600e3 })], сейчас).ответ).toBeNull();
  });

  /* Полминуты — тоже дыра. Округлить её в ноль значит соврать, пусть и немного. */
  it('меньше минуты не превращается в ноль', () => {
    expect(минуты(0.4)).toBe('меньше минуты');
  });

  it('часы отдельно: «145 мин» человек не читает', () => {
    expect(минуты(145)).toBe('2 ч 25 мин');
    expect(минуты(120)).toBe('2 ч');
  });

  /* Незнакомую причину не выдумываем: пустая строка честнее придуманной. */
  it('незнакомая причина — молчим', () => {
    expect(почему('квантовый скачок')).toBe('');
    expect(почему('swiped')).toBe('приложение смахнули');
  });
});

/* НОЧЬ ОТДЕЛЬНО ОТ СУТОК (SugarLife#727).

   Замечание владельца: «нам важна ночь, а не день». Сутки смешивают несравнимое — днём
   приложение перезапускают постоянно, и почти всегда это мы сами: установка, обновление,
   ручное снятие при проверке. 31 августа таких событий было десять, и ни одно ничего не
   говорит о надёжности. Ночью никто ничего не устанавливает. */
describe('границы последней ночи', () => {
  const вМс = (д: number, ч: number, м = 0) => new Date(2026, 8, д, ч, м).getTime();

  it('окно через полночь: утром считаем прошедшую ночь', () => {
    const г = границыНочи('23:00', '07:00', вМс(2, 9));
    expect(г).not.toBeNull();
    expect(г!.от).toBe(вМс(1, 23));
    expect(г!.до).toBe(вМс(2, 7));
  });

  /* Проснувшийся в четыре утра спрашивает про ЭТУ ночь, а не про прошлую: сказать ему про
     позавчерашнюю — значит ответить не на его вопрос. */
  it('ночь ещё идёт — считаем её до сейчас', () => {
    const г = границыНочи('23:00', '07:00', вМс(2, 4));
    expect(г!.от).toBe(вМс(1, 23));
    expect(г!.до).toBe(вМс(2, 4));
  });

  it('окно внутри суток тоже понимаем', () => {
    const г = границыНочи('01:00', '06:00', вМс(2, 9));
    expect(г!.от).toBe(вМс(2, 1));
    expect(г!.до).toBe(вМс(2, 6));
  });

  /* Своих границ не выдумываем: объявить чистой ночь, которой мы не видели, — хуже молчания. */
  it('окна нет — ночи нет', () => {
    expect(границыНочи(null, '07:00', вМс(2, 9))).toBeNull();
    expect(границыНочи('23:00', undefined, вМс(2, 9))).toBeNull();
    expect(границыНочи('ерунда', '07:00', вМс(2, 9))).toBeNull();
    expect(границыНочи('25:00', '07:00', вМс(2, 9))).toBeNull();
  });
});

describe('сводка отделяет ночь от дня', () => {
  const вМс = (д: number, ч: number) => new Date(2026, 8, д, ч).getTime();
  const сейчас = вМс(2, 9);
  const ночь = границыНочи('23:00', '07:00', сейчас)!;

  it('ночь чистая — говорим об этом вслух, даже когда днём были дыры', () => {
    const с = сводка([д({ atMs: вМс(1, 13), minutes: 12 })], сейчас, 24, ночь);
    expect(с.ночьЧистая).toBe(true);
    expect(с.ответ).toContain('Ночь прошла без перерывов');
    /* Дневные не выбрасываем, но и не пугаем ими: они про наладку, а не про жизнь. */
    expect(с.ответ).toContain('Днём');
  });

  it('дыра ночью — она и есть новость', () => {
    const с = сводка([
      д({ atMs: вМс(2, 3), minutes: 20 }),
      д({ atMs: вМс(1, 13), minutes: 12 }),
    ], сейчас, 24, ночь);
    expect(с.ночьЧистая).toBe(false);
    expect(с.ответ).toMatch(/^Ночью/);
    expect(с.сколько).toBe(1);
    expect(с.всего).toBe(20);
  });

  it('окна сна нет — отвечаем сутками и про ночь молчим', () => {
    const с = сводка([д({ atMs: вМс(2, 3), minutes: 20 })], сейчас, 24, null);
    expect(с.ночьЧистая).toBeNull();
    expect(с.ответ).toContain('За сутки');
  });
});
