import type { ConnectorView } from '@/sources/bridge';

/* ДОЕЗЖАЮТ ЛИ НАШИ ДАННЫЕ ТУДА, КУДА МЫ ИХ ШЛЁМ (SugarLife#547, SugarLifeCore#127).

   Nightscout бывает двух ролей сразу: источник (мы читаем) и приёмник (мы пишем). Первая роль на
   экране была всегда, вторая — не видна вовсе. Человек узнавал, что выгрузка встала, случайно и
   поздно: например, когда врач открывал отчёт и не находил там последней недели.

   Строка отвечает ровно на один вопрос — «доезжает?» — и в трёх словах:
     · «доезжает» + когда ушла последняя запись;
     · «в очереди N» — копится, значит сейчас не уходит;
     · текст ошибки — если приёмник ответил отказом.

   ОЧЕРЕДЬ САМА ПО СЕБЕ НЕ БЕДА. Между выгрузками записи копятся всегда: при шаге в пять минут в
   очереди законно лежит горсть показаний. Бедой её делает возраст последней отправки — вот его и
   сравниваем с шагом, а не выдумываем порог «сколько записей — это много». */

export interface СтрокаДоставки {
  id: string;
  имя: string;
  /** Короткий ответ: «доезжает» / «не доезжает» / «молчит». */
  знак: 'ок' | 'нет' | 'ждём';
  /** Подпись под именем — что именно происходит. */
  под: string;
}

function срок(мс: number): string {
  const м = Math.round(мс / 60000);
  if (м < 1) return 'только что';
  if (м < 60) return м + ' мин назад';
  const ч = Math.floor(м / 60);
  return ч < 24 ? ч + ' ч назад' : Math.floor(ч / 24) + ' д назад';
}

export function строкиДоставки(
  connectors: ConnectorView[] | undefined, сейчас = Date.now(),
): СтрокаДоставки[] {
  if (!connectors?.length) return [];
  return connectors.map((к) => {
    const имя = к.displayName || к.id;
    if (к.outboxLastError) {
      /* Текст ошибки показываем как есть: «сервер отказал» без подробностей не лечится, а с текстом
         человек хотя бы найдёт причину сам или перешлёт её тому, кто найдёт. */
      return { id: к.id, имя, знак: 'нет', под: к.outboxLastError };
    }
    const шагМс = Math.max(1, к.uploadEveryMin ?? 5) * 60000;
    const возраст = к.lastSentAtMs != null ? сейчас - к.lastSentAtMs : null;
    /* Ничего не отправляли ни разу — это не поломка: приёмник могли включить минуту назад.
       Но и «доезжает» сказать нельзя: проверять нечем. */
    if (возраст == null) {
      return { id: к.id, имя, знак: 'ждём', под: 'пока ничего не отправляли' };
    }
    /* Три шага молчания — то же правило, что у тревоги о пропаже данных: один пропуск бывает у
       всех, три подряд означают, что дорога закрыта. */
    if (возраст > шагМс * 3) {
      const хвост = к.outboxPending ? `, в очереди ${к.outboxPending}` : '';
      return { id: к.id, имя, знак: 'нет', под: `последняя запись ${срок(возраст)}${хвост}` };
    }
    const хвост = к.outboxPending ? ` · в очереди ${к.outboxPending}` : '';
    return { id: к.id, имя, знак: 'ок', под: `доезжает · ${срок(возраст)}${хвост}` };
  });
}
