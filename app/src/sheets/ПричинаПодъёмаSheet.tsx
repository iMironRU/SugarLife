import Иконка from '@/ui/Иконка';
import { checkmarkCircle, ellipseOutline, trashOutline } from 'ionicons/icons';
import Sheet from '@/ui/Sheet';
import { отметкаДля, type Причина } from '@/domain/причиныПодъёма';
import { ПРИЧИНЫ } from '@/слова/подъёмы';
import { отметитьПодъём, убратьОтметку, useОтметкиПодъёмов } from '@/settings/подъёмы';
import { часы } from '@/слова/время';

/* Чем объяснить подъём (#167).

   До сих пор с подъёмом можно было сделать ровно одно — записать еду. А если это была не
   еда, отметить было нечем: подъём оставался необъяснённым навсегда, разбор показывал его
   снова и снова, а человек, у которого отвалилась канюля, должен был либо соврать про
   еду, либо молчать. Приложение задавало вопрос и принимало один ответ из шести.

   ЕДА — ПЕРВАЯ В СПИСКЕ, НО НЕ ЕДИНСТВЕННАЯ. Она чаще прочих, поэтому стоит первой; выбор
   её ведёт туда же, куда вёл раньше, — в запись приёма этим временем.

   «НЕ ЗНАЮ» СТОИТ ПОСЛЕДНИМ И ОБЫЧНОЙ СТРОКОЙ. Не серым, не мелким, не «пропустить»: это
   полноценный ответ, и человек имеет право его дать. Без него он выберет любую причину,
   лишь бы убрать строку с глаз, — и данные станут хуже пустых. */
export default function ПричинаПодъёмаSheet({ at, rise, onClose, onЕда }: {
  at: number;
  rise: number;
  onClose: () => void;
  /** Выбрали еду — дальше обычная запись приёма этим временем. */
  onЕда: () => void;
}) {
  const отметки = useОтметкиПодъёмов();
  const текущая = отметкаДля(отметки, at)?.причина ?? null;

  const выбрать = (п: Причина) => {
    if (п === 'еда') { отметитьПодъём(at, 'еда'); onЕда(); return; }
    отметитьПодъём(at, п);
    onClose();
  };

  return (
    <Sheet isOpen onClose={onClose} title={`Подъём +${rise.toFixed(1).replace('.', ',')} ммоль в ${часы(at)}`}>
      <div className="sheet-note">
        Что это было? Отметка никуда не уходит и остаётся на этом устройстве — она нужна,
        чтобы разбор перестал спрашивать про этот подъём, а в записке врачу было видно,
        что вы об этом знаете.
      </div>

      <div className="list" style={{ marginTop: 10 }}>
        {ПРИЧИНЫ.map((п) => (
          <button key={п.ключ} className={'list-row pick-row' + (текущая === п.ключ ? ' on' : '')}
            onClick={() => выбрать(п.ключ)}>
            <Иконка icon={текущая === п.ключ ? checkmarkCircle : ellipseOutline} className="list-ico" />
            <span className="pick-main">
              <span className="list-title">{п.выбор}</span>
              {п.подпись && <span className="pick-sub">{п.подпись}</span>}
            </span>
          </button>
        ))}
      </div>

      {/* Снять отметку можно: человек мог ошибиться, а неверная причина в записке врачу
          хуже отсутствующей — по ней будут делать выводы. */}
      {текущая && (
        <button className="changed-btn во-всю" style={{ marginTop: 12 }}
          onClick={() => { убратьОтметку(at); onClose(); }}>
          <Иконка icon={trashOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
          Убрать отметку
        </button>
      )}
    </Sheet>
  );
}
