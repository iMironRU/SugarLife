import { useEffect, useState } from 'react';
import Иконка from '@/ui/Иконка';
import { playOutline, pauseOutline, refreshOutline, trashOutline, checkmarkCircle } from 'ionicons/icons';
import Sheet from '@/ui/Sheet';
import Row from '@/ui/Row';
import { sendIntent, type HardwareView, type UiSnapshot, type Intent } from '@/sources/bridge';
import { связь } from '@/domain/deviceState';
import { мостЖелезки, имяЖелезки, звеноЦепочки } from '@/domain/nearby';
import { словоЦепочки } from '@/слова/приборы';
import { ходПопытки, type Попытка, type Цель } from '@/domain/connectAttempt';
import { почемуМолчит } from '@/слова/попытка';
import { чтоСПрибором } from '@/domain/freshness';
import ПолосаХода from '@/ui/ПолосаХода';
import { ктоДержит } from '@/platform/ктоДержит';
import { словоЗанятости } from '@/слова/ктоДержит';
import { картаПрибора } from '@/показ/картаПрибора';
import ParamsForm from '@/ui/ParamsForm';
import ScanSheet from './ScanSheet';
import DeviceLogSheet from './DeviceLogSheet';
import { pulseOutline } from 'ionicons/icons';
import { нехватает } from '@/domain/deviceParams';

/* Карточка одного прибора (SugarLife#301).

   Её не было вовсе. Список приборов подписан «тапни устройство — там все действия», но
   плитка ничем не открывалась: подсказка обещала экран, которого нет. И на него же
   указывал единственный оставшийся путь.

   ПОЧЕМУ ЭТО БЫЛО ТУПИКОМ. «Подключить» на плитке показывалось, только когда прибор
   замечен в эфире. Замысел верный: кнопка, которая заведомо ничего не даст (прибор в
   другой комнате), читается как поломка приложения. Но у известного прибора «рядом»
   берётся из эфира, а в эфир он попадает, только когда его слушают, — получилось кольцо:
   подключить нельзя, потому что не видно, а не видно, потому что не подключён. Поиск
   нового не спасает: он по построению показывает только НЕзнакомых.

   ПОЭТОМУ ЗДЕСЬ «ПОДКЛЮЧИТЬ» ЕСТЬ ВСЕГДА. Карточку открывают намеренно — это и есть та
   осознанность, ради которой действие убрали с плитки. А раз оно может не сработать,
   рядом сказано почему: прибор должен быть рядом и свободен.

   ОЖИДАНИЕ ЖИВЁТ СНАРУЖИ (#303). Состояние попытки держит список, а не карточка: её
   могут закрыть через секунду после нажатия, и ожидание вместе с ней исчезло бы — а
   прибор в это время всё ещё пытается ответить.

   «Забыть» уводит запись из движка целиком (removeDevice, rev ≥ 1.8), поэтому со
   спросом: вернуть прибор можно только новым поиском, а серийник и мост придётся
   вводить заново. */
export default function HardwareSheet({ прибор, снимок, попытка, начать, сейчас, onClose }: {
  прибор: HardwareView;
  снимок: UiSnapshot | null | undefined;
  /** Ожидание ответа — общее со списком; null, когда ничего не ждём. */
  попытка: Попытка | null;
  начать: (цель: Цель, id: string, intent: Intent) => void;
  сейчас: number;
  onClose: () => void;
}) {
  const состояние = связь(прибор);
  const живой = состояние === 'live';
  /* Ведём прибор не мы. Признак — у движка в `devices[]`; `hardware[]` про роль не знает и
     показывает такую же живую связь, как у прибора, который ведём мы. */
  const записьПрибора = (снимок?.devices ?? []).find((d) => d.id === прибор.id) ?? null;
  const ведомый = записьПрибора?.role
    ? записьПрибора.role === 'follower'
    : записьПрибора?.companion === true;
  const звено = звеноЦепочки(прибор, снимок);
  const мост = мостЖелезки(прибор, снимок);

  /* Что показывать — решает показ/картаПрибора: приборы разные, и общий шаблон даёт
     либо пустые строки, либо потерянные (#378). Здесь только раскладка. */
  const карта = картаПрибора(прибор, снимок, сейчас);

  /* Занятость спрашиваем у системы, и только при молчащем приборе: живому этот вопрос не
     задают. Ответ может измениться, пока шторка открыта, — поэтому перезапрашиваем на
     смене состояния связи, а не один раз при открытии. */
  const [занятость, setЗанятость] = useState<string | null>(null);
  const молчит = связь(прибор) !== 'live';
  useEffect(() => {
    let живо = true;
    if (!молчит) { setЗанятость(null); return; }
    void ктоДержит(прибор.bleId ?? null).then((к) => { if (живо) setЗанятость(словоЗанятости(к)); });
    return () => { живо = false; };
  }, [молчит, прибор.bleId]);
  const занятие = чтоСПрибором(прибор);
  const строка = звено && !занятие
    ? словоЦепочки(звено, мост ? имяЖелезки(мост) : null)
    : карта.состояние;

  /* НАСТРОЙКИ ПРИБОРА — ЗДЕСЬ, А НЕ ГДЕ-ТО ЕЩЁ (SugarLife#362).

     С живого телефона: карточка честно сообщала «Не хватает настроек: Код сенсора» — и
     не оставляла способа этот код дать. Ни поля, ни ссылки: только «Подключить», которое
     заведомо не сработает, и «Забыть». Сказать человеку, чего от него хотят, и не дать
     это сделать — хуже, чем промолчать: молчание хотя бы не обещает.

     Спеку берём у ДВИЖКА (devices[]), а не выдумываем: какие поля нужны драйверу, знает
     он один. Железо и запись сопоставляются по id — это тот же прибор, просто разные
     проекции: hardware отвечает «на связи ли», device — «чем настроен».

     Форма — общая с облачными учётками и мастером (ui/ParamsForm): третья копия того же
     разошлась бы в первую же правку, как уже разошлись две. */
  const запись = (снимок?.devices ?? []).find((d) => d.id === прибор.id) ?? null;
  const поля = запись?.settings?.parameters ?? [];
  const [правки, setПравки] = useState<Record<string, string>>({});
  const [сохраняю, setСохраняю] = useState(false);
  const [читаемДля, setЧитаемДля] = useState<string | null>(null);
  const [журнал, setЖурнал] = useState(false);
  const [справка, setСправка] = useState(false);
  /* Показываем то, что уже знает движок, поверх — свои правки. Иначе человек, открыв
     карточку настроенного прибора, увидит пустые поля и решит, что настройки слетели. */
  const значения: Record<string, string> = {
    ...Object.fromEntries(поля.map((п) => [п.key, запись?.params?.[п.key] ?? п.default ?? ''])),
    ...правки,
  };
  const мало = нехватает(запись ? { settings: { parameters: поля } } as never : null, значения);
  const естьЧтоСохранить = Object.keys(правки).length > 0 && мало.length === 0;

  const сохранить = async () => {
    setСохраняю(true);
    await sendIntent({ type: 'setParams', deviceId: прибор.id, params: значения });
    setСохраняю(false);
    setПравки({});
  };

  const моё = попытка && попытка.id === прибор.id ? попытка : null;
  const ход = моё ? ходПопытки(моё, живой, сейчас) : null;
  const ждём = ход === 'идёт';

  const забыть = () => {
    if (!window.confirm(
      `Забыть «${имяЖелезки(прибор)}»? Запись уйдёт из приложения целиком — серийник, мост и `
      + 'настройки драйвера. Вернуть прибор можно будет только новым поиском.',
    )) return;
    void sendIntent({ type: 'removeDevice', deviceId: прибор.id });
    onClose();
  };

  return (
    <Sheet isOpen onClose={onClose} title={имяЖелезки(прибор)} subtitle={строка ?? undefined}>
      {/* Полоса хода — сразу под подписью, где сама подпись и говорит, что идёт (#745).
          Карточку открывают как раз затем, чтобы понять, движется ли дело: слова про
          «История сенсора: 40 %» через минуту выглядят точно так же. */}
      {занятие?.вид === 'занят' && <ПолосаХода доля={занятие.доля} />}

      {/* СНАЧАЛА — то, ради чего открыли: когда данные, что с сеансом (#378). Раньше
          первой строкой стоял адрес в эфире: сведение, нужное раз в жизни. */}
      {карта.сейчас.length > 0 && (
        <div className="list">
          {карта.сейчас.map((р) => (
            <Row key={р.ключ} title={р.метка} value={р.значение} sub={р.подпись} chevron={false} oneLine />
          ))}
        </div>
      )}

      {/* Чего не хватает — ПОЛНЫМ перечнем, а не усечённым заголовком (#362). В шапке
          строка обрезается, и именно её хвост — список недостающего — там и терялся. */}
      {прибор.registryState === 'NotConfigured' && прибор.note && (
        <div className="today-alert" style={{ marginTop: 12 }}>
          <div><span className="alert-title">{прибор.note}</span>
            <span>Пока не заполнено, прибор в эфир не выходит — движок его не поднимает.</span>
          </div>
        </div>
      )}

      {поля.length > 0 && (
        <>
          <div className="section-label sec">Настройки прибора</div>
          <ParamsForm spec={{ parameters: поля }} values={значения}
            onChange={(k, v) => setПравки((с) => ({ ...с, [k]: v }))}
            /* Кнопка чтения есть всегда: с фото она работает и там, где камеры нет. */
            onScan={setЧитаемДля} />
          <button className="food-save" disabled={сохраняю || !естьЧтоСохранить}
            onClick={() => void сохранить()} style={{ marginTop: 12 }}>
            <Иконка icon={checkmarkCircle} style={{ marginRight: 6, verticalAlign: -2 }} />
            {сохраняю ? 'Сохраняю…' : 'Сохранить'}
          </button>
          {!!мало.length && (
            <div className="metric-note" style={{ marginTop: 8 }}>
              Без этого прибор не заработает: {мало.map((п) => п.title.toLowerCase()).join(', ')}.
            </div>
          )}
          <ScanSheet isOpen={!!читаемДля} onClose={() => setЧитаемДля(null)}
            подпись="Код с упаковки сенсора"
            onВыбор={(r) => { if (читаемДля) setПравки((с) => ({ ...с, [читаемДля]: r.текст })); }} />
        </>
      )}

      {/* Итог прошлой попытки — словами, а не тишиной (#303). Держится до следующего
          нажатия: человек мог отвести взгляд, и мигнувшая надпись ничего бы не сказала. */}
      {ход === 'не ответил' && моё && (
        <div className="sheet-note" style={{ marginTop: 12 }}>{почемуМолчит(моё.цель)}</div>
      )}

      {/* КТО ЗАНЯЛ ПРИБОР (#422) — рядом с «почему молчит», потому что это и есть ответ.

          Спрашиваем систему, только когда данных у нас нет: у живого прибора вопрос не
          стоит, а лишний поход к Bluetooth-стеку ради «всё хорошо» ничего не добавляет.

          Фраза говорит ровно то, что мы знаем: прибор подключён на этом телефоне, а
          данные идут не нам. Кто именно его держит, узнать нельзя — имена установленных
          приложений идут как вероятность, а не как виновник. */}
      {занятость && (
        <div className="sheet-note warn" style={{ marginTop: 12 }}>{занятость}</div>
      )}

      {/* «Что происходит» — рядом с действиями, а не в настройках (#354). Сюда приходят
          с вопросом «почему молчит», и ответ должен лежать здесь же. */}
      <div className="list" style={{ marginTop: 12 }}>
        <Row icon={pulseOutline} title="Что происходит"
          sub="живой обмен с прибором: что приложение ему говорит и что слышит в ответ"
          onClick={() => setЖурнал(true)} />
      </div>

      {/* Справка о приборе — ниже и свёрнутая: её читают редко, а места она занимает
          столько же, сколько ответ на главный вопрос. Пустой — не показываем вовсе. */}
      {карта.оПриборе.length > 0 && (
        <>
          <button className="карта-ещё" onClick={() => setСправка((в) => !в)}>
            {справка ? 'Скрыть сведения о приборе' : 'Сведения о приборе'}
          </button>
          {справка && (
            <div className="list">
              {карта.оПриборе.map((р) => (
                <Row key={р.ключ} title={р.метка} value={р.значение} sub={р.подпись} chevron={false} oneLine />
              ))}
              {карта.черезМост && (
                <Row title="Через мост" value={карта.черезМост} chevron={false} oneLine />
              )}
            </div>
          )}
        </>
      )}
      {журнал && <DeviceLogSheet прибор={прибор} onClose={() => setЖурнал(false)} />}

      <div className="list" style={{ marginTop: 12 }}>
        {ведомый ? (
          /* ВЕДОМЫЙ: «стать основными» вместо «приостановить» (SugarLife#482).

             Раньше здесь была развилка «живой / не живой», и ведомый попадал в живого: связь у
             него есть, значит показывалась «Приостановить». А строка выше при этом советовала
             «закройте другую программу и нажмите „Подключить"» — кнопки с таким именем на экране
             не было вовсе. Совет, указывающий на несуществующую кнопку, хуже молчания: человек
             ищет её, не находит и решает, что не разобрался.

             Предупреждение стоит ЗДЕСЬ, а не в списке: у этого действия есть цена, и назвать её
             надо там, где палец. Пристройка ценой не обладает и потому происходит молча — граница
             ядра, и она же объясняет, почему кнопка ровно одна. */
          <Row icon={playOutline} chevron={false} disabled={ждём}
            title={ждём ? 'Подключаюсь…' : 'Стать основными'}
            sub={ждём
              ? 'жду ответа прибора'
              : 'сперва закройте программу, которая ведёт прибор, — иначе она его не отдаст'}
            onClick={() => начать('связь', прибор.id, { type: 'connect', deviceId: прибор.id })} />
        ) : живой ? (
          /* У моста действие иное по смыслу: блютус держит один центральный, и пока
             держим мы, другой телефон к мосту не подключится (SugarLifeCore#50). */
          <Row icon={pauseOutline} chevron={false} disabled={ждём}
            title={ждём ? 'Отпускаю…' : прибор.kind === 'bridge' ? 'Отпустить' : 'Приостановить'}
            sub={прибор.kind === 'bridge'
              ? 'освободить мост для другого телефона'
              : 'разорвать связь; запись о приборе останется'}
            onClick={() => начать('разрыв', прибор.id, { type: 'disconnect', deviceId: прибор.id })} />
        ) : (
          <Row icon={playOutline} chevron={false} disabled={ждём}
            title={ждём ? 'Подключаюсь…' : 'Подключить'}
            sub={ждём
              ? 'жду ответа прибора'
              : 'получится, если прибор рядом и не занят другим телефоном'}
            onClick={() => начать('связь', прибор.id, { type: 'connect', deviceId: прибор.id })} />
        )}

        {/* «Прочитать сейчас» имеет смысл только при живой связи: без неё запрос уйдёт в
            никуда, а человек решит, что сломан прибор. */}
        {живой && (
          <Row icon={refreshOutline} chevron={false} disabled={ждём}
            title="Прочитать сейчас" sub="не ждать очередного опроса"
            onClick={() => void sendIntent({ type: 'readNow', deviceId: прибор.id })} />
        )}

      </div>

      {/* «Забыть» отделено намеренно: оно стирает запись целиком, а стояло соседней
          строкой с «приостановить», у которого последствие несопоставимо меньше. Равный
          вес у неравного по разрушительности — это приглашение промахнуться. */}
      <div className="list" style={{ marginTop: 18 }}>
        <Row icon={trashOutline} chevron={false} disabled={ждём}
          title="Забыть прибор" sub="убрать запись из приложения; серийник и мост придётся вводить заново"
          onClick={забыть} />
      </div>
    </Sheet>
  );
}
