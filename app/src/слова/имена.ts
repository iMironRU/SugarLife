import type { Спросить } from '@/domain/mealNaming';

/* КАК СПРОСИТЬ ПРО ИМЯ ПРИЁМА (#324, переехало из domain/mealNaming.ts).

   Вопрос называет ровно то, что человек только что делал, и не требует ничего сверх: ни категории,
   ни состава, ни граммов по ингредиентам. Имя блюда — удобство, а не обязанность; вопрос, который
   выглядит анкетой, человек закроет и больше не откроет. */
export function вопрос(с: Спросить): string {
  return `Вы это ели ${с.count} раз${окончание(с.count)} — ${с.kind.toLowerCase()}, ${с.carbs} г. Как назовём?`;
}

/* «раз», «раза», «раз» — по последней цифре, с исключением на второй десяток. Своё склонение здесь
   потому, что общего у нас пока нет: заведём — сведём. */
function окончание(n: number): string {
  const д = n % 10;
  const дд = n % 100;
  if (дд >= 11 && дд <= 14) return '';
  if (д === 1) return '';
  if (д >= 2 && д <= 4) return 'а';
  return '';
}
