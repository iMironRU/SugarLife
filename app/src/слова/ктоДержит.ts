import type { КтоДержит } from '@/platform/ктоДержит';

/* Как сказать про занятый прибор (#422).

   Граница между наблюдением и приговором проходит по одному слову. «Датчик занят
   Juggluco» — утверждение, которого мы не можем проверить: чужие подключения нам не
   видны. «Подключён на этом телефоне, но данные идут не нам» — наблюдение, и оно верное.

   Имена установленных приложений добавляем как ВЕРОЯТНОСТЬ, а не как виновника. Человеку
   этого достаточно: решение у него простое — закрыть одно из двух. */
export function словоЗанятости(к: КтоДержит | null): string | null {
  if (!к || !к.занятЗдесь) return null;
  const основа = 'Прибор подключён на этом телефоне, но данные идут не нам.';
  if (!к.кандидаты.length) return `${основа} Похоже, его слушает другое приложение.`;
  if (к.кандидаты.length === 1) return `${основа} Установлено ${к.кандидаты[0]} — скорее всего, прибор у него.`;
  return `${основа} Установлены ${к.кандидаты.join(', ')} — прибор, скорее всего, у одного из них.`;
}
