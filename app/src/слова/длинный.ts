import type { Фон } from '@/domain/longInsulin';
import { часы, сколькоНазад } from './время';

/* ДЛИННЫЙ ИНСУЛИН — СЛОВАМИ (#324, переехало из domain/longInsulin.ts).

   Три состояния, и они разные по смыслу:

   · срок известен и не вышел — «примерно до 22:00»;
   · срок известен и вышел — «действие закончилось»;
   · срока нет — молчим о нём вовсе, называя только дозу и время.

   СРОК НЕ ВЫДУМЫВАЕМ, и правило это живёт в домене. У Тресибы 42 часа, у Лантуса 24, у Туджео
   больше суток и зависит от дозы; подставить «типичное» значит сказать за человека то, чего он не
   говорил, — и ошибиться ровно в тот момент, когда он проверяет, действует ли ещё вчерашний укол.

   ЗАКОНЧИВШИЙСЯ НЕ ПРЯЧЕМ, но и не выдаём за действующий: «был вчера в 22:10» — это ответ, а
   молчание — нет. Человек на ручках приходит сюда именно с вопросом «я вообще колол?».

   Часы и давность берём из общего словаря времени: свой формат здесь стал бы вторым способом
   написать одно и то же время на соседних строках экрана. */
export function подписьФона(ф: Фон): string {
  const начало = `${ф.ед} ед в ${часы(ф.когдаМс)}`;
  if (ф.доМс == null) return `${начало} · ${сколькоНазад(ф.когдаМс)}`;
  return ф.действует
    ? `${начало} · примерно до ${часы(ф.доМс)}`
    : `${начало} · действие закончилось`;
}
