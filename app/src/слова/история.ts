import type { СутьСобытия } from '@/domain/история';

/* КАК ЛЕНТА ИСТОРИИ ЗВУЧИТ ЧЕЛОВЕКУ (#324, третий заход).

   Домен отвечает сутью — числами и признаками; называет её этот файл. Смысл разделения не в
   опрятности: раньше правку слова нельзя было сделать, не тронув расчёт, а расчёт нельзя было
   проверить тестом, не сверяя буквы.

   ЛЕНТА ОТВЕЧАЕТ НА «ЧТО БЫЛО», А НЕ «ХОРОШО ЛИ ЭТО». Ни «много углеводов», ни «давно не менял» —
   разбор живёт в «Метриках», и там ему место. Здесь только факт и, где нужно, откуда он взялся. */

/** Как назвать расходник. Название — данные прибора, а не оценка. */
const ИМЯ_ЗАМЕНЫ: Record<string, string> = {
  sensor: 'сенсор', site: 'канюля', reservoir: 'резервуар', battery: 'батарейка',
};

export interface СловаСобытия {
  главное: string;
  подпись: string | null;
}

const число = (x: number, знаков: number) => x.toFixed(знаков).replace('.', ',');

export function назвать(с: СутьСобытия): СловаСобытия {
  switch (с.род) {
    /* Запись дневника пришла с готовым текстом: его писали не здесь, и переписывать его тут
       значило бы завести второго автора одной фразе. */
    case 'запись':
      return { главное: с.главное, подпись: с.подпись };

    /* Незнакомых сюда не приходит: домен их отфильтровал (`ЗНАКОМЫЕ_ЗАМЕНЫ`). Запасной вариант
       всё же есть — на случай, если списки разойдутся: показать ключом хуже, чем назвать, но
       молча потерять замену хуже обоих. Что они не разойдутся, проверяет тест рядом. */
    case 'замена':
      return { главное: `Замена: ${ИМЯ_ЗАМЕНЫ[с.что] ?? с.что}`, подпись: null };

    case 'ввод':
      return {
        главное: с.инсулин ? `${число(с.сколько, 1)} ед` : `${Math.round(с.сколько)} г`,
        /* Откуда запись — не украшение: доверие к своей и к чужой разное. */
        подпись: с.изОблака ? 'из облака' : null,
      };

    /* НИ СЛОВА О ТОМ, ЧТО ЧЕЛОВЕК ЧТО-ТО СКРЫЛ. Причин у подъёма больше двух (#167): недоданный
       болюс, отвалившаяся канюля, рассветный феномен, болезнь, нагрев сенсора. «Записи нет» —
       это про наши данные, а не про него. */
    case 'подъём':
      return {
        главное: `Подъём +${число(с.наСколько, 1)} ммоль`,
        подпись: 'сахар пошёл вверх · записи нет',
      };

    case 'приём':
      return { главное: `${Math.round(с.граммы)} г · ${с.имя}`, подпись: с.уточнение };
  }
}
