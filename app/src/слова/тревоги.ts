/* Выключатель самого правила приходит ключом `alarms.<id>.enabled` — среди обычных настроек, и это
   удобно: отдельного пути не нужно. Но подпись «enabled» человеку ничего не говорит. */
const ИМЯ_ВЫКЛЮЧАТЕЛЯ = 'Следить за этим';

/* Почему выключателя нет. Ядро отдаёт только признак `canDisable: false`, а объяснять просили нас —
   и правильно: молчаливое отсутствие человек читает как недоделку и идёт выключать уведомления
   целиком в системных настройках.

   Двух видов достаточно, и оба неслучайны: низкий сахар — то, ради чего всё существует; молчание во
   сне неочевидно, поэтому и объясняем подробнее, чем «нельзя». */
export function почемуНельзяВыключить(вид: string): string {
  if (вид === 'silence') {
    return 'Выключателя нет намеренно. Пока данных нет, тревога о низком сахаре сработать не может '
      + 'вовсе — считать нечего. Выключить эту значит выключить способность заметить, что защиты нет.';
  }
  if (вид === 'low') {
    return 'Выключателя нет намеренно: это та тревога, ради которой всё остальное и существует.';
  }
  return 'Выключателя нет намеренно: без этой тревоги остальные не работают как обещано.';
}

/* Незнакомый ключ. Единицу и шаг угадываем по окончанию — это догадка, но безопасная: ошибиться можно
   только в подписи и величине шага, а значение всё равно правит человек и проверяет движок. */
export function полеКлюча(ключ: string): ОписаниеПоля {
  const известное = ПОЛЕ[ключ];
  if (известное) return известное;
  const хвост = ключ.split('.').pop() ?? ключ;
  if (/Mmol$/i.test(хвост)) return { имя: хвост, единица: 'ммоль', шаг: 0.1, знаков: 1 };
  if (/Min$|min$/.test(хвост)) return { имя: хвост, единица: 'мин', шаг: 5, знаков: 0 };
  if (/^enabled$/i.test(хвост)) return { имя: ИМЯ_ВЫКЛЮЧАТЕЛЯ, единица: '', шаг: 0, знаков: 0 };
  if (/units$/i.test(хвост)) return { имя: хвост, единица: 'ед', шаг: 5, знаков: 0 };
  if (/volts$/i.test(хвост)) return { имя: хвост, единица: 'В', шаг: 0.05, знаков: 2 };
  return { имя: хвост, единица: '', шаг: 1, знаков: 0 };
}
