import { describe, it, expect } from 'vitest';
import { ярлыкЗастоя, знакЗастоя } from './застой';

describe('ярлык застоя', () => {
  it('три известные беды называет словами движка', () => {
    expect(ярлыкЗастоя('cloud-uploader-down')).toBe('загрузчик встал');
    expect(ярлыкЗастоя('cloud-uploader-nosensor')).toBe('сенсор потерян');
    expect(ярлыкЗастоя('cloud-stale')).toBe('данные старые');
  });

  /* Список у движка открытый. Пустота на месте новой беды читается как «всё хорошо» —
     это ровно та ошибка, ради которой issue и заведено. */
  it('незнакомый код показывает как есть, а не прячет', () => {
    expect(ярлыкЗастоя('cloud-unreachable')).toBe('cloud-unreachable');
    expect(ярлыкЗастоя('')).toBe('');
  });

  /* Значок обязан меняться вместе с ярлыком: два из четырёх случаев не про этот телефон,
     и перечёркнутое облако врало бы о них без слов. */
  it('знак отвечает на тот же вопрос, что и ярлык', () => {
    expect(знакЗастоя('cloud-uploader-down')).toBe('чужойТелефон');
    expect(знакЗастоя('cloud-uploader-nosensor')).toBe('прибор');
    expect(знакЗастоя('cloud-stale')).toBe('старое');
    expect(знакЗастоя('cloud-что-то-новое')).toBe('старое');
  });
});
