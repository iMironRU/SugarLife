import { describe, it, expect } from 'vitest';
import { ярлыкЗастоя, знакЗастоя, ярлыкБеды } from './застой';

describe('ярлык застоя', () => {
  it('три известные беды называет словами движка', () => {
    expect(ярлыкЗастоя('cloud-uploader-down')).toBe('загрузчик встал');
    expect(ярлыкЗастоя('cloud-uploader-nosensor')).toBe('сенсор потерян');
    expect(ярлыкЗастоя('cloud-stale')).toBe('данные старые');
  });

  /* Список у движка открытый. Пустота на месте новой беды читается как «всё хорошо» —
     это ровно та ошибка, ради которой issue и заведено. */
  it('незнакомый код показывает как есть, а не прячет', () => {
    expect(ярлыкЗастоя('cloud-unreachable')).toBe('cloud-unreachable');
    expect(ярлыкЗастоя('')).toBe('');
  });

  /* Значок обязан меняться вместе с ярлыком: два из четырёх случаев не про этот телефон,
     и перечёркнутое облако врало бы о них без слов. */
  it('знак отвечает на тот же вопрос, что и ярлык', () => {
    expect(знакЗастоя('cloud-uploader-down')).toBe('чужойТелефон');
    expect(знакЗастоя('cloud-uploader-nosensor')).toBe('прибор');
    expect(знакЗастоя('cloud-stale')).toBe('старое');
    expect(знакЗастоя('cloud-что-то-новое')).toBe('старое');
  });
});

/* ЧЕТВЁРТАЯ БЕДА (SugarLife#721, ядро SugarLifeCore#193).

   Полдня строка умела назвать три беды из четырёх: «сеть есть, до облака не достучались» наружу
   не выходило вовсе. У владельца падает VPN, а сервер при этом отвечает с мака за треть секунды —
   и подсказка «проверьте VPN» была единственной, по которой можно что-то сделать. */
describe('ярлык беды сети', () => {
  it('шесть кодов ядра названы сжатыми заголовками ядра', () => {
    expect(ярлыкБеды('cloud.offline')).toBe('связи нет');
    expect(ярлыкБеды('cloud.unreachable.online')).toBe('облако не отвечает');
    expect(ярлыкБеды('cloud.server.error')).toBe('облако с ошибкой');
    expect(ярлыкБеды('cloud.tls.failed')).toBe('шифрование не встало');
    expect(ярлыкБеды('cloud.unreachable')).toBe('облако недоступно');
    expect(ярлыкБеды('nightscout.auth.failed')).toBe('доступ отклонён');
  });

  /* Незнакомый код — не наше дело: молчим и отдаём прежний ответ строки. В отличие от застоя,
     где код показывается как есть: там список наш, здесь чужой и открытый, и сырой
     `parser.frame.invalid` в строке состояния не объяснит ничего. */
  it('чужие и незнакомые коды молчат', () => {
    expect(ярлыкБеды('parser.frame.invalid')).toBeNull();
    expect(ярлыкБеды('ble.link.lost')).toBeNull();
    expect(ярлыкБеды(null)).toBeNull();
    expect(ярлыкБеды(undefined)).toBeNull();
    expect(ярлыкБеды('')).toBeNull();
  });
});
