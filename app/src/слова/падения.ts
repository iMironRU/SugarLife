import type { Падение, СводкаПадений } from '@/показ/разборПадений';

/* КАК РАЗБОР ПАДЕНИЙ ЗВУЧИТ (#812).

   Домен отдаёт числа и признаки, называет их этот файл — по тому же шву, что и лента истории.

   ЛЕНТА РАЗБОРА НЕ ОЦЕНИВАЕТ. Ни «часто», ни «многовато», ни «стоит показать врачу»: она отвечает
   на «что было» и «повторяется ли», а вывод делает человек. Оценка здесь была бы вдвойне неуместна:
   до гипогликемии доходит одно падение из семи, и «тревожно» на таком основании — не факт, а
   запугивание. */

const число = (x: number) => x.toFixed(1).replace('.', ',');

/** Одна строка ленты. */
export function падениеСловами(п: Падение): { главное: string; подпись: string } {
  const начало = п.сНачала != null ? `с ${число(п.сНачала)}` : 'начало неизвестно';
  /* Идущее сейчас называем состоянием, а не длительностью: числа у него ещё нет. */
  const срок = п.минут == null ? 'идёт сейчас' : `${п.минут} мин`;
  return {
    главное: `${начало} · ${срок}`,
    /* Про сон говорим только когда он был: «не спал» — не новость, а лишняя строка в каждой. */
    подпись: п.спал ? 'во сне' : '',
  };
}

/**
 * Свод одной фразой.
 *
 * ЧИСЛО НА ОКНО, А НЕ «В СРЕДНЕМ В ДЕНЬ». Дробь вроде «0,9 в сутки» человек не проверяет и не
 * запоминает; «двенадцать за две недели» он сверяет со своей памятью — и именно это ему нужно,
 * чтобы решить, много это или нет. Решает он, не мы.
 */
export function сводкаСловами(с: СводкаПадений): string | null {
  if (!с.всего) return null;
  const дней = `за ${с.суток} дн.`;
  const ночью = с.ночью ? `, из них во сне ${с.ночью}` : '';
  const длилось = с.медианаМинут != null ? `. Обычно длится ${с.медианаМинут} мин` : '';
  return `${с.всего} ${склонение(с.всего)} ${дней}${ночью}${длилось}.`;
}

/** «1 спуск», «2 спуска», «5 спусков» — иначе фраза спотыкается на каждом числе. */
function склонение(n: number): string {
  const сотня = n % 100;
  if (сотня >= 11 && сотня <= 14) return 'спусков';
  switch (n % 10) {
    case 1: return 'спуск';
    case 2: case 3: case 4: return 'спуска';
    default: return 'спусков';
  }
}
