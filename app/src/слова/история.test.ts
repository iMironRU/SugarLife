import { describe, it, expect } from 'vitest';
import { назвать } from './история';
import { ЗНАКОМЫЕ_ЗАМЕНЫ } from '@/domain/история';

/* КАК ЛЕНТА ЗВУЧИТ (#324, третий заход).

   Раньше эти правила проверялись вперемешку с расчётом: тест ленты сличал собранную фразу, и
   поправить слово было нельзя, не тронув проверку расчёта. Теперь расчёт проверяется состоянием
   (`domain/история.test.ts`), а здесь — свойства формулировок.

   Свойства, а не буквы: «во фразе про подъём нет обвинения» переживёт переписывание текста, а
   `toBe('Подъём +3,4 ммоль')` упадёт от запятой и ничего при этом не защитит. */

describe('слова ленты истории', () => {
  it('запись дневника едет как есть: её текст писали не здесь', () => {
    const с = назвать({ род: 'запись', главное: 'Внесли 45 г', подпись: 'с телефона' });
    expect(с).toEqual({ главное: 'Внесли 45 г', подпись: 'с телефона' });
  });

  it('замену называют человеческим словом, а не ключом', () => {
    expect(назвать({ род: 'замена', что: 'site' }).главное).toBe('Замена: канюля');
  });

  /* ДВА СПИСКА — ЦЕНА РАЗДЕЛЕНИЯ, И ОНА РЕАЛЬНА. Домен решает, какие замены пускать в ленту;
     слова их называют. Разойдутся — человек увидит «Замена: reservoir». Здесь это и ловится. */
  it('каждый знакомый домену расходник назван словом', () => {
    for (const вид of ЗНАКОМЫЕ_ЗАМЕНЫ) {
      const главное = назвать({ род: 'замена', что: вид }).главное;
      expect(главное, `не назван: ${вид}`).not.toContain(вид);
      expect(главное).toMatch(/^Замена: [а-яё]+$/);
    }
  });

  it('инсулин в единицах, еда в граммах — и запятая, а не точка', () => {
    expect(назвать({ род: 'ввод', инсулин: true, сколько: 4.25, изОблака: true }).главное).toBe('4,3 ед');
    expect(назвать({ род: 'ввод', инсулин: false, сколько: 45, изОблака: true }).главное).toBe('45 г');
  });

  it('видно, что запись пришла из облака: доверие к своей и к чужой разное', () => {
    expect(назвать({ род: 'ввод', инсулин: true, сколько: 2, изОблака: true }).подпись).toBe('из облака');
  });

  /* НИ СЛОВА О ТОМ, ЧТО ЧЕЛОВЕК ЧТО-ТО СКРЫЛ. Причин у подъёма больше двух (#167): недоданный
     болюс, отвалившаяся канюля, рассветный феномен, болезнь, нагрев сенсора. */
  it('подъём называет величину и не обвиняет', () => {
    const с = назвать({ род: 'подъём', наСколько: 3.42 });
    expect(с.главное).toContain('3,4');
    expect(`${с.главное} ${с.подпись}`).not.toMatch(/не записал|скрыл|забыл|пропустил/i);
  });

  it('приём: сколько и что, уточнение отдельной строкой', () => {
    const с = назвать({ род: 'приём', граммы: 60, имя: 'Обед', уточнение: 'дома' });
    expect(с.главное).toBe('60 г · Обед');
    expect(с.подпись).toBe('дома');
  });

  /* ЛЕНТА ОТВЕЧАЕТ НА «ЧТО БЫЛО», А НЕ «ХОРОШО ЛИ ЭТО» — разбор живёт в «Метриках». */
  it('ни одна формулировка не оценивает', () => {
    const все = [
      назвать({ род: 'замена', что: 'sensor' }),
      назвать({ род: 'ввод', инсулин: true, сколько: 12, изОблака: true }),
      назвать({ род: 'подъём', наСколько: 9 }),
      назвать({ род: 'приём', граммы: 200, имя: 'Ужин', уточнение: null }),
    ];
    for (const с of все) {
      expect(`${с.главное} ${с.подпись ?? ''}`)
        .not.toMatch(/много|мало|слишком|давно пора|плохо|хорошо|стоило/i);
    }
  });
});
