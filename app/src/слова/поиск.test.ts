import { describe, it, expect } from 'vitest';
import { СЛОВО_ПУСТОТЫ, словоПустоты } from './поиск';

/* Слова проверяем отдельно от расчёта (#324): формулировки правятся чаще правил, и общий тест
   ломался бы от правки буквы. Здесь остались только те свойства фраз, которые НЕ косметические. */
describe('слова пустого поиска', () => {
  it('первые секунды не гадаем: список причин объясняет то, чего ещё не случилось', () => {
    expect(словоПустоты('слушаю')).not.toMatch(/занят другим телефоном/);
  });

  it('ждём долго — причины идут по убыванию частоты, а не как удобнее перечислять', () => {
    const т = словоПустоты('долго пусто');
    expect(т.indexOf('занят')).toBeGreaterThan(-1);
    expect(т.indexOf('занят')).toBeLessThan(т.indexOf('далеко'));
  });

  /* В браузере блютуса нет как класса. Списать пустоту на разрешения — враньё: человек пойдёт их
     проверять и ничего не найдёт. */
  it('браузер называем браузером, а не настройками', () => {
    expect(словоПустоты('эфира нет')).toMatch(/браузер/i);
    expect(словоПустоты('эфира нет')).not.toMatch(/разреш/i);
  });

  it('словарь полон: у каждого состояния есть фраза', () => {
    for (const [состояние, фраза] of Object.entries(СЛОВО_ПУСТОТЫ)) {
      expect(фраза.length, состояние).toBeGreaterThan(20);
    }
  });
});
