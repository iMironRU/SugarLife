import { describe, it, expect } from 'vitest';
import { СЛОВО_ПУСТОГО, словоПустого } from './журнал';

/* У каждого состояния свой выход: обновить приложение, открыть на телефоне, поднять подробность,
   подождать. Проверяем, что фразы этих выходов не путают (#324). */
describe('слова пустого журнала', () => {
  it('в браузере зовём на телефон, а на телефоне — обновиться', () => {
    expect(словоПустого('в браузере')).toMatch(/браузер/i);
    const наТелефоне = словоПустого('сборка старая');
    expect(наТелефоне).toMatch(/сборка/i);
    /* «Откройте на телефоне» человеку с телефоном — это отправить его туда, где он уже стоит. */
    expect(наТелефоне).not.toMatch(/в браузере|на телефоне/i);
  });

  it('всё отфильтровано — вопрос к порогу, а не к прибору', () => {
    expect(словоПустого('только служебные')).toMatch(/подробн/i);
  });

  it('словарь полон: у каждого состояния есть фраза', () => {
    for (const [состояние, фраза] of Object.entries(СЛОВО_ПУСТОГО)) {
      expect(фраза.length, состояние).toBeGreaterThan(20);
    }
  });
});
