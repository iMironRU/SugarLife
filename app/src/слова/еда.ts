import type { Пора, Повод } from '@/domain/foodNow';

/* Как называется приём в это время суток (SugarLife#324).

   Правило — какая сейчас пора — считает домен: там граница между утром и днём, и там же
   отдельная ночь, потому что ночью ест не проголодавшийся, а разбуженный сахаром. Здесь
   только имя для поры. */
export const ПРИЁМ_ПОРЫ: Record<Пора, string> = {
  утро: 'Завтрак', день: 'Обед', вечер: 'Ужин', ночь: 'Перекус',
};

/* ПОЧЕМУ ПОДНЯЛИ ИМЕННО ЭТИ ПЛИТКИ (#324, переехало из domain/foodNow.ts).

   Группа обязана быть ПОДПИСАНА: видно, почему именно эти. Молча переставленный список — это
   когда приложение решает за тебя и не объясняет; мы так не делаем нигде.

   И отдельно, потому что граница тонкая: мы упорядочиваем список, а не советуем дозу. «Сахар 3,4 —
   вот быстрые углеводы» помощь; «съешь 15 граммов» — назначение, и его мы не даём. Поэтому во
   фразе про гипо стоит число человека и слово «если», а не количество. */
const вПору: Record<Пора, string> = {
  утро: 'Обычно по утрам', день: 'Обычно днём', вечер: 'Обычно вечером',
  /* Ночью ест не проголодавшийся, а разбуженный сахаром: «обычно по ночам» звучало бы как
     описание привычки, которой человек не выбирал. */
  ночь: 'Ночью — обычно понемногу',
};

export function почемуЭти(п: Повод): string {
  if (п.вид === 'гипо') {
    return `Сахар ${п.mmol.toFixed(1).replace('.', ',')} — если купируешь, вот быстрые углеводы`;
  }
  if (п.вид === 'падает') return 'Сахар падает — если купируешь, вот быстрые углеводы';
  if (п.вид === 'намерение') return `Обычно на «${п.приём.toLowerCase()}»`;
  return вПору[п.пора];
}
