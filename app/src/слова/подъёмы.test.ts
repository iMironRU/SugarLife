import { describe, it, expect } from 'vitest';
import { ПРИЧИНЫ, видПричины } from './подъёмы';

describe('слова причин подъёма', () => {
  /* Главное правило этого словаря, и оно про слова, а не про расчёт: причины — список
     возможностей, а не обвинений. Человек с хроническим диагнозом и так живёт с чувством вины за
     каждое число. */
  it('ни одна формулировка не обвиняет', () => {
    const всё = ПРИЧИНЫ.map((п) => `${п.выбор} ${п.метка} ${п.подпись ?? ''}`).join(' ').toLowerCase();
    expect(всё).not.toMatch(/забы|не записал|пропустил|виноват|поленил/);
  });

  /* Без «не знаю» человек выберет любую причину, лишь бы убрать строку с глаз, — и данные станут
     хуже пустых: не «неизвестно», а «неправда». Врач, читающий «канюля ×3», должен видеть
     настоящие три канюли, а не три нажатия ради тишины. */
  it('«не знаю» есть в списке и стоит последним', () => {
    expect(ПРИЧИНЫ[ПРИЧИНЫ.length - 1].ключ).toBe('неизвестно');
  });

  it('у каждой предложенной причины есть и выбор, и метка', () => {
    for (const п of ПРИЧИНЫ) {
      expect(п.выбор.length, п.ключ).toBeGreaterThan(0);
      expect(п.метка.length, п.ключ).toBeGreaterThan(0);
    }
  });

  it('«не знаю» называется честно, а не отговоркой', () => {
    expect(видПричины('неизвестно').метка).toBe('причина не найдена');
  });
});
