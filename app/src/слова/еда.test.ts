import { describe, it, expect } from 'vitest';
import { почемуЭти, ПРИЁМ_ПОРЫ } from './еда';

/* Граница, из-за которой эти фразы вообще написаны так, а не иначе: мы упорядочиваем список, а не
   советуем дозу. «Сахар 3,4 — если купируешь, вот быстрые углеводы» помощь; «съешь 15 граммов» —
   назначение, и его мы не даём (#324). */
describe('почему подняли именно эти плитки', () => {
  it('число человека в запятых, и рядом «если» — а не количество', () => {
    const т = почемуЭти({ вид: 'гипо', mmol: 3.2 });
    expect(т).toContain('3,2');
    expect(т).toContain('если');
    expect(т).not.toMatch(/\d+\s*(г|грамм)/);
  });

  it('падение с нормального сахара объясняем без числа: числу тут верить рано', () => {
    expect(почемуЭти({ вид: 'падает' })).toBe('Сахар падает — если купируешь, вот быстрые углеводы');
  });

  it('выбранный приём называем его же словом, строчными', () => {
    expect(почемуЭти({ вид: 'намерение', приём: 'Ужин' })).toBe('Обычно на «ужин»');
  });

  /* Ночью ест не проголодавшийся, а разбуженный сахаром: «обычно по ночам» звучало бы как
     описание привычки, которой человек не выбирал. */
  it('ночь объясняем иначе, чем прочие поры', () => {
    expect(почемуЭти({ вид: 'пора', пора: 'ночь' })).toBe('Ночью — обычно понемногу');
    expect(почемуЭти({ вид: 'пора', пора: 'утро' })).toBe('Обычно по утрам');
  });

  it('у каждой поры есть имя приёма', () => {
    expect(Object.values(ПРИЁМ_ПОРЫ).every((и) => и.length > 0)).toBe(true);
  });
});
