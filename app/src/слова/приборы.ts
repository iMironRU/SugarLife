import type { ЗвеноЦепочки } from '@/domain/nearby';
import type { SourceStatus } from '@/sources/bridge';
import { сколькоНет } from './время';

/* Как называется путь, которым данные попадают в приложение (#324).

   Облако у нас сегодня одно, поэтому названо прямо. Когда каналов станет больше
   (Connector, SugarLifeCore#15), имя должно приехать из канала: «через облако» ничего
   не говорит человеку, у которого их два. */
export const СЛОВО_КАНАЛА: Record<ChannelView['kind'], string> = {
  direct: 'по радио', bridged: 'через мост', cloud: 'через Nightscout',
};

/* То же самое одним словом — для панели, где на строку приходится треть экрана.
   Полная фраза там не помещается, а обрезанная хуже короткой. */
const КОРОТКО_КАНАЛ: Record<ChannelView['kind'], string> = {
  direct: 'радио', bridged: 'мост', cloud: 'облако',
};

/** Назвать канал. null на входе — молчание на выходе: домен уже решил, что говорить нечего. */
export const названиеКанала = (k: ChannelView['kind'] | null): string | null =>
  (k ? СЛОВО_КАНАЛА[k] : null);

export const короткоКанал = (k: ChannelView['kind'] | null): string | null =>
  (k ? КОРОТКО_КАНАЛ[k] : null);

/* Состояние связи словами. `unknown` намеренно без слова: «состояние неизвестно» —
   это не новость, а признание, что мы не спросили, и человеку с ним делать нечего. */
export const меткаСвязи: Record<Связь, string | null> = {
  live: 'на связи, данные идут',
  wait: 'подключается — данных пока нет',
  off: 'нет связи',
  unknown: null,
};

/* Что сказать про обрыв (#324, SugarLifeCore#39).

   «Связь потеряна» рядом со строкой «на связи» — это два ответа на один вопрос.
   Правильный ответ один: что именно оборвалось и чем это компенсировано. Радио молчит,
   а цифры идут облаком — это СОСТОЯНИЕ, а не тревога; тревога начинается там, где данных
   нет ни откуда.

   Разбор — чей канал молчит и есть ли обход — делает домен (domain/однаПравда.ts).
   Здесь только слова. */
export function словоОбрыва(о: Обрыв | null): string | null {
  if (!о) return null;
  const { сОбходом, совсем } = о;
  if (!совсем.length) {
    if (!сОбходом.length) return null;
    const с = сОбходом[0];
    const путь = названиеКанала(с.откуда);
    return сОбходом.length === 1
      ? `Радио с «${с.имя}» молчит — данные идут ${путь}`
      : `Радио молчит у ${сОбходом.length} приборов — данные идут ${путь}`;
  }
  return совсем.length === 1
    ? `«${совсем[0].имя}» не на связи, и данных от него нет`
    : `Нет связи и данных: ${совсем.map((с) => с.имя).join(', ')}`;
}


/** Подпись про свежесть. null — говорить нечего, состояние скажет обычная метка. */
export function подписьСвежести(с: Свежесть): string | null {
  if (!с) return null;
  if (с.вид === 'прогрев') return 'ждём первое показание';
  return с.мс == null ? 'на связи, данных нет' : `на связи, данных нет ${сколькоНет(с.мс)}`;
}

/* Чем прибор занят и чего ему не хватает. Слова движка отдаём как есть: он один знает,
   чего не хватает и что сейчас делает, а пересказ был бы вторым мнением о том же. */
export function подписьЗанятия(з: Занятие): string | null {
  if (!з) return null;
  return з.вид === 'неНастроен' ? (з.заметка ?? 'Не хватает настроек') : з.чем;
}

/* Подсказка про мост: нужен ли он этой модели (#406).

   Слова разные не для красоты: у помпы и сенсора разные причины и разные приборы, и
   человек, читающий подсказку, ищет в ней СВОЙ случай. Общая формулировка «может
   понадобиться мост» не отвечает никому. */
export function подсказкаПроМост(вид: 'pump' | 'sensor', обязателен: boolean): string {
  if (вид === 'pump') {
    return обязателен
      ? 'Эта помпа управляется по радио — нужен мост (RileyLink/OrangeLink).'
      : 'Старые Medtronic (Paradigm, 5xx/7xx) — по радио, требуют RileyLink/OrangeLink. Современные — напрямую/через аплоадер.';
  }
  return обязателен
    ? 'Этот сенсор не вещает BLE сам — нужен мост (MiaoMiao/Bubble).'
    : 'Libre 1 и старые сенсоры подключаются через мост (MiaoMiao/Bubble). Современные — напрямую.';
}

/* КАК НАЗВАТЬ ЗВЕНО ЦЕПОЧКИ (#324, переехало из domain/nearby.ts).

   Состояние считает домен: он один знает, отвечает ли мост и отвечает ли за ним прибор. Слова
   живут здесь, потому что за каждым стоит СВОЁ ДЕЙСТВИЕ: «мост не на связи» — идти к мосту, помпу
   трогать незачем; «устройство не отвечает» — расстояние, батарея помпы, частота. Перепутать их
   значит отправить человека чинить исправное.

   Имя моста подставляет вызывающий: оно есть не всегда. */
export function словоЦепочки(з: ЗвеноЦепочки, мост: string | null): string {
  if (з === 'мост молчит') return мост ? `«${мост}» не на связи` : 'мост не на связи';
  if (з === 'устройство молчит') return 'мост на связи, устройство не отвечает';
  return мост ? `на связи через «${мост}»` : 'на связи через мост';
}

/* СТАТУС ИСТОЧНИКА ДАННЫХ ПО-РУССКИ (контракт 1.7; переехало из домена в #324).

   Это жизненный цикл ПОЛУЧЕНИЯ данных, а не состояние связи. Разница не формальная: сенсор может
   быть подключён и при этом ещё ничего не отдавать — идёт прогрев или первый обмен. Раньше такое
   состояние выглядело как «подключено», и человек ждал цифру, которой ещё неоткуда взяться.

   «Отстаёт» тоже отдельно от «нет связи»: связь есть, показания идут, но последнее старше четверти
   часа. Для ночи это разные новости. */
export function sourceStatusLabel(s: SourceStatus | undefined | null): string | null {
  switch (s) {
    case 'Live': return 'на связи';
    case 'Acquiring': return 'связь есть, показаний ещё нет';
    case 'Connecting': return 'подключается';
    case 'Delayed': return 'отстаёт';
    case 'Disconnected': return 'нет связи';
    /* Ручка (rev ≥ 1.15). Не «нет связи»: связи у неё нет по устройству, и напоминать надо не о
       ней, а о том, что пора поднести прибор к телефону. */
    case 'ReadOnTouch': return 'читается при поднесении';
    default: return null; // мост поля не прислал — не выдумываем
  }
}
