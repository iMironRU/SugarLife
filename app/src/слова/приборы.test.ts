import { describe, it, expect } from 'vitest';
import { словоОбрыва, подписьСвежести, подписьЗанятия, словоЦепочки } from './приборы';
import type { СтрокаПравды } from '@/domain/однаПравда';

/* Словарям тесты не нужны — проверять там нечего, а тест, повторяющий строку, ломается
   на каждой правке формулировки и не ловит ни одной ошибки.

   Здесь другой случай: формулировка ВЫБИРАЕТСЯ — один прибор или несколько, есть обход
   или нет. Проверяем именно выбор и то, без чего фраза бесполезна: имя прибора и путь,
   которым идут данные. Букв не сверяем. */

const с = (p: Partial<СтрокаПравды>): СтрокаПравды => ({
  id: 'a', имя: 'Прибор', состояние: 'нет связи', откуда: null, когдаМс: null,
  вместоСостояния: null, дорога: false, ...p,
});

describe('слово обрыва', () => {
  it('разбирать нечего — молчим', () => {
    expect(словоОбрыва(null)).toBe(null);
  });

  it('радио молчит, данные идут — говорим чем компенсировано', () => {
    const ф = словоОбрыва({ сОбходом: [с({ имя: 'Medtronic 722', откуда: 'cloud' })], совсем: [] });
    expect(ф).toMatch(/Medtronic 722/);
    expect(ф).toMatch(/Nightscout/);
    expect(ф).not.toMatch(/^Связь потеряна/);
  });

  /* Имя обязательно: безымянное «связь потеряна» человек не может ни проверить, ни
     опровергнуть — у него на экране два прибора. */
  it('данных нет ниоткуда — тревога с именем', () => {
    expect(словоОбрыва({ сОбходом: [], совсем: [с({ имя: 'Sibionics GS1' })] })).toMatch(/Sibionics GS1/);
  });

  it('молчат несколько — перечисляем поимённо', () => {
    const ф = словоОбрыва({ сОбходом: [], совсем: [с({ id: 'a', имя: 'A' }), с({ id: 'b', имя: 'B' })] });
    expect(ф).toMatch(/A, B/);
  });
});

describe('подпись про свежесть', () => {
  /* Проверяем не буквы, а то, что число попадает в строку: «на связи, данных нет» без
     срока и с ним — разные новости, и вторую человек читает как «пора идти чинить». */
  it('молчит со сроком — срок назван', () => {
    expect(подписьСвежести({ вид: 'молчит', мс: 7 * 60_000 })).toMatch(/7 мин/);
  });

  /* Прибор не сообщал ничего с самого старта: факт есть, числа нет, выдумывать нельзя. */
  it('молчит без срока — факт без выдуманного числа', () => {
    const ф = подписьСвежести({ вид: 'молчит', мс: null });
    expect(ф).toBeTruthy();
    expect(ф).not.toMatch(/\d/);
  });

  it('говорить нечего — молчим', () => {
    expect(подписьСвежести(null)).toBe(null);
  });
});

describe('подпись занятия', () => {
  /* Слова движка отдаём как есть: он один знает, чего не хватает. */
  it('заметку движка не пересказываем', () => {
    expect(подписьЗанятия({ вид: 'неНастроен', заметка: 'Не хватает: Код сенсора' }))
      .toBe('Не хватает: Код сенсора');
  });

  /* Движок такой прибор не поднимает вовсе — значит молчать о причине нельзя, даже
     когда он поленился прислать перечень. */
  it('заметки нет — всё равно не молчим', () => {
    expect(подписьЗанятия({ вид: 'неНастроен', заметка: null })).toBeTruthy();
  });
});

/* ЗВЕНО ЦЕПОЧКИ — СЛОВАМИ (#324, переехало из domain/nearby.test.ts вслед за функцией).

   Состояние считает домен, называет его этот слой, и проверять их надо порознь: тест, сверяющий
   расчёт вместе с буквами, ломается от правки слова — а правка слова тут бывает чаще правки
   расчёта. */
describe('словоЦепочки', () => {
  it('мост молчит — называем мост, потому что идти надо к нему', () => {
    expect(словоЦепочки('мост молчит', 'OrangeLink')).toBe('«OrangeLink» не на связи');
    expect(словоЦепочки('мост молчит', null)).toBe('мост не на связи');
  });

  it('мост жив, а прибор нет — это другое действие и другие слова', () => {
    expect(словоЦепочки('устройство молчит', 'OrangeLink')).toBe('мост на связи, устройство не отвечает');
  });

  it('всё живо — называем, через что идут данные', () => {
    expect(словоЦепочки('на связи', 'OrangeLink')).toBe('на связи через «OrangeLink»');
    expect(словоЦепочки('на связи', null)).toBe('на связи через мост');
  });
});
