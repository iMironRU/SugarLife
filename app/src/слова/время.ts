/* Как называется время (#408).

   Двенадцать мест форматировали дату руками, каждое по-своему, — и разошлись ровно так,
   как расходятся два списка одного и того же. В журнале приёмов день назывался «сегодня»
   и «19 авг», в истории — «Сегодня» и «19 августа»; время приёма собиралось строкой без
   ведущего нуля, и «09:05» превращалось в «9:05» — на соседних экранах одно и то же
   событие выглядело по-разному.

   Формат даты — это формулировка, а не вычисление: она отвечает на вопрос «как сказать»,
   а не «что произошло». Поэтому живёт здесь, вместе с остальными словами.

   Локаль пишем одну — 'ru'. Раньше в коде встречались и 'ru', и 'ru-RU': результат тот
   же, но два написания одного намерения — это два намерения через год. */
const ЛОКАЛЬ = 'ru';

/** 09:05 — всегда с ведущим нулём. */
export const часы = (t: number): string =>
  new Date(t).toLocaleTimeString(ЛОКАЛЬ, { hour: '2-digit', minute: '2-digit' });

/** 09:05:31 — для журнала обмена, где секунды и есть содержание. */
export const часыСек = (t: number): string =>
  new Date(t).toLocaleTimeString(ЛОКАЛЬ, { hour: '2-digit', minute: '2-digit', second: '2-digit' });

/** 19 августа */
export const деньМесяц = (t: number): string =>
  new Date(t).toLocaleDateString(ЛОКАЛЬ, { day: 'numeric', month: 'long' });

/** 19 авг — там, где строка тесная. */
export const деньМесяцКоротко = (t: number): string =>
  new Date(t).toLocaleDateString(ЛОКАЛЬ, { day: 'numeric', month: 'short' });

/** 19 августа 2026 г. — год нужен там, где смотрят на прошлые годы (анализы, осмотры). */
export const датаПолная = (t: number): string =>
  new Date(t).toLocaleDateString(ЛОКАЛЬ, { day: 'numeric', month: 'long', year: 'numeric' });

/** 19 авг, 18:30 */
export const датаИВремя = (t: number): string =>
  new Date(t).toLocaleString(ЛОКАЛЬ, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });

/* «Сегодня» / «Вчера» / дата.

   Границу считаем по КАЛЕНДАРНЫМ суткам, а не по «прошло 24 часа»: в час ночи вчерашний
   ужин был вчера, хотя прошло six часов. Раньше в одном месте так и было — сравнение
   разницы в миллисекундах, — и после полуночи оно называло вчерашним то, что случилось
   сегодня утром. */
export function имяДня(t: number, { заглавно = false, коротко = false } = {}): string {
  const д = new Date(t); д.setHours(0, 0, 0, 0);
  const сегодня = new Date(); сегодня.setHours(0, 0, 0, 0);
  const дней = Math.round((сегодня.getTime() - д.getTime()) / 86400e3);
  if (дней === 0) return заглавно ? 'Сегодня' : 'сегодня';
  if (дней === 1) return заглавно ? 'Вчера' : 'вчера';
  return коротко ? деньМесяцКоротко(t) : деньМесяц(t);
}

/* Сколько назад. «только что» вместо «0 мин назад»: ноль человек читает как поломку
   счётчика, а не как «прямо сейчас». */
export function сколькоНазад(t: number, сейчас = Date.now()): string {
  const м = Math.max(0, Math.round((сейчас - t) / 60000));
  if (м < 1) return 'только что';
  if (м < 60) return `${м} мин назад`;
  return `${Math.floor(м / 60)} ч назад`;
}

/* Длительность в днях → «1 д 18 ч». Дробные дни («≈ 1,8 дн») человеку приходится
   пересчитывать в уме, а решение принимается именно в часах: хватит ли до утра, доживу
   ли до замены. Часы округляем вниз: «осталось не меньше», а не наоборот. */
export function дниЧасы(дней: number): string {
  const всегоЧ = Math.max(0, Math.floor(дней * 24));
  const д = Math.floor(всегоЧ / 24);
  const ч = всегоЧ % 24;
  if (д === 0) return `${ч} ч`;
  if (ч === 0) return `${д} д`;
  return `${д} д ${ч} ч`;
}

/* Длительность, а не момент. «данных нет 7 мин назад» — не по-русски и не про то:
   вопрос не «когда было последнее», а «сколько уже нет». Поэтому своё слово, а не
   сколькоНазад, который отвечает на первый вопрос. */
export function сколькоНет(мс: number): string {
  const м = Math.max(0, Math.round(мс / 60000));
  if (м < 60) return `${м} мин`;
  return `${Math.floor(м / 60)} ч`;
}
