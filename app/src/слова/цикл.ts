import type { ПочемуНеЗнаем, ЗначениеЦикла } from '@/domain/loopValue';

/* ПОЧЕМУ ПРО ИНСУЛИН НЕИЗВЕСТНО — СЛОВАМИ (#324, переехало из domain/loopValue.ts).

   Правило остаётся в домене, и оно важное: «нет инсулина» и «неизвестно, сколько инсулина» —
   разные вещи, и показать пусто значит сказать «активного инсулина нет». Это неправда, и это
   ровно та неправда, из-за которой человек может уколоть лишнего.

   Здесь только произношение. Срок у «молчит» собирается тут же: он часть фразы, а не часть
   правила — правило знает миллисекунды, человек читает «40 мин». */

const СЛОВА: Record<ПочемуНеЗнаем, string> = {
  'нет расчёта': 'цикл не присылал расчёт',
  'молчит': 'цикл молчит',
  'нет значения': 'цикл не прислал это значение',
};

function срок(мс: number): string {
  const м = Math.round(мс / 60000);
  if (м < 60) return м + ' мин';
  const ч = Math.floor(м / 60);
  return ч < 24 ? ч + ' ч' : Math.floor(ч / 24) + ' д';
}

/** Подпись рядом с прочерком. null — верить можно, объяснять нечего. */
export function почемуНеЗнаем(з: ЗначениеЦикла): string | null {
  if (!з.почему) return null;
  const слово = СЛОВА[з.почему];
  return з.почему === 'молчит' && з.молчитМс != null ? `${слово} ${срок(з.молчитМс)}` : слово;
}
