import { describe, it, expect } from 'vitest';
import { подписьФона } from './длинный';

const час = 3600e3;
const т = new Date(2026, 7, 18, 12, 0, 0).getTime();

/* Обещание, ради которого эта подпись написана так: срок действия мы не выдумываем (#287). */
describe('подпись длинного инсулина', () => {
  it('срок известен — называем его', () => {
    expect(подписьФона({ ед: 24, когдаМс: т, доМс: т + час, действует: true })).toMatch(/примерно до/);
  });

  it('срок вышел — говорим прямо, а не «до»', () => {
    expect(подписьФона({ ед: 24, когдаМс: т, доМс: т - час, действует: false })).toMatch(/закончилось/);
  });

  /* Закончившийся не прячем, но и не выдаём за действующий: «был вчера в 22:10» это ответ, а
     молчание — нет. Человек на ручках приходит именно с вопросом «я вообще колол?». */
  it('срока нет — про срок ни слова, но доза названа', () => {
    const с = подписьФона({ ед: 24, когдаМс: т, доМс: null, действует: null });
    expect(с).not.toMatch(/до |закончилось/);
    expect(с).toMatch(/24 ед/);
  });
});
