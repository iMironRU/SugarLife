import { describe, it, expect } from 'vitest';
import { часы, имяДня, сколькоНазад, дниЧасы } from './время';

/* Проверяем то, из-за чего задача и завелась: одинаковые по смыслу строки собирались
   в разных местах по-разному и молча расходились. */

describe('время', () => {
  /* «9:05» и «09:05» на соседних экранах — одно и то же событие выглядит разным. */
  it('часы всегда с ведущим нулём', () => {
    const д = new Date(2026, 7, 19, 9, 5);
    expect(часы(д.getTime())).toBe('09:05');
  });
});

describe('имя дня', () => {
  const в = (сдвигДней: number, ч = 12) => {
    const д = new Date(); д.setHours(ч, 0, 0, 0); д.setDate(д.getDate() - сдвигДней);
    return д.getTime();
  };

  it('сегодня и вчера — словами', () => {
    expect(имяДня(в(0))).toBe('сегодня');
    expect(имяДня(в(1))).toBe('вчера');
  });

  /* Заголовку раздела нужна заглавная, строке внутри — строчная. Разные написания
     одного слова в приложении уже жили порознь и разошлись. */
  it('заглавная — по просьбе, а не по месту вызова', () => {
    expect(имяДня(в(0), { заглавно: true })).toBe('Сегодня');
  });

  /* Граница — календарные сутки, а не «прошло 24 часа»: в час ночи вчерашний ужин был
     вчера, хотя прошло шесть часов. */
  it('граница по суткам, а не по прошедшим часам', () => {
    const вчераПоздно = new Date(); вчераПоздно.setDate(вчераПоздно.getDate() - 1); вчераПоздно.setHours(23, 30, 0, 0);
    expect(имяДня(вчераПоздно.getTime())).toBe('вчера');
  });

  it('давнее — датой', () => {
    expect(имяДня(в(5))).toMatch(/\d+ /);
    expect(имяДня(в(5), { коротко: true }).length).toBeLessThanOrEqual(имяДня(в(5)).length);
  });
});

describe('сколько назад и длительность', () => {
  it('ноль минут — «только что», а не «0 мин назад»', () => {
    expect(сколькоНазад(1000, 1000)).toBe('только что');
  });
  it('минуты и часы', () => {
    expect(сколькоНазад(0, 7 * 60_000)).toBe('7 мин назад');
    expect(сколькоНазад(0, 125 * 60_000)).toBe('2 ч назад');
  });
  /* Часы вниз: «осталось не меньше», а не наоборот — по этой строке решают, доживёт ли
     резервуар до утра. */
  it('дни и часы, часы вниз', () => {
    expect(дниЧасы(1.9)).toBe('1 д 21 ч');
    expect(дниЧасы(0.5)).toBe('12 ч');
    expect(дниЧасы(2)).toBe('2 д');
  });
});
