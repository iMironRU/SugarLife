import type { Цель, Ход } from '@/domain/connectAttempt';

/* Слова про попытку подключиться или отпустить прибор (SugarLife#324).

   Правило — сколько ждать и чем кончилось — в домене. Здесь только речь.

   ПОЧЕМУ БЕЗ ВЫДУМОК О ПРИЧИНЕ. Назвать одну причину мы не можем: движок различает
   «занят другим телефоном» лишь как догадку, а «далеко» не знает вовсе. Поэтому
   перечисляем то, что человек может проверить сам, и в порядке вероятности для прибора
   за мостом. */

/** Короткое слово в строке списка. Пусто — показывать нечего. */
export function словоОжидания(состояние: { цель: Цель; ход: Ход } | null): string | null {
  if (!состояние) return null;
  const { цель, ход } = состояние;
  if (ход === 'не ответил') return цель === 'связь' ? 'не ответил' : 'не отпустился';
  return цель === 'связь' ? 'подключаюсь…' : 'отпускаю…';
}

/** Объяснение под строкой, когда прибор так и не ответил. */
export function почемуМолчит(цель: Цель): string {
  return цель === 'связь'
    ? 'Прибор не ответил. Так бывает: он спит между обменами, лежит далеко или занят другим телефоном. Можно попробовать ещё раз.'
    : 'Прибор не отпустился. Попробуйте ещё раз — связь могла быть занята обменом.';
}
