import { describe, it, expect } from 'vitest';
import { падениеСловами, сводкаСловами } from './падения';

describe('слова разбора падений', () => {
  it('строка называет начало и срок', () => {
    const с = падениеСловами({ ключ: 'к', когдаМс: 0, минут: 25, сНачала: 10.6, спал: false });
    expect(с.главное).toBe('с 10,6 · 25 мин');
    expect(с.подпись).toBe('');
  });

  /* «Не спал» — не новость, а лишняя строка в каждой записи. */
  it('про сон говорим, только когда он был', () => {
    expect(падениеСловами({ ключ: 'к', когдаМс: 0, минут: 9, сНачала: 8, спал: true }).подпись).toBe('во сне');
  });

  it('идущее сейчас называем состоянием, а не числом', () => {
    expect(падениеСловами({ ключ: 'к', когдаМс: 0, минут: null, сНачала: 9, спал: false }).главное)
      .toContain('идёт сейчас');
  });

  it('без числа в начале не выдумываем его', () => {
    expect(падениеСловами({ ключ: 'к', когдаМс: 0, минут: 5, сНачала: null, спал: false }).главное)
      .toBe('начало неизвестно · 5 мин');
  });

  describe('свод', () => {
    it('ничего не было — фразы нет, а не «0 спусков»', () => {
      expect(сводкаСловами({ всего: 0, ночью: 0, медианаМинут: null, суток: 14 })).toBeNull();
    });

    it('число на окно, а не в среднем в день', () => {
      const ф = сводкаСловами({ всего: 12, ночью: 3, медианаМинут: 22, суток: 14 })!;
      expect(ф).toContain('12 спусков за 14 дн.');
      expect(ф).toContain('во сне 3');
      expect(ф).toContain('22 мин');
      /* Дробь вроде «0,9 в сутки» человек не проверяет и не запоминает. */
      expect(ф).not.toMatch(/в сутки|в день/);
    });

    it('склонение не спотыкается', () => {
      const ф = (n: number) => сводкаСловами({ всего: n, ночью: 0, медианаМинут: null, суток: 14 })!;
      expect(ф(1)).toContain('1 спуск ');
      expect(ф(2)).toContain('2 спуска ');
      expect(ф(5)).toContain('5 спусков ');
      expect(ф(11)).toContain('11 спусков ');
      expect(ф(21)).toContain('21 спуск ');
    });

    /* Лента отвечает на «что было», а не «хорошо ли это». */
    it('ни одна фраза не оценивает', () => {
      const ф = сводкаСловами({ всего: 30, ночью: 20, медианаМинут: 40, суток: 14 })!;
      expect(ф).not.toMatch(/часто|многовато|тревож|стоит|плохо|опасн/i);
    });
  });
});
