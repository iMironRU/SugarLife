import { describe, it, expect } from 'vitest';
import { почемуНеЗнаем } from './цикл';

describe('почему про инсулин неизвестно — словами', () => {
  it('верим — объяснять нечего', () => {
    expect(почемуНеЗнаем({ known: true, почему: null })).toBeNull();
  });

  it('три причины звучат по-разному: они ведут в разные места', () => {
    expect(почемуНеЗнаем({ known: false, почему: 'нет расчёта' })).toBe('цикл не присылал расчёт');
    expect(почемуНеЗнаем({ known: false, почему: 'нет значения' })).toBe('цикл не прислал это значение');
  });

  it('срок молчания читается по-человечески', () => {
    const м = (мс: number) => почемуНеЗнаем({ known: false, почему: 'молчит', молчитМс: мс });
    expect(м(40 * 60e3)).toBe('цикл молчит 40 мин');
    expect(м(3 * 3600e3)).toBe('цикл молчит 3 ч');
    expect(м(50 * 3600e3)).toBe('цикл молчит 2 д');
  });

  /* Срока нет — говорим без него, а не пишем «цикл молчит undefined». */
  it('без срока фраза остаётся целой', () => {
    expect(почемуНеЗнаем({ known: false, почему: 'молчит' })).toBe('цикл молчит');
  });
});
