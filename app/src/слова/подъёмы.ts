import type { Причина } from '@/domain/причиныПодъёма';

/* ЧЕМ ОБЪЯСНИТЬ ПОДЪЁМ — СЛОВАМИ (#167, переехало из домена в #324).

   Домен держит перечень возможностей и правила поиска отметки; как каждая из них называется —
   здесь. Причина простая: формулировки правятся чаще правил, а тест, сверяющий расчёт вместе с
   буквами, ломается от правки буквы и не ловит ни одной ошибки расчёта.

   ПРИЧИНЫ — СПИСОК ВОЗМОЖНОСТЕЙ, А НЕ ОБВИНЕНИЙ. Ни одна формулировка здесь не говорит «ты забыл»
   или «ты не сделал». Человек с хроническим диагнозом и так живёт с чувством вины за каждое
   число; приложение не должно его добавлять. Это правило про СЛОВА, и теперь оно живёт там, где
   слова, — раньше его приходилось помнить, читая файл про поиск отметок.

   «НЕ ЗНАЮ» — ПОЛНОЦЕННЫЙ ОТВЕТ, и он есть в списке намеренно. Без него человек выберет любую
   причину, лишь бы убрать строку с глаз, — и данные станут хуже, чем пустые: не «неизвестно», а
   «неправда». Врач, читающий «канюля ×3», должен видеть настоящие три канюли, а не три нажатия
   ради тишины. */

export interface ВидПричины {
  ключ: Причина;
  /** Как её называет человек, когда выбирает. */
  выбор: string;
  /** Как она читается в списке и в записке врачу. */
  метка: string;
  /** Короткое пояснение — почему это вообще вариант. */
  подпись?: string;
}

/* Словарь полон по типу: новая причина не соберётся, пока ей не написаны слова. Раньше полноту
   стерёг только порядок в массиве, и забытая причина молча получала бы «не знаю». */
const СЛОВА: Record<Причина, Omit<ВидПричины, 'ключ'>> = {
  еда: { выбор: 'Еда', метка: 'еда', подпись: 'запишем приём этим временем' },
  болюс: { выбор: 'Инсулина не хватило', метка: 'инсулин', подпись: 'болюс не сделан, сделан позже или меньше нужного' },
  канюля: { выбор: 'Канюля или набор', метка: 'канюля', подпись: 'отошла, перегнулась, плохо всасывает' },
  рассвет: { выбор: 'Утренний подъём', метка: 'рассветный феномен', подпись: 'сахар растёт сам под утро, без еды' },
  болезнь: { выбор: 'Болезнь или стресс', метка: 'болезнь или стресс', подпись: 'температура, воспаление, сильное волнение' },
  сенсор: { выбор: 'Похоже, врал сенсор', метка: 'сенсор', подпись: 'нагрелся, прижали во сне, первые часы после установки' },
  неизвестно: { выбор: 'Не знаю', метка: 'причина не найдена', подпись: 'честный ответ; лучше пустого или выдуманного' },
};

/* Порядок показа — решение этого слоя, а не домена: от него зависит только то, что человек
   увидит первым в списке. Полноту при этом всё равно сторожит тип: пропущенная причина не
   соберётся в `СЛОВА` выше.

   «Не знаю» стоит последним намеренно — он полноценный ответ, но не первый напрашивающийся. */
const ПОРЯДОК: readonly Причина[] = [
  'еда', 'болюс', 'канюля', 'рассвет', 'болезнь', 'сенсор', 'неизвестно',
];

export const ПРИЧИНЫ: ВидПричины[] = ПОРЯДОК.map((к) => ({ ключ: к, ...СЛОВА[к] }));

export const видПричины = (п: Причина): ВидПричины => ({ ключ: п, ...(СЛОВА[п] ?? СЛОВА.неизвестно) });
