/* КТО ВИНОВАТ В ЗАСТОЕ — В ДВА СЛОВА (SugarLife#721).

   Движок различает беды и присылает готовую фразу (`monitor.staleReason.words` и её короткую
   форму). Фраза живёт на «Сегодня», рядом с числом, — так просило ядро, и правильно просило:
   связь-то в порядке, а в разделе связи её читали бы как обрыв.

   Но есть место, куда фраза не помещается физически: строка состояния над кругом. Она видна на
   ВСЕХ экранах, она одна на приложение, и текст в ней обрезается многоточием — рядом заряды, и
   ужимается именно текст. «Встал загрузчик, который пишет в облако…» превращается там в
   «Встал загруз…», то есть в ничто.

   ПОЭТОМУ ЗДЕСЬ НЕ ПЕРЕСКАЗ, А ЯРЛЫК. Он отвечает на один вопрос — кого трясти, — и ответ нужен
   ровно потому, что два случая из четырёх НЕ ПРО ЭТОТ ТЕЛЕФОН. Человек, видя одинаковое «нет
   связи», шёл смахивать наше приложение, когда встал чужой телефон.

   СЛОВА БЕРЁМ ИЗ ИМЕНИ КОДА, А НЕ СОЧИНЯЕМ. `ЗагрузчикМолчит` → «загрузчик молчит»: это
   по-прежнему слово движка, просто в строчку. Так ярлык не может разойтись с фразой, которую
   человек прочтёт ниже, — а разойтись двум формулировкам об одном достаточно одного релиза.

   КОДЫ СВЕРЕНЫ С ЯДРОМ, А НЕ ВЫВЕДЕНЫ ПО ПАМЯТИ. Я записал их сюда кириллицей — по именам
   перечисления внутри движка (`ПочемуЧислаСтарые`), — и промахнулся: наружу выходит машинный код
   (`contract/ЗастойВОблаке.kt`, функция `код`). Ошибка не падает и не видна в тестах: ярлык просто
   не находится, и человек читает `cloud-uploader-down`. Поймала её проверка глазами в демо-мосте.

   НЕЗНАКОМЫЙ КОД ПОКАЗЫВАЕМ КАК ЕСТЬ. Список у движка открытый; пустота на месте новой беды
   читается как «всё хорошо», а код читается как «появилось что-то новое» — и это правда. */

const ЯРЛЫК: Record<string, string> = {
  /* Встал тот, кто пишет в облако. Обычно это ЧУЖОЙ телефон, и трясти надо не этот. */
  'cloud-uploader-down': 'загрузчик встал',
  /* Загрузчик пишет о себе, а показаний нет: сенсор потерян на ЕГО стороне. */
  'cloud-uploader-nosensor': 'сенсор потерян',
  /* Про загрузчик движок не знает — его отчёты из облака мы не читаем. Тогда говорим
     то единственное, что знаем и без него. */
  'cloud-stale': 'данные старые',
};

export function ярлыкЗастоя(код: string): string {
  return ЯРЛЫК[код] ?? код;
}

/* ЧЕЙ ЭТО ЗНАК. Значок отвечает на тот же вопрос, что и ярлык, и потому обязан меняться вместе с
   ним: перечёркнутое облако при вставшем загрузчике — такая же неправда, как «нет связи», только
   без слов. Облако-то отвечает.

   Возвращаем не картинку, а имя роли: набор значков — дело экрана, а не словаря. */
export type ЗнакЗастоя = 'чужойТелефон' | 'прибор' | 'старое';

/* ЧЕТВЁРТАЯ БЕДА НАКОНЕЦ РАЗЛИЧИМА (SugarLife#721, ядро SugarLifeCore#193).

   Полдня назад строка умела назвать три беды из четырёх: застой в облаке движок различал, а
   «сеть есть, до облака не достучались» наружу не выходило вовсе — только в журнал движка. Мы
   это и просили, и ядро отдало: теперь у беды прибора шесть кодов вместо одного общего.

   Для человека это разные беды с разными действиями, и одна подсказка на все означала, что
   трое из четверых чинят не то. Про VPN сказать было нельзя, хотя именно он у владельца и
   падал: сервер при этом отвечал с мака за 0,35 секунды.

   ЯРЛЫКИ — СЖАТЫЕ ЗАГОЛОВКИ ЯДРА, А НЕ НАШИ СЛОВА. «Интернет есть, а облако не отвечает» в
   строку не влезет, но «облако не отвечает» — это та же мысль их же словарём. Полная фраза с
   подсказкой про VPN приезжает в `problem.remediation` и показывается там, где есть место. */
const ЯРЛЫК_БЕДЫ: Record<string, string> = {
  'cloud.offline': 'связи нет',
  /* Та самая четвёртая. Заголовок ядра: «Интернет есть, а облако не отвечает». */
  'cloud.unreachable.online': 'облако не отвечает',
  'cloud.server.error': 'облако с ошибкой',
  'cloud.tls.failed': 'шифрование не встало',
  'cloud.unreachable': 'облако недоступно',
  'nightscout.auth.failed': 'доступ отклонён',
};

/** Ярлык беды прибора. Незнакомый код — не наше дело: молчим и отдаём прежний ответ строки. */
export function ярлыкБеды(код: string | null | undefined): string | null {
  return код ? ЯРЛЫК_БЕДЫ[код] ?? null : null;
}

/* ЗНАК У БЕДЫ СЕТИ — ПЕРЕЧЁРКНУТОЕ ОБЛАКО, И ЗДЕСЬ ОНО ЧЕСТНО.

   В застое оно врало: облако-то отвечало. А тут не отвечает именно облако — либо его не
   слышно, либо оно ответило не так. Один знак на всё семейство: различает их не картинка,
   а слова, и заводить шесть значков значило бы просить человека выучить словарь. */

export function знакЗастоя(код: string): ЗнакЗастоя {
  if (код === 'cloud-uploader-down') return 'чужойТелефон';
  if (код === 'cloud-uploader-nosensor') return 'прибор';
  return 'старое';
}
