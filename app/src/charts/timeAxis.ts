/* Подписи оси времени: сколько их и какие (SugarLife#157).

   Было: «23:10 23:15 23:20 … 00:05» — двенадцать подписей подряд, читается как забор.
   Ось времени нужна для одного — понять, где на графике «сейчас», а где «час назад»;
   для этого хватает трёх-четырёх опорных точек. Двенадцать решают эту задачу хуже, а
   не лучше: глазу не за что зацепиться, все одинаковые и все рядом. Точное время точки
   человек всё равно берёт не отсюда, а из списка измерений под графиком.

   Два правила, и оба про опору:

   1. Подписи стоят на КРУГЛЫХ временах (23:00, 23:30, 00:00), а не там, куда попала
      сетка. Круглое время — это то, что человек помнит про свой день («поел в семь»),
      а 23:07 не значит ничего.
   2. Сколько их — считаем от ширины, а не задаём числом. На узком телефоне влезает
      три, на широком шесть; фиксированное число либо переполнит первый, либо обеднит
      второй.

   Полночь подписываем датой: «00:00» ничем не отличается от «23:55», хотя это уже
   другой день, и на суточном окне это единственное место, где видно границу. */

/** Шаги подписей — от пяти минут до суток. Все делят час или сутки нацело, иначе
    «круглое время» перестанет быть круглым: 25 минут ничем не лучше 23:07. */
const ШАГИ_МИН = [5, 10, 15, 20, 30, 60, 120, 180, 360, 720, 1440];

/** Сколько пикселей отводим одной подписи вместе с воздухом вокруг. */
const МЕСТО_НА_ПОДПИСЬ = 64;

const МЕСЯЦЫ = ['янв', 'фев', 'мар', 'апр', 'мая', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек'];

/* Шаг подписей под окно и ширину. Берём наименьший из «круглых», при котором подписи
   ещё не сталкиваются: крупнее — потеряем опору, мельче — вернём забор. */
export function шагПодписей(окноМс: number, ширинаPx: number): number {
  const сколько = Math.max(2, Math.min(7, Math.floor(ширинаPx / МЕСТО_НА_ПОДПИСЬ)));
  const идеал = окноМс / сколько;
  const шаг = ШАГИ_МИН.find((м) => м * 60_000 >= идеал) ?? ШАГИ_МИН[ШАГИ_МИН.length - 1];
  return шаг * 60_000;
}

/* Где именно стоят подписи. Округляем по МЕСТНОМУ времени, а не по UTC: круглое время
   — это круглое время на часах человека, и в поясе со смещением в полчаса «13:00» по
   UTC оказалось бы в 13:30 на экране. */
export function подписи(t0: number, t1: number, шагМс: number): number[] {
  const сдвиг = -new Date(t0).getTimezoneOffset() * 60_000;
  const первая = Math.ceil((t0 + сдвиг) / шагМс) * шагМс - сдвиг;
  const метки: number[] = [];
  for (let t = первая; t <= t1; t += шагМс) метки.push(t);
  return метки;
}

/* Что написано в подписи. Полночь — датой: на суточном и недельном окне это
   единственная граница, которую видно, а «00:00» рядом с «23:55» её не показывает. */
export function подписьВремени(t: number, шагМс: number): string {
  const d = new Date(t);
  const полночь = d.getHours() === 0 && d.getMinutes() === 0;
  if (шагМс >= 24 * 3_600_000 || полночь) return `${d.getDate()} ${МЕСЯЦЫ[d.getMonth()]}`;
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
}

/* Готовые настройки оси — чтобы три графика не собирали их каждый по-своему: именно
   так и разъехались подписи, формат был скопирован, а прореживание нет. */
export function осьВремени(t0: number, t1: number, ширинаPx: number) {
  const шаг = шагПодписей(t1 - t0, ширинаPx);
  return {
    customValues: подписи(t0, t1, шаг),
    formatter: (v: number) => подписьВремени(v, шаг),
  };
}

/* Ширина области графика. Меряем от окна, а не от контейнера: график лежит в экране с
   известными полями, а замер контейнера потребовал бы кадра — на первом рендере его
   ещё нет, и подписи успели бы встать по неверной ширине. */
export function ширинаГрафика(поляГрафика: number): number {
  const окно = typeof window === 'undefined' ? 380 : window.innerWidth;
  return Math.max(180, окно - 2 * 18 - поляГрафика);
}
