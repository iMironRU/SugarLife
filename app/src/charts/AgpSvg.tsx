import { LOW, HIGH, отрезки, type AgpPoint } from '@/domain/agp';
import { gluValue, unitLabel, useUnit } from '@/domain/units';
import { размерПодписи } from './cssVar';

/* Типовой день (AGP) — картинкой, без библиотеки графиков (SugarLife#156).

   В «Метриках» тот же график рисует ECharts, и там это правильно: холст, зум, подсказки
   по касанию. В записке он не годится по одной причине — записку ПЕЧАТАЮТ. Печать
   браузера холст отдаёт как получится, а лист у нас чёрно-белый и в миллиметрах, тогда
   как холст меряется пикселями экрана телефона.

   SVG печатается тем же движком, что и текст: масштабируется под лист, не размывается и
   не требует второго экземпляра библиотеки в памяти ради четырёх раз в год.

   ЧИСЛА ТЕ ЖЕ. Перцентили считает `agp()` из домена — тот же вызов, что у экранного
   графика. Своей арифметики здесь нет: две ветки одних и тех же цифр разъезжаются, и
   врач получил бы картинку, которой человек на экране не видел.

   ЧТО ИМЕННО РИСУЕМ. Коридор 5–95 — где сахар бывал, коридор 25–75 — где он был
   обычно, медиана — типовой день. Это стандартная раскладка AGP: врач читает её
   годами и ищет глазами привычное. */

/* Разрыв рисуем разрывом. `agp()` выбрасывает получасовые корзины, в которых показаний
   не было; соединить их линией значит нарисовать сахар, которого никто не измерял, —
   ровно в тех местах, где сенсор молчал. */
const ШАГ_РАЗРЫВА = 1.01;

const Ш = 320, В = 132;
const ПОЛЕ = { слева: 26, справа: 6, сверху: 8, снизу: 16 };

export default function AgpSvg({ точки, подпись = true }: {
  точки: AgpPoint[]; подпись?: boolean;
}) {
  const unit = useUnit();
  const g = (mmol: number) => gluValue(mmol, unit);
  if (!точки.length) return null;

  const верхМмоль = Math.max(15, Math.ceil(Math.max(...точки.map((p) => p.p95)) + 1));
  const yМин = g(2), yМакс = g(верхМмоль);
  const x = (ч: number) => ПОЛЕ.слева + (ч / 24) * (Ш - ПОЛЕ.слева - ПОЛЕ.справа);
  const y = (мм: number) => {
    const v = g(мм);
    return ПОЛЕ.сверху + (1 - (v - yМин) / (yМакс - yМин)) * (В - ПОЛЕ.сверху - ПОЛЕ.снизу);
  };

  /* Отрезки без разрывов: каждая непрерывная цепочка корзин рисуется отдельно
     (правило и его граница — в domain/agp.ts, там же тест). */
  const куски = отрезки(точки, ШАГ_РАЗРЫВА);

  const лента = (кусок: AgpPoint[], низ: (p: AgpPoint) => number, верх: (p: AgpPoint) => number) =>
    [...кусок.map((p) => `${x(p.t).toFixed(1)},${y(верх(p)).toFixed(1)}`),
     ...[...кусок].reverse().map((p) => `${x(p.t).toFixed(1)},${y(низ(p)).toFixed(1)}`)].join(' ');

  const линия = (кусок: AgpPoint[]) =>
    кусок.map((p) => `${x(p.t).toFixed(1)},${y(p.p50).toFixed(1)}`).join(' ');

  /* Подписи слышат системный крупный шрифт тем же пересчётом, что и оси остальных
     графиков: внутри viewBox это единицы рисунка, и CSS с его rem сюда не достаёт. */
  const кегль = размерПодписи(9);
  const часы = [0, 6, 12, 18, 24];
  const метки = [LOW, HIGH].filter((v) => g(v) > yМин && g(v) < yМакс);

  return (
    <svg className="agp-svg" viewBox={`0 0 ${Ш} ${В}`}
      role="img" aria-label="Типовой день: медиана и коридоры сахара по часам суток">
      {/* Целевой диапазон — фоном, а не двумя линиями: врач смотрит, сколько кривой в
          нём лежит, и полоса отвечает на это без пересчёта в уме. */}
      <rect className="agp-цель" x={x(0)} y={y(HIGH)} width={x(24) - x(0)} height={y(LOW) - y(HIGH)} />
      {куски.map((к, i) => (
        <g key={i}>
          <polygon className="agp-широкий" points={лента(к, (p) => p.p05, (p) => p.p95)} />
          <polygon className="agp-узкий" points={лента(к, (p) => p.p25, (p) => p.p75)} />
          {/* Одна корзина — линии не выйдет; точка честнее отрезка в никуда. */}
          {к.length > 1
            ? <polyline className="agp-медиана" points={линия(к)} />
            : <circle className="agp-медиана-точка" cx={x(к[0].t)} cy={y(к[0].p50)} r={1.6} />}
        </g>
      ))}
      {метки.map((v) => (
        <g key={v}>
          <line className="agp-порог" x1={x(0)} y1={y(v)} x2={x(24)} y2={y(v)} />
          <text className="agp-подпись" fontSize={кегль} x={ПОЛЕ.слева - 4} y={y(v) + 3} textAnchor="end">
            {unit === 'mgdl' ? Math.round(g(v)) : String(v).replace('.', ',')}
          </text>
        </g>
      ))}
      {часы.map((ч) => (
        <text key={ч} className="agp-подпись" fontSize={кегль} x={x(ч)} y={В - 4}
          textAnchor={ч === 0 ? 'start' : ч === 24 ? 'end' : 'middle'}>{ч}</text>
      ))}
      {подпись && (
        <text className="agp-подпись" fontSize={кегль} x={Ш - ПОЛЕ.справа} y={ПОЛЕ.сверху + 2} textAnchor="end">
          {unitLabel(unit)}
        </text>
      )}
    </svg>
  );
}
