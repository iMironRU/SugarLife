import { describe, it, expect } from 'vitest';
import { шагПодписей, подписи, подписьВремени, осьВремени } from './timeAxis';

/* Ось проверяем арифметикой, потому что глазами это ловится только на телефоне и
   только если посмотреть на все окна подряд: на часовом подписей было двенадцать, а на
   суточном их могло стать три штуки не на круглых временах — и то и другое выглядит
   «нормально», пока не начнёшь искать по ним время. */

const МИН = 60_000;
const ЧАС = 3_600_000;
// Времена строим местными, а не из строк: правило про круглое время — про часы
// человека, и тест обязан читать их так же.
const t = (д: number, ч: number, м = 0) => new Date(2026, 7, д, ч, м).getTime();

describe('шаг подписей', () => {
  it('часовое окно на телефоне — пятнадцать минут, а не каждая точка', () => {
    expect(шагПодписей(ЧАС, 340)).toBe(15 * МИН);
  });

  it('сутки на телефоне — часы, а не минуты', () => {
    expect(шагПодписей(24 * ЧАС, 340)).toBe(6 * ЧАС);
  });

  it('неделя — сутки', () => {
    expect(шагПодписей(7 * 24 * ЧАС, 340)).toBe(24 * ЧАС);
  });

  /* Ширина, а не число: на широком экране подписей должно стать больше, иначе мы
     обедняем его ради узкого. */
  it('шире экран — подписи чаще', () => {
    expect(шагПодписей(6 * ЧАС, 900)).toBeLessThan(шагПодписей(6 * ЧАС, 340));
  });

  it('очень узкая полоса — минимум две подписи, а не ноль', () => {
    expect(шагПодписей(3 * ЧАС, 60)).toBe(120 * МИН);
  });
});

describe('где стоят подписи', () => {
  it('на круглых временах, а не от края окна', () => {
    const метки = подписи(t(12, 23, 7), t(13, 0, 20), 30 * МИН);
    expect(метки.map((м) => подписьВремени(м, 30 * МИН)))
      .toEqual(['23:30', '13 авг']);
  });

  it('окно короче шага — подписей может не быть вовсе, и это лучше кривой', () => {
    expect(подписи(t(12, 23, 1), t(12, 23, 9), 30 * МИН)).toEqual([]);
  });

  it('шаг ровно ложится в окно — первая подпись на границе', () => {
    const метки = подписи(t(12, 12, 0), t(12, 15, 0), ЧАС);
    expect(метки).toHaveLength(4);
    expect(подписьВремени(метки[0], ЧАС)).toBe('12:00');
  });
});

describe('что написано в подписи', () => {
  it('обычное время — часы и минуты', () => {
    expect(подписьВремени(t(12, 9, 5), 15 * МИН)).toBe('09:05');
  });

  /* Полночь — граница суток, и «00:00» её не показывает: рядом с «23:55» это просто
     ещё одно время. Дата отвечает на вопрос «какой это день» без второй строки. */
  it('полночь — датой', () => {
    expect(подписьВремени(t(13, 0, 0), 30 * МИН)).toBe('13 авг');
  });

  it('суточный шаг — всегда датой, даже если метка не в полночь', () => {
    expect(подписьВремени(t(13, 12, 0), 24 * ЧАС)).toBe('13 авг');
  });
});

describe('готовая ось', () => {
  it('на часовом окне телефона выходит три-четыре подписи, а не двенадцать', () => {
    const конец = t(12, 23, 58);
    const ось = осьВремени(конец - ЧАС, конец, 340);
    expect(ось.customValues.length).toBeGreaterThanOrEqual(3);
    expect(ось.customValues.length).toBeLessThanOrEqual(4);
    expect(ось.formatter(ось.customValues[0])).toMatch(/^\d\d:\d\d$/);
  });
});
