import type { ComponentType } from 'react';

/* Прогрев куска с echarts.

   Отдельным файлом от Chart.tsx не по вкусу: файл, который экспортирует и компонент,
   и функцию, теряет горячую перезагрузку — правка компонента перезагружает страницу
   целиком вместо подмены на месте.

   Зачем прогревать. echarts нужен трём вкладкам из пяти, то есть почти наверняка
   понадобится; вопрос только когда. Если ждать нажатия, переключение на вкладку с
   графиком показывает пустое место, которое заполняется вторым шагом. */

export type Модуль = { default: ComponentType<{ option: any; height: number }> };

let готовый: Модуль['default'] | null = null;
let поехало: Promise<unknown> | null = null;

export const прогретьГрафик = (): Promise<unknown> =>
  (поехало ??= import('./EChart').then((m: Модуль) => { готовый = m.default; }));

export const готовыйГрафик = (): Модуль['default'] | null => готовый;
