import { sendIntent } from '@/sources/bridge';
import { getDeviceConfig, подписатьсяНаНастройки } from './deviceConfig';

/*
 * ВЫБРАННЫЙ ИНСУЛИН УХОДИТ ДВИЖКУ (#674, ядро SugarLifeCore#201).
 *
 * Человек выбирает свой быстрый инсулин на карточке помпы, и до сих пор этот выбор НИКУДА НЕ
 * УХОДИЛ: он лежал в наших локальных настройках, а движок считал активный инсулин по умолчаниям —
 * пик 75 минут, длительность 5 часов.
 *
 * Цена не косметическая. У быстрых инсулинов кривые разные: у Fiasp пик 60–90 минут, у Humalog
 * 1–2 часа, у короткого человеческого 2–4. На активном инсулине стоит и число на экране, и
 * решение о дозе — то есть человек, выбравший свой инсулин, получал расчёт по чужому.
 *
 * КРИВУЮ ДЕРЖИТ ЯДРО, МЫ ШЛЁМ ИМЯ (вариант А, согласован в #674). Наш справочник хранит
 * человеческие диапазоны — «пик 2–4 ч»; выбор точки внутри диапазона решение медицинское, и
 * принимать его у нас некому. Отсюда и разделение: идентификатор наш, числа их.
 *
 * ЗАЧЕМ СЛАТЬ `null`. Человек может убрать выбор — тогда у движка не должно остаться прежнего
 * инсулина: расчёт по позавчерашнему выбору хуже расчёта по умолчанию, потому что выглядит
 * настроенным.
 *
 * Досылается при старте: выбрать инсулин могли когда угодно, а движку об этом не говорили ни разу.
 * Это ровно тот же случай, что был с единицами глюкозы (`domain/units.ts`), и найден он той же
 * узкой проверкой — «настройки, которые движок принимает, а мы не пишем».
 */

/** Что уже отправлено. Снимок приходит часто, а настройка меняется редко — молчим, пока не сменилась. */
let отданный: string | null | undefined;

export function отдатьИнсулинДвижку(): void {
  const id = getDeviceConfig().fastInsulinId;
  if (id === отданный) return;
  отданный = id;
  void sendIntent({ type: 'setConfig', patch: { 'insulin.type': id } });
}

/** Отправить сейчас и следить за сменой. Возвращает отписку. */
export function следитьЗаИнсулином(): () => void {
  отдатьИнсулинДвижку();
  return подписатьсяНаНастройки(отдатьИнсулинДвижку);
}

/** Только для тестов: забыть, что уже отправляли. */
export function забытьОтправленное(): void { отданный = undefined; }
