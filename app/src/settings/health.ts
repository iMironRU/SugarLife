import { useSyncExternalStore } from 'react';
import { прочитатьJson, записатьJson } from './storage';

/* Показатели, которые знает человек, а не приложение (SugarLife#156).

   Вес, давление, HbA1c и даты плановых проверок нам взять неоткуда: их не отдаёт ни
   помпа, ни сенсор, ни облако. При этом ровно это врач и записывает на приёме — и
   ровно этого не хватало записке к приёму.

   Отдельным разделом, а не анкетой перед печатью. Анкету пришлось бы заполнять заново
   каждый раз, а даты скринингов живут годами и нужны не только записке: по ним видно,
   что офтальмолог был четырнадцать месяцев назад при сроке в год.

   ЧТО МЫ С ЭТИМ НЕ ДЕЛАЕМ. Не считаем по ним ничего медицинского и не даём советов:
   давление и вес лежат как есть и попадают в записку как есть. Единственный вывод,
   который мы себе позволяем, — календарный: срок из рекомендаций против даты. */

export interface Замер { значение: number; когда: number }
export interface Давление { верх: number; низ: number; когда: number }

export interface Здоровье {
  вес?: Замер | null;
  hba1c?: Замер | null;
  давление?: Давление | null;
  /** id проверки → когда делали в последний раз. */
  проверки: Record<string, number>;
  /** Когда поставили диагноз — от него считаются сроки, начинающиеся «через 5 лет». */
  дебют?: number | null;
  /* Какой набор целей НМГ применяется. В рекомендациях их два, и выбирает не
     приложение: цели индивидуальны и назначаются врачом (domain/visitNote.ts). */
  цели?: 'обычные' | 'мягкие';
}

const КЛЮЧ = 'sl.health.v1';
const ПУСТО: Здоровье = { проверки: {} };

let состояние: Здоровье = загрузить();
const слушатели = new Set<() => void>();

function загрузить(): Здоровье {
  const v = прочитатьJson<Здоровье>(КЛЮЧ, ПУСТО);
  return { ...ПУСТО, ...v, проверки: { ...(v.проверки ?? {}) } };
}

export function здоровье(): Здоровье { return состояние; }

export function записатьЗдоровье(правка: Partial<Здоровье>): void {
  состояние = { ...состояние, ...правка };
  записатьJson(КЛЮЧ, состояние);
  слушатели.forEach((f) => f());
}

/** Отметить, что проверку сделали. Дата — обычно сегодня, но бывает и задним числом. */
export function отметитьПроверку(id: string, когда: number): void {
  записатьЗдоровье({ проверки: { ...состояние.проверки, [id]: когда } });
}

/** Убрать отметку: человек ошибся датой или проверкой — стирать должно быть можно. */
export function забытьПроверку(id: string): void {
  const проверки = { ...состояние.проверки };
  delete проверки[id];
  записатьЗдоровье({ проверки });
}

export function useHealth(): Здоровье {
  return useSyncExternalStore(
    (f) => { слушатели.add(f); return () => { слушатели.delete(f); }; },
    () => состояние,
    () => состояние,
  );
}
