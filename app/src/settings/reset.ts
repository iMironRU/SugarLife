import { КЛЮЧИ, убрать } from './storage';

/* Полный сброс локальных данных.

   Списка ключей здесь больше нет — он один на приложение, в settings/storage.ts, и
   несёт назначение каждого ключа. Два списка неизбежно разошлись бы: добавляешь ключ
   ради переезда в движок, а про сброс забываешь — и он переживает «сбросить
   настройки». Именно так этот список уже трижды отставал от жизни.

   Что остаётся здесь — правило, а не перечисление: сброс убирает всё, что связано с
   человеком и его устройствами, и не трогает то, что помечено переживающим. Тема и
   единицы переживают намеренно: они про удобство и ничего о человеке не раскрывают. */

export const STORAGE_KEYS = КЛЮЧИ.filter((k) => !k.переживаетСброс).map((k) => k.key);
export const KEPT_KEYS = КЛЮЧИ.filter((k) => k.переживаетСброс).map((k) => k.key);

export function resetLocalData(): void {
  for (const k of STORAGE_KEYS) убрать(k);
  try { indexedDB.deleteDatabase('sugarlife'); } catch { /* ignore */ }
}

