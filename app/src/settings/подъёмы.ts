import { useSyncExternalStore } from 'react';
import { прочитатьJson, записатьJson } from './storage';
import { ДОПУСК_МС, type ОтметкаПодъёма, type Причина } from '@/domain/причиныПодъёма';

/* Чем человек объяснил подъём (#167).

   Хранится у нас, а не в движке, и наружу не уходит: это его слова о своей жизни, а не
   показания прибора. Врачу они попадают только в записке, которую он собирает сам.

   Держим месяц: записка к приёму смотрит на две недели, разбор — на две-четыре, и
   отметки старше просто некому читать. Ограничение по времени, а не по числу: сто
   отметок за неделю — это картина, и обрезать её посередине значило бы соврать в сводке. */
const КЛЮЧ = 'sl.rises.v1';
const ЖИЗНЬ_МС = 31 * 24 * 3600e3;

let список: ОтметкаПодъёма[] | null = null;
const subs = new Set<() => void>();

function загрузить(): ОтметкаПодъёма[] {
  if (!список) список = прочитатьJson<ОтметкаПодъёма[]>(КЛЮЧ, []);
  return список;
}

export function отметитьПодъём(at: number, причина: Причина): void {
  const сейчас = Date.now();
  /* Отметка на тот же подъём заменяет прежнюю, а не ложится второй: человек передумал —
     это одно событие с уточнённым ответом, а не два разных. */
  const без = загрузить().filter((о) => Math.abs(о.at - at) > ДОПУСК_МС);
  список = [...без, { at, причина, когдаМс: сейчас }]
    .filter((о) => сейчас - о.at <= ЖИЗНЬ_МС)
    .sort((a, b) => b.at - a.at);
  записатьJson(КЛЮЧ, список);
  subs.forEach((f) => f());
}

export function убратьОтметку(at: number): void {
  список = загрузить().filter((о) => Math.abs(о.at - at) > ДОПУСК_МС);
  записатьJson(КЛЮЧ, список);
  subs.forEach((f) => f());
}

export function отметкиПодъёмов(): ОтметкаПодъёма[] { return загрузить(); }

export function useОтметкиПодъёмов(): ОтметкаПодъёма[] {
  return useSyncExternalStore(
    (cb) => { subs.add(cb); return () => { subs.delete(cb); }; },
    загрузить, загрузить,
  );
}
