import { useSyncExternalStore } from 'react';
import { прочитатьJson, записатьJson } from './storage';

/* Что из находок разбора человек уже видел (SugarLife#148).

   Счётчик на входе в аналитику должен отвечать на вопрос «есть ли там что-то, ради
   чего стоит зайти СЕЙЧАС». Простое число важных находок на этот вопрос не отвечает:
   «канюля четвёртый день» — правда, но она была правдой и вчера, и позавчера.
   Постоянная цифра на кнопке через неделю означает ровно ноль — человек перестаёт её
   видеть, и когда там появится настоящая беда, он не заметит разницы.

   Поэтому считаем непрочитанное: находки, которых не было в списке, когда он в
   последний раз открывал разбор. Зашёл — всё текущее стало прочитанным.

   Храним идентификаторы, а не время визита. Время не различает «находка старая» и
   «находка новая, но появилась до визита»: разбор пересчитывается раз в час, и
   находка, возникшая за минуту до захода, по времени выглядела бы новой. */

const KEY = 'sl.seen.insights.v1';
const ПАМЯТЬ = 200; // идентификаторов; больше не бывает даже близко, но пусть не растёт вечно

let state: string[] = прочитатьJson<string[]>(KEY, []);
const subs = new Set<() => void>();

export function useSeenInsights(): string[] {
  return useSyncExternalStore(
    (cb) => { subs.add(cb); return () => { subs.delete(cb); }; },
    () => state, () => state,
  );
}

/* Отметить прочитанным то, что сейчас на экране.

   Именно текущие, а не «все когда-либо»: находка, которая исчезла и вернулась через
   месяц, — это новый повод зайти, а не старый, о котором уже знали. */
export function отметитьПрочитанными(ids: string[]): void {
  const было = new Set(state);
  if (ids.every((id) => было.has(id))) return; // ничего нового — не будим подписчиков
  state = [...new Set([...state, ...ids])].slice(-ПАМЯТЬ);
  записатьJson(KEY, state);
  subs.forEach((f) => f());
}
