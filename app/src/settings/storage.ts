/* Доступ к хранилищу в одном месте.

   localStorage бросает: в приватном режиме Safari, при переполнении квоты, при
   запрете сторонних данных. Раньше try/catch был в каждом модуле — восемнадцать
   копий одной обработки, и в паре мест его не было вовсе. Здесь он один. */
export function прочитать(key: string): string | null {
  try { return localStorage.getItem(key); } catch { return null; }
}

export function записать(key: string, value: string): void {
  try { localStorage.setItem(key, value); } catch { /* приватный режим, квота — переживём */ }
}

export function убрать(key: string): void {
  try { localStorage.removeItem(key); } catch { /* ignore */ }
}

/** Прочитать JSON. Битое значение — не повод падать: возвращаем запасное. */
export function прочитатьJson<T>(key: string, запасное: T): T {
  const raw = прочитать(key);
  if (raw == null) return запасное;
  try { return JSON.parse(raw) as T; } catch { return запасное; }
}

export function записатьJson(key: string, value: unknown): void {
  try { записать(key, JSON.stringify(value)); } catch { /* несериализуемое — не наш случай */ }
}

/* Что отдать движку при переезде (SugarLifeCore#28).

   Отдаём СЫРЫЕ строки, как лежат: разбирать их должен тот, кто будет раскладывать
   по полям контракта, а он ещё обсуждается. Пустые ключи не отдаём — иначе импорт,
   который «доливает только пустые места», получит пустую строку вместо отсутствия
   и решит, что место занято. */
export function кПереносу(куда: Перенос): Record<string, string> {
  const итог: Record<string, string> = {};
  for (const k of КЛЮЧИ) {
    if (k.перенос !== куда) continue;
    const v = прочитать(k.key);
    if (v != null && v !== '') итог[k.key] = v;
  }
  return итог;
}
