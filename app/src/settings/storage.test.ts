import { describe, it, expect } from 'vitest';
import { КЛЮЧИ } from './storage';
import { STORAGE_KEYS, KEPT_KEYS } from './reset';

/* Таблица ключей — то место, откуда однажды поедет вся конфигурация в движок
   (SugarLifeCore#28). Ошибка в ней не видна на экране: ключ просто не уедет, и
   человек узнает об этом после переустановки, когда настройка не вернётся. */

describe('таблица ключей хранилища', () => {
  it('ключи не повторяются', () => {
    const все = КЛЮЧИ.map((k) => k.key);
    expect(все.length).toBe(new Set(все).size);
  });

  it('каждый ключ назван по нашему префиксу', () => {
    const чужие = КЛЮЧИ.filter((k) => !/^sl[.-]/.test(k.key)).map((k) => k.key);
    expect(чужие).toEqual([]);
  });

  /* Кэш и техфлаг переносить некуда по определению: первый восстановим из сети,
     второй привязан к этой установке приложения. Если такой ключ помечен к
     переносу — это описка, и она уедет в движок молча. */
  it('кэши и флаги никуда не переезжают', () => {
    const странные = КЛЮЧИ.filter((k) => (k.вид === 'кэш' || k.вид === 'флаг') && k.перенос !== 'нет');
    expect(странные.map((k) => k.key)).toEqual([]);
  });

  /* Данные человека — события со временем. В конфиге они потеряют время события, а
     именно оно в них и есть весь смысл; плюс настройка размером в мегабайт поедет
     в каждом снимке. */
  it('замены и показания едут в историю, а не в настройки', () => {
    const вКонфиг = КЛЮЧИ.filter((k) => k.вид === 'данные' && k.перенос === 'config').map((k) => k.key);
    expect(вКонфиг).toEqual(['sl.mealnames.v1']); // имена приёмов — словарь, не события
  });

  it('сброс и сохраняемое выводятся из одной таблицы и не пересекаются', () => {
    expect(STORAGE_KEYS.length + KEPT_KEYS.length).toBe(КЛЮЧИ.length);
    expect(STORAGE_KEYS.filter((k) => KEPT_KEYS.includes(k))).toEqual([]);
  });

  /* Настройка, которую сброс не трогает, обязана быть безобидной: сброс отдаёт
     устройство другому человеку, и всё, что о прежнем что-то говорит, должно уйти. */
  it('переживают сброс только безобидные настройки', () => {
    expect([...KEPT_KEYS].sort()).toEqual(
      ['sl.analytics.v1', 'sl.carbunits', 'sl.install.v1', 'sl.theme', 'sl.units'].sort(),
    );
  });
});
