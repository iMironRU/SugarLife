import { useSyncExternalStore } from 'react';
import { прочитатьJson, записатьJson } from './storage';

/* Вопросы к приёму: что человек отметил и что дописал сам (SugarLife#156).

   Хранится отдельно от разбора и переживает перезапуск намеренно: список копится
   между приёмами. «Спросить про ночные гипо» приходит в голову за две недели до
   кабинета, а вылетает у двери — если список живёт только на открытом экране, он
   бесполезен ровно в тот момент, ради которого затевался.

   Отметки хранятся по id находки, а не по тексту вопроса: текст мы можем переписать
   при следующей правке формулировок, и тогда все отметки слетели бы разом. */

export interface Вопросы {
  /** id находок разбора, которые человек оставил в отчёте. */
  выбранные: string[];
  /** Свои формулировки — они и есть то, ради чего список редактируемый. */
  свои: string[];
  /* Нужен ли этот раздел вообще (SugarLife#267).

     Вопросы к приёму нужны не всем и не всегда: у одного приём через месяц, другой
     ходит к врачу с готовым списком в голове, третьему хватает цифр. Раздел из
     четырёх предложенных вопросов, который человеку не нужен, — не «лишняя мелочь», а
     половина экрана отчёта, которую он листает каждый раз.

     По умолчанию ВЫКЛЮЧЕНО. Отчёт открывают, чтобы посмотреть цифры, а вопросы — это
     отдельная работа: их обдумывают, а не пробегают глазами. Кому нужно, включит один
     раз, и с этого момента список копится между приёмами, как и раньше. */
  нужны?: boolean;
}

const КЛЮЧ = 'sl.visitq.v1';
const ПУСТО: Вопросы = { выбранные: [], свои: [], нужны: false };

let состояние: Вопросы = загрузить();
const слушатели = new Set<() => void>();

function загрузить(): Вопросы {
  const v = прочитатьJson<Вопросы>(КЛЮЧ, ПУСТО);
  /* У того, кто уже успел что-то отметить или дописать, раздел нужен по факту: гасить
     его при обновлении значило бы спрятать чужую работу. */
  const своё = (v.выбранные?.length ?? 0) + (v.свои?.length ?? 0) > 0;
  return { выбранные: v.выбранные ?? [], свои: v.свои ?? [], нужны: v.нужны ?? своё };
}

function сохранить(следующее: Вопросы): void {
  состояние = следующее;
  записатьJson(КЛЮЧ, состояние);
  слушатели.forEach((f) => f());
}

export function переключитьВопрос(id: string): void {
  const есть = состояние.выбранные.includes(id);
  сохранить({
    ...состояние,
    выбранные: есть ? состояние.выбранные.filter((x) => x !== id) : [...состояние.выбранные, id],
  });
}

export function добавитьВопрос(текст: string): void {
  const t = текст.trim();
  if (!t || состояние.свои.includes(t)) return;
  сохранить({ ...состояние, свои: [...состояние.свои, t] });
}

export function нужныЛиВопросы(нужны: boolean): void {
  сохранить({ ...состояние, нужны });
}

export function убратьСвой(индекс: number): void {
  сохранить({ ...состояние, свои: состояние.свои.filter((_, i) => i !== индекс) });
}

export function useVisitQuestions(): Вопросы {
  return useSyncExternalStore(
    (f) => { слушатели.add(f); return () => { слушатели.delete(f); }; },
    () => состояние,
    () => состояние,
  );
}
