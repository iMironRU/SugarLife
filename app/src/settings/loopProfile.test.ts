import { describe, it, expect } from 'vitest';
import { LOOP_LIMITS, outOfRec, уровеньРиска, сторонаРиска, type LoopLimit } from './loopProfile';

const предел = (id: string): LoopLimit => {
  const l = LOOP_LIMITS.find((x) => x.id === id);
  if (!l) throw new Error('нет предела ' + id);
  return l;
};

/* ШКАЛА РИСКА (#566). Проверяем на живых пределах, а не на выдуманных: смысл «жёлтого» и «красного»
   задают именно их числа, и подмена их фикстурой проверила бы только арифметику. */
describe('уровеньРиска', () => {
  it('внутри рекомендованного — норма, с какой стороны ни подходи', () => {
    const iob = предел('iob');            // 1…8, рекомендовано 4…6, хуже — вверх
    expect(уровеньРиска(iob, 4)).toBe('норма');
    expect(уровеньРиска(iob, 6)).toBe('норма');
    expect(уровеньРиска(iob, 1)).toBe('норма');   // ниже рекомендованного не опасно
  });

  it('через жёлтый к красному: полпути до предела — уже красный', () => {
    const iob = предел('iob');            // от recMax 6 до max 8, середина — 7
    expect(уровеньРиска(iob, 6.5)).toBe('край');
    expect(уровеньРиска(iob, 7)).toBe('предел');
    expect(уровеньРиска(iob, 8)).toBe('предел');
  });

  it('у предела «хуже вниз» шкала идёт в другую сторону', () => {
    const gap = предел('gap');            // 3…20, рекомендовано 5, below: true
    expect(сторонаРиска(gap)).toBe(-1);
    expect(уровеньРиска(gap, 20)).toBe('норма');  // реже микроболюсы — не риск
    expect(уровеньРиска(gap, 4.5)).toBe('край');
    expect(уровеньРиска(gap, 4)).toBe('предел');  // середина между 5 и 3
    expect(уровеньРиска(gap, 3)).toBe('предел');
  });

  it('сторона риска у каждого предела своя — цвет нельзя вешать на знак кнопки', () => {
    expect(сторонаРиска(предел('iob'))).toBe(1);
    expect(сторонаРиска(предел('msmb'))).toBe(1);
    expect(сторонаРиска(предел('gap'))).toBe(-1);
  });

  it('согласована с outOfRec: норма ровно там, где внутри рекомендованного', () => {
    for (const l of LOOP_LIMITS) {
      for (let v = l.min; v <= l.max + 1e-9; v += l.step) {
        expect(уровеньРиска(l, v) === 'норма').toBe(!outOfRec(l, v));
      }
    }
  });
});
