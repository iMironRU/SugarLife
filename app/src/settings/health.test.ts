import { describe, it, expect, vi, beforeEach } from 'vitest';

const отправлено: unknown[] = [];
vi.mock('@/sources/bridge', () => ({
  sendIntent: (i: unknown) => { отправлено.push(i); return Promise.resolve({ accepted: true }); },
}));

const { записатьЗдоровье, отдатьОкноСна } = await import('./health');

/* ОКНО СНА УХОДИТ ДВИЖКУ (#597).

   Настройка жила у нас с #280 и считала прогноз резервуара. Движок про неё не знал, и вся его
   модель сна — пороги строже во сне, ночной звук, вечерняя проверка — не работала ни разу.
   Между ними не хватало одной строки. */
describe('окно сна уходит движку', () => {
  beforeEach(() => { отправлено.length = 0; });

  it('заданное окно уезжает расписанием', () => {
    записатьЗдоровье({ режим: { отбой: '23:30', подъём: '07:15' } });
    expect(отправлено).toHaveLength(1);
    expect(отправлено[0]).toMatchObject({
      type: 'setConfig',
      patch: { 'sleep.from': '23:30', 'sleep.to': '07:15', 'sleep.source': 'schedule' },
    });
  });

  it('половина окна — не окно: источник не назначаем', () => {
    /* По одному краю движок не может сказать, спит человек или нет. Сказать «расписание есть»,
       когда его нет, — обещать защиту, которой не будет. */
    записатьЗдоровье({ режим: { отбой: '23:30', подъём: null } });
    expect(отправлено.at(-1)).toMatchObject({ patch: { 'sleep.source': null } });
  });

  it('стёртое окно стирается и у движка', () => {
    записатьЗдоровье({ режим: { отбой: '23:30', подъём: '07:15' } });
    отправлено.length = 0;
    записатьЗдоровье({ режим: { отбой: null, подъём: null } });
    expect(отправлено.at(-1)).toMatchObject({ patch: { 'sleep.from': null, 'sleep.to': null } });
  });

  it('правка не про режим движка не дёргает', () => {
    /* Иначе каждое «отметил проверку» слало бы движку одно и то же окно. */
    записатьЗдоровье({ цели: 'мягкие' });
    expect(отправлено).toHaveLength(0);
  });

  it('досыл при старте отправляет то, что уже задано', () => {
    записатьЗдоровье({ режим: { отбой: '00:10', подъём: '06:40' } });
    отправлено.length = 0;
    отдатьОкноСна();
    expect(отправлено.at(-1)).toMatchObject({ patch: { 'sleep.from': '00:10', 'sleep.to': '06:40' } });
  });
});
