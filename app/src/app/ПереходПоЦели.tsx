import { useEffect } from 'react';
import { слушатьЦель } from '@/показ/цельПерехода';
import { useStack } from '@/app/stackCtx';
import { setTab } from '@/app/nav';
import { ОхранаSection, DeviceSection } from '@/sections/lazy';

/* ПРИШЁЛ ИЗ УВЕДОМЛЕНИЯ — ПОПАЛ ТУДА, О ЧЁМ ОНО (SugarLife#524).

   Уведомление знает, о чём оно; приложение до сих пор об этом не узнавало и открывалось там, где
   человек был в прошлый раз. Ночью, спросонья, это означает поиск руками вместо ответа.

   ТРИ ПРАВИЛА, БЕЗ КОТОРЫХ ПЕРЕХОД ВРЕДЕН.

   1. Не выбрасывать человека из того, что он делает. Если открыта шторка (ввод еды, правка дозы) —
      переход ждёт: потерянный приём пищи дороже одного лишнего касания. То же правило, что у
      обновления приложения (#150).

   2. «Назад» возвращает туда, где был. Раздел кладётся ПОВЕРХ стека вкладки, а не заменяет его.

   3. Цель переживает холодный старт. Она копится в `цельПерехода` и приезжает сюда, когда экраны
      готовы, — иначе терялась бы ровно в самом важном случае: приложение выгрузили, и уведомление
      подняло его с нуля.

   Куда ведём — решает натив в момент показа уведомления: он знает, о какой тревоге речь. Здесь
   только исполнение, чтобы правило «куда вести» не разошлось между платформами. */
export default function ПереходПоЦели() {
  const { push, pop, depth } = useStack();

  useEffect(() => слушатьЦель((цель) => {
    /* Шторка открыта — значит человек что-то вводит. Ждём: цель вернётся к нам следующим
       событием, а прервать ввод нельзя. */
    if (document.querySelector('.модалка')) return;

    if (цель === 'сегодня') { setTab(2); return; }
    if (цель === 'охрана') {
      setTab(2);
      /* Открываем поверх того, что было: человек нажмёт «назад» и вернётся к своему экрану. */
      push(<ОхранаSection onClose={pop} />, { id: 'охрана' });
      return;
    }
    /* Приборы открываются по виду, а не по идентификатору: у раздела вход именно такой, и
       уведомление о резервуаре ведёт к помпе, о молчании — к сенсору. */
    if (цель === 'помпа') {
      setTab(2);
      push(<DeviceSection cat="pump" title="Помпа" onClose={pop} />,
        { id: 'категория', cat: 'pump', title: 'Помпа' });
      return;
    }
    if (цель === 'сенсор') {
      setTab(2);
      push(<DeviceSection cat="sensor" title="Сенсор" onClose={pop} />,
        { id: 'категория', cat: 'sensor', title: 'Сенсор' });
      return;
    }
    /* Незнакомая цель — просто «Сегодня». Новая цель от натива не должна ронять переход:
       лучше привести на главный экран, чем никуда. */
    setTab(2);
  }), [push, pop, depth]);

  return null;
}
