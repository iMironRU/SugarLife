/* Степень сворачивания верхней панели — одна непрерывная величина 0…1.

   Раньше здесь были три ступени (полная / компактная / строка). Между ступенями
   панель прыгала: часть свойств уже доехала, часть ещё нет, а на месте исчезнувших
   оставалась пустота. Плюс каждая ступень включала переход длиной 0.28 с — своя
   скорость у панели и своя у пальца, и этот рассинхрон читался как рваность.

   Теперь состояний нет вовсе. Есть одна форма, все размеры которой выражены через
   эту величину, и она идёт прямо за прокруткой, без анимации: панель меняется ровно
   за пальцем.

   Величина уходит в CSS-переменную --p, а не в React. Прокрутка сообщает её
   десятки раз в секунду; перерисовывать на каждый кадр компонент со стором,
   мостом и графиком — это те самые пропущенные кадры. Здесь же меняется одно
   число в стиле корневого элемента, дальше всё считает CSS (см. theme/parts/shell.css:
   высота панели, отступ контента и липкая полоса выражены через --p). */

const ДИАПАЗОН = 120; // на скольких пикселях прокрутки панель сворачивается целиком
const ШАГ = 0.004; // мельче — глазу не видно, а запись в стиль не бесплатна

/* Полшага сворачивания — на столько панель ниже покоя в СРЕДНЕМ положении.
   Держится в паре с --sl-panel-mid (theme/parts/shell.css): 92 * 0.5 = 46. */
export const СЕРЕДИНА = 0.5;
const ПОЛШАГА = 46;
/* Запас, чтобы решение не переворачивалось от округления в пару пикселей: содержимое
   меняется (пришло показание, подгрузился график), и «ровно впритык» означало бы
   панель, дышащую на каждом обновлении данных. */
const ЗАПАС = 6;

/* Хватит ли экрану роста, если панель встанет на середину.

   Считаем от СОБСТВЕННОЙ высоты содержимого — без отступа сверху, который сам зависит
   от положения панели. Иначе ответ зависел бы от текущего состояния, а состояние — от
   ответа, и экран мигал бы между двумя положениями.

   Отдельной функцией и под тестом: ошибка здесь не видна в браузере (там всегда есть
   мышь и полоса прокрутки), а на телефоне выглядит как прыгающая панель. */
export function серединаЛи(своё: number, отступСередины: number, доступно: number): boolean {
  return своё + отступСередины + ЗАПАС <= доступно;
}

/** Насколько ниже покоя стоит панель в среднем положении (px) — для замеров в UI. */
export function полшага(): number { return ПОЛШАГА; }

let progress = -1; // -1 = ещё не писали, чтобы первый вызов прошёл всегда

export function setProgress(v: number): void {
  const p = Math.min(1, Math.max(0, v));
  if (Math.abs(p - progress) < ШАГ) return;
  progress = p;
  document.documentElement.style.setProperty('--p', String(Math.round(p * 1000) / 1000));
}

export function getProgress(): number {
  return Math.max(0, progress);
}

/** Прокрутка активного экрана → степень сворачивания. */
export function setCollapse(px: number): void {
  setProgress(Math.max(0, px) / ДИАПАЗОН);
}

/* Обработчик onIonScroll для экранов. В карусели все вкладки смонтированы (просто
   сдвинуты), поэтому реагируем ТОЛЬКО на скролл АКТИВНОЙ панели карусели. */
export function reportContentScroll(e: { target: EventTarget | null; detail: { scrollTop: number } }): void {
  const el = e.target as HTMLElement | null;
  if (!el) return;
  const pane = el.closest?.('.pager-pane');
  if (pane && !pane.classList.contains('is-active')) return;
  /* На экране со сжатой панелью прокрутка её не трогает: она уже сжата, а отступ
     содержимого там постоянный — дышащая панель таскала бы содержимое за собой. */
  if (pane?.querySelector('.screen.is-compact')) return;
  поПрокрутке(e.detail.scrollTop);
}

/* Сменилась вкладка — панель встаёт СРАЗУ, без анимации.

   Анимация нужна там, где человек видит переход состояния: прокрутил экран, панель
   поехала за пальцем. Переключение вкладки — не переход, а смена поверхности: ты
   уходил с раздела со сжатой панелью и возвращаешься к нему же. Анимировать тут
   значит показывать движение там, где ничего не менялось, — а рядом в этот момент
   едет карусель, и два движения сразу читаются как рывок.

   Отдельной функцией, а не флагом в плавно(): вызовов всего два, и каждый обязан
   явно сказать, что именно происходит. */
export function сразу(изменить: () => void): void {
  const root = document.documentElement;
  window.clearTimeout(снять);
  снять = 0;
  root.classList.remove('p-anim');
  изменить();
}

/* Смена экрана — единственное место, где панели положено ехать, а не прыгать.

   Под пальцем анимации нет и быть не должно (см. выше). Но при переходе значение
   меняется скачком: ушли с прокрутанного экрана на непрокрутанный — панель мгновенно
   разворачивается на сто пикселей, и этот рывок совпадает по времени с выездом новой
   страницы. Два разных движения в один момент и читаются как моргание.

   Класс живёт ровно длительность перехода: оставить его насовсем — значит вернуть
   отставание панели от пальца при первой же прокрутке. */
let снять = 0;
export function плавно(изменить: () => void): void {
  const root = document.documentElement;
  root.classList.add('p-anim');
  изменить();
  window.clearTimeout(снять);
  снять = window.setTimeout(() => { снять = 0; root.classList.remove('p-anim'); }, 280);
}

/* Палец всегда важнее анимации.

   Снимать плавность по таймеру достаточно только пока вкладка на виду: в фоне
   браузер растягивает таймеры до секунд, и класс мог бы застать начало прокрутки —
   панель поехала бы с отставанием ровно там, где отставать не должна. Прокрутка
   поэтому не ждёт таймера, а снимает плавность сама. */
export function поПрокрутке(px: number): void {
  if (снять) {
    window.clearTimeout(снять);
    снять = 0;
    document.documentElement.classList.remove('p-anim');
  }
  setCollapse(px);
}

/* Синхронизация панели с тем экраном, который стал активным.

   Вкладки и страницы стека помнят свою прокрутку. Переключились на вкладку,
   прокрутанную вниз, — панель должна быть свёрнута ровно настолько же, иначе она
   развернётся поверх содержимого, которое стоит на месте. Раньше вместо этого
   панель просто разворачивалась заново — отсюда и скачок при переключении. */
export function syncToActiveScreen(таб?: number): void {
  /* Кто спрашивает, тот и говорит, про какую вкладку речь.

     Искать по .is-active оказалось нельзя: класс приезжает своим рендером карусели, и
     панель со своим useLayoutEffect регулярно попадала в кадр, когда его ещё нет. Тогда
     синхронизация либо разворачивала панель на весь рост, либо не делала ничего — и в
     обоих случаях положение панели переставало соответствовать экрану.

     Номер вкладки известен вызывающему всегда: он же им и переключает. Запасной путь
     по .is-active оставлен для вызовов, у которых номера нет (прокрутка). */
  const pane = таб != null
    ? document.querySelector(`.pager-pane[data-tab="${таб}"]`)
    : document.querySelector('.pager-pane.is-active');
  /* Страницы нет вовсе — молчим. Раньше здесь стояло setCollapse(0), и это значило
     «не знаю, значит разворачиваю»: панель вставала на весь рост поверх содержимого,
     которое считает отступ от сжатой высоты. Незнание — не повод менять положение. */
  if (!pane) return;
  /* В разделе панель всегда компактная, и прокрутка её не трогает.

     Раздел — рабочая поверхность: список устройств, редактор базала, логи. Человек
     пришёл туда работать со списком, а не смотреть на сахар, и сто пикселей панели
     стоят двух-трёх строк, которых ему не хватает. Сахар при этом никуда не девается:
     в сжатом виде остаются и число, и строка связи — обещание «значение всегда на
     виду» держится, просто мельче.

     Пинуем именно здесь, а не отдельным флагом: тогда состояние панели по-прежнему
     выводится из того, что сейчас на экране, а не хранится где-то рядом и не рискует
     разойтись с ним. */
  /* Уходящую страницу не считаем: она уже снята со стека и доигрывает уход
     (app/stack.tsx), а панель обязана возвращаться к состоянию вкладки СРАЗУ —
     иначе после «назад» она остаётся сжатой, будто раздел ещё открыт. */
  const stack = pane.querySelector('.stack-page.is-top:not(.is-leaving) .stack-body') as HTMLElement | null;
  if (stack) { setProgress(1); return; }
  /* Экран, которому крупная панель не нужна, держит её сжатой всегда — не только
     после прокрутки. Признак берём из разметки экрана, а не из списка вкладок:
     список пришлось бы держать в двух местах и однажды разойтись. */
  /* Содержимого мало — панель встаёт на середину, а не жмётся в строку. Сжимать её
     до предела там, где под ней всё равно остаётся пустое место, значит отнимать у
     сахара размер и ничего не давать взамен (ui/Screen.tsx решает, когда так). */
  if (pane.querySelector('.screen.is-mid')) { setProgress(СЕРЕДИНА); return; }
  if (pane.querySelector('.screen.is-compact')) { setProgress(1); return; }
  const content = pane.querySelector('ion-content') as (HTMLElement & { getScrollElement?: () => Promise<HTMLElement> }) | null;
  if (content?.getScrollElement) {
    content.getScrollElement().then((el) => setCollapse(el.scrollTop)).catch(() => setCollapse(0));
  } else {
    setCollapse(0);
  }
}
