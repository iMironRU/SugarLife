/* Правила жеста «назад» — отдельно от его подключения.

   Само перетаскивание проверяется только пальцем: движение идёт через кадры, а в
   фоновой вкладке кадров нет вовсе, и автоматическая проверка тут бессильна. Но
   решения, которые жест принимает, — арифметика, и её незачем оставлять
   непроверенной: именно в порогах живут «закрывается от случайного касания» и
   «не закрывается, хотя тянул через весь экран». */

/** Ширина зоны у левой кромки, из которой жест вообще начинается. */
export const КРАЙ_PX = 36;
/** Доля ширины экрана, после которой отпускание закрывает страницу. */
export const ПОРОГ_ДОЛЯ = 0.35;
/** Скорость, при которой закрываем даже с короткого движения (px/мс). */
export const ПОРОГ_СКОРОСТИ = 0.35;

/* От кромки, а не откуда угодно, по двум причинам. Это конвенция платформы — жест от
   края означает «назад» и в iOS, и в Android. И внутри страниц живут свои
   горизонтальные списки (полосы фильтров в разборе): жест из середины отбирал бы у
   них движение. */
export function canStartBack(startX: number): boolean {
  return startX <= КРАЙ_PX;
}

/* Закрывать или вернуть на место. Два условия, а не одно: медленно, но далеко — это
   осознанное «назад»; быстро, но коротко — это привычный флик, и он тоже «назад».
   Останется одно условие — половина жестов будет ощущаться сломанной. */
export function shouldGoBack(dx: number, width: number, velocityX: number): boolean {
  if (dx <= 0) return false; // движение влево страницу не «переворачивает»
  return dx > Math.max(1, width) * ПОРОГ_ДОЛЯ || velocityX > ПОРОГ_СКОРОСТИ;
}
