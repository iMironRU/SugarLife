import { describe, it, expect } from 'vitest';
import { уводитьЛиНаСегодня, ВКЛАДКА_СЕГОДНЯ } from './возврат';
import { ОТСТАВАНИЕ_МС } from '@/domain/latestGlucose';

/* Вернулся из фона — открывать «Сегодня» (SugarLife#703).

   Правило «где человек был» работало только при ПЕРЕЗАПУСКЕ приложения. А сворачивают его
   намного чаще, чем оно перезапускается: правило было написано для редкого случая и не
   работало в частом. */

const б = (o: Partial<Parameters<typeof уводитьЛиНаСегодня>[0]> = {}) => уводитьЛиНаСегодня({
  отсутствовалМс: ОТСТАВАНИЕ_МС + 60e3, вкладка: 4, глубина: 1, открытаШторка: false, ...o,
});

describe('возврат из фона', () => {
  it('ушёл вглубь надолго — возвращаем на «Сегодня»', () => {
    expect(б()).toBe(true);
  });

  /* Отвлёкся на звонок — это не «другая обстановка». Порог тот же, с которого показанное
     число считается отставшим: если картина не устарела, разговор можно продолжать. */
  it('отсутствовал недолго — не трогаем', () => {
    expect(б({ отсутствовалМс: ОТСТАВАНИЕ_МС })).toBe(false);
    expect(б({ отсутствовалМс: 60e3 })).toBe(false);
  });

  /* Шторка жива вместе с набранными данными: увести человека значит стереть его работу.
     Здесь главная разница с перезапуском, где данные и так не переживают перезагрузку. */
  it('открытая шторка сильнее любого срока', () => {
    expect(б({ открытаШторка: true })).toBe(false);
    expect(б({ отсутствовалМс: 12 * 3600e3, открытаШторка: true })).toBe(false);
  });

  /* Возвращать некуда: человек и так там, куда мы собирались его вести. */
  it('стоял на «Сегодня» верхним уровнем — не событие', () => {
    expect(б({ вкладка: ВКЛАДКА_СЕГОДНЯ, глубина: 0 })).toBe(false);
  });

  /* А вот раздел, открытый ИЗ «Сегодня», — это уже вглубь. */
  it('на «Сегодня», но в разделе — уводим', () => {
    expect(б({ вкладка: ВКЛАДКА_СЕГОДНЯ, глубина: 1 })).toBe(true);
  });

  it('соседняя вкладка верхним уровнем — тоже уводим: там не экран действия', () => {
    expect(б({ вкладка: 0, глубина: 0 })).toBe(true);
  });

  /* Часы съехали назад — не гадаем, тем же правилом, что и в место.ts. */
  it('отрицательное время не считаем', () => {
    expect(б({ отсутствовалМс: -1000 })).toBe(false);
    expect(б({ отсутствовалМс: NaN })).toBe(false);
  });
});
