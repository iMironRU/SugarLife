const DASH = '—';

// Тренд из контракта → символ стрелки
// Короткий статус помпы для крыла
function shortStatus(s?: string | null): string {
  if (!s) return DASH;
  const l = s.toLowerCase();
  if (l.includes('приостан') || l.includes('пауза') || l.includes('suspend') || l.includes('stop')) return 'Пауза';
  if (l.includes('замкнут') || l.includes('closed')) return 'Цикл вкл';
  if (l.includes('открыт') || l.includes('open')) return 'Цикл выкл';
  return s;
}
/* АДРЕС ИСТОЧНИКА — НЕ ДЛЯ ЭТОЙ СТРОКИ (SugarLife#700).

   Имя приходит из реестра приборов и выглядит как «Внешний CGM (j96160575.nightscout-jino.ru-cgm)».
   Скобка в нём — адрес, а не формулировка: он не меняется никогда, действия по нему нет, и в
   разборе поломки его смотрят на карточке прибора, а не на главном экране. При этом он занимал
   больше половины ширины строки и всё равно не читался целиком.

   Владелец сказал прямо: неважное видно хорошо, важное нет. Первая правка развернула приоритет
   обрезания — возраст перестал резаться, — но обжору оставила на месте, и строка выглядела
   прежней. Здесь мы его и снимаем.

   Режем ТОЛЬКО хвостовую скобку и только в этой строке. Полное имя остаётся в разделе связи и на
   карточке прибора: если два источника когда-нибудь окажутся тёзками, различить их будет где. */
const безАдреса = (имя?: string | null) => имя?.replace(/\s*\([^)]*\)\s*$/, '') || имя;

