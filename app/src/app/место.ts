/* Где человек был, когда приложение перезапустилось (#400).

   Обновление перезагружает приложение, и человек оказывался на «Сегодня» — не там, где
   стоял. Своими словами он это описал так: «приложение моргает, появляется экран
   запуска, и я потерялся, где был и что делал». Потеря места читается как сбой, а в
   приложении, которым пользуются в момент решения о дозе, сбой — дорогое ощущение.

   ВОССТАНАВЛИВАЕМ НЕ ВСЕГДА, и это главное правило здесь. Приложение, открытое утром,
   должно открываться на экране действия, а не на карточке помпы, куда человек заходил
   вчера вечером. Возврат уместен, только если человек был там ЧТО ТОЛЬКО ЧТО: перезапуск
   наш (обновление) или прошло несколько минут — то есть перезапуск случился посреди
   работы, а не между сессиями.

   ЧЕГО НЕ ВОССТАНАВЛИВАЕМ: шторок. Шторка — незаконченное действие с набранными
   данными, и данные перезагрузку не переживают. Открыть пустую шторку ввода еды на том
   месте, где человек её заполнял, — худший из возможных ответов: он выглядит как «всё
   на месте», а введённого там нет. Пусть лучше её не будет, чем будет пустая. */

/** Сколько после обычной перезагрузки место ещё считается «тем же». */
export const СВЕЖЕСТЬ_МС = 5 * 60e3;
/* Наш перезапуск живёт дольше: OTA качает бандл по мобильной сети, и между решением
   человека и первым кадром может пройти заметно больше пяти минут. Но не бесконечно —
   отметка, пережившая ночь, вернула бы человека во вчера. */
export const СВЕЖЕСТЬ_НАШЕГО_МС = 30 * 60e3;

export function восстанавливатьЛи(
  записаноМс: number | null | undefined, сейчас: number, нашПерезапуск: boolean,
): boolean {
  if (!записаноМс || !Number.isFinite(записаноМс)) return false;
  const прошло = сейчас - записаноМс;
  if (прошло < 0) return false;            // часы съехали назад — не гадаем
  return прошло <= (нашПерезапуск ? СВЕЖЕСТЬ_НАШЕГО_МС : СВЕЖЕСТЬ_МС);
}
