import { describe, it, expect } from 'vitest';
import { серединаЛи } from './panel';

/* Правило среднего положения панели. Проверяем именно арифметику: в браузере экран
   всегда выше телефонного, и «полупустой экран» там не воспроизводится вовсе — а
   ошибка в этом месте выглядит как панель, прыгающая между двумя размерами. */

describe('среднее положение панели', () => {
  it('короткий экран — панель встаёт на середину', () => {
    expect(серединаЛи(300, 190, 800)).toBe(true);
  });

  it('содержимое не помещается — панель сжата до предела', () => {
    expect(серединаЛи(700, 190, 800)).toBe(false);
  });

  /* Впритык — не повод: содержимое меняется каждые пять минут, и решение,
     принятое по последнему пикселю, переворачивалось бы вместе с ним. */
  it('впритык считаем «не помещается»', () => {
    expect(серединаЛи(610, 190, 800)).toBe(false);
    expect(серединаЛи(600, 190, 800)).toBe(true);
  });

  /* Ответ не зависит от того, в каком положении панель сейчас: считаем от
     собственной высоты содержимого, а не от того, что видно на экране. */
  it('одно и то же содержимое даёт один ответ при любом текущем отступе', () => {
    expect(серединаЛи(300, 190, 800)).toBe(серединаЛи(300, 190, 800));
  });
});
