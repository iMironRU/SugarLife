import { createContext, useContext, type ReactNode } from 'react';

/* Контекст стека вынесен из stack.tsx намеренно: в файле с компонентом не должно быть
   других экспортов, иначе ломается горячая перезагрузка — правишь хук, а React
   пересоздаёт всё дерево и теряет открытые страницы. */
export interface StackApi {
  push: (node: ReactNode) => void;
  pop: () => void;
  depth: number;
  /* Путь до текущей страницы: имя вкладки и заголовки всех страниц над ней.

     Крошка собирается СТЕКОМ, а не пишется в каждом разделе руками. Написанная руками
     она уже разъехалась: «Профиль · Хозяйство» при том, что в Профиле раздел называется
     иначе; «Профиль · Сервисы · Учётки» при глубине два. Стек знает настоящий путь и не
     может соврать — а строка в файле не знает даже, откуда её открыли.

     Имена кладут сами страницы: вкладка — своё, раздел — свой заголовок. */
  назвать: (глубина: number, имя: string) => void;
  путь: string[];
}

export const StackCtx = createContext<StackApi>({
  push: () => {}, pop: () => {}, depth: 0, назвать: () => {}, путь: [],
});

export const useStack = (): StackApi => useContext(StackCtx);

/* На каком этаже стоит страница. Раздаёт стек при отрисовке, а не считает сама
   страница по текущей глубине.

   Считать было соблазнительно: «при первом рендере глубина равна моей». Но страницы
   ленивые — сперва рисуется заглушка, настоящий раздел монтируется позже, — и «первый
   рендер» приходится не на тот момент. Крошка в итоге показывала соседний раздел
   вместо родителя, то есть врала ровно так же, как написанная руками.

   Ноль — вкладка: с неё начинается любой путь. */
export const ЭтажCtx = createContext(0);
export const useЭтаж = (): number => useContext(ЭтажCtx);
