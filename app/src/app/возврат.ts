import { getTab, setTab } from '@/app/nav';
import { текущаяГлубина } from '@/app/местоStore';
import { ОТСТАВАНИЕ_МС } from '@/domain/latestGlucose';

/* ВЕРНУЛСЯ ИЗ ФОНА ЧЕРЕЗ ПОЛЧАСА — ОТКРЫВАТЬ «СЕГОДНЯ» (SugarLife#703).

   Правило «где человек был» уже написано и работает — при ПЕРЕЗАПУСКЕ приложения
   (app/место.ts). Возврат из фона этой дорогой не идёт: приложение живо, состояние в памяти
   цело, и человек возвращается ровно туда, где был, хоть через час.

   А сворачивают приложение НАМНОГО чаще, чем оно перезапускается. То есть правило было
   написано для редкого случая и не работало в частом.

   СРОК НЕ ТРЕТИЙ. У нас уже два числа, выбранных по причинам: пять минут после обычной
   перезагрузки и тридцать после нашей. Владелец назвал «10–15». Заводить третье число на глаз
   не стали — взяли то, у которого есть смысл: `ОТСТАВАНИЕ_МС`, возраст, с которого показанное
   число считается отставшим. Пятнадцать минут.

   Довод простой: если то, на что человек смотрел, за время его отсутствия успело устареть, он
   вернулся в ДРУГУЮ обстановку — и разговор надо начинать с начала, а не с середины вчерашней
   мысли. Совпало и с вилкой владельца, и это не случайность: обе цифры про одно — как быстро
   стареет картина у человека с диабетом.

   ЧЕГО ПРАВИЛО НЕ ТРОГАЕТ.

   Шторок. Здесь главная разница с перезапуском: при перезагрузке данные шторки не переживают
   и пустая шторка хуже её отсутствия, а при возврате из фона она жива вместе с набранным.
   Закрыть наполовину заполненный ввод еды потому, что человек двадцать минут говорил по
   телефону, — это стереть его работу.

   И тех, кто и так на «Сегодня» или стоит на вкладке верхним уровнем: если человек свернул
   приложение, никуда не углубившись, возвращать его некуда. Правило имеет смысл только для
   ушедших вглубь. */

/** Вкладка «Сегодня» — второй элемент TAB_PATHS. Держим по имени, а не числом в коде вызова. */
export const ВКЛАДКА_СЕГОДНЯ = 2;

export function уводитьЛиНаСегодня(п: {
  отсутствовалМс: number;
  вкладка: number;
  /** Сколько разделов открыто поверх вкладки. Ноль — человек не углублялся. */
  глубина: number;
  открытаШторка: boolean;
}): boolean {
  if (п.открытаШторка) return false;
  if (п.вкладка === ВКЛАДКА_СЕГОДНЯ && п.глубина === 0) return false;
  if (!Number.isFinite(п.отсутствовалМс) || п.отсутствовалМс < 0) return false;
  return п.отсутствовалМс > ОТСТАВАНИЕ_МС;
}

/* СЧЁТЧИК ОТКРЫТЫХ ШТОРОК — ОДИН НА ВСЕ, И ЖИВЁТ В САМОЙ ШТОРКЕ (ui/Sheet.tsx).

   Спрашивать DOM («есть ли ion-modal без класса overlay-hidden») было бы гаданием по вёрстке
   чужого компонента: класс переименуют в следующей версии Ionic, и правило замолчит молча.
   Регистрация при монтировании честнее и не зависит ни от чьей разметки. */
let открытых = 0;
export function шторкаОткрылась(): void { открытых += 1; }
export function шторкаЗакрылась(): void { открытых = Math.max(0, открытых - 1); }
export function естьОткрытаяШторка(): boolean { return открытых > 0; }

let ушёлВМс: number | null = null;

/** Следить за уходом в фон и возвращением. Зовётся один раз при старте приложения. */
export function следитьЗаВозвратом(): () => void {
  const наСмену = () => {
    if (document.visibilityState === 'hidden') { ушёлВМс = Date.now(); return; }
    const ушёл = ушёлВМс;
    ушёлВМс = null;
    if (ушёл == null) return;
    const вкладка = getTab();
    const надо = уводитьЛиНаСегодня({
      отсутствовалМс: Date.now() - ушёл,
      вкладка,
      глубина: текущаяГлубина(вкладка),
      открытаШторка: естьОткрытаяШторка(),
    });
    if (надо) setTab(ВКЛАДКА_СЕГОДНЯ);
  };
  document.addEventListener('visibilitychange', наСмену);
  return () => document.removeEventListener('visibilitychange', наСмену);
}
