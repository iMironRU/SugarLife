import { useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import { создатьЖест } from '@/ui/Жест';
import { StackCtx, type StackApi } from './stackCtx';
import { syncToActiveScreen, плавно } from './panel';
import { useGoHome } from './nav';
import { canStartBack, shouldGoBack } from './backGesture';
import { собрать, type Метка } from './разделы';
import { местоВкладки, сохранитьМесто } from './местоStore';

/* Стек страниц внутри вкладки.

   Почему не модалки. Разделы вроде «Устройства → карточка помпы → базальный профиль» —
   это иерархия: у каждого экрана есть родитель, к которому возвращаются. Модалка
   предназначена для другого — для одноразовой подзадачи, прерывающей поток. Когда
   иерархию изображают модалками, приходится вручную воспроизводить всё, что даёт
   навигация: держать карточку между панелью и таббаром (а значит мерить их высоты в
   JS и ловить отставание), прятать нижний слой, ужимать подложку, гасить события на
   хосте, вести руками список того, что закрыть при смене вкладки.

   Здесь ничего этого нет по построению. Оболочка — HeroPanel → Pager → TabBar, и
   .pager-pane это ровно область между панелью и таббаром. Страница внутри панели
   получает нужные границы сама, через inset: 0. Мерить нечего, отставать нечему.

   Стек свой у каждой вкладки: уходя на другую и возвращаясь, человек ожидает застать
   то же место, где был. */

type Страница = { key: number; node: ReactNode; метка?: Метка };

export function StackHost({ tab, children }: { tab: number; children: ReactNode }) {
  const [pages, setPages] = useState<Страница[]>([]);

  /* Уходящая страница живёт ещё четверть секунды после того, как снята со стека.

     Появлялась она выездом справа, а исчезала мгновенно — React просто убирал узел.
     Асимметрия читается как сбой: то, что въехало, обязано уехать, иначе непонятно,
     куда оно делось и вернётся ли. Свайпом «назад» уход был плавным, кнопкой — нет,
     то есть одно и то же действие выглядело двумя разными.

     Держим снятый узел отдельно от стека: он уже не часть навигации (вернуться в него
     нельзя), он доигрывает. Поэтому и состояние отдельное, а не флаг внутри pages. */
  const [уходит, setУходит] = useState<{ key: number; node: ReactNode } | null>(null);
  const таймерУхода = useRef(0);

  /* Какая страница именно что открыта — ей и играть въезд. Раньше анимация висела на
     каждой .stack-page, и браузер проигрывал её всякий раз, когда перерисовывал узел
     заново: вернулся на вкладку с открытым разделом — а он «проявляется», будто ты
     его только что открыл. */
  const [въезжает, setВъезжает] = useState(0);
  const таймерВъезда = useRef(0);

  const push = useCallback((node: ReactNode, метка?: Метка) => {
    setPages((p) => {
      const key = (p[p.length - 1]?.key ?? 0) + 1;
      setВъезжает(key);
      window.clearTimeout(таймерВъезда.current);
      таймерВъезда.current = window.setTimeout(() => setВъезжает(0), 260);
      return [...p, { key, node, метка }];
    });
  }, []);

  /* Уход верхней страницы — один на все способы выйти.

     Способов три: кнопка «назад», свайп и нажатие своей вкладки в таб-баре. Первый и
     третий обязаны выглядеть одинаково: человек не различает «как» он вышел, он видит
     только результат, и страница, то уезжающая, то исчезающая мгновенно, читается как
     сбой (#220). */
  const увестиВерх = useCallback((всё: boolean) => {
    setPages((p) => {
      const верх = p[p.length - 1];
      if (верх) {
        setУходит(верх);
        window.clearTimeout(таймерУхода.current);
        таймерУхода.current = window.setTimeout(() => setУходит(null), 240);
      }
      /* «Домой» снимает весь стек, но уезжает только верхняя: нижние человек не видит,
         и анимировать их — работа впустую. */
      return всё ? [] : p.slice(0, -1);
    });
  }, []);

  const pop = useCallback(() => увестиВерх(false), [увестиВерх]);

  /* Отдельная функция, а не флаг в pop(), и это не вкусовщина.

     Разделы получают pop как onClose и вешают его прямо обработчиком: onClick={pop}.
     Обработчик получает первым аргументом событие, поэтому любой необязательный
     параметр у pop оказывается «истиной» при каждом нажатии кнопки «назад» — что мы
     тут же и поймали: уход перестал анимироваться именно у кнопки.

     Здесь уход не нужен: свайп уже дотащил страницу до края, и проигрывать анимацию
     заново значило бы вернуть её на место и увести второй раз. */
  const popПослеЖеста = useCallback(() => setPages((p) => p.slice(0, -1)), []);

  useEffect(() => () => {
    window.clearTimeout(таймерУхода.current);
    window.clearTimeout(таймерВъезда.current);
  }, []);

  const api = useMemo<StackApi>(() => ({ push, pop, depth: pages.length }), [push, pop, pages.length]);

  /* Вернуть человека туда, где он был (#400).

     Собираем стек ОДИН раз при монтировании и без анимации: страницы не «открываются
     заново» — они там были. Въезд справа тут был бы враньём про действие, которого
     человек не совершал.

     Останавливаемся на первой метке, которой нет в реестре: пропустить её и открыть то,
     что было выше, значит подсунуть человеку экран без родителя — кнопка «назад» увела
     бы его не туда, откуда он пришёл. */
  const восстановлено = useRef(false);
  useEffect(() => {
    if (восстановлено.current) return;
    восстановлено.current = true;
    const метки = местоВкладки(tab);
    if (!метки.length) return;
    const собранные: Страница[] = [];
    for (const м of метки) {
      const node = собрать(м, pop);
      if (!node) break;
      собранные.push({ key: собранные.length + 1, node, метка: м });
    }
    if (собранные.length) setPages(собранные);
  }, [tab, pop]);

  /* И запоминаем, где он сейчас. Только помеченные разделы: непомеченный восстановить
     нечем, и записать его значило бы обещать возврат, которого не будет. */
  useEffect(() => {
    if (!восстановлено.current) return;
    const метки: Метка[] = [];
    for (const с of pages) {
      if (!с.метка) break;
      метки.push(с.метка);
    }
    сохранитьМесто(tab, метки);
  }, [pages, tab]);

  /* Панель должна знать про открытую страницу и слышать её прокрутку.

     Сигнал сворачивания шёл только от ion-content вкладок, а у страницы стека
     скроллер свой — панель о нём не знала и не сворачивалась. Иногда всё же
     сворачивалась: когда жест перехватывал управление. Отсюда и «ведёт себя
     странно» — срабатывало через раз.

     События scroll не всплывают, поэтому ловим их на перехвате.

     До отрисовки, а не после: обычный эффект отрабатывает уже показанным кадром, и
     новая страница успевала появиться с панелью от прежнего экрана — свёрнутой, если
     тот был прокручен. Кадр не тот, потом рывок. */
  useLayoutEffect(() => {
    // открылась/закрылась страница — панель встаёт по прокрутке того, что теперь видно
    плавно(syncToActiveScreen);
  }, [pages.length]);

  /* Нажали свою вкладку в таб-баре — выходим в корень раздела (см. nav.pressTab).
     Тем же уходом, что и кнопка «назад»: раньше здесь стоял мгновенный сброс стека, и
     раздел просто исчезал — то же действие выглядело двумя разными (#220). */
  const домой = useGoHome(tab);
  useEffect(() => {
    if (домой) увестиВерх(true);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [домой]);

  /* Свайп «назад». Пороги и правила — в app/backGesture.ts, там же тесты: само
     перетаскивание проверяется только пальцем, а вот арифметика решений оставаться
     непроверенной не должна — в порогах живут «закрылось от случайного касания» и
     «не закрылось, хотя тянул через весь экран».

     Соперник у жеста один — свайп между вкладками; он выключен, пока открыта страница
     (см. canStart в App). Два жеста на одно движение — это та самая рваность, которую
     мы вычищали из панели: побеждает то один, то другой, и поведение «через раз». */
  const верх = useRef<HTMLDivElement>(null);
  const [тянут, setТянут] = useState(false);

  useEffect(() => {
    const el = верх.current;
    if (!el || !pages.length) return;
    let W = 1;
    const жест = создатьЖест({
      el,
      threshold: 10,
      canStart: (d) => canStartBack(d.startX),
      onStart: () => {
        W = el.clientWidth || 1;
        el.style.transition = 'none';
        setТянут(true);
      },
      onMove: (d) => {
        // назад тянем только вперёд: движение влево страницу не «переворачивает»
        el.style.transform = `translate3d(${Math.max(0, d.deltaX)}px,0,0)`;
      },
      onEnd: (d) => {
        const dx = Math.max(0, d.deltaX);
        const закрыть = shouldGoBack(dx, W, d.velocityX);
        el.style.transition = 'transform .22s cubic-bezier(.3,.9,.3,1)';
        el.style.transform = закрыть ? `translate3d(${W}px,0,0)` : '';
        if (закрыть) {
          /* Ждём, пока страница доедет за край, и только потом снимаем её со стека:
             иначе она исчезнет посреди движения, и вместо ухода получится мигание. */
          window.setTimeout(() => { setТянут(false); popПослеЖеста(); }, 200);
        } else {
          window.setTimeout(() => setТянут(false), 220);
        }
      },
    });
    жест.enable();
    return () => жест.destroy();
  }, [pages.length, popПослеЖеста]);

  /* Прокрутка раздела панель не двигает — она там уже сжата (app/panel.ts).

     Иначе получилось бы хуже, чем было: отступ содержимого раздела привязан к текущей
     высоте панели, и панель, дышащая за прокруткой, таскала бы содержимое за собой. */

  return (
    <StackCtx.Provider value={api}>
      {children}
      {/* Уходящая — поверх всех, но уже без событий: нажимать в неё нечего, а перехват
          касаний на четверть секунды после «назад» ощущается как залипание. */}
      {уходит && (
        <div key={'out' + уходит.key} className="stack-page is-top is-leaving" aria-hidden>
          {уходит.node}
        </div>
      )}
      {pages.map((p, i) => (
        /* Ниже верхней страницы всё скрыто: рисовать нижние незачем, а вот держать
           их смонтированными нужно — иначе возврат терял бы состояние (набранный
           адрес, раскрытую часть суток, правку профиля). */
        <div key={p.key}
          ref={i === pages.length - 1 ? верх : undefined}
          className={'stack-page'
            + (i === pages.length - 1 ? ' is-top' : '')
            + (p.key === въезжает ? ' is-entering' : '')
            /* Пока тянут, страницу под верхней надо ВИДЕТЬ — иначе из-под уходящей
               покажется пустота вместо того, куда возвращаются. */
            + (тянут && i === pages.length - 2 ? ' is-under' : '')}
          aria-hidden={i !== pages.length - 1}>
          {p.node}
        </div>
      ))}
    </StackCtx.Provider>
  );
}
