import { прочитать, записать } from '@/settings/storage';
import { восстанавливатьЛи } from './место';
import type { Метка } from './разделы';

/* Хранилище места: какие разделы были открыты в каждой вкладке (#400).

   Вкладка и так переживает перезагрузку — она в адресе (app/nav.ts). Терялся стек
   разделов внутри неё, потому что стек это React-узлы. Храним не узлы, а метки. */
const КЛЮЧ = 'sl.place.v1';
/* Отметку «перезапускаемся мы сами» ставит тот, кто перезагружает: обновление в вебе,
   OTA в нативе. Она же отличает «человек нажал Обновить» от «система выгрузила
   приложение из памяти» — окна восстановления у этих случаев разные. */
const КЛЮЧ_НАШ = 'sl.place.ours.v1';

interface Место { когдаМс: number; вкладки: Record<string, Метка[]> }

let память: Место | null = null;

function загрузить(): Место {
  if (память) return память;
  try {
    const s = прочитать(КЛЮЧ);
    const м = s ? (JSON.parse(s) as Место) : null;
    память = м && typeof м.когдаМс === 'number' && м.вкладки ? м : { когдаМс: 0, вкладки: {} };
  } catch { память = { когдаМс: 0, вкладки: {} }; }
  return память;
}

/* Читаем ОДИН раз при загрузке модуля, до первой отрисовки.

   Дальше стек начнёт сохранять себя сам, и запись затрёт то, что мы собирались
   восстановить: пустой стек при старте — это тоже состояние, и оно приезжает раньше,
   чем человек что-либо открыл. */
const начальное = загрузить();
const нашПерезапуск = прочитать(КЛЮЧ_НАШ) === '1';
try { if (нашПерезапуск) записать(КЛЮЧ_НАШ, ''); } catch { /* приватный режим */ }
const восстанавливаем = восстанавливатьЛи(начальное.когдаМс, Date.now(), нашПерезапуск);

/** Что было открыто в этой вкладке — если возвращать вообще уместно. */
export function местоВкладки(tab: number): Метка[] {
  if (!восстанавливаем) return [];
  return начальное.вкладки[String(tab)] ?? [];
}

/** Мы сами сейчас перезагрузимся — вернуть человека на место обязательно. */
export function этоНашПерезапуск(): void {
  try { записать(КЛЮЧ_НАШ, '1'); } catch { /* приватный режим */ }
}

/* СКОЛЬКО РАЗДЕЛОВ ОТКРЫТО ВО ВКЛАДКЕ ПРЯМО СЕЙЧАС (#703).

   Отличается от `местоВкладки` тем, что не спрашивает, уместно ли восстановление: тот вопрос
   про запуск приложения, а этот — про то, где человек стоит в эту секунду. Стек сохраняет себя
   сам при каждом изменении, поэтому память здесь и есть текущая правда. */
export function текущаяГлубина(tab: number): number {
  return (загрузить().вкладки[String(tab)] ?? []).length;
}

export function сохранитьМесто(tab: number, метки: Метка[]): void {
  const м = загрузить();
  const было = JSON.stringify(м.вкладки[String(tab)] ?? []);
  if (было === JSON.stringify(метки)) return;
  м.вкладки[String(tab)] = метки;
  м.когдаМс = Date.now();
  память = м;
  try { записать(КЛЮЧ, JSON.stringify(м)); } catch { /* приватный режим */ }
}
