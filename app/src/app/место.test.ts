import { describe, it, expect } from 'vitest';
import { восстанавливатьЛи, СВЕЖЕСТЬ_МС, СВЕЖЕСТЬ_НАШЕГО_МС } from './место';

const СЕЙЧАС = 1_800_000_000_000;

describe('возвращать ли человека туда, где он был', () => {
  it('да — если он был там только что', () => {
    expect(восстанавливатьЛи(СЕЙЧАС - 60e3, СЕЙЧАС, false)).toBe(true);
  });

  /* Приложение, открытое утром, должно открываться на экране действия, а не на карточке
     помпы, куда человек заходил вчера вечером. */
  it('нет — если это новая сессия, а не продолжение прежней', () => {
    expect(восстанавливатьЛи(СЕЙЧАС - СВЕЖЕСТЬ_МС - 1, СЕЙЧАС, false)).toBe(false);
    expect(восстанавливатьЛи(СЕЙЧАС - 12 * 3600e3, СЕЙЧАС, false)).toBe(false);
  });

  /* Наш перезапуск — обещание: человек нажал «Обновить» и вправе вернуться на место,
     даже если бандл качался по мобильной сети десять минут. */
  it('после нашего обновления окно шире', () => {
    expect(восстанавливатьЛи(СЕЙЧАС - 10 * 60e3, СЕЙЧАС, true)).toBe(true);
    expect(восстанавливатьЛи(СЕЙЧАС - СВЕЖЕСТЬ_НАШЕГО_МС - 1, СЕЙЧАС, true)).toBe(false);
  });

  it('нет отметки — нечего восстанавливать', () => {
    expect(восстанавливатьЛи(null, СЕЙЧАС, true)).toBe(false);
    expect(восстанавливатьЛи(undefined, СЕЙЧАС, false)).toBe(false);
  });

  /* Часы на телефоне переводят, и метка из будущего — не повод гадать, сколько прошло. */
  it('метка из будущего — не восстанавливаем', () => {
    expect(восстанавливатьЛи(СЕЙЧАС + 60e3, СЕЙЧАС, true)).toBe(false);
  });
});
