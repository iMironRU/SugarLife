const КОРЕНЬ = new URL('../', import.meta.url).pathname;

/* Не наше и не про экран: сборка, чужие зависимости, натив. Список поимённый — «всё, что
   не src» однажды тихо исключило бы index.html обратно. */
const МИМО = new Set(['node_modules', 'dist', 'ios', 'android', 'coverage', '.git']);
const СМОТРИМ = ['.css', '.html', '.js', '.jsx', '.ts', '.tsx'];

function файлы(путь: string): string[] {
  return readdirSync(путь, { withFileTypes: true }).flatMap((e) => {
    if (МИМО.has(e.name)) return [];
    const полный = join(путь, e.name);
    if (e.isDirectory()) return файлы(полный);
    return СМОТРИМ.some((р) => e.name.endsWith(р)) ? [полный] : [];
  });
}

/* Пояснения вычёркиваем, а не пропускаем по отступу: слово стоит и в рассказе о том,
   почему его больше нет, — сторож ловил бы сам этот рассказ. Заменяем комментарии
   пробелами, чтобы номера строк не поехали. */
const БЕЗ_ПОЯСНЕНИЙ = (текст: string) => текст
  .replace(/\/\*[\s\S]*?\*\//g, (с) => с.replace(/[^\n]/g, ' '))
  .replace(/<!--[\s\S]*?-->/g, (с) => с.replace(/[^\n]/g, ' '))
  .replace(/(^|[^:])\/\/[^\n]*/g, (с, п) => п + ' '.repeat(с.length - п.length));

describe('анимации кончаются', () => {
  const все = файлы(КОРЕНЬ);

  /* Сам список тоже под проверкой: если обход однажды перестанет доставать до index.html,
     все остальные проверки пройдут — на пустоте они всегда зелёные. */
  it('обход достаёт до встроенных стилей index.html', () => {
    expect(все.some((f) => f.endsWith('/index.html'))).toBe(true);
    expect(все.length).toBeGreaterThan(50);
  });

  for (const файл of все) {
    it(файл.slice(КОРЕНЬ.length), () => {
      const плохие = БЕЗ_ПОЯСНЕНИЙ(readFileSync(файл, 'utf8')).split('\n')
        .map((с, i) => ({ с, n: i + 1 }))
        .filter(({ с }) => /\binfinite\b/.test(с))
        .map(({ с, n }) => `${n}: ${с.trim()}`);
      expect(плохие, 'бесконечная анимация — 78 % ядра на телефоне; поставьте число повторов').toEqual([]);
    });
  }
});
