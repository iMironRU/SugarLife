import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/* ПРОЗРАЧНОСТЬ СКАНЕРА — ДВЕ ПОЛОВИНЫ ОДНОГО, И ПОРОЗНЬ ОНИ БЕСПОЛЕЗНЫ (#621).

   Камеру рисует натив ПОД веб-слоем, и прозрачным должно стать всё дерево до корня. Класс вешает
   код, красит правило; если пропадёт любая половина, вторая молча перестанет работать — а
   выглядеть это будет не как поломка сканера, а как чёрный прямоугольник вместо картинки. Три дня
   его и принимали за подложку плагина.

   Проверяем текстом файлов, а не поведением: правило живёт в CSS, класс в TS, и ни один
   исполняемый тест не свяжет их между собой. */

const КОРЕНЬ = join(process.cwd(), 'src');
const читать = (п: string) => readFileSync(join(КОРЕНЬ, п), 'utf8');

describe('прозрачность сканера', () => {
  it('класс вешается и на корень, и на body', () => {
    const код = читать('platform/scanCode.ts');
    expect(код).toMatch(/document\.documentElement/);
    expect(код).toMatch(/document\.body/);
  });

  it('снимается тем же путём, что и надевается — забытая прозрачность делает приложение невидимым', () => {
    const код = читать('platform/scanCode.ts');
    expect(код).toMatch(/прозрачность\(true\)/);
    expect(код).toMatch(/прозрачность\(false\)/);
    // Снятие обязано быть в finally: иначе любая ошибка посреди скана оставит человека ни с чем.
    expect(код.slice(код.indexOf('finally'))).toMatch(/прозрачность\(false\)/);
  });

  it('правило красит и корень тоже', () => {
    expect(читать('theme/parts/sheets.css')).toMatch(/html\.скан-идёт/);
  });
});
