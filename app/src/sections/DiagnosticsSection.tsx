import { IonIcon } from '@ionic/react';
import { useState } from 'react';
import { documentTextOutline, shareOutline, warningOutline, qrCodeOutline } from 'ionicons/icons';
import Section from '@/ui/Section';
import Row from '@/ui/Row';
import ScanSheet from '@/sheets/ScanSheet';
import Готовность from '@/ui/Готовность';
import ВПриложении from '@/ui/ВПриложении';
import { мешает } from '@/domain/scanReadiness';
import { useSnapshot, sendIntent } from '@/sources/bridge';
import type { LoggingState } from '@/sources/bridge';

/* Диагностика: уровень лога, захват, выгрузка.

   Понадобилось из-за конкретного случая: сенсор «на связи», а данных нет — и понять
   почему нечем. Драйвер пишет подробный лог с фазами обмена, но из приложения его не
   видно и не достать (SugarLifeCore#17).

   Экран для редкого случая, поэтому лежит в глубине профиля, а не на виду: человеку с
   диабетом диагностика нужна раз в полгода, и место на главном она занимать не должна.

   Два места, где здесь легко навредить, и оба про честность, а не про удобство.

   ПЕРВОЕ: цена подробности. На уровне Trace лог пишется постоянно и заметно ест батарею
   и место. Молча включить и забыть — значит съесть у человека день автономности, и он
   не поймёт почему. Поэтому цена написана рядом, а не спрятана в справку.

   ВТОРОЕ: в логе лежат его данные. Значения сахара, идентификаторы устройств, иногда
   сырой обмен с сенсором. «Поделиться» отправляет это наружу — в мессенджер, в почту,
   в чужие руки. Предупредить об этом обязаны мы, до нажатия, а не после. */

const УРОВНИ: { id: LoggingState['level']; name: string; цена: string }[] = [
  { id: 'Error', name: 'Ошибки', цена: 'только сбои' },
  { id: 'Warn', name: 'Важное', цена: 'сбои и предупреждения' },
  { id: 'Info', name: 'Обычный', цена: 'по умолчанию' },
  { id: 'Debug', name: 'Подробный', цена: 'для разбора проблемы' },
  { id: 'Trace', name: 'Всё подряд', цена: 'ест батарею и место' },
];

export default function DiagnosticsSection({ onClose }: { onClose: () => void }) {
  const [читаем, setЧитаем] = useState(false);
  const snap = useSnapshot();
  const logging = snap?.logging ?? null;
  const [делюсь, setДелюсь] = useState(false);

  /* Чтение кодов с фото живёт ВЫШЕ развилки про логи и намеренно.

     Логи ведёт движок, и в браузере их нет — раздел там показывает заглушку. А чтение
     кодов от движка не зависит вовсе и в браузере работает полностью; спрятав его за той
     же развилкой, мы отняли бы его ровно у того места, где им и будут пользоваться:
     разбирать присланный снимок чужой коробки удобнее за компьютером, а не с телефона. */
  /* Сводка готовности — третий вход из #333, и он для тех, кто вернулся разбираться
     позже. Здесь, в отличие от рабочих экранов, уместно сказать и «всё в порядке»:
     сюда приходят именно с вопросом, а не мимо. */
  const готовность = (
    <>
      <div className="section-label sec">Поиск приборов</div>
      <Готовность помеха={мешает(snap)} спокойно />
    </>
  );

  const коды = (
    <>
      {/* Это стенд, а не рабочий путь: рабочий живёт в поле «Код сенсора», где код и
          спрашивают. Сюда приходят с другим вопросом — «что вообще написано на этой
          коробке». */}
      <div className="section-label sec">Коды на упаковке</div>
      <div className="list">
        <Row icon={qrCodeOutline} title="Прочитать код с фото"
          sub="QR, DataMatrix, штрихкод — покажем строку как есть"
          onClick={() => setЧитаем(true)} />
      </div>
      <div className="sheet-note">
        Что напечатано на коробке, разбирает движок: у каждого производителя своё правило.
        Здесь видно ровно то, что записано в самом коде, — это и нужно прислать, когда
        сенсор не опознаётся.
      </div>
      <ScanSheet isOpen={читаем} onClose={() => setЧитаем(false)} подпись="Любой код с упаковки прибора" />
    </>
  );

  /* Движка нет — и логировать нечего: Nightscout-шим в браузере ничего не пишет.
     Экран с переключателями, которые ни на что не влияют, хуже его отсутствия. */
  if (!logging) {
    return (
      <Section title="Диагностика" описание="Записи о работе приложения и обмене с приборами. Нужны, когда что-то разбирают: сюда попадает то, чего не видно на экранах." onBack={onClose}>
        {готовность}
        {коды}
        <div className="loop-empty">
          <IonIcon icon={documentTextOutline} />
          <div className="loop-empty-t">Логов нет</div>
          <div className="loop-empty-s">
            Лог ведёт движок приложения, а в браузере он не работает. В приложении будет и
            уровень подробности, и выгрузка.
          </div>
          {/* Ссылка вместо совета (#315): человек и так знал, что делать, — он не мог
              сделать это отсюда. */}
          <ВПриложении раздел="диагностика" подпись="Открыть диагностику в приложении" />
        </div>
      </Section>
    );
  }

  const поделиться = async () => {
    setДелюсь(true);
    await sendIntent({ type: 'exportLog' });
    window.setTimeout(() => setДелюсь(false), 2000);
  };

  return (
    <Section title="Диагностика" описание="Записи о работе приложения и обмене с приборами. Нужны, когда что-то разбирают: сюда попадает то, чего не видно на экранах." onBack={onClose}>

      {готовность}
      {коды}

      <div className="section-label sec">Подробность</div>
      <div className="list">
        {УРОВНИ.map((у) => (
          <button key={у.id} className="list-row"
            onClick={() => sendIntent({ type: 'setLogLevel', level: у.id })}>
            <span className="pick-main">
              <span className="list-title">{у.name}</span>
              <span className="pick-sub">{у.цена}</span>
            </span>
            {logging.level === у.id && <span className="meth-now">сейчас</span>}
          </button>
        ))}
      </div>
      <div className="sheet-note">
        Чем подробнее, тем больше расход батареи и места. Для обычной работы хватает
        «обычного»; подробный включают, когда что-то разбирают, и выключают после.
      </div>

      {/* Переключателей «Писать в файл» и «Сырой обмен» здесь больше нет (#317).

          Оба ничего не делали. Флаг доезжал до движка, ложился в переменную и
          возвращался обратно в снимке — круг замыкался, а запись от этого не менялась:
          `captureRaw` и `captureFile` не читаются в ядре нигде, кроме этих трёх мест.
          Плюс не переживали перезапуск, то есть слетали ровно тогда, когда нужны, —
          человек включает подробную запись ПЕРЕД тем, как ловить проблему.

          Настройка, которая ничего не делает, хуже отсутствующей: человек включает её,
          воспроизводит проблему, выгружает лог — а сырья там нет, и узнаёт об этом тот,
          кто будет разбирать, через несколько дней. В разделе «Диагностика» это бьёт
          ещё и по доверию ко всему разделу: если врёт эта настройка, что ещё врёт.

          Вернём, когда ядро начнёт их читать. */}

      <button className="sheet-danger diag-share" onClick={поделиться} disabled={делюсь}>
        <IonIcon icon={делюсь ? shareOutline : shareOutline} />
        {делюсь ? 'Открываю…' : 'Поделиться логом'}
      </button>
      {/* Предупреждение ДО нажатия, а не после: отправленное обратно не вернуть. */}
      <div className="sheet-note warn">
        <IonIcon icon={warningOutline} style={{ verticalAlign: '-2px', marginRight: 4 }} />
        В логе твои данные: значения сахара, идентификаторы устройств, при включённом
        сыром обмене — переписка с сенсором. Отправляй только тому, кто разбирает проблему.
      </div>
    </Section>
  );
}
