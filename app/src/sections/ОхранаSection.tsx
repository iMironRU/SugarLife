import { useState } from 'react';
import { IonToggle } from '@ionic/react';
import Иконка from '@/ui/Иконка';
import { playOutline, chevronForward, musicalNotesOutline } from 'ionicons/icons';
import Section from '@/ui/Section';
import Sheet from '@/ui/Sheet';
import Row from '@/ui/Row';
import { useStack } from '@/app/stackCtx';
import { AlarmsSection } from '@/sections/lazy';
import { useОхрана, подтвердитьФокус, фокусПодтверждён } from '@/показ/охранаХук';
import { useSnapshot, sendIntent } from '@/sources/bridge';
import { сводка, минуты, почему } from '@/показ/былаЛиОхрана';
import { часы } from '@/слова/время';
import type { Строка } from '@/показ/охрана';
import {
  открытьДоступКТихомуРежиму, открытьПолноэкранные, проверитьТревогу, поднимитеГромкость,
  открытьНастройкиТревог,
} from '@/platform/тревоги';
import { попроситьИсключение, задатьБодрствование } from '@/platform/фон';

/* «Охрана» — раздел, отвечающий на один вопрос (#473, core#115).

   Всё, от чего зависит «нас разбудят», было разложено по разным местам: пороги в тревогах,
   сторож молчания там же, доступ к «Не беспокоить» в системе, энергосбережение на экране
   готовности, приборы в снимке. Человек не мог ответить на простое «я защищён этой ночью?».

   ПОРЯДОК ЗДЕСЬ — САМА МЫСЛЬ. Сначала ответ, потом кнопка починки, потом из чего ответ
   сложился, и только в конце пороги. Пороги при беззвучной тревоге не значат ничего: они
   описывают, при каких числах мы будем кричать в подушку.

   ЗЕЛЁНЫХ ГАЛОЧЕК РАДИ ГАЛОЧЕК НЕТ. Список показывает и то, чего мы не знаем, — отдельным
   знаком: вендорскую защиту прошивки проверить нельзя, и «всё в порядке» там было бы
   выдумкой. */
export default function ОхранаSection({ onClose }: { onClose: () => void }) {
  const { push, pop } = useStack();
  const { охрана: о, обновить } = useОхрана();
  const снимок = useSnapshot();
  /* Была ли охрана этой ночью (мост 1.46). Считаем здесь, а не в хуке охраны: это ответ на другой
     вопрос — не «разбудим ли», а «наблюдали ли». Смешивать их значит получить строку, которая
     отвечает на оба сразу и ни на один толком. */
  const дыры = сводка(снимок?.guardHistory ?? [], Date.now());
  const [занят, setЗанят] = useState<string | null>(null);
  const [проверил, setПроверил] = useState(false);
  /** Какой пункт раскрыт шторкой. Один: шторка перекрывает экран, двух сразу не бывает. */
  const [открыт, setОткрыт] = useState<number | null>(null);

  const починить = async (что: NonNullable<Строка['действие']>) => {
    setЗанят(что);
    if (что === 'доступ к «Не беспокоить»') await открытьДоступКТихомуРежиму();
    else if (что === 'разрешить полный экран') await открытьПолноэкранные();
    else if (что === 'включить уведомления') {
      /* Своего экрана для этого у системы нет там же, где остальные: ведём в настройки
         приложения тем же путём, что и фон. */
      await попроситьИсключение();
    }
    else if (что === 'настройки фона') await попроситьИсключение();
    else if (что === 'настройки уведомлений') await открытьНастройкиТревог();
    else if (что === 'разрешить поднимать громкость') {
      /* Никуда не ведём: разрешение наше собственное, и чинится оно здесь же, одним нажатием. */
      await поднимитеГромкость(true);
    }
    else if (что === 'включить ночной звук') {
      /* «Обычное» — раз в пять секунд, как у xDrip4iOS: этого хватает, чтобы система не
         усыпила поток, и это дешевле «настойчивого» по батарее. */
      await задатьБодрствование('обычное');
    }
    setЗанят(null);
    /* Перечитываем: доступ мог быть выдан прямо сейчас, а тревогу мы только что включили
       сами. Экран, оставшийся прежним, читается как «нажал, и не сработало». */
    обновить();
  };

  return (
    <Section title="Охрана"
      описание="Разбудим ли этой ночью. Не список настроек, а ответ: всё, от чего он зависит, собрано здесь."
      onBack={onClose}>

      {!о ? null : (
        <>
          {/* Ответ — первым и предложением, а не галочкой: «этой ночью разбудим» читается
              за полсекунды, список ниже нужен тому, кто спросит «из чего это следует». */}
          <div className={'охрана-ответ ' + (о.ответ === 'разбудим' ? 'да' : 'нет')}>
            <div className="охрана-ответ-заг">
              {о.ответ === 'разбудим' ? 'Этой ночью разбудим'
                : о.ответ === 'не сторожим' ? 'Этой ночью не сторожим'
                  : 'Ночью может не разбудить'}
            </div>
            <div className="охрана-ответ-текст">{о.почему}</div>
          </div>

          {/* Кнопка починки — до списка: человеку, у которого сломано, нужно действие, а не
              отчёт. Ведём в тот системный экран, который закрывает первую же поломку. */}
          {(() => {
            const дело = о.главное;
            if (!дело) return null;
            const подпись = дело === 'доступ к «Не беспокоить»' ? 'Выдать доступ к «Не беспокоить»'
                : дело === 'включить ночной звук' ? 'Держать звук ночью'
                : дело === 'разрешить поднимать громкость' ? 'Поднимать громкость на тревоге'
                : дело === 'настройки уведомлений' ? 'Открыть настройки уведомлений'
                : дело === 'разрешить полный экран' ? 'Разрешить полноэкранные уведомления'
                  : дело === 'включить уведомления' ? 'Включить уведомления'
                    : 'Открыть настройки фона';
            return (
              <button className="changed-btn is-undo во-всю" disabled={занят === дело}
                onClick={() => void починить(дело)}>
                {занят === дело ? 'Открываю…' : подпись}
              </button>
            );
          })()}

          {/* СТРОКА ОТВЕЧАЕТ «ЧТО», ШТОРКА — «ПОЧЕМУ И ЧТО ДЕЛАТЬ» (#529).

              Длинный текст обрывался многоточием прямо в строке: человек видел «нет доступа к
              „Не беспокоить" — ноч…» и не мог ни дочитать, ни понять, как с этим быть. Тот же
              приём, что у правил тревог: список сверху, объяснение по нажатию. */}
          <div className="section-label sec">Из чего это состоит</div>
          <div className="list">
            {о.строки.map((с, i) => (
              <div key={i} className="list-row охрана-пункт">
                <span className={'охрана-знак-п ' + (с.знак === 'ок' ? 'ок' : с.знак === 'нет' ? 'нет' : 'незнаем')} />
                {с.подробно ? (
                  <button className="охрана-пункт-кнопка" onClick={() => setОткрыт(i)}>
                    <span className="list-title">{с.имя}</span>
                    {с.под && <span className="pick-sub">{с.под}</span>}
                  </button>
                ) : (
                  <span className="pick-main">
                    <span className="list-title">{с.имя}</span>
                    {с.под && <span className="pick-sub">{с.под}</span>}
                  </span>
                )}
                {с.знак === 'нет' && с.действие ? (
                  <button className="охрана-чинить" onClick={() => void починить(с.действие!)}>
                    исправить <Иконка icon={chevronForward} />
                  </button>
                ) : с.подробно ? (
                  <Иконка icon={chevronForward} className="охрана-шеврон-п" />
                ) : null}
              </div>
            ))}
          </div>

          {/* Подробность — шторкой снизу: полный текст и что с этим делать. */}
          {открыт != null && о.строки[открыт] && (
            <Sheet isOpen onClose={() => setОткрыт(null)}
              title={о.строки[открыт].имя} subtitle={о.строки[открыт].под}>
              <div className="охрана-подробно">{о.строки[открыт].подробно}</div>
              {о.строки[открыт].знак === 'нет' && о.строки[открыт].действие && (
                <button className="changed-btn is-undo во-всю" style={{ marginTop: 14 }}
                  disabled={занят === о.строки[открыт].действие}
                  onClick={() => { const д = о.строки[открыт!].действие!; setОткрыт(null); void починить(д); }}>
                  Исправить
                </button>
              )}

              {/* ЕДИНСТВЕННОЕ, ЧТО МЫ СПРАШИВАЕМ У ЧЕЛОВЕКА (#561).

                  Состав фокуса «Не беспокоить» система приложению не отдаёт. Пока мы этого не
                  знали, на сборке без права на срочные ответ «ночью может не разбудить» висел
                  вечно — и погасить его было нечем. Предупреждение, которое нельзя устранить,
                  учит не читать предупреждения; владелец сказал об этом прямо.

                  Поэтому спрашиваем один раз и верим на слово: свой экран настроек он видел, а мы
                  нет. Передумать можно тем же переключателем. */}
              {о.строки[открыт].имя === 'Список «Не беспокоить»' && (
                <button className="changed-btn во-всю" style={{ marginTop: 14 }}
                  onClick={() => { подтвердитьФокус(!фокусПодтверждён()); setОткрыт(null); }}>
                  {фокусПодтверждён()
                    ? 'Нет, я не добавлял в разрешённые'
                    : 'Я добавил SugarLife в разрешённые фокуса'}
                </button>
              )}
            </Sheet>
          )}

          {/* Проверочная тревога — здесь же: услышать, как это прозвучит ночью, не
              дожидаясь ночи. Узнать, что тревоги молчат, во время гипогликемии — худший
              из возможных способов узнать. */}
          <button className="changed-btn is-undo во-всю" style={{ marginTop: 12 }}
            onClick={() => { void проверитьТревогу(); setПроверил(true); }}>
            <Иконка icon={playOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
            Проверить тревогу сейчас
          </button>
          {проверил && (
            <div className="sheet-note">
              Если ничего не прозвучало — тревога не разбудит и ночью. Проверьте список выше.
            </div>
          )}
        </>
      )}

      {/* БЫЛА ЛИ ОХРАНА — ПОСЛЕ ОБЕЩАНИЯ, ДО НАСТРОЕК.

          Обещание отвечает на «разбудят ли меня сегодня», эти строки — на «наблюдали ли, пока я
          спал». Второй вопрос человек задаёт утром, и до сих пор ответить на него было нечем:
          приложение, поднявшееся после выгрузки, вело себя как ни в чём не бывало.

          Место выбрано не нами: ядро назвало его в контракте — рядом с обещанием, там же, где
          человек об этом думает. */}
      {дыры.ответ && (
        <>
          <div className="section-label sec">Пока вас не было</div>
          <div className="list">
            <div className="охрана-дыры">
              <div className="охрана-дыры-ответ">{дыры.ответ}</div>
              {/* Подробности мельче и ниже: «когда именно» спрашивает не каждый, а ответ нужен всем. */}
              <div className="охрана-дыры-список">
                {(снимок?.guardHistory ?? []).slice(-5).reverse().map((д) => (
                  <div key={д.atMs}>
                    {часы(д.atMs)}{' · '}{минуты(д.minutes)}
                    {почему(д.why) ? ' · ' + почему(д.why) : ''}
                  </div>
                ))}
              </div>
            </div>
          </div>
        </>
      )}

      <div className="section-label sec">Настройки</div>
      <div className="list">
        {/* ПЕРЕХВАТ ЗВУКА В МАШИНЕ (мост 1.63, ядро #180).

            Опора — это воспроизведение: пока она держится, головное устройство переключено на
            телефон, и радио с тюнера магнитолы человек не слышит. До 1.63 ядро выбирало за него
            радио, и мы измерили цену: пять раз из пяти система убивала приложение в ту же минуту
            после запрета опоры — ровно за рулём. Теперь умолчание обратное.

            Но выбор остаётся за человеком, и потому выключатель здесь. Цену называем обеими
            сторонами: включено — можно остаться без радио, выключено — можно остаться без
            тревоги. Второе тише и потому опаснее, поэтому оно и написано в подписи. */}
        <Row icon={musicalNotesOutline} title="Перехватывать звук в машине"
          sub={снимок?.audio?.holdAudioAnchor === false
            ? 'выключено: система может выгрузить приложение за рулём, и тогда тревога не прозвучит'
            : 'держим звук, иначе за рулём приложение выгружается; если играло радио — нажмите на магнитоле выбор источника'}
          right={<IonToggle checked={снимок?.audio?.holdAudioAnchor !== false}
            onIonChange={(e) => {
              /* Пишем ключ, а не решение: держать или нет — считает движок, мы лишь передаём
                 волю человека. `on` не шлём пустым — движок ждёт `off` или отсутствие ключа. */
              void sendIntent({ type: 'setConfig', patch: { 'audio.carAnchor': e.detail.checked ? null : 'off' } });
            }} />} />
        <Row icon={playOutline} title="Правила тревог"
          sub="по каким числам движок решает будить — и что из этого можно поправить"
          onClick={() => push(<AlarmsSection onClose={pop} />, { id: 'тревоги' })} />
      </div>
    </Section>
  );
}
