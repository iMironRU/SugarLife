import { useState } from 'react';
import Иконка from '@/ui/Иконка';
import { playOutline, chevronForward } from 'ionicons/icons';
import Section from '@/ui/Section';
import Row from '@/ui/Row';
import { useStack } from '@/app/stackCtx';
import { AlarmsSection } from '@/sections/lazy';
import { useОхрана } from '@/показ/охранаХук';
import type { Строка } from '@/показ/охрана';
import { открытьДоступКТихомуРежиму, проверитьТревогу, задатьТревогу, настройкиТревоги } from '@/platform/тревоги';
import { попроситьИсключение, задатьБодрствование } from '@/platform/фон';

/* «Охрана» — раздел, отвечающий на один вопрос (#473, core#115).

   Всё, от чего зависит «нас разбудят», было разложено по разным местам: пороги в тревогах,
   сторож молчания там же, доступ к «Не беспокоить» в системе, энергосбережение на экране
   готовности, приборы в снимке. Человек не мог ответить на простое «я защищён этой ночью?».

   ПОРЯДОК ЗДЕСЬ — САМА МЫСЛЬ. Сначала ответ, потом кнопка починки, потом из чего ответ
   сложился, и только в конце пороги. Пороги при беззвучной тревоге не значат ничего: они
   описывают, при каких числах мы будем кричать в подушку.

   ЗЕЛЁНЫХ ГАЛОЧЕК РАДИ ГАЛОЧЕК НЕТ. Список показывает и то, чего мы не знаем, — отдельным
   знаком: вендорскую защиту прошивки проверить нельзя, и «всё в порядке» там было бы
   выдумкой. */
export default function ОхранаSection({ onClose }: { onClose: () => void }) {
  const { push, pop } = useStack();
  const { охрана: о, обновить } = useОхрана();
  const [занят, setЗанят] = useState<string | null>(null);
  const [проверил, setПроверил] = useState(false);

  const починить = async (что: NonNullable<Строка['действие']>) => {
    setЗанят(что);
    if (что === 'доступ к «Не беспокоить»') await открытьДоступКТихомуРежиму();
    else if (что === 'настройки фона') await попроситьИсключение();
    else if (что === 'включить сторож') {
      const н = await настройкиТревоги();
      if (н) await задатьТревогу({ ...н, silenceOn: true });
    } else if (что === 'включить ночной звук') {
      /* «Обычное» — раз в пять секунд, как у xDrip4iOS: этого хватает, чтобы система не
         усыпила поток, и это дешевле «настойчивого» по батарее. */
      await задатьБодрствование('обычное');
    } else if (что === 'включить тревогу') {
      const н = await настройкиТревоги();
      if (н) await задатьТревогу({ ...н, on: true });
    }
    setЗанят(null);
    /* Перечитываем: доступ мог быть выдан прямо сейчас, а тревогу мы только что включили
       сами. Экран, оставшийся прежним, читается как «нажал, и не сработало». */
    обновить();
  };

  return (
    <Section title="Охрана"
      описание="Разбудим ли этой ночью. Не список настроек, а ответ: всё, от чего он зависит, собрано здесь."
      onBack={onClose}>

      {!о ? null : (
        <>
          {/* Ответ — первым и предложением, а не галочкой: «этой ночью разбудим» читается
              за полсекунды, список ниже нужен тому, кто спросит «из чего это следует». */}
          <div className={'охрана-ответ ' + (о.ответ === 'разбудим' ? 'да' : 'нет')}>
            <div className="охрана-ответ-заг">
              {о.ответ === 'разбудим' ? 'Этой ночью разбудим'
                : о.ответ === 'не сторожим' ? 'Этой ночью не сторожим'
                  : 'Ночью может не разбудить'}
            </div>
            <div className="охрана-ответ-текст">{о.почему}</div>
          </div>

          {/* Кнопка починки — до списка: человеку, у которого сломано, нужно действие, а не
              отчёт. Ведём в тот системный экран, который закрывает первую же поломку. */}
          {(() => {
            const дело = о.главное;
            if (!дело) return null;
            const подпись = дело === 'доступ к «Не беспокоить»' ? 'Выдать доступ к «Не беспокоить»'
              : дело === 'включить сторож' ? 'Включить сторож молчания'
                : дело === 'включить тревогу' ? 'Включить тревогу о низком сахаре'
                : дело === 'включить ночной звук' ? 'Держать звук ночью'
                  : 'Открыть настройки фона';
            return (
              <button className="changed-btn is-undo во-всю" disabled={занят === дело}
                onClick={() => void починить(дело)}>
                {занят === дело ? 'Открываю…' : подпись}
              </button>
            );
          })()}

          <div className="section-label sec">Из чего это состоит</div>
          <div className="list">
            {о.строки.map((с, i) => (
              <div key={i} className="list-row охрана-пункт">
                <span className={'охрана-знак-п ' + (с.знак === 'ок' ? 'ок' : с.знак === 'нет' ? 'нет' : 'незнаем')} />
                <span className="pick-main">
                  <span className="list-title">{с.имя}</span>
                  {с.под && <span className="pick-sub">{с.под}</span>}
                </span>
                {с.знак === 'нет' && с.действие && (
                  <button className="охрана-чинить" onClick={() => void починить(с.действие!)}>
                    исправить <Иконка icon={chevronForward} />
                  </button>
                )}
              </div>
            ))}
          </div>

          {/* Проверочная тревога — здесь же: услышать, как это прозвучит ночью, не
              дожидаясь ночи. Узнать, что тревоги молчат, во время гипогликемии — худший
              из возможных способов узнать. */}
          <button className="changed-btn is-undo во-всю" style={{ marginTop: 12 }}
            onClick={() => { void проверитьТревогу(); setПроверил(true); }}>
            <Иконка icon={playOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
            Проверить тревогу сейчас
          </button>
          {проверил && (
            <div className="sheet-note">
              Если ничего не прозвучало — тревога не разбудит и ночью. Проверьте список выше.
            </div>
          )}
        </>
      )}

      <div className="section-label sec">Настройки</div>
      <div className="list">
        <Row icon={playOutline} title="Пороги и тихие часы"
          sub="при каких числах будить и когда молчать о высоком"
          onClick={() => push(<AlarmsSection onClose={pop} />, { id: 'тревоги' })} />
      </div>
    </Section>
  );
}
