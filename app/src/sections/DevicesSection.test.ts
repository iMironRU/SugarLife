import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';

/* Барьер против немой плитки (SugarLife#301).

   Плитка прибора была неподвижным `div`, хотя подсказка прямо под списком обещала «тапни
   устройство — там все действия». Известный прибор нельзя было подключить ничем: на
   плитке «Подключить» показывалось только когда прибор замечен в эфире, а в эфир он
   попадает, лишь когда его слушают. Поиск нового по построению показывает только
   НЕзнакомых. Кольцо замкнулось, и на железе это встало намертво.

   Проверять здесь есть что ровно потому, что поломка была не в логике, а в отсутствии
   обработчика: тесты домена такое не видят, а глазами это ловится только на телефоне с
   реальным прибором — то есть в самый дорогой момент.

   Проверяем текст исходника, а не рендер: рендерить пришлось бы Ionic-модалку со стеком
   и снимком, и тест сломался бы от любой перестановки, ничего не сторожа. */

const секция = readFileSync('src/sections/DevicesSection.tsx', 'utf8');
const карточка = readFileSync('src/sheets/HardwareSheet.tsx', 'utf8');

describe('список приборов', () => {
  it('плитка прибора нажимаема и открывает карточку', () => {
    /* Именно button: div с onClick не даёт ни фокуса, ни клавиатуры, ни озвучки. */
    expect(секция).toMatch(/<button key=\{d\.id} className="list-row" onClick=/);
  });

  /* Подсказка не украшение — это единственное место, где сказано, где искать действия.
     Разъехаться она может только вместе с карточкой, поэтому сторожим обе. */
  it('обещание подсказки подкреплено карточкой', () => {
    expect(секция).toContain('Тапни устройство');
    expect(секция).toContain('HardwareSheet');
  });

  /* Кнопка внутри кнопки — невалидная разметка, и тап по плитке слился бы с тапом по
     действию. Действия живут в карточке, на плитке их нет вовсе. */
  it('на плитке нет кнопок действий', () => {
    const список = секция.slice(секция.indexOf('className="list-row"'), секция.indexOf('Найти новое устройство'));
    expect(список).not.toContain('changed-btn');
    expect(список).not.toContain('sendIntent');
  });
});

describe('карточка прибора', () => {
  /* Главное свойство карточки: «Подключить» здесь БЕЗУСЛОВНО. Вернуть сюда проверку
     «рядом» значит вернуть то самое кольцо — прибор не подключить, пока он не подключён. */
  it('«Подключить» не зависит от того, замечен ли прибор в эфире', () => {
    expect(карточка).toMatch(/type: 'connect'/);
    /* Сторожим механизм, а не слово: «рядом» в тексте кнопки как раз уместно — оно
       объясняет, почему действие может не сработать. Нельзя другое — брать это
       условием, а условие приходит из рядомЖелезо. */
    expect(карточка).not.toContain('рядомЖелезо');
  });

  it('умеет отпустить, прочитать и забыть', () => {
    for (const т of ["'disconnect'", "'readNow'", "'removeDevice'"]) expect(карточка).toContain(т);
  });

  /* Забыть — это удаление записи из движка целиком: серийник, мост, настройки драйвера.
     Вернуть можно только новым поиском, поэтому без спроса нельзя. */
  it('«Забыть» спрашивает подтверждение', () => {
    const от = карточка.indexOf('const забыть');
    const кусок = карточка.slice(от, карточка.indexOf('removeDevice', от));
    expect(кусок).toContain('window.confirm');
  });
});
