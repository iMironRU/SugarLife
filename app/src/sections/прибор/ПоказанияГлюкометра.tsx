import { датаИВремя } from '@/слова/время';
import { toUnits, unitLabel } from '@/domain/units';

/* Последние показания с пальца — только для карточки глюкометра (#406).

   ПОЧЕМУ ОНИ НЕ В ЛЕНТЕ СЕНСОРА. С пальца точнее по крови, но реже по времени: подмешав
   их в ленту, мы дали бы им в расчётах диапазона вес, которого у них нет. Поэтому они
   живут отдельно и объясняют это прямо здесь — иначе первый же вопрос будет «а почему их
   нет в графике». */
export default function ПоказанияГлюкометра({ список }: { список: { t: number; mmol: number }[] }) {
  if (!список.length) return null;
  return (
    <>
      <div className="section-label sec">Последние показания</div>
      <div className="basal-rows">
        {[...список].reverse().slice(0, 8).map((x) => (
          <div key={x.t} className="basal-row">
            <span>{датаИВремя(x.t)}</span>
            <b>{toUnits(x.mmol)} {unitLabel()}</b>
          </div>
        ))}
      </div>
      <div className="sheet-note">
        Эти показания не подмешиваются в ленту сенсора: с пальца точнее по крови,
        но реже по времени, и в расчётах диапазона вес у них был бы неправильный.
      </div>
    </>
  );
}
