import { describe, it, expect } from 'vitest';
import { строкиСостояния } from './строкиСостояния';
import { телеметрияМоста, силаСигнала } from './телеметрияМоста';
import { прямоеЧтение } from './прямоеЧтение';

/* Правила карточки прибора (#406).

   Все три жили внутри семисот строк на четыре разных прибора и проверялись только глазами. Здесь
   не форма, а решения: какие числа человек видит, откуда они взяты и куда его ведёт единственная
   кнопка «прямое чтение». */

const возраст = (days: number) => ({ at: 0, days, hours: days * 24 });

describe('строки состояния', () => {
  it('у сенсора — день и сколько носится', () => {
    expect(строкиСостояния('sensor', { возрастСенсора: возраст(6) })).toEqual([
      { k: 'День', v: '7' },
      { k: 'Носится', v: '6 дн' },
    ]);
  });

  /* День СЕДЬМОЙ при шести полных сутках: человек считает дни ношения с первого, а не с нулевого. */
  it('первый день сенсора называется первым', () => {
    expect(строкиСостояния('sensor', { возрастСенсора: возраст(0) })[0]).toEqual({ k: 'День', v: '1' });
  });

  it('нет возраста — нет строк, а не прочерки', () => {
    expect(строкиСостояния('sensor', {})).toEqual([]);
    expect(строкиСостояния('pump', { прибор: {} })).toEqual([]);
  });

  /* Остаток от движка вытесняет наш из облака: два разных остатка на двух экранах — повод
     усомниться в обоих (#596). */
  it('остаток движка вытесняет облачный', () => {
    const строки = строкиСостояния('pump', { прибор: { reservoir: 120 }, остаток: { units: 58 } });
    expect(строки).toContainEqual({ k: 'Резервуар', v: '58 ед' });
    expect(строки).not.toContainEqual({ k: 'Резервуар', v: '120 ед' });
  });

  it('движок молчит — берём облачный', () => {
    expect(строкиСостояния('pump', { прибор: { reservoir: 120 }, остаток: null }))
      .toContainEqual({ k: 'Резервуар', v: '120 ед' });
  });

  /* «Хватит» — словами движка. Своей фразы не пишем: он знает про заправку катетера и временные
     базалы, а наш ответ на тот же вопрос однажды пообещал владельцу четыре лишних дня инсулина. */
  it('«хватит» — только словами движка', () => {
    expect(строкиСостояния('pump', { остаток: { units: 58, words: '≈ 2 д 4 ч' } }))
      .toContainEqual({ k: 'Хватит', v: '≈ 2 д 4 ч' });
    expect(строкиСостояния('pump', { остаток: { units: 58 } }).map((с) => с.k)).not.toContain('Хватит');
  });

  it('ноль в подаче — это значение, а не пустота', () => {
    const строки = строкиСостояния('pump', { прибор: { tempRate: 0, pumpBattery: 0 } });
    expect(строки).toContainEqual({ k: 'Временный базал', v: '0,0 ед/ч' });
    expect(строки).toContainEqual({ k: 'Батарея', v: '0%' });
  });

  it('глюкометру и петле здесь сказать нечего', () => {
    expect(строкиСостояния('meter', { прибор: { reservoir: 50 }, возрастСенсора: возраст(3) })).toEqual([]);
    expect(строкиСостояния('loop', { прибор: { status: 'Live' } })).toEqual([]);
  });
});

describe('телеметрия моста', () => {
  it('чего не знаем — не рисуем', () => {
    expect(телеметрияМоста(null, null)).toEqual([]);
    expect(телеметрияМоста({}, null)).toEqual([]);
  });

  it('заряд из снимка важнее облачного', () => {
    expect(телеметрияМоста({ batteryPct: 60 }, 42)[0]).toEqual({ k: 'Заряд моста', v: '60%' });
  });

  /* Заряд из AAPS приходит только вместе с расчётом цикла и пропадает вместе с ним — поэтому он
     запасной, а не основной. */
  it('снимок молчит — берём облачный', () => {
    expect(телеметрияМоста({}, 42)[0]).toEqual({ k: 'Заряд моста', v: '42%' });
  });

  it('ноль процентов — это заряд, а не отсутствие данных', () => {
    expect(телеметрияМоста({ batteryPct: 0 }, null)).toEqual([{ k: 'Заряд моста', v: '0%' }]);
  });

  /* Человеку нужен ответ «стоит ли переложить телефон ближе», а не число в дБм. */
  it('сигнал — числом и словом', () => {
    expect(силаСигнала(-55)).toBe('хороший');
    expect(силаСигнала(-70)).toBe('хороший');
    expect(силаСигнала(-71)).toBe('средний');
    expect(силаСигнала(-85)).toBe('средний');
    expect(силаСигнала(-86)).toBe('слабый');
    expect(телеметрияМоста({ rssi: -92 }, null)).toEqual([{ k: 'Сигнал', v: '-92 дБм · слабый' }]);
  });
});

describe('прямое чтение', () => {
  const всёГотово = {
    записанБезМодели: false, нативная: true, нуженМост: false,
    естьМост: false, естьДрайвер: true, наСвязи: false, ужеЗаведён: false,
  };

  /* Порядок препятствий и есть правило: без модели неизвестно даже, что искать. */
  it('без модели ведём выбирать модель — раньше всего остального', () => {
    expect(прямоеЧтение({ ...всёГотово, записанБезМодели: true, нативная: false, естьДрайвер: false }).делать)
      .toBe('выбрать-модель');
  });

  it('в браузере BLE нет как класса — и жать некуда', () => {
    const о = прямоеЧтение({ ...всёГотово, нативная: false });
    expect(о.делать).toBe('ничего');
    expect(о.подпись).toContain('браузер');
  });

  it('нужен мост и его нет — ведём выбирать мост', () => {
    expect(прямоеЧтение({ ...всёГотово, нуженМост: true }).делать).toBe('выбрать-мост');
    expect(прямоеЧтение({ ...всёГотово, нуженМост: true, естьМост: true }).делать).toBe('искать');
  });

  it('драйвера нет — говорим прямо и никуда не ведём', () => {
    expect(прямоеЧтение({ ...всёГотово, естьДрайвер: false }).делать).toBe('ничего');
  });

  it('на связи — жать нечего', () => {
    expect(прямоеЧтение({ ...всёГотово, наСвязи: true })).toEqual({ подпись: 'подключено', делать: 'ничего' });
  });

  /* Поиск показывает только НЕзнакомых. Для заведённого прибора он открывал пустой экран, где
     прибор не появится никогда (#301) — поэтому заведённого подключаем по id. */
  it('заведённый прибор подключаем, а не ищем заново', () => {
    expect(прямоеЧтение({ ...всёГотово, ужеЗаведён: true }).делать).toBe('подключить-известный');
  });

  it('незнакомый — ищем в эфире', () => {
    expect(прямоеЧтение(всёГотово).делать).toBe('искать');
  });

});
