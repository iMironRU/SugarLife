/*
 * ПРЯМОЕ ЧТЕНИЕ: ЧТО МЕШАЕТ И ЧТО ДЕЛАТЬ (#406).
 *
 * Одна строка на экране прибора отвечает сразу на два вопроса: «почему не подключено» и «куда
 * жать». Ответ — лестница препятствий, и ПОРЯДОК В НЕЙ И ЕСТЬ ПРАВИЛО: без модели неизвестно
 * даже, что искать; в браузере BLE нет как класса; дальше мост и наличие драйвера.
 *
 * Правило жило двумя вложенными тернарными лесенками внутри карточки на четыре прибора, и
 * проверить его было нечем. А ошибка в нём стоит дорого: один раз строка вела в поиск для
 * прибора, который уже заведён, — поиск по построению показывает только НЕзнакомых, и человек
 * открывал пустой экран, где его прибор не появится никогда (#301).
 */

export type ЧтоДелатьСПрямым =
  | 'выбрать-модель'
  | 'выбрать-мост'
  | 'подключить-известный'
  | 'искать'
  | 'ничего';

export interface СостояниеПрямого {
  подпись: string;
  делать: ЧтоДелатьСПрямым;
}

export function прямоеЧтение(в: {
  /** Прибор записан, но модель не выбрана: неизвестно, чем его читать. */
  записанБезМодели: boolean;
  /** Нативная сборка. В браузере BLE нет как класса — это свойство платформы, а не «пока не сделали». */
  нативная: boolean;
  /** Модели этого вида нужен мост (Libre 1 не вещает сам, Paradigm говорит по радио). */
  нуженМост: boolean;
  /** Мост выбран или виден в снимке. */
  естьМост: boolean;
  /** Движок предлагает драйвер для этого вида — прямой или через мост. */
  естьДрайвер: boolean;
  /** Связь живая прямо сейчас. */
  наСвязи: boolean;
  /** Этот вид уже заведён у движка: подключаться надо К НЕМУ, а не искать заново. */
  ужеЗаведён: boolean;
}): СостояниеПрямого {
  if (в.записанБезМодели) return { подпись: 'сначала укажите модель — иначе неизвестно, как читать', делать: 'выбрать-модель' };
  if (!в.нативная) return { подпись: 'только в приложении для телефона — браузер не умеет BLE', делать: 'ничего' };
  if (в.нуженМост && !в.естьМост) return { подпись: 'нужен мост — выбрать', делать: 'выбрать-мост' };
  if (!в.естьДрайвер) return { подпись: 'драйвер этого устройства ещё в разработке', делать: 'ничего' };
  if (в.наСвязи) return { подпись: 'подключено', делать: 'ничего' };
  if (в.ужеЗаведён) return { подпись: 'подключить — прибор уже заведён', делать: 'подключить-известный' };
  return { подпись: 'найти прибор в эфире', делать: 'искать' };
}
