import type { DeviceCatKey } from '@/sections/DeviceSection';
import type { Age } from '@/domain/treatmentStats';
import { ageText } from './поКатегории';
import { fmt } from '@/domain/units';

/*
 * «СЕЙЧАС НА УСТРОЙСТВЕ» — ЧТО ИМЕННО ПОКАЗЫВАЕМ (#406).
 *
 * Правило жило внутри карточки прибора, в `useMemo` посреди семисот строк на четыре разных
 * прибора. Проверить его было нельзя, а решает оно не мелочь: какие числа человек видит про свою
 * помпу и откуда они взяты. Два таких числа мы уже разводили руками — остаток и «на сколько
 * хватит» приходили то от движка, то из веб-слоя, и два разных ответа на один вопрос заставляли
 * сомневаться в обоих (#596).
 *
 * Здесь только выбор строк. Пустых не рисуем вовсе: строка «Прошивка —» выглядит как поломка, а
 * не как отсутствие данных.
 */

export interface СтрокаСостояния { k: string; v: string }

/** То, что знает движок про подачу инсулина. Пусто — не считал, и врать нечем. */
export interface ОстатокДвижка { units?: number | null; words?: string | null }

/** Прибор из нашего слоя: то, что доехало через Nightscout. Запасной ответ, когда движок молчит. */
export interface ПриборИзОблака {
  status?: string | null;
  reservoir?: number | null;
  pumpBattery?: number | null;
  baseBasal?: number | null;
  tempRate?: number | null;
  lastBolus?: number | null;
}

export function строкиСостояния(
  cat: DeviceCatKey,
  вход: {
    прибор?: ПриборИзОблака | null;
    остаток?: ОстатокДвижка | null;
    возрастСенсора?: Age | null;
  },
): СтрокаСостояния[] {
  const строки: СтрокаСостояния[] = [];
  const dev = вход.прибор ?? null;

  if (cat === 'sensor' && вход.возрастСенсора) {
    строки.push({ k: 'День', v: String(вход.возрастСенсора.days + 1) });
    строки.push({ k: 'Носится', v: ageText(вход.возрастСенсора) });
  }

  if (cat === 'pump') {
    if (dev?.status) строки.push({ k: 'Статус', v: dev.status });
    /* ОСТАТОК — ОТ ДВИЖКА, КОГДА ОН ЕГО СЧИТАЕТ (#596). Кружок на «Сегодня» уже берёт его оттуда;
       здесь стоял наш из веб-слоя, и два разных остатка на двух экранах — повод усомниться в обоих. */
    const остаток = вход.остаток?.units ?? dev?.reservoir;
    if (остаток != null) строки.push({ k: 'Резервуар', v: Math.round(остаток) + ' ед' });
    /* НА СКОЛЬКО ХВАТИТ — СЛОВАМИ ДВИЖКА, А НЕ НАШИМИ (#596).

       Своей формулировки не пишем: движок считает по падению остатка и знает про заправку
       катетера и временные базалы; наша фраза про то же самое была бы вторым ответом на один
       вопрос — таких мы за день ловили шесть, и один обещал владельцу четыре лишних дня инсулина. */
    if (вход.остаток?.words) строки.push({ k: 'Хватит', v: вход.остаток.words });
    if (dev?.pumpBattery != null) строки.push({ k: 'Батарея', v: dev.pumpBattery + '%' });
    if (dev?.baseBasal != null) строки.push({ k: 'Базальная скорость', v: fmt(dev.baseBasal) + ' ед/ч' });
    if (dev?.tempRate != null) строки.push({ k: 'Временный базал', v: fmt(dev.tempRate) + ' ед/ч' });
    if (dev?.lastBolus != null) строки.push({ k: 'Последний болюс', v: fmt(dev.lastBolus) + ' ед' });
  }

  return строки;
}
