import Иконка from '@/ui/Иконка';
import { sparklesOutline } from 'ionicons/icons';
import type { Догадка } from '@/domain/догадкаМодели';

/* ПРИБОР УЖЕ НАЗВАЛСЯ — предлагаем, а не отправляем в список из 69 (SugarLife#485).

   Кнопка ставит модель одним тапом, но ставит её ЧЕЛОВЕК. Молчаливо записать нельзя: модель у нас
   определяет резервуар и спецификации, и ошибка в ней — это враньё в прогнозе «на сколько хватит»,
   которого человек не заметит.

   ОСНОВАНИЕ ДОГАДКИ ПОКАЗЫВАЕМ РЯДОМ. «Похоже, это Paradigm 522/722» без объяснения — это фокус;
   «прибор назвался Medtronic 722» — то, что человек может проверить сам, посмотрев на помпу.

   Полный справочник остаётся на месте, строкой ниже: семейство драйвера — не модель, у одного
   `medtronic` десяток строк с разной ёмкостью, и разницу знает только человек. */
export default function ДогадкаМодели({ догадки, onВыбрать }: {
  догадки: Догадка[]; onВыбрать: (id: string) => void;
}) {
  if (!догадки.length) return null;
  const [первая] = догадки;
  return (
    <>
      <div className="today-alert">
        <Иконка icon={sparklesOutline} className="alert-ico" />
        <div>
          <span className="alert-title">
            {первая.точно ? 'Похоже, это' : 'Возможно, это'} {первая.имя}
          </span>
          <span>
            Прибор назвался «{первая.какНазвался}». Модель нужна нам для резервуара и спецификаций —
            выбрать её всё равно вам, мы только предлагаем.
          </span>
          <span className="alert-ask alert-ask-row">
            {догадки.map((д) => (
              <button key={д.id} className="changed-btn is-undo" onClick={() => onВыбрать(д.id)}>
                {догадки.length === 1 ? 'Это она' : д.имя}
              </button>
            ))}
          </span>
        </div>
      </div>
    </>
  );
}
