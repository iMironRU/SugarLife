import Иконка from '@/ui/Иконка';
import { sparklesOutline } from 'ionicons/icons';
import type { Догадка } from '@/domain/догадкаМодели';
import { имяСправочникаРядом } from '@/domain/имяПрибора';

/* ПРИБОР УЖЕ НАЗВАЛСЯ — предлагаем, а не отправляем в список из 69 (SugarLife#485).

   Кнопка ставит модель одним тапом, но ставит её ЧЕЛОВЕК. Молчаливо записать нельзя: модель у нас
   определяет резервуар и спецификации, и ошибка в ней — это враньё в прогнозе «на сколько хватит»,
   которого человек не заметит.

   КРУПНО — ИМЯ ИЗ ЭФИРА, А НЕ ИМЯ СПРАВОЧНИКА (#770).

   Здесь заголовком стояло «Похоже, это Paradigm 522/722», а «прибор назвался Medtronic 722» уходило
   в объяснение. Снаружи это читалось как ДВЕ РАЗНЫЕ ЖЕЛЕЗКИ, и владелец справедливо спросил, какая
   из них его: два имени, оба заголовками, и ни слова о том, что прибор один.

   Переворачиваем. Крупно — то, что человек может проверить сам, посмотрев на помпу. Имя справочника
   идёт следом, с ролью: под ним мы знаем резервуар и спецификации. И на кнопке стоит оно же —
   нажимая, человек видит, что именно записывает.

   Полный справочник остаётся на месте, строкой ниже: семейство драйвера — не модель, у одного
   `medtronic` десяток строк с разной ёмкостью, и разницу знает только человек. */
export default function ДогадкаМодели({ догадки, onВыбрать }: {
  догадки: Догадка[]; onВыбрать: (id: string) => void;
}) {
  if (!догадки.length) return null;
  const [первая] = догадки;
  const одна = догадки.length === 1;
  /* Имена совпали — второго не рисуем вовсе: «он же называется так же» это шум, а не связь. */
  const второе = одна ? имяСправочникаРядом(первая.какНазвался, первая.имя) : null;
  return (
    <>
      <div className="today-alert">
        <Иконка icon={sparklesOutline} className="alert-ico" />
        <div>
          <span className="alert-title">{первая.какНазвался}</span>
          <span>
            {второе ? <>
              Так прибор назвался сам — это имя можно сверить с надписью на корпусе.
              В нашем справочнике {первая.точно ? 'он же' : 'похоже, он же'} называется «{второе}»:
              под этим именем мы знаем его резервуар и спецификации. Прибор один, имена
              разные — выбрать модель всё равно вам.
            </> : <>
              Так прибор назвался сам. Модель нужна нам для резервуара и спецификаций —
              выбрать её всё равно вам, мы только предлагаем.
            </>}
          </span>
          <span className="alert-ask alert-ask-row">
            {догадки.map((д) => (
              <button key={д.id} className="changed-btn is-undo" onClick={() => onВыбрать(д.id)}>
                {одна ? `Это ${д.имя}` : д.имя}
              </button>
            ))}
          </span>
        </div>
      </div>
    </>
  );
}
