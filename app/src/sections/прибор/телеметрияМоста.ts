/*
 * ЧТО МОСТ РАССКАЗЫВАЕТ О СЕБЕ САМ (#406).
 *
 * Это НЕ настройки: у OrangeLink и MiaoMiao пользовательских параметров нет вовсе, а заряд,
 * прошивка и сигнал есть. Порядок источников не вкусовой — прямое чтение живёт своей жизнью, а
 * заряд из AAPS приходит только вместе с расчётом и при молчащем цикле пропадает вместе с ним.
 *
 * Чего не знаем — не рисуем: пустая строка «Прошивка —» выглядит как поломка, а не как
 * отсутствие данных.
 */

export interface СтрокаМоста { k: string; v: string }

export interface МостВСнимке {
  batteryPct?: number | null;
  firmware?: string | null;
  rssi?: number | null;
}

/*
 * СИГНАЛ СЛОВОМ, А НЕ ТОЛЬКО ЧИСЛОМ.
 *
 * RSSI в дБм — отрицательное число, и меньше значит хуже. Человеку это не говорит ничего, а
 * ответ ему нужен один: стоит ли переложить телефон ближе. Пороги грубые и намеренно такие —
 * точность здесь не нужна.
 */
export function силаСигнала(rssi: number): string {
  return rssi >= -70 ? 'хороший' : rssi >= -85 ? 'средний' : 'слабый';
}

export function телеметрияМоста(
  мост: МостВСнимке | null | undefined,
  зарядИзОблака: number | null | undefined,
): СтрокаМоста[] {
  const строки: СтрокаМоста[] = [];
  const заряд = мост?.batteryPct ?? зарядИзОблака ?? null;
  if (заряд != null) строки.push({ k: 'Заряд моста', v: заряд + '%' });
  if (мост?.firmware) строки.push({ k: 'Прошивка', v: мост.firmware });
  if (мост?.rssi != null) строки.push({ k: 'Сигнал', v: `${мост.rssi} дБм · ${силаСигнала(мост.rssi)}` });
  return строки;
}
