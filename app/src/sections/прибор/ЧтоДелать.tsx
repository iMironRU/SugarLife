import type { Problem } from '@/sources/bridge';

/* ЧТО ДЕЛАТЬ, КОГДА ПРИБОР НЕ РАБОТАЕТ (мост ≥ 1.58, ядро #171).

   До 1.58 человек видел «нет связи» — и всё. При этом у движка лежал готовый справочник ошибок по
   RFC 9457: стабильный код, заголовок, «что делать», серьёзность. Он просто не показывался никому,
   кроме облачных учёток: функция, превращавшая беду в человеческие слова, не вызывалась ниоткуда.

   ОТЛИЧИЕ ОТ ПОДСКАЗКИ (`note`) — в том, чей это ответ. Подсказка — догадка движка по поведению
   («долго не встаёт, возможно занят»); здесь — случившийся отказ с адресом. Ядро сказало прямо:
   показывать оба, они отвечают на разные вопросы. Поэтому это отдельный блок, а не замена.

   СВОИХ СЛОВ НЕ ПИШЕМ. `remediation` показывается как есть: он говорит, КУДА ИДТИ, и ошибка здесь
   стоит человеку получаса, а ночью — ночи. Правило записано в мосте рядом с типом.

   Код показываем мелко и рядом: по нему ищут в переписке и в задачах. Человеку он не мешает —
   он к нему и не приглядывается, — а нам без него разбор идёт по пересказу. */
export default function ЧтоДелать({ беда }: { беда?: Problem | null }) {
  if (!беда) return null;
  const тяжёлая = беда.severity === 'Error' || беда.severity === 'Critical';
  return (
    <div className={'sheet-note' + (тяжёлая ? ' warn' : '')}>
      <b>{беда.title}</b>
      {беда.remediation ? <> {беда.remediation}</> : null}
      <span className="что-делать-код">{беда.code}</span>
    </div>
  );
}
