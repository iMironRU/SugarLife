import Иконка from '@/ui/Иконка';
import { имяДня, часы } from '@/слова/время';
import { useState } from 'react';
import { restaurantOutline, cloudOutline, chevronForward } from 'ionicons/icons';
import Section from '@/ui/Section';
import { useTreatments, useEntries } from '@/sources/db';
import { useMeals } from '@/sources/mealStore';
import { необъяснённыеПодъёмы } from '@/domain/mealMoment';
import { отметкаДля, видПричины } from '@/domain/причиныПодъёма';
import { useОтметкиПодъёмов } from '@/settings/подъёмы';
import ПричинаПодъёмаSheet from '@/sheets/ПричинаПодъёмаSheet';
import { подписьПриёма } from '@/domain/имяПриёма';
import { ключГруппы } from '@/domain/foods';
import { useMealNames } from '@/settings/mealNames';
import MealEditSheet from '@/sheets/MealEditSheet';
import FoodSheet from '@/sheets/FoodSheet';
import type { Meal } from '@/domain/meals';
import { useCarbUnit, toCarbs, carbUnitLabel, plural } from '@/domain/units';
import { onlyLocal } from '@/domain/meals';

/* Журнал приёмов.

   Раньше внесённую еду негде было увидеть: на «Сегодня» только сумма за день. Человек
   внёс приём и не мог проверить ни что он записался, ни с каким временем — а время мы
   как раз просим указывать точно, потому что от него считаются активные углеводы.
   Просить точность и не показывать результат — нечестно.

   Показываем ОБА источника вместе: свои записи и углеводы из Nightscout. Разделять их
   в списке незачем — человек ел один раз, а откуда об этом узнали, это наша кухня.
   Но пометку источника оставляем: удалить можно только своё, чужое приедет снова.

   Сутки по умолчанию: столько живут активные углеводы и столько человек помнит, что
   ел. Неделя — по запросу, для разбора.

   Лечение берём из локальной базы, а не из живого стора. Стор держит последние 120
   событий — и на неделе это оказалось пусто: события лечения у человека с помпой почти
   целиком temp basal, они идут каждые несколько минут и вытесняют всё остальное. За сто
   двадцать событий набирается несколько часов, а не неделя. В IndexedDB же лежит
   докачанная история, и окно там задаём мы. */

const ЧАС = 3600e3;

export default function MealsSection({ onClose }: { onClose: () => void }) {
  const meals = useMeals();
  const cu = useCarbUnit();
  /* Неделя убрана (#381): недельный обзор нужен для разбора, и его место в «Метриках».
     Здесь окно одно — сутки, а переключатель отдан на другое: подъёмы без записи. */
  const окно = 24;
  const [вкладка, setВкладка] = useState<'приёмы' | 'безЗаписи'>('приёмы');
  const entries = useEntries(окно * ЧАС);
  const [правим, setПравим] = useState<Meal | null>(null);
  /* Куда записать еду по подъёму: время начала подъёма. Человек его как раз и не помнит
     точно — а данные помнят. */
  const [добавляем, setДобавляем] = useState<number | null>(null);
  /* Сначала спрашиваем ЧТО это было, и только потом — сколько съели. Обратный порядок
     заставлял человека, у которого отвалилась канюля, отвечать про еду (#167). */
  const [причина, setПричина] = useState<{ at: number; rise: number } | null>(null);
  const отметки = useОтметкиПодъёмов();

  const лечение = useTreatments(окно * ЧАС);
  const от = Date.now() - окно * ЧАС;
  const свои = onlyLocal(meals, лечение)
    .filter((m) => m.t >= от)
    .map((m) => ({ id: m.id, t: m.t, carbs: m.carbs, kind: m.kind, своё: true }));
  const облачные = лечение
    .filter((t) => (t.carbs ?? 0) > 0 && t.t >= от)
    .map((t) => ({ id: 'ns' + t.t, t: t.t, carbs: t.carbs as number, kind: t.type, своё: false }));

  const все = [...свои, ...облачные].sort((a, b) => b.t - a.t);
  /* Имя, данное человеком (#122), главнее нашей догадки о том, обед это или перекус.
     Хранится оно на группе (тип + округлённые углеводы), поэтому и достаётся по ключу
     группы, а не по записи: назвав «овсянку» однажды, человек назвал все свои овсянки. */
  const { names: имена } = useMealNames();
  /* Подъёмы без записи — уже написанное правило (domain/mealMoment): рост 2,2 ммоль за
     45 минут, если рядом нет еды. Оно работало на подсказку «когда ели» при вводе задним
     числом; здесь тот же ответ показан списком. */
  const подъёмы = необъяснённыеПодъёмы(entries, все.map((x) => x.t));
  const сумма = Math.round(все.reduce((s, x) => s + x.carbs, 0));

  return (
    <Section title="Приёмы пищи" описание="Что и когда вы ели. Отсюда считаются активные углеводы, поэтому пропущенная запись портит не только историю, но и подсказки."
        subtitle={все.length
          ? `${все.length} ${plural(все.length, 'приём', 'приёма', 'приёмов')} · ${toCarbs(сумма, cu)} ${carbUnitLabel(cu)}`
          : 'Пока пусто'}
        onBack={onClose}>

      {/* «Без записи», а не «необъявленные приёмы» (#381). Второе утверждает, что человек
          ел и не записал, — а причин больше: недоданный болюс, отвалившаяся канюля,
          рассветный феномен, болезнь, нагрев сенсора (#376). Обвинительная рамка в
          приложении для человека с хроническим диагнозом — худшее, что можно сделать.
          «Без записи» — факт: подъём есть, записи нет. */}
      <div className="period">
        <button className={'period-seg' + (вкладка === 'приёмы' ? ' on' : '')}
          onClick={() => setВкладка('приёмы')}>Приёмы</button>
        <button className={'period-seg' + (вкладка === 'безЗаписи' ? ' on' : '')}
          onClick={() => setВкладка('безЗаписи')}>Без записи{подъёмы.length ? ` · ${подъёмы.length}` : ''}</button>
      </div>

      {вкладка === 'безЗаписи' ? (
        подъёмы.length === 0 ? (
          <div className="loop-empty">
            <Иконка icon={restaurantOutline} />
            <div className="loop-empty-t">Всё объяснено</div>
            <div className="loop-empty-s">
              За сутки не было подъёмов, под которыми нет записи. Это не оценка — просто
              сейчас объяснять нечего.
            </div>
          </div>
        ) : (
          <>
            <div className="meal-log">
              {подъёмы.map((п) => (
                <button key={п.at} className="meal-row" onClick={() => setПричина(п)}>
                  <div className="meal-when"><b>{время(п.at)}</b><span>{день(п.at)}</span></div>
                  <div className="meal-what">
                    {/* Насколько поднялся — это и есть повод: «+3,4 ммоль» человек
                        сопоставит со своей памятью лучше, чем слово «подъём». */}
                    <b>+{п.rise.toFixed(1).replace('.', ',')} ммоль</b>
                    {/* Отмеченный подъём говорит, чем он объяснён, а не «записи нет»:
                        человек уже ответил, и повторять вопрос — значит его не слышать. */}
                    <span>{(() => {
                      const о = отметкаДля(отметки, п.at);
                      return о ? видПричины(о.причина).метка : 'сахар пошёл вверх · записи нет';
                    })()}</span>
                  </div>
                </button>
              ))}
            </div>
            {/* Ни одного слова о том, что человек что-то скрыл: причин у подъёма больше
                двух (#167), и выбирать за него мы не вправе. */}
            <div className="metric-note">
              Подъём мог быть от еды, недоданного болюса, отвалившейся канюли, болезни или
              нагрева сенсора. Тапните и отметьте, что это было, — разбор перестанет
              спрашивать про него, а в записке врачу будет видно, что вы это знаете.
            </div>
          </>
        )
      ) : все.length === 0 ? (
        <div className="loop-empty">
          <Иконка icon={restaurantOutline} />
          <div className="loop-empty-t">Записей нет</div>
          <div className="loop-empty-s">
            Ни в приложении, ни в Nightscout за этот период. Внести приём можно с экрана
            «Сегодня» — плитка углеводов.
          </div>
        </div>
      ) : (
        <div className="meal-log">
          {все.map((x) => (
            /* Тап по строке открывает правку (#381). Раньше единственным действием была
               корзина: ошибся в граммах — стирай и вноси заново. Правим только своё:
               облачное приедет снова при следующем обновлении, и правка, которую
               перезапишут, хуже её отсутствия. */
            <button key={x.id} className={'meal-row' + (x.своё ? '' : ' is-soon')}
              disabled={!x.своё}
              onClick={() => { const м = meals.find((m) => m.id === x.id); if (м) setПравим(м); }}>
              <div className="meal-when">
                <b>{время(x.t)}</b>
                <span>{день(x.t)}</span>
              </div>
              <div className="meal-what">
                <b>{toCarbs(x.carbs, cu)} {carbUnitLabel(cu)}</b>
                <span>
                  {(() => {
                    const п = подписьПриёма({
                      имя: имена[ключГруппы(x.kind, x.carbs)],
                      kind: x.kind, часЕды: new Date(x.t).getHours(), граммы: x.carbs,
                    });
                    /* Уточнение второй строкой, а не в скобках: «Овсянка» — то, что человек
                       ищет глазами, а «завтрак» — то, чем это было по нашему счёту. Слепив
                       их в одну строку, мы заставили бы читать обе, чтобы найти первую. */
                    return <>{п.главное}{п.уточнение && <> · <span className="meal-kind">{п.уточнение}</span></>}</>;
                  })()}
                  {!x.своё && <> · <Иконка icon={cloudOutline} /> Nightscout</>}
                </span>
              </div>
              {x.своё && <Иконка icon={chevronForward} className="list-chev" />}
            </button>
          ))}
        </div>
      )}
      {правим && <MealEditSheet приём={правим} onClose={() => setПравим(null)} />}
      {причина && (
        <ПричинаПодъёмаSheet at={причина.at} rise={причина.rise}
          onClose={() => setПричина(null)}
          onЕда={() => { const at = причина.at; setПричина(null); setДобавляем(at); }} />
      )}

      {добавляем != null && (
        <FoodSheet isOpen onClose={() => setДобавляем(null)} времяПодъёма={добавляем} />
      )}
    </Section>
  );
}

const время = часы;
const день = (t: number) => имяДня(t, { коротко: true });
