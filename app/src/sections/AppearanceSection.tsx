import Иконка from '@/ui/Иконка';
import {
  ellipse, sunny, moon, languageOutline, checkmarkCircle, phonePortraitOutline,
  notificationsOutline, appsOutline, ellipseOutline,
} from 'ionicons/icons';
import Section from '@/ui/Section';
import Row from '@/ui/Row';
import { useSnapshot } from '@/sources/bridge';
import { толькоОблако } from '@/domain/толькоОблако';
import { бодрствование } from '@/platform/фон';
import { IonToggle } from '@ionic/react';
import { useEffect, useState } from 'react';
import { useTheme } from '@/theme/useTheme';
import {
  баннерВозможен, состояниеБаннера, включитьБаннер, поднятьБаннер, сводкаВключена, включитьСводку,
  сводкаВсплывает, включитьВсплытие,
  type СостояниеБаннера,
} from '@/platform/живойБаннер';
import { виджетВозможен, добавитьВиджет, type ИтогДобавления } from '@/platform/виджет';
import {
  состояниеЗначка, задатьЗначок, оговоркаЗначка, ЗНАЧОК_СЛОВАМИ,
  type ЗначокСостояние, type ВидЗначка,
} from '@/platform/значок';

/* «Оформление» отдельным разделом.

   Раньше это были три плитки темы внизу «Профиля» — и всё. Раздел появился, потому что
   у оформления набралось три разных выбора, а не один: тема, палитра и когда-нибудь
   язык.

   ЧТО СЮДА НЕ ПОПАДЁТ. Крупный текст, уменьшение движения, повышенный контраст. Обо
   всём этом система уже знает и говорит нам сама; свой переключатель рядом с системным
   означал бы два независимых состояния одного и того же — человек включит крупный шрифт
   в телефоне, у нас ничего не изменится, он включит наш, и дальше они разъедутся. Наше
   дело — слушать систему, а не спрашивать заново (#325).

   Различать потоки не только цветом — тоже не настройка: значок и форма не мешают тому,
   кто цвета различает, а чёрно-белую печать отчёта врачу чинят заодно. Такое работает
   всегда и не переключается.

   Единицы глюкозы и еды остались в «Настройках» намеренно: это про то, в чём считать, а
   не про то, как выглядит. Человек ищет их рядом с «сколько у меня инсулина».

   ЧТО ВИДНО, НЕ ОТКРЫВАЯ ПРИЛОЖЕНИЕ — тоже здесь (#500). Живой баннер, сводка в шторке, виджет и
   цифры на значке жили в разделе «Тревоги», и это было неверно: они ничего не решают и никого не
   будят — они показывают. Раздел назывался «Тревоги», а половина его содержимого тревогами не была,
   и об это спотыкались. Тревоге место рядом с порогом гипогликемии, показу — рядом с темой. */
/* ДВЕ ЧАСТИ ОДНОГО РАЗДЕЛА (решение владельца).

   За одной строкой «Тема» пряталось всё: баннер, сводка, значок, тема, палитра, язык. Слово на двери
   было меньше того, что за дверью, и человек, искавший «где включить баннер», туда не заходил.

   Экран остался один — решение из #500 держать показ рядом с видом мы не отменяем. Разделились
   ВХОДЫ: «Экран блокировки и значок» и «Вид приложения». `часть` говорит, с какого вошли, и раздел
   показывает соответствующую половину.

   `часть` необязательна: без неё раздел показывает всё, как раньше. Так продолжают работать старые
   ссылки и восстановление после перезапуска, сохранённое до этой правки. */
export type ЧастьОформления = 'показ' | 'вид';

export default function AppearanceSection({ onClose, часть }: {
  onClose: () => void;
  часть?: ЧастьОформления;
}) {
  const { theme, setTheme } = useTheme();
  const [баннер, setБаннер] = useState<СостояниеБаннера | null>(null);
  /** Что ответила система на «Показать сейчас». null — ещё не нажимали. */
  const [подъём, setПодъём] = useState<{ получилось: boolean; словами: string } | null>(null);
  /* СВЯЗКА, А НЕ ДВА ПРИЗНАКА ПО ОТДЕЛЬНОСТИ (#578).

     Ни «только облако», ни «бодрствование выключено» сами по себе бедой не являются: с прибором по
     эфиру нас разбудят и без опоры, а с опорой облако работает. Беда — только их совпадение, и
     предупреждать надо ровно о нём. Лишнее предупреждение учит не читать предупреждения. */
  const снимок = useSnapshot();
  const [опораВыключена, setОпораВыключена] = useState(false);
  useEffect(() => { void бодрствование().then((б) => setОпораВыключена(б?.режим === 'выключено')); }, []);
  const вФонеНеЖивём = толькоОблако(снимок) && опораВыключена;
  const [поднимаю, setПоднимаю] = useState(false);
  const [сводка, setСводка] = useState<boolean | null>(null);
  const [всплытие, setВсплытие] = useState(false);
  const [значок, setЗначок] = useState<ЗначокСостояние | null>(null);
  const [виджет, setВиджет] = useState<ИтогДобавления | null>(null);

  useEffect(() => {
    void состояниеБаннера().then(setБаннер);
    void сводкаВключена().then(setСводка);
    void сводкаВсплывает().then(setВсплытие);
    void состояниеЗначка().then(setЗначок);
  }, []);

  const темы: { key: 'system' | 'light' | 'dark'; label: string; icon: string; sub: string }[] = [
    { key: 'system', label: 'Системная', icon: ellipse, sub: 'как в настройках телефона' },
    { key: 'light', label: 'Светлая', icon: sunny, sub: 'днём и на солнце' },
    { key: 'dark', label: 'Тёмная', icon: moon, sub: 'ночью не слепит' },
  ];

  const показПоказ = часть !== 'вид';
  const показВид = часть !== 'показ';

  return (
    <Section
      title={часть === 'показ' ? 'Экран блокировки и значок' : часть === 'вид' ? 'Вид приложения' : 'Оформление'}
      onBack={onClose}
      описание={часть === 'показ'
        ? 'Что видно, не открывая приложение: баннер на экране блокировки, тихая сводка в шторке и цифры на значке.'
        : 'Как приложение выглядит. Размер текста, контраст и уменьшение движения приложение берёт из настроек телефона — отдельно их здесь нет намеренно, иначе два места настраивали бы одно и то же по-разному.'}>

      {показВид && (
        <>
          <div className="section-label sec">Тема</div>
          <div className="list">
            {темы.map((т) => (
              <Row key={т.key} icon={т.icon} title={т.label} sub={т.sub} chevron={false}
                right={theme === т.key ? <Иконка icon={checkmarkCircle} className="pick-check" /> : undefined}
                onClick={() => setTheme(т.key)} />
            ))}
          </div>
        </>
      )}

      {/* ЧТО ВИДНО, НЕ ОТКРЫВАЯ ПРИЛОЖЕНИЕ. Все четыре отвечают на один вопрос и потому стоят
          вместе, а не разбросаны по разделам: баннер на блокировке, тихая сводка в шторке, цифры
          на значке и виджет на рабочем столе. */}
      {/* Заголовок нужен, только когда раздел показан целиком: войдя через «Экран блокировки и
          значок», человек уже прочитал это же самое в заголовке экрана. */}
      {часть == null && (баннерВозможен() || значок || виджетВозможен()) && (
        <div className="section-label sec">Не открывая приложение</div>
      )}

      {показПоказ && баннерВозможен() && (
        <>
          <div className="list">
            {/* ВЫКЛЮЧЕНО — ЗНАЧИТ СКАЗАНО, ПОЧЕМУ (#654).

                Карточку отключили целиком: измерили её за шестнадцать часов, и верное число она
                показывала пятую часть суток. Причину пишем здесь же, потому что выключатель без
                объяснения человек читает как поломку и лезет её чинить.

                «Не умеет» и «мы решили не показывать» — разные случаи, и различать их обязательно:
                первый лечится телефоном, второй — деньгами (push нужен платный аккаунт). */}
            <Row icon={phonePortraitOutline} title="Сахар на экране блокировки"
              sub={баннер?.выключенаПочему
                ? баннер.выключенаПочему
                : баннер?.умеет === false
                  ? 'нужен iOS 18 или новее'
                  : вФонеНеЖивём
                    ? 'обещание не выполнится: на заблокированном телефоне мы не работаем — см. ниже'
                    : 'живой баннер — и в «Динамическом острове», и на панели CarPlay'}
              right={<IonToggle checked={!!баннер?.включён}
                disabled={баннер?.умеет === false || !!баннер?.выключенаПочему}
                onIonChange={(e) => {
                  const v = e.detail.checked;
                  setБаннер((б) => (б ? { ...б, включён: v } : б));
                  void включитьБаннер(v);
                }} />} />
            {/* ПОКАЗАТЬ СЕЙЧАС — не дубль выключателя, а выход из тупика (#568).

                Выключатель отвечает на «хочу ли я баннер вообще», и на него человек нажимает один
                раз в жизни. Баннер при этом умирает регулярно и не по его воле: смахнули, система
                погасила через восемь часов, приложение переставили. Поднять его обратно можно
                только из активного приложения, а человек в этот момент смотрит на пустой экран
                блокировки и на включённый выключатель — и делать ему нечего.

                Строка есть только у включённого баннера: у выключенного она предлагала бы показать
                то, чего человек не просил. */}
            {баннер?.включён && баннер?.умеет !== false && (
              <Row icon={phonePortraitOutline} chevron={false} disabled={поднимаю}
                title={поднимаю ? 'Поднимаю…' : 'Показать сейчас'}
                sub={подъём?.словами
                  ?? 'если баннер пропал с экрана блокировки — вернуть его можно только отсюда'}
                onClick={() => {
                  setПоднимаю(true);
                  setПодъём(null);
                  void поднятьБаннер().then((и) => {
                    setПодъём(и);
                    setПоднимаю(false);
                    /* Перечитываем состояние: «идёт ли» — вопрос к системе, а не к нашей памяти. */
                    void состояниеБаннера().then(setБаннер);
                  });
                }} />
            )}
            {/* Сводка — сосед баннера: тот же вопрос, другой ответ. Уведомление переживает
                смахивание, доезжает до часов и лежит в центре уведомлений. */}
            {сводка != null && (
              <Row icon={notificationsOutline} title="Сводка в шторке"
                sub={вФонеНеЖивём
                  ? 'обещание не выполнится: в фоне обновлять её некому — см. ниже'
                  : 'сахар, разница и активный инсулин — одной строкой, тихо'}
                right={<IonToggle checked={сводка}
                  onIonChange={(e) => { const v = e.detail.checked; setСводка(v); void включитьСводку(v); }} />} />
            )}
            {/* Повадка сводки — только когда она включена: переключатель у выключенной строки
                предлагает настроить то, чего нет, и человек решает, что настройка не работает. */}
            {сводка && (
              <Row icon={notificationsOutline} title="Всплывать поверх экрана"
                sub="показываться сверху, как только пришло показание — беззвучно"
                right={<IonToggle checked={всплытие}
                  onIonChange={(e) => { const v = e.detail.checked; setВсплытие(v); void включитьВсплытие(v); }} />} />
            )}
          </div>
          {/* ОБЪЯСНЕНИЕ СТОИТ ЗДЕСЬ, А НЕ В «ОХРАНЕ» (#578).

              В «Охране» про фоновое бодрствование написано давно и подробно. Но обещание даётся
              ЗДЕСЬ — человек включает баннер на этом экране, и здесь же должен узнать, чем оно будет
              выполняться. Отправлять его читать в другой раздел значит рассчитывать, что он туда
              дойдёт; поймано на живой гипогликемии, когда карточка двадцать минут стояла на старом
              числе, а человек смотрел на неё и верил. */}
          {вФонеНеЖивём && (
            <div className="metric-note warn">
              <b>Источник у вас только облачный, а звук в фоне не удерживается.</b> Разбудить
              приложение в фоне нечем: система приостанавливает его при блокировке экрана, и до
              следующего открытия не обновятся ни баннер, ни сводка, ни повторная тревога. Показания
              потом приезжают пачкой — задним числом, со своими временами.
              {' '}Лечится одним: «Охрана» → «Держать звук ночью». Это сделка — живость против заряда,
              и решать вам.
            </div>
          )}
          <div className="metric-note">
            Баннер обновляется, когда приходит показание, — не раз в пятнадцать минут, как обычный
            виджет. Система гасит его через восемь часов; приложение продлевает само, пока получает
            данные. Сводка не звенит и не будит — тревога приходит отдельно.
          </div>
        </>
      )}

      {/* ЗНАЧОК. Число там только целое — ни запятой, ни единиц, — поэтому это выбор с ценой, и
          делает его человек. Пример у каждого вида показывает цену лучше объяснения. */}
      {показПоказ && значок && (
        <>
          <div className="section-label sec">Цифры на значке приложения</div>
          <div className="list">
            {/* ОТМЕТКА ВЫБОРА — ОДНА, И СЛЕВА (замечание владельца).

                Было две: слева у каждой строки пустой кружок, справа галочка у выбранной. Кружки
                читаются как радиокнопки — а они всегда пустые, и список выглядел так, будто не
                выбрано ничего, при том что галочка справа говорила обратное. Два индикатора одного
                состояния всегда спорят.

                Слева, потому что так уже сделано во всех остальных списках выбора приложения
                (единицы, источники, каталог визита): пустой круг — не выбрано, круг с галочкой —
                выбрано. */}
            {значок.виды.map((вид: ВидЗначка) => (
              <Row key={вид} icon={значок.вид === вид ? checkmarkCircle : ellipseOutline}
                title={ЗНАЧОК_СЛОВАМИ[вид]?.имя ?? вид}
                sub={ЗНАЧОК_СЛОВАМИ[вид]?.под}
                chevron={false}
                onClick={() => { setЗначок({ ...значок, вид }); void задатьЗначок(вид); }} />
            ))}
          </div>
          <div className="metric-note">
            {/* Устаревшие данные гасят значок целиком: цифра без возраста выглядит текущей всегда. */}
            Когда данные устаревают, значок гаснет — цифра без возраста выглядит свежей, а это худший
            вид вранья.{оговоркаЗначка() ? ' ' + оговоркаЗначка() : ''}
          </div>
        </>
      )}

      {показПоказ && виджетВозможен() && (
        <>
          <div className="list">
            <Row icon={appsOutline} title="Виджет на рабочем столе"
              sub="сахар, кольцо и возраст показания — без открытия приложения"
              onClick={() => { void добавитьВиджет().then(setВиджет); }} />
          </div>
          <div className="metric-note">
            {виджет === 'спросили'
              ? 'Система спросила, куда его поставить. Если окно не появилось — добавьте вручную: долгое нажатие на пустое место экрана → «Виджеты» → SugarLife.'
              : виджет === 'не умеет'
                ? 'Этот лаунчер не умеет ставить виджеты по просьбе приложения. Добавьте вручную: долгое нажатие на пустое место экрана → «Виджеты» → SugarLife.'
                : виджет === 'нет метода'
                  ? 'Эта сборка приложения старше виджета — обновите приложение целиком, не только интерфейс.'
                  : 'Возраст показания на виджете считает сам рабочий стол, поэтому «2 мин» не застынет, даже если приложение остановят.'}
          </div>
        </>
      )}

      {показВид && (
        <>
          {/* Палитра — единственная настройка доступности, которую система подсказать не
              может: про цветовосприятие она не знает ничего. Пока строки нет — есть честная
              заметка о том, что задача видна и в работе (#325). */}
          <div className="section-label sec">Язык и палитра</div>
          <div className="list">
            <Row icon={languageOutline} title="Язык" value="русский" chevron={false} disabled
              sub="других языков пока нет" />
          </div>
          <div className="metric-note">
            Различимая при дальтонизме палитра и перевод на другие языки — в работе. Всё
            остальное про восприятие приложение берёт из системных настроек и переключателей
            для этого не заводит.
          </div>
        </>
      )}
    </Section>
  );
}
