import Иконка from '@/ui/Иконка';
import HoldButton from '@/ui/HoldButton';
import Section from '@/ui/Section';
import { openOutline, refreshOutline } from 'ionicons/icons';
import { useState } from 'react';
import { sendIntent, useSnapshot } from '@/sources/bridge';
import { правилаНаЭкран, значениеСловом, следующее, сводкаПравила, рискПоля, type Поле } from '@/показ/правилаТревог';
import { фразаПравила, числаВнеФразы } from '@/показ/фразаПравила';
import { открытьСнаружи } from '@/platform/appUpdate';

/** Уровень риска классом: «норма» — без класса, цвет числа задаёт CSS (общий с профилем петли). */
const классРиска = (у: string) => (у === 'норма' ? undefined : у);

/*
 * ПРАВКА ПРАВИЛА — СТРАНИЦА, А НЕ ШТОРКА (#590, решение владельца).
 *
 * Правило одно на всё приложение: СМОТРЕТЬ МОЖНО В ШТОРКЕ, МЕНЯТЬ УХОДИШЬ НА СТРАНИЦУ.
 *
 * Шторка — для быстрого и отменяемого: выбрать единицы, внести углеводы, посмотреть и закрыть.
 * Правка порога тревоги — редкое сосредоточенное действие с последствием на всю ночь, и ей нужно
 * место: фраза правила, число под правкой с пределами, оговорка, статья. Всё это в шторку влезало
 * с трудом — она упирается в 88% экрана, а с закреплённым низом и подавно. Шторка на 88% экрана с
 * липким низом это уже страница, которая притворяется шторкой.
 *
 * ЗАЧЕМ СТРАНИЦА ЧИТАЕТ СНИМОК САМА. Стек хранит метку раздела, а не готовый узел: после
 * перезапуска страница собирается заново по `ruleId`. Передать ей правило целиком значило бы
 * восстановить экран с числами, которые были час назад.
 *
 * ЧЕРНОВИК ЖИВЁТ ДО ЗАПИСИ. Уход со страницы без записи ОТМЕНЯЕТ правку: из двух молчаливых
 * исходов этот безопасный — тревога остаётся работать так, как работала.
 */
export default function ПравилоSection({ ruleId, title, onClose }: {
  ruleId: string; title: string; onClose: () => void;
}) {
  const snap = useSnapshot();
  const правило = правилаНаЭкран(snap?.alarmRules).find((п) => п.id === ruleId) ?? null;

  const [черновик, setЧерновик] = useState<Record<string, string>>({});
  const [правимКлюч, setПравимКлюч] = useState<string | null>(null);
  const [ошибка, setОшибка] = useState<string | null>(null);
  const [ждём, setЖдём] = useState(false);

  if (!правило) {
    /* Правило пропало из снимка, пока страница была открыта: движок его выключил или сборка
       сменилась. Пустой экран здесь читался бы как поломка. */
    return (
      <Section title={title} onBack={onClose}>
        <div className="sheet-note warn">Это правило больше не приходит от движка. Вернитесь к списку.</div>
      </Section>
    );
  }

  const числа = правило.поля.filter((поле) => правило.включено && !поле.выключатель);
  const фраза = фразаПравила(правило.фраза, числа);
  const правимое = числа.find((ф) => ф.ключ === правимКлюч) ?? null;

  const исходные = new Map(правило.поля.map((ф) => [ф.ключ, ф.значение] as const));
  /* «Туда и обратно» правкой не считается: нажал «−0,1», передумал, нажал «+0,1» — записывать
     нечего, и кнопка записи должна погаснуть сама. */
  const правки = Object.entries(черновик).filter(([k, v]) => исходные.get(k) !== v);

  const сЧерновиком = (поле: Поле): Поле => {
    const v = черновик[поле.ключ];
    if (v == null) return поле;
    const n = Number(v);
    return { ...поле, значение: v, число: Number.isFinite(n) ? n : поле.число };
  };

  /* Все поля правила уходят ОДНОЙ записью, а не по одной: пороги правила связаны между собой
     («будить ниже» и «повторять через»), и половина применённой правки — состояние, которого
     человек не задумывал. */
  const записать = async () => {
    setЖдём(true);
    setОшибка(null);
    const r = await sendIntent({ type: 'setConfig', patch: Object.fromEntries(правки) });
    setЖдём(false);
    if (r.accepted) setЧерновик({});
    else setОшибка(r.error || 'движок не принял это значение');
  };

  const шаги = (поле: Поле) => {
    const текущее = сЧерновиком(поле);
    const ниже = следующее(текущее, -1);
    const выше = следующее(текущее, 1);
    if (!ниже && !выше) return null;
    const хуже: -1 | 1 | 0 = поле.границы?.worseTowards === 'down' ? -1
      : поле.границы?.worseTowards === 'up' ? 1 : 0;
    return (
      <div className="alert-ask alert-ask-row">
        <button className={'changed-btn' + (хуже === -1 ? ' хуже' : '')} disabled={!ниже}
          onClick={() => ниже && setЧерновик((ч) => ({ ...ч, [поле.ключ]: ниже }))}>
          −{поле.шаг.toString().replace('.', ',')}
        </button>
        <button className={'changed-btn' + (хуже === 1 ? ' хуже' : '')} disabled={!выше}
          onClick={() => выше && setЧерновик((ч) => ({ ...ч, [поле.ключ]: выше }))}>
          +{поле.шаг.toString().replace('.', ',')}
        </button>
      </div>
    );
  };

  const числоВоФразе = (поле: Поле) => {
    const текущее = сЧерновиком(поле);
    const правлено = черновик[поле.ключ] != null && черновик[поле.ключ] !== поле.значение;
    return (
      <button key={поле.ключ}
        className={'фраза-число' + (правимКлюч === поле.ключ ? ' правим' : '')
          + (правлено ? ' правлено' : ' ' + (классРиска(рискПоля(текущее)) ?? ''))}
        onClick={() => setПравимКлюч(правимКлюч === поле.ключ ? null : поле.ключ)}>
        {правлено && <s>{значениеСловом(поле)}</s>}
        {значениеСловом(текущее)}
      </button>
    );
  };

  const карточкаЧисла = (поле: Поле) => (
    <div className="правило-шаги" key={поле.ключ}>
      <div className="правило-шаги-имя">{поле.имя}</div>
      {шаги(поле)}
      {поле.границы && (
        /* «Допустимо …» — та же строка, что у пределов петли. Без неё человек крутит число
           вслепую: «0,15 ммоль/мин» само по себе не говорит ему ничего. */
        <div className="правило-предел">
          допустимо {поле.границы.min.toFixed(поле.знаков).replace('.', ',')}…
          {поле.границы.max.toFixed(поле.знаков).replace('.', ',')}
          {поле.единица ? ` ${поле.единица}` : ''}
        </div>
      )}
    </div>
  );

  return (
    <Section title={правило.имя} subtitle={сводкаПравила(правило)} onBack={onClose}
      footer={числа.length ? (
        /* НИЗ СТОИТ С САМОГО НАЧАЛА, а не появляется вместе с правкой (#567): появляющийся низ
           менял высоту, и кнопка уезжала из-под пальца. Пока править нечего — кнопки погашены;
           заодно видно заранее, что число само никуда не уйдёт и его надо записать. */
        <div className="page-foot">
          <div className="bas-act-col">
            <HoldButton label={ждём ? 'Записываю…' : 'Записать'}
              disabled={ждём || !правки.length} onComplete={() => void записать()} />
            <button className="page-btn" disabled={!правки.length} onClick={() => setЧерновик({})}>
              <Иконка icon={refreshOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
              Вернуть как было
            </button>
          </div>
        </div>
      ) : undefined}>

      {/* Фраза показывает ЧЕРНОВИК: число в тексте меняется сразу, и это и есть «станет так». */}
      {фраза && правило.включено && (
        <div className="правило-фраза">
          {фраза.map((к, i) => (к.вид === 'текст' ? <span key={i}>{к.текст}</span> : числоВоФразе(к.поле)))}
        </div>
      )}
      {/* Шаги — только у того числа, которое тронули: две кнопки на экране вместо восьми. */}
      {фраза && правило.включено && правимое && карточкаЧисла(правимое)}

      {/* Числа, которых во фразе нет (например «повторять через»), и все числа у правила без
          фразы. Спрятать их значило бы оставить настройку работать, а править стало бы негде. */}
      {(фраза ? числаВнеФразы(фраза, числа) : числа).map((поле) => (
        <div key={поле.ключ}>
          <div className="basal-row">
            <span>{поле.имя}</span>
            <b className={черновик[поле.ключ] != null && черновик[поле.ключ] !== поле.значение
              ? 'правлено' : классРиска(рискПоля(сЧерновиком(поле)))}>
              {черновик[поле.ключ] != null && черновик[поле.ключ] !== поле.значение && <s>{значениеСловом(поле)}</s>}
              {значениеСловом(сЧерновиком(поле))}{поле.единица ? ` ${поле.единица}` : ''}
            </b>
          </div>
          {шаги(поле)}
        </div>
      ))}

      {/* Почему выключателя нет — словами, а не молчанием (#482): молчаливое отсутствие человек
          читает как недоделку и идёт выключать уведомления целиком в системных настройках. */}
      {правило.почемуНельзя && <div className="sheet-note">{правило.почемуНельзя}</div>}
      {правило.оговорка && правило.включено && <div className="sheet-note warn">{правило.оговорка}</div>}
      {ошибка && <div className="sheet-note warn">Не приняли правку: {ошибка}</div>}

      {правило.ссылка && (
        <button className="changed-btn во-всю" style={{ marginTop: 8 }}
          onClick={() => открытьСнаружи(правило.ссылка as string)}>
          <Иконка icon={openOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
          Почему именно так
        </button>
      )}
    </Section>
  );
}
