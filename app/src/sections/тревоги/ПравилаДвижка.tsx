import Иконка from '@/ui/Иконка';
import HoldButton from '@/ui/HoldButton';
import { IonToggle } from '@ionic/react';
import { openOutline, chevronForward, refreshOutline } from 'ionicons/icons';
import { useState } from 'react';
import { sendIntent } from '@/sources/bridge';
import type { AlarmRuleView } from '@/sources/bridge';
import { правилаНаЭкран, значениеСловом, следующее, сводкаПравила, рискПоля, type Поле } from '@/показ/правилаТревог';
import { фразаПравила, числаВнеФразы } from '@/показ/фразаПравила';
import { открытьСнаружи } from '@/platform/appUpdate';
import Sheet from '@/ui/Sheet';

/* ПРАВИЛА ТРЕВОГ ИЗ ДВИЖКА (SugarLife#482, шаг 3).

   Экран не хранит своей копии правил: движок отдаёт список вместе с ключами настроек, тем же ключом
   настройка и правится (`setConfig`). Поэтому новая тревога появляется здесь сама, без нашей правки, —
   и поэтому же тут нет ни одного зашитого порога.

   ЧИСЛО БЕЗ ОБЪЯСНЕНИЯ НЕ ПОКАЗЫВАЕМ. У правил движка есть статья (`helpUrl`), и правило проекта общее с
   ядром: нет объяснения — нет настройки. «Скорость падения 0,15 ммоль/мин» человеку не говорит ничего,
   пока он не прочтёт, откуда она взялась.

   ОГОВОРКУ ПОКАЗЫВАЕМ РЯДОМ С ЧИСЛОМ, а не в подсказке: «порог 15 мин, фактически до 24» — это и есть
   правда о заданном числе, и прятать её значит обещать то, чего платформа не даёт.

   ШТОРКИ ВМЕСТО ПРОСТЫНИ (#500). Раскрытые разом, восемь правил давали экран на пять пролистываний:
   у каждого заголовок, выключатель, два-три числа с кнопками −/+ и ссылка на статью. Найти в этом
   нужное правило нельзя — можно только читать подряд, чего никто не делает.

   Список отвечает на обычный вопрос одной строкой: за чем следит, каким голосом и при каких числах.
   Числа правятся в шторке снизу — в неё идут редко и осознанно, и там у правила есть место на
   объяснение, оговорку и статью, не отнимая его у соседей. Раскрытие на месте (аккордеон) сюда не
   годится: список от него прыгает, и правило, которое правишь, уезжает под палец.

   ВЫКЛЮЧАТЕЛЬ ОСТАЁТСЯ СНАРУЖИ, в свёрнутой строке: «следить или нет» — решение куда более частое,
   чем правка порога, и прятать его за раскрытием значило бы менять местами частое и редкое.

   ЧИСЛА ПРАВЯТСЯ ЧЕРНОВИКОМ, А ЗАПИСЫВАЮТСЯ УДЕРЖАНИЕМ (#566, решение владельца).

   Раньше каждое нажатие «−0,1» немедленно уходило движку: пять нажатий — пять записей конфига, и
   «как было» взять неоткуда. Для порога, который решает, разбудят ли ночью, это неверный порядок:
   промах пальцем менял защиту молча и без пути назад.

   Теперь ± правят черновик, внизу закреплены «Вернуть как было» и удержание «Записать». Схема та
   же, что в профиле петли, и намеренно та же: два места, где число решает медицинский вопрос,
   должны спрашивать одинаково.

   Закрытие шторки с неписаным черновиком ОТМЕНЯЕТ правку. Из двух молчаливых исходов этот
   безопасный: тревога остаётся работать так, как работала. Поэтому же кнопка записи закреплена
   внизу, а не уезжает с прокруткой — уйти, не увидев её, трудно.

   ВЫКЛЮЧАТЕЛЬ ЧЕРНОВИКА НЕ ЗНАЕТ и уходит сразу: «следить или нет» — одно решение целиком, а не
   набор шагов, и держать его в черновике значило бы придумать половинчатое состояние. */

/** Уровень риска классом: «норма» — без класса, цвет числа задаёт CSS (общий с профилем петли). */
const классРиска = (у: string) => (у === 'норма' ? undefined : у);

export default function ПравилаДвижка({ правила }: { правила: AlarmRuleView[] | undefined }) {
  /** Какое правило открыто шторкой. Одно: шторка перекрывает экран, двух сразу не бывает. */
  const [открыто, setОткрыто] = useState<string | null>(null);
  /* Что не приняли — говорим сразу. Молчаливый отказ читается как «кнопка сломана», и человек жмёт
     её снова. */
  const [ошибка, setОшибка] = useState<string | null>(null);
  const [ждём, setЖдём] = useState<string | null>(null);
  /** Неписаные правки открытой шторки: ключ поля → новое значение строкой. */
  const [черновик, setЧерновик] = useState<Record<string, string>>({});
  /* Какое ЧИСЛО правим сейчас. Во фразе их несколько, а кнопок на экране должно быть две, а не
     восемь: тронул число — под фразой раскрылась пара −/+ для него одного. Заодно возвращается на
     место красная метка рискованной стороны — она делалась под одно число на экране. */
  const [правимКлюч, setПравимКлюч] = useState<string | null>(null);
  const список = правилаНаЭкран(правила);
  if (!список.length) return null;

  const открыть = (id: string | null) => { setЧерновик({}); setОшибка(null); setПравимКлюч(null); setОткрыто(id); };

  const править = async (ключ: string, значение: string) => {
    setЖдём(ключ);
    setОшибка(null);
    const r = await sendIntent({ type: 'setConfig', patch: { [ключ]: значение } });
    setЖдём(null);
    /* Структурные ключи движок валидирует сам. Не принял — значит значение вне допустимого. */
    if (!r.accepted) setОшибка(r.error || 'движок не принял это значение');
    return r.accepted;
  };

  /* Ключ → как было у движка. Нужен, чтобы «туда и обратно» не считалось правкой: человек нажал
     «−0,1», передумал, нажал «+0,1» — записывать нечего, и кнопка записи должна уйти сама. */
  const исходные = new Map(список.flatMap((п) => п.поля.map((ф) => [ф.ключ, ф.значение] as const)));
  const правки = Object.entries(черновик).filter(([k, v]) => исходные.get(k) !== v);
  const естьПравки = правки.length > 0;

  /* Все поля правила уходят ОДНОЙ записью, а не по одной. Пороги правила связаны между собой
     («будить ниже» и «повторять через»), и половина применённой правки — состояние, которого
     человек не задумывал. */
  const записать = async () => {
    setЖдём('запись');
    setОшибка(null);
    const r = await sendIntent({ type: 'setConfig', patch: Object.fromEntries(правки) });
    setЖдём(null);
    if (r.accepted) setЧерновик({});
    else setОшибка(r.error || 'движок не принял это значение');
  };

  /** Поле с подставленным черновиком — чтобы и число, и шаги считались от того, что человек видит. */
  const сЧерновиком = (поле: Поле): Поле => {
    const v = черновик[поле.ключ];
    if (v == null) return поле;
    const n = Number(v);
    return { ...поле, значение: v, число: Number.isFinite(n) ? n : поле.число };
  };

  /* Пара −/+ для ОДНОГО числа. Кнопка гаснет на пределе движка, а сторона, уводящая в риск,
     помечена контуром — как в профиле петли. Какая это сторона, знает движок (`worseTowards`): у
     порога гипо хуже вниз, у порога молчания вверх, и на знак кнопки это не ложится. */
  const шаги = (поле: Поле) => {
    const текущее = сЧерновиком(поле);
    const ниже = следующее(текущее, -1);
    const выше = следующее(текущее, 1);
    if (!ниже && !выше) return null;
    const хуже: -1 | 1 | 0 = поле.границы?.worseTowards === 'down' ? -1
      : поле.границы?.worseTowards === 'up' ? 1 : 0;
    return (
      <div className="alert-ask alert-ask-row">
        <button className={'changed-btn' + (хуже === -1 ? ' хуже' : '')} disabled={!ниже}
          onClick={() => ниже && setЧерновик((ч) => ({ ...ч, [поле.ключ]: ниже }))}>
          −{поле.шаг.toString().replace('.', ',')}
        </button>
        <button className={'changed-btn' + (хуже === 1 ? ' хуже' : '')} disabled={!выше}
          onClick={() => выше && setЧерновик((ч) => ({ ...ч, [поле.ключ]: выше }))}>
          +{поле.шаг.toString().replace('.', ',')}
        </button>
      </div>
    );
  };

  /* ЧИСЛО ВНУТРИ ФРАЗЫ. Тронул — раскрылись шаги под ним; тронул другое — прежнее свернулось.

     ЕДИНИЦУ ЗДЕСЬ НЕ ПИШЕМ: её несёт сама фраза («…быстрее 0,15 ммоль/мин и…»). Приписав свою,
     мы получили бы «0,15 ммоль/мин ммоль/мин» — поймано глазами на первом же снимке. Текст правила
     сочиняет движок, и слова в нём его; наше дело — число.
     Правленое число выделено, и рядом стоит прежнее: «было 3,9 → станет 3,6» человек проверяет
     глазами, а не памятью. «Станет так» отдельной строкой не нужно — фраза с подставленным
     черновиком и есть следствие правки. */
  const числоВоФразе = (поле: Поле) => {
    const текущее = сЧерновиком(поле);
    const правлено = черновик[поле.ключ] != null && черновик[поле.ключ] !== поле.значение;
    return (
      <button key={поле.ключ}
        className={'фраза-число' + (правимКлюч === поле.ключ ? ' правим' : '')
          + (правлено ? ' правлено' : ' ' + (классРиска(рискПоля(текущее)) ?? ''))}
        onClick={() => setПравимКлюч(правимКлюч === поле.ключ ? null : поле.ключ)}>
        {правлено && <s>{значениеСловом(поле)}</s>}
        {значениеСловом(текущее)}
      </button>
    );
  };

  /* Число строкой — для того, чего во фразе нет (например «повторять через»), и для правил, у
     которых фразы не случилось. */
  const строкаЧисла = (поле: Поле) => {
    const текущее = сЧерновиком(поле);
    const правлено = черновик[поле.ключ] != null && черновик[поле.ключ] !== поле.значение;
    return (
      <div key={поле.ключ}>
        <div className="basal-row">
          <span>{поле.имя}</span>
          {/* Правленое число выделено, и рядом стоит прежнее: «было 3,9 → станет 3,6» человек
              проверяет глазами, не листая память. */}
          {/* Правленое выделяем акцентом, непрёвленое красим по риску: цвет числа — та же шкала,
              что у пределов петли (мост 1.47). Смешивать их незачем — пока правка не записана,
              важнее «это черновик», чем «это далеко от рекомендованного». */}
          <b className={правлено ? 'правлено' : классРиска(рискПоля(текущее))}>
            {правлено && <s>{значениеСловом(поле)}</s>}
            {значениеСловом(текущее)}{поле.единица ? ` ${поле.единица}` : ''}
          </b>
        </div>
        {шаги(поле)}
      </div>
    );
  };

  return (
    <>
      <div className="section-label sec">Правила тревог</div>
      <div className="sheet-note">
        Считает движок — один расчёт на телефон и на айфон. Здесь то, по каким числам он это делает.
        Правка порога записывается удержанием: случайное касание не должно менять защиту.
      </div>
      {список.map((п) => {
        const выключатель = п.поля.find((поле) => поле.выключатель);
        const числа = п.поля.filter((поле) => п.включено && !поле.выключатель);
        const фраза = фразаПравила(п.фраза, числа);
        const правимое = числа.find((ф) => ф.ключ === правимКлюч) ?? null;
        return (
        <div key={п.id} className="правило">
          <div className="правило-шапка">
            <button className="правило-кнопка" onClick={() => открыть(п.id)}>
              <span className="правило-имя">{п.имя}</span>
              <span className="правило-сводка">{сводкаПравила(п)}</span>
            </button>
            {/* Выключатель — снаружи шторки и вне кнопки раскрытия: это два разных действия, и
                попадание пальцем не должно решать, какое из них случилось. */}
            {выключатель && (
              <IonToggle checked={выключатель.включено} disabled={ждём === выключатель.ключ}
                onIonChange={(e) => void править(выключатель.ключ, e.detail.checked ? 'on' : 'off')} />
            )}
            <Иконка icon={chevronForward} className="правило-шеврон" />
          </div>
          <Sheet isOpen={открыто === п.id} onClose={() => открыть(null)}
            title={п.имя} subtitle={сводкаПравила(п)}
            footer={числа.length ? (
              /* НИЗ СТОИТ С САМОГО НАЧАЛА, а не появляется вместе с правкой (#567).

                 Появляющийся низ менял высоту шторки, а она растёт снизу вверх — от одного нажатия
                 «+5» всё содержимое подскакивало сантиметра на два. Кнопка, которую человек только
                 что нажал, уезжала из-под пальца, и на её месте оказывалась соседняя: второе нажатие
                 попадало не туда, куда целились. Владелец увидел это первым же снимком.

                 Поэтому кнопки здесь всегда, а пока править нечего — они погашены. Это ещё и честнее:
                 видно заранее, что число само никуда не уйдёт и его надо записать. */
              <div className="page-foot">
                <div className="bas-act-col">
                  <HoldButton label={ждём ? 'Записываю…' : 'Записать'}
                    disabled={!!ждём || !естьПравки} onComplete={() => void записать()} />
                  <button className="page-btn" disabled={!естьПравки} onClick={() => setЧерновик({})}>
                    <Иконка icon={refreshOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
                    Вернуть как было
                  </button>
                </div>
              </div>
            ) : undefined}>
          {/* ПРАВИЛО ФРАЗОЙ, ЧИСЛА ВНУТРИ НЕЁ (#590, мост 1.67). Фраза приходит от движка вместе
              с правилом: сочинять медицинское утверждение из чужих параметров мы себе не
              позволяем, а шаблон по идентификатору сломал бы главное свойство экрана — новая
              тревога появляется здесь сама.

              Фраза показывает ЧЕРНОВИК: число в тексте меняется сразу, и это и есть «станет так»
              — отдельной строкой его писать не надо. */}
          {фраза && п.включено && (
            <div className="правило-фраза">
              {фраза.map((к, i) => (к.вид === 'текст'
                ? <span key={i}>{к.текст}</span>
                : числоВоФразе(к.поле)))}
            </div>
          )}
          {/* Шаги — только у того числа, которое тронули: две кнопки на экране вместо восьми. */}
          {фраза && п.включено && правимое && (
            <div className="правило-шаги">
              <div className="правило-шаги-имя">{правимое.имя}</div>
              {шаги(правимое)}
              {правимое.границы && (
                /* «Рекомендовано … · допустимо …» — та же строка, что у пределов петли. Без неё
                   человек крутит число вслепую: «0,15 ммоль/мин» ни о чём не говорит. */
                <div className="правило-предел">
                  допустимо {правимое.границы.min.toFixed(правимое.знаков).replace('.', ',')}…
                  {правимое.границы.max.toFixed(правимое.знаков).replace('.', ',')}
                  {правимое.единица ? ` ${правимое.единица}` : ''}
                </div>
              )}
            </div>
          )}
          <div className="basal-rows">
            {/* У выключенного правила числа не показываем: движок убирает его из профиля целиком, и
                они ничего не решают. Показанный порог у неработающего правила читается как обещание. */}
            {/* Выключатель здесь больше не рисуем — он в шапке, и два одинаковых переключателя в
                одном правиле означали бы, что один из них не тот. */}
            {(фраза ? числаВнеФразы(фраза, числа) : числа).map(строкаЧисла)}
          </div>
          {/* Почему выключателя нет — словами, а не молчанием (#482). Признак даёт движок, объясняем
              мы: молчаливое отсутствие человек читает как недоделку и идёт выключать уведомления
              целиком в системных настройках, где потеряет разом все тревоги. */}
          {п.почемуНельзя && <div className="sheet-note">{п.почемуНельзя}</div>}
          {п.оговорка && п.включено && <div className="sheet-note warn">{п.оговорка}</div>}
          {п.ссылка && (
            <button className="changed-btn во-всю" style={{ marginTop: 8 }}
              onClick={() => открытьСнаружи(п.ссылка as string)}>
              <Иконка icon={openOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
              Почему именно так
            </button>
          )}
          </Sheet>
        </div>
        );
      })}
      {ошибка && <div className="sheet-note warn">Не приняли правку: {ошибка}</div>}
    </>
  );
}
