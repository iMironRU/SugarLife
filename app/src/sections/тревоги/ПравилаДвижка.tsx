import Иконка from '@/ui/Иконка';
import Переключатель from '@/ui/Переключатель';

import { openOutline, chevronForward } from 'ionicons/icons';
import { useState } from 'react';
import { sendIntent } from '@/sources/bridge';
import type { AlarmRuleView } from '@/sources/bridge';
import { правилаНаЭкран, значениеСловом, следующее, сводкаПравила, type Поле } from '@/показ/правилаТревог';
import { открытьСнаружи } from '@/platform/appUpdate';
import Sheet from '@/ui/Sheet';

/* ПРАВИЛА ТРЕВОГ ИЗ ДВИЖКА (SugarLife#482, шаг 3).

   Экран не хранит своей копии правил: движок отдаёт список вместе с ключами настроек, тем же ключом
   настройка и правится (`setConfig`). Поэтому новая тревога появляется здесь сама, без нашей правки, —
   и поэтому же тут нет ни одного зашитого порога.

   ЧИСЛО БЕЗ ОБЪЯСНЕНИЯ НЕ ПОКАЗЫВАЕМ. У правил движка есть статья (`helpUrl`), и правило проекта общее с
   ядром: нет объяснения — нет настройки. «Скорость падения 0,15 ммоль/мин» человеку не говорит ничего,
   пока он не прочтёт, откуда она взялась.

   ОГОВОРКУ ПОКАЗЫВАЕМ РЯДОМ С ЧИСЛОМ, а не в подсказке: «порог 15 мин, фактически до 24» — это и есть
   правда о заданном числе, и прятать её значит обещать то, чего платформа не даёт.

   ШТОРКИ ВМЕСТО ПРОСТЫНИ (#500). Раскрытые разом, восемь правил давали экран на пять пролистываний:
   у каждого заголовок, выключатель, два-три числа с кнопками −/+ и ссылка на статью. Найти в этом
   нужное правило нельзя — можно только читать подряд, чего никто не делает.

   Список отвечает на обычный вопрос одной строкой: за чем следит, каким голосом и при каких числах.
   Числа правятся в шторке снизу — в неё идут редко и осознанно, и там у правила есть место на
   объяснение, оговорку и статью, не отнимая его у соседей. Раскрытие на месте (аккордеон) сюда не
   годится: список от него прыгает, и правило, которое правишь, уезжает под палец.

   ВЫКЛЮЧАТЕЛЬ ОСТАЁТСЯ СНАРУЖИ, в свёрнутой строке: «следить или нет» — решение куда более частое,
   чем правка порога, и прятать его за раскрытием значило бы менять местами частое и редкое. */

export default function ПравилаДвижка({ правила }: { правила: AlarmRuleView[] | undefined }) {
  /** Какое правило открыто шторкой. Одно: шторка перекрывает экран, двух сразу не бывает. */
  const [открыто, setОткрыто] = useState<string | null>(null);
  /* Что не приняли — говорим сразу. Молчаливый отказ читается как «кнопка сломана», и человек жмёт
     её снова. */
  const [ошибка, setОшибка] = useState<string | null>(null);
  const [ждём, setЖдём] = useState<string | null>(null);
  const список = правилаНаЭкран(правила);
  if (!список.length) return null;

  const править = async (ключ: string, значение: string) => {
    setЖдём(ключ);
    setОшибка(null);
    const r = await sendIntent({ type: 'setConfig', patch: { [ключ]: значение } });
    setЖдём(null);
    /* Структурные ключи движок валидирует сам. Не принял — значит значение вне допустимого. */
    if (!r.accepted) setОшибка(r.error || 'движок не принял это значение');
  };

  const строкаЧисла = (поле: Поле) => {
    const ниже = следующее(поле, -1);
    const выше = следующее(поле, 1);
    return (
      <div key={поле.ключ}>
        <div className="basal-row">
          <span>{поле.имя}</span>
          <b>{значениеСловом(поле)}{поле.единица ? ` ${поле.единица}` : ''}</b>
        </div>
        {(ниже || выше) && (
          <div className="alert-ask alert-ask-row">
            <button className="changed-btn" disabled={!ниже || ждём === поле.ключ}
              onClick={() => ниже && void править(поле.ключ, ниже)}>
              −{поле.шаг.toString().replace('.', ',')}
            </button>
            <button className="changed-btn" disabled={!выше || ждём === поле.ключ}
              onClick={() => выше && void править(поле.ключ, выше)}>
              +{поле.шаг.toString().replace('.', ',')}
            </button>
          </div>
        )}
      </div>
    );
  };

  return (
    <>
      <div className="section-label sec">Правила тревог</div>
      <div className="sheet-note">
        Считает движок — один расчёт на телефон и на айфон. Здесь то, по каким числам он это делает;
        правки уходят ему сразу.
      </div>
      {список.map((п) => {
        const выключатель = п.поля.find((поле) => поле.выключатель);
        return (
        <div key={п.id} className="правило">
          <div className="правило-шапка">
            <button className="правило-кнопка" onClick={() => setОткрыто(п.id)}>
              <span className="правило-имя">{п.имя}</span>
              <span className="правило-сводка">{сводкаПравила(п)}</span>
            </button>
            {/* Выключатель — снаружи шторки и вне кнопки раскрытия: это два разных действия, и
                попадание пальцем не должно решать, какое из них случилось. */}
            {выключатель && (
              <Переключатель checked={выключатель.включено} disabled={ждём === выключатель.ключ}
                onChange={(v) => void править(выключатель.ключ, v ? 'on' : 'off')} />
            )}
            <Иконка icon={chevronForward} className="правило-шеврон" />
          </div>
          <Sheet isOpen={открыто === п.id} onClose={() => setОткрыто(null)}
            title={п.имя} subtitle={сводкаПравила(п)}>
          <div className="basal-rows">
            {/* У выключенного правила числа не показываем: движок убирает его из профиля целиком, и
                они ничего не решают. Показанный порог у неработающего правила читается как обещание. */}
            {/* Выключатель здесь больше не рисуем — он в шапке, и два одинаковых переключателя в
                одном правиле означали бы, что один из них не тот. */}
            {п.поля.filter((поле) => п.включено && !поле.выключатель).map(строкаЧисла)}
          </div>
          {/* Почему выключателя нет — словами, а не молчанием (#482). Признак даёт движок, объясняем
              мы: молчаливое отсутствие человек читает как недоделку и идёт выключать уведомления
              целиком в системных настройках, где потеряет разом все тревоги. */}
          {п.почемуНельзя && <div className="sheet-note">{п.почемуНельзя}</div>}
          {п.оговорка && п.включено && <div className="sheet-note warn">{п.оговорка}</div>}
          {п.ссылка && (
            <button className="changed-btn во-всю" style={{ marginTop: 8 }}
              onClick={() => открытьСнаружи(п.ссылка as string)}>
              <Иконка icon={openOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
              Почему именно так
            </button>
          )}
          </Sheet>
        </div>
        );
      })}
      {ошибка && <div className="sheet-note warn">Не приняли правку: {ошибка}</div>}
    </>
  );
}
