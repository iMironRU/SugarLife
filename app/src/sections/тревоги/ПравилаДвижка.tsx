import Иконка from '@/ui/Иконка';
import { IonToggle } from '@ionic/react';
import { chevronForward } from 'ionicons/icons';
import { useState } from 'react';
import { sendIntent } from '@/sources/bridge';
import type { AlarmRuleView } from '@/sources/bridge';
import { правилаНаЭкран, сводкаПравила, type ПравилоНаЭкран } from '@/показ/правилаТревог';
import { useStack } from '@/app/stackCtx';
import { ПравилоSection } from '@/sections/lazy';

/* ПРАВИЛА ТРЕВОГ ИЗ ДВИЖКА (SugarLife#482, шаг 3).

   Экран не хранит своей копии правил: движок отдаёт список вместе с ключами настроек, тем же ключом
   настройка и правится (`setConfig`). Поэтому новая тревога появляется здесь сама, без нашей правки, —
   и поэтому же тут нет ни одного зашитого порога.

   ЧИСЛО БЕЗ ОБЪЯСНЕНИЯ НЕ ПОКАЗЫВАЕМ. У правил движка есть статья (`helpUrl`), и правило проекта общее с
   ядром: нет объяснения — нет настройки. «Скорость падения 0,15 ммоль/мин» человеку не говорит ничего,
   пока он не прочтёт, откуда она взялась.

   ОГОВОРКУ ПОКАЗЫВАЕМ РЯДОМ С ЧИСЛОМ, а не в подсказке: «порог 15 мин, фактически до 24» — это и есть
   правда о заданном числе, и прятать её значит обещать то, чего платформа не даёт.

   СПИСОК ВМЕСТО ПРОСТЫНИ (#500). Раскрытые разом, восемь правил давали экран на пять пролистываний:
   у каждого заголовок, выключатель, два-три числа с кнопками −/+ и ссылка на статью. Найти в этом
   нужное правило нельзя — можно только читать подряд, чего никто не делает.

   Список отвечает на обычный вопрос одной строкой: за чем следит, каким голосом и при каких числах.
   Раскрытие на месте (аккордеон) сюда не годится: список от него прыгает, и правило, которое
   правишь, уезжает под палец.

   ПРАВКА УШЛА НА СТРАНИЦУ (#590, решение владельца). Сначала числа правились здесь же, в шторке;
   потом у правила появились фраза, пределы и оговорка — и шторка выросла до 88% экрана с липким
   низом, то есть стала страницей, которая притворяется шторкой. Правило теперь одно на всё
   приложение: смотреть можно в шторке, менять уходишь на страницу.

   ВЫКЛЮЧАТЕЛЬ ОСТАЁТСЯ СНАРУЖИ, в свёрнутой строке: «следить или нет» — решение куда более частое,
   чем правка порога, и прятать его за раскрытием значило бы менять местами частое и редкое.

   ЧИСЛА ПРАВЯТСЯ ЧЕРНОВИКОМ, А ЗАПИСЫВАЮТСЯ УДЕРЖАНИЕМ (#566, решение владельца).

   Раньше каждое нажатие «−0,1» немедленно уходило движку: пять нажатий — пять записей конфига, и
   «как было» взять неоткуда. Для порога, который решает, разбудят ли ночью, это неверный порядок:
   промах пальцем менял защиту молча и без пути назад.

   ± правят черновик, внизу страницы закреплены «Вернуть как было» и удержание «Записать». Схема та
   же, что в профиле петли, и намеренно та же: два места, где число решает медицинский вопрос,
   должны спрашивать одинаково.

   Уход со страницы с неписаным черновиком ОТМЕНЯЕТ правку. Из двух молчаливых исходов этот
   безопасный: тревога остаётся работать так, как работала. Поэтому же кнопка записи закреплена
   внизу, а не уезжает с прокруткой — уйти, не увидев её, трудно.

   ВЫКЛЮЧАТЕЛЬ ЧЕРНОВИКА НЕ ЗНАЕТ и уходит сразу: «следить или нет» — одно решение целиком, а не
   набор шагов, и держать его в черновике значило бы придумать половинчатое состояние. */

export default function ПравилаДвижка({ правила }: { правила: AlarmRuleView[] | undefined }) {
  const { push, pop } = useStack();
  /* Что не приняли — говорим сразу. Молчаливый отказ читается как «кнопка сломана», и человек жмёт
     её снова. Здесь остался только выключатель: числа правятся на странице и отвечают там же. */
  const [ошибка, setОшибка] = useState<string | null>(null);
  const [ждём, setЖдём] = useState<string | null>(null);
  const список = правилаНаЭкран(правила);
  if (!список.length) return null;

  const открыть = (п: ПравилоНаЭкран) =>
    push(<ПравилоSection ruleId={п.id} title={п.имя} onClose={pop} />,
      { id: 'правило', ruleId: п.id, title: п.имя });

  const править = async (ключ: string, значение: string) => {
    setЖдём(ключ);
    setОшибка(null);
    const r = await sendIntent({ type: 'setConfig', patch: { [ключ]: значение } });
    setЖдём(null);
    /* Структурные ключи движок валидирует сам. Не принял — значит значение вне допустимого. */
    if (!r.accepted) setОшибка(r.error || 'движок не принял это значение');
    return r.accepted;
  };

  return (
    <>
      <div className="section-label sec">Правила тревог</div>
      <div className="sheet-note">
        Считает движок — один расчёт на телефон и на айфон. Здесь то, по каким числам он это делает.
        Правка порога записывается удержанием: случайное касание не должно менять защиту.
      </div>
      {список.map((п) => {
        const выключатель = п.поля.find((поле) => поле.выключатель);
        return (
        <div key={п.id} className="правило">
          <div className="правило-шапка">
            <button className="правило-кнопка" onClick={() => открыть(п)}>
              <span className="правило-имя">{п.имя}</span>
              <span className="правило-сводка">{сводкаПравила(п)}</span>
            </button>
            {/* Выключатель — снаружи и вне кнопки перехода: это два разных действия, и попадание
                пальцем не должно решать, какое из них случилось. «Следить или нет» — решение куда
                более частое, чем правка порога, и уводить его на страницу незачем. */}
            {выключатель && (
              <IonToggle checked={выключатель.включено} disabled={ждём === выключатель.ключ}
                onIonChange={(e) => void править(выключатель.ключ, e.detail.checked ? 'on' : 'off')} />
            )}
            <Иконка icon={chevronForward} className="правило-шеврон" />
          </div>
        </div>
        );
      })}
      {ошибка && <div className="sheet-note warn">Не приняли правку: {ошибка}</div>}
    </>
  );
}
