import { useEffect, useState } from 'react';
import { IonIcon, IonToggle } from '@ionic/react';
import { alarmOutline, notificationsOutline, playOutline, trendingUpOutline, phonePortraitOutline, cloudOfflineOutline, appsOutline } from 'ionicons/icons';
import Section from '@/ui/Section';
import Row from '@/ui/Row';
import {
  настройкиТревоги, задатьТревогу, проверитьТревогу, тревогиДоступны,
  ПОРОГ_ПО_УМОЛЧАНИЮ, МИН_ПОРОГ, МАКС_ПОРОГ,
  ВЫСОКИЙ_ПО_УМОЛЧАНИЮ, МИН_ВЫСОКИЙ, МАКС_ВЫСОКИЙ, ТИХО_ВЫКЛ,
  МОЛЧАНИЕ_ПО_УМОЛЧАНИЮ, МИН_МОЛЧАНИЕ, МАКС_МОЛЧАНИЕ, ШАГ_МОЛЧАНИЯ,
  type НастройкиТревоги,
} from '@/platform/тревоги';
import { isNative, platform } from '@/platform/appUpdate';
import { тихоСейчас } from '@/domain/тихиеЧасы';
import { баннерВозможен, состояниеБаннера, включитьБаннер, type СостояниеБаннера } from '@/platform/живойБаннер';
import { виджетВозможен, добавитьВиджет, type ИтогДобавления } from '@/platform/виджет';

/* Тревоги (#418).

   ЧЕСТНОСТЬ ПРО ДОСТАВКУ — ПЕРВЫМ ДЕЛОМ, а не сноской внизу. Человек включает тревогу и
   ложится спать с уверенностью, что его разбудят. Если разбудить мы не можем — сказать об
   этом надо до того, как он уснёт, а не после того, как не проснулся.

   ПРОВЕРОЧНАЯ КНОПКА ОБЯЗАТЕЛЬНА. Иначе узнать, работают ли тревоги, можно только когда
   ночью случится гипогликемия, — худший из возможных способов узнать. Кнопка проходит
   весь путь целиком: канал, звук, обход «не беспокоить», полноэкранное уведомление. */
const ПУСТО: НастройкиТревоги = {
  on: false, mmol: ПОРОГ_ПО_УМОЛЧАНИЮ,
  highOn: false, highMmol: ВЫСОКИЙ_ПО_УМОЛЧАНИЮ,
  quietFrom: ТИХО_ВЫКЛ, quietTo: ТИХО_ВЫКЛ,
  silenceOn: false, silenceMin: МОЛЧАНИЕ_ПО_УМОЛЧАНИЮ,
};

/* Час словами: «23:00». Минут в тихих часах нет намеренно — человек ложится «около
   одиннадцати», а не в 23:15, и точность здесь создаёт работу без пользы. */
const часПодпись = (ч: number) => (ч === ТИХО_ВЫКЛ ? 'не заданы' : `${String(ч).padStart(2, '0')}:00`);
const следующийЧас = (ч: number) => (ч === ТИХО_ВЫКЛ ? 22 : (ч + 1) % 24);

export default function AlarmsSection({ onClose }: { onClose: () => void }) {
  const [н, setН] = useState<НастройкиТревоги | null>(null);
  const [готово, setГотово] = useState(false);
  const [проверил, setПроверил] = useState(false);
  const [баннер, setБаннер] = useState<СостояниеБаннера | null>(null);
  const [виджет, setВиджет] = useState<ИтогДобавления | null>(null);

  useEffect(() => {
    void настройкиТревоги().then((r) => { setН(r ?? ПУСТО); setГотово(true); });
    void состояниеБаннера().then(setБаннер);
  }, []);

  const менять = (патч: Partial<НастройкиТревоги>) => {
    const новое = { ...(н ?? ПУСТО), ...патч };
    setН(новое);
    void задатьТревогу(новое);
  };

  const порог = н?.mmol ?? ПОРОГ_ПО_УМОЛЧАНИЮ;
  const молчание = н?.silenceMin ?? МОЛЧАНИЕ_ПО_УМОЛЧАНИЮ;
  const можем = тревогиДоступны();

  return (
    <Section title="Тревоги" описание="Что должно разбудить и при каких числах. Тревога — это то, что происходит, когда вы не смотрите на экран." onBack={onClose}>

      {/* Предел доставки — до всего остального. */}
      {!можем && (
        <div className="today-alert warn">
          <IonIcon icon={notificationsOutline} className="alert-ico" />
          <div>
            <span className="alert-title">
              {!isNative ? 'В браузере тревог нет' : 'На этом телефоне разбудить не сможем'}
            </span>
            <span>
              {!isNative
                ? 'Браузер не будит: страница спит вместе с телефоном. Тревоги работают в приложении на Android.'
                : platform === 'ios'
                  ? 'На iPhone нет фоновой службы и push-уведомлений, поэтому тревога придёт, только пока приложение открыто. Обещать ночную мы не можем и не будем.'
                  : 'Эта сборка старше тревог — обновите приложение целиком (не только интерфейс).'}
            </span>
          </div>
        </div>
      )}

      {/* Блока «ночью может не разбудить» здесь БОЛЬШЕ НЕТ (#473): сюда попадают из
          «Охраны», где этот ответ дан первым делом. Повторять его через экран — учить
          пролистывать: два одинаковых предупреждения подряд читают как одно. */}

      <div className="section-label sec">Низкий сахар</div>
      <div className="list">
        <Row icon={alarmOutline} title="Будить при низком сахаре"
          sub={можем ? 'звук будильника, поверх «не беспокоить»' : 'недоступно на этом устройстве'}
          right={<IonToggle checked={!!н?.on} disabled={!можем || !готово}
            onIonChange={(e) => менять({ on: e.detail.checked })} />} />
      </div>

      {н?.on && (
        <>
          <div className="section-label sec">Порог</div>
          <div className="basal-rows">
            <div className="basal-row">
              <span>Будить ниже</span>
              <b>{порог.toFixed(1).replace('.', ',')} ммоль/л</b>
            </div>
          </div>
          <div className="alert-ask alert-ask-row">
            <button className="changed-btn" disabled={порог <= МИН_ПОРОГ}
              onClick={() => менять({ mmol: Math.round((порог - 0.1) * 10) / 10 })}>−0,1</button>
            <button className="changed-btn" disabled={порог >= МАКС_ПОРОГ}
              onClick={() => менять({ mmol: Math.round((порог + 0.1) * 10) / 10 })}>+0,1</button>
          </div>
          {/* Правила, по которым тревога срабатывает, — словами. Человек, который их не
              знает, читает молчание как поломку, а задержку — как «не сработало». */}
          <div className="sheet-note">
            Будим, когда два показания подряд ниже порога: сенсор шумит, и одиночный выброс
            вниз — повод посмотреть, а не будить. Пока сахар не поднялся, тревога
            повторяется — сначала через десять минут, потом реже, до получаса.
          </div>
        </>
      )}

      {/* МОЛЧАНИЕ ПРИБОРА — СРАЗУ ПОСЛЕ НИЗКОГО САХАРА, и это не вопрос порядка строк.

          Гипо считается от показаний. Нет показаний — нечего сравнивать, и тревога молчит; на
          экране и в кармане это выглядит точно так же, как «всё хорошо». Человек, включивший
          только верхнюю строку, уходит спать под охраной, которой нет. Поэтому вторая стоит
          вплотную и объясняет себя словами, а не названием. */}
      <div className="section-label sec">Прибор молчит</div>
      <div className="list">
        <Row icon={cloudOfflineOutline} title="Будить, если данные перестали идти"
          sub={можем ? 'ночью тоже — тихие часы её не глушат' : 'недоступно на этом устройстве'}
          right={<IonToggle checked={!!н?.silenceOn} disabled={!можем || !готово}
            onIonChange={(e) => менять({ silenceOn: e.detail.checked })} />} />
      </div>
      {н?.on && !н?.silenceOn && (
        <div className="sheet-note warn">
          Тревога о низком сахаре считается по показаниям. Если сенсор замолчит, будить будет
          нечем — и тишина будет выглядеть так же, как хороший сахар.
        </div>
      )}
      {н?.silenceOn && (
        <>
          <div className="basal-rows">
            <div className="basal-row">
              <span>Ждать</span>
              <b>{молчание} мин</b>
            </div>
          </div>
          <div className="alert-ask alert-ask-row">
            <button className="changed-btn" disabled={молчание <= МИН_МОЛЧАНИЕ}
              onClick={() => менять({ silenceMin: молчание - ШАГ_МОЛЧАНИЯ })}>−5 мин</button>
            <button className="changed-btn" disabled={молчание >= МАКС_МОЛЧАНИЕ}
              onClick={() => менять({ silenceMin: молчание + ШАГ_МОЛЧАНИЯ })}>+5 мин</button>
          </div>
          <div className="sheet-note">
            Повторяем, пока данные не вернулись: первый раз через пятнадцать минут, дальше
            реже, до получаса. Молчание ночью означает, что тревога о низком сахаре сработать
            не может — считать нечего, и одного сигнала тут мало. Когда данные вернутся,
            уведомление уйдёт само. Пока приборы отданы другому телефону, эта тревога молчит:
            тогда пауза объяснена.
          </div>
        </>
      )}

      <div className="section-label sec">Высокий сахар</div>
      <div className="list">
        <Row icon={trendingUpOutline} title="Говорить о высоком"
          sub={можем ? 'без будильника ночью — см. тихие часы' : 'недоступно на этом устройстве'}
          right={<IonToggle checked={!!н?.highOn} disabled={!можем || !готово}
            onIonChange={(e) => менять({ highOn: e.detail.checked })} />} />
      </div>
      {н?.highOn && (
        <>
          <div className="basal-rows">
            <div className="basal-row">
              <span>Говорить выше</span>
              <b>{(н?.highMmol ?? ВЫСОКИЙ_ПО_УМОЛЧАНИЮ).toFixed(1).replace('.', ',')} ммоль/л</b>
            </div>
          </div>
          <div className="alert-ask alert-ask-row">
            <button className="changed-btn" disabled={(н?.highMmol ?? 0) <= МИН_ВЫСОКИЙ}
              onClick={() => менять({ highMmol: Math.round(((н?.highMmol ?? ВЫСОКИЙ_ПО_УМОЛЧАНИЮ) - 0.5) * 10) / 10 })}>−0,5</button>
            <button className="changed-btn" disabled={(н?.highMmol ?? 0) >= МАКС_ВЫСОКИЙ}
              onClick={() => менять({ highMmol: Math.round(((н?.highMmol ?? ВЫСОКИЙ_ПО_УМОЛЧАНИЮ) + 0.5) * 10) / 10 })}>+0,5</button>
          </div>
          <div className="sheet-note">
            Повторяем не чаще раза в час: высокий сахар требует решения, но не в ту же
            минуту, а тревога каждые десять минут — наказание за то, что вы уже знаете.
          </div>
        </>
      )}

      {/* ТИХИЕ ЧАСЫ ГЛУШАТ ТОЛЬКО ВЫСОКИЙ. Это и есть условие, при котором они вообще
          имеют право существовать: низкий сахар ночью требует действий сейчас, и
          заглушённая тревога — не тревога. Без этого правила человек однажды выключил бы
          тревоги целиком, вместе с той, которая спасает. */}
      <div className="section-label sec">Тихие часы</div>
      <div className="basal-rows">
        <div className="basal-row"><span>С</span><b>{часПодпись(н?.quietFrom ?? ТИХО_ВЫКЛ)}</b></div>
        <div className="basal-row"><span>До</span><b>{часПодпись(н?.quietTo ?? ТИХО_ВЫКЛ)}</b></div>
      </div>
      <div className="alert-ask alert-ask-row">
        <button className="changed-btn" disabled={!можем}
          onClick={() => менять({ quietFrom: следующийЧас(н?.quietFrom ?? ТИХО_ВЫКЛ) })}>Сдвинуть начало</button>
        <button className="changed-btn" disabled={!можем}
          onClick={() => менять({ quietTo: следующийЧас(н?.quietTo ?? ТИХО_ВЫКЛ) })}>Сдвинуть конец</button>
        <button className="changed-btn" disabled={!можем || (н?.quietFrom ?? ТИХО_ВЫКЛ) === ТИХО_ВЫКЛ}
          onClick={() => менять({ quietFrom: ТИХО_ВЫКЛ, quietTo: ТИХО_ВЫКЛ })}>Убрать</button>
      </div>
      <div className="sheet-note">
        {тихоСейчас(new Date().getHours(), н?.quietFrom ?? ТИХО_ВЫКЛ, н?.quietTo ?? ТИХО_ВЫКЛ)
          ? 'Сейчас тихие часы: о высоком промолчим. Низкий сахар разбудит в любом случае.'
          : 'Низкий сахар тихие часы не глушат никогда — ради этого они и могут существовать. Молчит только «высокий»: ночью он требует решения утром, а не подъёма.'}
      </div>

      {/* ЖИВОЙ БАННЕР — здесь же, а не отдельным разделом (#428). Это соседняя вещь: и
          тревога, и баннер отвечают на вопрос «что я узнаю, не открывая приложение».
          Развести их по разным экранам значило бы заставить искать дважды. */}
      {баннерВозможен() && (
        <>
          <div className="section-label sec">Живой баннер</div>
          <div className="list">
            <Row icon={phonePortraitOutline} title="Показывать сахар на экране блокировки"
              sub={баннер?.умеет === false
                ? 'нужен iOS 16.2 или новее'
                : 'и в «Динамическом острове», и на панели CarPlay'}
              right={<IonToggle checked={!!баннер?.включён} disabled={баннер?.умеет === false}
                onIonChange={(e) => {
                  const on = e.detail.checked;
                  setБаннер((б) => (б ? { ...б, включён: on } : б));
                  void включитьБаннер(on);
                }} />} />
          </div>
          <div className="sheet-note">
            Обновляется, когда приходит показание, — не раз в пятнадцать минут, как обычный
            виджет. Система гасит такие баннеры через восемь часов; приложение продлевает
            их само, пока получает данные.
          </div>
        </>
      )}

      {/* ВИДЖЕТ — ТО ЖЕ САМОЕ ДЛЯ ANDROID, и потому стоит там же, где баннер для айфона
          (#449). Вопрос у человека один: «что я узнаю, не открывая приложение». Ответ на
          двух платформах разный по механике, но искать его он будет в одном месте. */}
      {виджетВозможен() && (
        <>
          <div className="section-label sec">Виджет на рабочем столе</div>
          <div className="list">
            <Row icon={appsOutline} title="Поставить виджет на рабочий стол"
              sub="сахар, кольцо и возраст показания — без открытия приложения"
              onClick={() => { void добавитьВиджет().then(setВиджет); }} />
          </div>
          <div className="sheet-note">
            {виджет === 'спросили'
              ? 'Система спросила, куда его поставить. Если окно не появилось — добавьте вручную: долгое нажатие на пустое место экрана → «Виджеты» → SugarLife.'
              : виджет === 'не умеет'
                ? 'Этот лаунчер не умеет ставить виджеты по просьбе приложения. Добавьте вручную: долгое нажатие на пустое место экрана → «Виджеты» → SugarLife.'
                : виджет === 'нет метода'
                  ? 'Эта сборка приложения старше виджета — обновите приложение целиком, не только интерфейс.'
                  : 'Возраст показания на виджете считает сам рабочий стол, поэтому «2 мин» не застынет, даже если приложение остановят.'}
          </div>
        </>
      )}

      {можем && (
        <>
          <div className="section-label sec">Проверка</div>
          <button className="changed-btn is-undo во-всю" onClick={() => { void проверитьТревогу(); setПроверил(true); }}>
            <IonIcon icon={playOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
            Проверить тревогу сейчас
          </button>
          <div className="sheet-note">
            {проверил
              ? 'Отправили. Если ничего не слышно — проверьте разрешение на уведомления и «не беспокоить»: тревоги живут в отдельном канале «Тревоги», его громкость и обход задаются в настройках телефона.'
              : 'Пройдёт тем же путём, что настоящая тревога: тот же канал, звук и обход «не беспокоить». Проверьте до того, как ляжете спать, а не после.'}
          </div>
        </>
      )}

      <div className="sheet-note">
        Тревогу считает фоновая служба приложения, а не экран: она живёт, пока приложение
        не убрали из недавних. Убрали — приборы отпускаются и тревог не будет.
      </div>
    </Section>
  );
}
