import { useState } from 'react';
import Иконка from '@/ui/Иконка';
import { notificationsOutline, playOutline } from 'ionicons/icons';
import Section from '@/ui/Section';
import { проверитьТревогу, тревогиДоступны } from '@/platform/тревоги';
import { isNative, platform } from '@/platform/appUpdate';
import { useSnapshot } from '@/sources/bridge';
import ПравилаДвижка from './тревоги/ПравилаДвижка';
import { ядроУмеетТревоги } from '@/показ/правилаТревог';

/* Тревоги (#418, #482).

   ЧТО ОСТАЛОСЬ ПОСЛЕ ПЕРЕЕЗДА. Правила считает движок и отдаёт списком
   (sections/тревоги/ПравилаДвижка.tsx); числа правятся его же ключами. Своих порогов у экрана больше
   нет — они правили андроидную половину, которой не стало.

   ЧЕСТНОСТЬ ПРО ДОСТАВКУ — ПЕРВЫМ ДЕЛОМ, а не сноской внизу. Человек включает тревогу и ложится спать
   с уверенностью, что его разбудят. Если разбудить мы не можем — сказать об этом надо до того, как он
   уснёт, а не после того, как не проснулся.

   ПРОВЕРОЧНАЯ КНОПКА ОБЯЗАТЕЛЬНА. Иначе узнать, работают ли тревоги, можно только когда ночью случится
   гипогликемия, — худший из возможных способов узнать. Кнопка проходит весь путь целиком: канал, звук,
   обход «не беспокоить», полноэкранное уведомление. */

export default function AlarmsSection({ onClose }: { onClose: () => void }) {
  const [проверил, setПроверил] = useState(false);
  const снимок = useSnapshot();
  const правила = снимок?.alarmRules;
  const умеет = ядроУмеетТревоги(снимок?.bridgeRevision);
  const можем = тревогиДоступны();

  return (
    <Section title="Тревоги" описание="Что должно разбудить и при каких числах. Тревога — это то, что происходит, когда вы не смотрите на экран." onBack={onClose}>

      {/* Предел доставки — до всего остального. */}
      {!можем && (
        <div className="today-alert warn">
          <Иконка icon={notificationsOutline} className="alert-ico" />
          <div>
            <span className="alert-title">
              {!isNative ? 'В браузере тревог нет' : 'На этом телефоне разбудить не сможем'}
            </span>
            <span>
              {!isNative
                ? 'Браузер не будит: страница спит вместе с телефоном. Тревоги работают в приложении на телефоне.'
                : 'Эта сборка старше тревог — обновите приложение целиком (не только интерфейс).'}
            </span>
          </div>
        </div>
      )}

      {/* ЧЕМ АЙФОННАЯ ТРЕВОГА ОТЛИЧАЕТСЯ — сказать заранее (#482).

          Правила одни и те же, а доставка разная: обход «не беспокоить» и полноэкранное уведомление
          Apple выдаёт только по отдельному разрешению, которого у нас нет. Вместо них — свой звук,
          и он звучит, пока приложение живо в фоне. Умолчать об этом значит пообещать ночную
          тревогу, которой может не быть. */}
      {можем && platform === 'ios' && (
        <div className="sheet-note">
          На iPhone тревога будит своим звуком поверх беззвучного режима — пока включено фоновое
          бодрствование в «Охране». Обхода «Не беспокоить» и полноэкранного уведомления на iPhone у
          нас нет: их Apple выдаёт по отдельному разрешению.
        </div>
      )}

      {/* Блока «ночью может не разбудить» здесь БОЛЬШЕ НЕТ (#473): сюда попадают из
          «Охраны», где этот ответ дан первым делом. Повторять его через экран — учить
          пролистывать: два одинаковых предупреждения подряд читают как одно. */}

      <ПравилаДвижка правила={правила} />

      {/* ДВЕ РАЗНЫЕ ПРИЧИНЫ ПУСТОТЫ, и путать их нельзя (#482).

          Старое ядро — тревог нет вовсе: своей логики решений у нас не осталось, и это отказ, о
          котором человек обязан узнать до ночи, а не после. Новое ядро с пустым списком — это уже
          другое: правила есть, просто все выключены им самим. */}
      {можем && !умеет && (
        <div className="today-alert warn">
          <Иконка icon={notificationsOutline} className="alert-ico" />
          <div>
            <span className="alert-title">Тревог в этой сборке нет</span>
            <span>
              Приложению нужно ядро с моделью тревог, а здесь оно старее. Считать их некому: ни
              низкий сахар, ни пропажу данных мы не заметим. Обновите приложение целиком — не
              только интерфейс.
            </span>
          </div>
        </div>
      )}
      {можем && умеет && !правила?.length && (
        <div className="sheet-note warn">
          Движок не отдаёт ни одного правила — значит сейчас не следит ни за чем.
        </div>
      )}

      {/* БАННЕР, СВОДКА И ВИДЖЕТ ПЕРЕЕХАЛИ В «ОФОРМЛЕНИЕ» (#500). Раздел называется «Тревоги», а
         половина его содержимого тревогами не была: баннер, сводка и виджет ничего не решают и никого
         не будят — они показывают. Владелец споткнулся об это дважды, и он прав: это внешний вид, и
         жить ему рядом с темой, а не рядом с порогами гипогликемии.

         Здесь остались правила и проверка — то, что отвечает на «разбудит ли». */}

      {можем && (
        <>
          <div className="section-label sec">Проверка</div>
          <button className="changed-btn is-undo во-всю" onClick={() => { void проверитьТревогу(); setПроверил(true); }}>
            <Иконка icon={playOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
            Проверить тревогу сейчас
          </button>
          <div className="sheet-note">
            {проверил
              ? 'Отправили. Если ничего не слышно — проверьте разрешение на уведомления и «не беспокоить»: тревоги живут в отдельном канале «Тревоги», его громкость и обход задаются в настройках телефона.'
              : 'Пройдёт тем же путём, что настоящая тревога: тот же канал, звук и обход «не беспокоить». Проверьте до того, как ляжете спать, а не после.'}
          </div>
        </>
      )}

      <div className="sheet-note">
        Тревогу считает фоновая служба приложения, а не экран: она живёт, пока приложение
        не убрали из недавних. Убрали — приборы отпускаются и тревог не будет.
      </div>
    </Section>
  );
}
