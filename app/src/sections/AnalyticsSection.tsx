import { причинаНеготовности } from '@/показ/находки';
import { ПЕРИОДЫ_РАЗБОРА, дней } from '@/domain/периоды';
import { useEffect, useState } from 'react';
import Иконка from '@/ui/Иконка';
import { warning, alertCircle } from 'ionicons/icons';
import Section from '@/ui/Section';
import PageLoading from '@/ui/PageLoading';
import Insights from '@/ui/Insights';
import { useAnalysis } from '@/domain/useAnalysis';
import { useHistory } from '@/sources/db';
import Dynamics from '@/ui/Dynamics';
import { отметитьПрочитанными } from '@/settings/seenInsights';

/* Разбор данных — отдельный раздел, а не врезка на главном экране.

   На «Сегодня» человек решает, что делать сейчас; разбор отвечает на другой вопрос —
   что происходило и почему. Это разные режимы, и смешивать их концепция запрещает.
   Поэтому с «Сегодня» ведёт плитка, а вся разборка живёт здесь.

   Период выбирается явно: находки от него зависят напрямую. «Ночные гипо: 3 за
   14 дней» и «3 за 3 дня» — это разные новости, и человек должен видеть, за что
   считалось. */


/* Раздел умеет жить и внутри экрана «Метрики» (SugarLife#255): там он одна из трёх
   вкладок, и своя шапка ему не нужна — она была бы второй шапкой под настоящей. */
export default function AnalyticsSection({ onClose, встроенный }: {
  onClose?: () => void; встроенный?: boolean;
}) {
  const [days, setDays] = useState(14);
  /* Расчёт общий с плиткой на «Сегодня» (domain/useAnalysis.ts): счётчик важных
     находок и содержимое этого экрана обязаны совпадать, а совпадают они надёжно
     только если считаются одним кодом из одних аргументов. */
  const { analysis, loading: читаю } = useAnalysis(days);
  /* Для сравнения нужен ещё один такой же период назад. Читаем вдвое шире, а делит
     историю сам блок: он же решает, можно ли вообще сравнивать (ui/Dynamics.tsx). */
  const { entries: история } = useHistory(2 * days * 86400e3, { minRefreshMs: 3600e3 });

  /* Зашли — всё, что сейчас на экране, прочитано. Отсюда и берётся смысл счётчика на
     плитке: он показывает не «сколько всего важного», а «сколько появилось с прошлого
     раза» (SugarLife#148). */
  const ids = analysis.insights.map((i) => i.id).join(',');
  useEffect(() => {
    if (!читаю) отметитьПрочитанными(analysis.insights.map((i) => i.id));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [ids, читаю]);



  /* Качество данных — в подзаголовок, а не карточкой сверху (#197).

     Эта строка не сообщение, а оговорка ко ВСЕМУ, что ниже: она говорит, насколько
     верить находкам и процентам. Карточка занимала полтора экрана в начале раздела и
     отодвигала то, ради чего сюда пришли, — а по смыслу это ровно подзаголовок.

     Когда данных достаточно, не пишем ничего. Постоянная зелёная плашка «данных
     достаточно» читается первую неделю, потом перестаёт замечаться — и вместе с ней
     перестаёт замечаться жёлтая, которая важна. */
  const r = analysis.readiness;
  const вид = r.level === 'ready'
    ? null
    : r.level === 'partial'
      ? { icon: warning, color: 'var(--c-carb)', слово: 'с оговорками' }
      : { icon: alertCircle, color: 'var(--c-danger)', слово: 'данных мало' };

  /* Пока история читается — показываем ожидание, а не поспешный вердикт. Разбор по
     ещё не приехавшим данным сказал бы «данных пока мало», и это прочли бы как ответ.

     НО ТОЛЬКО ПРИ ПЕРВОМ ЧТЕНИИ. Раньше заглушка подменяла раздел ЦЕЛИКОМ, вместе с
     переключателем периодов, — то есть человек нажимал «90 дней» и терял кнопки, которыми
     нажимал. Вернуться было нечем, оставалось ждать.

     Теперь переключатель остаётся на месте всегда, а ожидание занимает только то место, где
     будут выводы. Ждать, глядя на живой переключатель, — это ожидание; ждать, глядя на пустой
     экран, — это поломка. */
  const первоеЧтение = читаю && !analysis.insights.length;
  if (первоеЧтение) return встроенный ? <PageLoading /> : <PageLoading title="Аналитика" />;

  const подзаголовок = (
        <>
          Разбор за {days} {дней(days)}
          {вид && (
            <>
              {' · '}
              <span style={{ color: вид.color }}>
                <Иконка icon={вид.icon} style={{ fontSize: 11, verticalAlign: '-1px', marginRight: 3 }} />
                {вид.слово}
              </span>
            </>
          )}
        </>
  );

  const тело = (
    <>
      {встроенный && <div className="metric-note" style={{ marginTop: 2 }}>{подзаголовок}</div>}
      <div className="period">
        {ПЕРИОДЫ_РАЗБОРА.map((d) => (
          <button key={d} className={'period-seg' + (days === d ? ' on' : '')} onClick={() => setDays(d)}>
            {d}
          </button>
        ))}
      </div>

      {/* Читаем более широкий период — переключатель уже на месте, ждём только выводы.
          Разбор за прежний период здесь не показываем: он про другие дни, и оставить его
          значило бы подписать старые числа новым заголовком. */}
      {читаю && <PageLoading />}

      {!читаю && <>
      {/* Причины остаются, но строкой, а не карточкой: «нет учёта углеводов» — это
          то, что человек может починить, и выбрасывать его вместе с плашкой нельзя.
          Показываем только когда есть оговорка: при полных данных объяснять нечего. */}
      {/* Разбор возвращает коды причин, называет их слой показа (#324). */}
      {вид && r.reasons.length > 0 && (
        <div className="sheet-note warn" style={{ marginTop: 10 }}>
          {r.reasons.map(причинаНеготовности).join(' · ')}
        </div>
      )}

      {/* Что изменилось — до находок, а не после (#195).

          Находки отвечают на «что происходит», а этот блок — на «сработало ли то, что
          я поменял». Второй вопрос человек задаёт себе первым, когда заходит сюда
          через неделю после смены базала: сначала «стало ли лучше», и только потом
          «почему». */}
      <div className="section-label sec">Что изменилось</div>
      <Dynamics entries={история} дней={days} кому="себе" />

      {/* Ряда фильтров по виду находки здесь больше нет (#149). Он не влезал в
          ширину — «Привычки» уезжали за край, — и прятал варианты: чего не видно,
          того для человека не существует. А главное, фильтровать девять пунктов
          незачем: вид находки виден по её тексту, а разделы по важности показывают
          всё сразу. */}
      <Insights analysis={analysis} />

      <div className="sheet-note">
        Всё посчитано из ваших же данных — истории CGM и событий Nightscout. Ничего не
        додумано: чего в данных нет, того здесь не будет. Это не назначения, а наблюдения,
        по которым удобно готовить вопросы врачу.
      </div>
    </>}
    </>
  );

  if (встроенный) return тело;
  return <Section title="Аналитика" onBack={onClose ?? (() => {})} subtitle={подзаголовок}
      описание="Что изменилось за период и почему. Разбор считается по тем же источникам, что и всё остальное, — если данные неполные, здесь об этом сказано.">{тело}</Section>;
}
