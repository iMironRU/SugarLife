import { createPortal } from 'react-dom';
import { деньМесяц, датаПолная } from '@/слова/время';
import AgpSvg from '@/charts/AgpSvg';
import type { AgpPoint } from '@/domain/agp';

/* Записка к приёму — файл, а не распечатка экрана (#156).

   ПЕЧАТЬ БРАУЗЕРА, А НЕ БИБЛИОТЕКА. Оба пути дают PDF, но библиотека — это триста
   килобайт кода и ещё столько же кириллического шрифта, который придётся вшить, иначе
   в файле окажутся квадраты. Мы только что померили, что половину первого экрана
   занимает то, чем пользуемся на треть (#405); добавлять к этому мегабайт ради
   документа, который человек делает четыре раза в год, — значит платить за него
   каждым запуском приложения. Печать в PDF есть в обеих системах, работает офлайн и
   верстается обычным CSS.

   ЭТО ОТДЕЛЬНЫЙ ДОКУМЕНТ. Печатать экран нельзя: он тёмный, узкий, с переключателями
   и кнопками, которые на бумаге превращаются в мусор. Здесь своя вёрстка под лист:
   чёрным по белому, таблицами, с полями.

   ЭТО НЕ МЕДИЦИНСКИЙ ДОКУМЕНТ, И ВЫГЛЯДЕТЬ ОН ТАК НЕ ДОЛЖЕН. Ни шапки организации, ни
   печати, ни подписи. Записку готовит пациент, и однажды принесённая вместо выписки
   она навредит — поэтому сказано прямо, первой строкой под заголовком.

   ИМЯ — ПО ЖЕЛАНИЮ И НЕ ХРАНИТСЯ. Файл уходит с телефона: в мессенджер, в почту, на
   чужой компьютер. Сегодня данные не покидают устройство вовсе, и это первый канал
   наружу — значит, что в него попадёт, решает человек, а не умолчание. */

/* Что не так со строкой — РАЗНЫЕ вещи, и называть их одним словом нельзя.

   Первая версия ставила «вне цели» всюду, где строка красная, и получилось «базал
   посчитан по 9 из 14 дней ▲ вне цели» — будто девять дней это плохой результат, а не
   предупреждение о неполноте. И «осмотр глазного дна · 16 мес назад ▲ вне цели» — у
   осмотра нет цели, у него есть срок. Врач читает пометку буквально; неверная хуже
   отсутствующей. */
export type Пометка = 'вне цели' | 'мало данных' | 'просрочено';
export interface СтрокаОтчёта { что: string; значение: string; примечание?: string | null; пометка?: Пометка | null }
export interface БлокОтчёта { имя: string; строки: СтрокаОтчёта[] }

export interface Записка {
  имя: string | null;
  отМс: number;
  доМс: number;
  дней: number;
  доля: number;
  хватаетДанных: boolean;
  минДней: number;
  минДоля: number;
  цели: string;
  /* Типовой день за те же четырнадцать дней. Отдельным полем, а не внутри блока: блоки
     — это строки «что: значение», а картинку в строку не положить. Пусто — раздела нет
     вовсе, потому что пустая рамка читается как сломанная печать. */
  типовойДень: AgpPoint[];
  блоки: БлокОтчёта[];
  вопросы: string[];
}

/* Пометка «вне цели» — сразу за числом, а не в конце ячейки.

   Первая версия вешала её на всю ячейку, и на листе выходило «0 · нужно ≥ 14 ▲ вне цели»:
   пометка относилась к норме, а не к числу. Читается как «норма неправильная».

   И это не только цвет: на чёрно-белом принтере красный исчезает совсем, а именно эти
   строки врач ищет первыми (#325). */
function Значение({ текст, пометка }: { текст: string; пометка?: Пометка | null }) {
  return (
    <span className={пометка ? 'печать-знач мимо' : 'печать-знач'}>
      {текст}
      {пометка && <span className="печать-метка"> ▲ {пометка}</span>}
    </span>
  );
}

export default function КПечати(з: Записка) {
  const естьЧто = з.блоки.some((б) => б.строки.length > 0);
  return createPortal(
    <div className="печать" role="document">
      <header className="печать-шапка">
        <h1>Записка к приёму</h1>
        {/* Кто и за что отвечает — сразу под заголовком, а не сноской внизу. Внизу это
            прочитают после того, как сделают вывод. */}
        <p className="печать-кто">
          Подготовлено пациентом в приложении SugarLife. Наблюдения по данным сенсора и
          помпы и вопросы к врачу. Не заключение, не выписка, не назначения.
        </p>
        <table className="печать-шапка-таблица">
          <tbody>
            {з.имя && <tr><th>Пациент</th><td>{з.имя}</td></tr>}
            <tr><th>Период</th><td>{деньМесяц(з.отМс)} — {деньМесяц(з.доМс)}</td></tr>
            {/* Полнота — в шапке. Отчёт по двум неделям с 40 % пропусков и отчёт без
                пропусков — разные документы, и разницу врач должен видеть до того, как
                начнёт читать проценты. */}
            <tr>
              <th>Дней с данными</th>
              <td>
                <Значение текст={String(з.дней)} пометка={з.дней < з.минДней ? 'мало данных' : null} />
                <span className="печать-тихо"> · нужно ≥ {з.минДней}</span>
              </td>
            </tr>
            <tr>
              <th>Время с активным сенсором</th>
              <td>
                <Значение текст={`${Math.round(з.доля)} %`} пометка={з.доля < з.минДоля ? 'мало данных' : null} />
                <span className="печать-тихо"> · нужно ≥ {з.минДоля} %</span>
              </td>
            </tr>
            <tr><th>Целевые значения</th><td>{з.цели}</td></tr>
          </tbody>
        </table>
        {!з.хватаетДанных && (
          <p className="печать-оговорка">
            Данных меньше, чем требует стандарт оценки ({з.минДней} дней и {з.минДоля} % времени
            с активным сенсором). Проценты ниже стоит читать с поправкой на пропуски.
          </p>
        )}
      </header>

      {/* Пусто — говорим об этом словами. Документ из одной шапки читается как ошибка
          печати, а не как «данных за период нет». */}
      {!естьЧто && (
        <p className="печать-оговорка">
          За выбранный период данных нет: сенсор не передавал показаний, записей о
          лечении тоже не поступало. Показывать в этой записке нечего.
        </p>
      )}

      {/* График — сразу после шапки, до таблиц. Проценты отвечают, СКОЛЬКО времени
          сахар был не там, а картинка — КОГДА; второй вопрос в кабинете задают первым,
          и ответ на него должен лежать выше, а не через страницу цифр. */}
      {з.типовойДень.length > 0 && (
        <section className="печать-блок печать-график">
          <h2>Типовой день за 14 дней</h2>
          <figure style={{ margin: 0 }}>
            <AgpSvg точки={з.типовойДень} />
            <figcaption>
              Линия — медиана: типичный сахар для этого часа. Плотная полоса — половина
              всех значений (25–75 %), бледная — почти все (5–95 %). Светлая полоса
              поперёк листа — целевой диапазон 3,9–10,0. По горизонтали часы суток.
              Разрыв линии означает, что показаний за это время не было.
            </figcaption>
          </figure>
        </section>
      )}

      {з.блоки.filter((б) => б.строки.length > 0).map((б) => (
        <section key={б.имя} className="печать-блок">
          <h2>{б.имя}</h2>
          <table>
            <tbody>
              {б.строки.map((с) => (
                <tr key={с.что}>
                  <th>{с.что}</th>
                  <td>
                    <Значение текст={с.значение} пометка={с.пометка} />
                    {с.примечание && <span className="печать-тихо"> · {с.примечание}</span>}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      ))}

      {з.вопросы.length > 0 && (
        <section className="печать-блок печать-вопросы">
          <h2>Вопросы к приёму</h2>
          {/* Место для ответа врача — то, ради чего лист и печатают: человек уносит с
              приёма не память, а бумагу с пометками. */}
          <ol>
            {з.вопросы.map((в) => (
              <li key={в}><span className="печать-вопрос">{в}</span><span className="печать-линейка" /></li>
            ))}
          </ol>
        </section>
      )}

      <footer className="печать-подвал">
        Составлено {датаПолная(Date.now())} · SugarLife
      </footer>
    </div>,
    document.body,
  );
}
