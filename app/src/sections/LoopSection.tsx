import Section from '@/ui/Section';
import Row from '@/ui/Row';
import { repeat, lockClosedOutline, listOutline } from 'ionicons/icons';
import { useStack } from '@/app/stackCtx';
import { LoopSetupSection } from '@/sections/lazy';
import { useLoopProfile, LOOP_MODES, limitsFor, fmtLimit } from '@/settings/loopProfile';

/* «Петля» — своё место, а не строка «Профиль петли» среди настроек (SugarLife#279).

   Петля не настройка и не прибор. Это режим управления подачей, у которого есть
   собственное состояние (какие полномочия сейчас), собственные правила понижения и
   собственная история изменений. Строка «Профиль петли» отвечала только на «как
   настроено» и молчала о главном — что происходит сейчас.

   Профиль отсюда никуда не делся: он стал тем, чем и был, — одним из ответов внутри
   темы, а не самой темой. */
/* Правила понижения полномочий. Не настраиваются: это описание поведения движка, и
   менять его из интерфейса нельзя — там граница безопасности. */
const ПРАВИЛА: [string, string][] = [
  ['нет данных НМГ', 'через заданные минуты полномочия понижаются на ступень, далее ещё на одну'],
  ['доза не подтверждена', 'микроболюсы снимаются немедленно'],
  ['расхождение часов помпы', 'понижение до L1: временную привязку доз восстановить нельзя'],
  ['потеря связи', 'ВБС отменяется, помпа возвращается к базальному профилю'],
  ['перезапуск приложения', 'старт с L2 с последующим подъёмом'],
  ['восстановление', 'после трёх циклов без замечаний, не ранее 15 минут'],
];

export default function LoopSection({ onClose }: { onClose: () => void }) {
  const { push, pop } = useStack();
  const профиль = useLoopProfile();
  const режим = LOOP_MODES.find((m) => m.id === профиль.mode) ?? LOOP_MODES[0];
  const лимиты = limitsFor(профиль.mode);
  /* Чего не хватает до следующей ступени — из того же словаря режимов, что и мастер.
     Человек, записавший профиль, возвращается сюда с вопросом «а дальше что»; раньше
     ответ был только внутри мастера, при выборе режима. */
  const следующий = LOOP_MODES[LOOP_MODES.findIndex((m) => m.id === профиль.mode) + 1] ?? null;

  return (
    <Section title="Петля" описание="Правила, по которым считается подача: уровень полномочий, пределы и профиль. Само включение подачи живёт не здесь." onBack={onClose}>
      {/* Первым — что сейчас, а не что настроено. Человек приходит сюда с вопросом
          «работает ли», и ответ на него не должен требовать нажатия. */}
      <div className="wz-l0">
        <span>
          Сейчас <b>{режим.code} · {режим.name}</b>. {профиль.savedAt
            ? 'Команды в помпу не отправляются: приложение в редакции Lite.'
            : 'Профиль ещё не записан.'}
        </span>
      </div>

      {следующий && (
        <div className="metric-note">
          Следующая ступень — <b>{следующий.code} · {следующий.name}</b>. {следующий.need}.
          Пока подача недоступна, это остаётся описанием, а не предложением.
        </div>
      )}

      <div className="section-label sec">Настройка</div>
      <div className="list">
        <Row icon={repeat} title="Профиль петли"
          sub={профиль.savedAt ? `${режим.code} · ${режим.name.toLowerCase()}` : 'не настроен'}
          onClick={() => push(<LoopSetupSection onClose={pop} />)} />
      </div>

      {профиль.savedAt && лимиты.length > 0 && (
        <>
          <div className="section-label sec">Лимиты</div>
          <div className="list">
            {лимиты.map((л) => (
              <Row key={л.id} icon={listOutline} title={л.name}
                value={`${fmtLimit(л, профиль.values[л.id])} ${л.unit}`} chevron={false} />
            ))}
          </div>
        </>
      )}

      {/* Правила понижения переехали сюда из мастера (#279). Они нужны не в момент
          настройки, а когда полномочия упали и человек спрашивает почему: справка о
          поведении, а не шаг настройки. */}
      <div className="section-label sec">Когда полномочия понижаются</div>
      {ПРАВИЛА.map(([что, следствие]) => (
        <div key={что} className="wz-rule">
          <span className="wz-rule-a">{что}</span>
          <span className="wz-rule-b">{следствие}</span>
        </div>
      ))}
      <div className="wz-fixed ok">
        <div className="wz-fixed-n">Нижняя ступень — не нулевая подача</div>
        <div className="wz-fixed-v ok">возврат к базальному профилю помпы</div>
        <div className="sheet-note">
          Полное прекращение подачи опасно так же, как избыток. Крайняя мера — вернуть
          управление профилю помпы.
        </div>
      </div>

      <div className="section-label sec">Границы</div>
      <div className="list">
        <Row icon={lockClosedOutline} title="Что приложение не делает"
          sub="не отправляет команды в помпу и не вводит инсулин"
          chevron={false} />
      </div>
      <div className="metric-note">
        Управление подачей живёт в редакции Pro. Здесь профиль записывается и хранится —
        чтобы он был готов и одинаков, когда подача станет доступна.
      </div>
    </Section>
  );
}
