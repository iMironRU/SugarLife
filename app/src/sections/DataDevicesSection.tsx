import { useState } from 'react';
import Section from '@/ui/Section';
import ServicesSection from './ServicesSection';
import SourcesSection from './SourcesSection';
import DevicesSection from './DevicesSection';

/* Один вход в хозяйство вместо трёх (SugarLife#279).

   Из Профиля вели три двери — «Откуда берутся данные», «Помпа, сенсоры, глюкометр,
   петля» и «Облака», — и список приборов встречался в двух из них. Человек выбирал
   дверь до того, как понимал, что ищет.

   ВХОД ОБЩИЙ, ВОПРОСЫ РАЗНЫЕ. Свести всё в один список нельзя: «почему цифры такие» —
   диагностика, с ней приходят, когда сахар отстал; «какой у меня прибор» — заведение и
   обслуживание, это бывает раз в несколько месяцев. Смешаешь — и человек ищет одно
   среди другого; мы уже дважды получали неправду там, где на два вопроса отвечало одно
   место (#230, #247).

   Поэтому вкладки, а не общий список: дверь одна, комнаты две. */
const ВКЛАДКИ = [
  /* «Данные», а не «Откуда данные»: длинное название ломалось на две строки и делало
     вкладку вдвое выше соседних. Вопрос «откуда» задаёт сам экран первой же строкой —
     повторять его в ярлыке незачем. */
  { key: 'данные', label: 'Данные' },
  { key: 'приборы', label: 'Приборы' },
  /* Облака третьей вкладкой, а не подвалом «Приборов». Работа с ними другая: адрес,
     токен, учётная запись, «что отсюда забираем» — ни одного действия из тех, что
     делают с железкой. Внизу списка приборов они выглядели придатком, хотя у многих
     людей облако — единственный источник вообще. */
  { key: 'облака', label: 'Облака' },
] as const;
type Вкладка = typeof ВКЛАДКИ[number]['key'];

const ОПИСАНИЕ: Record<Вкладка, string> = {
  данные: 'Откуда берутся цифры. По этим источникам считается всё остальное: активный инсулин, активные углеводы, прогноз и разбор.',
  приборы: 'Что у вас есть и на связи ли оно. Прибор — это ЧТО; каким путём он попадает в приложение, видно в его карточке.',
  облака: 'Серверы, через которые данные приходят и уходят. Облако — это КАК, а не что: одна и та же помпа может читаться и по радио, и отсюда.',
};

export default function DataDevicesSection({ onClose, вкладка: начальная }: {
  onClose: () => void;
  /* С какой вкладки открыть. Обращение «связь потеряна» ведёт сюда с вопросом «почему
     нет данных», и встречать его списком железа значит отвечать не на то (#279). */
  вкладка?: Вкладка;
}) {
  /* По умолчанию — ПРИБОРЫ (просьба с телефона).

     Раздел называется «Устройства и данные», и открывать его на «Данных» значило
     встречать человека ответом на второй вопрос. Приходят сюда почти всегда с первым:
     что у меня есть и на связи ли оно. «Откуда данные» нужнее в одном случае — когда
     сюда ведёт обращение «связь потеряна», и там вкладка по-прежнему передаётся явно. */
  const [вкладка, setВкладка] = useState<Вкладка>(начальная ?? 'приборы');

  return (
    /* Описание меняется вместе со вкладкой, а не описывает дверь целиком.

       Общее описание двери и собственное пояснение вкладки стояли двумя абзацами
       подряд — и первый из них не отвечал ни на один вопрос, потому что за дверью три
       разных предмета. Вкладки и есть предметы; значит описывать надо их. */
    <Section title="Устройства и данные" описание={ОПИСАНИЕ[вкладка]} onBack={onClose}
      подШапкой={(
        <div className="period sec-switch">
          {ВКЛАДКИ.map((в) => (
            <button key={в.key} className={'period-seg' + (вкладка === в.key ? ' on' : '')}
              onClick={() => setВкладка(в.key)}>{в.label}</button>
          ))}
        </div>
      )}>
      {вкладка === 'данные' && <SourcesSection встроенный />}
      {вкладка === 'приборы' && <DevicesSection встроенный />}
      {вкладка === 'облака' && <ServicesSection встроенный />}
    </Section>
  );
}
