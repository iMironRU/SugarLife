import { useCallback, useEffect, useState } from 'react';
import Section from '@/ui/Section';
import Sheet from '@/ui/Sheet';
import Иконка from '@/ui/Иконка';
import { chevronForward } from 'ionicons/icons';
import { строки, type ПунктНатива, type Строка } from '@/показ/разрешения';
import { прочитатьПрава, спроситьПраво, открытьНастройкиПрава } from '@/platform/права';

/* «РАЗРЕШЕНИЯ» — ОДИН СПИСОК ВМЕСТО ПОИСКА ПО НАСТРОЙКАМ ТЕЛЕФОНА (#538).

   Система прячет их в разных местах: уведомления в одном, срочные внутри них, Bluetooth в третьем,
   энергосбережение в четвёртом. Собрать картину человек не может — и узнаёт о запрете не тогда,
   когда его дал, а ночью, когда не сработала тревога.

   ЭТО НЕ ВТОРАЯ «ОХРАНА». «Охрана» отвечает на вопрос «разбудят ли меня этой ночью» и говорит про
   последствия; здесь — инвентарь: что мы просили, что нам дали, что можно поправить. Пересечение
   есть (уведомления важны обоим), и это нормально: один и тот же факт отвечает на два разных
   вопроса. Слова у него при этом одни (`показ/разрешения.ts`), чтобы ответы не разошлись.

   ЧТО МОЖНО СДЕЛАТЬ, СКАЗАНО В САМОЙ СТРОКЕ. Спросить систему можно ровно один раз: после отказа
   диалога больше не будет, и кнопка «Разрешить» стала бы кнопкой, которая ничего не делает. Там,
   где вопрос уже бессмыслен, ведём в настройки телефона. */
export default function PermissionsSection({ onClose }: { onClose: () => void }) {
  const [список, setСписок] = useState<ПунктНатива[] | null>(null);
  const [занят, setЗанят] = useState<string | null>(null);
  const [открыт, setОткрыт] = useState<Строка | null>(null);

  const перечитать = useCallback(() => { void прочитатьПрава().then(setСписок); }, []);

  useEffect(() => {
    перечитать();
    /* Возвращение из настроек телефона — главный момент этого экрана: человек ушёл чинить и
       вернулся. Экран, оставшийся прежним, читается как «сделал, и не помогло». */
    const слушатель = () => { if (document.visibilityState === 'visible') перечитать(); };
    document.addEventListener('visibilitychange', слушатель);
    return () => document.removeEventListener('visibilitychange', слушатель);
  }, [перечитать]);

  const нажали = async (с: Строка) => {
    if (!с.действие) return;
    setЗанят(с.id);
    if (с.действие === 'спросить') {
      const свежий = await спроситьПраво(с.id);
      if (свежий) setСписок(свежий);
      /* Ответ человека приходит позже самого вызова: системный диалог живёт своей жизнью, и
         состояние меняется, когда он его закроет. Перечитываем ещё раз следом. */
      setTimeout(перечитать, 400);
    } else {
      await открытьНастройкиПрава(с.id);
    }
    setЗанят(null);
  };

  const готово = список ? строки(список) : [];

  return (
    <Section title="Разрешения"
      описание="Что мы просили у телефона и что нам дали. Здесь же можно поправить."
      onBack={onClose}>

      {список === null ? (
        <div className="metric-note">
          Раздел работает в приложении на телефоне: у страницы в браузере этих разрешений нет.
        </div>
      ) : (
        <>
          <div className="list">
            {готово.map((с) => (
              <div key={с.id} className="list-row охрана-пункт">
                <span className={'охрана-знак-п ' + (с.знак === 'да' ? 'ок' : с.знак === 'нет' ? 'нет' : 'незнаем')} />
                <button className="охрана-пункт-кнопка" onClick={() => setОткрыт(с)}>
                  <span className="list-title">{с.имя}</span>
                  <span className="pick-sub">{статусСловами(с)}</span>
                </button>
                {с.действие ? (
                  <button className="охрана-чинить" disabled={занят === с.id}
                    onClick={() => void нажали(с)}>
                    {занят === с.id ? '…' : с.действие === 'спросить' ? 'спросить' : 'настройки'}
                    <Иконка icon={chevronForward} />
                  </button>
                ) : (
                  <Иконка icon={chevronForward} className="охрана-шеврон-п" />
                )}
              </div>
            ))}
          </div>

          <div className="metric-note">
            Отказ окончателен: система показывает свой вопрос один раз, дальше только настройки
            телефона. Ничего лишнего мы не просим — разрешение, которым не пользуются, всё равно
            однажды станет вопросом «зачем им это».
          </div>
        </>
      )}

      {/* Зачем разрешение — шторкой, а не подписью в строке: текст длинный, а в строке он
          обрывается многоточием ровно на том месте, где начинается ответ (#529). */}
      <Sheet isOpen={!!открыт} onClose={() => setОткрыт(null)} title={открыт?.имя ?? ''}>
        {открыт && (
          <>
            <p className="sheet-text">{открыт.зачем}</p>
            <p className="sheet-text">Сейчас: {статусСловами(открыт)}.</p>
            {открыт.действие && (
              <button className="changed-btn is-undo во-всю" disabled={занят === открыт.id}
                onClick={() => { void нажали(открыт); setОткрыт(null); }}>
                {открыт.действие === 'спросить' ? 'Спросить разрешение' : 'Открыть настройки телефона'}
              </button>
            )}
          </>
        )}
      </Sheet>
    </Section>
  );
}

/* «Не спрашивали» — не то же самое, что «запрещено», и путать их нельзя: в первом случае человеку
   достаточно нажать, во втором придётся идти в настройки. «Неизвестно» тоже своё слово: система не
   ответила, и выдавать это за отказ значит пугать без повода. */
function статусСловами(с: Строка): string {
  if (с.статус === 'разрешено') return 'разрешено';
  if (с.статус === 'не спрашивали') return 'ещё не спрашивали';
  if (с.статус === 'частично') return 'ограничено системой';
  if (с.статус === 'неизвестно') return 'не удалось узнать';
  return 'запрещено';
}
