import { IonIcon } from '@ionic/react';
import { phonePortraitOutline } from 'ionicons/icons';
import { открытьВПриложении, type Раздел } from '@/platform/deepLink';
import { isNative } from '@/platform/appUpdate';

/* Кнопка «Открыть в приложении» — вместо совета открыть его самому (SugarLife#315).

   Там, где мы честно говорим «в браузере это не работает», человек читал совет и выполнял
   его сам: искал приложение, вспоминал, где нужный экран. Совет без кнопки — тупик.

   ТЕКСТ «В ПРИЛОЖЕНИИ», А НЕ «ПРИЛОЖЕНИЕ», и это не придирка к словам. Схема может быть не
   зарегистрирована (старая сборка), приложение — снесено, браузер — заблокировать переход.
   Обещать успех мы не вправе; запасной путь на страницу «где взять» уводит через полсекунды
   молчания.

   СТАВИМ НЕ ВЕЗДЕ. Без App Links система спросит, чем открыть ссылку: один раз это
   терпимо, на каждом экране — надоедает. Поэтому кнопка живёт там, где без приложения
   дальше нельзя, а не там, где с ним удобнее. */
export default function ВПриложении({ раздел, подпись }: { раздел: Раздел; подпись?: string }) {
  // Мы уже внутри приложения — открывать себя же значит моргнуть экраном ради ничего.
  if (isNative) return null;
  return (
    <button className="changed-btn is-undo" style={{ marginTop: 10 }}
      onClick={() => открытьВПриложении(раздел)}>
      <IonIcon icon={phonePortraitOutline} style={{ marginRight: 6, verticalAlign: -2 }} />
      {подпись ?? 'Открыть в приложении'}
    </button>
  );
}
