import { useEffect, useRef, useState } from 'react';
import { useSnapshot } from '@/sources/bridge';
import { принять, свежие, ЖИЗНЬ_МС, type Копилка } from '@/показ/хорошиеНовости';

/* ХОРОШУЮ НОВОСТЬ ГОВОРИМ ТИХО (#482, просьба ядра).

   Стоит там же, где полоса тревоги, и это не случайность: человек, который встал ночью и пошёл
   возобновлять подачу, вернётся смотреть на то же место. Молчаливое исчезновение тревоги
   неотличимо от того, что её и не было.

   ЗВУКА НЕТ И КНОПКИ НЕТ. Хорошая новость, сказанная будильником, — плохая новость; «Понял» на ней
   требовал бы действия там, где отвечать не на что. Уходит сама.

   ЧАСЫ СВОИ, И ОНИ РЕДКИЕ. Новость живёт десять минут, а снимок приходит раз в несколько минут —
   без своего тика строка провисела бы до следующего снимка. Минута точности здесь достаточна:
   ошибка в полминуты на десятиминутном сроке человеку не видна. */

const ТИК_МС = 60_000;

export default function ХорошиеНовости() {
  const снимок = useSnapshot();
  /* Копилка переживает снимки: события одноразовы, снимок их забирает и очищает. */
  const копилка = useRef<Копилка>(new Map());
  const [, перерисовать] = useState(0);

  const события = снимок?.alarmEvents;
  useEffect(() => {
    if (!события?.length) return;
    принять(копилка.current, события, Date.now());
    перерисовать((n) => n + 1);
  }, [события]);

  useEffect(() => {
    const т = setInterval(() => перерисовать((n) => n + 1), ТИК_МС);
    return () => clearInterval(т);
  }, []);

  const новости = свежие(копилка.current, Date.now());
  if (!новости.length) return null;

  return (
    <>
      {новости.map((н) => (
        <div key={н.id} className="новость">
          <span className="новость-знак">✓</span>
          <span>{н.слова}</span>
        </div>
      ))}
    </>
  );
}

/** Только для проверки: срок жизни называет слой показа, а не разметка. */
export { ЖИЗНЬ_МС };
