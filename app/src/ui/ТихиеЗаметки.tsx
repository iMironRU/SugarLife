import { useSnapshot } from '@/sources/bridge';
import { тихиеЗаметки } from '@/показ/тихиеЗаметки';

/* СКАЗАТЬ, НЕ ТРЕБУЯ (#812, правило движка из #811).

   Здесь живёт «полёт вниз»: сахар идёт вниз устойчиво, и по этой скорости он придёт к порогу.
   Движок предупреждает так за 46 минут вместо девяти у сирены.

   ЗВУКА НЕТ, КНОПКИ НЕТ, И ЭТО НЕ НЕДОДЕЛКА. На 598 сутках истории владельца такое падение доходит
   до гипогликемии в одном случае из пяти. Как тревога это мусор — четыре ложных подъёма из пяти
   кончились бы тем, что защиту выключили бы целиком. Как спидометр работает: он и должен гореть
   часто, потому что ничего не прерывает.

   МЕСТО — НИЖЕ ТОГО, ЧТО ТРЕБУЕТ ОТВЕТА. Тревога и отбой первыми: там человеку есть что сделать.
   Заметка следом — она отвечает на вопрос «что происходит», а не «что делать».

   СЛОВА ДВИЖКА КАК ЕСТЬ. Числа в них пересобираются на каждый снимок, поэтому они свежие; а про
   падение сахара это ещё и медицинское высказывание, и второй его редакции быть не должно. */
export default function ТихиеЗаметки() {
  const снимок = useSnapshot();
  const заметки = тихиеЗаметки(снимок);
  if (!заметки.length) return null;

  return (
    <>
      {заметки.map((з) => (
        <div key={з.id} className="заметка">
          {/* Стрелка вниз, а не восклицательный знак: знак тревоги на строке, которая права в
              одном случае из пяти, обесценил бы его там, где он про настоящую беду. */}
          <span className="заметка-знак" aria-hidden="true">↓</span>
          <span className="заметка-текст">{з.текст}</span>
        </div>
      ))}
    </>
  );
}
