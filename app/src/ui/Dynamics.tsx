import { useMemo } from 'react';
import { stats } from '@/domain/agp';
import { toUnits, unitLabel } from '@/domain/units';
import { динамика, сравнимо, полнота, чтоСталоЛучше } from '@/domain/visitNote';
import type { Entry } from '@/sources/nightscout';

/* «Что изменилось» — один блок на два экрана (SugarLife#195).

   Появился в записке к приёму, но приём бывает раз в три месяца, а вопрос «то, что я
   поменял, работает?» возникает через неделю после того, как человек это поменял.
   Поэтому тот же блок нужен и в разборе — и потому он здесь, а не скопирован во второй
   экран: разъезжаются не формулы, разъезжаются пороги и формулировки.

   Разница между экранами ровно одна — кому адресована фраза: врачу («это стоит
   показать») или самому человеку («вот что изменилось»). Всё остальное общее.

   ГДЕ ЛЕГКО НАВРЕДИТЬ, и это не про код. Похвала, появляющаяся каждый раз, перестаёт
   читаться — и в тот день, когда она настоящая, её тоже не заметят. Поэтому только при
   реальных сдвигах и без восклицаний. А ухудшение — фактом: человек с диабетом и так
   живёт под постоянной оценкой, и приложение не должно добавлять к ней свою. */

const ДЕНЬ = 86_400_000;
const пц = (v: number) => `${Math.round(v)} %`;

export default function Dynamics({ entries, дней, кому, сейчас = Date.now() }: {
  /* История минимум за два периода: делим её здесь, а не грузим второй раз — окно
     побольше у вызывающего обычно уже прочитано. */
  entries: Entry[];
  дней: number;
  кому: 'врачу' | 'себе';
  сейчас?: number;
}) {
  const окно = дней * ДЕНЬ;
  const { сдвиги, можно, похвала } = useMemo(() => {
    const свежие = entries.filter((e) => e.t >= сейчас - окно);
    const прошлые = entries.filter((e) => e.t >= сейчас - 2 * окно && e.t < сейчас - окно);
    const можно = сравнимо(
      полнота(свежие, сейчас - окно, сейчас),
      полнота(прошлые, сейчас - 2 * окно, сейчас - окно),
    );
    const сдвиги = можно ? динамика(stats(свежие), stats(прошлые)) : [];
    return { сдвиги, можно, похвала: чтоСталоЛучше(сдвиги) };
  }, [entries, окно, сейчас]);

  const период = дней === 7 ? 'неделю' : дней === 14 ? 'две недели' : `${дней} дн.`;

  if (!можно) {
    /* Молчать нельзя: увидевший пустоту решит, что ничего не изменилось, — а мы просто
       не знаем. Дырявый прошлый период тем и опасен, что «стало лучше» в нём может
       означать «пропущены были плохие часы». */
    return (
      <div className="sheet-note">
        Сравнить с прошлым периодом не получается: в одном из них сенсор молчал больше
        трети времени. Такое сравнение показало бы не изменения, а пропуски.
      </div>
    );
  }

  if (!сдвиги.length) {
    return (
      <div className="sheet-note">
        Заметных изменений за {период} нет — всё держится примерно на прежнем уровне.
      </div>
    );
  }

  return (
    <>
      {/* Короткое окно шумно по своей природе: три дня против трёх сравнивают четыре
          завтрака с четырьмя другими, и одна неудачная ночь двигает проценты сильнее,
          чем всё, что человек поменял. Прятать блок за это нельзя — именно так люди и
          проверяют свежую правку, — но и молчать об этом нечестно. */}
      {дней < 7 && (
        <div className="sheet-note">
          {дней} дн. — короткое окно: одна неудачная ночь двигает эти проценты сильнее,
          чем настоящие изменения. Смотреть стоит на неделе и дольше.
        </div>
      )}
      {похвала && (
        <div className="sheet-note good">
          {кому === 'врачу'
            ? `Стало лучше: ${похвала}. Это результат двух недель ежедневной работы — её стоит показать врачу.`
            : `Стало лучше: ${похвала}. За ${период} — заметная разница.`}
        </div>
      )}
      <div className="basal-rows">
        {сдвиги.map((с) => (
          <div key={с.что} className="basal-row">
            <span>{с.что}</span>
            <b className={с.лучше ? 'val-good' : 'val-warn'}>
              {с.вид === 'глюкоза' ? `${toUnits(с.стало)} ${unitLabel()}` : пц(с.стало)}
              <small style={{ opacity: 0.6 }}>
                {' '}· было {с.вид === 'глюкоза' ? `${toUnits(с.было)} ${unitLabel()}` : пц(с.было)}
              </small>
            </b>
          </div>
        ))}
      </div>
    </>
  );
}
