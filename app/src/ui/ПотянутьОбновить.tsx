import { useRef, useState, type ReactNode } from 'react';
import Крутилка from './Крутилка';

/* ПОТЯНУТЬ ВНИЗ — ОБНОВИТЬ. Своё, вместо `IonRefresher` (SugarLife#405).

   Жест на месте, где его ожидают, и без кнопки: опрос идёт раз в минуту, но когда связь пропала и
   вернулась, ждать минуту незачем — человек уже смотрит в экран.

   ПОРОГ БОЛЬШЕ ОБЫЧНОГО (90 px, как было у Ionic здесь же): панель на этом экране и так ездит за
   пальцем, и при стандартном пороге случайный потяг запускал бы опрос по десять раз за прокрутку.

   ТЯНЕМ ТОЛЬКО ОТ САМОГО ВЕРХА. Если содержимое прокручено, вниз — это прокрутка, и перехватывать её
   нельзя: иначе список перестанет листаться там, где ему положено.

   СОПРОТИВЛЕНИЕ. Тянется вдвое медленнее пальца — так человек чувствует, что это не прокрутка, а
   натяжение, и понимает, что можно отпустить.

   ДВИЖЕНИЕ ИДЁТ МИМО REACT — И ЭТО ГЛАВНОЕ ЗДЕСЬ (замечание владельца: «резина жёсткая, палец
   оттягиваю, а он тупит»).

   Раньше высота натяжения жила в состоянии, и каждое движение пальца перерисовывало ВСЁ поддерево.
   На «Сегодня» под нами круг с графиком, карточки, обращения и живые тревоги — самый тяжёлый экран
   приложения; шестьдесят перерисовок в секунду он не тянет. На лёгких экранах то же самое было
   незаметно, поэтому и выглядело как «на остальных всё ок».

   Теперь за пальцем едет только сама полоска — прямой записью в стиль узла. React узнаёт лишь о
   смене СОСТОЯНИЯ (тянут / отпустите / спрашиваю), а это случается пару раз за жест. */
const ПОРОГ = 90;
const ПОТОЛОК = 200;

type Вид = 'нет' | 'тянут' | 'хватит';

export default function ПотянутьОбновить({ скроллер, обновить, children }: {
  скроллер: React.RefObject<HTMLDivElement | null>;
  обновить?: () => Promise<void>;
  children: ReactNode;
}) {
  const [вид, setВид] = useState<Вид>('нет');
  const [идёт, setИдёт] = useState(false);
  const старт = useRef<number | null>(null);
  const натяжение = useRef(0);
  const полоска = useRef<HTMLDivElement>(null);

  if (!обновить) return <>{children}</>;

  const высота = (px: number) => {
    натяжение.current = px;
    /* Прямая запись в стиль: узел уже смонтирован, и менять его высоту через состояние значит
       просить React перерисовать всё, что под ним, ради одного числа. */
    if (полоска.current) полоска.current.style.height = px + 'px';
  };

  const начало = (e: React.TouchEvent) => {
    const el = скроллер.current;
    старт.current = el && el.scrollTop <= 0 && !идёт ? e.touches[0].clientY : null;
  };

  const движение = (e: React.TouchEvent) => {
    if (старт.current == null) return;
    const dy = e.touches[0].clientY - старт.current;
    if (dy <= 0) { высота(0); if (вид !== 'нет') setВид('нет'); return; }
    const px = Math.min(ПОТОЛОК, dy / 2);
    высота(px);
    /* Слово меняется дважды за жест — на появлении натяжения и на переходе через порог. Только эти
       два момента и стоят перерисовки. */
    const нужен: Вид = px >= ПОРОГ / 2 ? 'хватит' : 'тянут';
    if (нужен !== вид) setВид(нужен);
  };

  const конец = () => {
    const было = натяжение.current;
    старт.current = null;
    высота(0);
    setВид('нет');
    if (было < ПОРОГ / 2 || идёт) return;
    setИдёт(true);
    void обновить().finally(() => setИдёт(false));
  };

  return (
    <div className="тянуть" onTouchStart={начало} onTouchMove={движение} onTouchEnd={конец} onTouchCancel={конец}>
      {/* Полоска в разметке всегда: монтировать её на первом же пикселе движения — та же перерисовка,
          от которой мы уходим, только в самый неудачный момент, когда палец уже поехал. */}
      <div className="тянуть-полоска" ref={полоска} style={{ height: идёт ? 44 : 0 }}>
        {идёт
          ? <><Крутилка /> <span>Спрашиваю…</span></>
          : вид !== 'нет' && <span>{вид === 'хватит' ? 'Отпустите, чтобы обновить' : 'Потяните, чтобы обновить'}</span>}
      </div>
      {children}
    </div>
  );
}
