import { useLayoutEffect } from 'react';
import { useДочитано } from './useДочитано';

/* Край прокручиваемой области: пружина и затемнение — одной деталью (SugarLife#285).

   Поведение жило врозь: пиксель для пружины — в стилях, метка конца и затемнение — в
   разметке двух поверхностей из трёх, а у шторок не было ничего. Каждую новую
   прокручиваемую область приходилось вспоминать и проверять руками; мы уже дважды
   поймали это на живом экране — «не пружинит» и «затемнение висит там, где конец».

   Теперь это один элемент. Ставится последним ребёнком прокручиваемого содержимого и
   делает три вещи разом: даёт метку конца, гасит затемнение, когда конец виден, и
   получает пиксель переполнения из стиля скроллера.

   Скроллер хук находит сам — по вычисленному overflow, а не по имени класса. Значит
   поверхность, которую заведут завтра, получит поведение, просто вставив эту деталь. */
export default function КрайПрокрутки() {
  const { конец, вКонце, прокручено } = useДочитано<HTMLDivElement>(null);

  /* Верхнее затухание рисует ::before содержимого, а класс ставим его хозяину.

     Псевдоэлементом — потому что прилипнуть к верху может только первый в потоке, а эта
     деталь стоит последней; ::before и есть первый ребёнок, не занимающий места в
     разметке. Классом на родителе — потому что до чужого псевдоэлемента иначе не
     достать.

     useLayoutEffect, а не useEffect: класс должен быть проставлен ДО кадра. С обычным
     эффектом между отрисовкой и правкой класса проходил кадр, и в первом же кадре
     затухание успевало мигнуть. */
  useLayoutEffect(() => {
    конец.current?.parentElement?.classList.toggle('прокручено', прокручено);
  }, [прокручено, конец]);

  return (
    <>
      <div ref={конец} className="stack-end" />
      {/* Событий не ловит: полоска у нижнего края — ровно то место, куда попадает палец
          при прокрутке (pointer-events в стиле). */}
      <div className={'stack-fade' + (вКонце ? ' off' : '')} />
    </>
  );
}
