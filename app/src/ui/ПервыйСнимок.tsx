import { useEffect, useState } from 'react';
import BrandDrop from '@/ui/BrandDrop';
import { ожидание, ДОЛГО_МС } from '@/domain/перваяКартина';
import { перечитатьВсё } from '@/platform/swUpdate';
import { isNative } from '@/platform/appUpdate';

/* Экран ожидания первого снимка (#420).

   НИКОГДА НЕ ПОКАЗЫВАТЬ ПУСТОЕ ПОЛОТНО. Раньше интерфейс рисовал пустоту всё время, пока
   первый снимок не пришёл: ни надписи, ни объяснения. Человек видит серый прямоугольник
   и решает, что приложение сломалось; он при этом прав — оно в этот момент действительно
   не работает.

   И НЕ КРУТИТЬ КОЛЕСО БЕСКОНЕЧНО. Вечная крутилка врёт не меньше серого экрана: обе
   утверждают «всё идёт по плану», когда план сломался. Через восемь секунд говорим
   словами, через тридцать — предлагаем действие.

   Слово «движок» здесь намеренно: человек, который дошёл до этого экрана, уже видел его
   в «О приложении» и в диагностике. Придумывать для той же вещи второе имя — значит
   заставить его гадать, одна это вещь или две. */
export default function ПервыйСнимок() {
  const [прошло, setПрошло] = useState(0);

  useEffect(() => {
    const старт = Date.now();
    const id = window.setInterval(() => setПрошло(Date.now() - старт), 1000);
    return () => window.clearInterval(id);
  }, []);

  const что = ожидание(прошло);

  return (
    <div className="connect">
      <BrandDrop size={96} pulse />
      {/* Крутилка только пока ждём по-нормальному. Дальше она мешает: движения нет, а
          вращение обещает, что оно есть. */}
      {что === 'поднимаем' && <div className="b-spin" />}
      <div className="connect-desc" style={{ textAlign: 'center', maxWidth: 300 }}>
        {что === 'поднимаем' && 'Поднимаем движок…'}
        {что === 'долго' && (
          <>
            Данные не приходят дольше обычного.
            <br />
            Так бывает после долгого перерыва: приложение сначала догружает историю
            прибора и только потом показывает экран.
          </>
        )}
        {что === 'очень долго' && (
          <>
            Движок молчит больше {Math.round(прошло / 1000)} секунд.
            <br />
            Если это повторяется — перезапустите приложение целиком: закройте его из
            списка недавних и откройте заново.
          </>
        )}
      </div>
      {/* В вебе есть за что потянуть: перечитать оболочку. В нативе такой кнопки нет —
          перезапуск делает человек, и обещать ему кнопку, которая ничего не изменит,
          хуже, чем не обещать ничего. */}
      {что === 'очень долго' && !isNative && (
        <button className="changed-btn is-undo во-всю" style={{ maxWidth: 280, marginTop: 16 }}
          onClick={() => void перечитатьВсё()}>
          Загрузить приложение заново
        </button>
      )}
    </div>
  );
}

/** Сколько ждём, прежде чем сказать словами, — для тех, кто хочет сослаться на порог. */
export { ДОЛГО_МС };
