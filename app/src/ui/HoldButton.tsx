import { useRef } from 'react';
import Иконка from './Иконка';
import { timeOutline } from 'ionicons/icons';

/* Кнопка «удерживайте, чтобы применить» (из прототипа мастера петли, 1100 мс).

   Не украшение: на экране, где настраивается подача инсулина, случайный тап не
   должен ничего применять. Полоса заполнения показывает прогресс удержания —
   иначе непонятно, что от тебя хотят.

   ОНА ОБЯЗАНА ОТЛИЧАТЬСЯ ОТ ОБЫЧНОЙ — ДО НАЖАТИЯ, А НЕ ПОСЛЕ (замечание владельца).

   Полоса заполнения объясняет происходящее тому, кто уже держит. Тому, кто только смотрит на
   экран, она не говорит ничего: он видит кнопку, жмёт её как все прочие, ничего не происходит — и
   делает единственный доступный вывод, что кнопка сломана. Особенно ночью и спросонья, то есть
   ровно там, где мы это удержание и завели.

   Поэтому у неё свой облик: пунктирная рамка (её видно и боковым зрением), значок времени и
   подпись под кнопкой.

   ПОДПИСЬ ВЫНЕСЕНА ИЗ КНОПКИ И НАЗЫВАЕТ СРОК (#570, решение владельца).

   Пилюля «держите» стояла внутри, впритык к названию действия, и читалась с ним одной фразой:
   «Понял держите». Два разных сообщения — ЧТО произойдёт и КАК нажимать — были слиты в строку, и
   первое из них важнее. На трёх кнопках из четырёх это было ещё заметнее: в названии уже стояло
   «Удерживайте», и пилюля повторяла его вторым словом.

   Теперь на кнопке — глагол, под ней — срок словами. Срок ВЫВОДИТСЯ ИЗ `holdMs`, а не пишется
   руками: разойдись подпись с поведением — и человек будет отпускать раньше, чем нужно, решив, что
   кнопка сломана. Такие расхождения появляются молча при первой же правке числа.

   СРОКИ СДЕЛАНЫ НАЗЫВАЕМЫМИ. Были 700 и 1100 мс — числа, которые вслух не произносятся: «удерживать
   1,1 секунды» никто не отсчитывает. Стали 1 и 2 секунды.

   Разница между ними сохранена намеренно и она прежняя: у «Понял» цена промаха — «случайно погасил
   тревогу», у применения дозы — «применил не то». Секунда спросонья длиннее, чем кажется, поэтому
   тревоге хватает одной, а лечению — двух. */
const HOLD_MS = 2000;

/** Срок словами. Секунды целыми: доли секунды человек не отсчитывает, а обещать их — обман. */
function срокСловами(мс: number): string {
  const с = Math.round(мс / 1000);
  const слово = с === 1 ? 'секунду' : с < 5 ? 'секунды' : 'секунд';
  return `удерживать ${с} ${слово}`;
}

export default function HoldButton({ label, disabled, className, holdMs, подсказка, onComplete }: {
  label: string; disabled?: boolean;
  /* Своя подпись вместо срока — на случай, когда рядом уже всё сказано. Пустая строка скрывает
     подпись совсем; по умолчанию стоит срок, выведенный из `holdMs`. */
  подсказка?: string;
  /** Свой вид кнопки — для тревожной полосы, где акцентная заливка была бы призывом. */
  className?: string;
  /* Насколько держать. Умолчание — 1100 мс, столько же, сколько у подачи инсулина. Тревоге
     хватает меньше: там цена ошибки — «не то применил», здесь — «случайно погасил», и держать
     секунду спросонья дольше, чем нужно. */
  holdMs?: number;
  onComplete: () => void;
}) {
  const fill = useRef<HTMLSpanElement>(null);
  const timer = useRef<number | null>(null);
  /* Один срок на поведение и на подпись — иначе они разойдутся при первой же правке числа, и
     разойдутся молча: человек станет отпускать раньше, чем нужно, и решит, что кнопка сломана. */
  const держать = holdMs ?? HOLD_MS;

  const stop = () => {
    if (timer.current) { window.clearInterval(timer.current); timer.current = null; }
    if (fill.current) fill.current.style.width = '0%';
  };

  const start = (e: React.PointerEvent) => {
    if (disabled) return;
    e.preventDefault();
    const t0 = Date.now();
    stop();
    timer.current = window.setInterval(() => {
      const p = Math.min(1, (Date.now() - t0) / держать);
      if (fill.current) fill.current.style.width = p * 100 + '%';
      if (p >= 1) { stop(); onComplete(); }
    }, 16);
  };

  const кнопка = (
    <button
      className={'hold-btn' + (disabled ? ' off' : '') + (className ? ' ' + className : '')}
      disabled={disabled}
      onPointerDown={start}
      onPointerUp={stop}
      onPointerLeave={stop}
      onPointerCancel={stop}
    >
      <span className="hold-fill" ref={fill} />
      <span className="hold-label">
        <Иконка icon={timeOutline} />
        {label}
      </span>
    </button>
  );

  /* Подпись — СНАРУЖИ кнопки, поэтому обёртка. Внутри она конкурировала с названием действия, а
     ещё её перекрывала полоса заполнения — то есть исчезала ровно в тот момент, когда объясняет. */
  const срок = подсказка ?? срокСловами(держать);
  if (!срок) return кнопка;
  return (
    <span className="hold-wrap">
      {кнопка}
      <span className="hold-hint">{срок}</span>
    </span>
  );
}
