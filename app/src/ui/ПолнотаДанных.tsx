import { IonSpinner } from '@ionic/react';
import Иконка from '@/ui/Иконка';
import { warning, alertCircle } from 'ionicons/icons';
import { useBackfilling } from '@/sources/backfill';
import { useHistory } from '@/sources/db';
import { useAnalysis } from '@/domain/useAnalysis';
import { причинаНеготовности } from '@/показ/находки';
import { дней } from '@/domain/периоды';

/* НАСКОЛЬКО ПОЛНЫ ДАННЫЕ ПОД ЧИСЛАМИ — ОДНИ СЛОВА НА ВЕСЬ РАЗДЕЛ (SugarLife#737).

   Владелец: «неполноту тоже выравнивай». Выравнивать оказалось не три формулировки одного,
   а два РАЗНЫХ факта, каждый из которых знала только одна вкладка:

   • «мы ещё дочитываем историю» — временное, наша вина, само пройдёт. Об этом говорили
     «Метрики» и молчали остальные;
   • «в данных дыры / дней мало / еда не записана» — свойство самих данных, само не пройдёт.
     Об этом говорил «Анализ» и молчали остальные.

   Беда была не в разных словах, а в том, что каждая вкладка признавалась в своей половине.
   В одну и ту же минуту «Метрики» честно писали «данные ещё пополняются», а «Анализ» рядом
   показывал находки по той же недочитанной истории — молча, и «Отчёт» готовил по ней справку
   врачу. Молчание тут хуже разноголосицы: разноголосицу человек хотя бы заметит.

   ПОРЯДОК: сначала догрузка, потом качество. «Дыр много» при недочитанной истории — это
   ещё не про данные, это про нас; сказать о качестве первым значило бы обвинить сенсор в
   том, что не дочитали мы.

   ЧЕГО ЗДЕСЬ НЕТ. Пометок «мало данных» у отдельных строк «Отчёта» — они точнее нашего:
   «Базал посчитан по 9 из 14 дней» называет, какая именно цифра тонкая, а не красит весь
   экран. Сводить лучшее к общему — не унификация, а потеря. */

export default function ПолнотаДанных({ дни, сОговорками = true }: {
  дни: number;
  /* Показывать ли качество данных. «Отчёту» — нет: у него свои пометки у каждой строки,
     и общая плашка сверху спорила бы с ними, а не дополняла. */
  сОговорками?: boolean;
}) {
  const догружаем = useBackfilling();
  /* Чтение бесплатное: срез общий и уже прочитан соседями (sources/db.ts, #736). До той
     правки такой вопрос стоил бы полного чтения базы и здесь его задавать было нельзя. */
  const { entries } = useHistory(дни * 86400e3, { minRefreshMs: 3600e3 });
  const { analysis } = useAnalysis(дни);

  /* Запас в двое суток: у самого края окна история всегда чуть не дотягивает, и без запаса
     строка горела бы всегда — то есть перестала бы читаться. */
  const самоеСтарое = entries[0]?.t;
  const собираем = догружаем && (самоеСтарое == null || самоеСтарое > Date.now() - дни * 86400e3 + 2 * 86400e3);

  const r = analysis.readiness;
  const вид = !сОговорками || r.level === 'ready' ? null
    : r.level === 'partial'
      ? { icon: warning, color: 'var(--c-carb)', слово: 'с оговорками' }
      : { icon: alertCircle, color: 'var(--c-danger)', слово: 'данных мало' };

  if (!собираем && !вид) return null;

  return (
    <>
      {собираем && (
        <div className="gather-note">
          <IonSpinner name="crescent" />
          <span>Собираем историю за {дни} {дней(дни)} — данные ещё пополняются, показано не за весь период.</span>
        </div>
      )}
      {вид && (
        <div className="metric-note" style={{ marginTop: 8 }}>
          <span style={{ color: вид.color }}>
            <Иконка icon={вид.icon} style={{ fontSize: 11, verticalAlign: '-1px', marginRight: 3 }} />
            {вид.слово}
          </span>
          {/* Причины остаются строкой, а не карточкой: «нет учёта углеводов» — это то, что
              человек может починить, и выбрасывать его вместе с плашкой нельзя. Коды
              называет слой показа (показ/находки.ts), а не мы здесь. */}
          {r.reasons.length > 0 && <> · {r.reasons.map(причинаНеготовности).join(' · ')}</>}
        </div>
      )}
    </>
  );
}
