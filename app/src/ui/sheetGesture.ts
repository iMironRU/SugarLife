/* Правила смахивания шторки вниз — отдельно от подключения, как и у жеста «назад».

   Само перетаскивание проверяется только пальцем: оно идёт через кадры, а в скрытой
   вкладке кадров нет. Но решения — арифметика, и оставлять её непроверенной незачем:
   в порогах живут «закрылась от случайного касания» и «тянул, а она вернулась».

   ПОЧЕМУ НЕ ШТАТНЫМ СПОСОБОМ IONIC. Смахивание там включается вместе с breakpoints, а
   breakpoints забирают вертикальный жест себе целиком: содержимое перестаёт
   прокручиваться — мы это уже проходили на шторке еды и потому запретили их тестом
   (SugarLife#161). Тем более сейчас: тело шторки прокручиваем мы сами, и Ionic про
   этот скроллер ничего не знает — он тянул бы шторку вместо прокрутки.

   Поэтому жест наш, и главное в нём — кто владеет движением вниз. На шапке всегда
   шторка: шапка вне прокрутки, спорить не с чем. В теле — по положению прокрутки:
   список прокручен, палец ведёт вниз — человек возвращается к началу списка, а не
   закрывает шторку; дотянул до верха и ведёт дальше — вот теперь «закрыть».
   Обратный порядок («тело тянет шторку всегда») мы уже видели у breakpoints: до
   нижних кнопок было не добраться. */

/** Сколько пройти пальцем, прежде чем решать, чьё это движение (px). Меньше — и
    шторку дёргает от случайного касания при листании. */
export const ПОРОГ_СТАРТА = 10;
/** Окно измерения скорости (мс). События касания приходят пачками с шагом в доли
    миллисекунды, и на таком шаге скорость не значит ничего. */
export const ОКНО_СКОРОСТИ = 8;
/** Доля высоты шторки, после которой отпускание закрывает. */
export const ПОРОГ_ДОЛЯ = 0.3;
/** Скорость, при которой закрываем даже с короткого движения (px/мс). */
export const ПОРОГ_СКОРОСТИ = 0.4;

/* Закрывать или вернуть на место. Два условия, а не одно: медленно, но далеко — это
   осознанное «закрыть»; быстро, но коротко — привычный флик, и он тоже «закрыть».
   С одним условием половина жестов ощущалась бы сломанной. */
export function закрыватьЛи(dy: number, height: number, velocityY: number): boolean {
  if (dy <= 0) return false; // вверх шторку не закрывают
  return dy > Math.max(1, height) * ПОРОГ_ДОЛЯ || velocityY > ПОРОГ_СКОРОСТИ;
}

/* Насколько сдвинуть шторку за пальцем. Вверх — не пускаем вовсе: тянуть выше своего
   места ей некуда, а резинка там читалась бы как «сейчас развернётся на весь экран»,
   чего мы не умеем. */
export function сдвиг(dy: number): number {
  return Math.max(0, dy);
}

/* Владеет ли движением шторка. Отдельной функцией, потому что это и есть спорное
   место: одно неверное «да» — и содержимое перестаёт листаться, одно неверное «нет» —
   и шторку нельзя смахнуть.

   Проверяем на каждом кадре, а не только в начале: палец может дотянуть список до
   верха и продолжить вниз одним движением — тогда шторка подхватывает его дальше. */
export function тянемШторку(вШапке: boolean, scrollTop: number): boolean {
  return вШапке || scrollTop <= 0;
}

/* Начинать ли перетаскивание вообще. Отдельно от тянемШторку, потому что вопрос
   другой: там — кому принадлежит движение, здесь — куда оно направлено.

   Жест только вниз. Без этого он захватывал и движение вверх: палец ведёт вверх у
   верхней границы списка, жест начинается (тело-то в нуле), шторка стоит на месте — а
   прокрутка уже отдана жесту. Со стороны это выглядит как «полоса прокрутки появилась,
   а содержимое не едет; дёрнешь второй раз — поехало». */
export function начинатьЛи(вШапке: boolean, scrollTop: number, dy: number): boolean {
  return dy > 0 && тянемШторку(вШапке, scrollTop);
}
