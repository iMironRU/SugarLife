import { IonIcon } from '@ionic/react';
import { chevronBack } from 'ionicons/icons';
import type { ReactNode } from 'react';

/* Заголовок страницы стека — один на все разделы.

   Был разнобой: в «Сервисах» и «Устройствах» слева стрелка «назад», в карточках
   устройства, облака и базального профиля справа крестик. Одно и то же действие
   выглядело двумя разными, и по виду кнопки нельзя было понять, вернёшься ты на шаг
   назад или закроешь всё.

   Теперь везде стрелка слева: это шаг назад по стеку, а не закрытие поверх лежащего
   окна. Отдельным компонентом — чтобы разнобой не завёлся снова при следующем
   добавленном разделе. */
export default function PageHead({ title, subtitle, onBack, действие }: {
  title: string;
  /* Не только строка: в подзаголовке живёт то, что уточняет весь раздел, и иногда это
     уточнение цветное — например, качество данных в разборе (#197).

     Роль у него ровно одна — уточнить ЗАГОЛОВОК, когда одного имени мало («Шаг 1 из 4»,
     «вход в облако»). «Что это» ушло в описание под шапкой, «что сейчас» — в тело.
     Раньше все смыслы делили одну строку, и раздел получал случайно доставшийся (#311).

     Пути здесь нет намеренно. Крошку пробовали — она висела над заголовком ничьей
     строкой: отвечала на вопрос, который человек уже решил, нажав на строку в списке, а
     места занимала как настоящее содержимое. Вернуть её просто, но только если найдётся
     случай, где человек ДЕЙСТВИТЕЛЬНО не понимает, где он. */
  subtitle?: ReactNode;
  onBack: () => void;
  /* Действие справа — «Далее» у мастера (SugarLife#259).

     Симметрия здесь не украшение: слева шаг назад, справа шаг вперёд, и оба на одной
     высоте. Раньше «Далее» жило в закреплённом низу вместе с «Назад», и низ съедал
     полосу экрана на каждом шаге ради двух кнопок — при том что содержимого на шаге
     часто было в половину экрана.

     Главное действие раздела (применить, перенести в помпу) сюда не ставится: оно
     весомее навигации, требует удержания и должно быть там, где человек читает
     последствия, — то есть в теле последнего шага. */
  действие?: ReactNode;
}) {
  return (
    <div className="sheet-head">
      <button className="sheet-close" onClick={onBack} aria-label="Назад"><IonIcon icon={chevronBack} /></button>
      <div style={{ flex: 1, minWidth: 0 }}>
        <div className="sheet-title">{title}</div>
        {subtitle && <div className="sheet-subtitle">{subtitle}</div>}
      </div>
      {действие}
    </div>
  );
}
