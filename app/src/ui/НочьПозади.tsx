import { useSnapshot } from '@/sources/bridge';
import { ночьПозади } from '@/показ/ночьПозади';
import { часы } from '@/слова/время';

/* ЧТО БЫЛО НОЧЬЮ — ПЕРВЫМ, ЧТО ВИДНО В ИСТОРИИ (#597).

   Остальное в истории человек помнит сам и приходит уточнить. Про ночь он не помнит ничего: он
   спал. Была ли тревога, услышал ли, ответил ли — до сегодня это знал только разработчик.

   Берём эпизоды у ядра (мост 1.59). Вчерашняя сборка из журнала — сшивание «началась» с «ответил»
   по идентификатору — снята: у них есть `asleep` и `unwoken`, которых у нас быть не могло.

   МОЛЧАНИЕ ТОЖЕ ОТВЕТ. «Ночь прошла спокойно» говорим, только когда эпизоды у нас ЕСТЬ и среди них
   нет ночных. Нет самих эпизодов — молчим: сказать «тревог не было», когда мы не знаем, значит
   дать человеку лечь спать с ложной уверенностью. */
export default function НочьПозади() {
  const снимок = useSnapshot();
  const ночь = ночьПозади(снимок?.alarmEpisodes, Date.now(), снимок?.sleep);

  if (ночь.спокойно) {
    return (
      <div className="ночь">
        <div className="ночь-глава">Ночь</div>
        <div className="ночь-тихо">Ночь прошла спокойно — ни одной тревоги.</div>
      </div>
    );
  }
  if (!ночь.строки.length) return null;

  return (
    <div className="ночь">
      <div className="ночь-глава">Ночь</div>
      {ночь.строки.map((с) => (
        <div key={с.когдаМс} className={'ночь-строка' + (с.неДобудились ? ' без-ответа' : '')}>
          <b>{часы(с.когдаМс)}</b>
          <span>{с.что}</span>
          {/* «Не добудились» — не упрёк, а факт, который человек узнаёт только отсюда: его звали,
              он спал и не услышал. Отличается от «не ответил»: днём смахнуть — его право. */}
          <i>{с.неДобудились ? 'не добудились'
            : с.ответЧерезС === null ? 'без ответа'
              : с.ответЧерезС < 90 ? `ответили через ${с.ответЧерезС} с`
                : `ответили через ${Math.round(с.ответЧерезС / 60)} мин`}</i>
        </div>
      ))}
    </div>
  );
}
