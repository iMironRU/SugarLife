import { useEffect, useState } from 'react';
import { запросЖурнала, useSnapshot } from '@/sources/bridge';
import { ночьПозади, границыНочи, type НочьПозади as Ночь } from '@/показ/ночьПозади';
import { часы } from '@/слова/время';

/* ЧТО БЫЛО НОЧЬЮ — ПЕРВЫМ, ЧТО ВИДНО В ИСТОРИИ (#597).

   Остальное в истории человек помнит сам и приходит уточнить. Про ночь он не помнит ничего: он
   спал. Была ли тревога, услышал ли он её, ответил ли — до сегодня это знал только разработчик,
   читающий журнал движка.

   МОЛЧАНИЕ ТОЖЕ ОТВЕТ. «Ночь прошла спокойно» говорим только когда журнал за эту ночь есть: пустой
   журнал означает, что мы не работали, и это ПРОТИВОПОЛОЖНЫЙ ответ. Спутать их — дать человеку
   лечь спать с уверенностью, что его разбудят.

   Ничего не показываем, пока не знаем: пустое место честнее догадки. */
export default function НочьПозади() {
  const [ночь, setНочь] = useState<Ночь | null>(null);
  /* Окно сна — от движка. Первое место, где мы вообще читаем `sleep`: до сих пор поле было описано
     в зеркале и не использовалось ни разу. */
  const окно = useSnapshot()?.sleep ?? null;

  useEffect(() => {
    let жив = true;
    void (async () => {
      const { от } = границыНочи(Date.now(), окно);
      const ответ = await запросЖурнала({ sinceMs: от, limit: 4000 });
      if (жив && ответ) setНочь(ночьПозади(ответ.records, Date.now(), окно));
    })();
    return () => { жив = false; };
  }, [окно?.from, окно?.to]);

  if (!ночь) return null;
  if (ночь.спокойно) {
    return (
      <div className="ночь">
        <div className="ночь-глава">Ночь</div>
        <div className="ночь-тихо">Ночь прошла спокойно — ни одной тревоги.</div>
      </div>
    );
  }
  if (!ночь.строки.length) return null;

  return (
    <div className="ночь">
      <div className="ночь-глава">Ночь</div>
      {ночь.строки.map((с) => (
        <div key={с.когдаМс} className={'ночь-строка' + (с.ответЧерезС === null ? ' без-ответа' : '')}>
          <b>{часы(с.когдаМс)}</b>
          <span>{с.что}</span>
          {/* «Не ответили» — не упрёк, а факт, который человек узнаёт только отсюда. Он спал. */}
          <i>{с.ответЧерезС === null ? 'без ответа'
            : с.ответЧерезС < 90 ? `ответили через ${с.ответЧерезС} с`
              : `ответили через ${Math.round(с.ответЧерезС / 60)} мин`}</i>
        </div>
      ))}
    </div>
  );
}
