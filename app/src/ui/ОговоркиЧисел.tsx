import { useSnapshot } from '@/sources/bridge';
import { ПодробнееПоТеме } from '@/ui/Подробнее';
import { предупредитьОСыром, сыроеНавсегда, ПОЯСНЕНИЕ_СЫРОГО } from '@/domain/сырое';

/* ЧТО НЕ ТАК С ЧИСЛАМИ НАД НАМИ — СЛОВАМИ, А НЕ ЗНАКОМ (SugarLife#702).

   Владелец: «В кружочке около „инс." и значения было `*` типа сноски — это что такое было?»
   Вопрос сам по себе и есть диагноз: знак на экране, о значении которого спрашивают у
   разработчика.

   Слова у нас БЫЛИ. Движок присылает их в `monitor.iobIncomplete`, и контракт говорит прямо:
   «показывать надо строкой рядом с числом, и словами движка». Мы клали их в `title` —
   подсказку при наведении мышью, которой НА ТЕЛЕФОНЕ НЕ СУЩЕСТВУЕТ. Оставалась голая
   звёздочка: знак, который обещает сноску и не даёт её.

   То же и с пометкой «сырое»: её пояснение жило там же и так же не показывалось.

   ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ КАЗАЛОСЬ УТРОМ. Сегодня выяснилось, что пометка «сырое» — последняя
   линия обороны: когда калибратор час отдавал число с поправкой девятилетней свежести, именно
   снятая пометка сделала ошибку опасной (#750). Сырьё «21,5» человек за истину не примет, а
   посчитанное «19,3» примет. Значит объяснение этой пометки обязано быть доступно — а на
   телефоне оно было недоступно физически.

   ЗДЕСЬ, А НЕ В КРУГЕ. В круге места нет: там уже число, единицы, стрелка, активный инсулин и
   возраст. Мы туда однажды пробовали вклиниться — вышел `ЗастойВОблаке`, который в итоге встал
   ровно сюда же, подписью под числами. Подпись их не разрывает: она к ним и относится.

   ЗНАК ОСТАВЛЯЕМ. Теперь он не обещает сноску, которой нет, — сноска прямо под ним. Он
   указывает, какое именно из двух чисел неполное, а этого слова внизу не говорят. */

export default function ОговоркиЧисел() {
  const снимок = useSnapshot();
  const неполный = снимок?.monitor?.iobIncomplete?.trim() || null;
  const сырое = предупредитьОСыром(снимок);
  if (!неполный && !сырое) return null;

  return (
    <>
      {неполный && (
        <div className="оговорка-числа">
          {/* Слова движка дословно: он один знает, чего именно не хватает, и своей
              формулировки у нас быть не может — расчёта мы не видели. */}
          {неполный}{' '}<ПодробнееПоТеме тема="insulinActive" />
        </div>
      )}
      {сырое && (
        <div className="оговорка-числа">
          {ПОЯСНЕНИЕ_СЫРОГО}
          {/* «Подожди, прогревается» и «у этого прибора алгоритма нет» — разные советы, и
              булево их уравнивало. Второй случай стоит назвать: ждать там нечего. */}
          {сыроеНавсегда(снимок) && ' Этот прибор калиброванного числа не даёт вовсе.'}
          {' '}<ПодробнееПоТеме тема="readiness" />
        </div>
      )}
    </>
  );
}
