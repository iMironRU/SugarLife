import { отложить } from '@/settings/snooze';

/* «Потом» у подсветки (SugarLife#147).

   Одна кнопка на все подсветки, потому что и правило одно. Восемь своих кнопок с
   восемью способами хранения разъехались бы через месяц — а разъехавшись, они
   разъедутся молча: не показавшееся предупреждение никто не замечает.

   Слово выбрано намеренно. Не «скрыть» и не «понятно»: скрыть значит «навсегда»
   (а мы вернёмся, когда станет хуже), понятно — это про чтение, а вопрос был про
   действие. «Потом» ровно и означает то, что происходит.

   Вид у неё тише соседних действий: «Поменял батарейку» — это ответ, который меняет
   данные, а «Потом» ничего не меняет и претендовать на то же внимание не должно. */
export default function SnoozeBtn({ ключ, эпизод, уровень }: {
  ключ: string; эпизод: string; уровень: number;
}) {
  return (
    <button className="snooze-btn" onClick={() => отложить(ключ, эпизод, уровень)}>
      Потом
    </button>
  );
}
