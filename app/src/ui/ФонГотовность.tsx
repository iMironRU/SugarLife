import { useEffect, useState } from 'react';
import { IonIcon } from '@ionic/react';
import { warningOutline, checkmarkCircle } from 'ionicons/icons';
import {
  фонГотовность, попроситьИсключение, type ФонОтвет,
  бодрствование, задатьБодрствование, бодрствованиеВозможно,
  ПОДПИСЬ_БОДРСТВОВАНИЯ, type Бодрствование, type РежимБодрствования,
} from '@/platform/фон';

/* «Телефон усыпит приложение в фоне» — строкой, а не диалогом (#380, ядро SugarLife#382).

   Главный случай тут — НЕ отказ человека. Он обратный: системное исключение выдано, а
   прошивка всё равно душит фон своей защитой. Ровно на таких телефонах мониторинг умирает
   ночью при всех зелёных галочках, и молчать про это вреднее всего.

   Почему строкой на экране готовности, а не всплывающей просьбой: диалог закрывают не
   читая, и второй раз он уже не появится. Строка ждёт, пока человек придёт разбираться,
   и в этот момент отвечает на его вопрос.

   Кнопка — только когда нам есть куда вести. Системный экран исключений открыть можем,
   вендорский «Запуск приложений» — нет, никаким API. */
export default function ФонГотовность({ спокойно }: {
  /* «Спокойно» — режим диагностики: туда приходят за ответом, и «всё в порядке» там
     уместно. На рабочих экранах зелёная галочка — шум (тот же уговор, что в Готовность). */
  спокойно?: boolean;
}) {
  const [ответ, setОтвет] = useState<ФонОтвет | null | 'ждём'>('ждём');
  const [открыли, setОткрыли] = useState(false);
  const [бодр, setБодр] = useState<Бодрствование | null>(null);

  useEffect(() => {
    void фонГотовность().then(setОтвет);
    void бодрствование().then(setБодр);
  }, []);

  /* АЙФОН ОТВЕЧАЕТ НА ТОТ ЖЕ ВОПРОС ИНАЧЕ (#388).

     Про оптимизацию батареи спрашивать бессмысленно — такого понятия там нет. Зато есть
     ровно та же беда с другой стороны: пока сенсор на связи, система будит нас его
     пакетами и всё хорошо само; а у человека на одном облаке будить нечем, и цифры
     замирают до следующего открытия приложения.

     Поэтому здесь, в том же месте, где Android объясняет про засыпание, айфон получает
     свой орган управления. Одно место на вопрос «переживёт ли мониторинг уход с экрана» —
     иначе человек будет искать ответ там, где его для его телефона нет. */
  if (бодрствованиеВозможно()) {
    if (!бодр) {
      if (!спокойно) return null;
      return <div className="sheet-note">Про фон сказать нечего: эта сборка старше выключателя.</div>;
    }
    const выбрать = (р: РежимБодрствования) => {
      setБодр({ ...бодр, режим: р });
      void задатьБодрствование(р);
    };
    const включено = бодр.режим !== 'выключено';
    if (!включено && !спокойно) {
      /* На рабочем экране молчим только пока всё очевидно. Выключенное бодрствование —
         не «всё в порядке», но и не беда: с прибором на связи оно и не нужно. Строку
         показываем в диагностике, где за ответом и приходят. */
      return null;
    }
    return (
      <div className="sheet-note">
        <div style={{ marginBottom: 8 }}>
          <b>Фон на айфоне.</b> Пока прибор на связи, система будит приложение его же
          показаниями. Если данные идут только из облака, будить нечем — приложение
          засыпает, и цифры замирают до следующего открытия. Тогда включите здесь.
        </div>
        {/* Выбор из трёх, а не три действия: поэтому чипы, как у окон графика, а не
            кнопки обращения. У кнопок обращения «главная» растягивается во всю ширину —
            здесь это назначило бы главным один из режимов, а главного тут нет. */}
        <div className="win-chips" style={{ marginTop: 4 }}>
          {бодр.режимы.map((р) => (
            <button key={р} className={'win-chip' + (бодр.режим === р ? ' on' : '')}
              onClick={() => выбрать(р)}>{ПОДПИСЬ_БОДРСТВОВАНИЯ[р]?.имя ?? р}</button>
          ))}
        </div>
        <div style={{ marginTop: 6 }}>{ПОДПИСЬ_БОДРСТВОВАНИЯ[бодр.режим]?.цена}</div>
      </div>
    );
  }

  if (ответ === 'ждём') return null;

  /* Спросить не у кого — браузер, iOS или сборка старше. В диагностике говорим об этом
     вслух: «не знаем» и «всё хорошо» — разные новости, и вторая тут была бы выдумкой. */
  if (!ответ) {
    if (!спокойно) return null;
    return <div className="sheet-note">Про фон сказать нечего: эту сборку не спросить — она старше этих методов, или это браузер.</div>;
  }

  if (!ответ.problem) {
    if (!спокойно) return null;
    return (
      <div className="sheet-note">
        <IonIcon icon={checkmarkCircle} style={{ marginRight: 6, verticalAlign: -2 }} />
        Фон: телефон приложение не усыпляет.
      </div>
    );
  }

  return (
    <div className="today-alert">
      <IonIcon icon={warningOutline} className="alert-ico" />
      <div>
        <span className="alert-title">{ответ.reason}</span>
        <span>{ответ.whatToDo}</span>
        {ответ.weCanOpenSettings && (
          <span className="alert-ask alert-ask-row">
            <button className="changed-btn is-undo" disabled={открыли}
              onClick={() => { setОткрыли(true); void попроситьИсключение().then((ок) => { if (!ок) setОткрыли(false); }); }}>
              {открыли ? 'Открываю…' : 'Открыть настройки'}
            </button>
          </span>
        )}
      </div>
    </div>
  );
}
