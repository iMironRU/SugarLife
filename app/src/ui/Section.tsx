import type { ReactNode } from 'react';
import PageHead from './PageHead';
import { useДочитано } from './useДочитано';

/* Оболочка раздела — единственное место, где страница стека становится страницей.

   Разделов одиннадцать, и собирали они себя тремя разными способами: девять через
   `.sheet stack-body` с PageHead, мастер петли со своей шапкой и без PageHead,
   BasalSteps вообще без `stack-body`. Плюс «назад» существовал в трёх видах: сверху,
   продублированный снизу, и нигде (SugarLife#162).

   Разнобой здесь дороже, чем кажется. `stack-body` несёт не только вид: в нём инерция
   прокрутки, отступ под панелью и пружина на iOS — то, что отличает нативное
   ощущение от «сайта в браузере». Раздел, собранный мимо него, ведёт себя иначе, и
   заметно это телом, а не глазом; в код за такой разницей никто не идёт.

   Здесь у раздела три места и ни одного свободного: шапка, прокручиваемое тело,
   закреплённый низ. Низ — не «ещё один слот», а отдельная роль: главное действие
   раздела не должно уезжать вместе с содержимым (правка базала, перенос в помпу).

   Шапка заменяемая (head) ровно для одного случая — мастера, у которого вместо
   заголовка шаги. Это содержимое заголовочной области, а не повод строить свою
   страницу: иначе следующий мастер построит четвёртую.

   ПРАВИЛО ПРО «НАЗАД», одно на все разделы. Выход — только стрелка слева вверху,
   которую ставит шапка. Внизу кнопки выхода нет ни у одного раздела: раньше её
   местами дублировали ради большого пальца, и одно действие оказывалось в двух
   местах — человек каждый раз ищет, где оно на ЭТОМ экране.

   Низ отдан действиям раздела: перенести профиль в помпу, отменить правку, шагнуть
   дальше в мастере. Слово «Назад» внизу есть ровно в одном месте — в мастере, — и
   значит там шаг назад, а не выход; на первом шаге оно и написано иначе: «Закрыть». */
export default function Section({ title, subtitle, onBack, действие, подШапкой, head, footer, className, children }: {
  title?: string;
  subtitle?: ReactNode;
  onBack: () => void;
  /** Действие справа в шапке — «Далее» у мастера (см. PageHead). */
  действие?: ReactNode;
  /* Полоса под заголовком — прогресс мастера. Она отвечает на тот же вопрос, что и
     заголовок («где я»), и потому обязана стоять там же и никуда не уезжать: полоса,
     видная только в начале прокрутки, показывает прогресс ровно тогда, когда он и так
     очевиден. */
  подШапкой?: ReactNode;
  /** Своя шапка вместо заголовка — для мастера с шагами. */
  head?: ReactNode;
  /** Закреплённый низ: главное действие раздела, которое не уезжает с прокруткой. */
  footer?: ReactNode;
  /** Дополнительный класс тела — для разделов со своей раскладкой внутри. */
  className?: string;
  children: ReactNode;
}) {
  /* Видно ли конец содержимого — тем же наблюдателем, что и «дочитайте до конца» в
     мастере: вопрос один и тот же, и считать его двумя способами незачем. */
  const { конец, вКонце } = useДочитано<HTMLDivElement>(null);

  return (
    <>
      {/* Шапка — отдельным этажом страницы, а не первой строкой прокрутки (#261).

          Раньше она уезжала вместе с содержимым, и в длинном разделе человек терял
          сразу две вещи: где он находится и как отсюда выйти. В мастере к этому
          добавилось «Далее» — за ним приходилось мотать наверх, хотя дочитал он как раз
          низ. Прокрутка нужна содержимому, а не навигации.

          Этажом, а не sticky: страница уже разложена колонкой (шапка · тело · низ), и
          третий этаж встаёт в ту же раскладку без вычисления, где кончается панель.
          Sticky пришлось бы привязывать к её высоте — то есть завести ещё одно место,
          которое надо не забыть поправить, когда панель изменится. */}
      <div className="stack-head">
        {head ?? (title ? <PageHead title={title} subtitle={subtitle} onBack={onBack} действие={действие} /> : null)}
        {подШапкой}
      </div>
      <div className={'sheet stack-body' + (className ? ' ' + className : '')}>
        {/* Внутренняя обёртка нужна ради одного: чтобы короткий раздел ВСЁ РАВНО был
            чуть выше экрана. iOS включает пружину только у прокручиваемого, и раздел
            из трёх строк не пружинил вовсе — палец тянет, а экран стоит, и это
            читается как «зависло» (#207).

            Отступы живут здесь же, а не на скроллере: min-height считается от
            содержимого родителя, и с отступами снаружи лишним оказался бы не пиксель,
            а все двадцать шесть. */}
        <div className="stack-fill">
          {children}
          {/* Метка конца списка: по ней же гаснет затемнение внизу. */}
          <div ref={конец} className="stack-end" />
        </div>
        {/* Затемнение у нижнего края — «здесь есть продолжение» без полосы прокрутки
            (#272).

            Гаснет, когда конец списка виден. Это не украшение и не оптимизация:
            градиент, висящий всегда, обещает продолжение и там, где его нет, — а
            обещание, которое человек проверил и не подтвердил, он перестаёт замечать
            и там, где оно правдиво.

            Событий не ловит (pointer-events: none): полоска у края экрана — как раз то
            место, куда попадает палец при прокрутке. */}
        <div className={'stack-fade' + (вКонце ? ' off' : '')} />
      </div>
      {footer}
    </>
  );
}
