import { IonIcon } from '@ionic/react';
import { water, nutrition, medkit } from 'ionicons/icons';

/* Три потока — глюкоза, углеводы, инсулин — в одном месте (замечание с телефона).

   Их набор повторяется по всему приложению: переключатель метрик, слоты источников,
   дальше будут отчёт и разбор. И повторялся по-разному: в «Метриках» — таблетки со
   значками в порядке глюкоза · углеводы · инсулин, в «Источниках» — подчёркнутые
   вкладки с точками в порядке сахар · инсулин · углеводы. Одно и то же, названное
   двумя словами и выстроенное двумя порядками.

   Разнобой тут не про красоту. Человек листает «Метрики», потом заходит в источники и
   ищет привычную третью позицию — а там другая. Секунда на пересчёт каждый раз, и она
   не окупается ничем.

   ПОРЯДОК КАНОНИЧЕСКИЙ: глюкоза первой, потому что с неё начинается любой вопрос;
   углеводы вторыми, потому что их вводят чаще инсулина; инсулин третьим.

   Слово «глюкоза», а не «сахар»: им же названы единицы в настройках, и в паре
   «Единицы глюкозы» / «Глюкоза» человек видит одно и то же понятие. В обычной речи
   приложения «сахар» остаётся — там, где фраза, а не ярлык. */

export type Поток = 'глюкоза' | 'углеводы' | 'инсулин';

export const ПОТОКИ: { ключ: Поток; имя: string; цвет: string; значок: string }[] = [
  { ключ: 'глюкоза', имя: 'Глюкоза', цвет: 'var(--c-glu)', значок: water },
  { ключ: 'углеводы', имя: 'Углеводы', цвет: 'var(--c-carb)', значок: nutrition },
  { ключ: 'инсулин', имя: 'Инсулин', цвет: 'var(--c-ins)', значок: medkit },
];

/** Состояние потока, если его есть чем показать: пусто / идёт обходным путём / всё хорошо. */
export type СостояниеПотока = 'пусто' | 'обход' | 'хорошо';

export default function ЧипыПотоков({ выбран, выбрать, состояние }: {
  выбран: Поток;
  выбрать: (п: Поток) => void;
  /* Точка у названия — то, что иначе теряется вместе с обзором: переключатель
     показывает один поток, а знать, что со вторым беда, надо не открывая его. */
  состояние?: Partial<Record<Поток, СостояниеПотока>>;
}) {
  return (
    <div className="metric-chips">
      {ПОТОКИ.map((п) => {
        const on = выбран === п.ключ;
        const с = состояние?.[п.ключ];
        return (
          <button key={п.ключ} className={'metric-chip' + (on ? ' on' : '')}
            onClick={() => выбрать(п.ключ)}
            style={on ? {
              borderColor: `color-mix(in srgb, ${п.цвет} 60%, transparent)`,
              background: `color-mix(in srgb, ${п.цвет} 20%, var(--color-neutral-900))`,
            } : undefined}>
            <IonIcon icon={п.значок} style={{ color: on ? п.цвет : 'var(--color-neutral-500)' }} />
            <span>{п.имя}</span>
            {с && <span className={'поток-точка ' + с} />}
          </button>
        );
      })}
    </div>
  );
}
