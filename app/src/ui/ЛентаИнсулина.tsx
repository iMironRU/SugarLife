import { useEffect, useState } from 'react';
import Иконка from '@/ui/Иконка';
import { waterOutline } from 'ionicons/icons';
import { часы, имяДня } from '@/слова/время';
import { лентаЧеловека } from '@/показ/лентаЧеловека';
import { изЛечения, лентаИстории, поДням, свернутьПовторы, этоИнсулин } from '@/domain/история';

/* ЧТО ВВОДИЛИ — НА ЭКРАНЕ «ИНСУЛИН», А НЕ В ОБЩЕЙ ИСТОРИИ (SugarLife#697).

   Решение владельца по итогам живого использования. Лента вводов лежала в «Истории»,
   вперемешку с едой и заменами, — то есть за ответом на «колол или нет» приходилось уходить
   с того самого экрана, который про подачу инсулина.

   ГРАФИК И ЛЕНТА НЕ СПОРЯТ, А ОТВЕЧАЮТ НА РАЗНОЕ. График сверху говорит, КАК ШЛО: базал
   ступенями, болюсы столбиками, час-два-шесть. Лента говорит, ЧТО ИМЕННО И КОГДА: «0,7 ед в
   22:08». По графику нельзя прочесть число, по ленте — форму. Поэтому обе, и в таком порядке.

   ОКНО СВОЁ И НАЗВАНО ВСЛУХ. Фишки часов над графиком его не трогают: они доходят до одного
   часа, и лента при них была бы почти всегда пустой. Двое суток — то же окно, в котором лента
   жила в «Истории»; менять заодно с переездом значило бы поменять две вещи и не понять, какая
   из них сработала.

   ПРО ПЕТЛЮ СКАЗАНО ПРЯМО, НО ТОЛЬКО ТАМ, ГДЕ ЕСТЬ ГРАФИК. Работу цикла (TempBasal) сюда не
   пускает движок: это не ввод человека. Рядом с графиком об этом надо сказать — временные
   базалы на нём ВИДНЫ, и молчание о разнице читалось бы как пропажа: «на картинке есть, в
   списке нет, значит список врёт».

   А у человека на шприц-ручке графика нет и цикла нет. Оговорка про «график выше» там
   указывает на пустое место, а про временные базалы — на то, чего у него не бывает. Проверка
   глазами это и поймала: текст был написан для помпы и показывался ручке. */

const ОКНО_МС = 48 * 3600e3;

export default function ЛентаИнсулина({ включена = true, сГрафиком = true }: {
  включена?: boolean;
  /** Есть ли выше график подачи. У шприц-ручки его нет — значит и ссылаться не на что. */
  сГрафиком?: boolean;
}) {
  const [точки, setТочки] = useState<{ atMs: number; kind: string; amount: number }[] | null>(null);

  /* Читаем, только когда вкладка на виду: все пять экранов смонтированы разом ради свайпа,
     и невидимому читать базу незачем — это и были рывки на соседних вкладках. */
  useEffect(() => {
    if (!включена) return;
    let жив = true;
    void лентаЧеловека(Date.now() - ОКНО_МС, Date.now())
      .then((т) => { if (жив) setТочки(т ?? []); });
    return () => { жив = false; };
  }, [включена]);

  /* Пока не прочитали — молчим. Пустая лента и непрочитанная выглядят одинаково, а значат
     разное: «вводов не было» и «мы ещё не знаем». Второе выдавать за первое нельзя. */
  if (!точки) return null;

  const события = свернутьПовторы(лентаИстории([изЛечения(точки.filter((т) => этоИнсулин(т.kind)))]));
  const дни = поДням(события);

  return (
    <>
      <div className="section-label sec">Что вводили · за двое суток</div>
      {дни.length === 0 ? (
        <div className="metric-note">
          За двое суток вводов не записано.{сГрафиком && ' Работу цикла — временные базалы — здесь'
            + ' не показываем: это подача автоматики, а не ваш ввод. На графике выше она есть.'}
        </div>
      ) : (
        <>
          {дни.map(({ день, события: сег }) => (
            <div key={день}>
              <div className="section-label sec">{имяДня(день, { заглавно: true })}</div>
              <div className="meal-log">
                {сег.map((с) => (
                  <div key={с.ключ} className="meal-row">
                    <div className="meal-when">
                      <b>{часы(с.когдаМс)}</b>
                      {/* Диапазон, а не время последнего повтора: «с 22:08 по 22:14» отвечает
                          «сколько раз подряд», а одно время делало бы вид, что ввод был один. */}
                      {с.доМс && <span>по {часы(с.доМс)}</span>}
                    </div>
                    <Иконка icon={waterOutline} className="list-ico" />
                    <div className="meal-what">
                      <b>{с.главное}{с.повторов ? ` · ${с.повторов} раз` : ''}</b>
                      {с.подпись && <span>{с.подпись}</span>}
                    </div>
                  </div>
                ))}
              </div>
            </div>
          ))}
          {сГрафиком && (
            <div className="metric-note">
              Временные базалы цикла сюда не идут — это подача автоматики, а не ваш ввод. На
              графике выше они есть.
            </div>
          )}
        </>
      )}
    </>
  );
}
