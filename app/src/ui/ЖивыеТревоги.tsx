import { useЖивыеТревоги, понял, type ЖиваяТревога } from '@/показ/живыеТревоги';
import HoldButton from '@/ui/HoldButton';
import { activeInsulin } from '@/domain/loopValue';
import { useЧужаяПетля } from '@/показ/чужаяПетля';
import { сколькоНазад } from '@/слова/время';
import { fmt } from '@/domain/units';

/* «ПОНЯЛ» — ТАМ, ГДЕ ЧЕЛОВЕК ОКАЗЫВАЕТСЯ (SugarLife#482, макет v2 — #500).

   Разбуженный сиреной открывает приложение — и первое, что он должен увидеть, это что случилось и
   кнопка, которая это выключает. Прятать ответ в системном уведомлении (потянуть баннер вниз, найти
   «Понял») — значит требовать точных движений от человека спросонья.

   ЧТО ИСПРАВЛЕНО МАКЕТОМ. Полоса была набрана как рядовое обращение: заголовок кеглем заметки, число
   строчкой под ним, «Понял» — маленькой кнопкой сбоку. Владелец прочитал это на телефоне и сказал
   прямо: мелко. Теперь по макету — число крупным, пара «возраст и инсулин» столбиком, а «Понял» —
   кнопка во всю ширину карточки: спросонья попадают в неё, а не в соседний элемент.

   ГОЛОСА ТРЕВОГИ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК. Справа стояла подпись уровня — «разбудит
   ночью», «звуком днём», «молча». Три беды в одной строке:

   · время не то. Тревога уже сработала, под ней написано «1 мин назад», — а подпись обещает будущее;
   · экран не тот. «Насколько громкое это правило» — вопрос раздела тревог, там его и задают;
   · и главное: разбудит ли нас ночью, считает движок (`nightPromise`) с оглядкой на разрешения,
     «Не беспокоить» и заряд, а «Охрана» отвечает на это осторожно. Полоса же обещала безусловно —
     то есть спорила с «Охраной» и ошибалась в сторону успокоения. Правило 9 в
     docs/поверхности-показа.md: сообщаем факт, а не намерение.

   Тяжесть видна цветом, знаком «!» и местом наверху — этого хватает.

   ЦВЕТ ПО ЗОНЕ, а не по факту тревоги: низкий сахар и высокий выглядят по-разному, потому что и
   решения после них разные. Прочие поводы (молчание прибора, резервуар) остаются нейтральными —
   красить их в тревожный цвет значило бы уравнять «сахар 3,1» и «данных нет». */

/** Зона по заголовку: сахарные тревоги красим, остальные — нет (см. шапку). */
function зона(т: ЖиваяТревога): 'низкий' | 'высокий' | null {
  if (т.заголовок === 'Низкий сахар' || т.заголовок === 'Сахар падает') return 'низкий';
  if (т.заголовок === 'Высокий сахар') return 'высокий';
  return null;
}

export default function ЖивыеТревоги() {
  const тревоги = useЖивыеТревоги();
  const петля = useЧужаяПетля();
  const инсулин = activeInsulin({ iob: петля.iob, loopAt: петля.loopAt } as never);

  if (!тревоги.length) return null;

  return (
    <>
      {тревоги.map((т) => {
        const з = зона(т);
        return (
          <div key={т.id} className={'тревога' + (з ? ' ' + з : '')}>
            <div className="тревога-шапка">
              <span className="тревога-знак">!</span>
              <span className="тревога-имя">{т.заголовок}</span>
            </div>

            <div className="тревога-число-ряд">
              {/* Крупно — только число, и только когда тревога про число. У «данных нет» числа нет,
                  и на его месте стоит пояснение обычным кеглем: иначе туда попадает первое слово
                  фразы и получается огромное «Приложение». */}
              {т.число
                ? <span className="тревога-число">{т.число}</span>
                : <span className="тревога-текст">{т.текст}</span>}
              <span className="тревога-мелочи">
                {т.когда > 0 && <span>{сколькоНазад(т.когда)}</span>}
                {инсулин.known && петля.iob != null && (
                  <span className="тревога-инсулин">инс. {fmt(петля.iob)} ед</span>
                )}
              </span>
            </div>

            {/* СЛОВА ДВИЖКА — ПОД ЧИСЛОМ, А НЕ ВМЕСТО НЕГО.

                Было «число ИЛИ слова»: когда тревога про число, фраза движка не показывалась вовсе.
                А она и есть самое полезное, что тревога может сказать, — что происходит и что делать,
                с поправкой на обстановку (дома надо съесть, за рулём сначала остановиться). Число же
                и так стоит в кружке над полосой; ради его повтора мы прятали единственное, чего в
                кружке нет.

                Когда числа нет, фраза занимает его место (выше) и здесь не повторяется. */}
            {т.число && т.текст && <div className="тревога-слова">{т.текст}</div>}

            {т.нуженОтвет && (
              /* «ПОНЯЛ» — УДЕРЖАНИЕМ, А НЕ КАСАНИЕМ (решение владельца).

                 Полоса стоит первой среди обращений, по ней проходит палец при прокрутке, и
                 случайное касание гасило бы тревогу молча. Цена промаха здесь — тишина вместо
                 предупреждения, поэтому кнопка требует подержать; полоса заполнения показывает,
                 сколько осталось, иначе человек решит, что кнопка сломана.

                 Держать меньше, чем у подачи инсулина: там ошибка означает «применил не то», здесь —
                 «случайно погасил», и секунда спросонья длиннее, чем кажется. Секунда против двух —
                 и обе теперь названы подписью под кнопкой (#570), а не намёком внутри неё.

                 Полоса уходит сразу, не дожидаясь снимка: движок держит тревогу активной, пока
                 держится причина, и ждать его значило бы оставить нажатую кнопку висеть. */
              <HoldButton label="Понял" className="тревога-понял" holdMs={1000}
                onComplete={() => понял(т.id)} />
            )}
          </div>
        );
      })}
    </>
  );
}
