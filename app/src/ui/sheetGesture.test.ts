import { describe, it, expect } from 'vitest';
import { закрыватьЛи, сдвиг, тянемШторку, начинатьЛи } from './sheetGesture';

/* Пороги смахивания под тестами по той же причине, что и у жеста «назад»: ошибка
   здесь не видна глазами, она выглядит как «шторка закрывается сама» или «её не
   смахнуть» — и то и другое человек спишет на приложение, а не на число. */

describe('смахивание шторки вниз', () => {
  const H = 600;

  it('короткое медленное движение шторку не закрывает', () => {
    expect(закрыватьЛи(40, H, 0.1)).toBe(false);
  });

  it('дотянул до трети высоты — закрываем', () => {
    expect(закрыватьЛи(H * 0.31, H, 0)).toBe(true);
  });

  /* Флик — привычный способ отмахнуться: короткое, но быстрое движение. Без него
     пришлось бы каждый раз тащить шторку через полэкрана. */
  it('короткий, но быстрый флик закрывает', () => {
    expect(закрыватьЛи(60, H, 0.5)).toBe(true);
  });

  it('движение вверх не закрывает', () => {
    expect(закрыватьЛи(-200, H, 2)).toBe(false);
  });

  it('нулевая высота не делит на ноль', () => {
    expect(закрыватьЛи(10, 0, 0)).toBe(true);
  });

  it('вверх шторка не уезжает', () => {
    expect(сдвиг(-120)).toBe(0);
    expect(сдвиг(75)).toBe(75);
  });

  /* Правило владения движением: у прокрученного списка вниз мотается содержимое, а
     не шторка. Проверяем именно здесь — глазами это ловится только на телефоне и
     выглядит как «список залип». */
  it('в шапке тянем шторку при любой прокрутке тела', () => {
    expect(тянемШторку(true, 400)).toBe(true);
  });

  it('прокрученное тело движение вниз отдаёт себе', () => {
    expect(тянемШторку(false, 120)).toBe(false);
  });

  it('тело в самом верху отдаёт движение шторке', () => {
    expect(тянемШторку(false, 0)).toBe(true);
  });

  /* Направление проверяем на старте: движение вверх — это прокрутка, и отбирать его
     нельзя даже когда список стоит в нуле. Именно так ломалась прокрутка: жест
     начинался, шторка не двигалась, содержимое тоже. */
  it('движение вверх жест не начинает', () => {
    expect(начинатьЛи(false, 0, -30)).toBe(false);
    expect(начинатьЛи(true, 0, -30)).toBe(false);
  });

  it('движение вниз из верха списка жест начинает', () => {
    expect(начинатьЛи(false, 0, 30)).toBe(true);
  });

  it('движение вниз по прокрученному телу жест не начинает', () => {
    expect(начинатьЛи(false, 200, 30)).toBe(false);
  });
});
