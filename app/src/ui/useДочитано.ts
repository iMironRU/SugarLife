import { useEffect, useRef, useState } from 'react';

/* Виден ли конец содержимого раздела — и был ли он виден хоть раз.

   Отвечает сразу на два вопроса, потому что вопрос физически один, а применений два:

   • `вКонце` — прямо сейчас. По нему гаснет затемнение у нижнего края (#272): оно
     обещает продолжение и на последнем экране висеть не должно;
   • `дочитано` — было ли доведено до конца хоть раз. По нему открывается «Далее» на
     шаге мастера, где нет настроек, только последствия (#261). Обратно не гаснет:
     человек, вернувшийся перечитать абзац, не должен обнаружить кнопку снова запертой.

   МЕРИМ ПРОКРУТКОЙ, А НЕ НАБЛЮДАТЕЛЕМ ПЕРЕСЕЧЕНИЙ. Наблюдатель выглядел изящнее и был
   выброшен по факту: он привязан к циклу отрисовки и в невидимой странице не
   срабатывает вовсе — ни разу, даже первым проходом. На устройстве он, возможно, и
   работал бы, но проверить его нечем, а «дочитано» молча оставалось бы ложным навсегда.

   Два случая, из-за которых арифметику прокрутки обычно ругают, здесь безопасны.
   Содержимое короче экрана: scrollHeight равен clientHeight, условие выполняется сразу
   — и это правильный ответ, читать нечего. Пружина на iOS: scrollTop уезжает за
   пределы, сумма только растёт, и конец остаётся концом.

   Порог в четыре пикселя — не суеверие: дробные высоты при масштабировании дают
   расхождение в доли пикселя, и точное равенство не наступает никогда. */
const ПОРОГ_ДНА = 4;

export function useДочитано<T extends HTMLElement>(ключ: unknown) {
  const конец = useRef<T | null>(null);
  const [вКонце, setВКонце] = useState(false);
  const [дочитано, setДочитано] = useState(false);

  useEffect(() => {
    setВКонце(false);
    setДочитано(false);
    const узел = конец.current;
    const скроллер = узел?.closest('.stack-body') as HTMLElement | null;
    if (!скроллер) return;

    const пересчитать = () => {
      const дно = скроллер.scrollTop + скроллер.clientHeight >= скроллер.scrollHeight - ПОРОГ_ДНА;
      setВКонце(дно);
      if (дно) setДочитано(true);   // только вверх: дочитанное дочитано до смены ключа
    };

    пересчитать();
    скроллер.addEventListener('scroll', пересчитать, { passive: true });
    /* Содержимое приезжает не сразу — список устройств, история, разбор. Пока его нет,
       конец «виден» просто потому, что показывать нечего; пересчитываем при изменении
       высоты, иначе затемнение не появится над уже приехавшим списком. */
    const наблюдатель = new ResizeObserver(пересчитать);
    наблюдатель.observe(скроллер);
    if (узел?.parentElement) наблюдатель.observe(узел.parentElement);

    return () => {
      скроллер.removeEventListener('scroll', пересчитать);
      наблюдатель.disconnect();
    };
  }, [ключ]);

  return { конец, вКонце, дочитано };
}
