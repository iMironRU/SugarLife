import { useEffect, useRef, useState } from 'react';

/* «Далее» открывается, когда дочитано до конца (SugarLife#261).

   Нужно не везде и включается поимённо. Экран, который человек просто листает, запирать
   нельзя: он быстро научится проматывать в конец не читая, и запрет перестанет значить
   что-либо вообще — как и любое препятствие, которое ставят на всё подряд.

   Где это оправдано: правила понижения полномочий в мастере петли. Там нет ни одной
   настройки, только последствия — что произойдёт, когда пропадут данные НМГ или
   разойдутся часы помпы. Человек, пролиставший их за секунду, узнает об этом в момент,
   когда оно случится.

   МЕРИМ ВИДИМОСТЬЮ КОНЦА, А НЕ ПОЛОЖЕНИЕМ ПРОКРУТКИ. Арифметика на scrollTop врёт в
   двух частых случаях: содержимое короче экрана (прокрутки нет вовсе — и «до конца» не
   наступит никогда) и пружина на iOS (scrollTop уезжает за пределы). Наблюдатель отвечает
   на тот же вопрос прямо: виден ли конец. Помещается всё на экран — значит уже дочитано,
   и запирать нечего.

   Сброс по ключу: на новом шаге мастера читать надо заново, а узел переиспользуется. */
export function useДочитано<T extends HTMLElement>(ключ: unknown) {
  const конец = useRef<T | null>(null);
  const [дочитано, setДочитано] = useState(false);

  useEffect(() => {
    setДочитано(false);
    const узел = конец.current;
    if (!узел) return;
    /* Корень — сам скроллер раздела: относительно окна конец «виден» и тогда, когда
       лежит под панелью или ниже экрана. */
    const корень = узел.closest('.stack-body');
    const наблюдатель = new IntersectionObserver(
      (записи) => { if (записи.some((з) => з.isIntersecting)) setДочитано(true); },
      { root: корень, threshold: 0.01 },
    );
    наблюдатель.observe(узел);
    return () => наблюдатель.disconnect();
  }, [ключ]);

  return { конец, дочитано };
}
