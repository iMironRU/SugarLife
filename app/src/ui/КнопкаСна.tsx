import { useSnapshot, sendIntent } from '@/sources/bridge';

/* «ЛЁГ СПАТЬ» И «ПРОСНУЛСЯ» (#597, ядро #115).

   Владелец сказал: «у нас может быть кнопка лёг спать. И проснулся» — и это меняет расстановку.
   Я строил лесенку от часов к окну и поставил кнопку сверху уточнением. Неверно: кнопка —
   ФУНДАМЕНТ.

   Она работает везде: телефон без сервисов Google, дешёвый Android, айфон без часов. Наблюдение из
   часов приезжает задним числом и есть не у всех; кнопка — это «сейчас», и она единственная
   отвечает на вопрос «спит ли он прямо сейчас», на который платформы не отвечают вовсе.

   ПОЧЕМУ «ПРОСНУЛСЯ» ВИДНА ВСЕГДА, ПОКА ВКЛЮЧЕНО. У движка ручной переключатель НЕ снимается сам:
   `вручнуюВключён` — значит спит, и точка. Забыл нажать утром — приложение весь день считает, что
   человек спит, и тревоги идут по-ночному: громко и мимо тихого режима.

   Ошибка в безопасную сторону, но невыносимая днём. Пока движок не снимает переключатель сам
   (спросили), выход один и он должен быть на виду — не за настройкой и не в меню.

   «ЛЁГ» ПОКАЗЫВАЕМ ТОЛЬКО КОГДА ПОРА. Момент называет движок (`checkDue`): за полчаса до окна сна,
   и не раньше. Кнопка, висящая весь день, — приглашение нажать её случайно. */
export default function КнопкаСна() {
  const сон = useSnapshot()?.sleep ?? null;
  if (!сон) return null;

  const вручную = сон.asleep && сон.source === 'manual';
  if (!вручную && !сон.checkDue) return null;

  const переключить = (на: boolean) => {
    void sendIntent({ type: 'setConfig', patch: { 'sleep.manual': на ? 'on' : null } });
  };

  return вручную ? (
    <button className="сон-кнопка проснулся" onClick={() => переключить(false)}>
      <span className="сон-главное">Проснулся</span>
      <span className="сон-подпись">пока не нажмёте, тревоги идут по-ночному</span>
    </button>
  ) : (
    <button className="сон-кнопка лёг" onClick={() => переключить(true)}>
      <span className="сон-главное">Лёг спать</span>
      <span className="сон-подпись">ночью тревоги громче и настойчивее</span>
    </button>
  );
}
