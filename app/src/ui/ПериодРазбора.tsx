import type { ReactNode } from 'react';
import { ПЕРИОДЫ_РАЗБОРА, дней } from '@/domain/периоды';

/* ШАПКА ПЕРИОДА — ОДНА НА ВСЕ ВКЛАДКИ (SugarLife#734).

   Владелец: «прыгает шапка». Прыгала — и не там, где я чинил в прошлый раз.

   Тогда (#690) я свёл СПИСОК периодов в одну константу и добавил обеим вкладкам одинаковую
   строку над переключателем — ровно чтобы он стоял на одной высоте. Разметка при этом
   осталась в двух файлах, и высота разъехалась заново: «Метрики» обернули свой ряд в липкую
   коробку с `padding: 6px 20px 10px`, а «Анализ» — нет. Двадцать пикселей разницы, и один и
   тот же орган управления стоит на разных местах.

   Урок тот же, что со сторожем анимаций днём раньше: свести значения мало, если разметка
   осталась в двух руках. Одинаковость, которую приходится поддерживать вниманием, — это
   не одинаковость, а обещание её.

   Поэтому здесь и коробка, и строка, и ряд — одним куском. Разъехаться теперь нечему:
   вкладка получает `children` для того, что у неё СВОЁ (у «Метрик» — чипы потоков), а
   общее не решает.

   ЛИПКОСТЬ ПАРАМЕТРОМ, А НЕ ВСЕГДА. Внутри экрана «Метрики» ряд обязан липнуть под
   панелью: на девяноста днях он уезжает вверх, и чтобы сменить период, надо прокрутить
   обратно. А тот же раздел, открытый отдельной страницей (`разделы.tsx`, «разбор»),
   липнуть не должен: там над ним нет панели, к нижней кромке которой прилипать. */

export default function ПериодРазбора({ слово, дни, выбрать, липкий = true, children }: {
  /** Первое слово строки: «Разбор» или «Метрики». Дальше — «за N дней» одинаково. */
  слово: string;
  дни: number;
  выбрать: (д: number) => void;
  липкий?: boolean;
  /** Что вкладка добавляет от себя, под рядом периодов и внутри той же коробки. */
  children?: ReactNode;
}) {
  const тело = (
    <>
      {/* Слово живёт здесь, а не на кнопках: пять кнопок словами в строку не влезают,
          а «3 дн.» против «3 дня» на соседних вкладках человек читает как разные вещи. */}
      <div className="metric-note" style={{ marginTop: 2 }}>{слово} за {дни} {дней(дни)}</div>
      <div className="period">
        {ПЕРИОДЫ_РАЗБОРА.map((д) => (
          <button key={д} className={'period-seg' + (дни === д ? ' on' : '')} onClick={() => выбрать(д)}>{д}</button>
        ))}
      </div>
      {children}
    </>
  );
  return липкий ? <div className="metrics-sticky">{тело}</div> : <>{тело}</>;
}
