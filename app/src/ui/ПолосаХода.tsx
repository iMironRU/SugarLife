/* ПОЛОСА ДОБОРА — ТАМ, ГДЕ РАБОТА ДЛИТСЯ МИНУТЫ (SugarLife#745, ядро #86 и #192 п. 7).

   Слова про ход у нас были с моста 1.22: «Подбираю частоту помпы…», «История сенсора: 40 %».
   Доля тоже была объявлена — с 1.26, — и всё это время приходила пустой: движок терял её при
   перекладывании карточки прибора в железо. Тип собирался, тесты были зелёными, умолчание
   `null`. Мы честно сообщили ядру, что поля не читаем; читать было нечего.

   ЗАЧЕМ ПОЛОСА, ЕСЛИ СЛОВА ЕСТЬ. Добор истории сенсора длится минуты. Слова говорят, ЧТО идёт,
   и не говорят, ДВИЖЕТСЯ ЛИ: «История сенсора: 40 %» через минуту выглядит точно так же, как
   «История сенсора: 40 %» пять минут назад. Полоса отвечает на второй вопрос одним взглядом —
   и это ровно та беда, которую мы неделю чинили под именем «догоняю».

   БЕЗ ДОЛИ ПОЛОСЫ НЕТ. У подбора частоты помпы доля неизвестна: список частот, и заранее не
   сказать, на какой попытке отзовётся прибор. Полоса, ползущая в никуда, врёт хуже, чем честные
   слова, — а к концу работы ещё и прыгает с середины в сто. */
export default function ПолосаХода({ доля }: { доля: number | null }) {
  if (доля == null) return null;
  return (
    <div className="ход-полоса" role="progressbar"
      aria-valuenow={доля} aria-valuemin={0} aria-valuemax={100}>
      <i style={{ width: `${доля}%` }} />
    </div>
  );
}
