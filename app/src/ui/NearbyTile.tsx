import Иконка from './Иконка';
import { сколькоНазад } from '@/слова/время';
import { bluetoothOutline, chevronForward } from 'ionicons/icons';
import { useSnapshot } from '@/sources/bridge';
import Notice from './Notice';
import { движокЖивой } from '@/domain/deviceState';
import { железоДиспетчера, потерянаСвязь, имяЖелезки } from '@/domain/nearby';
import { однаПравда, разборОбрыва } from '@/domain/однаПравда';
import { названиеКанала, словоОбрыва, подписьЗанятия } from '@/слова/приборы';

import { useStack } from '@/app/stackCtx';
import { DataDevicesSection } from '@/sections/lazy';

/* Вход в «устройства рядом» с главного экрана.

   Плитка не должна кричать. «Посмотри, что рядом» полезно ровно в двух случаях: когда
   подключать ещё нечего и когда связь отвалилась. Когда всё работает, постоянное
   напоминание про скан — шум на экране, к которому человек привыкает и перестаёт
   замечать; а замечать он должен именно тогда, когда что-то сломалось.

   Поэтому два вида: заметная карточка при проблеме и тихая строка в остальное время.

   В браузере не показываем вовсе. BLE там нет как класса, и вход в поиск, который
   ничего не найдёт никогда, — обещание, которого мы не выполним. Признак живого
   движка — наличие драйверов в снимке: Nightscout-шим их не отдаёт. */
export default function NearbyTile() {
  const snap = useSnapshot();
  const { push, pop } = useStack();

  /* Признак — драйвер ЖЕЛЕЗА, а не «хоть какой-нибудь драйвер» (#256): Nightscout-шим
     завёл свой, сервисный, и карточка «Подключить устройство» полезла в браузер, где
     эфира нет как класса. Правило одно на всех — domain/deviceState.ts. */
  if (!движокЖивой(snap)) return null;

  /* Железо и его состояние — из тех же мест, что у диспетчера, и по тому же правилу
     (#224). Плитка считала «на связи» сама: смотрела на connection и пропускала status.
     А connection — это сокет, status — жизненный цикл данных: устройство бывает
     Connected и при этом Disconnected по смыслу. Отсюда и получалось, что плитка
     писала «на связи 2 устройства», а раздел устройств и приложение ядра — что связи
     нет. Одно приложение не может отвечать на один вопрос двумя способами.

     Правило теперь одно на всех: domain/deviceState.ts. */
  const железо = железоДиспетчера(snap);
  /* Одна правда на прибор — правило в domain/однаПравда, чтобы плитка и раздел приборов
     не разошлись в словах. */
  const правда = однаПравда(snap, Date.now());
  /* Тревога — не «что-то отвалилось», а «данные не идут»: правило и разбор в
     domain/nearby.ts (#247). Раньше здесь стояло «отвалилась хоть одна железка», и
     карточка «Связь с устройством потеряна» висела ровно над лентой, где обе железки
     только что отчитались «на связи». */
  const потеряно = потерянаСвязь(snap);
  const проблема = железо.length === 0 || потеряно.length > 0;
  /* Куда вести, зависит от того, есть ли уже своё железо.

     Нечего подключать — веди в поиск: там ищут незнакомое. А если железка заведена и
     отвалилась, поиск бесполезен и даже вреден: своё в нём не показывается вовсе
     (SugarLifeCore#34), и человек решит, что устройство пропало. Ему нужен диспетчер —
     список своего с состоянием и «подключить». Он живёт в «Устройствах».

     Ведём на вкладку «Откуда данные», а не в список приборов: человек нажимает эту
     кнопку с вопросом «почему нет данных», и там написана причина (#279).

     Отдельного экрана поиска больше нет (#337): «Приборы» и есть эфир — там и своё, и
     новое в одной ленте. Второй экран показывал только незнакомых, и своё устройство в
     нём не находилось ровно тогда, когда его искали. */
  const открыть = () => {
    const вкладка = железо.length === 0 ? 'приборы' : 'данные';
    push(<DataDevicesSection onClose={pop} вкладка={вкладка} />, { id: 'приборы', вкладка });
  };

  /* СТРОКА НА ПРИБОР, а не одно слово на всех (SugarLifeCore#39).

     Было: «На связи Sibionics GS1 · посмотреть, что рядом». Голое «на связи» — ровно та
     половина ответа, из-за которой человек идёт чинить исправное: прибор может быть «на
     связи» через Nightscout, пока радио молчит.

     Теперь каждая строка отвечает на три вопроса сразу — подключено ли, откуда цифры,
     когда последние, — и «на связи» без «через что» на первом экране не существует. */
  if (!проблема) {
    return (
      <button className="nearby-quiet nearby-строки" onClick={открыть}>
        <span className="nearby-список">
          {правда.map((с) => (
            <span key={с.id} className="nearby-строка">
              <i className={'поток-точка ' + (с.состояние === 'подключено' ? 'хорошо' : с.откуда ? 'обход' : 'пусто')} />
              <b>{с.имя}</b>
              <span>{подписьЗанятия(с.вместоСостояния) ?? [
                с.состояние,
                названиеКанала(с.откуда),
                с.когдаМс ? сколькоНазад(с.когдаМс) : null,
              ].filter(Boolean).join(' · ')}</span>
            </span>
          ))}
        </span>
        <Иконка icon={chevronForward} className="nearby-chev" />
      </button>
    );
  }

  /* Тревожное состояние — обычное обращение, тем же элементом, что и остальные (#225).
     Своя вёрстка была ровно тем, из-за чего плитка обзавелась и собственным правилом
     связи, и собственным размером кнопок (#230). Вид — «предложение»: человеку есть
     что сделать прямо сейчас, и действие одно. */
  return (
    <Notice вид="предложение" значок={bluetoothOutline}
      /* Имя обязательно. Безымянное «связь потеряна» человек не может ни проверить, ни
         опровергнуть: у него на экране два устройства, и какое из них молчит —
         единственное, что ему нужно знать, чтобы пойти и починить. */
      /* Заголовок называет КАНАЛ, а не факт обрыва (SugarLifeCore#39). «Связь потеряна»
         рядом со строкой «на связи» — два ответа на один вопрос; правильный один: что
         именно оборвалось и чем это компенсировано. Радио молчит, а цифры идут облаком —
         это состояние, а не тревога. */
      заголовок={железо.length === 0 ? 'Подключить устройство'
        : словоОбрыва(разборОбрыва(правда))
        ?? (потеряно.length === 1 ? `«${имяЖелезки(потеряно[0])}» не на связи`
        : `Не на связи: ${потеряно.map(имяЖелезки).join(', ')}`)}
      действия={(
        <button className="changed-btn is-undo" onClick={открыть}>
          {железо.length === 0 ? 'Посмотреть, что рядом' : 'Открыть устройства'}
        </button>
      )}>
      {железо.length === 0
        ? 'Посмотреть, что рядом в эфире. Модель заранее указывать не нужно.'
        : 'Открыть поиск и переподключить — или отдать устройство другому телефону.'}
    </Notice>
  );
}
