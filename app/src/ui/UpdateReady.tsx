import { IonIcon } from '@ionic/react';
import { refreshOutline } from 'ionicons/icons';
import { useState } from 'react';
import { useUpdateState, applyUpdate } from '@/platform/swUpdate';
import { APP_BUILD } from '@/platform/appUpdate';
import { прочитать, записать } from '@/settings/storage';

/* «Обновление скачано и ждёт» — на «Сегодня», а не только в настройках (SugarLife#150).

   Само по себе обновление приложения не про диабет, и на экране действия ему было бы
   не место. Важным его делает механика PWA: наш service worker зарегистрирован в
   режиме prompt, и скачанная версия НЕ применяется, пока открыт хоть один клиент.
   Телефонное приложение не закрывают — его сворачивают. Значит человек может неделями
   ходить со сборкой, которую мы давно починили, и быть уверенным, что у него свежая:
   приложения ведь обновляются сами.

   Поэтому говорим не «вышла новая версия», а «скачана и ждёт перезапуска». Разница
   существенная: во втором случае от человека требуется действие, которого он иначе
   не совершит, потому что не знает о нём.

   Тихой строкой, не подсветкой-предупреждением: рядом с «инсулина на два часа»
   жёлтая карточка про обновление уравнивала бы несравнимое. Обновление ждёт — оно
   подождёт ещё.

   Сами не применяем никогда. Применение перезагружает приложение, и если в этот
   момент открыта шторка ввода еды, введённое пропадёт. Обновление не стоит
   потерянного приёма пищи. */

const КЛЮЧ = 'sl.update.postponed.v1';

/* Откладываем по версии, а не по времени.

   У ждущего обновления нет собственного номера — service worker не сообщает, что
   именно приехало. Зато известна версия, В КОТОРОЙ человек сказал «потом»: пока он
   в ней и сидит, спрашивать больше не о чем. Обновится — ключ перестанет совпадать,
   и следующее обновление спросит заново.

   По времени было бы хуже: строка вернулась бы через час и научила бы себя не
   замечать — ровно то, из-за чего мы вычищаем постоянные подсветки (#147). */
const отложено = (): boolean => прочитать(КЛЮЧ) === APP_BUILD;

export default function UpdateReady() {
  const upd = useUpdateState();
  const [скрыто, setСкрыто] = useState(отложено);

  /* Только 'available'. «Проверяю», «актуально» и ошибка проверки — состояния экрана
     настроек: они отвечают на вопрос, который здесь никто не задавал. */
  if (upd.status !== 'available' || скрыто) return null;

  const потом = () => { записать(КЛЮЧ, APP_BUILD); setСкрыто(true); };

  return (
    <div className="upd-row">
      <IonIcon icon={refreshOutline} className={upd.applying ? 'spin' : ''} />
      <span className="upd-text">
        <b>Обновление скачано</b>
        <i>Перезапустит приложение — пара секунд.</i>
      </span>
      <span className="upd-actions">
        <button className="changed-btn is-undo" onClick={applyUpdate} disabled={upd.applying}>
          {upd.applying ? 'Обновляю…' : 'Обновить'}
        </button>
        <button className="changed-btn" onClick={потом} disabled={upd.applying}>Потом</button>
      </span>
    </div>
  );
}
