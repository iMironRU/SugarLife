import { refreshOutline } from 'ionicons/icons';
import Notice from './Notice';
import { useState, useEffect } from 'react';
import { useUpdateState, applyUpdate, перечитатьВсё } from '@/platform/swUpdate';
import { ключОтказа, КЛЮЧ_ОТКАЗА as КЛЮЧ } from '@/platform/отставание';
import { вДневник } from '@/sources/дневникStore';
import { APP_BUILD, isNative, применитьOta } from '@/platform/appUpdate';
import { useОтаОбновление } from '@/platform/otaWatch';
import { прочитать, записать } from '@/settings/storage';

/* «Обновление скачано и ждёт» — на «Сегодня», а не только в настройках (SugarLife#150).

   Само по себе обновление приложения не про диабет, и на экране действия ему было бы
   не место. Важным его делает механика PWA: наш service worker зарегистрирован в
   режиме prompt, и скачанная версия НЕ применяется, пока открыт хоть один клиент.
   Телефонное приложение не закрывают — его сворачивают. Значит человек может неделями
   ходить со сборкой, которую мы давно починили, и быть уверенным, что у него свежая:
   приложения ведь обновляются сами.

   Поэтому говорим не «вышла новая версия», а «скачана и ждёт перезапуска». Разница
   существенная: во втором случае от человека требуется действие, которого он иначе
   не совершит, потому что не знает о нём.

   Тихой строкой, не подсветкой-предупреждением: рядом с «инсулина на два часа»
   жёлтая карточка про обновление уравнивала бы несравнимое. Обновление ждёт — оно
   подождёт ещё.

   Сами не применяем никогда. Применение перезагружает приложение, и если в этот
   момент открыта шторка ввода еды, введённое пропадёт. Обновление не стоит
   потерянного приёма пищи. */


/* Откладываем по версии, а не по времени.

   У ждущего обновления нет собственного номера — service worker не сообщает, что
   именно приехало. Зато известна версия, В КОТОРОЙ человек сказал «потом»: пока он
   в ней и сидит, спрашивать больше не о чем. Обновится — ключ перестанет совпадать,
   и следующее обновление спросит заново.

   По времени было бы хуже: строка вернулась бы через час и научила бы себя не
   замечать — ровно то, из-за чего мы вычищаем постоянные подсветки (#147). */
/* Ключом была одна своя сборка — и это оказалось тупиком (#386). Сказав «потом», человек
   больше не получал предложений никогда: его сборка не менялась, а сменить её можно было
   только этим предложением. Теперь ключ — пара «откуда → куда»: следующий релиз спросит
   заново, тот же самый — промолчит (platform/отставание.ts). */
const отложено = (наСервере: string | null): boolean => прочитать(КЛЮЧ) === ключОтказа(APP_BUILD, наСервере);

export default function UpdateReady() {
  const upd = useUpdateState();
  /* Нативная половина (#312). В вебе обновление УЖЕ скачано service worker'ом и ждёт
     перезапуска; в нативе оно только найдено — качать будем по нажатию. Разница
     существенная для текста: обещать «пара секунд» там, где сейчас начнётся загрузка
     десятка мегабайт по мобильной сети, нельзя. */
  const ota = useОтаОбновление();
  const [ставлю, setСтавлю] = useState(false);
  const [отказ, setОтказ] = useState<string | null>(null);

  /* «Отстали, а воркера нет» — второй повод сказать (#386).

     Первый повод («обновление скачано») приходит от service worker и требует, чтобы вся
     его цепочка сработала. Когда она молчит, приложение молчало вместе с ней: сборка на
     телефоне отставала на две версии, и узнать об этом было неоткуда — экран выглядел
     точно так же, как у свежего. Молчание тут хуже лишней строки: человек уверен, что
     видит сегодняшнее приложение, и принимает решения по нему. */
  const застряли = !isNative && upd.застряли;

  /* В дневник — то же, что человек видит здесь (#396). Один раз на сборку: обращение
     висит, пока его не применят, и без этого каждый запуск дописывал бы новую строку. */
  const есть = isNative ? !!ota : (upd.status === 'available' || застряли);
  const сборка = isNative ? ota?.build : upd.serverBuild;
  useEffect(() => {
    if (!есть) return;
    вДневник('сборка', застряли ? 'Приложение отстало от сервера' : 'Обновление ждёт перезапуска',
      сборка ? `сборка ${сборка}` : null, true);
  }, [есть, застряли, сборка]);
  const скрыто = отказ === ключОтказа(APP_BUILD, upd.serverBuild) || отложено(upd.serverBuild);

  if (скрыто) return null;
  /* Только 'available'. «Проверяю», «актуально» и ошибка проверки — состояния экрана
     настроек: они отвечают на вопрос, который здесь никто не задавал. */
  if (!(isNative ? ota : (upd.status === 'available' || застряли))) return null;

  const потом = () => {
    const к = ключОтказа(APP_BUILD, upd.serverBuild);
    записать(КЛЮЧ, к); setОтказ(к);
  };

  /* Тем же элементом, что и остальные обращения (#225). Своя вёрстка тут была ровно
     тем, из-за чего кнопки пришлось увеличивать отдельно, а «Потом» вести себя иначе,
     чем у подсветок. Вид — «сообщение»: обновление не про диабет и тревожным быть не
     должно, но и молчать о нём нельзя (#150). */
  const занят = ставлю || upd.applying;
  return (
    <Notice вид="сообщение" значок={refreshOutline}
      заголовок={isNative ? 'Есть новая сборка' : (застряли ? 'Приложение отстало' : 'Обновление скачано')}
      действия={(
        <>
          <button className="changed-btn is-undo" disabled={занят}
            onClick={() => {
              if (!isNative) {
                /* Застряли — обычная кнопка ничего не переключит: переключать нечего.
                   Тогда сносим сохранённую оболочку и берём всё заново (#386). */
                if (застряли) { setСтавлю(true); void перечитатьВсё(); return; }
                applyUpdate(); return;
              }
              setСтавлю(true);
              void применитьOta(ota!).then((ок) => { if (!ок) setСтавлю(false); });
            }}>
            {занят ? 'Обновляю…' : 'Обновить'}
          </button>
          <button className="changed-btn" onClick={потом} disabled={занят}>Потом</button>
        </>
      )}>
      {isNative
        ? `Сборка ${ota!.build}. Скачается и перезапустит приложение — лучше по Wi-Fi.`
        : застряли
          /* Обе сборки названы по именам. «Есть обновление» человек читает как «что-то
             там улучшили» и откладывает; «у вас e4e0f87, а выложено 7bd588f» — это уже
             факт про его телефон, и с ним видно, насколько он отстал. */
          ? `У вас сборка ${APP_BUILD}, а выложена ${upd.serverBuild}. Загрузим заново — пара секунд, нужна сеть.`
          : 'Перезапустит приложение — пара секунд.'}
    </Notice>
  );
}
