import Иконка from './Иконка';
import { closeOutline } from 'ionicons/icons';
import { isValidElement, type ReactElement, type ReactNode } from 'react';
import { поВажности } from '@/domain/notices';

/* Обращение — единственный способ приложения заговорить с человеком (SugarLife#225).

   Их было восемь, и собраны они были по-разному: три написаны прямо в экране «Сегодня»
   как div с классом, две вынесены в компоненты со своей вёрсткой, у части есть «Потом»,
   у части нет, порядок — какой раньше в коде, тот и выше.

   Разнобой уже стоил дважды. Кнопки пришлось увеличивать в трёх местах по отдельности.
   А плитка устройств завела себе собственный ответ на вопрос «на связи ли» и писала
   «на связи» там, где раздел устройств говорил обратное (#230) — потому что у неё был
   свой код, и общее правило до неё не дошло.

   ТРИ ВИДА, И ЭТО НЕ ПРО ЦВЕТ. Предупреждение — то, что случится, если не вмешаться
   (резервуар кончится ночью). Предложение — то, что человек может сделать прямо сейчас
   (подключить устройство, обновиться). Сообщение — то, что просто должно быть известно
   (помпа на паузе). Разные виды требуют разного внимания, и смешивать их цветом значит
   уравнивать несравнимое.

   АНАТОМИЯ ОДНА. Значок, заголовок одной строкой, объяснение «почему это важно», ряд
   действий. Действия внизу и всегда в одном месте: человек, привыкший, что «Потом»
   справа, не должен искать его заново в каждой карточке. */

export type ВидОбращения = 'предупреждение' | 'предложение' | 'сообщение';

const КЛАСС: Record<ВидОбращения, string> = {
  предупреждение: 'today-alert warn',
  предложение: 'today-alert',
  сообщение: 'today-alert info',
};

export default function Notice({ вид, значок, заголовок, children, действия, отложить }: {
  /** Кто это обращение: по нему считается порядок (domain/notices.ts). */
  id?: string;
  вид: ВидОбращения;
  значок: string;
  /** Что случилось — одной строкой, без «пожалуйста» и без восклицаний. */
  заголовок: ReactNode;
  /** Почему это важно и что будет, если не трогать. */
  children?: ReactNode;
  /** Ряд действий: главное и второстепенное. «Потом» живёт крестиком, см. ниже. */
  действия?: ReactNode;
  /* Крестик справа вверху — «пока не до этого».

     Раньше это была кнопка «Потом» в ряду действий, и она соседствовала с «Поменял
     батарейку». Два действия рядом, из которых одно меняет данные, а второе прячет
     карточку, — постоянный риск нажать не то, особенно на ходу.

     Крестик не значит «сделал» и не значит «навсегда»: обращение вернётся, когда
     станет хуже (правило эпизода и уровня — settings/snooze.ts). Поэтому он есть
     только там, где такое возвращение предусмотрено. У состояний вроде «помпа на
     паузе» крестика нет вовсе: это не сообщение, которое можно принять к сведению, а
     факт, который перестанет быть правдой сам. */
  отложить?: () => void;
}) {
  return (
    <div className={КЛАСС[вид]}>
      <Иконка icon={значок} />
      <div>
        <b>{заголовок}</b>
        {children && <span>{children}</span>}
        {действия && <span className="alert-ask alert-ask-row">{действия}</span>}
      </div>
      {отложить && (
        <button className="notice-close" onClick={отложить} aria-label="Пока не до этого">
          <Иконка icon={closeOutline} />
        </button>
      )}
    </div>
  );
}

/* Сколько обращений показывать разом — и в каком порядке.

   Пять карточек подряд человек не читает: он проматывает их одним движением, и шестое,
   важное, уезжает вместе с ними. Предел не косметический — он определяет, услышат ли
   нас вообще.

   Порядок считается по важности (domain/notices.ts), а не по месту в разметке. Раньше
   он и был местом в разметке: какая карточка написана выше, ту человек и видел первой.
   Это не решение, а случайность — при следующей правке экрана порядок поменялся бы сам.

   Лишнее не прячется молча: под стопкой строка «ещё N». Иначе человек не узнает, что
   чего-то не видел, — ровно то, за что мы снимали фильтры в #149. */
const ПРЕДЕЛ_ОБРАЩЕНИЙ = 3;

export function NoticeStack({ children, предел = ПРЕДЕЛ_ОБРАЩЕНИЙ }: {
  children: ReactNode; предел?: number;
}) {
  /* Внутрь стопки идут только те обращения, чьё условие показа знает вызывающий: он
     ставит их в разметку или не ставит. Компоненты, решающие это сами (обновление,
     устройства), в стопку не попадают — иначе пришлось бы либо дублировать их условие
     здесь, либо считать занятым место, на котором нарисуется null. Они живут рядом и
     ниже: у них своя редкость и свой повод. */
  const узлы = (Array.isArray(children) ? children : [children])
    .flat(3)
    .filter((x): x is ReactElement<{ id?: string }> => isValidElement(x));
  /* Ключ обращения берём из его же id: он стоит рядом с текстом, и перепутать его с
     чужим при перестановке разметки нельзя. */
  const все = поВажности(узлы.map((узел, i) => ({ id: узел.props.id ?? `без-имени-${i}`, узел })));
  const видимые = все.map((x) => x.узел).slice(0, предел);
  const скрыто = все.length - видимые.length;
  return (
    <>
      {видимые}
      {скрыто > 0 && (
        <div className="an-off-note">
          Ещё {скрыто} {скрыто === 1 ? 'сообщение' : скрыто < 5 ? 'сообщения' : 'сообщений'} —
          покажем, когда разберётесь с этими
        </div>
      )}
    </>
  );
}
