import Иконка from './Иконка';
import { chevronForward } from 'ionicons/icons';
import { useStack } from '@/app/stackCtx';
import { ОхранаSection } from '@/sections/lazy';
import { useОхрана } from '@/показ/охранаХук';
import { Capacitor } from '@capacitor/core';

/* Состояние охраны там, где человек смотрит сахар (#473).

   Ядро просило не прятать его за «Настройки → Уведомления → Дополнительно»: это не
   настройка, а состояние защиты. Но и карточкой оно быть не должно: в исправном состоянии
   это фон, и занимать им полэкрана каждый день — учить не замечать.

   Поэтому строка. Одна, с ответом и поводом; тап открывает раздел. */
export default function СтрокаОхраны() {
  const { push, pop } = useStack();
  const { охрана: о } = useОхрана();
  /* На айфоне строка ЕСТЬ, и это исправление моей же ошибки: сначала я её там спрятал,
     решив, что сказать нечего. Сказать есть что — ночью айфон будит собственным звуком, и
     это переключатель, а не приговор (core#115).

     Нет её только в браузере: там страница спит вместе с телефоном, чинить нечего, и
     строка заняла бы место молча. */
  if (!Capacitor.isNativePlatform() || !о) return null;

  const беда = о.ответ !== 'разбудим';
  const первая = о.строки.find((с) => с.знак === 'нет');
  return (
    <button className={'охрана-строка' + (беда ? ' беда' : '')}
      onClick={() => push(<ОхранаSection onClose={pop} />, { id: 'охрана' })}>
      <span className={'охрана-знак' + (беда ? ' нет' : ' ок')} />
      <span className="охрана-текст">
        <b>{о.ответ === 'разбудим' ? 'Ночью разбудим'
          : о.ответ === 'не сторожим' ? 'Ночью не сторожим'
            : 'Ночью может не разбудить'}</b>
        <span>{беда ? (первая?.под ?? о.почему) : 'тревоги и сторож молчания на месте'}</span>
      </span>
      <Иконка icon={chevronForward} className="охрана-шеврон" />
    </button>
  );
}
