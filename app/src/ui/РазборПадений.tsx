import { useSnapshot } from '@/sources/bridge';
import { падения, сводка } from '@/показ/разборПадений';
import { падениеСловами, сводкаСловами } from '@/слова/падения';
import { часы, деньМесяц } from '@/слова/время';

/* «СПУСКИ» В РАЗБОРЕ (#812).

   На «Сегодня» полоса отвечает «что происходит»; здесь — «повторяется ли». Владелец сказал это
   прямо, увидев ночной спуск с 10,6 до 7,2: «и в аналитике такие полёты нужно разбирать». Смысл в
   накоплении — один спуск не говорит ничего, десять с одинаковым началом говорят.

   МОЛЧИМ, КОГДА ИХ НЕ БЫЛО. Не «спусков не найдено», а пусто: раздел и так отвечает на вопрос
   «что было», и строка про отсутствие занимала бы место, ничего не сообщая. Тот же довод, по
   которому мы не пишем «всё в порядке» на рабочих экранах.

   ДАННЫЕ БЕРЁМ ГОТОВЫЕ. Движок ведёт журнал эпизодов по всем уровням, «полёт вниз» там уже лежит.
   Своего накопления не заводим: второй ответ на тот же вопрос разошёлся бы с первым молча. */
export default function РазборПадений({ дней }: { дней: number }) {
  const снимок = useSnapshot();
  const от = Date.now() - дней * 86400e3;
  const ряд = падения(снимок, от);
  if (!ряд.length) return null;

  const свод = сводкаСловами(сводка(ряд, дней));

  return (
    <>
      <div className="section-label sec">Спуски</div>
      {свод && <div className="metric-note" style={{ marginTop: 0 }}>{свод}</div>}
      <div className="list">
        {ряд.map((п) => {
          const с = падениеСловами(п);
          return (
            <div key={п.ключ} className="list-row охрана-пункт">
              <span className="pick-main">
                <span className="list-title">{с.главное}</span>
                <span className="pick-sub">
                  {деньМесяц(п.когдаМс)}, {часы(п.когдаМс)}{с.подпись && ` · ${с.подпись}`}
                </span>
              </span>
            </div>
          );
        })}
      </div>
      {/* ЧЕГО ЗДЕСЬ НЕТ — сказано вслух, потому что человек этого ждёт. Причину спуска мы не
          знаем: у неё их больше двух (недоданный болюс, отвалившаяся канюля, нагрузка, жара), и
          назвать одну значило бы выбрать за него. */}
      <div className="sheet-note">
        Почему был спуск, здесь не написано — причин у него больше двух, и выбирать одну за вас мы
        не станем. Что было перед ним, видно в «Истории» за то же время.
      </div>
    </>
  );
}
