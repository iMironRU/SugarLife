import Иконка from '@/ui/Иконка';
import { openOutline } from 'ionicons/icons';
import { useSnapshot } from '@/sources/bridge';

/* «Подробнее» — ссылка наружу, на статью (SugarLifeCore#16).

   Подсказка под полем отвечает на «что сюда вписать». На «как это получить» она ответить не
   может: поднять Nightscout или выдать токен с правом записи — это страница текста, а не строка
   под полем. Раньше такие вещи заканчивались тем, что человек шёл искать ответ в поиске и
   находил чужую инструкцию к другой версии.

   ЗЕРКАЛО — ЗАПАСНОЙ ВЫХОД, А НЕ ВТОРАЯ КНОПКА (core#114). Тот же текст лежит в репозитории и
   отвечает даже там, где основной домен ещё не разрешается. Но поставить их рядом нельзя: два
   одинаковых «подробнее» у одного поля человек читает как выбор, которого нет, — и первым делом
   попробует угадать, чем они отличаются. Поэтому зеркало появляется отдельной, тихой строкой и
   названо тем, чем является: «не открывается?».

   ЖИЛ ВНУТРИ ParamsForm И ПОТОМУ НЕ ПРИМЕНЯЛСЯ БОЛЬШЕ НИГДЕ (SugarLife#740). Ядро прислало
   сводку: `snapshot.help` — карта из двадцати двух статей — не читается у нас НИ РАЗУ. Статьи
   написаны, лежат в вики, доезжают до оболочки и не показываются. Машинка при этом была готова,
   просто заперта в одном файле. */
export default function Подробнее({ адрес, зеркало }: { адрес: string; зеркало?: string | null }) {
  /* СВОЯ КОРОБКА, А НЕ ГОЛЫЕ ССЫЛКИ В ЧУЖОМ ПОТОКЕ.

     В форме параметров пара стояла в контейнере, который сам разводил её по строкам. Стоило
     поставить компонент внутрь абзаца — «Подробнее» и «не открывается?» слиплись в одно
     слово. Собственная колонка делает вид одинаковым везде, а не только там, где повезло
     с окружением. */
  return (
    <span className="подробнее">
      <a className="param-help" href={адрес} target="_blank" rel="noreferrer">
        <Иконка icon={openOutline} /> Подробнее
      </a>
      {зеркало && зеркало !== адрес && (
        <a className="param-help-alt" href={зеркало} target="_blank" rel="noreferrer">
          не открывается?
        </a>
      )}
    </span>
  );
}

/* ССЫЛКА ПО ПОНЯТИЮ, А НЕ ПО АДРЕСУ.

   Адреса статей знает движок и присылает их картой в каждом снимке (`snapshot.help`). Своих не
   подставляем и не хардкодим: адрес уезжает в выпущенное приложение, а домен переезжает — у ядра
   это записано отдельным доводом, и он наш тоже.

   ПОНЯТИЯ НЕТ В КАРТЕ — НЕ ПОКАЗЫВАЕМ НИЧЕГО. Битая ссылка хуже отсутствующей: человек нажимает,
   попадает в пустоту и перестаёт нажимать вообще. Карта у движка открытая, и новые статьи
   появятся здесь сами, без нашей правки. */
export function ПодробнееПоТеме({ тема }: { тема: string }) {
  const снимок = useSnapshot();
  const ссылка = снимок?.help?.[тема];
  if (!ссылка?.url) return null;
  return <Подробнее адрес={ссылка.url} зеркало={ссылка.mirror} />;
}
