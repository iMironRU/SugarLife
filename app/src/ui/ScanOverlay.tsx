import { createPortal } from 'react-dom';

/* Видоискатель поверх камеры (SugarLife#350).

   Камера показывается ПОД веб-слоем, приложение на это время прозрачно — значит от нас
   на экране остаётся только то, что нарисовано здесь. Без этого человек смотрит в
   прозрачное ничто и не знает ни что происходит, ни как выйти.

   Три вещи, и все обязательные: рамка, куда наводить, слово о том, что ищем, и выход.
   Кнопка «Отмена» крупная и внизу — её жмут одной рукой, второй держа коробку. */
export default function ScanOverlay({ подпись, onОтмена }: {
  подпись: string; onОтмена: () => void;
}) {
  return createPortal(
    <div className="скан-слой">
      <div className="скан-рамка" />
      <div className="скан-подпись">{подпись}</div>
      <button className="скан-отмена" onClick={onОтмена}>Отмена</button>
    </div>,
    document.body,
  );
}
