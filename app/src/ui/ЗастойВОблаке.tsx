import { useSnapshot } from '@/sources/bridge';
import { ПодробнееПоТеме } from '@/ui/Подробнее';

/* «В ОБЛАКЕ НЕТ СВЕЖИХ» — ПОДПИСЬ К ЧИСЛАМ (ядро #157, мост ≥ 1.56).

   Третье состояние, которого не было ни в связи, ни в причинах отказа. Движок различает три
   беды и присылает готовые слова: встал загрузчик, загрузчик жив но сенсор в него не пишет,
   либо об отчётах судить нечем. Своих слов мы здесь не пишем — какая из трёх, решаем не мы.

   Отдельный файл, а не строка в Today: одна мысль, один хозяин, и подключить её на другой
   экран будет нечем ошибиться. */
export default function ЗастойВОблаке() {
  const снимок = useSnapshot();
  /* Короткая форма (мост ≥ 1.57) — она и задумана для этого места. `words` остаётся запасным
     путём для старого моста: там три предложения, но три предложения лучше пустоты. */
  const причина = снимок?.monitor?.staleReason;
  const слова = причина?.shortWords || причина?.words;
  if (!слова) return null;
  /* Фраза движка отвечает «кого трясти». На «почему облако отвечает, а чисел в нём нет»
     она ответить не может — это страница текста, и она написана (тема `staleCloud`,
     SugarLife#740). До сегодня карта статей приезжала в каждом снимке и не читалась нами
     ни разу. */
  return (
    <div className="застой-в-облаке">
      {слова}
      {' '}<ПодробнееПоТеме тема="staleCloud" />
    </div>
  );
}
