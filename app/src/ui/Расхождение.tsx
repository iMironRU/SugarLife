import { useSnapshot } from '@/sources/bridge';
import { расхождение } from '@/показ/расхождение';

/* «ПРИБОРЫ РАСХОДЯТСЯ» (#822).

   Такого не показывает ни одна программа: все рисуют одно число и молчат о том, что второе другое.
   У владельца два сенсора на разных руках расходились на четыре ммоль — и узнать об этом можно было,
   только открыв два приложения подряд.

   ЗДЕСЬ ЖЕ, ГДЕ «ПОЛЁТ ВНИЗ», И ПО ТОЙ ЖЕ ПРИЧИНЕ: это высказывание про сахар прямо сейчас, оно
   ничего не требует и ни на что не отвечает кнопкой. Ниже тревоги и отбоя — там человеку есть что
   делать, здесь только знать.

   ЧИСЛА ПРИБОРОВ РЯДОМ С ФРАЗОЙ — не украшение. Совет «проверьте глюкометром, какой ближе»
   невыполним, если не видно, какой прибор что показывает: человек померит и не поймёт, к чему
   приложить результат.

   ЗНАК — ВОПРОС, А НЕ ВОСКЛИЦАНИЕ. Мы не знаем, какой прибор врёт, и не притворяемся, что знаем. */
export default function Расхождение() {
  const снимок = useSnapshot();
  const р = расхождение(снимок);
  if (!р) return null;

  return (
    <div className="заметка расхождение">
      <span className="заметка-знак" aria-hidden="true">≠</span>
      <span className="заметка-текст">
        {р.текст}
        {р.приборы.length > 0 && (
          <span className="расхождение-числа">
            {р.приборы.map((п) => (
              <span key={п.id} className="расхождение-прибор">
                <b>{п.число}</b> {п.имя}
              </span>
            ))}
          </span>
        )}
      </span>
    </div>
  );
}
