import { IonPage, IonContent } from '@ionic/react';
import КрайПрокрутки from './КрайПрокрутки';
import { useEffect, useRef, useState, type ReactNode } from 'react';
import { reportContentScroll, серединаЛи, полшага, плавно, syncToActiveScreen } from '@/app/panel';
import { useTab, useGoHome } from '@/app/nav';

/* Оболочка вкладки — единственное место, где вкладка становится страницей.

   Раньше каждый из пяти экранов писал это сам:

     <IonPage><IonContent fullscreen forceOverscroll scrollEvents
       onIonScroll={reportContentScroll}><div className="screen screen-pad">

   Четыре пропса и два класса, скопированные пять раз. Забыть onIonScroll — панель на
   этом экране перестанет сворачиваться; забыть screen-pad — содержимое встанет на
   восемь пикселей выше, чем у соседей. Ровно это и случилось (SugarLife#159): отступ
   под панелью разошёлся между вкладками вдвое, потому что правило существовало только
   в виде образца для копирования.

   Здесь оно существует физически. Экран описывает содержимое и больше ничего: ни
   прокрутку, ни отступы, ни то, как он становится страницей.

   Отступ сверху задаёт CSS одной величиной (--sl-content-top в theme/parts/shell.css),
   общей со страницами стека и шторками. Первые блоки своих margin-top не приносят —
   иначе зазор снова начнёт складываться из чужих полей. */
export default function Screen({ tab, panel = 'compact', children }: {
  tab: number;
  /* Насколько велика панель на этом экране.

     'full' — там, где сахар и есть содержимое: «Сегодня». Круг крупный, панель
     занимает своё место по праву, прокрутка её сворачивает за пальцем.

     'compact' — везде остальном. На «Метриках», «НМГ», «Инсулине» и в «Профиле»
     круг повторяет то, что и так на экране, или к делу не относится вовсе, а сто
     пикселей стоят трёх строк списка. Человек всё равно сворачивал панель прокруткой
     первым же движением — значит она там открыта зря.

     Сахар при этом не исчезает: в сжатом виде остаются число, стрелка и строка
     связи. Обещание «значение всегда на виду» держится, просто оно перестаёт быть
     главным там, где главное другое. */
  panel?: 'full' | 'compact';
  children: ReactNode;
}) {
  /* Вкладка — нулевой этаж пути: с неё начинается любая крошка в разделах под ней.
     Имя берём из одного списка, а не пишем на каждом экране: два места для одного
     названия разошлись бы в первый же день, когда вкладку переименуют. */
  const active = useTab();
  const ref = useRef<HTMLIonContentElement>(null);
  const тело = useRef<HTMLDivElement>(null);

  /* Полупустой экран держит панель на середине, а не в тонкой строке.

     Симптом простой: на «Инсулине» под коротким графиком остаётся половина экрана
     пустоты, а панель при этом сжата до предела. Сжатие — плата за место, и брать её
     там, где место всё равно не нужно, не за что: сахар теряет размер, а взамен не
     появляется ни строки.

     Решает замер, а не список экранов: содержимое одного и того же экрана бывает и
     коротким, и длинным (график за час и за сутки), и список пришлось бы держать в
     двух местах — он разошёлся бы с правдой в первый же день.

     Считаем от собственной высоты содержимого: отступ сверху сам зависит от положения
     панели, и мерить «сколько видно» значило бы спрашивать ответ у самого ответа. */
  const [середина, setСередина] = useState(false);
  useEffect(() => {
    if (panel !== 'compact') return;
    const el = тело.current;
    const хост = el?.parentElement;
    if (!el || !хост) return;
    const пересчитать = () => {
      const отступ = parseFloat(getComputedStyle(el).paddingTop) || 0;
      const своё = el.scrollHeight - отступ;
      /* Отступ середины: если мы уже в ней — это текущий, иначе сжатый плюс полшага.
         Так вопрос остаётся одним и тем же в обоих состояниях. */
      const отступСередины = el.classList.contains('is-mid') ? отступ : отступ + полшага();
      setСередина(серединаЛи(своё, отступСередины, хост.clientHeight));
    };
    пересчитать();
    const наблюдатель = new ResizeObserver(пересчитать);
    наблюдатель.observe(el);
    наблюдатель.observe(хост);
    return () => наблюдатель.disconnect();
  }, [panel, children]);

  /* Панель пересинхронизируем ТОЛЬКО когда замер изменил ответ, и только если экран
     сейчас на виду.

     Не на смене вкладки: там синхронизацию делает панель, и вторая, своя, попадала в
     кадр, когда карусель ещё не пометила новую страницу активной, — синхронизация
     читала соседнюю вкладку и пинала панель в её положение. «Сегодня» из-за этого
     открывался со сжатой панелью поверх содержимого.

     Плавно, а не сразу: замер меняется от данных (догрузился график), человек в этот
     момент смотрит на экран, и скачок размера читался бы как сбой. */
  const прошлое = useRef(середина);
  useEffect(() => {
    if (прошлое.current === середина) return;
    прошлое.current = середина;
    if (active !== tab) return;
    плавно(() => syncToActiveScreen(tab));
  }, [середина, active, tab]);

  /* Уходя с экрана, возвращаем его к покою.

     Карусель держит все пять вкладок смонтированными, и каждая помнила свою
     прокрутку — а панель следует за прокруткой активной. Из-за этого вкладки
     выглядели по-разному: на одной панель развёрнута, на другой уже сжата, хотя
     человек ничего с ней не делал. Сравнить это можно только скриншотами, а
     почувствовать — как «приложение каждый раз немного другое».

     Цена решения названа честно: прокрутил длинные «Метрики», ушёл и вернулся —
     ищешь место заново. Мы выбрали предсказуемость: одинаковый вид всех вкладок
     важнее сохранённого места на одной из них. */
  useEffect(() => {
    if (active === tab) return;
    void ref.current?.scrollToTop(0);
  }, [active, tab]);

  /* Нажал свою вкладку ещё раз — «наверх».

     Это уже привычный жест таб-бара, и у нас для него был готов сигнал: тем же
     нажатием стек возвращается в корень (nav.pressTab). Логично, что после корня
     следующее значение того же нажатия — вернуть к покою и сам экран.

     Порядок важен: пока открыт раздел, нажатие закрывает его, а не крутит экран под
     ним — иначе человек, выходящий из «Аналитики», незаметно потеряет и место на
     «Метриках». Поэтому проверяем, есть ли открытая страница; закрывает её StackHost
     тем же сигналом.

     Заодно это ответ на цену прошлого решения: экраны возвращаются к покою при уходе,
     а теперь есть и способ попасть наверх, не уходя.

     Прокрутка анимированная, и не только ради привычности: панель следует за
     событиями прокрутки без собственной анимации (app/panel.ts), поэтому мгновенный
     прыжок наверх раскрыл бы её рывком. Плавная прокрутка даёт панели разворачиваться
     вместе с содержимым — одно движение вместо двух. */
  const домой = useGoHome(tab);
  useEffect(() => {
    if (!домой || active !== tab) return;
    if (document.querySelector('.pager-pane.is-active .stack-page')) return;
    void ref.current?.scrollToTop(250);
  }, [домой, active, tab]);

  return (
    <IonPage>
      <IonContent ref={ref} fullscreen forceOverscroll scrollEvents onIonScroll={reportContentScroll}>
        <div ref={тело} className={'screen' + (panel === 'compact' ? ' is-compact' : '') + (середина ? ' is-mid' : '')}>
          {children}
          {/* Вкладка ничем не отличается от раздела: список настроек такой же длинный,
              и где он кончается, человеку так же не видно (#272, #285). */}
          <КрайПрокрутки />
        </div>
      </IonContent>
    </IonPage>
  );
}
