import { IonIcon } from '@ionic/react';
import { cloudOfflineOutline, chevronForward } from 'ionicons/icons';
import { useStore } from '@/sources/store';
import { useSnapshot } from '@/sources/bridge';
import { setOnboarded } from '@/settings/onboarding';
import type { UiSnapshot } from '@/sources/bridge';

/* Настроено ли — по флагу движка ИЛИ по факту идущих данных.

     Флаг отвечает на вопрос «есть ли настроенный источник», и обычно этого хватает. Но
     он может отстать: прибор заводят прямо сейчас, показания уже пошли, а сводка
     настроенности приходит следующим снимком. И полсекунды поверх живого сахара висит
     «Приложение не настроено» с кнопкой «пройти мастер заново» — предложение выбросить
     то, что только что настроили.

     Идущие данные — доказательство сильнее любого флага: источник, который шлёт
     показания, настроен по определению. Обратное неверно, поэтому правило одностороннее:
     молчащий источник остаётся настроенным. */
function настроено(snap: UiSnapshot | null | undefined): boolean {
  if (snap?.setup?.configured) return true;
  const g = snap?.monitor?.glucose;
  return !!g && g !== '—' && g !== '';
}

/* Приложение не настроено — заметный выход, а не мелкая надпись.

   Человек мог нажать «Уже настроено — просто открыть», а настроено оказалось ничего:
   раньше он оставался с прочерками и подписью «Нет данных. Подключите Nightscout в
   профиле» — то есть его отправляли искать настройку самому.

   Кнопка возвращает мастер первого запуска: снимаем флаг «онбординг пройден», и гейт
   в App.tsx показывает его снова. Данные при этом не трогаются.

   ОДИН вид на всех экранах, без вариантов: две разные версии читались как разные
   вещи, хотя это одна и та же кнопка про одно и то же. */
/* Пока источник не настроен, экран показывает ТОЛЬКО эту кнопку.

   Иначе выходило так: сверху баннер «приложение не настроено», а под ним живой на вид
   сахар, статистика за 90 дней и график базала — из локальной истории, оставшейся от
   прежнего подключения. Цифры выглядят текущими, хотя обновляться им неоткуда, и это
   худший вид вранья, какой может быть в приложении про инсулин.

   Только для 'off' — источника нет вовсе. При обрыве связи статус другой ('stale'),
   и последние известные значения остаются на месте: ночью они могут быть важнее всего. */
export function DataGate({ children }: { children: React.ReactNode }) {
  const { status } = useStore();
  /* Настроенность спрашиваем у движка, а не считаем по облакам (#337, мост 1.20).

     Стор считал её по списку Nightscout-облаков, и прямой BLE-сенсор, который прямо
     сейчас шлёт показания, в счёт не входил: данные идут, а поверх них висит «приложение
     не настроено» с кнопкой, зовущей настраивать заново. Это видели на живом телефоне.

     Настроено ≠ на связи. Молчащий источник остаётся настроенным: связь рвётся по десять
     раз на дню, и предлагать «настроить заново» при каждом обрыве значит гнать человека
     по кругу вместо того, чтобы сказать «прибор не отвечает». */
  if (настроено(useSnapshot())) return <>{children}</>;
  if (status === 'off') return <NotConfigured />;
  return <>{children}</>;
}

export default function NotConfigured() {
  const { status } = useStore();
  if (настроено(useSnapshot())) return null;
  // 'off' = ни одного включённого облака. Только это и значит «не настроено»;
  // при обрыве связи (stale/error) настройки на месте, мастер предлагать незачем.
  if (status !== 'off') return null;

  return (
    <button className="nocfg" onClick={() => setOnboarded(false)}>
      <IonIcon icon={cloudOfflineOutline} className="nocfg-ico" />
      <span className="nocfg-txt">
        <span className="nocfg-t">Приложение не настроено</span>
        <span className="nocfg-d">Не подключён ни один источник данных. Мастер займёт минуту.</span>
      </span>
      <IonIcon icon={chevronForward} className="nocfg-chev" />
    </button>
  );
}
