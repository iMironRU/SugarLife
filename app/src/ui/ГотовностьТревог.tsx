import { useEffect, useState } from 'react';
import Иконка from './Иконка';
import { notificationsOutline, checkmarkCircle } from 'ionicons/icons';
import {
  готовностьТревог, открытьНастройкиТревог, чинитсяНастройками, тревогиДоступны,
  type ГотовностьТревог,
} from '@/platform/тревоги';

/* «Ночью может не разбудить» — строкой, до ночи (#468).

   Канал тревоги заведён как будильник: громкость будильника, обход «Не беспокоить»,
   полноэкранное намерение, вибрация. Система исполняет это только при выданных
   разрешениях, а без них МОЛЧА ДЕЛАЕТ ВИД, ЧТО ИСПОЛНИЛА. Утром уведомление в шторке на
   месте — и человек уверен, что защита была.

   Разрешение в манифесте — только право спросить. Доступ выдаёт человек, руками, в
   системных настройках. Пока не выдал, поломка не выглядит поломкой — и узнать о ней
   постфактум означает узнать после ночи, которую проспали.

   Тот же приём, что и с фоном (#380): строка на экране, а не всплывающая просьба. Диалог
   закрывают не читая, и второй раз он не появится; строка ждёт, пока человек придёт
   разбираться, и в этот момент отвечает на его вопрос. */
export default function ГотовностьТревогБлок({ спокойно }: {
  /* «Спокойно» — режим диагностики: туда приходят за ответом, и «всё в порядке» там
     уместно. На рабочих экранах зелёная галочка — шум. */
  спокойно?: boolean;
}) {
  const [г, setГ] = useState<ГотовностьТревог | null | 'ждём'>('ждём');
  const [открыли, setОткрыли] = useState(false);

  useEffect(() => { void готовностьТревог().then(setГ); }, []);

  if (г === 'ждём' || !тревогиДоступны()) return null;

  /* Спросить не у кого — сборка старше проверки. Это НЕ «всё хорошо»: молчание здесь
     читается как обещание разбудить, а мы этого не знаем. */
  if (!г) {
    return (
      <div className="sheet-note warn">
        Эта сборка старше проверки разрешений — узнать, разбудит ли ночью, отсюда нельзя.
        Обновите приложение целиком.
      </div>
    );
  }

  if (!г.проблема) {
    if (!спокойно) return null;
    return (
      <div className="sheet-note">
        <Иконка icon={checkmarkCircle} style={{ marginRight: 6, verticalAlign: -2 }} />
        {/* Про пропажу данных здесь больше не пишем: это правило движка, и его порог виден на
            экране правил (#482). Дублировать его тут значило бы завести второй ответ на тот же
            вопрос — и разойтись с ним при первой же правке. */}
        Тревоги: разрешения на месте — звук, обход «не беспокоить», полный экран.
      </div>
    );
  }

  return (
    <div className="today-alert warn">
      <Иконка icon={notificationsOutline} className="alert-ico" />
      <div>
        <span className="alert-title">Ночью может не разбудить</span>
        <span>
          {г.чегоНет.join('. ')}.
          {' '}Разрешение в приложении — только право спросить: доступ выдаёте вы, в
          системных настройках.
        </span>
        {/* Кнопка — только когда системный экран правда чинит поломку. Айфонное «фоновое
            бодрствование выключено» чинится нашим же переключателем в «Охране», и отправлять
            за этим в системные настройки значит водить человека кругами. */}
        {чинитсяНастройками(г.поломки) && (
          <span className="alert-ask alert-ask-row">
            <button className="changed-btn is-undo" disabled={открыли}
              onClick={() => {
                setОткрыли(true);
                void открытьНастройкиТревог().then((ок) => { if (!ок) setОткрыли(false); });
              }}>
              {открыли ? 'Открываю…' : 'Открыть настройки'}
            </button>
          </span>
        )}
      </div>
    </div>
  );
}
