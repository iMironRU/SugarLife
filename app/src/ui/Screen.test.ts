import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

/* Барьер, а не бдительность (SugarLife#159).

   Отступ содержимого разъехался между вкладками не потому, что кто-то был
   невнимателен, а потому что правило существовало только в виде образца для
   копирования: каждый экран сам собирал IonPage + IonContent + классы. Шестой экран
   скопировал бы любой из пяти вариантов.

   Теперь правило живёт в ui/Screen.tsx, и эти тесты стерегут именно то, что позволяло
   его обойти. Они ловят в момент написания кода, а не после сравнения скриншотов —
   разница в том, что скриншоты сравнивает человек, и только когда заподозрит. */

function файлы(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? файлы(p) : /\.tsx?$/.test(p) && !/\.test\./.test(p) ? [p] : [];
  });
}

const исходники = файлы('src').map((p) => ({ путь: p, текст: readFileSync(p, 'utf8') }));

describe('оболочка экрана', () => {
  /* IonPage/IonContent — это и есть «страница». Собирать её вручную можно только в
     одном месте; везде ещё это значит, что кто-то завёл шестой способ. */
  /* Список исключений был — шторки собирали себя сами. После #161 он пуст: все три
     поверхности собираются оболочками, и примитивы Ionic живут только в них. */
  it('страницу собирает только ui/Screen.tsx', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/(Screen|Sheet)\.tsx$/.test(f.путь))
      .filter((f) => /<IonPage[\s>]|<IonContent[\s>]/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители, 'IonPage/IonContent вне оболочки — это новый способ собрать экран').toEqual([]);
  });

  /* Прокрутка панели держится на onIonScroll. Экран, который подписался сам, однажды
     подпишется иначе — или забудет, и панель на нём перестанет сворачиваться. */
  it('на прокрутку подписывается только оболочка', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/Screen\.tsx$|app\/(panel|stack)\.tsx?$/.test(f.путь))
      .filter((f) => /reportContentScroll/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители).toEqual([]);
  });

  /* Верхний отступ — одна величина на все поверхности. Любой padding-top в стилях
     экранов возвращает нас к сумме из нескольких слагаемых, с которой всё началось. */
  it('верхний отступ содержимого задан ровно в одном правиле', () => {
    const стили = файлы('src/theme').filter((p) => p.endsWith('.css'))
      .map((p) => ({ путь: p, текст: readFileSync(p, 'utf8') }));
    const места = стили.flatMap((f) =>
      f.текст.split('\n')
        .map((строка, i) => ({ f: f.путь, i: i + 1, строка }))
        .filter(({ строка }) => /--sl-content-top/.test(строка) && !/^\s*\*/.test(строка)),
    );
    // одно объявление в shell.css + по одному применению на каждую из трёх поверхностей
    expect(места.length, `--sl-content-top встречается ${места.length} раз: ` +
      места.map((m) => `${m.f}:${m.i}`).join(', ')).toBeLessThanOrEqual(4);
  });
});

describe('оболочка раздела', () => {
  /* Разделов одиннадцать, и собирали они себя тремя способами. Теперь способ один —
     ui/Section.tsx, и стеречь надо ровно то, что позволяло завести четвёртый:
     самодельный корень и самодельный заголовок.

     PageLoading — законное исключение: это заглушка на месте раздела, пока едет его
     код, и выглядеть она обязана как раздел. Оболочкой её не сделать — у неё нет ни
     «назад», ни содержимого. */
  const своя = /ui\/(Section|PageLoading)\.tsx$/;

  it('корень раздела собирает только ui/Section.tsx', () => {
    const нарушители = исходники
      .filter((f) => !своя.test(f.путь))
      .filter((f) => /className="sheet stack-body"|'sheet stack-body'/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители, 'самодельный корень раздела — это четвёртый способ собрать страницу').toEqual([]);
  });

  it('заголовок раздела ставит только оболочка', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/(Section|PageHead)\.tsx$/.test(f.путь))
      .filter((f) => /<PageHead[\s>]/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители).toEqual([]);
  });
});

describe('оболочка шторки', () => {
  /* Восемь шторок с четырьмя разными настройками стоили нам двух починок:
     неработающей прокрутки и заблокированного экрана. Обе — из-за того, что
     настройка жила в месте использования (SugarLife#161). */

  it('модалку собирает только ui/Sheet.tsx', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/Sheet\.tsx$/.test(f.путь))
      .filter((f) => /<IonModal[\s>]/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители).toEqual([]);
  });

  /* breakpoints забирают вертикальный жест себе: содержимое перестаёт прокручиваться,
     и до нижней кнопки не добраться. Мы это уже чинили в шторке еды — по одному файлу
     за раз. Здесь запрет общий, чтобы чинить больше не пришлось. */
  it('breakpoints не используются нигде', () => {
    const нарушители = исходники
      // именно использование, а не упоминание: про запрет написано в комментариях
      .filter((f) => /breakpoints=\{|initialBreakpoint=\{/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители, 'перетаскивание за содержимое ломает прокрутку').toEqual([]);
  });
});
