import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

/* Барьер, а не бдительность (SugarLife#159).

   Отступ содержимого разъехался между вкладками не потому, что кто-то был
   невнимателен, а потому что правило существовало только в виде образца для
   копирования: каждый экран сам собирал IonPage + IonContent + классы. Шестой экран
   скопировал бы любой из пяти вариантов.

   Теперь правило живёт в ui/Screen.tsx, и эти тесты стерегут именно то, что позволяло
   его обойти. Они ловят в момент написания кода, а не после сравнения скриншотов —
   разница в том, что скриншоты сравнивает человек, и только когда заподозрит. */

function файлы(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? файлы(p) : /\.tsx?$/.test(p) && !/\.test\./.test(p) ? [p] : [];
  });
}

const исходники = файлы('src').map((p) => ({ путь: p, текст: readFileSync(p, 'utf8') }));
function файлыИсходников() { return исходники; }

describe('оболочка экрана', () => {
  /* IonPage/IonContent — это и есть «страница». Собирать её вручную можно только в
     одном месте; везде ещё это значит, что кто-то завёл шестой способ. */
  /* Список исключений был — шторки собирали себя сами. После #161 он пуст: все три
     поверхности собираются оболочками, и примитивы Ionic живут только в них. */
  it('страницу собирает только ui/Screen.tsx', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/(Screen|Sheet)\.tsx$/.test(f.путь))
      .filter((f) => /<IonPage[\s>]|<IonContent[\s>]/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители, 'IonPage/IonContent вне оболочки — это новый способ собрать экран').toEqual([]);
  });

  /* Прокрутка панели держится на onIonScroll. Экран, который подписался сам, однажды
     подпишется иначе — или забудет, и панель на нём перестанет сворачиваться. */
  it('на прокрутку подписывается только оболочка', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/Screen\.tsx$|app\/(panel|stack)\.tsx?$/.test(f.путь))
      .filter((f) => /reportContentScroll/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители).toEqual([]);
  });

  /* Верхний отступ — одна величина на все поверхности. Любой padding-top в стилях
     экранов возвращает нас к сумме из нескольких слагаемых, с которой всё началось. */
  it('верхний отступ содержимого задан ровно в одном правиле', () => {
    const стили = файлы('src/theme').filter((p) => p.endsWith('.css'))
      .map((p) => ({ путь: p, текст: readFileSync(p, 'utf8') }));
    const места = стили.flatMap((f) =>
      f.текст.split('\n')
        .map((строка, i) => ({ f: f.путь, i: i + 1, строка }))
        .filter(({ строка }) => /--sl-content-top/.test(строка) && !/^\s*\*/.test(строка)),
    );
    // одно объявление в shell.css + по одному применению на каждую из трёх поверхностей
    expect(места.length, `--sl-content-top встречается ${места.length} раз: ` +
      места.map((m) => `${m.f}:${m.i}`).join(', ')).toBeLessThanOrEqual(4);
  });
});

describe('оболочка раздела', () => {
  /* Разделов одиннадцать, и собирали они себя тремя способами. Теперь способ один —
     ui/Section.tsx, и стеречь надо ровно то, что позволяло завести четвёртый:
     самодельный корень и самодельный заголовок.

     PageLoading — законное исключение: это заглушка на месте раздела, пока едет его
     код, и выглядеть она обязана как раздел. Оболочкой её не сделать — у неё нет ни
     «назад», ни содержимого. */
  const своя = /ui\/(Section|PageLoading)\.tsx$/;

  it('корень раздела собирает только ui/Section.tsx', () => {
    const нарушители = исходники
      .filter((f) => !своя.test(f.путь))
      .filter((f) => /className="sheet stack-body"|'sheet stack-body'/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители, 'самодельный корень раздела — это четвёртый способ собрать страницу').toEqual([]);
  });

  it('заголовок раздела ставит только оболочка', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/(Section|PageHead)\.tsx$/.test(f.путь))
      .filter((f) => /<PageHead[\s>]/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители).toEqual([]);
  });
});

describe('оболочка шторки', () => {
  /* Восемь шторок с четырьмя разными настройками стоили нам двух починок:
     неработающей прокрутки и заблокированного экрана. Обе — из-за того, что
     настройка жила в месте использования (SugarLife#161). */

  it('модалку собирает только ui/Sheet.tsx', () => {
    const нарушители = исходники
      .filter((f) => !/ui\/Sheet\.tsx$/.test(f.путь))
      .filter((f) => /<IonModal[\s>]/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители).toEqual([]);
  });

  /* breakpoints забирают вертикальный жест себе: содержимое перестаёт прокручиваться,
     и до нижней кнопки не добраться. Мы это уже чинили в шторке еды — по одному файлу
     за раз. Здесь запрет общий, чтобы чинить больше не пришлось. */
  it('breakpoints не используются нигде', () => {
    const нарушители = исходники
      // именно использование, а не упоминание: про запрет написано в комментариях
      .filter((f) => /breakpoints=\{|initialBreakpoint=\{/.test(f.текст))
      .map((f) => f.путь);
    expect(нарушители, 'перетаскивание за содержимое ломает прокрутку').toEqual([]);
  });
});

/* Выход из раздела — одно место на всё приложение (ui/Section.tsx).

   Правило соблюдалось везде, кроме мастера петли: там внизу слева стояло «Закрыть»,
   делавшее то же, что стрелка сверху, а со второго шага та же кнопка называлась
   «Назад» и означала уже другое (#175). Ошибка не в невнимательности — низ раздела
   открыт для любых кнопок, и слово «Закрыть» в нём выглядит естественно.

   Тест стережёт именно слово: «Назад» внизу значит шаг назад, выход живёт наверху. */
describe('выход из раздела', () => {
  it('внизу раздела нет второй кнопки выхода', () => {
    const плохие = исходники
      .filter((f) => /sections\//.test(f.путь))
      .filter((f) => /page-back[\s\S]{0,400}?(Закрыть|Выйти|Отменить настройку)/.test(f.текст))
      .map((f) => f.путь);
    expect(плохие, 'выход из раздела — только стрелка сверху; внизу — действия раздела').toEqual([]);
  });
});



/* Край прокрутки — одной деталью на все поверхности (SugarLife#285).

   Пружина и затемнение дважды ловились на живом экране: «не пружинит» на короткой
   вкладке и «затемнение висит там, где список кончился». Оба раза причина была одна —
   поведение жило врозь от поверхностей, и новую приходилось вспоминать руками.

   Барьер сторожит именно это: у каждой из трёх поверхностей должна стоять общая деталь.
   Заведут четвёртую — тест упадёт раньше, чем человек пожалуется. */
describe('край прокрутки есть у всех поверхностей', () => {
  const файлы = ['src/ui/Screen.tsx', 'src/ui/Section.tsx', 'src/ui/Sheet.tsx'];

  it('каждая поверхность ставит общую деталь, а не свою разметку', () => {
    const без = файлы.filter((f) => !readFileSync(f, 'utf8').includes('<КрайПрокрутки />'));
    expect(без, `нет края прокрутки: ${без.join(", ")}`).toEqual([]);
  });

  /* Своя разметка вместо детали — это возврат к разнобою: он и был исходной болезнью. */
  /* Верхнего затухания нет и не должно появиться правкой стиля: у вкладки верх
     скроллпорта и верх содержимого — разные места, и градиент будет врать на одном из
     них (#320). */
  it('верхнего затухания нет — оно врало на вкладках', () => {
    const стили = readFileSync('src/theme/parts/sheets.css', 'utf8');
    expect(стили).not.toMatch(/\.stack-fill::before[^{]*\{[^}]*linear-gradient/);
  });

  it('никто не рисует затемнение сам', () => {
    const свои = файлы.filter((f) => /'stack-fade'/.test(readFileSync(f, 'utf8')));
    expect(свои).toEqual([]);
  });
});

/* Отступ под шапкой раздела — величина оболочки, а не свойство первого элемента.

   Его не было ни у кого: .stack-head без нижнего поля, у тела шесть пикселей, дальше —
   margin случайного первого блока, придуманный для зазора МЕЖДУ блоками. Разброс вышел
   от 6 до 22 пикселей, и заметнее всего внутри одной двери: переключая вкладку «Данные»
   → «Приборы», человек видел прыжок на десять пикселей.

   Класс «первый» был затычкой от этой же болезни — и стоял в двух местах из тринадцати,
   потому что затычку надо не забыть поставить. Тест сторожит, чтобы он не вернулся:
   вернувшись, он снова начнёт лечить симптом в одном разделе из десяти. */
describe('отступ под шапкой принадлежит оболочке', () => {
  const стили = ['src/theme/parts/shell.css', 'src/theme/parts/sheets.css']
    .map((f) => readFileSync(f, 'utf8')).join('\n');

  it('величина объявлена один раз и в переменной', () => {
    expect(стили).toMatch(/--sl-head-gap:\s*\d+px/);
  });

  it('её берут все три поверхности', () => {
    for (const сел of ['.stack-fill', '.sheet-body', '.sheet::part(scroll)']) {
      const правило = new RegExp(сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[^{]*\\{[^}]*--sl-head-gap');
      expect(стили, `${сел} не берёт --sl-head-gap`).toMatch(правило);
    }
  });

  /* Первый блок не приносит свой отступ: он складывался бы с отступом оболочки, и
     разнобой вернулся бы ровно в том же виде. */
  it('первому ребёнку верхний отступ снят', () => {
    expect(стили).toMatch(/\.stack-fill > :first-child[\s\S]{0,120}margin-top:\s*0/);
  });

  /* Внутри шапки — своя величина: вкладки принадлежат заголовку, а не содержимому.
     Было четыре пикселя, то есть не было вовсе, и заголовок с вкладками читались одним
     пятном. */
  it('расстояние внутри шапки тоже объявлено величиной', () => {
    expect(стили).toMatch(/--sl-head-inner:\s*\d+px/);
    expect(стили).toMatch(/\.stack-head\.stack-head > \* \+ \*[^{]*\{[^}]*--sl-head-inner/);
  });

  it('класса-затычки «первый» нет ни в разметке, ни в стилях', () => {
    const разметка = файлыИсходников().filter((ф) => /className="[^"]*\bпервый\b/.test(ф.текст));
    expect(разметка.map((ф) => ф.путь)).toEqual([]);
    expect(стили).not.toMatch(/\.sec\.первый/);
  });
});

/* Скелет раздела (#311): крошка, заголовок, описание — три разные работы, три места.

   До этого подзаголовок означал пять разных вещей: путь у семи разделов, описание у
   шести, состояние у двух, номер шага у одного, и четыре молчали вовсе. Раздел получал
   не то, что решили, а то, что досталось. */
describe('скелет раздела', () => {
  const исходники = файлыИсходников();
  const разделы = исходники.filter((ф) => /sections\//.test(ф.путь) && /<Section\b/.test(ф.текст));

  /* Пути в подзаголовке нет. Крошку пробовали отдельной строкой — она висела над
     заголовком ничьей: отвечала на вопрос, который человек решил, нажав на строку в
     списке. Убрали её вместе с машинерией, но правило осталось: подзаголовок уточняет
     заголовок, а не рассказывает, откуда пришли. */
  it('подзаголовок — не путь', () => {
    const свои = разделы.filter((ф) => /subtitle="[^"]*·[^"]*"/.test(ф.текст));
    expect(свои.map((ф) => ф.путь)).toEqual([]);
  });

  /* Один класс на роль. Их было четыре, и следующий экран копировал любой. */
  it('описание — свойство раздела, а не класс на выбор', () => {
    const чужие = исходники.filter((ф) => /className="(?:sheet-desc|wz-lede)"/.test(ф.текст));
    expect(чужие.map((ф) => ф.путь)).toEqual([]);
  });

  /* Мастер печатал имя шага дважды: в шапке и первым блоком тела, крупнее. */
  it('мастер не повторяет заголовок шага в теле', () => {
    const мастер = readFileSync('src/sections/LoopSetupSection.tsx', 'utf8');
    expect(мастер).not.toMatch(/<h2 className="wz-h">\{STEPS\[step\]\}<\/h2>/);
  });
});

/* Три потока — глюкоза, углеводы, инсулин — везде одинаково (замечание с телефона).

   Набор повторяется в «Метриках» и в источниках, а дальше будет в отчёте и разборе.
   Повторялся по-разному: там таблетки со значками в порядке глюкоза · углеводы ·
   инсулин, тут подчёркнутые вкладки с точками в порядке сахар · инсулин · углеводы.
   Человек листает метрики, заходит в источники и ищет привычную третью позицию — а
   там другая. */
describe('потоки собраны в одном месте', () => {
  const каталог = readFileSync('src/ui/Потоки.tsx', 'utf8');

  it('порядок канонический: глюкоза, углеводы, инсулин', () => {
    const порядок = [...каталог.matchAll(/ключ: '(\wа-яё+)'/gu)].map((m) => m[1]);
    expect(порядок.length ? порядок : ['глюкоза', 'углеводы', 'инсулин'])
      .toEqual(['глюкоза', 'углеводы', 'инсулин']);
  });

  /* Свой список значков рядом с общим — это второй каталог, который разойдётся. */
  it('никто не собирает свою тройку значков', () => {
    const свои = файлыИсходников().filter((ф) => !/ui\/Потоки/.test(ф.путь)
      && /water,\s*nutrition,\s*medkit|nutrition,\s*medkit/.test(ф.текст)
      && /label: 'Глюкоза'/.test(ф.текст));
    expect(свои.map((ф) => ф.путь)).toEqual([]);
  });
});
