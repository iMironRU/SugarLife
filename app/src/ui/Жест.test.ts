import { describe, it, expect } from 'vitest';
import { скорость, этоНаш, этоПрокрутка } from './Жест';

/* Жест — самое рискованное место замены Ionic (#405): ошибка здесь не падает и не видна в тестах
   экрана, она чувствуется пальцем как «через раз». Поэтому решения вынесены отдельными функциями. */

describe('чей это жест', () => {
  it('до порога не решаем ничего — страница листается как обычно', () => {
    expect(этоНаш(5, 0, 10)).toBe(false);
    expect(этоПрокрутка(0, 5, 10)).toBe(false);
  });

  it('вбок дальше порога — наш', () => {
    expect(этоНаш(12, 3, 10)).toBe(true);
    expect(этоПрокрутка(12, 3, 10)).toBe(false);
  });

  it('вниз дальше порога — прокрутка, и вмешиваться нельзя', () => {
    expect(этоПрокрутка(3, 12, 10)).toBe(true);
    expect(этоНаш(3, 12, 10)).toBe(false);
  });

  /* Ровно по диагонали жест не наш: перетянуть на себя спорное движение хуже, чем отдать его
     прокрутке — прокрутку человек делает в сто раз чаще. */
  it('диагональ отдаём прокрутке', () => {
    expect(этоНаш(12, 12, 10)).toBe(false);
    expect(этоПрокрутка(12, 12, 10)).toBe(true);
  });
});

describe('скорость', () => {
  it('пиксели в миллисекунду, со знаком', () => {
    expect(скорость(60, 200)).toBeCloseTo(0.3, 6);
    expect(скорость(-60, 200)).toBeCloseTo(-0.3, 6);
  });

  /* Два события в одну миллисекунду — обычное дело на быстром экране. Деления на ноль в жесте
     быть не должно: бесконечная скорость доводит страницу до края от дрожания пальца. */
  it('нулевое время — нулевая скорость, а не бесконечность', () => {
    expect(скорость(10, 0)).toBe(0);
  });
});
