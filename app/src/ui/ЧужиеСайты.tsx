import { чужиеСайтыНеСчитаются } from '@/показ/чужиеСайты';
import { ЧУЖИЕ_САЙТЫ_НЕ_СЧИТАЮТСЯ } from '@/слова/чужиеСайты';

/* Оговорка про чужие сайты — одним куском на все места, где показывается беда связи.

   Отдельным файлом, потому что мест три: «Сегодня», блок застоя и карточка прибора. Три копии
   одной мысли разошлись бы молча — ровно то, из-за чего у нас заведён слой слов. */
export default function ЧужиеСайты({ код }: { код?: string | null }) {
  if (!чужиеСайтыНеСчитаются(код)) return null;
  return <div className="застой-подсказка">{ЧУЖИЕ_САЙТЫ_НЕ_СЧИТАЮТСЯ}</div>;
}
