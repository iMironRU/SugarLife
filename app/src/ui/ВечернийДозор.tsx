import { useEffect, useRef } from 'react';
import { useSnapshot } from '@/sources/bridge';
import { notify } from '@/platform/notify';
import { прочитать, записать } from '@/settings/storage';
import { вечернийВопрос } from '@/показ/вечернийДозор';
import { послеПерезагрузки } from '@/показ/послеПерезагрузки';
import { порогМолчанияМин } from '@/показ/порогМолчания';

/* ДВА ПУТИ ОХРАНЫ, У КОТОРЫХ НЕТ СВОЕГО ЭКРАНА (#473, #477).

   Раздел «Охрана» отвечает тому, кто в него зашёл. А заходить в него незачем: пока всё работает,
   повода нет. Оба пути ниже — про то, чтобы человек узнал, НЕ ЗАХОДЯ.

   ВЕЧЕР: «разбудят ли этой ночью» — спрашиваем, пока он не спит. Разрешение, которого не хватает
   в три часа ночи, чинить некому.

   УТРО ПОСЛЕ ПЕРЕЗАГРУЗКИ: «ночью мониторинга не было». Единственный случай, когда нас выключает
   сама платформа и человек в этом не виноват.

   ПОЧЕМУ ОДИН КОМПОНЕНТ. Оба смотрят в один снимок, оба пишут отметку «уже сказали» и оба ничего
   не рисуют. Разводить их по двум местам значило бы дважды писать одну и ту же осторожность.

   РИСУЕМ НИЧЕГО. Это поверхность уведомления, а не экрана: человек в эту минуту на приложение не
   смотрит — в том и смысл. */

const КЛЮЧ_ВЕЧЕРА = 'sl.guard.evening.v1';
const КЛЮЧ_ПЕРЕЗАГРУЗКИ = 'sl.guard.reboot.v1';

export default function ВечернийДозор() {
  const снимок = useSnapshot();
  /* СКАЗАЛИ В ЭТОМ ЗАПУСКЕ — БОЛЬШЕ НЕ ГОВОРИМ, даже если запись на диск не удалась. Снимок
     приезжает раз в пять минут, и без этой памятки приватный режим браузера превратил бы одно
     уведомление в поток. */
  const сказаноВечером = useRef<string | null>(null);
  const сказаноПроРазрыв = useRef<number>(0);

  useEffect(() => {
    if (!снимок) return;

    const вечер = вечернийВопрос({
      сон: снимок.sleep,
      обещание: снимок.nightPromise,
      сейчас: Date.now(),
      спрашивалиЗа: сказаноВечером.current ?? прочитать(КЛЮЧ_ВЕЧЕРА),
    });
    if (вечер) {
      сказаноВечером.current = вечер.ключ;
      записать(КЛЮЧ_ВЕЧЕРА, вечер.ключ);
      void notify(вечер.заголовок, вечер.текст, 'охрана');
    }

    const отметка = Math.max(сказаноПроРазрыв.current, Number(прочитать(КЛЮЧ_ПЕРЕЗАГРУЗКИ)) || 0);
    const разрыв = послеПерезагрузки({
      история: снимок.guardHistory,
      сказаноПо: отметка,
      /* Ночной порог, а не дневной: разрыв случился, пока человек спал, и нарушено было именно
         ночное обещание — самое строгое из двух. */
      порогМолчанияМин: порогМолчанияМин(снимок.alarmRules, 'сон'),
    });
    if (разрыв) {
      сказаноПроРазрыв.current = разрыв.поМс;
      записать(КЛЮЧ_ПЕРЕЗАГРУЗКИ, String(разрыв.поМс));
      void notify(разрыв.заголовок, разрыв.текст, 'охрана');
    }
  }, [снимок]);

  return null;
}
