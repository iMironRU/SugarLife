import { useКрасноеВОхране } from '@/показ/охранаХук';
import { ОхранаSection, DiagnosticsSection, HealthSection, LoopSection, DataDevicesSection, AboutSection, AppearanceSection, PermissionsSection } from '@/sections/lazy';
import {
  optionsOutline, nutritionOutline,
  hardwareChipOutline, repeat, documentTextOutline, heartOutline, informationCircleOutline,
  colorPaletteOutline, shieldCheckmarkOutline, flashOutline, lockClosedOutline, phonePortraitOutline,
} from 'ionicons/icons';
import { useState, useEffect, useRef } from 'react';
import { resetLocalData } from '@/settings/reset';
import { unitLabel, useUnit, carbUnitLabel, useCarbUnit } from '@/domain/units';
import { useTheme } from '../theme/useTheme';
import { APP_EDITION, APP_VERSION, APP_BUILD, isNative } from '@/platform/appUpdate';
import { useStack } from '@/app/stackCtx';
import { разделИзАдреса } from '@/platform/deepLink';
import { прочитатьПрава, слушатьПрава } from '@/platform/права';
import { состояниеБаннера } from '@/platform/живойБаннер';
import { сводкаВключена } from '@/platform/живойБаннер';
import { состояниеЗначка } from '@/platform/значок';
import { подписьПоказа, type СостояниеПоказа } from '@/показ/подписьПоказа';
import { сколькоНеВПорядке, type ПунктНатива } from '@/показ/разрешения';
import { setTab } from '@/app/nav';
import { useSnapshot } from '@/sources/bridge';
import { useHealth } from '@/settings/health';
import { поВажности } from '@/domain/screenings';
import { useLoopProfile, LOOP_MODES } from '@/settings/loopProfile';
import { useDeviceConfig, deviceStatus } from '@/settings/deviceConfig';
import { pumpById, sensorById } from '@/domain/catalog';
import { useМодели } from '@/показ/модели';
import { взятьРазделыPro, type РазделPro } from '@/издание';
import Row from '@/ui/Row';
import UnitsModal from '@/sheets/UnitsModal';
import CarbUnitsModal from '@/sheets/CarbUnitsModal';
import Screen from '@/ui/Screen';

export default function Profile() {
  const красноеВОхране = useКрасноеВОхране();
  const { theme } = useTheme();
  const unit = useUnit();
  /* Список разрешений читаем здесь только ради цифры рядом со строкой: без неё раздел заметит
     лишь тот, кто уже пошёл его искать, — то есть тот, у кого уже что-то не сработало. */
  const [права, setПрава] = useState<ПунктНатива[] | null>(null);
  /* Состояние показа — ради подписи у входа (#556). Название двери говорит, ЧТО за ней настраивают;
     человек приходит с вопросом «почему я не вижу сахар на блокировке», и ответ на него — состояние,
     а не перечень возможностей. */
  const [показ, setПоказ] = useState<СостояниеПоказа>({ баннер: null, сводка: null, значок: null });
  const [unitsOpen, setUnitsOpen] = useState(false);
  const [carbUnitsOpen, setCarbUnitsOpen] = useState(false);
  const carbUnit = useCarbUnit();
  const { push, pop } = useStack();

  /* Входящий диплинк — открываем ИМЕННО ТОТ раздел, за которым шли (#315).

     Без этого ссылка ведёт «в приложение», человек попадает на «Сегодня» и начинает
     искать то, за чем пришёл, — то есть возвращаемся к совету, только длиннее.

     Слушаем здесь, а не в App.tsx: разделы открываются стеком профиля, и стек живёт тут.
     Открываем один раз на адрес: повторное событие того же адреса (система шлёт его при
     возврате из фона) не должно класть второй такой же экран поверх первого. */
  const открытоПо = useRef<string | null>(null);
  useEffect(() => {
    if (!isNative) return;
    let снять: (() => void) | null = null;
    void import('@capacitor/app').then(({ App }) => {
      App.addListener('appUrlOpen', ({ url }) => {
        if (открытоПо.current === url) return;
        const раздел = разделИзАдреса(url);
        if (!раздел) return;
        открытоПо.current = url;
        setTab(4);
        if (раздел === 'диагностика') push(<DiagnosticsSection onClose={pop} />, { id: 'диагностика' });
        else push(<DataDevicesSection onClose={pop} вкладка="приборы" />, { id: 'приборы', вкладка: 'приборы' });
      }).then((h) => { снять = () => void h.remove(); });
    });
    return () => { снять?.(); };
    /* eslint-disable-next-line react-hooks/exhaustive-deps */
  }, []);
  /* Издание берём у движка, а не у константы сборки (#298, #294). Константа говорит, чем
     нас собрали, движок — что внутри на самом деле. Для обновления важно второе: релиз
     выпускает Lite, и предлагать его сборке Pro значит поставить рядом второе приложение
     вместо обновления. */
  const снимок = useSnapshot();
  const издание = снимок?.edition ?? 'lite';


  const reset = () => {
    if (!window.confirm('Сбросить настройки? С этого устройства будут удалены облака, записанные устройства и локальная история глюкозы.')) return;
    resetLocalData();
    location.reload();
  };


  /* Что записано в устройствах — коротко, для строки-входа. Названия моделей, а не
     «настроено»: человек проверяет глазами свою помпу и свой сенсор, а слово
     «настроено» одинаково выглядит и когда всё верно, и когда записана не та модель. */
  const devCfg = useDeviceConfig();
  const модели = useМодели();
  /* Разделы издания Pro (#296, #294). Условий два, и они о разном: СБОРКА решает, есть ли код вовсе
     (в Lite ветка до сборки не доживает), ДВИЖОК — умеет ли он подавать. Pro-бандл поверх
     lite-движка показал бы пульт помпы, за которым нет тракта записи, — кнопку, которой нечем
     исполнить команду прибору, вводящему инсулин. */
  const [проРазделы, setПроРазделы] = useState<РазделPro[]>([]);
  useEffect(() => { void взятьРазделыPro(издание).then(setПроРазделы); }, [издание]);
  /* Перечитываем при возвращении на экран: человек мог уйти в настройки телефона и что-то там
     поменять — цифра, оставшаяся прежней, сказала бы, что это не помогло. */
  useEffect(() => {
    const спросить = () => {
      void прочитатьПрава().then(setПрава);
      void Promise.all([состояниеБаннера(), сводкаВключена(), состояниеЗначка()])
        .then(([б, св, зн]) => setПоказ({
          баннер: б ? б.включён : null,
          сводка: св,
          значок: зн ? зн.вид : null,
        }));
    };
    спросить();
    const слушатель = () => { if (document.visibilityState === 'visible') спросить(); };
    document.addEventListener('visibilitychange', слушатель);
    /* И на ответ системного диалога: цифра у входа должна гаснуть в тот же миг, когда человек
       нажал «Разрешить», а не при следующем открытии экрана (#558). */
    const отписаться = слушатьПрава(setПрава);
    return () => {
      document.removeEventListener('visibilitychange', слушатель);
      отписаться();
    };
  }, []);
  const устройства = [pumpById(модели.pumpId)?.model, sensorById(модели.sensorId)?.name]
    .filter(Boolean).join(' · ') || 'ничего не записано';
  /* Справа — только то, что требует действия. Строка молчит, пока всё в порядке:
     постоянная надпись «настроено» перестаёт читаться, и «нужен мост» рядом с ней
     пропадёт вместе со всеми остальными. */
  const нуженМост = deviceStatus('pump', devCfg) === 'needsBridge'
    || deviceStatus('sensor', devCfg) === 'needsBridge';

  const loop = useLoopProfile();
  const loopMode = LOOP_MODES.find((m) => m.id === loop.mode);
  /* Подпись у «Здоровья» — то, что требует действия, и ничего больше. Список
     обследований со сроками длинный, а на строке помещается одно слово: пусть это
     будет число просроченного, а не бодрое «всё в порядке» (#156). */
  const здоровье = useHealth();
  const просрочено = поВажности(здоровье.проверки, Date.now(), здоровье.дебют)
    .filter((с) => с.состояние === 'просрочено').length;
  const здоровьеПодпись = просрочено
    ? `вышел срок: ${просрочено} ${просрочено === 1 ? 'проверка' : просрочено < 5 ? 'проверки' : 'проверок'}`
    : 'вес, давление, анализы, обследования';

  const loopSub = loop.savedAt
    ? `${loopMode?.code} · ${loopMode?.name.toLowerCase()}`
    : 'не настроен';

  return (
    <Screen tab={4}>
          {/* Шапки с именем и тройки показателей здесь больше нет — по трём разным
              причинам, и ни одна не про экономию места.

              GMI и средний сахар живут в «Метриках», где у них есть период. Здесь они
              считались по тому, что держит стор для главного экрана, — по последним
              288 точкам, то есть примерно за сутки, и подпись об этом молчала. GMI за
              сутки — не оценка HbA1c ничем, кроме названия; человек же сравнивает эту
              цифру с анализом из лаборатории. Дубль был не только лишним, но и хуже
              оригинала.

              СУИ приезжает из профиля Nightscout: с нативным ядром или без облака его
              просто нет, и на его месте стоял бы прочерк. А там, где он действительно
              нужен, он и так виден — в строке болюса при вводе еды.

              Имя и «Замкнутый цикл · Nightscout» — то же самое: имя берётся из профиля
              Nightscout, без него в аватаре стояло бы слово «Профиль». Тип терапии
              виден в устройствах, источник — в облаках.

              Когда появятся мульти-профили, переключатель вернётся сюда настоящим
              элементом управления, а не подписью под аватаром. */}

          {/* Порядок разделов — по тому, зачем сюда заходят, а не по тому, что важнее
              звучит. Приходят посмотреть: на связи ли облако, что вообще подключено,
              какая петля настроена. Единицы глюкозы меняют один раз в жизни, но они
              стояли первыми и отодвигали вниз всё, ради чего экран открывают.

              Поэтому сверху то, что работает, ниже — настройки. Диагностика, версия и
              оформление в конце: туда идут по конкретному поводу и заранее знают, что
              ищут.

              Заголовков над КАЖДОЙ строкой было три — «Устройства», «Сервисы»,
              «Алгоритм», — и каждый повторял название единственной строки под собой.
              Их убрали правильно: заголовок нужен, когда собирает разнородное под общим
              смыслом, а над одной строкой он только отнимает высоту и разбивает на три
              куска то, что глазом читается как один список входов.

              А вот общего заголовка не хватало, и это было видно раньше, чем понятно:
              у всех остальных блоков он есть, и глаз читает ритм «заголовок — блок».
              Первый блок из ритма выпадал, и экран казался слегка сломанным (#212).

              «Что настроено» вместо «Моё хозяйство»: второе звучало по-домашнему там,
              где речь о приборах, подающих инсулин. Заголовок собирает разное —
              устройства, облака, правила счёта, здоровье — и отвечает на общий для них
              вопрос: что здесь уже настроено и требует присмотра.

              Границу ЧТО (устройства) и КАК (сервисы) из docs/CONNECT-UX.md §10 это не
              трогает: разделы разные, входы разные, рядом стоят только строки. */}
          <div className="section-label sec">Что настроено</div>
          <div className="list">
            {/* Подпись — то, что записано на самом деле. Заголовок перечисляет, что
                внутри раздела, и на вопрос «а что у меня подключено» не отвечал: за
                ответом надо было открывать. Самый быстрый взгляд — тот, ради которого
                никуда не переходят. */}
            {/* Одна дверь в хозяйство вместо трёх (#279): источники, приборы и облака
                лежали порознь, и человеку приходилось выбирать дверь до того, как он
                понял, что ищет. Внутри — две вкладки, потому что вопросы разные. */}
            <Row icon={hardwareChipOutline} title="Устройства и данные"
              sub={устройства} value={нуженМост ? 'нужен мост' : undefined}
              onClick={() => push(<DataDevicesSection onClose={pop} />, { id: 'приборы' })} />
            {/* профиль петли: только настройка — подача не включается (решение 0004) */}
            <Row icon={repeat} title="Петля" sub={loopSub}
              onClick={() => push(<LoopSection onClose={pop} />, { id: 'петля' })} />
            {/* Здоровье — рядом с железом и петлёй по той же причине: это «моё,
                работающее», просто не про приборы, а про то, что знает сам человек
                и записывает врач (#156). */}
            <Row icon={heartOutline} title="Здоровье" sub={здоровьеПодпись}
              onClick={() => push(<HealthSection onClose={pop} />, { id: 'здоровье' })} />
            {/* Охрана — единственный вход в тему «разбудят ли этой ночью» (#473). Пороги,
                сторож молчания, разрешения и проверочная тревога — всё внутри. */}
            {/* ЦИФРА ГОВОРИТ, ГДЕ ИСКАТЬ КРАСНОЕ (#523). Без неё человек угадывает, в каком разделе
                беда: список выглядит одинаково спокойным и когда всё в порядке, и когда ночью нас
                не услышат. Считает её тот же хук, что рисует сам раздел, — одно число, один
                источник. */}
            <Row icon={shieldCheckmarkOutline} title="Охрана"
              sub="разбудим ли этой ночью и что этому мешает"
              бейдж={красноеВОхране || undefined}
              onClick={() => push(<ОхранаSection onClose={pop} />, { id: 'охрана' })} />
            {/* Тревог отдельной строкой здесь БОЛЬШЕ НЕТ (#473): два входа в одну тему
                заставляли человека гадать, где искать ответ «разбудят ли». Пороги живут
                внутри «Охраны» — там, где сказано, услышим ли мы их вообще. */}
          </div>

          {/* настройки */}
          {проРазделы.length > 0 && (
        <>
          <div className="section-label sec">Управление подачей</div>
          <div className="list">
            {проРазделы.map((р) => (
              <Row key={р.id} icon={flashOutline} title={р.название}
                sub="издание Pro: команды помпе"
                onClick={() => push(<р.Экран onClose={pop} />, { id: 'pro', раздел: р.id })} />
            ))}
          </div>

        </>
      )}

          {/* ОФОРМЛЕНИЕ — СРАЗУ ПОД «ЧТО НАСТРОЕНО» (замечание владельца).

              Раздел стоял предпоследним, ниже диагностики. То есть «что видно на экране
              блокировки» — вещь, которую смотрят каждый день, — лежало под «логами работы»,
              которые открывают раз в полгода, когда что-то сломалось. Порядок был обратен
              частоте. */}
          {/* ДВА ВХОДА ВМЕСТО ОДНОГО (решение владельца).

              Была одна строка «Тема», а за ней — баннер на экране блокировки, сводка в шторке,
              цифры на значке, тема, палитра и язык. Слово на двери оказалось меньше того, что за
              дверью: человек, который ищет, где включить баннер, по слову «Тема» туда не пойдёт.

              Экран остался один — это по-прежнему «Оформление», и решение из #500 держать показ
              вместе с видом мы не отменяем. Разошлись только входы, потому что вопросов за дверью
              два и приходят с ними по отдельности: «что я вижу, не открывая приложение» и «как
              выглядит само приложение». */}
          <div className="section-label sec">Оформление</div>
          <div className="list">
            <Row icon={phonePortraitOutline} title="Экран блокировки и значок"
              sub={подписьПоказа(показ)}
              onClick={() => push(<AppearanceSection onClose={pop} часть="показ" />,
                { id: 'оформление', часть: 'показ' })} />
            <Row icon={colorPaletteOutline} title="Вид приложения"
              sub={theme === 'system' ? 'тема как в настройках телефона · язык, палитра'
                : (theme === 'light' ? 'светлая тема' : 'тёмная тема') + ' · язык, палитра'}
              onClick={() => push(<AppearanceSection onClose={pop} часть="вид" />,
                { id: 'оформление', часть: 'вид' })} />
            {/* ЕДИНИЦЫ — ЗДЕСЬ ЖЕ, А НЕ СВОИМ РАЗДЕЛОМ (решение владельца).

                Вопрос владельца звучал с сомнением — «единицы это тоже оформление даже?» — и
                сомнение уместное. Но по делу да: ммоль и мг/дл не меняют ни одного записанного
                числа, только то, как оно прочитается, — ровно это и написано в самой шторке
                единиц. Рядом уже стоит язык, а язык и единицы — одно и то же по сути: на чём
                приложение с человеком разговаривает, словами и числами.

                Двух строк под своим заголовком они не стоили: заголовок «Единицы» над двумя
                строками — это оглавление длиной с содержание. */}
            <Row icon={optionsOutline} title="Единицы глюкозы" value={unitLabel(unit)} onClick={() => setUnitsOpen(true)} />
            <Row icon={nutritionOutline} title="Единицы еды" value={carbUnitLabel(carbUnit)} onClick={() => setCarbUnitsOpen(true)} />
          </div>

      {/* Про хранение. Стояло рядом с выгрузкой в CSV и объясняло, почему она
              вообще есть; выгрузка ушла (данные выносит бэкап движка), а строка
              осталась — вопрос «где лежат мои данные» от этого не исчез. */}
          <div className="metric-note" style={{ marginTop: 14 }}>
            Данные хранятся только на этом устройстве, без облака и аккаунта.
          </div>

          {/* Диагностика — в глубине, а не на виду: человеку с диабетом она нужна раз в
              полгода, когда что-то не работает, и место на главном занимать не должна.
              Но найти её надо уметь быстро, поэтому рядом с «о приложении», где и так
              ищут версию и обновление (SugarLifeCore#17). */}
          <div className="section-label sec">Диагностика</div>
          <div className="list">
            <Row icon={documentTextOutline} title="Логи работы"
              sub="уровень подробности, запись в файл, выгрузка"
              onClick={() => push(<DiagnosticsSection onClose={pop} />, { id: 'диагностика' })} />
          </div>

          {/* о приложении: версия + сборка + обновление */}
          {/* «О приложении» — отдельный раздел (замечание с телефона).

              Плашка внизу Профиля показывала одну сборку из двух и звала «Обновиться»
              кнопку, которая сначала спрашивает сервер. Обе неправды исправлены внутри
              раздела; здесь остаётся вход и то, что человек проверяет чаще всего —
              какая версия стоит. */}

          {/* РАЗРЕШЕНИЯ — РЯДОМ С «О ПРИЛОЖЕНИИ», А НЕ В ОФОРМЛЕНИИ (#538).

              Это не настройка вида и не настройка поведения: это инвентарь того, что телефон нам
              позволил. Сюда идут с вопросом «почему не сработало» — то есть примерно тогда же,
              когда открывают «О приложении», чтобы посмотреть версию. Цифра рядом показывает, есть
              ли о чём говорить, — иначе строку заметят только те, кто уже ищет. */}
          {права !== null && (
            <>
              <div className="section-label sec">Доступ</div>
              <div className="list">
                <Row icon={lockClosedOutline} title="Разрешения"
                  sub="что мы просили у телефона и что нам дали"
                  бейдж={сколькоНеВПорядке(права) || undefined}
                  onClick={() => push(<PermissionsSection onClose={pop} />, { id: 'разрешения' })} />
              </div>
            </>
          )}

          <div className="section-label sec">О приложении</div>
          <div className="list">
            <Row icon={informationCircleOutline}
              title={`${издание === 'pro' ? 'SugarLife.Pro' : APP_EDITION} ${APP_VERSION}`}
              sub={`сборка ${APP_BUILD}${isNative ? ' · нативное' : ' · PWA'}`}
              onClick={() => push(<AboutSection onClose={pop} />, { id: 'оПриложении' })} />
          </div>

          {/* оформление */}
          <button className="logout" onClick={reset}>Сбросить настройки</button>

        <UnitsModal isOpen={unitsOpen} onClose={() => setUnitsOpen(false)} />
        <CarbUnitsModal isOpen={carbUnitsOpen} onClose={() => setCarbUnitsOpen(false)} />
    </Screen>
  );
}
