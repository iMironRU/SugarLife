import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

/* Чужого кода в дереве быть не должно (#439).

   Двадцать две тысячи строк из JugglucoNG под GPL-3.0 пролежали в нашем публичном
   MIT-репозитории и уехали в опубликованный APK. Приехали они внутри коммита про
   уведомления: шестьдесят строк по делу и двадцать две тысячи — попутно. Я читал диф по
   тому файлу, ради которого коммит делался, и списка файлов целиком не посмотрел.

   Решение владельца записано: калибровка нужна ему ЛИЧНО — для сверки в реальном времени
   и часовых проверок на телефоне. В публичное она не уходит никогда.

   Правило теперь стережёт машина, а не внимательность человека. Внимательность уже
   показала, чего она стоит на коммите в двадцать две тысячи строк: чем крупнее чужое
   вложение, тем легче оно проходит — большой диф не читают, его пролистывают.

   Ловим по МЕСТУ и по СОДЕРЖИМОМУ: каталог могут назвать иначе, а вот строчка про
   GPL в заголовке файла переживает переименование. */

/* НО СЛОВО «GPL» И ЛИЦЕНЗИЯ GPL — РАЗНЫЕ ВЕЩИ (#436).

   Первая версия сторожа валила любое упоминание — и первым делом поймала наши
   собственные файлы, где написано ровно противоположное: «сам алгоритм чужой, лежит
   под GPL-3.0, в нашем дереве его нет». Сторож, который наказывает за честное
   объяснение, учит не объяснять; следующий человек просто уберёт комментарий, и мы
   потеряем единственное место, где сказано, откуда взялась эта строка кода.

   Поэтому две ступени.

   1. ЛИЦЕНЗИОННАЯ ШАПКА — всегда нарушение, без исключений. Её узнают по формуле
      разрешения, а не по названию лицензии: «this program is free software»,
      «redistribute it and/or modify», SPDX-метка. Скопированный файл приносит эту
      формулу с собой — она и есть то, чем лицензия выдаётся.
   2. ПРОСТО УПОМИНАНИЕ — нарушение, если рядом нет явной расписки. Расписка одна и
      пишется от руки: строка «ЧУЖОГО КОДА ЗДЕСЬ НЕТ». Чужой файл её не принесёт
      никогда — она на русском и её надо написать самому, то есть посмотреть на файл
      и ответить за него. Ровно то действие, которого не хватило в тот раз. */

const РАСПИСКА = 'ЧУЖОГО КОДА ЗДЕСЬ НЕТ';

/* Формула выдачи лицензии, а не имя лицензии. Списано с шапок GPL-файлов: они все
   начинаются одинаково, потому что текст рекомендован самой лицензией. */
const ШАПКА = [
  /SPDX-License-Identifier:\s*[^\n]*GPL/i,
  /this program is free software/i,
  /redistribute it and\/or modify/i,
  /under the terms of the GNU/i,
  /either version [23]/i,
];
const УПОМИНАНИЕ = [/GNU GPL/i, /GPL-[23]\.0/i, /General Public License/i];

export type Приговор = 'шапка' | 'упоминание' | 'чисто';

export function приговор(голова: string): Приговор {
  if (ШАПКА.some((м) => м.test(голова))) return 'шапка';
  if (УПОМИНАНИЕ.some((м) => м.test(голова)) && !голова.includes(РАСПИСКА)) return 'упоминание';
  return 'чисто';
}

const КОРЕНЬ = join(process.cwd(), '..');
/* Только ИСХОДНИКИ. В каталогах сборки лежат скомпилированные пакеты с тем же именем, и
   проверка падала бы на машине, где недавно собирали, — то есть у того, кто работает. */
const ЗАПРЕЩЁННЫЕ_КАТАЛОГИ = [
  'app/android/app/src/main/java/ru/imiron/sugarlife/vendor',
  'app/ios/App/App/vendor',
];

/* Где ищем чужие лицензии. Только наш исходный код: в node_modules чужого кода полно, и
   он там законно — вопрос в том, что уезжает в НАШУ сборку. */
const ГДЕ_ИСКАТЬ = ['app/android/app/src', 'app/ios/App/App', 'app/src'];

/* СМОТРИМ НА ТО, ЧТО ЗНАЕТ GIT, А НЕ НА ДИСК.

   Сторож искал по файловой системе — и краснел на машине владельца. У него лежит скачанная
   вендорская калибровка: она нужна ему ЛИЧНО, для сверки в реальном времени, и каталог для неё
   стоит в .gitignore. То есть в репозиторий эти файлы не попадут никак, а тест всё равно валился.

   Это хуже, чем кажется. Сторож, который краснеет на законном, учит не смотреть на красное — и
   в тот день, когда он поймает настоящее, его пролистают вместе с привычным. Проверка, которую
   принято игнорировать, защищает хуже отсутствующей: она ещё и создаёт уверенность.

   Беда, ради которой сторож заведён, — чужой код В РЕПОЗИТОРИИ (двадцать две тысячи строк под
   GPL-3.0 в публичном MIT-дереве). Момент, когда это происходит, — файл становится отслеживаемым.
   Его и стережём. Каталог в .gitignore этой границы не пересекает по определению. */
function отслеживаемые(): string[] {
  try {
/* --full-name обязателен: без него git отдаёт пути ОТНОСИТЕЛЬНО текущего каталога, то есть
       с «../», и ни один префикс из списков ниже не совпал бы. Проверено выводом, а не памятью. */
    return execFileSync('git', ['ls-files', '-z', '--full-name', '--', '..'],
      { encoding: 'utf8', cwd: process.cwd() })
      .split('\0').filter(Boolean);
  } catch (e) {
    /* Молча пропустить нельзя: сторож, который при поломке отвечает «нарушений нет», — это худший
       из возможных исходов. Пусть падает и называет причину. */
    throw new Error('сторож чужого кода не смог спросить git: ' + String(e));
  }
}

describe('сторож отличает лицензию от разговора о ней', () => {
  /* Шапка настоящего GPL-файла — то, что приезжает вместе со скопированным кодом. */
  it('лицензионная шапка — нарушение, даже с распиской', () => {
    const шапка = `/*
 * Copyright (C) 2023 someone
 * This program is free software: you can redistribute it and/or modify
 * it under the terms of the GNU General Public License, either version 3.
 * ${РАСПИСКА}
 */`;
    expect(приговор(шапка)).toBe('шапка');
  });

  it('SPDX-метка ловится тоже', () => {
    expect(приговор('// SPDX-License-Identifier: GPL-3.0-or-later')).toBe('шапка');
  });

  /* Ровно наш случай: файл объясняет, что чужого кода в нём нет. */
  it('объяснение с распиской проходит', () => {
    expect(приговор(`/* Алгоритм портирован в JugglucoNG и лежит под GPL-3.0.
       В нашем дереве его нет — скачивается скриптом. ${РАСПИСКА}. */`)).toBe('чисто');
  });

  /* Без расписки — молчаливое упоминание. Может быть честным, а может быть остатком
     шапки, которую кто-то подчистил. Разбираться должен человек, а не сторож. */
  it('упоминание без расписки — нарушение', () => {
    expect(приговор('/* портировано из JugglucoNG, GPL-3.0 */')).toBe('упоминание');
  });

  it('обычный файл чист', () => {
    expect(приговор('export function сумма(a: number, b: number) { return a + b; }')).toBe('чисто');
  });
});

describe('чужого кода в дереве нет', () => {
  it('в запрещённых каталогах нет ни одного отслеживаемого файла', () => {
    const все = отслеживаемые();
    const найдены = ЗАПРЕЩЁННЫЕ_КАТАЛОГИ.filter((к) => все.some((f) => f.startsWith(к + '/')));
    expect(найдены).toEqual([]);
  });

  it('в исходниках нет файлов под GPL', () => {
    const нарушители: string[] = [];
    /* Тоже по отслеживаемым, и по той же причине. Заодно ушёл обход дерева руками: git и так
       знает список, а `readdirSync` спускался в каталоги сборки и в чужие копии. */
    const исходники = отслеживаемые().filter((f) => ГДЕ_ИСКАТЬ.some((где) => f.startsWith(где + '/')));
    {
      for (const отн of исходники) {
        const f = join(КОРЕНЬ, отн);
        if (f.endsWith('чужойКод.test.ts')) continue;
        /* Читаем только начало: лицензия живёт в шапке, а файлы бывают на двадцать тысяч
           строк — читать их целиком значит сделать тест, который никто не станет ждать. */
        let голова = '';
        try { голова = readFileSync(f, 'utf8').slice(0, 4000); } catch { continue; }
        const п = приговор(голова);
        if (п !== 'чисто') нарушители.push(`${f.replace(КОРЕНЬ, '')} (${п})`);
      }
    }
    expect(нарушители).toEqual([]);
  });
});
