import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/* НАПРАВЛЕНИЕ ЗАВИСИМОСТЕЙ МЕЖДУ СЛОЯМИ (#407, #324).

   Слои у нас такие, и стрелки идут сверху вниз:

     screens / sections / sheets / ui   — как нарисовать
     показ/                             — что и в каком порядке показать
     слова/                             — как это назвать
     domain/                            — что происходит

   Правило одно: НИЖНИЙ СЛОЙ НЕ ЗНАЕТ О ВЕРХНЕМ. Домен не спрашивает у показа, показ не
   спрашивает у экранов. Стоит стрелке развернуться — и правило перестаёт быть проверяемым
   без запуска интерфейса, а формулировка перестаёт правиться без риска для расчёта.

   Ловим это тестом, а не договорённостью, потому что нарушается оно не злым умыслом:
   пишешь функцию в домене, ей нужна подпись — и рука сама тянется импортировать готовую.
   Так `картаПрибора` и оказался в домене: не решением, а по одному импорту за раз.

   Слова из этого правила исключены НАМЕРЕННО: домену иногда нужно назвать состояние
   (например, чтобы сложить строку журнала), и запрет здесь означал бы дублирование
   словаря. Слова ничего не знают ни о снимке, ни о экране — они безопасны в любую
   сторону. */

const КОРЕНЬ = join(process.cwd(), 'src');

/** Кто над кем: слой → слои, которые ему запрещено импортировать. */
const НЕЛЬЗЯ: Record<string, string[]> = {
  domain: ['показ', 'ui', 'sections', 'sheets', 'screens', 'charts'],
  показ: ['ui', 'sections', 'sheets', 'screens', 'charts'],
  слова: ['показ', 'domain', 'ui', 'sections', 'sheets', 'screens', 'charts', 'sources', 'settings'],
};

function файлы(dir: string): string[] {
  try {
    return readdirSync(dir).flatMap((n) => {
      const p = join(dir, n);
      return statSync(p).isDirectory() ? файлы(p) : [p];
    });
  } catch { return []; }
}

/* Что этот файл импортирует — только имена слоёв из псевдонима `@/`, и только ЗНАЧЕНИЯ.

   `import type` не в счёт, и это не поблажка. Полнота словаря держится типом:
   `Record<Связь, string>` не даст забыть случай, а `Связь` живёт в домене — там, где
   состояние и появляется. Тип исчезает при сборке и ничего за собой не тянет; запретив
   его, мы получили бы вторую копию перечисления в слое слов и разошлись бы на первом же
   новом состоянии. Опасен импорт КОДА: он тащит за собой поведение. */
function импорты(файл: string): string[] {
  const текст = readFileSync(файл, 'utf8');
  const найдено: string[] = [];
  for (const м of текст.matchAll(/^import\s+(type\s+)?[^;]*?from\s+'@\/([^/']+)/gm)) {
    if (!м[1]) найдено.push(м[2]);
  }
  return найдено;
}

describe('слои знают только о тех, кто ниже', () => {
  for (const [слой, запрещено] of Object.entries(НЕЛЬЗЯ)) {
    it(`${слой}/ не импортирует ${запрещено.join(', ')}`, () => {
      const нарушители: string[] = [];
      for (const f of файлы(join(КОРЕНЬ, слой))) {
        if (!f.endsWith('.ts') && !f.endsWith('.tsx')) continue;
        /* Тесты не в счёт: тест показа вправе взять образец из домена, чтобы собрать
           входные данные, и это не зависимость слоя, а оснастка проверки. */
        if (f.endsWith('.test.ts') || f.endsWith('.test.tsx')) continue;
        for (const и of импорты(f)) {
          if (запрещено.includes(и)) нарушители.push(`${f.replace(КОРЕНЬ, '')} → @/${и}`);
        }
      }
      expect(нарушители).toEqual([]);
    });
  }
});
