import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/* ФРАЗ ЧЕЛОВЕКУ В ДОМЕНЕ БОЛЬШЕ НЕ СТАНОВИТСЯ (#324).

   Рядом стоит `слои.test.ts` — он ловит стрелку зависимости, развёрнутую вверх. Но текст в домене
   он не видит: файл, который сам держит свои формулировки, ничего не импортирует и правило не
   нарушает. А беда та же самая — правку слова нельзя сделать, не тронув расчёт, и расчёт нельзя
   проверить тестом, не сверяя буквы.

   ЭТО ХРАПОВИК, А НЕ ЗАПРЕТ. Утверждать «в домене фраз нет» было бы неправдой: часть из
   оставшихся — справочники (перечень обследований, что нужно вендорскому аккаунту, подписи
   параметров драйвера), и там название — это данные, а не формулировка интерфейса. Разбирать их
   надо по одному и с решением на каждый, а не сносить разом.

   Поэтому тест не запрещает, а фиксирует: столько-то и ни фразой больше. Добавили текст в домен —
   тест упал, и это повод спросить себя, туда ли он лёг. Убрали — тест тоже упал, и это повод
   опустить число: иначе долг «уменьшается» только на словах.

   ЧТО СЧИТАЕМ ФРАЗОЙ. Сначала выбрасываем подстановки `${…}`: без этого ключ кэша
   `${days}|${час}|${отметки}` считался фразой человеку, хотя человек его не видит никогда. То, что
   осталось, — фраза, если в нём есть кириллица, пробел и больше восемнадцати знаков.

   Ключи состояний («нет записи», «мост молчит») в счёт не попадают по длине — и правильно: это
   словарь домена, тот самый, который слой слов и называет. */

const КОРЕНЬ = join(process.cwd(), 'src');

/* Сколько фраз сейчас в каждом файле. Список закрытый: файла нет в нём — значит фраз быть не
   должно вовсе. */
const БЮДЖЕТ: Record<string, number> = {
  // ——— справочники: там название это данные, а не формулировка интерфейса ———
  'screenings.ts': 15,          // перечень обследований и цитаты из клинических рекомендаций
  'requirementsCatalog.ts': 11, // что нужно вендорскому аккаунту
  'driverParams.ts': 4,         // подписи параметров драйвера, слово в слово от ядра
  'battery.ts': 3,              // как ведёт себя кривая разряда у типа батарейки
  'visitNote.ts': 3,            // целевые коридоры по возрасту и рискам
  'catalog.ts': 1,
  'catalogSupport.ts': 1,

  // ——— долг: это формулировки для показа, и место им слоем выше ———
  'deviceLog.ts': 4,
  'foodNow.ts': 3,
  'сырое.ts': 3,
  'loopValue.ts': 2,
  'sourceStatus.ts': 2,
  'cloudAccounts.ts': 1,
  'longInsulin.ts': 1,
  'mealNaming.ts': 1,
  'история.ts': 1,
};

/** Строковые литералы файла — без комментариев, с учётом экранирования. */
function литералы(текст: string): string[] {
  const найдено: string[] = [];
  let i = 0;
  while (i < текст.length) {
    const c = текст[i];
    if (c === '/' && текст[i + 1] === '*') {
      const j = текст.indexOf('*/', i + 2);
      i = j < 0 ? текст.length : j + 2;
      continue;
    }
    if (c === '/' && текст[i + 1] === '/') {
      const j = текст.indexOf('\n', i);
      i = j < 0 ? текст.length : j + 1;
      continue;
    }
    if (c === '\'' || c === '"' || c === '`') {
      let j = i + 1;
      const буфер: string[] = [];
      while (j < текст.length) {
        if (текст[j] === '\\') { j += 2; continue; }
        if (текст[j] === c) break;
        буфер.push(текст[j]);
        j += 1;
      }
      найдено.push(буфер.join(''));
      i = j + 1;
      continue;
    }
    i += 1;
  }
  return найдено;
}

function фразаЧеловеку(с: string): boolean {
  const без = с.replace(/\$\{[^}]*\}/g, '');
  return /[А-Яа-яЁё]/.test(без) && без.trim().includes(' ') && без.length > 18;
}

function файлы(dir: string): string[] {
  try {
    return readdirSync(dir).flatMap((n) => {
      const p = join(dir, n);
      return statSync(p).isDirectory() ? файлы(p) : [p];
    });
  } catch { return []; }
}

describe('фразы человеку в domain/', () => {
  const счёт = new Map<string, number>();
  for (const f of файлы(join(КОРЕНЬ, 'domain'))) {
    if (!f.endsWith('.ts') || f.endsWith('.test.ts')) continue;
    const n = литералы(readFileSync(f, 'utf8')).filter(фразаЧеловеку).length;
    if (n > 0) счёт.set(f.split('/').pop() as string, n);
  }

  it('в новом файле домена фраз человеку не заводим', () => {
    const новые = [...счёт.keys()].filter((имя) => !(имя in БЮДЖЕТ));
    expect(новые, 'слова этих состояний — в слова/, а не тут').toEqual([]);
  });

  it('в известных файлах фраз не прибавилось', () => {
    const выросли = [...счёт.entries()]
      .filter(([имя, n]) => имя in БЮДЖЕТ && n > БЮДЖЕТ[имя])
      .map(([имя, n]) => `${имя}: было ${БЮДЖЕТ[имя]}, стало ${n}`);
    expect(выросли).toEqual([]);
  });

  /* Долг обязан уменьшаться видимо. Разобрали файл, а число оставили прежним — и следующий
     читатель решит, что там всё ещё стоит текст, которого давно нет. */
  it('бюджет не отстал от правды', () => {
    const отстали = Object.entries(БЮДЖЕТ)
      .filter(([имя, n]) => n - (счёт.get(имя) ?? 0) > 2)
      .map(([имя, n]) => `${имя}: в бюджете ${n}, на деле ${счёт.get(имя) ?? 0} — опустите число`);
    expect(отстали).toEqual([]);
  });
});
