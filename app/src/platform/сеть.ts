import { registerPlugin, Capacitor } from '@capacitor/core';

/* ЕСТЬ ЛИ У ТЕЛЕФОНА СЕТЬ — СПРАШИВАЕМ НАТИВ, А НЕ БРАУЗЕР (SugarLife#858, вторая попытка).

   Первый заход опрашивал `navigator.onLine` раз в полсекунды: событие `offline` в WKWebView
   приходит с опозданием, а свойство, казалось, обновляется раньше. На телефоне владельца это не
   сработало вовсе — авиарежим включён, а строка спокойно писала «Внешний CGM · 1 мин». В WKWebView
   `navigator.onLine` в авиарежиме остаётся `true`: врёт сам источник, и никакой опрос этого не
   исправит.

   Правду знает наблюдатель пути в нативном слое (`Сеть.swift`), и она там уже есть — мы по ней
   будим облако движка. Теперь то же состояние приходит и в веб: событием при смене и вопросом
   `состояниеСети()` при открытии, потому что событий до подписки никто не слышал.

   ПОЧЕМУ НЕ ЧЕРЕЗ ДВИЖОК. Мы докладываем ему `networkBack`, и он кладёт беду облака — но по
   упавшему запросу, а это минуты (ядро #241). «Нет сети» — факт про наш телефон, и путь к экрану
   у него должен быть короткий.

   В БРАУЗЕРЕ остаётся `navigator.onLine`: другого источника там нет, и там он не врёт — это
   обычная страница в обычном браузере.

   ЧТО ЭТО ЗНАЧИТ И ЧЕГО НЕ ЗНАЧИТ. Ответ здесь — «есть ли у телефона ход в сеть», а не «дойдём ли
   мы до вашего Nightscout». В сети с белым списком тут будет «есть», и это честно: про тот случай
   говорит оговорка про чужие сайты (`показ/чужиеСайты.ts`). */

interface Плагин {
  addListener(event: 'сеть', cb: (e: { есть: boolean }) => void): Promise<{ remove: () => void }>;
  состояниеСети(): Promise<{ есть: boolean }>;
}

const Native = registerPlugin<Плагин>('SugarLifeBridge');

const слушатели = new Set<(есть: boolean) => void>();
let состояние: boolean = typeof navigator === 'undefined' ? true : navigator.onLine;

function принять(есть: boolean): void {
  if (есть === состояние) return;
  состояние = есть;
  слушатели.forEach((ф) => ф(есть));
}

if (Capacitor.isNativePlatform()) {
  /* Сборка натива старше этого события — тогда остаёмся на браузерном значении. Хуже прежнего
     не станет: оно и было единственным источником. */
  void Native.addListener('сеть', (e) => принять(!!e.есть)).catch(() => {});
  void Native.состояниеСети().then((r) => принять(!!r.есть)).catch(() => {});
}

/** Есть ли сеть у телефона прямо сейчас. */
export function естьСеть(): boolean {
  return состояние;
}

/** Подписаться на смену. Возвращает отписку. */
export function слушатьСеть(ф: (есть: boolean) => void): () => void {
  слушатели.add(ф);
  return () => { слушатели.delete(ф); };
}

/** Только для тестов и демо-моста: подать состояние, как будто его прислал натив. */
export function податьСеть(есть: boolean): void { принять(есть); }
