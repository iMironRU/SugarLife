/* Спасение из сломанной сборки — сторона приложения (SugarLife#131).

   Сам сторож живёт вне бандла (public/boot-guard.js): бандл — ровно то, что ломается,
   и код восстановления не может зависеть от него. Здесь то, что умеет только
   приложение: сказать «я жив» и заметить, что живо оно только на вид.

   Второе — не выдумка на будущее, а разбор случившегося: сломанная сборка перекрыла
   экран невидимой модалкой. React смонтировался, первый кадр нарисовался, «жив» было
   бы сказано честно — и сторож бы замолчал. А нажать было нельзя ничего. */

/** Ключ и пороги продублированы в public/boot-guard.js — там же объяснено почему.
    Совпадение стережёт тест: два файла с одним смыслом расходятся молча. */
export const КЛЮЧ_СТОРОЖА = 'sl-boot-guard';
export const ПОРОГ_НЕУДАЧ = 2;

/** Через сколько после первого кадра проверяем, не перекрыт ли экран. */
const ЗАДЕРЖКА_ПРОВЕРКИ = 3000;

/* Узлы описаны по форме, а не типом DOM: правило проверяется тестами, а браузерного
   DOM в них нет — и заводить его целиком ради двух вызовов дороже, чем описать ровно
   то, что мы у узла спрашиваем. */
type Узел = { closest(селектор: string): unknown };
type Корень = { querySelector(селектор: string): unknown };

declare global {
  interface Window {
    слЖив?: () => void;
    слСпасение?: (причина?: string) => void;
  }
}

/* Перекрыт ли экран нашим же слоем.

   Спрашиваем не «есть ли модалка в разметке» (она есть всегда — шторки живут
   смонтированными), а «что окажется под пальцем в середине экрана». Это тот же вопрос,
   который задаёт себе человек, и ответ на него не зависит от того, каким классом
   ошиблись.

   Открытая шторка — законная причина оказаться под пальцем, поэтому спрашиваем и о
   ней. Именно этим «перекрыто» отличается от «работает как задумано». */
export function перекрытоЛи(подПальцем: Узел | null, естьОткрытаяШторка: boolean): boolean {
  if (естьОткрытаяШторка || !подПальцем) return false;
  return !!подПальцем.closest('ion-modal, ion-backdrop, .sheet-modal');
}

/** Есть ли сейчас открытая шторка — по её же признаку, а не по нашему состоянию. */
export function естьОткрытаяШторка(корень: Корень = document): boolean {
  return !!корень.querySelector('ion-modal:not(.overlay-hidden)');
}

/* Сказать сторожу, что приложение ожило. Зовём после первого кадра: раньше — соврём
   (кадра ещё нет), позже — сторож успеет показать спасение поверх рабочего экрана. */
function сообщитьЖив(): void {
  window.слЖив?.();
}

/* Проверить, можно ли вообще нажать хоть что-то, и позвать спасение, если нельзя.

   Проверяем один раз после запуска, а не по таймеру: перекрытие такого рода — свойство
   сборки, а не момента. Постоянная проверка стоила бы кадров и ловила бы законные
   шторки в момент их появления. */
function проверитьПерекрытие(): void {
  if (typeof document === 'undefined') return;
  const x = Math.round(window.innerWidth / 2);
  const y = Math.round(window.innerHeight / 2);
  if (перекрытоЛи(document.elementFromPoint(x, y), естьОткрытаяШторка())) {
    window.слСпасение?.('Экран перекрыт невидимым слоем — до кнопок не добраться.');
  }
}

/* Признак того, что приложение действительно на экране, а не «render() позвали».

   Разница не теоретическая: render() возвращается сразу, а дерево может не собраться
   — упасть в ленивом куске, повиснуть на первом запросе. Сказать «жив» в этот момент
   значит снять сторожа ровно там, где он и нужен. Поэтому ждём саму разметку: она
   появляется вместе с первым кадром.

   ЖДЁМ КОРЕНЬ, А НЕ ОБОЛОЧКУ (SugarLife#236). Раньше признаком был `.app-shell` — обёртка главного
   экрана. У App три ветки, и оболочка есть только в одной: онбординг и загрузка
   рисуют своё. То есть на телефоне, где приложение поставили только что, сторож не
   слышал «жив» НИКОГДА — человек спокойно проходил онбординг, а через сорок пять
   секунд поверх рабочего экрана появлялось «Приложение не отвечает» с предложением
   загрузить всё заново. Хуже: счётчик неудач при этом рос от запуска к запуску, и с
   третьего раза спасение показывалось сразу, без всякого ожидания.

   `ion-app` — корень, через который проходят ВСЕ ветки. Он не может пропасть незаметно:
   без него приложение не работает вовсе. Именно этим он лучше класса, который легко
   переименовать или забыть проставить в новой ветке (а барьер ниже стережёт, чтобы
   новая ветка не появилась в обход корня).

   Да, «жив» теперь говорится и на экране загрузки. Это честно: сторож стережёт «бандл
   не ожил», а нарисованный экран загрузки — доказательство обратного. Зависшая
   загрузка данных — другая беда, и лечится она внутри приложения, а не переустановкой. */
export const ПРИЗНАК_ЖИВОГО = 'ion-app';
const ШАГ_ОЖИДАНИЯ = 300;

/* Ждём оболочку, но не вечно: если её нет и через десять секунд, замолчать — правильно.
   Дальше слово за сторожем вне бандла, у него свой срок и своё спасение. */
export function завестиСторожа(): void {
  if (typeof document === 'undefined') return;
  const до = Date.now() + 10_000;
  const шаг = () => {
    if (document.querySelector(ПРИЗНАК_ЖИВОГО)) {
      сообщитьЖив();
      window.setTimeout(проверитьПерекрытие, ЗАДЕРЖКА_ПРОВЕРКИ);
      return;
    }
    if (Date.now() < до) window.setTimeout(шаг, ШАГ_ОЖИДАНИЯ);
  };
  шаг();
}
