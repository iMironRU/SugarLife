import { registerPlugin, Capacitor } from '@capacitor/core';

/* Тревога о низком сахаре — настройка здесь, исполнение в нативе (#418).

   ПОЧЕМУ НЕ В JS. Ночью интерфейса нет: экран погашен, webview усыплён, и решение «пора
   будить» принять некому. До сих пор уведомления звались с экрана «Сегодня» — то есть
   тревога работала ровно тогда, когда человек и так смотрел на телефон. Ночная
   гипогликемия, единственное, ради чего всё это существует, приходила беззвучно.

   Считает и будит Тревоги.kt в фоновом сервисе: он живёт столько же, сколько процесс, и
   снимки движка доходят до него в три часа ночи. Отсюда уезжают только настройки —
   включено ли и при каком пороге. Правило исполняется в одном месте, а не в двух.

   ЧЕГО ЭТО НЕ ДАЁТ. На iOS нет ни фонового сервиса, ни push (платного Apple Developer
   Program у нас нет). Значит на айфоне тревога придёт, только пока приложение живо, и
   обещать большее нельзя — экран об этом говорит прямо. */

export interface НастройкиТревоги {
  on: boolean;
  /** Порог в ммоль/л. Ниже него — будим. */
  mmol: number;
  /** Высокий сахар — отдельный повод и отдельный порог. */
  highOn: boolean;
  highMmol: number;
  /* Тихие часы: час начала и час конца, −1 — не заданы. Глушат ТОЛЬКО высокий:
     низкий сахар ночью требует действий сейчас, а тревога, которую заглушили,
     не тревога. Ради этого правила тихие часы вообще имеют право существовать —
     без него человек выключил бы все тревоги разом. */
  quietFrom: number;
  quietTo: number;
  /** Идут ли тихие часы прямо сейчас — считает натив, чтобы часы были одни. */
  quietNow?: boolean;
  /* Молчание прибора (#243). Тревога НАД тревогами: гипо и высокий считаются от показаний,
     и когда показаний нет, они молчат — молчание выглядит как «всё хорошо». Эта следит не за
     числом, а за тем, что числа приходят. Тихие часы её не глушат: именно ночью на неё и
     рассчитывают. */
  silenceOn: boolean;
  /** Через сколько минут без данных будить. */
  silenceMin: number;
}

interface Плагин {
  hypoAlarm(): Promise<НастройкиТревоги>;
  setHypoAlarm(o: НастройкиТревоги): Promise<void>;
  testAlarm(): Promise<void>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

export const ПОРОГ_ПО_УМОЛЧАНИЮ = 3.9;
export const ВЫСОКИЙ_ПО_УМОЛЧАНИЮ = 13.9;
/* Ниже десяти «высокий» превращается в обычное послеобеденное число и звенел бы каждый
   день; выше двадцати он приходит тогда, когда человек уже сам всё понял. */
export const МИН_ВЫСОКИЙ = 10.0;
export const МАКС_ВЫСОКИЙ = 20.0;
export const ТИХО_ВЫКЛ = -1;
/* Полчаса. Обычная пауза между показаниями НМГ — пять минут, значит тридцать это шесть
   пропусков подряд: случайностью такое уже не объяснить. */
export const МОЛЧАНИЕ_ПО_УМОЛЧАНИЮ = 30;
/* Ниже пятнадцати — тревога на обычной паузе: НМГ моргает, мост переподключается, и всё
   чинится само. Выше часа — человек успевает принять решение вслепую, а тревога придёт
   после него. */
export const МИН_МОЛЧАНИЕ = 15;
export const МАКС_МОЛЧАНИЕ = 60;
export const ШАГ_МОЛЧАНИЯ = 5;
/* Ниже трёх — это уже не «посмотреть», а «есть сахар немедленно», и такой порог означал бы
   тревогу, которая будит, когда действовать поздно. Выше пяти — тревога на нормальном
   сахаре, а она учит выключать тревоги вообще. */
export const МИН_ПОРОГ = 3.0;
export const МАКС_ПОРОГ = 5.0;

/** Умеет ли эта сборка будить в фоне. false — браузер или сборка старше методов. */
export function тревогиДоступны(): boolean {
  return Capacitor.isNativePlatform() && Capacitor.getPlatform() === 'android';
}

export async function настройкиТревоги(): Promise<НастройкиТревоги | null> {
  if (!тревогиДоступны()) return null;
  try {
    return await Native.hypoAlarm();
  } catch {
    /* Метода нет — сборка старше тревог. Это НЕ «выключено»: молчать об этом нельзя,
       иначе человек решит, что тревоги настроены, и уснёт с этой уверенностью. */
    return null;
  }
}

export async function задатьТревогу(н: НастройкиТревоги): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  try { await Native.setHypoAlarm(н); return true; } catch { return false; }
}

/** Проверочная тревога — тем же путём, что настоящая: канал, звук, обход «не беспокоить». */
export async function проверитьТревогу(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  try { await Native.testAlarm(); return true; } catch { return false; }
}

/* ГОТОВНОСТЬ РАЗБУДИТЬ (#468).

   Канал тревоги заведён правильно: громкость будильника, обход «Не беспокоить»,
   полноэкранное намерение, вибрация. Но система исполняет всё это только при выданных
   разрешениях, а без них МОЛЧА ДЕЛАЕТ ВИД, ЧТО ИСПОЛНИЛА. Утром уведомление в шторке на
   месте — и человек уверен, что защита была.

   Разрешение в манифесте — только право спросить. Доступ к «Не беспокоить» и право на
   полноэкранные уведомления выдаёт человек руками, и пока он их не выдал, ночная тревога
   приходит беззвучной строкой. Поэтому список того, чего не хватает, показываем ДО ночи,
   а не выясняем после. */
/* Код поломки — машине, фраза — человеку (#473, #475).

   Дословную строку нельзя разложить по разделам экрана: «услышим ли тревогу» и «заметим ли
   пропажу данных» — разные пункты, а все поломки разрешений валились в один. Код говорит,
   К ЧЕМУ относится беда; фраза остаётся в ядре приложения, чтобы на двух платформах она
   не разошлась. */
export type КодПоломки = 'notifications-off' | 'dnd-access' | 'fullscreen' | 'channel-lowered';

export interface Поломка {
  код: КодПоломки | string;
  текст: string;
}

export interface ГотовностьТревог {
  /** Есть ли о чём говорить. false — молчим, зелёных галочек не рисуем. */
  проблема: boolean;
  /** Чего не хватает — словами от натива: ответ один на обе платформы. */
  чегоНет: string[];
  /** То же самое с кодами: по ним раскладываем по пунктам экрана. */
  поломки: Поломка[];
  сторожМолчания: boolean;
  порогМолчанияМин: number;
}

interface ПлагинГотовности {
  alarmReadiness(): Promise<{
    problem: boolean; missing: string[];
    problems?: { code: string; text: string }[];
    silenceWatchdogOn: boolean; silenceThresholdMin: number;
  }>;
  openDndAccess(): Promise<void>;
  openFullScreenAccess(): Promise<void>;
}
const NativeГотовность = registerPlugin<ПлагинГотовности>('SugarLifeBridge');

export async function готовностьТревог(): Promise<ГотовностьТревог | null> {
  if (!тревогиДоступны()) return null;
  try {
    const r = await NativeГотовность.alarmReadiness();
    return {
      проблема: !!r.problem,
      чегоНет: Array.isArray(r.missing) ? r.missing : [],
      поломки: Array.isArray(r.problems)
        ? r.problems.map((п) => ({ код: п.code, текст: п.text }))
        /* Сборка старше кодов — раскладываем по старому, одной кучей: лучше показать
           поломку не в том пункте, чем не показать вовсе. */
        : (Array.isArray(r.missing) ? r.missing : []).map((т) => ({ код: 'dnd-access', текст: т })),
      сторожМолчания: !!r.silenceWatchdogOn,
      порогМолчанияМин: Number(r.silenceThresholdMin) || МОЛЧАНИЕ_ПО_УМОЛЧАНИЮ,
    };
  } catch {
    /* Метода нет — сборка старше проверки. Это НЕ «всё в порядке»: молчание здесь
       читается как обещание, что разбудим, а мы этого не знаем. */
    return null;
  }
}

/** Открыть системный экран доступа к «Не беспокоить». */
export async function открытьДоступКТихомуРежиму(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  try { await NativeГотовность.openDndAccess(); return true; } catch { return false; }
}

/* Полноэкранные уведомления — второй системный экран, отдельный от «Не беспокоить»
   (#468, #472). Появился в Android 14: право в манифесте есть, но система выдаёт его сама
   только звонилкам и будильникам, остальным — руками человека. До Android 14 разрешение не
   нужно, и натив отвечает отказом — поэтому кнопку показываем только при своём коде. */
export async function открытьПолноэкранные(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  try { await NativeГотовность.openFullScreenAccess(); return true; } catch { return false; }
}
