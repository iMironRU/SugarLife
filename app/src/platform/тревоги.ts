import { registerPlugin, Capacitor } from '@capacitor/core';

/* Тревога о низком сахаре — настройка здесь, исполнение в нативе (#418).

   ПОЧЕМУ НЕ В JS. Ночью интерфейса нет: экран погашен, webview усыплён, и решение «пора
   будить» принять некому. До сих пор уведомления звались с экрана «Сегодня» — то есть
   тревога работала ровно тогда, когда человек и так смотрел на телефон. Ночная
   гипогликемия, единственное, ради чего всё это существует, приходила беззвучно.

   Считает и будит Тревоги.kt в фоновом сервисе: он живёт столько же, сколько процесс, и
   снимки движка доходят до него в три часа ночи. Отсюда уезжают только настройки —
   включено ли и при каком пороге. Правило исполняется в одном месте, а не в двух.

   ЧЕГО ЭТО НЕ ДАЁТ. На iOS нет ни фонового сервиса, ни push (платного Apple Developer
   Program у нас нет). Значит на айфоне тревога придёт, только пока приложение живо, и
   обещать большее нельзя — экран об этом говорит прямо. */

export interface НастройкиТревоги {
  on: boolean;
  /** Порог в ммоль/л. Ниже него — будим. */
  mmol: number;
}

interface Плагин {
  hypoAlarm(): Promise<НастройкиТревоги>;
  setHypoAlarm(o: НастройкиТревоги): Promise<void>;
  testAlarm(): Promise<void>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

export const ПОРОГ_ПО_УМОЛЧАНИЮ = 3.9;
/* Ниже трёх — это уже не «посмотреть», а «есть сахар немедленно», и такой порог означал бы
   тревогу, которая будит, когда действовать поздно. Выше пяти — тревога на нормальном
   сахаре, а она учит выключать тревоги вообще. */
export const МИН_ПОРОГ = 3.0;
export const МАКС_ПОРОГ = 5.0;

/** Умеет ли эта сборка будить в фоне. false — браузер или сборка старше методов. */
export function тревогиДоступны(): boolean {
  return Capacitor.isNativePlatform() && Capacitor.getPlatform() === 'android';
}

export async function настройкиТревоги(): Promise<НастройкиТревоги | null> {
  if (!тревогиДоступны()) return null;
  try {
    return await Native.hypoAlarm();
  } catch {
    /* Метода нет — сборка старше тревог. Это НЕ «выключено»: молчать об этом нельзя,
       иначе человек решит, что тревоги настроены, и уснёт с этой уверенностью. */
    return null;
  }
}

export async function задатьТревогу(н: НастройкиТревоги): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  try { await Native.setHypoAlarm(н); return true; } catch { return false; }
}

/** Проверочная тревога — тем же путём, что настоящая: канал, звук, обход «не беспокоить». */
export async function проверитьТревогу(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  try { await Native.testAlarm(); return true; } catch { return false; }
}
