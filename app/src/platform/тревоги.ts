import { registerPlugin, Capacitor } from '@capacitor/core';
import { уНатива } from './уНатива';

/* Тревоги: разрешения и проверка — здесь, правила — в движке (#418, #482).

   ПОРОГИ ОТСЮДА УШЛИ. Считает тревоги движок: одни правила на Android и на iPhone, они же приезжают на
   экран списком и правятся через `setConfig`. Пока правила жили в андроидных настройках, у айфона
   тревог не было вовсе — и не могло появиться.

   Осталось то, что есть только у платформы: выданы ли разрешения (без них система МОЛЧА делает вид, что
   исполнила канал с обходом «не беспокоить») и проверочная тревога — единственный способ узнать, что
   всё работает, не дожидаясь ночной гипогликемии. */

interface Плагин {
  testAlarm(): Promise<void>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

/* ТЕПЕРЬ И АЙФОН (#482).

   Раньше здесь стоял только Android — и это было честно: своей доставки на iOS у нас не было, тревога
   приходила, лишь пока приложение открыто. Теперь у айфона есть своя половина: уведомления с действием
   «Понял», очередь подтверждений и свой звук поверх беззвучного режима, пока держится фоновое
   бодрствование. Правила при этом одни и те же — их считает движок.

   Чего у iOS нет и не будет без платного аккаунта: обхода «не беспокоить» (Critical Alerts) и
   полноэкранных уведомлений. Про это говорит `готовностьТревог`, а не молчание этой функции. */
export function тревогиДоступны(): boolean {
  const п = Capacitor.getPlatform();
  return Capacitor.isNativePlatform() && (п === 'android' || п === 'ios');
}

/** Проверочная тревога — тем же путём, что настоящая: канал, звук, обход «не беспокоить». */
export async function проверитьТревогу(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  return уНатива('testAlarm', async () => { await Native.testAlarm(); return true; }, false);
}

/* ГОТОВНОСТЬ РАЗБУДИТЬ (#468).

   Канал тревоги заведён правильно: громкость будильника, обход «Не беспокоить»,
   полноэкранное намерение, вибрация. Но система исполняет всё это только при выданных
   разрешениях, а без них МОЛЧА ДЕЛАЕТ ВИД, ЧТО ИСПОЛНИЛА. Утром уведомление в шторке на
   месте — и человек уверен, что защита была.

   Разрешение в манифесте — только право спросить. Доступ к «Не беспокоить» и право на
   полноэкранные уведомления выдаёт человек руками, и пока он их не выдал, ночная тревога
   приходит беззвучной строкой. Поэтому список того, чего не хватает, показываем ДО ночи,
   а не выясняем после. */
/* Код поломки — машине, фраза — человеку (#473, #475).

   Дословную строку нельзя разложить по разделам экрана: «услышим ли тревогу» и «заметим ли
   пропажу данных» — разные пункты, а все поломки разрешений валились в один. Код говорит,
   К ЧЕМУ относится беда; фраза остаётся в ядре приложения, чтобы на двух платформах она
   не разошлась. */
export type КодПоломки =
  | 'notifications-off' | 'dnd-access' | 'fullscreen' | 'channel-lowered'
  /* Айфонное: в фоне приложение засыпает, и звучать тревоге нечем. Чинится НЕ системными
     настройками, а нашим же переключателем фонового бодрствования — поэтому кнопки в настройки
     у этой поломки нет. */
  | 'ios-keep-alive'
  /* Тоже айфонное и тоже наше: громкость убавлена, а поднимать её на тревоге запрещено. */
  | 'ios-volume'
  /* Айфонные про «Не беспокоить» (#500): срочные выключены человеком / сборка вовсе без права на
     срочные (чинится только переустановкой) / сводка по расписанию задерживает / на экране
     блокировки уведомления выключены. */
  | 'time-sensitive-off' | 'time-sensitive-unsupported' | 'scheduled-summary' | 'lock-screen-off';

export interface Поломка {
  код: КодПоломки | string;
  текст: string;
}

export interface ГотовностьТревог {
  /** Есть ли о чём говорить. false — молчим, зелёных галочек не рисуем. */
  проблема: boolean;
  /** Чего не хватает — словами от натива: ответ один на обе платформы. */
  чегоНет: string[];
  /** То же самое с кодами: по ним раскладываем по пунктам экрана. */
  поломки: Поломка[];
}

interface ПлагинГотовности {
  alarmReadiness(): Promise<{
    problem: boolean; missing: string[];
    problems?: { code: string; text: string }[];
  }>;
  openDndAccess(): Promise<void>;
  openFullScreenAccess(): Promise<void>;
  /** Айфонный близнец `openDndAccess`: там доступ один и экран один — карточка приложения. */
  openAlarmSettings(): Promise<void>;
}
const NativeГотовность = registerPlugin<ПлагинГотовности>('SugarLifeBridge');

export async function готовностьТревог(): Promise<ГотовностьТревог | null> {
  if (!тревогиДоступны()) return null;
  /* Запасное — null, а НЕ «всё в порядке»: молчание здесь читается как обещание, что разбудим,
     а мы этого не знаем. Тем нужнее след: без него отказ этой проверки неотличим от исправности. */
  return уНатива('alarmReadiness', async () => {
    const r = await NativeГотовность.alarmReadiness();
    return {
      проблема: !!r.problem,
      чегоНет: Array.isArray(r.missing) ? r.missing : [],
      поломки: Array.isArray(r.problems)
        ? r.problems.map((п) => ({ код: п.code, текст: п.text }))
        /* Сборка старше кодов — раскладываем по старому, одной кучей: лучше показать
           поломку не в том пункте, чем не показать вовсе. */
        : (Array.isArray(r.missing) ? r.missing : []).map((т) => ({ код: 'dnd-access', текст: т })),
    };
  }, null);
}

/* ГРОМКОСТЬ ТРЕВОГИ — ТОЛЬКО НА АЙФОНЕ (#482).

   Свой звук пробивает беззвучный режим, но не убавленную громкость: играем мы на общем уровне медиа.
   Поэтому на время будящей тревоги поднимаем его сами и возвращаем обратно, когда она смолкла. На
   Android этого вопроса нет — там канал тревоги играет громкостью будильника, отдельной от медиа. */
export interface ГромкостьТревоги {
  /** Поднимаем ли на время тревоги. */
  поднимаем: boolean;
  /** Какая громкость сейчас, 0…1 — то, что человек услышит, если не поднимать. */
  уровень: number;
}

interface ПлагинГромкости {
  alarmVolume(): Promise<{ boost: boolean; level: number }>;
  setAlarmVolume(o: { boost: boolean }): Promise<{ boost: boolean }>;
}
const NativeГромкость = registerPlugin<ПлагинГромкости>('SugarLifeBridge');

interface ПлагинФокуса {
  setFocusAllowed(o: { allowed: boolean }): Promise<{ allowed: boolean }>;
}
const NativeФокус = registerPlugin<ПлагинФокуса>('SugarLifeBridge');

/** null — вопрос не про эту платформу (Android, браузер) или сборка старше. */
export async function громкостьТревоги(): Promise<ГромкостьТревоги | null> {
  if (!тревогиДоступны() || Capacitor.getPlatform() !== 'ios') return null;
  return уНатива('alarmVolume', async () => {
    const r = await NativeГромкость.alarmVolume();
    return { поднимаем: !!r.boost, уровень: Number(r.level) || 0 };
  }, null);
}

export async function поднимитеГромкость(поднимаем: boolean): Promise<boolean> {
  if (!тревогиДоступны() || Capacitor.getPlatform() !== 'ios') return false;
  return уНатива('setAlarmVolume', async () => { await NativeГромкость.setAlarmVolume({ boost: поднимаем }); return true; }, false);
}

/* ОТВЕТ ЧЕЛОВЕКА ПРО СПИСОК ФОКУСА — НЕ ТОЛЬКО К НАМ, НО И К ДВИЖКУ (#685).

   Прочитать «Разрешённые уведомления» режима Фокусирования нельзя никаким API, поэтому ответ у нас
   один — его собственный. Мы его помнили, но держали при себе: доклад о доставке собирает натив, а
   решение «разбудим ли» принимает движок, и ни тот, ни другой про localStorage не знают.

   Отсюда и бралась просьба, которую нельзя погасить: человек отвечал «добавил», мы кивали и
   продолжали слать движку `false`. Теперь ответ доезжает. */
export async function фокусРазрешён(разрешено: boolean): Promise<boolean> {
  if (!тревогиДоступны() || Capacitor.getPlatform() !== 'ios') return false;
  return уНатива('setFocusAllowed', async () => { await NativeФокус.setFocusAllowed({ allowed: разрешено }); return true; }, false);
}

/** Открыть системный экран доступа к «Не беспокоить» (Android). */
export async function открытьДоступКТихомуРежиму(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  return уНатива('openDndAccess', async () => { await NativeГотовность.openDndAccess(); return true; }, false);
}

/** Есть ли среди поломок та, что чинится системными настройками. */
export function чинитсяНастройками(поломки: Поломка[]): boolean {
  /* «Сборка без права» тоже не чинится системным экраном — только переустановкой целиком. */
  const наши = ['ios-keep-alive', 'ios-volume', 'time-sensitive-unsupported'];
  return поломки.some((п) => !наши.includes(п.код));
}

/** Куда ведёт кнопка «Открыть настройки»: у платформ разные экраны, у экрана — один вопрос. */
export async function открытьНастройкиТревог(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  if (Capacitor.getPlatform() === 'ios') {
    return уНатива('openAlarmSettings', async () => { await NativeГотовность.openAlarmSettings(); return true; }, false);
  }
  return открытьДоступКТихомуРежиму();
}

/* Полноэкранные уведомления — второй системный экран, отдельный от «Не беспокоить»
   (#468, #472). Появился в Android 14: право в манифесте есть, но система выдаёт его сама
   только звонилкам и будильникам, остальным — руками человека. До Android 14 разрешение не
   нужно, и натив отвечает отказом — поэтому кнопку показываем только при своём коде. */
export async function открытьПолноэкранные(): Promise<boolean> {
  if (!тревогиДоступны()) return false;
  return уНатива('openFullScreenAccess', async () => { await NativeГотовность.openFullScreenAccess(); return true; }, false);
}
