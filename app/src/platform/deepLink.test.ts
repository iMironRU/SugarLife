import { describe, it, expect } from 'vitest';
import { адресРаздела, разделИзАдреса } from './deepLink';

/* Диплинк (SugarLife#315). Проверяем разбор, а не переход: переход зависит от системы,
   а вот «ссылка ведёт НА РАЗДЕЛ, а не просто в приложение» — наше обещание. */

describe('адрес раздела', () => {
  it('собирается и разбирается обратно', () => {
    (['диагностика', 'приборы', 'поиск'] as const).forEach((р) => {
      expect(разделИзАдреса(адресРаздела(р))).toBe(р);
    });
  });

  /* Издание Pro отвечает на свою схему (#296), но путь у них общий: ссылка, присланная
     человеку с Pro, обязана открыть тот же раздел. */
  it('схема издания Pro разбирается так же', () => {
    expect(разделИзАдреса('sugarlife.pro://раздел/приборы')).toBe('приборы');
  });

  it('процентное кодирование — обычное дело для кириллицы в адресе', () => {
    expect(разделИзАдреса('sugarlife://раздел/%D0%BF%D1%80%D0%B8%D0%B1%D0%BE%D1%80%D1%8B')).toBe('приборы');
  });

  /* Чужое и незнакомое не открываем: адрес приходит извне, и вести по нему на угаданный
     экран — то же, что доверять данным из сети. */
  it('незнакомый раздел и чужая схема — молчим', () => {
    expect(разделИзАдреса('sugarlife://раздел/настройки')).toBe(null);
    expect(разделИзАдреса('sugarlife://что-то/другое')).toBe(null);
    expect(разделИзАдреса('https://imiron.ru/SugarLife/раздел/приборы')).toBe(null);
    expect(разделИзАдреса('')).toBe(null);
  });
});
