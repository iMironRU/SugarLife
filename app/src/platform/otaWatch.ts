import { useEffect, useState } from 'react';
import { узнатьOta, isNative, type ОтаБандл } from './appUpdate';
import { прочитать, записать } from '@/settings/storage';

/* Автопроверка обновления в нативе (SugarLife#312).

   В вебе о готовом обновлении говорит service worker, и человек узнаёт о нём сам. В
   нативе такого механизма нет: JS приезжает через OTA, а спросить сервер умела только
   кнопка в разделе «О приложении». То есть узнать про свежую сборку можно было, лишь
   зайдя туда и нажав, — то есть уже подозревая, что отстал.

   А отстать легко: телефонное приложение не закрывают, его сворачивают. Человек уверен,
   что оно обновляется само, — и в нативе эта уверенность даже обоснованнее, потому что
   приложения из магазинов так и делают.

   НЕ ПРИМЕНЯЕМ САМИ. Применение перезагружает webview, и если в этот момент открыта
   шторка ввода еды, введённое пропадёт. Обновление не стоит потерянного приёма пищи —
   то же правило, что в вебе (#150). Поэтому здесь только «узнать» и сказать.

   НЕ ЧАЩЕ РАЗА В ТРИ ЧАСА. Проверка на каждом открытии экрана превратилась бы в фоновый
   трафик, которого человек не заказывал; у многих мобильный интернет считанный. Три часа
   — компромисс: за день выйдет несколько попыток, и обновление, выпущенное утром,
   доедет к вечеру само. */
const КЛЮЧ = 'sl.ota.checked.v1';
export const ПАУЗА_МС = 3 * 60 * 60_000;

/* Правило отдельно от хранилища и сети: его и проверяем тестом.

   «Не спрашивали ни разу» — отдельный случай, а не ноль. Считать пустую отметку нулём
   значит сравнивать с началом эпохи: на живых часах это всегда «пора», и ошибка не
   всплывает, но она есть, и всплыла бы у любого, кто подставит своё время. */
export function пораЛи(былоМс: string | null | undefined, сейчас: number): boolean {
  const было = Number(былоМс);
  if (!былоМс || !Number.isFinite(было)) return true;
  return сейчас - было > ПАУЗА_МС;
}

/* Работа с миром — параметром, а не жёстко внутри.

   Не ради «чистоты»: без этого правило «отметка ДО запроса» проверить нечем, а именно
   оно и защищает человека от лишнего трафика. Умолчания те же, что были, поэтому на
   стороне вызова ничего не меняется. */
export interface Мир {
  прочитать: (k: string) => string | null;
  записать: (k: string, v: string) => void;
  узнать: () => Promise<ОтаБандл | 'нет' | 'ошибка'>;
  нативно: boolean;
}
const мирПоУмолчанию = (): Мир => ({ прочитать, записать, узнать: узнатьOta, нативно: isNative });

/** Спросить сервер, если пора. Возвращает найденное или null. */
export async function проверитьЕслиПора(
  сейчас = Date.now(), мир: Мир = мирПоУмолчанию(),
): Promise<ОтаБандл | null> {
  if (!мир.нативно || !пораЛи(мир.прочитать(КЛЮЧ), сейчас)) return null;
  /* Отметку ставим ДО запроса, а не после. Иначе при недоступной сети приложение
     ходило бы за манифестом на каждом возврате из фона — то есть чаще всего именно
     тогда, когда сеть плохая. */
  мир.записать(КЛЮЧ, String(сейчас));
  const б = await мир.узнать();
  return typeof б === 'object' ? б : null;
}

/* Хук для «Сегодня»: проверить при запуске и при возвращении из фона.

   Возвращение важнее запуска: приложение стартует редко, а из фона выходит по нескольку
   раз в день — и именно там человек проводит время, не подозревая, что сборка устарела. */
export function useОтаОбновление(): ОтаБандл | null {
  const [найдено, setНайдено] = useState<ОтаБандл | null>(null);

  useEffect(() => {
    if (!isNative) return;
    let живо = true;
    const спросить = () => {
      void проверитьЕслиПора().then((б) => { if (живо && б) setНайдено(б); });
    };
    спросить();
    /* visibilitychange, а не событие Capacitor: оно одинаково работает и в вебе, и в
       нативе, и не требует ещё одного плагина ради одного сигнала. */
    const слушатель = () => { if (document.visibilityState === 'visible') спросить(); };
    document.addEventListener('visibilitychange', слушатель);
    return () => { живо = false; document.removeEventListener('visibilitychange', слушатель); };
  }, []);

  return найдено;
}
