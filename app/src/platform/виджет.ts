import { registerPlugin, Capacitor } from '@capacitor/core';
import { уНатива } from './уНатива';

/* Виджет на рабочем столе (#449).

   ЗАЧЕМ КНОПКА, ЕСЛИ ВИДЖЕТ И ТАК ЕСТЬ В СПИСКЕ. Путь без неё такой: долго нажать на
   пустое место, найти «Виджеты», пролистать чужой список до буквы S, потянуть плитку на
   экран. Половина людей до конца не доходит и решает, что виджета нет вовсе. Система умеет
   предложить это одним диалогом — грех не спросить.

   ЧЕГО ЭТО НЕ ДАЁТ. Механизма нет до Android 8, и часть прошивок его не поддерживает. Тогда
   говорим прямо: добавьте руками, вот как. Молчаливая кнопка, которая ничего не делает,
   хуже отсутствующей — человек нажмёт и решит, что сделал. */
interface Плагин {
  pinWidget(): Promise<{ supported: boolean; asked: boolean }>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

export const виджетВозможен = (): boolean =>
  Capacitor.isNativePlatform() && Capacitor.getPlatform() === 'android';

export type ИтогДобавления = 'спросили' | 'не умеет' | 'нет метода';

export async function добавитьВиджет(): Promise<ИтогДобавления> {
  if (!виджетВозможен()) return 'не умеет';
  /* Запасное — «нет метода», а не «не умеет»: телефон, может, и умеет, а вот приложение на нём
     прошлое. Разные новости, и путать их нельзя. */
  return уНатива('pinWidget', async () => {
    const r = await Native.pinWidget();
    return r.supported && r.asked ? 'спросили' : 'не умеет';
  }, 'нет метода' as const);
}
