import { describe, it, expect } from 'vitest';
import { корневойРазмер, БАЗА, APPLE_BODY, ПОТОЛОК } from './размерТекста';

describe('корневой размер по системной настройке', () => {
  it('обычная настройка — обычный размер', () => {
    expect(корневойРазмер(APPLE_BODY)).toBe(БАЗА);
  });

  it('крупный системный шрифт увеличивает текст', () => {
    expect(корневойРазмер(APPLE_BODY * 1.3)).toBeCloseTo(БАЗА * 1.3, 1);
  });

  /* Втрое выросшая мелочь не «читается лучше» — она перестаёт помещаться, и человек
     теряет не только текст, но и управление. */
  it('крайние настройки доступности упираются в потолок', () => {
    expect(корневойРазмер(53)).toBe(БАЗА * ПОТОЛОК);
    expect(корневойРазмер(100)).toBe(БАЗА * ПОТОЛОК);
  });

  /* Выбравший мелкий системный шрифт просит уплотнить списки в почте, а не уменьшить
     число сахара. */
  it('мельче обычного не делаем', () => {
    expect(корневойРазмер(12)).toBe(БАЗА);
  });

  it('спросить не удалось — оставляем как есть', () => {
    expect(корневойРазмер(null)).toBe(БАЗА);
    expect(корневойРазмер(undefined)).toBe(БАЗА);
    expect(корневойРазмер(0)).toBe(БАЗА);
    expect(корневойРазмер(NaN)).toBe(БАЗА);
  });
});
