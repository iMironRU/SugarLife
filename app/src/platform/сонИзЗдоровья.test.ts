import { describe, it, expect } from 'vitest';
import { подготовитьСессии } from './сонИзЗдоровья';

/* Готовим наблюдения для движка (#597, ядро #177). Решение принимает он; наше дело — не отдать
   ему кривизну и не назвать телефон часами. */
describe('подготовка сессий сна', () => {
  it('целую сессию отдаём как есть', () => {
    const с = подготовитьСессии([{ fromMs: 100, toMs: 200, source: 'watch' }]);
    expect(с).toEqual([{ fromMs: 100, toMs: 200, source: 'watch' }]);
  });

  it('битую отбрасываем, остальные оставляем', () => {
    /* Одна кривая запись не повод потерять остальные — так же решило и ядро у себя. */
    const с = подготовитьСессии([
      { fromMs: 200, toMs: 100, source: 'watch' },
      { fromMs: 100, toMs: 100, source: 'watch' },
      { fromMs: 300, toMs: 400, source: 'phone' },
    ]);
    expect(с).toHaveLength(1);
    expect(с[0].fromMs).toBe(300);
  });

  it('незнакомый источник называем неизвестным, а не выдумываем', () => {
    /* Доверие к часам и к телефону разное. Назвать телефон часами дороже, чем сказать «не знаю». */
    expect(подготовитьСессии([{ fromMs: 1, toMs: 2, source: 'Fitbit' }])[0].source).toBe('unknown');
  });

  it('мусор вместо чисел не уезжает', () => {
    expect(подготовитьСессии([{ fromMs: NaN, toMs: 5, source: 'watch' }])).toEqual([]);
  });

  it('пусто и «нет данных» — одно и то же для списка, а не ошибка', () => {
    expect(подготовитьСессии(null)).toEqual([]);
    expect(подготовитьСессии(undefined)).toEqual([]);
  });
});
