import { describe, it, expect } from 'vitest';
import { отсталиЛи, ключОтказа } from './отставание';

describe('отсталиЛи', () => {
  it('молчит, пока сервер не ответил', () => {
    expect(отсталиЛи('e4e0f87', null)).toBe(false);
    expect(отсталиЛи('e4e0f87', undefined)).toBe(false);
  });
  it('молчит на своей же сборке', () => {
    expect(отсталиЛи('7bd588f', '7bd588f')).toBe(false);
  });
  it('видит расхождение', () => {
    expect(отсталиЛи('e4e0f87', '7bd588f')).toBe(true);
  });
  it('не трогает сборку из исходников', () => {
    expect(отсталиЛи('dev', '7bd588f')).toBe(false);
  });
});

describe('ключОтказа', () => {
  it('меняется, когда выходит следующий релиз — иначе «потом» значило бы «никогда»', () => {
    expect(ключОтказа('e4e0f87', '6b28ebd')).not.toBe(ключОтказа('e4e0f87', '7bd588f'));
  });
  it('не меняется, пока релиз тот же', () => {
    expect(ключОтказа('e4e0f87', '7bd588f')).toBe(ключОтказа('e4e0f87', '7bd588f'));
  });
});
