/* Системный размер текста на iOS (#325).

   Размеры переведены в rem — и на Android этого достаточно: браузер сам масштабирует
   корневой размер по настройке «размер шрифта». На iOS нет: WKWebView про Dynamic Type
   веб-странице ничего не сообщает, и rem там остаются теми же шестнадцатью пикселями,
   какую бы крупность человек ни выбрал в настройках телефона.

   То есть без этого файла вся работа по переводу в rem для владельца айфона не значит
   ничего. Молчать об этом нельзя: человек включил крупный шрифт, а приложение сделало
   вид, что не слышало.

   Способ узнать один: спросить систему шрифтом `-apple-system-body` — это и есть тот
   размер, который человек выбрал. Меряем его на невидимой пробе и ставим корню.

   ПОТОЛОК ОБЯЗАТЕЛЕН. На крайних настройках доступности body доходит до пятидесяти с
   лишним пикселей — втрое против обычного. Втрое выросшая мелочь не «читается лучше»,
   она перестаёт помещаться: подписи налезают, кнопки уезжают за край, и человек теряет
   не только текст, но и управление. Полтора раза — предел, за которым мы приносим больше
   вреда, чем пользы. */

/** Обычный размер корня и обычный body у Apple. */
export const БАЗА = 16;
export const APPLE_BODY = 17;
export const ПОТОЛОК = 1.5;

/* Чистое правило — его и проверяем тестом. Ошибка здесь не падает: она просто делает
   текст не того размера, и заметит это лишь тот, у кого зрение слабое. */
export function корневойРазмер(системныйPx: number | null | undefined): number {
  if (!системныйPx || !Number.isFinite(системныйPx) || системныйPx <= 0) return БАЗА;
  const во = системныйPx / APPLE_BODY;
  /* Меньше обычного не делаем никогда. Человек, выбравший мелкий системный шрифт,
     просит уплотнить списки в почте, а не уменьшить число сахара. */
  const ограниченный = Math.min(Math.max(во, 1), ПОТОЛОК);
  return Math.round(БАЗА * ограниченный * 100) / 100;
}

/** Спросить систему. null — спрашивать некого (не Apple, нет DOM). */
export function спроситьСистему(): number | null {
  if (typeof document === 'undefined' || typeof CSS === 'undefined') return null;
  if (!CSS.supports?.('font', '-apple-system-body')) return null;
  const проба = document.createElement('div');
  проба.style.cssText = 'position:absolute;visibility:hidden;pointer-events:none;font:-apple-system-body';
  document.body.appendChild(проба);
  const px = parseFloat(getComputedStyle(проба).fontSize);
  проба.remove();
  return Number.isFinite(px) ? px : null;
}

/* Спрашиваем не один раз: крупность меняют в настройках телефона, не выходя из
   приложения, и возвращаются обратно уже с другой. Возврат из фона — тот момент, когда
   это стоит перепроверить. */
export function следитьЗаРазмером(): void {
  const применить = () => {
    const px = корневойРазмер(спроситьСистему());
    document.documentElement.style.fontSize = px === БАЗА ? '' : `${px}px`;
  };
  применить();
  document.addEventListener('visibilitychange', () => { if (!document.hidden) применить(); });
}
