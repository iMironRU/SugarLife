import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

/* СТОРОЖ СЛЕДА У ОБЁРТОК НАТИВА (#668).

   У натива такая проверка есть с августа (`scripts/молчаливые-отказы.sh`): каждая ветка отказа
   обязана оставить строку в журнале движка. У веба её не было, и веб этим пользовался: тридцать
   семь мест гасили ошибку молча, и отличить «метода нет в старой сборке» от «метод есть и упал»
   было нельзя ниоткуда.

   Правило простое: зовёшь натив — зови через `уНатива`. Он вернёт запасное и оставит след, один
   раз на имя за сеанс.

   ИСКЛЮЧЕНИЯ ПИШУТСЯ ЗДЕСЬ И С ПРИЧИНОЙ. Список, в который дописывают молча, — это не список
   исключений, а способ обойти проверку. */
const ПАПКА = join(__dirname, '.');

/* Файлы, где голый `catch` законен, и почему. */
const МОЖНО: Record<string, string> = {
  'уНатива.ts': 'сам помощник — он и есть тот, кто ловит',
  'scanCode.ts': 'сканер: отказ показывается человеку на месте, своей строкой на экране',
  'scanFromImage.ts': 'разбор картинки: неудача — обычный исход, о ней говорит сам экран',
  'swUpdate.ts': 'служебный работник браузера, а не натив: своего журнала у него нет',
  'appUpdate.ts': 'сеть и загрузка обновления: исход показывается человеку строкой в «О программе»',
  'offlineShell.ts': 'кэш браузера, не натив',
  'deepLink.ts': 'разбор чужой ссылки: кривая ссылка — не наш отказ',
  'notify.ts': 'разрешение на уведомления: ответ системы показывается на экране охраны',
};

describe('обёртки натива не глотают отказ молча', () => {
  const файлы = readdirSync(ПАПКА).filter((и) => и.endsWith('.ts') && !и.endsWith('.test.ts'));

  for (const имя of файлы) {
    if (МОЖНО[имя]) continue;
    it(`${имя} зовёт натив через уНатива`, () => {
      const строки = readFileSync(join(ПАПКА, имя), 'utf8').split('\n');
      const голые: string[] = [];
      строки.forEach((s, i) => {
        if (!/\bcatch\s*(\([^)]*\))?\s*\{/.test(s)) return;
        голые.push(`строка ${i + 1}: ${s.trim().slice(0, 70)}`);
      });
      expect(
        голые,
        `${имя}: отказ натива обязан оставлять след — зовите через уНатива(). `
        + 'Если голый catch здесь законен, впишите файл в МОЖНО с причиной.',
      ).toEqual([]);
    });
  }

  it('список исключений не пуст и у каждого есть причина', () => {
    /* Проверка на саму себя: исключение без причины — это дыра, которую забудут закрыть. */
    for (const [имя, почему] of Object.entries(МОЖНО)) {
      expect(почему.length, `${имя}: причина обязана быть словами`).toBeGreaterThan(20);
    }
  });
});
