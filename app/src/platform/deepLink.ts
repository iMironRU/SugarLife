import { isNative } from './appUpdate';
import { ССЫЛКИ } from './appUpdate';

/* Диплинк: ссылка вместо совета (SugarLife#315).

   В четырёх местах приложение честно говорило «в браузере это не работает, откройте на
   телефоне» — и оставляло человека выполнять совет самому. Совет без кнопки это тупик:
   он знает, что делать, и не может это сделать отсюда.

   ПОЧЕМУ СХЕМА, А НЕ https-ССЫЛКА. Универсальные ссылки, которые открываются без окна
   выбора, требуют Associated Domains — а это платный аккаунт разработчика Apple, которого
   у нас нет. На Android можно было бы сделать App Links, но тогда поведение разъехалось бы
   между платформами, а разъехавшееся поведение мы чиним потом дольше, чем экономим.

   «УСТАНОВЛЕНО ЛИ» БРАУЗЕР НЕ СКАЖЕТ, и это не его недоработка, а защита: сайт не должен
   знать, что стоит на телефоне. Обход один и общий для всех: пробуем открыть схему и, если
   через полсекунды страница всё ещё жива, уводим на запасной адрес. Отсюда и текст кнопки
   «Открыть в приложении», а не «Открыть приложение»: обещать успех мы не вправе. */

export type Раздел = 'диагностика' | 'приборы' | 'поиск';

const СХЕМА = 'sugarlife';
/* Полсекунды. Меньше — не успеет переключиться приложение на медленном телефоне, и мы
   уведём человека со страницы, которая вот-вот откроется. Больше — он успеет решить, что
   ничего не произошло, и нажмёт второй раз. */
const ЖДЁМ_МС = 700;

export function адресРаздела(раздел: Раздел): string {
  return `${СХЕМА}://раздел/${раздел}`;
}

/* Открыть раздел в установленном приложении, а не вышло — увести туда, где его берут.

   В самом приложении диплинк не нужен: мы уже внутри, и открывать себя же значит
   моргнуть экраном ради ничего. Там вызывающий просто переходит на раздел. */
export function открытьВПриложении(раздел: Раздел): void {
  if (isNative) return;
  const ушли = () => { window.location.href = ССЫЛКИ.гдеВзять; };

  /* Скрытая ссылка, а не location.href: в части браузеров попытка перейти по
     незарегистрированной схеме через location рушит текущую страницу с ошибкой, и человек
     остаётся ни с чем. Клик по ссылке в тех же условиях просто не делает ничего. */
  const a = document.createElement('a');
  a.href = адресРаздела(раздел);
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);

  const таймер = window.setTimeout(() => {
    /* Страница ещё видима — значит приложение не перехватило ссылку. Скрытая вкладка
       означает обратное: система показала приложение, и уводить некуда. */
    if (!document.hidden) ушли();
  }, ЖДЁМ_МС);

  /* Ушли в приложение — отменяем запасной путь. Иначе человек вернётся в браузер и
     обнаружит, что его без спроса увели на страницу загрузки. */
  const отменить = () => {
    if (document.hidden) window.clearTimeout(таймер);
  };
  document.addEventListener('visibilitychange', отменить, { once: true });
}

/* Разбор входящего адреса — на стороне приложения.

   Без него ссылка ведёт «в приложение», и человек попадает на «Сегодня», где начинает
   искать то, за чем шёл. Раздел в пути именно для этого. */
export function разделИзАдреса(url: string): Раздел | null {
  const m = /^sugarlife(?:\.pro)?:\/\/раздел\/([^/?#]+)/i.exec(url.trim());
  const имя = m ? decodeURIComponent(m[1]) : null;
  return имя === 'диагностика' || имя === 'приборы' || имя === 'поиск' ? имя : null;
}
