/* Переживёт ли приложение уход с экрана — вопрос к платформе, не к движку (#380).

   В режиме Doze система игнорирует замки бодрствования и приостанавливает сеть всем,
   кроме приложений из списка исключений. То есть выключенный экран может означать не
   «мониторинг спит», а «мониторинг выключен», и узнаёт человек об этом задним числом —
   по дырке в ленте показаний.

   СЛОВА ЖИВУТ В ЯДРЕ, а не здесь. Вопрос один и тот же на двух платформах и у двух
   изданий, и ответ должен быть один: разные слова на один вопрос — это два разных
   ответа. Отсюда уходит только запрос, обратно приходит готовое: проблема ли это, что
   происходит, что делать и можем ли мы открыть нужный экран сами. */
import { registerPlugin, Capacitor } from '@capacitor/core';

export interface ФонОтвет {
  /** Выдано ли системное исключение из оптимизации батареи. */
  ignoring: boolean;
  manufacturer: string;
  /** Есть ли о чём говорить. false — экран готовности молчит. */
  problem: boolean;
  reason: string;
  whatToDo: string;
  /* Открыть системный экран исключений мы можем, вендорский «Запуск приложений» — нет,
     никаким API. Обещать кнопку, которая никуда не ведёт, хуже, чем показать путь
     текстом: человек нажмёт, попадёт не туда и решит, что сделал. */
  weCanOpenSettings: boolean;
}

interface Плагин {
  batteryOptimization(): Promise<ФонОтвет>;
  requestBatteryExemption(): Promise<{ opened: 'dialog' | 'settings' }>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

/* null — «спросить не у кого»: браузер, iOS или сборка старше этих методов. Это НЕ
   «всё в порядке», и путать их нельзя: молчание про фон читается как обещание, что в
   фоне всё работает, а мы этого не знаем. */
export async function фонГотовность(): Promise<ФонОтвет | null> {
  if (!Capacitor.isNativePlatform()) return null;
  try {
    return await Native.batteryOptimization();
  } catch {
    return null;
  }
}

/** Показать системную просьбу. Зовётся только когда weCanOpenSettings. */
export async function попроситьИсключение(): Promise<boolean> {
  try {
    await Native.requestBatteryExemption();
    return true;
  } catch {
    return false;
  }
}

/* ФОНОВОЕ БОДРСТВОВАНИЕ НА iOS (#388).

   Тот же вопрос — «переживёт ли мониторинг уход с экрана» — но у айфона на него другой
   ответ, и потому другой орган управления. Фоновый режим `bluetooth-central` будит нас,
   когда прибор что-то прислал: пока сенсор на связи, всё хорошо само. А у человека на
   одном облаке прибора нет вовсе — будить нечем, система приложение приостанавливает, и
   цифры из Nightscout перестают приходить до следующего открытия.

   Именно так живёт наблюдатель — родитель, который смотрит на чужой сенсор. Ему свежесть
   цифры важнее всех, и именно он остаётся без неё.

   Приём взят у xDrip4iOS: проигрывать миллисекунду тишины раз в несколько секунд, чтобы
   система не сочла процесс бездельником. Это стоит батареи, поэтому включает его человек,
   а не мы за него: включённое по умолчанию бодрствование съедало бы заряд у всех ради
   случая, который есть не у всех. */
export type РежимБодрствования = 'выключено' | 'обычное' | 'настойчивое';

export interface Бодрствование {
  режим: РежимБодрствования;
  /** Список возможных значений приходит из натива — чтобы экран не держал их копией. */
  режимы: РежимБодрствования[];
}

interface ПлагинФона {
  backgroundKeepAlive(): Promise<{ mode: string; modes: string[] }>;
  setBackgroundKeepAlive(o: { mode: string }): Promise<{ mode: string }>;
}
const NativeФон = registerPlugin<ПлагинФона>('SugarLifeBridge');

export const бодрствованиеВозможно = (): boolean =>
  Capacitor.isNativePlatform() && Capacitor.getPlatform() === 'ios';

export async function бодрствование(): Promise<Бодрствование | null> {
  if (!бодрствованиеВозможно()) return null;
  try {
    const r = await NativeФон.backgroundKeepAlive();
    return {
      режим: (r.mode as РежимБодрствования) ?? 'выключено',
      режимы: (r.modes as РежимБодрствования[]) ?? ['выключено', 'обычное', 'настойчивое'],
    };
  } catch {
    /* Метода нет — сборка старше. Это не «выключено»: сказать «выключено» значило бы
       обещать выключатель, которого в этой сборке нет. */
    return null;
  }
}

export async function задатьБодрствование(режим: РежимБодрствования): Promise<boolean> {
  if (!бодрствованиеВозможно()) return false;
  try { await NativeФон.setBackgroundKeepAlive({ mode: режим }); return true; } catch { return false; }
}

/* Слова про режимы живут здесь, а не в натив-коде: это подписи, а не поведение. Цена
   названа в каждой — человек выбирает между свежестью и зарядом, и выбирать вслепую
   он не должен. */
export const ПОДПИСЬ_БОДРСТВОВАНИЯ: Record<РежимБодрствования, { имя: string; цена: string }> = {
  выключено: { имя: 'Выключено', цена: 'система усыпит приложение — цифры замрут до следующего открытия' },
  обычное: { имя: 'Обычное', цена: 'напоминаем системе о себе раз в пять секунд' },
  настойчивое: { имя: 'Настойчивое', цена: 'раз в две секунды — надёжнее и заметнее по батарее' },
};
