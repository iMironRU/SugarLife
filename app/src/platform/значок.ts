import { registerPlugin, Capacitor } from '@capacitor/core';
import { isNative } from './appUpdate';

/* САХАР ЦИФРАМИ НА ЗНАЧКЕ ПРИЛОЖЕНИЯ (SugarLife#500).

   Значок умеет только целое число — ни запятой, ни единиц, ни стрелки. Поэтому вид числа это выбор
   с ценой, и делает его человек, а не мы за него:

     десятые «79» — ничего не теряется, но первый день читается как чужая единица;
     целые «8»    — привычно сразу, зато 7,6 и 8,4 выглядят одинаково: «нормально» и «пора смотреть»
                    сливаются в одно;
     мг «142»     — привычно тем, кто вырос на mg/dL.

   Список видов приходит от платформы, а не хранится здесь копией: появится новый — он появится и на
   экране, без правки интерфейса. */

export type ВидЗначка = 'выключен' | 'сахар' | 'десятые' | 'целые' | 'мг';

interface Плагин {
  glucoseBadge(): Promise<{ mode: string; modes: string[] }>;
  setGlucoseBadge(o: { mode: string }): Promise<{ mode: string }>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

export interface ЗначокСостояние {
  вид: ВидЗначка;
  виды: ВидЗначка[];
}

export const значокВозможен = (): boolean => isNative;

/** null — платформа не та или сборка старше значка: тогда настройки не показываем вовсе. */
export async function состояниеЗначка(): Promise<ЗначокСостояние | null> {
  if (!значокВозможен()) return null;
  try {
    const r = await Native.glucoseBadge();
    const виды = (Array.isArray(r.modes) ? r.modes : []) as ВидЗначка[];
    return { вид: (r.mode as ВидЗначка) || 'выключен', виды: виды.length ? виды : ['выключен'] };
  } catch { return null; }
}

export async function задатьЗначок(вид: ВидЗначка): Promise<boolean> {
  if (!значокВозможен()) return false;
  try { await Native.setGlucoseBadge({ mode: вид }); return true; } catch { return false; }
}

/** Как называется вид по-человечески и что он значит. Пример показывает цену выбора лучше слов. */
export const ЗНАЧОК_СЛОВАМИ: Record<ВидЗначка, { имя: string; под: string }> = {
  выключен: { имя: 'Не показывать', под: 'значок остаётся чистым' },
  /* Запятая на значке возможна (#550): поле `badge` у уведомления — число с плавающей точкой, и
     разделитель система ставит сама по локали телефона. Мы считали иначе, потому что смотрели
     только на `setBadgeCount(Int)`. */
  сахар: { имя: 'Как везде', под: '7,9 → 7,9 · то же число, что на всех экранах' },
  десятые: { имя: 'Десятые, без запятой', под: '7,9 → 79 · ничего не теряется' },
  целые: { имя: 'Целыми', под: '7,9 → 8 · 7,6 и 8,4 будут выглядеть одинаково' },
  мг: { имя: 'В мг/дл', под: '7,9 → 142 · привычно тем, кто считает в мг/дл' },
};

/** На Android число на значке рисует лаунчер, и умеет это не каждый. Молчать об этом нельзя. */
export const оговоркаЗначка = (): string | null =>
  Capacitor.getPlatform() === 'android'
    ? 'Число на иконке рисует лаунчер телефона. Некоторые показывают только точку или ничего — это их решение, и повлиять на него мы не можем.'
    : null;
