import { isNative } from './appUpdate';

/* Может ли приложение открыться БЕЗ СЕТИ (SugarLife#359).

   С телефона: PWA выходит из фона на плохой связи — и белый экран. Белый, а не наш
   тёмный: значит не доехал сам документ. Оболочка у нас лежит в кэше service worker
   ровно для этого случая, но проверить с чужого телефона нечем, а «должно работать» —
   не ответ.

   GitHub Pages отдаёт index.html с `max-age=600`. Через десять минут браузер обязан
   сходить на сервер, и на плохой связи это ожидание ничем не ограничено. Единственное,
   что спасает, — воркер, отдающий оболочку из кэша, не спрашивая сеть. Значит вопрос
   один: доехал ли он.

   Поэтому не «должно работать», а измеримо: есть ли воркер, УПРАВЛЯЕТ ли он этой
   страницей и лежит ли в его кэше сам документ. Три разных ответа, и путают их чаще
   всего: зарегистрированный воркер, который ещё не управляет страницей, при следующем
   запуске её не спасёт. */

export interface СостояниеОболочки {
  поддержка: boolean;      // воркеры вообще есть в этом браузере
  зарегистрирован: boolean;
  управляет: boolean;      // именно эта страница идёт через воркер
  оболочкаВКэше: boolean;  // документ лежит в кэше — запуск без сети возможен
  файлов: number;
}

export const ПУСТО: СостояниеОболочки = {
  поддержка: false, зарегистрирован: false, управляет: false, оболочкаВКэше: false, файлов: 0,
};

export async function состояниеОболочки(): Promise<СостояниеОболочки> {
  /* В нативной сборке вопроса нет: файлы лежат в самом приложении, сеть для запуска не
     нужна вовсе. Показывать там «оболочка не сохранена» значило бы пугать поломкой,
     которой не существует. */
  if (isNative || typeof navigator === 'undefined' || !('serviceWorker' in navigator)) {
    return { ...ПУСТО, поддержка: false };
  }
  const reg = await navigator.serviceWorker.getRegistration().catch(() => null);
  const управляет = !!navigator.serviceWorker.controller;

  let оболочкаВКэше = false;
  let файлов = 0;
  try {
    const имена = await caches.keys();
    for (const имя of имена) {
      const c = await caches.open(имя);
      const ключи = await c.keys();
      файлов += ключи.length;
      /* Ищем именно ДОКУМЕНТ, а не «хоть что-нибудь». Кэш с картинками и шрифтами, но
         без index.html, offline-запуска не даёт: браузеру некуда прийти. */
      if (!оболочкаВКэше) {
        оболочкаВКэше = ключи.some((r) => {
          const u = new URL(r.url);
          return u.pathname.endsWith('/') || u.pathname.endsWith('/index.html');
        });
      }
    }
  } catch { /* приватный режим — кэшей нет, и это честный ответ «нет» */ }

  return { поддержка: true, зарегистрирован: !!reg, управляет, оболочкаВКэше, файлов };
}

/* Слово для человека. Разделяем «сохранено» и «сохранено, но эта страница идёт мимо
   воркера»: во втором случае следующий запуск без сети всё ещё может не открыться, и
   молчать об этом нельзя. */
export function словоОболочки(с: СостояниеОболочки): { главное: string; пояснение: string } {
  if (!с.поддержка) {
    return {
      главное: 'не требуется',
      пояснение: 'Файлы приложения лежат на устройстве — запуск не зависит от сети.',
    };
  }
  if (!с.зарегистрирован) {
    return {
      главное: 'не сохранено',
      пояснение: 'Без сети приложение не откроется. Откройте его один раз при хорошей связи — оболочка сохранится сама.',
    };
  }
  if (!с.управляет) {
    return {
      главное: 'сохраняется',
      пояснение: 'Оболочка есть, но эта вкладка открыта мимо неё. После следующего запуска приложение будет открываться и без сети.',
    };
  }
  if (!с.оболочкаВКэше) {
    return {
      главное: 'неполно',
      пояснение: 'Часть файлов сохранена, а стартовой страницы среди них нет — без сети запуск не гарантирован. Обновите приложение при хорошей связи.',
    };
  }
  return {
    главное: 'сохранено',
    пояснение: `Приложение откроется без сети: ${с.файлов} файлов оболочки лежат на устройстве. Данные при этом обновятся, когда связь появится.`,
  };
}
