import { describe, it, expect } from 'vitest';
import { ПОДПИСЬ_БОДРСТВОВАНИЯ, type РежимБодрствования } from './фон';

/* Выбор между свежестью и зарядом человек делает сам (#388) — значит цена каждого режима
   должна быть названа. Кнопка «Настойчивое» без слов о том, чем она отличается, это не
   выбор, а угадывание: обе выглядят одинаково, а батарею тратят по-разному. */
describe('режимы фонового бодрствования названы вместе с ценой', () => {
  const режимы: РежимБодрствования[] = ['выключено', 'обычное', 'настойчивое'];

  it('у каждого режима есть имя и цена', () => {
    for (const р of режимы) {
      expect(ПОДПИСЬ_БОДРСТВОВАНИЯ[р]?.имя, р).toBeTruthy();
      expect(ПОДПИСЬ_БОДРСТВОВАНИЯ[р]?.цена, р).toBeTruthy();
    }
  });

  /* «Выключено» — не нейтральное состояние, а последствие: приложение уснёт. Если написать
     здесь пусто или «ничего не делаем», человек прочитает это как «всё в порядке». */
  it('выключенный режим говорит о последствии, а не о бездействии', () => {
    expect(ПОДПИСЬ_БОДРСТВОВАНИЯ.выключено.цена).toMatch(/усып|замр|засн/);
  });

  /* Настойчивый режим стоит батареи, и об этом сказано прямо: обещание надёжности без
     упоминания цены — половина правды. */
  it('настойчивый режим признаётся, что стоит батареи', () => {
    expect(ПОДПИСЬ_БОДРСТВОВАНИЯ.настойчивое.цена).toMatch(/батаре|заряд/);
  });
});
