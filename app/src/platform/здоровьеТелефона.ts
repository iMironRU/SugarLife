import { registerPlugin, Capacitor } from '@capacitor/core';
import { уНатива } from './уНатива';

/* ВЕС И ДАВЛЕНИЕ ИЗ «ЗДОРОВЬЯ» ТЕЛЕФОНА (SugarLife#557).

   Правило проекта — нулевой ручной ввод того, что система знает. Вес и давление человек вводил
   руками, хотя их давно записали его весы, тонометр или часы: мы просили ввести заново то, что
   лежит в телефоне.

   ТОЛЬКО ЧТЕНИЕ И ТОЛЬКО ЭТИ ДВЕ ВЕЛИЧИНЫ. Запись наружу (глюкоза, инсулин, углеводы) идёт через
   коннекторы движка — заводить второй путь до ответа ядра нельзя. Права на запись не просим вовсе:
   разрешение, которым не пользуются, однажды становится вопросом «зачем им это».

   ПРАВО НА ЧТЕНИЕ НЕВОЗМОЖНО ПРОВЕРИТЬ. Apple намеренно не сообщает приложению, дали ли ему читать:
   по одному факту отказа можно было бы догадаться о диагнозе. Поэтому «нет данных» и «не дали»
   выглядят одинаково — и говорить об этом человеку надо честно, а не изображать поломку. */

interface Плагин {
  healthRead(): Promise<{
    доступно?: boolean;
    вес?: number; весКогда?: number;
    верх?: number; низ?: number; давлениеКогда?: number;
  }>;
}
const Native = registerPlugin<Плагин>('SugarLifeBridge');

export interface ИзЗдоровья {
  вес: { значение: number; когда: number } | null;
  давление: { верх: number; низ: number; когда: number } | null;
}

/** Умеет ли платформа отдать эти данные вообще. На Android и в браузере — нет. */
export const здоровьеТелефонаВозможно = (): boolean => Capacitor.getPlatform() === 'ios';

/** null — платформа не та или сборка старше метода: тогда кнопки нет вовсе. */
export async function взятьИзЗдоровья(): Promise<ИзЗдоровья | null> {
  if (!здоровьеТелефонаВозможно()) return null;
  return уНатива('healthRead', async () => {
    const о = await Native.healthRead();
    if (!о?.доступно) return null;
    return {
      вес: о.вес != null && о.весКогда != null
        ? { значение: Math.round(о.вес * 10) / 10, когда: о.весКогда } : null,
      давление: о.верх != null && о.низ != null && о.давлениеКогда != null
        ? { верх: Math.round(о.верх), низ: Math.round(о.низ), когда: о.давлениеКогда } : null,
    };
  }, null);
}
