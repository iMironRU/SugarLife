import { вЖурналДвижка } from '@/sources/bridge';

/* СПРОСИТЬ НАТИВ И ОСТАВИТЬ СЛЕД (SugarLife#668).

   В вебе девяносто шесть мест, где ошибка гасится молча, и тридцать семь из них — обёртки над
   нативом одной формы:

       try { await Native.testAlarm(); return true; } catch { return false; }

   Часть отказов законна: метода нет в сборке постарше, приложение живёт дальше. Но отличить «метода
   нет» от «метод есть и упал» было НЕЛЬЗЯ НИОТКУДА — следа не оставалось ни одного.

   У натива для такого давно есть сторож (`scripts/молчаливые-отказы.sh`): каждая ветка отказа обязана
   оставить строку в журнале движка. У веба сторожа не было, и веб этим пользовался.

   ОДНА ЗАПИСЬ НА ИМЯ ЗА СЕАНС. Наивный след залил бы журнал: `фонГотовность` спрашивают на каждом
   заходе в раздел, и на старом телефоне это сотни одинаковых строк — ровно тот мусор, в котором
   28 августа утонула настоящая причина. Первый отказ пишем, повторы считаем молча.

   ЧЕГО ЗДЕСЬ НЕТ. Это не «обработка ошибок»: помощник ничего не чинит и ничего не решает за
   вызывающего. Он только не даёт отказу пройти бесследно. Что показать человеку — по-прежнему
   решает тот, кто звал. */

/** Имена, о чьём отказе уже сказано. Повторы считаем, но не пишем. */
const сказано = new Map<string, number>();

export async function уНатива<T>(имя: string, зов: () => Promise<T>, приОтказе: T): Promise<T> {
  try {
    return await зов();
  } catch (e) {
    const было = сказано.get(имя) ?? 0;
    сказано.set(имя, было + 1);
    if (было === 0) {
      /* Уровень Debug, а не Warn: отсутствующий метод — обычная жизнь на старой сборке, и
         предупреждением она забьёт то, что предупреждением быть должно. */
      вЖурналДвижка('Debug', 'native', `${имя}: ${(e as Error)?.message ?? 'отказ без причины'}`);
    }
    return приОтказе;
  }
}

/** Сколько раз натив отказал по этому имени — для разбора и для тестов. */
export function отказовНатива(имя: string): number {
  return сказано.get(имя) ?? 0;
}

/** Только для тестов: забыть накопленное. */
export function забытьОтказы(): void {
  сказано.clear();
}
