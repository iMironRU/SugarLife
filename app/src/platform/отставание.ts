/* Отстало ли приложение от сервера (#386).

   Правило вынесено отдельно и с тестом, потому что ошибка здесь незаметна: она не падает
   и не рисует ничего лишнего — она просто МОЛЧИТ, а человек продолжает ходить со старой
   сборкой и считать её свежей. Так и вышло: сборка на телефоне отстала на две версии,
   приложение об этом не сказало ни слова, и обнаружилось это только по отсутствию
   экрана, который мы выкатили накануне.

   Сравниваем СВОЮ сборку с серверной, а не «новее/старее»: у коротких SHA нет порядка,
   и придумывать его нельзя. «Не совпадает» — достаточный повод сказать человеку, что
   он не на том, что выложено. */
export function отсталиЛи(моя: string, наСервере: string | null | undefined): boolean {
  if (!наСервере) return false;          // не спросили или не ответили — молчим, а не пугаем
  if (!моя || моя === 'dev') return false; // сборка из исходников заведомо не совпадёт
  return моя !== наСервере;
}

/* Чем помечено «я уже сказал „потом“».

   Ключом была ОДНА своя сборка — и это тупик: сказав «потом», человек больше не получал
   предложений НИКОГДА, потому что его сборка не менялась, а сменить её можно было только
   этим предложением. Дверь запиралась с той стороны, где стоит человек.

   Пара «откуда → куда» развязывает узел: следующий релиз даёт другую пару и спрашивает
   заново. Пока релиз тот же — молчим, как и обещали. */
export const КЛЮЧ_ОТКАЗА = 'sl.update.postponed.v1';

export function ключОтказа(моя: string, наСервере: string | null | undefined): string {
  return `${моя}→${наСервере ?? '?'}`;
}
