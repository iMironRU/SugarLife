import { describe, it, expect } from 'vitest';
import { проверитьЕслиПора, пораЛи, ПАУЗА_МС, type Мир } from './otaWatch';
import type { ОтаБандл } from './appUpdate';

/* Автопроверка обновления (SugarLife#312). Проверяем не «находит ли» — это дело сети, —
   а два правила, которые легко нарушить незаметно: не чаще положенного и отметка ДО
   запроса. Оба про чужой трафик, а он у многих считанный. */

const бандл: ОтаБандл = { build: 'abc1234', version: '0.3.0-abc1234', url: 'https://example/ota.zip' };

function мир(ответ: ОтаБандл | 'нет' | 'ошибка' = бандл, нативно = true) {
  const хранилище = new Map<string, string>();
  let спросили = 0;
  const м: Мир = {
    прочитать: (k) => хранилище.get(k) ?? null,
    записать: (k, v) => { хранилище.set(k, v); },
    узнать: async () => { спросили += 1; return ответ; },
    нативно,
  };
  return { м, сколькоСпросили: () => спросили };
}

describe('когда спрашивать сервер', () => {
  it('первый раз — спрашиваем', async () => {
    const { м, сколькоСпросили } = мир();
    expect(await проверитьЕслиПора(1_000_000, м)).toEqual(бандл);
    expect(сколькоСпросили()).toBe(1);
  });

  /* Проверка на каждом возврате из фона — фоновый трафик, которого никто не заказывал. */
  it('второй раз подряд — молчим', async () => {
    const { м, сколькоСпросили } = мир();
    await проверитьЕслиПора(1_000_000, м);
    expect(await проверитьЕслиПора(1_000_000 + ПАУЗА_МС - 1, м)).toBe(null);
    expect(сколькоСпросили()).toBe(1);
  });

  it('пауза вышла — спрашиваем снова', async () => {
    const { м, сколькоСпросили } = мир();
    await проверитьЕслиПора(1_000_000, м);
    await проверитьЕслиПора(1_000_000 + ПАУЗА_МС + 1, м);
    expect(сколькоСпросили()).toBe(2);
  });

  /* Отметка ставится ДО запроса. Иначе при недоступной сети приложение ходило бы за
     манифестом на каждом возврате из фона — то есть чаще всего именно тогда, когда
     сеть плохая. */
  it('неудачный запрос тоже сбрасывает паузу', async () => {
    const { м, сколькоСпросили } = мир('ошибка');
    expect(await проверитьЕслиПора(2_000_000, м)).toBe(null);
    expect(await проверитьЕслиПора(2_000_000 + 1000, м)).toBe(null);
    expect(сколькоСпросили()).toBe(1);
  });

  it('в вебе не спрашиваем вовсе — там обновление ведёт service worker', async () => {
    const { м, сколькоСпросили } = мир(бандл, false);
    expect(await проверитьЕслиПора(3_000_000, м)).toBe(null);
    expect(сколькоСпросили()).toBe(0);
  });

  it('мусор в отметке не запирает проверку навсегда', () => {
    expect(пораЛи('не число', 5_000_000)).toBe(true);
    expect(пораЛи(null, 5_000_000)).toBe(true);
  });
});
