import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { перекрытоЛи, естьОткрытаяШторка, КЛЮЧ_СТОРОЖА, ПОРОГ_НЕУДАЧ, ПРИЗНАК_ЖИВОГО } from './rescue';

/* Спасение проверяем тестами по неприятной причине: его правильность видна только
   тогда, когда всё остальное уже сломано. Поймать ошибку в нём «по ходу дела»
   невозможно — к моменту, когда оно понадобится, чинить будет нечем. */

/* Поддельные узлы вместо настоящего DOM: правило спрашивает у узла ровно одно —
   попадает ли он под селектор, — и подделка отвечает на тот же вопрос. Настоящий DOM
   в тестах потребовал бы отдельной среды ради двух вызовов. */
const подПальцем = (селекторы: string[]) => ({
  closest: (сел: string) => (селекторы.some((с) => сел.includes(с)) ? {} : null),
});
const корень = (есть: boolean) => ({ querySelector: () => (есть ? {} : null) });

describe('перекрыт ли экран', () => {
  it('под пальцем модалка, а открытых шторок нет — это перекрытие', () => {
    expect(перекрытоЛи(подПальцем(['.sheet-modal']), false)).toBe(true);
  });

  /* Открытая шторка под пальцем — это работа, а не поломка. Без этой проверки
     спасение выскакивало бы поверх любой шторки, и человек учился бы его закрывать —
     ровно тогда, когда однажды оно окажется настоящим. */
  it('открытая шторка под пальцем — не перекрытие', () => {
    expect(перекрытоЛи(подПальцем(['.sheet-modal']), true)).toBe(false);
  });

  it('под пальцем обычное содержимое — всё в порядке', () => {
    expect(перекрытоЛи(подПальцем([]), false)).toBe(false);
  });

  it('под пальцем ничего — не выдумываем поломку', () => {
    expect(перекрытоЛи(null, false)).toBe(false);
  });

  it('затемнение поверх экрана считаем перекрытием', () => {
    expect(перекрытоЛи(подПальцем(['ion-backdrop']), false)).toBe(true);
  });
});

describe('признак открытой шторки', () => {
  it('спрашиваем у разметки, а не у своего состояния', () => {
    expect(естьОткрытаяШторка(корень(false))).toBe(false);
    expect(естьОткрытаяШторка(корень(true))).toBe(true);
  });

  /* Селектор — половина правила: шторки живут в разметке всегда, и «есть ion-modal»
     значило бы «шторка открыта» ровно никогда не в ту сторону. */
  it('открытость ищется исключением скрытых', () => {
    let спросили = '';
    естьОткрытаяШторка({ querySelector: (с: string) => { спросили = с; return null; } });
    expect(спросили).toContain(':not(.overlay-hidden)');
  });
});

/* Сторож запуска живёт вне бандла и потому не может импортировать эти константы.
   Дублирование осознанное, а тест — единственное, что мешает копиям разъехаться:
   разошедшись, они не сломают сборку и не выдадут ошибку, просто спасение перестанет
   срабатывать. Узнаем об этом в тот единственный день, когда оно понадобится. */
describe('сторож вне бандла', () => {
  const сторож = readFileSync('public/boot-guard.js', 'utf8');

  it('ключ хранилища тот же, что в приложении', () => {
    expect(сторож).toContain(`'${КЛЮЧ_СТОРОЖА}'`);
  });

  it('порог неудачных запусков тот же', () => {
    expect(сторож).toMatch(new RegExp(`ПОРОГ\\s*=\\s*${ПОРОГ_НЕУДАЧ}\\b`));
  });

  it('умеет и обновиться, и загрузиться заново', () => {
    expect(сторож).toContain('SKIP_WAITING');
    expect(сторож).toContain('unregister');
  });

  /* Приложение зовёт эти две функции; переименование в одном файле молча оставит
     сторожа висеть на экране или, наоборот, никогда не сработать. */
  it('объявляет то, что зовёт приложение', () => {
    expect(сторож).toContain('window.слЖив');
    expect(сторож).toContain('window.слСпасение');
  });

  /* Без этой проверки автоматическая попытка спасения превращается в петлю: сборка
     сломана, спасение перезагружает, счётчик снова за порогом — и так по кругу, не
     давая даже нажать кнопку. */
  it('сам перезагружается только при живом ждущем обновлении', () => {
    expect(сторож).toMatch(/ждёт\s*=\s*reg && reg\.waiting/);
    expect(сторож).toMatch(/if \(ждёт \|\| !самиРешили\)/);
  });

  /* Первый запуск на новом телефоне — это загрузка всего приложения по сети, и
     двенадцати секунд ей мало на слабой связи. Без отдельного срока человек встречал
     бы приложение сообщением о поломке в момент, когда всё исправно (#209). */
  it('первому запуску даёт больше времени, чем повторному', () => {
    const первый = /ЖДЁМ_ПЕРВЫЙ\s*=\s*(\d+)/.exec(сторож)?.[1];
    const обычный = /ЖДЁМ\s*=\s*(\d+)/.exec(сторож)?.[1];
    expect(Number(первый)).toBeGreaterThan(Number(обычный));
  });

  /* Пока страница грузится, сообщать о поломке — врать: всё идёт, просто медленно. */
  it('во время загрузки страницы молчит', () => {
    expect(сторож).toContain("document.readyState !== 'complete'");
  });

  /* В фоне браузер растягивает таймеры: свёрнутое приложение легко «не успевает» за
     двенадцать секунд, будучи целым. Без этой проверки сторож сам становится той
     поломкой, от которой стережёт. */
  it('в фоне спасение не показывает', () => {
    expect(сторож).toContain("visibilityState === 'hidden'");
  });

  it('подключён в index.html обычным скриптом, а не модулем', () => {
    const html = readFileSync('index.html', 'utf8');
    expect(html).toMatch(/<script src="\/boot-guard\.js"><\/script>/);
  });
});

/* «Жив» привязан к разметке оболочки, а не к вызову render(). Если класс переименуют,
   приложение будет работать, а сторож — считать каждый запуск неудачным и однажды
   показать спасение поверх исправного экрана. */
describe('признак живого приложения', () => {
  it('оболочка приложения размечена тем же классом, который мы ждём', () => {
    const app = readFileSync('src/app/App.tsx', 'utf8');
    expect(app).toContain(ПРИЗНАК_ЖИВОГО.slice(1));
  });
});

