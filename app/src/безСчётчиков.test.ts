import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/* В ПРИЛОЖЕНИИ СЧЁТЧИКОВ НЕТ (решение владельца, 21.09.2026: «только на сайте, из приложения убери»).

   Счётчик Яндекс.Метрики добавили в `app/index.html`, имея в виду сайт. Но эта страница — не только
   сайт: она же стоит в нативном приложении на телефоне, она же уезжает бандлом по воздуху и она же
   открывается веб-версией в `/v2/`. Со включёнными `clickmap` и `trackLinks` счётчик отправлял бы
   в Яндекс нажатия и переходы внутри медицинского приложения — чей это сахар, на каком экране
   человек задержался ночью.

   Сайт — это страницы из `prototypes/` (главная и страница установки). Там счётчик остаётся.

   СТОРОЖ, А НЕ ДОГОВОРЁННОСТЬ. Ошибка была честной: файл называется `index.html`, как у любого
   сайта, и что он же — приложение, из его имени не видно. Значит её повторят, и узнать об этом
   надо до сборки, а не по трафику в отчёте Метрики. */

const СЧЁТЧИКИ = [
  'mc.yandex.ru',
  'metrika',
  'googletagmanager.com',
  'google-analytics.com',
];

describe('страница приложения', () => {
  it('не подключает счётчиков посещаемости', () => {
    const страница = readFileSync(join(process.cwd(), 'index.html'), 'utf8').toLowerCase();
    const найдено = СЧЁТЧИКИ.filter((с) => страница.includes(с));
    expect(найдено, 'счётчики — только на сайте (prototypes/), не в приложении').toEqual([]);
  });
});
