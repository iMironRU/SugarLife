/* ИЗДАНИЕ СБОРКИ — ОДНА КАЛИТКА В PRO (SugarLife#296).

   Издания разъезжаются СБОРКОЙ, а не содержимым репозитория. Причина не в порядке: в Pro появится
   пульт помпы — остановить и возобновить подачу, часы, базальный профиль. Это команды прибору, который
   вводит человеку инсулин, и в издании «просто посмотреть сахар» их не должно быть вовсе: ни экранов,
   ни кнопок, ни кода отправки. Не спрятанных — отсутствующих.

   ПОЧЕМУ ЭТОГО МАЛО — ПРОВЕРЯТЬ ПО ФЛАГАМ УМЕНИЙ. Флаги (`canSuspendResume` и соседи) говорят, умеет
   ли ПРИБОР. Это защита от случайности: сегодня они у всех драйверов `false`, и пульт не показался бы
   и без изданий. Но защита от случайности — не граница: настоящую даёт сборка, в которой кода просто
   нет.

   КАК ЭТО РАБОТАЕТ. `SUGARLIFE_EDITION` подставляется на сборке значением, а не читается в рантайме:
   в Lite условие ниже становится литеральной ложью, и сборщик выбрасывает ветку вместе со всем, что
   она тянет. Проверяется это не на глаз, а `scripts/edition-check.mjs` — он ищет в собранном Lite
   слова, которые есть только в Pro.

   Переменная та же, что у `capacitor.config.ts`: одно издание — одно имя. Два имени дали бы сборку,
   где приложение называется Pro, а бандл собран как Lite, и молча. Имя латиницей намеренно: кириллица
   в переменных окружения ломает workflow целиком и тоже молча (#448).

   ВСЁ, ЧТО ТОЛЬКО ДЛЯ PRO, ЛЕЖИТ В `src/pro/`. Импортировать оттуда напрямую нельзя ниоткуда, кроме
   этого файла: барьерный тест (`src/издание.test.ts`) следит, чтобы Pro не растёкся вкраплениями по
   общим экранам — тогда его нельзя было бы исключить, не разбирая каждый компонент. */

import type { РазделPro } from './pro/разделы';

export type Издание = 'lite' | 'pro';

const ИЗДАНИЕ: Издание = __ИЗДАНИЕ__ === 'pro' ? 'pro' : 'lite';

/** Собрано ли это издание с управлением подачей. Не «разрешено», а именно «есть в сборке». */
const ЭТО_PRO = ИЗДАНИЕ === 'pro';

/* Разделы Pro — лениво и только в Pro-сборке.

   Возвращаем загрузчик, а не компонент: в Lite здесь `null`, и ветка с `import()` до сборщика не
   доживает. Вызывающему остаётся честная развилка «есть раздел или нет», одинаковая и для отсутствия
   кода, и для прибора без умений. */
const загрузить = ЭТО_PRO ? () => import('./pro/разделы') : null;

/* Загруженный реестр держим здесь же. Стек страниц собирает раздел заново после перезапуска и делает
   это синхронно — спрашивать модуль обещанием ему нечем, а заводить второй способ загрузки значило бы
   получить два разных ответа на «есть ли этот раздел». */
let реестр: РазделPro[] = [];

/*
 * СБОРКА РЕШАЕТ, ЧТО ЕСТЬ; ДВИЖОК — ЧТО МОЖНО (SugarLife#294, решение владельца «спрашиваем движок,
 * кто он»).
 *
 * До сих пор Pro-разделы появлялись по одному признаку — какой сборкой нас собрали. Это утверждение
 * приложения о себе, а не наблюдаемый факт: Pro-бандл, запущенный поверх lite-движка, показал бы
 * пульт помпы, за которым нет тракта записи. Кнопка, которой нечем исполнить команду прибору,
 * вводящему инсулин, — худший вид пустого обещания.
 *
 * Теперь условий два, и они о разном:
 *
 *   — СБОРКА отвечает «есть ли код вовсе». Это граница безопасности: в Lite экранов и отправки нет
 *     физически, и проверяется это `scripts/edition-check.mjs` по собранному бандлу;
 *   — ДВИЖОК отвечает «умеет ли он подавать». Это наблюдаемый факт: тракт записи собран в отдельном
 *     исходнике ядра и в его lite-сборке не компилируется.
 *
 * Ни одно не заменяет другое. Уберём сборку — Pro растечётся по общим экранам и его нельзя будет
 * исключить; уберём движок — покажем пульт там, где команду исполнить нечем.
 *
 * МОЛЧАНИЕ МОСТА СЧИТАЕМ LITE. Старое ядро поля не шлёт, и в любом сомнении издание без управления
 * безопаснее.
 */
export async function взятьРазделыPro(изданиеДвижка?: Издание | null): Promise<РазделPro[]> {
  if (!загрузить || изданиеДвижка !== 'pro') return [];
  try {
    реестр = (await загрузить()).РАЗДЕЛЫ_PRO;
  } catch {
    /* Кусок не доехал (обрыв связи на первом заходе) — молчим списком, а не падаем: раздел просто
       не появится, и человек увидит приложение без него, а не белый экран. */
    реестр = [];
  }
  return реестр;
}

/** Раздел по метке — для восстановления стека. null означает «такого раздела в этой сборке нет». */
export function разделProПоId(id: string): РазделPro | null {
  return реестр.find((р) => р.id === id) ?? null;
}

/* Тип наружу отдаём отсюда же: `export type` исчезает при сборке и ничего за собой не тянет, а
   экранам нужно знать форму раздела, не заглядывая в каталог издания. */
export type { РазделPro } from './pro/разделы';
