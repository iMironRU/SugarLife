import type { РазделPro } from './pro/разделы';

export type Издание = 'lite' | 'pro';

export const ИЗДАНИЕ: Издание = __ИЗДАНИЕ__ === 'pro' ? 'pro' : 'lite';

/** Собрано ли это издание с управлением подачей. Не «разрешено», а именно «есть в сборке». */
export const ЭТО_PRO = ИЗДАНИЕ === 'pro';

/* Разделы Pro — лениво и только в Pro-сборке.

   Возвращаем загрузчик, а не компонент: в Lite здесь `null`, и ветка с `import()` до сборщика не
   доживает. Вызывающему остаётся честная развилка «есть раздел или нет», одинаковая и для отсутствия
   кода, и для прибора без умений. */
const загрузить = ЭТО_PRO ? () => import('./pro/разделы') : null;

/* Загруженный реестр держим здесь же. Стек страниц собирает раздел заново после перезапуска и делает
   это синхронно — спрашивать модуль обещанием ему нечем, а заводить второй способ загрузки значило бы
   получить два разных ответа на «есть ли этот раздел». */
let реестр: РазделPro[] = [];

/** Спросить разделы Pro. В Lite — пустой список, и ветка с загрузкой до сборки не доживает. */
export async function взятьРазделыPro(): Promise<РазделPro[]> {
  if (!загрузить) return [];
  try {
    реестр = (await загрузить()).РАЗДЕЛЫ_PRO;
  } catch {
    /* Кусок не доехал (обрыв связи на первом заходе) — молчим списком, а не падаем: раздел просто
       не появится, и человек увидит приложение без него, а не белый экран. */
    реестр = [];
  }
  return реестр;
}

/** Раздел по метке — для восстановления стека. null означает «такого раздела в этой сборке нет». */
export function разделProПоId(id: string): РазделPro | null {
  return реестр.find((р) => р.id === id) ?? null;
}

/* Тип наружу отдаём отсюда же: `export type` исчезает при сборке и ничего за собой не тянет, а
   экранам нужно знать форму раздела, не заглядывая в каталог издания. */
export type { РазделPro } from './pro/разделы';
