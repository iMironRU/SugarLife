import { useSyncExternalStore } from 'react';
import { прочитать, записать } from '@/settings/storage';
import { добавить, type ЗаписьДневника, type ВидЗаписи } from '@/domain/дневник';

/* Хранилище дневника экрана (#396). Правило добавления живёт в domain/дневник.ts и
   проверено тестами; здесь только чтение-запись и подписка для React. */
const КЛЮЧ = 'sl.diary.v1';

let список: ЗаписьДневника[] | null = null;
const subs = new Set<() => void>();

function загрузить(): ЗаписьДневника[] {
  if (список) return список;
  try {
    const s = прочитать(КЛЮЧ);
    список = s ? (JSON.parse(s) as ЗаписьДневника[]) : [];
  } catch { список = []; }
  return список;
}

/** Записать строку, которую человек ВИДЕЛ на экране, теми же словами. */
export function вДневник(
  вид: ВидЗаписи, главное: string, подпись?: string | null, однажды = false,
): void {
  const сейчас = Date.now();
  const было = загрузить();
  const стало = добавить(было, { ключ: `${вид}-${сейчас}`, когдаМс: сейчас, вид, главное, подпись }, сейчас, однажды);
  if (стало === было) return;             // повтор — ничего не изменилось
  список = стало;
  try { записать(КЛЮЧ, JSON.stringify(стало)); } catch { /* приватный режим — переживём */ }
  subs.forEach((f) => f());
}

export function дневник(): ЗаписьДневника[] { return загрузить(); }

/* «Обновились до сборки X» — записываем при старте, сверяя свою сборку с запомненной.

   Обновление приезжает тремя путями (service worker в вебе, OTA и APK в нативе), и
   ловить каждый по отдельности значило бы три раза написать одно и то же и один раз
   забыть. Сборка сменилась — значит обновление доехало, каким бы путём оно ни шло.

   Первый запуск не событие: там сравнивать не с чем, и строка «обновились» на чистой
   установке была бы неправдой. Просто запоминаем, с чего начали. */
const КЛЮЧ_СБОРКИ = 'sl.diary.build.v1';

export function отметитьСборку(сборка: string): void {
  if (!сборка || сборка === 'dev') return;   // сборка из исходников меняется каждый запуск
  const было = прочитать(КЛЮЧ_СБОРКИ);
  if (было === сборка) return;
  if (было) вДневник('сборка', `Обновились до сборки ${сборка}`, `было ${было}`);
  try { записать(КЛЮЧ_СБОРКИ, сборка); } catch { /* приватный режим */ }
}

export function useДневник(): ЗаписьДневника[] {
  return useSyncExternalStore(
    (cb) => { subs.add(cb); return () => { subs.delete(cb); }; },
    загрузить, загрузить,
  );
}
