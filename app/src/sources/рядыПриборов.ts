import { getBridge, type UiSnapshot } from './bridge';
import { putSeries, type Series } from './db';
import { устройствоРоли } from '@/domain/deviceState';

/*
 * ИСТОРИЯ ЗАРЯДА И ОСТАТКА КОПИТСЯ ИЗ СНИМКА ДВИЖКА, А НЕ ИЗ НАШЕЙ ЗАГРУЗКИ (#748).
 *
 * Копилка нужна потому, что вопросы к ней — недельные: «сколько помпа проработает на 1%» и
 * «остаток не двигается сколько часов». В облаке за один запрос лежат последние часы, и цикла
 * разряда там не увидеть; значит копим сами, по крупице из каждого снимка.
 *
 * Наполнял её `sources/deviceExtras` — наша собственная загрузка Nightscout. На нативной сборке
 * она молчит: облако держит движок, а у нас либо не включено, либо не пробивается (56 отказов за
 * сутки в журнале телефона). Копилка на телефоне оставалась пустой, и вместе с ней молча гасла
 * подсказка «резервуар не меняется N часов» — не ошибка, не прочерк, просто её никогда не было.
 *
 * Тот же класс беды, что и «до утра не хватит»: тихая деградация, которую видно только по тому,
 * что подсказка НЕ появилась. Такое не ловится глазами — поэтому источник и меняем на живой.
 *
 * В браузере снимок даёт Nightscout-шим, и точки идут оттуда же; вторая дорога (`deviceExtras`)
 * остаётся, потому что в браузере она жива и приносит историю глубже одного снимка. Обе пишут в
 * одно хранилище, дубли и середины плато отсеиваются при записи.
 */

/** Что берём у помпы: чем измеряем и где храним. */
const РЯДЫ: Array<{
  склад: Series;
  значение: (д: NonNullable<ReturnType<typeof устройствоРоли>>) => number | null | undefined;
  когда: (д: NonNullable<ReturnType<typeof устройствоРоли>>, снимокМс: number) => number;
}> = [
  {
    склад: 'reservoir',
    значение: (д) => д.reservoirU,
    /* Время НАБЛЮДЕНИЯ, а не прихода: помпа отдаёт остаток пачками, и метка прихода склеила бы
       часовое плато в одну минуту. Нет метки — считаем моментом снимка. */
    когда: (д, снимокМс) => д.reservoirAtMs ?? снимокМс,
  },
  {
    склад: 'battery',
    значение: (д) => д.batteryPct,
    когда: (_д, снимокМс) => снимокМс,
  },
];

export function копитьРядыПриборов(): () => void {
  /* Последнее записанное — чтобы не тревожить базу каждую минуту одним и тем же. Проверка
     дешёвая и снимает чтение всего склада на каждый снимок. */
  const записано = new Map<Series, string>();

  const принять = (с: UiSnapshot) => {
    const помпа = устройствоРоли(с, 'pump');
    if (!помпа) return;
    const снимокМс = с.monitor?.latestAtMs ?? Date.now();
    for (const ряд of РЯДЫ) {
      const v = ряд.значение(помпа);
      if (v == null || !Number.isFinite(v)) continue;
      const t = ряд.когда(помпа, снимокМс);
      if (!Number.isFinite(t) || t <= 0) continue;
      const ключ = `${t}:${v}`;
      if (записано.get(ряд.склад) === ключ) continue;
      записано.set(ряд.склад, ключ);
      void putSeries(ряд.склад, [{ t, v }]);
    }
  };

  return getBridge().subscribe(принять);
}
