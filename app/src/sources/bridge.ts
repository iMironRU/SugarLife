  /* Телефон подключён к магнитоле (rev ≥ 1.31): звук ведём в колонки, полный экран не показываем,
     громкость не трогаем — за рулём испуг это метры торможения. */
  inCar?: boolean;
  /* Готовая фраза для человека — за рулём она другая: дома надо съесть, в машине сначала
     остановиться. Слова живут в ядре, чтобы на двух платформах совет был один. */
  words?: string | null;
