/* Роль — то, к чему привязаны экран и алгоритм (rev ≥ 1.8, SugarLifeCore#34).

   До неё интерфейс сводил роль сам: искал среди devices[] сенсор, помпу, «кто
   основной». Это работало, пока источник был один. С каналами и облаком правило
   перестало быть очевидным, а алгоритм в движке нуждается в той же привязке — два
   канона расходятся всегда, и роль переехала в движок ПО НАШЕМУ правилу
   (domain/deviceState.ts, оно же эталон в их реализации).

   ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Расходки и чисел: резервуар, заряд, оба срока сенсора и
   сама глюкоза читаются с активного источника. Один срок на роли слил бы «день 12 из
   14» (паспортный) и предупреждение (реальный, у части сенсоров дольше) — а это
   разные вещи: одно пугает раньше времени, другое обещает больше, чем есть.

   Роль отвечает ровно на «кто сейчас за это отвечает и как мы до него дотягиваемся». */
export interface RoleView {
  /** 'cgm' | 'insulin' | 'meter'. Ввод инсулина — ОДНА роль: помпа и ручка это два
      способа делать одно, и переход МДИ↔помпа не должен терять историю роли. */
  role: string;
  /** Активный источник — правило (а): «откуда сейчас берутся цифры», облако тоже
      законный источник. На вопрос «на связи ли сама железка» отвечает via. */
  activeSourceId?: string | null;
  sourceIds?: string[];
  /** Текущий способ подачи — вид активного источника, только у роли insulin. */
  method?: 'pump' | 'pen' | null;
  /** Канал активного источника — из него строится «через что» человеку. */
  via?: 'direct' | 'bridged' | 'cloud' | null;
  /** С прямого/локального источника, даже когда активен облачный канал. */
  serial?: string | null;
  /* Почему роль наполняет не прямой путь (rev ≥ 1.13, SugarLifeCore#55). Готовая фраза
     вида «Medtronic 722 не на связи»; null — вопрос не стоит: путь прямой либо прямого
     пути у роли нет вовсе.

     Берём как есть и своей не подменяем — то же правило, что с remediation у облачных
     ошибок: движок знает, ЧТО именно молчит, а мы написали бы общее место. Наш расчёт
     причины (domain/sources.ts) остаётся запасным для старых сборок. */
  fallbackReason?: string | null;
}

/* Экземпляр ЖЕЛЕЗА (rev ≥ 1.8, SugarLifeCore#42/#44).

   Диспетчер устройств рисуется прямо отсюда, и это главное, что даёт проекция:
   раньше мы сами фильтровали devices[] по виду и гадали, где железка, где мост, а где
   облако, притворяющееся помпой. Облаков здесь нет по построению — облако это источник
   слота, а не железка: у него нет ни «рядом», ни «переподключить», ни батареи.

   Связь видна с обеих сторон: у слота (roles[].activeSourceId) — кто его наполняет, у
   железа (inSlot) — в каком слоте оно стоит. Одна связка, два конца — и ни одного
   места, где нам пришлось бы её выводить самим. */
export interface HardwareView {
  /** Тот же id, что мы шлём в connect/disconnect. */
  id: string;
  name: string;
  kind: 'sensor' | 'pump' | 'bridge';
  /** Понятное имя модели; null — модель неизвестна (законное состояние). */
  model?: string | null;
  connection: Link | string;
  status?: SourceStatus;
  /** Когда железку последний раз видели в эфире. */
  nearbyAtMs?: number | null;
  /** В каком слоте стоит СЕЙЧАС; null — ни в каком. */
  inSlot?: 'cgm' | 'insulin' | null;
  /* Цепочка — здесь же, а не только у проекции источника (rev ≥ 1.9, SugarLifeCore#50):
     диспетчер устройств строится из hardware[], и без этих полей два «нет связи»
     неразличимы. Смысл тот же: ссылка на мост и состояние первого звена, а собственный
     connection у такого устройства означает второе звено. */
  behindBridgeId?: string | null;
  bridgeConnection?: Link | string | null;
  autoConnect?: boolean;
  batteryPct?: number | null;
  rssi?: number | null;
  firmware?: string | null;
  /* Расходка ЭТОГО прибора (rev ≥ 1.11, SugarLifeCore#53): остаток в единицах, вольты
     помпы, время чтения. Числом, а не строкой: по нему считается «на сколько хватит», а
     monitor.reservoir форматирован и один на приложение.

     reservoirAtMs нужен, чтобы прогноз считался от времени НАБЛЮДЕНИЯ, а не от прихода
     снимка: помпа могла молчать час, и остаток за этот час уже уменьшился (#280). */
  reservoirU?: number | null;
  batteryV?: number | null;
  reservoirAtMs?: number | null;
  /* Когда прибор в последний раз ЧТО-ТО сообщил (rev ≥ 1.18, SugarLife#305): показание
     сенсора, состояние помпы. null — не сообщал ничего.

     Это третья, отдельная величина, и путать её с двумя соседними нельзя: nearbyAtMs —
     «видели рекламу в эфире», connection — «канал жив». Связь бывает живой, а данных
     нет, и именно этот случай человек читает как «сенсор работает». */
  latestAtMs?: number | null;
  /** Модель по справочнику приложения (rev ≥ 1.14) — то же, что у DeviceView. */
  deviceModel?: string | null;
  /* Стабильная личность прибора: серийник помпы, код сенсора (rev ≥ 1.11). Именно она
     различает два одинаковых прибора — то, что мы просили, доставая адрес регуляркой из
     id. Регулярка была догадкой о формате ключа; id проекционный и может смениться. */
  serial?: string | null;
  /* Адрес в эфире СЕЙЧАС (rev ≥ 1.11): MAC на Android, UUID телефона на iOS. Эфемерен —
     как личность не годится, но «какой из двух» различает. */
  bleId?: string | null;
  /* 'possibly' — связь не встаёт дольше тридцати секунд. Точное «занято телефоном X»
     ядро отложило (SugarLifeCore#41), и до тех пор это догадка, а не факт: так её и
     показываем — «возможно», без имени чужого телефона. */
  busy?: 'possibly' | null;
  /* Докуда включён подробный обмен (rev ≥ 1.25). null/отсутствует — обычный уровень.
     Держим временем, а не флагом: подробность гаснет сама, и «включено» без срока
     соврало бы через четверть часа. */
  logDetailUntilMs?: number | null;
  registryState?: 'Recorded' | 'Configured' | 'Linked' | 'Paused' | 'NotConfigured';
  /* Чего не хватает / чем занят — то же, что у DeviceView (мост 1.22/1.24). У железа это
     важнее: именно его карточку открывают, когда «не работает». */
  note?: string | null;
  progress?: string | null;
}

