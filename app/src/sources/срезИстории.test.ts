import { describe, it, expect } from 'vitest';
import { изСреза, type Срез } from './срезИстории';
import type { Entry } from '@/domain/types';

const сейчас = 100 * 86400e3;
const точка = (сколькоДнейНазад: number): Entry =>
  ({ t: сейчас - сколькоДнейНазад * 86400e3, mgdl: 100, mmol: 5.5, dir: 'Flat' });

const срез = (дней: number, точки: Entry[]): Срез =>
  ({ windowMs: дней * 86400e3, entries: точки, at: сейчас });

describe('узкое окно берём из широкого, а не читаем заново', () => {
  it('то же окно — отдаём как есть', () => {
    const с = срез(14, [точка(1), точка(10)]);
    expect(изСреза(с, 14 * 86400e3, сейчас)).toBe(с.entries);
  });

  /* Ради этого всё и написано: семь дней лежат внутри четырнадцати. */
  it('окно уже — берём хвост широкого', () => {
    const с = срез(14, [точка(13), точка(10), точка(3), точка(1)]);
    const взято = изСреза(с, 7 * 86400e3, сейчас);
    expect(взято).toHaveLength(2);
    expect(взято!.every((e) => e.t >= сейчас - 7 * 86400e3)).toBe(true);
  });

  /* Отдать узкий вместо широкого значило бы показать разбор за две недели по данным за одну —
     то есть соврать тихо, вместо того чтобы честно сказать «читаю». */
  it('окно шире прочитанного — читать', () => {
    expect(изСреза(срез(7, [точка(1)]), 14 * 86400e3, сейчас)).toBeNull();
  });

  it('среза нет — читать', () => {
    expect(изСреза(null, 7 * 86400e3, сейчас)).toBeNull();
  });

  /* Граница считается от СЕЙЧАС, а не от момента чтения: пока человек листал периоды, время шло. */
  it('граница сдвигается вместе со временем', () => {
    const с = срез(14, [точка(8), точка(6)]);
    /* Через двое суток после чтения восьмидневная точка выпадает из недельного окна. */
    const позже = сейчас + 2 * 86400e3;
    expect(изСреза(с, 7 * 86400e3, позже)).toHaveLength(0);
    expect(изСреза(с, 7 * 86400e3, сейчас)).toHaveLength(1);
  });
});
