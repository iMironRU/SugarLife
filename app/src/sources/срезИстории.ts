/* Записи здесь нужны только временем: какой у них тип, знает вызывающий, а нам всё равно.
   Так модуль не тянет за собой ни одну из двух наших разновидностей `Entry` — и не окажется
   привязан к той, которая однажды разойдётся с другой. */
export interface Срез<З extends { t: number } = { t: number }> {
  /** Какое окно прочитано, в миллисекундах. */
  windowMs: number;
  entries: З[];
  /** Когда прочитан. */
  at: number;
}

/**
 * Что отдать из уже прочитанного среза для запрошенного окна.
 *
 * @returns записи, если срез покрывает окно; null — если нет и придётся читать.
 */
export function изСреза<З extends { t: number }>(
  срез: Срез<З> | null, windowMs: number, сейчас: number,
): З[] | null {
  if (!срез) return null;
  /* Ровно то же окно — отдаём как есть, без лишнего прохода по массиву. */
  if (срез.windowMs === windowMs) return срез.entries;
  /* Срез уже запрошенного — старой части в нём нет, отдать нечего. */
  if (срез.windowMs < windowMs) return null;
  /* Срез шире — берём из него хвост. Граница считается от СЕЙЧАС, а не от момента чтения:
     пока человек листал периоды, время шло, и окно «последние семь дней» сдвинулось вместе с ним. */
  const порог = сейчас - windowMs;
  return срез.entries.filter((e) => e.t >= порог);
}
