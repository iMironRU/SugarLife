import { describe, it, expect } from 'vitest';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/* Сторож бесконечных анимаций (SugarLife#725).

   Измерено на песочнице (Huawei P40 lite) через отладчик WebView: одна работающая
   CSS-анимация — любая, хоть точка четыре на четыре пикселя в углу — стоит
   47 секунд процессора за минуту вместо 5. Семьдесят восемь процентов ядра против
   восьми. `will-change: opacity` не помогает: дело не в перерисовке области, а в том,
   что кадр производится шестьдесят раз в секунду и вся поверхность WebView идёт через
   конвейер.

   Цена этого не «телефон греется». В суточном прогоне система убила приложение —
   человек остался без наблюдения, пока спал.

   Ошибка не видна ни на глаз, ни в отладке на маке: там процессор есть. Поэтому
   проверяем по исходникам. Ждущая анимация обязана кончаться: `infinite` в стилях
   запрещён, ставьте число повторов. Тридцать секунд — тот же порог, после которого
   экран первого снимка перестаёт крутить колесо и говорит словами. */

const корень = new URL('./', import.meta.url).pathname;

function css(путь: string): string[] {
  return readdirSync(путь, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? css(join(путь, e.name)) : e.name.endsWith('.css') ? [join(путь, e.name)] : []);
}

describe('анимации кончаются', () => {
  for (const файл of css(корень)) {
    it(файл.slice(корень.length), () => {
      /* Пояснения вычёркиваем, а не пропускаем по отступу: слово `infinite` стоит и в
         объяснении, почему его больше нет, — и сторож ловил бы сам рассказ о себе.
         Заменяем комментарии пробелами, чтобы номера строк не поехали. */
      const текст = readFileSync(файл, 'utf8').replace(/\/\*[\s\S]*?\*\//g, (с) => с.replace(/[^\n]/g, ' '));
      const плохие = текст.split('\n')
        .map((с, i) => ({ с, n: i + 1 }))
        .filter(({ с }) => /\binfinite\b/.test(с))
        .map(({ с, n }) => `${n}: ${с.trim()}`);
      expect(плохие, 'бесконечная анимация — 78 % ядра на телефоне; поставьте число повторов').toEqual([]);
    });
  }
});
