#!/usr/bin/env python3
"""Какие поля снимка мы ДЕЙСТВИТЕЛЬНО читаем — с точностью до типа (SugarLife#813, мост 1.72).

Зачем отдельным файлом. Сверка контракта раньше искала объявление `имя:` во всём
`sources/bridge.ts`. Так 4 сентября мы пропустили `title` у разрешения: `title` уже был у
параметра драйвера, у беды прибора и у справки — три чужих объявления, и сверка отчиталась
«всё прочитано», пока ядро писало, что завело поле по нашей же просьбе. Свои пять придуманных
имён мы в это время продолжали показывать.

Это тот же случай, что с `problem` в августе, только на шаг тоньше: там имя встречалось в чужом
ВЫРАЖЕНИИ, здесь — в чужом ТИПЕ. Лечение то же и до конца: сверять пару «тип + поле».

ПАРЫ ТИПОВ ИЩЕМ САМИ, без таблицы руками: у своего двойника имена полей совпадают почти все, у
чужого — одно-два случайно. Таблица, которую надо помнить пополнять, протухла бы на первом же
новом типе — а протухший сторож хуже отсутствующего.

СКОБКИ СЧИТАЕМ, А НЕ УГАДЫВАЕМ. Первая версия искала конец типа регулярным выражением, и на
`DeviceView` (пятьдесят полей, вложенные литералы) промахнулась: один блок проглотил половину
файла и дал ложную тревогу на поле, которое мы читаем. Ложная тревога у сторожа хуже, чем её
отсутствие: после второй его перестают читать.

СЧИТАЕМ ПАРЫ «ТИП + ПОЛЕ», А НЕ ИМЕНА. Это третья попытка, и первые две ловились одним и тем же:
`title` есть у беды прибора, у параметра драйвера и у справки, поэтому список прочитанных ИМЁН
объявлял прочитанным и `title` у разрешения. Пока ответ даётся по имени, чужой однофамилец всегда
закроет собой новое поле.

Печатает по строке на каждое НЕпрочитанное поле: `Тип.поле`. Решение о том, простительно ли это,
принимает сверка — здесь только факт.

Типы без двойника в зеркале пропускаем целиком: решение принимается о ПОЛЕ, которое такой тип
несёт (`config` — «настройки читаем адресно»), и оно проверяется отдельно, в самом снимке.
Перечислять сверх этого внутренности значит завалить сторожа шумом, после которого его перестанут
читать.
"""
import re
import sys
from pathlib import Path

ХВАТИТ_ОБЩИХ = 2      # два общих поля — уже двойник, а не совпадение имён
ДОЛЯ_ДВОЙНИКА = 0.25  # …или четверть полей типа, если он большой


def безКомментариев(текст: str) -> str:
    """Убрать `/* … */` и `// …`.

    БЕЗ ЭТОГО РАЗБОР ВРЁТ В НАШУ ПОЛЬЗУ. Комментарии здесь русские и многословные, а правило поиска
    поля — «слово, за ним двоеточие». В набор полей `PermissionView` так попали `вместо`,
    `настройка`, `приходит`, `средства`, `существует`, `целиком` — шесть несуществующих полей. Беда
    не в мусоре: чем шире наш набор, тем охотнее сверка объявляет чужое поле прочитанным. Сторож,
    ошибающийся в сторону «всё хорошо», не сторож.
    """
    текст = re.sub(r'/\*.*?\*/', ' ', текст, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', текст)


def тело(текст: str, откуда: int, открыть: str, закрыть: str) -> str:
    """Кусок от первой скобки после `откуда` до парной ей. Пусто — скобка не закрылась."""
    начало = текст.find(открыть, откуда)
    if начало < 0:
        return ''
    глубина = 0
    for i in range(начало, len(текст)):
        if текст[i] == открыть:
            глубина += 1
        elif текст[i] == закрыть:
            глубина -= 1
            if глубина == 0:
                return текст[начало + 1:i]
    return ''


def типыЯдра(текст: str) -> dict[str, set[str]]:
    текст = безКомментариев(текст)
    из = {}
    for м in re.finditer(r'\bdata class (\w+)\s*\(', текст):
        внутри = тело(текст, м.end() - 1, '(', ')')
        # Только верхний уровень: вложенные литералы полями этого типа не являются.
        из[м.group(1)] = set(re.findall(r'\bval (\w+)\s*:', внутри))
    return из


def нашиТипы(текст: str) -> dict[str, set[str]]:
    текст = безКомментариев(текст)
    из = {}
    # И `interface X {`, и `type X = {` — у нас есть оба вида, и второй ничем не хуже.
    for м in re.finditer(r'\bexport (?:interface|type) (\w+)[^{;]*?\{', текст):
        внутри = тело(текст, м.end() - 1, '{', '}')
        # Вложенные объекты выбрасываем: их ключи — не поля этого типа.
        плоско = re.sub(r'\{[^{}]*\}', ' ', внутри)
        while '{' in плоско and '}' in плоско:
            новое = re.sub(r'\{[^{}]*\}', ' ', плоско)
            if новое == плоско:
                break
            плоско = новое
        из[м.group(1)] = set(re.findall(r'(?:^|[;,{\s])(\w+)\??\s*:', плоско, re.M))
    return из


def main() -> int:
    ядро = Path(sys.argv[1]).read_text(encoding='utf-8') if len(sys.argv) > 1 else sys.stdin.read()
    наше = Path(sys.argv[2] if len(sys.argv) > 2 else 'src/sources/bridge.ts').read_text(encoding='utf-8')

    их, мои = типыЯдра(ядро), нашиТипы(наше)
    непрочитано: list[str] = []
    for имя, поля in их.items():
        порог = max(ХВАТИТ_ОБЩИХ, int(len(поля) * ДОЛЯ_ДВОЙНИКА))
        # ДВОЙНИКОВ МОЖЕТ БЫТЬ НЕСКОЛЬКО, и это не беспорядок. Прибор ядра мы читаем и как
        # `DeviceView`, и как `HardwareView`: у экрана железа свой разрез тех же данных. Поле,
        # прочитанное хоть в одном из них, прочитано — требовать его в «главном» значило бы
        # выдумать главный там, где его нет, и получить ложную тревогу.
        двойники = [f for f in мои.values() if len(поля & f) >= порог]
        if двойники:
            видим: set[str] = set()
            for f in двойники:
                видим |= поля & f
            непрочитано += [f'{имя}.{п}' for п in sorted(поля - видим)]
        else:
            # Двойника нет — тип у нас не зеркалится вовсе; см. про это в шапке.
            pass
    print('\n'.join(непрочитано))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
