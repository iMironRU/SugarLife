#!/usr/bin/env bash
# Ищет механизмы, которые могут отказать МОЛЧА (SugarLife#593).
#
# ЗАЧЕМ. Тревога, не прозвучавшая звуком, и опора, у которой отобрали сессию, выглядят снаружи
# одинаково с работающими: ничего не происходит. Разница видна только в журнале, а журнал пишется
# лишь там, где мы про это вспомнили. За один день мы трижды наступили на это: баннер писал только
# удачные исходы, звук тревоги писал в NSLog, опора не писала вовсе.
#
# Правило простое: если ветка отказа существует, из неё обязан идти след в журнал ДВИЖКА — его можно
# выгрузить с телефона наутро, в отличие от NSLog, который виден только подключённому Xcode.
#
# Скрипт не умный: он показывает места, где отказ обрабатывается, и не видит следа рядом. Часть
# находок будет законной — там, где отказ не значит поломки. Такие помечают комментарием «молча:
# <почему>» в той же ветке, и скрипт их пропустит.
#
# Запуск: bash scripts/молчаливые-отказы.sh
#
# Имена переменных латиницей — bash 3.2 в macOS не умеет имён вне ASCII (грабля, на которую я
# наступал в этом же каталоге дважды).
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
NATIVE="$HERE/ios/App/App $HERE/ios/App/SugarLifeWidgets"

echo "Ветки отказа без следа в журнале движка:"
FOUND=0
while IFS=: read -r file line _; do
  [ -z "${file:-}" ] && continue
  # Смотрим win после ветки: есть ли там запись в журнал или пометка «молча:».
  win=$(sed -n "${line},$((line + 16))p" "$file" 2>/dev/null || true)
  case "$win" in
    *вЖурнал*|*молча:*) continue ;;
  esac
  echo "  · ${file#"$HERE/"}:$line"
  FOUND=$((FOUND + 1))
done < <(grep -rn "} catch {\|catch {$" $NATIVE --include='*.swift' 2>/dev/null || true)

if [ "$FOUND" -eq 0 ]; then
  echo "  (нет — каждая ветка отказа оставляет след)"
else
  echo
  echo "Найдено: $FOUND. Либо добавь запись в журнал, либо пометь ветку комментарием «молча: почему»."
fi
