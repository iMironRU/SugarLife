#!/usr/bin/env bash
# Собрать и поставить приложение на подключённый iPhone — одной командой (#428).
#
# Зачем скриптом. Шагов четыре, и забывается всегда один и тот же: пересобрать веб перед
# синхронизацией. Тогда на телефон уезжает вчерашний интерфейс с сегодняшней нативкой, и
# concert выглядит как «правка не приехала».
#
# ПОДПИСЬ. Бесплатный Apple ID даёт профиль на семь дней: через неделю приложение
# перестаёт запускаться, пока не пересоберёшь. Данные при этом остаются — истекает право
# запуска, а не база. Команда разработчика берётся из DEVELOPMENT_TEAM или из Xcode.
#
# Запуск:  bash scripts/ios-на-телефон.sh            (телефон подключён и разблокирован)
#          DEVELOPMENT_TEAM=XXXXXXXXXX bash scripts/ios-на-телефон.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE"

echo "1/3 · веб (CAP=1, относительные пути)"
CAP=1 npm run build

echo "2/3 · capacitor sync ios"
npx cap sync ios

echo "3/3 · сборка и установка"
# ИМЯ ПЕРЕМЕННОЙ ЛАТИНИЦЕЙ — ВЫНУЖДЕННО. bash (в macOS он версии 3.2) не умеет имён переменных вне
# ASCII: `УСТР=…` он читает как команду и падает с «command not found», а из-за `|| true` в конце
# строки скрипт при этом заканчивался с нулём — то есть молча ничего не ставил. Остальные слова здесь
# по-прежнему русские; ограничение касается только имён.
#
# Ищем устройство и по «connected», и по «available»: спаренный по Wi-Fi телефон пишется вторым словом,
# а ставится на него ровно так же.
# Берём идентификатор по его виду (UUID), а не по номеру колонки: имя телефона у человека из двух
# слов сдвигает все колонки, и разбор по позиции достаёт из строки слово «iPhone» вместо адреса.
DEVICE_ID=$(xcrun devicectl list devices 2>/dev/null \
  | grep -E '(connected|available)' \
  | grep -oE '[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}' | head -1 || true)
if [ -z "${DEVICE_ID:-}" ]; then
  echo "Телефон не найден. Подключи его кабелем, разблокируй и разреши доверие — потом повтори." >&2
  echo "Либо открой app/ios/App/App.xcworkspace и нажми Run: результат тот же." >&2
  exit 1
fi
cd ios/App
# ПРАВА — СНАЧАЛА С НИМИ, НЕ ВЫШЛО — БЕЗ НИХ (SugarLife#500).
#
# По умолчанию просим право на срочные уведомления (App/Тревоги.entitlements): без него «Не беспокоить»
# молча прячет карточку тревоги — сирена звучит, а на экране пусто, и владелец прожил это вживую.
# Но бесплатной личной команде Apple это право может не выдать (у Loop так и задокументировано).
# Тогда не ломаем установку, как когда-то ломала платная группа (#466), а собираем без права и говорим
# об этом вслух — а в приложении «Охрана» сама покажет «сборка без права на срочные».
build_app() {   # имя латиницей — см. про bash 3.2 выше

  xcodebuild -project App.xcodeproj -scheme App -configuration Debug \
    -destination "id=$DEVICE_ID" -allowProvisioningUpdates \
    ${DEVELOPMENT_TEAM:+DEVELOPMENT_TEAM="$DEVELOPMENT_TEAM"} \
    SL_ENTITLEMENTS="$1" \
    build
}
# ЗАПАСНОЙ ПУТЬ — НЕ «БЕЗ ПРАВ ВОВСЕ» (SugarLife#542).
#
# Раньше при отказе подписи собирали с пустыми правами, и это было верно, пока прав было ровно одно —
# срочные уведомления. Теперь их два, и второе (общая связка с виджетом) личной команде ВЫДАЁТСЯ:
# сбрасывая всё, мы молча забирали у виджета данные — он ставился и всегда показывал «нет данных».
#
# Поэтому падаем не в пустоту, а на связку: теряем ровно то, чего команда не даёт.
RIGHTS="${SL_ENTITLEMENTS:-App/Тревоги.entitlements}"
if ! build_app "$RIGHTS"; then
  echo
  echo "Подпись с правами ($RIGHTS) не прошла — похоже, команда разработчика их не выдаёт." >&2
  echo "Собираю со связкой (виджет продолжит получать данные), но без срочных уведомлений:" >&2
  echo "«Не беспокоить» сможет спрятать карточку тревоги — добавьте SugarLife в разрешённые" >&2
  echo "приложения фокуса (Настройки → Фокусирование)." >&2
  echo
  build_app "App/Связка.entitlements"
fi

# СОБРАТЬ — ЕЩЁ НЕ ПОСТАВИТЬ. `xcodebuild build` с телефоном в качестве назначения только собирает
# под его архитектуру; на сам телефон ничего не уезжает. Скрипт при этом бодро заканчивался нулём, и
# «поставил» отличалось от «собрал» только тем, что на телефоне оставалась вчерашняя сборка — а это
# ровно тот случай, ради которого скрипт и написан («правка не приехала»).
echo
echo "Ставлю на телефон"
APP_PATH=$(xcodebuild -project App.xcodeproj -scheme App -configuration Debug \
  -destination "id=$DEVICE_ID" -showBuildSettings 2>/dev/null \
  | awk -F' = ' '/ BUILT_PRODUCTS_DIR = /{print $2; exit}')
xcrun devicectl device install app --device "$DEVICE_ID" "$APP_PATH/App.app"

echo
echo
echo "Отдача показаний в петлю (iAPS) требует платного аккаунта: общая группа приложений"
echo "личной команде недоступна. Нужна — собери так:"
echo "  SL_ENTITLEMENTS=App/App.entitlements bash scripts/ios-на-телефон.sh"
echo
echo "Готово. Живой баннер включается в приложении: Профиль → Тревоги → «Показывать сахар"
echo "на экране блокировки». Подпись живёт семь дней — через неделю запусти этот скрипт снова."
