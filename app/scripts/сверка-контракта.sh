#!/usr/bin/env bash
# Что ядро отдаёт, а мы не читаем (SugarLife#544).
#
# Ядро ушло на 1.43, пока мы читали 1.40 — три ревизии с полями, которые закрывали задачи, названные
# в тот же день «нерешаемыми без ядра». Нашли это не мы: ядро прогнало свою сверку (SugarLifeCore#127)
# и написало, что светофор пролежал непрочитанным двое суток. Такое надо находить проверкой, а не
# случайным чтением чужого кода.
#
# Скрипт сравнивает поля снимка и интенты ядра с упоминаниями в нашем коде. Он ищет СЛОВО, а не
# осмысленное использование: field может упоминаться и лежать без дела. Обратное надёжно — если слова
# нет вовсе, field не читается точно, и для нашей задачи этого достаточно.
#
# Слово — целиком (grep -w), и это не придирка. Поле 1.50 зовётся `decision`, а у нас в комментариях
# полтора десятка ссылок на `docs/decisions/…`. Поиск подстрокой нашёл бы их и объявил поле
# прочитанным — за сутки до того, как мы его вообще завели.
#
# ИМЕНА ПЕРЕМЕННЫХ ЛАТИНИЦЕЙ — вынужденно: bash в macOS версии 3.2 и не-ASCII имён не понимает,
# читает их как команду и падает. Остальные слова здесь по-прежнему русские.
#
# Запуск:  SUGARLIFE_CORE_DIR=~/path/to/core bash scripts/сверка-контракта.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
CORE="${SUGARLIFE_CORE_DIR:-}"

if [ -z "$CORE" ] || [ ! -d "$CORE" ]; then
  echo "Не задан SUGARLIFE_CORE_DIR — не с чем сверять." >&2
  exit 1
fi

BRIDGE="$CORE/bridge/src/commonMain/kotlin/ru/imiron/sugarlife/bridge"
[ -d "$BRIDGE" ] || { echo "В $CORE не найден мост ($BRIDGE)" >&2; exit 1; }

# СВЕРЯЕМСЯ С origin/main, А НЕ С РАБОЧЕЙ КОПИЕЙ (#574).
#
# Клон ядра лежит на диске неделями и устаревает молча. Сверка на нём отвечала «синхронны», когда мы
# отставали на три ревизии, — то есть успокаивала ровно там, где обязана была предупредить. Проверка,
# которой можно верить только после ручного git pull, не проверка.
#
# Тянем сами и читаем файлы из origin/main, не трогая рабочую копию: она может быть занята.
if git -C "$CORE" rev-parse --git-dir >/dev/null 2>&1; then
  git -C "$CORE" fetch -q origin 2>/dev/null || echo "Внимание: не смог обновить клон ядра — сверяю по тому, что есть." >&2
  FROM_REF="origin/main"
else
  FROM_REF=""
  echo "Внимание: $CORE не репозиторий — сверяю по файлам на диске, они могут быть старыми." >&2
fi

# Файл моста из origin/main, если можем; иначе с диска.
# Имена переменных латиницей — вынужденно: bash 3.2 в macOS не умеет имён вне ASCII (та же грабля,
# что уже описана в шапке; я наступил на неё второй раз и оставляю след прямо здесь).
bridge_files() {
  if [ -n "$FROM_REF" ]; then
    git -C "$CORE" ls-tree -r --name-only "$FROM_REF" -- bridge | grep '\.kt$' | while read -r f; do
      git -C "$CORE" show "$FROM_REF:$f" 2>/dev/null
    done
  else
    cat "$BRIDGE"/*.kt 2>/dev/null
  fi
}

# ОДИН файл моста — из того же origin/main, что и всё остальное.
#
# Было так: ревизию скрипт брал из origin/main, а списки полей — с диска. Клон на диске стоял на
# 1.43, и сверка честно печатала «мост ядра 1.50», сравнивая при этом со старыми файлами: заголовок
# новый, вывод старый, расхождений «нет». Ровно тот случай, ради которого сверка и заведена, —
# инструмент, который врёт в сторону спокойствия.
bridge_file() {
  if [ -n "$FROM_REF" ]; then
    git -C "$CORE" show "$FROM_REF:bridge/src/commonMain/kotlin/ru/imiron/sugarlife/bridge/$1" 2>/dev/null
  else
    cat "$BRIDGE/$1" 2>/dev/null
  fi
}

# Ревизия объявлена рядом со снимком, но искать её по одному файлу — способ однажды промолчать:
# у ядра она уже переезжала. Ищем по всему мосту.
CORE_REV=$(bridge_files | grep 'BRIDGE_REVISION *=' | grep -oE '[0-9]+\.[0-9]+' | head -1)
# Наша ревизия — по всему, что зеркалит контракт, а не по одному bridge.ts.
#
# Часть контракта живёт только в нативе: submitLog шлёт оболочка, и веб про него не знает вовсе.
# Ревизия 1.50 добавила поле именно туда, и проверка «что упомянуто в bridge.ts» показала бы отставание
# ещё долго после того, как мы её догнали.
OUR_REV=$( { grep -rhoE 'rev ≥ [0-9]+\.[0-9]+|мост [0-9]+\.[0-9]+' \
      "$HERE/src/sources/bridge.ts" "$HERE/ios/App/App" "$HERE/android/app/src/main/java" 2>/dev/null || true; } \
  | grep -oE '[0-9]+\.[0-9]+' | sort -V | tail -1)

echo "мост ядра:     $CORE_REV"
echo "наше зеркало:  $OUR_REV (самая поздняя ревизия, названная в вебе или нативе)"
[ "$CORE_REV" = "$OUR_REV" ] || echo "  ↑ расходятся — ниже видно, чего именно не хватает"
echo

# ЗНАКОМЫЕ НЕПРОЧИТАННЫЕ — С ПРИЧИНОЙ У КАЖДОГО.
#
# Список без причин перестают читать. Ровно это с нами и случилось: `roleWhy` лежал среди «обычных
# семи» и оказался именно тем, чего не хватало, — ядро написало про него отдельно, потому что мы
# сами не заметили. Тот же класс, что предупреждения сборки: перечень, который пролистывают, не
# защищает, а создаёт уверенность.
#
# Поэтому здесь у каждого поля стоит РЕШЕНИЕ, а не факт. Всё, чего в списке нет, требует ответа:
# прочитать или объяснить, почему не читаем. Появилось новое — скрипт назовёт его отдельно.
#
# Имена латиницей: bash 3.2 в macOS не понимает не-ASCII имён (граблю ловим пятый раз за сутки).
known_unread() {
  cat <<'СПИСОК'
bolusing|идёт ли болюс прямо сейчас — издание Pro, в Lite подачи нет
progressPercent|доля подбора частоты; ход показываем словами (domain/freshness.ts), полосу не рисуем
createdAtMs|когда человек нажал команду прибору — Pro: команд в Lite нет
context|наблюдения из Apple Health (вес, пульс, активность) — экрана для них ещё нет, ядро #142
linkChangedAtMs|когда менялась связь; лента подключений снята с «Сегодня» до разбора (#597)
nativeBridge|признак «коннектор нативный» — на показ не влияет, выбираем не мы
profileName|имя активного профиля настроек; профиль пока один, показывать нечего
СПИСОК
}

# Поля снимка: `val имя:` в UiSnapshot.kt. Служебные и приватные не берём.
FIELDS=$(bridge_file UiSnapshot.kt | grep -hoE '^\s+val [a-zA-Z][a-zA-Z0-9]*' | awk '{print $2}' | sort -u)
NEW=0
echo "НОВЫЕ поля снимка, которых нет в нашем коде и в списке решений:"
for field in $FIELDS; do
  # Однобуквенные и слишком общие слова дают ложные совпадения — их сверять бессмысленно.
  [ ${#field} -ge 4 ] || continue
  grep -rqwF "$field" "$HERE/src" 2>/dev/null && continue
  if known_unread | grep -q "^$field|"; then continue; fi
  echo "  · $field"
  NEW=$((NEW + 1))
done
if [ "$NEW" -eq 0 ]; then
  echo "  (нет — всё непрочитанное объяснено)"
else
  echo
  echo "  Каждое из них — либо прочитать, либо вписать в known_unread с причиной." >&2
fi
echo
echo "Знакомые непрочитанные и почему:"
known_unread | while IFS='|' read -r name why; do echo "  · $name — $why"; done
echo

# Интенты: значения type в Intent.kt (`@SerialName("…")` либо строковый литерал).
INTENTS=$(bridge_file Intent.kt | grep -hoE '"[a-zA-Z][a-zA-Z0-9]+"' | tr -d '"' | sort -u || true)
# Интенты, которых мы намеренно не шлём. Та же причина, что у полей: список без объяснений
# перестают читать, и однажды в нём окажется нужное.
known_unsent() {
  cat <<'СПИСОК'
suspendDelivery|остановить подачу — издание Pro, команд прибору в Lite нет
resumeDelivery|возобновить подачу — Pro
acknowledgeWrite|подтвердить исход команды — Pro, команд нет
writeBasalProfile|записать базальный профиль в помпу — Pro
setPumpTime|выставить часы помпы — Pro
setAutoConnectAll|подключать все приборы разом — экрана нет, приборов у владельца два
unlinkAccount|отвязать вендорский аккаунт — раздела учёток ещё нет
importLegacyConfig|разовый импорт старой настройки — прошёл однажды, живёт в истории
СПИСОК
}

echo "НОВЫЕ интенты ядра, которых мы не шлём и не объяснили:"
NOSEND=0
for it in $INTENTS; do
  [ ${#it} -ge 5 ] || continue
  # Ищем и в вебе, и в нативе: часть интентов шлёт натив (журнал, сеть, тревоги), и поиск только по
  # src объявлял их «не шлём» — ещё один способ соврать в сторону спокойствия.
  grep -rqwF "$it" "$HERE/src" "$HERE/ios/App/App" "$HERE/android/app/src/main/java" 2>/dev/null && continue
  if known_unsent | grep -q "^$it|"; then continue; fi
  echo "  · $it"
  NOSEND=$((NOSEND + 1))
done
if [ "$NOSEND" -eq 0 ]; then
  echo "  (нет — всё неотправляемое объяснено)"
else
  echo "  Каждый — либо слать, либо вписать в known_unsent с причиной." >&2
fi
echo
echo "Знакомые неотправляемые и почему:"
known_unsent | while IFS='|' read -r name why; do echo "  · $name — $why"; done
echo
# ПОЛЯ ВНУТРИ ИНТЕНТОВ, а не только их имена.
#
# 1.50 не завела ни одного нового интента — она добавила поле `decision` в submitLog. Скрипт сверял
# имена интентов и поля снимка, а поля интентов не сверял вовсе, и отставание показал одной строкой
# «ревизии расходятся», без единого слова о том, чего не хватает. Догадаться, что смотреть надо в
# Intent.kt, пришлось глазами — то есть проверка не сработала там, где была нужна.
INTENT_FIELDS=$(bridge_file Intent.kt | grep -hoE '^\s+val [a-zA-Z][a-zA-Z0-9]*' | awk '{print $2}' | sort -u)
echo "Поля интентов, которых нет в нашем коде:"
NOFIELD=0
for f in $INTENT_FIELDS; do
  [ ${#f} -ge 5 ] || continue
  if ! grep -rqwF "$f" "$HERE/src" "$HERE/ios/App/App" "$HERE/android/app/src/main/java" 2>/dev/null; then
    echo "  · $f"
    NOFIELD=$((NOFIELD + 1))
  fi
done
[ "$NOFIELD" -eq 0 ] && echo "  (все упоминаются)"
echo
# КОД ВОЗВРАТА ГОВОРИТ ПРО НОВОЕ, А НЕ ПРО ОБЪЯСНЁННОЕ.
#
# Скрипт пока не стоит в CI — это решение владельца, потому что падение сверки остановит сборку.
# Но код возврата честный уже сейчас: кто захочет поставить, получит проверку, а не отчёт.
if [ "$NEW" -gt 0 ] || [ "$NOSEND" -gt 0 ] || [ "$CORE_REV" != "$OUR_REV" ]; then
  exit 1
fi
