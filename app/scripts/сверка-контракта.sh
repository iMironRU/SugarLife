}

echo "НОВЫЕ интенты ядра, которых мы не шлём и не объяснили:"
NOSEND=0
for it in $INTENTS; do
  [ ${#it} -ge 5 ] || continue
  # Ищем и в вебе, и в нативе: часть интентов шлёт натив (журнал, сеть, тревоги), и поиск только по
  # src объявлял их «не шлём» — ещё один способ соврать в сторону спокойствия.
  grep -rqwF "$it" "$HERE/src" "$HERE/ios/App/App" "$HERE/android/app/src/main/java" 2>/dev/null && continue
  if known_unsent | grep -q "^$it|"; then continue; fi
  echo "  · $it"
  NOSEND=$((NOSEND + 1))
done
if [ "$NOSEND" -eq 0 ]; then
  echo "  (нет — всё неотправляемое объяснено)"
else
  echo "  Каждый — либо слать, либо вписать в known_unsent с причиной." >&2
fi
echo
# ОБЪЯВИТЬ — НЕ ЗНАЧИТ СЛАТЬ (SugarLife#660).
#
# Проверка выше смотрит с их стороны: «ядро завело интент, мы про него не слышали». Она ищет СЛОВО,
# и объявления в нашем же типе моста ей достаточно, чтобы посчитать интент отправляемым.
#
# Так тринадцать интентов тихо числились нашими, не будучи отправленными ни разу. Среди них
# `logMeal`: углеводы, которые человек вносит руками, ложились в базу и оставались там навсегда.
# Проверка, заведённая ловить «дали, а мы не взяли», молчала именно там, где взяли на словах.
#
# Поэтому вторая проверка — с НАШЕЙ стороны, где список точен: что объявлено в `bridge.ts`, то
# должно и звучать. Ищем вызов, а не имя: в вебе `type: '<имя>'` вне самого bridge.ts, в нативе —
# `"type":"<имя>"` внутри JSON.
echo "Объявлены у нас, но ни разу не отправляются:"
MUTE=0
for it in $(grep -oE "type: '[a-zA-Z]+'" "$HERE/src/sources/bridge.ts" | sed "s/type: '//;s/'//" | sort -u); do
  grep -rE "type: *'$it'" "$HERE/src" --include='*.ts' --include='*.tsx' 2>/dev/null \
    | grep -v 'sources/bridge.ts' | grep -qv '\.test\.' && continue
  grep -rq "$it" "$HERE/ios/App/App" "$HERE/android/app/src/main/java" 2>/dev/null && continue
  if known_unsent | grep -q "^$it|"; then continue; fi
  echo "  · $it"
  MUTE=$((MUTE + 1))
done
if [ "$MUTE" -eq 0 ]; then
  echo "  (нет — всё объявленное отправляется или объяснено)"
else
  echo "  Каждый — либо звать, либо вписать в known_unsent с причиной." >&2
  BAD=1
fi
echo
# КЛЮЧИ НАСТРОЙКИ, КОТОРЫЕ ДВИЖОК ПРИНИМАЕТ, А МЫ НЕ ПИШЕМ (SugarLife#677).
#
# Узкая проверка вместо широкой. Широкую («описано в зеркале, но не читается») я пробовал — она
# даёт полсотни полей, потому что зеркало это копия контракта, а читаем мы законно меньше. Вечно
# красная проверка бесполезна.
#
# А здесь список короткий и осмысленный: белый список конфига у движка — это ровно те настройки,
# которые он УМЕЕТ принять. Каждая, которую мы не пишем, — либо экран, которого нет, либо
# соединение, которого забыли сделать.
#
# Ради чего заведена: `sleep.from`/`sleep.to` — настройка «Обычно ложусь / встаю» жила у нас с #280,
# движку не уходила, и вся его модель сна (пороги строже во сне, ночной звук, вечерняя проверка
# «разбудим ли этой ночью») не работала НИ РАЗУ. Нашёл это владелец вопросом, а не проверка.
CONFKEYS=$(bridge_or_engine_config_keys)
echo "Настройки, которые движок принимает, а мы не пишем:"
NOCONF=0
for key in $CONFKEYS; do
  grep -rqF "'$key'" "$HERE/src" --include='*.ts' --include='*.tsx' 2>/dev/null && continue
  if known_unset | grep -q "^$key|"; then continue; fi
  echo "  · $key"
  NOCONF=$((NOCONF + 1))
done
if [ "$NOCONF" -eq 0 ]; then
  echo "  (нет — всё принимаемое либо пишем, либо объяснено)"
else
  echo "  Каждая — либо писать, либо вписать в known_unset с причиной." >&2
  BAD=1
fi
echo
echo "Знакомые неотправляемые и почему:"
known_unsent | while IFS='|' read -r name why; do echo "  · $name — $why"; done
echo
# ПОЛЯ ВНУТРИ ИНТЕНТОВ, а не только их имена.
#
# 1.50 не завела ни одного нового интента — она добавила поле `decision` в submitLog. Скрипт сверял
# имена интентов и поля снимка, а поля интентов не сверял вовсе, и отставание показал одной строкой
# «ревизии расходятся», без единого слова о том, чего не хватает. Догадаться, что смотреть надо в
# Intent.kt, пришлось глазами — то есть проверка не сработала там, где была нужна.
INTENT_FIELDS=$(bridge_file Intent.kt | grep -hoE '^\s+val [a-zA-Z][a-zA-Z0-9]*' | awk '{print $2}' | sort -u)
echo "Поля интентов, которых нет в нашем коде:"
NOFIELD=0
for f in $INTENT_FIELDS; do
  [ ${#f} -ge 5 ] || continue
  if ! grep -rqwF "$f" "$HERE/src" "$HERE/ios/App/App" "$HERE/android/app/src/main/java" 2>/dev/null; then
    echo "  · $f"
    NOFIELD=$((NOFIELD + 1))
  fi
done
[ "$NOFIELD" -eq 0 ] && echo "  (все упоминаются)"
echo
# КОД ВОЗВРАТА ГОВОРИТ ПРО НОВОЕ, А НЕ ПРО ОБЪЯСНЁННОЕ.
#
# Скрипт пока не стоит в CI — это решение владельца, потому что падение сверки остановит сборку.
# Но код возврата честный уже сейчас: кто захочет поставить, получит проверку, а не отчёт.
if [ "$NEW" -gt 0 ] || [ "$NOSEND" -gt 0 ] || [ "$CORE_REV" != "$OUR_REV" ]; then
  exit 1
fi
