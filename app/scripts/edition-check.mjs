/* ПРОВЕРКА ИЗДАНИЯ ПО СОБРАННОМУ БАНДЛУ (SugarLife#296).

   Барьерный тест следит за импортами в исходниках, а этот скрипт — за тем, что получилось. Разница
   существенная: импорт можно и не писать, а строку с командой помпе — вставить прямо в общий экран.
   Здесь мы смотрим на то, что реально уедет на телефон.

   Ищем слова, которые в Lite не имеют права встретиться ни при каких обстоятельствах. Список
   намеренно про КОМАНДЫ ПРИБОРУ, а не про слово «pro»: издание — это не название, а наличие кода,
   который останавливает подачу инсулина.

   Запуск: node scripts/edition-check.mjs [каталог сборки]   (по умолчанию dist)
   Возвращает ненулевой код, если нашёл, — этого достаточно и для CI, и для рук. */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = process.argv[2] ?? 'dist';

/* Что ищем. Каждая строка — то, что появится в Pro вместе с пультом: сами интенты и слова экрана.
   Пополнять этот список обязан тот, кто добавляет в Pro новую команду прибору. */
const ЗАПРЕЩЕНО_В_LITE = [
  'suspendDelivery',
  'resumeDelivery',
  'setPumpTime',
  'writeBasalProfile',
  'Остановить подачу',
  'Возобновить подачу',
];

function файлы(dir) {
  try {
    return readdirSync(dir).flatMap((n) => {
      const p = join(dir, n);
      return statSync(p).isDirectory() ? файлы(p) : [p];
    });
  } catch { return []; }
}

const найдено = [];
for (const f of файлы(корень)) {
  if (!/\.(js|css|html)$/.test(f)) continue;
  const текст = readFileSync(f, 'utf8');
  for (const слово of ЗАПРЕЩЕНО_В_LITE) {
    if (текст.includes(слово)) найдено.push(`${f}: ${слово}`);
  }
}

if (найдено.length) {
  console.error('В Lite-сборке нашлось то, чего в ней быть не должно:');
  найдено.forEach((с) => console.error('  ' + с));
  console.error('\nЭто команды прибору, который вводит инсулин. Издание «просто посмотреть сахар»');
  console.error('не должно нести их вовсе — ни экранов, ни кнопок, ни кода отправки (#296).');
  process.exit(1);
}
console.log(`Lite-сборка чистая: команд прибору нет (проверено слов: ${ЗАПРЕЩЕНО_В_LITE.length}).`);
