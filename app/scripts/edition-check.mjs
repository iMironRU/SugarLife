/* ПРОВЕРКА ИЗДАНИЯ ПО СОБРАННОМУ БАНДЛУ (SugarLife#296).

   Барьерный тест следит за импортами в исходниках, а этот скрипт — за тем, что получилось. Разница
   существенная: импорт можно и не писать, а строку с командой помпе — вставить прямо в общий экран.
   Здесь мы смотрим на то, что реально уедет на телефон.

   Ищем слова, которые в Lite не имеют права встретиться ни при каких обстоятельствах. Список
   намеренно про КОМАНДЫ ПРИБОРУ, а не про слово «pro»: издание — это не название, а наличие кода,
   который останавливает подачу инсулина.

   ПРОВЕРКА ИДЁТ В ОБЕ СТОРОНЫ (#294). У Lite не должно быть команд прибору; у Pro не должно быть
   обновления по воздуху. Второе — решение владельца и причина у него регуляторная: удостоверение
   берётся на движок, Pro вырастает в петлю, а обновление по воздуху означает, что человек
   пользуется версией, которую никто не проверял, и молча. Выключатель тут не годится: его включат
   обратно правкой, которую никто не заметит. Здесь мы смотрим на то, что реально уедет на телефон.

   Запуск: node scripts/edition-check.mjs [каталог сборки] [издание]
     издание: lite (по умолчанию) | pro
   Возвращает ненулевой код, если нашёл, — этого достаточно и для CI, и для рук. */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = process.argv[2] ?? 'dist';
const издание = (process.argv[3] ?? process.env.SUGARLIFE_EDITION ?? 'lite').toLowerCase();

/* Что ищем. Каждая строка — то, что появится в Pro вместе с пультом: сами интенты и слова экрана.
   Пополнять этот список обязан тот, кто добавляет в Pro новую команду прибору. */
const ЗАПРЕЩЕНО_В_LITE = [
  'suspendDelivery',
  'resumeDelivery',
  'setPumpTime',
  'writeBasalProfile',
  'Остановить подачу',
  'Возобновить подачу',
];

/* Что ищем в PRO. Адрес манифеста обновлений — единственная нить, за которую тянется весь тракт
   загрузки бандла: без него нечего спросить и нечего применить. Слова плагина рядом, чтобы правка,
   переехавшая на другой адрес, не прошла мимо. */
const ЗАПРЕЩЕНО_В_PRO = [
  'SugarLife/v2/ota',
  'capacitor-updater',
  'CapacitorUpdater',
];

function файлы(dir) {
  try {
    return readdirSync(dir).flatMap((n) => {
      const p = join(dir, n);
      return statSync(p).isDirectory() ? файлы(p) : [p];
    });
  } catch { return []; }
}

const это_pro = издание === 'pro';
const запрещено = это_pro ? ЗАПРЕЩЕНО_В_PRO : ЗАПРЕЩЕНО_В_LITE;

const найдено = [];
for (const f of файлы(корень)) {
  if (!/\.(js|css|html)$/.test(f)) continue;
  const текст = readFileSync(f, 'utf8');
  for (const слово of запрещено) {
    if (текст.includes(слово)) найдено.push(`${f}: ${слово}`);
  }
}

if (найдено.length) {
  console.error(`В ${это_pro ? 'Pro' : 'Lite'}-сборке нашлось то, чего в ней быть не должно:`);
  найдено.forEach((с) => console.error('  ' + с));
  if (это_pro) {
    console.error('\nЭто обновление по воздуху. Pro вырастает в петлю, которая подаёт инсулин, и её');
    console.error('версия обязана меняться только сборкой: иначе человек пользуется тем, чего никто');
    console.error('не проверял, и узнать об этом неоткуда (#294).');
  } else {
    console.error('\nЭто команды прибору, который вводит инсулин. Издание «просто посмотреть сахар»');
    console.error('не должно нести их вовсе — ни экранов, ни кнопок, ни кода отправки (#296).');
  }
  process.exit(1);
}
console.log(это_pro
  ? `Pro-сборка чистая: обновления по воздуху нет (проверено слов: ${запрещено.length}).`
  : `Lite-сборка чистая: команд прибору нет (проверено слов: ${запрещено.length}).`);
