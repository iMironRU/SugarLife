package ru.imiron.sugarlife

import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * СРОК ПОПРАВКИ КАЛИБРАТОРА (SugarLife#750, ядро SugarLifeCore#195).
 *
 * Поправка — мостик на четыре минуты между точными расчётами вендорского алгоритма. Срока у неё не
 * было, и пока точные ответы шли, это было незаметно.
 *
 * А потом мы впервые встали попутчиком к живому сенсору: вошли в чужой сеанс в середине, буферы
 * вендорского ядра набирались не с нашего начала, точные ответы прекратились — и мостик на четыре
 * минуты стал постоянным мостом длиной в час.
 *
 * Измерено ядром на 46 совпавших по минуте точках: наше значение ровно «сырое − 2,1» сорок шесть
 * минут подряд при расхождении с правдой в +9 ммоль. На экране 19,3 там, где 10,3.
 *
 * Пометка «сырое» при этом была снята: значение считалось посчитанным. То есть приложение
 * переставало предупреждать ровно тогда, когда начинало ошибаться опаснее.
 */
class КалибровкаПоправкаTest {

    /** В норме мостик закрывает четыре записи между точными расчётами. */
    @Test
    fun `свежая поправка годна весь свой срок`() {
        for (возраст in 0..5) {
            assertTrue("возраст $возраст должен быть годен", поправкаГодна(100, 100 + возраст, 5))
        }
    }

    /** Час на одной поправке — это и была беда. */
    @Test
    fun `просроченная поправка не годна`() {
        assertFalse(поправкаГодна(100, 106, 5))
        assertFalse(поправкаГодна(100, 160, 5))
    }

    /** Поправки не было вовсе — значит и мостить нечем. */
    @Test
    fun `без поправки годности нет`() {
        assertFalse(поправкаГодна(null, 100, 5))
    }

    /** Номер записи пошёл назад — начался другой сеанс, старая поправка к нему не относится. */
    @Test
    fun `поправка из будущего не годна`() {
        assertFalse(поправкаГодна(100, 99, 5))
        assertFalse(поправкаГодна(100, 0, 5))
    }
}
