package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * ЧТО ПОКАЗЫВАЕТ ЗАСТАВКА (SugarLifeCore#232).
 *
 * Проверяем слова, а не показ: показ — три строки в `MainActivity`, а решение «что сказать и стоит
 * ли говорить вообще» живёт здесь, и ошибиться в нём дороже.
 */
class ЗаставкаЧислаTest {

    private val час = 3_600_000L

    @Test
    fun возраст_называем_словами_а_не_минутами_подряд() {
        // «117 мин назад» человек делит в уме, а нам от него нужно одно — понять, свежее это или нет.
        assertEquals("только что", ЗаставкаЧисла.возрастСловами(30_000))
        assertEquals("1 минуту назад", ЗаставкаЧисла.возрастСловами(60_000))
        assertEquals("4 минуты назад", ЗаставкаЧисла.возрастСловами(4 * 60_000))
        assertEquals("17 минут назад", ЗаставкаЧисла.возрастСловами(17 * 60_000))
        assertEquals("2 часа назад", ЗаставкаЧисла.возрастСловами(2 * час))
        assertEquals("5 часов назад", ЗаставкаЧисла.возрастСловами(5 * час))
    }

    @Test
    fun склонение_не_врёт_на_одиннадцати() {
        // Одиннадцать — не «одиннадцать минуту». Ошибка мелкая, но она видна каждому и сразу.
        assertEquals("11 минут назад", ЗаставкаЧисла.возрастСловами(11 * 60_000))
        assertEquals("21 минуту назад", ЗаставкаЧисла.возрастСловами(21 * 60_000))
        assertEquals("22 минуты назад", ЗаставкаЧисла.возрастСловами(22 * 60_000))
    }

    @Test
    fun предел_возраста_названа_шестью_часами() {
        /*
         * Дальше этого срока число на весь экран человек прочтёт как текущее — а мы в этот момент
         * заведомо не на связи. Лучше пусто и честно, чем крупно и неверно.
         */
        assertEquals(6 * час, ЗаставкаЧисла.ПРЕДЕЛ_ВОЗРАСТА_МС)
    }
}
