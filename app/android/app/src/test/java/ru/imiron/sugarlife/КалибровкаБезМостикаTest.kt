package ru.imiron.sugarlife

import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Assume
import org.junit.Test

/**
 * МОСТИК МЕЖДУ ТОЧНЫМИ РАСЧЁТАМИ СТРОИМ НЕ МЫ (SugarLife#750, ядро SugarLifeCore#196).
 *
 * Вендорский алгоритм считает точно раз в пять записей. В промежутках мы отдавали `сырое + поправка`
 * и помечали это калиброванным. Первого сентября мы впервые встали попутчиком к живому сенсору,
 * точные ответы прекратились — и мостик прожил час: сорок шесть минут подряд на экране было 19,3 там,
 * где 10,3 (ядро #195, сверено поминутно).
 *
 * Правило доверия уехало в ядро, где ему и место. Снаружи остались вычисление и один честный ответ:
 * «это был точный расчёт или нет». Здесь сторожим ровно это — что между расчётами мы МОЛЧИМ, а не
 * выдаём сырьё за посчитанное.
 */
class КалибровкаБезМостикаTest {

    /** Файлов чужого алгоритма нет — мы в расчёте не участвуем, и вопрос о точности не к нам. */
    @Test
    fun `без вендорского алгоритма мы в расчёте не участвуем`() {
        val к = SibionicsVendorCalibrator()   // configure не звали: ядра нет
        assertNull(к.calibrate(10.3f, 30f, 100))
        assertNull("нет алгоритма — ядро должно вести себя как раньше", к.последнийТочный())
    }

    /**
     * С живым алгоритмом: точный расчёт — число, всё остальное — молчание.
     *
     * Идёт только там, где скачан чужой алгоритм (`app/scripts/fetch-vendor-calibration.sh`); в CI
     * его нет и проверять нечего.
     */
    @Test
    fun `между точными расчётами отдаём молчание, а не сырьё`() {
        Assume.assumeTrue("чужой алгоритм не скачан — проверять нечего", ВендорскийАлгоритм.доступен)
        val к = SibionicsVendorCalibrator()
        к.configure("XDUD671K")
        var точных = 0
        for (i in 0 until 60) {
            val сырое = 10f + (i % 7) * 0.1f
            val ответ = к.calibrate(сырое, 30f, i)
            when (к.последнийТочный()) {
                true -> { точных++; assertNotNull("точный расчёт — это число", ответ) }
                false -> assertNull("между расчётами мостик строит ядро, а не мы", ответ)
                null -> fail("алгоритм есть — ответ обязан быть да или нет, а не «не знаю»")
            }
        }
        assertTrue("вендорское ядро должно было ответить хотя бы раз за час", точных > 0)
    }

    /** Без температуры компенсацию не посчитать — это тоже «не точный расчёт», а не повод выдумать. */
    @Test
    fun `без температуры не считаем`() {
        Assume.assumeTrue("чужой алгоритм не скачан — проверять нечего", ВендорскийАлгоритм.доступен)
        val к = SibionicsVendorCalibrator()
        к.configure("XDUD671K")
        assertNull(к.calibrate(10.3f, null, 100))
        assertTrue("нет температуры — расчёта не было", к.последнийТочный() == false)
    }
}
