package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Что мы обещаем движку (SugarLife#482).
 *
 * Ошибка в эту сторону не видна на телефоне: перепутанный ответ означает либо обещание разбудить, которое
 * никто не выполнит, либо «обещание нарушено» на исправной охране. И то и другое человек заметит ночью.
 */
class ДоставкаTest {
    @Test
    fun `всё на месте — разбудим`() {
        assertEquals("yes", Доставка.вывод(emptyList(), тихийРежимСейчас = false))
    }

    /* Уведомления выключены целиком — показывать нечем, и «тихо» тут было бы враньём. */
    @Test
    fun `уведомления выключены — доставить нечем`() {
        assertEquals("no", Доставка.вывод(listOf("notifications-off"), тихийРежимСейчас = false))
        assertEquals("no", Доставка.вывод(listOf("notifications-off", "dnd-access"), тихийРежимСейчас = true))
    }

    /* Канал понижен человеком в системных настройках: уведомление придёт, звука не будет — всегда. */
    @Test
    fun `понижённый канал — только тихо`() {
        assertEquals("quiet", Доставка.вывод(listOf("channel-lowered"), тихийРежимСейчас = false))
    }

    /* Нет доступа к «Не беспокоить» — беда только тогда, когда тихий режим ВКЛЮЧЁН. Иначе звук идёт. */
    @Test
    fun `нет доступа к тихому режиму — смотря включён ли он сейчас`() {
        assertEquals("yes", Доставка.вывод(listOf("dnd-access"), тихийРежимСейчас = false))
        assertEquals("quiet", Доставка.вывод(listOf("dnd-access"), тихийРежимСейчас = true))
    }

    /* Полный экран решает, прочтут ли тревогу с заблокированного экрана, а будит звук. Ложное
       «обещание нарушено» учит не верить настоящему. */
    @Test
    fun `запрет полного экрана не отменяет пробуждение`() {
        assertEquals("yes", Доставка.вывод(listOf("fullscreen"), тихийРежимСейчас = false))
    }
}
