package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * ЧЕГО НЕ ДОЛЖНО БЫТЬ В ОТПРАВЛЕННОМ ЖУРНАЛЕ (SugarLife#656).
 *
 * Проверки написаны по НАСТОЯЩИМ записям с телефона владельца за 2 сентября 2026: адрес заменён на
 * вымышленный, форма строк сохранена. Тем и ценны: выдуманный образец не показал бы, что адрес
 * лежит ещё и внутри текста системной ошибки.
 */
class ВычисткаЖурналаTest {

    private val адрес = "j00000000.nightscout-example.ru"

    @Test
    fun `адрес облака в имени потока заменён, а хвост потока остался`() {
        val было = """{"id":"ns:$адрес-cgm","code":"cloud-offline"}"""
        val стало = ВычисткаЖурнала.вычистить(было)
        assertEquals("""{"id":"ns:<облако>-cgm","code":"cloud-offline"}""", стало)
    }

    /* Хвост — не украшение: по нему видно, какой канал молчит. Три потока живут на одном адресе. */
    @Test
    fun `три потока одного облака остаются различимыми`() {
        val стало = ВычисткаЖурнала.вычистить("ns:$адрес-cgm ns:$адрес-pump ns:$адрес-treat")
        assertEquals("ns:<облако>-cgm ns:<облако>-pump ns:<облако>-treat", стало)
    }

    /* Полный запрос приезжает внутри текста системной ошибки — вычистка по имени поля его не видит. */
    @Test
    fun `адрес внутри текста ошибки тоже вычищен`() {
        val было = """{"err":"Exception in http request: url=https://$адрес/api/v1/entries.json?count=288"}"""
        val стало = ВычисткаЖурнала.вычистить(было)
        assertFalse(стало.contains("nightscout-example"))
        assertTrue("путь запроса нужен для разбора", стало.contains("/api/v1/entries.json"))
    }

    /* Строка запроса уходит целиком: именно там носят токен, и по имени поля его не поймать. */
    @Test
    fun `строка запроса не уезжает наружу`() {
        val стало = ВычисткаЖурнала.вычистить("https://$адрес/api/v1/entries.json?token=секрет-123&count=5")
        assertFalse("токен из запроса не должен уехать", стало.contains("секрет-123"))
        assertEquals("https://<облако>/api/v1/entries.json", стало)
    }

    /* НАЙДЕНО ПРОГОНОМ ПО НАСТОЯЩЕМУ ЖУРНАЛУ, а не придумано: первая версия правила оставляла
       адрес в 49 записях из 4351 — там, где облако названо целиком, без потока. Одна форма была
       на виду, вторая нет. */
    @Test
    fun `голый адрес облака, без хвоста потока, тоже вычищен`() {
        assertEquals("""{"id":"ns:<облако>","streams":3}""",
            ВычисткаЖурнала.вычистить("""{"id":"ns:$адрес","streams":3}"""))
        assertEquals("""{"id":"ns:<облако>-cgm","cloud":"ns:<облако>"}""",
            ВычисткаЖурнала.вычистить("""{"id":"ns:$адрес-cgm","cloud":"ns:$адрес"}"""))
    }

    /* Уже вычищенное второй раз не трогаем: правило требует точку в адресе, а в `<облако>` её нет. */
    @Test
    fun `повторная вычистка ничего не меняет`() {
        val раз = ВычисткаЖурнала.вычистить("""{"id":"ns:$адрес-cgm","cloud":"ns:$адрес"}""")
        assertEquals(раз, ВычисткаЖурнала.вычистить(раз))
    }

    @Test
    fun `обычные записи не трогаем`() {
        val было = """{"tag":"engine","event":"start","fields":{"build":"1.2.3"}}"""
        assertEquals(было, ВычисткаЖурнала.вычистить(было))
    }

    /* Вычистка идёт по всему файлу разом, а он многострочный: NDJSON — строка на запись. */
    @Test
    fun `чистится каждая строка файла`() {
        val было = "ns:$адрес-cgm\nобычная строка\nhttps://$адрес/api/v1/treatments.json?count=1"
        val стало = ВычисткаЖурнала.вычистить(было)
        assertFalse(стало.contains(адрес))
        assertTrue(стало.contains("обычная строка"))
    }
}
