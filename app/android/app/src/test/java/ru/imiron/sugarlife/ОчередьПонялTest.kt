package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Очередь «понял» (SugarLife#482).
 *
 * Проверяем то, из-за чего ответ человека может пропасть: перезапуск между нажатием и доставкой, повторное
 * нажатие, просроченная запись и переведённые назад часы. Всё это происходит ночью и в одиночку — увидеть
 * это на телефоне можно только случайно.
 */
class ОчередьПонялTest {
    private val час = 60L * 60 * 1000

    @Test
    fun `запись переживает разбор и сборку`() {
        val хранимое = ОчередьПонял.добавить(null, "a-1", 1_000)
        val записи = ОчередьПонял.живые(хранимое, 2_000)
        assertEquals(1, записи.size)
        assertEquals("a-1", записи[0].id)
        assertEquals(1_000, записи[0].нажатоМс)
    }

    /* Человек жмёт второй раз, потому что уведомление не исчезло мгновенно. Это не второй ответ. */
    @Test
    fun `повторное нажатие не задваивает запись и не двигает время`() {
        val первое = ОчередьПонял.добавить(null, "a-1", 1_000)
        val второе = ОчередьПонял.добавить(первое, "a-1", 5_000)
        val записи = ОчередьПонял.живые(второе, 6_000)
        assertEquals(1, записи.size)
        assertEquals(1_000, записи[0].нажатоМс)
    }

    @Test
    fun `разные тревоги живут рядом и убираются поодиночке`() {
        var х = ОчередьПонял.добавить(null, "a-1", 1_000)
        х = ОчередьПонял.добавить(х, "b-2", 1_100)
        х = ОчередьПонял.убрать(х, "a-1")
        val записи = ОчередьПонял.живые(х, 1_200)
        assertEquals(1, записи.size)
        assertEquals("b-2", записи[0].id)
    }

    /* Сутки — граница. Ответ на позавчерашнюю тревогу гасить нечего, а погасить он может чужую. */
    @Test
    fun `просроченное не доставляем`() {
        val х = ОчередьПонял.добавить(null, "a-1", 0)
        assertEquals(1, ОчередьПонял.живые(х, ОчередьПонял.ЖИВЁТ_МС).size)
        assertTrue(ОчередьПонял.живые(х, ОчередьПонял.ЖИВЁТ_МС + 1).isEmpty())
    }

    /* Часы на телефоне ходят назад: сеть поправила время, человек сменил пояс. Свежий ответ от этого
       пропадать не должен. */
    @Test
    fun `часы перевели назад — запись остаётся`() {
        val х = ОчередьПонял.добавить(null, "a-1", 10 * час)
        assertEquals(1, ОчередьПонял.живые(х, 9 * час).size)
    }

    /* Идентификатор приходит от движка, а формат хранения у нас строчный. Покалеченный ключ хуже
       потерянного: он погасит не ту тревогу или не погасит ничего. */
    @Test
    fun `негодный идентификатор в очередь не попадает`() {
        assertTrue(ОчередьПонял.живые(ОчередьПонял.добавить(null, "с\tтабом", 1_000), 1_000).isEmpty())
        assertTrue(ОчередьПонял.живые(ОчередьПонял.добавить(null, "с\nпереводом", 1_000), 1_000).isEmpty())
        assertTrue(ОчередьПонял.живые(ОчередьПонял.добавить(null, "  ", 1_000), 1_000).isEmpty())
    }

    /* Мусор в хранилище (недописанная строка после падения) не должен ронять разбор: потеряем строку,
       но не всю очередь. */
    @Test
    fun `битые строки пропускаем, целые читаем`() {
        val записи = ОчередьПонял.разобрать("a-1\t1000\nмусор\nb-2\t1100\n")
        assertEquals(listOf("a-1", "b-2"), записи.map { it.id })
    }
}
