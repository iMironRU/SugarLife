package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Как показывать тревогу движка (SugarLife#482).
 *
 * Ядро предупредило о трёх местах, где легко ошибиться, и все три — здесь. Ошибка в каждом видна только
 * ночью и только один раз: тревога, которую не показали, или лесенка из десяти одинаковых.
 */
class ПравилаПоказаTest {

    @Test
    fun `уровень решает громкость`() {
        assertEquals(ПравилаПоказа.Как.НЕ_ПОКАЗЫВАТЬ, ПравилаПоказа.как("Состояние"))
        assertEquals(ПравилаПоказа.Как.ТИХО, ПравилаПоказа.как("Заметка"))
        assertEquals(ПравилаПоказа.Как.ОБЫЧНО, ПравилаПоказа.как("Сегодня"))
        assertEquals(ПравилаПоказа.Как.БУДИТЬ, ПравилаПоказа.как("Разбудить"))
        assertEquals(ПравилаПоказа.Как.БУДИТЬ, ПравилаПоказа.как("ОбещаниеНарушено"))
    }

    /* Список уровней у движка открытый. Промолчать о незнакомом — потерять тревогу; показать обычным
       звуком — худшее, что случится, это лишний звук. */
    @Test
    fun `незнакомый уровень не теряем`() {
        assertEquals(ПравилаПоказа.Как.ОБЫЧНО, ПравилаПоказа.как("НовыйУровень"))
    }

    /* Ловушка ядра №1: repeat — то же событие, а не новое. Ключ уведомления зависит только от id,
       поэтому повтор обновляет карточку, а не строит лесенку в шторке. */
    @Test
    fun `повтор обновляет то же уведомление`() {
        assertEquals(ПравилаПоказа.ключУведомления("гипо"), ПравилаПоказа.ключУведомления("гипо"))
        assertNotEquals(ПравилаПоказа.ключУведомления("гипо"), ПравилаПоказа.ключУведомления("молчание-во-сне"))
    }

    /* Ловушка №2: отбой гасит только свой id. */
    @Test
    fun `отбой — только cleared`() {
        assertTrue(ПравилаПоказа.этоОтбой("cleared"))
        listOf("started", "repeat", "escalated", "pauseOver").forEach {
            assertFalse(it, ПравилаПоказа.этоОтбой(it))
        }
    }

    /* Ключи не должны пересечься с нашими собственными номерами (4712…4714): столкновение означало бы,
       что тревога движка стирает нашу с экрана. */
    @Test
    fun `ключи уведомлений не лезут в наши номера`() {
        listOf("гипо", "высокий", "молчание-днём", "прогноз", "a", "", "очень-длинный-идентификатор")
            .forEach { assertTrue(it, ПравилаПоказа.ключУведомления(it) >= 5000) }
    }

    /**
     * Передача дежурства. Одной ревизии мало: движок, который умеет тревоги, но не считает ни одной,
     * оставил бы человека без охраны — наша половина ушла бы в отставку, не передав никому дежурство.
     */
    @Test
    fun `дежурство передаём только когда есть и мост, и правила`() {
        assertTrue(ПравилаПоказа.ведётДвижок("1.30", 3))
        assertTrue(ПравилаПоказа.ведётДвижок("2.0", 1))
        assertFalse(ПравилаПоказа.ведётДвижок("1.30", 0))
        assertFalse(ПравилаПоказа.ведётДвижок("1.29", 5))
        assertFalse(ПравилаПоказа.ведётДвижок(null, 5))
        assertFalse(ПравилаПоказа.ведётДвижок("непонятно", 5))
    }

    private fun с(id: String, what: String = "started", level: String = "Разбудить") =
        ПравилаПоказа.Событие(id = id, what = what, level = level, baseLevel = level, atMs = 1)

    @Test
    fun `отбой снимает только свою тревогу`() {
        val шаги = ПравилаПоказа.план(
            listOf(с("гипо", what = "cleared"), с("молчание-во-сне")),
            активные = null,
            показано = setOf("гипо", "молчание-во-сне"),
        )
        assertEquals(listOf("гипо"), шаги.filterIsInstance<ПравилаПоказа.Шаг.Снять>().map { it.id })
        assertEquals(
            listOf("молчание-во-сне"),
            шаги.filterIsInstance<ПравилаПоказа.Шаг.Показать>().map { it.событие.id },
        )
    }

    /* Движок перезапустился, «отбоя» не было, а тревоги в списке висящих больше нет: уведомление
       обязано уйти, иначе оно останется на экране навсегда. */
    @Test
    fun `пропавшая из списка висящих снимается без отбоя`() {
        val шаги = ПравилаПоказа.план(emptyList(), активные = listOf("молчание-во-сне"), показано = setOf("гипо", "молчание-во-сне"))
        assertEquals(listOf("гипо"), шаги.filterIsInstance<ПравилаПоказа.Шаг.Снять>().map { it.id })
    }

    /* Списка в снимке нет вовсе — старый мост. Не трогаем ничего: отсутствующий список и пустой
       означают разное, и по первому снять всё значило бы выключить охрану на старой сборке. */
    @Test
    fun `нет списка висящих — ничего не снимаем`() {
        assertTrue(ПравилаПоказа.план(emptyList(), активные = null, показано = setOf("гипо")).isEmpty())
    }

    /* Пустой список — это ответ: не висит ничего. */
    @Test
    fun `пустой список висящих снимает всё`() {
        val шаги = ПравилаПоказа.план(emptyList(), активные = emptyList(), показано = setOf("гипо", "высокий"))
        assertEquals(setOf("гипо", "высокий"), шаги.filterIsInstance<ПравилаПоказа.Шаг.Снять>().map { it.id }.toSet())
    }

    /* Показ и исчезновение из списка могут приехать одним снимком. Снимать только что показанное —
       значит мигнуть тревогой и погасить её. */
    @Test
    fun `только что показанное не снимаем тем же снимком`() {
        val шаги = ПравилаПоказа.план(listOf(с("гипо")), активные = emptyList(), показано = emptySet())
        assertTrue(шаги.filterIsInstance<ПравилаПоказа.Шаг.Показать>().isNotEmpty())
        assertTrue(шаги.filterIsInstance<ПравилаПоказа.Шаг.Снять>().isEmpty())
    }

    /* Уровень «состояние» вообще не уведомление: его человек видит на экране приложения. */
    @Test
    fun `состояние не показываем`() {
        assertTrue(ПравилаПоказа.план(listOf(с("резервуар", level = "Состояние")), null, emptySet()).isEmpty())
    }

    /* Слова временно наши: у события в контракте формулировки нет. Незнакомый id обязан получить общее
       слово, а не выдуманное частное — и всё равно показаться. */
    @Test
    fun `слова находятся и для незнакомой тревоги`() {
        assertEquals("Низкий сахар", ПравилаПоказа.слова("гипо", "Разбудить", 3.6).first)
        assertEquals("3,6 ммоль", ПравилаПоказа.слова("гипо", "Разбудить", 3.6).second)
        assertEquals("Данных нет", ПравилаПоказа.слова("молчание-во-сне", "Разбудить", null).first)
        assertEquals(
            "Тревога может не разбудить",
            ПравилаПоказа.слова("гипо:не-разбудит", "ОбещаниеНарушено", null).first,
        )
        assertEquals("Тревога", ПравилаПоказа.слова("что-то-новое", "Сегодня", null).first)
    }
}
