package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Точность пробуждения (SugarLife#482).
 *
 * Ошибиться здесь значит дать движку пообещать человеку время, которого система не даст: он напишет
 * «узнаем за 15 минут», а узнаем за 24. Проверяется тестом, потому что на телефоне разница видна только
 * в ту ночь, когда тревога опоздала.
 */
class ТочностьTest {

    @Test
    fun `выключатель включён и система разрешила — точно`() {
        assertEquals(Точность.ТОЧНО_МИН, Точность.точностьМин("on", разрешеноСистемой = true))
        assertTrue(Точность.точныйБудильник("on", разрешеноСистемой = true))
    }

    /* Человек попросил точность, разрешения ещё нет: это по-прежнему девять минут. Доложить ноль
       значило бы соврать движку, а через него — человеку. */
    @Test
    fun `просил, но система не разрешила — по-прежнему неточно`() {
        assertEquals(Точность.НЕТОЧНО_МИН, Точность.точностьМин("on", разрешеноСистемой = false))
        assertFalse(Точность.точныйБудильник("on", разрешеноСистемой = false))
        assertTrue(Точность.нуженЗапросРазрешения("on", разрешеноСистемой = false))
    }

    /* На Android 12 разрешение выдаётся при установке само. Согласия в нём нет: человек ничего не
       выбирал, а точный будильник он не просил — значит и не ставим. */
    @Test
    fun `разрешение без просьбы точность не включает`() {
        assertEquals(Точность.НЕТОЧНО_МИН, Точность.точностьМин("off", разрешеноСистемой = true))
        assertFalse(Точность.точныйБудильник("off", разрешеноСистемой = true))
        assertFalse(Точность.нуженЗапросРазрешения("off", разрешеноСистемой = true))
    }

    /* Старое ядро выключателя не присылает вовсе — ведём себя как при выключенном. */
    @Test
    fun `нет выключателя — неточно и ничего не просим`() {
        assertEquals(Точность.НЕТОЧНО_МИН, Точность.точностьМин(null, разрешеноСистемой = true))
        assertFalse(Точность.нуженЗапросРазрешения(null, разрешеноСистемой = false))
    }
}
