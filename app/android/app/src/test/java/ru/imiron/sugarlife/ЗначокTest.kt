package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/* Значок умеет только целое число, поэтому вид числа — выбор с ценой, и цена эта считается здесь.
   Правила те же, что на айфоне (ios/App/App/Значок.swift): менять их надо в двух местах разом. */
class ЗначокTest {

    @Test
    fun `десятые ничего не теряют`() {
        assertEquals(79, Значок.число("десятые", 7.9))
        assertEquals(114, Значок.число("десятые", 11.44))
    }

    /* Ровно та потеря, о которой экран предупреждает словами: «нормально» и «пора смотреть»
       выглядят одинаково. */
    @Test
    fun `целые сливают соседние значения`() {
        assertEquals(Значок.число("целые", 7.6), Значок.число("целые", 8.4))
    }

    @Test
    fun `мг считается точным коэффициентом`() {
        assertEquals(142, Значок.число("мг", 7.9))
    }

    @Test
    fun `выключенный и незнакомый вид не рисуют ничего`() {
        assertNull(Значок.число("выключен", 7.9))
        assertNull(Значок.число("что-то-новое", 7.9))
    }
}
