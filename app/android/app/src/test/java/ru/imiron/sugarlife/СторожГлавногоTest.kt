package ru.imiron.sugarlife

import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/** Порог сторожа главного потока (SugarLifeCore#236). */
class СторожГлавногоTest {

    @Test fun `кадр интерфейса зависанием не считаем`() {
        assertFalse("возврат из фона законно занимает сотни миллисекунд", СторожГлавного.встал(800))
        assertFalse(СторожГлавного.встал(2_999))
    }

    @Test fun `три секунды уже зависание`() {
        assertTrue(СторожГлавного.встал(3_000))
        assertTrue(СторожГлавного.встал(10_000))
    }

    /**
     * Зазор до системного порога — вся суть выбора. Система объявляет ANR по вводу через пять
     * секунд; снять стек надо раньше, иначе виноватый кадр уже уехал.
     */
    @Test fun `кричим раньше системы`() {
        assertTrue("порог должен быть строго меньше пяти секунд", СторожГлавного.ПОРОГ_МС < 5_000)
        assertTrue("и щупать надо чаще, чем порог", СторожГлавного.ШАГ_МС < СторожГлавного.ПОРОГ_МС)
    }
}
