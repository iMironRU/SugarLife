package ru.imiron.sugarlife

import android.content.pm.ServiceInfo
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * ОПЕКУН НЕ ДОЛЖЕН ВЫКЛЮЧАТЬСЯ ЧЕРЕЗ ШЕСТЬ ЧАСОВ (SugarLifeCore#216).
 *
 * У того, кто смотрит за ребёнком или за родителем по интернету, приборов нет и не будет. Ему
 * оставался `dataSync` с потолком в шесть часов в сутки — то есть наблюдение выключалось системой
 * под утро, ровно когда нужнее всего.
 */
class ТипСлужбыTest {

    private val прибором = ServiceInfo.FOREGROUND_SERVICE_TYPE_CONNECTED_DEVICE
    private val медиа = ServiceInfo.FOREGROUND_SERVICE_TYPE_MEDIA_PLAYBACK
    private val синхро = ServiceInfo.FOREGROUND_SERVICE_TYPE_DATA_SYNC

    @Test
    fun опекун_с_опорой_уходит_от_потолка_в_шесть_часов() {
        val тип = ТипСлужбы.выбрать(прибор = false, медиа = true)
        assertTrue("опекуну не объявили медиа: ${ТипСлужбы.словами(тип)}", тип and медиа != 0)
        assertEquals(
            "к медиа примешали dataSync — его потолок в шесть часов приедет вместе с ним",
            0, тип and синхро,
        )
    }

    @Test
    fun опекун_без_опоры_остаётся_на_синхронизации() {
        /* Опора выключена человеком — врать про плеер нельзя. Живём с потолком и честно. */
        assertEquals(синхро, ТипСлужбы.выбрать(прибор = false, медиа = false))
    }

    @Test
    fun с_прибором_объявляем_прибор() {
        val тип = ТипСлужбы.выбрать(прибор = true, медиа = false)
        assertEquals(прибором, тип)
        assertEquals("dataSync притащил бы свой потолок", 0, тип and синхро)
    }

    @Test
    fun и_прибор_и_плеер_объявляем_оба() {
        val тип = ТипСлужбы.выбрать(прибор = true, медиа = true)
        assertTrue(тип and прибором != 0)
        assertTrue(тип and медиа != 0)
        assertEquals(0, тип and синхро)
    }

    @Test
    fun пустых_обещаний_системе_не_даём() {
        /* Ровно то, за что нас, судя по журналу, убили на песочнице: служба объявляла подключённый
           прибор при выключенном Bluetooth. Ни один тип не должен появляться без своего факта. */
        val ничего = ТипСлужбы.выбрать(прибор = false, медиа = false)
        assertEquals("объявили прибор, которого нет", 0, ничего and прибором)
        assertEquals("объявили плеер, которого нет", 0, ничего and медиа)
    }

    @Test
    fun словами_читает_человек_а_не_машина() {
        assertTrue("mediaPlayback" in ТипСлужбы.словами(ТипСлужбы.выбрать(false, true)))
        assertTrue("6ч/сут" in ТипСлужбы.словами(ТипСлужбы.выбрать(false, false)))
    }

    /**
     * ОБЕЩАТЬ ПРИБОР МОЖНО ТОЛЬКО КОГДА ОН ЕСТЬ (SugarLifeCore#228).
     *
     * Сюда передавалось одно лишь разрешение на Bluetooth, и оттого после каждого запуска — когда
     * прибор стоял на паузе, а соединения не было — мы объявляли системе `connectedDevice`.
     *
     * Снято с телефона владельца 06.09: в этом состоянии нас убили через три минуты, и поднять было
     * нечем. В тот же день, держа прибор по-настоящему, тот же телефон прожил три с половиной часа.
     *
     * Тест сторожит СМЫСЛ довода: «нам можно держать прибор» и «мы его держим» — разные утверждения,
     * и системе мы говорим второе.
     */
    @Test
    fun без_прибора_на_связи_connectedDevice_не_объявляем() {
        val безПрибора = ТипСлужбы.выбрать(прибор = false, медиа = false)
        assertFalse(
            "обещали системе прибор, которого нет: ${ТипСлужбы.словами(безПрибора)}",
            "connectedDevice" in ТипСлужбы.словами(безПрибора),
        )
        assertTrue(
            "без прибора и без звука остаётся dataSync: ${ТипСлужбы.словами(безПрибора)}",
            "dataSync" in ТипСлужбы.словами(безПрибора),
        )
        // А с прибором — объявляем, и у этого типа нет предела по времени.
        assertTrue("connectedDevice" in ТипСлужбы.словами(ТипСлужбы.выбрать(прибор = true, медиа = false)))
    }

    /**
     * ПОДЪЁМ С `dataSync` БЫЛ НЕВОЗМОЖЕН (SugarLifeCore#228).
     *
     * Условие «новый тип обязан содержать старый» ложно всегда, когда старый — `dataSync`:
     * `connectedDevice and dataSync == 0`. Поймано на живом телефоне через минуту после того, как
     * попутчик впервые подключился сам: прибор на связи, а системе объявлен потолок в шесть часов.
     */
    @Test
    fun с_dataSync_поднимаемся_а_вниз_не_идём() {
        val данные = ServiceInfo.FOREGROUND_SERVICE_TYPE_DATA_SYNC
        val прибор = ServiceInfo.FOREGROUND_SERVICE_TYPE_CONNECTED_DEVICE
        val медиа = ServiceInfo.FOREGROUND_SERVICE_TYPE_MEDIA_PLAYBACK

        assertTrue("не поднялись с dataSync на прибор", ТипСлужбы.поднимать(данные, прибор))
        assertTrue("не поднялись с dataSync на медиа", ТипСлужбы.поднимать(данные, медиа))
        // Добавить второй тип к настоящему — тоже подъём.
        assertTrue(ТипСлужбы.поднимать(прибор, прибор or медиа))
        // На dataSync назад нельзя: потолок в шесть часов есть только у него.
        assertFalse("понизились до dataSync", ТипСлужбы.поднимать(прибор, данные))
        assertFalse("дёрнулись без нужды", ТипСлужбы.поднимать(прибор, прибор))
    }

    /**
     * ПЕРЕЙТИ С ПЛЕЕРА НА ПРИБОР — ТОЖЕ ПРАВО, А НЕ ПОНИЖЕНИЕ (SugarLifeCore#217).
     *
     * Здесь стояло `assertFalse("уронили второй тип", поднимать(прибор or медиа, прибор))`, и с ним
     * та же формула «новый содержит старый» запрещала уйти с `mediaPlayback` на `connectedDevice`:
     * их пересечение пусто.
     *
     * Поймано на телефоне владельца 10.09, как только опору перестали держать при живом приборе:
     *
     * ```
     * 11:03:03  старт: тип mediaPlayback     ← прибор ещё не подключился, опора ещё играла
     * 11:03:04  опора снята                  ← плеера больше нет
     * 11:05     types=0x00000002             ← а системе обещан по-прежнему он
     * ```
     *
     * Прибор при этом был на связи, показания шли, а `connectedDevice` не объявлен вовсе. Это то же
     * враньё, за которое нас убили на песочнице, только наоборот: тогда обещали прибор без прибора,
     * теперь плеер без плеера.
     */
    @Test
    fun с_плеера_на_прибор_уходим() {
        val прибор = ServiceInfo.FOREGROUND_SERVICE_TYPE_CONNECTED_DEVICE
        val медиа = ServiceInfo.FOREGROUND_SERVICE_TYPE_MEDIA_PLAYBACK

        assertTrue("застряли на плеере при живом приборе", ТипСлужбы.поднимать(медиа, прибор))
        assertTrue("не отпустили плеер, которого больше нет", ТипСлужбы.поднимать(прибор or медиа, прибор))
    }
}
