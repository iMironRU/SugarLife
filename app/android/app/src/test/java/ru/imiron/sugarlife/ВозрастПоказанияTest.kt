package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

/**
 * ЧТО ВИДЖЕТ ВПРАВЕ УТВЕРЖДАТЬ (SugarLife#694).
 *
 * Беду увидели глазами: «Данных нет · 22 ч 48 мин» на рабочем столе в час, когда показания шли раз
 * в минуту. Тестом её было не поймать, потому что правила не существовало — оно было размазано по
 * отрисовке, которая идёт в чужом процессе. Теперь правило есть, и вот его границы.
 */
class ВозрастПоказанияTest {

    private val минута = 60 * 1000L

    @Test
    fun `свежее до пятнадцатой минуты`() {
        assertEquals(Стадия.СВЕЖЕЕ, ВозрастПоказания.стадия(0))
        assertEquals(Стадия.СВЕЖЕЕ, ВозрастПоказания.стадия(14 * минута))
        assertEquals(Стадия.СВЕЖЕЕ, ВозрастПоказания.стадия(15 * минута))
    }

    @Test
    fun `после пятнадцати минут числу не верим`() {
        assertEquals(Стадия.УСТАРЕЛО, ВозрастПоказания.стадия(15 * минута + 1))
        assertEquals(Стадия.УСТАРЕЛО, ВозрастПоказания.стадия(59 * минута))
        assertEquals(Стадия.УСТАРЕЛО, ВозрастПоказания.стадия(60 * минута))
    }

    /** Час без перерисовки — и «данных нет» превращается в утверждение о том, чего мы не знаем. */
    @Test
    fun `после часа не верим и себе`() {
        assertEquals(Стадия.СЛЕПО, ВозрастПоказания.стадия(60 * минута + 1))
        assertEquals(Стадия.СЛЕПО, ВозрастПоказания.стадия(22 * 60 * минута + 48 * минута))
    }

    /** Часы перевели назад — не повод гасить показание: чужая ошибка во времени пройдёт сама. */
    @Test
    fun `запись из будущего считается свежей`() {
        assertEquals(Стадия.СВЕЖЕЕ, ВозрастПоказания.стадия(-5 * минута))
    }

    /** Будильник заводится на минуту, когда виджету будет что сказать. */
    @Test
    fun `рубежи идут по порядку`() {
        val когда = 1_700_000_000_000L
        assertEquals(когда + 15 * минута, ВозрастПоказания.следующийРубеж(когда, Стадия.СВЕЖЕЕ))
        assertEquals(когда + 60 * минута, ВозрастПоказания.следующийРубеж(когда, Стадия.УСТАРЕЛО))
    }

    /**
     * Слепому виджету будильник не нужен: «неизвестно» остаётся правдой сколько угодно долго.
     * Лишний будильник будил бы телефон всю ночь ради слова, которое не меняется.
     */
    @Test
    fun `слепому будить себя незачем`() {
        assertNull(ВозрастПоказания.следующийРубеж(1_700_000_000_000L, Стадия.СЛЕПО))
    }
}
