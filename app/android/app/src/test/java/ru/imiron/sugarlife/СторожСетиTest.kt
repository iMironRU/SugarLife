package ru.imiron.sugarlife

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * 830 СООБЩЕНИЙ ЗА СУТКИ ПРЕВРАЩАЮТСЯ В ЕДИНИЦЫ (SugarLifeCore#213).
 *
 * `onCapabilitiesChanged` система зовёт на любое изменение свойств сети — скорость канала, уровень
 * сигнала, метрики оператора. Мы на каждый вызов говорили движку «сеть вернулась».
 */
class СторожСетиTest {

    @Test
    fun поток_одинаковых_сообщений_превращается_в_одно() {
        val с = СторожСети()
        /* Ровно то, что делает система при живом Wi-Fi: сообщает свойства снова и снова. */
        val сказали = (1..500).count { с.мнениеСменилось(true) }
        assertEquals("шумные повторы дошли до движка", 1, сказали)
    }

    @Test
    fun настоящий_разрыв_и_возврат_видны_оба() {
        val с = СторожСети()
        assertTrue("первое мнение не дошло", с.мнениеСменилось(true))
        repeat(50) { с.мнениеСменилось(true) }
        assertTrue("пропажу интернета не заметили", с.мнениеСменилось(false))
        repeat(50) { с.мнениеСменилось(false) }
        assertTrue("возвращение интернета не заметили", с.мнениеСменилось(true))
    }

    @Test
    fun первое_мнение_доходит_даже_если_интернета_нет() {
        /* Начинаем с «не знаем». Движку после перезапуска нужно услышать состояние, а не только
           его смену: иначе он останется без мнения и вернётся к угадыванию по свежести. */
        assertTrue(СторожСети().мнениеСменилось(false))
    }

    @Test
    fun молчим_ровно_тогда_когда_ничего_не_произошло() {
        val с = СторожСети()
        с.мнениеСменилось(true)
        assertFalse(с.мнениеСменилось(true))
    }
}
