package ru.imiron.sugarlife

import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * КОГДА ПОДНИМАТЬ ЭКРАН ПОСЛЕ СМЕРТИ ОТРИСОВЩИКА (SugarLifeCore#231).
 *
 * Снято с телефона владельца: отрисовщик упал сам в 07:28, пока приложение было в фоне. Мы пометили
 * и стали ждать возвращения. Человек открыл приложение в 08:24 — и увидел пустоту, потому что чинить
 * мы начали ровно в этот миг. Пятьдесят шесть минут были потрачены на ожидание.
 */
class ПодъёмЭкранаTest {

    @Test
    fun упал_сам_в_фоне_чиним_сразу() {
        // Про память речи нет: это наша ошибка внутри отрисовщика, а не нехватка на телефоне.
        // Значит к возвращению человека экран должен быть уже готов.
        assertTrue(СторожОтрисовщика.пораПоднимать(самУпал = true, наВиду = false))
    }

    @Test
    fun убит_по_памяти_в_фоне_ждём() {
        /*
         * Здесь ожидание — не лень, а расчёт: систему прижало по памяти, она убила отрисовщик именно
         * поэтому. Пересобрать его тут же значит попроситься под тот же нож.
         */
        assertFalse(СторожОтрисовщика.пораПоднимать(самУпал = false, наВиду = false))
    }

    @Test
    fun на_виду_поднимаем_всегда() {
        // Человек смотрит на пустой экран прямо сейчас — тут не до бережливости.
        assertTrue(СторожОтрисовщика.пораПоднимать(самУпал = true, наВиду = true))
        assertTrue(СторожОтрисовщика.пораПоднимать(самУпал = false, наВиду = true))
    }
}
