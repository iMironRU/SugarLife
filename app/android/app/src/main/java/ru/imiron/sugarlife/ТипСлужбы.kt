package ru.imiron.sugarlife

import android.content.pm.ServiceInfo

/**
 * ЧЕМ СЛУЖБА ПРЕДСТАВЛЯЕТСЯ СИСТЕМЕ (#380, #685, SugarLifeCore#216).
 *
 * Вынесено из [SugarLifeService] отдельно не ради красоты: тут одно решение, у него три исхода и
 * своя цена у каждого — такое проверяют тестом, а не чтением.
 *
 * ДВА ПОТРЕБИТЕЛЯ, И ВТОРОЙ НЕ УРЕЗАННЫЙ ПЕРВЫЙ. Есть человек со своими приборами, и есть тот, кто
 * смотрит за ним через интернет: родитель за ребёнком, взрослый за родителем. У второго приборов не
 * будет никогда — значит `connectedDevice` ему объявить не из чего, а у `dataSync` на Android 15
 * потолок шесть часов в сутки на всё приложение. Посмотрел вечером, лёг спать — под утро наблюдения
 * нет, и ровно в те часы, когда оно нужнее всего. То есть режим опекуна выключается по документации,
 * а не по вредности прошивки.
 *
 * `mediaPlayback` предела не имеет — и это единственная опора, доступная тому, у кого нет приборов.
 *
 * ОБЪЯВЛЯЕМ ТОЛЬКО ТО, ЧТО ЕСТЬ. `connectedDevice` без прибора — враньё, и на песочнице за него,
 * судя по всему, и убили: служба обещала подключённый прибор при выключенном Bluetooth, и через
 * восемь минут после ухода в фон приложение остановили на сутки. `mediaPlayback` без звучащего
 * плеера — то же самое враньё, поэтому оно подпёрто фактом (`ЗвуковаяОпора.можноОбъявлятьМедиа`), а
 * не намерением человека включить опору.
 */
object ТипСлужбы {

    /**
     * @param прибор ПРИБОР НА СВЯЗИ ПРЯМО СЕЙЧАС — и разрешение выдано (SugarLifeCore#228).
     *
     *   Здесь стояло одно только разрешение на Bluetooth, и это была ровно та беда, о которой
     *   предупреждает абзац выше. После каждого запуска прибор оставался на паузе — авто-подключение
     *   выключила миграция, — соединения не было, а системе мы объявляли `connectedDevice`.
     *
     *   Снято с телефона владельца 06.09: в этом состоянии нас убили через три минуты, и поднять
     *   было нечем (#227). В тот же день, когда прибор держали по-настоящему, тот же телефон прожил
     *   три с половиной часа.
     *
     *   Разрешения мало ещё и по смыслу: оно говорит «нам МОЖНО держать прибор», а системе мы
     *   обещаем «мы его держим». Это разные утверждения, и второе проверяемо.
     *
     * @param медиа играет ли опора И числимся ли мы плеером прямо сейчас.
     */
    fun выбрать(прибор: Boolean, медиа: Boolean): Int {
        var тип = 0
        if (прибор) тип = тип or ServiceInfo.FOREGROUND_SERVICE_TYPE_CONNECTED_DEVICE
        if (медиа) тип = тип or ServiceInfo.FOREGROUND_SERVICE_TYPE_MEDIA_PLAYBACK
        /* dataSync — только когда больше сказать нечего. Примешивать его к остальным значит притащить
           с собой и его потолок: тип-то объявлен, и шесть часов начнут считаться. */
        return if (тип != 0) тип else ServiceInfo.FOREGROUND_SERVICE_TYPE_DATA_SYNC
    }

    /**
     * МЕНЯТЬ ЛИ ОБЪЯВЛЕННЫЙ ТИП (SugarLifeCore#228).
     *
     * Правило «вниз не понижаем никогда» верно: разрешение можно отобрать, а объявленный тип работает
     * до перезапуска, и понижение сделало бы шесть часов из ничего.
     *
     * Но записано оно было как «новый тип обязан содержать старый», и на этом подъём с `dataSync`
     * оказался невозможен: `connectedDevice and dataSync == 0`, то есть условие ложно всегда.
     *
     * Поймано на живом телефоне 07.09, через минуту после того, как попутчик впервые подключился сам:
     * прибор на связи, а системе объявлен `dataSync` с его потолком в шесть часов. Мы перестали врать
     * и немедленно начали ошибаться в другую сторону.
     *
     * `dataSync` — это «сказать нечего»; уход с него на что угодно есть повышение, а не замена.
     */
    fun поднимать(текущий: Int, нужен: Int): Boolean = when {
        нужен == текущий -> false
        текущий == ServiceInfo.FOREGROUND_SERVICE_TYPE_DATA_SYNC -> true
        else -> (нужен and текущий) == текущий      // новый содержит старый — значит это подъём
    }

    /** Только для журнала: тип — битовая маска, а в журнале её должен прочесть человек. */
    fun словами(тип: Int): String = buildList {
        if (тип and ServiceInfo.FOREGROUND_SERVICE_TYPE_CONNECTED_DEVICE != 0) add("connectedDevice")
        if (тип and ServiceInfo.FOREGROUND_SERVICE_TYPE_MEDIA_PLAYBACK != 0) add("mediaPlayback")
        if (тип and ServiceInfo.FOREGROUND_SERVICE_TYPE_DATA_SYNC != 0) add("dataSync (предел 6ч/сут на Android 15)")
    }.joinToString("+").ifEmpty { "без типа" }
}
