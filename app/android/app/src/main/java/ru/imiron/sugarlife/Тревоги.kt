/**
 * Тревога о низком сахаре (SugarLife#418).
 *
 * ПОЧЕМУ ЭТО ЖИВЁТ В KOTLIN, А НЕ В ИНТЕРФЕЙСЕ. Ночью интерфейса нет: экран погашен, webview усыплён, и
 * решение «пора будить» принять некому. Тревога, работающая только при открытом приложении, — не тревога,
 * а сообщение. Поэтому правило исполняется здесь, рядом с движком, который в фоне живёт (см. #380).
 *
 * ОДНО МНЕНИЕ, А НЕ ДВА. Пороги и «включено ли» задаёт человек в приложении; они приезжают сюда один раз и
 * лежат в настройках. Здесь их не пересчитывают и не додумывают — здесь только исполняют. Два мнения о том,
 * что считать гипогликемией, разошлись бы в первую же ночь.
 *
 * ПОДТВЕРЖДЕНИЕ ВТОРЫМ ПОКАЗАНИЕМ. Сенсор шумит, и одиночный выброс вниз — повод посмотреть, а не будить.
 * Будим, когда подряд идут два показания ниже порога. Цена ошибки несимметрична, но в обе стороны: ложная
 * тревога в три часа ночи учит выключать тревоги вообще, и следующая — настоящая — не разбудит.
 *
 * ПОВТОР С РАСТУЩИМ ИНТЕРВАЛОМ. Тревога, звучащая одинаково каждые пять минут, тоже учит её выключать.
 * Первый повтор через 10 минут, дальше вдвое, до получаса — пока сахар не поднялся выше порога.
 */
object Тревоги {
    private const val TAG = "SugarLifeТревоги"
    /* Канал виден снаружи: тем же каналом показывает будящие тревоги движка (ТревогиДвижка.kt).
       Второй канал с теми же настройками означал бы два переключателя в системе на одно и то же —
       человек приглушил бы один и не понял, почему звук остался. */
    const val КАНАЛ = "sugarlife-alarm"
    private const val ID_ГИПО = 4712
    /* Своё уведомление, а не переписывание гипо: это разные поводы, и «данных нет» не должно
       стирать с экрана «низкий сахар», а низкий — прятать то, что данных больше не идёт. */
    private const val ID_МОЛЧАНИЕ = 4713
    private const val ID_ПЕРЕЗАГРУЗКА = 4714

    private const val НАСТРОЙКИ = "sugarlife-alarms"
    private const val КЛЮЧ_ВКЛ = "hypo-on"
    private const val КЛЮЧ_ПОРОГ = "hypo-mmol"
    private const val КЛЮЧ_ВЫСОКИЙ_ВКЛ = "high-on"
    private const val КЛЮЧ_ВЫСОКИЙ = "high-mmol"
    private const val КЛЮЧ_ТИХО_С = "quiet-from"
    private const val КЛЮЧ_ТИХО_ДО = "quiet-to"
    private const val КЛЮЧ_МОЛЧАНИЕ_ВКЛ = "silence-on"
    private const val КЛЮЧ_МОЛЧАНИЕ_МИН = "silence-min"
    private const val КЛЮЧ_ОТДАЛИ = "devices-released"

    /** Значения по умолчанию — те же, что показывает экран настроек. */
    const val ПОРОГ_ПО_УМОЛЧАНИЮ = 3.9
    const val ВЫСОКИЙ_ПО_УМОЛЧАНИЮ = 13.9
    /** Тихие часы выключены: -1 означает «не заданы», а не полночь. */
    const val ТИХО_ВЫКЛ = -1
    /** Молчание: полчаса. Обычная пауза НМГ — пять минут, значит тридцать это шесть пропусков подряд. */
    const val МОЛЧАНИЕ_ПО_УМОЛЧАНИЮ_МИН = 30

    private const val ПЕРВЫЙ_ПОВТОР_МС = 10 * 60_000L
    /* Молчание повторяем реже гипо: гипо — состояние человека, молчание — состояние техники,
       и вторая новость терпит чуть дольше. Но не бесконечно: полчаса — потолок обеих. */
    private const val ПЕРВЫЙ_ПОВТОР_МОЛЧАНИЯ_МС = 15 * 60_000L
    private const val МАКС_ПОВТОР_МС = 30 * 60_000L

    /** Сколько подряд показаний ниже порога нужно, чтобы будить. */
    private const val ПОДТВЕРЖДЕНИЙ = 2

    @Volatile private var подрядНиже = 0
    @Volatile private var последняяТревогаМс = 0L
    @Volatile private var следующийПовторМс = ПЕРВЫЙ_ПОВТОР_МС
    @Volatile private var последнееПоказаниеМс = 0L

    /* Высокий считается отдельным счётчиком: это другой повод, и путать их нельзя.
       Повтор у него реже — высокий сахар не требует действий в ту же минуту, а тревога,
       звучащая каждые десять минут при 14 ммоль, будет выключена в первую же ночь. */
    /* Время самого свежего показания и признак того, что про молчание уже сказали.

       В памяти, а не в настройках — намеренно. Пережить перезапуск процесса эта пара не должна:
       после перезапуска мы просто не знаем, шли ли данные, пока нас не было, и тревожить «данных
       нет два часа» на основании собственной смерти нечестно. Первое же показание всё расскажет. */
    @Volatile private var времяПоследнихМс = 0L
    @Volatile private var сказалиОМолчанииМс = 0L

    /* ПОВТОР ТРЕВОГИ О МОЛЧАНИИ (#468). Раньше она звучала РОВНО ОДИН РАЗ: проспал — не узнал.
       А молчание ночью означает «твоя защита выключена»: пока цифр нет, тревога о низком сахаре
       сработать не может в принципе, считать нечего. Поэтому повторяем, как у гипо, — с растущим
       интервалом, чтобы не превратить тревогу в шум, который учатся выключать. Верхнего предела по
       числу повторов нет: молчание кончается либо приходом данных, либо руками человека. */
    @Volatile private var следующийПовторМолчанияМс = ПЕРВЫЙ_ПОВТОР_МОЛЧАНИЯ_МС

    @Volatile private var подрядВыше = 0
    @Volatile private var последняяВысокаяМс = 0L
    private const val ПОВТОР_ВЫСОКОГО_МС = 60 * 60_000L

    fun настроить(
        ctx: Context,
        включено: Boolean,
        порогMmol: Double,
        высокийВкл: Boolean,
        высокийMmol: Double,
        тихоС: Int,
        тихоДо: Int,
        молчаниеВкл: Boolean,
        молчаниеМин: Int,
    ) {
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).edit()
            .putBoolean(КЛЮЧ_ВКЛ, включено)
            .putFloat(КЛЮЧ_ПОРОГ, порогMmol.toFloat())
            .putBoolean(КЛЮЧ_ВЫСОКИЙ_ВКЛ, высокийВкл)
            .putFloat(КЛЮЧ_ВЫСОКИЙ, высокийMmol.toFloat())
            .putInt(КЛЮЧ_ТИХО_С, тихоС)
            .putInt(КЛЮЧ_ТИХО_ДО, тихоДо)
            .putBoolean(КЛЮЧ_МОЛЧАНИЕ_ВКЛ, молчаниеВкл)
            .putInt(КЛЮЧ_МОЛЧАНИЕ_МИН, молчаниеМин)
            .apply()
        Log.i(TAG, "настройки: гипо=$включено/$порогMmol высокий=$высокийВкл/$высокийMmol тихо=$тихоС..$тихоДо молчание=$молчаниеВкл/$молчаниеМин")
    }

    fun высокийВключён(ctx: Context): Boolean =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).getBoolean(КЛЮЧ_ВЫСОКИЙ_ВКЛ, false)

    fun высокийПорог(ctx: Context): Double =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE)
            .getFloat(КЛЮЧ_ВЫСОКИЙ, ВЫСОКИЙ_ПО_УМОЛЧАНИЮ.toFloat()).toDouble()

    fun тихоС(ctx: Context): Int =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).getInt(КЛЮЧ_ТИХО_С, ТИХО_ВЫКЛ)

    fun тихоДо(ctx: Context): Int =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).getInt(КЛЮЧ_ТИХО_ДО, ТИХО_ВЫКЛ)

    /**
     * Идут ли сейчас тихие часы.
     *
     * Окно может переходить через полночь (с 23 до 7) — это обычный случай, а не край:
     * тихие часы для того и заводят, чтобы захватить ночь. Поэтому сравнение разное в
     * зависимости от того, перевалило ли окно за сутки.
     */
    fun тихоСейчас(ctx: Context, час: Int = java.util.Calendar.getInstance().get(java.util.Calendar.HOUR_OF_DAY)): Boolean {
        val с = тихоС(ctx); val до = тихоДо(ctx)
        if (с == ТИХО_ВЫКЛ || до == ТИХО_ВЫКЛ || с == до) return false
        return if (с < до) час in с until до else час >= с || час < до
    }

    fun молчаниеВключено(ctx: Context): Boolean =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).getBoolean(КЛЮЧ_МОЛЧАНИЕ_ВКЛ, false)

    fun молчаниеПорог(ctx: Context): Int =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE)
            .getInt(КЛЮЧ_МОЛЧАНИЕ_МИН, МОЛЧАНИЕ_ПО_УМОЛЧАНИЮ_МИН)

    /**
     * Приборы отданы другому телефону — молчание объяснено, и тревожить не о чем (#395).
     *
     * Без этого сторож ругался бы ровно на то, что человек сделал сам и нарочно: нажал «отдать»,
     * чтобы подключиться со второго телефона, — и через полчаса получил тревогу о том, что данных
     * нет. Тревога, ругающая за собственное решение человека, будет выключена первой.
     */
    fun приборыОтданы(ctx: Context, отданы: Boolean) {
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).edit()
            .putBoolean(КЛЮЧ_ОТДАЛИ, отданы).apply()
        if (!отданы) времяПоследнихМс = 0L
    }

    fun приборыОтданы(ctx: Context): Boolean =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).getBoolean(КЛЮЧ_ОТДАЛИ, false)

    fun включено(ctx: Context): Boolean =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE).getBoolean(КЛЮЧ_ВКЛ, false)

    fun порог(ctx: Context): Double =
        ctx.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE)
            .getFloat(КЛЮЧ_ПОРОГ, ПОРОГ_ПО_УМОЛЧАНИЮ.toFloat()).toDouble()

    /**
     * Разобрать снимок движка и решить, будить ли.
     *
     * Снимок приходит целиком и часто; нас интересует одно число и его время. Время нужно, чтобы не считать
     * подтверждением ПОВТОР одного и того же показания: движок эмитит снимок на любое изменение, и без
     * проверки времени два одинаковых снимка сошли бы за два показания.
     */
    fun приСнимке(ctx: Context, json: String) {
        val (сахар, когдаМс) = разобрать(json) ?: return
        if (когдаМс != 0L && когдаМс == последнееПоказаниеМс) return
        последнееПоказаниеМс = когдаМс
        /* Приход данных отмечаем ДО всех порогов и выключателей: сторож молчания следит за самим
           фактом, что цифры идут, и знать об этом обязан независимо от того, включена ли гипо. */
        данныеПришли(ctx, когдаМс)
        /* Заодно сверяем, чем мы располагаем (#482): человек мог отобрать доступ к «Не беспокоить» или
           включить тихий режим час назад, а перезапуска с тех пор не было. Доклад уходит, только если
           ответ изменился, — это несколько сравнений на показание. */
        Доставка.доложить(ctx)
        if (!включено(ctx) && !высокийВключён(ctx)) return

        высокий(ctx, сахар)
        if (!включено(ctx)) return

        val порог = порог(ctx)
        if (сахар >= порог) {
            /* Поднялся — счётчик и повторы сбрасываем. Тревога кончилась не потому, что мы устали
               спрашивать, а потому, что причина ушла. */
            if (подрядНиже > 0 || последняяТревогаМс != 0L) Log.i(TAG, "сахар $сахар ≥ порога $порог — отбой")
            подрядНиже = 0
            последняяТревогаМс = 0
            следующийПовторМс = ПЕРВЫЙ_ПОВТОР_МС
            return
        }

        подрядНиже++
        if (подрядНиже < ПОДТВЕРЖДЕНИЙ) {
            Log.i(TAG, "сахар $сахар ниже порога $порог, но это первое показание — ждём подтверждения")
            return
        }

        val сейчас = System.currentTimeMillis()
        if (последняяТревогаМс != 0L && сейчас - последняяТревогаМс < следующийПовторМс) return
        if (последняяТревогаМс != 0L) следующийПовторМс = minOf(следующийПовторМс * 2, МАКС_ПОВТОР_МС)
        последняяТревогаМс = сейчас

        показать(
            ctx,
            "Низкий сахар: ${"%.1f".format(сахар).replace('.', ',')}",
            "Ниже вашего порога ${"%.1f".format(порог).replace('.', ',')} ммоль/л. Проверьте глюкометром.",
        )
    }

    /**
     * Высокий сахар (#418).
     *
     * ТИХИЕ ЧАСЫ ГЛУШАТ ЕГО, А ГИПО — НЕТ, и это главное различие между двумя тревогами.
     * Высокий сахар ночью требует решения утром; низкий — сейчас. Тихие часы заводят,
     * чтобы спать, и тревога, которая будит ради «13,9», приведёт к тому, что человек
     * выключит тревоги вообще — вместе с той, которая спасает.
     *
     * Повтор реже: раз в час против десяти минут у гипо. Тревога, звучащая каждые десять
     * минут при высоком, — это не помощь, а наказание за то, что человек уже знает.
     */
    private fun высокий(ctx: Context, сахар: Double) {
        if (!высокийВключён(ctx)) return
        val порог = высокийПорог(ctx)
        if (сахар <= порог) {
            подрядВыше = 0
            последняяВысокаяМс = 0
            return
        }
        подрядВыше++
        if (подрядВыше < ПОДТВЕРЖДЕНИЙ) return
        if (тихоСейчас(ctx)) {
            Log.i(TAG, "высокий $сахар, но идут тихие часы — молчим до утра")
            return
        }
        val сейчас = System.currentTimeMillis()
        if (последняяВысокаяМс != 0L && сейчас - последняяВысокаяМс < ПОВТОР_ВЫСОКОГО_МС) return
        последняяВысокаяМс = сейчас
        показать(
            ctx,
            "Высокий сахар: ${"%.1f".format(сахар).replace('.', ',')}",
            "Выше вашего порога ${"%.1f".format(порог).replace('.', ',')} ммоль/л уже второе показание подряд.",
        )
    }


    /**
     * Данные пришли — заново запускаем счёт молчания и молча снимаем прошлую тревогу (#243).
     *
     * МОЛЧА. О том, что связь вернулась, сообщать не надо: человек либо спит, и будить его хорошей
     * новостью — издевательство, либо чинил сенсор и сам всё видит. Уведомление просто исчезает.
     */
    private fun данныеПришли(ctx: Context, когдаМс: Long) {
        /* Время самого показания, а не «сейчас»: снимок мог приехать пачкой после паузы, и считать
           паузу от момента доставки значило бы стереть её. Нет времени у показания — берём часы. */
        времяПоследнихМс = if (когдаМс != 0L) когдаМс else System.currentTimeMillis()
        if (сказалиОМолчанииМс != 0L) {
            Log.i(TAG, "данные вернулись — снимаем тревогу о молчании")
            сказалиОМолчанииМс = 0
            следующийПовторМолчанияМс = ПЕРВЫЙ_ПОВТОР_МОЛЧАНИЯ_МС
            снять(ctx, ID_МОЛЧАНИЕ)
        }
    }

    /**
     * Данных нет слишком долго (SugarLife#243).
     *
     * ЭТО ТРЕВОГА НАД ТРЕВОГАМИ. Гипо и высокий срабатывают от показаний; когда показаний нет, они
     * молчат — и молчание выглядит ровно как «всё хорошо». Сенсор отвалился в три часа ночи, сахар
     * едет вниз, телефон спокоен: тревоги включены, порог задан, будить нечем. Единственный способ
     * закрыть эту дыру — следить не за числом, а за тем, что числа приходят.
     *
     * ПО ЧАСАМ, А НЕ ПО СНИМКУ. Отсюда и отдельный будильник: снимков в молчание не бывает по
     * определению, значит и повода проснуться у кода нет. Считает [SilenceWatchdog], который будит
     * сам себя, — иначе проверка жила бы только пока идут данные, то есть ровно когда не нужна.
     *
     * ТИХИЕ ЧАСЫ ЕЁ НЕ ГЛУШАТ, в отличие от высокого сахара. Тихие часы существуют, чтобы не будить
     * ради того, что подождёт до утра. «Данных нет» до утра не ждёт: именно ночью на эту тревогу
     * рассчитывают, и заглушить её значит вернуть ту самую дыру, ради которой всё написано.
     *
     * ОДИН РАЗ ЗА ОДНО МОЛЧАНИЕ (#243). Повторять бессмысленно: сенсор не начнёт отвечать оттого,
     * что мы позвоним ещё раз, а тревога, звенящая всю ночь над неисправимым, учит выключать
     * тревоги вообще. Счётчик сбрасывается, когда данные вернулись, — тогда следующая пауза снова
     * получит право голоса.
     */
    fun проверитьМолчание(ctx: Context) {
        if (!молчаниеВключено(ctx)) return
        /* Ни разу не видели данных — говорить не о чем. Это не «всё плохо», а «ещё не начиналось»:
           так выглядит первый запуск, и тревога здесь означала бы ругань на пустое место. */
        val было = времяПоследнихМс
        if (было == 0L) return
        if (приборыОтданы(ctx)) return

        val прошлоМин = (System.currentTimeMillis() - было) / 60_000L
        val порог = молчаниеПорог(ctx).toLong()
        if (прошлоМин < порог) return

        val сейчас = System.currentTimeMillis()
        /* Уже говорили — молчим до следующего повтора, а не до скончания века. */
        if (сказалиОМолчанииМс != 0L) {
            if (сейчас - сказалиОМолчанииМс < следующийПовторМолчанияМс) return
            следующийПовторМолчанияМс = minOf(следующийПовторМолчанияМс * 2, МАКС_ПОВТОР_МС)
        }
        сказалиОМолчанииМс = сейчас
        val когда = java.text.SimpleDateFormat("HH:mm", java.util.Locale("ru")).format(java.util.Date(было))
        показать(
            ctx,
            "Данных нет $прошлоМин ${минут(прошлоМин)}",
            "Последнее показание в $когда. Пока цифры не идут, тревога о низком сахаре сработать не может — считать нечего.",
            ID_МОЛЧАНИЕ,
        )
        Log.w(TAG, "молчание $прошлоМин мин (порог $порог) — будим")
    }

    /**
     * ПРОБЬЁТСЯ ЛИ ТРЕВОГА НОЧЬЮ (#468).
     *
     * Разрешения в манифесте — это только право спросить. Доступ к «Не беспокоить» выдаёт человек
     * руками, и пока он не выдан, система молча игнорирует обход тихого режима: тревога придёт, но
     * беззвучной. Хуже всего, что выглядит это исправно — уведомление в шторке утром на месте.
     *
     * Поэтому спрашиваем сами и говорим вслух. Возвращаем то, чего не хватает, человеческим языком;
     * пустой список — всё на месте.
     */
    fun чегоНеХватаетДляНочи(ctx: Context): List<String> = поломки(ctx).map { it.second }

    /**
     * То же, но КОДОМ И ФРАЗОЙ (просьба интерфейса, SugarLife#473).
     *
     * Дословную строку нельзя разложить по разделам экрана: «услышим ли тревогу» и «заметим ли
     * пропажу данных» — разные пункты, а поломки разрешений валились в один. Код машине, фраза
     * человеку; фраза по-прежнему живёт здесь, чтобы на двух платформах не разошлась.
     *
     * Коды: `notifications-off`, `dnd-access`, `fullscreen`, `channel-lowered`.
     */
    fun поломки(ctx: Context): List<Pair<String, String>> {
        val nm = ctx.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
        val нет = mutableListOf<Pair<String, String>>()
        if (!nm.areNotificationsEnabled()) {
            нет += "notifications-off" to "уведомления выключены целиком"
        }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M && !nm.isNotificationPolicyAccessGranted) {
            нет += "dnd-access" to "нет доступа к «Не беспокоить» — ночью тревога будет беззвучной"
        }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE && !nm.canUseFullScreenIntent()) {
            нет += "fullscreen" to "запрещены полноэкранные уведомления — тревога останется строкой в шторке"
        }
        val канал = nm.getNotificationChannel(КАНАЛ)
        if (канал != null && канал.importance < NotificationManager.IMPORTANCE_HIGH) {
            нет += "channel-lowered" to "канал тревог понижен в системных настройках — звука не будет"
        }
        return нет
    }

    /**
     * УСТУПИТЬ ДЕЖУРСТВО ДВИЖКУ (#482).
     *
     * Зовётся один раз, когда в снимке появились правила движка: с этой минуты тревоги считает он, а мы
     * только показываем (ТревогиДвижка.kt). Двоевластие в тревогах запрещено прямо — две реализации,
     * работающие параллельно, невозможно проверить по отдельности.
     *
     * Снимаем СВОИ уведомления и гасим свой сторож молчания: иначе на экране осталась бы наша тревога,
     * которую уже никто не обновляет, а сторож будил бы вторым голосом по своим порогам.
     *
     * Счётчики обнуляем на случай возврата дежурства (старая сборка ядра после отката): считать
     * подтверждения с середины нельзя.
     */
    fun уступить(ctx: Context) {
        снять(ctx, ID_ГИПО)
        снять(ctx, ID_МОЛЧАНИЕ)
        SilenceWatchdog.отменить(ctx)
        подрядНиже = 0
        последняяТревогаМс = 0
        следующийПовторМс = ПЕРВЫЙ_ПОВТОР_МС
        сказалиОМолчанииМс = 0
        следующийПовторМолчанияМс = ПЕРВЫЙ_ПОВТОР_МОЛЧАНИЯ_МС
        Log.i(TAG, "дежурство по тревогам передано движку")
    }

    /**
     * ТЕЛЕФОН ПЕРЕЗАГРУЗИЛСЯ, А МОНИТОРИНГА НЕТ (#476).
     *
     * Уровень «обещание нарушено»: это не событие о сахаре, а отказ самой охраны. Ночное обновление
     * системы выключает всё разом и ничего не поднимает — до разблокировки телефон шифрован, движку
     * негде взять свою базу.
     *
     * Звучим как тревога, а не как заметка: человек, которому нужно нажать одну кнопку, чтобы
     * вернуть себе защиту, должен об этом узнать сейчас, а не утром по дырке в графике.
     *
     * Хранилище устройства обязательно: обычное до разблокировки недоступно, и обращение к нему тут
     * просто упало бы.
     */
    fun сказатьПроПерезагрузку(ctx: Context) {
        val ctxУстройства = ctx.createDeviceProtectedStorageContext()
        показать(
            ctxУстройства,
            "Мониторинг не работает",
            "Телефон перезагрузился — похоже, ставилось обновление системы. Пока вы не разблокируете " +
                "телефон, данные не собираются и тревоги о низком сахаре сработать не могут.",
            ID_ПЕРЕЗАГРУЗКА,
        )
    }

    /** Разблокировали — сообщение своё отработало, висеть ему незачем. */
    fun снятьПроПерезагрузку(ctx: Context) {
        runCatching { снять(ctx.createDeviceProtectedStorageContext(), ID_ПЕРЕЗАГРУЗКА) }
    }

    /** Куда вести человека за доступом к «Не беспокоить». null — версия Android слишком старая. */
    fun экранДоступаКТихомуРежиму(): Intent? =
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M)
            Intent(android.provider.Settings.ACTION_NOTIFICATION_POLICY_ACCESS_SETTINGS)
        else null

    /** «35 минут», «31 минуту», «32 минуты» — иначе тревога выглядит машинной запиской. */
    private fun минут(n: Long): String {
        val сотня = n % 100
        val единицы = n % 10
        return when {
            сотня in 11..14 -> "минут"
            единицы == 1L -> "минуту"
            единицы in 2..4 -> "минуты"
            else -> "минут"
        }
    }

    private fun снять(ctx: Context, id: Int) {
        runCatching {
            (ctx.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager).cancel(id)
        }.onFailure { Log.w(TAG, "не удалось снять уведомление $id: $it") }
    }

    /** Разбор снимка: сахар в ммоль и время показания. null — числа нет, и выдумывать его нельзя. */
    private fun разобрать(json: String): Pair<Double, Long>? = runCatching {
        val monitor = JSONObject(json).optJSONObject("monitor") ?: return null
        if (monitor.isNull("glucoseMmol")) return null
        val сахар = monitor.optDouble("glucoseMmol")
        if (сахар.isNaN() || сахар <= 0.0) return null
        сахар to monitor.optLong("latestAtMs", 0L)
    }.getOrNull()

    /**
     * Проверочная тревога — та же дорога, что и настоящая (#418).
     *
     * Иначе проверить нечем: человек включает тревоги вечером и узнаёт, работают ли они, только когда ночью
     * случится гипогликемия. Это худший из возможных способов узнать. Кнопка проходит весь путь целиком:
     * канал, звук, обход «не беспокоить», полноэкранное намерение.
     */
    fun проверочная(ctx: Context) {
        показать(
            ctx,
            "Проверка тревоги",
            "Так будет выглядеть и звучать тревога о низком сахаре. Это проверка — сахар в порядке.",
        )
    }

    private fun показать(ctx: Context, заголовок: String, текст: String, id: Int = ID_ГИПО) {
        val nm = ctx.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
        канал(nm)
        val открыть = PendingIntent.getActivity(
            ctx, 2,
            ctx.packageManager.getLaunchIntentForPackage(ctx.packageName)
                ?: Intent(Intent.ACTION_MAIN),
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
        )
        val n: Notification = NotificationCompat.Builder(ctx, КАНАЛ)
            .setContentTitle(заголовок)
            .setContentText(текст)
            .setStyle(NotificationCompat.BigTextStyle().bigText(текст))
            .setSmallIcon(R.mipmap.ic_launcher)
            /* CATEGORY_ALARM — то, чем «не беспокоить» отличает будильник от почты: в режиме DND
               системные исключения для будильников пропускают именно эту категорию. */
            .setCategory(NotificationCompat.CATEGORY_ALARM)
            .setPriority(NotificationCompat.PRIORITY_MAX)
            .setDefaults(NotificationCompat.DEFAULT_ALL)
            /* Полноэкранное намерение: на заблокированном экране система показывает тревогу поверх, а не
               строкой в шторке, которую утром смахнут вместе с почтой. */
            .setFullScreenIntent(открыть, true)
            .setContentIntent(открыть)
            .setAutoCancel(true)
            .build()
        runCatching { nm.notify(id, n) }
            .onFailure { Log.w(TAG, "не удалось показать тревогу: $it") }
    }

    /**
     * Отдельный канал, и это не формальность (#418).
     *
     * У постоянной строки мониторинга важность LOW — она не должна звенеть. Тревоге нужен свой канал с
     * HIGH, звуком будильника и обходом «не беспокоить»: важность канала на Android 8+ человек может
     * поменять сам, но задать её при создании — наше дело, второй раз канал уже не переписать.
     */
    fun каналТревог(nm: NotificationManager) = канал(nm)

    private fun канал(nm: NotificationManager) {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
        if (nm.getNotificationChannel(КАНАЛ) != null) return
        val звук: Uri = android.media.RingtoneManager.getDefaultUri(android.media.RingtoneManager.TYPE_ALARM)
            ?: android.media.RingtoneManager.getDefaultUri(android.media.RingtoneManager.TYPE_NOTIFICATION)
        nm.createNotificationChannel(
            NotificationChannel(КАНАЛ, "Тревоги", NotificationManager.IMPORTANCE_HIGH).apply {
                description = "Низкий сахар и другие поводы разбудить"
                enableVibration(true)
                setBypassDnd(true)
                lockscreenVisibility = Notification.VISIBILITY_PUBLIC
                setSound(
                    звук,
                    AudioAttributes.Builder()
                        .setUsage(AudioAttributes.USAGE_ALARM)
                        .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                        .build(),
                )
            },
        )
    }
