package ru.imiron.sugarlife

/**
 * ЧТО ВЫРЕЗАЕМ ИЗ ЖУРНАЛА ПЕРЕД ОТПРАВКОЙ (SugarLife#656).
 *
 * Журнал человек отправляет в мессенджер, и обратной дороги у него нет. Значит вопрос не «что
 * туда полезного положить», а «чего там быть не должно».
 *
 * ЧТО НАШЛОСЬ НА ЖИВОМ ТЕЛЕФОНЕ 2 сентября 2026, в журнале за сутки:
 *
 * - **147 записей с адресом облака** владельца — в поле `id` каждого потока: `ns:<хост>-cgm`;
 * - **30 записей с полным адресом запроса** — `https://<хост>/api/v1/entries.json?count=288`
 *   внутри текста системной ошибки.
 *
 * Вычистка в ядре есть, но она по ИМЕНИ ПОЛЯ: `token`, `secret`, `password`, `mac`. Адрес лежит в
 * поле `id`, а запрос — внутри свободного текста `err`, и оба проходят мимо. Токен сегодня не
 * попался, но попадётся: адрес Nightscout носят с `?token=…`, и такой запрос в тексте ошибки
 * окажется целиком.
 *
 * Адрес облака — это не «просто хост». Nightscout часто открыт на чтение, и по адресу человека
 * находят его сахар за годы.
 *
 * ЧТО СОХРАНЯЕМ. Хвост потока (`-cgm`, `-pump`, `-treat`) и путь запроса: по ним видно, КАКОЙ канал
 * молчит и КУДА мы стучались, а это половина разбора. Убираем ровно адрес и строку запроса —
 * последняя и есть место, где живут токены.
 *
 * ПРАВИЛО ОДНО, ИСПОЛНЕНИЙ ДВА (здесь и `ios/App/App/ВычисткаЖурнала.swift`) — потому что файл
 * собирает оболочка, у каждой свой. Настоящее место этому правилу — в ядре, рядом с `Redactor`:
 * тогда исполнение будет одно на обе. Написано им в #656.
 */
object ВычисткаЖурнала {

    const val ОБЛАКО = "<облако>"

    /* Адрес потока: `ns:<хост>-<поток>`. Хвост оставляем — он отвечает, какой канал молчит.
       Хост узнаём по точке в нём; поток — кусок без точек в самом конце. */
    private val ИДЕНТИФИКАТОР = Regex("""ns:([^"\s,}]*\.[^"\s,}]*?)-([a-z]+)(?![\w.-])""")

    /* И ГОЛЫЙ АДРЕС ОБЛАКА, БЕЗ ХВОСТА ПОТОКА.

       Найдено прогоном правила по настоящему журналу: после первой замены адрес оставался ещё в
       49 записях — там, где облако названо целиком, без потока: `{"id":"ns:<хост>","streams":3}` и
       `{"cloud":"ns:<хост>"}`. Одна форма была на виду, вторая нет; выдуманный образец второй бы не
       показал. Требуем точку в адресе — тогда уже вычищенное `ns:<облако>-cgm` под правило не
       попадает. */
    private val ГОЛЫЙ_АДРЕС = Regex("""ns:[A-Za-z0-9._-]*\.[A-Za-z0-9._-]*""")

    /* Запрос целиком: схема, хост, путь, строка запроса. Оставляем путь, убираем хост и всё после
       вопросительного знака — там живут токены. */
    private val ЗАПРОС = Regex("""https?://([^/\s"'\\]+)([^\s"'\\]*)""")

    fun вычистить(журнал: String): String =
        ИДЕНТИФИКАТОР.replace(журнал) { "ns:$ОБЛАКО-${it.groupValues[2]}" }
            .let { ГОЛЫЙ_АДРЕС.replace(it, "ns:$ОБЛАКО") }
            .let { ЗАПРОС.replace(it) { м -> "https://$ОБЛАКО" + м.groupValues[2].substringBefore('?') } }
}
