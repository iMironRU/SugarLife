package ru.imiron.sugarlife

import android.content.Context
import android.os.Handler
import android.os.Looper
import android.util.Log
import java.util.UUID

/**
 * ПАССИВНЫЙ НАБЛЮДАТЕЛЬ МОСТА ПОМПЫ — опыт, а не возможность (SugarLifeCore#124).
 *
 * ПОЧЕМУ ОТДЕЛЬНО ОТ ДРАЙВЕРА. Сенсор — вещатель: он сам шлёт кадры, и подписаться на них могут все.
 * Мост к помпе устроен иначе — это радиомодем: ему отправляют команду («настройся на частоту, передай
 * пакет, жди ответ»), он относит её помпе и приносит ответ. Два приложения рядом означают два потока
 * команд в один модем, с перепутанными ответами и сбитыми таймингами, а протокол помпы ещё и с
 * состоянием: последовательность пробуждения, сессия. Похоже, отсюда же и застарелая задача #77 —
 * «после чтения связь с мостом рвётся кодом 8».
 *
 * И ЛОВУШКА В СОБСТВЕННЫХ СЛОВАХ, которую стоит назвать вслух: наш read-only означает «не меняем
 * настройки помпы». Но чтобы ПРОЧИТАТЬ историю, мы передаём — команду мосту и пакет помпе. По радио
 * мы такой же говорящий, как AndroidAPS, и «мы только читаем» тут не оправдание.
 *
 * ЧТО ДЕЛАЕТ ЭТОТ КОД. Подключается к мосту, подписывается на его уведомления и НЕ ОТПРАВЛЯЕТ НИ
 * ОДНОГО БАЙТА. Всё, что мост приносит от помпы по запросам соседней программы, попадает в журнал.
 * Помешать мы не можем не «аккуратно», а физически: не передаём — значит не мешаем. Такие гарантии
 * дороже любых договорённостей.
 *
 * ХУДШИЙ ИСХОД ОПЫТА — пустой журнал: значит уведомления моста до второго подписчика не доходят, и мы
 * узнаем это за пять минут, ничем не рискуя.
 *
 * Кода здесь ровно столько, чтобы поставить опыт. Появится режим «пассивный наблюдатель помпы» —
 * он будет жить в драйвере и в ядре, а этот файл уйдёт.
 */
object ПодслушатьМост {
    private const val TAG = "SugarLifeПодслушать"

    /* Те же характеристики, что у рабочего моста: данные и ответы RileyLink-совместимого модема. */
    private val RL_DATA = UUID.fromString("C842E849-5028-42E2-867C-016ADADA9155")
    private val RL_RESP = UUID.fromString("6E6C7910-B89E-43A5-A0FE-50C5E2B81F4A")

    private var link: BleLink? = null
    private var кадров = 0
    private val руки = Handler(Looper.getMainLooper())

    /**
     * Слушать мост [адрес] в течение [минут], не отправляя ничего.
     *
     * @return строка для журнала опыта: сколько кадров пришло и с чего начали.
     */
    fun начать(ctx: Context, адрес: String, минут: Int = 30): String {
        стоп()
        кадров = 0
        val л = BleLink(
            ctx.applicationContext,
            адрес,
            // Подписываемся на ОБЕ: какая из них несёт ответы помпе-соседу, мы как раз и выясняем.
            notifyChars = setOf(RL_DATA, RL_RESP),
            медленноеПодключение = true,
        )
        л.onState = { состояние -> Log.i(TAG, "мост: $состояние") }
        л.subscribe(RL_DATA) { байты -> записать("DATA", байты) }
        л.subscribe(RL_RESP) { байты -> записать("RESP", байты) }
        link = л
        л.connect()
        руки.postDelayed({ стоп() }, минут * 60_000L)
        Log.i(TAG, "начали слушать $адрес на $минут мин — в мост не пишем ни байта")
        return "слушаем $адрес, $минут мин, запись выключена"
    }

    /** Сколько кадров поймали к этому моменту — чтобы не листать журнал руками. */
    fun сколько(): Int = кадров

    fun стоп() {
        руки.removeCallbacksAndMessages(null)
        link?.let { л -> runCatching { л.disconnect() }.onFailure { e -> Log.w(TAG, "не закрылось: $e") } }
        link = null
        Log.i(TAG, "перестали слушать, всего кадров: $кадров")
    }

    private fun записать(откуда: String, байты: ByteArray) {
        кадров++
        /* Кадр целиком и в шестнадцатеричном виде: разбирать его будет наш же декодер помпы, и
           додумывать за него содержимое здесь нельзя — опыт затем и ставится, чтобы узнать, сколько
           понятно БЕЗ знания вопроса, на который это ответ. */
        Log.i(TAG, "кадр #$кадров $откуда len=${байты.size} hex=${байты.joinToString("") { "%02x".format(it) }}")
    }
}
