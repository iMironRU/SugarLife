package ru.imiron.sugarlife

import android.app.AlarmManager
import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.content.ComponentName
import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.util.Log

/**
 * ПОДНЯТЬСЯ ПОСЛЕ СМЕРТИ (SugarLifeCore#227).
 *
 * Мы три дня учились жить дольше — и научились: сутки с лишним на POCO, девятнадцать часов на
 * Хуавее. Но конец у всех вариантов был одинаковый, потому что поднять нас после смерти было НЕЧЕМ.
 * Службу во всём приложении умели стартовать ровно двое: приёмник загрузки (то есть перезагрузка
 * телефона) и человек, открывший приложение. Хуавей после этого простоял тёмным три с половиной
 * часа, POCO — двенадцать, и оба раза единственным лекарством были руки владельца.
 *
 * ПОЧЕМУ НАШ БУДИЛЬНИК ПАУЗЫ НЕ ГОДИЛСЯ. [AlarmWakeups] регистрирует приёмник В ПАМЯТИ ПРОЦЕССА, а
 * отмена корутины ещё и снимает сам будильник. Умер процесс — исчез приёмник, и вручить ему
 * пробуждение стало некому. Это примитив сна, а не воскрешения, и `dumpsys alarm` на телефоне
 * владельца честно показывал ноль отложенных будильников через одиннадцать часов темноты.
 *
 * Поднять мёртвый процесс умеет только приёмник, ОБЪЯВЛЕННЫЙ В МАНИФЕСТЕ: система создаёт его сама,
 * чтобы вручить широковещательное сообщение. Отсюда [ВоскрешениеПриёмник].
 *
 * ПОЧЕМУ БУДИЛЬНИК ИМЕННО ТОЧНЫЙ, ХОТЯ ТОЧНОСТЬ НАМ НЕ НУЖНА. С Android 12 поднять службу переднего
 * плана из фона запрещено — кроме нескольких исключений. Одно из них: приложение, исполняющее
 * ТОЧНЫЙ будильник, система на минуту кладёт во временный список освобождённых, и оттуда служба
 * стартует. Неточный будильник такого списка не даёт: он разбудит наш приёмник, приёмник позовёт
 * службу, и система откажет. То есть точность здесь — не про минуты, а про само право подняться;
 * опоздание на девять минут мы бы пережили, отказ — нет.
 *
 * Поэтому решение о точности здесь СВОЁ, а не то, что в [Точность]. Там выключатель человека, и он
 * про его сон: будить ли по тревоге минута в минуту ценой предупреждения о батарее. Здесь никого не
 * будят — здесь проверяют, живы ли мы, — и спрашивать об этом человека не о чем.
 *
 * И ГЛАВНОЕ — БЕЗ ЕДИНОГО ВОПРОСА НА ЭКРАНЕ. Владелец потребовал «без запроса батарейки», и это не
 * каприз: исключение из экономии заряда — тот самый экран с предупреждением, на который человек
 * должен ткнуть, не понимая цены. `USE_EXACT_ALARM` выдаётся при установке молча, диалога не
 * существует. Оно предназначено будильникам и календарям, и правила магазина его сузили бы — но мы
 * в магазин не публикуемся, APK ставится кабелем, так что запрет нас не касается.
 *
 * ЧЕГО ЭТО НЕ ДЕЛАЕТ. Оно не мешает нас убить и не спорит с PowerGenie. Смерть остаётся, просто
 * после неё темнота длится не двенадцать часов, а [ЧЕРЕЗ_МС].
 *
 * И ОДНОГО БУДИЛЬНИКА МАЛО — ЭТО ЗАМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО. На EMUI нас убивают не как процесс, а
 * через `forceStopPackage`: `Force stopping ru.imiron.sugarlife.pro … iAwareF[PowerGenie]`. Android
 * при остановке пакета СНИМАЕТ ВСЕ ЕГО БУДИЛЬНИКИ и держит пакет в состоянии `stopped`, куда
 * широковещательные сообщения не доставляются вовсе. Проверено командой `am force-stop`: наших
 * будильников после неё ноль. То есть убийца стирает ровно тот механизм, который должен был пережить
 * убийство.
 *
 * Отсюда второй звонящий — [проверить] из виджета. Его будильник принадлежит системе, и остановка
 * пакета до него не дотягивается.
 */
object Воскрешение {

    /**
     * Через сколько проверять, живы ли мы.
     *
     * Это верхняя граница темноты: столько человек проживёт без наблюдения, если нас убили сразу
     * после проверки. Четверть часа выбрана по цене вопроса — одно пробуждение в пятнадцать минут
     * заряд не ест, а сенсор всё равно отдаёт показание раз в пять минут, и терять больше трёх
     * подряд незачем.
     */
    const val ЧЕРЕЗ_МС = 15 * 60_000L

    /**
     * Ставить ли будильник воскрешения.
     *
     * Выключил наблюдение человек — значит выключил, и воскрешать нечего: это было бы включением
     * того, от чего отказались. То же правило, что у приёмника загрузки.
     */
    fun ставитьЛи(мониторингВключён: Boolean): Boolean = мониторингВключён

    /**
     * Поднимать ли службу прямо сейчас.
     *
     * Живую службу трогать нельзя: `startForegroundService` по живой службе — это лишний
     * `onStartCommand`, а на телефоне владельца каждый такой заход стоил переподключения прибора.
     */
    fun поднимать(мониторингВключён: Boolean, службаЖива: Boolean): Boolean =
        мониторингВключён && !службаЖива

    /**
     * ЕСТЬ ЛИ ВИДЖЕТ НА ЭКРАНЕ (SugarLifeCore#227).
     *
     * Спрашивать можно и нужно: ответ точный, мгновенный и без разрешений — система хранит список
     * размещённых экземпляров, а не догадки о них.
     *
     * И это не любопытство. На EMUI виджет — ЕДИНСТВЕННЫЙ путь назад после `forceStopPackage`, то
     * есть его отсутствие меняет не удобство, а то, что мы вправе обещать человеку на ночь. Значит
     * знать это обязаны и мы, и движок: обещание, выданное без такого знания, ничего не стоит — ровно
     * та же причина, по которой заведена [Доставка].
     */
    @JvmStatic
    fun виджетЕсть(ctx: Context): Boolean = runCatching {
        val мм = AppWidgetManager.getInstance(ctx.applicationContext) ?: return false
        мм.getAppWidgetIds(ComponentName(ctx.applicationContext, SugarWidget::class.java)).isNotEmpty()
    }.getOrDefault(false)

    private const val TAG = "SugarLifeВоскрешение"
    private const val ДЕЙСТВИЕ = "ru.imiron.sugarlife.ВОСКРЕСНУТЬ"
    private const val КОД = 7227

    private fun намерение(ctx: Context): PendingIntent = PendingIntent.getBroadcast(
        ctx.applicationContext, КОД, Intent(ДЕЙСТВИЕ).setPackage(ctx.packageName),
        PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
    )

    /**
     * Взвести на следующую проверку. Зовётся при каждом старте службы и из самого приёмника.
     *
     * ПЕРЕВЗВОДИМ ПО ОДНОМУ, А НЕ СТАВИМ ПОВТОРЯЮЩИЙСЯ. Повторяющийся будильник система в Doze
     * растягивает молча и на своё усмотрение, и точным он не бывает вовсе. Одиночный, поставленный
     * заново на каждом срабатывании, даёт нам запись о каждом пробуждении — а по ней видно, дожили
     * мы до следующего или нет.
     */
    @JvmStatic
    fun взвести(ctx: Context) {
        val app = ctx.applicationContext
        if (!ставитьЛи(SugarLifeService.былВключён(app))) { снять(app); return }
        val am = app.getSystemService(Context.ALARM_SERVICE) as? AlarmManager ?: return
        val когда = System.currentTimeMillis() + ЧЕРЕЗ_МС
        val точно = Точность.разрешеноСистемой(app)
        runCatching {
            if (точно) am.setExactAndAllowWhileIdle(AlarmManager.RTC_WAKEUP, когда, намерение(app))
            else am.setAndAllowWhileIdle(AlarmManager.RTC_WAKEUP, когда, намерение(app))
        }.onFailure { Log.w(TAG, "будильник воскрешения не поставился: $it") }
            /* Пишем ТОЧНО/НЕТОЧНО не для красоты: неточный означает, что подняться из фона нам не
               дадут, и в журнале это должно быть видно ДО того, как мы умрём, а не после. */
            .onSuccess { Log.i(TAG, "проверка жизни через ${ЧЕРЕЗ_МС / 60_000} мин, будильник ${if (точно) "точный" else "НЕТОЧНЫЙ — подняться из фона не дадут"}") }
    }

    /**
     * ПРОВЕРИТЬ И ПОДНЯТЬ. Общее тело для всех, кто может нас разбудить.
     *
     * Звонящих двое, и второй появился по замеру. Будильник — наш собственный, и его убийца стирает
     * (см. ниже). Виджет — чужой: обновление ему шлёт система, будильник на это принадлежит ей же, и
     * остановка нашего пакета его не трогает.
     *
     * ЗАМЕРЕНО НА ХУАВЕЕ 09.09, ради этого всё и переписано:
     *
     * ```
     * 20:54:09  am force-stop           → stopped=true, наших будильников 0
     * 21:30:15  AlarmManager: WAKEUP alarm trigger APPWIDGET_UPDATE, package name is: android
     *           Start proc 27299 for broadcast {…/SugarWidget}
     *           PG_ash: ru.imiron.sugarlife.pro pop from SHDA
     *           PG_ash: has widget app: ru.imiron.sugarlife.pro
     * ```
     *
     * То есть виджет поднял процесс из состояния `stopped`, куда нас загнал `forceStopPackage`, и
     * PowerGenie сам вынул нас из своего списка — потому что у приложения есть виджет. Процесс при
     * этом поднялся, а служба нет: виджет рисовал себя и уходил. Тридцать шесть минут темноты вместо
     * семи часов, и это единственный найденный путь, переживающий остановку пакета.
     *
     * @param откуда только для журнала — по нему видно, каким из двух путей мы вернулись.
     */
    @JvmStatic
    fun проверить(ctx: Context, откуда: String) {
        val app = ctx.applicationContext
        /* Взводим СРАЗУ, до всего остального: если подъём службы упадёт, следующая попытка всё равно
           обязана состояться. Цепочка, рвущаяся на первой неудаче, — это не воскрешение. */
        взвести(app)

        val включён = SugarLifeService.былВключён(app)
        if (!поднимать(включён, SugarLifeService.живаЛи())) {
            if (включён) Log.i(TAG, "$откуда: служба жива")
            return
        }

        /*
         * ЗДЕСЬ МЫ НЕ ОБЕЩАЕМ, А ПРОБУЕМ И ДОКЛАДЫВАЕМ.
         *
         * Отказ системы приходит исключением `ForegroundServiceStartNotAllowedException`, и без этой
         * записи он неотличим от успеха — а молчание мы уже принимали за успех дважды и оба раза
         * ошибались. Что именно скажет прошивка, выяснит телефон, а не рассуждение.
         */
        runCatching { SugarLifeService.start(app) }
            .onSuccess { Log.i(TAG, "$откуда: служба была мертва — подняли") }
            .onFailure { Log.w(TAG, "$откуда: подняться не дали: $it") }
    }

    @JvmStatic
    fun снять(ctx: Context) {
        val am = ctx.applicationContext.getSystemService(Context.ALARM_SERVICE) as? AlarmManager ?: return
        runCatching { am.cancel(намерение(ctx)) }
    }
}

/** Приёмник из МАНИФЕСТА — см. [Воскрешение]: только такой умеет поднять мёртвый процесс. */
class ВоскрешениеПриёмник : BroadcastReceiver() {
    override fun onReceive(context: Context, intent: Intent) = Воскрешение.проверить(context, "будильник")
}
