package ru.imiron.sugarlife

/**
 * ЧТО ВИДЖЕТ ВПРАВЕ УТВЕРЖДАТЬ, КОГДА ПОКАЗАНИЕ СТАРЕЕТ (SugarLife#694).
 *
 * Правило вынесено из виджета сюда по одной причине: в виджете его нельзя проверить. Отрисовка
 * живёт в чужом процессе (лаунчер), возраст там считает `Chronometer`, и увидеть беду можно было
 * только глазами на рабочем столе — что и произошло: владелец увидел «Данных нет · 22 ч 48 мин» в
 * час, когда показания шли раз в минуту.
 *
 * Ложь была не в числе — с метки действительно прошло двадцать два часа, — а в СЛОВЕ рядом с ним.
 * Виджет утверждал, что данных нет, хотя узнать о возвращении данных ему неоткуда: сам себя он
 * перерисовывает не чаще раза в полчаса, а приложение к тому часу система убила.
 *
 * Отсюда три стадии, и граница между второй и третьей — про НАС, а не про сахар:
 *
 * - [Стадия.СВЕЖЕЕ] — число показываем как есть;
 * - [Стадия.УСТАРЕЛО] (15 минут) — числу больше не верим. Порог медицинский и общий на все
 *   поверхности: живой баннер айфона, виджеты обоих телефонов, дыра в линии графика. Одно молчание
 *   не может называться на двух телефонах разными сроками;
 * - [Стадия.СЛЕПО] (час) — не верим и себе. Просить перерисовку мы вправе раз в пять минут; если
 *   за час не прошла ни одна просьба, то виджет не «видит, что данных нет» — он просто давно не
 *   перерисовывался. Единственное честное слово тут «неизвестно», и никаких секундомеров: они идут
 *   сами и растут без предела.
 *
 * Час — не медицинский порог: числа к этой минуте на экране уже нет. Это срок нашего собственного
 * знания, и потому он живёт здесь, а не берётся у ядра.
 */
enum class Стадия { СВЕЖЕЕ, УСТАРЕЛО, СЛЕПО }

object ВозрастПоказания {

    /** Через сколько числу перестают верить. Тот же порог, что у живого баннера на айфоне. */
    const val УСТАРЕЛО_МС = 15 * 60 * 1000L

    /** Через сколько виджет перестаёт верить себе: см. шапку. */
    const val СЛЕПОТА_МС = 60 * 60 * 1000L

    /**
     * Возраст → что мы вправе сказать.
     *
     * Отрицательный возраст (часы телефона перевели назад, запись «из будущего») считаем свежестью:
     * гасить показание из-за чужой ошибки во времени — второе враньё поверх первого, а перевод
     * часов пройдёт сам.
     */
    fun стадия(возрастМс: Long): Стадия = when {
        возрастМс > СЛЕПОТА_МС -> Стадия.СЛЕПО
        возрастМс > УСТАРЕЛО_МС -> Стадия.УСТАРЕЛО
        else -> Стадия.СВЕЖЕЕ
    }

    /**
     * Когда виджету снова будет что сказать — на эту минуту и заводится будильник.
     *
     * `null` — сказать больше нечего: дальше «неизвестно» остаётся правдой сколько угодно долго, и
     * будить себя незачем. Это важнее, чем кажется: будильник, заведённый «на всякий случай»,
     * будит телефон впустую всю ночь.
     */
    fun следующийРубеж(когдаМс: Long, стадия: Стадия): Long? = when (стадия) {
        Стадия.СВЕЖЕЕ -> когдаМс + УСТАРЕЛО_МС
        Стадия.УСТАРЕЛО -> когдаМс + СЛЕПОТА_МС
        Стадия.СЛЕПО -> null
    }
}
