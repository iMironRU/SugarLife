package ru.imiron.sugarlife

/**
 * ОЧЕРЕДЬ «ПОНЯЛ» — чистая половина (SugarLife#482).
 *
 * Человек жмёт «Понял» в уведомлении в три часа ночи. Уведомление переживает смерть процесса, а движок —
 * нет: его к этому моменту может не быть в памяти вовсе. Если нажатие не доедет, эскалация продолжится
 * ПОСЛЕ того, как человек ответил, — то есть кнопка соврёт, а это хуже, чем её отсутствие.
 *
 * Поэтому нажатие сначала записывается, а потом отдаётся. Не наоборот.
 *
 * ЗДЕСЬ НЕТ ANDROID. Хранение и отправку делает [Понял]; сюда вынесено то, что можно проверить тестом:
 * что запись переживает разбор-сборку, что повтор не задваивается и что просроченное выбрасывается.
 *
 * СУТКИ ЖИЗНИ. «Понял», не доехавший за сутки, выбрасываем. Он отвечает на тревогу, которая давно
 * кончилась; доставленный через неделю, он погасил бы не ту — а гасить чужую тревогу опаснее, чем
 * потерять ответ на позавчерашнюю.
 *
 * ПОВТОР БЕЗОПАСЕН. Ключ — `alarmId` движка, интент идемпотентен по нему (rev 1.29). Значит доставить
 * дважды не страшно, а вот потерять — страшно: поэтому запись убираем только после «принято».
 */
object ОчередьПонял {
    /** Сутки. Дольше держать нечего: тревога кончилась, а ответ на неё — нет. */
    const val ЖИВЁТ_МС = 24L * 60 * 60 * 1000

    data class Запись(val id: String, val нажатоМс: Long)

    /* Формат нарочно свой и простой: строка на запись, `id<таб>время`. JSON здесь потребовал бы org.json,
       которого в обычном JVM-тесте нет, — и проверять пришлось бы на телефоне то, что проверяется за
       миллисекунду. Идентификаторы с табом или переводом строки в очередь не берём: такой id мы всё равно
       не смогли бы отдать обратно неизменным, а молча покалеченный ключ хуже потерянного. */
    private const val РАЗДЕЛИТЕЛЬ = '\t'

    fun годныйId(id: String): Boolean =
        id.isNotBlank() && !id.contains(РАЗДЕЛИТЕЛЬ) && !id.contains('\n') && !id.contains('\r')

    fun разобрать(хранимое: String?): List<Запись> =
        (хранимое ?: "").lineSequence()
            .mapNotNull { строка ->
                val части = строка.split(РАЗДЕЛИТЕЛЬ)
                val id = части.getOrNull(0)?.trim().orEmpty()
                val мс = части.getOrNull(1)?.trim()?.toLongOrNull()
                if (id.isBlank() || мс == null) null else Запись(id, мс)
            }
            .toList()

    fun собрать(записи: List<Запись>): String =
        записи.joinToString("\n") { "${it.id}$РАЗДЕЛИТЕЛЬ${it.нажатоМс}" }

    /**
     * Добавить нажатие. Повторное нажатие по той же тревоге НЕ задваивает запись и не двигает время:
     * человек ответил один раз, и отвечать заново его никто не просил — он просто нажал ещё раз, потому
     * что уведомление не исчезло мгновенно.
     */
    fun добавить(хранимое: String?, id: String, сейчасМс: Long): String {
        if (!годныйId(id)) return хранимое ?: ""
        val было = живые(хранимое, сейчасМс)
        if (было.any { it.id == id }) return собрать(было)
        return собрать(было + Запись(id, сейчасМс))
    }

    /* Что ещё имеет смысл доставлять. Просроченное отсеиваем здесь, а не при добавлении: телефон может
       пролежать выключенным, и решать судьбу записи надо в момент доставки.

       Запись «из будущего» оставляем. Часы на телефоне ходят назад — сеть поправила время, человек сменил
       пояс, — и выбросить по этому признаку значило бы потерять свежий ответ ровно из-за того, что
       телефону подсказали точное время. */
    fun живые(хранимое: String?, сейчасМс: Long): List<Запись> =
        разобрать(хранимое).filter { сейчасМс - it.нажатоМс <= ЖИВЁТ_МС }

    /** Убрать доставленное. Только после «принято» — иначе потеряем ответ по дороге. */
    fun убрать(хранимое: String?, id: String): String =
        собрать(разобрать(хранимое).filterNot { it.id == id })
}
