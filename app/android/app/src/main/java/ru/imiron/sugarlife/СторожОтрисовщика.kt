package ru.imiron.sugarlife

import android.app.Activity
import android.os.Build
import android.util.Log
import android.webkit.RenderProcessGoneDetail
import android.webkit.WebView
import com.getcapacitor.Bridge
import com.getcapacitor.BridgeWebViewClient

/**
 * СЕРЫЙ ЭКРАН ПРИ ВОЗВРАТЕ ИЗ ФОНА (SugarLifeCore#210, находка владельца).
 *
 * Владелец описал это тремя наблюдениями подряд: вернулся из фона — серый экран; следом система
 * предложила снять приложение; после перезапуска сенсор не подключался. Это не три беды, а одна
 * цепочка, и начинается она здесь.
 *
 * ЧТО ПРОИСХОДИТ. Отрисовщик WebView живёт в ОТДЕЛЬНОМ процессе (`webview:sandboxed_process0`) — на
 * телефоне владельца он занимал 239 МБ. Под нехваткой памяти система убивает именно такие процессы:
 * большие и не на переднем плане. На том же телефоне замерено 6,6 ГБ из 7,8 занято и 1,4 ГБ в свопе
 * — то есть повод у неё был.
 *
 * Наш процесс при этом жив: движок в журнале шёл минута в минуту до самого конца. Мёртв только
 * отрисовщик, и человек видит пустоту.
 *
 * ПОЧЕМУ ДАЛЬШЕ УБИВАЛИ НАС. `onRenderProcessGone` без обработчика возвращает `false`, а это
 * задокументированная просьба к системе прибить приложение. Мы его не переопределяли вовсе:
 * `MainActivity` был голым `BridgeActivity`. То есть смерть чужого процесса мы своими руками
 * превращали в смерть своего — и теряли вместе с ней наблюдение за сахаром.
 *
 * ЧТО ДЕЛАЕМ ТЕПЕРЬ. Отвечаем `true` («мы справились сами») и поднимаем экран заново. Если
 * приложение в этот момент не на виду — не дёргаем его в фоне, а помечаем и пересоздаём при
 * следующем возвращении: пересборка невидимого экрана стоит памяти ровно там, где её и не хватает.
 *
 * И ГЛАВНОЕ — ПИШЕМ В ЖУРНАЛ. До сих пор про это событие не знал никто: движковый журнал полон, а
 * про поверхность в нём не было ни строки, и разбирать серый экран приходилось по обстановке.
 * Теперь оно называется своим именем.
 *
 * Наследуемся от `BridgeWebViewClient`, а не подменяем его: у Capacitor в нём своя обработка ссылок
 * и схем, и потерять её ради одного метода было бы дорогим разменом.
 */
class СторожОтрисовщика(
    bridge: Bridge,
    private val активность: Activity,
    private val наВиду: () -> Boolean,
) : BridgeWebViewClient(bridge) {

    /** Отрисовщик умер, пока нас не было видно: поднимем экран, когда человек вернётся. */
    @Volatile private var ждём: Boolean = false

    /** Функцией, а не свойством: из Java геттер кириллического свойства не позвать. */
    fun нуженПодъём(): Boolean = ждём

    override fun onRenderProcessGone(view: WebView?, detail: RenderProcessGoneDetail?): Boolean {
        val самУпал = Build.VERSION.SDK_INT >= Build.VERSION_CODES.O && detail?.didCrash() == true
        /* «Сам упал» и «система убила по памяти» — разные беды, и лечатся они по-разному: первое наша
           ошибка, второе обстановка на телефоне. Различие бесплатное, а без него в журнале была бы
           одна строка на два разных случая. */
        bleLog(
            "Warn", "отрисовщик экрана умер", null,
            "причина" to if (самУпал) "сам упал" else "система убила по памяти",
            "наВиду" to наВиду().toString(),
        )
        Log.w("SugarLife", "webview renderer gone: crash=$самУпал")

        runCatching { (view?.parent as? android.view.ViewGroup)?.removeView(view) }
        runCatching { view?.destroy() }

        if (наВиду()) поднятьЭкран() else ждём = true
        /* `true` — «беду мы обработали, приложение убивать не нужно». Ровно эта строка и разрывает
           цепочку: чужой процесс умер, наш остаётся жив, наблюдение продолжается. */
        return true
    }

    /** Пересобрать экран. Зовётся из [onRenderProcessGone] и при возвращении, если ждали. */
    fun поднятьЭкран() {
        ждём = false
        bleLog("Info", "поднимаем экран заново", null)
        runCatching { активность.recreate() }
            .onFailure { bleLog("Warn", "экран не пересобрался: $it", null) }
    }
}
