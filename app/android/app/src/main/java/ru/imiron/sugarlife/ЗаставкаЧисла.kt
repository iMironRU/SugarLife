package ru.imiron.sugarlife

import android.content.Context

/**
 * ЧТО ПОКАЗАТЬ, ПОКА СТРАНИЦА ПОДНИМАЕТСЯ (SugarLifeCore#232).
 *
 * Человек открыл приложение с одним вопросом: какой у меня сахар. Ответ у нас есть — он лежит в
 * уведомлении и в значке строки состояния, — а на экране в эти секунды мы показывали ожидание.
 *
 * HTML-заставка тут не помощник по построению: она сама живёт в том WebView, которого в этот момент
 * нет. Значит рисовать должна система.
 *
 * ЧИСЛО ХРАНИМ, ПОТОМУ ЧТО ЗАСТАВКА НУЖНА РАНЬШЕ ДАННЫХ. В службе оно живёт в памяти и умирает
 * вместе с процессом — а заставка нужна ровно тогда, когда процесс только поднялся.
 *
 * ВОЗРАСТ ОБЯЗАТЕЛЕН. Число без возраста в момент, когда мы заведомо не на связи, — та самая ложь,
 * которую мы вычищаем третий день. То же с сырым: сырое называем сырым (эпик #135).
 */
object ЗаставкаЧисла {

    private const val PREFS = "sugarlife-заставка"
    private const val ЧИСЛО = "ммоль"
    private const val КОГДА = "когда"
    private const val СЫРОЕ = "сырое"

    /** Дальше этого срока число не показываем: старое на весь экран человек прочтёт как текущее. */
    const val ПРЕДЕЛ_ВОЗРАСТА_МС = 6 * 60 * 60_000L

    /**
     * ГОЛОС У ЗАСТАВКИ (SugarLifeCore#232).
     *
     * Без записи в журнал «заставки не было» неотличимо от «была и снялась так быстро, что человек не
     * заметил». Первое надо чинить, второе — успех, и путать их нельзя. На это я уже наступил, ловя
     * заставку снимками экрана: шесть кадров подряд и ни одного доказательства.
     *
     * Функцией, а не свойством: `bleLog` внутренний и с vararg, из Java его не позвать.
     */
    @JvmStatic
    fun сказать(что: String) = bleLog("Debug", что, null)

    fun запомнить(ctx: Context, ммоль: Double, когдаМс: Long, сырое: Boolean) {
        ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit()
            .putFloat(ЧИСЛО, ммоль.toFloat())
            .putLong(КОГДА, когдаМс)
            .putBoolean(СЫРОЕ, сырое)
            .apply()
    }

    /**
     * Строки заставки: число и подпись под ним. `null` — показывать нечего, и заставки не будет.
     *
     * Пусто бывает честно: свежая установка, выключенный мониторинг, сутки без данных. Тогда пустой
     * экран — правда, а выдуманное число было бы ложью.
     */
    fun слова(ctx: Context, сейчасМс: Long = System.currentTimeMillis()): Pair<String, String>? {
        val п = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        val ммоль = п.getFloat(ЧИСЛО, 0f).takeIf { it > 0f } ?: return null
        val когда = п.getLong(КОГДА, 0L).takeIf { it > 0L } ?: return null
        val возраст = сейчасМс - когда
        if (возраст < 0 || возраст > ПРЕДЕЛ_ВОЗРАСТА_МС) return null
        val число = "%.1f".format(ммоль).replace('.', ',')
        val сырое = if (п.getBoolean(СЫРОЕ, false)) " · сырое" else ""
        return число to "${возрастСловами(возраст)}$сырое"
    }

    /**
     * Возраст словами. Минуты до часа, дальше часы: «117 мин назад» человек делит в уме, а нам от
     * него нужно одно — понять, свежее это или нет.
     */
    fun возрастСловами(мс: Long): String {
        val минут = мс / 60_000L
        return when {
            минут < 1 -> "только что"
            минут < 60 -> "$минут ${склонение(минут, "минуту", "минуты", "минут")} назад"
            else -> (минут / 60).let { ч -> "$ч ${склонение(ч, "час", "часа", "часов")} назад" }
        }
    }

    private fun склонение(n: Long, одна: String, две: String, много: String): String {
        val д = n % 10
        return when {
            n % 100 in 11..14 -> много
            д == 1L -> одна
            д in 2..4 -> две
            else -> много
        }
    }
}
