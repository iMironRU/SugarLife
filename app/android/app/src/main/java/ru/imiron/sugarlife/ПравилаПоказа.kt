package ru.imiron.sugarlife

/**
 * КАК ПОКАЗЫВАТЬ ТРЕВОГУ ДВИЖКА — чистая половина (SugarLife#482, контракт 1.30).
 *
 * Движок решает, ЧТО случилось и какого оно уровня. Мы решаем, как это звучит и выглядит. Здесь только
 * второе, и без единого вызова Android — чтобы правила показа проверялись тестом, а не ночью.
 *
 * Три ловушки, о которых ядро предупредило отдельно, живут ровно тут:
 *  — `repeat` НЕ новая тревога: то же событие, которому человек не ответил. Новое уведомление вместо
 *    обновления даёт в шторке лесенку;
 *  — `cleared` гасит ТОЛЬКО свой `id`: событий с разными id в одном снимке бывает несколько;
 *  — уровень не выводится из `id`: он приходит полем и растёт при эскалации.
 */
object ПравилаПоказа {

    data class Событие(
        val id: String,
        val what: String,
        val level: String,
        val baseLevel: String,
        val atMs: Long,
        val throughSpeaker: Boolean = false,
        val needsAck: Boolean = false,
        val mmol: Double? = null,
        /** Готовая фраза от ядра (мост ≥ 1.31). Пустая — ядро старое, работает наша табличка. */
        val words: String? = null,
        /* СВЕТОФОР ДОСТАВКИ (мост 1.31…1.35). Решение о звуке принимает движок: у него тот же
           уровень, но с поправками на сон, машину, доставку и ранг среди одновременных событий,
           которых у оболочки нет и быть не может. Мы исполняем. */
        val sound: Boolean = true,
        val loudness: String = "show",
        val soundKind: String = "none",
        val bypassQuiet: Boolean = false,
        val fullScreen: Boolean = false,
        val repeatUntilAck: Boolean = false,
        val distinctLook: Boolean = false,
        val raiseVolumeTo: Int? = null,
        val inCar: Boolean = false,
    )

    /** Как это звучит. Теперь — прочтение приказа движка, а не собственный вывод из уровня. */
    enum class Как { НЕ_ПОКАЗЫВАТЬ, ТИХО, ОБЫЧНО, БУДИТЬ }

    /*
     ИСПОЛНЕНИЕ, А НЕ РЕШЕНИЕ (мост 1.34, #482).

     Здесь стоял свой светофор: уровень → как звучать. Рядом жил такой же у движка, и два решения об
     одном разошлись в первую же ночь — красная тревога прозвучала обычным уведомлением, а человек
     услышал «просто музыку». Владелец сказал прямо: «у семи нянек дитя без глаза».

     Теперь `loudness` приходит готовым: show — показать молча, shout — обычный звук, yell — громкость
     будильника. Уровень остаётся только для наших слов, если движок их не прислал.

     Старое ядро (без поля) по-прежнему обслуживается прежним выводом из уровня: `loudness` придёт
     умолчанием "show", и молчаливая тревога была бы хуже неточно озвученной.
     */
    fun как(с: Событие): Как {
        if (!с.sound) return Как.ТИХО
        return when (с.loudness) {
            "yell" -> Как.БУДИТЬ
            "shout" -> Как.ОБЫЧНО
            "show" -> когдаПриказаНет(с.level)
            else -> Как.ОБЫЧНО
        }
    }

    /** Запас для старого ядра: прежний вывод из уровня. Новое присылает `loudness` и сюда не заходит. */
    private fun когдаПриказаНет(level: String): Как = when (level) {
        "Состояние" -> Как.НЕ_ПОКАЗЫВАТЬ          // видно на экране приложения, звучать нечему
        "Заметка" -> Как.ТИХО                      // копится молча
        "Сегодня" -> Как.ОБЫЧНО                    // обычный звук, тихие часы уважает
        "Разбудить" -> Как.БУДИТЬ
        /* НЕ БУДИМ СИРЕНОЙ О ТОМ, ЧТО НЕ СМОЖЕМ РАЗБУДИТЬ (#482): если разбудить мы не можем, то и
           вой ночью бессмысленен, а днём он пугает на ровном месте. */
        "ОбещаниеНарушено" -> Как.ОБЫЧНО
        else -> Как.ОБЫЧНО
    }

    /** Снять уведомление молча. Только `cleared`; всё остальное — показать. */
    fun этоОтбой(what: String): Boolean = what == "cleared"

    /**
     * Ведёт ли тревоги движок.
     *
     * Два факта, и оба из снимка: мост говорит на 1.30 (значит `alarmEvents` вообще существуют) и правила
     * у движка есть. Одного мало: ревизия без правил означала бы «умеет, но ничего не считает», и наша
     * проверка ушла бы в отставку, не передав никому дежурство.
     *
     * Двоевластия это не создаёт, а снимает: в каждый момент тревоги ведёт ровно один — и решает это
     * факт от движка, а не флаг сборки.
     */
    fun ведётДвижок(ревизия: String?, правил: Int): Boolean {
        if (правил <= 0) return false
        val части = (ревизия ?: "").split(".")
        val старшая = части.getOrNull(0)?.toIntOrNull() ?: return false
        val младшая = части.getOrNull(1)?.toIntOrNull() ?: return false
        return старшая > 1 || (старшая == 1 && младшая >= 30)
    }

    /**
     * Ключ уведомления по `id` тревоги: одна тревога — одно уведомление, повтор обновляет его, а не
     * плодит новое.
     *
     * Смещение — чтобы не столкнуться с нашими собственными номерами (4712…4714): столкновение означало бы,
     * что тревога движка стирает с экрана нашу или наоборот, и заметить это можно только ночью.
     */
    fun ключУведомления(id: String): Int = 5000 + (id.hashCode().rem(1000).let { if (it < 0) -it else it })

    /**
     * КУДА ВЕСТИ ЧЕЛОВЕКА, НАЖАВШЕГО НА ЭТУ ТРЕВОГУ (#524).
     *
     * Знание «о чём было уведомление» есть только здесь, в момент показа: через час, когда человек
     * нажмёт, от тревоги останется один id. Правило то же, что на iOS, — иначе одинаковая тревога на
     * двух телефонах приводила бы в разные места.
     *
     * ТЕПЕРЬ ТУДА ВЕДЁТ ЛЮБАЯ ТРЕВОГА, А НЕ ТОЛЬКО НЕЗНАКОМАЯ (SugarLife#703).
     *
     * Здесь была табличка: резервуар и батарея на помпу, молчание на сенсор. На тревоге она
     * оборачивается против человека: кнопка «Понял» живёт на «Сегодня», а раздел кладётся ПОВЕРХ —
     * значит, чтобы ответить, надо сначала нажать «назад». Спросонья.
     *
     * Владелец: «Иначе я не понимаю, в чём тревога. И хуже того, начинаю искать, где её отключить».
     * Тревога, на которую нельзя ответить сразу, толкает выключить тревоги — в приложении, которое
     * будит при низком сахаре, худшего исхода нет.
     *
     * Пока тревога не отвечена, действие важнее объяснения. С «Сегодня» до раздела один шаг, и там
     * же под тревогами стоит строка охраны.
     */
    fun цель(id: String): String = "сегодня"

    /** Что делать с уведомлением: показать так-то или снять. */
    sealed interface Шаг {
        data class Показать(val событие: Событие, val как: Как) : Шаг
        data class Снять(val id: String) : Шаг
    }

    /**
     * ПЛАН ПО СНИМКУ: события плюс сверка со списком висящих.
     *
     * Здесь же обе оставшиеся ловушки ядра. `cleared` снимает ТОЛЬКО свой id — событий в одном снимке
     * бывает несколько, и погасить заодно соседнюю значит выключить охрану, о которой никто не просил.
     * А сверка со списком нужна для тех тревог, о которых «отбоя» не приезжало вовсе: движок
     * перезапустился, сменился профиль, — и уведомление осталось бы висеть вечно.
     *
     * `активные = null` — списка в снимке нет: тогда не снимаем ничего. Пустой список и отсутствующий
     * означают разное, и путать их нельзя: по первому надо убрать всё, по второму — не трогать.
     */
    fun план(
        события: List<Событие>,
        активные: List<String>?,
        показано: Set<String>,
    ): List<Шаг> {
        val шаги = mutableListOf<Шаг>()
        for (с in события) {
            if (этоОтбой(с.what)) { шаги += Шаг.Снять(с.id); continue }
            val как = как(с)
            if (как != Как.НЕ_ПОКАЗЫВАТЬ) шаги += Шаг.Показать(с, как)
        }
        if (активные != null) {
            val живые = активные.toSet()
            /* Что показываем ЭТИМ ЖЕ снимком — не трогаем, даже если в списке висящих его нет.
               Событие и список приезжают вместе, и порядок между ними не гарантирован: снять только что
               показанное значило бы мигнуть тревогой и погасить её. Событию верим больше, чем списку:
               оно говорит «случилось сейчас», список — «висит вообще». */
            val покажем = шаги.filterIsInstance<Шаг.Показать>().map { it.событие.id }.toSet()
            val снимем = шаги.filterIsInstance<Шаг.Снять>().map { it.id }.toSet()
            for (id in показано) {
                if (!живые.contains(id) && !снимем.contains(id) && !покажем.contains(id)) шаги += Шаг.Снять(id)
            }
        }
        return шаги
    }

    /**
     * СЛОВА — временно наши (#482).
     *
     * У событий в контракте формулировки нет, и до её появления писать что-то надо: уведомление без текста
     * человек не прочитает. Табличка узкая намеренно, а незнакомый id получает честное общее слово, а не
     * выдуманное частное: «Тревога» лучше, чем неверная догадка о том, что случилось.
     *
     * Ядру отправлен запрос на `words` у события — по той же причине, по какой они сами запретили нам
     * писать формулировки для `learning`: на двух платформах они разойдутся.
     */
    fun слова(id: String, level: String, mmol: Double?, words: String? = null): Pair<String, String> {
        val основа = id.substringBefore(':')
        val хвост = id.substringAfter(':', "")
        val сахар = mmol?.let { "%.1f".format(it).replace('.', ',') + " ммоль" }
        val заголовок = when {
            хвост.contains("не-разбудит") || level == "ОбещаниеНарушено" -> "Тревога может не разбудить"
            основа.startsWith("гипо") -> "Низкий сахар"
            основа.startsWith("высок") -> "Высокий сахар"
            основа.startsWith("прогноз") || основа.contains("падени") -> "Сахар падает"
            основа.startsWith("молчание") -> "Данных нет"
            основа.startsWith("залип") -> "Линия не меняется"
            основа.startsWith("подача") -> "Подача инсулина стоит"
            основа.startsWith("резервуар") -> "Резервуар заканчивается"
            основа.startsWith("батаре") -> "Батарея помпы"
            else -> "Тревога"
        }
        val текст = when {
            /* СЛОВА ЯДРА ГЛАВНЕЕ ТАБЛИЧКИ (замечание владельца: в уведомлении стояла заглушка
               «Приложение сообщает о состоянии» при живой фразе в событии). Ядро отдаёт words с
               моста 1.31 — за рулём они другие, и наша табличка о таком не знает. */
            !words.isNullOrBlank() -> words
            /* «Тревога может не разбудить» с сахаром в тексте читается как тревога ПРО САХАР, и
               человек закрывает её, решив, что 10,2 не повод (#482). Беда здесь другая — в самой
               доставке, и говорить надо про неё. */
            заголовок == "Тревога может не разбудить" -> "Проверьте «Охрану»: сейчас разбудить не сможем"
            сахар != null -> сахар
            заголовок == "Тревога" -> "Приложение сообщает: $id"
            else -> "Приложение сообщает о состоянии"
        }
        return заголовок to текст
    }
}
