package ru.imiron.sugarlife

import android.content.Intent

/**
 * КУДА ВЕЛИ ЧЕЛОВЕКА, ПРИШЕДШЕГО ИЗ УВЕДОМЛЕНИЯ (#524).
 *
 * Уведомление кладёт цель себе в намерение, активность её достаёт, плагин отдаёт webview. Между этими
 * тремя нужен общий склад: приложение могли выгрузить, и цель приходит раньше, чем появляется экран,
 * способный её открыть. Потерять её именно в этом случае — значит потерять ровно тогда, когда она
 * была нужна: человека подняли ночью, он нажал на тревогу и попал «куда остановился».
 *
 * Цель одна и последняя: пока он шёл до телефона, могло прийти второе уведомление — вести надо туда,
 * куда нажали, а не устраивать очередь переходов.
 */
const val ЦЕЛЬ = "sugarlife.цель"

object ЦельПерехода {
    private var ожидает: String? = null
    /** Кому отдавать сразу, если webview уже слушает. */
    var слушатель: ((String) -> Unit)? = null
        set(значение) {
            field = значение
            val ц = ожидает
            if (значение != null && ц != null) { ожидает = null; значение(ц) }
        }

    /** Достать цель из намерения активности и пустить её дальше. Чужие намерения молча пропускаем. */
    fun из(намерение: Intent?) {
        val ц = намерение?.getStringExtra(ЦЕЛЬ) ?: return
        /* Намерение живёт дольше одного показа: система отдаёт тот же объект и при повороте экрана.
           Стираем сразу, иначе один тап уводил бы в раздел ещё и завтра. */
        намерение.removeExtra(ЦЕЛЬ)
        val с = слушатель
        if (с != null) с(ц) else ожидает = ц
    }

    /** Забрать накопленную цель (webview спрашивает при старте) — и забыть. */
    fun забрать(): String {
        val ц = ожидает ?: return ""
        ожидает = null
        return ц
    }
}
