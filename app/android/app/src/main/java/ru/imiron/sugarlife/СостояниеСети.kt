package ru.imiron.sugarlife

/*
 * ЧТО ПРО СЕТЬ ЗНАЕМ ТОЛЬКО МЫ (SugarLife#805).
 *
 * Два факта, которых у движка нет и быть не может: идём ли мы через VPN и сколько длился последний
 * обрыв. Оба про НАШ телефон, а движок видит только свои запросы к облаку.
 *
 * Правило владельца, ради которого это заведено: «источник истины должен быть один — пусть даже мы
 * определяем, но фразы всегда говорит нам ядро». Поэтому здесь голые факты и ни одного слова
 * человеку: подсказку про VPN и длительность обрыва произносит движок.
 *
 * ОТДЕЛЬНЫМ ОБЪЕКТОМ, А НЕ ПОЛЯМИ ПЛАГИНА: пишет их наблюдатель сети в плагине, читает доклад о
 * доставке в другом файле. Через плагин это шло бы ссылкой, которая живёт не всегда.
 */
object СостояниеСети {
    /* Идём ли через VPN.
     *
     * На Android это ФАКТ: `NetworkCapabilities.TRANSPORT_VPN` — документированный признак. На
     * айфоне того же приходится добиваться догадкой по именам интерфейсов, и разницу в надёжности
     * движку сообщаем как есть: он один решает, как говорить при неуверенности. */
    @Volatile var черезVPN: Boolean = false

    /* Сколько длился последний обрыв, секунд. `null` — обрывов ещё не было.
     *
     * Нужен, чтобы после возврата сказать «связи не было двадцать одну минуту» вместо тревожного
     * «связи нет» в настоящем времени: первое — закрытый факт о прошлом, на второе человеку нечем
     * ответить. */
    @Volatile var последнийОбрывСек: Int? = null

    private var пропалаВ = 0L

    /** Сеть пропала. Засекаем один раз: система шлёт события пачкой, и переписывать момент значило
     *  бы обнулять счёт на каждом шевелении. */
    @Synchronized fun пропала() {
        if (пропалаВ == 0L) пропалаВ = System.currentTimeMillis()
    }

    /** Сеть вернулась — считаем, сколько её не было. */
    @Synchronized fun вернулась(): Int? {
        if (пропалаВ == 0L) return null
        последнийОбрывСек = ((System.currentTimeMillis() - пропалаВ) / 1000).toInt()
        пропалаВ = 0L
        return последнийОбрывСек
    }

    /** Забрать длительность обрыва ОДИН раз: дыра — событие, а не состояние, и повторять её при
     *  каждом докладе значило бы заводить движку по дыре на каждое шевеление сети. */
    @Synchronized fun взятьОбрыв(): Int? {
        val было = последнийОбрывСек
        последнийОбрывСек = null
        return было
    }
}
