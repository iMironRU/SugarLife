package ru.imiron.sugarlife

/**
 * КОГДА СЕТЬ ДЕЙСТВИТЕЛЬНО ВЕРНУЛАСЬ (SugarLifeCore#213).
 *
 * Движку сообщают «сеть вернулась», чтобы он разбудил всех, кто досиживает паузу перед следующей
 * попыткой достучаться до облака. Смысл сообщения — СОБЫТИЕ: ходить было нельзя, стало можно.
 *
 * Мы же слали его на СОСТОЯНИЕ. Android зовёт `onCapabilitiesChanged` на любое изменение свойств
 * сети — скорость канала, уровень сигнала, метрики оператора, — и это происходит постоянно при
 * живом соединении. За сутки на телефоне владельца набежало **830 сообщений «сеть вернулась»**:
 * тридцать шесть в час, ровно, включая ночь, когда телефон лежал на тумбочке и Wi-Fi не менялся.
 *
 * Батарею это не ело — обработчик в движке дешёвый и намеренно идемпотентный (core#128). Ело
 * журнал: 1660 записей из 17 365, каждая десятая. В тот же день человек полторы минуты смотрел на
 * серый экран, и об ЭТОМ в журнале не оказалось ни строки — зато «сеть вернулась» лежала 830 раз.
 * Ровный шум вытесняет редкое, а разбирают журнал именно ради редкого.
 *
 * Здесь нет ни одного типа Android — чтобы решение можно было проверить тестом, а не глазами.
 */
class СторожСети {

    /* Начинаем с «не знаем», а не с «сеть есть». Так первое же сообщение системы — какое угодно —
       считается сменой мнения и уходит движку. Это важнее, чем кажется: движок должен узнать
       состояние сети, даже если оно не менялось с его точки зрения, иначе после перезапуска он
       останется без мнения вовсе. Одно сообщение на старте — вся цена. */
    private var интернетЕсть: Boolean? = null

    /**
     * Система сказала, есть ли сейчас интернет.
     *
     * @return `true`, только если мнение ИЗМЕНИЛОСЬ — в любую сторону. На повторное «всё ещё есть»
     *   отвечаем `false`: говорить движку нечего, а именно из этих повторов и складывались 830
     *   сообщений за сутки.
     */
    fun мнениеСменилось(есть: Boolean): Boolean {
        if (есть == интернетЕсть) return false
        интернетЕсть = есть
        return true
    }
}
