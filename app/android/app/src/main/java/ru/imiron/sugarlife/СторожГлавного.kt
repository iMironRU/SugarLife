package ru.imiron.sugarlife

import android.os.Handler
import android.os.Looper
import android.os.SystemClock
import android.util.Log

/**
 * НА ЧЁМ ВСТАЛ ГЛАВНЫЙ ПОТОК (SugarLifeCore#236).
 *
 * Владелец видел системное «приложение не отвечает» при выходе из фона — а телефон об этом молчит:
 * в `dumpsys dropbox` последние две записи ANR старше нынешней сборки, `lastanr` пуст, три цикла
 * «свернуть — открыть» подряд повторить беду не дали. То есть она есть, а следа её у нас нет.
 *
 * Сбор logcat даёт факт и время. Стек главного потока пишет dropbox — тот самый, что молчит. Значит
 * снять стек должны мы сами, и снять его надо ПОКА ПОТОК ЕЩЁ СТОИТ: после того как система покажет
 * диалог, виноватый кадр уже уехал.
 *
 * КАК РАБОТАЕТ. Отдельный поток раз в секунду кладёт в главный дешёвую задачу и смотрит, когда та
 * выполнилась. Не выполнилась [ПОРОГ_МС] — главный занят, и мы снимаем его стек.
 *
 * ЭТО НЕ ЗАМЕНА СИСТЕМНОМУ ANR, А ЕГО ПРЕДВЕСТНИК. Система считает ввод зависшим через пять секунд;
 * мы кричим через три. Значит поймаем и те простои, которые до диалога не дошли, — а они и есть
 * ранние признаки той же беды.
 */
object СторожГлавного {

    /**
     * Сколько простоя считаем зависанием.
     *
     * Три секунды — не круглое число, а зазор до системного порога: по вводу ANR объявляется через
     * пять, и снять стек надо раньше. Ставить меньше нельзя: кадр интерфейса при возврате из фона
     * законно занимает сотни миллисекунд, и мы бы кричали на здоровое приложение.
     */
    const val ПОРОГ_МС = 3_000L

    /** Как часто щупаем. Секунда — дешевле некуда при пороге в три. */
    const val ШАГ_МС = 1_000L

    /** Сколько кадров стека пишем. Двадцати пяти хватает, чтобы дойти до нашего кода. */
    const val КАДРОВ = 25

    /** Чистое правило — его и проверяет тест. */
    fun встал(простойМс: Long): Boolean = простойМс >= ПОРОГ_МС

    private const val TAG = "SugarLifeСторож"

    private val руки = Handler(Looper.getMainLooper())
    @Volatile private var ответилВ = 0L
    @Volatile private var запущен = false

    @JvmStatic
    fun завести() {
        if (запущен) return
        запущен = true
        ответилВ = SystemClock.uptimeMillis()
        Log.i(TAG, "сторож главного потока заведён: порог ${ПОРОГ_МС / 1000} с, шаг ${ШАГ_МС} мс")
        val поток = Thread({ круг() }, "сторож-главного")
        поток.isDaemon = true
        /* Ниже обычного: сторож не должен отнимать процессор у того, за кем следит. */
        поток.priority = Thread.MIN_PRIORITY
        поток.start()
    }

    private fun круг() {
        var кричали = false
        var всталВ = 0L
        while (true) {
            руки.post { ответилВ = SystemClock.uptimeMillis() }
            try {
                Thread.sleep(ШАГ_МС)
            } catch (_: InterruptedException) {
                return
            }
            val простой = SystemClock.uptimeMillis() - ответилВ
            /*
             * ПИШЕМ ПЕРЕХОДЫ, А НЕ СОСТОЯНИЕ. Строка на каждый круг — это 86 400 записей в сутки
             * ровного молчания, и сторож стал бы тем же, чем был блоб калибратора (#235): утопил бы
             * журнал, заведённый его же ради.
             */
            if (встал(простой) && !кричали) {
                кричали = true
                всталВ = SystemClock.uptimeMillis()
                Log.w(TAG, "ГЛАВНЫЙ ПОТОК СТОИТ ${простой} мс, вот где:\n${стекГлавного()}")
            } else if (!встал(простой) && кричали) {
                кричали = false
                Log.w(TAG, "главный поток отпустило, стоял ${SystemClock.uptimeMillis() - всталВ + простой} мс")
            }
        }
    }

    /** Снимок стека главного потока. `Thread.stackTrace` не останавливает его — только смотрит. */
    private fun стекГлавного(): String = runCatching {
        Looper.getMainLooper().thread.stackTrace.take(КАДРОВ).joinToString("\n") { "    at $it" }
    }.getOrElse { "стек не снялся: $it" }
}
