package ru.imiron.sugarlife

import android.util.Log
import kotlin.math.abs
import ru.imiron.sugarlife.contract.SensorCalibrator

/**
 * Калибровка Sibionics вендорским алгоритмом (core#88).
 *
 * Сенсор отдаёт только сырьё; калибровка целиком на телефоне. До сих пор мы клали сырое значение в поле
 * «калиброванное» — на живом приборе это давало 13.9 там, где у Juggluco было 9.8. По такому числу человек
 * считает дозу, поэтому поле мы очистили и ждали настоящего расчёта. Вот он.
 *
 * САМ АЛГОРИТМ — ЧУЖОЙ. Он портирован в JugglucoNG и лежит под GPL-3.0; в нашем дереве его нет, он
 * скачивается скриптом `app/scripts/fetch-vendor-calibration.sh` и в git не попадает. Обязательства GPL
 * наступают при передаче программы другому человеку — пока сборка личная, их нет. Этот файл — наш
 * переходник, и он остаётся нашим.
 *
 * ЧУЖОГО КОДА ЗДЕСЬ НЕТ — это расписка для сторожа (app/src/чужойКод.test.ts). Он ловит упоминания GPL,
 * потому что скопированный файл приносит их с собой; расписку пишут руками, посмотрев на файл.
 *
 * Нет скачанных файлов — нет и калибровки: приложение честно покажет сырое значение и скажет, что оно
 * сырое. Заглушек здесь не будет.
 */
/**
 * ГОДНА ЛИ ПОПРАВКА ПО СРОКУ (SugarLife#750).
 *
 * Отдельной функцией и под тестом, а не условием в две строки внутри класса: класс тянет за собой
 * чужой алгоритм, которого в дереве нет, и проверить его в сборке нечем. А ошибка здесь стоит
 * девяти ммоль на экране — это разница между «немедленно колоть» и «всё в порядке».
 *
 * @param откуда номер записи, на которой поправка получена; `null` — поправки не было
 * @param сейчас номер текущей записи
 * @param срок сколько записей поправке позволено жить
 */
internal fun поправкаГодна(откуда: Int?, сейчас: Int, срок: Int): Boolean {
    if (откуда == null) return false
    val возраст = сейчас - откуда
    /* Назад по номеру записи — тоже конец: значит начался другой сеанс сенсора, и старая поправка
       к нему отношения не имеет. */
    return возраст in 0..срок
}

class SibionicsVendorCalibrator : SensorCalibrator {

    private var core: ВендорскийАлгоритм? = null
    private var чувствительность: Float = 0f
    /** Последняя разница между точным ответом и сырым — ею закрываются промежуточные минуты. */
    private var поправка: Float? = null
    /** Номер записи, на которой поправка получена. По нему и считается её срок (#750). */
    private var поправкаОтЗаписи: Int? = null

    override fun configure(sensorCode: String?) {
        /* ЧУВСТВИТЕЛЬНОСТЬ ПАРТИИ — ИЗ КОДА СЕНСОРА. Она закодирована в последних четырёх символах
           («671K» у XDUD671K) и входит в расчёт напрямую. Не узнав её, алгоритм считает по умолчанию
           (1.27) и расходится с прибором на всём диапазоне. */
        чувствительность = ВендорскийАлгоритм.чувствительностьИзКода(sensorCode) ?: ПО_УМОЛЧАНИЮ
        core = ВендорскийАлгоритм.создать(чувствительность)
        поправка = null
        поправкаОтЗаписи = null
        точныхОтветов = 0
        Log.i(TAG, "калибратор настроен: код=${sensorCode ?: "—"} чувствительность=$чувствительность")
    }

    /**
     * ЗНАЧЕНИЕ КАЖДУЮ МИНУТУ, А ТОЧНЫЙ РАСЧЁТ — РАЗ В ПЯТЬ (core#88).
     *
     * Вендорский алгоритм отдаёт ответ каждую пятую минуту. Отдавать в остальные минуты пустоту — значит
     * оставить на графике четыре дырки из пяти, а петле не дать опоры. Первоисточник (JugglucoNG,
     * `liveValue`) поступает иначе: запоминает поправку `ответ − сырое` и в промежутках отдаёт
     * `сырое + поправка`.
     *
     * Границы оттуда же, и они не украшение: ответ принимается в пределах 1…50 ммоль, поправка — если по
     * модулю меньше 40. Вышли за них — забываем поправку и отдаём сырое, потому что дальше начинается
     * выдумывание.
     */
    /**
     * ПРОГРЕТ ЛИ АЛГОРИТМ (core#109).
     *
     * Внутри вендорского ядра фильтр Калмана и температурные средние набираются по десятку отсчётов, а
     * точный расчёт приходит раз в пять записей. Первый такой расчёт считается на пустых буферах и потому
     * неверен: на живом приборе он дал 8.9 там, где было 6.5, и эта поправка тянулась четыре минуты.
     *
     * Готовым считаем себя после ДВУХ точных ответов: первый — на непрогретых буферах, второй уже на
     * набранных. Ровно на нём ряд и встал на место (снято в Nightscout поминутно).
     */
    override fun warmedUp(): Boolean = точныхОтветов >= ТОЧНЫХ_ДЛЯ_ПРОГРЕВА

    /** Сколько раз алгоритм ответил точно с последнего сброса — по ним и судим о прогреве (core#109). */
    private var точныхОтветов = 0

    override fun calibrate(rawMmol: Float, temperatureC: Float?, index: Int): Float? {
        val c = core ?: return null
        // БЕЗ ТЕМПЕРАТУРЫ НЕ СЧИТАЕМ. Она входит в компенсацию напрямую, и подставить сюда «примерно 30»
        // значит выдумать результат. Нет температуры — нет ответа, сырое значение остаётся рядом.
        val t = temperatureC ?: return null
        val ответ = c.process(rawMmol, t, index)
        if (ответ != null && ответ.isFinite() && ответ > МИН_ММОЛЬ && ответ <= МАКС_ММОЛЬ) {
            точныхОтветов++
            поправка = ответ - rawMmol
            поправкаОтЗаписи = index
            return ответ
        }
        /*
         * НЕТ ОТВЕТА И НЕТ ПОПРАВКИ — ЗНАЧИТ НЕТ КАЛИБРОВАННОГО ЧИСЛА (поймано на живом приборе).
         *
         * Здесь возвращалось `rawMmol`, то есть сырьё уезжало наверх под видом калиброванного. Две
         * беды сразу, и обе видел владелец:
         *
         * 1. Мы нарушали собственное правило «сырое называем сырым»: число помечалось калиброванным,
         *    хотя алгоритм его не считал.
         * 2. Когда алгоритм просыпался (точный расчёт приходит раз в пять записей), значение прыгало
         *    СТУПЕНЬКОЙ: 11,1 → 7,5 при почти неизменном сырье 10,3 → 10,1. Сахар не скакал —
         *    скакало то, чем мы его считали.
         *
         * Молчание здесь честнее: сырое значение и так идёт рядом, и показ пометит его сырым.
         */
        val п = поправка
        if (п == null || !п.isFinite() || abs(п) >= МАКС_ПОПРАВКА) return null

        /*
         * У ПОПРАВКИ ЕСТЬ СРОК (SugarLife#750, ядро SugarLifeCore#195).
         *
         * Поправка — мостик на четыре минуты между точными расчётами. Срока у неё не было, только
         * проверка величины, — и пока точные ответы шли, это было незаметно.
         *
         * А потом мы впервые встали ПОПУТЧИКОМ к живому сенсору: вошли в чужой сеанс в середине,
         * буферы вендорского ядра набирались не с нашего начала, точные ответы прекратились — и
         * мостик на четыре минуты стал постоянным мостом длиной в час.
         *
         * Измерено ядром на 46 совпавших по минуте точках: наше значение ровно `сырое − 2,1`
         * сорок шесть минут подряд, при расхождении с правдой в +9 ммоль. На экране 19,3 там, где
         * 10,3. Это не оттенок — это разница между «немедленно колоть» и «всё в порядке».
         *
         * ХУЖЕ ВСЕГО, ЧТО ПОМЕТКА «СЫРОЕ» ПРИ ЭТОМ СНЯТА: значение считалось посчитанным, а
         * посчитанное человек принимает за истину. Сырьё «21,5» он бы не принял, а «19,3» примет.
         * То есть приложение переставало предупреждать ровно тогда, когда начинало ошибаться
         * опаснее.
         *
         * ПРИЗНАК СТАЛ МОМЕНТОМ. Это ровно тот урок, который мы с ядром пересказываем друг другу
         * каждую неделю: признак надо не забыть снять, а момент гаснет сам.
         *
         * СБРАСЫВАЕМ И ПРОГРЕВ, а не только поправку. Вернуть `null` мало: тогда мы скажем «это
         * сырьё», но `warmedUp()` продолжит утверждать, что алгоритм прогрет, — а он не считает
         * уже час. Из двух предложенных ядром вариантов это второй, и он честнее: мы сообщаем не
         * только «число сырое», но и «считать больше некому».
         *
         * Назад по номеру записи — тоже конец: значит начался другой сеанс, и старая поправка к
         * нему отношения не имеет.
         */
        if (!поправкаГодна(поправкаОтЗаписи, index, СРОК_ПОПРАВКИ)) {
            Log.w(TAG, "поправка протухла — отдаём сырое и снимаем прогрев")
            поправка = null
            поправкаОтЗаписи = null
            точныхОтветов = 0
            return null
        }
        return (rawMmol + п).coerceAtLeast(0f)
    }

    override fun reset() {
        core = ВендорскийАлгоритм.создать(чувствительность)
        поправка = null; поправкаОтЗаписи = null; точныхОтветов = 0
    }

    /* СОСТОЯНИЕ ПЕРЕЖИВАЕТ ПЕРЕЗАПУСК (core#88). У самого алгоритма для этого есть snapshot/restore — им и
       пользуемся, а не выдумываем своё: внутри фильтр и температурные средние, и правильно сохранить их
       умеет только он сам. */
    override fun snapshot(): ByteArray? = core?.snapshot()

    override fun restore(state: ByteArray?): Boolean {
        val c = core ?: ВендорскийАлгоритм.создать(чувствительность)?.also { core = it } ?: return false
        val получилось = c.restore(state)
        /* ВОССТАНОВЛЕННОЕ СОСТОЯНИЕ — УЖЕ ПРОГРЕТОЕ (core#109).
        
           В снимке лежат те самые фильтр и температурные средние, ради набора которых мы и молчим первые
           минуты. Заставлять человека ждать их заново после каждого перезапуска приложения незачем — он
           уже подождал однажды.
        
           Верность того давнего старта — отдельный вопрос (core#104): прогрет не значит прав. Но молчание
           тут не поможет: через десять минут вышли бы те же числа. */
        if (получилось) точныхОтветов = ТОЧНЫХ_ДЛЯ_ПРОГРЕВА
        return получилось
    }

    private companion object {
        /** Сколько точных ответов считаем прогревом (core#109): первый приходит на пустых буферах, второй —
         *  на набранных. Ровно на втором ряд и встал на место, снято на живом приборе. */
        const val ТОЧНЫХ_ДЛЯ_ПРОГРЕВА = 2

        const val TAG = "SugarLifeCalib"
        /** Значение вендора, когда код не разобран. Оно же стоит и в первоисточнике. */
        const val ПО_УМОЛЧАНИЮ = 1.27f
        /** Границы первоисточника: ответ вне их не принимается, поправка вне их — забывается. */
        const val МИН_ММОЛЬ = 1f
        const val МАКС_ММОЛЬ = 50f
        const val МАКС_ПОПРАВКА = 40f
        /** Сколько записей живёт поправка (#750). Точный расчёт приходит раз в пять записей, то есть
         *  в норме мостику четыре минуты; пятая — запас на одну пропущенную запись, чтобы значение не
         *  мигало между сырым и посчитанным там, где всё в порядке. Дальше начинается выдумывание. */
        const val СРОК_ПОПРАВКИ = 5
    }
}
