package ru.imiron.sugarlife

import android.util.Log
import ru.imiron.sugarlife.contract.SensorCalibrator

/**
 * Калибровка Sibionics вендорским алгоритмом (core#88).
 *
 * Сенсор отдаёт только сырьё; калибровка целиком на телефоне. До сих пор мы клали сырое значение в поле
 * «калиброванное» — на живом приборе это давало 13.9 там, где у Juggluco было 9.8. По такому числу человек
 * считает дозу, поэтому поле мы очистили и ждали настоящего расчёта. Вот он.
 *
 * САМ АЛГОРИТМ — ЧУЖОЙ. Он портирован в JugglucoNG и лежит под GPL-3.0; в нашем дереве его нет, он
 * скачивается скриптом `app/scripts/fetch-vendor-calibration.sh` и в git не попадает. Обязательства GPL
 * наступают при передаче программы другому человеку — пока сборка личная, их нет. Этот файл — наш
 * переходник, и он остаётся нашим.
 *
 * ЧУЖОГО КОДА ЗДЕСЬ НЕТ — это расписка для сторожа (app/src/чужойКод.test.ts). Он ловит упоминания GPL,
 * потому что скопированный файл приносит их с собой; расписку пишут руками, посмотрев на файл.
 *
 * Нет скачанных файлов — нет и калибровки: приложение честно покажет сырое значение и скажет, что оно
 * сырое. Заглушек здесь не будет.
 */
class SibionicsVendorCalibrator : SensorCalibrator {

    private var core: ВендорскийАлгоритм? = null
    private var чувствительность: Float = 0f
    /* БЫЛ ЛИ ПОСЛЕДНИЙ ОТВЕТ ТОЧНЫМ (контракт, ядро SugarLifeCore#196).

       `null` — вендорского алгоритма нет вовсе, мы в расчёте не участвуем и ядро ведёт себя как
       раньше. `true` — точный расчёт. `false` — алгоритм в эту минуту не ответил, и мостик, если
       он уместен, строит ядро. */
    private var последнийБылТочным: Boolean? = null

    override fun configure(sensorCode: String?) = configure(sensorCode, null)

    override fun configure(sensorCode: String?, variant: String?) {
        /* ЧУВСТВИТЕЛЬНОСТЬ ИЗ КОДА СЕНСОРА — ПОПРАВКА (SugarLifeCore#206).
           Здесь стояло: «входит в расчёт напрямую; не узнав её, алгоритм считает по умолчанию (1.27) и
           расходится с прибором на всём диапазоне». Замерено на стенде — неверно: подаём 0,50 / 1,37 /
           2,50, алгоритм за первую сотню отсчётов приходит к своим 1,5 независимо от входа, ответы
           совпадают до сотой. Значение оставляем (вреда нет, а для V116A поведение не проверено), но
           лечить им расхождение бессмысленно. */
        чувствительность = ВендорскийАлгоритм.чувствительностьИзКода(sensorCode) ?: ПО_УМОЛЧАНИЮ
        /* СЕМЕЙСТВО РЕШАЕТ ВАРИАНТ ПРИБОРА, А НЕ КОД. Три варианта из пяти считают V116A: EU (SiJoy),
           Hematonix (Русибионикс), Sibionics 2. Взяв не то семейство, мы посчитаем молча неверно. */
        val семейство = ВендорскийАлгоритм.Семейство.поВарианту(variant)
        core = ВендорскийАлгоритм.создать(чувствительность, семейство)
        последнийБылТочным = null
        точныхОтветов = 0
        Log.i(
            TAG,
            "калибратор настроен: код=${sensorCode ?: "—"} вариант=${variant ?: "—"} " +
                "семейство=$семейство чувствительность=$чувствительность",
        )
    }

    /**
     * ПРОГРЕТ ЛИ АЛГОРИТМ (core#109).
     *
     * Внутри вендорского ядра фильтр Калмана и температурные средние набираются по десятку отсчётов, а
     * точный расчёт приходит раз в пять записей. Первый такой расчёт считается на пустых буферах и потому
     * неверен: на живом приборе он дал 8.9 там, где было 6.5, и эта поправка тянулась четыре минуты.
     *
     * Готовым считаем себя после ДВУХ точных ответов: первый — на непрогретых буферах, второй уже на
     * набранных. Ровно на нём ряд и встал на место (снято в Nightscout поминутно).
     */
    override fun warmedUp(): Boolean = точныхОтветов >= ТОЧНЫХ_ДЛЯ_ПРОГРЕВА

    /** Сколько раз алгоритм ответил точно с последнего сброса — по ним и судим о прогреве (core#109). */
    private var точныхОтветов = 0

    /**
     * МОСТИК МЕЖДУ ТОЧНЫМИ РАСЧЁТАМИ СТРОИМ НЕ МЫ (ядро SugarLifeCore#196).
     *
     * Вендорский алгоритм отвечает раз в пять записей. В промежутках значение всё равно нужно —
     * иначе на графике четыре дырки из пяти, а петле не на что опереться, — и раньше мостик мы
     * строили сами: запоминали `ответ − сырое` и отдавали `сырое + поправка`.
     *
     * Первого сентября это обошлось в девять ммоль. Мы впервые встали попутчиком к живому сенсору,
     * вошли в чужой сеанс в середине, точные ответы прекратились — а мостик остался, потому что
     * срока у него не было. Сорок шесть минут подряд приложение показывало 19,3 там, где было 10,3
     * (#750, ядро #195).
     *
     * Срок мы починили в тот же день. А потом ядро забрало правило целиком, и это правильнее:
     * «как долго можно показывать число, которое мы не можем пересчитать» — правило ДОВЕРИЯ к
     * значению, по которому человек считает дозу. Все такие правила живут в ядре, под его тестами
     * и сторожами. Это одно уехало наружу вместе с алгоритмом — и осталось без срока, без проверки
     * на настоящих данных и без сторожа проводки. Снаружи ловить его было некому: мы и не поймали.
     *
     * Теперь между расчётами возвращаем то, что вернул вендор, — то есть `null`, — и говорим
     * `последнийТочный() == false`. Мостик и его десять минут (два вендорских цикла) — у ядра.
     *
     * У НАС ОСТАЁТСЯ ВЫЧИСЛЕНИЕ: чужое ядро, чувствительность из кода сенсора, температура. И
     * `warmedUp()`: «был ли точный расчёт» — внутреннее знание алгоритма, снаружи его не видно.
     */
    override fun calibrate(rawMmol: Float, temperatureC: Float?, index: Int): Float? {
        val c = core
        if (c == null) {
            /* Алгоритма нет вовсе (файлы не скачаны) — мы в расчёте не участвуем. Отвечаем `null`
               на вопрос о точности: пусть ядро ведёт себя как раньше, а не строит мостик от
               поправки, которой никогда не было. */
            последнийБылТочным = null
            return null
        }
        // БЕЗ ТЕМПЕРАТУРЫ НЕ СЧИТАЕМ. Она входит в компенсацию напрямую, и подставить сюда «примерно 30»
        // значит выдумать результат. Нет температуры — нет ответа, сырое значение остаётся рядом.
        val t = temperatureC
        if (t == null) {
            последнийБылТочным = false
            return null
        }
        val ответ = c.process(rawMmol, t, index)
        if (ответ != null && ответ.isFinite() && ответ > МИН_ММОЛЬ && ответ <= МАКС_ММОЛЬ) {
            точныхОтветов++
            последнийБылТочным = true
            return ответ
        }
        /*
         * СЫРЬЁ ПОД ВИДОМ КАЛИБРОВАННОГО СЮДА НЕ ВЕРНЁТСЯ (поймано на живом приборе).
         *
         * Здесь когда-то возвращалось `rawMmol`, и это давало две беды сразу: число помечалось
         * калиброванным, хотя алгоритм его не считал, а когда алгоритм просыпался, значение прыгало
         * ступенькой — 11,1 → 7,5 при почти неизменном сырье. Сахар не скакал; скакало то, чем мы
         * его считали.
         *
         * Молчание здесь честнее: сырое значение и так идёт рядом, и показ пометит его сырым.
         */
        последнийБылТочным = false
        return null
    }

    /** true — точный расчёт вендорского ядра, false — не ответило, null — алгоритма нет вовсе. */
    override fun последнийТочный(): Boolean? = последнийБылТочным

    override fun reset() {
        core = ВендорскийАлгоритм.создать(чувствительность)
        последнийБылТочным = null; точныхОтветов = 0
    }

    /* СОСТОЯНИЕ ПЕРЕЖИВАЕТ ПЕРЕЗАПУСК (core#88). У самого алгоритма для этого есть snapshot/restore — им и
       пользуемся, а не выдумываем своё: внутри фильтр и температурные средние, и правильно сохранить их
       умеет только он сам. */
    override fun snapshot(): ByteArray? = core?.snapshot()

    override fun restore(state: ByteArray?): Boolean {
        val c = core ?: ВендорскийАлгоритм.создать(чувствительность)?.also { core = it } ?: return false
        val получилось = c.restore(state)
        /* ВОССТАНОВЛЕННОЕ СОСТОЯНИЕ — УЖЕ ПРОГРЕТОЕ (core#109).
        
           В снимке лежат те самые фильтр и температурные средние, ради набора которых мы и молчим первые
           минуты. Заставлять человека ждать их заново после каждого перезапуска приложения незачем — он
           уже подождал однажды.
        
           Верность того давнего старта — отдельный вопрос (core#104): прогрет не значит прав. Но молчание
           тут не поможет: через десять минут вышли бы те же числа. */
        if (получилось) точныхОтветов = ТОЧНЫХ_ДЛЯ_ПРОГРЕВА
        return получилось
    }

    private companion object {
        /** Сколько точных ответов считаем прогревом (core#109): первый приходит на пустых буферах, второй —
         *  на набранных. Ровно на втором ряд и встал на место, снято на живом приборе. */
        const val ТОЧНЫХ_ДЛЯ_ПРОГРЕВА = 2

        const val TAG = "SugarLifeCalib"
        /** Значение вендора, когда код не разобран. Оно же стоит и в первоисточнике. */
        const val ПО_УМОЛЧАНИЮ = 1.27f
        /** Границы первоисточника: ответ вне их за расчёт не считаем. */
        const val МИН_ММОЛЬ = 1f
        const val МАКС_ММОЛЬ = 50f
    }
}
