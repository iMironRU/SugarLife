package ru.imiron.sugarlife

import android.app.AlarmManager
import android.content.Context
import android.os.Build

/**
 * ТОЧНОСТЬ ПРОБУЖДЕНИЯ — решение человека, исполнение наше (SugarLife#482, ядро #16).
 *
 * Неточный будильник система вправе сдвинуть до девяти минут: порог «15 минут» на деле означает «узнаем
 * в пределах 24». Точный даёт заданное время ценой отдельного разрешения и системного предупреждения про
 * батарею. Выбор между «узнать раньше» и «ещё одно разрешение» — не наш и не движка: цена обеих сторон
 * названа числами в статье, а решает человек. Выключатель приезжает в правилах молчания
 * (`alarms.exactWakeups`), и наше дело — исполнить и честно доложить, что получилось.
 *
 * ФАКТ, А НЕ ЖЕЛАНИЕ. Точность докладываем по тому, что есть на самом деле: включённый выключатель без
 * выданного разрешения — это по-прежнему девять минут. Доложить ноль значило бы, что движок пообещает
 * человеку время, которого система не даст.
 *
 * ПОЧЕМУ ОДНОГО РАЗРЕШЕНИЯ МАЛО. На Android 12 `SCHEDULE_EXACT_ALARM` выдаётся при установке сам. Считать
 * это согласием нельзя: человек ничего не выбирал. Поэтому точный будильник включает выключатель, а
 * разрешение лишь позволяет его исполнить.
 */
object Точность {
    /** Неточный будильник в Doze: система пакует пробуждения не чаще раза в девять минут. */
    const val НЕТОЧНО_МИН = 9
    const val ТОЧНО_МИН = 0

    private const val НАСТРОЙКИ = "sugarlife-alarms"
    private const val КЛЮЧ = "exact-wakeups"

    /** Чистое правило: что доложить движку. */
    fun точностьМин(выключатель: String?, разрешеноСистемой: Boolean): Int =
        if (выключатель == "on" && разрешеноСистемой) ТОЧНО_МИН else НЕТОЧНО_МИН

    /** Ставить ли точный будильник. Тот же ответ, но словами исполнителя. */
    fun точныйБудильник(выключатель: String?, разрешеноСистемой: Boolean): Boolean =
        точностьМин(выключатель, разрешеноСистемой) == ТОЧНО_МИН

    /** Человек попросил точность, а система ещё не дала: значит экрану есть что предложить. */
    fun нуженЗапросРазрешения(выключатель: String?, разрешеноСистемой: Boolean): Boolean =
        выключатель == "on" && !разрешеноСистемой

    /* Выключатель приходит в снимке, а нужен он будильнику — тому, что заводится в фоне без всякого
       снимка. Поэтому зеркалим его в настройки: снимка в момент пробуждения может не быть вовсе. */
    fun запомнить(ctx: Context, выключатель: String?) {
        val prefs = ctx.applicationContext.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE)
        val было = prefs.getString(КЛЮЧ, null)
        if (было == выключатель) return
        prefs.edit().putString(КЛЮЧ, выключатель ?: "off").apply()
    }

    fun выключатель(ctx: Context): String =
        ctx.applicationContext.getSharedPreferences(НАСТРОЙКИ, Context.MODE_PRIVATE)
            .getString(КЛЮЧ, "off") ?: "off"

    /** Разрешила ли система точные будильники. До Android 12 разрешения не существует вовсе. */
    fun разрешеноСистемой(ctx: Context): Boolean {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.S) return true
        val am = ctx.getSystemService(Context.ALARM_SERVICE) as AlarmManager
        return runCatching { am.canScheduleExactAlarms() }.getOrDefault(false)
    }

    fun точныйБудильник(ctx: Context): Boolean =
        точныйБудильник(выключатель(ctx), разрешеноСистемой(ctx))

    fun точностьМин(ctx: Context): Int =
        точностьМин(выключатель(ctx), разрешеноСистемой(ctx))
}
