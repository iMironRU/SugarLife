import Foundation
import UserNotifications
import AVFoundation
import UIKit

/**
 ДОСТАВКА ТРЕВОГ НА АЙФОНЕ (SugarLife#482).

 Раздел с ядром тот же, что на Android: движок решает, что случилось и какого это уровня, оболочка
 показывает и даёт ответить. Здесь вторая половина — для iOS.

 ПОЧЕМУ ЭТО НЕ КОПИЯ ANDROID-ВЕРСИИ. Отличий три, и все существенные.

  1. **Звук пробивает беззвучный режим только СВОЙ.** Уведомление со стандартным звуком на беззвучном
     телефоне молчит, каким бы важным мы его ни объявили: Critical Alerts требуют разрешения Apple,
     которого у нас нет. Единственный способ — играть звук самим через аудио-сессию, ту же, что держит
     приложение живым в фоне (#388). Поэтому будящая тревога здесь = уведомление ПЛЮС свой звук.

  2. **Мы можем не жить.** На Android процесс держит foreground-сервис; на iOS приложение засыпает, если
     его нечем будить. При работе от облака это решает фоновое бодрствование, и оно — выбор человека.
     Отсюда честный доклад движку (`reportDelivery`): нет бодрствования — «разбудить не сможем».

  3. **Повторов не заводим.** На Android их отмеряет будильник системы; здесь единственный источник
     тиканья — снимки движка. Повтор придёт со следующим событием `repeat` от него же, и заводить своё
     расписание значило бы завести второе мнение о том, когда напоминать.

 ПРАВИЛА ПОКАЗА ПОВТОРЯЮТ Тревоги/ПравилаПоказа.kt. Это осознанное дублирование: общего кода у наших
 оболочек нет, а класть правила показа в движок нельзя — они про интерфейс, а не про решение. Список
 случаев тот же, и менять его надо в двух местах разом: уровень → как звучит, `cleared` → снять, сверка
 с `activeAlarms`, ключ по `id`.
 */
final class Тревоги: NSObject {

    static let общие = Тревоги()

    private let категория = "sugarlife.тревога"
    private let действиеПонял = "sugarlife.понял"
    private let ключОчереди = "sugarlife.понял.очередь"
    /// Сутки: ответ, не доехавший за это время, отвечает на тревогу, которой давно нет (#482).
    private let живётОчередь: TimeInterval = 24 * 60 * 60

    /// Что уже показано: id тревоги → уровень. По нему снимаем лишнее и решаем, звучать ли снова.
    private var показано: [String: String] = [:]
    private var дежуритДвижок = false
    private var сирена: AVAudioPlayer?

    /// Отправитель интентов в движок. Ставит плагин: сам движок здесь не виден и не должен быть.
    var отправить: ((String) -> String)?
    /// Короткая запись в журнал движка. Ставится плагином вместе с `отправить`.
    var вЖурналДвижка: ((_ уровень: String, _ событие: String) -> Void)?
    /* Куда вести человека, нажавшего на уведомление (#524). Ставит плагин; здесь мы только зовём —
       кто и как открывает раздел, тревогам знать незачем. */
    var повестиВ: ((String) -> Void)?

    // MARK: — запуск

    /// Категория с кнопкой «Понял» и делегат. Зовётся один раз при старте плагина.
    func настроить() {
        let понял = UNNotificationAction(identifier: действиеПонял, title: "Понял", options: [])
        let к = UNNotificationCategory(identifier: категория, actions: [понял],
                                       intentIdentifiers: [], options: [])
        UNUserNotificationCenter.current().setNotificationCategories([к])
        UNUserNotificationCenter.current().delegate = self
        /* ДОКЛАДЫВАТЬ ПРИ СМЕНЕ МАРШРУТА, А НЕ ТОЛЬКО ПРИ ЗАПУСКЕ (#569).

           Человек садится в машину с уже работающим приложением: если маршрут отдан один раз при
           старте, движок так и будет считать, что звук идёт в телефон, и правила про дорогу снова не
           сработают — только теперь молча и на ровном месте.

           Подписка дешёвая, а событие редкое: воткнули наушники, подключились к магнитоле, вынули. */
        NotificationCenter.default.addObserver(
            self, selector: #selector(маршрутСменился),
            name: AVAudioSession.routeChangeNotification, object: nil)
        разгрестиОчередь()
    }

    @objc private func маршрутСменился() { доложитьОДоставке() }

    /// Спросить разрешение на уведомления. Без него тревог не будет вовсе — и об этом скажет доклад.
    func спроситьРазрешение(_ готово: ((Bool) -> Void)? = nil) {
        UNUserNotificationCenter.current().requestAuthorization(options: [.alert, .sound, .badge]) { ок, _ in
            DispatchQueue.main.async {
                self.доложитьОДоставке()
                готово?(ок)
            }
        }
    }

    /// Первый и единственный раз: система всё равно покажет диалог только однажды.
    private func спроситьРазрешениеОдинРаз() {
        UNUserNotificationCenter.current().getNotificationSettings { [weak self] s in
            guard s.authorizationStatus == .notDetermined else { return }
            self?.спроситьРазрешение()
        }
    }

    /// Проверочная тревога: тот же путь, что у настоящей будящей — уведомление и свой звук.
    func проверочная() {
        let к = UNMutableNotificationContent()
        /* Проверку запускают из «Охраны» — туда и возвращаем (#524). */
        к.userInfo = ["цель": "охрана"]
        к.title = "Проверка тревоги"
        к.body = "Так будет звучать тревога о низком сахаре. Это проверка — сахар в порядке."
        к.sound = .default
        к.categoryIdentifier = категория
        if #available(iOS 15.0, *) { к.interruptionLevel = .timeSensitive }
        UNUserNotificationCenter.current().add(
            UNNotificationRequest(identifier: "sugarlife.проверка", content: к, trigger: nil))
        зазвучать()
        /* Сама себя гасит через пять секунд: проверка, которую надо выключать руками, пугает больше,
           чем показывает. Настоящая тревога звучит до «понял» — в этом и разница. */
        DispatchQueue.main.asyncAfter(deadline: .now() + 5) { [weak self] in self?.замолчать() }
    }

    // MARK: — снимок

    /// Снимок пришёл: показать новое, снять лишнее, отдать накопившиеся «понял».
    func приСнимке(_ json: String) {
        guard let data = json.data(using: .utf8),
              let корень = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { return }

        let правил = (корень["alarmRules"] as? [[String: Any]])?.count ?? 0
        let ведёт = ядроУмеет(корень["bridgeRevision"] as? String) && правил > 0
        if ведёт != дежуритДвижок {
            NSLog("SugarLife: тревоги \(ведёт ? "ведёт движок" : "движок не считает")")
            if !ведёт { показано.keys.forEach { снять($0) }; замолчать() }
            дежуритДвижок = ведёт
            /* Разрешение спрашиваем ЗДЕСЬ, а не при первом запуске приложения. Системный диалог
               показывается один раз за установку: спросить его на пустом экране, до того как человек
               завёл источник данных, — значит потратить единственную попытку на вопрос без контекста.
               Здесь у движка уже есть правила, то есть следить действительно есть за чем. */
            if ведёт { спроситьРазрешениеОдинРаз() }
        }
        guard ведёт else { return }

        let события = (корень["alarmEvents"] as? [[String: Any]]) ?? []
        for с in события { применить(с) }

        /* Сверка со списком висящих — для тех тревог, о которых «отбоя» не приходило вовсе: движок
           перезапустился, сменился профиль. Списка нет в снимке — не трогаем ничего: отсутствующий
           список и пустой означают разное. */
        if let активные = корень["activeAlarms"] as? [String] {
            let живые = Set(активные)
            for id in показано.keys where !живые.contains(id) { снять(id) }
        }
        разгрестиОчередь()
    }

    /* Своя логика решений у нас не осталась, поэтому старое ядро означает «тревог нет вовсе».
       Проверяем ревизию прямо: пустой список правил бывает и у нового. */
    private func ядроУмеет(_ ревизия: String?) -> Bool {
        let части = (ревизия ?? "").split(separator: ".")
        guard части.count >= 2, let с = Int(части[0]), let м = Int(части[1]) else { return false }
        return с > 1 || (с == 1 && м >= 30)
    }

    /*
     ИСПОЛНЕНИЕ, А НЕ РЕШЕНИЕ (мост 1.31…1.35, #482).

     Здесь стоял свой светофор: уровень → «молчим / тихо / обычно / будить». Рядом жил такой же у
     движка — с поправками на сон, машину, доставку и ранг среди одновременных событий, которых у
     оболочки нет и быть не может. Два решения об одном разошлись в первую же ночь: красная тревога
     прозвучала обычным уведомлением, и человек услышал «просто музыку».

     Теперь решение приходит готовым и исполняется дословно. Уровень остаётся только для наших слов.
     */
    private struct Приказ {
        let звучать: Bool          // sound: одно событие из нескольких звучит, остальные молча
        let громкость: String      // loudness: show | shout | yell
        let звук: String           // soundKind: none | soft | sharp
        let пробиваться: Bool      // bypassQuiet
        let повторять: Bool        // repeatUntilAck
        let инаяВнешность: Bool    // distinctLook: отказ охраны выглядит иначе, чем событие о сахаре
        let громкостьДо: Int?      // raiseVolumeTo, в машине nil
        let вМашине: Bool          // inCar
        let слова: String?         // words: готовая фраза, за рулём другая

        init(_ с: [String: Any]) {
            звучать = (с["sound"] as? Bool) ?? true
            громкость = (с["loudness"] as? String) ?? "show"
            звук = (с["soundKind"] as? String) ?? "none"
            пробиваться = (с["bypassQuiet"] as? Bool) ?? false
            повторять = (с["repeatUntilAck"] as? Bool) ?? false
            инаяВнешность = (с["distinctLook"] as? Bool) ?? false
            громкостьДо = с["raiseVolumeTo"] as? Int
            вМашине = (с["inCar"] as? Bool) ?? false
            слова = с["words"] as? String
        }

        /// Своим звуковым потоком — только «орать»: он и есть то единственное, что слышно на
        /// беззвучном телефоне. Играть его для «кричать» значит будить там, где обещали не будить.
        var сирена: Bool { звучать && громкость == "yell" }
        /// Уведомление со звуком системы — «кричать» и выше.
        var звукУведомления: Bool { звучать && громкость != "show" }
    }

    private func применить(_ с: [String: Any]) {
        guard let id = с["id"] as? String, !id.isEmpty else { return }
        let что = (с["what"] as? String) ?? "started"
        if что == "cleared" { снять(id); return }

        let приказ = Приказ(с)
        /* «Показать молча» — это всё равно показать: событие уровня «Состояние» видно на экране
           приложения, и уведомления для него не нужно, а вот заметка в шторке нужна. Разбирает это
           движок; наше дело — не выдумывать здесь исключений. */
        показать(id: id, с: с, приказ: приказ)
        показано[id] = приказ.громкость
    }

    // MARK: — показ

    private func показать(id: String, с: [String: Any], приказ: Приказ) {
        let нуженОтвет = (с["needsAck"] as? Bool) ?? false
        let наши = слова(id: id, уровень: (с["level"] as? String) ?? "", mmol: с["mmol"] as? Double)

        let к = UNMutableNotificationContent()
        /* ЦЕЛЬ ПЕРЕХОДА КЛАДЁМ В САМО УВЕДОМЛЕНИЕ (#524). Оно знает, о чём оно, — и это
           единственный момент, когда знание есть: когда человек нажмёт, разобрать «о чём была та
           тревога» будет уже нечем, кроме id. */
        к.userInfo = ["цель": цельПоТревоге(id)]
        /* СЛОВА ДВИЖКА ГЛАВНЕЕ НАШИХ (rev ≥ 1.31). Они учитывают обстановку — за рулём совет другой:
           дома надо съесть, в машине сначала остановиться. Свои формулировки остаются запасом на
           случай, если поле не приехало: молчаливая тревога хуже неточно названной. */
        if let слова = приказ.слова, !слова.isEmpty {
            к.title = наши.0
            к.body = слова
        } else {
            к.title = наши.0
            к.body = наши.1
        }
        к.sound = приказ.звукУведомления ? .default : nil
        if нуженОтвет { к.categoryIdentifier = категория }
        if #available(iOS 15.0, *) {
            /* Срочный уровень — по приказу пробиваться, а не по нашей догадке об уровне: именно он
               проводит уведомление сквозь «Не беспокоить». */
            к.interruptionLevel = приказ.пробиваться ? .timeSensitive : .active
        }

        let запрос = UNNotificationRequest(identifier: id, content: к, trigger: nil)
        UNUserNotificationCenter.current().add(запрос)

        /* В ЖУРНАЛ — ПРИКАЗ, а не наше толкование. Когда ночью тревога прозвучит не так, вопрос
           будет один: движок велел или мы не исполнили. По этой строке ответ виден сразу.

           И ИМЕННО В ЖУРНАЛ ДВИЖКА, а не только в NSLog. Строка тут была, но жила там, где её видит
           лишь тот, кто в ту минуту держит телефон подключённым к Xcode. Владелец наутро спросил,
           почему тревога пришла без звука, — и ответить оказалось нечем: приказ был, а прочитать
           его негде. Ровно правило 8 в docs/поверхности-показа.md, и мы нарушили его сами, написав
           это правило неделю назад. */
        let приказСловами = "\(приказ.громкость)/\(приказ.звук), звучать \(приказ.звучать), "
            + "пробиваться \(приказ.пробиваться), громкость до \(приказ.громкостьДо.map(String.init) ?? "—")"
            + (приказ.вМашине ? ", в машине" : "")
        NSLog("SugarLife: тревога \(id) — " + приказСловами)
        вЖурналДвижка?("Info", "приказ \(id): " + приказСловами)
        /* И САМИ СЛОВА. Владелец прочитал на телефоне «высокий сахар долго, а инсулина нет» — при
           том, что инсулин был. Разбирать пришлось по его пересказу: приказ мы записали, а фразу,
           которую человек увидел, нет. Спорить о том, что именно было написано, — худший способ
           разбирать медицинское сообщение.

           Фраза приходит от движка; храним её только здесь, в журнале на устройстве. Наружу
           журнал не уходит: в нём числа человека. */
        if let слова = приказ.слова, !слова.isEmpty {
            вЖурналДвижка?("Info", "слова \(id): " + слова)
        }

        /* ОБА ИСХОДА, А НЕ ОДИН. Пишем и то, что своим звуком играем, и то, что не играем и почему.
           Запись при одном исходе делает тишину двусмысленной: её отсутствие означало бы и «не
           сработало», и «приказ был тихий», а это разные беды и разные виноватые. */
        if приказ.сирена {
            зазвучать(резкий: приказ.звук == "sharp", доПроцента: приказ.вМашине ? nil : приказ.громкостьДо)
        } else {
            вЖурналДвижка?("Info", "своим звуком не играем: приказ \(приказ.громкость)"
                + " — звук отдан системе, а он идёт на громкости звонка, и её мы поднять не можем")
        }
    }

    private func снять(_ id: String) {
        показано.removeValue(forKey: id)
        UNUserNotificationCenter.current().removePendingNotificationRequests(withIdentifiers: [id])
        UNUserNotificationCenter.current().removeDeliveredNotifications(withIdentifiers: [id])
        if показано.values.contains(where: { $0 == "yell" }) == false { замолчать() }
    }

    /*
     Куда ведёт эта тревога.

     Человеку нужен не «экран приложения», а то место, где написано, что делать: про сахар — на
     «Сегодня», где стоит полоса с «Понял»; про молчание прибора — в карточку прибора; про резервуар
     и батарею — к помпе; про саму охрану — в «Охрану».

     Незнакомый id ведёт на «Сегодня»: главный экран — не ответ, но и не тупик.
     */
    private func цельПоТревоге(_ id: String) -> String {
        let основа = id.split(separator: ":").first.map(String.init) ?? id
        if id.contains("не-разбудит") { return "охрана" }
        if основа.hasPrefix("молчание") || основа.hasPrefix("залип") { return "сенсор" }
        if основа.hasPrefix("резервуар") || основа.hasPrefix("батаре") || основа.hasPrefix("подача") { return "помпа" }
        return "сегодня"
    }

    /* СЛОВА ВРЕМЕННО НАШИ (#482): у события в контракте формулировки нет. Табличка узкая намеренно, а
       незнакомый id получает честное общее слово, а не выдуманное частное. Ядру отправлен запрос на
       `words` — по той же причине, по какой они запретили нам сочинять формулировки для `learning`. */
    private func слова(id: String, уровень: String, mmol: Double?) -> (String, String) {
        let основа = id.split(separator: ":").first.map(String.init) ?? id
        let сахар = mmol.map { String(format: "%.1f", $0).replacingOccurrences(of: ".", with: ",") + " ммоль" }
        let заголовок: String
        if id.contains("не-разбудит") || уровень == "ОбещаниеНарушено" {
            заголовок = "Тревога может не разбудить"
        } else if основа.hasPrefix("гипо") { заголовок = "Низкий сахар" }
        else if основа.hasPrefix("высок") { заголовок = "Высокий сахар" }
        else if основа.hasPrefix("прогноз") || основа.contains("падени") { заголовок = "Сахар падает" }
        else if основа.hasPrefix("молчание") { заголовок = "Данных нет" }
        else if основа.hasPrefix("залип") { заголовок = "Линия не меняется" }
        else if основа.hasPrefix("подача") { заголовок = "Подача инсулина стоит" }
        else if основа.hasPrefix("резервуар") { заголовок = "Резервуар заканчивается" }
        else if основа.hasPrefix("батаре") { заголовок = "Батарея помпы" }
        else { заголовок = "Тревога" }

        /* «Тревога может не разбудить» с сахаром в тексте читается как тревога ПРО САХАР, и человек
           закрывает её, решив, что 10,2 не повод (#482). Беда здесь другая — в самой доставке. */
        let текст: String
        if заголовок == "Тревога может не разбудить" {
            текст = "Проверьте «Охрану»: сейчас разбудить не сможем"
        } else {
            текст = сахар ?? (заголовок == "Тревога" ? "Приложение сообщает: \(id)" : "Приложение сообщает о состоянии")
        }
        return (заголовок, текст)
    }

    // MARK: — звук, который слышно на беззвучном

    private func зазвучать(резкий: Bool = true, доПроцента: Int? = nil) {
        guard сирена == nil else { return }
        do {
            /* Та же категория, что у фонового бодрствования, но БЕЗ `.mixWithOthers`: тревога имеет
               право приглушить музыку — иначе её не услышат именно тогда, когда она нужна. */
            try AVAudioSession.sharedInstance().setCategory(.playback, options: [.duckOthers])
            try AVAudioSession.sharedInstance().setActive(true)
        } catch {
            /* ТРЕВОГА НЕ ПРОЗВУЧАЛА — И ОБ ЭТОМ ОБЯЗАН ОСТАТЬСЯ СЛЕД (#593).

               Здесь была только строка в NSLog. То есть звук не пошёл, человек не проснулся, а
               узнать об этом мог лишь тот, кто в ту минуту держал телефон подключённым к Xcode.
               Наутро разбирать нечего.

               Из всех молчаливых отказов этот дороже прочих: остальные стоят неудобства, этот —
               непрозвучавшей тревоги. */
            NSLog("SugarLife: аудио-сессия занята — тревога прозвучит только уведомлением (\(error))")
            вЖурналДвижка?("Error", "звук тревоги не пошёл: сессию не отдали")
            return
        }
        /* Громкость поднимаем ДО игры: свой звук пробивает беззвучный режим, но не убавленный
           уровень — на четверти громкости тревога звучит на четверть (Громкость.swift).

           НАСКОЛЬКО поднимать, решает движок (raiseVolumeTo). В машине он присылает пусто — уровень
           в колонках выставил человек под дорогу, и резкий подъём там опаснее, чем недосказать. */
        if let до = доПроцента { Громкость.общая.поднять(до: Float(до) / 100) }
        сирена = try? AVAudioPlayer(data: сигнал(резкий: резкий))
        сирена?.numberOfLoops = -1      // до «понял» или отбоя: тревога, замолкающая сама, не тревога
        сирена?.volume = 1
        let пошёл = сирена?.play() ?? false
        /* ФАКТ, А НЕ НАМЕРЕНИЕ (правило 9). `play()` возвращает, началось ли воспроизведение, и
           раньше мы этот ответ выбрасывали: в журнале стоял бы «сыграли» и тогда, когда не сыграли.
           Уровень громкости пишем свой, измеренный, — по нему видно, услышат ли вообще. */
        вЖурналДвижка?(пошёл ? "Info" : "Error",
                       пошёл ? "звук тревоги пошёл, громкость \(Int(Громкость.общая.сейчас * 100))%"
                             : "звук тревоги не пошёл: плеер не начал играть")
    }

    private func замолчать() {
        сирена?.stop()
        сирена = nil
        /* Уровень возвращаем всегда: поднять и забыть — значит утром включить музыку в наушниках
           на полной громкости. */
        Громкость.общая.вернуть()
        /* И КАТЕГОРИЮ СЕССИИ — ТОЖЕ. Тревога брала её с «приглушить остальных», а возвращала только
           громкость: после первой же ночной тревоги музыка человека звучала тише до перезапуска
           приложения. Найдено по ночному журналу, где после каждой тревоги приложение умирало в
           течение трёх минут — три случая из трёх.

           Правильную категорию знает опора, она её хозяйка. Наше дело — сказать, что мы отзвучали. */
        ФоновоеБодрствование.shared.вернутьОбщийРежим()
    }

    /* Сигнал строим в коде, а не носим файлом — как и тишину для бодрствования (#388): так его видно
       целиком и не надо объяснять ресурс тому, кто откроет проект. Две секунды: секунда тона 880 Гц и
       секунда паузы, чтобы звук читался как тревога, а не как гул. */
    /*
     ДВА РАЗНЫХ СИГНАЛА, А НЕ ОДИН ПОГРОМЧЕ (мост 1.35).

     Один звук на всё приучает: человек перестаёт отличать «резервуар кончается» от «сахар три и
     две», не глядя на экран. Резкий — короткие рубленые импульсы на высоком тоне, их слышно сквозь
     сон; мягкий — ровный низкий тон, он сообщает, а не поднимает.
     */
    private func сигнал(резкий: Bool) -> Data {
        let частота = 44100.0, длительность = 2.0
        let тон = резкий ? 1180.0 : 660.0
        let всего = Int(частота * длительность)
        var сэмплы = [Int16](repeating: 0, count: всего)
        for i in 0..<всего {
            let t = Double(i) / частота
            guard t < 1.0 else { break }
            /* Плавные края: щелчок в начале и конце режет слух и звучит как поломка динамика. */
            let края = min(1.0, min(t, 1.0 - t) * 40)
            /* Резкий рубится на импульсы по 120 мс с паузами: непрерывный тон той же громкости
               мозг отфильтровывает как фон, прерывистый — нет. */
            let импульс = резкий ? (t.truncatingRemainder(dividingBy: 0.24) < 0.12 ? 1.0 : 0.0) : 1.0
            сэмплы[i] = Int16(sin(2 * .pi * тон * t) * 12000 * края * импульс)
        }
        var d = Data()
        func u32(_ v: UInt32) { withUnsafeBytes(of: v.littleEndian) { d.append(contentsOf: $0) } }
        func u16(_ v: UInt16) { withUnsafeBytes(of: v.littleEndian) { d.append(contentsOf: $0) } }
        let байтДанных = UInt32(сэмплы.count * 2)
        d.append(contentsOf: Array("RIFF".utf8)); u32(36 + байтДанных)
        d.append(contentsOf: Array("WAVE".utf8))
        d.append(contentsOf: Array("fmt ".utf8)); u32(16); u16(1); u16(1)
        u32(UInt32(частота)); u32(UInt32(частота) * 2); u16(2); u16(16)
        d.append(contentsOf: Array("data".utf8)); u32(байтДанных)
        сэмплы.withUnsafeBufferPointer { d.append(UnsafeBufferPointer(start: $0.baseAddress, count: $0.count)) }
        return d
    }

    // MARK: — «понял» и его очередь

    /* Ответ человека записываем ДО попытки отдать. Уведомление переживает смерть процесса: человек
       жмёт «понял» ночью, движка в памяти может не быть, и потерянное нажатие означает продолжение
       эскалации после ответа — то есть кнопку, которая соврала. */
    private func запомнитьПонял(_ id: String, когдаМс: Double) {
        var очередь = UserDefaults.standard.dictionary(forKey: ключОчереди) as? [String: Double] ?? [:]
        if очередь[id] == nil { очередь[id] = когдаМс }   // повторное нажатие не двигает время ответа
        UserDefaults.standard.set(очередь, forKey: ключОчереди)
    }

    private func разгрестиОчередь() {
        var очередь = UserDefaults.standard.dictionary(forKey: ключОчереди) as? [String: Double] ?? [:]
        guard !очередь.isEmpty else { return }
        let сейчас = Date().timeIntervalSince1970 * 1000
        for (id, когда) in очередь {
            /* Просроченное выбрасываем: оно отвечает на тревогу, которая давно кончилась, а
               доставленное через неделю погасило бы не ту. */
            if сейчас - когда > живётОчередь * 1000 { очередь.removeValue(forKey: id); continue }
            let json = "{\"type\":\"acknowledgeAlarm\",\"alarmId\":\(jsonStr(id)),\"atMs\":\(Int(когда))}"
            let ответ = отправить?(json) ?? ""
            /* «Не принято» — законный исход: на ядре без модели тревог такого интента нет вовсе.
               Тогда запись остаётся и уедет со следующей попыткой. */
            if ответ.contains("\"accepted\":true") { очередь.removeValue(forKey: id) }
        }
        UserDefaults.standard.set(очередь, forKey: ключОчереди)
    }

    // MARK: — что мы можем прямо сейчас

    /**
     КУДА СЕЙЧАС ИДЁТ ЗВУК (`route`, контракт 1.31 — SugarLife#569, ядро #123).

     Поле живёт в контракте с 1.31, движок его читает, и на нём держится весь класс правил про дорогу:
     в машине не поднимать громкость, не разворачивать тревогу на весь экран, не держать звуковую
     опору — она перехватит магнитолу. Но слать его не начала ни одна платформа, и правила не
     срабатывали НИ РАЗУ. Сверка контракта такое не ловит: поле читается, интент есть — просто никто
     его не отправлял. В журнале с телефона владельца это видно дословно: `"route":"phone"` всегда.

     ОПРЕДЕЛЯЕМ МАРШРУТ, А НЕ ПЕРЕМЕЩЕНИЕ. Едет ли человек и водитель ли он — мы не знаем и знать не
     должны: телефон отвечает только на вопрос «куда выведен звук». Магнитола отвечает `carAudio` и
     когда машина стоит, и это правильно — правило про перехват радио от скорости не зависит.

     `bluetoothA2DP` считаем наушниками намеренно. Это может быть и колонка в комнате, и гарнитура, но
     не магнитола: у неё свой тип. Ошибиться в сторону «наушники» безопаснее — правила для наушников
     мягче правил для машины, и лишний раз промолчать хуже, чем лишний раз перехватить радио.
     */
    static func маршрутЗвука() -> String {
        let выходы = AVAudioSession.sharedInstance().currentRoute.outputs
        if выходы.contains(where: { $0.portType == .carAudio }) { return "car" }
        if выходы.contains(where: {
            $0.portType == .headphones || $0.portType == .bluetoothA2DP
                || $0.portType == .bluetoothHFP || $0.portType == .bluetoothLE
                || $0.portType == .usbAudio
        }) { return "headphones" }
        if выходы.contains(where: { $0.portType == .builtInSpeaker }) { return "speaker" }
        /* Пусто бывает, пока сессия не активна: тогда честнее сказать «телефон», чем выдумать. */
        return "phone"
    }

    /**
     Доложить движку, чем располагаем (`reportDelivery`, контракт 1.30, подробности — 1.49).

     На айфоне сводка `canWake` держится на одном: живём ли мы в фоне. Уведомление, которое некому
     показать, не разбудит никого.

     ПОДРОБНОСТИ ВАЖНЕЕ СВОДКИ (#588). «Доставить нечем» — приговор без объяснения: человек идёт
     гулять по системным настройкам наугад, вечером, когда собирался спать. Движку нужны ФАКТЫ, а не
     наш вывод: что именно отобрано. Ответ он соберёт сам и словами, одинаковыми на обеих платформах.

     ЧТО МЫ ЧЕСТНО МОЖЕМ СКАЗАТЬ, А ЧТО НЕТ:

      · `notificationsEnabled` — знаем точно, спрашиваем систему.
      · `dndAccess` — на айфоне это право на СРОЧНЫЕ уведомления: только оно пробивает «Не
        беспокоить». Личной команде Apple его не выдаёт, но спрашиваем всё равно: сборка может быть
        и подписана иначе.
      · `audioHeld` — держим ли звуковой поток. Наш единственный способ звучать поверх беззвучного.
      · `batteryPercent` — мёртвый телефон не будит, это тоже «не разбудим».

     Чего НЕ шлём и почему: `fullScreenAllowed` и `alarmChannelIntact` — понятия Android (полноэкранное
     намерение и канал уведомлений), на iOS им нет соответствия. Прислать их выдуманными значило бы
     сказать движку то, чего мы не знаем; поля необязательные, и молчание здесь честнее догадки.
     */
    func доложитьОДоставке() {
        UNUserNotificationCenter.current().getNotificationSettings { s in
            let разрешено = s.authorizationStatus == .authorized || s.authorizationStatus == .provisional
            /* ФАКТ, А НЕ НАМЕРЕНИЕ (#593). Здесь стояло `режим != .выключено` — то есть чего человек
               ХОТЕЛ. Держим ли мы звук на самом деле, это отдельный вопрос: сессию могли отобрать
               звонком или другим приложением, и тогда опоры нет при включённом выключателе.

               Движок строит на этом обещание разбудить. Сообщить намерение вместо состояния значит
               ошибиться в сторону опасности: человек ляжет спать, считая, что его разбудят. */
            let хотели = ФоновоеБодрствование.shared.режим != .выключено
            let живём = ФоновоеБодрствование.shared.держимЗвук
                || (хотели && UIApplication.shared.applicationState != .background)
            let ответ = !разрешено ? "no" : (живём ? "yes" : "no")
            /* «ЕСТЬ ЛИ ДОСТУП К ТИХОМУ РЕЖИМУ» — ЭТО НЕ CRITICAL ALERTS (SugarLife#685).

               Здесь стояло `s.criticalAlertSetting == .enabled`, и это подменяло вопрос. Critical
               Alerts — право, которое человек включить НЕ МОЖЕТ: оно требует платного аккаунта
               разработчика и отдельного одобрения Apple. У нас его нет и не будет, значит поле
               уезжало движку вечным `false`.

               Движок делал из этого честный вывод «не докричимся» и просил починить доступ. Чинить
               было нечего: единственное, что человеку доступно на iOS, — добавить приложение в
               «Разрешённые уведомления» своего режима Фокусирования. Владелец это давно сделал, а
               просьба висела и висела. Неснимаемая просьба хуже отсутствующей: она приучает
               пролистывать предупреждения не глядя, и однажды пролистают настоящее.

               Прочитать список Фокуса нельзя никаким API. Поэтому спрашиваем человека и помним его
               ответ. Не ответил — поля НЕ ШЛЁМ вовсе: контракт прямо говорит, что `null` значит
               «оболочка не сообщает», причину движок тогда не назовёт и придумывать не станет. Это
               честнее, чем отвечать за человека. */
            let фокус = UserDefaults.standard.object(forKey: "sl.focus-allowed") as? Bool
            /* Заряд включаем только на время вопроса: постоянное слежение за батареей ради одного
               числа в докладе — плата, которой можно не платить. */
            let былоСлежение = UIDevice.current.isBatteryMonitoringEnabled
            UIDevice.current.isBatteryMonitoringEnabled = true
            let заряд = UIDevice.current.batteryLevel
            UIDevice.current.isBatteryMonitoringEnabled = былоСлежение
            let маршрут = Тревоги.маршрутЗвука()
            /* ИГРАЕТ ЛИ УЖЕ ЧТО-ТО ЧЕРЕЗ ЭТОТ ВЫХОД (мост 1.53, SugarLifeCore#155).

               Факт, который видим только мы, и без него правило про машину слишком грубое. Магнитола
               играет радио СВОИМ источником — телефон при этом молчит, и наша тишина перетянет выход
               на себя. А когда человек слушает музыку С ТЕЛЕФОНА, магнитола уже переключена на нас:
               красть нечего, и опору можно держать — то есть баннер в машине может жить.

               Что из этого следует, решает движок: своё правило мы вчера сняли и заводить второе не
               станем. Наше дело — сообщить факт и вовремя переспросить.

               СПРАШИВАЕМ НЕ СЕССИЮ, А ДОЗОР (мост 1.62). Мгновенный `isOtherAudioPlaying` мерцает
               в такт нашему собственному пульсу тишины, и здесь мы читали его мимо гистерезиса,
               который завели именно против этого мерцания. Доклад бывает не только от дозора —
               маршрут сменился, приложение развернули, — и в такой миг мы увозили движку фазовый
               артефакт вместо факта. Устоявшееся значение хранит ФоновоеБодрствование, оно же
               помнит, с какого момента звук держится. */
            let чужойЗвук = ФоновоеБодрствование.shared.чужойЗвукИдёт
            let чужойЗвукС = ФоновоеБодрствование.shared.чужойЗвукСМс

            var поля = "\"canWake\":\(jsonStr(ответ)),\"tickPrecisionMin\":0,\"route\":\(jsonStr(маршрут))"
            поля += ",\"otherAudioPlaying\":\(чужойЗвук)"
            /* Момент — только когда он есть: движку сказано, что при `null` он считает началом
               первый отчёт со звуком, и это ровно прежнее поведение. */
            if let с = чужойЗвукС { поля += ",\"otherAudioSinceMs\":\(с)" }
            поля += ",\"notificationsEnabled\":\(разрешено)"
            if let ф = фокус { поля += ",\"dndAccess\":\(ф)" }
            поля += ",\"audioHeld\":\(живём)"
            /* Отрицательный уровень означает «система не сказала» — тогда молчим, а не шлём минус. */
            if заряд >= 0 { поля += ",\"batteryPercent\":\(Int((заряд * 100).rounded()))" }

            _ = self.отправить?("{\"type\":\"reportDelivery\",\(поля)}")
            NSLog("SugarLife: доложили о доставке — \(ответ), звук идёт в \(маршрут), уведомления \(разрешено), тихий режим \(фокус.map(String.init) ?? "не спрашивали")")
        }
    }
}

// MARK: — ответ человека

extension Тревоги: UNUserNotificationCenterDelegate {

    /// Показываем и когда приложение открыто: тревога, видимая только в свёрнутом виде, — половина тревоги.
    func userNotificationCenter(_ center: UNUserNotificationCenter,
                                willPresent notification: UNNotification,
                                withCompletionHandler completionHandler:
                                @escaping (UNNotificationPresentationOptions) -> Void) {
        if #available(iOS 14.0, *) { completionHandler([.banner, .sound, .list]) }
        else { completionHandler([.alert, .sound]) }
    }

    func userNotificationCenter(_ center: UNUserNotificationCenter,
                                didReceive response: UNNotificationResponse,
                                withCompletionHandler completionHandler: @escaping () -> Void) {
        let id = response.notification.request.identifier
        if response.actionIdentifier == действиеПонял {
            запомнитьПонял(id, когдаМс: Date().timeIntervalSince1970 * 1000)
            снять(id)
            замолчать()
            разгрестиОчередь()
        } else if response.actionIdentifier == UNNotificationDefaultActionIdentifier {
            /* Нажали на само уведомление — ведём туда, о чём оно (#524). Раньше приложение
               открывалось там, где человек был в прошлый раз, и он искал руками. */
            if let цель = response.notification.request.content.userInfo["цель"] as? String {
                повестиВ?(цель)
            }
            /* Открыл приложение — сирену глушим, но «понял» НЕ засчитываем: это разные вещи. Увидеть
               тревогу и подтвердить её — два разных ответа, и решать за человека второй мы не вправе.
               Кнопка ждёт его на «Сегодня» полосой, которую видно сразу (ui/ЖивыеТревоги.tsx). */
            замолчать()
        }
        completionHandler()
    }
}
