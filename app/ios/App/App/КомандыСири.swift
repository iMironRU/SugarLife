/*
 КОМАНДЫ SIRI: ПОВЕРХНОСТЬ НАША, СОДЕРЖАНИЕ — ДВИЖКА (SugarLife#510).

 Владелец выбрал две первые: «какой у меня сахар» и «понял». Обе доступны без единого нового поля
 в контракте — и это не совпадение, а условие: своей логики за командой быть не может, иначе
 появится второй ответ на тот же вопрос. Ровно из-за этого тревоги уехали в движок (#482).

 ГЛАВНОЕ ОГРАНИЧЕНИЕ, ИЗ КОТОРОГО ВЫВЕДЕНО ВСЁ ОСТАЛЬНОЕ: команду зовут тогда, когда приложение
 может быть выгружено. Поднимать ради ответа движок — значит заставлять человека ждать секунды на
 вопрос, ответ на который уже лежит готовым. Поэтому:

 - «какой сахар» читает ОБЩУЮ ЗАПИСЬ — ту же, из которой живёт виджет. Она пишется при каждом
   показании и переживает смерть процесса;
 - «понял» кладёт ответ в ОЧЕРЕДЬ (`Тревоги.понялПоказанные`) — тем же путём, которым работает
   кнопка «Понял» в самом уведомлении. Ответ записывается ДО попытки отдать движку: человек жмёт
   ночью, движка в памяти может не быть, а потерянное нажатие означает продолжение эскалации после
   ответа, то есть кнопку, которая соврала.

 ВОЗРАСТ В ОТВЕТЕ ОБЯЗАТЕЛЕН. «6,3» голосом без «две минуты назад» — то же враньё, что число без
 возраста на экране блокировки (#500). Поэтому возраст говорится всегда, а не только когда он
 велик.

 ЕДИНИЦ В ОТВЕТЕ НЕТ, И ЭТО НАМЕРЕННО. Общая запись хранит уже отформатированное число, но не
 хранит, в чём оно: у человека на мг/дл там «113», у нас «6,3». Сказать «ммоль» наугад — соврать
 тому, кто выбрал другие единицы; молчание тут честнее. Появится единица в записи — скажем и её.

 ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: ничего, что меняет подачу. В Lite таких команд нет не потому, что мы
 их не написали, а потому что исполнять их нечем.
 */

@available(iOS 16.0, *)
struct КакойСахар: AppIntent {
    static var title: LocalizedStringResource = "Какой у меня сахар"
    static var description = IntentDescription("Последнее показание и сколько ему минут.")
    /* Приложение не открываем: ответ голосом на заблокированном телефоне — весь смысл команды. */
    static var openAppWhenRun = false

    func perform() async throws -> some IntentResult & ProvidesDialog {
        guard let с = ОбщаяЗапись.прочитать(), !с.значение.isEmpty else {
            return .result(dialog: "Показаний пока нет. Откройте приложение.")
        }
        let возраст = Date().timeIntervalSince1970 - с.когдаМс / 1000
        let фраза = "\(с.значение), \(словамиВозраст(возраст))"
        /* Стрелку добавляем словом, а не символом: голосом «стрелка вверх» не читается, а на
           карточке ответа символ выглядит обрывком. Нет стрелки — не выдумываем. */
        let куда = направлениеСловом(с.стрелка)
        return .result(dialog: "\(фраза)\(куда.isEmpty ? "" : ", \(куда)")")
    }
}

@available(iOS 16.0, *)
struct Понял: AppIntent {
    static var title: LocalizedStringResource = "Понял"
    static var description = IntentDescription("Погасить тревогу, не разблокируя телефон.")
    static var openAppWhenRun = false

    func perform() async throws -> some IntentResult & ProvidesDialog {
        let погашено = await Тревоги.понялПоказанные()
        if погашено.isEmpty { return .result(dialog: "Сейчас нет тревог, на которые надо отвечать.") }
        /* Говорим, ЧТО именно погасили: «понял» вслепую опасен — человек мог не знать, что тревог
           было две, и уйти спать, ответив одной фразой на обе. */
        return .result(dialog: "Погасил: \(погашено.joined(separator: ", ")).")
    }
}

@available(iOS 16.0, *)
struct КомандыSugarLife: AppShortcutsProvider {
    static var appShortcuts: [AppShortcut] {
        /* Имя приложения в фразе обязательно — этого требует система. Формы даём разные: человек
           спрашивает как привык, а не как записано в документации. */
        AppShortcut(intent: КакойСахар(),
                    phrases: ["Какой у меня сахар в \(.applicationName)",
                              "Сахар в \(.applicationName)",
                              "Что с сахаром в \(.applicationName)"],
                    shortTitle: "Какой сахар", systemImageName: "drop")
        AppShortcut(intent: Понял(),
                    phrases: ["Понял в \(.applicationName)",
                              "Погаси тревогу в \(.applicationName)"],
                    shortTitle: "Понял", systemImageName: "checkmark.circle")
    }
}

/* Возраст словами. Отдельно от разметки, потому что говорится вслух: «2 мин» вслух не читается. */
func словамиВозраст(_ секунд: TimeInterval) -> String {
    if секунд < 90 { return "только что" }
    let минут = Int((секунд / 60).rounded())
    if минут < 60 { return "\(минут) \(склонение(минут, "минуту", "минуты", "минут")) назад" }
    let часов = Int((секунд / 3600).rounded())
    return "\(часов) \(склонение(часов, "час", "часа", "часов")) назад"
}

func направлениеСловом(_ стрелка: String) -> String {
    switch стрелка.trimmingCharacters(in: .whitespaces) {
    case "⇈": return "быстро растёт"
    case "↑": return "растёт"
    case "↗": return "медленно растёт"
    case "→": return "держится ровно"
    case "↘": return "медленно падает"
    case "↓": return "падает"
    case "⇊": return "быстро падает"
    default: return ""
    }
}

func склонение(_ n: Int, _ одна: String, _ две: String, _ пять: String) -> String {
    let сотня = n % 100, десяток = n % 10
    if сотня >= 11 && сотня <= 14 { return пять }
    if десяток == 1 { return одна }
    if десяток >= 2 && десяток <= 4 { return две }
    return пять
}
