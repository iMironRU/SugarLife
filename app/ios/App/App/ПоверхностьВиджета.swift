import Foundation
import WidgetKit

/* ВИДЖЕТ НА РАБОЧЕМ СТОЛЕ (SugarLife#666).

   Своим файлом — по той же причине, что значок и сводка. Правило записано в коде с августа:
   «одна общая ветка означала бы, что выключенный баннер молча гасит и виджет». Пока код жил в
   общем доме, правило держалось на том, что кто-то его помнит. Двадцать восьмого августа не
   вспомнил никто, и значок со сводкой замолчали вместе с выключенной карточкой (#655).

   Виджет тогда уцелел — его вызов уже стоял отдельной строкой. Теперь у него и дом отдельный.

   Число берём у `Снимок` — там же, где все: две дороги к одному числу расходятся на округлении. */
final class ПоверхностьВиджета {
    static let общая = ПоверхностьВиджета()
    private init() {}

    /* Что уже показано. Отметка своя, не общая с карточкой: общая означала бы, что выключенная
       карточка лишает виджет обновлений.

       ЗАВОДИМ ЕЁ ОТ ТОГО, ЧТО УЖЕ ЛЕЖИТ В СВЯЗКЕ (SugarLife#694).

       Общая запись переживает процесс — она в связке ключей. А эта отметка жила только в памяти и
       на новом процессе была нулём. Значит первая же точка пачки догрузки, а она САМАЯ СТАРАЯ,
       ложилась поверх свежей как текущая.

       Виджет читает запись когда захочет — расписание у него своё. Попав на этот миг, он рисовал
       показание суточной давности и дальше считал возраст от него системным таймером, без нашего
       участия. Владелец видел «Данных нет · 22 ч», потом «1 день 23 ч» — при живом приложении и
       показаниях раз в минуту. Счётчик не врал: он честно считал от того, что мы сами подсунули.

       Отложенная просьба (#712) закрыла случай, когда перерисовку в этот миг просим МЫ. Здесь
       закрывается остальное: система вправе перерисовать сама, и запись не должна уходить назад
       никогда. */
    private lazy var показаноМс: Double = ОбщаяЗапись.прочитать()?.когдаМс ?? 0

    /* ПРОСИМ ПО ДЕЛУ, А НЕ НА КАЖДОЕ ПОКАЗАНИЕ (SugarLife#692).

       Измерено на живом телефоне: показания приходят раз в минуту, 1416 за сутки, и на каждое мы
       звали `reloadTimelines`. У WidgetKit суточный бюджет перерисовок — несколько десятков.
       Полторы тысячи просьб он тратит в первые минуты, а дальше не слушает вовсе: владелец видел
       на рабочем столе число почти восьмиминутной давности при живом приложении.

       Третий раз за проект одна и та же болезнь: живая карточка (применено 59 просьб из 374) и
       `networkBack` (1944 при двенадцати настоящих поводах). Слишком частая просьба обесценивает
       все остальные — система перестаёт различать, какая из них важная.

       Поэтому: смена зоны — сразу, всё прочее — не чаще раза в пять минут. Зона это и есть повод
       смотреть на виджет, а пятая подряд девятка в норме не стоит перерисовки. Плата названа
       честно: в спокойной зоне число может отставать до пяти минут. Отставало восемь и без правила.

       Возраст на виджете при этом правдив ВСЕГДА: его считает система (`Text(_, style: .timer)`),
       без наших обновлений. Устаревает число, а не рассказ о его свежести. */
    private static let НЕ_ЧАЩЕ_СЕК: Double = 5 * 60
    /// Через сколько после последнего снимка считаем пачку догрузки законченной. То же, что у баннера.
    private static let ПАЧКА_УЛЕГЛАСЬ_СЕК: Double = 4
    private var отложенная: DispatchWorkItem?
    private var просилиВ: Date = .distantPast
    private var показаннаяЗона = ""

    /// Куда рассказывать о просьбах. Ставит плагин — сам движок отсюда не виден.
    var вЖурнал: ((String, String) -> Void)?

    func обновить(_ json: String?, историяДвижка: [СахарАтрибуты.ContentState.Точка]) {
        guard let json, let data = json.data(using: .utf8),
              let корень = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let monitor = корень["monitor"] as? [String: Any] else { return }
        let значение = (monitor["glucose"] as? String) ?? ""
        guard !значение.isEmpty, значение != "—" else { return }
        let когдаМс = (monitor["latestAtMs"] as? Double) ?? Date().timeIntervalSince1970 * 1000
        /* ТОЧКА СТАРШЕ ПОКАЗАННОЙ — НЕ НОВОСТЬ. Виджет говорит, что сейчас, а не что было. */
        if когдаМс <= показаноМс { return }
        показаноМс = когдаМс

        let mmol = monitor["glucoseMmol"] as? Double
        /* Ряд тот же, что у баннера, и собирается там же (#562): иначе график на рабочем столе и
           на экране блокировки рисуют разные три часа. */
        let ряд = Снимок.рядДляПоказа(monitor, когдаМс: когдаМс, историяДвижка: историяДвижка)
        let число = String(значение.split(separator: " ").first ?? "")
            .replacingOccurrences(of: ".", with: ",")

        /* РЕШАЕМ ДО ЗАПИСИ, А НЕ ПОСЛЕ. Общую запись обновляем ВСЕГДА: система может перерисовать
           виджет по своему расписанию в любой момент, и застать там вчерашнее число было бы хуже
           всего. Экономим только на просьбах. */
        let зона = Снимок.зонаСахара(mmol)
        let сменаЗоны = зона != показаннаяЗона
        let давно = Date().timeIntervalSince(просилиВ) >= Self.НЕ_ЧАЩЕ_СЕК
        показаннаяЗона = зона

        ОбщаяЗапись.записать(ОбщаяЗапись.Снимок(
            значение: число.isEmpty ? значение : число,
            стрелка: Снимок.стрелкаТренда(monitor["trend"] as? String),
            разница: Снимок.дельта(ряд),
            mmol: mmol,
            зона: зона,
            инсулин: Снимок.инсулинСтрокой(monitor),
            когдаМс: когдаМс,
            ряд: ИсторияСахара.дляПоказа(ряд).map { .init(т: $0.т.timeIntervalSince1970, в: $0.в) }
        ))
        guard сменаЗоны || давно else {
            вЖурнал?("Debug", "виджет: запись обновлена, систему не просим — зона та же и просили \(Int(Date().timeIntervalSince(просилиВ))) с назад")
            return
        }
        /* ЖДЁМ, ПОКА ПАЧКА УЛЯЖЕТСЯ (SugarLife#711, второй заход).

           Первая попытка отсекала точки «назад» — и не помогла: пачка догрузки идёт ПО
           ВОЗРАСТАНИЮ, каждая точка новее предыдущей, и сторож пропускал их все. Журнал показал
           то же самое, что и до правки: зона скачет «выше → коридор → выше» внутри одной секунды,
           шесть просьб к системе.

           Урок был записан у баннера, и не в словах про «устаревшие точки», как я решил в первый
           раз, а в самом приёме: отложенная проверка, которая переводится на каждый новый снимок и
           срабатывает один раз, когда снимки кончились. Пачка любой длины даёт одну просьбу.

           Четыре секунды — те же, что у баннера. Одно число на двоих: разъехавшись, они дали бы
           две разные догадки о том, когда пачка кончилась. */
        отложенная?.cancel()
        let дело = DispatchWorkItem { [weak self] in
            guard let self else { return }
            self.просилиВ = Date()
            WidgetCenter.shared.reloadTimelines(ofKind: "ru.imiron.sugarlife.виджет")
            let возрастМин = Int((Date().timeIntervalSince1970 * 1000 - когдаМс) / 60000)
            /* Возраст показания в самой записи (#694): по нему видно, свежее ли то, что мы
               отдаём виджету. Без него «просим перерисовать» ничего не говорит о том, ЧТО
               он нарисует, — а именно это и оказалось бедой. */
            self.вЖурнал?("Info", "виджет: просим систему перерисовать — \(сменаЗоны ? "сменилась зона на \(зона)" : "прошло пять минут"), показанию \(возрастМин) мин")
        }
        отложенная = дело
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.ПАЧКА_УЛЕГЛАСЬ_СЕК, execute: дело)
    }
}
