import Foundation
import Network

/**
 СЕТЬ ВЕРНУЛАСЬ — СКАЗАТЬ ДВИЖКУ СРАЗУ (SugarLife#544, мост 1.42).

 Облачные потоки движка переподключаются сами, с нарастающей паузой: 5 с, 15 с, 30 с, минута. Пауза
 нужна, чтобы не долбить недоступный сервер, — но она же означает, что после возвращения Wi-Fi мы
 сидим и ждём её конца, теряя пятиминутки на ровном месте. Хуже всего ночью: минута ожидания там
 стоит одного пропущенного показания, а десять — тревоги о молчании, которой не должно было быть.

 Движок для этого принимает `networkBack`: поток жив — интент не делает ничего, поток досиживает
 паузу — просыпается немедленно. Он идемпотентен, поэтому лучше сказать лишний раз, чем промолчать.

 СЛУШАЕМ ЛЮБОЕ ИЗМЕНЕНИЕ, А НЕ ТОЛЬКО ВОЗВРАТ (SugarLife#549, уточнение ядра).

 Сперва мы слали только переход «не было → есть»: повод казался один — разбудить ожидающих. Ядро
 объяснило второй, и он важнее.

 Есть случай, который без нас не различить: сеть с белым списком. Мессенджеры работают, полоски на
 месте, человек уверен, что данные идут, — а до Nightscout не достучаться. Так же выглядят
 гостиничный портал, рабочая сеть и выключенный VPN. Мнение телефона о сети — единственный ключ,
 отличающий «связи нет» от «связь есть, а нас не пускают»: в первом случае движок молчит и ждёт, во
 втором говорит человеку, что проверить.

 Знать это движок может, только если мы рассказываем о состоянии сети регулярно, а не однажды.
 Интент идемпотентен: поток жив — ничего не произойдёт. Смена интерфейса Wi-Fi↔LTE случается
 несколько раз в день, а не в секунду, так что «часто» здесь — это всё равно редко.
 */
final class Сеть {

    static let общая = Сеть()

    private let наблюдатель = NWPathMonitor()
    private let очередь = DispatchQueue(label: "ru.imiron.sugarlife.сеть")
    /* Помним последнее состояние — но лишь чтобы не молчать, когда сеть ПОЯВИЛАСЬ, и не звать
       движок, когда её нет. О самом факте «сеть есть» рассказываем на каждое обновление пути. */
    private var былаСеть = true

    /// Кому сказать. Ставит плагин: сам движок отсюда не виден и не должен быть.
    var сообщить: ((String) -> Void)?

    private init() {}

    func слушать() {
        наблюдатель.pathUpdateHandler = { [weak self] путь in
            guard let self else { return }
            let есть = путь.status == .satisfied
            let вернулась = есть && !self.былаСеть
            self.былаСеть = есть
            /* Нет сети — молчим: сказать «сеть есть» было бы неправдой, а другого смысла у интента
               нет. Движок в этот момент и так ждёт. */
            guard есть else { NSLog("SugarLife: сети нет"); return }
            NSLog(вернулась ? "SugarLife: сеть вернулась — будим облако"
                            : "SugarLife: сеть сменилась — говорим движку, что связь есть")
            self.сообщить?("{\"type\":\"networkBack\"}")
        }
        наблюдатель.start(queue: очередь)
    }

    /* Возвращение приложения на экран — тоже повод сказать.

       Пока оно спало, сеть могла уйти и вернуться, а наблюдатель в усыплённом процессе событий не
       получает: с его точки зрения ничего не менялось. Человек в этот момент смотрит на экран и
       ждёт свежего числа — самый неудачный момент досиживать минутную паузу. */
    func приВозвращении() {
        сообщить?("{\"type\":\"networkBack\"}")
    }
}
