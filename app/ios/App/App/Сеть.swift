import Foundation
import Network

/**
 СЕТЬ ВЕРНУЛАСЬ — СКАЗАТЬ ДВИЖКУ СРАЗУ (SugarLife#544, мост 1.42).

 Облачные потоки движка переподключаются сами, с нарастающей паузой: 5 с, 15 с, 30 с, минута. Пауза
 нужна, чтобы не долбить недоступный сервер, — но она же означает, что после возвращения Wi-Fi мы
 сидим и ждём её конца, теряя пятиминутки на ровном месте. Хуже всего ночью: минута ожидания там
 стоит одного пропущенного показания, а десять — тревоги о молчании, которой не должно было быть.

 Движок для этого принимает `networkBack`: поток жив — интент не делает ничего, поток досиживает
 паузу — просыпается немедленно. Он идемпотентен, поэтому лучше сказать лишний раз, чем промолчать.

 СЛУШАЕМ ЛЮБОЕ ИЗМЕНЕНИЕ, А НЕ ТОЛЬКО ВОЗВРАТ (SugarLife#549, уточнение ядра).

 Сперва мы слали только переход «не было → есть»: повод казался один — разбудить ожидающих. Ядро
 объяснило второй, и он важнее.

 Есть случай, который без нас не различить: сеть с белым списком. Мессенджеры работают, полоски на
 месте, человек уверен, что данные идут, — а до Nightscout не достучаться. Так же выглядят
 гостиничный портал, рабочая сеть и выключенный VPN. Мнение телефона о сети — единственный ключ,
 отличающий «связи нет» от «связь есть, а нас не пускают»: в первом случае движок молчит и ждёт, во
 втором говорит человеку, что проверить.

 Знать это движок может, только если мы рассказываем о состоянии сети регулярно, а не однажды.
 Интент идемпотентен: поток жив — ничего не произойдёт. Смена интерфейса Wi-Fi↔LTE случается
 несколько раз в день, а не в секунду, так что «часто» здесь — это всё равно редко.
 */
final class Сеть {

    static let общая = Сеть()

    private let наблюдатель = NWPathMonitor()
    private let очередь = DispatchQueue(label: "ru.imiron.sugarlife.сеть")
    /* Помним последнее состояние — но лишь чтобы не молчать, когда сеть ПОЯВИЛАСЬ, и не звать
       движок, когда её нет. */
    private var былаСеть = true
    /* ЧЕРЕЗ ЧТО ИМЕННО МЫ В СЕТИ (SugarLife#682).

       Здесь мы будили движок на КАЖДОЕ обновление пути — «о самом факте „сеть есть“ рассказываем
       всегда». За сутки это дало 1944 интента при ДВЕНАДЦАТИ настоящих обрывах: телефон меняет
       маршруты постоянно, и каждая мелочь шла через мост в фоне. Журнал на пятую часть состоял из
       «сеть вернулась», и читающий его делал ровно тот вывод, которого там нет, — что связь рвётся.

       Но и молчать на смене нельзя: при переходе Wi-Fi → сотовая сеть есть и до, и после, а сокеты
       под нами умирают, и облако обязано переподписаться. Разницу видно по составу интерфейсов —
       её и запоминаем. Сеть та же и интерфейсы те же — движку сказать нечего. */
    private var черезЧто = ""

    /* ИДЁМ ЛИ МЫ ЧЕРЕЗ VPN (SugarLife#805, случай владельца).

       Он оказался в сети, где открыт только белый список адресов, и поверх работал VPN — не
       работало вообще ничего. Движок в этот момент писал общее «если пользуетесь VPN, проверьте»,
       и человеку, который пользуется им постоянно, эта фраза не сказала ничего.

       Факт видим только мы, и он почти даром: состав интерфейсов мы и так собираем строкой выше.
       Туннель узнаётся по имени — `utun` у большинства клиентов, `ipsec` у встроенного IKEv2,
       `ppp` у старых.

       ЭТО ДОГАДКА, А НЕ ФАКТ, и говорить об этом надо честно. Apple не даёт спросить «включён ли
       VPN» никаким API; по именам интерфейсов туннель виден почти всегда, но «не нашли» не значит
       «нет». Поэтому наружу уходит только положительный ответ, а решать, что сказать при
       неуверенности, будет движок: у одной беды должен быть один голос. */
    private(set) var черезVPN = false

    /* КОГДА СЕТЬ ПРОПАЛА — чтобы на возврате сказать, сколько её не было (#805).

       «Связи нет» — тревожное утверждение о настоящем, на которое человек ответить не может.
       «Связи не было двадцать одну минуту» — закрытый факт о прошлом: понятно, что кончилось,
       сколько длилось и есть ли дыра в данных.

       Момент наш: обрыв и возврат видит этот наблюдатель, движок про сеть нашего телефона не знает
       ничего. Длительность отдаём фактом, слова — за движком. */
    private var пропалаВ: Date?
    /// Сколько длился последний обрыв, секунд. `nil` — обрывов ещё не было.
    private(set) var последнийОбрывСек: Int?

    /// Кому сказать. Ставит плагин: сам движок отсюда не виден и не должен быть.
    var сообщить: ((String) -> Void)?

    private init() {}

    func слушать() {
        наблюдатель.pathUpdateHandler = { [weak self] путь in
            guard let self else { return }
            let есть = путь.status == .satisfied
            let вернулась = есть && !self.былаСеть
            self.былаСеть = есть
            /* Туннель узнаём по имени интерфейса — состав пути у нас уже есть, спрашивать
               отдельно нечего. */
            self.черезVPN = путь.availableInterfaces.contains { и in
                let имя = и.name.lowercased()
                return имя.hasPrefix("utun") || имя.hasPrefix("ipsec") || имя.hasPrefix("ppp")
                    || имя.hasPrefix("tap")
            }
            if вернулась, let пропала = self.пропалаВ {
                self.последнийОбрывСек = Int(Date().timeIntervalSince(пропала))
                self.пропалаВ = nil
                NSLog("SugarLife: сеть вернулась, не было \(self.последнийОбрывСек ?? -1) с")
            }
            /* Нет сети — молчим: сказать «сеть есть» было бы неправдой, а другого смысла у интента
               нет. Движок в этот момент и так ждёт. */
            guard есть else {
                NSLog("SugarLife: сети нет")
                self.черезЧто = ""
                /* Засекаем один раз: путь при обрыве обновляется не единожды, и переписывать
                   момент значило бы обнулять счёт на каждом шевелении. */
                if self.пропалаВ == nil { self.пропалаВ = Date() }
                return
            }
            let черезЧтоТеперь = путь.availableInterfaces.map { $0.name }.joined(separator: ",")
            let сменилсяПуть = черезЧтоТеперь != self.черезЧто
            self.черезЧто = черезЧтоТеперь
            /* Ни возвращения, ни смены пути — обновление ни о чём. Молчим: разбудить движок здесь
               значит заплатить фоновой работой за новость, которой нет. */
            guard вернулась || сменилсяПуть else { return }
            NSLog(вернулась ? "SugarLife: сеть вернулась — будим облако"
                            : "SugarLife: сеть теперь через \(черезЧтоТеперь) — говорим движку")
            self.сообщить?("{\"type\":\"networkBack\"}")
        }
        наблюдатель.start(queue: очередь)
    }

    /* Возвращение приложения на экран — тоже повод сказать.

       Пока оно спало, сеть могла уйти и вернуться, а наблюдатель в усыплённом процессе событий не
       получает: с его точки зрения ничего не менялось. Человек в этот момент смотрит на экран и
       ждёт свежего числа — самый неудачный момент досиживать минутную паузу. */
    func приВозвращении() {
        сообщить?("{\"type\":\"networkBack\"}")
    }
}
