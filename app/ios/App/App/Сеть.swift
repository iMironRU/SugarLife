import Foundation
import Network

/**
 СЕТЬ ВЕРНУЛАСЬ — СКАЗАТЬ ДВИЖКУ СРАЗУ (SugarLife#544, мост 1.42).

 Облачные потоки движка переподключаются сами, с нарастающей паузой: 5 с, 15 с, 30 с, минута. Пауза
 нужна, чтобы не долбить недоступный сервер, — но она же означает, что после возвращения Wi-Fi мы
 сидим и ждём её конца, теряя пятиминутки на ровном месте. Хуже всего ночью: минута ожидания там
 стоит одного пропущенного показания, а десять — тревоги о молчании, которой не должно было быть.

 Движок для этого принимает `networkBack`: поток жив — интент не делает ничего, поток досиживает
 паузу — просыпается немедленно. Он идемпотентен, поэтому лучше сказать лишний раз, чем промолчать.

 СЛУШАЕМ ТОЛЬКО ПЕРЕХОД «не было → есть». `NWPathMonitor` шлёт о любой смене пути: Wi-Fi ушёл на
 LTE, поменялся интерфейс, изменилась дороговизна канала. Сообщать движку о каждой значило бы
 будить его без повода — а повод у нас ровно один.
 */
final class Сеть {

    static let общая = Сеть()

    private let наблюдатель = NWPathMonitor()
    private let очередь = DispatchQueue(label: "ru.imiron.sugarlife.сеть")
    /* Стартуем «сеть есть»: при первом же запуске приложение и так подключается заново, и
       рассказывать движку о «возвращении» того, что не пропадало, незачем. */
    private var былаСеть = true

    /// Кому сказать. Ставит плагин: сам движок отсюда не виден и не должен быть.
    var сообщить: ((String) -> Void)?

    private init() {}

    func слушать() {
        наблюдатель.pathUpdateHandler = { [weak self] путь in
            guard let self else { return }
            let есть = путь.status == .satisfied
            defer { self.былаСеть = есть }
            guard есть, !self.былаСеть else { return }
            NSLog("SugarLife: сеть вернулась — будим облако")
            self.сообщить?("{\"type\":\"networkBack\"}")
        }
        наблюдатель.start(queue: очередь)
    }

    /* Возвращение приложения на экран — тоже повод сказать.

       Пока оно спало, сеть могла уйти и вернуться, а наблюдатель в усыплённом процессе событий не
       получает: с его точки зрения ничего не менялось. Человек в этот момент смотрит на экран и
       ждёт свежего числа — самый неудачный момент досиживать минутную паузу. */
    func приВозвращении() {
        сообщить?("{\"type\":\"networkBack\"}")
    }
}
