import Foundation
import UserNotifications

/**
 СВОДКА В ШТОРКЕ: САХАР И АКТИВНЫЙ ИНСУЛИН, ОБНОВЛЯЕТСЯ САМА (SugarLife#500).

 Зачем она, когда есть живой баннер. Баннер живёт на экране блокировки и в машине, но его можно
 смахнуть, он гаснет через восемь часов и его нет на часах. Уведомление лежит в Центре уведомлений,
 доезжает до часов и переживает смахивание — это второй, независимый способ узнать число, не открывая
 приложение. У xDrip4iOS он же и есть.

 КАК ЭТО РАБОТАЕТ. Идентификатор один и тот же, поэтому каждое новое показание не добавляет строку, а
 ЗАМЕНЯЕТ прежнюю: в шторке всегда ровно одна свежая сводка, а не лента из двенадцати за час.
 Уровень `passive` — она не звенит, не подсвечивает экран и не всплывает баннером: это фон, а не
 событие. Тревоги приходят отдельно и ведут себя иначе (Тревоги.swift), путать их нельзя.

 ЧЕГО ОНА НЕ ДЕЛАЕТ. Не будит и не заменяет тревогу: тихое уведомление на беззвучном телефоне не
 слышно вовсе. И не появляется, пока приложение не исполняется, — как и всё остальное здесь.

 ПОЧЕМУ ЭТО ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ. Постоянная строка в шторке — вещь на любителя: одному она даёт
 число не разблокируя телефон, другому засоряет центр уведомлений рядом с живым баннером, который уже
 показывает то же самое. Решает человек.
 */
final class Сводка {

    static let общая = Сводка()

    private let ключ = "sl.status-note"
    private let идентификатор = "sugarlife.сводка"
    /// Реже, чем приходят показания: пять минут — шаг НМГ, чаще обновлять нечего.
    private let нечаще: TimeInterval = 4 * 60
    private var показаноВ: Date?
    private var показаноПоказание: Double = 0

    /* ИНСУЛИН ПРИХОДИТ НЕ ОТТУДА, ОТКУДА САХАР (#500).

       В облачном режиме движок активный инсулин не считает — он отдаёт ноль, а число, которое человек
       видит в приложении, приезжает из Nightscout через веб-слой. Значит для сводки его приходится
       брать оттуда же и хранить здесь: в фоне webview спит, и спросить будет некого.

       Со сроком годности: пока приложение спит, инсулин продолжает расходоваться, и вчерашние
       восемь единиц в шторке — это не «нет данных», это ложь в сторону опасности. Пятнадцать минут
       без обновления — и мы про инсулин молчим. */
    private var инсулинИзВеба: (значение: Double, когда: Date)?
    private let инсулинЖивёт: TimeInterval = 15 * 60

    func принятьИнсулин(_ значение: Double?) {
        guard let значение else { инсулинИзВеба = nil; return }
        инсулинИзВеба = (значение, Date())
    }

    /// Что показать про инсулин: сначала движок, если он считает; иначе свежее число из веб-слоя.
    private func инсулинСейчас(_ отДвижка: Double?) -> Double? {
        if let и = отДвижка, и > 0.05 { return и }
        guard let (значение, когда) = инсулинИзВеба,
              Date().timeIntervalSince(когда) <= инсулинЖивёт else { return nil }
        return значение
    }

    private init() {}

    /// Показывать ли сводку. Выключение сразу убирает её из шторки: настройка, которая
    /// «начнёт действовать потом», выглядит как несработавшая.
    var включена: Bool {
        get { UserDefaults.standard.bool(forKey: ключ) }
        set {
            UserDefaults.standard.set(newValue, forKey: ключ)
            if !newValue { снять() }
        }
    }

    func снять() {
        UNUserNotificationCenter.current().removePendingNotificationRequests(withIdentifiers: [идентификатор])
        UNUserNotificationCenter.current().removeDeliveredNotifications(withIdentifiers: [идентификатор])
        показаноВ = nil
        показаноПоказание = 0
    }

    /**
     Обновить сводку по свежему показанию.

     `инсулин` — активный инсулин от движка; `nil` или ноль означает «сказать нечего», и тогда строки
     про инсулин просто нет. Писать «инс. 0 ед» нельзя: ноль от движка и «движок не считал» выглядят
     одинаково, а значат разное.
     */
    func обновить(сахар: String, стрелка: String, разница: String, инсулин: Double?,
                  когдаМс: Double, старое: Bool) {
        guard включена else { return }
        /* То же показание — не трогаем: система по одному идентификатору перерисует строку, и в
           шторке она прыгнет наверх без всякой новости. */
        if когдаМс == показаноПоказание { return }
        if let было = показаноВ, Date().timeIntervalSince(было) < нечаще, !старое { return }
        показаноПоказание = когдаМс
        показаноВ = Date()

        let к = UNMutableNotificationContent()
        к.title = [сахар, стрелка].filter { !$0.isEmpty }.joined(separator: " ")
        var строки: [String] = []
        if !разница.isEmpty { строки.append(разница) }
        if let и = инсулинСейчас(инсулин), и > 0.05 {
            строки.append("инс. " + String(format: "%.1f", и).replacingOccurrences(of: ".", with: ",") + " ед")
        }
        /* Возраст словами и в теле, а не таймером: у уведомления таймера нет, а число без возраста
           в шторке через час выглядит текущим. */
        строки.append(старое ? "данные устарели" : "только что")
        к.body = строки.joined(separator: " · ")
        к.sound = nil
        if #available(iOS 15.0, *) { к.interruptionLevel = .passive }

        UNUserNotificationCenter.current().add(
            UNNotificationRequest(identifier: идентификатор, content: к, trigger: nil))
    }
}
