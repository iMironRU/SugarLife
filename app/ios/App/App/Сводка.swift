import Foundation
import UserNotifications

/**
 СВОДКА В ШТОРКЕ: САХАР И АКТИВНЫЙ ИНСУЛИН, ОБНОВЛЯЕТСЯ САМА (SugarLife#500).

 Зачем она, когда есть живой баннер. Баннер живёт на экране блокировки и в машине, но его можно
 смахнуть, он гаснет через восемь часов и его нет на часах. Уведомление лежит в Центре уведомлений,
 доезжает до часов и переживает смахивание — это второй, независимый способ узнать число, не открывая
 приложение. У xDrip4iOS он же и есть.

 КАК ЭТО РАБОТАЕТ. Идентификатор один и тот же, поэтому каждое новое показание не добавляет строку, а
 ЗАМЕНЯЕТ прежнюю: в шторке всегда ровно одна свежая сводка, а не лента из двенадцати за час.
 Уровень `passive` — она не звенит, не подсвечивает экран и не всплывает баннером: это фон, а не
 событие. Тревоги приходят отдельно и ведут себя иначе (Тревоги.swift), путать их нельзя.

 ЧЕГО ОНА НЕ ДЕЛАЕТ. Не будит и не заменяет тревогу: тихое уведомление на беззвучном телефоне не
 слышно вовсе. И не появляется, пока приложение не исполняется, — как и всё остальное здесь.

 ПОЧЕМУ ЭТО ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ. Постоянная строка в шторке — вещь на любителя: одному она даёт
 число не разблокируя телефон, другому засоряет центр уведомлений рядом с живым баннером, который уже
 показывает то же самое. Решает человек.
 */
final class Сводка {

    static let общая = Сводка()

    private let ключ = "sl.status-note"
    private let ключВсплытия = "sl.status-note.pop"
    private let идентификатор = "sugarlife.сводка"
    /* Реже, чем приходят показания. Пять минут — общий шаг всех внешних поверхностей
       (docs/поверхности-показа.md): шторка, баннер и виджеты живут по одному расписанию, чтобы
       человек не сверял, почему в двух местах разные числа. */
    private let нечаще: TimeInterval = 5 * 60
    private var показаноВ: Date?
    private var показаноПоказание: Double = 0

    /* ИНСУЛИН ПРИХОДИТ НЕ ОТТУДА, ОТКУДА САХАР (#500).

       В облачном режиме движок активный инсулин не считает — он отдаёт ноль, а число, которое человек
       видит в приложении, приезжает из Nightscout через веб-слой. Значит для сводки его приходится
       брать оттуда же и хранить здесь: в фоне webview спит, и спросить будет некого.

       Со сроком годности: пока приложение спит, инсулин продолжает расходоваться, и вчерашние
       восемь единиц в шторке — это не «нет данных», это ложь в сторону опасности. Пятнадцать минут
       без обновления — и мы про инсулин молчим. */
    private var инсулинИзВеба: (значение: Double, когда: Date)?
    private let инсулинЖивёт: TimeInterval = 15 * 60

    func принятьИнсулин(_ значение: Double?) {
        guard let значение else { инсулинИзВеба = nil; return }
        инсулинИзВеба = (значение, Date())
    }

    /// Свежий инсулин из веб-слоя — для баннера, который спрашивает то же самое (#500).
    func инсулинДляПоказа() -> Double? { инсулинСейчас(nil) }

    /// Что показать про инсулин: сначала движок, если он считает; иначе свежее число из веб-слоя.
    private func инсулинСейчас(_ отДвижка: Double?) -> Double? {
        if let и = отДвижка, и > 0.05 { return и }
        guard let (значение, когда) = инсулинИзВеба,
              Date().timeIntervalSince(когда) <= инсулинЖивёт else { return nil }
        return значение
    }

    private init() {}

    /// «11:40» — час показания. Формат тот же, что у баннера в разрыве: одно число не может
    /// называться в шторке и на экране блокировки по-разному.
    private func время(_ когдаМс: Double) -> String {
        let ф = DateFormatter()
        ф.locale = Locale(identifier: "ru_RU")
        ф.dateFormat = "H:mm"
        return ф.string(from: Date(timeIntervalSince1970: когдаМс / 1000))
    }

    /// Показывать ли сводку. Выключение сразу убирает её из шторки: настройка, которая
    /// «начнёт действовать потом», выглядит как несработавшая.
    var включена: Bool {
        get { UserDefaults.standard.bool(forKey: ключ) }
        set {
            UserDefaults.standard.set(newValue, forKey: ключ)
            if !newValue { снять() }
        }
    }

    /* ВСПЛЫВАТЬ ИЛИ ЛЕЖАТЬ ТИХО (#539).

       Тихая сводка живёт в центре уведомлений: чтобы её прочесть, надо потянуть шторку. Владелец
       смотрит на соседей (xDrip) и хочет иначе — чтобы число само показывалось поверх экрана, как
       только пришло. Это разные повадки одной и той же строки, и выбирать между ними должен тот,
       чей это телефон: одному «мелькает каждые пять минут» — то, ради чего всё ставилось, другому —
       повод выключить совсем.

       Звука нет ни в одном из двух: всплывающая сводка не тревога и звенеть не должна. Разбудить
       ночью она тоже не может — по построению, и это правильно: для этого есть тревоги. */
    var всплывает: Bool {
        get { UserDefaults.standard.bool(forKey: ключВсплытия) }
        set { UserDefaults.standard.set(newValue, forKey: ключВсплытия) }
    }

    func снять() {
        UNUserNotificationCenter.current().removePendingNotificationRequests(withIdentifiers: [идентификатор])
        UNUserNotificationCenter.current().removeDeliveredNotifications(withIdentifiers: [идентификатор])
        показаноВ = nil
        показаноПоказание = 0
    }

    /**
     Обновить сводку по свежему показанию.

     `инсулин` — активный инсулин от движка; `nil` или ноль означает «сказать нечего», и тогда строки
     про инсулин просто нет. Писать «инс. 0 ед» нельзя: ноль от движка и «движок не считал» выглядят
     одинаково, а значат разное.
     */
    func обновить(сахар: String, стрелка: String, разница: String, инсулин: Double?,
                  когдаМс: Double, старое: Bool) {
        guard включена else { return }
        /* То же показание — не трогаем: система по одному идентификатору перерисует строку, и в
           шторке она прыгнет наверх без всякой новости. */
        if когдаМс == показаноПоказание { return }
        /* УСТАРЕВШЕЕ ПОКАЗАНИЕ НЕ СОЗДАЁТ КАРТОЧКУ (правило 6, docs/поверхности-показа.md).

           Владелец увидел в шторке «10,3 · показание в 7:14 · сейчас», а в приложении в ту же секунду
           5,2. Обе честные: движок на старте дочитывал историю, каждая прошлая точка приезжала как
           «последнее показание», и первая же опубликовала себя карточкой. Дальше пятиминутный такт
           закрепил её на экране — верное число показывалось только в приложении.

           Уже висящую карточку старым числом обновляем: показать, что она постарела, — обязанность.
           Создавать её ради старого числа — нет. Отличаем по тому, показывали ли мы что-то вообще. */
        if старое, показаноВ == nil { return }
        if let было = показаноВ, Date().timeIntervalSince(было) < нечаще, !старое { return }
        показаноПоказание = когдаМс
        показаноВ = Date()

        let к = UNMutableNotificationContent()
        к.title = [сахар, стрелка].filter { !$0.isEmpty }.joined(separator: " ")
        var строки: [String] = []
        if !разница.isEmpty { строки.append(разница) }
        if let и = инсулинСейчас(инсулин), и > 0.05 {
            строки.append("инс. " + String(format: "%.1f", и).replacingOccurrences(of: ".", with: ",") + " ед")
        }
        /* ВОЗРАСТ ГОВОРИТ СИСТЕМА — НАШЕ ДЕЛО СКАЗАТЬ ТО, ЧЕГО ОНА НЕ ЗНАЕТ (#553).

           Справа на карточке iOS сама пишет, когда её доставили: «2 минуты назад». Мы писали рядом
           «только что · в 17:08» — и получалось три отметки времени в одной строке, из которых наша
           первая ещё и спорила с системной.

           Но эти времена — РАЗНЫЕ. Система показывает возраст УВЕДОМЛЕНИЯ, а нас интересует возраст
           ПОКАЗАНИЯ. Обычно они совпадают, и тогда добавлять нечего. Расходятся они в единственном,
           зато важном случае: приложение усыпили, карточка висит с прежним числом, а система по-
           прежнему говорит про момент доставки — и число выглядит свежим.

           Поэтому час показания пишем ТОЛЬКО при расхождении: «показание в 15:30» рядом с системным
           «2 минуты назад» сразу объясняет, что перед человеком. Слова «только что» больше нет
           вовсе: она стареет вместе с карточкой и первой начинает врать. */
        /* СВЕЖЕСТЬ РЕШАЕТ ДВИЖОК, А НЕ НАШ ПОРОГ.

           Здесь стояло «или расхождение больше двух минут» — и владелец снова увидел «показание в
           17:20» рядом с системным «2 минуты назад». Порог оказался чутким не к тому: его данные
           приезжают из облака с задержкой, и к моменту, когда мы собираем карточку, показанию уже
           бывает пара минут. Это нормальная жизнь, а не повод объясняться.

           Оставляем единственное честное условие: движок сказал, что показание устарело. У него для
           этого есть такт источника — он знает, что для минутного сенсора две минуты много, а для
           пятиминутного облака нет. Наше фиксированное число такого различить не умело. */
        if старое {
            строки.append("показание в " + время(когдаМс))
        }
        к.body = строки.joined(separator: " · ")
        /* Сводка — про сахар, значит ведёт на «Сегодня» (#524). */
        к.userInfo = ["цель": "сегодня"]
        к.sound = nil
        /* `active` — всплыть поверх экрана и не звенеть; `passive` — молча лечь в центр уведомлений.
           Выше этого не поднимаемся никогда: `timeSensitive` пробивает «Не беспокоить», а сводка
           этого права не имеет — им пользуются тревоги, и разбавлять его фоном значит обесценить. */
        if #available(iOS 15.0, *) { к.interruptionLevel = всплывает ? .active : .passive }

        UNUserNotificationCenter.current().add(
            UNNotificationRequest(identifier: идентификатор, content: к, trigger: nil))
    }
}
