import Foundation

/*
 Три часа показаний для живого баннера (#428, макет v2 — #500).

 ЗАЧЕМ КОПИТЬ САМИМ. Движок отдаёт снимок — то, что происходит сейчас: одно число и его
 время. Истории в снимке нет и не будет: это состояние, а не журнал. Графику же нужен ряд,
 и взять его больше неоткуда — в фоне интерфейса нет, а значит нет и того слоя, где живут
 записи Nightscout.

 ПОЧЕМУ НА ДИСКЕ, А НЕ В ПАМЯТИ. Приложение на iOS убивают буднично: система выгружает
 его, как только сочтёт нужным. Ряд в памяти означал бы пустой график после каждого такого
 случая — то есть ровно тогда, когда человек берёт телефон и хочет понять, что было. Тринадцать
 пар чисел на диске стоят ничего.

 ПРОПУСКИ НЕ ЗАШИВАЕМ. Если показаний не было полчаса, в ряду будет дыра — и график обязан
 показать её разрывом, а не прямой линией через всю карточку. Линия, соединяющая два конца
 молчания, выглядит как ровный сахар — это худшее враньё, какое здесь можно нарисовать.
 */
enum ИсторияСахара {
    /* ТРИ ЧАСА, А НЕ ЧАС (макет v2). Час отвечает «растёт», три — «как давно и с какой амплитудой»:
       две качели от 3,8 до 13,1 и спокойный вечер на фиксированной оси выглядят по-разному, а на
       часовом окне с автомасштабом одинаково. Тридцать семь точек при пятиминутном шаге — это
       полторы тысячи байт при лимите ActivityKit в четыре килобайта. */
    static let ОКНО: TimeInterval = 3 * 60 * 60
    private static let КЛЮЧ = "sl.banner-series.v1"

    private struct Точка: Codable { var т: Double; var в: Double }

    /// Запомнить показание и вернуть весь ряд за последний час.
    static func добавить(значение: Double, когдаМс: Double) -> [СахарАтрибуты.ContentState.Точка] {
        let t = когдаМс / 1000
        var ряд = прочитать()
        /* То же показание пришло второй раз — снимок движка эмитится на любое изменение,
           и без этой проверки один момент времени породил бы десяток точек подряд. */
        if !ряд.contains(where: { abs($0.т - t) < 1 }) {
            ряд.append(Точка(т: t, в: значение))
        }
        let порог = Date().timeIntervalSince1970 - ОКНО
        ряд = ряд.filter { $0.т >= порог }.sorted { $0.т < $1.т }
        записать(ряд)
        return ряд.map { .init(т: Date(timeIntervalSince1970: $0.т), в: $0.в) }
    }

    /* ПРОРЕЖИВАНИЕ ПЕРЕД ОТПРАВКОЙ — ИНАЧЕ БАННЕР ПРОСТО НЕ ОБНОВЛЯЕТСЯ (#545).

       Расчёт «тридцать семь точек» выше исходил из пятиминутного шага НМГ. У владельца показания
       приезжают РАЗ В МИНУТУ (так их кладёт в облако его система), и за три часа копится под две
       сотни точек. ActivityKit молча отказывает: `Payload maximum size exceeded` — баннер остаётся
       висеть с последним, что успело пролезть, и выглядит это как «застрял», а не как «мы шлём
       слишком много».

       Поэтому в баннер уезжает прореженный ряд: не чаще одной точки в пять минут. Для линии на
       карточке шириной в пол-экрана разницы нет — соседние минуты всё равно ложатся в один пиксель,
       — а размер падает впятеро. Последняя точка сохраняется всегда: она и есть текущее показание,
       и терять её из-за арифметики шага нельзя.

       Дыры прореживание не заращивает: пропуск остаётся пропуском, и разрыв на графике будет там
       же, где был. */
    static func дляПоказа(_ ряд: [СахарАтрибуты.ContentState.Точка],
                          шаг: TimeInterval = 5 * 60) -> [СахарАтрибуты.ContentState.Точка] {
        guard let последняя = ряд.last else { return ряд }
        var итог: [СахарАтрибуты.ContentState.Точка] = []
        for т in ряд {
            if let прошлая = итог.last, т.т.timeIntervalSince(прошлая.т) < шаг { continue }
            итог.append(т)
        }
        /* Текущее показание — всегда последнее в ряду. Если шаг его «съел», ставим отдельно:
           график, отстающий от числа над ним на четыре минуты, противоречит сам себе. */
        if итог.last?.т != последняя.т { итог.append(последняя) }
        return итог
    }

    /// Ряд без добавления — когда баннер включили, а нового показания ещё нет.
    static func ряд() -> [СахарАтрибуты.ContentState.Точка] {
        let порог = Date().timeIntervalSince1970 - ОКНО
        return прочитать().filter { $0.т >= порог }.sorted { $0.т < $1.т }
            .map { .init(т: Date(timeIntervalSince1970: $0.т), в: $0.в) }
    }

    private static func прочитать() -> [Точка] {
        guard let d = UserDefaults.standard.data(forKey: КЛЮЧ),
              let р = try? JSONDecoder().decode([Точка].self, from: d) else { return [] }
        return р
    }

    private static func записать(_ р: [Точка]) {
        guard let d = try? JSONEncoder().encode(р) else { return }
        UserDefaults.standard.set(d, forKey: КЛЮЧ)
    }
}
