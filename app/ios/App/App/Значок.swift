import Foundation
import UserNotifications

/**
 САХАР ЦИФРАМИ НА ЗНАЧКЕ ПРИЛОЖЕНИЯ (SugarLife#500).

 ЗАПЯТАЯ НА ЗНАЧКЕ ВОЗМОЖНА — И ЭТО ГЛАВНОЕ, ЧТО ЗДЕСЬ НАДО ЗНАТЬ (#550).

 Мы считали, что значок умеет только целое: `setBadgeCount` принимает `Int`, и на этом рассуждение
 заканчивалось. Владелец показал соседнее приложение, у которого на значке стоит «5,8», и оказалось,
 что путь другой: у уведомления поле `badge` — это `NSNumber`, а не `Int`, и дробное значение система
 форматирует ПО ЛОКАЛИ. В русской это запятая.

 Проверено на симуляторе: `{"aps":{"badge":5.8}}` рисует на значке «5,8».

 Карточку уведомления, которым мы ставим число, тут же убираем: она нужна была только как повозка для
 `badge` и висела бы в шторке пустой строкой. Сам значок при этом остаётся — он не привязан к
 карточке.

 Поэтому вид числа — выбор с ценой, и делает его человек:

  — `сахар` («5,8») — то же, что на всех остальных поверхностях, ничего пересчитывать не надо;
  — `десятые` («58» = 5,8) — для тех, кому запятая на значке кажется мусором;
  — `целые` («6») — привычно с первого взгляда, зато 7,6 и 8,4 выглядят одинаково, то есть «нормально»
    и «пора смотреть» сливаются в одно;
  — `мг` («104») — привычно тем, кто вырос на mg/dL, и требует пересчёта в уме всем остальным.

 ЧЕГО ЗНАЧОК НЕ ДЕЛАЕТ. Не будит и не говорит о возрасте показания. Поэтому при устаревших данных мы
 его ГАСИМ, а не оставляем последнее число: цифра без возраста выглядит текущей всегда, а это самый
 дешёвый способ соврать.

 Выключено по умолчанию: цифры на иконке видит каждый, кто взял телефон в руки.
 */
final class Значок {

    enum Вид: String, CaseIterable {
        case выключен, сахар, десятые, целые, мг

        /// Что показать на значке. nil — не показывать ничего.
        func число(_ mmol: Double) -> Double? {
            switch self {
            case .выключен: return nil
            /* Дробное — то самое «5,8»: система сама поставит разделитель по локали телефона.
               Округляем до десятых мы: без этого на значок уехало бы 5.799999. */
            case .сахар: return (mmol * 10).rounded() / 10
            case .десятые: return (mmol * 10).rounded()
            case .целые: return mmol.rounded()
            /* 18,018 — не «примерно 18»: коэффициент точный, и округлять его самим значит разойтись
               с любым другим приложением на телефоне в единице последнего разряда. */
            case .мг: return (mmol * 18.018).rounded()
            }
        }
    }

    static let общий = Значок()

    private let ключ = "sl.badge-mode"
    private var показано: Double = -1

    private init() {}

    var вид: Вид {
        get { Вид(rawValue: UserDefaults.standard.string(forKey: ключ) ?? "") ?? .выключен }
        set {
            UserDefaults.standard.set(newValue.rawValue, forKey: ключ)
            if newValue == .выключен { поставить(0) }
        }
    }

    /// Обновить по свежему показанию. Устаревшее гасит значок: см. выше, почему.
    func обновить(mmol: Double?, старое: Bool) {
        guard вид != .выключен else { return }
        guard let mmol, mmol > 0, !старое, let число = вид.число(mmol) else { поставить(0); return }
        поставить(число)
    }

    private func поставить(_ число: Double) {
        guard число != показано else { return }
        показано = число
        /* ЦЕЛОЕ СТАВИМ ПРЯМЫМ ПУТЁМ, ДРОБНОЕ — ЧЕРЕЗ УВЕДОМЛЕНИЕ.

           `setBadgeCount` принимает только `Int`, и дробное через него не пройдёт. Зато поле `badge`
           у содержимого уведомления — `NSNumber`, и туда дробное кладётся; система показывает его на
           значке по локали. Уведомление при этом пустое и тихое: оно тут не сообщение, а повозка. */
        let целое = число == число.rounded()
        if целое, #available(iOS 16.0, *) {
            UNUserNotificationCenter.current().setBadgeCount(Int(число))
            return
        }
        let к = UNMutableNotificationContent()
        к.badge = NSNumber(value: число)
        к.sound = nil
        if #available(iOS 15.0, *) { к.interruptionLevel = .passive }
        let id = "sugarlife.значок"
        UNUserNotificationCenter.current().add(
            UNNotificationRequest(identifier: id, content: к, trigger: nil)
        ) { _ in
            /* Карточку убираем сразу: в шторке она была бы пустой строкой без текста, а значок от
               её удаления не гаснет — он живёт отдельно от уведомления, которым его поставили. */
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) {
                UNUserNotificationCenter.current().removeDeliveredNotifications(withIdentifiers: [id])
            }
        }
    }
}
