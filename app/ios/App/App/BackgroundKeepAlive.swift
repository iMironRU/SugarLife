import Foundation
import AVFoundation
import UIKit

/**
 Не дать системе усыпить приложение, когда будить его нечем (#388).

 Фоновый режим `bluetooth-central` (#379) решает половину задачи: приложение просыпается, когда прибор
 что-то прислал. Но **у человека на одном облаке прибора нет вовсе** — ни сенсора, ни моста. Будить нас
 нечем: iOS приостанавливает процесс, и данные из Nightscout перестают приходить до следующего открытия.
 Именно так живёт наблюдатель — родитель, который смотрит на чужой сенсор, — и ему свежесть цифры важнее
 всех.

 Приём взят у xDrip4iOS: проигрывать **миллисекунду тишины** раз в несколько секунд. Фоновый режим `audio`
 не даёт системе приостановить процесс.

 Две вещи здесь важнее самого приёма, и обе от них же:

  — включается **только при уходе в фон**: на экране оно не нужно и батарею не ест;
  — это **выбор человека**, а не наша самодеятельность. По умолчанию выключено. Честная сделка: живость
    против батареи, и решает тот, чей телефон.

 Звук строим в коде, а не носим файлом: сорок четыре нулевых сэмпла с заголовком WAV — это сотня байт,
 которую видно целиком. Ресурс пришлось бы объяснять всякому, кто откроет проект.
 */
final class ФоновоеБодрствование {

    enum Режим: String, CaseIterable {
        case выключено, обычное, настойчивое

        /// Как часто напоминать системе о себе. У xDrip4iOS ровно эти числа: 5 и 2 секунды.
        var интервал: TimeInterval? {
            switch self {
            case .выключено: return nil
            case .обычное: return 5
            case .настойчивое: return 2
            }
        }
    }

    static let shared = ФоновоеБодрствование()

    private let ключ = "sugarlife.background-keep-alive"
    /* СЛЕД В ЖУРНАЛЕ ДВИЖКА, А НЕ ТОЛЬКО В NSLog (#593).

       Опора умирает не на глазах у разработчика, а ночью в кармане. NSLog виден только тому, кто в
       эту минуту держит телефон подключённым к Xcode; журнал движка выгружается с устройства и
       читается утром. Молчаливо умирающий механизм неотличим от работающего — это тот же урок, что с
       баннером, который писал только удачные исходы. */
    var вЖурнал: ((_ уровень: String, _ событие: String) -> Void)?

    /* ФАКТ, А НЕ НАМЕРЕНИЕ. `режим` — это настройка, то есть чего человек хотел. Держим ли мы звук на
       самом деле — отдельный вопрос, и отвечать на него надо отдельно: сессию могли отобрать. */
    var держимЗвук: Bool { проигрыватель?.isPlaying == true }

    private var проигрыватель: AVAudioPlayer?
    private var таймер: DispatchSourceTimer?
    /// Сколько тиков подряд звук не пошёл. Нужен, чтобы писать в журнал один раз, а не каждые пять секунд.
    private var молчалиПодряд = 0
    private let очередь = DispatchQueue(label: "ru.imiron.sugarlife.keepalive")

    private(set) var режим: Режим {
        get { Режим(rawValue: UserDefaults.standard.string(forKey: ключ) ?? "") ?? .выключено }
        set { UserDefaults.standard.set(newValue.rawValue, forKey: ключ) }
    }

    private init() {}

    /// Подписаться на уход в фон и возвращение. Зовётся один раз, при старте плагина.
    func начать() {
        NotificationCenter.default.addObserver(
            self, selector: #selector(ушлиВФон),
            name: UIApplication.didEnterBackgroundNotification, object: nil)
        NotificationCenter.default.addObserver(
            self, selector: #selector(вернулись),
            name: UIApplication.willEnterForegroundNotification, object: nil)
        /* ПРЕРЫВАНИЕ — ГЛАВНАЯ ДЫРА, И ОНА БЫЛА ОТКРЫТА (#593).

           Позвонили, другое приложение взяло звук монопольно, магнитола перехватила маршрут — сессию
           у нас отбирают, проигрыватель останавливается. Таймер после этого продолжал тикать и звать
           `play()` в деактивированную сессию: вернуть её можно только повторным `setActive(true)`,
           которого мы не делали нигде, кроме входа в фон.

           То есть после ЛЮБОГО прерывания опора молча умирала до следующего открытия приложения.
           Выключатель в «Охране» показывал «включено», а тишина не играла — и никто об этом не знал. */
        NotificationCenter.default.addObserver(
            self, selector: #selector(прерваны(_:)),
            name: AVAudioSession.interruptionNotification, object: nil)
        /* Сброс медиа-служб системой: проигрыватель и сессия становятся негодными целиком, их надо
           создавать заново. Случается редко, но молча. */
        NotificationCenter.default.addObserver(
            self, selector: #selector(медиаСброшены),
            name: AVAudioSession.mediaServicesWereResetNotification, object: nil)
        /* СМЕНА МАРШРУТА — ПОВОД ПЕРЕСМОТРЕТЬ ОПОРУ, а не только повод для тревог.

           В машину садятся с уже усыплённым приложением: телефон в кармане, опора держится, и вот
           появился CarPlay. Решать только при уходе в фон значило бы отпускать магнитолу лишь
           тогда, когда человек откроет приложение и снова его закроет. */
        NotificationCenter.default.addObserver(
            self, selector: #selector(маршрутСменился),
            name: AVAudioSession.routeChangeNotification, object: nil)
    }

    @objc private func маршрутСменился() {
        /* Только в фоне: на переднем плане опора не нужна вовсе, приложение и так живо. */
        DispatchQueue.main.async { [weak self] in
            guard UIApplication.shared.applicationState == .background else { return }
            self?.применить()
        }
    }

    @objc private func прерваны(_ уведомление: Notification) {
        guard let код = уведомление.userInfo?[AVAudioSessionInterruptionTypeKey] as? UInt,
              let вид = AVAudioSession.InterruptionType(rawValue: код) else { return }
        switch вид {
        case .began:
            вЖурнал?("Warn", "опора прервана — звук у нас отобрали")
        default:
            /* Прерывание кончилось. Поднимаемся, только если мы в фоне и режим включён: на переднем
               плане опора не нужна, а включать её там значило бы жечь заряд впустую. */
            guard UIApplication.shared.applicationState == .background, режим != .выключено else { return }
            вЖурнал?("Info", "опора поднимается после прерывания")
            применить()
        }
    }

    @objc private func медиаСброшены() {
        проигрыватель = nil
        guard UIApplication.shared.applicationState == .background, режим != .выключено else { return }
        вЖурнал?("Warn", "медиа-службы сброшены — опору собираем заново")
        применить()
    }

    func установить(_ новый: Режим) {
        режим = новый
        NSLog("SugarLife: фоновое бодрствование — \(новый.rawValue)")
        // Меняют настройку обычно на экране, то есть на переднем плане: тогда просто запомнили. Но если
        // приложение уже в фоне (настройку изменили из шторки/через мост) — применяем сразу.
        if UIApplication.shared.applicationState == .background { применить() } else { остановить() }
    }

    @objc private func ушлиВФон() { применить() }
    @objc private func вернулись() { остановить() }

    private func применить() {
        /* УХОД В ФОН ОСТАВЛЯЕТ СЛЕД ВСЕГДА — И КОГДА ОПОРУ ПОДНЯЛИ, И КОГДА НЕТ.

           За сутки приложение убили 21 раз, и разобраться почему было НЕЧЕМ: в журнале за все
           эти часы нет ни одной записи с тегом keepalive. Ни одной — потому что писали мы только
           про поломки, а самый частый исход тут не поломка, а вот этот `guard`: режим выключен,
           выходим молча.

           Значит «опора не поднималась никогда» и «опора работала и упала» выглядели одинаково —
           пустотой. Ровно то, против чего мы завели правило 8 и что ядро записало инвариантом 6:
           если запись делается при одном исходе, её отсутствие означает две разные беды.

           Утром мы закрыли это у баннера и у тревог, а здесь пропустили — и потеряли на этом день. */
        guard let интервал = режим.интервал else {
            вЖурнал?("Info", "ушли в фон без опоры: фоновое бодрствование выключено")
            остановить()
            return
        }
        /* В МАШИНЕ ОПОРУ ОТПУСКАЕМ — ИНАЧЕ ПЕРЕХВАТИМ МАГНИТОЛУ.

           Владелец: «радио в машине блокируется». По журналу видно, как это выглядело: маршрут `car`,
           «ушли в фон с опорой», и следом раз за разом «опора прервана — звук у нас отобрали». Мы и
           головное устройство отбирали звук друг у друга по кругу.

           Опора — это воспроизведение. Даже беззвучное и с `.mixWithOthers`, в машине оно заставляет
           головное устройство переключиться на телефон: вместо радио человек получает тишину. То есть
           механизмом, написанным чтобы не мешать в дороге, мы мешали сильнее всего.

           РЕШЕНИЕ НЕ НАШЕ. Оно записано у ядра: core/contract/…/ЗвуковаяОбстановка.kt, `Машина →
           держатьОпору = false`, с той же причиной слово в слово. Поля в контракте для него пока нет,
           и мы попросили его завести (SugarLifeCore#149): маршрут наблюдаем мы, а что из него следует
           — решает движок, и держать это в двух местах значит однажды разойтись.

           Потеря невелика и названа там же: в машине телефон почти всегда на зарядке и в руках, а
           прошивки выгружают приложения не тогда, когда экран горит. */
        if Тревоги.маршрутЗвука() == "car" {
            вЖурнал?("Info", "ушли в фон без опоры: в машине не держим, иначе перехватим магнитолу")
            остановить()
            return
        }
        do {
            // `.playback` — единственная категория, которая продолжает жить в фоне. `.mixWithOthers`
            // обязателен: без него мы остановим музыку или подкаст человека ради своей тишины.
            try AVAudioSession.sharedInstance().setCategory(.playback, options: [.mixWithOthers])
            try AVAudioSession.sharedInstance().setActive(true)
        } catch {
            /* Не смогли занять сессию — опоры нет. Сказать об этом обязаны: выключатель в «Охране»
               по-прежнему показывает «включено», и молчание здесь читается как «всё в порядке». */
            NSLog("SugarLife: не удалось занять аудио-сессию (\(error)) — фоновое бодрствование не работает")
            вЖурнал?("Error", "опору не подняли: сессию не отдали")
            return
        }
        if проигрыватель == nil {
            проигрыватель = try? AVAudioPlayer(data: тишина())
            проигрыватель?.volume = 0
            проигрыватель?.prepareToPlay()
        }
        таймер?.cancel()
        let t = DispatchSource.makeTimerSource(queue: очередь)
        t.schedule(deadline: .now(), repeating: интервал)
        t.setEventHandler { [weak self] in
            guard let self, let p = self.проигрыватель, !p.isPlaying else { return }
            /* РЕЗУЛЬТАТ ПРОВЕРЯЕМ. `play()` возвращает, получилось ли, и мы его игнорировали: в
               мёртвой сессии он молча отвечает «нет» каждые пять секунд, а наружу это выглядит
               работающей опорой.

               Пишем один раз на серию неудач, а не каждый тик: пять записей в секунду забьют журнал,
               в котором мы же потом будем искать причину. */
            if p.play() {
                if self.молчалиПодряд > 0 { self.вЖурнал?("Info", "опора снова играет") }
                self.молчалиПодряд = 0
            } else {
                self.молчалиПодряд += 1
                if self.молчалиПодряд == 3 { self.вЖурнал?("Error", "опора не играет: сессия не принимает звук") }
            }
        }
        t.resume()
        таймер = t
        NSLog("SugarLife: фоновое бодрствование включено, раз в \(интервал) с")
        /* И удачный исход — тоже в журнал. Без него запись остаётся односторонней, а односторонняя
           запись и есть двусмысленное молчание. Маршрут называем здесь же: по нему потом видно, что
           именно у нас отобрали, — наушники выдернули, магнитола перехватила, звонок пришёл. */
        вЖурнал?("Info", "ушли в фон с опорой: тик \(Int(интервал)) с, маршрут \(Тревоги.маршрутЗвука())")
    }

    private func остановить() {
        таймер?.cancel(); таймер = nil
        проигрыватель?.stop()
        try? AVAudioSession.sharedInstance().setActive(false, options: [.notifyOthersOnDeactivation])
    }

    /// Миллисекунда тишины: заголовок WAV и сорок четыре нулевых сэмпла при 44.1 кГц, моно, 16 бит.
    private func тишина() -> Data {
        let частота: UInt32 = 44_100
        let сэмплов = 44                        // ≈ 1 мс
        let данных = UInt32(сэмплов * 2)
        var d = Data()
        func u32(_ v: UInt32) { withUnsafeBytes(of: v.littleEndian) { d.append(contentsOf: $0) } }
        func u16(_ v: UInt16) { withUnsafeBytes(of: v.littleEndian) { d.append(contentsOf: $0) } }
        d.append(contentsOf: Array("RIFF".utf8)); u32(36 + данных)
        d.append(contentsOf: Array("WAVE".utf8))
        d.append(contentsOf: Array("fmt ".utf8)); u32(16); u16(1); u16(1)
        u32(частота); u32(частота * 2); u16(2); u16(16)
        d.append(contentsOf: Array("data".utf8)); u32(данных)
        d.append(Data(repeating: 0, count: сэмплов * 2))
        return d
    }
}
