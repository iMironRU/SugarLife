import Foundation
import AVFoundation
import UIKit

/**
 Не дать системе усыпить приложение, когда будить его нечем (#388).

 Фоновый режим `bluetooth-central` (#379) решает половину задачи: приложение просыпается, когда прибор
 что-то прислал. Но **у человека на одном облаке прибора нет вовсе** — ни сенсора, ни моста. Будить нас
 нечем: iOS приостанавливает процесс, и данные из Nightscout перестают приходить до следующего открытия.
 Именно так живёт наблюдатель — родитель, который смотрит на чужой сенсор, — и ему свежесть цифры важнее
 всех.

 Приём взят у xDrip4iOS: проигрывать **миллисекунду тишины** раз в несколько секунд. Фоновый режим `audio`
 не даёт системе приостановить процесс.

 Две вещи здесь важнее самого приёма, и обе от них же:

  — включается **только при уходе в фон**: на экране оно не нужно и батарею не ест;
  — это **выбор человека**, а не наша самодеятельность. По умолчанию выключено. Честная сделка: живость
    против батареи, и решает тот, чей телефон.

 Звук строим в коде, а не носим файлом: сорок четыре нулевых сэмпла с заголовком WAV — это сотня байт,
 которую видно целиком. Ресурс пришлось бы объяснять всякому, кто откроет проект.
 */
final class ФоновоеБодрствование {

    enum Режим: String, CaseIterable {
        case выключено, обычное, настойчивое

        /// Как часто напоминать системе о себе. У xDrip4iOS ровно эти числа: 5 и 2 секунды.
        var интервал: TimeInterval? {
            switch self {
            case .выключено: return nil
            case .обычное: return 5
            case .настойчивое: return 2
            }
        }
    }

    static let shared = ФоновоеБодрствование()

    private let ключ = "sugarlife.background-keep-alive"
    /* СЛЕД В ЖУРНАЛЕ ДВИЖКА, А НЕ ТОЛЬКО В NSLog (#593).

       Опора умирает не на глазах у разработчика, а ночью в кармане. NSLog виден только тому, кто в
       эту минуту держит телефон подключённым к Xcode; журнал движка выгружается с устройства и
       читается утром. Молчаливо умирающий механизм неотличим от работающего — это тот же урок, что с
       баннером, который писал только удачные исходы. */
    var вЖурнал: ((_ уровень: String, _ событие: String) -> Void)?

    /* ФАКТ, А НЕ НАМЕРЕНИЕ. `режим` — это настройка, то есть чего человек хотел. Держим ли мы звук на
       самом деле — отдельный вопрос, и отвечать на него надо отдельно: сессию могли отобрать. */
    var держимЗвук: Bool { проигрыватель?.isPlaying == true }

    private var проигрыватель: AVAudioPlayer?
    private var таймер: DispatchSourceTimer?
    /// Сколько тиков подряд звук не пошёл. Нужен, чтобы писать в журнал один раз, а не каждые пять секунд.
    private var молчалиПодряд = 0
    /// Сколько тиков опора отработала. Нужен, чтобы докладывать «играю» раз в пять минут, а не каждые пять секунд.
    private var тиков = 0
    /// Играл ли чужой звук на прошлом тике — чтобы переспрашивать движок на смене, а не каждые пять секунд.
    private var чужойБыл = false
    /* Ответ движка «держать ли опору» (мост 1.51). nil — снимка ещё не было: держим, как и он сам
       велит для незнакомого маршрута. Хранится фактом, а не выводится из настройки. */
    var держатьПоДвижку: Bool?
    private let очередь = DispatchQueue(label: "ru.imiron.sugarlife.keepalive")

    private(set) var режим: Режим {
        get { Режим(rawValue: UserDefaults.standard.string(forKey: ключ) ?? "") ?? .выключено }
        set { UserDefaults.standard.set(newValue.rawValue, forKey: ключ) }
    }

    private init() {}

    /// Подписаться на уход в фон и возвращение. Зовётся один раз, при старте плагина.
    func начать() {
        NotificationCenter.default.addObserver(
            self, selector: #selector(ушлиВФон),
            name: UIApplication.didEnterBackgroundNotification, object: nil)
        NotificationCenter.default.addObserver(
            self, selector: #selector(вернулись),
            name: UIApplication.willEnterForegroundNotification, object: nil)
        /* ПРЕРЫВАНИЕ — ГЛАВНАЯ ДЫРА, И ОНА БЫЛА ОТКРЫТА (#593).

           Позвонили, другое приложение взяло звук монопольно, магнитола перехватила маршрут — сессию
           у нас отбирают, проигрыватель останавливается. Таймер после этого продолжал тикать и звать
           `play()` в деактивированную сессию: вернуть её можно только повторным `setActive(true)`,
           которого мы не делали нигде, кроме входа в фон.

           То есть после ЛЮБОГО прерывания опора молча умирала до следующего открытия приложения.
           Выключатель в «Охране» показывал «включено», а тишина не играла — и никто об этом не знал. */
        NotificationCenter.default.addObserver(
            self, selector: #selector(прерваны(_:)),
            name: AVAudioSession.interruptionNotification, object: nil)
        /* Сброс медиа-служб системой: проигрыватель и сессия становятся негодными целиком, их надо
           создавать заново. Случается редко, но молча. */
        NotificationCenter.default.addObserver(
            self, selector: #selector(медиаСброшены),
            name: AVAudioSession.mediaServicesWereResetNotification, object: nil)
        /* СМЕНА МАРШРУТА — ПОВОД ПЕРЕСМОТРЕТЬ ОПОРУ, а не только повод для тревог.

           В машину садятся с уже усыплённым приложением: телефон в кармане, опора держится, и вот
           появился CarPlay. Решать только при уходе в фон значило бы отпускать магнитолу лишь
           тогда, когда человек откроет приложение и снова его закроет. */
        NotificationCenter.default.addObserver(
            self, selector: #selector(маршрутСменился),
            name: AVAudioSession.routeChangeNotification, object: nil)

        /* ЗАПУСК СРАЗУ В ФОНЕ — И ЭТО НЕ РЕДКОСТЬ, А НАШ ОБЫЧНЫЙ СПОСОБ ПРОСНУТЬСЯ.

           Опора вставала только по `didEnterBackground`. Но это событие приходит, когда человек
           СВЕРНУЛ приложение, — а нас гораздо чаще поднимает система: после того как выгрузила,
           по уведомлению, при подключении к машине. Тогда мы стартуем в фоне, перехода «в фон» не
           происходит вовсе, опора не встаёт — и через полторы минуты нас усыпляют снова.

           Видно это стало сразу, как журнал начал писать оба исхода: телефон лежал заблокированный,
           приложение поднялось, и в журнале за всю его короткую жизнь НЕТ строки про уход в фон.
           А дальше тишина. Утренний ряд — 6, 8, 10, 12 минут — это он и есть: система будит, мы не
           вооружаемся, умираем, она будит снова.

           Когда человек открывает приложение сам и потом гасит экран, переход происходит, опора
           встаёт, и живём мы 60–88 минут. Разница ровно в этом. */
        if UIApplication.shared.applicationState != .active { применить() }
    }

    /// Пересмотреть опору: решение движка изменилось или сменился маршрут. Только в фоне.
    func пересмотреть() { маршрутСменился() }

    /* ВЕРНУТЬ ЗВУК В ОБЩИЙ РЕЖИМ ПОСЛЕ ТРЕВОГИ.

       Тревога берёт сессию с `.duckOthers` — приглушить остальных, иначе её не услышат. А отпускала
       она только громкость: категорию никто не возвращал. То есть после ПЕРВОЙ ЖЕ ночной тревоги
       сессия навсегда оставалась приглушающей, и музыка человека звучала тише, пока он не
       перезапустит приложение. Заметить это почти нельзя: связь между «ночью пищало» и «днём тихо
       играет» человек не проведёт.

       Категорию возвращаем ВСЕГДА, даже если опора не нужна: приглушение чужого звука — не наше
       право, и держать его после того, как тревога отзвучала, нечем оправдать.

       Решает здесь опора, а не тревога: категория — её хозяйство, и знать правильную должна она
       одна. Тревога только говорит «я отзвучала». */
    func вернутьОбщийРежим() {
        do {
            try AVAudioSession.sharedInstance().setCategory(.playback, options: [.mixWithOthers])
        } catch {
            вЖурнал?("Warn", "не вернули общий режим звука: \((error as NSError).localizedDescription)")
            return
        }
        /* Опора после чужой сессии могла остаться немой — поднимаем её тем же путём, что при
           обычном отказе, а не своим третьим. */
        if таймер != nil { проигрыватель = nil; применить() }
    }

    @objc private func маршрутСменился() {
        /* Только в фоне: на переднем плане опора не нужна вовсе, приложение и так живо. */
        DispatchQueue.main.async { [weak self] in
            guard UIApplication.shared.applicationState == .background else { return }
            self?.применить()
        }
    }

    @objc private func прерваны(_ уведомление: Notification) {
        guard let код = уведомление.userInfo?[AVAudioSessionInterruptionTypeKey] as? UInt,
              let вид = AVAudioSession.InterruptionType(rawValue: код) else { return }
        switch вид {
        case .began:
            вЖурнал?("Warn", "опора прервана — звук у нас отобрали")
        default:
            /* Прерывание кончилось. Поднимаемся, только если мы в фоне и режим включён: на переднем
               плане опора не нужна, а включать её там значило бы жечь заряд впустую. */
            guard UIApplication.shared.applicationState == .background, режим != .выключено else { return }
            вЖурнал?("Info", "опора поднимается после прерывания")
            применить()
        }
    }

    @objc private func медиаСброшены() {
        проигрыватель = nil
        guard UIApplication.shared.applicationState == .background, режим != .выключено else { return }
        вЖурнал?("Warn", "медиа-службы сброшены — опору собираем заново")
        применить()
    }

    func установить(_ новый: Режим) {
        режим = новый
        NSLog("SugarLife: фоновое бодрствование — \(новый.rawValue)")
        // Меняют настройку обычно на экране, то есть на переднем плане: тогда просто запомнили. Но если
        // приложение уже в фоне (настройку изменили из шторки/через мост) — применяем сразу.
        if UIApplication.shared.applicationState == .background { применить() } else { остановить() }
    }

    @objc private func ушлиВФон() { применить() }
    @objc private func вернулись() { остановить() }

    /// Поднимаем ли опору повторно после немоты — только ради честной строки в журнале.
    private var поднимаемЗаново = false

    private func применить() {
        /* УХОД В ФОН ОСТАВЛЯЕТ СЛЕД ВСЕГДА — И КОГДА ОПОРУ ПОДНЯЛИ, И КОГДА НЕТ.

           За сутки приложение убили 21 раз, и разобраться почему было НЕЧЕМ: в журнале за все
           эти часы нет ни одной записи с тегом keepalive. Ни одной — потому что писали мы только
           про поломки, а самый частый исход тут не поломка, а вот этот `guard`: режим выключен,
           выходим молча.

           Значит «опора не поднималась никогда» и «опора работала и упала» выглядели одинаково —
           пустотой. Ровно то, против чего мы завели правило 8 и что ядро записало инвариантом 6:
           если запись делается при одном исходе, её отсутствие означает две разные беды.

           Утром мы закрыли это у баннера и у тревог, а здесь пропустили — и потеряли на этом день. */
        guard let интервал = режим.интервал else {
            вЖурнал?("Info", "ушли в фон без опоры: фоновое бодрствование выключено")
            остановить()
            return
        }
        /* ДЕРЖАТЬ ЛИ ОПОРУ — РЕШАЕТ ДВИЖОК (мост 1.51, ядро #149).

           Здесь стояла наша копия правила: «маршрут car → не держим». Правило было верное — мы взяли
           его дословно из ЗвуковаяОбстановка.kt, — но копия чужого решения живёт ровно до того дня,
           когда одна из двух сторон его поправит и не скажет.

           Теперь маршрут по-прежнему наблюдаем мы (к чему подключён телефон, знает только оболочка) и
           сообщаем его в reportDelivery, а обратно приезжает разобранный ответ: держать или нет.
           Заодно бесплатно получили наушники и колонку, о которых наша копия не знала вовсе.

           Пока ответа нет — держим. Это умолчание самого движка: незнакомый маршрут он считает
           телефоном, «не запрещаем себе ничего из-за того, чего не поняли». */
        if держатьПоДвижку == false {
            вЖурнал?("Info", "ушли в фон без опоры: движок не велел при маршруте \(Тревоги.маршрутЗвука())")
            остановить()
            return
        }
        do {
            // `.playback` — единственная категория, которая продолжает жить в фоне. `.mixWithOthers`
            // обязателен: без него мы остановим музыку или подкаст человека ради своей тишины.
            try AVAudioSession.sharedInstance().setCategory(.playback, options: [.mixWithOthers])
            try AVAudioSession.sharedInstance().setActive(true)
        } catch {
            /* Не смогли занять сессию — опоры нет. Сказать об этом обязаны: выключатель в «Охране»
               по-прежнему показывает «включено», и молчание здесь читается как «всё в порядке». */
            NSLog("SugarLife: не удалось занять аудио-сессию (\(error)) — фоновое бодрствование не работает")
            /* Текст ошибки, а не общая фраза: «сессию не отдали» одинаково звучит и когда её держит
               звонок, и когда категория несовместима, — а чинится это по-разному. */
            вЖурнал?("Error", "опору не подняли: \((error as NSError).localizedDescription) "
                + "(код \((error as NSError).code))")
            return
        }
        if проигрыватель == nil {
            проигрыватель = try? AVAudioPlayer(data: тишина())
            проигрыватель?.volume = 0
            /* ТИШИНА ИГРАЕТ НЕПРЕРЫВНО, А НЕ ТОЛЧКАМИ (SugarLife#650).

               Было: миллисекунда тишины раз в пять секунд. То есть 4999 миллисекунд из 5000 сессия
               была жива, но не играла ничего, — для системы это приложение, которое звук почти не
               использует, и выносит она такое первым.

               28 августа это стало видно рядом: на телефоне владельца сенсоров нет, xDrip читает тот
               же Nightscout тем же приёмом с тишиной — и в момент проверки он был жив, а нас в списке
               процессов не было вовсе. Данные одни, телефон один, разный только сон.

               Заодно это добивает мерцание чужого звука в корне (#647): без пульса нет и фазы, в
               которую мы попадали, слушая сами себя. Гистерезис остаётся вторым рубежом.

               Таймер ниже становится сторожем: он не заводит звук каждые пять секунд, а проверяет,
               не остановили ли нас, — и поднимает заново. */
            проигрыватель?.numberOfLoops = -1
            проигрыватель?.prepareToPlay()
        }
        таймер?.cancel()
        let t = DispatchSource.makeTimerSource(queue: очередь)
        t.schedule(deadline: .now(), repeating: интервал)
        t.setEventHandler { [weak self] in
            guard let self, let p = self.проигрыватель, !p.isPlaying else { return }
            /* РЕЗУЛЬТАТ ПРОВЕРЯЕМ. `play()` возвращает, получилось ли, и мы его игнорировали: в
               мёртвой сессии он молча отвечает «нет» каждые пять секунд, а наружу это выглядит
               работающей опорой.

               Пишем один раз на серию неудач, а не каждый тик: пять записей в секунду забьют журнал,
               в котором мы же потом будем искать причину. */
            if p.play() {
                if self.молчалиПодряд > 0 { self.вЖурнал?("Info", "опора снова играет") }
                self.молчалиПодряд = 0
                /* ЖИВА ЛИ ОПОРА — ГОВОРИМ РЕГУЛЯРНО, А НЕ ТОЛЬКО КОГДА СЛОМАЛАСЬ.

                   Карточка перестала принимать обновления, и различить две причины оказалось нечем:
                   система их не применяет — или мы живы урывками, потому что опора молчит. Первое от
                   второго отличается ровно этой строкой, и её не было: успех мы писали только как
                   «снова играет», то есть после поломки.

                   Раз в пять минут: чаще незачем, а реже — и вопрос снова останется без ответа.
                   Тик у опоры пятисекундный, поэтому считаем тики, а не заводим второй таймер. */
                self.тиков += 1
                if self.тиков % 60 == 0 {
                    self.вЖурнал?("Info", "опора играет, маршрут \(Тревоги.маршрутЗвука())")
                }
                /* ЧУЖОЙ ЗВУК ПОЯВИЛСЯ ИЛИ ПРОПАЛ — ПЕРЕСПРАШИВАЕМ ДВИЖОК.

                   В машине это разница между «человек слушает музыку с телефона» и «играет радио»:
                   в первом случае магнитола уже наша и опору держать можно, во втором нет. Ядро
                   решает по факту, который видим только мы, — значит менять решение надо в ту
                   секунду, когда факт изменился, а не при следующем уходе в фон.

                   Песня кончилась, человек нажал паузу, началась реклама на радио — всё это меняет
                   ответ, и ждать перехода в фон здесь значит ждать никогда. */
                /* Та же проверка, что у дозора: два места, читающих один признак по-своему, —
                   ровно та беда, которую мы весь день разгребали в другом месте. */
                self.проверитьЧужойЗвук()
            } else {
                self.молчалиПодряд += 1
                /* НЕМУЮ ОПОРУ ПОДНИМАЕМ, А НЕ ПРОСТО ЗАПИСЫВАЕМ.

                   Здесь стояла одна строка в журнал — и всё. Мы честно сообщали, что звук не идёт,
                   и продолжали не идти: таймер тикал в мёртвую сессию, а через несколько секунд нас
                   усыпляли. В журнале это выглядело так:

                     16:43:13  опора не играет: сессия не принимает звук
                     16:43:20  последняя запись — приложение остановилось

                   Запись без попытки починиться — это молчаливый отказ, просто с подписью. Правило
                   8 требует следа, но след не заменяет действия.

                   Пересобираем сессию и проигрыватель целиком: `setActive(true)` в занятой сессии не
                   помогает, если проигрыватель уже негоден, а различить это отсюда нельзя.

                   Раз в 3 промаха (15 секунд) — чаще незачем: если сессию держит звонок, частые
                   попытки её не отнимут, а батарею потратят. */
                if self.молчалиПодряд % 3 == 0 {
                    /* ПОЧЕМУ НЕ ИГРАЕТ — СПРАШИВАЕМ СИСТЕМУ, А НЕ СЕБЯ.

                       `play()` возвращает голое `false` без причины, и по нему нельзя отличить
                       «звук занят другим приложением» от «сессия не наша» или «проигрыватель негоден».
                       А отличать надо: это три разные починки, и наугад мы уже пробовали.

                       Спрашиваем ровно то, что система готова сказать: играет ли кто-то ещё, какая
                       категория действует на самом деле, есть ли выход. Ответ идёт в журнал вместе с
                       отказом — иначе следующий разбор снова упрётся в «не играет» без продолжения. */
                    let сессия = AVAudioSession.sharedInstance()
                    let чужой = сессия.isOtherAudioPlaying ? "да" : "нет"
                    let выходов = сессия.currentRoute.outputs.count
                    self.вЖурнал?("Error", "опора не играет: чужой звук \(чужой), категория "
                        + "\(сессия.category.rawValue), выходов \(выходов), громкость "
                        + "\(Int(сессия.outputVolume * 100))% — поднимаю заново")
                    self.проигрыватель = nil
                    self.поднимаемЗаново = true
                    DispatchQueue.main.async { [weak self] in
                        self?.применить()
                        self?.поднимаемЗаново = false
                    }
                }
            }
        }
        t.resume()
        таймер = t
        /* Опора играет — её тик и следит за признаком; второй дозор был бы вторым читателем. */
        дозор?.cancel(); дозор = nil
        NSLog("SugarLife: фоновое бодрствование включено, раз в \(интервал) с")
        /* И удачный исход — тоже в журнал. Без него запись остаётся односторонней, а односторонняя
           запись и есть двусмысленное молчание. Маршрут называем здесь же: по нему потом видно, что
           именно у нас отобрали, — наушники выдернули, магнитола перехватила, звонок пришёл. */
        /* «Ушли в фон» — только когда это правда. Повторный подъём после немоты зовёт ту же
           функцию, и одинаковая строка на два разных события снова сделала бы журнал
           двусмысленным — в третий раз за сутки на том же самом. */
        вЖурнал?("Info", (поднимаемЗаново ? "опора поднята заново" : "ушли в фон с опорой")
            + ": тик \(Int(интервал)) с, маршрут \(Тревоги.маршрутЗвука())")
    }

    private func остановить() {
        таймер?.cancel(); таймер = nil
        проигрыватель?.stop()
        try? AVAudioSession.sharedInstance().setActive(false, options: [.notifyOthersOnDeactivation])
        /* НО ЗА ЧУЖИМ ЗВУКОМ ПРОДОЛЖАЕМ СЛЕДИТЬ (ядро #155).

           Ядро держит опору в машине после минуты непрерывной музыки и отпускает в ту же секунду,
           как она кончилась. Вся конструкция стоит на том, что смену признака мы доносим мгновенно.

           А наблюдение жило ВНУТРИ тика опоры — и выключалось вместе с ней. То есть в машине с
           радио мы переставали замечать, что человек включил музыку, и правило не могло сработать
           НИКОГДА: чтобы узнать про музыку, нужна опора, а чтобы поднять опору, нужно узнать про
           музыку.

           Поэтому дозор отдельный и дешёвый: ни сессии, ни звука, только чтение признака. */
        завестиДозор()
    }

    /* Дозор за чужим звуком. Работает, когда опоры нет: пока она есть, признак читает её же тик. */
    private var дозор: DispatchSourceTimer?

    private func завестиДозор() {
        дозор?.cancel()
        let d = DispatchSource.makeTimerSource(queue: очередь)
        /* Десять секунд: музыку человек включает не мгновенно, а держать чаще незачем — чтение
           признака дёшево, но не бесплатно, и мы в фоне. */
        d.schedule(deadline: .now() + 10, repeating: 10)
        d.setEventHandler { [weak self] in self?.проверитьЧужойЗвук() }
        d.resume()
        дозор = d
    }

    /* ЧУЖОЙ ЗВУК МЕРЦАЕТ, И МЕРЦАЕТ НЕ ОН (SugarLife#647).

       28 августа журнал показал ровный маятник: «появился» — «пропал» — «появился», строго каждые
       пять секунд, тысячами. Никакой музыки при этом не было.

       Мы читали признак В ТАКТ С СОБСТВЕННЫМ ПУЛЬСОМ. Опора играет миллисекунду тишины раз в пять
       секунд, рядом ровно так же пульсирует xDrip, и между пульсами `isOtherAudioPlaying` честно
       отвечает «нет», а во время — «да». Опрос попал в фазу и снимал то одно, то другое.

       Цена оказалась не в мусоре в журнале. Каждый переворот дёргал движок отчётом о доставке —
       раз в пять секунд, в фоне, круглые сутки. Приложение стало умирать вчетверо чаще: медиана
       жизни упала с нескольких часов до двадцати пяти минут.

       Поэтому смене верим не сразу, а когда она продержится. Мгновенный признак — не факт: факт
       здесь тот, что человек включил музыку, а он длится минуты, не секунды.

       ТРИДЦАТЬ СЕКУНД. Ядро держит опору в машине после МИНУТЫ непрерывной музыки — половина
       этого срока сигналу не мешает. В обратную сторону, «музыка кончилась», мы теперь на полминуты
       медленнее: платим опорой, которая подержится лишние тридцать секунд. По сравнению с признаком,
       который врал каждые пять секунд, это дёшево. */
    private var чужойКандидат: Bool?
    private var кандидатС: CFAbsoluteTime = 0
    private let УСТОЙЧИВОСТЬ: CFTimeInterval = 30

    /// Сменился ли чужой звук — и если смена УСТОЯЛА, сказать движку.
    private func проверитьЧужойЗвук() {
        let чужой = AVAudioSession.sharedInstance().isOtherAudioPlaying
        /* Вернулось к тому, во что мы верим, — кандидат больше не кандидат. */
        if чужой == чужойБыл { чужойКандидат = nil; return }
        let сейчас = CFAbsoluteTimeGetCurrent()
        /* Первый раз видим другое — засекаем. Маятник сюда и попадает: он переворачивается на
           каждом опросе, срок не набирается никогда, и движок мы больше не дёргаем. */
        guard чужойКандидат == чужой else { чужойКандидат = чужой; кандидатС = сейчас; return }
        guard сейчас - кандидатС >= УСТОЙЧИВОСТЬ else { return }
        чужойКандидат = nil
        чужойБыл = чужой
        вЖурнал?("Info", "чужой звук \(чужой ? "появился" : "пропал") — держится \(Int(сейчас - кандидатС)) с, переспрашиваю")
        DispatchQueue.main.async { Тревоги.общие.доложитьОДоставке() }
    }

    /// Миллисекунда тишины: заголовок WAV и сорок четыре нулевых сэмпла при 44.1 кГц, моно, 16 бит.
    private func тишина() -> Data {
        let частота: UInt32 = 44_100
        let сэмплов = 44                        // ≈ 1 мс
        let данных = UInt32(сэмплов * 2)
        var d = Data()
        func u32(_ v: UInt32) { withUnsafeBytes(of: v.littleEndian) { d.append(contentsOf: $0) } }
        func u16(_ v: UInt16) { withUnsafeBytes(of: v.littleEndian) { d.append(contentsOf: $0) } }
        d.append(contentsOf: Array("RIFF".utf8)); u32(36 + данных)
        d.append(contentsOf: Array("WAVE".utf8))
        d.append(contentsOf: Array("fmt ".utf8)); u32(16); u16(1); u16(1)
        u32(частота); u32(частота * 2); u16(2); u16(16)
        d.append(contentsOf: Array("data".utf8)); u32(данных)
        d.append(Data(repeating: 0, count: сэмплов * 2))
        return d
    }
