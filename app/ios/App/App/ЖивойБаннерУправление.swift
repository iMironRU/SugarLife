enum СрокиКарточки {
    /// Не чаще этого шлём изменившееся число той же зоны (#649).
    static let порогЧислаСек: TimeInterval = 5 * 60
    /* ЗАПАС ДОЛЖЕН ПЕРЕЖИТЬ НАШ СОБСТВЕННЫЙ ПОРОГ, А НЕ РОВНО ЕГО (#428, измерено 3 сентября).

       Здесь была минута сверху — «на дорогу». Расчёт молчаливо предполагал, что кормим мы карточку
       РОВНО раз в пять минут. На живом телефоне вышло иначе: порог отсчитывается от прошлой
       отправки, а отправляем мы на ПРИХОДЕ показания, и показания идут своим тактом. Замер:

         10:55:35  карточка обновлена, годна 6 мин   → срок истекал в 11:01:35
         11:01:18  следующее кормление               → 342 с, запас 18 секунд

       Восемнадцать секунд — это не запас, это совпадение. Любая заминка — и карточка тускнеет
       между двумя нашими же кормлениями. Ровно та беда, которую мы разбирали в #651 и решили, что
       закрыли: «мы сами назначили ей срок короче, чем сами же собирались её кормить».

       Две минуты вместо одной: порог плюс такт источника с запасом. Цена названа честно — карточка
       на две минуты дольше выглядит свежей, чем строго заслуживает. Но потолок в пятнадцать минут
       никуда не делся, и он же главный: старое показание протухнет по нему, а не по этому запасу. */
    /* Не чаще этого просим перерисовку, когда на карточке НИЧЕГО не изменилось. Живёт здесь, а не
       в плагине, потому что от него зависит срок годности: два места — два расхождения. */
    static let порогПовтораСек: TimeInterval = 10 * 60

    /* ЗАПАС СЧИТАЕМ ОТ ХУДШЕГО ПОРОГА, А НЕ ОТ ЛУЧШЕГО (#428, замер 3 сентября, второй заход).

       Утром я поправил запас с одной минуты до двух — и поправил не от того числа. Считал от
       пятиминутного порога (число изменилось), а карточка чаще живёт по десятиминутному: пока
       сахар стоит на месте, обновлять нечего, и мы молчим десять минут.

       На живом телефоне это дало ровно ту же дыру, только шире:

         11:42:20  карточка обновлена, годна ещё 452 с   → протухнет в 11:49:52
         11:52:20  раньше этого мы её не тронем          → 2,5 минуты протухшей

       Владелец увидел это как «баннер не обновляется» — и был прав: карточка стояла на 14,0 и
       выглядела мёртвой, потому что мы сами запретили себе её кормить.

       Считаем от большего порога: пока мы живы и данные есть, карточка не должна тускнеть между
       нашими же кормлениями. Потолок в пятнадцать минут от показания не тронут и остаётся главным
       — устаревшие данные обязаны выглядеть устаревшими, и вот это как раз правда. */
    static var запасПротуханияСек: TimeInterval { порогПовтораСек + 2 * 60 }
}

@available(iOS 16.2, *)
enum ЖивойБаннер {
    #if canImport(ActivityKit)
    private static var текущий: Activity<СахарАтрибуты>?

    /* ОБНОВЛЕНИЯ ИДУТ ПО ОДНОМУ, А НЕ ВНАХЛЁСТ (#428, приём xDrip — первый же комментарий у них).

       Их слова: «ActivityKit updates are serialized so a second request cannot race an update
       already in progress. If another request arrives while ActivityKit is updating, only the
       newest content needs to follow it.» Под это у них построена целая очередь.

       У нас каждое обновление порождало свою задачу, ни с кем не согласованную, — и в журнале
       3 сентября стоят три обновления за 82 секунды. Если ActivityKit и правда теряет то, что
       пришло поверх незаконченного, мы теряли их сами и валили это на систему.

       Держим ровно одно в полёте. Пришло новое, пока идёт старое, — запоминаем ПОСЛЕДНЕЕ и
       отдаём его следом: промежуточные числа никому не нужны, на экране должно быть текущее. */
    private static var идётОбновление = false
    private static var ждётОтдачи: (СахарАтрибуты.ContentState, Date, String)?

    /* ЧТО ПОКАЗАТЬ, КОГДА РОДИТЬ НАКОНЕЦ РАЗРЕШАТ (#428).

       Рождение возможно только из переднего плана, а показание приходит когда придёт — чаще всего
       в фоне. Без этой памяти карточка рождалась бы с тем числом, которое случайно совпало с
       моментом открытия приложения, а не с последним известным. */
    private static var отложенное: (СахарАтрибуты.ContentState, String, Date)?

    /* ВРЕМЯ ВЫПОЛНЕНИЯ ПОД АСИНХРОННУЮ РАБОТУ (#428, приём xDrip со ссылкой на документацию Apple).

       ActivityKit разрешает обновлять карточку из фона, но само обновление асинхронно, а приложение
       в фоне могут усыпить между вызовом и его завершением. Тогда наружу это выглядит как «система
       не приняла», хотя система его и не видела.

       Просим у системы время явно. Если она отказала — работу всё равно делаем: хуже, чем без
       просьбы, не будет, а строка в журнале объяснит, почему обновление могло не доехать. */
    @discardableResult
    private static func сБюджетомФона<T>(_ дело: () throws -> T) rethrows -> T {
        let билет = UIApplication.shared.beginBackgroundTask(withName: "Живая карточка")
        defer { if билет != .invalid { UIApplication.shared.endBackgroundTask(билет) } }
        if билет == .invalid {
            вЖурнал?("Debug", "система не дала времени на фоновую работу с карточкой")
        }
        return try дело()
    }

    /* КОГДА ЧИСЛУ НА БАННЕРЕ ВЕРИТЬ УЖЕ НЕЛЬЗЯ (#500).

       Баннер может застрять: приложение усыпили, система придержала обновления, сеть пропала. Число
       при этом остаётся на экране блокировки и выглядит текущим — самый опасный вид вранья, какой
       здесь возможен. Срок годности показания система знает от нас и по нему приглушает карточку
       сама, даже если приложение уже не исполняется.

       Пятнадцать минут — ровно тот порог, по которому приложение объявляет разрыв (#530). Раньше
       здесь стояло двенадцать, и это давало два разных ответа об одном молчании: система считала
       показание протухшим на три минуты раньше, чем это же признавало приложение. */
    private static func устарело(_ когдаМс: Double, следующее: Date? = nil) -> Date {
        let поПоказанию = Date(timeIntervalSince1970: когдаМс / 1000 + 15 * 60)
        /* НО НЕ ДОЛЬШЕ, ЧЕМ ЖДЁМ СЛЕДУЮЩЕЕ ПОКАЗАНИЕ ПЛЮС ЗАПАС.

           Владелец: «таймер ушёл в минуса». Так и есть: счётчик до следующего показания рисует
           система, он идёт сам и уходит за ноль, — а поле «опаздывает» заморожено в момент
           последнего кормления и говорит «всё по расписанию». Живой счётчик против мёртвого флага:
           карточка противоречит сама себе, и права в ней живая половина.

           Пятнадцать минут были рассчитаны на пятиминутный такт. У минутного источника это
           четырнадцать минут вранья на экране блокировки.

           Запас берём от порога отправки (`запасПротуханияСек`), а не числом: пока мы шлём раз в
           пять минут, срок обязан переживать эти пять минут, иначе карточка умирает между нашими
           же кормлениями. Потолок в пятнадцать минут остаётся: правило разрыва одно на все
           поверхности. */
        guard let следующее else { return поПоказанию }
        return min(поПоказанию, следующее.addingTimeInterval(СрокиКарточки.запасПротуханияСек))
    }

    static func обновить(
        значение: String, стрелка: String, разница: String, когдаМс: Double, старое: Bool, источник: String,
        ряд: [СахарАтрибуты.ContentState.Точка] = [], mmol: Double? = nil, зона: String = "коридор",
        инсулин: String = "", прогноз: Double? = nil, разрыв: Bool = false, последнее: String = "",
        /* КОГДА ЖДАТЬ СЛЕДУЮЩЕЕ — РЕШАЕТ ЗВАВШИЙ (мост 1.41). Здесь мы про это ничего не знаем: такт
           измеряет движок, а пять минут были нашим допущением и врали у минутных источников. */
        следующее: Date? = nil, опоздание: Int = 0
    ) -> String {
        let когда = Date(timeIntervalSince1970: когдаМс / 1000)
        let состояние = СахарАтрибуты.ContentState(
            значение: значение,
            стрелка: стрелка,
            разница: разница,
            когда: когда,
            старое: старое,
            ряд: ряд,
            mmol: mmol,
            зона: зона,
            инсулин: инсулин,
            прогноз: прогноз,
            следующее: разрыв ? nil : (следующее ?? когда.addingTimeInterval(5 * 60)),
            разрыв: разрыв,
            последнее: последнее,
            опоздание: опоздание
        )

        /* Человек мог выключить живые уведомления в настройках телефона — это его право, и
           обходить его нечем. Говорим правду наверх, чтобы экран мог объяснить, почему
           баннера нет, вместо того чтобы молча ничего не делать. */
        guard ActivityAuthorizationInfo().areActivitiesEnabled else { return "выключено в настройках" }

        /* ОБНОВЛЯЕМ ТОЛЬКО ЖИВУЮ АКТИВНОСТЬ, И ПРОВЕРЯЕМ, ЧТО ОНА ЖИВА (#559).

           Владелец увидел баннер, простоявший 54 минуты, — при том что тихая сводка в шторке в те же
           минуты обновлялась исправно. Значит приложение работало, данные шли, а `update` уходил в
           пустоту.

           Так и было: мы держали ссылку на активность и обновляли её, не спрашивая, в каком она
           состоянии. Система же могла её завершить — по своему сроку, из-за смахивания, после
           перезагрузки, — и тогда `update` не делает ничего. Молча: ошибки нет, исключения нет,
           мы рапортуем «обновлено» и ждём следующего показания, чтобы снова ничего не сделать.

           Теперь мёртвую ссылку выбрасываем и поднимаем баннер заново. `.stale` живой: это наше же
           «показание протухло», и обновление его как раз оживит. */
        let живая = [текущий, Activity<СахарАтрибуты>.activities.first]
            .compactMap { $0 }
            .first { $0.activityState == .active || $0.activityState == .stale }

        if let активный = живая {
            текущий = активный
            слушатьПрименённое(активный)
            /* ИСХОД ОБНОВЛЕНИЯ — ФАКТ, А НЕ НАМЕРЕНИЕ (правило 9).

               Здесь мы возвращали «обновлено» СРАЗУ, не дожидаясь самого обновления: `update` живёт
               в отдельной задаче, и к моменту нашего ответа она ещё не начиналась. То есть журнал
               писал, что мы обновили карточку, ровно в тех случаях, когда мы этого не сделали, —
               включая тот, где приложение усыпили между вызовом и задачей.

               Владелец увидел «Не обновляется» на экране блокировки в минуту, когда журнал говорил
               «обновлено», данные были свежими, а приложение живым. Разобрать это оказалось нечем:
               инструмент отвечал за нас, а не за систему.

               Теперь пишем ПОСЛЕ обновления и называем состояние активности, каким его видит
               ActivityKit. `.stale` при свежем сроке годности означает, что система наше обновление
               не приняла, — и это совсем другой разговор, чем «мы не отдали». */
            let сроку = устарело(когдаМс, следующее: следующее)
            /* СКОЛЬКО ВЕСИТ СОДЕРЖИМОЕ (#530).

               У живой карточки жёсткий предел — четыре килобайта на состояние. Превысил — обновление
               отбрасывается МОЛЧА: ни ошибки, ни исключения. Ровно та картина, что у нас: создание
               доходит, пятнадцать следующих обновлений нет.

               Гадать о размере нельзя: в состоянии лежит ряд для графика, и сколько он весит после
               кодирования, известно только кодировщику. Меряем и пишем — если предел близко, это
               видно числом, а не рассуждением о количестве точек. */
            let вес = (try? JSONEncoder().encode(состояние).count) ?? -1
            if вес > 3500 || вес < 0 {
                вЖурнал?("Warn", "содержимое карточки \(вес) Б — предел 4096, обновление может"
                    + " отбрасываться молча")
            }
            /* `@MainActor` не для порядка: `UIApplication` живёт на главном потоке, и просить у
               него время из фоновой задачи — ошибка, которую Swift 6 уже не прощает. */
            /* Очередь живёт на главном потоке: `UIApplication` спрашивать больше неоткуда, а
               гонку двух обновлений мы как раз и убираем. */
            Task { @MainActor in поставитьВОчередь(активный, состояние, сроку, вес) }
            return "обновлено"
        }
        /* Ссылка была, но активность мертва — забываем её, иначе следующий заход снова возьмёт
           труп из `текущий` и снова ничего не обновит. */
        if текущий != nil {
            NSLog("SugarLife: баннер был закрыт системой — поднимаем заново")
            текущий = nil
        }

        /* УСТАРЕВШЕЕ ПОКАЗАНИЕ НЕ СОЗДАЁТ БАННЕР (правило 6, docs/поверхности-показа.md).

           Обновить живую карточку старым числом правильно: человек должен видеть, что она постарела.
           А вот СОЗДАТЬ карточку ради старого числа незачем — она объявление, а «вот число
           семичасовой давности» объявлением не является.

           Ловится этим и storm на старте: движок дочитывает историю, и каждая прошлая точка приезжает
           как «последнее показание». В журнале это шесть перерисовок за девять секунд числами от 7,4
           до 10,6 (#571). Все они устаревшие — значит ни одна баннер не поднимет. */
        if старое {
            return "старое — не поднимаем"
        }

        /* ТРУП РЯДОМ С ЖИВОЙ КАРТОЧКОЙ — ХУЖЕ, ЧЕМ ОТСУТСТВИЕ КАРТОЧКИ.

           Владелец увидел на экране блокировки мёртвый баннер в ту минуту, когда журнал писал
           «карточка обновлена: живая, годна до 14 мин» — и оба были правы. Карточек было две.

           Когда систем­а выгружает приложение, она завершает его активности сама, политикой по
           умолчанию: завершённая карточка остаётся на экране блокировки до четырёх часов. Наш поиск
           живой её не видел (мы берём только `.active` и `.stale`), мы поднимали новую — и рядом
           продолжал лежать замерший труп с числом получасовой давности.

           Два числа об одном сахаре на одном экране: ровно то, из-за чего человек перестаёт верить
           обоим. Поэтому перед созданием сметаем завершённые немедленно.

           `.immediate`, а не по умолчанию: политика по умолчанию и есть та, что оставила труп. */
        let трупы = Activity<СахарАтрибуты>.activities.filter {
            $0.activityState == .ended || $0.activityState == .dismissed
        }
        if !трупы.isEmpty {
            вЖурнал?("Info", "убрали завершённых карточек: \(трупы.count)")
            for т in трупы { Task { await т.end(nil, dismissalPolicy: .immediate) } }
        }

        /* РОДИТЬ КАРТОЧКУ МОЖНО ТОЛЬКО ИЗ ПЕРЕДНЕГО ПЛАНА (#428, разведка чужих исходников).

           Правило платформы, которого мы не знали. Обновлять живую карточку из фона можно свободно,
           а `Activity.request` из фона система отвергает — с ошибкой, в тексте которой стоит слово
           `foreground`. Ровно её мы и ловили 142 раза за сутки, не понимая, что это отказ РОЖДЕНИЯ,
           а не отказ обновления.

           Так делают все, у кого это видно в коде: xDrip4iOS откладывает старт до `.active`,
           GlucoseDirect и Trio проверяют то же самое перед созданием. Мы проверки не имели вовсе.

           Содержимое запоминаем: как только приложение окажется на переднем плане — само или по
           Быстрой команде, — карточка родится с ним, а не с пустотой. */
        guard UIApplication.shared.applicationState == .active else {
            отложенное = (состояние, источник, устарело(когдаМс, следующее: следующее))
            return "рождение отложено: приложение не на переднем плане"
        }

        do {
            let новая = try сБюджетомФона {
                try Activity.request(
                    attributes: СахарАтрибуты(источник: источник),
                    content: ActivityContent(state: состояние, staleDate: устарело(когдаМс, следующее: следующее)),
                    pushType: nil
                )
            }
            текущий = новая
            отложенное = nil
            слушатьПрименённое(новая)
            /* Хвост идентификатора — чтобы в журнале было видно, ту ли карточку мы потом кормим:
               «обновляем не ту» и «обновляем ту, а она не меняется» — разные беды. */
            вЖурнал?("Info", "карточка родилась, id \(новая.id.suffix(6)), карточек всего "
                + "\(Activity<СахарАтрибуты>.activities.count)")
            return "запущено"
        } catch {
            /* молча: след оставляет не эта ветка, а тот, кто нас позвал. Исход возвращается строкой,
               и `обновитьЖивойБаннер` пишет в журнал КАЖДЫЙ исход, включая этот. Дублировать запись
               здесь значило бы получить две строки об одном событии. */
            return "не удалось: \(error.localizedDescription)"
        }
    }

    static func погасить() {
        let все = Activity<СахарАтрибуты>.activities
        текущий = nil
        for а in все {
            Task { await а.end(nil, dismissalPolicy: .immediate) }
        }
    }

    /// Строка в журнал движка. Ставит плагин: сам движок отсюда не виден и не должен быть.
    static var вЖурнал: ((_ уровень: String, _ событие: String) -> Void)?

    /* ЧТО СИСТЕМА ПРИМЕНИЛА, А НЕ ЧТО МЫ ОТПРАВИЛИ (#530, третий заход к одному вопросу).

       Мы научились писать исход обновления по факту — и я решил, что этого хватает. Не хватает:
       `activityState == .active` означает «активность запущена и срок годности не вышел», и НИЧЕГО
       не говорит о том, доехало ли наше число до экрана. Я прочитал «живая» как «приняли» и сказал
       это владельцу увереннее, чем позволял инструмент.

       `contentUpdates` — поток содержимого, которое система ДЕЙСТВИТЕЛЬНО показала. Разница между
       «отправили 7,5» и «показано 7,4» видна только здесь.

       Подписываемся один раз на активность: поток живёт, пока жива она. */
    private static var слушаем = false

    @available(iOS 16.2, *)
    /* `default`, а не `@unknown default`: в этой SDK у ActivityState есть состояние, которого не
       было раньше (`.pending` для карточек, запускаемых push-ом), и перечислять их поимённо значит
       ломать сборку на каждом обновлении Xcode. Здесь это подпись в журнал, а не решение, — точность
       имени дешевле сборки. */
    /* ОЧЕРЕДЬ ОБНОВЛЕНИЙ: ровно одно в полёте (#428).

       Пришло новое, пока идёт старое, — держим только последнее. Промежуточные числа никому не
       нужны: на экране должно оказаться текущее, а не все по дороге. */
    @MainActor
    private static func поставитьВОчередь(
        _ активность: Activity<СахарАтрибуты>, _ состояние: СахарАтрибуты.ContentState,
        _ сроку: Date, _ вес: Int,
    ) {
        ждётОтдачи = (состояние, сроку, "\(вес)")
        guard !идётОбновление else {
            вЖурнал?("Debug", "обновление встало в очередь — предыдущее ещё идёт")
            return
        }
        идётОбновление = true
        Task { @MainActor in
            defer { идётОбновление = false }
            while let (сост, срок, вес) = ждётОтдачи {
                ждётОтдачи = nil
                await отдать(активность, сост, срок, вес)
            }
        }
    }

    @MainActor
    private static func отдать(
        _ активность: Activity<СахарАтрибуты>, _ состояние: СахарАтрибуты.ContentState,
        _ сроку: Date, _ вес: String,
    ) async {
        /* ГДЕ МЫ БЫЛИ В ЭТУ МИНУТУ (#428). Рождение работает только на переднем плане — это мы
           знаем. Работает ли оттуда же обновление, не знает никто, и без этой пометки в журнале
           различить фон от переднего плана нельзя: строки выглядят одинаково. */
        let где = UIApplication.shared.applicationState == .active ? "передний план" : "фон"
        let былаДо = имяСостояния(активность.activityState)
        /* Время выполнения — на всю асинхронную часть, а не на вызов: усыпить нас могут ровно
           между просьбой и её завершением. */
        let билет = UIApplication.shared.beginBackgroundTask(withName: "Обновление карточки")
        await активность.update(ActivityContent(state: состояние, staleDate: сроку))
        if билет != .invalid { UIApplication.shared.endBackgroundTask(билет) }
        let вСистеме = Activity<СахарАтрибуты>.activities
            .first { $0.id == активность.id }?.content.state.значение ?? "её уже нет"
        let легло = вСистеме == состояние.значение ? "ЛЕГЛО" : "не легло"
        вЖурнал?("Info", "карточка обновлена (\(где)): была \(былаДо) → "
            + "\(имяСостояния(активность.activityState)), отдали \(состояние.значение) — \(легло); "
            + "в системе \(вСистеме), годна ещё \(Int(сроку.timeIntervalSinceNow)) с, "
            + "вес \(вес) Б, id \(активность.id.suffix(6))")
    }

    private static func имяСостояния(_ с: ActivityState) -> String {
        switch с {
        case .active: return "живая"
        case .stale: return "протухшая"
        case .ended: return "завершена"
        case .dismissed: return "убрана"
        default: return "иное (\(с))"
        }
    }

    private static func слушатьПрименённое(_ активность: Activity<СахарАтрибуты>) {
        guard !слушаем else { return }
        слушаем = true
        /* НАБЛЮДАТЕЛЬ СЧИТАЕТ ТОЛЬКО ПОКА МЫ НЕ СПИМ, И ЭТО НАДО ЗАПИСАТЬ (#428).

           На этой подписке мы построили вывод «система применяет одно обновление из шести»: за
           сутки 374 обновления против 59 строк «система показала». Числа верные, вывод — нет.

           Поток `contentUpdates` живёт в нашем процессе. Приложение усыпили — поток не идёт, и
           применённое системой обновление никто не запишет. То есть 59 это не «сколько система
           применила», а «сколько мы не проспали». Сравнивать их с 374 нельзя, а мы сравнили и
           выключили карточку по этому сравнению.

           Поэтому пишем границы наблюдения. Тогда 59 читается как «столько за столько-то часов
           бодрствования», а не как приговор системе. */
        вЖурнал?("Info", "наблюдение за карточкой началось")
        Task {
            for await содержимое in активность.contentUpdates {
                вЖурнал?("Info", "система показала: \(содержимое.state.значение)")
            }
            /* Поток кончился — активность завершена. Следующая подпишется заново. */
            слушаем = false
            вЖурнал?("Info", "поток обновлений карточки кончился: активность завершена")
        }
    }

    /* ПОДНЯТЬ КАРТОЧКУ ПО ПРОСЬБЕ ИЗВНЕ (#428, приём xDrip и Trio).

       Зовётся из `LiveActivityIntent` — Быстрой команды или её автоматизации. Смысл в том, что
       интент исполняется в переднем контексте, а значит рождение разрешено: это единственный
       способ поднять карточку, не заставляя человека открывать приложение.

       Так обходят и восьмичасовой предел жизни карточки: автоматизация по расписанию (или, для
       машины, по подключению CarPlay) поднимает её заново.

       Показываем последнее известное. Ничего не известно — честно отвечаем: поднимать нечего, и
       выдумывать число, которого у нас нет, мы не станем. */
    @discardableResult
    static func поднятьПоПросьбе() -> String {
        guard ActivityAuthorizationInfo().areActivitiesEnabled else { return "выключено в настройках" }
        guard let (состояние, источник, сроку) = отложенное ?? последнееПоказанное() else {
            return "нечего показывать: показания ещё не приходили"
        }
        /* Живую не трогаем: перезапуск ради перезапуска сбрасывает возраст карточки и ничего не
           даёт. Поднимаем только когда её нет. */
        if [текущий, Activity<СахарАтрибуты>.activities.first].compactMap({ $0 })
            .contains(where: { $0.activityState == .active || $0.activityState == .stale }) {
            return "уже жива"
        }
        for т in Activity<СахарАтрибуты>.activities { Task { await т.end(nil, dismissalPolicy: .immediate) } }
        do {
            let новая = try сБюджетомФона {
                try Activity.request(
                    attributes: СахарАтрибуты(источник: источник),
                    content: ActivityContent(state: состояние, staleDate: сроку),
                    pushType: nil
                )
            }
            текущий = новая
            отложенное = nil
            слушатьПрименённое(новая)
            return "поднята по просьбе"
        } catch {
            return "не удалось: \(error.localizedDescription)"
        }
    }

    /// Содержимое последней живой карточки — чтобы поднять её тем же, а не пустотой.
    private static func последнееПоказанное() -> (СахарАтрибуты.ContentState, String, Date)? {
        guard let а = Activity<СахарАтрибуты>.activities.first else { return nil }
        return (а.content.state, а.attributes.источник, Date().addingTimeInterval(15 * 60))
    }

    static var живой: Bool { !Activity<СахарАтрибуты>.activities.isEmpty }
    #else
    static func обновить(значение: String, стрелка: String, разница: String, когдаМс: Double, старое: Bool, источник: String,
                         ряд: [СахарАтрибуты.ContentState.Точка] = [], mmol: Double? = nil, зона: String = "коридор",
                         инсулин: String = "", прогноз: Double? = nil, разрыв: Bool = false,
                         последнее: String = "", следующее: Date? = nil,
                         опоздание: Int = 0) -> String { "нет ActivityKit" }
    static func погасить() {}
    @discardableResult static func поднятьПоПросьбе() -> String { "нет ActivityKit" }
    static var живой: Bool { false }
    #endif
}
