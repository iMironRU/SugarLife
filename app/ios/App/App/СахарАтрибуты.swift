import ActivityKit
import Foundation

/*
 Состояние живого баннера — общее для приложения и расширения (#428).

 Отдельным файлом и в обеих целях намеренно: приложение это состояние СОБИРАЕТ, расширение
 РИСУЕТ, и тип у них обязан быть один. Скопировать его в два места значило бы завести две
 правды о том, что показано человеку на экране блокировки.
 */

public struct СахарАтрибуты: ActivityAttributes {
    public struct ContentState: Codable, Hashable {
        /// Готовая строка значения — «13,5». Формат числа решает приложение: единицы,
        /// запятая и округление живут там, где живут остальные слова.
        public var значение: String
        /// Стрелка тренда как символ: → ↗ ↑ ↘ ↓. Пусто — тренда нет, и рисовать нечего.
        public var стрелка: String
        /// Разница с прошлым показанием — «+0,2». Пусто — сравнивать не с чем.
        public var разница: String
        /// Когда пришло показание. Возраст считает система — так он не устаревает между
        /// обновлениями баннера, а сам идёт вперёд.
        public var когда: Date
        /// Данные устарели: показание есть, но оно старое. Баннер должен это показать.
        public var старое: Bool

        public init(значение: String, стрелка: String, разница: String, когда: Date, старое: Bool) {
            self.значение = значение
            self.стрелка = стрелка
            self.разница = разница
            self.когда = когда
            self.старое = старое
        }
    }

    /// Неизменное за жизнь баннера. Имя источника показываем в развёрнутом виде: у
    /// человека может быть два сенсора, и «13,5» без источника — половина ответа.
    public var источник: String

    public init(источник: String) {
        self.источник = источник
    }
}

