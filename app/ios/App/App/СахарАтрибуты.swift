import ActivityKit
import Foundation

/*
 Состояние живого баннера — общее для приложения и расширения (#428).

 Отдельным файлом и в обеих целях намеренно: приложение это состояние СОБИРАЕТ, расширение
 РИСУЕТ, и тип у них обязан быть один. Скопировать его в два места значило бы завести две
 правды о том, что показано человеку на экране блокировки.
 */

public struct СахарАтрибуты: ActivityAttributes {
    public struct ContentState: Codable, Hashable {
        /// Готовая строка значения — «13,5». Формат числа решает приложение: единицы,
        /// запятая и округление живут там, где живут остальные слова.
        public var значение: String
        /// Стрелка тренда как символ: → ↗ ↑ ↘ ↓. Пусто — тренда нет, и рисовать нечего.
        public var стрелка: String
        /// Разница с прошлым показанием — «+0,2». Пусто — сравнивать не с чем.
        public var разница: String
        /* ЧИСЛО ЧИСЛОМ, А НЕ ТОЛЬКО СТРОКОЙ (макет v2). Строка нужна для показа, число — чтобы
           решить зону (цвет) и поставить точку на график. Одно без другого заставило бы разбирать
           строку обратно, а это вторая дорога к тому же числу. */
        public var mmol: Double?
        /* Зона: «коридор» / «выше» / «ниже». Считает приложение по правилам движка — расширение не
           знает ни целей, ни порогов и знать не должно. */
        public var зона: String
        /// Активный инсулин строкой — «0,8 ед». Пусто: движок не считал, и врать нечем.
        public var инсулин: String
        /* Прогноз — куда идёт кривая. Рисуется тающим хвостом за правый край. nil — прогноза нет,
           и хвоста нет: выдуманное продолжение хуже отсутствующего. */
        public var прогноз: Double?
        /* Когда ждём следующее показание. Системный таймер отсчитывает до него сам, поэтому
           секундомер идёт и без обновлений баннера. nil — ждать нечего (разрыв). */
        public var следующее: Date?
        /* РАЗРЫВ — ОТДЕЛЬНОЕ СОСТОЯНИЕ, А НЕ ТУСКЛОЕ ЧИСЛО (макет v2). После пятнадцати минут
           ожидание перестаёт быть ожиданием: числа нет вовсе, вместо него причина и сколько это
           длится, а последнее известное уходит в мелкую строку. */
        public var разрыв: Bool
        /// «6,1 в 9:24» — последнее известное показание, только для разрыва.
        public var последнее: String
        /// Когда пришло показание. Возраст считает система — так он не устаревает между
        /// обновлениями баннера, а сам идёт вперёд.
        public var когда: Date
        /// Данные устарели: показание есть, но оно старое. Баннер должен это показать.
        public var старое: Bool
        /* ЧАС ПОКАЗАНИЙ ЦЕЛИКОМ, а не только последнее (#428).

           Стрелка отвечает «растёт», но не отвечает «как»: разгоняется подъём или выдыхается,
           давно он идёт или начался только что. За рулём это и есть вопрос — по мгновенному
           тренду решение принять нельзя. Линия отвечает на него формой, без чтения чисел.

           Ряд едет целиком в состоянии баннера: расширение живёт отдельным процессом и данных
           не имеет — что передали, то и нарисует.

           ТРИ ЧАСА, А НЕ ОДИН (макет v2). Час отвечает «растёт», три — «как давно и с какой
           амплитудой»: две качели от 3,8 до 13,1 за три часа и спокойный день на фиксированной оси
           выглядят по-разному, а на часовом окне с автомасштабом одинаково. Тридцать семь точек по
           пять минут — это около полутора килобайт при лимите четыре. */
        public var ряд: [Точка]

        /// Точка ряда: когда и сколько. Отдельным типом, чтобы время и значение нельзя было
        /// перепутать местами — оба Double, и в паре чисел ошибка молчалива.
        /// Тот же баннер, но без веры в число: система сказала, что обновлений не было слишком долго.
        public func состаренное(_ устарело: Bool) -> ContentState {
            guard устарело, !разрыв else { return self }
            var с = self
            с.старое = true
            с.разрыв = true
            /* Ждать больше нечего: секундомер «до следующего» на давно молчащем баннере отсчитывал бы
               событие, которого не будет. */
            с.следующее = nil
            return с
        }

        public struct Точка: Codable, Hashable {
            public var т: Date
            public var в: Double
            public init(т: Date, в: Double) { self.т = т; self.в = в }
        }

        public init(значение: String, стрелка: String, разница: String, когда: Date, старое: Bool,
                    ряд: [Точка] = [], mmol: Double? = nil, зона: String = "коридор",
                    инсулин: String = "", прогноз: Double? = nil, следующее: Date? = nil,
                    разрыв: Bool = false, последнее: String = "") {
            self.значение = значение
            self.стрелка = стрелка
            self.разница = разница
            self.когда = когда
            self.старое = старое
            self.ряд = ряд
            self.mmol = mmol
            self.зона = зона
            self.инсулин = инсулин
            self.прогноз = прогноз
            self.следующее = следующее
            self.разрыв = разрыв
            self.последнее = последнее
        }
    }

    /* КОГДА ПРИЛОЖЕНИЕ ЗАМОЛЧАЛО, А БАННЕР ОСТАЛСЯ (#530).

       Всё выше приезжает из приложения — включая признаки «старое» и «разрыв». Пока приложение
       живо, это работает. Но iOS усыпляет процесс, сеть пропадает, движок теряет подписку — и
       баннер остаётся на экране блокировки ровно таким, каким его оставили: со свежим на вид
       числом, под которым тикает уже сорокаминутный возраст. Это худший вид вранья, какой у нас
       есть: человек смотрит на экран блокировки чаще, чем в приложение.

       Систему мы об этом предупреждаем сами — `staleDate` в ActivityContent. По его наступлению
       ActivityKit перерисовывает баннер и поднимает `isStale`, даже если приложение уже не
       исполняется. Здесь мы этот флаг превращаем в состояние: раз обновлений не было дольше срока
       годности показания — числу не верим, показываем разрыв.

       Считает по-прежнему приложение: сроки, слова и формат последнего показания приехали готовыми.
       Расширение только выбирает между двумя заранее собранными правдами. */
    /// Неизменное за жизнь баннера. Имя источника показываем в развёрнутом виде: у
    /// человека может быть два сенсора, и «13,5» без источника — половина ответа.
    public var источник: String

    public init(источник: String) {
        self.источник = источник
    }
}

