import Foundation

/* ЧТЕНИЕ СНИМКА: ОДНО ЧИСЛО — ОДНА ДОРОГА (SugarLife#663).

   Эти пять чтений нужны всем поверхностям сразу: живой карточке, значку, тихой сводке, виджету.
   Жили они приватными методами внутри плагина — то есть внутри того же файла, где и мост, и BLE, и
   проводка тревог. Поверхность, которой они понадобились, обязана была переехать туда же.

   Именно так значок со сводкой и оказались внутри решения о карточке, а выключение карточки унесло
   их с собой (#655). Соседство было не случайностью, а следствием: разделяемому коду негде было
   жить, кроме общего дома.

   Здесь они свободными функциями и без состояния. `ряд` берёт историю движка параметром, а не
   лезет за ней в плагин: так его можно позвать откуда угодно и проверить чем угодно.

   ПРАВИЛО, КОТОРОЕ ЭТИ ФУНКЦИИ ДЕРЖАТ: одно число считается в одном месте. Две дороги к одному
   числу расходятся на округлении, и человек видит «7,4» на значке при «7,5» в сводке — а мы потом
   ищем, кто из них врёт. */
enum Снимок {
    /**
     ЗОНА САХАРА — ТОЛЬКО ДЛЯ ЦВЕТА (макет v2).

     Границы коридора те же, что рисует график и что показывает круг на «Сегодня»: 3,9 и 10. Правило
     проекта — цвет означает зону и ничего больше, поэтому иных зон здесь нет и заводить их нельзя:
     разошедшись, они сделали бы один и тот же оттенок значащим разное на двух поверхностях.

     Целевой коридор пока постоянный. Когда движок начнёт отдавать личные цели в снимке, брать надо
     будет их — но не раньше: подставлять «типичные» за человека мы не станем.
     */
    static func зонаСахара(_ mmol: Double?) -> String {
        guard let mmol, mmol > 0 else { return "коридор" }
        if mmol > 10 { return "выше" }
        if mmol < 3.9 { return "ниже" }
        return "коридор"
    }

    /// Активный инсулин строкой для баннера — тем же путём, что для сводки (движок, а в облаке — веб).
    /* ИНСУЛИН ДЛЯ ПОВЕРХНОСТЕЙ: СНОВА НАШ ПЕРВЫМ (мост 1.47, ядро #136).

       Здесь стоял обход: чужой `loopIOB` первым, наш `confirmedIOB` запасным. Завели его, когда
       владелец снял экран с «инс. 0,7 ед» в шторке и «инс. 2,1 ед» в круге в ту же минуту — наш
       расчёт занижал втрое.

       Причина оказалась не в модели, а в разборе: ядро выбрасывало запись первой же строкой, если у
       неё нет поля `insulin`, — а у временного базала его нет вовсе, там ставка и длительность. То
       есть `confirmedIOB` был ровно суммой болюсов, и на замкнутом цикле, где большую часть подаёт
       базал, занижение было систематическим.

       Починено в 1.47: временный базал доезжает и входит РАЗНИЦЕЙ с профильным, а не целиком —
       ставка ниже профиля даёт отрицательный вклад, и это правильно. Возвращаем наш вперёд: он
       построен на свидетельстве и его можно объяснить, чужой готовый и необъяснимый.

       Не сойдётся с `loopIOB` — это баг, а не «слегка неточно»: ядро просило заводить задачу. */
    static func инсулинИзСнимка(_ monitor: [String: Any]) -> Double? {
        if let наш = monitor["confirmedIOB"] as? Double, наш > 0.05 { return наш }
        if let чужой = monitor["loopIOB"] as? Double, чужой > 0.05 { return чужой }
        return nil
    }

    /**
     Разница с прошлым показанием — «+0,1» (#500).

     Стрелка говорит «растёт», но не говорит «насколько»: у соседей по экрану блокировки это число
     есть, и без него наш баннер отвечает на вопрос беднее при тех же данных.

     Считаем по ряду, который у нас уже накоплен, и молчим, если между точками больше пятнадцати
     минут: разница через дыру в данных — это не тренд, а разность двух разных историй.
     */
    static func дельта(_ ряд: [СахарАтрибуты.ContentState.Точка]) -> String {
        guard ряд.count >= 2 else { return "" }
        let предыдущая = ряд[ряд.count - 2], последняя = ряд[ряд.count - 1]
        guard последняя.т.timeIntervalSince(предыдущая.т) <= 15 * 60 else { return "" }
        let d = последняя.в - предыдущая.в
        return String(format: "%+.1f", d).replacingOccurrences(of: ".", with: ",")
    }

    /// Тренд движка — стрелкой. Незнакомое значение отдаём пустым: выдуманная стрелка
    /// хуже отсутствующей, по ней принимают решение о дозе.
    static func стрелкаТренда(_ t: String?) -> String {
        /* ИМЕНА ОТ ДВИЖКА, А НЕ ОТ NIGHTSCOUT (#500). Здесь стояли `SingleUp`, `Flat`, `FortyFiveUp` —
           словарь Nightscout, которого движок не знает: его тренды называются иначе. Ни одно имя не
           совпадало никогда, поэтому стрелки на баннере не было вовсе — и заметить это можно было
           только глазами, на живом экране блокировки: пустая стрелка выглядит как «тренда нет».

           Символы те же, что в приложении (domain/trend.ts): одна и та же картина не должна
           означать в двух местах разное. */
        switch t {
        case "RisingRapidly": return "⇈"
        case "Rising": return "↑"
        case "RisingSlowly": return "↗"
        case "Stable": return "→"
        case "FallingSlowly": return "↘"
        case "Falling": return "↓"
        case "FallingRapidly": return "⇊"
        /* `Unknown` от драйвера и прочерк от старого моста — оба «не знаю», и рисовать нечего:
           выдуманная стрелка хуже отсутствующей, по ней принимают решение о дозе. */
        default: return ""
        }
    }

    /* ОДИН РЯД НА ВСЕ ПОВЕРХНОСТИ (#562, docs/поверхности-показа.md).

       Баннер брал историю у движка, а виджет — из нашей копилки, которая копится только пока
       приложение живо. На двух графиках об одном сахаре получалась разная длина линии: на баннере
       три часа, на виджете обрывки тех часов, когда телефон нас будил. Человек видит их рядом на
       одном экране блокировки, и вопрос «какому верить» возникает мгновенно.

       История движка полнее нашей всегда, когда она есть: в ней нет дыр от сна приложения. Своя
       копилка остаётся запасным путём — для браузерного шима и первых секунд после запуска, пока
       движок ещё не ответил.

       Последнее показание дописываем из снимка: запрос истории мог отстать на минуту, и график,
       заканчивающийся раньше числа над ним, противоречит сам себе. */
    /* Историю движка берём ПАРАМЕТРОМ, а не из чужого поля: иначе это чтение снова привязано к
       одному владельцу, и следующая поверхность потащит за собой весь плагин. */
    static func рядДляПоказа(_ monitor: [String: Any], когдаМс: Double,
                             историяДвижка: [СахарАтрибуты.ContentState.Точка]) -> [СахарАтрибуты.ContentState.Точка] {
        let mmol = monitor["glucoseMmol"] as? Double
        var ряд: [СахарАтрибуты.ContentState.Точка]
        if let mmol, mmol > 0 {
            ряд = ИсторияСахара.добавить(значение: mmol, когдаМс: когдаМс)
        } else {
            ряд = ИсторияСахара.ряд()
        }
        guard !историяДвижка.isEmpty else { return ряд }
        ряд = историяДвижка
        let момент = Date(timeIntervalSince1970: когдаМс / 1000)
        if ряд.last.map({ момент.timeIntervalSince($0.т) > 30 }) ?? true, let mmol, mmol > 0 {
            ряд.append(.init(т: момент, в: mmol))
        }
        return ряд
    }

    /* ИНСУЛИН СТРОКОЙ — с запасным путём на сводку.

       Карточка и виджет рисуются и тогда, когда снимка под рукой нет: система будит расширение
       сама. Тогда берём последнее, что показывала сводка, — но только его, а не выдумываем ноль:
       ноль на экране означает «инсулина нет», и это утверждение, а не отсутствие ответа. */
    static func инсулинСтрокой(_ monitor: [String: Any]? = nil) -> String {
        let значение = (monitor.flatMap { инсулинИзСнимка($0) }) ?? Сводка.общая.инсулинДляПоказа()
        guard let и = значение, и > 0.05 else { return "" }
        return String(format: "%.1f", и).replacingOccurrences(of: ".", with: ",") + " ед"
    }
}
