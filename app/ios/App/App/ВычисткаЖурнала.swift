import Foundation

/*
 ЧТО ВЫРЕЗАЕМ ИЗ ЖУРНАЛА ПЕРЕД ОТПРАВКОЙ (SugarLife#656).

 Журнал человек отправляет в мессенджер, и обратной дороги у него нет. Значит вопрос не «что туда
 полезного положить», а «чего там быть не должно».

 ЧТО НАШЛОСЬ НА ЖИВОМ ТЕЛЕФОНЕ 2 сентября 2026, в журнале за сутки:

 - 147 записей с адресом облака владельца — в поле `id` каждого потока: `ns:<хост>-cgm`;
 - 30 записей с полным адресом запроса — `https://<хост>/api/v1/entries.json?count=288` внутри
   текста системной ошибки.

 Вычистка в ядре есть, но она по ИМЕНИ ПОЛЯ: `token`, `secret`, `password`, `mac`. Адрес лежит в
 поле `id`, а запрос — внутри свободного текста `err`, и оба проходят мимо. Токен сегодня не
 попался, но попадётся: адрес Nightscout носят с `?token=…`.

 Адрес облака — это не «просто хост». Nightscout часто открыт на чтение, и по адресу человека
 находят его сахар за годы.

 Хвост потока (`-cgm`, `-pump`, `-treat`) и путь запроса СОХРАНЯЕМ: по ним видно, какой канал молчит
 и куда мы стучались, а это половина разбора.

 ПРАВИЛО ОДНО, ИСПОЛНЕНИЙ ДВА (здесь и `android/.../ВычисткаЖурнала.kt`) — файл собирает оболочка, у
 каждой платформы своя. Настоящее место правилу — в ядре, рядом с `Redactor`; написано им в #656.
 Тесты живут на стороне Android, там же, где есть чем их гонять.
 */
enum ВычисткаЖурнала {

    static let облако = "<облако>"

    /// Адрес потока `ns:<хост>-<поток>`: хост узнаём по точке, поток — кусок без точек в конце.
    private static let идентификатор = try! NSRegularExpression(
        pattern: #"ns:([^"\s,}]*\.[^"\s,}]*?)-([a-z]+)(?![\w.-])"#)

    /// Голый адрес облака, без хвоста потока: `{"cloud":"ns:<хост>"}`. Найдено прогоном по настоящему
    /// журналу — первая замена его не ловила, и адрес оставался в 49 записях. Точка обязательна:
    /// иначе правило съело бы уже вычищенное `ns:<облако>-cgm`.
    private static let голыйАдрес = try! NSRegularExpression(pattern: #"ns:[A-Za-z0-9._-]*\.[A-Za-z0-9._-]*"#)

    /// Запрос целиком: схема, хост, путь, строка запроса. Путь оставляем, хост и запрос убираем.
    private static let запрос = try! NSRegularExpression(
        pattern: #"https?://([^/\s"'\\]+)([^\s"'\\]*)"#)

    static func вычистить(_ журнал: String) -> String {
        var текст = журнал as NSString
        текст = идентификатор.stringByReplacingMatches(
            in: текст as String, range: NSRange(location: 0, length: текст.length),
            withTemplate: "ns:\(облако)-$2") as NSString

        текст = голыйАдрес.stringByReplacingMatches(
            in: текст as String, range: NSRange(location: 0, length: текст.length),
            withTemplate: "ns:\(облако)") as NSString

        /* Путь оставить, а строку запроса убрать одним шаблоном нельзя — режем сами. Идём с конца,
           чтобы замены не сдвигали ещё не обработанные места. */
        let найдено = запрос.matches(in: текст as String,
                                     range: NSRange(location: 0, length: текст.length))
        for м in найдено.reversed() {
            let путь = м.range(at: 2).location == NSNotFound ? "" : текст.substring(with: м.range(at: 2))
            let безЗапроса = путь.split(separator: "?", maxSplits: 1, omittingEmptySubsequences: false).first.map(String.init) ?? ""
            текст = текст.replacingCharacters(in: м.range, with: "https://\(облако)\(безЗапроса)") as NSString
        }
        return текст as String
    }
}
