import Foundation

/* ЗНАЧОК НА ИКОНКЕ И ТИХАЯ СВОДКА В ШТОРКЕ (SugarLife#663).

   Отдельным типом, а не методом плагина. Причина не в красоте: 28 августа эти две поверхности
   обновлялись ВНУТРИ решения о живой карточке, карточку выключили — и они замолчали вместе с ней.
   Владелец увидел это на заблокированном телефоне раньше нас (#655).

   Разнести вызовы (#658) было половиной дела: код по-прежнему жил в чужом доме, и следующая правка
   соседа снова могла его задеть. Теперь у поверхности свой файл, своя память о показанном и своё
   условие «есть что менять» — и погасить её можно только намеренно.

   Своё условие нужно и по делу: проигрывание истории на старте даёт сотни снимков в секунду, и без
   него значок перерисовывался бы сотни раз подряд ради одного и того же числа.

   Число берём у `Снимок` — там же, где его берут все остальные: две дороги к одному числу
   расходятся на округлении. */
final class ЗначокИСводка {
    static let общая = ЗначокИСводка()
    private init() {}

    /* Что уже показано. Память своя, не общая с карточкой: общая означала бы, что решение одной
       поверхности молчит за другую. */
    private var показаниеМс: Double = 0
    private var своёСтарое = false

    func обновить(_ json: String?, историяДвижка: [СахарАтрибуты.ContentState.Точка]) {
        guard let json, let data = json.data(using: .utf8),
              let корень = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let monitor = корень["monitor"] as? [String: Any] else { return }
        let значение = (monitor["glucose"] as? String) ?? "—"
        guard значение != "—", !значение.isEmpty else { return }
        let когдаМс = (monitor["latestAtMs"] as? Double) ?? Date().timeIntervalSince1970 * 1000
        let свежестьСтарая = ((monitor["status"] as? String) ?? "") != "Live"
        guard когдаМс != показаниеМс || свежестьСтарая != своёСтарое else { return }
        показаниеМс = когдаМс
        своёСтарое = свежестьСтарая
        /* Число и разделитель — те же, что на карточке: две дороги к одному числу разойдутся на
           округлении, и человек увидит «7,4» на значке при «7,5» в сводке. */
        let число = String(значение.split(separator: " ").first ?? "")
            .replacingOccurrences(of: ".", with: ",")
        Значок.общий.обновить(mmol: monitor["glucoseMmol"] as? Double, старое: свежестьСтарая)
        Сводка.общая.обновить(
            сахар: число.isEmpty ? значение : число,
            стрелка: Снимок.стрелкаТренда(monitor["trend"] as? String),
            разница: Снимок.дельта(Снимок.рядДляПоказа(monitor, когдаМс: когдаМс, историяДвижка: историяДвижка)),
            инсулин: Снимок.инсулинИзСнимка(monitor), когдаМс: когдаМс, старое: свежестьСтарая)
    }
}
