/* Сторож запуска — единственный код восстановления, живущий ВНЕ бандла (SugarLife#131).

   Случай, ради которого он написан: сломанная сборка перекрыла интерфейс невидимой
   модалкой. Приложение выглядело нормально и не отвечало ни на одно нажатие, а
   единственный путь к спасению — кнопка «Обновить и перезагрузить» — находился внутри
   того самого интерфейса, который не работал. Обходной путь (закрыть все копии
   приложения) существует, но человек его не знает и знать не должен.

   Поэтому сторож обязан быть отдельным файлом с обычным <script>, а не частью бандла:
   бандл — ровно то, что ломается. Ни модулей, ни импортов, ни сборки.

   Он ничего не делает, пока приложение живо: React зовёт window.слЖив() после первого
   кадра, и счётчик обнуляется. Считаются только НЕУДАЧНЫЕ запуски.

   Пороги продублированы в src/platform/rescue.ts (там же тест, стерегущий совпадение):
   двум файлам нельзя разъезжаться, а импортировать один в другой здесь нечем. */
(function () {
  var КЛЮЧ = 'sl-boot-guard';
  /* Столько неудачных запусков подряд — и мы показываем спасение сами. Один запуск
     ничего не значит: приложение могли закрыть в момент загрузки, переключиться на
     другое, потерять сеть. Два подряд — это уже поломка, а не случайность. */
  var ПОРОГ = 2;
  /* Сколько ждём слова «жив». Первый экран собирается за доли секунды даже на слабом
     телефоне; двенадцать секунд — это заведомо «что-то не так», а не «медленно». */
  var ЖДЁМ = 12000;

  function прочитать() {
    try { return JSON.parse(localStorage.getItem(КЛЮЧ) || '{}') || {}; } catch (e) { return {}; }
  }
  function записать(v) {
    try { localStorage.setItem(КЛЮЧ, JSON.stringify(v)); } catch (e) { /* приватный режим */ }
  }

  var было = прочитать();
  var подряд = (typeof было.подряд === 'number' ? было.подряд : 0) + 1;
  записать({ подряд: подряд, начат: Date.now() });

  var таймер = 0;

  /* Применить ждущее обновление. Оно и есть спасение в самом частом случае: сломанная
     сборка уже заменена исправленной, воркер с ней стоит в очереди и ждёт, когда
     отпустят все вкладки. Человеку об этой очереди знать неоткуда.

     САМИ перезагружаемся, только если ждущее обновление действительно есть. Без этой
     проверки автоматическая попытка превращалась бы в петлю: сборка сломана, спасение
     перезагружает, счётчик неудач снова за порогом, спасение перезагружает опять —
     приложение крутится и не даёт даже нажать кнопку.

     По кнопке перезагружаемся всегда: человек нажал сам, и «ничего не произошло» —
     худший ответ на осознанное действие. */
  function обновиться(самиРешили) {
    if (!navigator.serviceWorker) { if (!самиРешили) location.reload(); return; }
    navigator.serviceWorker.getRegistration().then(function (reg) {
      var ждёт = reg && reg.waiting;
      if (ждёт) reg.waiting.postMessage({ type: 'SKIP_WAITING' });
      if (ждёт || !самиРешили) setTimeout(function () { location.reload(); }, 400);
    }).catch(function () { if (!самиРешили) location.reload(); });
  }

  /* Снести воркер и кэши целиком. Тяжелее обновления и потому вторым: приложение
     скачается заново с сети. Локальные данные (настройки, история) лежат в IndexedDB и
     localStorage — их не трогаем, иначе спасение стоило бы человеку его записей. */
  function сбросить() {
    var дела = [];
    if (navigator.serviceWorker) {
      дела.push(navigator.serviceWorker.getRegistrations().then(function (rs) {
        return Promise.all(rs.map(function (r) { return r.unregister(); }));
      }));
    }
    if (window.caches) {
      дела.push(caches.keys().then(function (ks) {
        return Promise.all(ks.map(function (k) { return caches.delete(k); }));
      }));
    }
    Promise.all(дела).catch(function () { /* всё равно перезагружаемся */ })
      .then(function () { location.replace(location.pathname + '?свежо=' + Date.now()); });
  }

  /* Показывать спасение можно только тому, кто смотрит на экран.

     В фоне браузер растягивает таймеры до секунд и минут: свёрнутое приложение легко
     «не успевает» за двенадцать секунд, будучи совершенно целым. Человек вернулся бы к
     работающему приложению и увидел «Приложение не отвечает» — то есть сторож сам стал
     бы той поломкой, от которой стережёт.

     Поэтому в фоне не показываем, а ждём возвращения и отсчитываем срок заново: пока
     на экран не смотрят, спешить некуда. */
  function показать(причина) {
    if (document.getElementById('sl-rescue')) return;
    if (document.visibilityState === 'hidden') {
      document.addEventListener('visibilitychange', function повтор() {
        if (document.visibilityState === 'hidden') return;
        document.removeEventListener('visibilitychange', повтор);
        таймер = setTimeout(function () { показать(причина); }, ЖДЁМ);
      });
      return;
    }
    var д = document.createElement('div');
    д.id = 'sl-rescue';
    д.setAttribute('style', [
      'position:fixed', 'inset:0', 'z-index:2147483647',
      'display:flex', 'flex-direction:column', 'align-items:center', 'justify-content:center',
      'gap:14px', 'padding:24px', 'box-sizing:border-box',
      'background:#161826', 'color:#e9e9ed',
      'font-family:Inter,system-ui,sans-serif', 'text-align:center',
    ].join(';'));
    var кнопка = 'display:block;width:100%;max-width:320px;padding:14px 18px;border-radius:16px;'
      + 'border:0;font:inherit;font-size:15px;cursor:pointer;';
    д.innerHTML =
      '<div style="font-size:17px;font-weight:600">Приложение не отвечает</div>'
      + '<div style="font-size:14px;color:#9397ab;max-width:340px;line-height:1.45">' + причина + '</div>'
      + '<button id="sl-r-upd" style="' + кнопка + 'background:#9184d9;color:#12131c;font-weight:600">'
      + 'Обновить и перезагрузить</button>'
      + '<button id="sl-r-reset" style="' + кнопка + 'background:#242636;color:#e9e9ed">'
      + 'Загрузить заново с сети</button>'
      + '<div style="font-size:12px;color:#6f7285;max-width:340px;line-height:1.4">'
      + 'Записи и настройки останутся: они хранятся отдельно от приложения.</div>';
    document.body.appendChild(д);
    document.getElementById('sl-r-upd').onclick = function () { обновиться(false); };
    document.getElementById('sl-r-reset').onclick = сбросить;
  }

  /* Приложение ожило — снимаем сторожа и обнуляем счётчик. Обнуляем именно здесь, а не
     при запуске: иначе один удачный старт стирал бы память о череде неудачных. */
  window.слЖив = function () {
    if (таймер) { clearTimeout(таймер); таймер = 0; }
    записать({ подряд: 0, начат: Date.now() });
    var э = document.getElementById('sl-rescue');
    if (э && э.parentNode) э.parentNode.removeChild(э);
  };

  /* Приложение поняло, что оно живо, но нажать в нём ничего нельзя (перекрыто своим же
     слоем). Для сторожа это такой же неудачный запуск: показываем спасение сразу и
     оставляем счётчик неудач нетронутым. */
  window.слСпасение = function (причина) {
    показать(причина || 'Экран перекрыт невидимым слоем — до кнопок не добраться.');
  };

  if (подряд > ПОРОГ) {
    /* Уже не первый провал — ждать нечего. Пробуем применить обновление сами: если
       исправленная сборка уже скачана, человек не должен ни о чём просить. */
    показать('Прошлые запуски закончились ничем. Скорее всего, сборка сломана — обновление это чинит.');
    обновиться(true);
  } else {
    таймер = setTimeout(function () {
      показать('Загрузка идёт слишком долго. Обычно это значит, что сборка сломана.');
    }, ЖДЁМ);
  }
})();
